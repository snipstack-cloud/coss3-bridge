# -*- coding: utf-8 -*-
"""Самопроверка марша по контракту модели (18.09).

Контракт: {"cmd":"ATTACK","count":40,"target":"cell","cx":13,"cy":4,
           "via":{"cx":13,"cy":8},"hold_if_outnumbered":1.3,"expires":90}.
Мост исполняет ровно то, что модель написала: MOVE в клетку сбора, ждёт, пока
дойдут, проверяет её порог у цели и бьёт — либо стоит и говорит почему.
"""
import sys
import llm_policy as L

беды = []


def проверка(имя, условие, пояснение=""):
    if условие:
        print("  ОК   " + имя)
    else:
        беды.append(имя)
        print("  ПЛОХО " + имя + (" — " + пояснение if пояснение else ""))


class Мост:
    """Заглушка: запоминает приказы, как их получил бы block_hcmd."""
    def __init__(self):
        self.приказы = []
        self.занят = False

    def attack(self, count, target="base", mode="", cx=-1, cy=-1):
        if self.занят:
            return False
        self.приказы.append((count, target, mode, cx, cy))
        return True


def сетка(имя, **клетки):
    строки = [["."] * 16 for _ in range(16)]
    for k, v in клетки.items():
        x, y = (int(t) for t in k.split(","))
        строки[y][x] = str(v)
    return {f"{имя}{y}": "".join(строки[y]) for y in range(16)}


КОМАНДА = {"cmd": "ATTACK", "count": 40, "target": "cell", "cx": 13, "cy": 4,
           "via": {"cx": 13, "cy": 8}, "hold_if_outnumbered": 1.3, "expires": 90}

# 1. Разбор контракта.
_, attack, _, брак, цель, _, _, клетка, к = L.to_commands({"commands": [КОМАНДА]})
проверка("ATTACK разобран", attack == 40 and цель == "cell" and клетка == (13, 4))
проверка("via разобран", к.get("via") == (13, 8), str(к))
проверка("порог разобран", к.get("hold") == 1.3)
проверка("срок разобран", к.get("expires") == 90)
проверка("брака нет", брак == [], str(брак))

_, _, _, брак, _, _, _, _, к = L.to_commands({"commands": [dict(КОМАНДА, via={"cx": 99})]})
проверка("кривая via названа вслух", any("via" in б for б in брак) and "via" not in к)
_, _, _, брак, _, _, _, _, к = L.to_commands({"commands": [dict(КОМАНДА, hold_if_outnumbered=-1)]})
проверка("кривой порог назван вслух", any("hold_if_outnumbered" in б for б in брак) and "hold" not in к)
_, _, _, брак, _, _, _, _, к = L.to_commands({"commands": [dict(КОМАНДА, retreat_below=0.5)]})
проверка("retreat_below принят, но объявлен неисполняемым",
         к.get("retreat") == 0.5 and any("НЕ ИСПОЛНЯЕТСЯ" in б for б in брак))
_, attack, _, брак, цель, _, _, _, к = L.to_commands(
    {"commands": [{"cmd": "ATTACK", "count": 20, "target": "wave"}]})
проверка("target=wave принят", attack == 20 and цель == "wave" and брак == [])
_, _, _, _, _, _, _, _, к = L.to_commands(
    {"commands": [{"cmd": "ATTACK", "count": 20, "target": "peasants"}]})
проверка("без via контракт пуст", к == {})

# 2. Марш: сбор, порог, удар.
БАЗА = dict(gametime=400, grid_n=16, my_cx=13, my_cy=14, mil_inf=30, mil_shooters=20,
            my_freewar=45, map_open=1)
мост = Мост()
волны = []
L.МАРШ.clear()
L.начать_марш(400, 40, "cell", (13, 4), к := {"via": (13, 8), "hold": 1.3, "expires": 90},
              dict(БАЗА))
проверка("марш начат в фазе сбор", L.МАРШ["фаза"] == "сбор" and L.МАРШ["expires"] == 90)

# такт 1: приказ мог не дойти — не считаем, даже если сетка пуста
L.шаг_марша(dict(БАЗА, gametime=420, **сетка("arow", **{"12,12": 5})), мост, 420, волны)
проверка("первый такт не считается сбором", L.МАРШ["фаза"] == "сбор" and мост.приказы == [])
# такт 2: ещё идут (wave_n > 0)
L.шаг_марша(dict(БАЗА, gametime=440, wave_n=40, wave_cx=13, wave_cy=10), мост, 440, волны)
проверка("пока идут — ждём", L.МАРШ["фаза"] == "сбор" and мост.приказы == [])
т = "\n".join(L.блок_марша(dict(БАЗА)))
проверка("блок в запросе называет сбор", "клетку сбора (13,8)" in т and "из 90" in т, т)
# такт 3: дошли, врага у цели мало — удар
st = dict(БАЗА, gametime=460, **сетка("arow", **{"13,8": 9, "13,9": 9}),
          **сетка("frow", **{"13,4": 9, "13,3": 9, "3,3": 9}))
L.шаг_марша(st, мост, 460, волны)
проверка("собрались — удар начат", L.МАРШ["фаза"] == "удар", L.МАРШ["фаза"])
проверка("удар ушёл на цель, режим атаки",
         мост.приказы == [(40, "cell", "", 13, 4)], str(мост.приказы))
проверка("волна записана", волны == [(460, 40, "cell")], str(волны))
проверка("память отправки заполнена", L.ОТПРАВКА.get("армия") == 50)
т = "\n".join(L.блок_марша(st))
проверка("блок сообщает об ударе", "СОБРАЛИСЬ" in т and "начат" in т, т)

# 3. Порог: врага у цели больше 1.3 × своих — стоим и говорим.
мост = Мост()
волны = []
L.начать_марш(500, 20, "cell", (13, 4), {"via": (13, 8), "hold": 1.3}, dict(БАЗА))
проверка("срок по умолчанию", L.МАРШ["expires"] == L.МАРШ_СРОК)
L.шаг_марша(dict(БАЗА, gametime=520, wave_n=20), мост, 520, волны)
st = dict(БАЗА, gametime=540, **сетка("arow", **{"13,8": 9}),
          **сетка("frow", **{"13,4": 9, "13,3": 9, "12,4": 9}))
L.шаг_марша(st, мост, 540, волны)
проверка("порог сработал — стоим", L.МАРШ["фаза"] == "стоим" and мост.приказы == [])
проверка("названо число врага и порог", any("27 врага" in с and "1.3" in с for с in L.МАРШ["отчёт"]),
         str(L.МАРШ["отчёт"]))
т = "\n".join(L.блок_марша(st))
проверка("блок говорит, что удар не начат", "НЕ НАЧАТ" in т)

# 4. Срок истёк.
мост = Мост()
волны = []
L.начать_марш(600, 20, "peasants", (-1, -1), {"via": (13, 8), "expires": 60}, dict(БАЗА))
L.шаг_марша(dict(БАЗА, gametime=620, wave_n=20), мост, 620, волны)
L.шаг_марша(dict(БАЗА, gametime=670, wave_n=7, **сетка("arow", **{"13,8": 9})), мост, 670, волны)
проверка("срок истёк — марш отменён", L.МАРШ["фаза"] == "истёк" and мост.приказы == [])
проверка("сказано, сколько в пути", any("в пути ещё 7" in с for с in L.МАРШ["отчёт"]))

# 5. Цель без клетки: порог не проверяется, удар идёт на peasants.
мост = Мост()
волны = []
L.начать_марш(700, 20, "peasants", (-1, -1), {"via": (13, 8), "hold": 1.3}, dict(БАЗА))
L.шаг_марша(dict(БАЗА, gametime=720, wave_n=20), мост, 720, волны)
L.шаг_марша(dict(БАЗА, gametime=740, **сетка("arow", **{"13,8": 9})), мост, 740, волны)
проверка("на peasants удар без порога", L.МАРШ["фаза"] == "удар"
         and мост.приказы == [(20, "peasants", "", -1, -1)], str(мост.приказы))

# 6. Файл приказа занят — повтор в следующий такт, фаза не теряется.
мост = Мост()
мост.занят = True
волны = []
L.начать_марш(800, 20, "cell", (13, 4), {"via": (13, 8)}, dict(БАЗА))
L.шаг_марша(dict(БАЗА, gametime=820, wave_n=20), мост, 820, волны)
L.шаг_марша(dict(БАЗА, gametime=840, **сетка("arow", **{"13,8": 9})), мост, 840, волны)
проверка("приказ не забран — ждём", L.МАРШ["фаза"] == "сбор" and волны == [])
мост.занят = False
L.шаг_марша(dict(БАЗА, gametime=860, **сетка("arow", **{"13,8": 9})), мост, 860, волны)
проверка("забрали — удар", L.МАРШ["фаза"] == "удар" and len(волны) == 1)

# 7. Между партиями память пуста; без марша блок молчит.
L.МАРШ.clear()
проверка("без марша блок молчит", L.блок_марша(dict(БАЗА)) == [])

print()
print(f"ПРОВАЛОВ: {len(беды)}")
sys.exit(1 if беды else 0)
