#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Сторож ключа `без_атаки` (28.10, серия обороны по нациям): готовая волна НЕ идёт к его базе и НЕ бьёт кучи
дальше `без_атаки_R` клеток от ратуши; кучу у ратуши бьёт как прежде; без ключа — как было (ветка БАЗА при его=0).
Картина — 3:11 первой волны серии: ратуша (12,3), его база (2,12), его армии не видно, свои 6."""
import sys
import strategy_live as SL

# Ратуша в (12,3): без obuild _дом отдаёт (8,8), а здесь важна именно геометрия картины.
SL._дом = lambda st: (12, 3)


def стратегия(ключи):
    ж = SL.ЖиваяСтратегия.__new__(SL.ЖиваяСтратегия)
    ж.п = dict({"штурм_при": 0.92}, **ключи)
    ж.реестр = SL.РеестрВолн()
    в = SL.Волна("W1", 1, 0.0, (12, 3), "cell")
    в.подтверждена, в.размер = True, 6
    return ж, в


база = {"my_cx": 12, "my_cy": 3, "en_base": [2, 12, 2], "grid_n": 16, "brow12": "..e.............", "mil_inf": 6, "mil_shooters": 0, "p1_army": 0,
        "groups": [{"id": 1, "n": 6, "пик": 6, "стрелков": 0, "конных": 0, "cx": 12, "cy": 3}]}
ош = 0

# 1. Без ключа — как было: кучи нет, его=0, волна идёт в его базу (ветка БАЗА).
ж, в = стратегия({})
пр, прич = ж._удар_готовой(в, dict(база, ecells=[]))
if пр is None or "БАЗА" not in прич:
    print("ПРОВАЛ 1: без ключа ветка БАЗА должна работать как прежде:", пр, прич); ош += 1

# 2. С ключом и без куч — ждём дома, в его базу не идём.
ж, в = стратегия({"без_атаки": 1})
пр, прич = ж._удар_готовой(в, dict(база, ecells=[]))
if пр is not None or "БЕЗ_АТАКИ" not in прич:
    print("ПРОВАЛ 2: с ключом волна не должна идти к его базе:", пр, прич); ош += 1

# 3. С ключом куча у ЕГО базы (10 клеток от ратуши) при любом перевесе — не бьём.
пр, прич = ж._удар_готовой(в, dict(база, ecells=[{"x": 3, "y": 12, "n": 1, "пик": 1, "стрелков": 0}]))
if пр is not None or "БЕЗ_АТАКИ" not in прич:
    print("ПРОВАЛ 3: куча у его базы — не цель:", пр, прич); ош += 1

# 4. С ключом куча в двух клетках от ратуши при перевесе 6 на 2 — бьём (местный перевес, оборона).
пр, прич = ж._удар_готовой(в, dict(база, ecells=[{"x": 10, "y": 4, "n": 2, "пик": 2, "стрелков": 0}]))
if пр is None or пр.get("target") != "cell" or (пр.get("cx"), пр.get("cy")) != (10, 4):
    print("ПРОВАЛ 4: куча у ратуши при перевесе — бить:", пр, прич); ош += 1

# 5. Радиус ключом: R=1 — та же куча в двух клетках уже не цель.
ж, в = стратегия({"без_атаки": 1, "без_атаки_R": 1})
пр, прич = ж._удар_готовой(в, dict(база, ecells=[{"x": 10, "y": 4, "n": 2, "пик": 2, "стрелков": 0}]))
if пр is not None or "БЕЗ_АТАКИ" not in прич:
    print("ПРОВАЛ 5: R=1 — куча в двух клетках не цель:", пр, прич); ош += 1

print(f"ошибок: {ош}")
sys.exit(1 if ош else 0)
