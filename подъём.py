#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Сторож на СОЧЕТАНИЯ: правда ли два факта ходят вместе, или это совпадение.

    python3 подъём.py "перехват" "ПЛАНКА СБОРА ВЫРОСЛА"
    python3 подъём.py "простой" "атака началась" [<каталог трасс>]

Зачем. Ночь 23.09 дала 22 находки вида «простой крестьян растёт, и в это же
время идёт атака». Счёт их отклонил: простой встречается в 67% тактов, атака в
11%, и совпадать они обязаны сами собой. Модель честно сообщает о совпадении,
а мы тратим на проверку больше, чем на сам разбор.

МЕРА — ПОДЪЁМ (lift): во сколько раз пара встречается ЧАЩЕ, чем если бы факты
были независимы. Считается по фактам `факты.py`, то есть ровно по тем строкам,
которые видела модель.

    подъём = P(оба) / (P(первого) * P(второго))

Замеренные образцы 23.09, чтобы было с чем сравнивать:

    «перехват» + «ПЛАНКА СБОРА ВЫРОСЛА»   76x   — механизм, брать
    «простой»  + «атака началась»        1,34x  — совпадение, отбрасывать

Порог предлагается 3x, но он не священный: смотреть надо и на подъём, и на то,
сколько раз пара вообще встретилась. Подъём 50x при двух случаях не значит
ничего.
"""
import json, os, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import факты as Ф

if len(sys.argv) < 3:
    raise SystemExit(__doc__)
А, Б = sys.argv[1].lower(), sys.argv[2].lower()
РЕЗ = os.path.expanduser(sys.argv[3] if len(sys.argv) > 3 else "~/coss3-res")

n = a = b = оба = 0
примеры = []
for корень, _, файлы in os.walk(РЕЗ):
    if "coss3_bot.jsonl" not in файлы:
        continue
    путь = os.path.join(корень, "coss3_bot.jsonl")
    части = путь.split(os.sep)
    if len(части) < 4 or not re.match(r"20\d\d-\d\d-\d\d", части[-4]):
        continue
    строки = [json.loads(s) for s in open(путь, encoding="utf-8") if s.strip()]
    for gt, фф in Ф.факты(строки):
        n += 1
        есть_а = any(А in ф.lower() for ф in фф)
        есть_б = any(Б in ф.lower() for ф in фф)
        a += есть_а
        b += есть_б
        if есть_а and есть_б:
            оба += 1
            if len(примеры) < 3:
                примеры.append(f"{частей(части) if False else части[-4]}/{части[-3]}/{части[-2]} gt {gt}")

if not n:
    raise SystemExit(f"трасс не нашлось в {РЕЗ}")
p1, p2, p12 = a / n, b / n, оба / n
print(f"тактов {n}")
print(f"«{sys.argv[1]}»: {a} ({100 * p1:.2f}%)")
print(f"«{sys.argv[2]}»: {b} ({100 * p2:.2f}%)")
print(f"вместе: {оба} ({100 * p12:.2f}%), ожидание при независимости "
      f"{100 * p1 * p2:.3f}%")
if p1 and p2 and p12:
    подъём = p12 / (p1 * p2)
    вердикт = ("СОВПАДЕНИЕ, отбрасывать" if подъём < 3 else
               "стоит смотреть" if оба >= 10 else
               f"подъём высок, но случаев всего {оба} — мало")
    print(f"ПОДЪЁМ: {подъём:.2f}x  -> {вердикт}")
else:
    print("вместе не встречались ни разу")
for п in примеры:
    print("  пример:", п)
