#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""ЗАГРУЗЧИК МОСТА БЕЗ ПРАВКИ ФАЙЛОВ ИГРЫ (7.11, слово игрока: «вот официальный клиент хакатона, контрольные суммы у меня
не сходятся — нужно его пример использовать»).

ПОЧЕМУ. Лобби сравнивает контрольную сумму кода игры (`init.script` `_init_CalcCheckSum` = `StateMachineLibraryCodeMD5Checksum`,
`miscext3.script` `roomchecksum`). `install_bridge.py` вписывает блоки в `progress.inc`, `doprogress.inc` и `lib/miscext2.script` —
сумма у нас другая, чем у остальных участников, и в общую комнату нас не пускают.

КАК ДЕЛАЕТ ОФИЦИАЛЬНЫЙ БОТ (01-AI-bot-setup.exe, `payload/work/01-ai-bot/loader.pas`, `docs/ARCHITECTURE.md`): игра запускается
с ключом `-startscript <loader.pas>`; загрузчик в главном меню создаёт на объекте камеры ЧАСТНУЮ машину состояний
(`GameObjectCreateProgressStateMachineBehaviour` на временном объекте → `BaseObjectBehavioursAssign` на камеру), дописывает в неё
состояние строками `StateMachineStateAddCodeLine`, ставит `StateIndex`/`Interval` и включает. Файлы игры не меняются, библиотека
скриптов та же — сумма сходится. Загрузчик сам проверяет, что сумма до и после установки одна.

ЧТО ДЕЛАЕТ ЭТОТ ФАЙЛ. Собирает `work/coss3/loader.pas` из тех же блоков, что ставит `install_bridge.py` в `progress.inc`
(`block_gameloop.inc`, `block_hstate.inc`, `block_hcmd.inc`), и `work/coss3/preflight.pas` — пробу компиляции тех же строк внутри
невызываемой процедуры (как `preflight/stage-*.pas` официального).

КОНТЕКСТ БЛОКОВ. В `progress.inc` блоки стоят внутри `if (lastprogresstime>0) and (deltatime>0) then begin … end;` состояния
Progress, которое движок зовёт ДЛЯ КАЖДОГО ИГРОКА (`plind` = игрок текущей машины состояний). Из локальных имён Progress блоки берут
только `plind` (проверено: `farmused` в hstate — поле `gPlayer[plind].counter`). Камера одна, поэтому такт загрузчика ПО ОЧЕРЕДИ
берёт игроков: свой игрок интерфейса и все существующие не-ИИ слоты (`bexists and not bai`), по одному за вызов, и выполняет блоки
для него на той же глубине вложенности (`if (plind >= 0) then begin … end;`) — вложенность важна: скаляр, объявленный глубже, в этом
языке не копит (память проекта, 17.09).

ЧЕГО ЗДЕСЬ НЕТ (пока): `block_endgame.inc` (интерфейсный `doprogress.inc`, конец партии для фермы) и `block_kills.inc`
(ворота смерти в `lib/miscext2.script` — правка библиотеки и есть причина расхождения суммы; события гибели придётся брать иначе).
Клиент сетевой партии по-прежнему закрыт условием `not _net_IsClient` в блоках — сначала надо перевести приказы на штатные
сетевые записи (раздел (296) ПЛАН).

    python3 загрузчик.py "<игра>"            # пишет <игра>/work/coss3/loader.pas и preflight.pas
    python3 загрузчик.py --out <папка>        # только собрать, без игры
Запуск игры: из папки игры `cossacks.exe -startscript work/coss3/loader.pas` (Steam: `steam -applaunch 333420 -startscript
"<игра>\\work\\coss3\\loader.pas"`, как `AppController.Launch` официального). Игру до этого вернуть к исходным файлам:
`python install_bridge.py "<игра>" --uninstall`.
"""
import argparse, hashlib, os, sys

ЗДЕСЬ = os.path.dirname(os.path.abspath(__file__))
БЛОКИ = ("block_gameloop.inc", "block_hstate.inc", "block_hcmd.inc")
СОСТОЯНИЕ = "Coss3Tick"
ИНТЕРВАЛ_МС = 100
ПАПКА = "work/coss3"
ПРЕФИКС = "[*] = ;"


def строки_блока(имя: str, каталог: str = "") -> list[str]:
    """Код блока без обёртки `      [*] = ;` — то, что движок видит в секции Code."""
    out = []
    for n, l in enumerate(open(os.path.join(ЗДЕСЬ, имя), encoding="latin-1").read().split("\n"), 1):
        if not l.strip():
            continue
        i = l.find(ПРЕФИКС)
        if i < 0:
            raise SystemExit(f"{имя}:{n}: строка не в форме `[*] = ;` — {l[:80]!r}")
        # (299) `@@OUT@@` - заполнитель каталога, куда игра пишет файлы моста. Его подставляет
        # install_bridge.py:171 (`text.replace("@@OUT@@", outdir)`), а здесь подстановки не было:
        # в loader.pas уходило литеральное @@OUT@@, и игра писала пульс в файл `@@OUT@@coss3_hb.dat`
        # рядом с cossacks.exe. Политика такой файл не ищет никогда - поймано живой проверкой 7.11.
        # Пусто = относительный путь, то есть папка игры: как у установщика без --outdir.
        код = l[i + len(ПРЕФИКС):].replace("@@OUT@@", каталог)
        if any(ord(ch) > 127 for ch in код):
            raise SystemExit(f"{имя}:{n}: не-ASCII в коде блока")
        out.append(код)
    return out


def тело(каталог: str = "") -> list[str]:
    """Верх такта: выбрать игрока по очереди, затем блоки на глубине 1, как в Progress."""
    head = [
        "// coss3 bridge tick: generated by zagruzchik.py, the same blocks install_bridge.py puts into progress.inc.",
        "// Progress runs per player; the camera callback runs once, so it takes the players in turn.",
        "var c3rt : Integer = ParserSelectByKey('coss3_rt');",
        "if (c3rt = 0) then c3rt := ParserCreate('coss3_rt');",
        "var c3me : Integer = GetPlayerIndexInterfaceIO;",
        "var c3last : Integer = ParserGetIntValueByKeyByHandle(c3rt, 'last');",
        "var c3k : Integer;",
        "var plind : Integer = -1;",
        "for c3k := 1 to gc_MaxPlayerCount-1 do",
        "begin",
        "   var c3p : Integer = (c3last + c3k) mod (gc_MaxPlayerCount-1);",
        "   if (plind < 0) then",
        "   if (c3p = c3me) or ((gPlayer[c3p].bexists) and (not gPlayer[c3p].bai)) then",
        "   plind := c3p;",
        "end;",
        "if (plind >= 0) then ParserSetIntValueByKeyByHandle(c3rt, 'last', plind);",
        "ParserSetIntValueByKeyByHandle(c3rt, 'ticks', ParserGetIntValueByKeyByHandle(c3rt, 'ticks') + 1);",
        "if (plind >= 0) and (plind < gc_MaxPlayerCount-1) then",
        "begin",
    ]
    код = []
    for имя in БЛОКИ:
        код.append(f"// ===== {имя} =====")
        код += строки_блока(имя, каталог)
    return head + код + ["end;"]


def паскаль_строка(s: str) -> str:
    return "'" + s.replace("'", "''") + "'"


def собрать_loader(код: list[str], sha: str) -> str:
    add = "\n".join(f"   StateMachineStateAddCodeLine(sm,{паскаль_строка(СОСТОЯНИЕ)},{паскаль_строка(l)});" for l in код)
    return f"""// coss3 bridge loader. Generated by zagruzchik.py from {', '.join(БЛОКИ)}. source_sha256={sha}
// Modelled on the official hackathon bot loader (01-AI-bot, work/01-ai-bot/loader.pas): a private state machine on the camera,
// filled with StateMachineStateAddCodeLine. No game file is modified, so the script library checksum stays the stock one.

procedure C3L_AddTick(sm : Integer);
begin
{add}
end;

procedure C3L_Reject(report : Integer; reason : String);
begin
   ParserSetValueByKeyByHandle(report,'rejected_reason',reason);
   ParserSetIntValueByKeyByHandle(report,'complete',1);
   ParserSaveToFileByHandle(report,'{ПАПКА}/loader.cfg');
   Log('COSS3_LOADER rejected: '+reason);
end;

function C3L_Preflight(report : Integer) : Boolean;
begin
   Result:=False;
   var p : Integer = ParserCreate('coss3_preflight');
   if p=0 then exit;
   ParserClearByHandle(p);
   ParserSetIntValueByKeyByHandle(p,'marker',0);
   var before : String = StateMachineLibraryCodeMD5Checksum;
   var passed : Boolean = EvaluateFile('{ПАПКА}/preflight.pas');
   ParserSetBoolValueByKeyByHandle(report,'preflight_evaluate',passed);
   ParserSetIntValueByKeyByHandle(report,'preflight_marker',ParserGetIntValueByKeyByHandle(p,'marker'));
   passed:=passed and (ParserGetIntValueByKeyByHandle(p,'marker')=1) and (StateMachineLibraryCodeMD5Checksum=before);
   Result:=passed;
end;

procedure C3L_Start;
begin
   Log('COSS3_LOADER begin source={sha}');
   var report : Integer = ParserCreate('coss3_loader');
   if report=0 then exit;
   ParserClearByHandle(report);
   ParserSetValueByKeyByHandle(report,'source_sha256','{sha}');
   ParserSetIntValueByKeyByHandle(report,'setup_complete',0);
   ParserSetIntValueByKeyByHandle(report,'complete',0);
   var before : String = StateMachineLibraryCodeMD5Checksum;
   ParserSetValueByKeyByHandle(report,'library_before',before);
   ParserSetValueByKeyByHandle(report,'cached_library_digest',gstring_checksumlong);
   ParserSaveToFileByHandle(report,'{ПАПКА}/loader.cfg');
   if gstring_checksumlong<>before then
   begin C3L_Reject(report,'base_scripts_differ'); exit; end;
   if gInterface.gamemode<>gc_gamemode_mainmenu then
   begin C3L_Reject(report,'main_menu_only'); exit; end;
   if not C3L_Preflight(report) then
   begin C3L_Reject(report,'native_compile_preflight'); exit; end;

   var camera : Integer = GetCameraHandle;
   ParserSetIntValueByKeyByHandle(report,'camera_handle',camera);
   if camera=0 then
   begin C3L_Reject(report,'camera_missing'); exit; end;
   if GetBaseObjectBehaviourCount(camera)<>0 then
   begin C3L_Reject(report,'camera_has_existing_behaviours (another bot loader running?)'); exit; end;
   var librarySM : Integer = StateMachineLibraryGet('.\\data\\scripts\\misc\\projectile.aix');
   if librarySM=0 then
   begin C3L_Reject(report,'native_helper_library_not_loaded'); exit; end;
   var miscPlayer : Integer = GetPlayerHandleByName('misc');
   if miscPlayer=0 then
   begin C3L_Reject(report,'misc_player_missing'); exit; end;
   var helper : Integer = CreatePlayerGameObjectHandleByHandle(miscPlayer,'misc','point',0,0,0);
   if helper=0 then
   begin C3L_Reject(report,'helper_create'); exit; end;
   SetGameObjectVisibleByHandle(helper,False);
   var helperBehaviour : Integer = GameObjectCreateProgressStateMachineBehaviour(helper,'','NothingEmpty',False,False,250);
   if helperBehaviour=0 then
   begin GameObjectRequestToDestroyByHandle(helper); C3L_Reject(report,'source_behaviour_create'); exit; end;
   BaseObjectBehavioursAssign(helper,camera);
   var behaviour : Integer = GetBaseObjectBehaviourByClassName(camera,'TXProgressStateMachineBehaviour');
   if behaviour=0 then
   begin GameObjectRequestToDestroyByHandle(helper); C3L_Reject(report,'camera_behaviour_copy'); exit; end;
   var privateSM : Integer = GetBehaviourIntProperty(behaviour,'StateMachine');
   ParserSetIntValueByKeyByHandle(report,'private_sm',privateSM);
   if (privateSM=0) or (privateSM=librarySM) then
   begin GameObjectRequestToDestroyByHandle(helper); C3L_Reject(report,'camera_private_sm'); exit; end;
   C3L_AddTick(privateSM);
   var stateIndex : Integer = StateMachineGetStateIndByName(privateSM,'{СОСТОЯНИЕ}');
   ParserSetIntValueByKeyByHandle(report,'state_index',stateIndex);
   if stateIndex<0 then
   begin GameObjectRequestToDestroyByHandle(helper); C3L_Reject(report,'callback_state_missing'); exit; end;
   SetBehaviourIntProperty(behaviour,'StateIndex',stateIndex);
   SetBehaviourIntProperty(behaviour,'Interval',{ИНТЕРВАЛ_МС});
   var after : String = StateMachineLibraryCodeMD5Checksum;
   ParserSetValueByKeyByHandle(report,'library_after_setup',after);
   if after<>before then
   begin GameObjectRequestToDestroyByHandle(helper); C3L_Reject(report,'library_changed_after_setup'); exit; end;
   GameObjectRequestToDestroyByHandle(helper);
   ParserSetIntValueByKeyByHandle(report,'setup_complete',1);
   ParserSetIntValueByKeyByHandle(report,'complete',1);
   ParserSaveToFileByHandle(report,'{ПАПКА}/loader.cfg');
   SetBehaviourBoolProperty(behaviour,'Enabled',True);
   Log('COSS3_LOADER armed camera='+IntToStr(camera)+' private_sm='+IntToStr(privateSM)+' md5='+after);
end;

C3L_Start;
"""


def собрать_preflight(код: list[str]) -> str:
    """Проба компиляции: те же строки внутри невызываемой процедуры (официальный preflight/stage-*.pas делает так же)."""
    тело_пробы = "\n".join("   " + l for l in код)
    return f"""// coss3 bridge preflight: compile-only probe of the tick code. The procedure is never called.
procedure C3P_Probe;
begin
{тело_пробы}
end;

ParserSetIntValueByKeyByHandle(ParserSelectByKey('coss3_preflight'),'marker',1);
"""


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("game", nargs="?", help="папка игры: файлы лягут в <игра>/work/coss3")
    ap.add_argument("--out", help="собрать в эту папку вместо игры")
    ap.add_argument("--outdir", default="",
                    help="каталог, куда ИГРА пишет файлы моста (@@OUT@@ в блоках). "
                         "Пусто - папка игры, как у install_bridge.py без --outdir")
    a = ap.parse_args()
    if not a.game and not a.out:
        ap.error("нужна папка игры или --out")
    каталог = a.outdir or ""
    if каталог and not каталог.isascii():
        ap.error("--outdir должен быть ASCII: блоки .inc не допускают иных букв в коде")
    if каталог and not каталог.endswith(("\\", "/")):
        каталог += "\\"          # имя файла клеится сразу за каталогом
    код = тело(каталог)
    sha = hashlib.sha256("\n".join(код).encode("latin-1")).hexdigest()
    куда = a.out or os.path.join(a.game, *ПАПКА.split("/"))
    os.makedirs(куда, exist_ok=True)
    loader = собрать_loader(код, sha).encode("latin-1")      # кодируем ДО open(..., "wb"): упавший кодировщик не оставит пустой файл
    pre = собрать_preflight(код).encode("latin-1")
    open(os.path.join(куда, "loader.pas"), "wb").write(loader)
    open(os.path.join(куда, "preflight.pas"), "wb").write(pre)
    print(f"собрано: {куда}/loader.pas ({len(код)} строк такта, {len(loader)} байт), preflight.pas ({len(pre)} байт), source_sha256 {sha[:16]}…")
    for имя in БЛОКИ:
        print(f"  {имя}: {len(строки_блока(имя))} строк")
    if a.game:
        print('запуск: из папки игры  cossacks.exe -startscript work/coss3/loader.pas   (до этого: install_bridge.py --uninstall)')
    return 0


if __name__ == "__main__":
    sys.exit(main())
