#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Сторож анализа противника (7.10, §118, `анализ_врага.py`) на синтетических тактах и на записи партии А."""
import os
import анализ_врага as АВ

ошибок = 0


def проверка(имя, усл):
    global ошибок
    print(("ОК   " if усл else "ПРОВАЛ ") + имя)
    ошибок += 0 if усл else 1


def такт(t, его, наши=None):
    return {"gametime": t, "my_cx": 3, "my_cy": 13, "en_base": [2, 1], "map_w": 256,
            "ecells": его, "ocells": наши or [{"x": 2, "y": 12, "n": 40, "пик": 40, "стрелков": 0}],
            "obuild": [{"тип": "center", "x": 56, "z": 216}, {"тип": "mill", "x": 56, "z": 216}]}


а = АВ.АнализВрага()
лагерь = {"x": 2, "y": 10, "n": 20, "пик": 18, "стрелков": 2, "идут": 0}
поток = {"x": 2, "y": 5, "n": 8, "пик": 4, "стрелков": 4, "идут": 8, "tx": 2, "ty": 10}
for t in range(300, 345, 5):
    о = а.обновить(такт(t, [лагерь, поток]))
виды = {н["вид"] for н in о["находки"]}
проверка("1. лагерь в 3 клетках, 40+ с — найден", "лагерь" in виды)
проверка("2. поток к своему лагерю — не отрыв", "отрыв" not in виды)
проверка("3. лагерь в 25 с — ещё не лагерь", "лагерь" not in {н["вид"] for н in АВ.АнализВрага().обновить(такт(300, [лагерь]))["находки"]})
стрелки = {"x": 3, "y": 11, "n": 7, "пик": 0, "стрелков": 7, "идут": 7, "tx": 3, "ty": 13}
о = а.обновить(такт(350, [лагерь, стрелки]))
сб = [н for н in о["находки"] if н["вид"] == "стрелки без пик"]
проверка("4. стрелки без пик к ратуше — найдены, цель крестьяне", bool(сб) and "крестьяне" in сб[0]["цель"])
с_пиками = [стрелки, {"x": 3, "y": 10, "n": 10, "пик": 10, "стрелков": 0, "идут": 10, "tx": 3, "ty": 13}]
проверка("5. стрелки с пиками туда же — не «без пик»",
         not [н for н in а.обновить(такт(355, [лагерь] + с_пиками))["находки"] if н["вид"] == "стрелки без пик"])
АВ.текущий(такт(600, [лагерь]))
р1 = АВ._ТЕКУЩИЙ["а"]
АВ.текущий(такт(600, [лагерь]))
проверка("6. тот же такт — тот же анализ", АВ._ТЕКУЩИЙ["а"] is р1)
АВ.текущий(такт(20, [лагерь]))
проверка("7. время назад — новая партия", АВ._ТЕКУЩИЙ["а"] is not р1)
к = os.path.expanduser("~/coss3-res-игрок-отл/igrok_07_10_pA/1")
if os.path.exists(к):
    первые, потеря = АВ.прогон(к, печать=False)
    проверка("8. партия А: лагерь раньше первых потерь крестьян на 2+ минуты",
             "лагерь" in первые and потеря and потеря - первые["лагерь"] >= 120)
print("ошибок:", ошибок)
