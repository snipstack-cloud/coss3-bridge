# -*- coding: utf-8 -*-
"""«В поле» считается по КЛЕТКЕ, и одинаково в двух блоках (§99, 5.10).

Что нашлось на маке игрой рукой из снимка 11:00 проверки p5: наша куча 74 стояла
в клетке (10,10) при ратуше в (12,13) — 3,6 клетки, около 58 единиц. По старой
мерке блока она НЕ была «в поле» (порог 60 единиц), а свободной не считалась,
потому что стояла с приказом. Итог: ни RETREAT, ни ENGAGE её не брали (они
отбирают дальних), ATTACK и MOVE берут только свободных. Главная сила была
недоступна ни одному приказу.

Теперь мерка — та же сетка 16x16, которой мост говорит с моделью: боец в поле,
если его клетка не совпадает с клеткой ратуши и не соседняя с ней (дальше одной
клетки по Чебышёву).

ПОЧЕМУ ЭТА ПРОВЕРКА СУЩЕСТВУЕТ. Мерка живёт в ДВУХ блоках: `block_hstate.inc`
отдаёт `mil_away` («сколько в поле»), `block_hcmd.inc` отбирает бойцов для
retreat и engage («кого можно приказать»). Они в разных областях видимости, и
общей константы у них быть не может — имя из чужого блока не компилируется.
Значит числа продублированы, а дубль расходится молча: ровно так сетка 16
уже дублировалась (`hacn` против `cHmGrid`) без всякой защиты. Расхождение
вернуло бы §99 — мост отдаёт «в поле N», а приказать их не может.

Проверяется:
  1. оба блока меряют поле КЛЕТКАМИ, а не 60 единицами;
  2. сетка и домашний радиус в двух блоках СОВПАДАЮТ;
  3. радиус сетки в `block_hcmd` равен `cHmGrid` блока состояния;
  4. Чебышёв, а не сумма и не евклид: берётся БОЛЬШАЯ из двух разниц;
  5. python не остался со словами «дальше 60» — они стали ложью.
"""
import io
import os
import re
import sys

ЗДЕСЬ = os.path.dirname(os.path.abspath(__file__))
ошибок = 0


def проверить(условие, что):
    global ошибок
    if not условие:
        ошибок += 1
        print("  СБОЙ:", что)
    else:
        print("  ок:", что)


def читать(имя):
    return io.open(os.path.join(ЗДЕСЬ, имя), encoding="latin-1").read()


def число(текст, образец):
    м = re.search(образец, текст)
    return int(м.group(1)) if м else None


СОСТ = читать("block_hstate.inc")
КМД = читать("block_hcmd.inc")

print("1. мерка поля — клетка, а не 60 единиц")
проверить("if (hswd > 60) then" not in СОСТ,
          "mil_away больше не считает по 60 единицам")
проверить("if (hadd > 60) then" not in КМД,
          "отбор retreat/engage больше не считает по 60 единицам")
проверить("if (hqdc > cHmHome) then" in СОСТ,
          "mil_away судит по клеткам (cHmHome)")
проверить("if (hafdc > hafr) then hatake2 := True;" in КМД,
          "отбор retreat/engage судит по клеткам (hafr)")

print("2. два блока меряют ОДНИМ числом")
домой_сост = число(СОСТ, r"const cHmHome = (\d+);")
домой_кмд = число(КМД, r"var hafr : Integer = (\d+);")
сетка_сост = число(СОСТ, r"var hqn  : Integer = (\d+);")
сетка_кмд = число(КМД, r"var hafn : Integer = (\d+);")
проверить(домой_сост == 1, "домашний радиус = 1 клетка (ратуша и соседние)")
проверить(домой_сост == домой_кмд,
          "радиус дома совпал: состояние %s, команды %s" % (домой_сост, домой_кмд))
проверить(сетка_сост == сетка_кмд,
          "сетка совпала: состояние %s, команды %s" % (сетка_сост, сетка_кмд))

print("3. сетка та же, которой мост говорит с моделью")
cHmGrid = число(СОСТ, r"const cHmGrid = (\d+);")
проверить(cHmGrid == 16, "cHmGrid = 16, как в сетке запроса")
проверить(сетка_сост == cHmGrid,
          "копия сетки в счёте поля равна cHmGrid (%s)" % cHmGrid)
проверить(сетка_кмд == cHmGrid,
          "копия сетки в отборе бойцов равна cHmGrid (%s)" % cHmGrid)

print("4. Чебышёв, а не сумма")
проверить("if (hqdc < hqdy) then hqdc := hqdy;" in СОСТ,
          "состояние берёт БОЛЬШУЮ из двух разниц")
проверить("if (hafdc < hafdy) then hafdc := hafdy;" in КМД,
          "команды берут БОЛЬШУЮ из двух разниц")
проверить("hqdc + hqdy" not in СОСТ and "hafdc + hafdy" not in КМД,
          "разницы не складываются (это был бы ромб, а не квадрат)")

print("5. мерка названа вслух в логе приказа")
проверить("[field>" in КМД,
          "RETREAT/ENGAGE/skipped пишут в лог порог и клетку ратуши")

print("6. python не остался со словами «дальше 60»")
for имя in ("llm_policy.py", "strategy_live.py", "coss3_bridge.py", "send.py"):
    текст = io.open(os.path.join(ЗДЕСЬ, имя), encoding="utf-8").read()
    проверить("дальше 60" not in текст and "60 от базы" not in текст
              and "60 от ратуши" not in текст,
              "%s: слов про 60 единиц не осталось" % имя)

print()
print("ошибок:", ошибок)
sys.exit(1 if ошибок else 0)
