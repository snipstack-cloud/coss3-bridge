"""Порог еды судит и ПОКУПКУ: mil.1 за 750 еды не берётся на пустой амбар.

ЧЕМ КУПЛЕН. Живая партия 4.10 против невозможного нативного ИИ. Стратегия
шт_s2 заказала `mil.1` на 70-й секунде, когда в амбаре лежало 779 еды при
пороге 800. Движок покупку разрешил — на одну единицу хватало, — еда упала до
нуля к 1:34, и крестьян стало 10 из 18: восемь умерли от голода. Ключ
--food-floor тогда умел только ставить людей на еду и покупок не судил.

mil.1 — это +140 % к ЕДЕ (`dmscript.global:550`), то есть прокачка, ради
которой и копят; отказ здесь не отменяет её, а откладывает до амбара в
порог+750.
"""
import llm_policy as L

ПОРОГ = 800


def такт(**п):
    с = dict(gametime=70, food=779, peasants=18, on_food=0,
             mil_inf=4, mil_shooters=0, mil_cav=0)
    с.update(п)
    return с


провалы = []


def ждём(что: str, условие: bool):
    if not условие:
        провалы.append(что)


# Без ключа мост в покупку не вмешивается вовсе.
L.ЕДА_ПОРОГ = 0
ждём("без ключа отказа быть не должно",
     L.прокачка_еды_рано(такт(), "mil.1") is None)

L.ЕДА_ПОРОГ = ПОРОГ

# --- 1. ТОТ САМЫЙ СЛУЧАЙ: 779 еды, цена 750.
отказ = L.прокачка_еды_рано(такт(), "mil.1")
ждём("при 779 еды mil.1 должна быть отвергнута", отказ is not None)
if отказ:
    for число in ("750", "779", "800"):
        ждём(f"в отказе нет числа {число}", число in отказ)
    ждём("отказ не называет живую партию", "4.10" in отказ)

# --- 2. Амбар порог+цена и выше — покупка проходит.
ждём("при 1550 еды отказа быть не должно",
     L.прокачка_еды_рано(такт(food=ПОРОГ + L.ЦЕНА_MIL1), "mil.1") is None)
ждём("при 3733 еды отказа быть не должно (случай 16.09)",
     L.прокачка_еды_рано(такт(food=3733), "mil.1") is None)

# --- 3. Границы ключа те же, что у расстановки людей: срок и число бойцов.
ждём("после 300 с ключ молчит",
     L.прокачка_еды_рано(такт(gametime=301), "mil.1") is None)
ждём("при 20 бойцах ключ молчит",
     L.прокачка_еды_рано(такт(mil_inf=20), "mil.1") is None)
ждём("бойцы считаются всех родов",
     L.прокачка_еды_рано(такт(mil_inf=7, mil_shooters=7, mil_cav=6),
                         "mil.1") is None)

# --- 4. ПРАВИЛО УЗКОЕ: прочие прокачки не трогаем — их цены в python нет.
for чужая in ("mil.2", "bla.1", "aca.1", "", None):
    ждём(f"прокачка {чужая!r} не должна судиться этим ключом",
         L.прокачка_еды_рано(такт(), чужая) is None)

# 6.10, проверка 6: любая прокачка с ценой едой — всю партию, по цене из upg_avail
_ст = {"gametime": 582, "food": 1186, "mil_inf": 40, "upg_avail": "bar.pikeman.1.3=f1100g400i0"}
if L.прокачка_еды_рано(_ст, "bar.pikeman.1.3") is None:
    провалы.append("ступень атаки за 1100 еды при 1186 в амбаре на 9:42 должна отложиться")
if L.прокачка_еды_рано(dict(_ст, food=2500), "bar.pikeman.1.3") is not None:
    провалы.append("при 2500 еды ступень за 1100 должна пройти")
if L.прокачка_еды_рано(dict(_ст, upg_avail=""), "bar.pikeman.1.3") is not None:
    провалы.append("без цены прокачку судить нельзя")

if провалы:
    for п in провалы:
        print("СТОП:", п)
    raise SystemExit(1)
print(f"ХОРОШО: mil.1 за {L.ЦЕНА_MIL1} еды отвергается, пока в амбаре меньше "
      f"{ПОРОГ + L.ЦЕНА_MIL1}, и только до {L.ЕДА_ПОРОГ_ДО} с; прочие с ценой едой — всю "
      f"партию, если амбар упал бы ниже порога")
