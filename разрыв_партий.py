# -*- coding: utf-8 -*-
"""Где трасса делится на партии — ОДНО место для всех, кто её читает.

Повод, 1.10. `run_report.py` и `log_review.py` резали трассу по первому же откату
игрового времени и напечатали «партий 2» там, где партия была ОДНА. Снимок это
доказал: 133 записи, время 4 -> 674, ни одного отката, ни одной дыры. А в трассе
был шаг назад 124 -> 110, и вот откуда он:

    решение готовилось 41 с при бюджете такта 11 с — применяется на 58
    игровых секунд позже

То есть запись такта несёт время, когда запрос БЫЛ СОБРАН, а медленный ответ
приходит не по порядку. Откат на десятки секунд — это поздний ответ, а не новая
партия. Цена ошибки — все счёты «за партию» в отчёте: число тактов, исход,
крестьяне врага «от и до» делятся между двумя половинами одной партии.

Признак НОВОЙ партии отличается от позднего ответа двумя вещами сразу: новая
партия начинается близко к нулю, а поздний ответ отстаёт не больше, чем модель
думает. В партии 1.10 худшее отставание было 58 игровых секунд, поэтому пороги
взяты с запасом в три раза.

ВАЖНО: про «откат, признанный поздним ответом», читатель должен узнавать ВСЛУХ —
молчаливое склеивание так же опасно, как молчаливый разрыв. Для этого функция
отдаёт и список замечаний.
"""
from __future__ import annotations

# Новая партия, если время упало СИЛЬНО...
ПАДЕНИЕ_ПАРТИИ = 180
# ...или если оно упало заметно И пришло к самому началу партии.
НАЧАЛО_ПАРТИИ = 30
ПАДЕНИЕ_К_НАЧАЛУ = 90


def новая_партия(прежний_gt: int, новый_gt: int) -> bool:
    """Новая ли это партия, а не поздно применённое решение."""
    if новый_gt >= прежний_gt:
        return False
    падение = прежний_gt - новый_gt
    if падение > ПАДЕНИЕ_ПАРТИИ:
        return True
    return новый_gt <= НАЧАЛО_ПАРТИИ and падение > ПАДЕНИЕ_К_НАЧАЛУ


def разделить(записи: list[dict]) -> tuple[list[list[dict]], list[str]]:
    """Трасса -> (список партий, замечания про откаты времени).

    Замечания перечисляют КАЖДЫЙ откат, признанный поздним ответом: иначе
    склейка двух партий в одну была бы такой же тихой, как прежний разрыв.
    """
    партии: list[list[dict]] = []
    тек: list[dict] = []
    замечания: list[str] = []
    for р in записи:
        gt = р.get("gt", 0) or 0
        if тек:
            прежний = тек[-1].get("gt", 0) or 0
            if gt < прежний:
                if новая_партия(прежний, gt):
                    партии.append(тек)
                    тек = []
                else:
                    замечания.append(
                        f"время шло назад {прежний} -> {gt} ({прежний - gt} с): "
                        "это поздно применённое решение, а не новая партия — "
                        "такт собран раньше, чем ответ пришёл")
        тек.append(р)
    if тек:
        партии.append(тек)
    return партии, замечания
