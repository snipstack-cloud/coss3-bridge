# -*- coding: utf-8 -*-
"""Слой ФАКТОВ над трассой: не числа, а готовые утверждения.

Зачем. Разбор трассы языковой моделью 22-23.09 померен на трёх партиях:
на 51-64 тактах годен, на 152 вырождается. ВСЕ ложные находки были
арифметическими или разборными — «4+14=18 зданий», «процент из одной колонки,
имя из другой», «сумма BALANCE не сходится с крестьянами». То есть модель
ошибается ровно там, где ей приходится считать.

Факт вычисляется здесь, питоном, и ложным быть не может. Модели остаётся
искать СОЧЕТАНИЯ и ПОВТОРЫ — единственное, что у неё сегодня выходило.

ЧЕГО ЗДЕСЬ БЫТЬ НЕ ДОЛЖНО. Факт — это то, что ВИДНО В ТРАССЕ, а не то, что я
думаю об игре. «Повтор BUILD по строящемуся» — факт. «Бот плохо воюет» — нет.
Каждый факт ниже сверен руками на нескольких тактах 22-23.09; неверный факт
опаснее сырого числа, потому что выглядит авторитетно и дальше не проверяется.

    python3 факты.py <трасса.jsonl>          # напечатать факты по тактам
"""
from __future__ import annotations
import json, os, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from coss3_bridge import ROLE, RESOURCE

ИМЯ_РОЛИ = {v: k for k, v in ROLE.items()}
ИМЯ_РЕСУРСА = {v: k for k, v in RESOURCE.items()}
ПОРОГ_ЕДЫ = 500          # ниже него движок стопорит производство (проверено кодом игры)


def _ч(x):
    try:
        return int(float(x))
    except (TypeError, ValueError):
        return 0


def _строится(st):
    """Что строится сейчас: {роль: процент}. Формат wip — `роль/предел/людей/%`."""
    из = {}
    for кусок in str(st.get("wip") or "").split(","):
        поля = кусок.split("/")
        if len(поля) >= 4 and поля[0].strip():
            из[поля[0].strip()] = _ч(поля[-1])
    return из


ГОТОВЫХ = {"minegold": "mines_gold", "mineiron": "mines_iron",
           "minecoal": "mines_coal", "center": "centers", "mill": "mills",
           "smith": "smiths", "ba17": "ba17", "store": "my_stores",
           "house": "houses"}


def факты(строки):
    """[(gt, [факт, ...]), ...] по всей партии. Серии считаются здесь же."""
    из = []
    еда_подряд = 0
    простой_подряд, простой_сказано = 0, 0
    была_атака = False
    прошлая_фаза, фаза_с = None, None
    for d in строки:
        st = d.get("state") or {}
        if not st:
            continue
        gt = _ч(d.get("gt"))
        ф = []
        строится = _строится(st)
        кмд = d.get("cmds") or []

        # --- повторы заказа: проверено счётом 22-23.09 по base25/local_events
        for c in кмд:
            if c.get("cmd") != "BUILD":
                continue
            роль = ИМЯ_РОЛИ.get(c.get("a1"), str(c.get("a1")))
            надо = _ч(c.get("a2"))
            if роль in строится:
                ф.append(f"повтор BUILD {роль}: она УЖЕ СТРОИТСЯ ({строится[роль]}%)")
            готово = _ч(st.get(ГОТОВЫХ.get(роль, "")))
            if ГОТОВЫХ.get(роль) and готово >= надо:
                ф.append(f"пустой BUILD {роль} всего {надо}: их уже {готово}")

        # --- BUILDERS без BUILD: промпт моста прямо зовёт это пустым ходом
        строители = [c for c in кмд if c.get("cmd") == "BUILDERS" and _ч(c.get("a1")) > 0]
        if строители and not any(c.get("cmd") == "BUILD" for c in кмд):
            ф.append(f"BUILDERS {_ч(строители[0].get('a1'))} без BUILD — пустой ход")

        # --- BALANCE просит больше людей, чем есть (мост урежет сам)
        бал = [c for c in кмд if c.get("cmd") == "BALANCE"]
        if бал:
            сумма = sum(_ч(c.get("a2")) for c in бал)
            if сумма > _ч(st.get("peasants")):
                ф.append(f"BALANCE просит {сумма} чел. при {_ч(st.get('peasants'))} крестьянах")

        # --- отказы и вето моста: это ЕГО слова, а не модели
        for r in (d.get("rejected") or []):
            ф.append("мост отбросил: " + str(r)[:70])
        if str(d.get("veto") or "").strip():
            ф.append("вето: " + str(d["veto"])[:70])

        # --- еда ниже порога, серией
        # Серии — СОБЫТИЯМИ, а не каждый такт. Первый прогон 23.09 дал факты в
        # 87% тактов: простой печатался 26 раз подряд, атака 87 раз. Такая
        # выжимка не короче числовой, а значит не лечит ничего.
        было = еда_подряд
        еда_подряд = еда_подряд + 1 if _ч(st.get("food")) < ПОРОГ_ЕДЫ else 0
        if еда_подряд == 1:
            ф.append(f"еда упала ниже {ПОРОГ_ЕДЫ} ({_ч(st.get('food'))})")
        elif еда_подряд and еда_подряд % 10 == 0:
            ф.append(f"еда ниже {ПОРОГ_ЕДЫ} уже {еда_подряд} тактов подряд")
        elif было >= 3 and not еда_подряд:
            ф.append(f"еда вернулась выше {ПОРОГ_ЕДЫ} после {было} тактов")

        # --- люди без дела, серией
        без_дела = _ч(st.get("idle_pea"))
        было_п = простой_подряд
        простой_подряд = простой_подряд + 1 if без_дела > 0 else 0
        if простой_подряд == 3:
            ф.append(f"простой: {без_дела} крестьян без дела третий такт подряд")
            простой_сказано = без_дела
        elif простой_подряд > 3 and без_дела >= 2 * max(1, простой_сказано):
            ф.append(f"простой РАСТЁТ: {без_дела} крестьян без дела, "
                     f"{простой_подряд} тактов подряд")
            простой_сказано = без_дела
        elif было_п >= 3 and not простой_подряд:
            ф.append(f"простой кончился после {было_п} тактов")
            простой_сказано = 0

        # --- волна: событиями, а не одинаковой строкой в тридцати тактах
        m = d.get("march") if isinstance(d.get("march"), dict) else None
        фаза = (m or {}).get("фаза")
        if фаза != прошлая_фаза:
            if фаза:
                ф.append(f"волна: фаза «{фаза}», послано {(m or {}).get('послано')}, "
                         f"цель {(m or {}).get('цель')}")
            elif прошлая_фаза:
                ф.append(f"волна кончилась (была «{прошлая_фаза}»)")
            прошлая_фаза, фаза_с = фаза, gt
        elif фаза and фаза_с is not None and gt - фаза_с >= 60:
            ф.append(f"волна стоит в фазе «{фаза}» уже {gt - фаза_с} с")
            фаза_с = gt

        # --- бой: РАЗНИЦА за такт, не накопленный итог
        if из:
            п, пред_п = d.get("потери") or {}, из[-1][2]
            d_ = {k: _ч(п.get(k)) - _ч(пред_п.get(k)) for k in
                  ("en_pea", "en_mil", "my_pea", "my_mil")}
            if any(d_.values()):
                ф.append("за такт: убито крестьян {en_pea}, бойцов {en_mil}; "
                         "потеряно {my_pea}/{my_mil}".format(**d_))
        есть_атака = bool(d.get("attack"))
        if есть_атака and not была_атака:
            ф.append(f"атака началась, цель {d.get('target')}")
        elif была_атака and not есть_атака:
            ф.append("атака кончилась")
        была_атака = есть_атака
        из.append((gt, ф, d.get("потери") or {}))
    return [(gt, ф) for gt, ф, _ in из]


def кратко(st):
    """Одна строка состояния — на случай, если факт нужно посмотреть в контексте."""
    return (f"еда {_ч(st.get('food'))}, дер {_ч(st.get('wood'))}, кам {_ч(st.get('stone'))}, "
            f"зол {_ч(st.get('gold'))} | крест {_ч(st.get('peasants'))}"
            f"({_ч(st.get('idle_pea'))} без дела) | пех {_ч(st.get('mil_inf'))}, "
            f"кав {_ч(st.get('my_freewar'))}")


if __name__ == "__main__":
    строки = [json.loads(s) for s in open(sys.argv[1], encoding="utf-8") if s.strip()]
    всего = 0
    for gt, ф in факты(строки):
        if ф:
            всего += 1
            print(f"{gt:>5} | " + "; ".join(ф))
    сост = sum(1 for d in строки if d.get("state"))
    print(f"\nтактов с состоянием {сост}, из них с фактами {всего} "
          f"({100 * всего // max(1, сост)}%)")
