#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""МЕРА «ПОРОГ В ПОЛЕ ПО КЛЕТКЕ ДОЕХАЛ» на живой игре (5.10, §99).

Мера названа маком ДО правки, здесь она только исполняется — тремя приказами и
снимками состояния между ними:

  1. `MOVE 200 cell (cx,cy) g1` — увести кучу в клетку в ДВУХ клетках от ратуши.
     Отбор у MOVE прежний (свободные из дома), и правки он не касается;
  2. дождаться, пока дойдут: группа 1 стоит в названной клетке;
  3. `RETREAT 200 home g2` — ТО, ЧТО ПРОВЕРЯЕТСЯ. Отбор retreat идёт по мерке
     «в поле», и до правки куча в двух клетках (около 32 единиц при клетке 16)
     порога 60 единиц не проходила: приказ не брал никого. Если правка доехала,
     группа 2 родится числом, равным куче;
  4. снимки `ocells` до и после — куча сдвинулась к ратуше;
  5. `MOVE` туда же и `ENGAGE 200 army g4` — то же для второго приказа, который
     держал 60.

ПОЧЕМУ ЧИСЛА БЕРУТСЯ ИЗ ГРУПП, А НЕ ИЗ ЛОГА ИГРЫ. Мак просил строку лога с
числом взятых. В этой установке `cossacks.ini` говорит `LogFileEnabled = false`,
и лог не пишется вовсе; включать его значит перезапускать игру, а ini читается
при старте. Номер группы даёт то же число ЧЕСТНЕЕ: блок запоминает состав
группы в момент приказа и отдаёт его в состоянии полем `groups`, то есть число
приходит из игры, а не из нашего желания. Заодно видно, где группа стоит.

ЧТО СЧИТАТЬ ПРОВАЛОМ: группа 2 не родилась или родилась нулём при куче в поле —
значит отбор её не увидел. Тогда порог по клетке в игре не тот, что в
репозитории, и первым делом смотреть УСТАНОВЛЕННЫЙ файл, а не исходник.

Запускается рядом с идущей партией; стратегия в это время тоже отдаёт приказы и
может занять файл — такой отказ громкий, приказ повторяется.
"""
from __future__ import annotations
import argparse
import os
import sys
import time

for _s in (sys.stdout, sys.stderr):
    try:
        _s.reconfigure(encoding="utf-8", errors="replace")
    except Exception:
        pass

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from coss3_bridge import Bridge
import coss3_map as M

ИГРА = r"C:\Program Files (x86)\Steam\steamapps\common\Cossacks 3"
ПРОТУХ = 60.0


def сказать(текст: str, куда) -> None:
    строка = time.strftime("%H:%M:%S ") + текст
    print(строка, flush=True)
    куда.write(строка + "\n")
    куда.flush()


def состояние(br: Bridge, журнал, прошлое=None):
    """Свежайшее состояние; None — партия встала или кончилась.

    ДВА РАЗНЫХ «ПУСТО», и путать их дорого — первый прогон этой меры умер ровно
    на этом. `read_state` отдаёт None, когда файл НЕ ИЗМЕНИЛСЯ с прошлого
    чтения (защита от снимка-отката), а опрашиваем мы чаще, чем игра пишет. Это
    не беда: берём прошлое. Беда — когда файл сам протух, и тогда виноваты
    пауза по фокусу, встший тик или конец партии."""
    возраст = br.возраст_состояния()
    if возраст is None or возраст > ПРОТУХ:
        сказать(f"состояние ПРОТУХЛО (возраст {возраст}) — партия стоит, тик "
                f"встал или окно не в фокусе", журнал)
        return None
    новое = br.read_state()
    if новое:
        return новое
    return прошлое if прошлое else {}


def группы(st: dict) -> dict:
    return {int(г.get("id") or 0): г for г in M.наши_группы(st)}


def куча_в(st: dict, cx: int, cy: int) -> int:
    for к in M.наши_кучи_с_полем(st):
        if int(к.get("x", -1)) == cx and int(к.get("y", -1)) == cy:
            return int(к.get("n") or 0)
    return 0


def отдать(br: Bridge, приказ: dict, журнал, попыток: int = 24) -> bool:
    """Отдать приказ, пережив занятый файл: стратегия рядом отдаёт свои."""
    for _ in range(попыток):
        if br.attack_many([приказ]):
            сказать(f"ОТДАН {приказ}", журнал)
            до = time.time() + 25
            while time.time() < до and os.path.exists(br.atk_path):
                time.sleep(0.5)
            if os.path.exists(br.atk_path):
                сказать("  игра файл НЕ забрала за 25 с — тик встал или окно "
                        "не в фокусе", журнал)
                return False
            сказать("  файл забран игрой", журнал)
            return True
        time.sleep(2.0)
    сказать(f"НЕ ОТДАН (файл занят стратегией): {приказ}", журнал)
    return False


def снимок(st: dict, журнал, подпись: str) -> None:
    сказать(f"-- снимок: {подпись} --", журнал)
    сказать(f"   gt={st.get('gametime')} армия {st.get('mil_inf')}+"
            f"{st.get('mil_shooters')} свободных {st.get('my_freewar')} "
            f"в поле mil_away={st.get('mil_away')}", журнал)
    for строка in M.строки_поля(st):
        сказать("   " + строка, журнал)
    гр = группы(st)
    if гр:
        for номер in sorted(гр):
            г = гр[номер]
            сказать(f"   группа {номер}: n={г.get('n')} в ({г.get('cx')},"
                    f"{г.get('cy')}) режим {г.get('режим')} цель "
                    f"({г.get('tx')},{г.get('ty')})", журнал)
    else:
        сказать("   групп в состоянии нет", журнал)


def ждать(br: Bridge, журнал, условие, зачем: str, секунд: float = 240):
    """Ждать условия по свежему состоянию. Возвращает состояние или {}."""
    сказать(f"жду: {зачем} (до {секунд:.0f} с)", журнал)
    до = time.time() + секунд
    последнее = {}
    while time.time() < до:
        st = состояние(br, журнал, последнее)
        if st is None:
            return {}
        if st:
            последнее = st
        if st and условие(st):
            сказать(f"  дождался: {зачем}", журнал)
            return st
        time.sleep(3.0)
    сказать(f"  НЕ дождался за {секунд:.0f} с: {зачем}", журнал)
    return последнее


def main() -> int:
    ap = argparse.ArgumentParser(description="мера порога «в поле» по клетке")
    ap.add_argument("--dir", default=ИГРА)
    ap.add_argument("--plind", type=int, default=0)
    ap.add_argument("--отчёт", default="мера_поля.log")
    ap.add_argument("--с-минуты", type=float, default=280.0,
                    help="не начинать раньше этого игрового времени")
    ap.add_argument("--бойцов", type=int, default=16,
                    help="сколько свободных ждать перед первым приказом")
    a = ap.parse_args()

    br = Bridge(a.dir, plind=a.plind)
    with open(a.отчёт, "w", encoding="utf-8", newline="") as журнал:
        сказать("МЕРА §99: порог «в поле» по клетке, живая игра", журнал)
        st = состояние(br, журнал) or {}
        if not st:
            return 1
        дом = M.дом_клетка(st)
        if дом is None:
            сказать("ратуши в состоянии нет — мерить нечем", журнал)
            return 1

        # КУДА вести: два шага от ратуши В СТОРОНУ ЕГО БАЗЫ. Сторона берётся из
        # его зданий на сетке (brow), а не выдумывается: на этой карте ратуша в
        # (3,3), его дома в (11,12)-(12,13).
        его = его_сторона(st, дом)
        цx = max(0, min(15, дом[0] + 2 * его[0]))
        цy = max(0, min(15, дом[1] + 2 * его[1]))
        ч = max(abs(цx - дом[0]), abs(цy - дом[1]))
        сказать(f"ратуша в {дом}, его сторона {его}, клетка меры ({цx},{цy}), "
                f"Чебышёв {ч} — это ПОЛЕ по новой мерке и ДОМ по старой "
                f"(около {ч * (int(st.get('map_w') or 256) // 16)} единиц "
                f"против порога 60)", журнал)
        if ч < 2:
            сказать("клетка меры вышла ближе двух — мерить нечего", журнал)
            return 1

        st = ждать(br, журнал,
                   lambda s: (float(s.get("gametime") or 0) >= a.с_минуты
                              and int(float(s.get("my_freewar") or 0)) >= a.бойцов),
                   f"игровое время {a.с_минуты:.0f} и свободных {a.бойцов}", 900)
        if not st:
            return 1
        снимок(st, журнал, "до всего")

        # 1. MOVE в клетку меры, группой 1.
        if not отдать(br, {"count": 200, "target": "cell", "mode": "move",
                           "cx": цx, "cy": цy, "group": 1}, журнал):
            return 1
        st = ждать(br, журнал, lambda s: куча_в(s, цx, цy) >= 5,
                   f"куча пришла в ({цx},{цy})", 180)
        снимок(st, журнал, f"куча в ({цx},{цy}) — до RETREAT")
        было = куча_в(st, цx, цy)
        сказать(f"В КЛЕТКЕ МЕРЫ {было} бойцов, mil_away={st.get('mil_away')} "
                f"(до правки оба приказа ответили бы «в поле никого нет»)", журнал)

        # 2. RETREAT — ЭТО И ЕСТЬ ПРОВЕРКА ОТБОРА.
        if not отдать(br, {"count": 200, "target": "home", "mode": "retreat",
                           "group": 2}, журнал):
            return 1
        st = ждать(br, журнал, lambda s: 2 in группы(s), "группа 2 родилась", 60)
        гр = группы(st).get(2) or {}
        взято = int(гр.get("n") or 0)
        сказать(f"ИТОГ RETREAT: группа 2 несёт {взято} бойцов при куче {было} "
                + ("— ОТБОР УВИДЕЛ КУЧУ В ПОЛЕ" if взято > 0
                   else "— ОТБОР НИКОГО НЕ ВЗЯЛ, правка в игре не та"), журнал)
        st = ждать(br, журнал,
                   lambda s: (M.чебышёв_от_дома(s, *позиция(s, 2)) or 9) < ч
                   if позиция(s, 2) else False,
                   "группа 2 подошла к ратуше ближе клетки меры", 150)
        снимок(st, журнал, "после RETREAT")

        # 3. ENGAGE — второй приказ, который держал 60.
        if not отдать(br, {"count": 200, "target": "cell", "mode": "move",
                           "cx": цx, "cy": цy, "group": 3}, журнал):
            return 1
        st = ждать(br, журнал, lambda s: куча_в(s, цx, цy) >= 5,
                   f"куча снова в ({цx},{цy})", 180)
        снимок(st, журнал, f"куча снова в ({цx},{цy}) — до ENGAGE")
        было2 = куча_в(st, цx, цy)
        if not отдать(br, {"count": 200, "target": "army", "mode": "engage",
                           "group": 4}, журнал):
            return 1
        st = ждать(br, журнал, lambda s: 4 in группы(s), "группа 4 родилась", 60)
        гр4 = группы(st).get(4) or {}
        взято4 = int(гр4.get("n") or 0)
        сказать(f"ИТОГ ENGAGE: группа 4 несёт {взято4} бойцов при куче {было2} "
                + ("— ОТБОР УВИДЕЛ КУЧУ В ПОЛЕ" if взято4 > 0
                   else "— ОТБОР НИКОГО НЕ ВЗЯЛ"), журнал)
        st = ждать(br, журнал, lambda s: False, "смотрю, куда пошла группа 4", 90)
        снимок(st, журнал, "после ENGAGE")

        сказать("", журнал)
        сказать(f"МЕРА: RETREAT взял {взято} из {было}, ENGAGE взял {взято4} "
                f"из {было2}; клетка меры ({цx},{цy}), Чебышёв {ч} от ратуши "
                f"{дом}", журнал)
    return 0


def позиция(st: dict, номер: int):
    г = группы(st).get(номер)
    if not г:
        return None
    return (int(г.get("cx") or -1), int(г.get("cy") or -1))


def его_сторона(st: dict, дом) -> tuple:
    """Куда от нас его база: (-1|0|1, -1|0|1).

    Точку базы считает `coss3_map.база_врага` — центр его зданий на сетке
    `brow`, прижатый к настоящей клетке здания. По ЗДАНИЯМ, а не по армии: в
    поле её в начале партии нет вовсе (`ecells = none` на второй минуте), а
    дома стоят с первой секунды. Своего счёта тут не держим: второй способ
    сказать то же самое дал бы двум числам расходиться."""
    б = M.база_врага(st) or {}
    if not б:
        return (1, 1)
    знак = lambda v: (1 if v > 0 else (-1 if v < 0 else 0))
    return (знак(int(б.get("cx", дом[0])) - дом[0]),
            знак(int(б.get("cy", дом[1])) - дом[1]))


if __name__ == "__main__":
    raise SystemExit(main())
