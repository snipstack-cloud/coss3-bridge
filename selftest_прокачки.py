"""Оценщик ступеней казармы `прокачки.py` (§110) — пять обязательных проверок из разбора игрока 6.10 и сторожа.

  1. Против чистых мушкетёров защита пик даёт нулевой прямой эффект (пуля мимо ступени).
  2. Против чистых пик защита оценивается по фактическому изменению урона.
  3. При замене части пик стрелками пересчитываются ОБЕ составляющие, а не сохраняется прежний счёт.
  4. Промпт и --auto-upgrade получают одинаковые оценки на одном снимке.
  5. Если исследование не успевает к ближайшему бою, оно не получает выгоду этого боя.
Сторожа: прибавки ступеней в `combat_math` и `sim.ЭФФЕКТЫ` — одни числа; состав не виден — сказано, а не ноль;
симулятор исследует ступень 15,6 с (на записи p5, если она есть); контрольный случай p5 11:03 (32 пики / 52 стрелка).
"""
