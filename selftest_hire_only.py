# -*- coding: utf-8 -*-
"""Самопроверка: военный найм отдан событийному каналу (`--hire-only`,
`--hire-every`).

Замысел игрока 21.09: здание достроилось, модель назвала вид — а через
полминуты у врага другой состав, и нужен другой боец. Обычный такт идёт раз в
20 игровых секунд и занят всем сразу; узкий вопрос «кого нанимать» стоит доли
секунды (замер: 2,0-2,2 с у облака и `llama3.1:8b`), и его можно задавать хоть
каждые десять. Тогда состав армии перестаёт отставать от состава врага.

Три части, и каждая своим ключом:
* `--hire-every N` — спрашивать не только на достройке, но и раз в N секунд;
* `--hire-only 1` — у ОБЫЧНОГО такта военный `TRAIN` отбирается и говорится
  вслух; крестьяне остаются за ним;
* событийный канал из-под отбора ИЗЪЯТ — иначе нанимать было бы некому.

Последнее стережём отдельно: первая версия правки глушила и событие, и это
поймалось только проверкой.
"""
import llm_policy as L

беды = []


def проверка(имя, условие, пояснение=""):
    if условие:
        print("  ОК    " + имя)
    else:
        беды.append(имя)
        print("  ПЛОХО " + имя + (" — " + пояснение if пояснение else ""))


def разбор(команды, из_события=False):
    cmds, attack, why, брак, *_ = L.to_commands(
        {"commands": команды, "why": "проверка"}, из_события=из_события)
    return [c.cmd for c in cmds], брак


ВОЕННЫЙ = {"cmd": "TRAIN", "role": "infantry17", "total": -1}
КРЕСТЬЯНИН = {"cmd": "TRAIN", "role": "peasant", "total": -1}
СТРОЙКА = {"cmd": "BUILD", "role": "ba17", "total": 2}

# --- ключ выключен: всё как было ------------------------------------------
L.ТОЛЬКО_НАЙМ = False
имена, брак = разбор([ВОЕННЫЙ, КРЕСТЬЯНИН, СТРОЙКА])
проверка("с выключенным ключом военный TRAIN проходит",
         имена.count("TRAIN") == 2 and not брак, f"{имена} {брак}")

# --- ключ включён ----------------------------------------------------------
L.ТОЛЬКО_НАЙМ = True
имена, брак = разбор([ВОЕННЫЙ, КРЕСТЬЯНИН, СТРОЙКА])
проверка("военный TRAIN отобран", имена.count("TRAIN") == 1, str(имена))
проверка("крестьянин и стройка остались", "BUILD" in имена, str(имена))
проверка("отбор НЕ МОЛЧАЛИВЫЙ", len(брак) == 1 and "ОТДЕЛЬНЫЙ канал" in брак[0],
         "правило 1 проекта: отброшенное неотличимо от ненаписанного")

# --- событийный канал изъят из отбора --------------------------------------
имена, брак = разбор([ВОЕННЫЙ], из_события=True)
проверка("событийный ответ ПРОХОДИТ", имена == ["TRAIN"] and not брак,
         "первая версия правки глушила и его — нанимать было бы НЕКОМУ")

# --- про запрет сказано в промпте, а не только в отказе --------------------
_сост = {"gametime": 600, "food": 900, "peasants": 30, "ba17": 1,
         "mil_inf": 10, "my_freewar": 5}
_текст = L.situation(_сост, {}, [], "")   # возвращает СТРОКУ, не список
проверка("модель предупреждена ДО попытки",
         "ВОЕННЫХ НЕ ЗАКАЗЫВАЙ" in _текст and "КРЕСТЬЯН заказываешь" in _текст,
         "иначе она тратит команду каждый такт и читает отказ постфактум")

L.ТОЛЬКО_НАЙМ = False
_текст2 = L.situation(_сост, {}, [], "")
проверка("с выключенным ключом промпт молчит", "ВОЕННЫХ НЕ ЗАКАЗЫВАЙ" not in _текст2)

# --- РАЗБРОС СРОКА ОПРОСА (21.09) ------------------------------------------
#
# Замысел игрока: играем против другого бота, и если обе стороны опрашивают
# обстановку с одинаковым шагом, они входят в такт — каждый выбирает состав
# под ПРОШЛЫЙ состав противника, и состав качается. Случайный шаг рвёт связку.
проверка("«10» читается как ровный срок", L.срок_найма("10") == (10, 10))
проверка("«10-60» читается как разброс", L.срок_найма("10-60") == (10, 60))
проверка("перевёрнутый и мусорный ключ выключают опрос",
         L.срок_найма("60-10") == (0, 0) and L.срок_найма("мусор") == (0, 0)
         and L.срок_найма("-5") == (0, 0),
         "молча включать опрос на мусоре нельзя")

_сроки = {L.следующий_найм(10, 60) for _ in range(500)}
проверка("разброс укладывается в границы", min(_сроки) >= 10 and max(_сроки) <= 60)
проверка("разброс действительно разный", len(_сроки) > 30, f"значений {len(_сроки)}")
проверка("без разброса срок ровный", {L.следующий_найм(15, 15)} == {15})

# --- ЦЕНА СМЕНЫ СОСТАВА ----------------------------------------------------
#
# Чего разброс НЕ лечит: модель может качать состав от любого шевеления —
# спросили чаще, меняет чаще. Поэтому рядом с занятой очередью сказано, во
# что обходится смена. У ПУСТОЙ очереди этой строки быть не должно: там
# менять нечего.
_СВОИ = ("infantry17=pikeman,hp90,atk11,wkind1,pause0,dpike5,dsword4,dbullet4,"
         "food25,gold3,iron20,coal0 "
         "musk17=musketeernet,hp65,atk10,wkind3,pause375,dpike1,dsword1,"
         "dbullet0,food50,gold8,iron4,coal0")
_ст = {"gametime": 600, "ba17": 2, "food": 2000, "gold": 900, "iron": 500,
       "coal": 800, "mines_coal": 1, "fighters": _СВОИ,
       "p1_fighters": "infantry17=hp90,atk14,wkind1,pause0,dpike8,dsword7,dbullet4",
       "p1_inf": 50, "p1_enemy": 1, "ba_queues": "1:pikeman:inf,2:none"}
_занято = L.запрос_найма(_ст, {}, "ba17", 1, такт=20)
_пусто = L.запрос_найма(_ст, {}, "ba17", 2, такт=20)
проверка("у ЗАНЯТОЙ очереди названа цена смены",
         "СМЕНА СОСТАВА НЕ БЕСПЛАТНА" in _занято)
проверка("у ПУСТОЙ очереди про цену молчим",
         "СМЕНА СОСТАВА НЕ БЕСПЛАТНА" not in _пусто, "менять там нечего")

print()
if беды:
    print(f"БЕД: {len(беды)} — {', '.join(беды)}")
    raise SystemExit(1)
print("всё чисто")
