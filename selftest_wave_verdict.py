# -*- coding: utf-8 -*-
"""Самопроверка вердикта «ВОЛНА УШЛА / НИКТО НЕ ПОШЁЛ» (19.09).

По 53 партиям 31 приказ ATTACK при свободных не меньше запрошенного получил
«НИКТО НЕ ПОШЁЛ», хотя блок волну взял: wave_sent сменился на запрошенное
число. Ушедших в набеге замещают вернувшиеся из стычки и новые из казармы.
Теперь вердикт смотрит на wave_sent — сколько блок взял на самом деле.
"""
import sys
import llm_policy as L

беды = []


def проверка(имя, условие, пояснение=""):
    if условие:
        print("  ОК   " + имя)
    else:
        беды.append(имя)
        print("  ПЛОХО " + имя + (" — " + пояснение if пояснение else ""))


def итог(было, стало, n=29):
    return chr(10).join(L.итог_прошлого(было, стало, [("ATTACK", "", n)]))


# Живой случай barracks_now 12:37: свободных 51 -> 50, wave_sent 109 -> 29.
т = итог(dict(my_freewar=51, wave_sent=109), dict(my_freewar=50, wave_sent=29))
проверка("wave_sent сменился на запрошенное — ВОЛНА УШЛА", "ВОЛНА УШЛА" in т and "блок взял 29" in т, т)
проверка("«никто не пошёл» не сказано", "НИКТО НЕ ПОШЁЛ" not in т)

# Свободных даже прибавилось (base16 11:33: 56 -> 71 при wave_sent 8 -> 42) — всё равно ушла, и сказано почему.
т = итог(dict(my_freewar=56, wave_sent=8), dict(my_freewar=71, wave_sent=42), n=42)
проверка("свободных прибавилось, но блок взял — ушла", "ВОЛНА УШЛА" in т and "заместили" in т, т)

# Блок взял меньше, чем просили (урезал до свободных) — названо.
т = итог(dict(my_freewar=20, wave_sent=0), dict(my_freewar=1, wave_sent=20), n=40)
проверка("взял меньше — сказано, сколько", "блок взял 20 (просил 40)" in т, т)

# wave_sent не сменился, свободных не убыло — вот это и есть «никто не пошёл».
т = итог(dict(my_freewar=30, wave_sent=25), dict(my_freewar=31, wave_sent=25), n=25)
проверка("ничего не сменилось — НИКТО НЕ ПОШЁЛ", "НИКТО НЕ ПОШЁЛ" in т, т)

# wave_sent тот же (просили столько же, сколько в прошлой волне), но свободных убыло — прежний признак работает.
т = итог(dict(my_freewar=40, wave_sent=25), dict(my_freewar=15, wave_sent=25), n=25)
проверка("wave_sent тот же, свободных убыло — ушла по старому признаку", "ВОЛНА УШЛА" in т and "40->15" in т, т)

# Старый мост без wave_sent — только старый признак.
т = итог(dict(my_freewar=40), dict(my_freewar=15), n=25)
проверка("без wave_sent — старый признак", "ВОЛНА УШЛА" in т)

print()
print(f"ПРОВАЛОВ: {len(беды)}")
sys.exit(1 if беды else 0)
