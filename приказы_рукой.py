#!/usr/bin/env python3
# -*- coding: utf-8 -*-
r"""НЕСКОЛЬКО ПРИКАЗОВ ЗА ТАКТ, РУКАМИ — проверка правки блока на живой игре.

Зачем. С 4.10 файл приказа несёт СПИСОК приказов (§78 мака, `block_hcmd.inc`,
ключ `orders`), и проверить это можно только живой игрой: контейнер для `.inc`
негоден (цикл три минуты, экран чёрный, «ПУЛЬСА НЕТ» имеет три причины).
Модель и стратегия пока отдают один приказ за такт, поэтому цикл в блоке
нечем разбудить — этот водитель отдаёт список руками.

Он же нужен для ОПЫТА С ПРИМАНКОЙ (§62): «десять пикинёров к его армии» и
«эта же группа назад» — два приказа, и второй теперь не затирает первый.

    python приказы_рукой.py --plind 1 --приказ "10 army engage" \
                            --приказ "200 cell retreat 6 7"
    python приказы_рукой.py --список            # что лежит в состоянии сейчас

Приказ словами: `<count> <target> [mode] [cx cy] [g<номер>] [f<cx>,<cy>]`, где
target — peasants, base, army, cell, home; mode — пусто (атака), move, retreat,
engage, face; `g<номер>` — НОМЕР ГРУППЫ (§78); `f<cx>,<cy>` — КУДА СМОТРЕТЬ
(§98, клетка сетки); `nohold` — у FACE не удерживать позицию (§102, по
умолчанию удерживают):

    "20 cell move 9 7 g1"   создать группу 1 из 20 отобранных и повести в клетку
    "0 cell move 11 9 g1"   приказ УЖЕ созданной группе 1: отбора нет, идут те же
    "0 home retreat g1"     она же домой
    "0 group move g1 to2"   группа 1 идёт К ГРУППЕ 2 и вливается в неё
    "20 cell move 9 7 f1,2"  двадцать идут в (9,7) и встают ЛИЦОМ на клетку (1,2)
    "0 home face g1 f1,2"    группа 1 разворачивается НА МЕСТЕ на клетку (1,2)
                             и ДЕРЖИТ её: приказы по свободным её не возьмут
    "0 home face g1 f1,2 nohold"   то же, но без удержания

Группа без count — это и есть «адресный приказ»: трогается только она, остальные
стоят. Так проверяется мера мака: куча с этим номером сдвинулась, прочие нет.

ЧТО СМОТРЕТЬ ПОСЛЕ. В ЛОГЕ ИГРЫ, а он лежит в каталоге сохранений —
`%USERPROFILE%\OneDrive\Documents\cossacks\log\cos_<дата>.log`, по файлу на
запуск. Здесь раньше было написано «`мост_в_игре.log` либо `game.log`», и это
была неправда, стоившая времени 5.10: ключ `LogFileEnabled` в `cossacks.ini`
лог НЕ отключает (партия при `false` писалась), а имя и место у него другие.
На один такт
должно быть СТОЛЬКО строк `bridge-human:`, сколько приказов, а в состоянии —
столько новых куч в `ocells`. Одна строка на два приказа значит, что в игре
стоит старый блок: он читает только плоские ключи первого приказа.
"""
from __future__ import annotations
import argparse
import os
import sys
import time

for _s in (sys.stdout, sys.stderr):
    try: _s.reconfigure(encoding="utf-8", errors="replace")
    except Exception: pass

from coss3_bridge import Bridge

ИГРА_ПО_УМОЛЧАНИЮ = r"C:\Program Files (x86)\Steam\steamapps\common\Cossacks 3"

# Состояние пишется каждую ИГРОВУЮ секунду, поэтому запас большой: партию могли
# поставить на паузу на минуту и вернуться. Тот же порог, что у `send.py`.
ПРОТУХ = 60.0


def разобрать(текст: str) -> dict:
    """«10 army engage» или «200 cell retreat 6 7» -> поля приказа."""
    части = текст.split()
    if not части:
        raise SystemExit("пустой приказ")
    try:
        приказ = {"count": int(части[0])}
    except ValueError:
        raise SystemExit(f"первым числом идёт count, а не {части[0]!r}")
    if len(части) > 1:
        приказ["target"] = части[1]
    if len(части) > 2 and части[2] not in ("", "attack"):
        приказ["mode"] = части[2]
    # Клетка — два ЧИСЛА подряд; слова g<N>/to<N> читаются отдельно ниже, и
    # путать их с клеткой нельзя: «0 group move g1 to2» клетки не несёт.
    числа = [ч for ч in части[3:] if ч.lstrip("-").isdigit()]
    if len(числа) >= 2:
        приказ["cx"], приказ["cy"] = int(числа[0]), int(числа[1])
    for ч in части[1:]:
        if ч.startswith("g") and ч[1:].isdigit():
            приказ["group"] = int(ч[1:])
        # `f<cx>,<cy>` — КУДА СМОТРЕТЬ (§98). Отдельным словом с запятой внутри,
        # чтобы не спутать с клеткой ЦЕЛИ: та идёт двумя числами через пробел.
        if ч == "nohold":
            приказ["hold"] = 0
        if ч.startswith("f") and "," in ч[1:]:
            сx, _, сy = ч[1:].partition(",")
            if сx.lstrip("-").isdigit() and сy.lstrip("-").isdigit():
                приказ["face"] = [int(сx), int(сy)]
        # `to<N>` — номер группы-ПОЛУЧАТЕЛЯ при цели `group`: идём к ней и
        # вливаемся. Отдельным словом, а не вторым `g`, чтобы в команде было
        # видно, кто идёт и к кому.
        if ч.startswith("to") and ч[2:].isdigit():
            приказ["gid"] = int(ч[2:])
    if приказ.get("target") == "group" and not приказ.get("gid"):
        raise SystemExit("цель group требует номера получателя словом to<N>, "
                         "например: 0 group move g1 to2")
    if приказ.get("target") == "cell" and "cx" not in приказ:
        raise SystemExit("цель cell требует двух чисел: cx и cy")
    if приказ["count"] <= 0 and not приказ.get("group"):
        raise SystemExit("count 0 имеет смысл только с номером группы: "
                         "кому тогда приказ?")
    if приказ.get("mode") == "face" and not приказ.get("face"):
        raise SystemExit("режим face требует клетки словом f<cx>,<cy>: "
                         "повернуться неизвестно куда нельзя")
    return приказ


def кучи(st: dict) -> str:
    """Кучи СО МЕРКОЙ БЛОКА, а не сырой строкой (5.10, §99).

    Сырое `ocells` не отвечало на вопрос, который задаёт каждая проверка
    приказа: возьмёт ли эту кучу RETREAT или ENGAGE. С порогом по клетке на это
    отвечает Чебышёв от клетки ратуши, и считает его `coss3_map`, одним числом
    с блоком."""
    import coss3_map
    куч = coss3_map.наши_кучи_с_полем(st)
    if not куч:
        return "нет"
    return "; ".join(
        f"({int(к.get('x', -1))},{int(к.get('y', -1))}) {int(к.get('n') or 0)}"
        + (" В ПОЛЕ" if к.get("в_поле") else " дома")
        for к in куч[:8])


def main() -> int:
    ap = argparse.ArgumentParser(description="несколько приказов за такт, руками")
    ap.add_argument("--dir", default=ИГРА_ПО_УМОЛЧАНИЮ, help="папка игры")
    ap.add_argument("--plind", type=int, default=1, help="слот бота (в партии с игроком 1)")
    ap.add_argument("--приказ", action="append", default=[], dest="приказы",
                    metavar="«count target [mode] [cx cy]»")
    ap.add_argument("--список", action="store_true", dest="только_список",
                    help="ничего не отдавать, только показать состояние")
    a = ap.parse_args()

    br = Bridge(a.dir, plind=a.plind)
    st = br.read_state() or {}
    if not st:
        print(f"состояния слота {a.plind} нет: игра не идёт или слот другой")
        return 1
    # ЗАЛЕЖЬ ОТ ПРОШЛОЙ ПАРТИИ СЛОТОМ НЕ СЧИТАЕТСЯ (урок 15.09; `send.py` это
    # проверяет с тех пор, а здесь слот задан ключом, и проверка обходилась).
    # Поймано 5.10: с закрытой игрой водитель показал gt=1172 и кучи прошлой
    # партии как живые. Для МЕРЫ это хуже, чем молчание: числа есть, они
    # складные, и вывод из них неверный.
    возраст = br.возраст_состояния()
    if возраст is None or возраст > ПРОТУХ:
        сколько = "неизвестно" if возраст is None else f"{возраст:.0f} с назад"
        print(f"состояние слота {a.plind} ПРОТУХЛО (записано {сколько}, порог "
              f"{ПРОТУХ:.0f} с): партия не идёт, тик встал или окно игры не в "
              f"фокусе — движок останавливает симуляцию без фокуса, и это не "
              f"выключается. Числа ниже были бы от прошлой партии.")
        return 1
    import coss3_map
    дом = coss3_map.дом_клетка(st)
    print(f"слот {a.plind}: gt={st.get('gametime')}, бойцов "
          f"{st.get('mil_inf')}+{st.get('mil_shooters')}, в поле "
          f"{st.get('mil_away')}, свободных {st.get('my_freewar')}, ратуша "
          + (f"({дом[0]},{дом[1]})" if дом else "ещё не стоит"))
    print(f"  кучи до: {кучи(st)}")
    if a.только_список:
        return 0
    if not a.приказы:
        print("нечего отдавать: задайте хотя бы один --приказ")
        return 1
    список = [разобрать(т) for т in a.приказы]
    for i, п in enumerate(список):
        print(f"  приказ {i}: {п}")
    if not br.attack_many(список):
        print("НЕ ОТДАНО: прошлый приказ ещё не забран игрой либо приказ негоден")
        return 1
    print(f"отдано приказов: {len(список)}; жду, пока игра заберёт файл")
    путь = br.atk_path
    до = time.time() + 20
    while time.time() < до and os.path.exists(путь):
        time.sleep(0.5)
    if os.path.exists(путь):
        print("игра файл НЕ забрала за 20 с — блок приказов не читает "
              "(пауза, окно не в фокусе или мост не стоит)")
        return 1
    print("файл забран игрой")
    # Кучи ПОСЛЕ: состояние переписывается каждую игровую секунду, но приказу
    # нужно время дойти до группы — смотрим дважды.
    for _ in range(6):
        time.sleep(2.0)
        st2 = br.read_state() or {}
        if кучи(st2) != кучи(st):
            print(f"  кучи после: {кучи(st2)}")
            break
    else:
        print(f"  кучи не изменились: {кучи(br.read_state() or {})}")
        print("  (это не обязательно отказ: приказ мог достаться тем, кто уже "
              "стоял в той же клетке)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
