# -*- coding: utf-8 -*-
"""Самопроверка блока «Вторая казарма ПО КАРМАНУ ПРЯМО СЕЙЧАС» (18.09).

Серия gold_mine2: золото 2500 набиралось к 7:33, а казарму модель заказывала
через четыре минуты. Блок говорит в тот же такт и помнит, сколько ждём; между
партиями память чистится.
"""
import sys
import llm_policy as L

беды = []


def проверка(имя, условие, пояснение=""):
    if условие:
        print("  ОК   " + имя)
    else:
        беды.append(имя)
        print("  ПЛОХО " + имя + (" — " + пояснение if пояснение else ""))


ЦЕНЫ = "ba17=food0,wood500,stone500,gold2500,iron0,coal0 mill=food0,wood60,stone300,gold0,iron0,coal0"


def т(gt, ba17=1, gold=2700, can="mill ba17 peasant", wip=""):
    st = dict(gametime=gt, ba17=ba17, gold=gold, can_now=can, wip=wip, build_cost=ЦЕНЫ)
    return chr(10).join(L.вторая_казарма(st))


L.ВТОРАЯ_КАЗАРМА.clear()
проверка("нет казармы — молчит", т(300, ba17=0) == "")
проверка("не по карману — молчит", т(400, can="mill peasant") == "")
проверка("уже две — молчит", т(400, ba17=2) == "")
проверка("вторая строится — молчит", т(400, wip="ba17/20/4/30") == "")

L.ВТОРАЯ_КАЗАРМА.clear()
т1 = т(453)
проверка("по карману — говорит в тот же такт", "ПО КАРМАНУ ПРЯМО СЕЙЧАС" in т1)
проверка("названо золото и цена", "золота 2700 при цене 2500" in т1, т1)
проверка("названо, сколько сверх", "сверх цены лежит 200" in т1, т1)
проверка("дана команда со строителями", '"role":"ba17","total":2' in т1 and '"BUILDERS","total":12' in т1)
проверка("первый такт без «уже N с»", "По карману уже" not in т1)
т2 = т(533, gold=3100)
проверка("через такты — сколько ждём", "По карману уже 80 с" in т2, т2)
проверка("ждём считается от первого такта", "с 453" not in т2 and L.ВТОРАЯ_КАЗАРМА["с"] == 453)

# заложили — молчит; когда встала — молчит и память чистится
проверка("заложили — молчит", т(560, wip="ba17/20/12/5") == "")
проверка("встала — молчит", т(600, ba17=2) == "")
проверка("память пуста после второй", L.ВТОРАЯ_КАЗАРМА == {})

# Между партиями: та же секунда в новой партии не наследует старт.
L.ВТОРАЯ_КАЗАРМА.clear()
т(453)
L.ВТОРАЯ_КАЗАРМА.clear()
проверка("новая партия начинает счёт заново", "По карману уже" not in т(700))

# Строка есть в запросе целиком.
L.ВТОРАЯ_КАЗАРМА.clear()
st = dict(gametime=460, food=3000, wood=2000, stone=2000, gold=2700, iron=500, coal=500,
          peasants=40, mil_inf=20, mil_shooters=10, my_freewar=30, ba17=1, smiths=1,
          centers=1, mills=1, can_now="mill ba17 peasant", cant_now="", build_cost=ЦЕНЫ)
проверка("блок доходит до запроса", "ПО КАРМАНУ ПРЯМО СЕЙЧАС" in L.situation(st, {}, [], ""))
L.ВТОРАЯ_КАЗАРМА.clear()

print()
print(f"ПРОВАЛОВ: {len(беды)}")
sys.exit(1 if беды else 0)
