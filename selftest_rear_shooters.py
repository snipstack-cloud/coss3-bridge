# -*- coding: utf-8 -*-
"""Ключ --rear-shooters: мост сам держит мушкетёров за N клеток от боя.

Почему ключ, а не подсказка. 27.09 подсказка просила двухшаговую процедуру
(«мушкетёров в тыл ходом MOVE, следующим ходом бей пикинёрами») и не сработала ни
в одной из шести копий двух редакций `split_control`: `MOVE` не отдан НИ РАЗУ. За
тот же день доехали ВСЕ задания, описывавшие целевое состояние (доля крестьян на
еде, академия к минуте, «армию дома не копи»), и не доехало ни одно, описывавшее
процедуру. Вывод дня: подсказкой переносится СОСТОЯНИЕ, процедуру исполняет мост.

И вторая находка того же дня, без которой ключ был бы бесполезен: обычный путь
удара ТЕРЯЛ поле `who` модели — `br.attack` звался без него, и «бей пикинёрами»
молча превращалось в «бей всеми». Ветка с урезанием поле передавала, а она
срабатывает только когда запрошено больше, чем свободно. Тест стережёт и это.

Стережётся:
* при выключенном ключе ничего не меняется — ни `who`, ни лишних приказов;
* при включённом удар уходит ПИКИНЁРАМИ, и мост говорит об этом вслух;
* свой выбор модели мост не переписывает: если она назвала `who` сама, он её не
  трогает;
* стрелки встают за N клеток от боя НА ЛИНИИ к нашей базе, и не дальше ратуши;
* без мушкетёров мост не молчит, а называет причину;
* поле `тыл` доезжает в снимок трассы — иначе мера «стрелки и пикинёры в разных
  клетках» по серии не считается вовсе.
"""
import inspect
import io
import os

import llm_policy as L

беды = []


def проверка(имя, условие, пояснение=""):
    if условие:
        print("  ОК    " + имя)
    else:
        беды.append(имя)
        print("  ПЛОХО " + имя + (" — " + str(пояснение)[:300] if пояснение else ""))


ИСТ = io.open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "llm_policy.py"),
              encoding="utf-8").read()

# 1. ПОТЕРЯННОЕ who: обычный путь удара обязан передавать вид бойцов.
вызовы = [с.strip() for с in ИСТ.split("br.attack(")[1:]]
обычный = [с for с in вызовы if с.startswith("attack, цель_атаки")]
проверка("обычный путь удара передаёт who модели",
         обычный and all("who=" in с[:160] for с in обычный),
         [с[:120] for с in обычный])

# 2. Ключ объявлен и по умолчанию выключен.
проверка("ключ --rear-shooters объявлен", '"--rear-shooters"' in ИСТ)
проверка("по умолчанию выключен",
         'ap.add_argument("--rear-shooters", type=int, default=0' in ИСТ)

# 3. Тыловая клетка считается ОТ БОЯ К НАШЕЙ БАЗЕ.
ст = {"my_cx": 3, "my_cy": 12}
_т = L.тыловая_клетка(ст, (12, 3), 6)
проверка("тыл на линии к базе: от (12,3) при базе (3,12) на 6 клеток это (6,9)",
         _т == (6, 9), _т)
проверка("и расстояние от боя РАВНО заказанным шести",
         _т is not None and max(abs(12 - _т[0]), abs(3 - _т[1])) == 6, _т)
проверка("дальше ратуши не уходим",
         L.тыловая_клетка(ст, (5, 11), 20) == (3, 12),
         L.тыловая_клетка(ст, (5, 11), 20))
проверка("бой в клетке ратуши — тыла нет",
         L.тыловая_клетка(ст, (3, 12), 6) is None)
проверка("без ратуши в состоянии тыла нет",
         L.тыловая_клетка({}, (12, 3), 6) is None)
проверка("выключенный ключ тыла не даёт",
         L.тыловая_клетка(ст, (12, 3), 0) is None)
# Клетка всегда внутри сетки.
плохие = [(б, L.тыловая_клетка(ст, б, 6)) for б in ((0, 0), (15, 15), (0, 15), (15, 0))
          if L.тыловая_клетка(ст, б, 6) is not None
          and not (0 <= L.тыловая_клетка(ст, б, 6)[0] <= 15
                   and 0 <= L.тыловая_клетка(ст, б, 6)[1] <= 15)]
проверка("клетка тыла всегда внутри сетки", not плохие, плохие)

# 4. Подмена вида — только когда модель вида НЕ назвала, и вслух.
проверка("удар подменяется на пикинёров лишь при пустом who модели",
         'and not кем_атака and _чис(st.get("mil_shooters")) > 0' in ИСТ)
проверка("подмена говорится вслух в запрос модели",
         "УДАР УХОДИТ ПИКИНЁРАМИ" in ИСТ and "вмешательство" in
         ИСТ.split("УДАР УХОДИТ ПИКИНЁРАМИ")[0][-400:])

# 5. Отвод — в такт БЕЗ удара (файл приказа один) и с причиной при отказе.
проверка("стрелков отводим в такт без удара",
         'if getattr(a, "rear_shooters", 0) and not волна_была' in ИСТ)
проверка("отвод идёт именно мушкетёрами",
         'who="musk17"' in ИСТ)
проверка("без мушкетёров мост называет причину",
         "мушкетёров нет ни одного" in ИСТ)
проверка("переставляем, когда бой ушёл",
         "бой ушёл — переставить" in ИСТ)

# 6. Поле тыла доезжает в снимок трассы.
проверка("тыл пишется в снимок трассы", '_снимок["тыл"]' in ИСТ)

# 7. Тыл живёт одну партию.
проверка("ТЫЛ чистится между партиями", "ТЫЛ.clear()" in ИСТ)

print()
if беды:
    print(f"БЕД: {len(беды)} — {', '.join(беды)}")
    raise SystemExit(1)
print("всё чисто")
