# -*- coding: utf-8 -*-
"""Таблица «что купить» не зовёт покупать то, что УЖЕ СТРОИТСЯ.

Повод, 22.09. Счёт по 465 тактам base24: в 16 процентах тактов таблица звала
купить ровно то, что в этот же миг строилось, и рядом, в «Итоге прошлого
решения», мост про то же здание говорил «УЖЕ ЗАЛОЖЕНО, не повторяй». Самый
крупный случай — «+141.3 бойца — казарма №2» при строящейся казарме №2.
Приглашение рядом с запретом: модель повторяла заказ в 21 проценте тактов,
до четырёх раз подряд.

Проверяется ЧЕТЫРЕ вещи, и третья важнее прочих:
  1. строящееся из советов убрано;
  2. про него сказано ВСЛУХ (молчаливый отброс неотличим от бездействия);
  3. НЕ строящееся из таблицы не пропало — иначе лечение хуже болезни;
  4. апгрейды фильтр не трогает: они не здания, их никто не «строит».
"""
import sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import llm_policy as L

ошибок = 0


def проверить(условие, что):
    global ошибок
    if not условие:
        ошибок += 1
        print("  СБОЙ:", что)
    else:
        print("  ок:", что)


def состояние(**поверх):
    """Снимок, на котором таблица заведомо непуста: казарма есть, золота мало."""
    st = {
        "gametime": 500, "ba17": 1, "stables": 0, "academi": 0,
        "gold": 300, "wood": 3000, "stone": 3000, "food": 2000,
        "iron": 3000, "coal": 1000,
        # Занятость мест мост читает по `on_<ресурс>` (РАБОТНИКИ_НА), а не по
        # work_*: с work_gold шахта выглядела НЕ полной, совета про неё не
        # возникало вовсе, и проверка 4 требовала убрать то, чего нет.
        "mines_gold": 1, "cap_gold": 5, "on_gold": 5,
        "mines_iron": 1, "cap_iron": 5, "on_iron": 2,
        "mil_shooters": 0, "wip": "",
        # Цены зданий мост берёт ИЗ СОСТОЯНИЯ, а не из своей таблицы: без
        # build_cost `что_купить` возвращает пустоту, и тест проверял бы
        # пустой список, ничего не замечая. Строка взята из настоящей партии
        # 22.09 (такт 509), а не сочинена.
        "build_cost": (
            "center=food0,wood2100,stone2100,gold0,iron0,coal0 "
            "mill=food0,wood60,stone300,gold0,iron0,coal0 "
            "smith=food0,wood400,stone120,gold0,iron2560,coal0 "
            "ba17=food0,wood500,stone500,gold2500,iron0,coal0 "
            "store=food0,wood75,stone30,gold0,iron0,coal0 "
            "house=food0,wood100,stone100,gold0,iron0,coal0 "
            "minegold=food0,wood100,stone100,gold0,iron0,coal0 "
            "mineiron=food0,wood100,stone100,gold0,iron0,coal0 "
            "minecoal=food0,wood100,stone100,gold0,iron0,coal0 "
            "stable=food0,wood2500,stone100,gold600,iron0,coal0 "
            "academi=food0,wood1050,stone1230,gold0,iron0,coal0"),
    }
    st.update(поверх)
    return st


def советы(st):
    return [с for с in L.что_купить(st) if с.strip().startswith("+")]


def имена_советов(st):
    """ИМЯ записи, а не вхождение слова.

    Совет про шахту содержит текст «казарме нужно 2500 золота», и проверка
    подстрокой ловила в нём «казарма» — тест падал там, где всё верно.
    Имя стоит между «— » и первым двоеточием: «+154.1 бойца — казарма №2: ...».
    """
    из_ = []
    for с in советы(st):
        if "— " in с and ":" in с:
            из_.append(с.split("— ", 1)[1].split(":", 1)[0].strip())
    return из_


def сноски(st):
    return [с for с in L.что_купить(st) if "(не в списке)" in с]


print("1. без стройки таблица советует как обычно")
пусто = состояние()
было = советы(пусто)
проверить(было, "советы есть, когда ничего не строится")
проверить(not сноски(пусто), "сносок про стройку нет")

print("2. строится казарма — её из советов убрали и сказали об этом")
стройка = состояние(wip="ba17/19/18/42")
стало = советы(стройка)
проверить(not any(и.startswith("казарма") for и in имена_советов(стройка)),
          "казармы в советах больше нет")
сн = сноски(стройка)
проверить(any("казарма" in с and "УЖЕ СТРОИТСЯ" in с for с in сн),
          "про казарму сказано вслух")
проверить(any("42%" in с for с in сн), "названа готовность 42 процента")

print("3. прочие советы на месте — фильтр бьёт точечно")
проверить(len(стало) >= len(было) - 1,
          f"из советов ушла только казарма ({len(было)} -> {len(стало)})")
проверить(L.что_купить(стройка), "таблица не опустела целиком")

print("4. строится шахта — тот же разбор по её роли")
шахта = состояние(wip="minegold/5/3/6")
проверить(not any(и.startswith("золотая шахта") for и in имена_советов(шахта)),
          "золотой шахты в советах нет")
проверить(any("золотая шахта" in с for с in сноски(шахта)),
          "про золотую шахту сказано вслух")

print("5. апгрейды фильтр не трогает")
проверить(not any("размен" in с for с in сноски(стройка)),
          "ни один апгрейд не попал в сноски")

print("6. строится ВСЁ, что таблица могла посоветовать")
всё = состояние(wip="ba17/19/18/42 minegold/5/3/6")
проверить(L.что_купить(всё), "таблица всё равно что-то говорит, а не молчит")

print()
print("ошибок:", ошибок)
sys.exit(1 if ошибок else 0)
