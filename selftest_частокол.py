#!/usr/bin/env python3
"""ЧАСТОКОЛ НА ПУТИ (1.11, слово игрока: «атаку армии на частокол направить»): ключ `частокол_бить`.

Живая партия 1.11 показала дыру: `ewalls_seg` 139 — бот частокол ВИДИТ, но ни одно правило
стены не читало, роли артиллерии в мосте нет ни одной, и `mil_guns` был 0 всю партию. Значит
ломать можно только руками, а для этого удар надо направить ПО КЛЕТКЕ СТЕНЫ.

Проверяется `_частокол_на_пути` напрямую и через воронку `привести`.
    python3 selftest_частокол.py"""
import collections
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import strategy_live as SL  # noqa: E402

ошибок = 0


def проверить(усл, что):
    global ошибок
    print(("ОК   " if усл else "ОШИБКА ") + что)
    ошибок += not усл


# Стена строкой, как её отдаёт живой мост: x,y,частокол,камень,ворот,строится,hp%мин
СТРОКОЙ = "1,12,10,0,0,0,100;2,12,16,0,0,0,100;3,12,20,0,0,0,100;2,13,16,0,0,0,40;2,14,17,0,0,1,1"
# та же стена списком, как она лежит в трассе и в симуляторе
СПИСКОМ = [[1, 12, 10, 0, 0, 0, 100], [2, 12, 16, 0, 0, 0, 100], [3, 12, 20, 0, 0, 0, 100],
           [2, 13, 16, 0, 0, 0, 40], [2, 14, 17, 0, 0, 1, 1]]
# армия в 6,13, цель — его крестьяне за стеной в 1,13
БАЗА = dict(my_army_cx=6, my_army_cy=13, my_cx=8, my_cy=13)
ВКЛ = {"частокол_бить": 1}

проверить(len(SL._стены_врага(dict(БАЗА, ewalls=СТРОКОЙ))) == 5
          and len(SL._стены_врага(dict(БАЗА, ewalls=СПИСКОМ))) == 5,
          "(а) стена разбирается И строкой моста, И списком трассы — по 5 клеток")
проверить(SL._стены_врага(dict(БАЗА)) == [] and SL._стены_врага(dict(БАЗА, ewalls="none")) == [],
          "(б) нет поля и «none» — пустой список, а не падение")

проверить(SL._частокол_на_пути(dict(БАЗА, ewalls=СТРОКОЙ), (1, 13), {}) is None,
          "(в) БЕЗ КЛЮЧА правило молчит — ни одно прежнее плечо не поедет")
проверить(SL._частокол_на_пути(dict(БАЗА, ewalls="none"), (1, 13), ВКЛ) is None,
          "(г) стен нет — перенацеливать нечего")

з = SL._частокол_на_пути(dict(БАЗА, ewalls=СТРОКОЙ), (1, 13), ВКЛ)
проверить(з is not None and з[0] == (2, 14),
          f"(д) из клеток НА ПУТИ берём САМУЮ СЛАБУЮ: {з[0] if з else None} (ждём 2,14 — её звено 1 %,"
          " и обход через неё не длиннее прямого)")
проверить(з is not None and "ЧАСТОКОЛ НА ПУТИ" in з[1] and "1 %" in з[1] and "СТРОИТСЯ" in з[1] and "обход" in з[1],
          "(е) правило говорит ВСЛУХ: клетку, звенья, слабейшее звено, стройку и обход")

# если доломанной клетки нет, берём слабейшую из остальных — 2,13 на 40 %
БЕЗ_СЛАБОЙ = "1,12,10,0,0,0,100;2,12,16,0,0,0,100;3,12,20,0,0,0,100;2,13,16,0,0,0,40"
ж = SL._частокол_на_пути(dict(БАЗА, ewalls=БЕЗ_СЛАБОЙ), (1, 13), ВКЛ)
проверить(ж is not None and ж[0] == (2, 13) and "40 %" in ж[1],
          f"(ж) без доломанной клетки берём слабейшую из прочих: {ж[0] if ж else None} (ждём 2,13 — 40 %)")

# запас обхода управляется ключом: с нулём клетка на шаг в сторону уже не годится
з2 = SL._частокол_на_пути(dict(БАЗА, ewalls=СТРОКОЙ), (1, 13), dict(ВКЛ, частокол_обход=0))
проверить(з2 is not None and з2[0] in ((2, 13), (2, 14)),
          f"(з) ключ `частокол_обход` сужает выбор, но преграду всё равно находит: {з2[0] if з2 else None}")

_и = SL._частокол_на_пути(dict(БАЗА, ewalls=СТРОКОЙ), (2, 13), ВКЛ)
проверить(_и is not None and _и[0] == (2, 14),
          f"(и) цель САМА в стене (запечатанная база) — правило РАБОТАЕТ и берёт слабейшее звено: {_и[0] if _и else None}. Прежняя защита тут молча выходила, и бот стоял")
проверить(SL._частокол_на_пути(dict(ewalls=СТРОКОЙ), (1, 13), ВКЛ) is None,
          "(к) нет координат армии — молчим, а не бьём наугад")
# запас обхода управляется ключом: с нулём стена сбоку не берётся
проверить(SL._частокол_на_пути(dict(БАЗА, ewalls="9,2,10,0,0,0,1"), (1, 13), ВКЛ) is None,
          "(л) стена далеко в стороне (9,2) при цели 1,13 — не преграда, не бьём")

# ВОРОТА при равной прочности предпочтительнее стены
з3 = SL._частокол_на_пути(dict(БАЗА, ewalls="2,13,16,0,0,0,100;3,13,16,0,2,0,100"), (1, 13), ВКЛ)
проверить(з3 is not None and з3[0] == (3, 13) and "ворота" in з3[1],
          f"(м) при равном hp берём клетку С ВОРОТАМИ: {з3[0] if з3 else None}")


# ВОРОНКА — на НАСТОЯЩЕЙ стратегии, не на заглушке: `привести` читает много её полей
# (`академия`, `академия_с`, …), и подделка их все не повторит. Файл берём живой.
ЖИВОЙ = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                     "sim/поиск/шт_s2_оборона_без_атаки_12мин_стойка_отряд_рефлекс_ратуша_пики_век_эко.json")


def через_воронку(п):
    стр = SL.ЖиваяСтратегия(ЖИВОЙ)
    проп, отд = collections.Counter(), collections.Counter()
    st = dict(БАЗА, ewalls=СТРОКОЙ, gametime=900, ba17=2, academies=1, wip="", upg_done="", upg_shown="")
    вышло = SL.привести([{"cmd": "ATTACK", "count": 80, "target": "cell", "cx": 1, "cy": 13,
                          "face": [1, 13]}], st, dict(стр.п, **п), стр, проп, отд)
    ат = [c for c in вышло if c.get("cmd") == "ATTACK"]
    return (ат[0] if ат else None), стр, отд


а0, с0, о0 = через_воронку({})
проверить(а0 is not None and (а0["cx"], а0["cy"]) == (1, 13) and а0.get("target") == "cell",
          f"(н) воронка БЕЗ ключа: цель и род приказа прежние — {(а0['cx'], а0['cy'], а0.get('target')) if а0 else None}")
а1, с1, о1 = через_воронку(ВКЛ)
проверить(а1 is not None and (а1["cx"], а1["cy"]) == (2, 14) and а1.get("target") == "wall",
          f"(о) воронка С ключом: удар перенацелен на стену 2,14 И род приказа стал wall — {(а1['cx'], а1['cy'], а1.get('target')) if а1 else None}")
проверить(а1 is not None and а1.get("face") == [2, 14],
          "(п) face переставлен на стену тоже — иначе бойцы смотрят мимо того, что бьют")
проверить(о1["ATTACK -> частокол"] == 1 and с1.реестр.мера["частокол: удар перенацелен на стену"] == 1
          and any("ЧАСТОКОЛ НА ПУТИ" in з for з in с1.реестр.записи),
          "(р) перенацеливание посчитано мерой и сказано в why")
проверить(о0["ATTACK -> частокол"] == 0 and с0.реестр.записи == [],
          "(с) без ключа ни меры, ни строки — тишина")

print(f"ошибок: {ошибок}")
raise SystemExit(1 if ошибок else 0)
