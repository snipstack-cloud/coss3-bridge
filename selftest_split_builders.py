# -*- coding: utf-8 -*-
"""ПОТОЛОК СТРОИТЕЛЕЙ ДЕЛИТСЯ МЕЖДУ ЗАКЛАДКАМИ ТАКТА (23.09).

Найдено разбором дебюта `base27`, где простой съедает 44,5 процента труда за
первые 200 секунд. На 12-й секунде модель заказала ратушу и мельницу одним
тактом при `BUILDERS 18`. Ратуша забрала всех восемнадцать, а мельница
получила от игры «BUILD eurmil: nobody to build it - no peasants at all» и
отложилась до 53-й секунды в одной копии и до 82-й в другой. Мельница
открывает еду — с неё и начинается голод дебюта.

Причина в устройстве блока, и обе её половины проверены по коду:
`block_hcmd.inc` читает потолок ОДНИМ предпроходом на такт и применяет к
КАЖДОЙ закладке, а людей с недостроя не снимает никогда (правило 16.09: новая
закладка обирала предыдущую, ратуша стояла на 92 процентах двенадцать минут).

Что проверяется:
  1. одна закладка — потолок не трогаем, модель вправе строить артелью;
  2. две закладки — потолок делится, и остаток достаётся второй;
  3. потолок НИЖЕ доли не поднимаем: мост урезает, а не раздаёт;
  4. вмешательство названо вслух и объясняет, что делать иначе;
  5. ключ есть и по умолчанию включён.
"""
import io, os, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import llm_policy as L

ошибок = 0


def проверить(условие, что):
    global ошибок
    if not условие:
        ошибок += 1
        print("  СБОЙ:", что)
    else:
        print("  ок:", что)


И = io.open(os.path.join(os.path.dirname(os.path.abspath(__file__)),
                         "llm_policy.py"), encoding="utf-8").read()


def поделить(закладок, потолок, свободных):
    """Та же арифметика, что в мосту; привязка к коду проверяется ниже."""
    доля = max(1, свободных // закладок)
    return доля if (закладок > 1 and потолок > доля) else потолок


print("1-3. арифметика деления")
проверить(поделить(1, 18, 18) == 18, "одна закладка — 18 остаётся 18")
проверить(поделить(2, 18, 18) == 9, "две закладки при 18 свободных — по 9")
проверить(поделить(3, 18, 17) == 5, "три закладки при 17 свободных — по 5")
проверить(поделить(2, 4, 18) == 4, "потолок 4 ниже доли 9 — не поднимаем")
проверить(поделить(2, 18, 1) == 1, "свободных 1 — доля не меньше единицы")

print("4. в мосту стоит ровно эта арифметика")
проверить('_доля = max(1, _своб // len(_зкл))' in И, "доля считается так же")
проверить('if len(_зкл) > 1 and _пот is not None:' in И,
          "делим только при двух и более закладках")
проверить('if _пот.a1 > _доля:' in И, "только вниз — мост урезает, а не раздаёт")

print("5. вмешательство названо вслух")
кусок = И[И.index("_доля = max(1, _своб // len(_зкл))"):][:1400]
проверить("сказать(" in кусок, "мост говорит о подмене")
проверить("некому" in кусок and "--split-builders 0" in кусок,
          "названа причина и то, чем отключается")
проверить("заказывай её одну" in кусок,
          "сказано, как добиться большой артели, а не только что запрещено")

print("6. ключ включён по умолчанию")
проверить(re.search(r'--split-builders",\s*type=int,\s*default=1', И) is not None,
          "default=1: это починка дефекта, а не идея")

print()
print("ошибок:", ошибок)
sys.exit(1 if ошибок else 0)
