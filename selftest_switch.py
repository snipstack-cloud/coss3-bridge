# -*- coding: utf-8 -*-
"""Самопроверка связки 4: «его защита съела наш урон — смени состав».

Урон = атака минус защита цели ПО ТИПУ ОРУЖИЯ, не меньше единицы
(lib/miscext2.script:380). Следствие, которого модель сама не выводит:
вложения врага в защиту от ПИК не трогают ПУЛЮ — она идёт против dbullet.

Живая партия 19.09: его пикинёр atk13 dpike7 против нашего atk8 — урон ровно
1 (пол), размен 12,86. Мушкетёр в том же положении бьёт на 6.

Стережётся:
* без ключа молчим — связка меряется отдельно;
* срабатывает ТОЛЬКО когда урон упёрся в пол, а не «когда размен плохой»;
* предлагается лишь тот вид, чьё здание УЖЕ стоит;
* названы оба числа (наш урон и урон заменой) и ПЛАТА.
"""
import llm_policy as L

беды = []


def проверка(имя, условие, пояснение=""):
    if условие:
        print("  ОК    " + имя)
    else:
        беды.append(имя)
        print("  ПЛОХО " + имя + (" — " + пояснение if пояснение else ""))


def строка(ключ=1, его_dpike=7, наш_atk=8, конюшня=0, казарм=2, наших=120):
    L.СМЕНА_СОСТАВА = ключ
    ст = {"gametime": 800, "peasants": 60, "mil_inf": наших, "mil_shooters": 0,
          "mil_cav": 0, "ba17": казарм, "stables": конюшня, "mills": 1,
          "p1_enemy": 1, "food": 20000, "gold": 9000, "iron": 3000,
          "p1_army": 200, "p1_inf": 200, "p1_shoot": 0, "p1_cav": 0,
          "fighters": (f"infantry17=pikeman,hp90,atk{наш_atk},wkind1,pause0,"
                       "dpike3,dsword2,dbullet4,food25,gold3,iron20 "
                       "musk17=musketeernet,hp65,atk10,wkind3,pause375,"
                       "dpike1,dsword1,dbullet0,food50,gold8,iron4 "
                       "dragoon17=dragoon,hp220,atk15,wkind3,pause562,"
                       "dpike0,dsword0,dbullet0,food90,gold7,iron5"),
          "p1_fighters": (f"infantry17=hp90,atk13,wkind1,pause0,dpike{его_dpike},"
                          "dsword6,dbullet4 "
                          "musk17=hp65,atk10,wkind3,pause375,dpike0,dsword0,dbullet0")}
    return "\n".join(L.сменить_состав(ст, {}))


print("Самопроверка смены состава:")
проверка("без ключа молчим", строка(ключ=0) == "")

с = строка()
проверка("строка появляется, когда урон упёрся в пол", с != "")
проверка("назван НАШ урон и слово ПОЛ", "на 1 — это ПОЛ" in с, с[:160])
проверка("названа его защита по нашему оружию", "dpike 7" in с, с[:160])
проверка("названа замена и ЕЁ урон", "musk17" in с and "урон 6" in с, с[:250])
проверка("во сколько раз больше", "в 6 раз больше" in с, с[:250])
проверка("назван готовый приказ", '"role":"musk17"' in с, с[-200:])
проверка("названа ПЛАТА", "ПЛАТА" in с and "порог" in с, с[-200:])

# пол не достигнут — менять не из-за чего
проверка("при атаке выше его защиты молчим", строка(наш_atk=20) == "",
         "урон 13, пола нет")

# конница лучше, но конюшни нет — не предлагаем недоступное
с2 = строка(конюшня=0)
проверка("не предлагаем вид, чьего здания нет", "dragoon17" not in с2, с2[:200])
с3 = строка(конюшня=1)
проверка("при готовой конюшне драгун в кандидатах",
         "dragoon17" in с3 or "musk17" in с3, с3[:200])

проверка("при крошечной армии молчим", строка(наших=3) == "",
         "менять состав из трёх бойцов нечего")

print()
if беды:
    print(f"БЕД: {len(беды)} — {', '.join(беды)}")
    raise SystemExit(1)
print("всё чисто")
