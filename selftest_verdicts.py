# -*- coding: utf-8 -*-
"""Три вердикта итога прошлого решения говорят правду там, где 22.09 врали.

Разбор 43 уроков модели за день показал: три повторяющихся урока ложны, и во
всех трёх виноват мост, а не модель (правило 2 проекта).

  1. UPGRADE: девять падений еды на 2000-4300 за такт шли сразу после
     UPGRADE bar.pikeman.X.3 (4200 еды по upg_shown), а мост говорил
     «проверить нечем» — модель записала «прокорм съедает больше поля».
     Теперь цена называется из состояния.
  2. ATTACK: из 26 «НИКТО НЕ ПОШЁЛ» в 7 блок волну ВЗЯЛ — wave_sent
     дописывается позже вердикта. Теперь вердикт помечен неокончательным,
     и следующим тактом мост даёт ПОПРАВКУ, если волна объявилась, снимая
     счётчик повторов.
  3. BUILD: «дело в ресурсах» про мельницу при дереве 300 и камне 300, а
     она стоит 60/300. Теперь при покрытой цене мост говорит «ресурсов
     ХВАТАЕТ» и цитирует игру, если та назвала причину.
  4. Трасса: урезание BALANCE (вмешательство) пишется полем — до 22.09 счёт
     по нему давал ложный ноль.
"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import llm_policy as L

ошибок = 0


def проверить(условие, что):
    global ошибок
    if not условие:
        ошибок += 1
        print("  СБОЙ:", что)
    else:
        print("  ок:", что)


БАЗА = {"gametime": 700, "food": 5000, "wood": 300, "stone": 300, "gold": 1000,
        "iron": 1000, "coal": 1000, "peasants": 40, "mills": 0, "wip": "",
        "wave_sent": 0, "my_freewar": 20, "my_agressors": 0, "ba17": 1,
        "build_cost": ("mill=food0,wood60,stone300,gold0,iron0,coal0 "
                       "ba17=food0,wood500,stone500,gold2500,iron0,coal0"),
        # upg_avail — поле ЖИВОГО состояния; upg_shown существует только в
        # трассе. 22.09 самопроверка стояла на upg_shown и потому прошла, а в
        # игре цена не называлась ни разу. Держим оба и проверяем каждое.
        "upg_avail": ("cen.1,mil.1,bar.pikeman.2.3=f4200g100i0,"
                      "bar.pikeman.1.3=f2100g50i0,aca.1=f0g325i0w200")}


def итог(было, стало, заказ, повторы=None):
    return "\n".join(L.итог_прошлого(было, стало, заказ, повторы))


print("1. UPGRADE называет цену")
т = итог(dict(БАЗА), dict(БАЗА, food=800), [("UPGRADE", "bar.pikeman.2.3", 0)])
проверить("еда 4200" in т and "золото 100" in т, "цена bar.pikeman.2.3 из upg_shown: еда 4200, золото 100")
проверить("плата за него, а не прокорм" in т, "сказано, что падение запаса — плата, а не прокорм")
проверить(L.цена_апгрейда("нет.такого", БАЗА) == "", "неизвестный апгрейд — цена не выдумывается")
проверить(L.цена_апгрейда("mil.1", БАЗА) == "", "апгрейд без цены в списке — пусто, а не выдумка")
проверить("дерево 200" in L.цена_апгрейда("aca.1", БАЗА), "академический апгрейд: считается и дерево")
# ГЛАВНОЕ: цена берётся из ЖИВОГО поля, а не из трассового
только_живое = {k: v for k, v in БАЗА.items() if k != "upg_shown"}
проверить("еда 4200" in L.цена_апгрейда("bar.pikeman.2.3", только_живое),
          "цена читается из upg_avail — поля, которое есть в живой игре")
только_трасса = dict(БАЗА); только_трасса.pop("upg_avail")
только_трасса["upg_shown"] = "bar.pikeman.2.3=f4200g100i0"
проверить("еда 4200" in L.цена_апгрейда("bar.pikeman.2.3", только_трасса),
          "upg_shown остаётся запасным — по нему считают готовые трассы")

print("2. ATTACK: вердикт неокончательный, поправка следующим тактом")
пов = {}
т1 = итог(dict(БАЗА, wave_sent=5), dict(БАЗА, wave_sent=5), [("ATTACK", "", 10)], пов)
проверить("НИКТО НЕ ПОШЁЛ" in т1 and "НЕ окончательный" in т1,
          "при неизменном wave_sent — «никто не пошёл», но с оговоркой")
проверить(("ATTACK", "ждём") in пов, "мост запомнил, что ждёт волну")
т2 = итог(dict(БАЗА, wave_sent=5), dict(БАЗА, wave_sent=10), [("BALANCE", "food", 3)], пов)
проверить("ПОПРАВКА" in т2 and "взял 10" in т2, "следующим тактом: «ПОПРАВКА: … блок взял 10»")
проверить(("ATTACK", "ждём") not in пов and ("ATTACK", "") not in пов,
          "ожидание и счётчик повторов сняты")
пов2 = {}
итог(dict(БАЗА, wave_sent=5), dict(БАЗА, wave_sent=5), [("ATTACK", "", 10)], пов2)
т3 = итог(dict(БАЗА, wave_sent=5), dict(БАЗА, wave_sent=5), [("BALANCE", "food", 3)], пов2)
проверить("ПОПРАВКА" not in т3, "если волна так и не объявилась — поправки нет")
проверить(("ATTACK", "ждём") not in пов2, "ожидание снимается после одного такта, не висит вечно")
т4 = итог(dict(БАЗА, wave_sent=5), dict(БАЗА, wave_sent=15), [("ATTACK", "", 10)], {})
проверить("ВОЛНА УШЛА" in т4 and "взял 15" in т4, "когда wave_sent сменился сразу — «волна ушла», как и было")

print("3. BUILD: «дело в ресурсах» только когда их не хватает")
т = итог(dict(БАЗА), dict(БАЗА), [("BUILD", "mill", 1)])
проверить("ресурсов ХВАТАЕТ" in т and "дерева 60" in т and "камня 300" in т,
          "мельница при 300/300: сказано, что ресурсов хватает, и названа цена")
проверить("дело в ресурсах" not in т, "ложного «дело в ресурсах» нет")
проверить("не находит строителей" in т, "названа настоящая причина первых секунд")
с_игрой = dict(БАЗА, last_fail="BUILD eurmil: nobody to build it - no peasants at all")
т = итог(dict(БАЗА), с_игрой, [("BUILD", "mill", 1)])
проверить("Игра сказала" in т and "nobody to build" in т, "если игра назвала причину — она процитирована")
т = итог(dict(БАЗА), dict(БАЗА, wood=30), [("BUILD", "mill", 1)])
проверить("дело в ресурсах" in т, "при дереве 30 — по-прежнему «дело в ресурсах»")
т = итог(dict(БАЗА), dict(БАЗА, wip="mill/10/8/12"), [("BUILD", "mill", 1)])
проверить("УЖЕ ЗАЛОЖЕНО" in т, "если мельница уже в wip — «уже заложено», как и было")

print("4. трасса: поле вмешательства")
src = open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "llm_policy.py"),
           encoding="utf-8").read()
проверить('"вмешательство": str(box.get("вмешательство") or "")' in src,
          "запись трассы содержит поле «вмешательство»")
проверить('box["вмешательство"] = вмешательство' in src,
          "коробка такта получает вмешательство в момент сборки запроса")

print()
print("ошибок:", ошибок)
sys.exit(1 if ошибок else 0)
