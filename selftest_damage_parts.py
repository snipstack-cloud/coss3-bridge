# -*- coding: utf-8 -*-
"""Разложение атаки: откуда берётся `atk` и почему апгрейды по списку НЕ прибавляют.

Повод, 28.09 (просьба мака). Он считал силу бойцов по списку взятых апгрейдов
(`upg_done`, `p1_upg_done`) и назвал дыру: если враг возьмёт АКАДЕМИЧЕСКИЕ
апгрейды, а поле промолчит, его стрелки окажутся сильнее нашего счёта, и правило
ошибётся в опасную сторону.

Дыра оказалась не там. Движок держит у оружия ЧЕТЫРЕ числа
(`classes.script:3549`): `damageinit` из данных, `damagestatic` — плоская прибавка
кузницы, `damagepercent` — ПРОЦЕНТНАЯ прибавка академии, и `damage`, который он
пересчитывает при каждом апгрейде любого вида:

    damage := floor((damageinit + damagestatic) * (1 + damagepercent / 100))

`player.script:1765` для плоских, `:1784` для процентных. А `atk` в `fighters` и
`p<n>_fighters` — это и есть `damage` (лучший оружейный слот, не нулевой). Значит
академические проценты в нём УЖЕ сидят, и прибавлять их по списку значит считать
дважды — ошибка в ту же опасную сторону, только с другого конца.

Чтобы это не оставалось верой на слово, блок с 28.09 отдаёт и сами члены —
`dinit`, `dmgs`, `dmgp`, — а `combat_math.сверка_атаки` проверяет тождество на
любых числах: живых, из трассы, из мока.

ЛОВУШКА ИМЕНИ, поймана этой же проверкой при первой попытке. Поле звалось `dmg0`,
и разбор прочитал его как `dmg` = 12: `combat_math._число` срезает от имени ВСЕ
хвостовые цифры. Поэтому имя поля не может кончаться цифрой — это правило
стережётся здесь по всем полям, какие блок пишет в строки бойцов.
"""
import io
import os
import re
import tempfile

import combat_math as C

беды = []


def проверка(имя, условие, пояснение=""):
    if условие:
        print("  ОК    " + имя)
    else:
        беды.append(имя)
        print("  ПЛОХО " + имя + (" — " + str(пояснение)[:300] if пояснение else ""))


ЗДЕСЬ = os.path.dirname(os.path.abspath(__file__))
БЛОК = io.open(os.path.join(ЗДЕСЬ, "block_hstate.inc"), encoding="latin-1").read()
МОК = io.open(os.path.join(ЗДЕСЬ, "mock_human.py"), encoding="utf-8").read()

# --- 1. Блок пишет три члена, обеим сторонам, ИЗ ТОГО ЖЕ СЛОТА -------------
for кто, строка, игрок, cid, uid, слот in (
        ("наши", "hsftxt", "plind", "hscid", "hsfid", "hsfwb"),
        ("его", "hsyftxt", "hspl", "hsycid", "hsyfid", "hsyfwb")):
    for поле, свойство in (("dmgs", "damagestatic"), ("dmgp", "damagepercent"),
                           ("dinit", "damageinit")):
        вызов = (f"{строка} := {строка} + ',{поле}' + IntToStr("
                 f"gPlayer[{игрок}].objbase[{cid}][{uid}].weapon[{слот}].{свойство});")
        проверка(f"{кто}: блок пишет {поле} из {свойство}", вызов in БЛОК, вызов)

проверка("в блоке нет кириллицы", not any(ord(c) > 127 for c in БЛОК))

# ИЗ ТОГО ЖЕ СЛОТА, что атака, — иначе число описывает другое оружие. Проверяем
# не текстом, а сравнением: слот, которым взята атака, и слот членов — один.
for кто, строка, слот in (("наши", "hsftxt", "hsfwb"), ("его", "hsyftxt", "hsyfwb")):
    атака = re.search(rf"{строка} := {строка} \+ ',atk' \+ IntToStr\((\w+)\);", БЛОК)
    проверка(f"{кто}: атака берётся из переменной лучшего слота", атака is not None)
    проверка(f"{кто}: члены берутся из слота {слот}, как и атака",
             БЛОК.count(f".weapon[{слот}].damagestatic") == 1
             and БЛОК.count(f".weapon[{слот}].damagepercent") == 1)

# --- 2. ЛОВУШКА ИМЕНИ: ни одно поле строки бойцов не кончается цифрой ------
имена = set(re.findall(r"\+ ',([a-z_]+[a-z0-9_]*)' \+ IntToStr", БЛОК))
плохие = sorted(и for и in имена if и[-1].isdigit())
проверка("ни одно имя поля не кончается цифрой", not плохие,
         f"разбор съест цифру как число: {плохие}")
проверка("имена найдены, проверка не пустая", len(имена) >= 8, имена)

# --- 3. Тождество: счёт, а не вера ----------------------------------------
плоский = C.сверка_атаки({"atk": 15, "dinit": 12, "dmgs": 3, "dmgp": 0})
проверка("плоская прибавка: сходится",
         плоский and плоский["сходится"] is True and плоский["ожидалось"] == 15, плоский)
процентный = C.сверка_атаки({"atk": 26, "dinit": 12, "dmgs": 8, "dmgp": 30})
проверка("ПРОЦЕНТНАЯ прибавка сидит в atk: floor(20*1.3)=26",
         процентный and процентный["сходится"] is True, процентный)
проверка("округление вниз, как floor у движка",
         C.сверка_атаки({"atk": 15, "dinit": 10, "dmgs": 2, "dmgp": 30})["ожидалось"] == 15,
         "floor(12*1.3)=15.6 -> 15")
кривое = C.сверка_атаки({"atk": 99, "dinit": 12, "dmgs": 3, "dmgp": 0})
проверка("расхождение видно", кривое and кривое["сходится"] is False, кривое)
проверка("нет членов — мера молчит, а не осуждает",
         C.сверка_атаки({"atk": 15}) is None,
         "мост до 28.09: «нет полей» и «не сходится» — разные вещи")

# --- 4. Разбор не путает имена --------------------------------------------
поля = C.разобрать("infantry17=pikeman,hp120,atk15,dpike5,dmgs3,dmgp0,dinit12")["infantry17"]
проверка("разбор даёт dinit, а не dmg",
         поля.get("dinit") == 12 and "dmg" not in поля, поля)

# --- 5. Мок: те же поля, и на его числах тождество выполняется -------------
проверка("мок отдаёт три члена",
         "dmgs{2 * len(self.апгрейды)},dmgp0,dinit12" in МОК
         and "dmgs0,dmgp0,dinit10" in МОК)

import mock_human as ММ
from coss3_bridge import parse_parser_file

with tempfile.TemporaryDirectory() as врем:
    мир = ММ.Мир(врем, plind=1)
    мир.апгрейды = {"bar.pikeman.1.1", "bar.pikeman.1.2"}
    мир.состояние()
    сырое = io.open(os.path.join(врем, "coss3_eco_P1.dat"), encoding="latin-1").read()
    st = parse_parser_file(сырое)
    бойцы = C.разобрать(st.get("fighters") or "")
    проверка("на моке строка бойцов доехала через файл", len(бойцы) >= 2, list(бойцы))
    сверки = {имя: C.сверка_атаки(поля) for имя, поля in бойцы.items()}
    проверка("на моке члены есть у каждого бойца",
             all(с is not None for с in сверки.values()), сверки)
    проверка("на моке тождество выполняется у каждого",
             all(с["сходится"] for с in сверки.values() if с), сверки)
    проверка("апгрейды двинули плоскую прибавку, а не проценты",
             сверки["infantry17"]["плоских"] == 4 and сверки["infantry17"]["процентов"] == 0,
             сверки["infantry17"])

print()
if беды:
    print(f"ПЛОХО: {len(беды)} — " + "; ".join(беды))
    raise SystemExit(1)
print("все проверки прошли")
