# -*- coding: utf-8 -*-
"""Готовность строя надо НАЗЫВАТЬ готовностью.

Повод, серия `wood_academy` 27.09. Академия встала во всех трёх копиях — впервые
за всю историю проекта, — офицеров и барабанщиков стало по 3-5, и команда
FORMATION не отдана НИ РАЗУ. Причина не в модели: строка запроса была ОДНА И ТА
ЖЕ при нуле и при пятерых — «Нужны ОБА (officer17 и drummer17 из академии), потом
команда FORMATION». Модель читала её как недостачу и писала в уроках «офицер и
барабанщик не вышли», имея пятерых.

Стережётся: при обоих больше нуля запрос говорит «МОЖНО СОБРАТЬ ПРЯМО СЕЙЧАС» и
называет саму команду; при нехватке — называет, ЧЕГО именно не хватает; когда
строй собран, идут его числа, а призыва уже нет.
"""
import os
import re

import llm_policy as L

КАТАЛОГ = os.path.join(os.path.dirname(os.path.abspath(__file__)), "fixtures")
беды = []


def проверка(имя, условие, пояснение=""):
    if условие:
        print("  ОК    " + имя)
    else:
        беды.append(имя)
        print("  ПЛОХО " + имя + (" — " + str(пояснение)[:300] if пояснение else ""))


def состояние(путь):
    st = {}
    for строка in open(путь, encoding="latin-1"):
        if "=" in строка:
            k, _, v = строка.partition("=")
            st[k.strip()] = v.strip()
    return st


def строки_про_строй(правки):
    st = состояние(os.path.join(КАТАЛОГ, "state_late.dat"))
    st.update(правки)
    L.ЧЕСТНО = True
    текст = L.situation(st, {}, [], "", волны=[], мир="")
    return [x.strip() for x in текст.split("\n")
            if re.search("СТРОЙ|СТРОЯ|строй:|FORMATION", x)]


нет = " ".join(строки_про_строй({"my_officers": "0", "my_drummers": "0", "squads": "0"}))
оба = " ".join(строки_про_строй({"my_officers": "5", "my_drummers": "5", "squads": "0"}))
один = " ".join(строки_про_строй({"my_officers": "2", "my_drummers": "0", "squads": "0"}))
собран = " ".join(строки_про_строй({"my_officers": "5", "my_drummers": "5", "squads": "1",
                                    "squad_units": "17", "squad_form": "SQUARE15",
                                    "squad_dmg": "2", "squad_def": "2",
                                    "squad_hdmg": "7", "squad_hdef": "7"}))

проверка("оба есть — запрос зовёт собрать строй СЕЙЧАС", "ПРЯМО СЕЙЧАС" in оба, оба[:200])
проверка("оба есть — названа сама команда", '"cmd":"FORMATION"' in оба, оба[:200])
проверка("оба есть — слова «нужны оба» больше НЕТ",
         "Нужны ОБА" not in оба and "НЕ ХВАТАЕТ" not in оба, оба[:200])
проверка("нет никого — сказано, чего не хватает",
         "НЕ ХВАТАЕТ офицера и барабанщика" in нет, нет[:200])
проверка("нет барабанщика — назван именно он",
         "НЕ ХВАТАЕТ барабанщика" in один, один[:200])
проверка("нехватка не выглядит готовностью", "ПРЯМО СЕЙЧАС" not in нет, нет[:200])
проверка("строй собран — идут его числа, а призыва уже нет",
         "SQUARE15" in собран and "ПРЯМО СЕЙЧАС" not in собран, собран[:200])

print()
if беды:
    print(f"БЕД: {len(беды)} — {', '.join(беды)}")
    raise SystemExit(1)
print("всё чисто")
