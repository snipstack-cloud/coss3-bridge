# -*- coding: utf-8 -*-
"""РАЗБОР ЕДЫ (7.10): баланс по тактам и цены ступеней по провалу.

Разбор пишется ради одного вопроса — куда уходит еда, — и у него три способа
соврать, каждый из которых уже случился при написании и потому проверяется:

  * считать траты по ЗАПРОШЕННЫМ `TRAIN`. Первая редакция так и делала и
    насчитала 921 мушкетёра при шести живых: мост просит найм каждый такт, движок
    почти всегда отказывает, а отказ еды не стоит. Траты считаются приростом
    юнитов в состоянии;
  * сопоставлять траты со снимком по РАВЕНСТВУ игрового времени. Снимок идёт
    каждые 2-5 с, решение раз в 5-15 с, и так поймалось 50 тактов из 2569.
    Поэтому траты берутся из того же состояния, что и всё остальное;
  * приписать цену ступени не тому заказу. Движок списывает при заказе, ступень
    появляется около 16 с позже, и если в окне два провала или две ступени —
    цену приписать нельзя, надо промолчать.
"""
import io
import json
import os
import subprocess
import sys
import tempfile

ЗДЕСЬ = os.path.dirname(os.path.abspath(__file__))
ошибок = 0


def проверить(условие, что):
    global ошибок
    if not условие:
        ошибок += 1
        print("  СБОЙ:", что)
    else:
        print("  ок:", что)


def прогнать(снимки, *ключи) -> str:
    with tempfile.TemporaryDirectory() as кат:
        путь = os.path.join(кат, "coss3_snap.jsonl")
        with io.open(путь, "w", encoding="utf-8", newline="") as ф:
            for с in снимки:
                ф.write(json.dumps(с, ensure_ascii=False) + "\n")
        из = subprocess.run(
            [sys.executable, os.path.join(ЗДЕСЬ, "разбор_еды.py"),
             "--снимок", путь, *ключи],
            capture_output=True, text=True, encoding="utf-8",
            env=dict(os.environ, PYTHONIOENCODING="utf-8"))
        return (из.stdout or "") + (из.stderr or "")


def снимок(gt, еда, на_еде=10, крестьян=10, пехоты=0, стрелков=0,
           прокачки="", золото=1000, мельниц=1):
    return {"gametime": gt, "food": еда, "on_food": на_еде, "food_ready": 5,
            "peasants": крестьян, "mil_inf": пехоты, "mil_shooters": стрелков,
            "mil_cav": 0, "mills": мельниц, "gold": золото,
            "upg_done": прокачки, "my_farm": 400, "my_farmused": 100}


print("1. баланс сходится, когда никто ничего не покупает")
# 10 на еде дают 11,0; 10 голов съедают 1,0; ждём +10,0 в секунду, то есть +50 за 5 с.
из = прогнать([снимок(100, 1000), снимок(105, 1050)])
проверить("НЕВЯЗКА медиана +0.00" in из, f"нулевая невязка названа нулём: {из[:300]!r}")

print("2. найм считается по ПРИРОСТУ юнитов, а не по запросам")
# За 5 с приход 50, съели 1,0*5=5, куплен пикинёр за 25 -> ждём 1000+50-5-25=1020.
из = прогнать([снимок(100, 1000), снимок(105, 1020, пехоты=1, крестьян=10)])
проверить("пикинёр" in из, f"покупка увидена по состоянию: {из[:300]!r}")
проверить("тактов с тратой еды 1 из 1" in из, "трата отнесена к тому такту")

print("3. прокорм считают ВСЕ головы, а не только крестьяне")
# 30 голов (10 крестьян + 20 пехоты) съедают 3,0 в секунду против 1,0 у десяти.
мало = прогнать([снимок(100, 1000), снимок(105, 1000)])
много = прогнать([снимок(100, 1000, пехоты=20), снимок(105, 1000, пехоты=20)])
проверить("прокорм" in мало and "прокорм" in много, "прокорм показан в разбивке")
проверить(мало != много, "армия меняет прокорм, а не только крестьяне")

print("4. цена ступени снимается по провалу перед её появлением")
# Провал 16000 на gt=105, ступень появилась на gt=120 — через 15 с, как в игре.
из = прогнать([снимок(100, 16100, прокачки="bar.pikeman.1.4"),
               снимок(105, 100, прокачки="bar.pikeman.1.4", золото=200),
               снимок(110, 200, прокачки="bar.pikeman.1.4", золото=200),
               снимок(120, 300, прокачки="bar.pikeman.1.4,bar.pikeman.1.5",
                      золото=200)])
проверить("ЦЕНЫ СТУПЕНЕЙ" in из, f"лестница напечатана: {из[:300]!r}")
проверить("bar.pikeman.1.5" in из, "ступень названа")
проверить("16000" in из, "цена снята провалом, а не выдумана")

print("5. две ступени сразу — цену приписать нельзя, и разбор молчит")
из = прогнать([снимок(100, 16100, прокачки="bar.pikeman.1.4"),
               снимок(105, 100, прокачки="bar.pikeman.1.4", золото=200),
               снимок(120, 300, золото=200,
                      прокачки="bar.pikeman.1.4,bar.pikeman.1.5,bar.pikeman.2.1")])
проверить("bar.pikeman.1.5" not in из,
          f"наугад цена не приписана: {из[:300]!r}")

print("6. мерится ПОСЛЕДНЯЯ партия файла, а `--все` сводит все")
двe = [снимок(600, 5000), снимок(605, 5050),
       снимок(100, 1000), снимок(105, 1050)]
одна = прогнать(двe)
проверить("партий 2, мерю партию 2" in одна,
          f"последняя партия выбрана: {одна[:200]!r}")
все = прогнать(двe, "--все")
проверить("мерю все" in все, "`--все` сводит обе")
проверить("тактов 1;" in одна and "тактов 2;" in все,
          "в одной партии такт один, во всех два")

print("7. без мельницы приход не считается — поля нет вовсе")
из = прогнать([снимок(100, 1000, мельниц=0), снимок(105, 995, мельниц=0)])
проверить("НЕВЯЗКА" in из, "разбор не падает без мельницы")

print()
print("ошибок:", ошибок)
sys.exit(1 if ошибок else 0)
