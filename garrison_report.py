# -*- coding: utf-8 -*-
"""Гарнизон врага и доступность его крестьян — по трассам серий.

Отвечает на вопрос, который модель задавала в каждой второй партии: стоит ли
армия противника гарнизоном и выходят ли его крестьяне за базу. Считает по
полям `p1_army`, `p1_mv_n`, `p1_mv_base` и по клеткам оценки (`state.assess`),
поэтому работает на любой трассе с веткой open-info.

    python3 garrison_report.py <каталог с трассами> [<каталог> ...]

Ответ 19.09 по 15 партиям лежит в `world.md`: гарнизон не двигается до десятой
минуты, а клетки крестьян без охраны кончаются на третьей.
"""
import sys
import json, glob, os, statistics

def чис(v):
    try:
        return int(float(v))
    except (TypeError, ValueError):
        return None

корни = sys.argv[1:] or ["."]
пути = []
for к in корни:
    пути += sorted(glob.glob(os.path.join(к, "**", "coss3_bot.jsonl"), recursive=True))
if not пути:
    print("трасс не нашлось: нужен каталог с coss3_bot.jsonl внутри")
    raise SystemExit(1)

тактов = 0
движ = []          # доля его армии в движении
к_базе = []        # сколько из них к нашей базе
клеток = 0
без_охраны = 0
охрана = []        # бойцов рядом с клеткой крестьян
разброс = []       # сколько клеток с крестьянами за такт
крестьян_в_клетке = []
по_времени = {}    # минута -> [доля в движении]

for f in пути:
    for строка in open(f, encoding="utf-8"):
        строка = строка.strip()
        if not строка:
            continue
        r = json.loads(строка)
        s = r.get("state") or {}
        a = s.get("assess") or {}
        армия = чис(s.get("p1_army"))
        mv = чис(s.get("p1_mv_n"))
        mvb = чис(s.get("p1_mv_base"))
        if армия and армия > 0 and mv is not None:
            тактов += 1
            д = mv / армия
            движ.append(д)
            к_базе.append((mvb or 0) / армия)
            мин = int((чис(r.get("gt")) or 0) // 60)
            по_времени.setdefault(мин, []).append(д)
        кл = a.get("клетки") or []
        if кл:
            разброс.append(len(кл))
        for c in кл:
            клеток += 1
            охрана.append(c["их_рядом"])
            крестьян_в_клетке.append(c["крестьян"])
            if c["их_рядом"] == 0:
                без_охраны += 1

print("файлов %d, тактов с числами врага %d, клеток с его крестьянами %d"
      % (len(пути), тактов, клеток))
print()
print("=== СТОИТ ЛИ ЕГО АРМИЯ ГАРНИЗОНОМ ===")
if движ:
    print("  доля армии В ДВИЖЕНИИ: медиана %.0f%%, среднее %.0f%%, максимум %.0f%%"
          % (100 * statistics.median(движ), 100 * statistics.mean(движ), 100 * max(движ)))
    нули = sum(1 for d in движ if d == 0)
    print("  тактов, где не двигался НИКТО: %d из %d (%.0f%%)"
          % (нули, len(движ), 100 * нули / len(движ)))
    почти = sum(1 for d in движ if d <= 0.1)
    print("  тактов, где в движении не больше десятой части: %d (%.0f%%)"
          % (почти, 100 * почти / len(движ)))
if к_базе:
    print("  доля армии, идущей К НАШЕЙ базе: медиана %.0f%%, максимум %.0f%%"
          % (100 * statistics.median(к_базе), 100 * max(к_базе)))
print()
print("=== ВЫХОДЯТ ЛИ ЕГО КРЕСТЬЯНЕ ИЗ-ПОД ОХРАНЫ ===")
if охрана:
    print("  бойцов рядом с клеткой крестьян: медиана %d, минимум %d, максимум %d"
          % (statistics.median(охрана), min(охрана), max(охрана)))
    print("  клеток БЕЗ единого бойца рядом: %d из %d (%.0f%%)"
          % (без_охраны, клеток, 100 * без_охраны / клеток))
if разброс:
    print("  клеток с крестьянами за такт: медиана %d, максимум %d"
          % (statistics.median(разброс), max(разброс)))
if крестьян_в_клетке:
    print("  крестьян в клетке: медиана %d, максимум %d"
          % (statistics.median(крестьян_в_клетке), max(крестьян_в_клетке)))
print()
print("=== МЕНЯЕТСЯ ЛИ ЭТО ПО ХОДУ ПАРТИИ (доля армии в движении) ===")
for мин in sorted(по_времени):
    v = по_времени[мин]
    if len(v) >= 5:
        print("  минута %2d: %3d тактов, в движении медиана %.0f%%"
              % (мин, len(v), 100 * statistics.median(v)))
