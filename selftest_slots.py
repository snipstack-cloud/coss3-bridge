# -*- coding: utf-8 -*-
"""Самопроверка ДВУХ СЛОТОВ: найм думает одновременно с тактом.

До 21.09 слот был один, и событийный вопрос о найме ВЫТЕСНЯЛ обычный такт.
Замер серии hire_channel против base24: обычных тактов 32,8 на партию против
47,6 у базы — минус 31 процент общих решений за партию.

Проверяется ПОВЕДЕНИЕ развилки, а не текст исходника: кто разбирается за
проход, уцелевает ли слот такта, когда разбирается найм, и не запирает ли
вечно думающий найм обычные решения. Отправка команд при этом остаётся
однопоточной — Bridge.send при гонке молча затирает чужую пачку.
"""
class Поток:
    def __init__(self, жив): self._ж = жив
    def is_alive(self): return self._ж


def развилка(pending, pending_найм):
    """Точная копия развилки из llm_policy: кто разбирается за проход."""
    готовы = [(с[1]["t"], имя, с) for имя, с in
              (("найм", pending_найм), ("такт", pending))
              if с is not None and not с[0].is_alive()]
    if not готовы:
        return "ждём", pending, pending_найм
    готовы.sort(key=lambda x: x[0])
    кто = готовы[0][1]
    return (кто,
            None if кто == "такт" else pending,
            None if кто == "найм" else pending_найм)


жив, готов = Поток(True), Поток(False)
Т = lambda п, t: (п, {"t": t})
случаи = [
    ("оба думают",              Т(жив, 1),   Т(жив, 2),   "ждём"),
    ("готов только такт",       Т(готов, 1), Т(жив, 2),   "такт"),
    ("готов только найм",       Т(жив, 1),   Т(готов, 2), "найм"),
    ("оба готовы, такт старше", Т(готов, 1), Т(готов, 5), "такт"),
    ("оба готовы, найм старше", Т(готов, 9), Т(готов, 2), "найм"),
    ("найма нет, такт готов",   Т(готов, 1), None,        "такт"),
    ("такта нет, найм готов",   None,        Т(готов, 2), "найм"),
    ("пусто",                   None,        None,        "ждём"),
]
беды = []
for имя, p, h, ждём in случаи:
    кто, p2, h2 = развилка(p, h)
    ок = кто == ждём
    # ГЛАВНОЕ: разбирается один — второй слот обязан УЦЕЛЕТЬ
    if кто == "найм" and p is not None and p2 is not p:
        ок, имя = False, имя + " (такт потерян!)"
    if кто == "такт" and h is not None and h2 is not h:
        ок, имя = False, имя + " (найм потерян!)"
    print(("  ОК    " if ок else "  ПЛОХО ") + f"{имя}: {кто}")
    if not ок: беды.append(имя)

# ГОЛОДАНИЕ. Правило «найм первым» морило такт: при --hire-every 10-25 событие
# готово почти всегда, и такт ждал очереди — на моке 9 нарушений порядка gt из
# 62 записей, с отставанием до 274 игровых секунд. Порядок по времени запроса
# этого не допускает: попросили раньше — разберут раньше.
кто, _, _ = развилка(Т(готов, 1), Т(готов, 2))
ок = кто == "такт"
print(("  ОК    " if ок else "  ПЛОХО ") + "старый такт НЕ ждёт свежего найма")
if not ок: беды.append("голодание такта")
кто, _, _ = развилка(Т(готов, 5), Т(жив, 1))
ок = кто == "такт"
print(("  ОК    " if ок else "  ПЛОХО ") + "думающий найм НЕ запирает такт")
if not ок: беды.append("запирание")
print()
print(f"БЕД: {len(беды)}" if беды else "всё чисто")
raise SystemExit(1 if беды else 0)
