# -*- coding: utf-8 -*-
"""Самопроверка связки 1: «его отряд у базы — вот готовый приказ».

Строка «ЕГО ОТРЯД N — в K клетках» говорится с 19.09, и её мало: команда,
названная без числа и без готового приказа, всё равно что не названа. Замер
20.09 на 51 такте: MOVE упомянут в 75 процентах тактов и отдан НОЛЬ раз,
UPGRADE назван в 2 процентах и отдан 56 раз — потому что рядом стоят цена и
выигрыш.

Пересчёт по 209 состояниям base21: строка выпадает в 76 тактах, из них 49 —
в 3-5 клетках, где блок «ВРАГ У ТВОЕЙ БАЗЫ» (радиус 2) молчит. В этих 49
тактах модель посылала волну дважды, и лишь однажды — в клетку этого отряда.

Стережётся:
* без ключа молчим и база остаётся ДОСЛОВНО прежней;
* ближе трёх клеток не дублируем блок «ВРАГ У ТВОЕЙ БАЗЫ»;
* не зовём бить, когда бить нечем: нужное число считается разменом;
* в одном такте мост не говорит «бей» и «нечем» разом.
"""
import llm_policy as L

беды = []


def проверка(имя, условие, пояснение=""):
    if условие:
        print("  ОК    " + имя)
    else:
        беды.append(имя)
        print("  ПЛОХО " + имя + (" — " + пояснение if пояснение else ""))


def состояние(его_отряд=15, клетка=(8, 8), свободных=116, его_армия=131):
    """Наша ратуша в (3,12); отряд врага ставится в названную клетку."""
    n = 16
    ст = {"gametime": 800, "grid_n": n, "map_w": 256, "map_open": 1,
          "my_cx": 3, "my_cy": 12, "my_freewar": свободных,
          "peasants": 60, "mil_inf": свободных, "mil_shooters": 0,
          "mil_cav": 0, "ba17": 2, "mills": 1, "food": 20000, "gold": 9000,
          "p1_enemy": 1, "p1_army": его_армия, "p1_ba17": 2,
          "fighters": ("infantry17=pikeman,hp90,atk8,wkind1,pause0,rmax190,"
                       "dpike3,dsword2,dbullet4,food25,gold3,iron20"),
          "p1_fighters": ("infantry17=hp90,atk13,wkind1,pause0,rmax190,"
                          "dpike7,dsword6,dbullet4")}
    # Клетка пишется знаком: 1-9 цифрой, 10-35 буквой a-z, 36-61 буквой A-Z,
    # 62 и больше «+» —
    # нижняя граница (`coss3_map.знак`). Ставить всегда цифру значило бы
    # никогда не проверить ветку со срезанным числом.
    import coss3_map as _карта
    цифра = _карта.знак(его_отряд)
    # Наш центр берётся из сетки `arow` (coss3_map.центр_сетки), а не из
    # my_cx/my_cy: пустая сетка — и блок молчит по построению. На этом
    # самопроверка однажды дала ложный ноль.
    свои = _карта.знак(max(1, свободных))
    for y in range(n):
        ряд = ["."] * n
        если_наш = ["."] * n
        if y == клетка[1]:
            ряд[клетка[0]] = цифра
        if y == 12:
            если_наш[3] = свои
        ст[f"frow{y}"] = "".join(ряд)
        ст[f"arow{y}"] = "".join(если_наш)
    return ст


def текст(ключ=1, **kw):
    """situation() возвращает ГОТОВУЮ строку. Склейка её через join режет
    текст по символам, и любая проверка подстроки даёт ложный ноль — на этом
    самопроверка сама себя однажды обманула."""
    L.УДАР_ПО_ОТРЯДУ = ключ
    ст = состояние(**kw)
    return L.situation(ст, ст, [], "", None)


# ключ выключен — ни приказа, ни отказа
без = текст(ключ=0)
проверка("без ключа приказа нет", "ОТБИТЬ ЕГО ЗДЕСЬ" not in без)
проверка("без ключа и отказа нет", "бить этот отряд НЕЧЕМ" not in без)
проверка("без ключа строка об отряде остаётся", "ЕГО ОТРЯД" in без)

с = текст()
проверка("приказ появляется", "ОТБИТЬ ЕГО ЗДЕСЬ" in с, с[:200])
проверка("приказ ведёт в клетку ОТРЯДА",
         '"cmd":"ATTACK","count":"all","target":"cell","cx":8,"cy":8' in с)
проверка("назван размен у базы против поля", "0,67" in с and "0,19" in с)
проверка("названо нужное число одним кулаком", "одним кулаком (размен по" in с)
проверка("названа ПЛАТА", "плата: пока бьёшь" in с and "дом без прикрытия" in с)

# ближе трёх клеток говорит блок «ВРАГ У ТВОЕЙ БАЗЫ» — не дублируем
близко = текст(клетка=(3, 10))
проверка("в 2 клетках приказа связки нет", "ОТБИТЬ ЕГО ЗДЕСЬ" not in близко,
         "там говорит блок «ВРАГ У ТВОЕЙ БАЗЫ»")

# бить нечем: отряд 9, свободных 10, размен по пикинёрам 3,75 -> нужно ~20
мало = текст(его_отряд=9, свободных=10, его_армия=130)
проверка("при нехватке сил приказа нет", "ОТБИТЬ ЕГО ЗДЕСЬ" not in мало, мало[-400:])
проверка("при нехватке сказано вслух, а не промолчано",
         "бить этот отряд НЕЧЕМ" in мало, мало[-400:])
проверка("в такте отказа мост не зовёт бить",
         "бей этот отряд ДО подхода" not in мало, мало[-400:])
проверка("при нехватке сказано, что делать вместо",
         "Держи их дома" in мало, мало[-400:])
проверка("бей и нечем не встречаются вместе",
         not ("ОТБИТЬ ЕГО ЗДЕСЬ" in с and "бить этот отряд НЕЧЕМ" in с))

# ОДИН ОТРЯД — ОДНО ЧИСЛО (20.09). Живая партия: про отряд в клетке (5,12) мост
# в одном такте сказал «не меньше 36», «ближайшие 36», «идут 37» и «ЕГО ОТРЯД
# 43». Модель сложила их по-своему («58 его отряда») и не пошла бить, хотя
# свободных было 69 при нужных 52. Числа считаются по-разному нарочно, убрать
# какое-то нельзя — но сказать, что бойцы ОДНИ И ТЕ ЖЕ, обязано.
# 80, а не 40: с 26.09 клетка срезается на 62, и сорок пишутся точно буквой E —
# ветку со срезанным числом надо проверять числом ВЫШЕ потолка.
близко2 = текст(клетка=(3, 11), его_отряд=80, свободных=80)
проверка("при срезанной цифре сказано, что это нижняя граница",
         "СРЕЗАНА на 62" in близко2, "иначе числа складывают")
проверка("сказано, что это ТЕ ЖЕ бойцы, а не добавка",
         "ТЕ ЖЕ бойцы, а не добавка" in близко2)

# Строка «можно послать сейчас» стояла рядом с «бить нечем» и читалась как
# приглашение: 14:07 модель послала 7 бойцов против 52 сразу после отказа.
проверка("строка о числе волны не приглашает послать всех",
         "НЕ ПРИГЛАШЕНИЕ ПОСЛАТЬ ВСЕХ" in близко2, близко2[:200])
проверка("решение о числе всё равно остаётся за моделью",
         "Число волны — твоё" in близко2)

print()
if беды:
    print(f"БЕД: {len(беды)} — {', '.join(беды)}")
    raise SystemExit(1)
print("всё чисто")
