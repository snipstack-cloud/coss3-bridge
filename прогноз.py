# -*- coding: utf-8 -*-
"""ПРОГНОЗ БОЯ ДО ПРИКАЗА — ожидаемые потери сторон по стоимости, с составом, прокачками и временем прибытия (8.10, §113).

Зачем (игрок 8.10, задание «запрет ручейка»): новая волна и подмога не должны идти в ожидаемый невыгодный контакт
по частям. Перед отправкой мост оценивает бой: кто реально вступит вместе, что останется от уже дерущейся волны к
приходу подмоги, сколько будет стоить размен. Один код для живого моста и симулятора — тот же закон боя, которым
симулятор считает потери (`sim/combat.py`, §6: «бьют ближние», стрелок в клетке контакта 13 % + залпы до контакта),
и те же характеристики бойцов из состояния (`fighters`, `p<n>_fighters` с прокачками, строй врага — `combat_math`).

    R = ожидаемая стоимость потерь противника / ожидаемая стоимость наших потерь

Стоимость бойца — цена найма (еда + золото + железо) по `sim/параметры.json`: пикинёр 48, мушкетёр 62, драгун 177.
Горизонт оценки один для всех (`ДЛИНА_БОЯ_С` 60 с). Нулевые потери: наши 0 и его > 0 → R = `R_МАКС`; оба 0 → бой не
предвидится (R None). Рядом с R всегда остаток нашей группы и исход миссии — выгодный размен ещё не значит, что волна
дожила до подмоги.

Два случая:
  новая волна     сила — бойцы, которые соберутся и вступят вместе (свободные дома), против его сил у цели;
  подмога         сила — подмога плюс ожидаемый остаток волны К ЕЁ ПРИБЫТИЮ: волна бьётся с его силами у цели
                  `прибытие_с` секунд (путь подмоги), потом вступает подмога.
Время прибытия — расстояние в клетках × 16 ед / 1,15 ед/с (марш, `угрозы.МАРШ_ЕД_В_С`).
"""
import math
import os
import sys

import combat_math as CM

_К = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(_К, "sim"))

ДЛИНА_БОЯ_С = 60.0
R_МАКС = 99.0
СЕК_НА_КЛЕТКУ = 16.0 / 1.15
# цена найма [код] sim/параметры.json (unit.script): еда + золото + железо
ЦЕНА = {"infantry17": 48.0, "musk17": 62.0, "dragoon17": 177.0}
РОДА = ("infantry17", "musk17", "dragoon17")


def _закон():
    import combat
    return combat


def стороны(состав: dict, х: dict) -> list:
    """{род: n} + {род: характеристики} → [(n, х)] для закона боя (род без характеристик — как пикинёр)."""
    из = []
    for род in РОДА:
        n = float(состав.get(род) or 0)
        if n <= 0:
            continue
        хх = х.get(род) or х.get("infantry17") or next(iter(х.values()), None)
        if хх:
            из.append((n, хх))
    return из


def стоимость(потери: dict) -> float:
    return sum(float(потери.get(р) or 0) * ЦЕНА[р] for р in РОДА)


def бой(наши: dict, его: dict, свои_х: dict, чужие_х: dict, длина_с: float = ДЛИНА_БОЯ_С, у_его_базы: bool = False) -> dict:
    """Один бой: {наши_потери, его_потери (по родам, суммой), R, стоимость_наша, стоимость_его, остаток_наш (доля)}."""
    A, B = стороны(наши, свои_х), стороны(его, чужие_х)
    nA, nB = sum(n for n, _ in A), sum(n for n, _ in B)
    if nA <= 0 or nB <= 0:
        return dict(наши_потери={}, его_потери={}, R=None, стоимость_наша=0.0, стоимость_его=0.0, остаток_наш=1.0 if nA > 0 else 0.0,
                    остаток_его=1.0 if nB > 0 else 0.0, наших_всего=nA, его_всего=nB, уничтожена=False)
    з = _закон()
    п = з.потери_за_бой(A, B, длина_с, None, None, False, залпом=True, у_его_базы=у_его_базы)
    # раскладка по родам — пропорционально численности каждого рода
    наши_п = {р: min(float(наши.get(р) or 0), п["наши"] * float(наши.get(р) or 0) / nA) for р in РОДА if float(наши.get(р) or 0) > 0}
    его_п = {р: min(float(его.get(р) or 0), п["его"] * float(его.get(р) or 0) / nB) for р in РОДА if float(его.get(р) or 0) > 0}
    сн, се = стоимость(наши_п), стоимость(его_п)
    if сн <= 1e-6 and се <= 1e-6:
        R = None
    elif сн <= 1e-6:
        R = R_МАКС
    else:
        R = min(R_МАКС, се / сн)
    его_ост = round(max(0.0, 1.0 - п["его"] / nB), 3)
    return dict(наши_потери=наши_п, его_потери=его_п, R=None if R is None else round(R, 2), стоимость_наша=round(сн, 1), стоимость_его=round(се, 1),
                остаток_наш=round(max(0.0, 1.0 - п["наши"] / nA), 3), остаток_его=его_ост, наших_всего=nA, его_всего=nB,
                # РЕЗУЛЬТАТ МИССИИ рядом с R (задание 8.10): его группа у цели уничтожена за горизонт (остаток ≤ 10 %) — закон боя
                # §6 даёт численному перевесу мало («бьют ближние», излишек 0,1), и 60 против 10 выходит R 0,86 при полном
                # уничтожении его десятки; по стоимости это проигрыш, по миссии — победа
                уничтожена=его_ост <= 0.1)


def новая_волна(сила: dict, его: dict, свои_х: dict, чужие_х: dict, у_его_базы: bool = False) -> dict:
    """Новая волна идёт в самостоятельный бой: сила — те, кто соберутся и вступят вместе."""
    из = бой(сила, его, свои_х, чужие_х, у_его_базы=у_его_базы)
    из["случай"] = "новая волна"
    return из


def подмога(подмога_: dict, волна: dict, его: dict, свои_х: dict, чужие_х: dict, прибытие_с: float, у_его_базы: bool = False) -> dict:
    """Подмога к действующей волне: волна бьётся `прибытие_с` без подмоги, потом вступают вместе остаток + подмога.
    {…, остаток_волны (доля к прибытию), волна_доживёт (остаток ≥ 0,3), R}."""
    if прибытие_с > 0 and sum(float(v or 0) for v in его.values()) > 0:
        первый = бой(волна, его, свои_х, чужие_х, длина_с=прибытие_с, у_его_базы=у_его_базы)
        остаток = {р: max(0.0, float(волна.get(р) or 0) - float(первый["наши_потери"].get(р) or 0)) for р in РОДА}
        его_ост = {р: max(0.0, float(его.get(р) or 0) - float(первый["его_потери"].get(р) or 0)) for р in РОДА}
        доля = первый["остаток_наш"]
    else:
        остаток, его_ост, доля = dict(волна), dict(его), 1.0
    вместе = {р: float(остаток.get(р) or 0) + float(подмога_.get(р) or 0) for р in РОДА}
    из = бой(вместе, его_ост, свои_х, чужие_х, у_его_базы=у_его_базы)
    из.update(случай="подмога", остаток_волны=round(доля, 3), волна_доживёт=доля >= 0.3, прибытие_с=round(прибытие_с))
    return из


def сек_пути(клеток: float) -> float:
    return float(клеток) * СЕК_НА_КЛЕТКУ


def состав_из_клеток(клетки, радиус_от=None, r: int = 0) -> dict:
    """{род: n} по клеткам с составом (пик/стрелков/конных); без состава — всё пикинёры; при `радиус_от` — в r клетках от неё."""
    из = {р: 0.0 for р in РОДА}
    for c in клетки or []:
        if радиус_от is not None and max(abs(int(c["x"]) - радиус_от[0]), abs(int(c["y"]) - радиус_от[1])) > r:
            continue
        n = float(c.get("n") or 0)
        с, к = float(c.get("стрелков") or 0), float(c.get("конных") or 0)
        из["musk17"] += с
        из["dragoon17"] += к
        из["infantry17"] += max(0.0, n - с - к)
    return из


def состав_по_долям(n: float, st: dict, префикс: str = "") -> dict:
    """n бойцов в долях армии: наши — mil_inf/mil_shooters/mil_cav, его — p<n>_inf/shoot/cav (префикс «p1_»)."""
    if префикс:
        и, с, к = (float(st.get(префикс + k) or 0) for k in ("inf", "shoot", "cav"))
    else:
        и, с, к = (float(st.get(k) or 0) for k in ("mil_inf", "mil_shooters", "mil_cav"))
    всего = и + с + к
    if всего <= 0:
        return {"infantry17": float(n), "musk17": 0.0, "dragoon17": 0.0}
    return {"infantry17": n * и / всего, "musk17": n * с / всего, "dragoon17": n * к / всего}


def словами(п: dict) -> str:
    """Строка для лога/причины: R, стоимости, остаток."""
    if п.get("R") is None:
        return "боя не предвидится"
    s = f"R={п['R']:.2f} (его потери ~{п['стоимость_его']:.0f} против наших ~{п['стоимость_наша']:.0f} по цене найма, " \
        f"наших {п['наших_всего']:.0f} против его {п['его_всего']:.0f}, остаток наш {п['остаток_наш']:.0%}, его {п['остаток_его']:.0%}" \
        + (" — его группа УНИЧТОЖЕНА" if п.get("уничтожена") else "")
    if п.get("случай") == "подмога":
        s += f"; волна к прибытию через {п['прибытие_с']} с — {п['остаток_волны']:.0%}" + ("" if п["волна_доживёт"] else ", НЕ ДОЖИВЁТ")
    return s + ")"
