#!/usr/bin/env python3
"""§170 СТРОЙ И ВСТРЕЧА В ЧИСТОЙ КЛЕТКЕ ПО Д10 (22.10): такты десятой живой партии Д 11:00–15:13
(`sim/кейсы/партия_д10_21_10_11-00_15-13.jsonl`, мост 1e73593). После горизонта игрок вынес стоящую в клетке ратуши кучу
216:77 при равном числе: ни строя, ни пуль — его фронт облепил кучу среди построек и 34 праздных крестьян (бьющих у него
~2×, ранено 188 из 227). Экзамен Fable 3/3: 15:00 — «В» выйти в чистую клетку (4,4) и ВСТАТЬ, стрелки позади; 13:01 — «А»
идти (удар 8 против 1, перевес по головам не важен); еда — «А» 1.3 → 1.4; состав — строй с офицером (В, В) / мушкетёры (Б).

Правки: (1) §81 `отрядов` 1 / `отряд_с` 660 в файле партии — найм офицера и барабанщика в академии, FORMATION; (2) §170б
`встреча_чистая` 1 — кулак в клетку на шаг от ратуши навстречу его главной куче, через `встреча_сек` FACE по номеру группы с
удержанием (+7/+7 строя стоя), пополнение +15 группой 94 туда же (была 93 — номер заслона §152, §170д); `стрелки_позади` 1 — мушкетёры отдельным MOVE в клетку
ратуши; (3) §170а оценщик ступеней: выигрыш — доля размена, не разность (при ударе 8 против 1 разность 0,03 прятала 1.3);
`цена_снята_при` 4000; (4) §170в живьём `aca.*` — только по карману и не больше 3 за такт (девять за такт выталкивали за
потолок 12 команд найм офицера и FORMATION).

В трассе нет своего поля `academies` (снимок его не пишет — ложный ноль), в кейсе оно берётся из `p1_academi`; офицеры и отряд
живьём в Д10 не нанимались — в тестах (б) они подставляются в состояние.
    python3 selftest_строй_д10.py
"""
import copy, json, os, sys, tempfile
К = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, К); sys.path.insert(0, os.path.join(К, "sim"))
os.environ.pop("COSS3_WAVE_CONTRACT", None)
import strategy_live as SL
import анализ_врага as АВ

кейс = [json.loads(l) for l in open(os.path.join(К, "sim/кейсы/партия_д10_21_10_11-00_15-13.jsonl"), encoding="utf-8")]
ошибок = 0
def проверить(усл, что):
    global ошибок
    print(("ОК   " if усл else "ОШИБКА ") + что); ошибок += not усл
def стратегия(доп):
    д = json.load(open(os.path.join(К, "sim/поиск/шт_s2_оборона_ручеёк_эко_так15_нужда.json"), encoding="utf-8"))
    assert д["итог"].get("отрядов") == 1 and д["итог"].get("встреча_чистая") == 1 and д["итог"].get("цена_снята_при") == 4000
    д["итог"].update(доп)
    with tempfile.NamedTemporaryFile("w", suffix=".json", delete=False, encoding="utf-8") as f:
        json.dump(д, f, ensure_ascii=False)
    return SL.ЖиваяСтратегия(f.name)
def ответ(С, s):
    АВ._ТЕКУЩИЙ.update({"а": None, "t": None, "ответ": None}); return С.ответ(copy.deepcopy(s))
def подставить(s, gt, офицеры_с=None, отряд_с=None):
    s = dict(s); s["academies"] = int(s.get("p1_academi") or 0)
    if офицеры_с is not None and gt >= офицеры_с:
        s["my_officers"], s["my_drummers"] = 1, 1
    if отряд_с is not None and gt >= отряд_с:
        s["squads"], s["squad_units"] = 1, 120
    return s
def прогон(доп, t1=913, **под):
    С = стратегия(доп); из = {}
    for s in кейс:
        gt = int(float(s["gametime"]))
        if gt > t1: break
        s = подставить(s, gt, **под)
        из[gt] = (s, ответ(С, s))
    return С, из
def движ(о):
    return [(c["cmd"], c.get("count"), c.get("who", ""), c.get("group"), c.get("cx"), c.get("cy"), c.get("face"), c.get("hold"))
            for c in о["commands"] if c["cmd"] in ("MOVE", "FACE")]
def найм(о, роли):
    return [(c.get("role"), c.get("total")) for c in о["commands"] if c["cmd"] == "TRAIN" and c.get("role") in роли]

# (а) найм офицера и барабанщика, как только есть академия
С, п = прогон({}, 913, офицеры_с=710, отряд_с=720)
проверить(найм(п[700][1], ("officer17", "drummer17")) == [], f"(а) 11:40 академии нет — офицер не просится: {найм(п[700][1], ('officer17', 'drummer17'))}")
проверить(sorted(найм(п[705][1], ("officer17", "drummer17"))) == [("drummer17", 1), ("officer17", 1)],
          f"(а) 11:45 академия встала — TRAIN officer17 1 и drummer17 1: {найм(п[705][1], ('officer17', 'drummer17'))}")
# (б) FORMATION при паре и без отряда; при отряде — нет
ф = {gt for gt, (s, о) in п.items() if any(c["cmd"] == "FORMATION" for c in о["commands"])}
проверить(ф == {710, 715}, f"(б) FORMATION с парой офицер+барабанщик, пока отряда нет (11:50–11:55), с отрядом — нет: {sorted(ф)}")
# (в) встреча в чистой клетке
о811 = п[811][1]; д811 = движ(о811)
проверить(д811 == [("MOVE", "all", "", 92, 4, 4, [11, 12], None)], f"(в) 13:31 его 207 идут от (11,12): все в (4,4) на шаг от ратуши лицом к нему: {д811}")
проверить("ВСТРЕЧА В ЧИСТОЙ" in о811.get("why", ""), "(в) why: ВСТРЕЧА В ЧИСТОЙ")
# (г) удержание через 20 с: FACE группе 92 с hold, ровно один раз
face92 = [(gt, x) for gt, (s, о) in п.items() if gt >= 811 for x in движ(о) if x[0] == "FACE" and x[3] == 92]
проверить(len(face92) == 1 and face92[0][0] == 832 and face92[0][1][1] == 0 and face92[0][1][7] == 1,
          f"(г) 13:52 FACE группе 92 count 0 hold 1, один раз: {face92}")
# (д) пополнение +15 — группой 93 в ту же клетку, затем своё удержание
m93 = [(gt, x) for gt, (s, о) in п.items() if gt >= 811 for x in движ(о) if x[3] == 94]
проверить([x[0] for x in m93][:4] == [842, 863, 878, 898] and m93[0][1][:6] == ("MOVE", 16, "infantry17", 94, 4, 4) and m93[1][1][0] == "FACE",
          f"(д) пополнение: 14:02 MOVE 16 пик группой 94 в (4,4), 14:23 FACE 94 hold, далее повтор: {m93[:4]}")
# один приказ движения за такт
много = [(gt, движ(о)) for gt, (s, о) in п.items() if len(движ(о)) > 1]
проверить(not много, f"(д) не больше одного MOVE/FACE за такт: {много[:2]}")
# (е) ключ 0 — прежний кулак в клетке ратуши, без FACE
С0, п0 = прогон({"встреча_чистая": 0}, 840, офицеры_с=710, отряд_с=720)
д0 = движ(п0[811][1])
проверить(д0 == [("MOVE", "all", "", 92, 3, 3, [11, 12], None)] and "КУЛАК У РАТУШИ" in п0[811][1].get("why", "")
          and not any(x[0] == "FACE" for gt, (s, о) in п0.items() for x in движ(о)), f"(е) ключ 0: все в клетку ратуши (3,3), FACE нет: {д0}")
# (ж) стрелки позади: следующим тактом MOVE мушкетёров группой 91 в клетку ратуши, удержание пик — после
С1, п1 = прогон({"стрелки_позади": 1}, 840, офицеры_с=710, отряд_с=720)
д816 = движ(п1[816][1])
проверить(д816 == [("MOVE", "all", "musk17", 91, 3, 3, [11, 12], None)], f"(ж) стрелки_позади 1: 13:36 MOVE musk17 группой 91 в (3,3): {д816}")
проверить(any(x[0] == "FACE" and x[3] == 92 for gt, (s, о) in п1.items() if gt > 816 for x in движ(о)), "(ж) удержание пик после отвода стрелков")
# (з) ступени: при ударе 8 против 1 — атака 1.3; с 1.3 — 1.4 (еда ≥ цена_снята_при)
взято = lambda s: set(str(s.get("upg_done") or "").split(","))
s781 = dict(п[781][0]); s781["upg_avail"] = s781.get("upg_shown")
проверить(С.стр._ступень_по_ценности(s781, взято(s781), 781.0) == "bar.pikeman.1.3", "(з) 13:01: ступень по ценности — bar.pikeman.1.3 (живьём не бралась до 14:40)")
s842 = dict(п[842][0]); s842["upg_avail"] = s842.get("upg_shown"); s842["upg_done"] += ",bar.pikeman.1.3"; s842["gold"] = 2000
проверить(С.стр._ступень_по_ценности(s842, взято(s842), 842.0) == "bar.pikeman.1.4", "(з) 14:02 с 1.3 и золотом 2000: следующая — bar.pikeman.1.4 (еда 19 824 ≥ цена_снята_при)")
# (и) академия: не больше трёх aca.* за такт, все по карману, потолок не срезает
плохие = []
for gt, (s, о) in п.items():
    ака = [c.get("role") for c in о["commands"] if c["cmd"] == "UPGRADE" and str(c.get("role", "")).startswith("aca.")]
    if len(ака) > 3 or "сверх" in о.get("why", ""):
        плохие.append((gt, ака))
проверить(not плохие, f"(и) aca.* ≤ 3 за такт и без «сверх 12 команд»: {плохие[:3]}")
print("ИТОГ:", "чисто" if not ошибок else f"ошибок {ошибок}")
sys.exit(1 if ошибок else 0)
