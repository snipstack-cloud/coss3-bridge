# -*- coding: utf-8 -*-
"""Проверки обхода его армии (просьба игрока 27.09): путь должен огибать бойцов."""
import sys, os
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "sim"))
import обход as O

ошибок = []
пусто = [[0] * 8 for _ in range(8)]

# 1. без врага путь прямой: длина равна числу шагов по диагонали/линии
п = O.путь((0, 0), (0, 5), пусто)
if len(п) != 5:
    ошибок.append(f"пустая карта: путь из {len(п)} шагов вместо 5")

# 2. стена его бойцов на прямой — путь обязан стать длиннее и обойти
стена = [[0] * 8 for _ in range(8)]
for y in range(1, 7):
    стена[y][3] = 20            # вертикальная стена в столбце 3
п = O.путь((1, 3), (6, 3), стена)
прошёл_сквозь = any(int(x) == 3 and 1 <= int(y) <= 6 for x, y in п)
if прошёл_сквозь:
    ошибок.append("путь идёт СКВОЗЬ стену его бойцов, а должен огибать")
if len(п) <= 5:
    ошибок.append(f"обход не длиннее прямой: {len(п)} шагов")

# 3. следующая клетка шага не совпадает с прямой, когда прямая опасна
сл = O.следующая((1, 3), (6, 3), стена)
if сл == (2.0, 3.0) and стена[3][2] == 0 and стена[3][3] == 20:
    # шаг в (2,3) допустим, дальше обход; опасно, если шаг прямо в стену
    pass
if сл == (3.0, 3.0):
    ошибок.append("шаг сделан прямо в клетку со его бойцами")

# 4. опасность прямой считается и больше нуля на стене
if not O.опасность_прямой((1, 3), (6, 3), стена) > 0:
    ошибок.append("опасность прямой через стену вышла нулевой")
if O.опасность_прямой((0, 0), (0, 5), пусто) != 0:
    ошибок.append("опасность на пустой карте не ноль")

# 5. недостижимая цель за пределами сетки не роняет и отдаёт цель
if O.путь((0, 0), (99, 99), пусто) != [(99, 99)]:
    ошибок.append("цель вне сетки должна возвращаться как есть")

# 6. пустая сетка (нет данных) — отдаём цель, а не падаем
if O.путь((0, 0), (3, 3), []) != [(3, 3)]:
    ошибок.append("без сетки должен возвращаться сама цель")

print(("ОШИБКИ:\n  " + "\n  ".join(ошибок)) if ошибок else "ОБХОД: ВСЕ ПРОВЕРКИ ПРОЙДЕНЫ")
raise SystemExit(1 if ошибок else 0)
