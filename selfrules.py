#!/usr/bin/env python3
"""Правила и меры, которые ЦИКЛ ПИШЕТ САМ — и проверки против пустого замера.

Зачем отдельный файл. Цикл из `selfloop.py` сочиняет доработки моста и меры к
ним. Если бы он правил `llm_policy.py`, то между итерациями ломал бы мост, и
серия мерила бы поломку, а не идею — это ровно та беда, что за 20.09 дала пять
ложных нулей. Поэтому правила живут ДАННЫМИ в `/io`, а не кодом: в такте есть
готовый шов (`llm_policy.py`, блок «Каждая правка своим ключом»), где питон уже
добавляет, снимает и объясняет команды модели. Правило цикла встаёт туда же и
ничем от `--auto-seed` не отличается, кроме того, что написано не человеком.

ЧЕГО ЦИКЛ КОСНУТЬСЯ НЕ МОЖЕТ, и это не пожелание:
  * `.inc` — его проверка только живой игрой на Windows, в контейнере экран
    чёрный, а «ПУЛЬСА НЕТ» имеет три причины;
  * `master` — всё уходит в ветку и приходит игроку диффом;
  * собственную меру ЗАДНИМ ЧИСЛОМ — мера записана до прогона и сверяется
    хешем (`selfloop.py`).

Четыре проверки, которые ловят пустой замер ДО того, как на него потратят
партии:

  1. ДОСТИЖИМОСТЬ МЕРЫ (`достижима`). Мера гоняется по УЖЕ СЫГРАННЫМ трассам
     базы. Если она падает — негодна. Если по всем партиям базы даёт одно и то
     же число — она не различает ничего, и любой её «ноль» после правки
     означал бы только, что поле не пишется в трассу. Пять случаев за 20.09:
     `режим:` не нашёлся из-за кавычки в JSON, `STAGE` искали в `cmds`, куда он
     не пишется, `upg_avail` не пишется вовсе.
  2. ПЕСОЧНИЦА ПРАВИЛА (`проверить_правило`). Правило прогоняется по записанным
     состояниям до первой партии: считаем сбои и СКОЛЬКО РАЗ ОНО ВООБЩЕ
     СРАБАТЫВАЕТ. Правило, которое не сработало ни разу на двух сотнях тактов,
     нельзя мерить партиями — мерить будет нечего.
  3. МЕРА ПРО ИСХОД (`про_исход`). Команды базы пропускаются через правило
     (`подделать`) и мера считается заново. Игру не переигрывали, значит исход
     измениться не мог: мера, которая всё-таки сдвинулась, считает работу
     самого правила, а не игру. Хотя бы одна мера обязана быть про исход.
     Куплено прогоном 21.09: обе меры итерации были про себя, ушли в ноль и
     дали два ПРОТИВОПОЛОЖНЫХ вердикта об одном факте.
  4. ПЛАЦЕБО (`selfloop.py`). Раз в N итераций циклу говорят, что правка
     применена, а играют базу. Всё, что он там «найдёт», — его собственная
     частота ложных находок, и она печатается в отчёте рядом с находками.
"""
from __future__ import annotations

import json
import os
import time
from dataclasses import dataclass

import coss3_bridge as B

# Что правило видит из движка. Список намеренно узкий: конструкторы команд и
# счёт. Всё остальное правило получает через `st` и `ctx`.
БЕЗОПАСНЫЕ = {
    "len": len, "int": int, "float": float, "min": min, "max": max, "abs": abs,
    "sorted": sorted, "sum": sum, "any": any, "all": all, "range": range,
    "round": round, "str": str, "dict": dict, "list": list, "set": set,
    "tuple": tuple, "enumerate": enumerate, "zip": zip, "bool": bool,
    "isinstance": isinstance, "True": True, "False": False, "None": None,
}


def чис(st: dict, ключ: str, иначе: float = 0.0) -> float:
    """Число из состояния. Значения приходят строками, и половина ложных нулей
    проекта — это `int(None)` или `int('')`, съеденный молча."""
    v = st.get(ключ)
    if v is None or v == "":
        return иначе
    try:
        return float(v)
    except (TypeError, ValueError):
        return иначе


def есть(st: dict, ключ: str) -> bool:
    """Поле ЕСТЬ В СНИМКЕ вообще. Отличать от нуля: «поля нет» и «поле равно
    нулю» — разные вещи, и путаница между ними стоила проекту двух серий."""
    return ключ in st and st[ключ] not in (None, "")


_ПО_НОМЕРУ = {н: имя for имя, н in B.RESOURCE.items()}


def имя_ресурса(номер) -> str:
    """Номер ресурса из команды BALANCE -> его имя. Пусто, если номер чужой."""
    try:
        return _ПО_НОМЕРУ.get(int(номер), "")
    except (TypeError, ValueError):
        return ""


def на_ресурсе(st: dict, c) -> float:
    """Сколько крестьян СЕЙЧАС на ресурсе этой команды BALANCE.

    Существует потому, что отображение «номер -> ресурс» модель перепутала на
    живом прогоне 21.09: она написала 2->gold, 3->iron, 4->coal, 5->stone, а на
    деле 2 это stone, 3 gold, 4 iron, 5 coal. Четыре ресурса из шести. Правило
    не падало и уверенно срабатывало 52 раза из 111 тактов, сравнивая
    заказанный камень с числом людей на золоте.

    Такую беду песочница поймать не может: она спрашивает «падает ли» и
    «срабатывает ли», а не «правильно ли». Поэтому таблица не даётся на память,
    а считается здесь — ошибиться негде.
    """
    имя = имя_ресурса(getattr(c, "a1", None))
    return чис(st, "on_" + имя) if имя else 0.0


ПОМОЩНИКИ = {
    "build": B.build, "train": B.train, "balance": B.balance,
    "builders": B.builders, "seed": B.seed, "upgrade": B.upgrade,
    "formation": B.formation, "Command": B.Command,
    "INFINITE": B.INFINITE, "RESOURCE": B.RESOURCE,
    "BUILDABLE": B.BUILDABLE,
    "чис": чис, "есть": есть,
    "имя_ресурса": имя_ресурса, "на_ресурсе": на_ресурсе,
}


@dataclass
class Правило:
    имя: str
    зачем: str
    код: str
    функция: object = None
    сбоев: int = 0
    сработало: int = 0
    последний_сбой: str = ""
    выключено: bool = False


@dataclass
class Мера:
    имя: str
    зачем: str
    код: str
    больше_лучше: bool = True
    функция: object = None


СБОЕВ_ДО_ОТКЛЮЧЕНИЯ = 5


def скомпилировать(код: str, имя_функции: str) -> object:
    """Исполнить исходник правила и достать из него функцию.

    Это НЕ защита от злого кода — код пишет наша же модель. Это защита от
    падения посреди партии: всё, что цикл сочинил, компилируется и зовётся
    здесь, а не в такте.
    """
    ns = {"__builtins__": dict(БЕЗОПАСНЫЕ)}
    ns.update(ПОМОЩНИКИ)
    exec(compile(код, "<" + имя_функции + ">", "exec"), ns)
    f = ns.get(имя_функции)
    if not callable(f):
        raise ValueError("в коде нет функции " + имя_функции + "()")
    return f


def загрузить_правила(путь: str) -> list:
    """Прочесть набор правил из /io. Битое правило не валит остальные."""
    if not путь or not os.path.exists(путь):
        return []
    with open(путь, encoding="utf-8") as f:
        д = json.load(f)
    вышло = []
    for r in д.get("правила", []):
        п = Правило(имя=str(r.get("имя", "?")), зачем=str(r.get("зачем", "")),
                    код=str(r.get("код", "")))
        try:
            п.функция = скомпилировать(п.код, "правило")
        except Exception as e:
            п.выключено = True
            п.последний_сбой = "не компилируется: " + str(e)
        вышло.append(п)
    return вышло


def загрузить_меры(путь: str) -> list:
    if not путь or not os.path.exists(путь):
        return []
    with open(путь, encoding="utf-8") as f:
        д = json.load(f)
    вышло = []
    for r in д.get("меры", []):
        м = Мера(имя=str(r.get("имя", "?")), зачем=str(r.get("зачем", "")),
                 код=str(r.get("код", "")),
                 больше_лучше=bool(r.get("больше_лучше", True)))
        try:
            м.функция = скомпилировать(м.код, "мера")
        except Exception as e:
            м.функция = None
            м.зачем += " [НЕ КОМПИЛИРУЕТСЯ: " + str(e) + "]"
        вышло.append(м)
    return вышло


def применить(правила: list, st: dict, cmds: list, ctx: dict) -> tuple:
    """Шов в такте: правила цикла правят команды модели.

    Возвращает новый список команд и слова, которые мост скажет вслух. Правило
    обязано вернуть `(cmds, [строки])`; вернуло что-то другое — считается сбоем
    и его правка отбрасывается ЦЕЛИКОМ. Пять сбоев — правило молча выключается
    до конца партии, но факт пишется в отчёт: правило, которое падает, тоже
    результат, и его нельзя ни засчитать, ни потерять.
    """
    сообщения = []
    for п in правила:
        if п.выключено or п.функция is None:
            continue
        было = list(cmds)
        try:
            ответ = п.функция(dict(st), list(cmds), dict(ctx))
            if ответ is None:
                continue
            новые, слова = ответ
            if not isinstance(новые, list):
                raise TypeError("правило вернуло не список команд")
            for c in новые:
                if not isinstance(c, B.Command):
                    raise TypeError("в списке не Command, а " + type(c).__name__)
            if list(новые) != было or слова:
                п.сработало += 1
            cmds = list(новые)
            for s in (слова or []):
                сообщения.append(str(s) + " [правило цикла «" + п.имя + "»]")
        except Exception as e:
            п.сбоев += 1
            п.последний_сбой = type(e).__name__ + ": " + str(e)
            cmds = было
            if п.сбоев >= СБОЕВ_ДО_ОТКЛЮЧЕНИЯ:
                п.выключено = True
    return cmds, сообщения


# --- проверка 2: песочница правила ------------------------------------------
def проверить_правило(п: Правило, такты: list) -> dict:
    """Прогнать правило по ЗАПИСАННЫМ тактам до первой партии.

    Такт — это `{'st': снимок, 'cmds': команды модели В ЭТОМ ТАКТЕ, 'gt': ...}`.
    КОМАНДЫ ОБЯЗАТЕЛЬНЫ, и это не удобство. Первая сборка звала правило с
    пустым списком команд, и правило, которое СНИМАЕТ чужой SEED, показало ноль
    срабатываний на 209 тактах — при том что снимать там было что. Песочница,
    построенная против ложных нулей, сама их и производила: правило, живущее
    правкой команд модели, не могло сработать в ней никогда.

    Два числа, и второе важнее первого: сколько раз правило упало и сколько раз
    оно ВООБЩЕ СРАБОТАЛО. Правило, не сработавшее ни разу на двух сотнях
    тактов, партиями мерить нечем — это заготовка будущего ложного нуля.
    """
    сбоев = срабатываний = 0
    примеры = []
    начало = time.time()
    for т in такты:
        if п.функция is None:
            break
        st = т.get("st") if isinstance(т, dict) and "st" in т else т
        cmds = list(т.get("cmds") or []) if isinstance(т, dict) else []
        было = list(cmds)
        try:
            ответ = п.функция(dict(st), list(cmds),
                              {"gt": чис(st, "gametime"), "проверка": True})
            if ответ is None:
                continue
            новые, слова = ответ
            if list(новые) != было or слова:
                срабатываний += 1
                if слова and len(примеры) < 3:
                    примеры.append(str(слова[0])[:200])
        except Exception as e:
            сбоев += 1
            if len(примеры) < 3:
                примеры.append("СБОЙ " + type(e).__name__ + ": " + str(e))
    return {
        "тактов": len(такты), "срабатываний": срабатываний, "сбоев": сбоев,
        "секунд": round(time.time() - начало, 2), "примеры": примеры,
        "годно": сбоев == 0 and срабатываний > 0,
        "почему": ("падает" if сбоев else
                   "не срабатывает ни разу" if срабатываний == 0 else "годно"),
    }


# --- проверка 1: достижимость меры ------------------------------------------
def достижима(м: Мера, партии: list) -> dict:
    """Мера гоняется по УЖЕ СЫГРАННЫМ партиям базы, до единой новой партии.

    Вердикты:
      «падает»       — мера негодна, считать нечем;
      «не различает» — по всем партиям базы одно и то же число. Такая мера не
                       отличит правку от базы НИКОГДА, и её ноль после правки
                       означал бы только, что поле не пишется в трассу;
      «годна»        — по базе есть разброс, значит есть чему меняться.
    """
    значения, сбои = [], []
    for п in партии:
        if м.функция is None:
            сбои.append("не компилируется")
            continue
        try:
            v = м.функция(п.get("трасса", []), dict(п.get("итог", {})))
            значения.append(float(v))
        except Exception as e:
            сбои.append(type(e).__name__ + ": " + str(e))
    if сбои or not значения:
        return {"вердикт": "падает", "значения": значения, "сбои": сбои[:3],
                "годна": False}
    разброс = max(значения) - min(значения)
    if len(значения) > 1 and разброс == 0:
        return {"вердикт": "не различает", "значения": значения,
                "годна": False,
                "почему": "по " + str(len(значения)) + " партиям базы одно "
                          "число " + ("%g" % значения[0]) + " — мера не "
                          "отличит правку от базы"}
    return {"вердикт": "годна", "значения": значения,
            "разброс_базы": round(разброс, 3),
            "медиана_базы": round(sorted(значения)[len(значения) // 2], 3),
            "годна": True}


# --- проверка 4: мера про ИСХОД, а не про работу самого правила --------------
def подделать(партии: list, п: Правило) -> list:
    """Трассы базы, у которых команды ПРОПУЩЕНЫ через правило. Игра НЕ играется.

    Это не замер и не предсказание — это подлог нарочно: единственное, что здесь
    меняется, есть правка команд самим правилом. Итог партии берётся прежний,
    потому что без новой партии он измениться не может.
    """
    вышло = []
    for партия in партии:
        новая = []
        for т in партия.get("трасса", []):
            st = т.get("state") or {}
            cmds = []
            for c in (т.get("cmds") or []):
                if isinstance(c, dict):
                    try:
                        cmds.append(B.Command(cmd=str(c.get("cmd", "")),
                                              a1=int(c.get("a1") or 0),
                                              a2=int(c.get("a2") or 0),
                                              upg=str(c.get("upg") or "")))
                    except (TypeError, ValueError):
                        pass
            новые = cmds
            if п.функция is not None:
                try:
                    ответ = п.функция(dict(st), list(cmds),
                                      {"gt": чис(st, "gametime"), "проверка": True})
                    if ответ and isinstance(ответ[0], list):
                        новые = [c for c in ответ[0] if isinstance(c, B.Command)]
                except Exception:
                    новые = cmds
            т2 = dict(т)
            т2["cmds"] = [{"cmd": c.cmd, "a1": c.a1, "a2": c.a2, "upg": c.upg}
                          for c in новые]
            новая.append(т2)
        вышло.append({"трасса": новая, "итог": dict(партия.get("итог", {}))})
    return вышло


def про_исход(м: Мера, партии: list, поддельные: list) -> dict:
    """Мера про ИСХОД ПАРТИИ или про то, что правило сработало?

    Куплено прогоном 21.09. Итерация 1 объявила две меры: «сколько SEED
    отброшено» и «доля тактов с SEED при созревшем поле». Трасса пишет команды
    УЖЕ ПОСЛЕ правил, поэтому в плече обе ушли в ноль — и цикл получил два
    противоположных вердикта об одном и том же факте «правило сработало». Про
    игру не сказала ни одна: армия, еда, цель никого не интересовали.

    Различить их можно без единой партии. Берём трассы базы, пропускаем команды
    через правило (`подделать`) и считаем меру заново. ИГРА НЕ ПЕРЕИГРЫВАЛАСЬ,
    значит исход измениться не мог. Мера, которая всё-таки изменилась, считает
    правку команд, то есть работу самого правила.
    """
    if м.функция is None:
        return {"про_исход": False, "почему": "мера не компилируется"}
    try:
        было = [float(м.функция(п.get("трасса", []), dict(п.get("итог", {}))))
                for п in партии]
        стало = [float(м.функция(п.get("трасса", []), dict(п.get("итог", {}))))
                 for п in поддельные]
    except Exception as e:
        return {"про_исход": False,
                "почему": "падает на подделанной трассе: " + type(e).__name__}
    сдвиг = [round(b - a, 6) for a, b in zip(было, стало)]
    шевельнулась = any(x != 0 for x in сдвиг)
    return {
        "про_исход": not шевельнулась, "было": было, "стало": стало,
        "сдвиг": сдвиг,
        "почему": ("считает работу самого правила: игру не переигрывали, а "
                   "мера сдвинулась на " + str(сдвиг) if шевельнулась else
                   "от одной лишь правки команд не меняется — значит про игру"),
    }


def отчёт_правил(правила: list) -> list:
    """Что правила наделали за партию — уходит в трассу и в журнал цикла."""
    return [{"имя": п.имя, "сработало": п.сработало, "сбоев": п.сбоев,
             "выключено": п.выключено, "последний_сбой": п.последний_сбой}
            for п in правила]
