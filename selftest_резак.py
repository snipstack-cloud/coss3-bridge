# -*- coding: utf-8 -*-
"""Селфтест правила РЕЗАК (1.11, замысел игрока): малая пачка по его крестьянам, пока армия в поле,
и ВЫБОР ДОРОГИ — цель с меньшим числом его бойцов в коридоре от нашей ратуши.

Проверяет семь вещей:
  (1) ключ 0 — правило молчит (как было);
  (2) армия дома — приказа нет, но ПРИЧИНА СКАЗАНА (правило 1 проекта: молчаливый отброс неотличим от бездействия);
  (3) есть другой ATTACK в такте — молчим (слот приказа один, это норма такта);
  (4) ВЫБОР ДОРОГИ: из двух клеток берётся та, к которой по коридору меньше его бойцов, даже если крестьян меньше;
  (5) охраняемая клетка не берётся, причина сказана; повтор не чаще `резак_повтор`;
  (6) ПРЕДЕЛ ПО ДОРОГЕ (`резак_дорога_до`): минимум может быть безнадёжен — отказ и причина;
  (7) без предела правило идёт, как было.
"""
import strategy_live as СЖ

ок, пало = 0, []


def проверить(что, имя):
    global ок
    if что:
        ок += 1
    else:
        пало.append(имя)


class Реестр:
    def __init__(self):
        import collections
        self.мера = collections.defaultdict(int)
        self.записи = []


def стратегия(ключи):
    с = СЖ.ЖиваяСтратегия.__new__(СЖ.ЖиваяСтратегия)
    с.п = dict(ключи)
    с.реестр = Реестр()
    return с


# Ратуша в (2,2). Крестьяне: (10,10) — 8 человек, но дорога идёт мимо его 40 бойцов в (6,6);
#                            (2,9)  — 4 человека, дорога чистая.
СОСТОЯНИЕ = {
    "gametime": 700.0,
    "my_cx": 2, "my_cy": 2,
    "mil_far": 120.0,
    "ecells": "6,6,40,40,0,0,0,-1,-1,0",
    "en_pea_cells": [{"x": 10, "y": 10, "крестьян": 8, "бойцов_рядом": 0},
                     {"x": 2, "y": 9, "крестьян": 4, "бойцов_рядом": 0}],
}
КЛЮЧИ = {"резак_крестьян": 12, "резак_армия": 50, "резак_крестьян_от": 3,
         "резак_охрана": 3, "резак_повтор": 60, "резак_коридор": 1}

# (1) ключ 0 — молчим
с = стратегия(dict(КЛЮЧИ, **{"резак_крестьян": 0}))
из, стр = с._резак_крестьян([], dict(СОСТОЯНИЕ))
проверить(из == [] and стр == "", "(1) ключ 0 — правило молчит")

# (2) армия дома — НЕ МОЛЧИМ, а говорим почему (правило 1 проекта)
с = стратегия(КЛЮЧИ)
из, стр = с._резак_крестьян([], dict(СОСТОЯНИЕ, **{"mil_far": 10.0}))
проверить(из == [] and "РЕЗАК ждёт" in стр and "приманки нет" in стр,
          f"(2) армия дома — приказа нет, но причина сказана: {стр[:70]}")

# (3) в такте уже есть ATTACK — молчим
с = стратегия(КЛЮЧИ)
чужой = [{"cmd": "ATTACK", "count": 50, "target": "cell", "cx": 9, "cy": 9}]
из, стр = с._резак_крестьян(list(чужой), dict(СОСТОЯНИЕ))
проверить(из == чужой and стр == "", "(3) слот приказа занят — молчим")

# (4) ВЫБОР ДОРОГИ: берём (2,9) с четырьмя крестьянами, а не (10,10) с восемью
с = стратегия(КЛЮЧИ)
из, стр = с._резак_крестьян([], dict(СОСТОЯНИЕ))
приказ = из[0] if из else {}
проверить(приказ.get("cmd") == "ATTACK" and приказ.get("_резак") is True
          and приказ.get("count") == 12 and приказ.get("who") == "musk17"
          and (приказ.get("cx"), приказ.get("cy")) == (2, 9),
          f"(4) выбрана чистая дорога (2,9), а не богатая (10,10) — получено {приказ.get('cx')},{приказ.get('cy')}")
проверить("РЕЗАК" in стр and "дорога чиста" in стр, f"(4б) строка про дорогу: {стр[:90]}")

# (5) охраняемая клетка не берётся; повтор не чаще
с = стратегия(КЛЮЧИ)
охрана = dict(СОСТОЯНИЕ, **{"en_pea_cells": [{"x": 2, "y": 9, "крестьян": 9, "бойцов_рядом": 5}]})
из, стр = с._резак_крестьян([], охрана)
проверить(из == [] and "цели нет" in стр, f"(5) клетка под охраной не берётся, причина сказана: {стр[:70]}")

с = стратегия(КЛЮЧИ)
с._резак_крестьян([], dict(СОСТОЯНИЕ))
из2, стр2 = с._резак_крестьян([], dict(СОСТОЯНИЕ, **{"gametime": 730.0}))
проверить(из2 == [] and стр2 == "", "(5б) повтор раньше 60 с не идёт")

# (6) ПРЕДЕЛ ПО ДОРОГЕ: единственная клетка, но дорога безнадёжна — не идём и говорим почему
с = стратегия(dict(КЛЮЧИ, **{"резак_дорога_до": 20}))
одна = dict(СОСТОЯНИЕ, **{"en_pea_cells": [{"x": 10, "y": 10, "крестьян": 8, "бойцов_рядом": 0}]})
из, стр = с._резак_крестьян([], одна)
проверить(из == [] and "НЕ ИДЁТ" in стр and "по дороге его 40" in стр,
          f"(6) предел по дороге: отказ при 40 врагах на пути, порог 20 — {стр[:80]}")

# (7) тот же случай без предела (ключ 0) — идём, как было
с = стратегия(КЛЮЧИ)
из, стр = с._резак_крестьян([], dict(одна))
проверить(из and из[0].get("cx") == 10, "(7) без предела правило идёт по единственной клетке")

if пало:
    print("ПАЛО:")
    for п in пало:
        print("   -", п)
    raise SystemExit(1)
print(f"ОК   резак: {ок} проверок")
