#!/usr/bin/env python3
"""ПИКИ ПО ПРАВУ ОГНЯ (1.11, слово игрока «делай второе»). Живая партия с обходом (e14ed8d): ОГОНЬ видел его 15–51 в 1 кл. от
ратуши за 25 с до первой смерти и слал одних стрелков; 48 крестьян легли в клетках d = 1. Ключ `огонь_пики` N:
  (1) без ключа — как было: один ATTACK стрелками, пик нет;
  (2) с ключом — вторым ATTACK того же такта пики `infantry17` числом max(N, 1,5 × его в клетке) в ту же клетку, помечены `_огонь`;
  (3) приманка в двух клетках от ратуши пик не поднимает (клетки ОГНЯ — не дальше `огонь_клеток` 1);
  (4) повтор не чаще `огонь_повтор`;
  (5) через ответ() на снимках живой Польши 6680 (10:40–12:10) пики уходят в клетку ратуши вместе со стрелками и
      доезжают до выхода стратегии (номер волны им не дан, запрет атаки до срока их не снял).

    python3 selftest_огонь_пики.py
"""
import copy, json, os, sys, tempfile
К = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, К); sys.path.insert(0, os.path.join(К, "sim"))
import strategy_live as SL
import анализ_врага as АВ

ошибок = 0
def проверить(усл, что):
    global ошибок
    print(("ОК   " if усл else "ОШИБКА ") + что); ошибок += not усл

class Реестр:
    def __init__(self):
        import collections
        self.мера = collections.defaultdict(int); self.записи = []

def голая(ключи):
    с = SL.ЖиваяСтратегия.__new__(SL.ЖиваяСтратегия)
    с.п = dict(ключи); с.реестр = Реестр()
    return с

# ратуша в (13,14) — по obuild; его 51 в соседней (12,13), стрелков у нас 30
СТ = {"gametime": 651.0, "mil_shooters": 30,
      "obuild": [{"тип": "center", "x": 13 * 16 * 2 + 16, "z": 14 * 16 * 2 + 16}],
      "map_w": 512, "map_h": 512,
      "ecells": [{"x": 12, "y": 13, "n": 51, "пик": 51, "стрелков": 0, "конных": 0, "идут": 0, "tx": -1, "ty": -1, "n18": 0}]}
дом = SL._наша_база(СТ)
СТ["ecells"][0]["x"], СТ["ecells"][0]["y"] = дом[0] - 1, дом[1] - 1
кл = (дом[0] - 1, дом[1] - 1)

из, why = голая({"огонь_рядом": 6})._огонь_рядом([], copy.deepcopy(СТ))
проверить(len(из) == 1 and из[0].get("who") == "musk17" and "пики стоят" in why, f"(1) без ключа — одни стрелки: {why[:90]}")

из, why = голая({"огонь_рядом": 6, "огонь_пики": 20})._огонь_рядом([], copy.deepcopy(СТ))
п = [c for c in из if c.get("who") == "infantry17"]
проверить(len(из) == 2 and п and п[0]["count"] == 77 and (п[0]["cx"], п[0]["cy"]) == кл and п[0].get("_огонь"),
          f"(2) пики вторым ATTACK, 1,5×51 = 77 в {кл}: {п}")
малый = copy.deepcopy(СТ); малый["ecells"][0]["n"] = 10
из, _ = голая({"огонь_рядом": 6, "огонь_пики": 20})._огонь_рядом([], малый)
проверить([c["count"] for c in из if c.get("who") == "infantry17"] == [20], "(2б) не меньше N (его 10 → 20 пик)")

приманка = copy.deepcopy(СТ); приманка["ecells"][0]["x"] = дом[0] - 2
из, why = голая({"огонь_рядом": 6, "огонь_пики": 20})._огонь_рядом([], приманка)
проверить(not из, f"(3) приманка в 2 кл. пик не поднимает: {из} {why}")

с = голая({"огонь_рядом": 6, "огонь_пики": 20})
с._огонь_рядом([], copy.deepcopy(СТ))
из2, _ = с._огонь_рядом([], dict(copy.deepcopy(СТ), gametime=660.0))
проверить(not из2, "(4) повтор раньше 15 с не идёт")

# (5) живые снимки через ответ()
АВ._ТЕКУЩИЙ.update({"а": None, "t": None, "ответ": None})
д = json.load(open(os.path.join(К, "sim/поиск/шт_s2_оборона_без_атаки_12мин_стойка_отряд_рефлекс_ратуша.json"), encoding="utf-8"))
д["итог"]["огонь_пики"] = 20
with tempfile.NamedTemporaryFile("w", suffix=".json", delete=False, encoding="utf-8") as f:
    json.dump(д, f, ensure_ascii=False)
С = SL.ЖиваяСтратегия(f.name)
нашли = None
for ln in open(os.path.join(К, "sim/кейсы/польша_6680_31_10_10_40-12_10.jsonl"), encoding="utf-8"):
    st = json.loads(ln)
    о = С.ответ(copy.deepcopy(st))
    пк = [c for c in о["commands"] if c.get("cmd") == "ATTACK" and c.get("who") == "infantry17" and c.get("_огонь")]
    if пк:
        нашли = (st["gametime"], пк[0], [c for c in о["commands"] if c.get("who") == "musk17"])
        break
проверить(нашли is not None and нашли[2] and not нашли[1].get("group"),
          f"(5) живые снимки: пики со стрелками в одном такте, без номера волны: {нашли[:2] if нашли else None}")
sys.exit(1 if ошибок else 0)
