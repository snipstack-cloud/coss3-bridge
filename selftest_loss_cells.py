# -*- coding: utf-8 -*-
"""Раскладка потерь ПО КЛЕТКАМ: в трассе и в такте.

ПРАВИЛО, КУПЛЕННОЕ ОШИБКОЙ 27.09: разность картового счётчика (`my_mil_lost`,
`p1_mil_lost`) можно относить к клетке ТОЛЬКО когда клетка контакта одна. Иначе
нужна раскладка по клеткам — а её в трассе не было, и разбор `rear_shooters`
приписал «в окне тыла наших −164, его −15» всей партии, не различая, где это
случилось.

Поэтому поле зовётся `убыло`, а не «погибло», и рядом лежит признак `точно`:
* клетка контакта ОДНА — вся разность счётчика её, верить можно;
* суммы убыли СОШЛИСЬ с разностью счётчиков — из клеток никто не ушёл, верить можно;
* иначе `точно` False, и убыль читается как «ушли ИЛИ погибли».

Стережётся ещё и то, что раскладка считается ДВАЖДЫ и по отдельным памятям: в
трассе (такты с облаком) и в снимке (сетка 5 с). Одна память на двоих мерила бы
разные промежутки одним числом.
"""
import io
import json
import os
import tempfile

import coss3_map as M
import llm_policy as L

беды = []


def проверка(имя, условие, пояснение=""):
    if условие:
        print("  ОК    " + имя)
    else:
        беды.append(имя)
        print("  ПЛОХО " + имя + (" — " + str(пояснение)[:300] if пояснение else ""))


# --- 1. Одна клетка контакта: разность счётчика её, и это «точно» ---
одна = M.раскладка_потерь([{"x": 3, "y": 4, "наших": 20, "его": 30}],
                          [{"x": 3, "y": 4, "наших": 14, "его": 22}], 6, 8)
проверка("одна клетка: убыль разложена",
         одна["клетки"] == [{"x": 3, "y": 4, "наших_убыло": 6, "его_убыло": 8}], одна)
проверка("одна клетка: признак «точно» поднят", одна["точно"] is True)
проверка("одна клетка: остатков нет",
         одна["остаток_наших"] == 0 and одна["остаток_его"] == 0, одна)

# --- 2. Две клетки, но суммы сошлись со счётчиками: тоже точно ---
две = M.раскладка_потерь(
    [{"x": 3, "y": 4, "наших": 20, "его": 30}, {"x": 7, "y": 8, "наших": 10, "его": 5}],
    [{"x": 3, "y": 4, "наших": 14, "его": 22}, {"x": 7, "y": 8, "наших": 8, "его": 5}],
    8, 8)
проверка("две клетки, суммы сошлись — точно", две["точно"] is True, две)
проверка("две клетки: обе в раскладке", len(две["клетки"]) == 2, две)

# --- 3. Две клетки, часть УШЛА: не точно, и остаток отрицательный ---
уход = M.раскладка_потерь(
    [{"x": 3, "y": 4, "наших": 20, "его": 30}, {"x": 7, "y": 8, "наших": 10, "его": 5}],
    [{"x": 3, "y": 4, "наших": 14, "его": 22}, {"x": 7, "y": 8, "наших": 8, "его": 5}],
    2, 8)
проверка("часть ушла, а не погибла — «точно» НЕ поднят", уход["точно"] is False, уход)
проверка("остаток показывает разрыв", уход["остаток_наших"] == -6, уход)

# --- 4. Клетка исчезла целиком (все ушли или погибли) ---
исчезла = M.раскладка_потерь([{"x": 3, "y": 4, "наших": 9, "его": 9}], [], 9, 9)
проверка("исчезнувшая клетка попадает в раскладку целиком",
         исчезла["клетки"] == [{"x": 3, "y": 4, "наших_убыло": 9, "его_убыло": 9}],
         исчезла)
проверка("и это точно: клетка была одна", исчезла["точно"] is True)

# --- 5. Прирост в клетке за убыль не считаем ---
прирост = M.раскладка_потерь([{"x": 1, "y": 1, "наших": 5, "его": 5}],
                             [{"x": 1, "y": 1, "наших": 9, "его": 5}], 0, 0)
проверка("подкрепление не выглядит потерей", прирост["клетки"] == [], прирост)

# --- 6. Имя поля честное: «убыло», а не «погибло» ---
ИСТ_КАРТА = io.open(os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                 "coss3_map.py"), encoding="utf-8").read()
проверка("поле зовётся «убыло», а не «погибло»",
         "наших_убыло" in ИСТ_КАРТА and "наших_погибло" not in ИСТ_КАРТА)

# --- 7. Раскладка доезжает в СНИМОК, и память у него своя ---
ИСТ = io.open(os.path.join(os.path.dirname(os.path.abspath(__file__)),
                           "llm_policy.py"), encoding="utf-8").read()
проверка("раскладка пишется в трассу", '_снимок["потери_клетки"]' in ИСТ)
проверка("раскладка пишется и в снимок", 'строка["потери_клетки"]' in ИСТ)
проверка("памяти у трассы и снимка РАЗНЫЕ",
         "КЛЕТКИ_БЫЛО" in ИСТ and "СНИМОК_БЫЛО" in ИСТ)
проверка("обе памяти чистятся между партиями",
         "КЛЕТКИ_БЫЛО.clear()" in ИСТ and "СНИМОК_БЫЛО.clear()" in ИСТ)


class Ключи:
    def __init__(self, путь, каждые=5):
        self.snaplog = путь
        self.snap_every = каждые


каталог = tempfile.mkdtemp()
путь = os.path.join(каталог, "с.jsonl")
a, когда = Ключи(путь), {}
L.СНИМОК_БЫЛО.clear()
L.писать_снимок(a, {"gametime": 100, "cells": "3,4,20,30,0,5", "cells_n": 1,
                    "my_mil_lost": 10, "p1_mil_lost": 20}, когда)
L.писать_снимок(a, {"gametime": 105, "cells": "3,4,14,22,0,4", "cells_n": 1,
                    "my_mil_lost": 16, "p1_mil_lost": 28}, когда)
строки = [json.loads(x) for x in open(путь, encoding="utf-8") if x.strip()]
_р = строки[-1].get("потери_клетки") or {}
проверка("снимок посчитал раскладку по своей памяти",
         _р.get("клетки") == [{"x": 3, "y": 4, "наших_убыло": 6, "его_убыло": 8}], _р)
проверка("и признак «точно» в снимке поднят", _р.get("точно") is True, _р)

print()
if беды:
    print(f"БЕД: {len(беды)} — {', '.join(беды)}")
    raise SystemExit(1)
print("всё чисто")
