# -*- coding: utf-8 -*-
"""Исход каждой волны — таблица манёвров по трассам отыгранных партий.

Пара к `combat_report.py`. Тот смотрит на ПАРТИЮ и момент первого подхода к
базе врага; этот — на каждое РЕШЕНИЕ ATTACK и на то, что из него вышло через
30 секунд, через 60 и к концу партии. Появился 18.09, когда выяснилось, что
«что стало с волной» мы каждый раз считаем заново ручным скриптом: разбор
«убиваем только у своей базы» был сделан один раз и повторить его на новой
серии было нечем.

    python3 outcome_report.py <каталог идеи> [<каталог идеи> ...]
    python3 outcome_report.py <каталог идеи> --csv волны.csv   # таблица целиком

Что считается одной строкой: такт, в котором мост отправил волну (поле `attack`
в трассе, вето не стояло). Снимок в этом такте — состояние ДО приказа, поэтому
он и есть точка отсчёта. Сколько ушло на самом деле — `wave_sent` следующего
такта: мост шлёт столько, сколько свободных, а не сколько просили.

Ярлыки исхода берутся с первого такта, чей gametime >= t+30 и >= t+60, и с
последнего такта партии. Волны накладываются: за 60 секунд успевает уйти
следующая, и её эффект попадает в ярлык предыдущей. Это не лечится и не
скрывается: столбец `след_через` говорит, через сколько секунд ушла следующая,
и читать ярлыки +60 стоит только там, где он больше 60.

Где дралась волна — по максимуму `mil_far` за 60 секунд после отправки:
  дома     < 60   — не ушла дальше своей базы (отпор или так и не пошла)
  в пути   60-179 — растянулась или перехвачена по дороге
  у врага  >= 180 — дошла (расстояние до базы врага около 210)

Убыль считается ПО ПАДЕНИЯМ ОТ ТАКТА К ТАКТУ, а не по разности концов окна:
армия врага прирастает на 15,9 в минуту, и за 60 секунд она БОЛЬШЕ в 102
волнах из 102 — разность концов не видит ни одной потери. Сумма тактовых
падений p1_army — нижняя оценка убитых (найм внутри такта маскирует часть),
но она та же, какой игрок 18.09 считал вручную «враг потерял 15, мы 5».
Своя убыль — так же по mil_inf+mil_shooters. Размен = убыль врага на одну нашу.

ПРЕДЕЛ МЕРЫ, найденный первым же прогоном (parallel_start + base15, 117 волн):
по тактам у базы врага его армия не убывает НИ РАЗУ — 0 из 117 волн. Всё, что
наши волны там делают, видно только по крестьянам (убыло 25) и по вехе.
А вся убыль армии врага (58 в parallel_start, 12 в base15) случается, когда
наша армия ДОМА — то есть когда он пришёл к нам. Это и есть «убиваем только у
своей базы», теперь одной командой на любой серии.

Второй взгляд, независимый от волн — «по тактам»: каждое падение армии врага
приписывается месту, где в этот такт стояла наша армия (mil_far). Именно так
получается «в parallel_start убито 58, все у нашей базы»: набег врага на нас
волной не является и в таблицу волн не попадает.
"""
import csv, glob, json, os, statistics as st, sys

ДОШЛА = 180
ДОМА = 60


def эпизоды(путь):
    эп, тек = [], []
    for строка in open(путь, encoding="utf-8"):
        строка = строка.strip()
        if not строка:
            continue
        r = json.loads(строка)
        тек.append(r)
        if "finish" in r:
            эп.append(тек)
            тек = []
    if тек:
        эп.append(тек)
    return эп


def ч(s, k):
    try:
        return float(s.get(k, 0) or 0)
    except (TypeError, ValueError):
        return 0.0


def армия(s):
    return ч(s, "mil_inf") + ч(s, "mil_shooters")


def после(т, i, секунд):
    """Первый такт с gametime >= gametime[i] + секунд, или None, если партия
    кончилась раньше — тогда ярлыка нет, а не «ноль»."""
    t0 = ч(т[i]["state"], "gametime")
    for j in range(i + 1, len(т)):
        if ч(т[j]["state"], "gametime") >= t0 + секунд:
            return j
    return None


def клетка(r):
    """Куда именно послали: peasants/base/army/home или клетка (cx,cy)."""
    ц = r.get("target") or ""
    for c in r.get("cmds") or []:
        if str(c.get("cmd", "")).upper() == "ATTACK" and c.get("target") == "cell":
            return f"cell({c.get('cx')},{c.get('cy')})"
    return ц


def волны(e, имя_серии, копия, номер):
    т = [r for r in e if r.get("state")]
    if len(т) < 10:
        return []
    исход = next((r.get("finish") for r in e if "finish" in r), "?")
    веха = next((r.get("веха_убийства") for r in т if r.get("веха_убийства")), None)
    отправки = [i for i, r in enumerate(т) if ч(r, "attack") > 0 and not r.get("veto")]
    строки = []
    for n, i in enumerate(отправки):
        s0 = т[i]["state"]
        t0 = ч(s0, "gametime")
        ушло = ч(т[i + 1]["state"], "wave_sent") if i + 1 < len(т) else 0.0
        след = ч(т[отправки[n + 1]]["state"], "gametime") - t0 if n + 1 < len(отправки) else None
        д = dict(серия=имя_серии, копия=копия, партия=номер, t=int(t0),
                 просили=int(ч(т[i], "attack")), ушло=int(ушло),
                 куда=клетка(т[i]),
                 марш="да" if т[i].get("march") else "",
                 своих_до=int(армия(s0)), врагов_до=int(ч(s0, "p1_army")),
                 крестьян_врага_до=int(ч(s0, "p1_peasants")),
                 след_через=None if след is None else int(след))
        # куда дошла и где дралась — по 60 секундам
        j60 = после(т, i, 60)
        окно = т[i + 1:(j60 + 1) if j60 is not None else len(т)]
        дальность = max((ч(r["state"], "mil_far") for r in окно), default=0.0)
        д["дальность"] = int(дальность)
        д["где"] = "у врага" if дальность >= ДОШЛА else "в пути" if дальность >= ДОМА else "дома"
        for горизонт, j in (("30", после(т, i, 30)), ("60", j60), ("конец", len(т) - 1)):
            if j is None:
                д[f"Δкрестьян_{горизонт}"] = д[f"Δврагов_{горизонт}"] = д[f"Δсвоих_{горизонт}"] = None
                continue
            s1 = т[j]["state"]
            д[f"Δкрестьян_{горизонт}"] = int(ч(s1, "p1_peasants") - ч(s0, "p1_peasants"))
            д[f"Δврагов_{горизонт}"] = int(ч(s1, "p1_army") - ч(s0, "p1_army"))
            д[f"Δсвоих_{горизонт}"] = int(армия(s1) - армия(s0))
        # убила ли ЭТА волна — веха случилась в окне между этой отправкой и следующей
        конец_окна = t0 + (след if след is not None else 10 ** 6)
        д["убила"] = "да" if (веха is not None and t0 < веха <= конец_окна) else ""
        # убыль по падениям от такта к такту в окне 60 с (или до конца партии)
        д["враг_убыль_60"], д["своя_убыль_60"], д["крестьян_убыль_60"] = убыль(т, i, j60)
        д["контакт"] = "да" if any(ч(r["state"], "mil_hurt") > 0 for r in окно) else ""
        д["размен_60"] = (round(д["враг_убыль_60"] / д["своя_убыль_60"], 2)
                          if д["своя_убыль_60"] > 0 else None)
        д["исход_партии"] = исход
        строки.append(д)
    return строки


def есть(s, *ключи):
    """Последняя запись партии (finish) несёт снимок без чисел врага: p1_army
    там None, и разность даёт «падение» на всю армию — 190 бойцов в один такт.
    Пара тактов считается только там, где обе стороны знают число."""
    return all(s.get(k) is not None for k in ключи)


def убыль(т, i, j):
    """Суммы тактовых падений p1_army, своей армии и p1_peasants на тактах i..j."""
    j = len(т) - 1 if j is None else j
    вр = св = кр = 0
    for k in range(i, j):
        a, b = т[k]["state"], т[k + 1]["state"]
        if not (есть(a, "p1_army", "p1_peasants", "mil_inf") and есть(b, "p1_army", "p1_peasants", "mil_inf")):
            continue
        вр += max(0, ч(a, "p1_army") - ч(b, "p1_army"))
        св += max(0, армия(a) - армия(b))
        кр += max(0, ч(a, "p1_peasants") - ч(b, "p1_peasants"))
    return int(вр), int(св), int(кр)


def по_тактам(e):
    """Убыль врага и своя по всем тактам партии, разложенная по месту нашей армии."""
    т = [r for r in e if r.get("state")]
    итог = {м: [0, 0] for м in ("дома", "в пути", "у врага")}
    for k in range(len(т) - 1):
        a, b = т[k]["state"], т[k + 1]["state"]
        if not (есть(a, "p1_army", "mil_inf") and есть(b, "p1_army", "mil_inf")):
            continue
        д = ч(a, "mil_far")
        м = "у врага" if д >= ДОШЛА else "в пути" if д >= ДОМА else "дома"
        итог[м][0] += max(0, ч(a, "p1_army") - ч(b, "p1_army"))
        итог[м][1] += max(0, армия(a) - армия(b))
    return итог


def медиана(xs):
    xs = [x for x in xs if x is not None]
    return round(st.median(xs), 2) if xs else None


def сводка(гр, заголовок):
    if not гр:
        return
    print(f"\n== {заголовок}: волн {len(гр)} ==")
    ушло = [x["ушло"] for x in гр]
    print(f"  ушло: медиана {медиана(ушло)}, просили медиана {медиана([x['просили'] for x in гр])}")
    for где in ("дома", "в пути", "у врага"):
        г = [x for x in гр if x["где"] == где]
        if not г:
            continue
        уб = sum(1 for x in г if x["убила"])
        вр, св = sum(x["враг_убыль_60"] for x in г), sum(x["своя_убыль_60"] for x in г)
        print(f"  {где:<8} {len(г):>4} волн ({100*len(г)/len(гр):.0f}%)  веха {уб:>2}  "
              f"контакт {sum(1 for x in г if x['контакт']):>3}  "
              f"убыль врага {вр:>4} / своя {св:>4}  размен {вр/max(1,св):.2f}  "
              f"крестьян врага убыло {sum(x['крестьян_убыль_60'] for x in г):>3}")
    по_цели = {}
    for x in гр:
        по_цели.setdefault(x["куда"].split("(")[0] or "?", []).append(x)
    print("  по цели:", ", ".join(f"{k} {len(v)} (убила {sum(1 for x in v if x['убила'])})"
                                  for k, v in sorted(по_цели.items(), key=lambda kv: -len(kv[1]))))
    марш = [x for x in гр if x["марш"]]
    if марш:
        print(f"  с контрактом марша: {len(марш)} (убила {sum(1 for x in марш if x['убила'])})")
    наложились = sum(1 for x in гр if x["след_через"] is not None and x["след_через"] < 60)
    print(f"  волн, за которыми следующая ушла раньше чем через 60 с: {наложились} — их ярлыки +60 смешаны")


def main(argv):
    csv_путь = None
    if "--csv" in argv:
        k = argv.index("--csv")
        csv_путь = argv[k + 1]
        argv = argv[:k] + argv[k + 2:]
    if not argv:
        sys.exit(__doc__)
    все, такты = [], {}
    for кат in argv:
        имя = os.path.basename(os.path.normpath(кат))
        for путь in sorted(glob.glob(os.path.join(кат, "*", "coss3_bot.jsonl"))):
            копия = os.path.basename(os.path.dirname(путь))
            for номер, e in enumerate(эпизоды(путь), 1):
                все.extend(волны(e, имя, копия, номер))
                for м, (вр, св) in по_тактам(e).items():
                    з = такты.setdefault(имя, {}).setdefault(м, [0, 0])
                    з[0] += вр; з[1] += св
    if not все:
        sys.exit("волн не нашлось")
    for имя in sorted({x["серия"] for x in все}):
        сводка([x for x in все if x["серия"] == имя], имя)
        print("  ПО ТАКТАМ, независимо от волн — где стояла наша армия, когда враг терял:")
        for м in ("дома", "в пути", "у врага"):
            вр, св = такты[имя].get(м, (0, 0))
            print(f"    {м:<8} убыль врага {int(вр):>4} / своя {int(св):>4}  размен {вр/max(1,св):.2f}")
    if len({x["серия"] for x in все}) > 1:
        сводка(все, "ВСЕ ВМЕСТЕ")
    if csv_путь:
        with open(csv_путь, "w", newline="", encoding="utf-8") as f:
            w = csv.DictWriter(f, fieldnames=list(все[0].keys()))
            w.writeheader()
            w.writerows(все)
        print(f"\nтаблица: {csv_путь} ({len(все)} строк)")


if __name__ == "__main__":
    main(sys.argv[1:])
