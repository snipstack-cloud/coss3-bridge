# -*- coding: utf-8 -*-
"""Самопроверка таблицы «Что купить»: здания и апгрейды в одной мере.

Повод: блок «Что держит план» назвал модели ОДНУ цель — следующую казарму, —
и она стала копить на неё, бросив апгрейды. Три живые партии 19.09 подряд:
приказов UPGRADE 15 -> 9 -> 6, упоминаний казармы 11 -> 25 -> 22, при том что
апгрейд был по карману в 30 тактах из 41, а заказан в пяти.

Стережётся здесь:
* апгрейд и здание стоят В ОДНОМ списке и сравнимы числом;
* КОНЮШНЯ названа единственным источником конницы (драгун — единственный наш
  боец, догоняющий убегающего крестьянина, country.script:2929,2978);
* темп конюшни назван НЕ ЗАМЕРЕННЫМ: его мерили для казармы, не для неё;
* цена не свёрнута в одно число — ресурсы не взаимозаменяемы.
"""
import llm_policy as L

беды = []


def проверка(имя, условие, пояснение=""):
    if условие:
        print("  ОК    " + имя)
    else:
        беды.append(имя)
        print("  ПЛОХО " + имя + (" — " + пояснение if пояснение else ""))


def таблица(gt=300, пик=120, мушк=31, казарм=2, конюшен=0, еда=20000, золото=12000):
    ст = {
        "gametime": gt, "peasants": 60, "food": еда, "gold": золото,
        "wood": 5000, "stone": 5000, "iron": 5000, "coal": 5000,
        "mil_inf": пик, "mil_shooters": мушк, "mil_cav": 0,
        "ba17": казарм, "stables": конюшен, "mills": 1, "p1_enemy": 1,
        "p1_army": 200,
        "build_cost": ("ba17=wood2500,stone2500,gold12500 "
                       "stable=wood2500,stone100,gold600"),
        "upg_avail": ("bar.pikeman.1.2=f700g400i0,"
                      "bar.musketeernet.2.1=f170g50i100"),
        "fighters": ("infantry17=pikeman,hp90,atk8,wkind1,pause0,dpike3,dsword2,dbullet4 "
                     "musk17=musketeernet,hp65,atk10,wkind3,pause375,dpike1,dsword1,dbullet0"),
        "p1_fighters": ("infantry17=hp90,atk13,wkind1,pause0,dpike7,dsword6,dbullet4 "
                        "musk17=hp65,atk10,wkind3,pause375,dpike0,dsword0,dbullet0"),
    }
    return "\n".join(L.что_купить(ст))


print("Самопроверка таблицы покупок:")
т = таблица()
проверка("таблица строится", т != "")
проверка("здание в списке", "казарма" in т, т[:200])
проверка("апгрейд в том же списке", "bar.pikeman.1.2" in т, т[:200])
проверка("КОНЮШНЯ в списке", "конюшня" in т, т[:200])
проверка("конюшня названа источником конницы", "КОННИЦЫ" in т, т[:300])
проверка("сказано про цель матча", "ЦЕЛЬ МАТЧА" in т, т[:300])
проверка("темп конюшни помечен как НЕ ЗАМЕРЕННЫЙ", "НЕ ЗАМЕРЕН" in т, т[:300])
проверка("цена показана по ресурсам, а не одним числом",
         "дерева" in т and "еды" in т, т[:200])
проверка("нехватка названа", "НЕ ХВАТАЕТ" in таблица(золото=100), "")

# Конюшня, которая уже стоит, больше не «единственный источник»
т2 = таблица(конюшен=1)
проверка("при готовой конюшне речь о второй, без лозунга про цель матча",
         "конюшня №2" in т2 and "ЦЕЛЬ МАТЧА" not in т2, т2[:200])

# У горизонта таблица молчит: покупать поздно
проверка("у самого горизонта таблицы нет",
         таблица(gt=L.ГОРИЗОНТ - 10) == "")

print()
if беды:
    print(f"БЕД: {len(беды)} — {', '.join(беды)}")
    raise SystemExit(1)
print("всё чисто")
