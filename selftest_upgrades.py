"""Проверка двух правок про апгрейды, без игры и без модели.

1. `отобрать_апгрейды` — что модель ВИДИТ в списке;
2. ветка `UPGRADE` в `итог_прошлого` — что она узнаёт про свой заказ.

Список апгрейдов взят ТОЧНО такой, какой отдаёт игра Нидерландам: имена и
порядок прочитаны из живого состояния контейнера 15.09 (`upg_avail`,
220 имён). Именно порядок и был причиной провала серии `upgrades`.
"""
import llm_policy as П
import mock_human as М

# Список игры: мусорное имя, ратуша, мельница, три десятка академии, кузница,
# и только потом военные. Собираем той же формой, что и мок.
СПИСОК = (["l", "cen.1", "mil.1", "mil.2"]
          + [f"aca.{i}" for i in range(1, 37)]
          + [f"bla.{i}" for i in range(1, 6)]
          + [f"art.cannon.{в}.{у}" for в in (1, 2) for у in range(1, 6)]
          + [f"bar.pikeman.{в}.{у}" for в in (1, 2) for у in range(1, 6)]
          + [f"bar.musketeernet.{в}.{у}" for в in (1, 2) for у in range(1, 6)])

БОЙЦЫ = ("infantry17=pikeman,hp90,food25,gold3,iron20,coal0 "
         "musk17=musketeernet,hp65,food50,gold8,iron4,coal0")

ошибок = 0


def проверь(что: str, условие: bool, пояснение: str = "") -> None:
    global ошибок
    print(("  ОК   " if условие else "  ПРОВАЛ ") + что
          + (f"  [{пояснение}]" if пояснение else ""))
    if not условие:
        ошибок += 1


print("== 1. Отбор апгрейдов ==")

пусто = {"fighters": БОЙЦЫ, "centers": 0, "mills": 0, "smiths": 0, "ba17": 0}
видно, срез, чем = П.отобрать_апгрейды(СПИСОК, пусто)
проверь("ничего не построено — возвращаемся к прежнему поведению",
        видно == СПИСОК[:П.СПИСОК_АПГРЕЙДОВ] and чем == "",
        f"показано {len(видно)}")

всё = {"fighters": БОЙЦЫ, "centers": 1, "mills": 1, "smiths": 1, "ba17": 1}
видно, срез, чем = П.отобрать_апгрейды(СПИСОК, всё)
проверь("военные апгрейды показаны",
        any(у.count(".") >= 3 for у in видно), ", ".join(видно[:4]))
проверь("защита пикинёра bar.pikeman.2.1 в списке",
        "bar.pikeman.2.1" in видно)
проверь("академии нет — её боту строить запрещено",
        not any(у.startswith("aca.") for у in видно))
проверь("мусорного имени 'l' нет", "l" not in видно)
проверь("пушки не показаны — артиллерийского двора не стоит",
        not any(у.startswith("art.") for у in видно))
проверь("апгрейды стоящих зданий на месте",
        "mil.1" in видно and "cen.1" in видно and "bla.1" in видно)
проверь("пикинёр идёт раньше мушкетёра — порядок из списка найма",
        видно.index("bar.pikeman.1.1") < видно.index("bar.musketeernet.1.1"))
проверь("скрытое посчитано", срез == len(СПИСОК) - len(видно), f"скрыто {срез}")

без_казармы = dict(всё, ba17=0)
видно, _, _ = П.отобрать_апгрейды(СПИСОК, без_казармы)
проверь("без казармы военных не показываем — их и не заказать",
        not any(у.startswith("bar.") for у in видно), ", ".join(видно))

print()
print("== 2. Итог прошлого решения ==")

заказ = [("UPGRADE", "bar.pikeman.2.1", 0)]
строки = П.итог_прошлого(всё, dict(всё), заказ)
текст = "\n".join(строки)
проверь("без отказа мост НЕ объявляет заказ принятым",
        "принят" not in текст and "отказа пока нет" in текст)
проверь("и честно говорит, что готовности не видит",
        "НЕ ВИДИТ" in текст, текст.strip().splitlines()[-1].strip()[:90])

сбой = dict(всё, last_fail="UPGRADE bar.pikeman.2.1: not enough resources")
строки = П.итог_прошлого(всё, сбой, заказ)
текст = "\n".join(строки)
проверь("отказ назван причиной игры",
        "НЕ ПРОШЁЛ" in текст and "not enough resources" in текст,
        текст.strip().splitlines()[-1].strip()[:90])

повторы: dict = {}
П.итог_прошлого(всё, сбой, заказ, повторы)
строки = П.итог_прошлого(всё, сбой, заказ, повторы)
проверь("повтор того же отказа посчитан",
        "2-Й РАЗ ПОДРЯД" in "\n".join(строки))

чужой = dict(всё, last_fail="UPGRADE mil.1: not enough resources")
строки = П.итог_прошлого(всё, чужой, заказ)
проверь("чужой отказ не приписан нашему заказу",
        "НЕ ПРОШЁЛ" not in "\n".join(строки))

print()
print("== 3. Мок умеет UPGRADE ==")
проверь("список апгрейдов у мока той же формы",
        "bar.pikeman.2.1" in М.АПГРЕЙДЫ and М.СПИСОК_АПГРЕЙДОВ_МОКА[0] == "l")
проверь("цена защиты пикинёра — настоящая, 250 еды и 150 золота",
        М.АПГРЕЙДЫ["bar.pikeman.2.1"] == (250, 150))

print()
print("ПРОВАЛОВ: %d" % ошибок)
raise SystemExit(1 if ошибок else 0)
