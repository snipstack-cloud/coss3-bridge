if _ж.сводим:
    беды.append(f"слившаяся пара должна забыться, а осталась: {_ж.сводим}")

# --- 3в. СТРАТЕГИЯ САМА ЗАВОДИТ ГРУППЫ (решение игрока 4.10) -----------------
# Пока волны были безымянны, адресные приказы умела только рука: «к своим»,
# «держать» и «вперёд» брали ВСЕХ дальше 60 от ратуши и задевали подмогу, которая
# ещё идёт. Теперь каждая уходящая волна получает СВОБОДНЫЙ номер — свободный по
# состоянию, а не по счётчику, иначе новая волна перебила бы состав живой группы.


class _СтрВолна:
    пропущено = {}

    class я:
        class дебют:
            готов = staticmethod(lambda st: True)

    def __init__(self, cmds):
        self.cmds = cmds

    def __call__(self, st):
        return [dict(c) for c in self.cmds]


def _живая(cmds):
    ж = SL.ЖиваяСтратегия.__new__(SL.ЖиваяСтратегия)
    ж.п, ж.имя, ж.сеть, ж.стр = {}, "t.json", None, _СтрВолна(cmds)
    ж.пропущено, ж.отдано = collections.Counter(), collections.Counter()
    ж.сводим, ж.номера = {}, 0
    return ж


_дома = {"gametime": 500, "map_w": 256, "map_h": 256, "mil_away": 0, "my_freewar": 30,
         "obuild": [{"тип": "center", "x": 50, "z": 54}],
         "ocells": [{"x": 3, "y": 3, "n": 30}], "groups": "none"}
_о = _живая([{"cmd": "ATTACK", "count": 20, "target": "army"}]).ответ(_дома)
if [c.get("group") for c in _о["commands"]] != [1]:
    беды.append(f"первая волна должна стать группой 1: {_о['commands']}")
# В `why` рождение НЕ объявляется нарочно (прогон smoke_hard4 4.10: мост 17 раз
# честно отказал в ударе, а `why` 17 раз сообщал о рождении группы — лгал). Намерение
# видно в самой команде, а о настоящем рождении говорит отправка.
if "становится группой" in _о["why"]:
    беды.append("why объявляет рождение группы до отправки — это ложь, когда удар "
                "не уйдёт (smoke_hard4: 17 отказов и 17 ложных рождений)")
# Номер берётся свободный: при живой группе 1 новая волна получает 2.
_о2 = _живая([{"cmd": "ATTACK", "count": 10, "target": "army"}]).ответ(
    dict(_дома, groups="1,20,20,0,0,9,9,0,-1,-1"))
if [c.get("group") for c in _о2["commands"]] != [2]:
    беды.append(f"вторая волна должна стать группой 2: {_о2['commands']}")
# Все шестнадцать заняты — волна уходит БЕЗ номера и говорит об этом.
_все = ";".join(f"{i},5,5,0,0,9,9,0,-1,-1" for i in range(1, 17))
_о3 = _живая([{"cmd": "ATTACK", "count": 10, "target": "army"}]).ответ(dict(_дома, groups=_все))
if _о3["commands"][0].get("group") is not None:
    беды.append("при шестнадцати живых группах номер выдавать некуда")
if "кончились" not in _о3["why"]:
    беды.append("исчерпание номеров должно называться вслух")
# Приказ существующей группе (count 0) номера не трогает.
_о4 = _живая([{"cmd": "RETREAT", "count": 0, "target": "home", "group": 1}]).ответ(
    dict(_дома, groups="1,20,20,0,0,9,9,0,-1,-1"))
if [c.get("group") for c in _о4["commands"]] != [1]:
    беды.append(f"приказ группе 1 не должен переименовываться: {_о4['commands']}")

# COUNT СЛОВОМ «ALL» — так стратегия и сеть просят всех свободных («подмога»).
# Живая игра проверки 5: номер получила ОДНА волна из 81, потому что int(float("all"))
# падал и число считалось нулём; восемьдесят ушли безымянными.
_оall = _живая([{"cmd": "ATTACK", "count": "all", "target": "wave"}]).ответ(_дома)
if _оall["commands"][0].get("group") != 1:
    беды.append(f"волна с count=all должна получить номер: {_оall['commands']}")

# Номер волны обязан доезжать до моста: ветка ATTACK в to_commands его читает.
_вых = L.to_commands({"commands": [{"cmd": "ATTACK", "count": 20, "target": "army", "group": 3}]},
                     set(), set(), st={"gametime": 300, "my_freewar": 30})
if _вых[3]:
    беды.append(f"ATTACK с номером группы дал брак: {_вых[3]}")
if L.ГРУППА_АТАКИ != 3:
    беды.append(f"номер группы у ATTACK не доехал: ГРУППА_АТАКИ = {L.ГРУППА_АТАКИ}")

# --- 4. формы в блоках ------------------------------------------------------
hstate = open(os.path.join(ЗДЕСЬ, "block_hstate.inc"), encoding="latin-1").read()
hcmd = open(os.path.join(ЗДЕСЬ, "block_hcmd.inc"), encoding="latin-1").read()
for имя, кусок, файл in (
        ("поле groups пишется", "ParserSetValueByKeyByHandle(hsp, 'groups', hgstr)", hstate),
        ("число групп пишется", "'groups_n'", hstate),
        ("состав читается из br_hgrp", "ParserSelectByKey('br_hgrp')", hstate),
        ("мёртвые не считаются", "if (not TObj(hgp).bdead) then", hstate),
        ("режим группы запоминается", "'_m', hagm)", hcmd),
        # Слияние: цель group в блоке команд, сам слив — в блоке состояния.
        ("цель group в приказе", "if (hatrg = 'group') then", hcmd),
        ("к кому идём запоминается", "'_to', hatgid)", hcmd),
        ("слияние по приходу", "merged into", hstate),
        ("дошли = та же клетка", "if (hgcell[hgid] = hgcell[hgto])", hstate)):
    if кусок not in файл:
        беды.append(f"нет: {имя} ({кусок!r})")
# Накопители групп объявлены ДО циклов: число во вложенном begin не накапливает.
до_цикла = hstate.split("for hgid := 1 to 16 do")[0]
for имя in ("hgliv", "hgpk", "hgsh", "hgcv", "hgsx", "hgsz", "hgtx", "hgty"):
    if f"var {имя} : Integer;" not in до_цикла:
        беды.append(f"накопитель {имя} объявлен не до цикла — он не будет накапливать "
                    f"(шесть счётчиков армии, 17.09)")
for n, s in enumerate(hstate.splitlines(), 1):
    if any(ord(c) > 127 for c in s):
        беды.append(f"block_hstate.inc:{n} — не-ASCII")
        break

if беды:
    print("ПЛОХО:")
    for б in беды:
        print("  -", б)
    raise SystemExit(1)
print("ХОРОШО: группы разбираются, адресный приказ трогает только свою, "
      "поле доезжает до промпта, критика и снимка, формы в блоках на месте")
