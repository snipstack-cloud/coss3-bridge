# -*- coding: utf-8 -*-
"""ГРУППЫ С НОМЕРАМИ (4.10, §78 мака): поле `groups` и адресный приказ.

Проверяется весь путь, кроме самой игры (её проверяет живая партия):
  1. разбор поля `groups` (`coss3_map.наши_группы`);
  2. петля на моке: два приказа одним файлом рождают две группы, приказ с
     номером и `count = 0` трогает ТОЛЬКО свою, приказ несуществующей — отказ;
  3. обвязка: группы доезжают до промпта модели, до строки критика и до снимка
     трассы. Поле, которое доехало только до состояния, — немое: по серии его не
     посчитать, а критик додумает недостающее;
  4. формы в блоках: поле пишется, накопители объявлены ДО циклов.

    python selftest_groups.py
"""
import os
import sys
import tempfile

ЗДЕСЬ = os.path.dirname(os.path.abspath(__file__))
if ЗДЕСЬ not in sys.path:
    sys.path.insert(0, ЗДЕСЬ)

import coss3_bridge as CB
import coss3_map as M
import llm_policy as L
import mock_human as MH

беды = []

# --- 1. разбор ---------------------------------------------------------------
st = {"groups": "1,4,4,0,0,9,9,1,9,9;2,3,1,2,0,5,1,2,-1,-1", "groups_n": 2}
гр = M.наши_группы(st)
if len(гр) != 2:
    беды.append(f"разобрано {len(гр)} групп вместо двух: {гр}")
else:
    if гр[0] != {"id": 1, "n": 4, "пик": 4, "стрелков": 0, "конных": 0,
                 "cx": 9, "cy": 9, "режим": 1, "tx": 9, "ty": 9}:
        беды.append(f"первая группа разобрана не так: {гр[0]}")
    if гр[1]["tx"] != -1:
        беды.append("стоящая группа должна иметь цель -1,-1")
# Обрезанная запись пропускается молча, но `groups_n` скажет о недостаче.
if M.наши_группы({"groups": "1,4,4,0"}) != []:
    беды.append("обрезанная запись не должна разбираться")
if M.наши_группы({"groups": "none"}) or M.наши_группы({}):
    беды.append("пустое поле должно давать пустой список")

# --- 2. петля на моке -------------------------------------------------------
with tempfile.TemporaryDirectory() as кат:
    м = MH.Мир(кат, plind=1)
    м.армия = 20
    br = CB.Bridge(кат, plind=1)
    br.attack_many([
        {"count": 5, "target": "cell", "mode": "move", "cx": 9, "cy": 7, "group": 1},
        {"count": 4, "target": "cell", "mode": "move", "cx": 3, "cy": 3, "group": 2}])
    м.атака()
    м.состояние()
    сост = br.read_state() or {}
    пара = M.наши_группы(сост)
    if [(г["id"], г["n"]) for г in пара] != [(1, 5), (2, 4)]:
        беды.append(f"мок отдал группы не так: {сост.get('groups')!r}")
    # Приказ ТОЛЬКО группе 1: у неё режим становится отходом, у второй остаётся.
    br.attack_many([{"count": 0, "target": "home", "mode": "retreat", "group": 1}])
    м.атака()
    м.состояние()
    режимы = {г["id"]: г["режим"] for г in M.наши_группы(br.read_state() or {})}
    if режимы.get(1) != 2:
        беды.append(f"группа 1 должна была уйти в отход, режимы: {режимы}")
    if режимы.get(2) != 1:
        беды.append(f"группа 2 не должна была тронуться, режимы: {режимы}")
    # Приказ несуществующей группе — отказ ВСЛУХ, а не тишина.
    br.attack_many([{"count": 0, "target": "home", "mode": "retreat", "group": 9}])
    м.атака()
    if "GROUP 9" not in str(м.отказ):
        беды.append(f"приказ несуществующей группе должен давать отказ, а дал {м.отказ!r}")

    # --- 2б. СЛИЯНИЕ: цель `group` + номер получателя `gid` ------------------
    br.attack_many([
        {"count": 3, "target": "cell", "mode": "move", "cx": 9, "cy": 7, "group": 3},
        {"count": 2, "target": "cell", "mode": "move", "cx": 9, "cy": 7, "group": 4}])
    м.атака()
    br.attack_many([{"count": 0, "target": "group", "mode": "move", "group": 3, "gid": 4}])
    м.атака()
    м.состояние()
    после = {г["id"]: г["n"] for г in M.наши_группы(br.read_state() or {})}
    if 3 in после:
        беды.append(f"влившаяся группа 3 должна исчезнуть, а осталась: {после}")
    if после.get(4) != 5:
        беды.append(f"группа 4 должна была стать из 2+3 = 5, а стала {после.get(4)}")
    # Цель `group` без номера получателя не уезжает вовсе.
    if br.attack_many([{"count": 0, "target": "group", "mode": "move", "group": 4}]):
        беды.append("цель group без gid ушла в игру — некуда идти")
    if os.path.exists(br.atk_path):
        os.unlink(br.atk_path)
    # Слияние в несуществующую группу — отказ вслух.
    br.attack_many([{"count": 0, "target": "group", "mode": "move", "group": 4, "gid": 9}])
    м.атака()
    if "no group 9" not in str(м.отказ):
        беды.append(f"слияние в несуществующую должно отказывать, а дало {м.отказ!r}")

# --- 3. обвязка: промпт, критик, снимок -------------------------------------
L.АРМИЯ_ПО_КЛЕТКАМ = True
полное = dict(st, ocells="2,3,9,9,0,0", ocells_all=1, gametime=300,
              map_w=256, map_h=256, peasants=20, mil_inf=7)
строки = L.открытая_информация(полное, {})
if not any("твои группы:" in s for s in строки):
    беды.append("в промпте модели нет строки про группы — адресный приказ ей не выразить")
if not any("group" in s and "count" in s for s in строки):
    беды.append("промпт не говорит, КАК отдать приказ группе")
# Строка критика: вызывать её целиком нечем (нужны команды и цель такта),
# поэтому проверяем, что поле в неё кладётся — по тому же коду, что исполняется.
исходник = open(os.path.join(ЗДЕСЬ, "llm_policy.py"), encoding="utf-8").read()
if 'строка["groups"]' not in исходник:
    беды.append("groups не доезжает до строки критика — он додумает, кто куда шёл")
# Снимок трассы: поле должно собираться списком списков.
if '_снимок["groups"]' not in исходник:
    беды.append("groups не попадает в снимок трассы — по серии его не посчитать")

# --- 4. формы в блоках ------------------------------------------------------
hstate = open(os.path.join(ЗДЕСЬ, "block_hstate.inc"), encoding="latin-1").read()
hcmd = open(os.path.join(ЗДЕСЬ, "block_hcmd.inc"), encoding="latin-1").read()
for имя, кусок, файл in (
        ("поле groups пишется", "ParserSetValueByKeyByHandle(hsp, 'groups', hgstr)", hstate),
        ("число групп пишется", "'groups_n'", hstate),
        ("состав читается из br_hgrp", "ParserSelectByKey('br_hgrp')", hstate),
        ("мёртвые не считаются", "if (not TObj(hgp).bdead) then", hstate),
        ("режим группы запоминается", "'_m', hagm)", hcmd),
        # Слияние: цель group в блоке команд, сам слив — в блоке состояния.
        ("цель group в приказе", "if (hatrg = 'group') then", hcmd),
        ("к кому идём запоминается", "'_to', hatgid)", hcmd),
        ("слияние по приходу", "merged into", hstate),
        ("дошли = та же клетка", "if (hgcell[hgid] = hgcell[hgto])", hstate)):
    if кусок not in файл:
        беды.append(f"нет: {имя} ({кусок!r})")
# Накопители групп объявлены ДО циклов: число во вложенном begin не накапливает.
до_цикла = hstate.split("for hgid := 1 to 16 do")[0]
for имя in ("hgliv", "hgpk", "hgsh", "hgcv", "hgsx", "hgsz", "hgtx", "hgty"):
    if f"var {имя} : Integer;" not in до_цикла:
        беды.append(f"накопитель {имя} объявлен не до цикла — он не будет накапливать "
                    f"(шесть счётчиков армии, 17.09)")
for n, s in enumerate(hstate.splitlines(), 1):
    if any(ord(c) > 127 for c in s):
        беды.append(f"block_hstate.inc:{n} — не-ASCII")
        break

if беды:
    print("ПЛОХО:")
    for б in беды:
        print("  -", б)
    raise SystemExit(1)
print("ХОРОШО: группы разбираются, адресный приказ трогает только свою, "
      "поле доезжает до промпта, критика и снимка, формы в блоках на месте")
