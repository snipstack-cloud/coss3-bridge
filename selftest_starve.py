# -*- coding: utf-8 -*-
"""Голодные смерти врага отделены от нашего удара.

Повод, 24.09, живая игра. Мост объявил веху на 5:20 - «у врага погибло
крестьян 5», - когда наша армия ни разу не выходила из дома: mil_away 0, своих
потерь 0, свои крестьяне только росли. Разбор снимков той же партии:

    t=231  еда врага 10   его крестьян 23  pea_lost 0
    t=236  еда врага 0    его крестьян 23  pea_lost 0
    t=241  еда врага 0    его крестьян 23  pea_lost 4
    t=251  еда врага 0    его крестьян 23  pea_lost 5
    t=266  еда врага 131  его крестьян 21  pea_lost 5  - и дальше не растёт

Крестьяне врага умерли с голоду ровно тогда, когда его еда дошла до нуля, и
перестали умирать, как только она вернулась. Это не случай одной партии: по 29
свежим прогонам 23-24.09 первая гибель крестьянина врага в 28 случаях
приходится на 236-256 с и ровно при нулевой еде врага. Единственное исключение
- debut4/2: первая гибель на 496 с при еде 7557, то есть настоящее убийство.

Почему так: p<n>_pea_lost берётся из gPlayer[pl].stat.killed, а движок
увеличивает этот счётчик в _unit_RemoveObjFromPlayerCounters
(lib/unit.script:3869) у ВЛАДЕЛЬЦА уничтоженного юнита при ЛЮБОЙ причине
смерти. Поле читается верно - неверно читалось его значение.

Цена ошибки: у меры «убито крестьян врага» был пол около пяти. base28
читалась как 6/7/7/23 против 42/36/7/35 у base27, а за вычетом голода это
0/3/0/14 против 37/33/3/29 - то есть «бьёт слабо» на деле означало «не бьёт
вовсе, три партии из четырёх в ноль».

Что проверяется:
  1. счётчики заведены и обнуляются на каждую партию;
  2. прирост при НУЛЕВОЙ еде врага идёт в голод и называется вслух;
  3. прирост при ЕДЕ БОЛЬШЕ НУЛЯ в голод НЕ идёт;
  4. веха считает прирост ПОСЛЕ ухода волны, а не накопленный итог;
  5. голод лежит в трассе, иначе по серии его не вычесть задним числом.
"""
import io, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import llm_policy as L

ошибок = 0


def проверить(условие, что):
    global ошибок
    if not условие:
        ошибок += 1
        print("  СБОЙ:", что)
    else:
        print("  ок:", что)


И = io.open(os.path.join(os.path.dirname(os.path.abspath(__file__)),
                         "llm_policy.py"), encoding="utf-8").read()

print("1. счётчики заведены и обнуляются на партию")
проверить("ГОЛОД_ВРАГА: list[int] = []" in И, "ГОЛОД_ВРАГА заведён")
проверить("ПОТ_ВРАГА_БЫЛО: list[int] = []" in И, "ПОТ_ВРАГА_БЫЛО заведён")
проверить("ЧИСТО_НА_ВОЛНЕ: list[int] = []" in И, "ЧИСТО_НА_ВОЛНЕ заведён")
for имя in ("ГОЛОД_ВРАГА.clear()", "ПОТ_ВРАГА_БЫЛО.clear()",
            "ЧИСТО_НА_ВОЛНЕ.clear()"):
    проверить(имя in И, "обнуляется на партию: " + имя)


def голод(ряд):
    """Та же формула, что в мосту: прирост при нулевой еде - голодный."""
    L.ГОЛОД_ВРАГА.clear()
    L.ПОТ_ВРАГА_БЫЛО.clear()
    for pea_lost, еда in ряд:
        прирост = pea_lost - (L.ПОТ_ВРАГА_БЫЛО[0] if L.ПОТ_ВРАГА_БЫЛО else 0)
        if прирост > 0 and еда == 0:
            if not L.ГОЛОД_ВРАГА:
                L.ГОЛОД_ВРАГА.append(0)
            L.ГОЛОД_ВРАГА[0] += прирост
        if L.ПОТ_ВРАГА_БЫЛО:
            L.ПОТ_ВРАГА_БЫЛО[0] = pea_lost
        else:
            L.ПОТ_ВРАГА_БЫЛО.append(pea_lost)
    return L.ГОЛОД_ВРАГА[0] if L.ГОЛОД_ВРАГА else 0


print("2. прирост при нулевой еде идёт в голод")
# ряд той самой живой партии 24.09
проверить(голод([(0, 10), (0, 0), (4, 0), (4, 0), (5, 0), (5, 131)]) == 5,
          "пять голодных смертей той партии посчитаны как голод")
проверить("С ГОЛОДУ" in И and "это не наш удар" in И,
          "каждый случай называется вслух, а не отбрасывается молча")

print("3. прирост при еде больше нуля в голод не идёт")
проверить(голод([(0, 500), (7, 500), (12, 430)]) == 0,
          "двенадцать убитых при полной еде - не голод")
проверить(голод([(0, 0), (5, 0), (9, 900)]) == 5,
          "смешанный случай: пять голодных, четыре наших")

print("4. веха считает прирост после ухода волны")
проверить("_чисто = max(0, _пот - _голод)" in И, "голод вычитается")
проверить("_порог = ЧИСТО_НА_ВОЛНЕ[0] if ЧИСТО_НА_ВОЛНЕ else 0" in И,
          "порог берётся с мига ухода волны")
проверить("if _чисто > _порог and волна_была and not ВЕХА_УБИЙСТВО:" in И,
          "условие вехи - ПРИРОСТ, а не накопленный итог")
проверить("if _пот > 0 and волна_была" not in И,
          "прежнее условие по накопленному итогу убрано")

print("5. голод лежит в трассе")
проверить('"голод_врага": (ГОЛОД_ВРАГА[0] if ГОЛОД_ВРАГА else 0),' in И,
          "поле «голод_врага» в записи трассы")

print()
print("ошибок:", ошибок)
sys.exit(1 if ошибок else 0)
