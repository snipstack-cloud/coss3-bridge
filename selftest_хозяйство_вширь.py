#!/usr/bin/env python3
"""ХОЗЯЙСТВО ВШИРЬ (1.11, century_net/2-ban: ИИ — вторая ратуша в 15:00, вторая мельница ~25:00, крестьян 233 против 147 к 30 мин;
у бота дома только к 20:00 при населении 454/475). Ключи лестницы `strategy_live.привести` (0 — как было): `ратуш` / `ратуш_с`,
`мельниц` / `мельница_пахарей`, `дома_доля`; крестьяне каждый такт при двух ратушах (`ЖиваяСтратегия.ответ`).

    python3 selftest_хозяйство_вширь.py
"""
import collections, os, sys
К = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, К); sys.path.insert(0, os.path.join(К, "sim"))
import strategy_live as SL

ошибок = 0
def проверить(усл, что):
    global ошибок
    print(("ОК   " if усл else "ОШИБКА ") + что); ошибок += not усл

class _Пустая:
    академия = False
    академия_с = 0

def снимок(**к):
    st = {"gametime": 900, "food": 3000, "wood": 2500, "stone": 2500, "gold": 3000, "iron": 2000, "peasants": 80,
          "centers": 1, "mills": 1, "ba17": 2, "mines_gold": 3, "mines_iron": 1, "academies": 1, "houses": 2,
          "my_farm": 400, "my_farmused": 350, "on_food": 20, "on_gold": 15, "food_ready": 20,
          "build_cost": "center=food0,wood2100,stone2100,gold0,iron0,coal0 mill=food0,wood60,stone300,gold0,iron0,coal0 "
                        "house=food0,wood104,stone104,gold0,iron0,coal0"}
    st.update(к)
    return st

def постройки(п, st):
    вышло = SL.привести([], st, dict(п), _Пустая(), collections.Counter(), collections.Counter())
    return [(c.get("role"), c.get("total")) for c in вышло if c.get("cmd") == "BUILD"]

база = {"казарм": 2, "шахт_золота": 3}
проверить(постройки(база, снимок()) == [], f"без ключей — ни дома, ни ратуши, ни мельницы: {постройки(база, снимок())}")
проверить(("house", 3) in постройки(dict(база, дома_доля=0.15), снимок()),
          "дома_доля 0,15: свободно 50 < 60 мест — дом заранее")
проверить(("center", 2) in постройки(dict(база, ратуш=2, ратуш_с=720), снимок()), "ратуш 2 с 12:00, дерево и камень есть — вторая ратуша")
проверить(("center", 2) not in постройки(dict(база, ратуш=2, ратуш_с=720), снимок(gametime=600)), "до ратуш_с — нет")
проверить(("center", 2) not in постройки(dict(база, ратуш=2), снимок(wood=1500)), "дерева меньше цены 2100 — ратуша ждёт")
проверить(("mill", 2) in постройки(dict(база, мельниц=2, мельница_пахарей=20), снимок(on_food=22)),
          "на еде 22 ≥ 20 × 1 — вторая мельница")
проверить(("mill", 2) not in постройки(dict(база, мельниц=2, мельница_пахарей=25), снимок(on_food=22)), "на еде 22 < 25 — нет")

# 1.11: конюшня вместо второй казармы
к2 = {"казарм": 3, "шахт_золота": 3, "казарма_потолок_золота": 0}
проверить(("ba17", 2) in постройки(к2, снимок(ba17=1, gold=3000, wood=600, stone=600)), "без ключа — вторая казарма ждётся как раньше")
проверить(("ba17", 2) not in постройки(dict(к2, казарма2_после_конюшни=1), снимок(ba17=1, gold=3000, wood=600, stone=600, stables=0)),
          "казарма2_после_конюшни: конюшни нет — вторая казарма не закладывается")
проверить(("ba17", 2) in постройки(dict(к2, казарма2_после_конюшни=1), снимок(ba17=1, gold=3000, wood=600, stone=600, stables=1)),
          "конюшня стоит — вторая казарма закладывается")

print(f"\n{'ВСЁ ОК' if not ошибок else f'ОШИБОК: {ошибок}'}")
sys.exit(1 if ошибок else 0)
