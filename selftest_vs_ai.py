"""Ключ --против-ии: бот на слоте 0, ИИ на слоте 1, квитанция сверяет сложность.

ЧЕМ КУПЛЕН. 4.10 партию против нативного ИИ дважды собирали командной строкой
руками, минуя пускатель, и дважды уронили: в первый раз потерялся весь набор
флагов базы из ini (еда 998 -> 0 на 1:34, восемь крестьян из восемнадцати
умерли от голода), во второй раз взялись пушки фермы вместо настройки игрока.
Поэтому дорога против ИИ теперь одна и та же — пускатель, — а тест держит на
месте три вещи, которые руками и терялись:

  * слот бота против ИИ равен нулю (локального игрока движок сажает только туда);
  * botslot в NEW не уезжает вовсе, вместо него уезжает ai;
  * контроль квитанции ждёт ai1 той сложности, которую просили, а не «слот бота
    человеческий» — проверка партии с человеком тут была бы прямо обратной.
"""
import sys

import против_игрока as вп

ЖДЁМ_СЛОЖНОСТЬ = 3

вызовы = {}
вп.пульс = lambda игра: "живо"
вп.контроль = lambda игра, партия, против_ии=False: (
    вызовы.update(слот=партия["слот"], против_ии=против_ии) or [])


def _пуск(*ключи) -> int:
    сохр, sys.argv = sys.argv, ["против_игрока.py", "--только-проверка", *ключи]
    try:
        return вп.main()
    finally:
        sys.argv = сохр


# --- 1. Против ИИ: слот 0 и признак дошёл до контроля.
вызовы.clear()
код = _пуск("--против-ии", str(ЖДЁМ_СЛОЖНОСТЬ), "--стратегия", "sim/поиск/шт_s2.json")
assert код == 0, f"контроль не прошёл, код {код}"
assert вызовы.get("против_ии") is True, f"признак не дошёл: {вызовы}"
assert вызовы.get("слот") == 0, f"слот бота против ИИ не нуль: {вызовы}"

# --- 2. Без ключа — как было: бот на слоте из ini, признака нет.
вызовы.clear()
код = _пуск("--стратегия", "sim/поиск/шт_s2.json")
assert код == 0, f"контроль не прошёл, код {код}"
assert вызовы.get("против_ии") is False, f"признак протёк в обычный пуск: {вызовы}"
assert вызовы.get("слот") >= 1, f"слот бота против человека должен быть от 1: {вызовы}"

# --- 3. Проверка квитанции: против ИИ судят по ai1, а не по человечности слота.
#     Читаем исходник: в ветке против ИИ не должно остаться ни bot_human, ни
#     bot_ai — иначе партия с живым ИИ будет забракована своей же проверкой.
текст = open("против_игрока.py", encoding="utf-8").read()
ветка = текст.split("    if против_ии:\n        # ЧИТАЕМ, А НЕ ВЕРИМ", 1)
assert len(ветка) == 2, "ветки проверки квитанции против ИИ не нашёл"
ветка = ветка[1].split("    else:", 1)[0]
assert "ai1" in ветка, "квитанция против ИИ не сверяет ai1"
for чужое in ("bot_human", "bot_ai", "botslot"):
    assert чужое not in ветка, f"в ветке против ИИ осталась проверка {чужое}"

print(f"ХОРОШО: --против-ии сажает бота на слот 0, botslot не посылает, "
      f"а квитанцию судит по ai1 (ждём {ЖДЁМ_СЛОЖНОСТЬ} для «невозможного»)")
