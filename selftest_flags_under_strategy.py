"""Ключи базы действуют и под --strategy, а не только когда зовётся модель.

ЧЕМ КУПЛЕН ЭТОТ ТЕСТ. Живая партия 4.10 против невозможного нативного ИИ. В
строке запуска стояло `--food-floor 800 --barracks-first 1 --no-gather 1`, и ни
один из ключей не сработал: весь десяток включался внутри ветки
`if not a.replay and not a.strategy`, которая просит ключ OpenRouter — под
стратегией в неё не заходят вовсе. Еда 998 -> 0 на 1:34, восемь крестьян из
восемнадцати умерли от голода, и в логе не было ни строки про порог еды.

Молчаливый отказ равен бездействию, а проверять такое глазами нельзя: ветка
большая, и правка в ней не видна из строки запуска. Поэтому тест смотрит В
ИСХОДНИК: включения ключей базы должны стоять ДО ветки, просящей ключ модели.
"""
import re
import sys

ИСХОДНИК = "llm_policy.py"

# Ключи, меняющие поведение МОСТА, а не запрос модели: под стратегией они нужны
# ровно так же. Имя — как у поля argparse в `getattr(a, ...)`.
КЛЮЧИ = ("food_floor", "barracks_first", "no_gather", "gather_resets",
         "gather_share", "no_stable", "musk_guard", "auto_upgrade", "drain_cap",
         "stall")

ВОРОТА = re.compile(r"if not a\.replay and not getattr\(a, \"strategy\"")


def main() -> int:
    строки = open(ИСХОДНИК, encoding="utf-8").read().split("\n")

    ворота = [н for н, с in enumerate(строки, 1) if ВОРОТА.search(с)]
    if len(ворота) != 1:
        print(f"СТОП: ветку ключа модели нашёл {len(ворота)} раз, ждал один "
              "— тест устарел вместе с кодом, починить тест")
        return 1
    ворота = ворота[0]

    плохо = []
    for ключ in КЛЮЧИ:
        # Включение ищем по строке с условием: `if ... getattr(a, "<ключ>" ...`.
        где = [н for н, с in enumerate(строки, 1)
               if с.lstrip().startswith("if ") and f'getattr(a, "{ключ}"' in с]
        if not где:
            плохо.append(f"{ключ}: включения не нашёл вовсе")
            continue
        под_воротами = [н for н in где if н > ворота]
        if под_воротами:
            плохо.append(f"{ключ}: включается на строке {под_воротами[0]}, "
                         f"то есть ПОСЛЕ ветки ключа модели ({ворота}) — "
                         "под --strategy ключ молча не подействует")

    for п in плохо:
        print("СТОП:", п)
    if плохо:
        return 1
    print(f"ключи базы ({len(КЛЮЧИ)}) включаются до ветки ключа модели "
          f"(строка {ворота}) — действуют и под --strategy")
    return 0


if __name__ == "__main__":
    sys.exit(main())
