#!/usr/bin/env python3
"""КАМЕНЬ (18.10, §166): такты седьмой живой партии Д (`sim/кейсы/партия_д7_18_10_0_13-13_16.jsonl`). Вживую камень 20–380 до
11:00 при 3–6 на камне; земли 13–15 (30–38 крестьян, 10–15 в шахтах, 5–10 на стройке), на еде 2–5; золото лежало 1600–4800
при 10–15 на золоте; академии (1230 камня) не было. Игрок: камень 1780 к 3:03, академия и казарма 2 из запаса.

Ключи `нужда_по_плану` 1, `нужда_макс` 10, `золото_до_нужды` 1500 (файл партии):
(а) 9:29 (камень 100, золото 1530, казарма 2 стоит, третья недоступна): потолок нужды по плану 1330 (академия 1230 + шахта
100), золота ≥ 1500 — BALANCE gold 5 и BALANCE stone ≥ 11, запись `§166 золото лежит … stone +5` (две шахты — 10 на золоте); без ключей — золото не
трогается, камень ≤ 6; (б) 7:58 (золото 2563 ≥ цены казармы 2500, казарма ждёт) — gold 5, stone ≥ 11; 7:28 (золото 2110 <
2500) — золото не трогается; (в) 12:31 (камень 980 < 1330, золото 4179 ≥ `золото_до` 4000) — снятые идут КАМНЮ, не еде:
stone ≥ 10, записи «еде +» нет; (г) 9:29 с камнем и деревом 2000 — плана нет, золото не трогается; (д) гистерезис: 5:57
нужда включена (еда 1367), еда 1000 — держится, еда 800 — гаснет.

    python3 selftest_д7_камень.py
"""
import copy, json, os, sys, tempfile
К = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, К); sys.path.insert(0, os.path.join(К, "sim"))
os.environ.pop("COSS3_WAVE_CONTRACT", None)
import strategy_live as SL
import анализ_врага as АВ

кейс = [json.loads(l) for l in open(os.path.join(К, "sim/кейсы/партия_д7_18_10_0_13-13_16.jsonl"), encoding="utf-8")]
ошибок = 0
def проверить(усл, что):
    global ошибок
    print(("ОК   " if усл else "ОШИБКА ") + что); ошибок += not усл
БЕЗ = {"нужда_по_плану": 0, "нужда_макс": 0, "золото_до_нужды": 0}
def стратегия(доп):
    д = json.load(open(os.path.join(К, "sim/поиск/шт_s2_оборона_ручеёк_эко_так15_нужда.json"), encoding="utf-8"))
    assert д["итог"].get("нужда_по_плану") == 1 and д["итог"].get("нужда_макс") == 10 and д["итог"].get("золото_до_нужды") == 1500
    д["итог"]["бюджет_с_академией"] = 0   # §170з судит свой селфтест (д13_бюджет_академии); здесь — правило при воротах еды 1200, как жило
    # 26.10: §170п (`переброс_раз` 50 в файле партии) даёт одно перемещение за 50 с и гасит остальные приказы.
    # Здесь судятся правила ДО него — пришпиливаем к 0, как мак сделал для трёх своих.
    д["итог"]["переброс_раз"] = 0
    # 27.10: §170м (пол прокормом, добор до пола, нужда после mil.1, золото по цене) включён в файле Д17 —
    # здесь судятся правила ДО него, пришпиливаем к 0 тем же порядком.
    for _к in ("пол_прокормом", "добор_до_пола", "нужда_после_mil1", "золото_по_цене", "пачка_крестьян"):
        д["итог"][_к] = 0
    # 29.10 (ключи стока и шахты в живом файле по слову игрока): здесь судятся правила ДО них — пришпилены к 0 тем же порядком, что §170м
    for _к5 in ("сток_излишек", "золото_лежит_по_факту", "шахта_без_срока", "закладка_по_срокам", "выпущенные_в_бюджет", "переброс_по_долям"):
        д["итог"][_к5] = 0
    д["итог"].update(доп)
    with tempfile.NamedTemporaryFile("w", suffix=".json", delete=False, encoding="utf-8") as f:
        json.dump(д, f, ensure_ascii=False)
    return SL.ЖиваяСтратегия(f.name)
def при(t): return next(s for s in кейс if float(s["gametime"]) >= t)
def ответ(С, s):
    АВ._ТЕКУЩИЙ.update({"а": None, "t": None, "ответ": None}); return С.ответ(copy.deepcopy(s))
def баланс(о, роль):
    v = [c.get("total") for c in о["commands"] if c["cmd"] == "BALANCE" and c.get("role") == роль]
    return v[-1] if v else None

# (а) 9:29
s = при(569); assert int(float(s["stone"])) == 100 and int(float(s["gold"])) == 1530, (s["stone"], s["gold"])
о, о0 = ответ(стратегия({}), s), ответ(стратегия(БЕЗ), s)
проверить(баланс(о, "gold") == 5 and (баланс(о, "stone") or 0) >= 11 and "§166 золото лежит" in о["why"] and "stone +5" in о["why"],
          f"(а) 9:29 с ключами: gold {баланс(о, 'gold')}, stone {баланс(о, 'stone')}; {[x for x in о['why'].split('|') if '§166' in x][:1]}")
проверить(баланс(о0, "gold") is None and (баланс(о0, "stone") or 0) <= 6, f"(а) без ключей: gold {баланс(о0, 'gold')}, stone {баланс(о0, 'stone')}")

# (б) 7:58 и 7:28
s = при(478); assert int(float(s["gold"])) == 2563, s["gold"]
о = ответ(стратегия({}), s)
проверить(баланс(о, "gold") == 5 and (баланс(о, "stone") or 0) >= 11, f"(б) 7:58 золото 2563 ≥ 2500 казармы: gold {баланс(о, 'gold')}, stone {баланс(о, 'stone')}")
s = при(448); assert int(float(s["gold"])) == 2110, s["gold"]
о = ответ(стратегия({}), s)
проверить(баланс(о, "gold") is None and "§166 золото" not in о["why"], f"(б) 7:28 золото 2110 < 2500: золото не трогается: gold {баланс(о, 'gold')}")

# (в) 12:31
s = при(751); assert int(float(s["gold"])) == 4179 and int(float(s["stone"])) == 980
о = ответ(стратегия({}), s)
проверить(баланс(о, "gold") == 5 and (баланс(о, "stone") or 0) >= 10 and "еде +" not in о["why"] and "при нужде stone" in о["why"],
          f"(в) 12:31 золото 4179 ≥ 4000, камень 980 < 1330: снятые камню: gold {баланс(о, 'gold')}, stone {баланс(о, 'stone')}")

# (г) плана нет
s = copy.deepcopy(при(569)); s["stone"] = 2000; s["wood"] = 2000
о = ответ(стратегия({}), s)
проверить(баланс(о, "gold") is None and "§166" not in о["why"], f"(г) камень и дерево 2000: золото не трогается, §166 молчит: gold {баланс(о, 'gold')}")

# (д) гистерезис
С = стратегия({}); s = при(357); ответ(С, s)
проверить(getattr(С.стр, "_нужда_вкл", None) is True, "(д) 5:57 еда 1367: нужда включена")
s2 = copy.deepcopy(s); s2["gametime"] = 362; s2["food"] = 1000; ответ(С, s2)
проверить(getattr(С.стр, "_нужда_вкл", None) is True, "(д) еда 1000 (≥ 0,7×1200): нужда держится")
s3 = copy.deepcopy(s); s3["gametime"] = 367; s3["food"] = 800; ответ(С, s3)
проверить(getattr(С.стр, "_нужда_вкл", None) is False, "(д) еда 800 (< 840): нужда гаснет")

print(f"\nошибок: {ошибок}")
sys.exit(1 if ошибок else 0)
