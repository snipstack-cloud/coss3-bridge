# -*- coding: utf-8 -*-
"""Самопроверка строки «БОЙ У ТВОЕЙ БАЗЫ идёт против N».

Строка отвечает на мысль игрока 19.09: он шлёт к нам сотню и ставит вторую
казарму, дома у него становится двести — но бой у нашей базы примет ПЕРВАЯ
сотня и дотекание, а не двести разом. Ловушки, которые тут проверяются:

* признаков ДВА — «уже дерутся у базы» (сетка) и «идут к базе» (mv_base);
  по base20 порознь они дают 8 и 8 тактов, вместе 16 из 132, и одного мало;
* складывать их нельзя: дошедшие попадают в оба, и знаменатель удвоится;
* блок говорит ВСЕГДА (ключа нет с 19.09), поэтому стережётся не
  выключение, а молчание в мирный такт: нет ни идущих, ни дерущихся —
  нет и строки.
"""
import llm_policy as L

беды = []


def проверка(имя, условие, пояснение=""):
    if условие:
        print("  ОК    " + имя)
    else:
        беды.append(имя)
        print("  ПЛОХО " + имя + (" — " + пояснение if пояснение else ""))


def строка(army=200, mv_base=0, у_базы=0, freewar=50, ba17=2):
    """Строка обороны из situation() на синтетическом состоянии."""
    n = 16
    сетка = ["." * n for _ in range(n)]
    if у_базы:
        # Наша база в (8,8); его бойцов ставим вплотную, в радиусе у_базы().
        знак = "9" if у_базы >= 9 else str(у_базы)
        ряд = list(сетка[8])
        ряд[9] = знак
        сетка[8] = "".join(ряд)
    сост = {
        "gametime": 300, "my_cx": 8, "my_cy": 8, "grid_n": n, "map_w": 256,
        "peasants": 30, "my_freewar": freewar,
        "mil_inf": freewar, "mil_shooters": 0, "mil_cav": 0,
        "food": 2000, "gold": 500, "ba17": 2,
        # p1_enemy — без него `поле_врага` не видит слота вовсе, и вся
        # синтетика тихо меряет пустоту (поймано здесь же, 19.09).
        "p1_enemy": 1,
        "p1_army": army, "p1_inf": army, "p1_peasants": 20, "p1_ba17": ba17,
        "p1_mv_n": mv_base, "p1_mv_base": mv_base, "p1_mv_cx": 8, "p1_mv_cy": 8,
        "p1_fighters": "infantry17=hp90,atk8,wkind1,pause0,dpike3,dsword2,dbullet4",
        "fighters": "infantry17=pikeman,hp90,atk8,wkind1,pause0,dpike3,dsword2,dbullet4",
    }
    for y, ряд in enumerate(сетка):
        сост[f"frow{y}"] = ряд
        сост[f"arow{y}"] = "." * n
        сост[f"prow{y}"] = "." * n
    т = L.situation(сост, {}, [], "")
    for s in т.split("\n"):
        if "БОЙ У ТВОЕЙ БАЗЫ идёт против" in s:
            return s.strip()
    return ""


print("Самопроверка обороны:")

с = строка(mv_base=100, army=200, freewar=50)
проверка("идущие к базе дают строку", "против 100" in с, с)
проверка("вся армия названа отдельно", "армии 200" in с, с)
проверка("остальные посчитаны", "остальные 100" in с, с)
проверка("перевес против ПРИШЕДШИХ, а не против всех",
         "перевес против пришедших 0.5" in с, с)

с2 = строка(mv_base=0, у_базы=9, army=200, freewar=90)
проверка("уже дерущиеся у базы тоже дают строку",
         "уже дерутся у базы" in с2, с2 or "строки нет")

с3 = строка(mv_base=100, у_базы=9, army=200, freewar=50)
проверка("признаки НЕ складываются (иначе знаменатель удвоится)",
         "против 109" not in с3, с3)

с4 = строка(mv_base=100, army=200, freewar=50, ba17=0)
проверка("без казарм дотекания не обещаем", "ДОТЕКАНИЕ" not in с4, с4)
проверка("с казармами дотекание названо числом", "ДОТЕКАНИЕ" in с, с)

проверка("мирный такт молчит", строка(mv_base=0) == "",
         "ни идущих, ни дерущихся — строки быть не должно")

print()
if беды:
    print(f"БЕД: {len(беды)} — {', '.join(беды)}")
    raise SystemExit(1)
print("всё чисто")
