# -*- coding: utf-8 -*-
"""Самопроверка строки «ЕГО ОТРЯД N — в K клетках от твоей базы».

Наблюдение игрока 19.09: он куёт сотню, шлёт к нам и ставит вторую казарму —
дома у него двести, но у нашей базы дерётся первая сотня и дотекание, а не
двести разом.

Признак берётся ПО РАССТОЯНИЮ, а не по флагу `mv_base`: тот считает бойцов,
чья цель приказа ближе 60 единиц карты к ратуше (block_hstate.inc:968), то
есть 3,75 клетки. В живой партии 19.09 его армия дошла до 201, отряды по 21–48
стояли в 3–5 клетках с 10:27 и до конца, а `mv_base` был НОЛЬ во всех тактах.

Порог пять клеток выбран по ВРЕМЕНИ ПОДХОДА (клетка 16 единиц, пехота 2,0 в
секунду — около сорока секунд), а не по боям: за 252 такта наша армия убывала
на 3+ при своих дома всего дважды, калибровать не на чем.
"""
import llm_policy as L

беды = []


def проверка(имя, условие, пояснение=""):
    if условие:
        print("  ОК    " + имя)
    else:
        беды.append(имя)
        print("  ПЛОХО " + имя + (" — " + пояснение if пояснение else ""))


def строка(army=200, отряд=40, далеко=4, freewar=50, ba17=2):
    """Строка про его отряд. Наша база в (8,8), отряд ставим на `далеко` клеток."""
    n = 16
    arow = ["." * n for _ in range(n)]
    ряд = list(arow[8]); ряд[8] = "9"; arow[8] = "".join(ряд)     # наши у (8,8)
    frow = ["." * n for _ in range(n)]
    if отряд:
        знак = "+" if отряд >= 36 else str(min(9, отряд))
        ряд = list(frow[8]); ряд[8 + далеко] = знак; frow[8] = "".join(ряд)
    сост = {
        "gametime": 300, "grid_n": n, "map_w": 256,
        "peasants": 30, "my_freewar": freewar,
        "mil_inf": freewar, "mil_shooters": 0, "mil_cav": 0,
        "food": 2000, "gold": 500, "ba17": 2, "mills": 1,
        "p1_enemy": 1, "p1_army": army, "p1_inf": army, "p1_ba17": ba17,
        "p1_fighters": "infantry17=hp90,atk8,wkind1,pause0,dpike3,dsword2,dbullet4",
        "fighters": "infantry17=pikeman,hp90,atk8,wkind1,pause0,dpike3,dsword2,dbullet4",
    }
    for y in range(n):
        сост[f"arow{y}"] = arow[y]
        сост[f"frow{y}"] = frow[y]
        сост[f"prow{y}"] = "." * n
    for s in L.situation(сост, {}, [], "").split("\n"):
        if "ЕГО ОТРЯД" in s:
            return s.strip()
    return ""


print("Самопроверка отряда у базы:")

с = строка(army=200, отряд=40, далеко=4, freewar=50)
проверка("отряд в 4 клетках даёт строку", с != "", "порог пять клеток")
проверка("названа вся армия отдельно", "армия 200" in с or "армии 200" in с, с)
проверка("сказано, что остальные НЕ РАЗОМ", "НЕ РАЗОМ" in с, с)
проверка("перевес считается против ОТРЯДА, а не против армии",
         "против ЭТОГО отряда" in с, с)
проверка("назван срок подхода", "с хода" in с, с)

сб = строка(army=200, отряд=40, далеко=1, freewar=50)
проверка("вплотную — говорим «УЖЕ У ТВОЕЙ БАЗЫ», без срока",
         "УЖЕ У ТВОЕЙ БАЗЫ" in сб and "с хода" not in сб, сб)

сд = строка(army=200, отряд=40, далеко=7, freewar=50)
проверка("за порогом (7 клеток) молчим", сд == "", сд)

см = строка(army=200, отряд=3, далеко=3, freewar=50)
проверка("одиночки (меньше 5) не считаются отрядом", см == "", см)

сн = строка(army=0, отряд=0, далеко=4, freewar=50)
проверка("нет его армии — нет строки", сн == "", сн)

print()
if беды:
    print(f"БЕД: {len(беды)} — {', '.join(беды)}")
    raise SystemExit(1)
print("всё чисто")
