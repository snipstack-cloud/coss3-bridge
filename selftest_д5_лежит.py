#!/usr/bin/env python3
"""ЛЕЖАЩИЕ РЕСУРСЫ Д5 (13.10, §153): состояния пятой живой партии Д (`sim/кейсы/партия_д5_13_10_2_00-15_15.jsonl`).
Вживую: с 9:30 до 15:15 закладка `ba17 3` шла первой в лестнице 80 тактов подряд (третья казарма — 2500/2500/12 500,
движок: NOT ENOUGH RESOURCES), академия не заказывалась ни разу; на золоте 15 при нуле трат с 9:00 (8378 к 15:00),
дерево на троих (академия 1050/1230 недоступна до 14:04), ступени пик ждали еды.

Ключи `казарма_потолок_золота` 5000, `золото_до` 4000 / `золото_мин` 5, `нужда_по_закладке` 1:
(а) 9:04 (ba17 2, золота на третью 12 500): закладка — академия, не казарма; без ключей — `BUILD ba17 3`, как было;
(б) 12:03 (золото 4475 ≥ 4000, на золоте 15): BALANCE gold 5; снятые — на ресурс с большей недостачей до академии (§166/§167:
    дерево 320 > камень 270, еда 3307 лежит),
    без `золото_до_нужды` — еде +10; без ключей — золото не трогается;
(в) 10:00 (дерево 934 < 1050 цены академии, закладка академии ждёт): нужда — дерево 7, камень 6; без ключа
    `нужда_по_закладке` при дереве ≥ 600 нужды нет (дерево 3);
(г) 14:04 (дерево 1094 ≥ 1050, камень 1440 ≥ 1230): закладка академии, нужды по дереву нет;
(д) 3:00 (ba17 1, золото 301, вторая казарма 500/500/2500 ≤ 5000): команды с ключами и без них одинаковы.

    python3 selftest_д5_лежит.py
"""
import copy, json, os, sys, tempfile
К = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, К); sys.path.insert(0, os.path.join(К, "sim"))
os.environ.pop("COSS3_WAVE_CONTRACT", None)
import strategy_live as SL
import анализ_врага as АВ

состояния = [json.loads(l) for l in open(os.path.join(К, "sim/кейсы/партия_д5_13_10_2_00-15_15.jsonl"), encoding="utf-8")]
ошибок = 0
def проверить(усл, что):
    global ошибок
    print(("ОК   " if усл else "ОШИБКА ") + что); ошибок += not усл

def стратегия(доп):
    д = json.load(open(os.path.join(К, "sim/поиск/шт_s2_оборона_ручеёк_эко_так15_нужда.json"), encoding="utf-8"))
    # 23.10: игрок поставил `шахт_золота` 4, и четвёртая шахта встаёт раньше академии.
    # Здесь судится лестница закладок при ТРЁХ шахтах (состояния Д5), поэтому тест фиксирует ключ сам.
    д["итог"]["шахт_золота"] = 3
    # 26.10: §170п (`переброс_раз` 50 в файле партии) даёт одно перемещение за 50 с и гасит остальные приказы.
    # Здесь судятся правила ДО него — пришпиливаем к 0, как мак сделал для трёх своих.
    д["итог"]["переброс_раз"] = 0
    # 27.10: §170м (пол прокормом, добор до пола, нужда после mil.1, золото по цене) включён в файле Д17 —
    # здесь судятся правила ДО него, пришпиливаем к 0 тем же порядком.
    # 28.10: `еда_лежит` 2000 (Д18/Д19) — порог теперь от желанной ступени, без ценника равен ключу: при еде 3307 потолок уводит
    # возврат шахтёров и лишних на дерево; здесь судится §166/§169в, правило ДО него — пришпилено к 0, как пять ключей §170м
    for _к in ("пол_прокормом", "добор_до_пола", "нужда_после_mil1", "золото_по_цене", "пачка_крестьян", "еда_лежит"):
        д["итог"][_к] = 0
    # 29.10 (ключи стока и шахты в живом файле по слову игрока): здесь судятся правила ДО них — пришпилены к 0 тем же порядком, что §170м
    for _к5 in ("сток_излишек", "золото_лежит_по_факту", "шахта_без_срока", "закладка_по_срокам", "выпущенные_в_бюджет"):
        д["итог"][_к5] = 0
    д["итог"].update(доп)
    with tempfile.NamedTemporaryFile("w", suffix=".json", delete=False, encoding="utf-8") as f:
        json.dump(д, f, ensure_ascii=False)
    return SL.ЖиваяСтратегия(f.name)

def ответ(С, st):
    АВ._ТЕКУЩИЙ.update({"а": None, "t": None, "ответ": None})
    return С.ответ(copy.deepcopy(st))

def при(t):
    return next(s for s in состояния if s["gametime"] >= t)

def стройки(о):
    return [(c.get("role"), c.get("total")) for c in о["commands"] if c["cmd"] == "BUILD"]

def баланс(о, роль):
    return max([int(c.get("total") or 0) for c in о["commands"] if c["cmd"] == "BALANCE" and c.get("role") == роль] or [-1])

БЕЗ = {"казарма_потолок_золота": 0, "золото_до": 0, "нужда_по_закладке": 0}
новая, старая = стратегия({}), стратегия(БЕЗ)

st_а = при(544)
print(f"а: {st_а['gametime']} с — ba17 {st_а['ba17']}, золото {st_а['gold']}, цена ba17 {SL._цена_здания(st_а, 'ba17')}, вживую {st_а['_cmds_live']}")
о, о0 = ответ(новая, st_а), ответ(старая, st_а)
проверить(стройки(о) == [("academi", 1)], f"(а) с ключами закладка — академия: {стройки(о)}")
проверить(стройки(о0) == [("ba17", 3)], f"(а) без ключей — BUILD ba17 3, как было: {стройки(о0)}")

st_б = при(720)
print(f"б: {st_б['gametime']} с — золото {st_б['gold']}, на золоте {st_б['on_gold']}, на еде {st_б['on_food']}, шахт {st_б['mines_gold']}")
о, о0 = ответ(новая, st_б), ответ(старая, st_б)
проверить(баланс(о, "gold") == 5, f"(б) с ключами на золоте 5: {баланс(о, 'gold')}")
# §166 (18.10): при нужде по плану (камень 960 < академии 1230) и еде 3307, что лежит, снятые с золота идут КАМНЮ; еде — без `золото_до_нужды`
# §167 (18.10): бригада и снятые с золота — на ресурс с большей недостачей до закладки академии: дерево 1050 − 730 = 320 > камень 1230 − 960 = 270
_нед = {"wood": 1050 - float(st_б["wood"]), "stone": 1230 - float(st_б["stone"])}
_куда = getattr(новая.стр, "_переброс_цель", None) or max(_нед, key=_нед.get)   # §168а: цель липкая — та, что стратегия держит с (а)
# §168а (20.10): ресурсу — не сверх `нужда_доля` земли с учётом снятых, остаток еде; в сумме прибавка 10
_приб = sum(max(0, (баланс(о, r) or int(st_б["on_" + r])) - int(st_б["on_" + r])) for r in (_куда, "food"))
проверить(баланс(о, "gold") == 5 and "при нужде " + _куда in о["why"] and _приб >= 10,
          f"(б) с §166/§167/§168а снятые на {_куда} и еде (недостача {_нед[_куда]:.0f}; еда {st_б['food']} лежит): {_куда} {баланс(о, _куда)}, food {баланс(о, 'food')}, прибавка {_приб}")
о166 = ответ(стратегия({"золото_до_нужды": 0}), st_б)
проверить(баланс(о166, "food") >= int(st_б["on_food"]) + 10, f"(б) без `золото_до_нужды` — еде +10 (≥ {int(st_б['on_food']) + 10}): {баланс(о166, 'food')}")
проверить(баланс(о0, "gold") in (-1, 15), f"(б) без ключей золото не трогается: {баланс(о0, 'gold')}")

st_в = при(600)
С = стратегия({"переброс": 0}); ответ(С, при(595))          # закладка академии в памяти прошлого такта; деление §153 — без переброса §167
о = ответ(С, st_в)
С0 = стратегия({"нужда_по_закладке": 0, "нужда_по_плану": 0, "переброс": 0}); ответ(С0, при(595)); о0 = ответ(С0, st_в)   # §166 тоже поднимает потолок
print(f"в: {st_в['gametime']} с — дерево {st_в['wood']}, камень {st_в['stone']}, на дереве {st_в['on_wood']}, закладка {стройки(о)}")
проверить(баланс(о, "wood") >= 7 and баланс(о, "stone") >= 6, f"(в) нужда по цене академии: дерево {баланс(о, 'wood')}, камень {баланс(о, 'stone')}")
проверить(баланс(о0, "wood") < 7, f"(в) без `нужда_по_закладке` при дереве {st_в['wood']} ≥ 600 нужды нет: дерево {баланс(о0, 'wood')}")

st_г = при(844)
С = стратегия({}); ответ(С, при(838)); о = ответ(С, st_г)
проверить(стройки(о) == [("academi", 1)] and баланс(о, "wood") < 7, f"(г) 14:04 академия по цене доступна, нужды нет: {стройки(о)}, дерево {баланс(о, 'wood')}")

st_д = при(180)
ком = lambda о: sorted(json.dumps(c, ensure_ascii=False, sort_keys=True) for c in о["commands"])
о, о0 = ответ(стратегия({}), st_д), ответ(стратегия(БЕЗ), st_д)
проверить(ком(о) == ком(о0), f"(д) {st_д['gametime']} с (ba17 {st_д['ba17']}, золото {st_д['gold']}): команды одинаковы ({len(о['commands'])})")
print(f"ошибок: {ошибок}")
sys.exit(1 if ошибок else 0)
