# -*- coding: utf-8 -*-
"""Самопроверка боя в числах по клетке (`coss3_map.бой_по_клеткам`).

Зачем он заведён. Мост считает перевес ПО АРМИЯМ ЦЕЛИКОМ, а дерутся клетки.
[Замер] 22.09 по 330 тактам `base24` с сетками (`combat_cells.py`):

* контакт есть в 43 процентах тактов, клеток боя 206;
* в клетке боя наших медианно 13 против его 19 — перевес ПО ГОЛОВАМ 1,00
  (кв1 0,36, кв3 2,42), ниже порога 1,3 в 65 процентах контактов;
* но голова головы не равна: ER пикинёров медиана 1,43 (максимум 18), и на
  десятой минуте его атака 18 против нашей 11, апгрейдов у него 9 против наших
  4. С КАЧЕСТВОМ перевес в клетке — **0,62** (кулаком 0,79), ниже порога 70
  процентов;
* глобальный перевес в те же миги — 1,27;
* армия размазана медианно по шести клеткам;
* клеток с его крестьянами 1875, наши бойцы стояли в них 82 раза (4,4 процента),
  и стояло там медианно восьмеро.

То есть перевес, которым мост обосновывает удар, в самом бою не существует. Это
и есть механика за «убивает хоть одного крестьянина лишь каждая девятая волна».

Стережётся:
* сетка читается И из живого состояния (`frow0..frowN`), И из снимка трассы,
  где она лежит списком — иначе счёт по серии пришлось бы писать дважды;
* знаки считаются как в блоке: цифры 1-9, буквы a-z это 10-35, «+» это 36;
* контактом считается клетка, где стоят ОБЕ стороны, а не соседние;
* клетки с его крестьянами и нашими бойцами считаются отдельно: «дошли» и
  «достали крестьян» — разные вещи, и вся разница между ними в этом числе;
* в снимок идут числа, а не сетки: строка не должна вырасти на килобайт;
* качество считается тем же `combat_math.размен`, каким мост считает размен в
  промпте, а не вторым, расходящимся счётом.
"""
import json
import os
import tempfile

import coss3_map as M
import llm_policy as L

беды = []


def проверка(имя, условие, пояснение=""):
    if условие:
        print("  ОК    " + имя)
    else:
        беды.append(имя)
        print("  ПЛОХО " + имя + (" — " + str(пояснение)[:300] if пояснение else ""))


def сетка(*строки):
    """Шесть клеток в ширину, чтобы примеры читались глазами."""
    return list(строки)


# Наши: 3 бойца в (1,0) и 12 в (4,1). Его: 5 в (4,1) — там и бой.
НАШИ = сетка(".3....", "....c.")
ЕГО = сетка("......", "....5.")
КРЕСТ = сетка("......", ".....7")

живое = {"grid_n": 6}
живое.update({f"arow{y}": р for y, р in enumerate(НАШИ)})
живое.update({f"frow{y}": р for y, р in enumerate(ЕГО)})
живое.update({f"prow{y}": р for y, р in enumerate(КРЕСТ)})
из_трассы = {"grid_n": 6, "arow": НАШИ, "frow": ЕГО, "prow": КРЕСТ}

for имя, st in (("живое состояние", живое), ("снимок трассы", из_трассы)):
    бой = M.бой_по_клеткам(st)
    проверка(f"{имя}: клетка боя найдена",
             бой["клетки"] == [{"x": 4, "y": 1, "наших": 12, "его": 5}], бой["клетки"])
    проверка(f"{имя}: буква читается как число (c = 12)",
             бой["наших"] == 15, бой)
    проверка(f"{имя}: занятых нами клеток две", бой["занято_клеток"] == 2, бой)

бой = M.бой_по_клеткам(живое)
проверка("соседняя клетка с крестьянами боем не считается",
         бой["у_крестьян"] == [], бой["у_крестьян"])

# Наши пришли ТУДА, где его крестьяне
рядом = dict(живое)
рядом.update({f"arow{y}": р for y, р in enumerate(сетка(".3....", ".....4"))})
бой = M.бой_по_клеткам(рядом)
проверка("клетка «наши и его крестьяне» видна отдельно",
         бой["у_крестьян"] == [{"x": 5, "y": 1, "крестьян": 7, "наших": 4}], бой["у_крестьян"])
проверка("и боем она не считается: его бойцов там нет", бой["клетки"] == [], бой["клетки"])

# «+» — нижняя граница 36, как везде в разборе сеток
плюс = {"grid_n": 6, "arow": сетка("+.....", "......"),
        "frow": сетка("+.....", "......"), "prow": сетка("......", "......")}
бой = M.бой_по_клеткам(плюс)
проверка("знак «+» это 36 и больше",
         бой["клетки"] == [{"x": 0, "y": 0, "наших": 36, "его": 36}], бой["клетки"])

# --- КАЧЕСТВО: голова головы не равна ---------------------------------------
# Его пикинёр вдвое злее нашего: атака 16 против 8 при равной защите.
качество = dict(живое)
качество["fighters"] = "infantry17=pikeman,hp90,atk8,wkind1,pause0,dpike3,dsword2,dbullet4"
качество["p1_fighters"] = "infantry17=hp90,atk16,wkind1,pause0,dpike3,dsword2,dbullet4"
бой = M.бой_по_клеткам(качество)
к = бой["клетки"][0]
проверка("размен посчитан и он больше единицы", бой.get("размен", 0) > 1, бой.get("размен"))
проверка("перевес по головам не изменился", к["перевес"] == round(12 / 5, 2), к)
проверка("перевес с качеством НИЖЕ, чем по головам",
         к["перевес_с_качеством"] < к["перевес"], к)
проверка("кулаком мягче, чем цепочкой (корень против линейного)",
         к["перевес_с_качеством"] < к["перевес_кулаком"] < к["перевес"], к)
проверка("без данных о бойцах качество не выдумывается",
         "размен" not in M.бой_по_клеткам(живое), M.бой_по_клеткам(живое).keys())

# Пустые сетки не роняют счёт
проверка("пустое состояние не роняет разбор",
         M.бой_по_клеткам({"grid_n": 6})["клетки"] == [])

# --- СНИМОК НЕСЁТ ЧИСЛА, А НЕ СЕТКИ ----------------------------------------
class Ключи:
    def __init__(self, путь):
        self.snaplog = путь
        self.snap_every = 5


путь = os.path.join(tempfile.mkdtemp(), "с.jsonl")
состояние = dict(из_трассы, gametime=100, food=900, mil_inf=15, p1_army=5)
L.писать_снимок(Ключи(путь), состояние, {})
строка = json.loads(open(путь, encoding="utf-8").read().strip())
проверка("в снимке бой лежит числами",
         строка.get("бой") == [[4, 1, 12, 5]], строка.get("бой"))
проверка("в снимке есть разброс армии по клеткам",
         строка.get("занято_клеток") == 2, строка)
проверка("самих сеток в снимке нет",
         "arow" not in строка and "frow" not in строка and "prow" not in строка,
         list(строка))

print()
if беды:
    print(f"БЕД: {len(беды)} — {', '.join(беды)}")
    raise SystemExit(1)
print("всё чисто")
