# -*- coding: utf-8 -*-
"""Снимок СТАРШЕ предыдущего не доезжает до модели.

Повод, 22.09. Игра иногда переписывает состояние содержимым чуть более старым,
чем прошлое: mtime новее, а gametime меньше на 2-26 с. За шесть партий таких
откатов было девять, и в откатном снимке заложенная стройка ПРОПАДАЛА из wip
(2 случая из 2). Модель видела мир без стройки и заказывала её второй раз:
повтор шёл в 7 тактах из 9 после отката против 26 процентов обычных
(z=3,4, p≈0,0007). Она была права — врало состояние (правило 2 проекта).

Проверяется:
  1. обычный ход времени вперёд читается как раньше;
  2. МЕЛКИЙ откат пропускается, и счётчик его считает;
  3. КРУПНЫЙ откат (новая партия) пропускать НЕЛЬЗЯ — она тоже откатывает
     время, но на сотни секунд;
  4. после пропуска следующий свежий снимок читается нормально, то есть
     сторож не залипает.
"""
import os, sys, tempfile, time
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import coss3_bridge as B

ошибок = 0


def проверить(условие, что):
    global ошибок
    if not условие:
        ошибок += 1
        print("  СБОЙ:", что)
    else:
        print("  ок:", что)


кат = tempfile.mkdtemp(prefix="coss3_stale_")
мост = B.Bridge(кат, 0) if hasattr(B, "Bridge") else None
if мост is None:
    # имя класса могло смениться — ищем тот, у кого есть read_state
    for имя in dir(B):
        о = getattr(B, имя)
        if isinstance(о, type) and hasattr(о, "read_state"):
            мост = о(кат, 0)
            break
проверить(мост is not None, "мост создан")


def записать(gt):
    """Кладём состояние с опорными ключами и заданным временем."""
    путь = мост.state_path
    with open(путь, "w", encoding="latin-1") as f:
        f.write(f"gametime = {gt}\npeasants = 10\ncenters = 1\nvictory = 0\n")
    # mtime обязан вырасти, иначе read_state сочтёт файл уже виденным
    t = time.time() + записать.шаг
    записать.шаг += 1
    os.utime(путь, (t, t))


записать.шаг = 1

print("1. время идёт вперёд")
записать(100); проверить((мост.read_state() or {}).get("gametime") == 100, "снимок 100 прочитан")
записать(120); проверить((мост.read_state() or {}).get("gametime") == 120, "снимок 120 прочитан")

print("2. мелкий откат — пропуск")
было = мост.устаревших
записать(108)
проверить(мост.read_state() is None, "снимок 108 (откат на 12 с) пропущен")
проверить(мост.устаревших == было + 1, "счётчик устаревших вырос")

print("3. сторож не залипает — следующий свежий читается")
записать(140)
проверить((мост.read_state() or {}).get("gametime") == 140, "снимок 140 прочитан")

print("4. крупный откат — НОВАЯ ПАРТИЯ, пропускать нельзя")
было = мост.устаревших
записать(5)
взят = мост.read_state()
проверить(взят is not None and взят.get("gametime") == 5,
          "снимок 5 (новая партия) принят")
проверить(мост.устаревших == было, "счётчик устаревших не тронут")

print()
print("ошибок:", ошибок)
sys.exit(1 if ошибок else 0)
