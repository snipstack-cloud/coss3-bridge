# -*- coding: utf-8 -*-
"""Схема ответа на СОБЫТИЙНОМ вызове: строится для каждого повода, перечисляет
ровно то, что мост знает сам, и не течёт в обычный такт.

Повод, 22.09. Стенды рук и найма мерили локальные модели СО СХЕМОЙ через
/api/generate и давали 21/21 и 11/11, а мост звал их через /v1 БЕЗ схемы
(«схема ответа не просится» — умолчание): на смоуке события шли 5,6 и 6,7 с,
а прямой замер показал, что без схемы qwen2.5:7b выдумывает поля («people»,
«destination») и называет ресурс по-русски. Годность мерили в одном режиме,
играли в другом.

Что проверяется:
  1. у КАЖДОГО повода есть ключ «схема», и она строится на настоящем снимке;
  2. перечисление совпадает с тем, что мост знает: найм — КОГО_КУЕТ здания,
     запас — доступные_бойцы (тот же код, что и в вопросе), докупка — ровно
     та роль, руки — КУДА_РУКИ; и везде есть wait;
  3. поля схемы — те, которые читает разборщик ответа этого повода;
  4. ask() без параметра «схема» собирает запрос как раньше — обычный такт
     не задет (проверяется через собранные kw, без вызова сети);
  5. у формы рук допустимы обе записи: строка и список пар.
"""
import json, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import llm_policy as L

ошибок = 0


def проверить(условие, что):
    global ошибок
    if not условие:
        ошибок += 1
        print("  СБОЙ:", что)
    else:
        print("  ок:", что)


st = {"ba17": 1, "stables": 1, "gametime": 500, "food": 900, "idle_pea": 12,
      "fighters": ("infantry17=pikeman,hp90,atk8,wkind1,pause0,rmax188,dpike5,dsword4,"
                   "dbullet4,food25,gold3,iron20,coal0 "
                   "musk17=musketeernet,hp65,atk10,wkind3,pause375,rmax1500,dpike0,"
                   "dsword0,dbullet0,food50,gold8,iron4,coal3 "
                   "dragoon17=dragoon,hp220,atk15,wkind3,pause562,rmax1500,dpike0,"
                   "dsword0,dbullet0,food60,gold20,iron10,coal2")}
данные = {"найм": ("ba17", 1), "докупка": "minegold", "запас": 700, "руки": 12}

print("1. схема есть у каждого повода и строится")
схемы = {}
for повод, оп in L.ПОВОДЫ.items():
    проверить("схема" in оп, f"у повода «{повод}» есть ключ «схема»")
    if "схема" in оп:
        сх = оп["схема"](st, данные[повод])
        схемы[повод] = сх
        json.dumps(сх)                      # сериализуется — иначе в запрос не уйдёт
        проверить(сх.get("type") == "object" and "properties" in сх,
                  f"«{повод}»: схема — объект с полями")

print("2. перечисления — из таблиц моста, и везде есть wait")
def enum(сх, поле):
    п = сх["properties"][поле]
    if "enum" in п:
        return п["enum"]
    for в in п.get("anyOf", []):
        if "enum" in в:
            return в["enum"]
    return []

e = enum(схемы["найм"], "role")
проверить(set(e) == set(L.КОГО_КУЕТ["ba17"]) | {"wait"},
          f"найм: role ⊂ КОГО_КУЕТ[ba17] + wait: {e}")
e = enum(схемы["запас"], "кого")
проверить(set(e) == set(L.доступные_бойцы(st)) | {"wait"},
          f"запас: кого = доступные_бойцы + wait: {e}")
проверить("dragoon17" in e, "запас: с конюшней драгун в списке")
st_без = dict(st, stables=0)
e2 = enum(L.ПОВОДЫ["запас"]["схема"](st_без, 700), "кого")
проверить("dragoon17" not in e2, "запас: без конюшни драгуна в списке НЕТ")
e = enum(схемы["докупка"], "что")
проверить(e == ["minegold", "wait"], f"докупка: что = ровно та роль + wait: {e}")
e = enum(схемы["руки"], "куда")
проверить(set(e) == {к for к, _, _ in L.КУДА_РУКИ} | {"wait"},
          f"руки: куда = КУДА_РУКИ + wait: {e}")

print("3. поля схемы — те, что читает разборщик")
ожидание = {"найм": {"role", "total", "why"},
            "докупка": {"что", "строителей", "why"},
            "запас": {"кого", "сколько", "why"},
            "руки": {"куда", "сколько", "why"}}
for повод, поля in ожидание.items():
    проверить(set(схемы[повод]["properties"]) == поля,
              f"«{повод}»: поля {sorted(поля)}")

print("4. обычный такт схему не получает")
class _Кл:
    class chat:
        class completions:
            последний = {}
            @staticmethod
            def create(**kw):
                _Кл.chat.completions.последний = kw
                class R:
                    class choices:
                        pass
                raise RuntimeError("стоп: kw собраны, дальше сеть не нужна")
было = L.СХЕМОЙ
L.СХЕМОЙ = False
try:
    L.ask(_Кл(), "m", "p")
except RuntimeError:
    pass
kw = _Кл.chat.completions.последний
проверить("response_format" not in kw, "ask() без «схема» и без --schema: response_format не ставится")
try:
    L.ask(_Кл(), "m", "p", схема=схемы["найм"])
except RuntimeError:
    pass
kw = _Кл.chat.completions.последний
проверить(kw.get("response_format", {}).get("json_schema", {}).get("schema") is схемы["найм"],
          "ask() со «схема»: в запрос ушла ровно она")
проверить(kw["response_format"]["json_schema"]["name"] == "coss3_event",
          "имя схемы события отличимо от схемы такта")
L.СХЕМОЙ = было

print("5. руки: обе формы записи допустимы схемой")
куда = схемы["руки"]["properties"]["куда"]
варианты = куда.get("anyOf", [])
проверить(any(в.get("type") == "string" for в in варианты), "строка допустима")
проверить(any(в.get("type") == "array" for в in варианты), "список пар допустим")

print()
print("ошибок:", ошибок)
sys.exit(1 if ошибок else 0)
