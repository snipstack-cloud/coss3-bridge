# -*- coding: utf-8 -*-
"""Ключ --musk-guard: мушкетёров не пускать в клетку с его пиками (игрок, 28.09).

Правило дословно: не ставить мушкетёров в клетку, если в ней или по соседству его
пикинёров больше, чем наших мушкетёров, И они дойдут раньше, чем те успеют их
перебить. Числа второго условия: форы два залпа (дальность 15,0 против 1,9), урон
пули по его пикинёру 6 при 90 hp, то есть нужно 7,5 мушкетёра на одного пикинёра.
"""
import llm_policy as L

ошибок = []
НАШИ = ("infantry17=pikeman,hp90,atk8,wkind1,pause0,rmax188,dpike3,dsword2,dbullet4"
        " musk17=musketeernet,hp65,atk10,wkind3,pause375,rmax1500,dpike0,dsword0,dbullet0")
ЕГО = ("infantry17=hp90,atk8,wkind1,pause0,rmax188,dpike3,dsword2,dbullet4"
       " musk17=hp65,atk10,wkind3,pause375,rmax1500,dpike0,dsword0,dbullet0")

def такт(его_в_клетке, пик_доля=1.0, **кв):
    st = {"grid_n": 16, "fighters": НАШИ, "p1_fighters": ЕГО, "p1_enemy": 1,
          "p1_inf": 100 * пик_доля, "p1_shoot": 100 * (1 - пик_доля), "p1_cav": 0}
    for y in range(16):
        ряд = ["."] * 16
        if y == 5:
            ряд[5] = "9" if его_в_клетке >= 9 else str(int(его_в_клетке))
        st[f"frow{y}"] = "".join(ряд)
    st.update(кв)
    return st

# 1. ключ выключен — молчит
L.МУШКЕТЁРЫ_БЕРЕЧЬ = False
if L.мушкетёрам_нельзя(такт(9), 5, 5, 5) is not None:
    ошибок.append("выключенный ключ вмешался")

L.МУШКЕТЁРЫ_БЕРЕЧЬ = True
# 2. его пик больше наших мушкетёров и перебить не успеем — ВЕТО со числами
нет = L.мушкетёрам_нельзя(такт(9), 5, 5, 5)
if нет is None:
    ошибок.append("девять его пик против пяти мушкетёров — должно быть вето")
else:
    for ч in ("musk17", "--musk-guard"):
        if ч not in нет:
            ошибок.append(f"в отказе нет «{ч}»")
    if "залпа" not in нет:
        ошибок.append("отказ не называет фору залпов — числа, ради которых он есть")
    if "infantry17" not in нет:
        ошибок.append("отказ обязан сказать, кем идти вместо мушкетёров")

# 3. его пик МЕНЬШЕ наших мушкетёров — первое условие игрока не выполнено, пускаем
if L.мушкетёрам_нельзя(такт(3), 5, 5, 20) is not None:
    ошибок.append("три его пики против двадцати мушкетёров — вето быть не должно")

# 4. в клетке и рядом пусто — не вмешиваемся
if L.мушкетёрам_нельзя(такт(0), 5, 5, 5) is not None:
    ошибок.append("пустая клетка — вето не нужно")

# 5. соседняя клетка тоже считается: его пики в (5,5), мушкетёры идут в (5,6)
if L.мушкетёрам_нельзя(такт(9), 5, 6, 5) is None:
    ошибок.append("пики В СОСЕДНЕЙ клетке тоже запрещают — правило игрока")

# 6. далеко — не запрещаем
if L.мушкетёрам_нельзя(такт(9), 12, 12, 5) is not None:
    ошибок.append("клетка в другом углу — вето быть не должно")

# 7. у него одни СТРЕЛКИ, пик нет — правило про пики, вето быть не должно
if L.мушкетёрам_нельзя(такт(9, пик_доля=0.0), 5, 5, 5) is not None:
    ошибок.append("если у него нет пик, мушкетёрам можно")

# 8. нет чисел бойцов — молчим, а не запрещаем наугад
без = такт(9); без.pop("p1_fighters")
if L.мушкетёрам_нельзя(без, 5, 5, 5) is not None:
    ошибок.append("без чисел его бойцов вето давать нельзя")

L.МУШКЕТЁРЫ_БЕРЕЧЬ = False
print("selftest_musk_guard: " + ("ОК, 8 проверок" if not ошибок
                                 else "ОШИБКИ\n  " + "\n  ".join(ошибок)))
raise SystemExit(1 if ошибок else 0)
