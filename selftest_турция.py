# -*- coding: utf-8 -*-
"""Селфтест правила ПРОТИВ ТУРЦИИ (4.11 (204)): сторожа шахт против налётов стрелков и конных.

Проверяет:
  (1) ключ 0 — правило молчит (как было);
  (2) ключ 1 при враге НЕ Турции — молчит; при Турции (tatar/jannisary в p1_fighters) — работает;
  (3) рано или мало свободных — сторожей нет, причина сказана;
  (4) сбор: три MOVE count=12 группам 81..83 в клетку ратуши, один раз;
  (5) налёт ИДЁТ к дальней шахте (идут > 0, tx,ty у шахты) — сторож послан MOVE в клетку шахты;
  (6) шахта у ратуши не сторожится; налёт больше предела — «удар, не налёт», сторож не идёт;
  (7) поводок: его стрелки в соседней с шахтой клетке — MOVE в их клетку, не чаще `сторож_повтор`;
  (8) налёта нет `сторож_держать` с — сторож домой и снова свободен.
"""
import strategy_live as СЖ

ок, пало = 0, []


def проверить(что, имя):
    global ок
    if что:
        ок += 1
    else:
        пало.append(имя)


class Реестр:
    def __init__(self):
        import collections
        self.мера = collections.defaultdict(int)
        self.записи = []


def стратегия(ключи):
    с = СЖ.ЖиваяСтратегия.__new__(СЖ.ЖиваяСтратегия)
    с.п = dict(ключи)
    с.реестр = Реестр()
    return с


# Живой вид (проба tur_raid_pol 4.11): у ЧУЖИХ бойцов sid нет, только статы — распознавание по отпечатку здоровья
ТУРЦИЯ = ("infantry17=hp95,atk9,wkind1,pause0,rmax206 musk17=hp65,atk12,wkind3,pause469,rmax1594 "
          "uniq_inf17=hp55,atk5,wkind2 reitar=hp230,atk15 uniq_cav17=hp185,atk140,wkind6,pause469,rmax2062")
ПОЛЬША = "infantry17=hp90,atk11,wkind1 musk17=hp70,atk9,wkind3 uniq_cav17=hp190,atk9 reitar=hp225,atk14"
# Карта 256: клетка 16 единиц. Ратуша в (2,2); шахты: (3,2) — у дома, (10,10) — дальняя (центр клетки 168,168).
СОСТ = {
    "gametime": 400.0, "map_w": 256, "map_h": 256,
    "my_cx": 2, "my_cy": 2, "my_free_nosq": 120,
    "p1_fighters": ТУРЦИЯ,
    "obuild": "center,40,40,1,100;minegold,56,40,1,100;mineiron,168,168,1,100",
    "ecells": "none",
}
КЛЮЧИ = {"против_турции": 1}


def шаг(с, **изм):
    st = dict(СОСТ, **изм)
    return с._против_турции([], st)


# (1) ключ 0
с = стратегия({"против_турции": 0})
из, стр = шаг(с)
проверить(из == [] and стр == "", "(1) ключ 0 — молчит")

# (2) не Турция — молчит; Турция — работает
с = стратегия(КЛЮЧИ)
из, стр = шаг(с, p1_fighters=ПОЛЬША)
проверить(из == [] and стр == "", "(2а) враг Польша — молчит")
с = стратегия({"против_турции": 2})
из, стр = шаг(с, p1_fighters=ПОЛЬША)
проверить(len(из) == 3, "(2б) ключ 2 — работает при любой нации")

# (3) рано / мало свободных
с = стратегия(КЛЮЧИ)
из, стр = шаг(с, gametime=200.0)
проверить(из == [] and "сторожей ещё нет" in стр, "(3а) рано — причина сказана")
с = стратегия(КЛЮЧИ)
из, стр = шаг(с, my_free_nosq=50)
проверить(из == [] and "50 < 76" in стр, "(3б) мало свободных — причина с числами")

# (4) сбор
с = стратегия(КЛЮЧИ)
из, стр = шаг(с)
проверить([c["group"] for c in из] == [81, 82, 83] and all(c["count"] == 12 and c["cmd"] == "MOVE"
          and (c["cx"], c["cy"]) == (2, 2) for c in из), "(4а) три группы по 12 у ратуши")
из2, _ = шаг(с, gametime=405.0)
проверить(из2 == [], "(4б) второй раз не собирает")

# (5) налёт ИДЁТ к дальней шахте: 8 его в (13,13), 8 стрелков, идут 8 к (10,11)
НАЛЁТ = "13,13,8,0,8,0,8,10,11,0"
из, стр = шаг(с, gametime=410.0, ecells=НАЛЁТ)
проверить(len(из) == 1 and из[0]["group"] == 81 and (из[0]["cx"], из[0]["cy"]) == (10, 10) and из[0]["count"] == 0,
          "(5а) сторож 81 к шахте (10,10)")
проверить("налёт на шахту (10, 10)" in стр, "(5б) сказано вслух")
из, _ = шаг(с, gametime=412.0, ecells=НАЛЁТ)
проверить(из == [], "(5в) второй сторож на ту же шахту не идёт, поводок не раньше повтора")

# (6) шахта у дома не сторожится; большой налёт — удар
с6 = стратегия(КЛЮЧИ)
шаг(с6)
из, стр = шаг(с6, gametime=410.0, ecells="4,2,6,0,6,0,6,3,2,0")
проверить(из == [], "(6а) налёт на шахту у ратуши — не сторожим")
из, стр = шаг(с6, gametime=415.0, ecells="11,11,60,20,40,0,60,10,10,0")
проверить(из == [] and "это удар" in стр, "(6б) 60 его — удар, сторож не идёт")

# (7) поводок: его стрелки встали в (11,10) — соседняя клетка
из, стр = шаг(с, gametime=425.0, ecells="11,10,8,0,8,0,0,-1,-1,0")
проверить(len(из) == 1 and из[0]["group"] == 81 and (из[0]["cx"], из[0]["cy"]) == (11, 10), "(7а) прогнать в (11,10)")
из, _ = шаг(с, gametime=430.0, ecells="11,10,8,0,8,0,0,-1,-1,0")
проверить(из == [], "(7б) не чаще 10 с")

# (8) налёта нет 30 с — домой
из, _ = шаг(с, gametime=440.0)
проверить(из == [], "(8а) тихо 15 с — ещё держит")
из, стр = шаг(с, gametime=460.0)
проверить(len(из) == 1 and (из[0]["cx"], из[0]["cy"]) == (2, 2) and "домой" in стр, "(8б) тихо 35 с — домой")
из, _ = шаг(с, gametime=470.0, ecells=НАЛЁТ)
проверить(len(из) == 1 and из[0]["group"] == 81, "(8в) снова свободен и послан")

# (9) 4.11 (206): ФАЙЛЫ — ключи в «итог»: живая стратегия читает `w.get("итог", w)` (strategy_live.py), а (204)/(205)
#     положили их в «лучший», и обе пробы tur_raid отыграли без сторожей и без налётчика
import json
_ф = json.load(open("sim/поиск/ветка_казарма3_качели2_лес_академия2_копить_турция.json", encoding="utf-8"))
проверить(int(_ф["итог"].get("против_турции") or 0) == 1, "(9а) против_турции в итог файла _турция")
_н = json.load(open("sim/поиск/турция_налётчик_татары.json", encoding="utf-8"))
проверить(_н["итог"].get("резак_who") == "uniq_cav17" and float(_н["итог"].get("конюшня_с") or 0) > 0
          and int(_н["итог"].get("резак_крестьян") or 0) > 0, "(9б) налётчик: конюшня и резак в итог")
# (10) отпечаток на ЖИВОЙ строке из пробы (Турция) и на польской — не путать
_живая = ("infantry17=hp95,atk9,wkind1,pause0,rmax206,dmgs0,dmgp0,dinit9,dpike0,dsword0,dbullet0 musk17=hp65,atk12,wkind3,"
          "pause469,rmax1594,dmgs0,dmgp0,dinit12,dpike0,dsword0,dbullet0 uniq_inf17=hp55,atk5,wkind2,pause0,rmax94,dmgs0,dmgp0,"
          "dinit5,dpike0,dsword0,dbullet0 reitar=hp230,atk15,wkind1,pause0,rmax188,dmgs0,dmgp0,dinit15,dpike0,dsword1,dbullet0 "
          "uniq_cav17=hp185,atk140,wkind6,pause469,rmax2062,dmgs0,dmgp0,dinit140,dpike0,dsword0,dbullet0")
проверить(СЖ._враг_турция({"p1_fighters": _живая}), "(10а) живая строка Турции распознана")
проверить(not СЖ._враг_турция({"p1_fighters": ПОЛЬША}), "(10б) Польша не Турция")

# (11) 4.11 (207): пешие лучники — ключ `лучники_с`: TRAIN archer -1 с T, не чаще 60 с; who=archer доходит до моста
с11 = стратегия({"лучники_с": 240})
из, _ = с11._лучники([], {"gametime": 200.0})
проверить(из == [], "(11а) до лучники_с — молчит")
из, стр = с11._лучники([], {"gametime": 250.0})
проверить(из and из[0] == {"cmd": "TRAIN", "role": "archer", "total": -1} and "ЛУЧНИКИ" in стр, "(11б) TRAIN archer -1")
из, _ = с11._лучники([], {"gametime": 280.0})
проверить(из == [], "(11в) не чаще 60 с")
import llm_policy as LP
_р = LP.to_commands({"commands": [{"cmd": "ATTACK", "count": 10, "who": "archer", "target": "cell", "cx": 5, "cy": 5},
                                  {"cmd": "TRAIN", "role": "archer", "total": -1}]})
проверить(_р[9] == "archer" and not _р[3], "(11г) who=archer проходит в мост без брака")
проверить(_р[0] and _р[0][0].a1 == 34, "(11д) TRAIN archer — роль 34")
_р = LP.to_commands({"commands": [{"cmd": "ATTACK", "count": 10, "who": "uniq_cav17", "target": "cell", "cx": 5, "cy": 5}]})
проверить(_р[9] == "uniq_cav17", "(11е) who=uniq_cav17 больше не «иду всеми» (татары налётчика (205))")
_блок = open("block_hcmd.inc", encoding="latin-1").read()
проверить("if (hawho = 'archer') then hawrole := gc_ai_unit_archer;" in _блок, "(11ж) блок знает who=archer")

print(f"selftest_турция: {ок} из {ок + len(пало)}")
for и in пало:
    print("  ПАЛО:", и)
