# -*- coding: utf-8 -*-
"""Селфтест правила ПРОТИВ ТУРЦИИ (4.11 (204)): сторожа шахт против налётов стрелков и конных.

Проверяет:
  (1) ключ 0 — правило молчит (как было);
  (2) ключ 1 при враге НЕ Турции — молчит; при Турции (tatar/jannisary в p1_fighters) — работает;
  (3) рано или мало свободных — сторожей нет, причина сказана;
  (4) сбор: три MOVE count=12 группам 81..83 в клетку ратуши, один раз;
  (5) налёт ИДЁТ к дальней шахте (идут > 0, tx,ty у шахты) — сторож послан MOVE в клетку шахты;
  (6) шахта у ратуши не сторожится; налёт больше предела — «удар, не налёт», сторож не идёт;
  (7) поводок: его стрелки в соседней с шахтой клетке — MOVE в их клетку, не чаще `сторож_повтор`;
  (8) налёта нет `сторож_держать` с — сторож домой и снова свободен.
"""
import strategy_live as СЖ

ок, пало = 0, []


def проверить(что, имя):
    global ок
    if что:
        ок += 1
    else:
        пало.append(имя)


class Реестр:
    def __init__(self):
        import collections
        self.мера = collections.defaultdict(int)
        self.записи = []


def стратегия(ключи):
    с = СЖ.ЖиваяСтратегия.__new__(СЖ.ЖиваяСтратегия)
    с.п = dict(ключи)
    с.реестр = Реестр()
    return с


ТУРЦИЯ = "infantry17=pikemantur,hp95,atk9 musk17=jannisary,hp65,atk12 uniq_cav17=tatar,hp185,atk15"
ПОЛЬША = "infantry17=pikemanpol,hp90,atk8 musk17=musketeerpol,hp70,atk9"
# Карта 256: клетка 16 единиц. Ратуша в (2,2); шахты: (3,2) — у дома, (10,10) — дальняя (центр клетки 168,168).
СОСТ = {
    "gametime": 400.0, "map_w": 256, "map_h": 256,
    "my_cx": 2, "my_cy": 2, "my_free_nosq": 120,
    "p1_fighters": ТУРЦИЯ,
    "obuild": "center,40,40,1,100;minegold,56,40,1,100;mineiron,168,168,1,100",
    "ecells": "none",
}
КЛЮЧИ = {"против_турции": 1}


def шаг(с, **изм):
    st = dict(СОСТ, **изм)
    return с._против_турции([], st)


# (1) ключ 0
с = стратегия({"против_турции": 0})
из, стр = шаг(с)
проверить(из == [] and стр == "", "(1) ключ 0 — молчит")

# (2) не Турция — молчит; Турция — работает
с = стратегия(КЛЮЧИ)
из, стр = шаг(с, p1_fighters=ПОЛЬША)
проверить(из == [] and стр == "", "(2а) враг Польша — молчит")
с = стратегия({"против_турции": 2})
из, стр = шаг(с, p1_fighters=ПОЛЬША)
проверить(len(из) == 3, "(2б) ключ 2 — работает при любой нации")

# (3) рано / мало свободных
с = стратегия(КЛЮЧИ)
из, стр = шаг(с, gametime=200.0)
проверить(из == [] and "сторожей ещё нет" in стр, "(3а) рано — причина сказана")
с = стратегия(КЛЮЧИ)
из, стр = шаг(с, my_free_nosq=50)
проверить(из == [] and "50 < 76" in стр, "(3б) мало свободных — причина с числами")

# (4) сбор
с = стратегия(КЛЮЧИ)
из, стр = шаг(с)
проверить([c["group"] for c in из] == [81, 82, 83] and all(c["count"] == 12 and c["cmd"] == "MOVE"
          and (c["cx"], c["cy"]) == (2, 2) for c in из), "(4а) три группы по 12 у ратуши")
из2, _ = шаг(с, gametime=405.0)
проверить(из2 == [], "(4б) второй раз не собирает")

# (5) налёт ИДЁТ к дальней шахте: 8 его в (13,13), 8 стрелков, идут 8 к (10,11)
НАЛЁТ = "13,13,8,0,8,0,8,10,11,0"
из, стр = шаг(с, gametime=410.0, ecells=НАЛЁТ)
проверить(len(из) == 1 and из[0]["group"] == 81 and (из[0]["cx"], из[0]["cy"]) == (10, 10) and из[0]["count"] == 0,
          "(5а) сторож 81 к шахте (10,10)")
проверить("налёт на шахту (10, 10)" in стр, "(5б) сказано вслух")
из, _ = шаг(с, gametime=412.0, ecells=НАЛЁТ)
проверить(из == [], "(5в) второй сторож на ту же шахту не идёт, поводок не раньше повтора")

# (6) шахта у дома не сторожится; большой налёт — удар
с6 = стратегия(КЛЮЧИ)
шаг(с6)
из, стр = шаг(с6, gametime=410.0, ecells="4,2,6,0,6,0,6,3,2,0")
проверить(из == [], "(6а) налёт на шахту у ратуши — не сторожим")
из, стр = шаг(с6, gametime=415.0, ecells="11,11,60,20,40,0,60,10,10,0")
проверить(из == [] and "это удар" in стр, "(6б) 60 его — удар, сторож не идёт")

# (7) поводок: его стрелки встали в (11,10) — соседняя клетка
из, стр = шаг(с, gametime=425.0, ecells="11,10,8,0,8,0,0,-1,-1,0")
проверить(len(из) == 1 and из[0]["group"] == 81 and (из[0]["cx"], из[0]["cy"]) == (11, 10), "(7а) прогнать в (11,10)")
из, _ = шаг(с, gametime=430.0, ecells="11,10,8,0,8,0,0,-1,-1,0")
проверить(из == [], "(7б) не чаще 10 с")

# (8) налёта нет 30 с — домой
из, _ = шаг(с, gametime=440.0)
проверить(из == [], "(8а) тихо 15 с — ещё держит")
из, стр = шаг(с, gametime=460.0)
проверить(len(из) == 1 and (из[0]["cx"], из[0]["cy"]) == (2, 2) and "домой" in стр, "(8б) тихо 35 с — домой")
из, _ = шаг(с, gametime=470.0, ecells=НАЛЁТ)
проверить(len(из) == 1 and из[0]["group"] == 81, "(8в) снова свободен и послан")

print(f"selftest_турция: {ок} из {ок + len(пало)}")
for и in пало:
    print("  ПАЛО:", и)
raise SystemExit(1 if пало else 0)
