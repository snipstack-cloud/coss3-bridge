"""Сторож: `strategy_live._в_мостовые` выбирает кучу «в поле» той же меркой, что блок (5.10).

Замечание Windows к §99: выбор клетки был на одну клетку шире мерки блока — куча в соседней с ратушей
клетке считалась «в поле», и `_К_СВОИМ`/`_СТОЙ` могли указать на кучу, которую блок двигать не станет."""
import sys
import strategy_live as SL

ош = 0
st = {"my_cx": 5, "my_cy": 5, "mil_away": 20, "map_w": 256,
      "obuild": [{"тип": "center", "x": 5.5 * 16, "z": 5.5 * 16}],
      "ocells": [{"x": 5, "y": 5, "n": 30}, {"x": 6, "y": 6, "n": 40}, {"x": 9, "y": 9, "n": 20}],
      "groups": []}
р = SL._в_мостовые({"cmd": "_СТОЙ"}, "_СТОЙ", st)
# большая из куч «в поле» — (9,9) с 20, а не соседняя с домом (6,6) с 40
if not р or (р.get("cx"), р.get("cy")) != (9, 9):
    print("ПРОВАЛ: _СТОЙ выбрал не ту кучу:", р); ош += 1
st2 = dict(st, ocells=[{"x": 5, "y": 5, "n": 30}, {"x": 6, "y": 5, "n": 40}])
р2 = SL._в_мостовые({"cmd": "_СТОЙ"}, "_СТОЙ", st2)
if р2 is not None:
    print("ПРОВАЛ: куча в соседней с ратушей клетке сочтена полем:", р2); ош += 1
st3 = {k: v for k, v in st.items() if k not in ("my_cx", "my_cy")}
р3 = SL._в_мостовые({"cmd": "_СТОЙ"}, "_СТОЙ", st3)
if not р3:
    print("ПРОВАЛ: без my_cx откат к прежней мерке не сработал"); ош += 1
print(f"ошибок: {ош}")
sys.exit(1 if ош else 0)
