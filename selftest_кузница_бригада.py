#!/usr/bin/env python3
"""КУЗНИЦА ПРИ СОЗРЕВАНИИ И БРИГАДА НЕ БОЛЬШЕ ЗЕМЛИ (14.10, §156, подсказка игрока: «за несколько секунд до созревания
вывожу крестьян на поле, как созрело — сразу прокачку еды в кузнице и сразу сбор еды»). Состояния Д5
(`sim/кейсы/партия_д5_13_10_2_00-15_15.jsonl`, второй отрезок): поле созрело 2:02-2:07, у бота на еде 0 → 10 → 7 → 10 → 7:
еда 10 + камень 3 (бригада §135) + дерево 5 (с дебюта) + стройка 5 = 23 на 20 крестьян, блок брал троих с еды под камень и
с камня под еду. bla.1 (`fieldlifeperc` 100, 400 дерева, 90 золота) у бота стояла на 11:41 (`срок bla.1` 701) за mil.1.

Ключ `кузница_при_созревании` 1 (в файле партии): (а) 2:07 (поле 28, дерева 390 < 400) — ещё нет; 2:17 (дерева 418, золота 334 < 90 + 250 на
mil.1, §158) — ещё нет; при золоте 340 или купленной mil.1 — `UPGRADE bla.1` в командах; ждёт закладка за 100 дерева — нет; без `build_cost` (двойник) — нет; 2:02 (поле 0, на еде 0) —
нет; ключ 0 — нет; bla.1 в `upg_done` или `upg_doing` — нет; (б) бригада: 2:12 (еда 10, камень 0,
дерево 5) — BALANCE food 10, stone 3 и **wood 2** (земля 15 − еда 10 − бригада 3); 2:17 (камень 3, еда 7) — food 10 и wood 2,
камень не просится; сумма целей по земле ≤ 15; (в) §157 ключ `бригада_с_дерева` 5: 4:00 (дерева 950) — stone 5 с дерева,
wood 1, еда не уступает (≤ 14); ключ 0 — stone 3 с еды; 2:12 (дерева 390 < 600) — ключ молчит.

    python3 selftest_кузница_бригада.py
"""
import copy, json, os, sys, tempfile
К = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, К); sys.path.insert(0, os.path.join(К, "sim"))
os.environ.pop("COSS3_WAVE_CONTRACT", None)
import strategy_live as SL
import анализ_врага as АВ

ряд = [json.loads(l) for l in open(os.path.join(К, "sim/кейсы/партия_д5_13_10_2_00-15_15.jsonl"), encoding="utf-8")]
_сбросы = [i for i in range(1, len(ряд)) if ряд[i]["gametime"] < ряд[i - 1]["gametime"]]
ряд = ряд[_сбросы[-1]:] if _сбросы else ряд
ошибок = 0
def проверить(усл, что):
    global ошибок
    print(("ОК   " if усл else "ОШИБКА ") + что); ошибок += not усл

def стратегия(доп):
    д = json.load(open(os.path.join(К, "sim/поиск/шт_s2_оборона_ручеёк_эко_так15_нужда.json"), encoding="utf-8"))
    assert д["итог"].get("кузница_при_созревании") == 1, "в файле партии ждём кузница_при_созревании 1"
    д["итог"]["бюджет_с_академией"] = 0   # §170з судит selftest_д13_бюджет_академии; здесь — §135 при воротах еды 1200, как жило
    д["итог"].update(доп)
    with tempfile.NamedTemporaryFile("w", suffix=".json", delete=False, encoding="utf-8") as f:
        json.dump(д, f, ensure_ascii=False)
    return SL.ЖиваяСтратегия(f.name)

def ответ(С, st):
    АВ._ТЕКУЩИЙ.update({"а": None, "t": None, "ответ": None})
    return С.ответ(copy.deepcopy(st))

def при(t):
    return next(s for s in ряд if s["gametime"] >= t)

def прокачки(о):
    return [c.get("role") for c in о["commands"] if c["cmd"] == "UPGRADE"]

def балансы(о):
    return {c.get("role"): int(c.get("total") or 0) for c in о["commands"] if c["cmd"] == "BALANCE"}

st_122, st_127, st_132, st_137 = при(122), при(127), при(132), при(137)
for имя, s in (("2:02", st_122), ("2:07", st_127), ("2:12", st_132), ("2:17", st_137)):
    print(f"{имя}: поле {s['food_ready']}, еда {s['on_food']}, дерево {s['on_wood']}, камень {s['on_stone']}, стройка {s['on_build']}, "
          f"крестьян {s['peasants']}, кузниц {s.get('smiths')}, дерева {s['wood']}, взято {s['upg_done']}")

# (а) кузница при созревании
С = стратегия({})
о = ответ(С, st_127)
проверить("bla.1" not in прокачки(о) and st_127["wood"] < 400, f"(а) 2:07 поле 28, дерева {st_127['wood']} < 400: bla.1 ещё не просится: {прокачки(о)}")
о = ответ(С, st_137)
проверить("bla.1" not in прокачки(о) and st_137["gold"] < 340, f"(а) 2:17 дерева {st_137['wood']}, золота {st_137['gold']} < 90 + 250 на mil.1: bla.1 ещё не просится (§158): {прокачки(о)}")
st_137 = copy.deepcopy(st_137); st_137["gold"] = 340
о = ответ(С, st_137)
проверить("bla.1" in прокачки(о) and "mil.1" in прокачки(о), f"(а) 2:17 при золоте 340: UPGRADE bla.1 (и mil.1 по-прежнему): {прокачки(о)}")
st_м = copy.deepcopy(при(137)); st_м["upg_done"] = "mil.1,aca.25"; st_м["gold"] = 100
проверить("bla.1" in прокачки(ответ(С, st_м)), "(а) mil.1 куплена, золота 100 ≥ 90: bla.1 просится")
st_з = copy.deepcopy(st_137); С.стр._закладка_цена = {"wood": 100, "stone": 100}
проверить("bla.1" not in прокачки(ответ(С, st_з)), f"(а) ждёт закладка за 100 дерева, дерева {st_137['wood']} < 500: не просится")
С.стр._закладка_цена = None
st_б = copy.deepcopy(st_137); st_б.pop("build_cost", None)
проверить("bla.1" not in прокачки(ответ(С, st_б)), "(а) без build_cost (двойник) — не просится")
st_127 = st_137   # дальше проверки на состоянии 2:17
о = ответ(С, st_122)
проверить("bla.1" not in прокачки(о), f"(а) 2:02 поле 0, на еде 0: bla.1 не просится: {прокачки(о)}")
о = ответ(стратегия({"кузница_при_созревании": 0}), st_127)
проверить("bla.1" not in прокачки(о), f"(а) ключ 0: {прокачки(о)}")
st_в = copy.deepcopy(st_127); st_в["upg_done"] = "bla.1,aca.25"
проверить("bla.1" not in прокачки(ответ(С, st_в)), "(а) bla.1 взята — не просится")
st_и = copy.deepcopy(st_127); st_и["upg_doing"] = "bla.1"
проверить("bla.1" not in прокачки(ответ(С, st_и)), "(а) bla.1 исследуется — не просится")

# (б) бригада не больше земли
о = ответ(С, st_132); б = балансы(о)
проверить(б.get("food") == 10 and б.get("stone") == 3 and б.get("wood") == 2,
          f"(б) 2:12 еда 10, камень 0, дерево 5: food 10, stone 3, wood 2: {б}")
проверить(sum(v for k, v in б.items() if k in ("food", "wood", "stone")) <= 15, f"(б) сумма целей по земле ≤ 15: {б}")
проверить(any("§156" in k for k in С.стр.отдано), f"(б) отдано: {[k for k in С.стр.отдано if '§156' in k]}")
о = ответ(С, st_137); б = балансы(о)
проверить(б.get("food") == 10 and "stone" not in б and б.get("wood") == 2, f"(б) 2:17 камень 3 стоит: food 10, wood 2, камень не просится: {б}")
# (в) §157: бригада с дерева, когда дерево лежит — Д5 4:00 (дерева 950, камня 80, на еде 14, на дереве 5, на камне 1,
# земля 20): ключ 5 — stone 5, wood 1, еда не выше 14; ключ 0 — как было: stone 3, еда уступает (14), дереву остаток 3
st_242 = при(242)
print(f"4:00: дерева {st_242['wood']}, камня {st_242['stone']}, еда {st_242['on_food']}, дерево {st_242['on_wood']}, камень {st_242['on_stone']}, шахтёров {st_242['on_mine']}")
о = ответ(стратегия({}), st_242); б = балансы(о)
проверить(б.get("stone") == 5 and б.get("wood") == 1 and б.get("food", 14) <= 14, f"(в) ключ 5: stone 5 с дерева, wood 1, еда ≤ 14: {б}")
проверить(sum(v for k, v in б.items() if k in ("food", "wood", "stone")) <= 20, f"(в) сумма по земле ≤ 20: {б}")
о = ответ(стратегия({"бригада_с_дерева": 0}), st_242); б = балансы(о)
проверить(б.get("stone") == 3 and б.get("food") == 14, f"(в) ключ 0: stone 3, еда уступает до 14: {б}")
о = ответ(стратегия({}), st_132); б = балансы(о)
проверить(б.get("stone") == 3 and б.get("wood") == 2 and б.get("food") == 10, f"(в) 2:12 дерева 390 < 600 — ключ молчит, как §156: {б}")
print(f"ошибок: {ошибок}")
sys.exit(1 if ошибок else 0)
