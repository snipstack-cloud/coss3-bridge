"""ОДНА СИЛА И ОДНА ГЕОМЕТРИЯ (5.11, (244), ход «Г»+«В» из АРХИТЕКТУРА_РЕШЕНИЙ.md, слово игрока «давай дорабатывать»).

До этого шесть судей одного закона боя (судья обороны, ручеёк/подмога, удар готовой, выход по сроку, лагерь, отход при подходе)
собирали ЕГО силу у клетки каждый по-своему: кто с линией строя (239), кто с подходом (236), кто с лагерем анализа (§170ж), кто
с флагами охоты (239), а кто без всего — и расходились в одном такте («ЛАГЕРЬ не бьём R 0,08» и «ОГОНЬ» (219); «не бьём» и «ШТУРМ
ВСЕМ» (236); R 2,5 при 10:1 (238)). Здесь — одно место:

  * `его_у_клетки(п, st, цель, окно, …)` — его состав у клетки: клетки в `окно` + лагерь анализа (`прогноз_по_лагерю`) + линия
    строя, сцепленная с целью (`прогноз_линия`) + его подход к цели (`прогноз_его_подход`, дальность `судья_подход`);
  * `наши_у_клетки(st, цель, окно)` — наш состав по клеткам у цели (стоящие там бьются вместе с подмогой, 231);
  * `бой(п, st, цель, сила, его, свои, чужие, у_базы, окно)` — `прогноз.новая_волна` с поправкой на флаги охоты обеих сторон
    (`прогноз_по_флагам`, 239) и подписью;
  * геометрия: `расст`, `в_поле(п, st, клетка, дом)` — «поле» одной линейкой (`поле_от`, 1 = мерка блока cHmHome; 2 = РАДИУС_ДОМА
    python, чтобы боец в двух клетках не был одновременно «дома» для выхода и «сиротой» для отзыва).

Вспомогательные функции отрядов/флагов/линии/подхода переехали сюда из `strategy_live.py` без изменений (их импортирует он же).
"""


def расст(a, b) -> int:
    """Чебышёв по клеткам — одна мерка на всех (блок и python)."""
    return max(abs(int(a[0]) - int(b[0])), abs(int(a[1]) - int(b[1])))


def поле_от(п: dict) -> int:
    """С какой клетки от ратуши начинается «поле» (ключ `поле_от`; 1 — как мерка блока, было везде)."""
    try:
        return max(1, int(float((п or {}).get("поле_от", 1) or 1)))
    except (TypeError, ValueError):
        return 1


def в_поле(п: dict, клетка, дом) -> bool:
    return расст(клетка, дом) > поле_от(п)


def _отряды_из(строка) -> list:
    """Список отрядов из `squads_list`/`p<n>_squads_list` блока: uid,men,formation,cx,cy,hold,hunt,holdmode."""
    из = []
    for ч in str(строка or "").split(";"):
        f = ч.split(",")
        if len(f) < 8:
            continue
        try:
            из.append({"n": int(f[1]), "x": int(f[3]), "y": int(f[4]), "hold": int(f[5]), "hunt": int(f[6]), "holdmode": int(f[7])})
        except (TypeError, ValueError):
            continue
    return из


def _доля_без_охоты(отряды: list, цель, окно: int = 2) -> float:
    """Доля бойцов в отрядах у цели (не дальше `окно`), у которых ВЫКЛЮЧЕН поиск врага (`hunt` 0). (239) Замер по 1395 тактам контакта
    бот против бота 5.11: отряд в удержании без охоты теряет 3–7 на одного его, с охотой выигрывает 6:1 — праздный боец ищет жертву только с
    `bsearchenemy` (unit.inc/nothing.inc:181). Отрядов у цели нет — 0 (свободные бойцы с приказом удара охотятся)."""
    у = [о for о in отряды if расст((о["x"], о["y"]), цель) <= окно and о["n"] > 0]
    всего = sum(о["n"] for о in у)
    if всего <= 0:
        return 0.0
    return sum(о["n"] for о in у if not о["hunt"]) / всего


def _с_флагами(х: dict, доля: float, множ: float) -> dict:
    """Характеристики с поправкой на долю бойцов без охоты: атака × (1 − доля + доля × множ)."""
    if доля <= 0 or not х:
        return х
    k = 1.0 - доля + доля * множ
    из = {}
    for род, б in х.items():
        if isinstance(б, dict) and б.get("atk") is not None:
            б = dict(б)
            б["atk"] = max(1, int(round(float(б["atk"]) * k)))
        из[род] = б
    return из


def _его_линия(его_кл: list, цель, мин: int = 10, предел: int = 4) -> list:
    """(239) Его клетки, СЦЕПЛЕННЫЕ с клеткой цели через смежные клетки от `мин` бойцов — линия строя целиком (LINE196 на 192 стоит на
    три клетки; прогноз видел 84–99 «у цели»). Не больше `предел` клеток."""
    по = {(int(c["x"]), int(c["y"])): c for c in его_кл if float(c.get("n") or 0) >= мин}
    старт = (int(цель[0]), int(цель[1]))
    если_нет = [c for c in его_кл if расст((c["x"], c["y"]), старт) <= 1 and float(c.get("n") or 0) >= мин]
    очередь = [старт] if старт in по else [(int(c["x"]), int(c["y"])) for c in если_нет[:1]]
    видено, из = set(очередь), []
    while очередь and len(из) < предел:
        кл = очередь.pop(0)
        if кл in по:
            из.append(по[кл])
        for dx in (-1, 0, 1):
            for dy in (-1, 0, 1):
                сосед = (кл[0] + dx, кл[1] + dy)
                if сосед in по and сосед not in видено:
                    видено.add(сосед)
                    очередь.append(сосед)
    return из


def vс_ок(вс) -> bool:
    try:
        int(вс)
        return вс is not None
    except (TypeError, ValueError):
        return False


def _флаги_прогноза(п: dict, st: dict, цель, свои: dict, чужие: dict, окно: int = 2):
    """(239) Поправка прогноза по флагам отрядов у цели (ключ `прогноз_по_флагам` 1): бойцы в отрядах без охоты (`hunt` 0) бьют с
    множителем `флаг_без_охоты` (0,3) — у обеих сторон. Возвращает (свои, чужие, подпись)."""
    if not int(float(п.get("прогноз_по_флагам", 0) or 0)):
        return свои, чужие, ""
    множ = float(п.get("флаг_без_охоты", 0.3) or 0.3)
    вс = st.get("враг_слот")
    его_список = st.get(f"p{int(вс)}_squads_list") if vс_ок(вс) else None
    if его_список is None:
        его_список = st.get("p1_squads_list")
    д_н = _доля_без_охоты(_отряды_из(st.get("squads_list")), цель, окно)
    д_е = _доля_без_охоты(_отряды_из(его_список), цель, окно)
    подпись = ""
    if д_н > 0 or д_е > 0:
        подпись = " [без охоты: наших " + f"{д_н:.0%}" + ", его " + f"{д_е:.0%}" + "]"
    return _с_флагами(свои, д_н, множ), _с_флагами(чужие, д_е, множ), подпись


def _его_подход_к(его_кл: list, цель, окно: int, дальность: float) -> list:
    """(236) Его клетки, ИДУЩИЕ к цели (`идут` > 0, их цель не дальше `окно`+1 от клетки цели), стоящие дальше `окно` и не дальше
    `окно` + `дальность` от неё. Контейнер bait_pol/3 15:02–15:27: его 135–145 в (10,3) шли в (9,3), где стоял наш отряд; прогноз
    удара и подмоги видел у цели 39–95 и слал 55 → 50 → 36 → 34 им навстречу."""
    из = []
    for c in его_кл:
        try:
            if float(c.get("идут") or 0) <= 0 or c.get("tx") is None or int(c.get("tx")) < 0:
                continue
            р = расст((c["x"], c["y"]), цель)
            к_цели = расст((c["tx"], c["ty"]), цель)
            if окно < р <= окно + дальность and к_цели <= окно + 1:
                из.append(c)
        except (TypeError, ValueError):
            continue
    return из


def _его_с_лагерем(его: dict, цель, st: dict, п: dict) -> tuple:
    """§170ж (30.10, партия с Польшей): ПРОГНОЗ НЕ МЕНЬШЕ ЛАГЕРЯ. Анализ видел «ЛАГЕРЬ его 221 (пик 221) в (8,9), 4 кл. от ратуши»,
    а прогнозы удара по лагерю и ручейка считали бой с 13–82 (состав по клетке/окну, лагерь стоял шире) и давали R 3–7: 27, потом
    105 и 109 человек ушли в 221 пику и легли (потери 193 против 97). Ключ `прогноз_по_лагерю` 1: если в 2 клетках от цели есть лагерь
    анализа крупнее состава из клеток, его состав берётся по лагерю (пик/стрелков из находки, остаток — пики). 0 — как было.
    Возвращает (состав, пометка)."""
    try:
        if not int(float((п or {}).get("прогноз_по_лагерю", 0) or 0)) or цель is None:
            return его, ""
        import анализ_врага as _АВ
        находки = (_АВ.текущий(st) or {}).get("находки") or []
    except Exception:
        return его, ""
    лаг = []
    for н in находки:
        try:
            if н.get("вид") == "лагерь" and расст(н["центр"], цель) <= 2:
                лаг.append(н)
        except (TypeError, ValueError, KeyError):
            continue
    if not лаг:
        return его, ""
    л = max(лаг, key=lambda н: float(н.get("n") or 0))
    n = float(л.get("n") or 0)
    было = sum(float(v or 0) for v in (его or {}).values())
    if n <= было:
        return его, ""
    пк, ст = float(л.get("пик") or 0), float(л.get("стрелков") or 0)
    кн = max(0.0, n - пк - ст)
    if пк + ст + кн < 1:
        пк = n
    новый = {"infantry17": пк, "musk17": ст, "dragoon17": кн}
    return новый, f" (его по лагерю {n:.0f}, в клетке было {было:.0f})"


def _сложить(a: dict, b: dict) -> dict:
    return {k: float(a.get(k) or 0) + float(b.get(k) or 0) for k in set(a) | set(b)}


def его_у_клетки(п: dict, st: dict, цель, окно: int, его_кл=None, лагерь: bool = True, линия=None, подход=None,
                 подход_окно=None) -> dict:
    """ЕГО СИЛА У КЛЕТКИ — одна на всех судей. Возвращает словарь:
      состав   — {infantry17, musk17, dragoon17} = клетки в `окно` от цели (+ лагерь анализа, если больше) + линия строя + подход;
      линия    — клетки линии вне окна (список), подход — идущие к цели клетки (список), подход_n — сколько идёт;
      подпись  — « [линия +N в K кл.] [его +M на подходе к цели] (его по лагерю …)»;
      клеток_n — его бойцов в клетках окна без добавок (для сообщений).
    `линия`/`подход` None — по ключам файла (`прогноз_линия`, `прогноз_его_подход`); False — выключить для этого судьи (отход при
    подходе считает подход по времени сам). `подход_окно` — окно подхода, если не равно `окно` (судья обороны: радиус)."""
    import прогноз as ПР
    import coss3_map as _КМ
    if его_кл is None:
        его_кл = [c for c in (st.get("ecells") if isinstance(st.get("ecells"), list) else _КМ.его_клетки(st)) if isinstance(c, dict)
                  and float(c.get("n") or 0) > 0]
    цель = (int(цель[0]), int(цель[1]))
    окно = max(0, int(окно))
    состав = ПР.состав_из_клеток(его_кл, цель, окно)
    клеток_n = float(sum(состав.values()))
    подпись = ""
    if лагерь:
        состав, _пл = _его_с_лагерем(состав, цель, st, п)
        подпись += _пл
    линия_кл = []
    if (int(float(п.get("прогноз_линия", 0) or 0)) if линия is None else bool(линия)):
        линия_кл = [c for c in _его_линия(его_кл, цель) if расст((c["x"], c["y"]), цель) > окно]
        if линия_кл:
            состав = _сложить(состав, ПР.состав_из_клеток(линия_кл, None))
            подпись += f" [линия +{int(sum(float(q.get('n') or 0) for q in линия_кл))} в {len(линия_кл)} кл.]"
    подход_кл, подход_n = [], 0
    if (int(float(п.get("прогноз_его_подход", 0) or 0)) if подход is None else bool(подход)):
        подход_кл = _его_подход_к(его_кл, цель, окно if подход_окно is None else int(подход_окно), float(п.get("судья_подход", 8) or 8))
        if подход_кл:
            подход_n = int(sum(float(q.get("идут") or 0) for q in подход_кл))
            состав = _сложить(состав, ПР.состав_из_клеток(подход_кл, None))
            подпись += f" [его +{подход_n} на подходе к цели]"
    return {"состав": состав, "линия": линия_кл, "подход": подход_кл, "подход_n": подход_n, "подпись": подпись, "клеток_n": клеток_n}


def наши_у_клетки(st: dict, цель, окно: int = 2) -> dict:
    """Наш состав по клеткам (`ocells`) не дальше `окно` от цели — стоящие у цели бьются вместе с подмогой (231)."""
    import прогноз as ПР
