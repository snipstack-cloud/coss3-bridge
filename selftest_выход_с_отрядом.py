#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Селфтест (275), 6.11: слово игрока по оборванной партии — «армия дошла до базы человека, но у бота не было даже
отряда, а на базе человека была армия, и эти группки разнесли».

Числа из той партии (трасса `C:\\coss3-io-274-НЕ-В-СЧЁТ`, оборвана на 6:49):
  ВЫХОД_К: выход 1 — 13 из дома на peasants 2,12, охрана 0, ПРОГНОЗ НЕ СЧИТАН
  ВЫХОД_К: выход 2 — 20 из дома на peasants 2,12, охрана 12, R=2.34
  ОТРЯД НА ХОДУ: … FORMATION 36          <- отряд собрался ПОСЛЕ, стоял дома
  итог: my_mil_lost 17, p0_mil_lost 1 — размен 0,06

    python3 selftest_выход_с_отрядом.py
"""
import json, os, sys, tempfile
К = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, К); sys.path.insert(0, os.path.join(К, "sim"))
import strategy_live as SL
ок, пало = 0, []


def проверить(что, имя):
    global ок
    ок += 1 if что else 0
    print(("ОК   " if что else "ОШИБКА ") + имя)
    if not что:
        пало.append(имя)


def стратегия(доп=None):
    д = json.load(open(os.path.join(К, "sim/поиск/польша_судья_по_врагу.json"), encoding="utf-8"))
    д["итог"].update(доп or {})
    with tempfile.NamedTemporaryFile("w", suffix=".json", delete=False, encoding="utf-8") as f:
        json.dump(д, f, ensure_ascii=False)
    return SL.ЖиваяСтратегия(f.name)


F = ("infantry17=pikemanpol,hp90,atk9,wkind1,pause0,rmax206,dmgs1,dmgp0,dinit8,dpike0,dsword0,dbullet0,food25,gold1,iron0,coal0")
F1 = ("infantry17=hp90,atk9,wkind1,pause0,rmax206,dmgs1,dmgp0,dinit8,dpike0,dsword0,dbullet0")

# Ратуша бота в (11,13) -> obuild 184,216 при карте 256. Его база и крестьяне в (2,12) — там же его армия.
БАЗА_БОТА = "center,184,216,1,100"
# gametime 800 > `выход_к` 720 (срок похода), и сила наших выше его: иначе правило отказывает ВЫШЕ моей
# проверки — по сроку или по перевесу, — и стенд мерил бы не то (поймано первым прогоном этого же файла).
st = {"gametime": 800, "map_w": 256, "map_h": 256, "my_cx": 11, "my_cy": 13, "obuild": БАЗА_БОТА,
      "враг_слот": 1, "p1_enemy": 1, "p1_human": 1, "fighters": F, "p1_fighters": F1,
      "mil_inf": 60, "mil_shooters": 0, "my_freewar": 60, "my_held": 0, "my_insquad": 0,
      "p1_army": 30, "upg_done": "mil.1", "p1_upg_done": "mil.1",
      # цель берётся из `en_pea_cells` (список словарей) и `en_base` — имена поймал этот же стенд,
      # первым прогоном он отвечал «ни клетки крестьян, ни его базы не вижу»
      "en_base": "2,12",
      "en_pea_cells": [{"x": 2, "y": 12, "крестьян": 8, "бойцов_рядом": 30}],
      "ecells": "2,12,30,30,0,0,0,-1,-1,0", "ocells": "11,13,60,60,0,0", "cells": "",
      "squads_list": "none", "squads_list_n": 0, "my_pea_lost": 0, "p1_pea_lost": 0}


def выход(доп, st_доп=None):
    С = стратегия(доп)
    С._вк = dict(база=0.0, выходов=0, последний=None)
    из, w = С._выход_к([], dict(st, **(st_доп or {})))
    return [c for c in из if c.get("cmd") == "ATTACK" and c.get("_выход_к")], w


# (1) как было: ключ 0 — выход уходит рыхлыми, отряда нет, это и разнесли в живой партии
а, wа = выход({"выход_с_отрядом": 0})
print("  как было:", [(c["count"], c.get("target")) for c in а], "|", wа[:140])
проверить(len(а) == 1, f"(1) ключ 0 — как было: выход уходит БЕЗ отряда ({[c['count'] for c in а]}; {wа[:90]})")

# (2) ключ 1, отряда нет, цель у его базы — не выходим вслух
б, wб = выход({})
print("  с ключом:", [(c["count"], c.get("target")) for c in б], "|", wб[:200])
проверить(len(б) == 0 and "ОТРЯДА НЕТ" in wб,
          f"(2) ключ 1: отряда нет, цель у его базы — не выходим, вслух «ОТРЯДА НЕТ» ({wб[:110]})")
проверить("у его базы" in wб, f"(3) причина названа верно — цель у его базы, а не «под охраной» ({wб[:110]})")

# (4) отряд есть и крупный — выход идёт
в, wв = выход({}, {"squads_list": "1,38,SQUARE36,11,13,0,1,0,91", "squads_list_n": 1, "my_insquad": 38})
проверить(len(в) == 1, f"(4) отряд 38 ≥ 20 — выход идёт ({[c['count'] for c in в]}; {wв[:90]})")

# (5) отряд есть, но мелкий — не выходим
г, wг = выход({}, {"squads_list": "1,12,SQUARE36,11,13,0,1,0,91", "squads_list_n": 1, "my_insquad": 12})
проверить(len(г) == 0 and "крупнейший 12 < 20" in wг, f"(5) отряд 12 < 20 — не выходим, число названо ({wг[:110]})")

# (6) порог отряда ключом
д, wд = выход({"выход_отряд_мин": 10}, {"squads_list": "1,12,SQUARE36,11,13,0,1,0,91", "squads_list_n": 1, "my_insquad": 12})
проверить(len(д) == 1, f"(6) `выход_отряд_мин` 10 — отряд 12 проходит ({[c['count'] for c in д]}; {wд[:90]})")

# (7) страховка от затыка: `выход_отряд_до` вышел — выходим вслух, партия без удара не останется
С7 = стратегия({"выход_отряд_до": 100})
С7._вк = dict(база=0.0, выходов=0, последний=None, отряд_отказ=100.0)
из7, w7 = С7._выход_к([], dict(st))
проверить(len([c for c in из7 if c.get("_выход_к")]) == 1,
          f"(7) страховка: ждём дольше `выход_отряд_до` 100 с — выход идёт, затыка нет ({w7[:100]})")

# (8) страховка выключена (0) — держим сколько угодно
С8 = стратегия({"выход_отряд_до": 0})
С8._вк = dict(база=0.0, выходов=0, последний=None, отряд_отказ=0.0)
из8, w8 = С8._выход_к([], dict(st, gametime=5000))
проверить(len([c for c in из8 if c.get("_выход_к")]) == 0 and "ОТРЯДА НЕТ" in w8,
          f"(8) `выход_отряд_до` 0 — страховки нет, держим без срока ({w8[:100]})")

# (9) цель НЕ у его базы и охраны мало — ключ не вмешивается
_далеко = {"en_base": "14,1", "en_pea_cells": [{"x": 6, "y": 6, "крестьян": 4, "бойцов_рядом": 2}],
           "ecells": "6,6,2,2,0,0,0,-1,-1,0"}
е, wе = выход({}, _далеко)
проверить(len(е) == 1 or "ОТРЯДА НЕТ" not in wе,
          f"(9) цель далеко от его базы, охрана мала — ключ молчит, выход как был ({wе[:110]})")

# (10) счётчик реестра заведён — чтобы итог эпизода считал отказы, а не я грепом
С10 = стратегия()
С10._вк = dict(база=0.0, выходов=0, последний=None)
С10._выход_к([], dict(st))
проверить(С10.реестр.мера.get("выход_к: отряда нет", 0) >= 1,
          f"(10) счётчик реестра «выход_к: отряда нет» растёт ({dict(С10.реестр.мера).get('выход_к: отряда нет')})")

# (11) ключи во всех трёх польских файлах
for имя in ("польша_судья_по_врагу", "польша_академия_второй", "польша_контейнер_билд_еды"):
    д = json.load(open(os.path.join(К, "sim/поиск", имя + ".json"), encoding="utf-8"))["итог"]
    проверить(д.get("выход_с_отрядом") == 1 and д.get("выход_отряд_мин") == 20 and д.get("выход_отряд_до") == 300,
              f"(11:{имя}) ключи на месте: выход_с_отрядом 1, выход_отряд_мин 20, выход_отряд_до 300")

print(f"selftest_выход_с_отрядом: {ок} из {ок + len(пало)}")
sys.exit(1 if пало else 0)
