#!/usr/bin/env python3
"""КЛЮЧ `пики_с` (20.10): пикинёров не нанимать до секунды N — и в дебюте, и в поддержании яруса 1, живьём и в двойнике
одним кодом (`tier1.Ярус1._пики_позже`). Повод: экзамен Fable 0:48 3/3 «восемь крестьян сразу, пики не раньше поля» и
развилка хозяйства Д7 из 1:03 (крестьяне с 1:03 + пики с 2:00 → к 9:00 48/78 против 42/70, казарма 2 7:23 против 8:08).
Состояния — Д7 1:19 (казарма готова, очередь пуста) и 1:25 (бесконечный заказ пик стоит).
(а) ключ 120 при готовой казарме: дебют завершён (иначе до `пики_с` работал бы один скрипт дебюта), заказ пик снят, крестьяне (`крестьяне_сразу`) идут; (а0) до казармы дебют идёт и пик не заказывает; (б) стоит `pikeman:inf` — отдан
`TRAIN infantry17 0`, положительных заказов пик нет; (б2) повтор снятия не раньше чем через 30 с; (в) с секунды 120 заказ пик
возвращается и снятия нет; (г) без ключа дебют заказывает пики как прежде; (д) то же через `Стратегия` файла партии Д8 (в нём
`пики_с` 120 и `крестьяне_сразу` 1).
    python3 selftest_пики_с.py
"""
import copy, json, os, sys
К = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, К); sys.path.insert(0, os.path.join(К, "sim"))
import tier1 as T1
import поиск_стратегии as ПС

д7 = [json.loads(l) for l in open(os.path.join(К, "sim/кейсы/партия_д7_18_10_0_13-13_16.jsonl"), encoding="utf-8") if l.strip()]
при = lambda t: copy.deepcopy(next(s for s in д7 if s["gametime"] >= t))
ошибок = 0
def проверить(усл, что):
    global ошибок
    print(("ОК   " if усл else "ОШИБКА ") + что); ошибок += not усл

def пики(из):
    def _роль(c): return c.get("role") if "role" in c else c.get("a1")
    def _n(c): return int((c.get("total") if "total" in c else c.get("a2")) or 0)
    return [c for c in из if c.get("cmd") == "TRAIN" and _роль(c) in ("infantry17", 23) and _n(c) != 0]
def снятий(из):
    def _роль(c): return c.get("role") if "role" in c else c.get("a1")
    def _n(c): return int((c.get("total") if "total" in c else c.get("a2")) or 0)
    return [c for c in из if c.get("cmd") == "TRAIN" and _роль(c) in ("infantry17", 23) and _n(c) == 0]
def крестьяне(из):
    def _роль(c): return c.get("role") if "role" in c else c.get("a1")
    return [c for c in из if c.get("cmd") == "TRAIN" and _роль(c) in ("peasant", 1)]

# (а) дебют не готов: 1:19, бойцов 0, очередь пуста
st = при(79); st["mil_inf"] = 0; st["train_now"] = ""; st["ba_queues"] = "1:none"
я = T1.Ярус1(n=4, крестьяне_сразу=True, пики_с=120)
из = я(st)
проверить(я.дебют.готов(st), "(а) с ключом дебют кончается при готовой казарме, не дожидаясь N бойцов")
st0 = при(79); st0["mil_inf"] = 0; st0["train_now"] = ""; st0["ba_queues"] = ""; st0["ba17"] = 0
я00 = T1.Ярус1(n=4, крестьяне_сразу=True, пики_с=120)
из00 = я00(st0)
проверить(not я00.дебют.готов(st0) and not пики(из00), f"(а0) до казармы дебют идёт, пик нет: {пики(из00)}")
проверить(not пики(из), f"(а) заказ пик дебюта снят до 2:00: {пики(из)}")
проверить(bool(крестьяне(из)), f"(а) крестьяне заказаны (крестьяне_сразу): {крестьяне(из)}")
# (г) без ключа — дебют заказывает пики
я0 = T1.Ярус1(n=4, крестьяне_сразу=True)
из0 = я0(st)
проверить(bool(пики(из0)), f"(г) без ключа дебют заказывает пики: {пики(из0)}")
# (б) 1:25, стоит бесконечный заказ пик
st2 = при(85); st2["mil_inf"] = 0
из2 = я(st2)
проверить(not пики(из2) and len(снятий(из2)) == 1, f"(б) бесконечный заказ пик снимается `TRAIN infantry17 0`: {из2}")
st3 = при(90); st3["mil_inf"] = 0
из3 = я(st3)
проверить(not снятий(из3), f"(б2) повтор снятия не раньше 30 с: {снятий(из3)}")
# (в) 2:05 — пики возвращаются
st4 = при(125); st4["mil_inf"] = 0; st4["train_now"] = "peaeng:inf"; st4["ba_queues"] = "1:none"
из4 = я(st4)
проверить(bool(пики(из4)) and not снятий(из4), f"(в) с 2:00 заказ пик есть, снятия нет: {из4}")
# (д) через Стратегию файла партии Д8
п = json.load(open(os.path.join(К, "sim/поиск/шт_s2_оборона_ручеёк_эко_так15_нужда.json"), encoding="utf-8"))["итог"]
проверить(п.get("пики_с") == 120 and п.get("крестьяне_сразу") == 1, "(д) в файле Д8 пики_с 120 и крестьяне_сразу 1")
С = ПС.Стратегия(п)
изд = С(copy.deepcopy(st2))
проверить(not пики(изд) and len(снятий(изд)) == 1, f"(д) Стратегия в 1:25: пик нет, снятие одно: {[c for c in изд if c.get('cmd') == 'TRAIN']}")
изд4 = С(copy.deepcopy(st4))
проверить(bool(пики(изд4)), f"(д) Стратегия в 2:05: пики заказаны: {[c for c in изд4 if c.get('cmd') == 'TRAIN']}")
print("ИТОГ:", "чисто" if not ошибок else f"ошибок {ошибок}")
sys.exit(1 if ошибок else 0)
