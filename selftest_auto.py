# -*- coding: utf-8 -*-
"""Самопроверка механических команд, которые ставит МОСТ, а не модель.

Счёт по 734 тактам четырёх серий 20.09 показал, что три команды решения почти
не несут и измеримо портятся оттого, что их отдаёт модель:

* `SEED` — 188 приказов, 98 процентов при УЖЕ созревших участках, 38 процентов
  повторены в пределах 25 секунд, а каждое поле стоит 5 золота;
* `BUILDERS` — 26 приказов без `BUILD` в том же такте пропали впустую (блок
  читает потолок только вместе с закладкой), 54 закладки ушли с потолком по
  умолчанию 3;
* `TRAIN` — 99 процентов это бесконечный заказ, и в 4 процентах тактов с едой
  выше порога крестьян не куёт никто.

Стережётся то, что дороже всего ошибиться: мост НЕ вмешивается, когда не надо,
и ГОВОРИТ вслух, когда вмешался (правило 1 проекта — молчаливое действие
неотличимо от бездействия).

Отдельно стережётся копилка вмешательств: до 20.09 четыре места писали
`вмешательство = принуждение = ...`, и второе за такт стирало первое.
"""
import types
import llm_policy as L

беды = []


def проверка(имя, условие, пояснение=""):
    if условие:
        print("  ОК    " + имя)
    else:
        беды.append(имя)
        print("  ПЛОХО " + имя + (" — " + пояснение if пояснение else ""))


def прогон(st, cmds, **ключи):
    """Кусок такта: применить механические правила и вернуть (команды, сказанное).

    Повторяет логику из основного цикла ровно теми же условиями. Дублирование
    намеренное: тянуть сюда весь цикл нельзя, а проверять правила нужно.
    """
    a = types.SimpleNamespace(auto_seed=0, auto_builders=0, auto_train=0)
    for k, v in ключи.items():
        setattr(a, k, v)
    gt = int(float(st.get("gametime") or 0))
    сказано = []
    cmds = list(cmds)

    if a.auto_seed:
        мельниц = L._чис(st.get("mills"))
        гот = st.get("food_ready")
        гот = int(float(гот)) if гот is not None else None
        сам = any(c.cmd == "SEED" for c in cmds)
        когда = L.ПОСЕВ.get("t")
        свежо = когда is not None and (gt - когда) < L.СОЗРЕВАНИЕ_С / 2
        if сам:
            L.ПОСЕВ["t"] = gt
            if гот is not None and гот > 0 and свежо:
                cmds = [c for c in cmds if c.cmd != "SEED"]
                сказано.append("SEED СНЯТ")
        elif мельниц > 0 and гот == 0 and not свежо:
            cmds.append(L.seed())
            L.ПОСЕВ["t"] = gt
            сказано.append("SEED ПОСТАВЛЕН")

    if a.auto_builders:
        есть_build = any(c.cmd == "BUILD" for c in cmds)
        есть_cap = any(c.cmd == "BUILDERS" for c in cmds)
        if есть_cap and not есть_build:
            cmds = [c for c in cmds if c.cmd != "BUILDERS"]
            сказано.append("BUILDERS СНЯТ")
        elif есть_build and not есть_cap:
            cmds.insert(0, L.builders(a.auto_builders))
            сказано.append("BUILDERS ПОСТАВЛЕН")

    if a.auto_train:
        еда = L._чис(st.get("food"))
        оч = str(st.get("train_now") or "")
        сам = any(c.cmd == "TRAIN" for c in cmds)
        if еда >= 500 and "pea" not in оч and not сам:
            cmds.append(L.train("peasant", L.INFINITE))
            сказано.append("TRAIN ПОСТАВЛЕН")
    return cmds, сказано


def имена(cmds):
    return [c.cmd for c in cmds]


# --- SEED ------------------------------------------------------------------
L.ПОСЕВ.clear()
c, ск = прогон({"gametime": 300, "mills": 1, "food_ready": 0}, [], auto_seed=1)
проверка("выкошенное поле засевается", "SEED" in имена(c) and ск == ["SEED ПОСТАВЛЕН"])

c, ск = прогон({"gametime": 320, "mills": 1, "food_ready": 0}, [], auto_seed=1)
проверка("повтор через 20 с не идёт", "SEED" not in имена(c) and not ск,
         "поле не вырастет быстрее, а стоит 5 золота")

c, ск = прогон({"gametime": 420, "mills": 1, "food_ready": 0}, [], auto_seed=1)
проверка("через полный срок сеем снова", "SEED" in имена(c))

L.ПОСЕВ.clear()
c, ск = прогон({"gametime": 300, "mills": 1, "food_ready": 12}, [], auto_seed=1)
проверка("при созревших участках мост не сеет", not ск)

L.ПОСЕВ.clear()
c, ск = прогон({"gametime": 300, "mills": 0, "food_ready": 0}, [], auto_seed=1)
проверка("без мельницы не сеем", not ск, "блок ответит «no mill built»")

L.ПОСЕВ.clear()
прогон({"gametime": 300, "mills": 1, "food_ready": 5}, [L.seed()], auto_seed=1)
c, ск = прогон({"gametime": 310, "mills": 1, "food_ready": 5}, [L.seed()], auto_seed=1)
проверка("повтор МОДЕЛИ при созревших участках снимается",
         "SEED" not in имена(c) and ск == ["SEED СНЯТ"])

L.ПОСЕВ.clear()
c, ск = прогон({"gametime": 300, "mills": 1, "food_ready": 0}, [L.seed()], auto_seed=1)
проверка("посев модели по делу НЕ трогаем", "SEED" in имена(c) and not ск)

L.ПОСЕВ.clear()
c, ск = прогон({"gametime": 300, "mills": 1, "food_ready": 0}, [], auto_seed=0)
проверка("с выключенным ключом мост молчит", not ск and not имена(c))

# --- BUILDERS --------------------------------------------------------------
c, ск = прогон({}, [L.build("mill", 1)], auto_builders=10)
проверка("закладке без потолка потолок ставится",
         имена(c) == ["BUILDERS", "BUILD"] and ск == ["BUILDERS ПОСТАВЛЕН"],
         "и ПЕРВЫМ в списке: блок исполняет по порядку")
проверка("потолок ровно тот, что в ключе", c[0].a1 == 10)

c, ск = прогон({}, [L.builders(4)], auto_builders=10)
проверка("потолок без закладки снимается", not имена(c) and ск == ["BUILDERS СНЯТ"],
         "блок читает BUILDERS только вместе с BUILD")

c, ск = прогон({}, [L.builders(4), L.build("mill", 1)], auto_builders=10)
проверка("свой потолок модели не трогаем", имена(c) == ["BUILDERS", "BUILD"] and not ск)
проверка("и число остаётся её", c[0].a1 == 4)

# --- TRAIN -----------------------------------------------------------------
c, ск = прогон({"food": 900, "train_now": ""}, [], auto_train=1)
проверка("еда есть, очередь пуста — заказ ставится",
         имена(c) == ["TRAIN"] and ск == ["TRAIN ПОСТАВЛЕН"])
проверка("заказ БЕСКОНЕЧНЫЙ", c[0].a2 == L.INFINITE,
         "конечный заказ оставляет потолок «один за раз»")

c, ск = прогон({"food": 400, "train_now": ""}, [], auto_train=1)
проверка("ниже порога 500 не заказываем", not ск, "движок всё равно погасит найм")

c, ск = прогон({"food": 900, "train_now": "peasant:1"}, [], auto_train=1)
проверка("крестьяне уже куются — не вмешиваемся", not ск)

c, ск = прогон({"food": 900, "train_now": ""}, [L.train("infantry17", -1)], auto_train=1)
проверка("модель заказала своё — не перебиваем", not ск)

# --- копилка вмешательств --------------------------------------------------
import re
код = open("llm_policy.py", encoding="utf-8").read()
проверка("ни одного затирающего присваивания не осталось",
         not re.search(r"вмешательство = принуждение = \(", код),
         "второе вмешательство за такт стирало первое")
проверка("копилка есть и склеивает через «; »",
         'вмешательство = (вмешательство + "; " if вмешательство else "") + текст' in код)

print()
if беды:
    print(f"БЕД: {len(беды)} — {', '.join(беды)}")
    raise SystemExit(1)
print("всё чисто")
