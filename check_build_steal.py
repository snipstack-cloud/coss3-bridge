"""Живая проверка правки: отнимает ли новая закладка строителей у недостроя.

Повторяем ровно ту ситуацию, что дала base10: ратуша строится тремя, свободных
крестьян не остаётся, и закладывается второе здание. До правки на следующем же
такте у ратуши становилось 0 строителей.
"""
import sys, time
import coss3_bridge as B

ИГРА = r"C:\Program Files (x86)\Steam\steamapps\common\Cossacks 3"
br = B.Bridge(ИГРА, 0)


def стройки(st):
    """wip -> {роль: (строителей, процент)}"""
    из = {}
    for кус in str(st.get("wip", "") or "").split(","):
        ч = кус.split("/")
        if len(ч) == 4:
            из[ч[0]] = (int(ч[2]), ч[3])
    return из


def ждать(секунд=25):
    st = br.wait_state(timeout=секунд)
    return st


def шаг(подпись, команды=None):
    if команды:
        while not br.send(команды):
            time.sleep(0.4)
        br.wait_consumed(timeout=15)
    st = ждать()
    с = стройки(st)
    print("  %-34s gt %4s | свободных %-3s | стройки: %s"
          % (подпись, st.get("gametime"), st.get("idle_pea"),
             ", ".join("%s %d строителей %s%%" % (к, v[0], v[1]) for к, v in с.items()) or "нет"))
    return st, с


print("== живая проверка: закладка не должна обнулять строителей ==")
st = ждать(40)
print("  партия идёт, крестьян", st.get("peasants"))

шаг("ставлю ратушу тремя", [B.build("center", 1), B.builders(3)])
for _ in range(3):
    st, с = шаг("жду")
    if с.get("center", (0,))[0] > 0:
        break

# Занимаем ВСЕХ, чтобы свободных не осталось — как было в base10
# Забиваем ВСЕХ: пока idle_pea не станет 0, изменённая ветка не сработает.
for _ in range(6):
    st, _с = шаг("гоню всех на ресурсы",
                 [B.balance("food", 30), B.balance("wood", 20), B.balance("stone", 20)])
    if int(float(st.get("idle_pea", 0) or 0)) == 0:
        break
st, до = шаг("проверяю перед закладкой")
было = до.get("center", (0, "?"))
print("  ДО закладки: у ратуши %d строителей, %s%%" % было)

шаг("ЗАКЛАДЫВАЮ мельницу", [B.build("mill", 1)])
st, после = шаг("сразу после")
st, после = шаг("такт спустя")

стало = после.get("center", (0, "?"))
print()
print("  было %d строителей -> стало %d" % (было[0], стало[0]))
if было[0] > 0 and стало[0] == 0:
    print("  ПРОВАЛ: закладка по-прежнему снимает строителей с недостроя")
    sys.exit(1)
if было[0] > 0 and стало[0] >= было[0]:
    print("  ОК: недострой сохранил своих строителей")
    sys.exit(0)
print("  НЕОДНОЗНАЧНО: ратуша могла достроиться сама, смотреть проценты выше")
sys.exit(2)
