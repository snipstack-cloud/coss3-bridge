# -*- coding: utf-8 -*-
"""ЧЕСТНАЯ ПЛАНКА СБОРА: `--gather-share`.

Повод, 23.09, счёт по `base27` — 55 тактов марша за четыре партии, УДАР НЕ
СЛУЧИЛСЯ НИ РАЗУ (53 такта в фазе «сбор», 2 «истёк»). Две причины, обе числом.

  1. `послано` НАКАПЛИВАЕТ ОДНИХ И ТЕХ ЖЕ бойцов: каждый ATTACK во время сбора
     считается примыканием и прибавляет своё число заново. Дошло до 2916 при
     живой армии 305 — планка 1944 при дошедших 108.
  2. Две трети недостижимы и БЕЗ двойного счёта: у клетки сбора стоит
     медианно 41 процент войска, максимум 70 (счёт по сетке `arow`).

По тем же 55 тактам: при доле 1/3 удар состоялся бы в 16, при 1/2 — в 2, при
2/3 — в нуле.

Что проверяется:
  1. ключ есть, по умолчанию 0 — поведение прежнее;
  2. при 0 планка считается как раньше: 2/3 от накопленного «послано»;
  3. при доле планка берёт ПОТОЛОК по живой армии — двойной счёт не проходит;
  4. когда послано меньше армии, потолок не мешает;
  5. когда армии в состоянии нет вовсе, правило не падает и не обнуляет планку.
"""
import os, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import llm_policy as L

ошибок = 0


def проверить(условие, что):
    global ошибок
    if not условие:
        ошибок += 1
        print("  СБОЙ:", что)
    else:
        print("  ок:", что)


def планка(послано, армия, доля):
    """Та же арифметика, что в шаге марша, — через настоящий модуль."""
    было = L.ПЛАНКА_ЧЕСТНАЯ
    L.ПЛАНКА_ЧЕСТНАЯ = доля
    st = {"mil_inf": армия, "mil_shooters": 0, "mil_cav": 0}
    try:
        _доля = L.ПЛАНКА_ЧЕСТНАЯ
        if _доля > 0:
            _армия = sum(L._чис(st.get(k)) for k in ("mil_inf", "mil_shooters", "mil_cav"))
            _база = min(послано, _армия) if _армия else послано
            return max(1, int(_доля * _база))
        return max(1, int(L.ДОЛЯ_СБОРА * послано))
    finally:
        L.ПЛАНКА_ЧЕСТНАЯ = было


ИСХОДНИК = open(os.path.join(os.path.dirname(os.path.abspath(__file__)),
                             "llm_policy.py"), encoding="utf-8").read()

print("1. ключ заведён и выключен по умолчанию")
проверить('"--gather-share"' in ИСХОДНИК, "ключ --gather-share есть")
проверить(re.search(r'--gather-share",\s*type=float,\s*default=0\.0', ИСХОДНИК) is not None,
          "по умолчанию 0.0 — прежние плечи не задеты")
проверить(L.ПЛАНКА_ЧЕСТНАЯ == 0.0, "глобальная доля выключена, пока ключ не задан")
проверить("ПЛАНКА_ЧЕСТНАЯ" in ИСХОДНИК.split("надо = max(1, int(ДОЛЯ_СБОРА")[0],
          "планка читает глобаль, а не выдуманный объект ключей")

# Проверка считает ту же арифметику своими руками, поэтому ОБЯЗАНА
# убедиться, что в мосту стоит ровно она: иначе тест проверял бы копию.
проверить('_база = min(МАРШ["послано"], _армия) if _армия else МАРШ["послано"]' in ИСХОДНИК,
          "в мосту планка берёт min(послано, живая армия)")
проверить('надо = max(1, int(_доля * _база))' in ИСХОДНИК,
          "и умножает на долю ровно так же, как считает тест")

print("2. при нуле — как было")
проверить(планка(2916, 305, 0) == int(2 / 3 * 2916),
          "2/3 от накопленного «послано» (%d)" % int(2 / 3 * 2916))

print("3. при доле — потолок по живой армии")
проверить(планка(2916, 305, 1 / 3) == int(305 / 3),
          "случай base27: 2916 послано при армии 305 -> планка %d, а не 1944" % int(305 / 3))
проверить(планка(2916, 305, 1 / 3) < 108,
          "дошедшие 108 ТЕПЕРЬ БЕРУТ планку — раньше 1944 не брались никогда")

print("4. когда послано меньше армии, потолок не мешает")
проверить(планка(44, 300, 1 / 3) == int(44 / 3),
          "планка считается от посланных: %d" % int(44 / 3))

print("5. армии в состоянии нет — не падаем и не обнуляем")
было = L.ПЛАНКА_ЧЕСТНАЯ
L.ПЛАНКА_ЧЕСТНАЯ = 1 / 3
st = {}
_армия = sum(L._чис(st.get(k)) for k in ("mil_inf", "mil_shooters", "mil_cav"))
_база = min(90, _армия) if _армия else 90
L.ПЛАНКА_ЧЕСТНАЯ = было
проверить(_база == 90 and max(1, int(_база / 3)) == 30,
          "без армии в снимке планка берётся от посланных, а не становится единицей")

print()
print("ошибок:", ошибок)
sys.exit(1 if ошибок else 0)
