# -*- coding: utf-8 -*-
"""Самопроверка частого снимка состояния (`--snap-every`).

Зачем он. Трасса `coss3_bot.jsonl` пишется РАЗ В ТАКТ, а такт идёт медианно раз
в 21 игровую секунду, в десятой части случаев раз в 46 и дольше (максимум 107 —
[замер] 22.09 по 464 тактам `base24`). Игра переписывает состояние КАЖДУЮ
СЕКУНДУ: в отчётах прогонов стоит «медиана 1,2 с, записей 1033» против полусотни
тактов за партию. Девятнадцать двадцатых данных выбрасывались.

Чего это стоило, померено в тот же день: гибель волны не прогнозируется вовсе
(поймано 8 эпизодов из 89), провал еды под порог ловится хуже тупого правила, а
любой счёт по партии — простой крестьян, время под порогом — считается по трём
точкам на минуту.

Стережётся:
* снимок пишется в СВОЙ файл. Все инструменты проекта считают тактом любую
  запись с полем `state`; подмешай снимки в общую трассу — и каждый замер в
  проекте молча начнёт мерить другое;
* шаг соблюдается по ИГРОВОМУ времени, а не по реальному;
* новая партия (игровое время упало) пишется сразу, а не через шаг;
* при `--snap-every 0` не пишется ничего;
* в строке только числа из белого списка: карты и цены сделали бы файл
  мегабайтным;
* ошибка записи не роняет партию.
"""
import json
import os
import tempfile

import llm_policy as L

беды = []


def проверка(имя, условие, пояснение=""):
    if условие:
        print("  ОК    " + имя)
    else:
        беды.append(имя)
        print("  ПЛОХО " + имя + (" — " + str(пояснение)[:300] if пояснение else ""))


class Ключи:
    def __init__(self, путь, каждые=5):
        self.snaplog = путь
        self.snap_every = каждые


def состояние(gt, **правки):
    ст = {"gametime": gt, "food": 900, "gold": 1000, "peasants": 30, "idle_pea": 4,
          "mil_inf": 20, "mil_away": 0, "p1_peasants": 40, "p1_army": 12,
          # то, чего в белом списке нет и быть не должно
          "arow": ["................"] * 16, "fighters": "infantry17=pikeman,hp90",
          "build_cost": "center=food0,wood700", "en_pea_cells": [{"x": 1, "y": 2}]}
    ст.update(правки)
    return ст


каталог = tempfile.mkdtemp()
путь = os.path.join(каталог, "снимок.jsonl")
a = Ключи(путь)
когда: dict = {}

L.писать_снимок(a, состояние(100), когда)
L.писать_снимок(a, состояние(102), когда)      # раньше шага — молчим
L.писать_снимок(a, состояние(105), когда)      # ровно шаг — пишем
L.писать_снимок(a, состояние(109), когда)      # снова рано
L.писать_снимок(a, состояние(130), когда)
строки = [json.loads(s) for s in open(путь, encoding="utf-8") if s.strip()]
проверка("шаг считается по игровому времени",
         [с["gametime"] for с in строки] == [100, 105, 130], строки)

L.писать_снимок(a, состояние(7), когда)        # новая партия: время упало
строки = [json.loads(s) for s in open(путь, encoding="utf-8") if s.strip()]
проверка("новая партия пишется сразу, а не через шаг",
         [с["gametime"] for с in строки][-1] == 7, строки[-1])

проверка("в строке только числа белого списка",
         all(к in L.ПОЛЯ_СНИМКА for к in строки[0]) and "arow" not in строки[0]
         and "fighters" not in строки[0] and "en_pea_cells" not in строки[0],
         list(строки[0]))
проверка("числа пришли числами, а не строками",
         all(isinstance(v, (int, float)) for v in строки[0].values()), строки[0])

# выключено — не пишем
путь2 = os.path.join(каталог, "выкл.jsonl")
L.писать_снимок(Ключи(путь2, каждые=0), состояние(200), {})
проверка("при --snap-every 0 файла не появляется", not os.path.exists(путь2))

# пустой путь тоже не пишет и не падает
L.писать_снимок(Ключи("", каждые=5), состояние(200), {})
проверка("без пути молчим и не падаем", True)

# запись в каталог, которого нет: партия не должна упасть
L.писать_снимок(Ключи(os.path.join(каталог, "нет_такого", "с.jsonl")), состояние(300), {})
проверка("ошибка записи не роняет партию", True)

# ВЕС: партия 20 минут при шаге 5 с — это 240 строк
путь3 = os.path.join(каталог, "вес.jsonl")
a3, к3 = Ключи(путь3), {}
for i in range(240):
    L.писать_снимок(a3, состояние(5 * i, food=900 + i, gold=1000 + 7 * i), к3)
вес = os.path.getsize(путь3)
проверка(f"вес партии в пределах разумного: {вес // 1024} КБ на 240 снимков",
         вес < 400 * 1024, вес)

# ПОЛЯ ПОТЕРЬ, ради которых всё и затевалось (добавлены 21.09, в трассах их нет)
проверка("поля потерь по счёту движка в белом списке",
         all(к in L.ПОЛЯ_СНИМКА for к in
             ("my_pea_lost", "my_mil_lost", "p1_pea_lost", "p1_mil_lost")))

# ТОЧНЫЕ КЛЕТКИ КОНТАКТА В СНИМКЕ (27.09, просьба мака). Сетка упирается в 61
# даже с двумя алфавитами, а решающий бой шёл при 194 против 36 в одной клетке.
# Трасса такие числа с 26.09 несёт, но она есть лишь в тактах с облаком —
# у идеи без облака в дебюте её там нет ПО ПОСТРОЕНИЮ (ловушка счёта 25.09).
путь4 = os.path.join(каталог, "клетки.jsonl")
a4, к4 = Ключи(путь4), {}
L.писать_снимок(a4, состояние(400, cells="12,13,194,36,0;3,4,7,0,15", cells_n=2), к4)
L.писать_снимок(a4, состояние(500, cells="none", cells_n=0), к4)
L.писать_снимок(a4, состояние(600), к4)                 # старый мост: поля нет
строки4 = [json.loads(s) for s in open(путь4, encoding="utf-8") if s.strip()]
проверка("точные числа клеток доехали БЕЗ потолка",
         строки4[0].get("cells") == [{"x": 12, "y": 13, "наших": 194, "его": 36,
                                      "крестьян": 0},
                                     {"x": 3, "y": 4, "наших": 7, "его": 0,
                                      "крестьян": 15}], строки4[0].get("cells"))
проверка("форма та же, что в трассе — список словарей",
         all(isinstance(к, dict) for к in строки4[0]["cells"]))
проверка("cells_n пришло числом", строки4[0].get("cells_n") == 2, строки4[0])
проверка("измеренный ноль отличим от отсутствия поля: none -> пустой список",
         строки4[1].get("cells") == [] and "cells" in строки4[1], строки4[1])
проверка("старый мост: ключа нет вовсе, а не пустой список",
         "cells" not in строки4[2] and "cells_n" not in строки4[2], строки4[2])

# ВЕС с клетками: 12 клеток на строку — потолок блока, худший случай
путь5 = os.path.join(каталог, "вес_клетки.jsonl")
клетки12 = ";".join(f"{i},{i},199,199,99" for i in range(12))
a5, к5 = Ключи(путь5), {}
for i in range(240):
    L.писать_снимок(a5, состояние(5 * i, cells=клетки12, cells_n=12), к5)
вес5 = os.path.getsize(путь5)
проверка(f"вес с клетками в худшем случае: {вес5 // 1024} КБ на 240 снимков",
         вес5 < 500 * 1024, вес5)

print()
if беды:
    print(f"БЕД: {len(беды)} — {', '.join(беды)}")
    raise SystemExit(1)
print("всё чисто")
