# -*- coding: utf-8 -*-
"""Потери в трассе: накопительно И за такт.

Повод, 23.09. Поле потерь в трассе есть с 20.09 и лежит в «потери», но это
НАКОПИТЕЛЬНЫЙ счётчик движка с начала партии. Я прочитал его как потери за
такт, сложил по тактам и получил 11432 убитых при пике армии 191 — после чего
объявил поле сломанным и записал «мера риска не считается» в итог плеча
`gather`. Поле было цело; неверным было действие.

Правильный счёт по тем же трассам: своих бойцов 782 у плеча против 789 у базы
(риск малых волн не подтвердился), крестьян врага 48 против 121.

Чтобы ошибка не повторилась, рядом кладётся «потери_такт» — разница с прошлым
тактом, посчитанная один раз и в мосту.

Что проверяется:
  1. оба поля есть в записи трассы и названы по-разному;
  2. разница считается по всем четырём счётчикам;
  3. ОТКАТ ВНИЗ (новая партия) даёт НОЛЬ, а не отрицательное число;
  4. пустой счётчик (старый блок, None) не роняет счёт;
  5. память прошлого такта обновляется только непустыми значениями.
"""
import io, os, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import llm_policy as L

ошибок = 0


def проверить(условие, что):
    global ошибок
    if not условие:
        ошибок += 1
        print("  СБОЙ:", что)
    else:
        print("  ок:", что)


И = io.open(os.path.join(os.path.dirname(os.path.abspath(__file__)),
                         "llm_policy.py"), encoding="utf-8").read()

print("1. оба поля в записи трассы")
проверить('"потери": _пот,' in И, "накопительное «потери» на месте")
проверить('"потери_такт": _пот_такт,' in И, "рядом «потери_такт»")
проверить("ПОТЕРИ_БЫЛО" in И, "память прошлого такта заведена")


def разница(сейчас, было):
    """Та же формула, что в мосту (проверяется ниже, что она та же)."""
    L.ПОТЕРИ_БЫЛО.clear()
    L.ПОТЕРИ_БЫЛО.update({к: в for к, в in было.items() if в is not None})
    return {к: max(0, (сейчас.get(к) or 0) - (L.ПОТЕРИ_БЫЛО.get(к) or 0))
            for к in ("en_pea", "en_mil", "my_pea", "my_mil")}


проверить('к: max(0, (_пот.get(к) or 0) - (ПОТЕРИ_БЫЛО.get(к) or 0))' in И,
          "в мосту формула ровно та, что проверяет тест")

print("2. разница по всем четырём счётчикам")
д = разница({"en_pea": 12, "en_mil": 40, "my_pea": 1, "my_mil": 30},
            {"en_pea": 10, "en_mil": 33, "my_pea": 1, "my_mil": 25})
проверить(д == {"en_pea": 2, "en_mil": 7, "my_pea": 0, "my_mil": 5},
          f"за такт: {д}")

print("3. откат вниз — новая партия, а не отрицательные потери")
д = разница({"en_pea": 0, "en_mil": 0, "my_pea": 0, "my_mil": 0},
            {"en_pea": 42, "en_mil": 71, "my_pea": 11, "my_mil": 217})
проверить(all(в == 0 for в in д.values()),
          "после NEW счётчики обнулились — разница ноль, а не минус двести")

print("4. пустой счётчик старого блока не роняет счёт")
д = разница({"en_pea": None, "en_mil": None, "my_pea": None, "my_mil": None},
            {"en_pea": 5, "en_mil": 5, "my_pea": 0, "my_mil": 0})
проверить(all(в == 0 for в in д.values()), "None читается как ноль")

print("5. память обновляется только непустыми")
L.ПОТЕРИ_БЫЛО.clear()
L.ПОТЕРИ_БЫЛО.update({"my_mil": 100})
L.ПОТЕРИ_БЫЛО.update({к: в for к, в in {"my_mil": None, "en_pea": 7}.items()
                      if в is not None})
проверить(L.ПОТЕРИ_БЫЛО.get("my_mil") == 100 and L.ПОТЕРИ_БЫЛО.get("en_pea") == 7,
          "None не затирает прежнее число")
L.ПОТЕРИ_БЫЛО.clear()

print()
print("ошибок:", ошибок)
sys.exit(1 if ошибок else 0)
