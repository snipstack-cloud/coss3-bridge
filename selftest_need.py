# -*- coding: utf-8 -*-
"""Самопроверка цены труда: сколько даёт ОДИН поставленный человек.

Замысел игрока 21.09 по калькулятору производственных функций: в формуле моста
не было члена расхода C_r вовсе. `net` — это уже случившееся изменение запаса, а
предельной отдачи труда («поставлю сюда одного — станет на столько больше») мост
не говорил НИГДЕ, ни в такте, ни в вопросе «куда людей».

Чем это подтверждено до правки ([замер] 21.09 по 9 партиям `base24`, 464 такта):

* простой есть в 422 тактах из 464, это 12,5 процента всего труда крестьян;
* в 100 процентах крестьяно-секунд простоя поставить их БЫЛО КУДА — дерево и
  камень открыты во всех 422 тактах, то есть места не кончались никогда;
* при этом на дереве стоял НОЛЬ человек в 28,8 процента этого времени, на камне
  в 23,8, а 13,2 процента простоя пришлось на такты, где еда УЖЕ провалилась под
  порог 500 и наём стоял целиком.

Числа отдачи взяты замером, а не из головы: по 202 окнам `base24`, где в обоих
концах окна `wip` пуст (значит дерево и камень никуда не тратились), дерево даёт
0,96 в секунду на человека (половины набора 0,97 и 0,95), камень 1,07 (1,05 и
1,12). Еда тем же счётом НЕ БЕРЁТСЯ — чистых окон остаётся 17 и половины
расходятся вдвое, — поэтому про неё мост говорит «?».

КОЛОНКИ РАСХОДА ЗДЕСЬ НЕТ, и это решено замером, а не вкусом. Первая редакция
считала расход как добыча минус чистое изменение запаса. [Замер] по 414 тактам
`base24`: у дерева он выходит ОТРИЦАТЕЛЬНЫМ в 39 процентах тактов, у камня в 43,
медиана расхода к добыче у обоих около нуля — дерево и камень почти не тратятся,
и разность двух близких чисел меряет там не расход, а погрешность отдачи. У
золота и железа расход настоящий, но сверх `net` не говорит ничего: расход минус
добыча — это ровно минус `net`.

Стережётся:
* без ключа не меняется ни один знак: ни в такте, ни в таблице события;
* колонка одна — `per_man`, и расход в неё не возвращается;
* неизвестное остаётся «?» и не подменяется нулём;
* шахтные числа согласованы с ДОБЫЧА_НА_ЧЕЛОВЕКА (замер 18.09), а не заведены
  вторым, расходящимся замером;
* узкое место называется по нехватке добычи и переводится в ЧИСЛО ЛЮДЕЙ.
"""
import llm_policy as L

беды = []


def проверка(имя, условие, пояснение=""):
    if условие:
        print("  ОК    " + имя)
    else:
        беды.append(имя)
        print("  ПЛОХО " + имя + (" — " + str(пояснение)[:400] if пояснение else ""))


def состояние(**правки):
    ст = {
        "gametime": 600, "peasants": 40, "idle_pea": 5, "on_build": 0,
        "on_food": 10, "on_wood": 5, "on_stone": 3,
        "on_gold": 5, "on_iron": 0, "on_coal": 0,
        "food": 900, "wood": 300, "stone": 200, "gold": 1000,
        "iron": 50, "coal": 0,
        "mills": 1, "food_ready": 4, "centers": 1, "ba17": 1,
        "mines_gold": 1, "mines_iron": 0, "mines_coal": 0,
        "cap_gold": 15, "cap_iron": 0, "cap_coal": 0,
        "wood_slots_free": 100, "stone_slots_free": 100,
    }
    ст.update(правки)
    return ст


БЫЛО = {"gametime": 560, "food": 800, "wood": 280, "stone": 180,
        "gold": 900, "iron": 50, "coal": 0}


def история():
    """Своя история прихода для вопроса «куда людей» — окно 20-90 с."""
    return [(560.0, {"food": 800.0, "wood": 280.0, "stone": 180.0,
                     "gold": 900.0, "iron": 50.0, "coal": 0.0})]


def запрос(нужда):
    L.ПОКАЗ_РАСХОДА = 1 if нужда else 0
    L.РЕСУРСЫ_РУК[:] = история()
    try:
        return L.запрос_рук(состояние(), {}, 5)
    finally:
        L.ПОКАЗ_РАСХОДА = 0


# --- БЕЗ КЛЮЧА МОЛЧИМ -------------------------------------------------------
без = запрос(False)
проверка("без ключа заголовок таблицы прежний",
         "resource,stock,workers,max_add,net\n" in без + "\n", без.splitlines()[1])
проверка("без ключа колонок расхода нет",
         "spend" not in без and "per_man" not in без, без)
проверка("без ключа системный текст прежний",
         L.система_рук() == L.SYSTEM_РУКИ)
L.ПОКАЗ_РАСХОДА = 0
проверка("без ключа блока в такте нет",
         L.цена_труда(состояние(), БЫЛО) == [])

# --- С КЛЮЧОМ -------------------------------------------------------------
с_ключом = запрос(True)
строки = {с.split(",")[0]: с.split(",") for с in с_ключом.splitlines() if "," in с}
проверка("с ключом заголовок вырос на одну колонку",
         "resource,stock,workers,max_add,net,per_man" in с_ключом,
         с_ключом.splitlines()[1])
проверка("колонки расхода нет: она отменена замером", "spend" not in с_ключом, с_ключом)
проверка("дерево: отдача одного 0.96", строки["wood"][-1] == "0.96", строки.get("wood"))
проверка("камень: отдача одного 1.07", строки["stone"][-1] == "1.07", строки.get("stone"))
проверка("золото: отдача из замера шахт (98 в минуту)",
         строки["gold"][-1] == f"{L.ДОБЫЧА_НА_ЧЕЛОВЕКА['gold'] / 60:.2f}", строки.get("gold"))
проверка("еда: отдача не замерена, стоит «?», а не ноль",
         строки["food"][-1] == "?", строки.get("food"))
L.ПОКАЗ_РАСХОДА = 1
проверка("с ключом системный текст объясняет колонку и счёт в людях",
         "per_man" in L.система_рук() and "не замерено" in L.система_рук()
         and "ЛЮДЯХ" in L.система_рук(), L.система_рук()[-300:])
L.ПОКАЗ_РАСХОДА = 0

# --- ЧИСЛА САМОЙ ФОРМУЛЫ ---------------------------------------------------
таблица = L.отдача_труда(состояние())
отдача, добыча = таблица["wood"]
проверка("добыча считается по людям и отдаче",
         abs(добыча - 5 * 0.96) < 1e-9, таблица["wood"])
проверка("у еды отдача неизвестна", таблица["food"] == (None, None), таблица["food"])
проверка("шахтные числа согласованы с замером 18.09",
         abs(таблица["gold"][0] - L.ДОБЫЧА_НА_ЧЕЛОВЕКА["gold"] / 60) < 1e-9, таблица["gold"])

# --- БЛОК ОБЫЧНОГО ТАКТА ---------------------------------------------------
L.ПОКАЗ_РАСХОДА = 1
блок = "\n".join(L.цена_труда(состояние(), БЫЛО))
проверка("в такте есть заголовок блока", "Цена одного человека" in блок, блок)
проверка("в такте сказано, что число замерено", "замер по отыгранным партиям" in блок, блок)
проверка("шахты, которой нет, в блоке нет", "железо:" not in блок and "уголь:" not in блок, блок)
проверка("в такте назван один человек числом",
         "ОДИН здесь даёт 0.96" in блок, блок)
проверка("про еду сказано, что отдача не замерена",
         "НЕ ЗАМЕРЕНО" in блок, блок)
# Нехватка переводится в людей: дерева было 280, стало 180 за 40 с — минус 2,5
# в секунду, при отдаче 0,96 это три человека.
просадка = "\n".join(L.цена_труда(состояние(wood=180), БЫЛО))
проверка("падение запаса переведено в число людей",
         "дерево УБЫВАЕТ" in просадка and "это 3 человека на нём" in просадка, просадка)
проверка("при растущих запасах убыли не выдумывается", "УБЫВАЕТ" not in блок, блок)
# Ни одной строки, если такт первый: сравнивать не с чем.
проверка("без прошлого состояния блок молчит", L.цена_труда(состояние(), None) == [])
проверка("при нулевом шаге времени блок молчит",
         L.цена_труда(состояние(), dict(БЫЛО, gametime=600)) == [])
L.ПОКАЗ_РАСХОДА = 0

# --- ОБСТАНОВКА ЦЕЛИКОМ ----------------------------------------------------
L.ПОКАЗ_РАСХОДА = 1
об = L.situation(состояние(), {}, [], "", было=БЫЛО)
проверка("блок доезжает до обстановки", "Цена одного человека" in об)
L.ПОКАЗ_РАСХОДА = 0
об2 = L.situation(состояние(), {}, [], "", было=БЫЛО)
проверка("без ключа обстановка прежняя", "Цена одного человека" not in об2)

print()
if беды:
    print(f"БЕД: {len(беды)} — {', '.join(беды)}")
    raise SystemExit(1)
print("всё чисто")
