# -*- coding: utf-8 -*-
"""Признаки решения «атаковать или обороняться».

Просьба игрока 27.09: «по сути в большинстве партий решение об атаке главное в
игре, после него восстановиться очень трудно». Он перечислил, из чего это решение
складывается: сколько его армии и где, как она растянута, какие у неё прокачки, в
строю она или нет, через сколько подойдёт его подкрепление, дойдёт ли моя атака,
есть ли у меня отряд, какая у меня армия и прокачки.

Модуль считает то, что можно посчитать из уже приходящих данных, ОДИНАКОВО для
моста и для симулятора: растянутость его армии, темп его подкрепления и сколько
его успеет подойти, пока идёт наша волна. Числа с источниками:

* КЛЕТКА = 16 единиц карты [код dmscript.global: 53,3333 пикселя на клетку,
  сетка моста 16 единиц на клетку];
* марш 1,1 единицы в секунду [замер живой игры: 136 единиц за 122 с] —
  14,5 с на клетку;
* его производство: 7,3 бойца в минуту при ОДНОЙ казарме и 23,7 при двух
  [замер 27.09 по 78 записям, 10 327 и 4 087 окон по 3 минуты]. Не 2×, потому что
  две казармы бывают позже и при других ресурсах — это оценка по факту, а не модель.

Мост этими числами НЕ РЕШАЕТ: он их называет, решает модель (правило проекта).
"""

ЕДИНИЦ_В_КЛЕТКЕ = 16.0
МАРШ_ЕД_В_СЕК = 1.1
СЕК_НА_КЛЕТКУ = ЕДИНИЦ_В_КЛЕТКЕ / МАРШ_ЕД_В_СЕК          # 14,5 с
ПРОИЗВОДСТВО_ПО_КАЗАРМАМ = {0: 0.0, 1: 7.3, 2: 23.7}     # бойцов в минуту [замер]


def растяжение(сетка) -> dict:
    """Как разбросана армия по клеткам сетки.

    `сетка` — список списков чисел (или None). Возвращает: сколько всего,
    в скольких клетках, сколько в самой большой и её доля. Доля 1,0 — вся армия в
    одной клетке (кулак), 0,2 — растянута по пяти клеткам поровну.
    """
    if not сетка:
        return {"всего": 0.0, "клеток": 0, "в_максимуме": 0.0, "доля_в_максимуме": 0.0}
    значения = [float(v) for ряд in сетка for v in (ряд or []) if float(v or 0) > 0]
    всего = sum(значения)
    макс = max(значения) if значения else 0.0
    return {"всего": всего, "клеток": len(значения), "в_максимуме": макс,
            "доля_в_максимуме": (макс / всего) if всего > 0 else 0.0}


def подкрепление_в_мин(казарм) -> float:
    """Сколько бойцов в минуту он делает при таком числе казарм [замер]."""
    try:
        n = int(float(казарм or 0))
    except (TypeError, ValueError):
        return 0.0
    if n <= 0:
        return 0.0
    if n in ПРОИЗВОДСТВО_ПО_КАЗАРМАМ:
        return ПРОИЗВОДСТВО_ПО_КАЗАРМАМ[n]
    # выше двух не мерено: продолжаем линейно от второй, честно вниз
    return ПРОИЗВОДСТВО_ПО_КАЗАРМАМ[2] + (n - 2) * (ПРОИЗВОДСТВО_ПО_КАЗАРМАМ[2] - ПРОИЗВОДСТВО_ПО_КАЗАРМАМ[1])


def марш_секунды(расстояние_клеток) -> float:
    """Сколько секунд идти столько клеток [замер марша]."""
    try:
        d = float(расстояние_клеток or 0)
    except (TypeError, ValueError):
        return 0.0
    return max(d, 0.0) * СЕК_НА_КЛЕТКУ


def подкрепления_к_приходу(казарм, секунды) -> float:
    """Сколько он успеет сделать, пока наша волна идёт."""
    return подкрепление_в_мин(казарм) * max(float(секунды or 0), 0.0) / 60.0


def решение(наших, сетка_его, казарм_его, расстояние_клеток, его_строй=0, наш_строй=0) -> dict:
    """Все признаки решения об атаке в одном словаре.

    `перевес_сейчас` — наших на одного его в целевой клетке; `перевес_к_приходу` —
    то же с учётом того, что он успеет донабрать, пока мы идём. Решения тут нет:
    только числа.
    """
    р = растяжение(сетка_его)
    сек = марш_секунды(расстояние_клеток)
    добавит = подкрепления_к_приходу(казарм_его, сек)
    в_клетке = р["в_максимуме"]
    наших = float(наших or 0)
    return {
        "его_всего": р["всего"], "его_клеток": р["клеток"],
        "его_в_клетке": в_клетке, "его_кулаком": р["доля_в_максимуме"],
        "марш_сек": сек, "он_добавит": добавит,
        "перевес_сейчас": (наших / в_клетке) if в_клетке > 0 else (наших and 99.0 or 0.0),
        "перевес_к_приходу": (наших / (в_клетке + добавит)) if (в_клетке + добавит) > 0 else (наших and 99.0 or 0.0),
        "его_строй": float(его_строй or 0), "наш_строй": float(наш_строй or 0),
    }
