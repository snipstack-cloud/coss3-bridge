# -*- coding: utf-8 -*-
"""Что волны СДЕЛАЛИ: доля убийственных, подходы и резерв, стоящий дома.

`series_report.py` считает партии, `idle_report.py` — простой крестьян. Про
армию не считал никто, а именно там 21.09 нашлось узкое место: армии у нас
больше, чем у врага, волн за партию два десятка, а крестьян врага убито за
партию единицы.

Меряется по ВОЛНАМ, а не по партиям, и это не придирка: волн на девять партий
двести с лишним, и доля убийственных отличима, тогда как по девяти партиям
такое тонет в разбросе.

Что печатается:
  * волн (такт с `attack` больше нуля) и сколько из них убили хоть одного
    крестьянина врага за 90 игровых секунд. У `base24` — 25 из 218, это 11
    процентов;
  * то же отдельно для волн, при которых армия РЕАЛЬНО ушла от базы: у базы 20
    из 121 = 17 процентов против 5 у оставшихся. Дойти решает;
  * подходы (переход `mil_far` через порог) и сколько СВОБОДНЫХ БОЙЦОВ стояло
    дома в этот миг: у базы медиана 40, максимум 123 — это и есть цена молчания;
  * убито крестьян врага за партию (сумма падений их числа): у базы медиана 7.

    python3 wave_report.py <каталог идеи> [<каталог базы>]
"""
import glob
import json
import os
import statistics as S
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import llm_policy as L

ОКНО = 90.0          # за сколько секунд после волны подводить итог
УШЛА = 150.0         # mil_far, при котором считаем, что армия реально ушла


def ч(v):
    try:
        return float(v)
    except (TypeError, ValueError):
        return 0.0


def партии(корень):
    for файл in sorted(glob.glob(f"{корень}/**/coss3_bot.jsonl", recursive=True)):
        текущая = []
        for строка in open(файл, encoding="utf-8"):
            строка = строка.strip()
            if not строка:
                continue
            x = json.loads(строка)
            if "finish" in x:
                if текущая:
                    yield текущая
                текущая = []
                continue
            if isinstance(x.get("state"), dict) and "gametime" in x["state"]:
                текущая.append(x)
        if текущая:
            yield текущая


def разбор(корень):
    волн = ушли = уб_всего = уб_ушли = 0
    подходов, дома_в_подход, убито_за_партию, партий = 0, [], [], 0
    for такты in партии(корень):
        партий += 1
        счёт: dict = {}
        крест = [ч(т["state"].get("p1_peasants")) for т in такты]
        убито_за_партию.append(sum(max(0.0, a - b) for a, b in zip(крест, крест[1:])))
        for i, т in enumerate(такты):
            st = т["state"]
            if L.волна_дошла(st, счёт, 1):
                подходов += 1
                дома_в_подход.append(ч(st.get("my_freewar")))
            if ч(т.get("attack")) <= 0:
                continue
            t0 = ч(st["gametime"])
            окно = [x["state"] for x in такты[i + 1:]
                    if ч(x["state"]["gametime"]) - t0 <= ОКНО]
            if not окно:
                continue
            волн += 1
            убила = ч(st.get("p1_peasants")) > min(ч(x.get("p1_peasants")) for x in окно)
            уб_всего += int(убила)
            if any(ч(x.get("mil_far")) >= УШЛА and ч(x.get("mil_away")) > 0 for x in окно):
                ушли += 1
                уб_ушли += int(убила)
    if not волн:
        print(f"{корень}: волн не нашлось")
        return None
    print(f"\n{корень}: партий {партий}")
    print(f"  волн с замеренным итогом: {волн}; убили хоть одного крестьянина "
          f"{уб_всего} ({100 * уб_всего / волн:.0f}%)")
    print(f"    из них армия реально ушла: {ушли}, убийственных {уб_ушли} "
          f"({100 * уб_ушли / max(ушли, 1):.0f}%); осталась дома: {волн - ушли}, "
          f"убийственных {уб_всего - уб_ушли} "
          f"({100 * (уб_всего - уб_ушли) / max(волн - ушли, 1):.0f}%)")
    print(f"  подходов к базе врага: {подходов} ({подходов / партий:.1f} за партию)")
    if дома_в_подход:
        print(f"    свободных бойцов ДОМА в этот миг: медиана "
              f"{S.median(дома_в_подход):.0f}, максимум {max(дома_в_подход):.0f}")
    print(f"  убито крестьян врага за партию: медиана {S.median(убито_за_партию):.0f} "
          f"(разброс {min(убито_за_партию):.0f}-{max(убито_за_партию):.0f})")
    return {"волн": волн, "доля": 100 * уб_всего / волн,
            "дома": S.median(дома_в_подход) if дома_в_подход else None,
            "убито": S.median(убито_за_партию)}


def main():
    if len(sys.argv) < 2:
        raise SystemExit(__doc__)
    идея = разбор(sys.argv[1])
    база = разбор(sys.argv[2]) if len(sys.argv) > 2 else None
    if идея and база:
        print("\nРАЗНИЦА (идея минус база):")
        print(f"  доля убийственных волн: {идея['доля']:.0f}% против {база['доля']:.0f}% "
              f"({идея['доля'] - база['доля']:+.0f} пунктов)")
        print(f"  убито крестьян за партию: {идея['убито']:.0f} против {база['убито']:.0f}")
        if идея["дома"] is not None and база["дома"] is not None:
            print(f"  свободных дома в миг подхода: {идея['дома']:.0f} против "
                  f"{база['дома']:.0f} — должно УПАСТЬ, если подкрепление идёт")
        print("  Волн на девять партий около двух сотен, и доля отличима; "
              "числа по партиям (убито) остаются наблюдением.")


if __name__ == "__main__":
    main()
