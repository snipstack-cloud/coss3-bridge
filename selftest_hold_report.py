# -*- coding: utf-8 -*-
"""РАЗБОР УДЕРЖАНИЯ (§102): мера «стреляют ли держащие» по трассе любой партии.

Решение игрока 5.10: отдельную партию под этот вопрос не ставить — померить
первой же, где оборона понадобится по делу. Значит мера обязана сниматься САМА,
и обязана отличать два разных нуля:

  * ноль убийств ПРИ КОНТАКТЕ — это и есть плохой ответ, которого боялся мак:
    держащие стрелки не стреляют;
  * ноль убийств БЕЗ КОНТАКТА — это не ответ вовсе. Первая партия §102 дала
    именно его: группа держала 17 снимков в нашем тылу, враг не подошёл, и если
    бы разбор молча написал «убийств ноль», мы бы записали ложный вывод.

И третий ложный вывод, найденный уже на живом файле (7.10): удержание ЧУЖОЙ
партии. Файл снимков дописывается партия за партией, а `id` группы действителен
только внутри одной партии — поэтому разбор обязан мерить последний эпизод, а не
весь файл, и обязан отличать настоящую границу партии от мелкого отката времени
внутри неё.

Проверяется на синтетической трассе, потому что живую нужного вида ещё не
сыграли — в этом и смысл: инструмент готов ДО партии, а не после.
"""
import io
import json
import os
import subprocess
import sys
import tempfile

ЗДЕСЬ = os.path.dirname(os.path.abspath(__file__))
ошибок = 0


def проверить(условие, что):
    global ошибок
    if not условие:
        ошибок += 1
        print("  СБОЙ:", что)
    else:
        print("  ок:", что)


def прогнать(снимки, *ключи) -> str:
    """Запускаем разбор отдельным процессом — так же, как его зовёт итог партии."""
    with tempfile.TemporaryDirectory() as кат:
        путь = os.path.join(кат, "coss3_snap.jsonl")
        with io.open(путь, "w", encoding="utf-8", newline="") as ф:
            for с in снимки:
                ф.write(json.dumps(с, ensure_ascii=False) + "\n")
        из = subprocess.run(
            [sys.executable, os.path.join(ЗДЕСЬ, "разбор_удержания.py"), путь,
             *ключи],
            capture_output=True, text=True, encoding="utf-8",
            env=dict(os.environ, PYTHONIOENCODING="utf-8"))
        return (из.stdout or "") + (из.stderr or "")


# Событие гибели: seq, gt, жертва_pl, жертва, x, y, убийца_pl, убийца, kx, ky, оружие
def снимок(gt, режим=4, кл=(8, 8), ecells=None, гибель=None, n=13):
    с = {"gametime": gt,
         "groups": [{"id": 7, "n": n, "пик": 8, "стрелков": 5, "конных": 0,
                     "cx": кл[0], "cy": кл[1], "режим": режим, "tx": -1, "ty": -1}]}
    if ecells is not None:
        с["ecells"] = ecells
    if гибель is not None:
        с["гибель"] = гибель
    return с


print("1. держала, но контакта не было — ноль НЕ считается ответом")
из = прогнать([снимок(100), снимок(105), снимок(110)])
проверить("держала 3 снимков" in из, f"тактов удержания посчитано: {из[:160]!r}")
проверить("контакта НЕ БЫЛО" in из, "про отсутствие контакта сказано вслух")
проверить("НИЧЕГО не значит" in из, "ноль без контакта назван неответом")

print("2. контакт был и держащие стрелки стреляли")
его = ["9,8,4,4,0,0,0,0,0"]          # его клетка рядом с (8,8)
пуля = [[1, 120, 1, "I", 9, 8, 0, "S", 8, 8, "U"]]
из = прогнать([снимок(100, ecells=его), снимок(110, ecells=его, гибель=пуля)])
проверить("его бойцы рядом в 2 снимках" in из, f"контакт посчитан: {из[:200]!r}")
проверить("ДЕРЖАЩИЕ СТРЕЛКИ СТРЕЛЯЮТ" in из, "пуля из клетки группы — ответ «да»")
проверить("из них пулей 1" in из, "оружие различается")

print("3. контакт был, а убийств нет — тревога, а не тишина")
из = прогнать([снимок(100, ecells=его), снимок(110, ecells=его)])
проверить("ВНИМАНИЕ" in из and "боялся мак" in из,
          "плохой ответ назван плохим, а не «ноль»")

print("4. пики в удержании бьются — видно отдельно от стрелков")
ближ = [[2, 130, 1, "I", 8, 8, 0, "I", 8, 8, "M"]]
из = прогнать([снимок(100, ecells=его, гибель=ближ)])
проверить("ДЕРЖАЩИЕ ПИКИ БЬЮТСЯ" in из, "ближний бой держащих виден")
проверить("стрелками 0" in из, "пика не засчитана за стрелка")

print("5. чужие убийства и чужие клетки не засчитываются")
далеко = [[3, 140, 1, "I", 1, 1, 0, "S", 1, 1, "U"]]     # наш, но из другой клетки
врагом = [[4, 150, 0, "I", 8, 8, 1, "S", 8, 8, "U"]]     # в нашей клетке, но ЕГО
из = прогнать([снимок(100, ecells=его, гибель=далеко + врагом)])
проверить("убийств из её клетки 0" in из,
          f"ни чужая клетка, ни чужой убийца не засчитаны: {из[:200]!r}")

print("6. никто не держал — мерить нечего, и это сказано")
из = прогнать([снимок(100, режим=2), снимок(110, режим=0)])
проверить("НИ ОДНА ГРУППА НЕ ДЕРЖАЛА" in из, "отсутствие удержания названо")

print("7. в файле две партии — мерится последняя, а не склейка")
# Повод 7.10: в живом файле лежало 26 партий, и разбор дважды показал «держала
# 17 снимков» из партии, которой уже нет. `id` группы держит `br_hgrp` номерами
# бойцов, действительными только внутри одной партии, так что склейка не просто
# завышает такты — она сводит под один номер РАЗНЫЕ группы.
прошлая = [снимок(600, ecells=его, гибель=пуля), снимок(605, ecells=его),
           снимок(610, ecells=его)]
эта = [снимок(100), снимок(105)]
из = прогнать(прошлая + эта)
проверить("партий в файле 2" in из, f"обе партии увидены: {из[:220]!r}")
проверить("держала 2 снимков" in из, "посчитана только последняя партия")
проверить("контакта НЕ БЫЛО" in из, "контакт прошлой партии не протёк в эту")
проверить("ДЕРЖАЩИЕ СТРЕЛКИ СТРЕЛЯЮТ" not in из,
          "убийство прошлой партии не засчитано этой")

print("8. мелкий откат времени внутри партии НЕ режет её на две")
# Мост читает снимок чуть старше предыдущего: в живом файле 6.10 такие откаты
# были на 6 и 15 с при 26 настоящих границах. Резать по ним — занижать всё,
# что делится на число партий.
из = прогнать([снимок(100, ecells=его), снимок(94, ecells=его),
               снимок(110, ecells=его)])
проверить("партий в файле 1" in из, f"откат на 6 с партию не разрезал: {из[:220]!r}")
проверить("держала 3 снимков" in из, "все три снимка остались в одной партии")

print("9. прошлую партию можно посмотреть нарочно — `--эпизод`")
из = прогнать(прошлая + эта, "--эпизод", "1")
проверить("мерю номер 1" in из, f"выбранная партия названа: {из[:220]!r}")
проверить("держала 3 снимков" in из, "мерилась именно прошлая партия")
из = прогнать(прошлая + эта, "--эпизод", "9")
проверить("партий всего 2" in из, "несуществующий эпизод назван, а не взят молча")

print("10. мера висит на итоге партии, а не на памяти человека")
ИТОГ = io.open(os.path.join(ЗДЕСЬ, "итог_партии.py"), encoding="utf-8").read()
проверить("разбор_удержания" in ИТОГ,
          "итог_партии.py сам зовёт разбор после каждой живой партии")
проверить("не имеет права уронить итог" in ИТОГ,
          "сбой разбора не рушит числа партии")

print()
print("ошибок:", ошибок)
sys.exit(1 if ошибок else 0)
