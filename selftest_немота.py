#!/usr/bin/env python3
"""Немой отказ `read_state` (29.10, разбор Д22): время изменения файла не двинулось.

Это была ЕДИНСТВЕННАЯ ветка чтения состояния, которая не оставляла следа, и
именно в ней 29.10 пропали 113,8 реальных секунд — весь главный бой Д22, с 11:10
до 13:48. Игра при этом шла: 1249 тактов своего цикла по `FileStreamExists:
coss3_ctl.dat` в `game.log`, 1095 проходов человеческого блока команд, а такт 670
у python завершился целиком. Две другие ветки отказа (обрывок, откат снимка)
печатают с первого раза, и в логе партии их не было ни одной.

Теперь ветка называет ЧИСЛО, которое отделяет причины друг от друга: игровое
время ВНУТРИ файла. Проверяем все три приговора и то, что счёт не врёт.

(а) немота короче предела — молчим (обычный ритм 0,8 с не должен сыпать строками).
(б) немота на пределе: внутри файла время УШЛО ВПЕРЁД — виноват Windows, mtime мало.
(в) немота на пределе: внутри файла то же время — не писала игра, искать в блоке.
(г) файл не читается — его держит кто-то ещё.
(д) удачное чтение сбрасывает череду, но `немых_дольше` помнит наибольшую.
(е) темп редеет: строка на пределе 10 с, дальше раз в 50 с — иначе конец партии даёт 18 строк.

    python3 selftest_немота.py
"""
import io, os, sys, tempfile
К = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, К)
import coss3_bridge as CB

ошибок = 0
def проверить(усл, что):
    global ошибок
    print(("ОК   " if усл else "ОШИБКА ") + что); ошибок += not усл


ОПОРА = {"gametime": 670, "peasants": 82, "centers": 1, "victory": 0}

def положить(br, gt, *, старое_время=True):
    """Записать состояние. `старое_время` — оставить mtime как был, то есть
    ровно тот случай, из-за которого завёлся этот тест.

    Метку времени в ОБА случая ставим РУКАМИ, а не часами. Первая сборка теста
    падала 5 раз из 12 именно там, где запись должна была стать свежей: она
    успевала попасть в то же деление времени, что и прошлая, и чтение законно
    отказывало по `st_mtime <= _last_mtime`. Это и есть мера того, насколько
    грубо деление mtime на этой машине — опираться на него в тесте нельзя.
    """
    было = os.stat(br.state_path).st_mtime if os.path.exists(br.state_path) else None
    текст = CB.dump_parser_file("br_hp", dict(ОПОРА, gametime=gt))
    io.open(br.state_path, "w", encoding="latin-1", newline="").write(текст)
    if было is not None:
        метка = было if старое_время else было + 2.0
        os.utime(br.state_path, (метка, метка))

def поймать(br, раз):
    """Опросить состояние `раз` раз и вернуть напечатанное."""
    из_буфера = io.StringIO()
    было, sys.stdout = sys.stdout, из_буфера
    try:
        for _ in range(раз):
            br.read_state()
    finally:
        sys.stdout = было
    return из_буфера.getvalue()


with tempfile.TemporaryDirectory() as d:
    П = CB.НЕМЫХ_ПРЕДЕЛ

    # --- (а) немота короче предела: ни строки -----------------------------
    br = CB.Bridge(d, plind=1)
    положить(br, 670, старое_время=False)
    assert br.read_state() is not None, "первое чтение должно пройти"
    сказано = поймать(br, П - 1)
    проверить(сказано == "" and br.немых == П - 1,
              f"(а) {П - 1} немых опросов — молчим, счёт {br.немых}")

    # --- (б) внутри файла время ушло вперёд: виноват Windows --------------
    положить(br, 700)                      # игра написала, mtime оставили прежним
    сказано = поймать(br, 1)               # ровно предел
    проверить("WINDOWS НЕ ОБНОВИЛ ВРЕМЯ" in сказано and "700" in сказано
              and "670" in сказано,
              f"(б) на пределе сказано про Windows и названы оба времени — {сказано.strip()[:120]}")

    # --- (в) внутри файла то же время: не писала игра ---------------------
    br2 = CB.Bridge(d, plind=1)
    положить(br2, 670, старое_время=False)
    assert br2.read_state() is not None
    сказано = поймать(br2, П)
    проверить("ИГРА НЕ ПИСАЛА" in сказано and "block_hstate" in сказано,
              f"(в) то же время внутри — приговор на блок — {сказано.strip()[:120]}")

    # --- (г) файл не читается: его держит кто-то ещё ----------------------
    br3 = CB.Bridge(d, plind=1)
    положить(br3, 670, старое_время=False)
    assert br3.read_state() is not None
    было_время = os.stat(br3.state_path).st_mtime
    os.unlink(br3.state_path)
    os.mkdir(br3.state_path)               # stat пройдёт, open — нет
    os.utime(br3.state_path, (было_время, было_время))
    сказано = поймать(br3, П)
    проверить("держит кто-то ещё" in сказано,
              f"(г) файл не прочитался — сказано про чужой захват — {сказано.strip()[:110]}")
    os.rmdir(br3.state_path)

    # --- (д) удачное чтение сбрасывает череду, наибольшая помнится --------
    br4 = CB.Bridge(d, plind=1)
    положить(br4, 670, старое_время=False)
    assert br4.read_state() is not None
    поймать(br4, П + 7)                    # череда П+7
    долгая = br4.немых_дольше
    положить(br4, 700, старое_время=False)  # свежее время — чтение пройдёт
    assert br4.read_state() is not None
    проверить(br4.немых == 0 and долгая == П + 7 and br4.немых_дольше == П + 7
              and br4.немых_всего == П + 7,
              f"(д) череда сброшена ({br4.немых}), наибольшая помнится "
              f"({br4.немых_дольше}), всего {br4.немых_всего}")
    # ЭТО ЧИСЛО И ИДЁТ В ТРАССУ (`ждал_с`). Первая сборка брала `немых`, а его
    # сбрасывает то самое удачное чтение, после которого пишется такт, — в
    # трассу шёл бы ноль на каждом такте, включая стопорный.
    проверить(br4.немых_перед == П + 7,
              f"(д2) в трассу уйдёт ожидание перед этим чтением: "
              f"{br4.немых_перед * 0.2:.0f} с ({br4.немых_перед} опросов)")

    # --- (е) темп редеет: 10 с, потом каждые 50 ---------------------------
    # Конец партии встаёт честно, и `wait_state` ждёт весь таймаут 180 с. При
    # шаге «каждые 10 с» это 18 строк на каждом эпизоде — шум, в котором
    # настоящая немота потеряется.
    br5 = CB.Bridge(d, plind=1)
    положить(br5, 670, старое_время=False)
    assert br5.read_state() is not None
    сказано = поймать(br5, 2 * П)           # 20 с немоты
    строк = [x for x in сказано.split("\n") if x.strip()]
    проверить(len(строк) == 1,
              f"(е) за 20 с немоты строк {len(строк)} (ждали 1: только на пределе)")
    сказано = поймать(br5, 8 * П)           # добираем немоту до 500 опросов = 100 с
    строк = [x for x in сказано.split("\n") if x.strip()]
    проверить(len(строк) == 2,
              f"(е2) дальше раз в 50 с: немота дошла до 100 с, строк {len(строк)} (ждали 2: на 50 с и на 100 с)")
    # 180 с таймаута конца партии дают 4 строки вместо 18
    проверить(sum(1 for n in range(1, 901) if n == П or n % (5 * П) == 0) == 4,
              "(е3) за таймаут 180 с (900 опросов) строк будет 4, а не 18")

    # наибольшая немота в реальных секундах — то, что пойдёт в итог партии
    проверить(br5.немых_дольше == 10 * П,
              f"(ж) наибольшая немота {br5.немых_дольше * 0.2:.0f} с — это число идёт в итог партии рядом с худшей паузой")

print(("ВСЁ ЧИСТО" if not ошибок else f"ОШИБОК {ошибок}") + f" (предел немоты {CB.НЕМЫХ_ПРЕДЕЛ} опросов = {CB.НЕМЫХ_ПРЕДЕЛ * 0.2:.0f} с)")
sys.exit(1 if ошибок else 0)
