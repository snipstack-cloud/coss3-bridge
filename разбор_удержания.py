#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""СТРЕЛЯЮТ ЛИ ДЕРЖАЩИЕ — мера §102, считается по трассе ЛЮБОЙ партии.

Решение игрока 5.10: отдельную партию под этот вопрос не ставить, померить первой
же, где оборона понадобится по делу. Чтобы это случилось само, а не когда кто-то
вспомнит, мера считается задним числом по частому снимку: в нём уже есть и
`groups` с режимом (4 = держит), и `гибель` — событие с классом убийцы, его
клеткой и оружием. Ничего дописывать в мост не нужно, нужен только разбор.

Что отвечает:
  * сколько тактов и какие группы держали позицию, сколько в них было бойцов;
  * БЫЛ ЛИ КОНТАКТ: стоял ли его боец в клетке держащей группы или рядом. Без
    контакта «стрелки молчали» не значит ничего, и это главная ловушка замера —
    первая партия §102 дала ноль убийств просто потому, что враг не подошёл;
  * убийства ИЗ КЛЕТКИ держащей группы, по классу убийцы (S стрелки, I пехота,
    C конница) и оружию (U пуля, A стрела, M ближний бой). Пуля из клетки
    держащей группы и есть ответ «держащие стрелки стреляют».

Клетка сверяется по Чебышёву с запасом 1: среднее группы ложится на границу
клеток и мигает между соседними (замер §102), а строй вообще занимает не одну
клетку.

    python разбор_удержания.py C:/coss3-io-igrok/coss3_snap.jsonl
"""
from __future__ import annotations
import argparse
import io
import json
import os
import sys

for _s in (sys.stdout, sys.stderr):
    try:
        _s.reconfigure(encoding="utf-8", errors="replace")
    except Exception:
        pass

КЛАССЫ = {"P": "крестьяне", "I": "пехота", "S": "стрелки", "C": "конница",
          "G": "пушки", "B": "здания", "O": "прочее", "-": "без убийцы"}
ОРУЖИЕ = {"U": "пуля", "A": "стрела", "F": "огненная стрела", "M": "ближний бой"}
ЗАПАС = 1          # клеток вокруг держащей группы, см. докстринг


def читать(путь):
    из = []
    with io.open(путь, encoding="utf-8") as ф:
        for строка in ф:
            строка = строка.strip()
            if not строка:
                continue
            try:
                из.append(json.loads(строка))
            except json.JSONDecodeError:
                continue      # обрезанная последняя строка — обычное дело
    return из


def чебышёв(a, b):
    return max(abs(a[0] - b[0]), abs(a[1] - b[1]))


def main() -> int:
    ap = argparse.ArgumentParser(description="стреляют ли держащие (§102)")
    ap.add_argument("снимок", nargs="?",
                    default=r"C:\coss3-io-igrok\coss3_snap.jsonl")
    ap.add_argument("--наш", type=int, default=0, help="слот нашего бота")
    a = ap.parse_args()

    if not os.path.exists(a.снимок):
        print(f"нет файла {a.снимок}")
        return 1
    снимки = читать(a.снимок)
    print(f"снимков: {len(снимки)}  файл: {a.снимок}")

    держали = {}        # id группы -> {тактов, бойцов, клетки}
    контакт = {}        # id -> тактов с его бойцом рядом
    убийства = []       # (id группы, класс убийцы, оружие, жертва)
    всего_наших = 0

    for с in снимки:
        группы = [г for г in (с.get("groups") or []) if г.get("режим") == 4]
        события = с.get("гибель") or []
        # Его клетки этого снимка — для вопроса «был ли контакт вообще».
        его = []
        for строка in (с.get("ecells") or []):
            try:
                части = str(строка).split(",")
                его.append((int(части[0]), int(части[1]), int(части[2])))
            except (ValueError, IndexError):
                continue
        for г in группы:
            кл = (int(г.get("cx", -1)), int(г.get("cy", -1)))
            д = держали.setdefault(int(г["id"]), {"тактов": 0, "бойцов": 0,
                                                  "клетки": set()})
            д["тактов"] += 1
            д["бойцов"] = max(д["бойцов"], int(г.get("n") or 0))
            д["клетки"].add(кл)
            if any(чебышёв(кл, (x, y)) <= ЗАПАС and n > 0 for x, y, n in его):
                контакт[int(г["id"])] = контакт.get(int(г["id"]), 0) + 1
            for е in события:
                # seq, gt, жертва_pl, жертва, x, y, убийца_pl, убийца, kx, ky, оружие
                if len(е) < 11:
                    continue
                if int(е[6]) != a.наш:
                    continue
                if чебышёв(кл, (int(е[8]), int(е[9]))) <= ЗАПАС:
                    убийства.append((int(г["id"]), е[7], е[10], е[3]))
        for е in события:
            if len(е) >= 7 and int(е[6]) == a.наш:
                всего_наших += 1

    if not держали:
        print("НИ ОДНА ГРУППА НЕ ДЕРЖАЛА позицию за эту партию — мерить нечего.")
        return 0

    print()
    for ид in sorted(держали):
        д = держали[ид]
        к = контакт.get(ид, 0)
        мои = [у for у in убийства if у[0] == ид]
        стрелки = [у for у in мои if у[1] == "S"]
        пули = [у for у in стрелки if у[2] == "U"]
        пики = [у for у in мои if у[1] == "I"]
        print(f"группа {ид}: держала {д['тактов']} снимков, бойцов до "
              f"{д['бойцов']}, клетки {sorted(д['клетки'])}")
        print(f"  КОНТАКТ: его бойцы рядом в {к} снимках из {д['тактов']}"
              + ("" if к else "  — контакта НЕ БЫЛО, и тогда ноль убийств "
                               "НИЧЕГО не значит"))
        print(f"  убийств из её клетки {len(мои)}: стрелками {len(стрелки)} "
              f"(из них пулей {len(пули)}), пехотой {len(пики)}")
        if пули:
            print(f"  ДЕРЖАЩИЕ СТРЕЛКИ СТРЕЛЯЮТ: {len(пули)} убитых пулей, "
                  f"жертвы {sorted({КЛАССЫ.get(у[3], у[3]) for у in пули})}")
        if пики:
            print(f"  ДЕРЖАЩИЕ ПИКИ БЬЮТСЯ: {len(пики)} убитых, жертвы "
                  f"{sorted({КЛАССЫ.get(у[3], у[3]) for у in пики})}")
        if к and not мои:
            print("  ВНИМАНИЕ: контакт был, а убийств из её клетки нет — это и "
                  "есть тот ответ, которого боялся мак. Смотреть вручную.")
    print()
    print(f"наших убийств за партию всего {всего_наших}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
