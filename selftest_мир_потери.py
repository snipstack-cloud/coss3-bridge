#!/usr/bin/env python3
"""Потерянные записи `world.md` (29.10): знание, которое не доехало до модели.

Разбор Д22 начался с вопроса про стопор, а попутно выяснилось вот что: девять
записей знания лежали в файле ПОСЛЕ заголовка `## Вопросы` и начинались со
звёздочки вместо дефиса. Шесть из них — итоги целой сессии, дописанные при её
закрытии 29.10 вечером. В разделе вопросов такая строка не подходит ни под одну
ветку `разобрать_мир` и пропадала МОЛЧА: счёт «169 строк знания» не менялся,
потому что считал уцелевшие, и до модели не доехало ни одной.

Это главное правило проекта наоборот: модель ошибается настолько, насколько
врёт описание мира — а здесь оно не врало, его просто не было.

(а) звёздочка в разделе вопросов — потеря замечена и названа.
(б) звёздочка в разделе знания — тоже потеря (дефис обязателен и там).
(в) вступление файла (проза без маркера) потерей НЕ считается — иначе
    предупреждение врало бы в каждом запуске.
(г) продолжение записи с отступом — не потеря.
(д) настоящий `world.md` проекта: потерь нет, и 9 перенесённых записей на месте.
(е) копилка сбрасывается между разборами, а не накапливается.

    python3 selftest_мир_потери.py
"""
import os, sys
К = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, К)
import llm_policy as L

ошибок = 0
def проверить(усл, что):
    global ошибок
    print(("ОК   " if усл else "ОШИБКА ") + что); ошибок += not усл


ВСТУПЛЕНИЕ = """# Что мы знаем о мире

Этот файл уходит в промпт ЦЕЛИКОМ и живёт дольше партии. Сюда кладут ответы на
вопросы модели и всё, что она не может увидеть в состоянии.
Строка знания начинается с `- `.

"""

# --- (а) звёздочка ПОСЛЕ заголовка вопросов — ровно случай 29.10 -----------
зн, воп = L.разобрать_мир(ВСТУПЛЕНИЕ + """- [код] хорошая запись

## Вопросы

- вопрос: почему?
  ответ: потому
* [замер, 29.10] ИТОГ СЕССИИ, который никто не увидит
  вторая строка этого итога
""")
проверить(len(зн) == 1 and len(воп) == 1 and len(L.МИР_ОТБРОШЕНО) == 1
          and "ИТОГ СЕССИИ" in L.МИР_ОТБРОШЕНО[0],
          f"(а) звёздочка в разделе вопросов замечена: знание {len(зн)}, "
          f"потеряно {L.МИР_ОТБРОШЕНО}")

# --- (б) звёздочка в разделе знания — дефис обязателен и там ---------------
зн, воп = L.разобрать_мир(ВСТУПЛЕНИЕ + """- [код] хорошая запись
* [замер] запись звёздочкой

## Вопросы
""")
проверить(len(зн) == 1 and len(L.МИР_ОТБРОШЕНО) == 1,
          f"(б) звёздочка в разделе знания тоже потеря: знание {len(зн)}, "
          f"потеряно {len(L.МИР_ОТБРОШЕНО)}")

# --- (в) вступление прозой — не потеря ------------------------------------
зн, воп = L.разобрать_мир(ВСТУПЛЕНИЕ + "- [код] запись\n")
проверить(len(зн) == 1 and L.МИР_ОТБРОШЕНО == [],
          f"(в) проза вступления потерей не считается — потеряно {L.МИР_ОТБРОШЕНО}")

# --- (г) продолжение с отступом — не потеря -------------------------------
зн, воп = L.разобрать_мир(ВСТУПЛЕНИЕ + """- [код] первая строка записи
  продолжение записи с отступом
  и ещё одно
""")
проверить(len(зн) == 1 and "продолжение записи" in зн[0]
          and "и ещё одно" in зн[0] and L.МИР_ОТБРОШЕНО == [],
          f"(г) продолжение склеено в одну запись, потерь нет — {len(зн)} запись")

# --- (д) настоящий файл проекта -------------------------------------------
путь = os.path.join(К, "world.md")
зн, воп = L.разобрать_мир(open(путь, encoding="utf-8").read())
проверить(L.МИР_ОТБРОШЕНО == [],
          f"(д) в world.md проекта потерь нет — {L.МИР_ОТБРОШЕНО}")
проверить(len(зн) >= 178,
          f"(д2) записей знания {len(зн)} (после переноса девяти было 178; "
          f"меньше — значит что-то опять уехало в раздел вопросов)")

# --- (е) копилка не накапливается -----------------------------------------
L.разобрать_мир(ВСТУПЛЕНИЕ + "* потеря\n")
было = len(L.МИР_ОТБРОШЕНО)
L.разобрать_мир(ВСТУПЛЕНИЕ + "- [код] чисто\n")
проверить(было == 1 and L.МИР_ОТБРОШЕНО == [],
          f"(е) копилка сброшена между разборами: было {было}, стало "
          f"{len(L.МИР_ОТБРОШЕНО)}")

# --- (ж) ЗНАНИЕ С ДЕФИСОМ В РАЗДЕЛЕ ВОПРОСОВ (1.11, просьба Windows, cdf312b) --------------------------------------------------
# Разбор не теряет такую строку — он отдаёт её модели ВОПРОСОМ: 24 замера ушли в промпт как «то, чего мы не знаем».
# Признак дешёвый: в разделе вопросов строка «- [метка] …», где метка начинается с код / замер / игрок, — потерянное знание.
import re
_ЗНАНИЕ = re.compile(r"^- \[(код|замер|игрок)[^\]]*\]")

def знание_в_вопросах(текст: str) -> list:
    _, _, хвост = текст.partition("\n## Вопросы")
    return [s for s in хвост.splitlines() if _ЗНАНИЕ.match(s)]

проверить(знание_в_вопросах(ВСТУПЛЕНИЕ + "- [код] знание\n\n## Вопросы\n\n- вопрос: почему?\n- [замер, 1.11] замер не на месте\n")
          == ["- [замер, 1.11] замер не на месте"], "(ж1) признак ловит дефисную запись знания в разделе вопросов")
проверить(знание_в_вопросах(ВСТУПЛЕНИЕ + "- [замер] знание на месте\n\n## Вопросы\n\n- вопрос: почему?\n  ответ: [код] так\n") == [],
          "(ж2) запись знания до вопросов и метка внутри ответа — не потеря")
_пв = знание_в_вопросах(open(путь, encoding="utf-8").read())
проверить(_пв == [], f"(ж) в разделе вопросов world.md нет записей знания: {[s[:80] for s in _пв]}")

print("ВСЁ ЧИСТО" if not ошибок else f"ОШИБОК {ошибок}")
sys.exit(1 if ошибок else 0)
