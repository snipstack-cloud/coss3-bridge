# -*- coding: utf-8 -*-
"""Снимок: у своего поля должен быть чужой близнец — иначе очки считаются вслепую.

Повод, 28.09 (мак). Он посчитал «по очкам впереди в 23 из 27» и сам поправил:
очки не засчитывали его ратушу, академию и дома. Попросил отдавать их из блока — а
проверка показала, что блок их пишет ДАВНО и трасса несёт все, дыра же была в
СНИМКЕ: в белом списке чужих полей стояли отряды, движение и апгрейды, из зданий
только `ba17`. Своих зданий в снимке шесть видов, его — один. На этой асимметрии
счёт очков и разъехался: одну сторону считали по видам, другую по общему числу `p1_bldgs`.

Правило, которое здесь стережётся: ЕСЛИ СВОЁ ПОЛЕ ЕСТЬ В СНИМКЕ И БЛОК ПИШЕТ ЧУЖОЙ
БЛИЗНЕЦ — близнец обязан быть в снимке тоже. Иначе любая мера, считающая обе
стороны, врёт в одну сторону молча.

Соответствие имён не выводимо из строк: своё зовётся `centers`, чужое `p1_center`;
своё `my_stores`, чужое `p1_store`. Поэтому таблица здесь явная — и она же служит
списком того, что вообще имеет смысл сравнивать по сторонам.
"""
import io
import os
import re

import llm_policy as L

беды = []


def проверка(имя, условие, пояснение=""):
    if условие:
        print("  ОК    " + имя)
    else:
        беды.append(имя)
        print("  ПЛОХО " + имя + (" — " + str(пояснение)[:300] if пояснение else ""))


ЗДЕСЬ = os.path.dirname(os.path.abspath(__file__))
БЛОК = io.open(os.path.join(ЗДЕСЬ, "block_hstate.inc"), encoding="latin-1").read()
ПОЛИТИКА = io.open(os.path.join(ЗДЕСЬ, "llm_policy.py"), encoding="utf-8").read()

# Что блок вообще пишет про чужого игрока.
ЧУЖИЕ_В_БЛОКЕ = set(re.findall(r"'p' \+ IntToStr\(hspl\) \+ '_([a-z0-9_]+)'", БЛОК))
проверка("чужие поля блока найдены", len(ЧУЖИЕ_В_БЛОКЕ) > 30, len(ЧУЖИЕ_В_БЛОКЕ))

# Хвосты, которые снимок пропускает по образцу имени.
_фильтр = re.search(r"_хвост in \((.*?)\) and _в not in", ПОЛИТИКА, re.S)
проверка("фильтр чужих полей снимка найден", _фильтр is not None)
ХВОСТЫ = set(re.findall(r'"([a-z0-9_]+)"', _фильтр.group(1))) if _фильтр else set()

# Своё имя -> чужой хвост. Соответствие явное: из строк оно не выводится.
ПАРЫ = {
    "centers": "center", "mills": "mill", "smiths": "smith", "ba17": "ba17",
    "my_stores": "store", "houses": "house", "academies": "academi",
    "mines_gold": "mgold", "mines_iron": "miron", "mines_coal": "mcoal",
    "food": "food", "wood": "wood", "stone": "stone",
    "gold": "gold", "iron": "iron", "coal": "coal",
}

for своё, чужой in sorted(ПАРЫ.items()):
    если_своё = своё in L.ПОЛЯ_СНИМКА
    если_блок = чужой in ЧУЖИЕ_В_БЛОКЕ
    если_чужой = (f"p1_{чужой}" in L.ПОЛЯ_СНИМКА) or (чужой in ХВОСТЫ)
    if not если_своё or not если_блок:
        # Своего в снимке нет либо блок чужого не пишет — сравнивать нечего.
        continue
    проверка(f"{своё} есть — значит и p1_{чужой} в снимке", если_чужой,
             "мера по обеим сторонам считала бы одну по видам, другую по общему числу")

# И отдельно то, с чего всё началось: три поля из просьбы мака.
for поле in ("center", "academi", "house"):
    проверка(f"p1_{поле} доезжает до снимка", поле in ХВОСТЫ,
             "именно их не хватало счёту очков 28.09")
    проверка(f"p1_{поле} пишет блок", поле in ЧУЖИЕ_В_БЛОКЕ)

print()
if беды:
    print(f"ПЛОХО: {len(беды)} — " + "; ".join(беды))
    raise SystemExit(1)
print("все проверки прошли")
