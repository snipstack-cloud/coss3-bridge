#!/usr/bin/env python3
"""§170с (27.10, Д17 — чистый замер экономики): ЕДА ЛЕЖИТ — потолок цели еды. В Д17 при 6456 еды цель еды была 46 (вся земля),
к 15:00 еды 24 332 при 54 на еде, академия (1050 дерева) уехала на 12:36 при дереве 486 в 8:00, переходов 170 за 15:02.
Кейс — живые такты Д17 9:30–14:40 (`партия_д17_27_10_9-30_14-40`), ключи файла партии Д17 (семь) ± `еда_лежит` 2000.

(а) ключ 0 на 10:12 (еда 4281, на еде 2, на дереве 25): цель еды ≥ 30 — как было (живьём 31).
(б) `еда_лежит` 2000 на 10:12: цель еды ≤ пол + 2, запись §170с, дерево выше, чем без ключа; «золото лежит» еде не прибавляет.
(в) гистерезис: включившись при 4281, при 1500 держится, при 900 выключается.
(г) по всему кейсу с ключом: сумма наземных перемещений (цель ≠ on_*) меньше, чем без ключа; цели еды не выше 20 ни в одном такте.

    python3 selftest_еда_лежит.py
"""
import copy, json, os, sys, tempfile
К = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, К); sys.path.insert(0, os.path.join(К, "sim"))
os.environ.pop("COSS3_WAVE_CONTRACT", None)
import strategy_live as SL
import анализ_врага as АВ
д17 = [json.loads(l) for l in open(os.path.join(К, "sim/кейсы/партия_д17_27_10_9-30_14-40.jsonl"), encoding="utf-8")]
ошибок = 0
def проверить(усл, что):
    global ошибок
    print(("ОК   " if усл else "ОШИБКА ") + что); ошибок += not усл
# `переброс_раз` здесь 0: ворота §170п глушат приказы, равные текущему или ждущие срока, а тест судит ЦЕЛЬ еды, не ворота
КЛЮЧИ_Д17 = {"пачка_крестьян": 6, "пол_прокормом": 1, "добор_до_пола": 2, "нужда_после_mil1": 1, "золото_по_цене": 1, "переброс_раз": 0, "кайт": 0}
def стратегия(доп):
    д = json.load(open(os.path.join(К, "sim/поиск/шт_s2_оборона_ручеёк_эко_так15_нужда.json"), encoding="utf-8"))
    д["итог"].update(КЛЮЧИ_Д17); д["итог"]["еда_лежит"] = 0; д["итог"].update(доп)
    with tempfile.NamedTemporaryFile("w", suffix=".json", delete=False, encoding="utf-8") as f:
        json.dump(д, f, ensure_ascii=False)
    return SL.ЖиваяСтратегия(f.name)
def ответ(С, s):
    АВ._ТЕКУЩИЙ.update({"а": None, "t": None, "ответ": None}); return С.ответ(copy.deepcopy(s))
def цель(о, роль):
    v = [int(c["total"]) for c in о["commands"] if c["cmd"] == "BALANCE" and c.get("role") == роль and str(c.get("total")) not in ("all", "")]
    return v[-1] if v else None
def прогон(доп):
    С = стратегия(доп); ряд = []
    for s in д17:
        ряд.append((s, ответ(С, s), С))
    return ряд
р0 = прогон({}); р1 = прогон({"еда_лежит": 2000})
s766, о0, _ = next(x for x in р0 if float(x[0]["gametime"]) == 612)   # 10:12: еда 4281, на еде 2, дереве 25; живьём food 2→31
_, о1, С1 = next(x for x in р1 if float(x[0]["gametime"]) == 612)
проверить((цель(о0, "food") or 0) >= 30, f"(а) ключ 0, 10:12 еда {s766['food']}: цель еды {цель(о0, 'food')} (живьём 31; повтор без истории партии)")
м = [x for x in о1["why"].split(", ") if "§170с" in x]
проверить(цель(о1, "food") is not None and цель(о1, "food") <= 12 and м and (цель(о1, "wood") or 0) > (цель(о0, "wood") or 0) and "еде +" not in о1["why"],
          f"(б) еда_лежит 2000, 10:12: цель еды {цель(о1, 'food')}, дерево {цель(о1, 'wood')}, камень {цель(о1, 'stone')}; {м[:1]}")
# (в) гистерезис на стратегии С1 (включена с 12:46)
о_1500 = ответ(С1, dict(s766, food=1500)); о_900 = ответ(С1, dict(s766, food=900))
проверить(any("§170с" in x for x in о_1500["why"].split(", ")) and (цель(о_1500, "food") or 0) <= 20, f"(в) еда 1500 после включения: держится — цель еды {цель(о_1500, 'food')}")
проверить(not any("§170с" in x for x in о_900["why"].split(", ")) and (цель(о_900, "food") or 0) >= 40, f"(в′) еда 900 < 1000: выключился — цель еды {цель(о_900, 'food')}")
# (г) по кейсу
def ходьба(р):
    n = 0; макс_еда = 0
    for s, о, _ in р:
        for роль in ("food", "wood", "stone"):
            ц = цель(о, роль)
            if ц is not None and ц != int(s.get("on_" + роль) or 0): n += abs(ц - int(s.get("on_" + роль) or 0))
        макс_еда = max(макс_еда, цель(о, "food") or 0)
    return n, макс_еда
н0, е0 = ходьба(р0); н1, е1 = ходьба(р1)
проверить(е1 <= 20 and е0 >= 30, f"(г) макс цель еды по кейсу {е0} → {е1}; людей в приказах сверх текущего: ключ 0 — {н0}, ключ 2000 — {н1} (справка)")
print(f"\nИТОГ: ошибок {ошибок}")
sys.exit(1 if ошибок else 0)
