# -*- coding: utf-8 -*-
"""Самопроверка: накопление не должно съедать окно удара.

Живая партия 20.09, такт 14:26. Мост объявил режим УДАР — перевес 1,5 при
пороге 1,3, наш кулак 129 против 48 бойцов у него дома, первая волна врага
только что снесена. И промолчал о том, что стоячий приказ `STAGE` держит армию
в клетке сбора. Модель написала «коплю кулак в (2,8) по STAGE» и никуда не
пошла: за следующие восемь минут ни одной волны, армия врага выросла с 86 до
119, окно закрылось само.

Игрок увидел это на экране раньше, чем я в числах: «армия снесла первую волну
противника, но дальше не пошла, а в реальной игре там есть шанс взять базу».

Стережётся:
* при УДАРЕ и ШАНСЕ включённое накопление названо ПОМЕХОЙ, с готовой отменой;
* при КОПИТЬ и ОПАСНОСТИ предупреждения нет — там копить и надо;
* без накопления мост молчит: отменять нечего.
"""
import llm_policy as L

беды = []


def проверка(имя, условие, пояснение=""):
    if условие:
        print("  ОК    " + имя)
    else:
        беды.append(имя)
        print("  ПЛОХО " + имя + (" — " + пояснение if пояснение else ""))


КЛЕТКА = {"x": 2, "y": 14, "крестьян": 10, "их_рядом": 0, "их_подкрепление": 86,
          "их_успеют": 86, "их_eta": 20, "наш_кулак": 129, "наш_eta": 90,
          "ушли_мимо": 0, "встретит": 86, "перевес": 1.5, "встретит_сразу": 86,
          "перевес_сразу": 1.5, "отрядов": 1, "дотекание": [0, 0],
          "перевес_без_подкрепления": 9.0, "вердикт": "можно"}
ПРОГНОЗ = {"их_армия": 86, "их_через_60": 97, "наша_армия": 131,
           "наша_через_60": 140, "голод": False, "к_нашей_базе": 0,
           "у_него_дома": 48, "наших_дома": 129, "его_дотекание_в_минуту": 27,
           "идущих": 0, "дойдут_через": None, "куда": None, "перевес_у_базы": None}
ОЦЕНКА = {"кулак": {"n": 129, "cx": 2, "cy": 8, "что": "свободные"},
          "прогноз": ПРОГНОЗ, "клетки": [КЛЕТКА]}


def строки(режим, накопление=True):
    L.НАКОПЛЕНИЕ.clear()
    if накопление:
        L.НАКОПЛЕНИЕ.update({"cx": 2, "cy": 8, "keep": 30})
    из = L.строки_оценки(dict(ОЦЕНКА, режим=режим))
    L.НАКОПЛЕНИЕ.clear()
    return "\n".join(из)


с = строки("УДАР")
проверка("при УДАРЕ накопление названо помехой", "мешает этому удару" in с, с[:200])
проверка("названа клетка, где стоит накопление", "(2,8)" in с)
проверка("дана готовая отмена", '"cmd":"STAGE","off":1' in с)
проверка("сказано, что бить следом всем кулаком", "ATTACK всем кулаком" in с)
проверка("объяснено, почему копить поздно",
         "перевес появился" in с and "сейчас он уже есть" in с)

проверка("при ШАНСЕ предупреждение тоже есть",
         "мешает этому удару" in строки("ШАНС"))
проверка("при КОПИТЬ предупреждения нет",
         "мешает этому удару" not in строки("КОПИТЬ"),
         "в этом режиме копить и надо")
проверка("при ОПАСНОСТИ предупреждения нет",
         "мешает этому удару" not in строки("ОПАСНОСТЬ"))
проверка("без накопления мост молчит",
         "мешает этому удару" not in строки("УДАР", накопление=False),
         "отменять нечего")

print()
if беды:
    print(f"БЕД: {len(беды)} — {', '.join(беды)}")
    raise SystemExit(1)
print("всё чисто")
