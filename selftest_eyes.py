"""Сторож глаз (6.10, `угрозы.py`): набег на базу виден по `ecells` (идут, tx, ty) в обеих формах поля."""
import sys
import угрозы as У

ош = 0
# Картина p6 в 5:31: ратуша (2,3) по obuild; его 25 из (6,9) идут в (1,5); наши 38 дома
st = {"map_w": 256, "obuild": [{"тип": "center", "x": 40, "z": 54}, {"тип": "mill", "x": 54, "z": 56}],
      "ecells": [{"x": 6, "y": 9, "n": 25, "стрелков": 5, "идут": 25, "tx": 1, "ty": 5},
                 {"x": 12, "y": 12, "n": 15, "стрелков": 7, "идут": 0, "tx": -1, "ty": -1}],
      "ocells": [{"x": 2, "y": 3, "n": 38}]}
о = У.оценить(st)
if о["дом"] != (2, 3):
    print("ПРОВАЛ: дом по ратуше из obuild:", о["дом"]); ош += 1
if (о["база"]["его"], о["база"]["стрелков"]) != (25, 5) or not о["база"]["сек"]:
    print("ПРОВАЛ: угроза базе не увидена:", о["база"]); ош += 1
if о["база"]["наших_дома"] != 38:
    print("ПРОВАЛ: наших дома:", о["база"]); ош += 1
# та же картина строками живого моста
жив = {"map_w": 256, "obuild": "center,40,54,1,100;mill,54,56,1,100",
       "ecells": "6,9,25,20,5,0,25,1,5;12,12,15,8,7,0,0,-1,-1", "ocells": "2,3,38,38,0,0"}
о2 = У.оценить(жив)
if о2["база"]["его"] != 25:
    print("ПРОВАЛ: строковая форма живого моста:", о2["база"]); ош += 1
# стоящий у себя — не угроза
о3 = У.оценить(dict(st, ecells=[{"x": 12, "y": 12, "n": 40, "идут": 0, "tx": -1, "ty": -1}]))
if о3["база"]["его"] or "нет" not in о3["строка"]:
    print("ПРОВАЛ: стоящий у своей базы — не угроза:", о3["строка"]); ош += 1
print(f"ошибок: {ош}")
sys.exit(1 if ош else 0)
