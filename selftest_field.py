# МОСТ САМ САЖАЕТ ЛЮДЕЙ НА СОЗРЕВШЕЕ ПОЛЕ (19.09). Случай узкий: поле готово,
# на еде НОЛЬ, запас ниже порога найма. 19.09 такое поле простояло три минуты,
# пока модель повторяла «поле зреет», и партия умерла от голода.
class _Арг:
    auto_food = 1
    builders_first = 0
    aim_peasants = False

def _решение(st, ответ=None, авто=1):
    """Что уйдёт в игру после вмешательства моста."""
    а = _Арг(); а.auto_food = авто
    cmds, *_ = L_.to_commands({"commands": ответ or []})
    # повторяем ту же проверку, что стоит в петле
    из_моста = None
    if а.auto_food and not any(c.cmd == "BALANCE" and c.a1 == L_.RESOURCE["food"]
                               for c in cmds):
        гот = L_._чис(st.get("food_ready")); мел = L_._чис(st.get("mills"))
        на = L_._чис(st.get("on_food")); еда = L_._чис(st.get("food"))
        кр = L_._чис(st.get("peasants"))
        if мел > 0 and гот > 0 and на == 0 and 0 < еда < 500 and кр > 0:
            из_моста = max(1, min(гот, кр // 2))
    return из_моста

СОЗРЕЛО = {"mills": 1, "food_ready": 25, "on_food": 0, "food": 248, "peasants": 18}
проверка("на созревшее поле мост сажает половину крестьян",
         _решение(СОЗРЕЛО) == 9, str(_решение(СОЗРЕЛО)))
проверка("но не больше готовых участков",
         _решение(dict(СОЗРЕЛО, food_ready=3)) == 3, str(_решение(dict(СОЗРЕЛО, food_ready=3))))
проверка("если модель сама поставила людей — мост молчит",
         _решение(СОЗРЕЛО, [{"cmd": "BALANCE", "role": "food", "total": 5}]) is None)
проверка("поле не созрело — не вмешивается",
         _решение(dict(СОЗРЕЛО, food_ready=0)) is None)
проверка("люди уже на еде — не вмешивается",
         _решение(dict(СОЗРЕЛО, on_food=4)) is None)
проверка("еды выше порога — не вмешивается (решает модель)",
         _решение(dict(СОЗРЕЛО, food=900)) is None)
проверка("ключом отключается", _решение(СОЗРЕЛО, авто=0) is None)

