# -*- coding: utf-8 -*-
"""Самопроверка блока «Поле ещё зреет».

У блока есть память между тактами (когда встала мельница), и её надо чистить
между партиями — иначе вторая партия начнёт с чужим сроком. Снимки промпта
этого не ловят.
"""
import sys
import llm_policy as L
L_ = L

беды = []


def проверка(имя, условие, пояснение=""):
    if условие:
        print("  ОК   " + имя)
    else:
        беды.append(имя)
        print("  ПЛОХО " + имя + (" — " + пояснение if пояснение else ""))


def текст(t, mills=1, on_food=0, food_ready=None):
    сост = dict(gametime=t, mills=mills, on_food=on_food)
    if food_ready is not None:
        сост["food_ready"] = food_ready
    return chr(10).join(L.созревание(сост))



L.ПОЛЕ.clear()
проверка("без мельницы молчит", текст(50, mills=0) == "")

L.ПОЛЕ.clear()
т1 = текст(70)
проверка("после мельницы говорит", "Поле ещё зреет" in т1)
проверка("называет срок", "105" in т1)
проверка("запрещает пустую команду", "BALANCE food НИКОГО НЕ ПОШЛЁТ" in т1)

текст(120)
проверка("считает от МЕЛЬНИЦЫ, а не от начала партии", "мельница стоит 50 с" in текст(120))

проверка("после срока предлагает SEED", "SEED" in текст(200))

проверка("как только люди на еде — замолкает", текст(260, on_food=15) == "")
проверка("и больше не возвращается", текст(300) == "")

L.ПОЛЕ.clear()
проверка("между партиями память пуста", L.ПОЛЕ == {})

# Поле food_ready: мост сам видит созревшие участки, гадать по сроку не нужно.
L.ПОЛЕ.clear()
текст(70, food_ready=0)
т9 = текст(140, food_ready=2)
проверка("созревшее поле названо вслух", "Поле СОЗРЕЛО" in т9)
проверка("сказано, сколько участков", "готовых участков: 2" in т9)
проверка("зовёт ставить людей", "BALANCE food" in т9)
проверка("когда люди встали — молчит", текст(160, on_food=12, food_ready=2) == "")

L.ПОЛЕ.clear()
проверка("при food_ready=0 говорит, что зреет", "ещё зреет" in текст(80, food_ready=0))

# Голод не мешает стройке: замер 17.09 показал 56 секунд простоя между готовой
# кузницей и заказом казармы, при золоте 850 и цене 500.
def голод(food=440, ba17=0, smiths=1, can_now="ba17 mill"):
    return chr(10).join(L.стройка_в_голод(
        dict(food=food, ba17=ba17, smiths=smiths, can_now=can_now)))


проверка("в голод зовёт ставить казарму", "Ставь КАЗАРМУ" in голод())
проверка("без кузницы зовёт кузницу", "Ставь КУЗНИЦУ" in голод(smiths=0, can_now="smith"))
проверка("при сытости молчит", голод(food=900) == "")
проверка("при готовой казарме молчит", голод(ba17=1) == "")
проверка("если не по карману — молчит", голод(can_now="mill") == "")


# СРОК ИСЧЕРПАНИЯ ЕДЫ рядом с призывом ставить людей (19.09). Голод в живой
# партии пришёл не внезапно: еда шла 989 -> 445 -> 354 -> 8 за две минуты, поле
# при этом стояло ГОТОВЫМ три минуты (25 участков, на еде ноль), а модель писала
# «поле зреет» и слала людей на дерево.
L_.ПОЛЕ.clear()
L_.созревание({"mills": 1, "on_food": 0, "gametime": 123, "food_ready": 0, "food": 354})
строки_поля = L_.созревание({"mills": 1, "on_food": 0, "gametime": 143,
                             "food_ready": 25, "food": 8})
проверка("поле созрело — мост зовёт ставить людей",
         any("Поле СОЗРЕЛО" in с for с in строки_поля), str(строки_поля))
проверка("и говорит, на сколько хватит еды",
         any("хватит на" in с for с in строки_поля), str(строки_поля))

# Пока еда РАСТЁТ, срока нет: пугать нечем.
L_.ПОЛЕ.clear()
L_.созревание({"mills": 1, "on_food": 0, "gametime": 100, "food_ready": 5, "food": 100})
растёт = L_.созревание({"mills": 1, "on_food": 0, "gametime": 120, "food_ready": 5,
                        "food": 900})
проверка("при растущей еде срока нет", not any("хватит на" in с for с in растёт),
         str(растёт))

# Выше порога 500 сказано и про порог, а не только про ноль.
проверка("до порога 500 срок назван отдельно",
         "ниже порога 500" in L_.срок_еды({"food": 2000, "gametime": 200},
                                          {"food": 2400, "gametime": 180}),
         L_.срок_еды({"food": 2000, "gametime": 200}, {"food": 2400, "gametime": 180}))
проверка("без прошлого состояния срок молчит", L_.срок_еды({"food": 100}, None) == "")

print()
print("ПРОВАЛОВ:", len(беды))

sys.exit(1 if беды else 0)
