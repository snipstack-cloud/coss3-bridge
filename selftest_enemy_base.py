# -*- coding: utf-8 -*-
"""Самопроверка: его база как точка и три числа цели «win10» (`--goal win10`).

Зачем. Ратуши врага в состоянии нет (24.09, разборы/ВРАГ_ГЛАЗАМИ_МОДЕЛИ.md):
его здания лежат только сеткой `brow`, крестьяне СНАРУЖИ нигде не складываются
(`p1_peasants` считает и тех, кто в шахтах), а «наших у его базы» модель могла
лишь прикинуть по картинке. Новая цель партии (решение игрока 24.09) —
армия врага <10, крестьян снаружи <10, наших у его базы >50 — стоит ровно на
этих трёх числах. Под ключом, потому что это строка промпта.
"""
import sys, os
sys.argv = [sys.argv[0]]
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import llm_policy as L
import coss3_map as M

ошибок = 0


def проверить(что, условие, пояснение=""):
    global ошибок
    print(("  ОК   " if условие else "  СБОЙ ") + что + (f" — {пояснение}" if пояснение else ""))
    ошибок += not условие


def сетка(имя, **клетки):
    строки = [["."] * 16 for _ in range(16)]
    for k, v in клетки.items():
        x, y = (int(t) for t in k.split(","))
        строки[y][x] = v if isinstance(v, str) else M.знак(v)
    return {f"{имя}{y}": "".join(строки[y]) for y in range(16)}


БАЗА = dict(gametime=800, grid_n=16, map_w=256, map_h=256, my_cx=12, my_cy=12,
            map_open=1, my_freewar=30, p1_enemy="true", p1_peasants=40,
            p1_inf=5, p1_shoot=0, p1_cav=0)

print("база врага по сетке зданий:")
st = dict(БАЗА, **сетка("brow", **{"12,12": "H", "11,12": "b", "2,3": "e", "3,3": "e", "3,4": "e", "9,9": "e"}))
б = M.база_врага(st)
проверить("найдена клетка здания у центра кучи (3,4), а не шахта (9,9) на отшибе", б.get("cx") == 3 and б.get("cy") == 4, str(б))
проверить("зданий в клетках сосчитано", б.get("клеток") == 4, str(б))
проверить("без brow — пусто", M.база_врага(dict(БАЗА)) == {})
проверить("свои здания за вражеские не считаются", M.база_врага(dict(БАЗА, **сетка("brow", **{"12,12": "H", "11,12": "b"}))) == {})

print("\nкрестьяне снаружи и наши у его базы:")
st.update(сетка("prow", **{"2,3": 6, "4,4": 3}))
st.update(сетка("arow", **{"3,3": 30, "5,5": 20, "12,12": 30}))
проверить("крестьян снаружи — сумма prow, а не p1_peasants", M.крестьян_снаружи(st) == 9)
проверить("наших у его базы — в двух клетках от (3,4): (3,3) и (5,5)", M.наших_у(st, 3, 4) == 50, str(M.наших_у(st, 3, 4)))
st_нас = dict(st, **сетка("arow", **{"3,3": 80}))
проверить("сетка режет клетку на 62 — это нижняя граница (потолок поднят 26.09)",
          M.наших_у(st_нас, 3, 4) == 62, str(M.наших_у(st_нас, 3, 4)))
проверить("радиус 2 не хватает (12,12)", M.наших_у(st, 3, 4, радиус=2) < 80)

print("\nстроки цели в запросе:")
L.ЧЕСТНО = False
L.ЦЕЛЬ_ПАРТИИ = ""
текст = "\n".join(L.открытая_информация(st, {}))
проверить("без ключа строки цели нет", "ЦЕЛЬ ПАРТИИ" not in текст and "его база:" not in текст)
L.ЦЕЛЬ_ПАРТИИ = "win10"
стр = L.открытая_информация(st, {})
текст = "\n".join(стр)
проверить("три условия названы", "меньше 10" in текст and "больше 50" in текст)
проверить("точка базы с клеткой и расстоянием", "его база: клетка (3,4)" in текст and "9 клеток от твоей ратуши" in текст, текст)
проверить("три числа: армия 5 нет (<10 — ЕСТЬ), снаружи 9 из 40 ЕСТЬ, у базы 50 — нет (не больше 50)",
          "его армия 5 — ЕСТЬ" in текст and "снаружи 9 из 40 всего — ЕСТЬ" in текст and "у его базы 50 — нет" in текст, текст)
текст_нас = "\n".join(L.открытая_информация(dict(st_нас, **сетка("prow", **{"2,3": 6})), {}))
проверить("при насыщенной клетке сказано «не меньше»", "у его базы не меньше 62" in текст_нас, текст_нас)
проверить("после 7:00 про срок не пишет", "до 7:00" not in текст)
st2 = dict(st, gametime=300, p1_inf=30)
текст2 = "\n".join(L.открытая_информация(st2, {}))
проверить("до 7:00 сказано, сколько ждать", "до 7:00 ещё 120 с" in текст2, текст2)
проверить("армия 30 — условие не выполнено", "его армия 30 — нет" in текст2)
st3 = dict(БАЗА, **сетка("prow", **{"2,3": 6}))
текст3 = "\n".join(L.открытая_информация(st3, {}))
проверить("без зданий врага — сказано, что базы не видно, и «у базы» не считается",
          "его базы на карте не видно" in текст3 and "считать не по чему" in текст3, текст3)
L.ЦЕЛЬ_ПАРТИИ = ""

print("\nпривязка к настоящему коду:")
исходник = open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "llm_policy.py"), encoding="utf-8").read()
проверить("brow пишется в трассу", '"arow", "brow"' in исходник)
проверить("точка базы пишется в трассу", '_снимок["en_base"]' in исходник)
проверить("ключ --goal заведён и доезжает", '"--goal"' in исходник and 'globals()["ЦЕЛЬ_ПАРТИИ"]' in исходник)
проверить("риск фланга не печатает 1000000", 'их базы — не посчитать' in исходник)

print()
print("СБОЕВ: %d" % ошибок)
sys.exit(1 if ошибок else 0)
