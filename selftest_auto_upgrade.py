# -*- coding: utf-8 -*-
"""Ключ --auto-upgrade: военный апгрейд берёт мост, пока золота выше резерва.

Числа из отсечения обученной сети 27.09: без апгрейдов убитых 60 вместо 79 при
потерях 165 вместо 140. Подсказкой это делать нельзя (upgrades2, 15.09).
"""
import llm_policy as L

ошибок = []
ЦЕНЫ = ("bar.pikeman.1.1=f100g150i0,bar.pikeman.2.1=f200g300i50,"
        "aca.1=f0g500i0,mil.1=f0g80i0")
# Числа бойцов НАСТОЯЩИЕ, из записей 27.09: пикинёр atk8 против его dpike3 —
# урон 5, то есть ступень атаки не упирается в его защиту и должна давать выигрыш.
НАШИ = ("infantry17=pikeman,hp90,atk8,wkind1,pause0,rmax188,dpike3,dsword2,dbullet4"
        " musk17=musketeernet,hp65,atk10,wkind3,pause375,rmax1500,dpike0,dsword0,dbullet0")
ЕГО = ("infantry17=hp90,atk8,wkind1,pause0,rmax188,dpike3,dsword2,dbullet4"
       " musk17=hp65,atk10,wkind3,pause375,rmax1500,dpike0,dsword0,dbullet0")
такт = lambda **кв: dict({"upg_avail": ЦЕНЫ, "gold": 1000, "food": 900, "iron": 300,
                          "ba17": 1, "smiths": 1, "mills": 1, "centers": 1,
                          "fighters": НАШИ, "p1_fighters": ЕГО, "p1_enemy": 1,
                          "mil_inf": 40, "mil_shooters": 5,
                          "can_inf": "infantry17", "upg_done": "", "upg_doing": ""}, **кв)

# 1. ключ выключен — мост молчит
L.АПГРЕЙД_РЕЗЕРВ = 0
if L.апгрейд_ключом(такт()) is not None:
    ошибок.append("выключенный ключ купил апгрейд")

L.АПГРЕЙД_РЕЗЕРВ = 500
реш = L.апгрейд_ключом(такт())
if реш is None:
    ошибок.append("при 1000 золота и резерве 500 апгрейд обязан браться")
else:
    имя, текст = реш
    # 2. берётся ВОЕННЫЙ, а не академия и не мельница
    if len(имя.split(".")) != 4:
        ошибок.append(f"взят не военный апгрейд: {имя}")
    if имя.startswith(("aca", "mil", "cen")):
        ошибок.append(f"взято здание вместо бойца: {имя}")
    # 3. текст называет числа и ключ
    if "--auto-upgrade" not in текст:
        ошибок.append("текст не называет ключ")
    for ч in ("500", "40"):        # резерв и число бойцов, кого касается прибавка
        if ч not in текст:
            ошибок.append(f"в тексте нет числа {ч}")
    if "окупаемост" not in текст:
        ошибок.append("текст не говорит, что выбор сделан по окупаемости")

# 4. резерв соблюдается: золота ровно на цену, но резерв не остаётся
if L.апгрейд_ключом(такт(gold=200)) is not None:
    ошибок.append("резерв нарушен: при 200 золота покупать нельзя")
# 5. золота хватает и на цену, и на резерв — берём
if L.апгрейд_ключом(такт(gold=651)) is None:
    ошибок.append("651 золота хватает на цену 150 и резерв 500")

# 6. не хватает ДРУГОГО ресурса — не берём
if L.апгрейд_ключом(такт(food=10)) is not None:
    ошибок.append("еды не хватает, а апгрейд взят")

# 7. взятое не покупается второй раз (откатывает следующую ступень, замер 20.09)
реш = L.апгрейд_ключом(такт(upg_done="bar.pikeman.1.1"))
if реш and реш[0] == "bar.pikeman.1.1":
    ошибок.append("взятый апгрейд заказан повторно")

# 8. уже оплачиваемое не заказывается
реш = L.апгрейд_ключом(такт(upg_doing="bar.pikeman.1.1"))
if реш and реш[0] == "bar.pikeman.1.1":
    ошибок.append("идущий апгрейд заказан повторно")

# 9. нет казармы — военных апгрейдов не показывают, значит и не берём
реш = L.апгрейд_ключом(такт(ba17=0))
if реш and реш[0].startswith("bar."):
    ошибок.append("апгрейд казармы взят без казармы")

# 9а. ЗАПАС ЕДЫ (28.09, по серии auto_upgrade): еда узкое место, апгрейды её едят.
# При еде 900 и запасе 800 на ступень ценой 100 денег хватает ровно...
if L.апгрейд_ключом(такт(food=900)) is None:
    ошибок.append("еды 900 при запасе 800 хватает на ступень за 100")
# ...а при 850 уже нет: 850 - 800 = 50 < 100
if L.апгрейд_ключом(такт(food=850)) is not None:
    ошибок.append("запас еды нарушен: 850 - 800 = 50, а ступень стоит 100")
# и то же для дорогой ступени: 2.1 стоит 200 еды
if L.апгрейд_ключом(такт(food=950, gold=5000)) is None:
    ошибок.append("при 950 еды дешёвая ступень должна браться")

# 10. БЕЗ ПРИЗНАКА p1_enemy числа врага невидимы — ключ обязан молчать, а не
# покупать вслепую: поле_врага читает p<n>_fighters только при p<n>_enemy.
_без = такт(); _без.pop("p1_enemy")
if L.апгрейд_ключом(_без) is not None:
    ошибок.append("без p1_enemy числа врага не видны — покупать нельзя")

# 11. цены нет в строке — наугад не покупаем
if L.апгрейд_ключом(такт(upg_avail="bar.pikeman.1.1")) is not None:
    ошибок.append("апгрейд без цены куплен наугад")

# --- РЕЗЕРВ ЕДЫ (28.09, по итогу серии auto_upgrade) -------------------------
# Серия показала механизм провала: запас вычитался из ЗОЛОТА, а еда тратилась до
# нуля. Апгрейды стоят едой (bar.musketeernet.1.1 — 2000), и в двух копиях из трёх
# еда кончилась при золоте 7-11 тысяч: найм встал, мушкетёров и стрелков вышло
# НОЛЬ против 13 и 112 у базы. Здесь резерв и проверяется — тем, что он РЕШАЕТ
# исход: один и тот же такт при запасе покупкой не проходит, без запаса проходит.
L.АПГРЕЙД_РЕЗЕРВ = 500

# 12. цена 100 еды при 850 еды и резерве 800 — тратить нечем, покупать нельзя
L.АПГРЕЙД_РЕЗЕРВ_ЕДЫ = 800
реш = L.апгрейд_ключом(такт(food=850))
if реш is not None and реш[0] == "bar.pikeman.1.1":
    ошибок.append("резерв еды не сработал: куплен апгрейд за 100 еды при запасе 50")

# 13. тот же такт без резерва еды — апгрейд обязан взяться (значит дело в резерве,
#     а не в чём-то ещё)
L.АПГРЕЙД_РЕЗЕРВ_ЕДЫ = 0
реш = L.апгрейд_ключом(такт(food=850))
if реш is None or реш[0] != "bar.pikeman.1.1":
    ошибок.append("без резерва еды тот же апгрейд обязан браться — иначе "
                  "проверка 12 ничего не доказывает")

# 14. еды хватает с запасом — берётся как прежде
L.АПГРЕЙД_РЕЗЕРВ_ЕДЫ = 800
if L.апгрейд_ключом(такт(food=1600)) is None:
    ошибок.append("при 1600 еды и резерве 800 апгрейд обязан браться")

# 15. про оба резерва сказано ВСЛУХ: молчаливый отказ неотличим от бездействия
реш = L.апгрейд_ключом(такт(food=1600))
# Ищем ЧИСЛО и назначение, а не формулировку: текст вслух пережил слияние двух
# правок, и проверка, привязанная к чужим словам, падала бы на каждой их редакции.
if реш and not ("800" in реш[1] and "найм" in реш[1]):
    ошибок.append("запас еды не назван вслух: " + реш[1][:140])
if реш and "резерв 500" not in реш[1] and "(резерв 500" not in реш[1]:
    ошибок.append("резерв золота не назван вслух: " + реш[1][:140])

# 16. умолчание ключа — 800 (двадцать мушкетёров по 40), и флаг существует
import io as _io
_ИСХ = _io.open(__file__.replace("selftest_auto_upgrade.py", "llm_policy.py"),
                encoding="utf-8").read()
if "АПГРЕЙД_РЕЗЕРВ_ЕДЫ: int = 800" not in _ИСХ:
    ошибок.append("умолчание резерва еды не 800")
if '"--auto-upgrade-food"' not in _ИСХ:
    ошибок.append("флага --auto-upgrade-food нет")

L.АПГРЕЙД_РЕЗЕРВ = 0
L.АПГРЕЙД_РЕЗЕРВ_ЕДЫ = 800
print("selftest_auto_upgrade: " + ("ОК, 19 проверок (8 про запас еды: нашли порознь, оставили одну реализацию)" if not ошибок
                                   else "ОШИБКИ\n  " + "\n  ".join(ошибок)))
raise SystemExit(1 if ошибок else 0)
