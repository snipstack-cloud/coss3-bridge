#!/usr/bin/env python3
"""ВЫХОД К ЕГО КРЕСТЬЯНАМ ПО СРОКУ (21.10, §169г, ключ `выход_к` — слово игрока): такты Д9 из
`sim/кейсы/партия_д9_20_10_0_12-15_15.jsonl` (мост c8effaa). В Д9 бот выиграл армию (214 против 89, размен 4,86) и НЕ ВЗЯЛ
ЦЕЛЬ: его крестьян убито 0, осталось 84; все 17 волн шли по его бойцам. Ключ: после срока, при нуле убитых крестьян и
перевесе дома — `ATTACK peasants` силой дома, в обход вето волны (`_держим_дом`, `не_навстречу`, `НЕ_ГОНИМСЯ` — они считают
силу ВОЛНЫ, не дома).

(а) до срока ни приказа, ни строки; после срока без перевеса — строка `ВЫХОД_К: ждём` с числами; (б) выход ровно один, в
13:02: `ATTACK target=peasants` с `count` = домашних (189, а не 27 волны), в why R и клетка; (в) при убитых крестянах
правило молчит («цель взята»); (г) ключ 0 — команды и why байт в байт как без ключей; (д) ЗАМЕР ЗАДАНИЯ: с
`выход_перевес` 1,2 (как просил мак) ключ на Д9 НЕ СРАБАТЫВАЕТ НИ РАЗУ — потому в файле 1,1; (е) приказ забирает такт: удара
готовой волны этим тактом нет, и ручеёк судит приказ порогом `выход_R`, а не `размен_при` (строка РАЗМЕН_ОК).
    python3 selftest_выход_к.py
"""
import copy, json, os, sys, tempfile
К = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, К); sys.path.insert(0, os.path.join(К, "sim"))
os.environ.pop("COSS3_WAVE_CONTRACT", None)
import strategy_live as SL
import анализ_врага as АВ

кейс = [json.loads(l) for l in open(os.path.join(К, "sim/кейсы/партия_д9_20_10_0_12-15_15.jsonl"), encoding="utf-8")]
ФАЙЛ = os.path.join(К, "sim/поиск/шт_s2_оборона_ручеёк_эко_так15_нужда.json")
ошибок = 0


def проверить(усл, что):
    global ошибок
    print(("ОК   " if усл else "ОШИБКА ") + что); ошибок += not усл


def стратегия(доп):
    д = json.load(open(ФАЙЛ, encoding="utf-8"))
    assert д["итог"].get("выход_к") == 780 and д["итог"].get("выход_перевес") == 1.1, "ключи выхода в файле стратегии"
    д["итог"].update(доп)
    with tempfile.NamedTemporaryFile("w", suffix=".json", delete=False, encoding="utf-8") as f:
        json.dump(д, f, ensure_ascii=False)
    return SL.ЖиваяСтратегия(f.name)


def прогон(доп, правка=None, t0=0, t1=10000):
    С = стратегия(доп); из = {}
    for s in кейс:
        gt = int(float(s["gametime"]))
        if gt < t0 or gt > t1:
            continue
        s = copy.deepcopy(s)
        if правка is not None:
            правка(gt, s)
        АВ._ТЕКУЩИЙ.update({"а": None, "t": None, "ответ": None})
        из[gt] = (s, С.ответ(s))
    return из


def строки(о, что="ВЫХОД_К"):
    return [ч for ч in str(о.get("why") or "").split("; ") if что in ч]


def выходы(п):
    return [gt for gt, (s, о) in п.items() if any("ВЫХОД_К: выход" in ч for ч in строки(о))]


п = прогон({})
до = [gt for gt, (s, о) in п.items() if gt < 780 and строки(о)]
проверить(not до, f"(а) до 13:00 ни одной строки ВЫХОД_К: {до[:3]}")
ждём = [gt for gt, (s, о) in п.items() if any("ВЫХОД_К: ждём" in ч for ч in строки(о))]
проверить(len(ждём) >= 5 and min(ждём) >= 780,
          f"(а) после срока без перевеса строка «ждём»: тактов {len(ждём)}, первый {min(ждём) if ждём else '-'}")
проверить(all("наших дома" in ч and "крестьян убито 0" in ч
              for gt, (s, о) in п.items() for ч in строки(о) if "ждём" in ч),
          "(а) в строке «ждём» названы оба числа — убитых крестьян и дома против его")

в = выходы(п)
проверить(в == [782], f"(б) выход ровно один, в 13:02: {[f'{g//60}:{g%60:02d}' for g in в]}")
if в:
    s, о = п[в[0]]
    атаки = [c for c in о["commands"] if c["cmd"] == "ATTACK" and c.get("_выход_к")]
    дома = SL.домашних_бойцов(s)
    проверить(len(атаки) == 1 and атаки[0].get("target") == "peasants" and int(атаки[0].get("count") or 0) == дома == 189,
              f"(б) один ATTACK peasants силой дома ({дома}): {атаки}")
    стр = строки(о)[0]
    проверить("R=" in стр and "peasants 12,0" in стр, f"(б) в why клетка и прогноз: {стр[:120]}")
    проверить(any("РАЗМЕН_ОК из дома 189" in ч for ч in строки(о, "РАЗМЕН_ОК")),
              "(е) ручеёк приказ не снял и посчитал своим прогнозом")
    проверить(not any(c["cmd"] == "ATTACK" and not c.get("_выход_к") and not c.get("_огонь") for c in о["commands"]),
              f"(е) удара готовой волны этим тактом нет: {[c for c in о['commands'] if c['cmd'] == 'ATTACK']}")

def убил(gt, s):
    if gt >= 780:
        s["p1_pea_lost"] = float(s.get("p1_pea_lost") or 0) + 3
пв = прогон({}, убил)
взята = [gt for gt, (s, о) in пв.items() if any("цель взята" in ч for ч in строки(о))]
проверить(not выходы(пв) and взята, f"(в) при убитых крестьянах выхода нет, строка «цель взята»: тактов {len(взята)}")

п0, пн = прогон({"выход_к": 0}), прогон({"выход_к": 0, "выход_перевес": 1.2})
# why сравнивается без первой части: там имя временного файла стратегии, оно у двух прогонов разное
без_имени = lambda о: "; ".join(str(о.get("why") or "").split("; ")[1:])
проверить(all(без_имени(п0[gt][1]) == без_имени(пн[gt][1]) and п0[gt][1]["commands"] == пн[gt][1]["commands"]
              for gt in п0),
          "(г) ключ 0: прочие ключи выхода ничего не меняют")
проверить(not any(строки(о) for gt, (s, о) in п0.items()), "(г) ключ 0: ни одной строки ВЫХОД_К")

п12 = прогон({"выход_перевес": 1.2})
проверить(not выходы(п12),
          "(д) ЗАМЕР: с выход_перевес 1,2 ключ на Д9 не срабатывает ни разу — в файле 1,1")

print("ИТОГ:", "чисто" if not ошибок else f"ошибок {ошибок}")
sys.exit(1 if ошибок else 0)
