#!/usr/bin/env python3
"""ВЫХОД К ЕГО КРЕСТЬЯНАМ ПО СРОКУ (§169г, ключ `выход_к`), ПЕРЕВЕС ПО ЗАКОНУ УРОНА (§170, 22.10, слово игрока).

В Д9 бот выиграл армию (размен 4,86) и не взял цель: его крестьян убито 0. Ключ: после срока, при нуле убитых крестьян и
перевесе — `ATTACK peasants` силой дома, в обход вето волны (`_держим_дом`, `не_навстречу`, `НЕ_ГОНИМСЯ` считают силу ВОЛНЫ,
не дома). Перевес сперва считался ПО ГОЛОВАМ, и партия Д10 показала, что такая мера негодна: 27 тактов «ждём» при нашем
ударе 8 против его 1 (наш пикинёр 11/7 против 8/3), потому что голов было 185 против 195. Слово игрока 22.10 — считать по
закону урона (`combat_math.урон`: атака минус защита по типу оружия, не меньше 1), сила = головы × урон за удар.

Судьи — два кейса живых партий: Д9 (`партия_д9_20_10_0_12-15_15.jsonl`) и Д10 (`партия_д10_21_10_11-00_15-13.jsonl`).
(а) до срока ни строки, после срока без перевеса — `ВЫХОД_К: ждём` с обоими числами; (б) Д10: выход в 13:01, один
`ATTACK peasants` силой дома, в why сила 1480 против 195; (в) при убитых крестьянах правило молчит; (г) ключ 0 — команды и
why байт в байт как без ключей; (д) ЗАМЕР, из-за которого мера и поменялась: по головам при 1,1 в Д10 выходов НОЛЬ;
(е) приказ забирает такт (удара готовой волны нет) и ручеёк судит его порогом `выход_R`; (ж) Д9: по урону выход в 13:13 —
там его пикинёр сперва СИЛЬНЕЕ нашего (13/5 против 11/5, удар 6 против 8), и правило честно ждёт, пока не возьмём 1.3.
    python3 selftest_выход_к.py
"""
import copy, json, os, sys, tempfile
К = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, К); sys.path.insert(0, os.path.join(К, "sim"))
os.environ.pop("COSS3_WAVE_CONTRACT", None)
import strategy_live as SL
import анализ_врага as АВ

КЕЙСЫ = {
    "Д9": [json.loads(l) for l in open(os.path.join(К, "sim/кейсы/партия_д9_20_10_0_12-15_15.jsonl"), encoding="utf-8")],
    "Д10": [json.loads(l) for l in open(os.path.join(К, "sim/кейсы/партия_д10_21_10_11-00_15-13.jsonl"), encoding="utf-8")],
}
ФАЙЛ = os.path.join(К, "sim/поиск/шт_s2_оборона_ручеёк_эко_так15_нужда.json")
ошибок = 0


def проверить(усл, что):
    global ошибок
    print(("ОК   " if усл else "ОШИБКА ") + что); ошибок += not усл


def стратегия(доп):
    д = json.load(open(ФАЙЛ, encoding="utf-8"))
    assert д["итог"].get("выход_к") == 780 and д["итог"].get("выход_перевес") == 1.0, "ключи выхода в файле стратегии"
    # 30.10: три ключа §170н включены в живом файле по слову игрока (партия с Польшей); здесь судится выход §169г как жил —
    # сила врага сырыми бойцами («195×1»). Пришпилены к 0; пересчёт качеством проверяет случай (б2) ниже.
    for _к5 in ("качество_врага", "стрелки_против_брони", "конюшня_его"):
        д["итог"][_к5] = 0
    д["итог"].update(доп)
    with tempfile.NamedTemporaryFile("w", suffix=".json", delete=False, encoding="utf-8") as f:
        json.dump(д, f, ensure_ascii=False)
    return SL.ЖиваяСтратегия(f.name)


def прогон(кейс, доп=None, правка=None):
    С = стратегия(доп or {}); из = {}
    for s in КЕЙСЫ[кейс]:
        s = copy.deepcopy(s)
        gt = int(float(s["gametime"]))
        if правка is not None:
            правка(gt, s)
        АВ._ТЕКУЩИЙ.update({"а": None, "t": None, "ответ": None})
        из[gt] = (s, С.ответ(s))
    return из


def строки(о, что="ВЫХОД_К"):
    return [ч for ч in str(о.get("why") or "").split("; ") if что in ч]


def выходы(п):
    return [gt for gt, (s, о) in п.items() if any("ВЫХОД_К: выход" in ч for ч in строки(о))]


# --- Д10: по головам правило молчало, по урону обязано выйти в 13:01 -------------------
п10 = прогон("Д10")
до = [gt for gt, (s, о) in п10.items() if gt < 780 and строки(о)]
проверить(not до, f"(а) до 13:00 ни одной строки ВЫХОД_К: {до[:3]}")
в10 = выходы(п10)
# В кейсе снимки — запись прошлой партии: `mil_away` в них нулевое всегда, и дома снова полная армия —
# поэтому правило честно повторяет выход через `выход_повтор` (п. 6 задания). Вживую ушедшая армия сразу
# уронит домашнюю силу, и повтора не будет (в Д10 так и случилось). Судим первый выход и расстояние между повторами.
проверить(в10 and в10[0] == 781 and all(b - a >= 60 for a, b in zip(в10, в10[1:])),
          f"(б) Д10: первый выход в 13:01, повторы не чаще 60 с: {[f'{g // 60}:{g % 60:02d}' for g in в10]}")
if в10:
    s, о = п10[в10[0]]
    атаки = [c for c in о["commands"] if c["cmd"] == "ATTACK" and c.get("_выход_к")]
    дома = SL.домашних_бойцов(s)
    проверить(len(атаки) == 1 and атаки[0].get("target") == "peasants" and int(атаки[0].get("count") or 0) == дома == 185,
              f"(б) один ATTACK peasants силой дома ({дома}): {атаки}")
    стр = строки(о)[0]
    проверить("185×8 = 1480" in стр and "195×1 = 195" in стр and "по закону урона" in стр,
              f"(б) в why сила обеих сторон по закону урона: {стр[-120:]}")
    # (б2) 30.10: с `качество_врага` 1 его 195 сырых бойцов пересчитаны в наши пики (§170н, веса из p1_fighters) — число меньше 195
    import re as _re
    С2 = стратегия({"выход_к": 780, "качество_врага": 1})
    _стр2 = ""
    for s2 in КЕЙСЫ["Д10"]:
        АВ._ТЕКУЩИЙ.update({"а": None, "t": None, "ответ": None}); о2 = С2.ответ(copy.deepcopy(s2))
        _м2 = _re.search(r"против его (\d+)×1 = (\d+) \(по закону урона\)", о2["why"])
        if _м2:
            _стр2 = _м2.group(0); _его2 = int(_м2.group(1)); break
    проверить(bool(_стр2) and _его2 < 195, f"(б2) с качество_врага 1 его сила пересчитана в пики (< 195): «{_стр2}»")
    проверить(any("РАЗМЕН_ОК из дома 185" in ч for ч in строки(о, "РАЗМЕН_ОК")),
              "(е) ручеёк приказ не снял и посчитал своим прогнозом")
    проверить(not any(c["cmd"] == "ATTACK" and not c.get("_выход_к") and not c.get("_огонь") for c in о["commands"]),
              f"(е) удара готовой волны этим тактом нет: {[c for c in о['commands'] if c['cmd'] == 'ATTACK']}")

def убил(gt, s):
    if gt >= 780:
        s["p1_pea_lost"] = float(s.get("p1_pea_lost") or 0) + 3
пв = прогон("Д10", правка=убил)
взята = [gt for gt, (s, о) in пв.items() if any("цель взята" in ч for ч in строки(о))]
проверить(not выходы(пв) and взята, f"(в) при убитых крестьянах выхода нет, строка «цель взята»: тактов {len(взята)}")

п0, пн = прогон("Д10", {"выход_к": 0}), прогон("Д10", {"выход_к": 0, "выход_перевес": 1.2})
без_имени = lambda о: "; ".join(str(о.get("why") or "").split("; ")[1:])   # в первой части имя временного файла
проверить(all(без_имени(п0[gt][1]) == без_имени(пн[gt][1]) and п0[gt][1]["commands"] == пн[gt][1]["commands"] for gt in п0),
          "(г) ключ 0: прочие ключи выхода ничего не меняют")
проверить(not any(строки(о) for gt, (s, о) in п0.items()), "(г) ключ 0: ни одной строки ВЫХОД_К")

# --- (д) ЗАМЕР: прежняя мера по головам. Снимаем рода войск — правило переходит на головы --
def без_родов(gt, s):
    s.pop("fighters", None); s.pop("p1_fighters", None)
пг = прогон("Д10", {"выход_перевес": 1.1}, без_родов)
проверить(not выходы(пг) and any("по головам" in ч for gt, (s, о) in пг.items() for ч in строки(о)),
          "(д) ЗАМЕР: по головам при 1,1 в Д10 выходов ноль — потому мера и поменялась на закон урона")

# --- (ж) Д9: его пикинёр сперва сильнее, правило ждёт до 1.3 ---------------------------
п9 = прогон("Д9")
в9 = выходы(п9)
проверить(в9 and в9[0] == 793,
          f"(ж) Д9: выход в 13:13, когда взяли 1.3 (до того его удар 8 против нашего 6): "
          f"{[f'{g // 60}:{g % 60:02d}' for g in в9[:3]]}")
ждём9 = [ч for gt, (s, о) in п9.items() if gt < 793 and gt >= 780 for ч in строки(о) if "ждём" in ч]
проверить(ждём9 and "сила" in ждём9[0], f"(ж) Д9 до выхода — «ждём» с силой обеих сторон: {ждём9[0][-90:] if ждём9 else '—'}")

print("ИТОГ:", "чисто" if not ошибок else f"ошибок {ошибок}")
sys.exit(1 if ошибок else 0)
