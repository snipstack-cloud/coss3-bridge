# -*- coding: utf-8 -*-
"""Простой крестьян и событийные вызовы — партия за партией.

Главная мера идеи `free_hands` названа до прогона: ДОЛЯ ПРОСТОЯ КРЕСТЬЯН, то
есть крестьяно-секунды простоя к крестьяно-секундам всего. Считать её глазами
нельзя — в трассе она не лежит готовой, и «свободных 5» в одном такте значит
разное при 20 и при 100 крестьянах.

    python3 idle_report.py <каталог идеи> [<каталог базы>]

Каталог — тот, где лежат копии прогона (`.../<дата>/<идея>/`), или сразу одна
копия. Партии внутри копии разделяются записью `finish`.

Что печатается и почему:
  * доля простоя — мера 1, ради неё всё;
  * события «руки» и их промежуток — мера 2: повода не случилось, значит
    меряли выключенный ключ (так 21.09 уже вышло с мерой «событий ноль»);
  * BALANCE от события против BALANCE обычного такта и урезания моста — мера 3;
  * ответы «жду» — мера 4: если почти всегда, повод не нужен;
  * такты с едой ниже порога — мера 5;
  * вехи и обычные такты — контроль: событийный вызов сдвигает `next_call`,
    поэтому обычных тактов станет меньше, и это названо признаком вреда.
"""
import json, glob, sys, statistics as S


def ч(v):
    try:
        return float(v)
    except (TypeError, ValueError):
        return 0.0


def партии(каталог):
    """[(файл, [такты], финал)] — по одной записи на партию."""
    ф = sorted(glob.glob(f"{каталог}/**/coss3_bot.jsonl", recursive=True))
    for файл in ф:
        текущая = []
        for строка in open(файл, encoding="utf-8"):
            строка = строка.strip()
            if not строка:
                continue
            x = json.loads(строка)
            if "finish" in x:
                yield файл, текущая, x
                текущая = []
                continue
            if isinstance(x.get("state"), dict) and "gametime" in x["state"]:
                текущая.append(x)
        if текущая:
            yield файл, текущая, {}


def партия_числами(такты, финал):
    простой = труд = 0.0
    событий = 0
    моменты = []
    bal_событие = bal_такт = урезаний = ждали = 0
    под_порогом = 0
    for i, т in enumerate(такты):
        st = т["state"]
        dt = 21.0                      # шаг по умолчанию: столько же, сколько медиана
        if i + 1 < len(такты):
            d = ч(такты[i + 1]["state"]["gametime"]) - ч(st["gametime"])
            if 0 < d < 300:
                dt = d
        простой += ч(st.get("idle_pea")) * dt
        труд += ч(st.get("peasants")) * dt
        if ч(st.get("food")) < 500:
            под_порогом += 1
        # СОБЫТИЕ: поле «повод» завели 21.09; в трассах до него есть только
        # метка «событие», и по ней вид определяется префиксом. Неизвестного
        # за ноль не выдаём — считаем отдельно.
        повод = т.get("повод") or ""
        метка = str(т.get("событие") or "")
        если_руки = повод == "руки" or метка.startswith("руки#")
        if если_руки:
            событий += 1
            моменты.append(ч(st.get("gametime")))
        почему = str(т.get("why") or "")
        for c in (т.get("cmds") or []):
            if str(c.get("cmd") or c)[:7] == "BALANCE":
                if если_руки:
                    bal_событие += 1
                else:
                    bal_такт += 1
        if если_руки:
            if "просили" in почему:
                урезаний += 1
            if "ЖДУ" in почему or "никого не двигал" in почему:
                ждали += 1
    промежутки = [b - a for a, b in zip(моменты, моменты[1:])]
    веха = any(т.get("веха_убийства") for т in такты)
    return {
        "тактов": len(такты),
        "обычных": len(такты) - событий,
        "простой": простой, "труд": труд,
        "доля": 100 * простой / труд if труд else 0.0,
        "событий": событий,
        "промежуток": S.median(промежутки) if промежутки else None,
        "bal_событие": bal_событие, "bal_такт": bal_такт,
        "урезаний": урезаний, "ждали": ждали,
        "под_порогом": под_порогом,
        "веха": веха, "финал": str(финал.get("finish") or "?"),
    }


def свод(каталог):
    ряды = [партия_числами(т, ф) for _, т, ф in партии(каталог) if т]
    if not ряды:
        print(f"{каталог}: партий не нашлось")
        return None
    print(f"\n{каталог}: партий {len(ряды)}")
    print(f"  {'#':>2} {'тактов':>7} {'обычных':>8} {'ПРОСТОЙ':>8} {'событий':>8} "
          f"{'промеж':>7} {'BAL соб/такт':>13} {'урезал':>7} {'ждал':>5} "
          f"{'еда<500':>8} {'веха':>5}")
    for i, р in enumerate(ряды, 1):
        print(f"  {i:>2} {р['тактов']:>7} {р['обычных']:>8} {р['доля']:>7.1f}% "
              f"{р['событий']:>8} "
              + (f"{р['промежуток']:>7.0f}" if р["промежуток"] else f"{'-':>7}")
              + f" {р['bal_событие']:>6}/{р['bal_такт']:<6} {р['урезаний']:>7} "
              f"{р['ждали']:>5} {р['под_порогом']:>8} {'да' if р['веха'] else 'нет':>5}")
    доли = [р["доля"] for р in ряды]
    print(f"  ИТОГО: простой медиана {S.median(доли):.1f}% "
          f"(разброс {min(доли):.1f}-{max(доли):.1f}), "
          f"событий всего {sum(р['событий'] for р in ряды)}, "
          f"вех {sum(1 for р in ряды if р['веха'])}/{len(ряды)}")
    return ряды


def main():
    if len(sys.argv) < 2:
        print(__doc__)
        raise SystemExit(2)
    идея = свод(sys.argv[1])
    база = свод(sys.argv[2]) if len(sys.argv) > 2 else None
    if идея and база:
        ди = S.median([р["доля"] for р in идея])
        дб = S.median([р["доля"] for р in база])
        print(f"\nГЛАВНАЯ МЕРА: простой {ди:.1f}% против {дб:.1f}% у базы "
              f"({ди - дб:+.1f} пункта)")
        # Три копии - наблюдение, а не измерение: это правило проекта, и
        # печатается оно здесь, чтобы разность не прочли как доказанную.
        if len(идея) < 9 or len(база) < 9:
            print("  ОСТОРОЖНО: партий мало, это наблюдение, а не измерение")
        ви, вб = (sum(1 for р in идея if р["веха"]), sum(1 for р in база if р["веха"]))
        print(f"КОНТРОЛЬ: вех {ви}/{len(идея)} против {вб}/{len(база)}; "
              f"обычных тактов медиана {S.median([р['обычных'] for р in идея]):.0f} "
              f"против {S.median([р['обычных'] for р in база]):.0f} — "
              f"событие сдвигает next_call, и это названный признак вреда")


if __name__ == "__main__":
    main()
