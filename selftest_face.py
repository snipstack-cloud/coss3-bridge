"""НАПРАВЛЕНИЕ СТРОЯ в приказах моста и приказ FACE (§98, 5.10).

Что нашлось (задание мака). `block_hcmd.inc` звал
`_player_SetGroupPosition(..., dirX, dirZ, ...)` с направлением, вписанным
КОНСТАНТОЙ `0, 1` — во всех приказах, всю историю проекта. Движок по этому
вектору делает две вещи (`units/global.inc/writemove.inc`): строит сетку группы
(ряды вдоль dir, шеренги поперёк, через `VectorRotateY(-90)`) и каждому бойцу
даёт `_unit_OrderMove(..., dirx, dirz)` — дошёл и повернулся туда. Итог: каждый
наш строй смотрел к +Z карты. В проверке 5 наша база была в (12,13), его в
(1,2), то есть `0,1` — это в сторону НАШЕЙ базы, и игрок подтвердил глазами:
стояли спиной к врагу. Урон от направления не зависит (`_misc_DoDamage` его не
читает); зависит построение и то, куда смотрят ряды, а стрелок, которого
развернули под огнём, не стреляет (`radiusmin`).

Что проверяется:
  1. константы `0, 1` в приказах не осталось, вектор считается;
  2. считается он ОТ ЦЕНТРА ПОСЫЛАЕМЫХ (среднее по `gIntegerList`), а не от
     ратуши и не от центра группы-получателя;
  3. поле `face` главнее всего остального, а вырожденный случай оставляет `0,1`
     И ГОВОРИТ ОБ ЭТОМ — иначе он неотличим от измеренного направления;
  4. отход смотрит НА ВРАГА, а не по ходу движения;
  5. приказ FACE поворачивает на месте, цели не требует и режим группы не
     переписывает (поворот — не миссия);
  6. лог несёт `dir=` с двумя цифрами, и они собраны из сотых, потому что
     `FloatToStrF` в этом движке нет;
  7. python: `face` разбирается у любой команды, доезжает в файл приказа полями
     `fx`/`fy`, FACE без клетки отвергается вслух;
  8. стратегия клеит `face` отходу ОДНИМ местом на все его ветки;
  9. водители руками (`приказы_рукой`, `send`) умеют и клетку взгляда, и FACE.
"""
