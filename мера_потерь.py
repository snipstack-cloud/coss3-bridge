#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""МЕРА РАСКЛАДКИ ПОТЕРЬ: для скольких смертей удалось назвать клетку.

Блок раз в игровую секунду спрашивает СНАЧАЛА картовый счётчик (`my_mil_lost`,
он же `gPlayer.stat.killed`): сколько погибло — он знает точно. И только если
счётчик двинулся, смотрит, в каких клетках убыло наших, и раскладывает ровно этот
бюджет. Поэтому проверять надо не сумму.

* СХОДИМОСТЬ — сумма по клеткам плюс неопознанные равны счётчику, точно, без
  допуска. Это сторож КОДА: разойтись они могут только из-за ошибки в блоке.
  Прежняя мера («сумма против счётчика в пределах 10 %») с этим устройством верна
  по построению и потому не проверяет ничего — проверка, которая не может
  провалиться, хуже её отсутствия;
* КАЧЕСТВО — доля смертей, которым клетки не нашлось вовсе (`lost_cells_odd`).
  Это единственное, что здесь действительно неизвестно заранее.

Чего мера не видит: смерть, положенную не в ту клетку, когда убыль в настоящей
клетке закрыта подкреплением, подошедшим в ту же секунду.

Такты без ратуши считаются отдельно: секция сеток закрыта `if (hscen > 0)`, и без
ратуши раскладки нет, а счётчик идёт.

    python мера_потерь.py --dir "<папка игры>"            # живая партия, раз в 3 с
    python мера_потерь.py --snap coss3_snap.jsonl         # по готовым снимкам
    python мера_потерь.py --dir "<игра>" --seconds 900    # сколько следить

Живьём числа читаются ВТОРЫМ окном: состояние переписывается каждую игровую
секунду, и смотреть его надо, не мешая партии.
"""
from __future__ import annotations

import argparse
import json
import os
import sys
import time

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import coss3_map as M
from coss3_bridge import Bridge


def _ц(v, п=0):
    try:
        return int(float(v))
    except (TypeError, ValueError):
        return п


def приговор(сумма: int, без_клетки: int, счётчик: int,
             допуск: float = 0.10) -> str:
    """Словами. Две разные вещи в одном приговоре, и путать их нельзя.

    СХОДИМОСТЬ (сумма плюс неопознанные равны счётчику) — сторож кода: блок
    раскладывает бюджет, названный счётчиком, и разойтись они могут только из-за
    ошибки. КАЧЕСТВО — доля смертей, которым клетки не нашлось вовсе. Прежний
    приговор сравнивал сумму со счётчиком и с этим устройством был бы верен
    всегда — проверка, которая не может провалиться, хуже её отсутствия.
    """
    if счётчик == 0 and сумма == 0 and без_клетки == 0:
        return "нечего мерить: не погиб никто"
    if (сумма + без_клетки) != счётчик:
        return (f"НЕ СХОДИТСЯ: по клеткам {сумма} + без клетки {без_клетки} "
                f"против счётчика {счётчик} — это ошибка в блоке, а не качество")
    if счётчик == 0:
        return f"СЧЁТЧИК НОЛЬ при сумме {сумма} — поле выдумывает смерти"
    доля = без_клетки / счётчик
    слово = "ХОРОШО" if доля <= допуск else "ПЛОХО"
    return (f"{слово}: разложено {сумма} из {счётчик}, без клетки {без_клетки} "
            f"({доля:.1%})")


def по_снимкам(путь: str, допуск: float) -> int:
    """Последняя запись партии несёт накопленное за неё целиком."""
    последняя = None
    строк = 0
    for строка in open(путь, encoding="utf-8"):
        строка = строка.strip()
        if not строка:
            continue
        try:
            з = json.loads(строка)
        except ValueError:
            continue
        строк += 1
        if M.есть_потери_клеток(з) or "lost_cells_sum" in з:
            последняя = з
    if последняя is None:
        print(f"{путь}: записей {строк}, поля раскладки нет ни в одной — "
              "это снимки ДО правки 27.09, а не провал меры")
        return 0
    мера = M.мера_потерь_по_клеткам(последняя, допуск) or {}
    print(f"{путь}: записей {строк}")
    print(f"  клеток с потерями {мера.get('клеток')}, "
          f"не влезло в строку {мера.get('не_влезло')}")
    print("  " + приговор(_ц(последняя.get("lost_cells_sum")),
                          _ц(последняя.get("lost_cells_odd")),
                          _ц(последняя.get("my_mil_lost")), допуск))
    return 0 if (мера.get("сходится") and мера.get("качество")) else 1


def живьём(d: str, plind: int, секунд: float, шаг: float, допуск: float) -> int:
    br = Bridge(d, plind)
    начало = time.time()
    прошлое = None
    без_ратуши = 0
    тактов = 0
    while time.time() - начало < секунд:
        try:
            st = br.read_state()
        except Exception as e:                      # партия могла кончиться
            print(f"состояние не прочитано: {e}", flush=True)
            time.sleep(шаг)
            continue
        if not st:
            time.sleep(шаг)
            continue
        if not M.есть_потери_клеток(st):
            print("поля lost_cells в состоянии НЕТ — либо мост старый, либо "
                  "секция сеток не работает (нет ратуши)", flush=True)
            time.sleep(шаг)
            continue
        тактов += 1
        if _ц(st.get("centers")) == 0:
            без_ратуши += 1
        gt = _ц(st.get("gametime"))
        сумма = _ц(st.get("lost_cells_sum"))
        без_клетки = _ц(st.get("lost_cells_odd"))
        счётчик = _ц(st.get("my_mil_lost"))
        клетки = M.потери_клеток(st)
        # Печатаем ТОЛЬКО когда числа сдвинулись: партия идёт пятнадцать минут, и
        # ровная простыня одинаковых строк прячет то самое место, где разъехалось.
        текущее = (сумма, без_клетки, счётчик)
        if текущее != прошлое:
            прошлое = текущее
            верх = sorted(клетки, key=lambda к: -к["погибло"])[:4]
            где = " ".join(f"{к['x']},{к['y']}:{к['погибло']}" for к in верх)
            print(f"{gt:5d} с  по клеткам {сумма:4d}  без клетки {без_клетки:3d}  "
                  f"счётчик {счётчик:4d}  клеток {len(клетки):2d}  {где}", flush=True)
        time.sleep(шаг)
    print()
    print(f"тактов прочитано {тактов}, из них без ратуши {без_ратуши}")
    п = прошлое or (0, 0, 0)
    итог = приговор(п[0], п[1], п[2], допуск)
    print("ИТОГ: " + итог)
    return 0 if итог.startswith(("ХОРОШО", "нечего")) else 1


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dir", default="", help="папка игры: следить за живой партией")
    ap.add_argument("--snap", default="", help="файл снимков coss3_snap.jsonl")
    ap.add_argument("--plind", type=int, default=0)
    ap.add_argument("--seconds", type=float, default=960.0)
    ap.add_argument("--step", type=float, default=3.0)
    ap.add_argument("--tolerance", type=float, default=0.10)
    a = ap.parse_args()
    if a.snap:
        return по_снимкам(a.snap, a.tolerance)
    if not a.dir:
        ap.error("нужен --dir или --snap")
    return живьём(a.dir, a.plind, a.seconds, a.step, a.tolerance)


if __name__ == "__main__":
    raise SystemExit(main())
