# -*- coding: utf-8 -*-
"""Собирает НАСТОЯЩИЕ запросы события «кого нанимать» из состояний отыгранных партий.

ВАЖНО, куплено ошибкой 21.09: событие срабатывает на ДОСТРОЙКЕ здания, значит
его очередь ПУСТА. Первая версия стенда всегда спрашивала про здание №1, и в
12 задачах из 13 оно уже ковало — такой обстановки в событии не бывает, и все
измерения шли по запросу, которого мост не отдаёт. Теперь номер выбирается
так, чтобы очередь ИМЕННО ЭТОГО здания была пустой.

Событий в трассах ещё нет — правка от 20.09 вечера. Поэтому запрос строится тем
же кодом, каким его строит мост (`запрос_найма`), но на снимках состояния из
настоящих партий. Берутся разные моменты: с углём и без, со стрелками и без,
ранние и поздние — чтобы задача не выродилась в один и тот же ответ.

    python3 bench_hire_cases.py [<каталог с прогонами>] [<куда писать задачи>]
"""
import json, glob, os, sys
# Путь к мосту берём ОТ ЭТОГО ФАЙЛА, а не абсолютом: иначе копия стенда из
# git worktree молча импортирует llm_policy рабочей копии и померит не ту
# версию. 21.09 так и вышло при сравнении форматов на стенде рук.
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import llm_policy as L

# ГДЕ ТРАССЫ — АРГУМЕНТОМ, а не зашито. Прежде здесь стоял `res4/2026-09-20`:
# каталог, которого нет ни на маке, ни на Windows, и стенд молча собирал НОЛЬ
# задач, печатая это одной строкой среди прочих. Поиск идёт в глубину, поэтому
# годится и каталог идеи (`<дата>/<идея>/`), и одна копия, и весь клон
# результатов.
#
# ВНИМАНИЕ ПРИ СРАВНЕНИИ С ПРЕЖНИМИ ЧИСЛАМИ: замеры 21.09 («13 задач, 2,0-2,2 с»)
# сняты на другом наборе состояний. Сменили каталог — числа несравнимы, надо
# перемерять обе стороны.
КАТАЛОГ = (sys.argv[1] if len(sys.argv) > 1
           else os.path.expanduser('~/coss3-res/2026-09-21/base24'))

состояния = []
файлов = sorted(glob.glob(os.path.join(КАТАЛОГ, '**', 'coss3_bot.jsonl'),
                          recursive=True))
if not файлов:
    raise SystemExit(f"трасс не нашлось: {os.path.join(КАТАЛОГ, '**', 'coss3_bot.jsonl')}\n"
                     f"Укажи каталог первым аргументом: "
                     f"python3 bench_hire_cases.py <каталог с прогонами>")
print(f'трасс: {len(файлов)} в {КАТАЛОГ}')
for f in файлов:
    # encoding ЯВНО: на маке умолчание utf-8, на Windows — cp1252, и стенд
    # там падал на первой же трассе (22.09). Умолчание системы читать нельзя.
    for l in open(f, encoding="utf-8"):
        l = l.strip()
        if not l:
            continue
        x = json.loads(l)
        st = x.get('state')
        if not st or 'finish' in x:
            continue
        состояния.append((f, x.get('gt'), st))

print('состояний всего:', len(состояния))

# Отбираем разнообразные: казарма есть, и разные по углю/стрелкам/времени
отобраны, видели = [], set()
for f, gt, st in состояния:
    if not L._чис(st.get('ba17')):
        continue
    уголь = L._чис(st.get('coal'))
    стрелков = L._чис(st.get('mil_shooters'))
    шахта = L._чис(st.get('mines_coal'))
    ключ = (уголь > 500, стрелков > 20, шахта > 0, L._чис(st.get('gametime')) > 600)
    if ключ in видели:
        continue
    видели.add(ключ)
    отобраны.append({'файл': f, 'gt': gt, 'st': st})

print('отобрано разных обстановок:', len(отобраны))
# СКАЗАТЬ ВСЛУХ, когда задач мало. Разнообразие задаётся грубым ключом (уголь,
# стрелки, угольная шахта, время), и на однообразной базе он схлопывается: на
# base24, где стрелков нет ни в одной партии, остаётся вчетверо меньше задач,
# чем было на наборе 20.09. Стенд от этого не ломается, но и мерить на пяти
# задачах нечего — молчать об этом нельзя.
if len(отобраны) < 8:
    print(f'  ВНИМАНИЕ: обстановок всего {len(отобраны)} — для замера мало.'
          f' Возьми каталог шире (несколько идей или дат) первым аргументом.')
задачи = []
# Историю ресурсов заполняем ПРЕДЫДУЩИМ тактом той же партии: иначе «чистыми
# за секунду» не появится, а в живом мосту оно есть всегда, кроме первых
# тактов. Такт передаём тот же, что у контейнера.
предыдущие = {}
for i, (f, gt, st) in enumerate(состояния):
    предыдущие[id(st)] = состояния[i - 1][2] if i and состояния[i - 1][0] == f else None

for о in отобраны:
    ИСХОДНОЕ = о['st']
    for роль in ('ba17', 'stables'):
        st = ИСХОДНОЕ          # каждое здание считается от ЧИСТОГО состояния:
        # иначе подстановка второго ложится поверх первой и в очереди
        # оказываются два новых здания сразу
        if not L._чис(st.get(роль)):
            continue
        # МОМЕНТ ДОСТРОЙКИ собирается подстановкой, и вот почему. Событие
        # будит модель, когда здание ТОЛЬКО ЧТО встало, — его очередь пуста.
        # В трассах такой такт почти не встречается: модель держит очереди
        # занятыми, и на 562 состояния нашлось всего два. Поэтому берём
        # настоящее состояние и меняем РОВНО ОДНО: добавляем новое здание с
        # пустой очередью, как при достройке. Всё остальное — из партии.
        оч = str(st.get('ba_queues') or '')
        занятые = [к for к in оч.split(',') if к.strip()]
        префикс = 's' if роль.startswith('stable') else ''
        номер = len([к for к in занятые
                     if к.strip().startswith(префикс)
                     and (префикс or not к.strip().startswith('s'))]) + 1
        st = dict(st, ba_queues=','.join(занятые + [f'{префикс}{номер}:none']))
        L.РЕСУРСЫ_ИСТОРИЯ.clear()
        # ПРЕДЫДУЩИЙ ТАКТ ИЩЕМ ПО ИСХОДНОМУ состоянию. Строкой выше `st` стал
        # НОВЫМ словарём (подстановка пустой очереди), и `id(st)` больше не тот,
        # по которому заполнялся справочник, — приход выходил пустым ВСЕГДА, а
        # значит стенд мерил запрос без строки «ЧИСТЫМИ за секунду», которая в
        # живом мосту есть. Найдено 21.09 при починке пути к трассам.
        пред = предыдущие.get(id(ИСХОДНОЕ))
        if пред:
            L.чистый_приход(пред)
        текст = L.запрос_найма(st, {}, роль, int(номер), такт=20)
        задачи.append({'роль': роль, 'gt': о['gt'], 'запрос': текст,
                       'кандидаты': list(L.КОГО_КУЕТ[роль]),
                       'еда': L._чис(st.get('food')), 'уголь': L._чис(st.get('coal')),
                       'шахта_угля': L._чис(st.get('mines_coal')),
                       'стрелков': L._чис(st.get('mil_shooters'))})
ВЫХОД = os.path.abspath(sys.argv[2] if len(sys.argv) > 2 else 'задачи_найма.json')
json.dump(задачи, open(ВЫХОД, 'w', encoding='utf-8'),
          ensure_ascii=False, indent=1)
print('задач собрано:', len(задачи), '->', ВЫХОД)
if задачи:
    print('длина запроса: медиана', sorted(len(з['запрос']) for з in задачи)[len(задачи)//2], 'символов')
    print('\n--- пример ---')
    print(задачи[0]['запрос'][:900])
