# -*- coding: utf-8 -*-
"""Ключ --hunt-peasants: мост сам ведёт волну по клеткам с крестьянами.

Повод, 27.09 вечер. `food_floor` перенесла узкое место из дебюта в эндшпиль: копия
3 уничтожила армию врага (его армия к концу 0, размен 1,44, убито 93 крестьянина) и
цель НЕ взяла — осталось 18 разбежавшихся крестьян, а волна стояла там, где добила
последнего. Победы приходят, когда его крестьян остаётся 1; довести с 18 до нуля не
умеет никто.

Почему ключ, а не подсказка: за 27.09 подсказкой доехали ВСЕ задания про целевое
состояние и НИ ОДНО про процедуру — окно 3х3 (0 из 3), FORMATION по готовности
(0 из 6), мушкетёры в тыл (0 MOVE из 6), двадцать бойцов к сроку (0 из 3).

Стережётся:
* выбор клетки: охрана дороже расстояния, и имя ключа словаря то самое, что отдаёт
  `coss3_map.крестьяне_врага` (`бойцов_рядом`, а не «охрана») — спутать значит
  всегда считать клетку неохраняемой;
* охота идёт в такт БЕЗ удара модели и по ПОТАКТОВОМУ флагу, не по вехе партии;
* разворачиваем уже идущих режимом `engage`, а не шлём свежих;
* цель переставляется, когда клетка опустела, и не чаще раза в 20 секунд;
* при малом числе бойцов вдали мост не молчит, а называет причину;
* поле «охота» доезжает и в трассу, и в снимок — иначе мера «доля времени волны в
  клетке с крестьянами» по серии не считается;
* охота живёт одну партию.
"""
import io
import os

import llm_policy as L

беды = []


def проверка(имя, условие, пояснение=""):
    if условие:
        print("  ОК    " + имя)
    else:
        беды.append(имя)
        print("  ПЛОХО " + имя + (" — " + str(пояснение)[:300] if пояснение else ""))


ИСТ = io.open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "llm_policy.py"),
              encoding="utf-8").read()


def мир(крестьяне: str, бойцы: str = "") -> dict:
    ст = {"grid_n": 16, "my_cx": 3, "my_cy": 12}
    ст.update({f"prow{y}": (крестьяне if y == 4 else "." * 16) for y in range(16)})
    ст.update({f"frow{y}": ((бойцы or "." * 16) if y == 4 else "." * 16) for y in range(16)})
    return ст


# 1. Ключ объявлен и по умолчанию выключен.
проверка("ключ --hunt-peasants объявлен", '"--hunt-peasants"' in ИСТ)
проверка("по умолчанию выключен",
         'ap.add_argument("--hunt-peasants", type=int, default=0' in ИСТ)

# 2. Выбор клетки.
без_охраны = L.клетка_охоты(мир("....5.......3...", "...........2...."), None)
проверка("выбрана клетка БЕЗ его бойцов, даже если она дальше",
         (без_охраны or {}).get("x") == 4, без_охраны)
проверка("у выбранной клетки бойцов рядом нет",
         (без_охраны or {}).get("бойцов_рядом") == 0, без_охраны)
# Когда обе клетки чисты — решает расстояние от ВОЛНЫ, а не от базы.
ст2 = мир("..3.........4...")
близко = L.клетка_охоты(ст2, (12, 4))
проверка("при равной охране берём ближнюю к волне",
         (близко or {}).get("x") == 12, близко)
далеко = L.клетка_охоты(ст2, (2, 4))
проверка("волна в другом углу — берём другую клетку",
         (далеко or {}).get("x") == 2, далеко)
проверка("крестьян нет — охотиться некуда", L.клетка_охоты(мир("." * 16), None) is None)
# Имя ключа словаря: та самая ловушка.
проверка("вес считается по ключу «бойцов_рядом», а не по выдуманной «охране»",
         'к.get("бойцов_рядом")' in ИСТ and 'к.get("охрана")' not in ИСТ)

# 3. Как охота отдаётся.
проверка("охота идёт в такт без удара модели, по потактовому флагу",
         'if (getattr(a, "hunt_peasants", 0) and not удар_в_такте' in ИСТ)
проверка("разворачиваем уже идущих режимом engage",
         'br.attack(_вдали, "cell", mode="engage"' in ИСТ)
проверка("цель переставляется, когда клетка опустела",
         "_есть_в_цели" in ИСТ and "not _есть_в_цели" in ИСТ)
проверка("не чаще раза в 20 секунд",
         'gt - _чис(ОХОТА.get("когда") or -10 ** 6) >= 20' in ИСТ)
проверка("при малом числе бойцов вдали называется причина",
         "охоту не веду: вдали всего" in ИСТ)
проверка("мост говорит об охоте и модели, а не только в лог",
         "МОСТ ВЕДЁТ ОХОТУ" in ИСТ)
проверка("своя атака модели важнее — мост не спорит",
         "он важнее" in ИСТ.split("МОСТ ВЕДЁТ ОХОТУ")[1][:600])
проверка("во время марша не вмешиваемся", "and not МАРШ)" in ИСТ)

# 4. Запись: и трасса, и снимок.
проверка("охота пишется в трассу", '_снимок["охота"]' in ИСТ)
проверка("охота пишется и в снимок", 'строка["охота"]' in ИСТ)
проверка("охота живёт одну партию", "ОХОТА.clear()" in ИСТ)

print()
if беды:
    print(f"БЕД: {len(беды)} — {', '.join(беды)}")
    raise SystemExit(1)
print("всё чисто")
