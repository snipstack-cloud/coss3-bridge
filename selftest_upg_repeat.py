# -*- coding: utf-8 -*-
"""Самопроверка: повторный заказ ВЗЯТОГО апгрейда отбрасывается.

Механика из кода игры (`lib/player.script:1986-1998`): апгрейды связаны в
цепочки `upgradelinks`, и взятие звена ВКЛЮЧАЕТ следующее, ставя ему
`done := False`. Для первого взятия это верно — ступень открылась. Но заказ
УЖЕ ВЗЯТОГО проходит снова, платно, и сбрасывает отметку у следующей ступени.

Живая партия 20.09, дважды подряд и одинаково: заказ `bar.pikeman.2.1` на 9:06
— потеря `bar.pikeman.2.2` на 9:59; тот же заказ на 11:00 — потеря на 11:46.
Атака пикинёра всё это время стояла на 8. В `base21` то же на 6:02 -> 6:23.

Стережётся:
* повторный заказ взятого НЕ уходит в игру;
* отброс сказан вслух и объясняет, почему (молчаливый отброс неотличим от
  бездействия);
* невзятый апгрейд по-прежнему проходит;
* без списка взятых поведение прежнее — мост не глохнет на пустом знании.
"""
import llm_policy as L

беды = []


def проверка(имя, условие, пояснение=""):
    if условие:
        print("  ОК    " + имя)
    else:
        беды.append(имя)
        print("  ПЛОХО " + имя + (" — " + пояснение if пояснение else ""))


ДОСТУПНЫ = {"bar.pikeman.2.1", "bar.pikeman.2.2", "bar.pikeman.2.3"}
ВЗЯТЫ = {"bar.pikeman.2.1", "bar.pikeman.2.2"}


def разбор(имя_апгрейда, взятые=ВЗЯТЫ):
    ответ = {"commands": [{"cmd": "UPGRADE", "role": имя_апгрейда}], "why": "тест"}
    return L.to_commands(ответ, ДОСТУПНЫ, взятые)


# повторный заказ взятого
cmds, attack, why, брак, *_ = разбор("bar.pikeman.2.1")
проверка("повторный заказ НЕ ушёл в игру",
         not any(getattr(c, "cmd", "") == "UPGRADE" for c in cmds),
         f"команд: {[getattr(c,'cmd','?') for c in cmds]}")
проверка("отброс сказан вслух", any("УЖЕ ВЗЯТ" in б for б in брак), str(брак))
проверка("названа причина — откат следующей ступени",
         any("ОТКАТЫВАЕТ следующую ступень" in б for б in брак), str(брак))
проверка("сказано, что делать вместо",
         any("СЛЕДУЮЩУЮ ступень" in б for б in брак), str(брак))

# невзятый проходит
cmds2, *_ , = разбор("bar.pikeman.2.3")[:1]
проверка("НЕвзятый апгрейд проходит",
         any(getattr(c, "cmd", "") == "UPGRADE" for c in cmds2),
         f"команд: {[getattr(c,'cmd','?') for c in cmds2]}")

# пустое знание не ломает прежнее поведение
cmds3 = разбор("bar.pikeman.2.1", взятые=None)[0]
проверка("без списка взятых команда проходит как раньше",
         any(getattr(c, "cmd", "") == "UPGRADE" for c in cmds3))
cmds4 = разбор("bar.pikeman.2.1", взятые=set())[0]
проверка("пустой список взятых не глушит команду",
         any(getattr(c, "cmd", "") == "UPGRADE" for c in cmds4))

# чужой нации по-прежнему отказ, и это другая причина
брак5 = разбор("чужой.апгрейд")[3]
проверка("неизвестное имя отвергается своей причиной",
         any("у твоей нации такого нет" in б for б in брак5), str(брак5))

print()
if беды:
    print(f"БЕД: {len(беды)} — {', '.join(беды)}")
    raise SystemExit(1)
print("всё чисто")
