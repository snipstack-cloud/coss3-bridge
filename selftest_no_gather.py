# -*- coding: utf-8 -*-
"""Ключ --no-gather: клетка сбора не заводится, и отказ приходит ВСЛУХ.

Откуда идея (счёт 25.09, 614 тактов трёх серий по сеткам arow и prow,
разборы/ПОЧЕМУ_НЕ_БЬЁМ.md): убийства крестьян врага идут там, где наши бойцы
стоят В ОДНОЙ КЛЕТКЕ с ними — 98 из 102 у base27, 17 из 24 у base28, 0 из 4 у
tier1. Доля таких тактов 13 / 8 / 4 процента ложится в том же порядке, что
убитые 102 / 24 / 4. Решает ПРИСУТСТВИЕ, а не масса: base27 убила 98 при
медианно 7,5 бойцах в клетке, tier1 с 18 не убил ни одного. А сбор только
откладывает: до клетки сбора доходит 29 процентов колонны у tier1 и 8 у base28,
оба выхода из «сбора» требуют половины и двух третей и не срабатывают (порог
взят 1 раз из 55 тактов), и колонна стоит до expires.

Что проверяется:
  1. ключ выключен по умолчанию и объявлен;
  2. БЕЗ ключа via берётся, как было, — поведение прежнее;
  3. С ключом via НЕ заводится, а удар сохраняется целиком (цель и клетка те же);
  4. отказ приходит ВСЛУХ и называет причину, а не молчит;
  5. это ОТДЕЛЬНЫЙ ключ от --wave-march: тот гасит лишь автоматический сбор при
     цели wave и так выключен по умолчанию, а via от самой модели берёт всё
     равно — в base28 так вышло 23 марша.
"""
import io, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import llm_policy as L

ошибок = 0


def проверить(условие, что):
    global ошибок
    if not условие:
        ошибок += 1
        print("  СБОЙ:", что)
    else:
        print("  ок:", что)


ЗДЕСЬ = os.path.dirname(os.path.abspath(__file__))
И = io.open(os.path.join(ЗДЕСЬ, "llm_policy.py"), encoding="utf-8").read()
К = {"cmd": "ATTACK", "count": 40, "target": "cell", "cx": 13, "cy": 2,
     "via": {"cx": 8, "cy": 6}}

print("1. ключ объявлен и выключен по умолчанию")
проверить("БЕЗ_СБОРА = False" in И, "глобаль выключена")
проверить('ap.add_argument("--no-gather"' in И, "ключ в разборе аргументов")
проверить('globals()["БЕЗ_СБОРА"] = True' in И, "ключ связан с глобалью")
проверить(L.БЕЗ_СБОРА is False, "при импорте выключен")

print()
print("2. БЕЗ ключа поведение прежнее")
L.БЕЗ_СБОРА = False
_, attack, _, брак, цель, _, _, клетка, к, _, _ = L.to_commands({"commands": [К]})
проверить(attack == 40 and цель == "cell" and клетка == (13, 2), "удар разобран")
проверить(к.get("via") == (8, 6), "via взята, как было: " + str(к.get("via")))
проверить(брак == [], "брака нет")

print()
print("3. С ключом сбора нет, а удар цел")
L.БЕЗ_СБОРА = True
_, attack, _, брак, цель, _, _, клетка, к, _, _ = L.to_commands({"commands": [К]})
проверить(attack == 40, "число бойцов не тронуто: " + str(attack))
проверить(цель == "cell" and клетка == (13, 2), "цель и клетка те же: %s %s" % (цель, клетка))
проверить("via" not in к, "via НЕ заведена: " + str(к))

print()
print("4. отказ ВСЛУХ, с причиной")
проверить(len(брак) == 1, "сказано ровно один раз")
текст = " ".join(str(б) for б in брак)
проверить("--no-gather" in текст, "назван ключ, которым выключено")
проверить("(8,6)" in текст, "названа отвергнутая клетка")
проверить("обычным ударом" in текст, "сказано, что будет вместо сбора")
проверить("В ОДНОЙ КЛЕТКЕ" in текст and "7,5" in текст, "названа причина числами")

print()
print("5. это не --wave-march")
проверить("Отличать от --wave-march 0" in И, "разница названа в справке ключа")
проверить('getattr(a, "wave_march", 0)' in И, "--wave-march живёт отдельно")
L.БЕЗ_СБОРА = False

print()
print("ошибок:", ошибок)
sys.exit(1 if ошибок else 0)
