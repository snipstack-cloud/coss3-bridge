# -*- coding: utf-8 -*-
"""События гибели: кто погиб, где и от кого — из ворот смерти движка (27.09).

Откуда. Единственное место, где движок в миг смерти знает и жертву, и убийцу —
`_misc_DoDamage` (`lib/miscext2.script:519-535`): там он сам пишет убийце
`TObj.kill+1`. `OnDeath` и `DeathStage1` срабатывают позже, когда нападавшие уже
сменили цель, а жертва не хранит, кто её бил. Блок `block_kills.inc` ставится
туда флагом `--human-kills`, пишет событие в именованный парсер `br_kills`
(кольцо на 128, сквозной номер; было 48 до 29.09), а блок состояния отдаёт кольцо наружу полем
`kills` рядом со счётчиком `my_mil_lost`, ВНЕ гейта ратуши.

Почему это заменяет раскладку по клеткам разностями и бюджетом: там клетка
угадывалась по убавлению, и первая живая проверка положила одну смерть из
десяти — да и ту в тыл. Здесь клетка берётся с координат жертвы в миг смерти.

Что тут стережётся:
* ИМЕНА и ФОРМА — как их пишет блок, одиннадцать полей через запятую;
* блок для lib — без префикса `[*] = ;`, и верификатор проверяет его как код,
  а не пропускает молча строку за строкой;
* классы решаются буквами В БЛОКЕ константами движка: чисел `gc_obj_usage_*`
  в скриптах нет, они живут в движке, и python их не знает;
* одиночные `if`, не `case`: одностроковые ветки `case` уже роняли состояние;
* новое читается ПО НОМЕРУ (`seq` выше `kills_n` прошлого состояния), а не
  «за последнюю секунду»: python видит каждое пятое состояние;
* поле доезжает во все четыре места — запрос модели, трасса такта, снимок,
  строка критика — и мок отдаёт его той же формы.
"""
