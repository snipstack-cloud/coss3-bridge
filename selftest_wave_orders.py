# -*- coding: utf-8 -*-
"""ЧЕТЫРЕ ПРИКАЗА ВОЛНЕ В ПОЛЕ (3.10): «к своим», «держать», «вперёд», «отряд».

Задание игрока звучало как правка блоков `.inc`. Блок менять не понадобилось, и это
проверено здесь по трём звеньям — потому что «работает» значит не «я так написал», а
«приказ дошёл до файла, который читает игра»:

1. `strategy_live._в_мостовые` — внутренний приказ симулятора становится мостовым;
2. `llm_policy.to_commands` — мостовой приказ разобран без брака;
3. `coss3_bridge.attack` — в файле приказа лежат нужные `mode`, `target`, `cx`, `cy`.

Чего тут НЕ проверяется: что игра послушается. Это живая игра на Windows.

    python selftest_wave_orders.py
"""
import json
import os
import sys
import tempfile

ЗДЕСЬ = os.path.dirname(os.path.abspath(__file__))
if ЗДЕСЬ not in sys.path:
    sys.path.insert(0, ЗДЕСЬ)

import strategy_live as SL
import coss3_bridge as CB
import llm_policy as LP

беды = []

# Состояние: ратуша в клетке (3,3), две наши кучи — дома и в поле, и одна далёкая.
СОСТОЯНИЕ = {
    "gametime": 500, "map_w": 256, "map_h": 256,
    "obuild": [{"тип": "center", "x": 50, "z": 54, "готово": True}],
    "ocells": [{"x": 3, "y": 3, "n": 5}, {"x": 6, "y": 7, "n": 20},
               {"x": 11, "y": 12, "n": 9}],
    "mil_away": 29, "my_freewar": 0, "peasants": 30,
}
ДОМ = SL._дом(СОСТОЯНИЕ)
if ДОМ != (3, 3):
    беды.append(f"дом посчитан как {ДОМ}, а ратуша в клетке (3,3)")

SL.ЖИВОЙ_МОСТ = True

# --- 1. перевод внутренних приказов -----------------------------------------
# «к своим»: самая дальняя куча (11,12) идёт к ближайшей своей — (6,7), а не домой.
п = SL._в_мостовые({"cmd": "_К_СВОИМ"}, "_К_СВОИМ", СОСТОЯНИЕ)
if not п or п.get("cmd") != "RETREAT" or (п.get("cx"), п.get("cy")) != (6, 7):
    беды.append(f"_К_СВОИМ -> {п}: ждали RETREAT в клетку (6,7)")
if п and п.get("count") != 9:
    беды.append(f"_К_СВОИМ: ждали count 9 (столько в дальней куче), вышло {п.get('count')}")

# Если в поле одна куча, ближайшая своя — дом, и это обычный отход домой.
одна = dict(СОСТОЯНИЕ, ocells=[{"x": 3, "y": 3, "n": 5}, {"x": 11, "y": 12, "n": 9}])
п = SL._в_мостовые({"cmd": "_К_СВОИМ"}, "_К_СВОИМ", одна)
if not п or п.get("target") == "cell":
    беды.append(f"_К_СВОИМ при единственной куче в поле -> {п}: ждали RETREAT домой")

# Волны в поле нет вовсе — приказ бессмысленный (дыра сети, §51): перевода быть не должно.
дома_всё = dict(СОСТОЯНИЕ, ocells=[{"x": 3, "y": 3, "n": 25}], mil_away=0)
if SL._в_мостовые({"cmd": "_К_СВОИМ"}, "_К_СВОИМ", дома_всё) is not None:
    беды.append("_К_СВОИМ без волны в поле перевёлся — а переводить нечего")

# «В ПОЛЕ» — по мерке блока (дальше 60 от ратуши, поле mil_away), а не по клеткам:
# на живых снимках куча из двух бойцов стояла в соседней с домом клетке при mil_away = 0,
# и приказ уехал бы только за отказом.
рядом = dict(СОСТОЯНИЕ, ocells=[{"x": 3, "y": 3, "n": 5}, {"x": 2, "y": 3, "n": 2}],
             mil_away=0)
for _имя in ("_К_СВОИМ", "_СТОЙ", "_ВПЕРЁД", "_ОТРЯД", "_НА_КЛЕТКУ"):
    if SL._в_мостовые({"cmd": _имя, "aim": [9, 9]}, _имя, рядом) is not None:
        беды.append(f"{_имя} перевёлся при mil_away = 0 — дальше 60 от ратуши никого")

# Счёт приказа не больше, чем бойцов в поле: блок возьмёт всё равно столько.
мало = dict(СОСТОЯНИЕ, mil_away=3)
п = SL._в_мостовые({"cmd": "_СТОЙ"}, "_СТОЙ", мало)
if not п or п.get("count") != 3:
    беды.append(f"_СТОЙ при mil_away = 3 -> {п}: счёт должен быть урезан до 3")

# «держать»: в клетку, где волна стоит сейчас (приближение, названное вслух).
п = SL._в_мостовые({"cmd": "_СТОЙ"}, "_СТОЙ", СОСТОЯНИЕ)
if not п or (п.get("cx"), п.get("cy")) != (6, 7):
    беды.append(f"_СТОЙ -> {п}: ждали RETREAT в клетку самой большой кучи в поле (6,7)")

# «вперёд»: ENGAGE на цель, по умолчанию армия.
п = SL._в_мостовые({"cmd": "_ВПЕРЁД"}, "_ВПЕРЁД", СОСТОЯНИЕ)
if not п or п.get("cmd") != "ENGAGE" or п.get("target") != "army":
    беды.append(f"_ВПЕРЁД -> {п}: ждали ENGAGE на army")

# «отряд»: доля самой большой кучи в поле идёт на клетку.
п = SL._в_мостовые({"cmd": "_ОТРЯД", "aim": [9, 9], "share": 0.5}, "_ОТРЯД", СОСТОЯНИЕ)
if not п or (п.get("cx"), п.get("cy")) != (9, 9) or п.get("count") != 10:
    беды.append(f"_ОТРЯД -> {п}: ждали 10 бойцов (половину от 20) в клетку (9,9)")
# Без цели отделять некуда.
if SL._в_мостовые({"cmd": "_ОТРЯД", "share": 0.5}, "_ОТРЯД", СОСТОЯНИЕ) is not None:
    беды.append("_ОТРЯД без aim перевёлся — а клетки нет")

# «на меньшую кучу»: все, кто в поле, в бой на клетку.
п = SL._в_мостовые({"cmd": "_НА_КЛЕТКУ", "aim": [9, 9]}, "_НА_КЛЕТКУ", СОСТОЯНИЕ)
if not п or п.get("cmd") != "ENGAGE" or (п.get("cx"), п.get("cy")) != (9, 9):
    беды.append(f"_НА_КЛЕТКУ -> {п}: ждали ENGAGE в клетку (9,9)")

# Таблица «что умеет мост» должна совпадать с тем, что переводится. Иначе журнал тени
# врёт о возможностях моста — а по нему мак и решает, чего просить.
import tactic_core as TC
if set(TC.В_МОСТЕ) != set(TC.РЕШЕНИЯ):
    беды.append("В_МОСТЕ и РЕШЕНИЯ разошлись: "
                f"{sorted(set(TC.РЕШЕНИЯ) ^ set(TC.В_МОСТЕ))}")
for _имя, _ждём in (("к_своим", True), ("вперёд", True), ("отряд_на_меньшую", True),
                    ("на_меньшую", True), ("держать", "приближение"),
                    ("собраться", "приближение")):
    if TC.В_МОСТЕ.get(_имя) != _ждём:
        беды.append(f"В_МОСТЕ[{_имя}] = {TC.В_МОСТЕ.get(_имя)!r}, ждали {_ждём!r}")

# В СИМУЛЯТОРЕ перевода быть не должно: он исполняет эти приказы сам и точнее.
SL.ЖИВОЙ_МОСТ = False
if SL._в_мостовые({"cmd": "_К_СВОИМ"}, "_К_СВОИМ", СОСТОЯНИЕ) is None:
    pass    # сама функция не смотрит на флаг; флаг смотрит `привести`
отдано, пропущено = {}, {}
import collections
отдано, пропущено = collections.Counter(), collections.Counter()


class _Пустая:
    """`привести` спрашивает у стратегии только про академию."""
    академия = False
    академия_с = 0


вышло = SL.привести([{"cmd": "_К_СВОИМ"}], СОСТОЯНИЕ, {"еда_до": 0.6}, _Пустая(),
                    пропущено, отдано)
if any(c.get("cmd") == "RETREAT" for c in вышло):
    беды.append("в симуляторе (ЖИВОЙ_МОСТ = False) приказ перевёлся в мостовой — "
                "симулятор должен исполнять его своим кодом")
SL.ЖИВОЙ_МОСТ = True

# --- 2. разбор мостовых приказов to_commands --------------------------------
def разобрать(команды):
    """(цель_движения, клетка, брак) из to_commands."""
    out = LP.to_commands({"commands": команды}, set(), set(), st=СОСТОЯНИЕ)
    return out[6], out[7], out[3]

цель, клетка, брак = разобрать([{"cmd": "RETREAT", "count": 9, "target": "cell",
                                 "cx": 6, "cy": 7}])
if цель != "retreat_cell" or клетка != (6, 7):
    беды.append(f"RETREAT target=cell разобран как {цель} {клетка}")
if брак:
    беды.append(f"RETREAT target=cell дал брак: {брак}")

цель, _, брак = разобрать([{"cmd": "RETREAT", "count": 9}])
if цель != "retreat":
    беды.append(f"RETREAT без цели разобран как {цель}, а должен вести домой")

# Клетки нет — говорим вслух и идём домой, а не молчим.
цель, _, брак = разобрать([{"cmd": "RETREAT", "count": 9, "target": "cell"}])
if цель != "retreat" or not any("cell" in б for б in брак):
    беды.append(f"RETREAT target=cell без cx/cy: цель {цель}, брак {брак} — "
                f"ждали отход домой И слово об этом")

цель, _, брак = разобрать([{"cmd": "ENGAGE", "count": 200}])
if цель != "engage:army":
    беды.append(f"ENGAGE без цели разобран как {цель}, а по умолчанию это army")
if брак:
    беды.append(f"ENGAGE дал брак: {брак}")

цель, клетка, брак = разобрать([{"cmd": "ENGAGE", "count": 50, "target": "cell",
                                 "cx": 9, "cy": 9}])
if цель != "engage:cell" or клетка != (9, 9):
    беды.append(f"ENGAGE target=cell разобран как {цель} {клетка}")

# --- 3. что ложится в файл приказа ------------------------------------------
with tempfile.TemporaryDirectory() as кат:
    br = CB.Bridge(кат, plind=0)
    проверки = [
        ("отход домой", dict(count=9, target="home", mode="retreat"),
         {"mode": "retreat", "target": "home"}),
        ("к своим", dict(count=9, target="cell", mode="retreat", cx=6, cy=7),
         {"mode": "retreat", "target": "cell", "cx": "6", "cy": "7"}),
        ("вперёд", dict(count=200, target="army", mode="engage"),
         {"mode": "engage", "target": "army"}),
    ]
    for имя, kw, ждём in проверки:
        if os.path.exists(br.atk_path):
            os.unlink(br.atk_path)
        if not br.attack(**kw):
            беды.append(f"{имя}: attack вернул False")
            continue
        текст = open(br.atk_path, encoding="latin-1").read()
        for к, v in ждём.items():
            if f"{к} = {v}" not in текст.replace("'", ""):
                беды.append(f"{имя}: в файле приказа нет «{к} = {v}». Файл:\n{текст}")
    # Цель, которой у отхода быть не может, должна стать домом, а не уехать как есть.
    if os.path.exists(br.atk_path):
        os.unlink(br.atk_path)
    br.attack(count=9, target="base", mode="retreat")
    текст = open(br.atk_path, encoding="latin-1").read()
    if "target = home" not in текст.replace("'", ""):
        беды.append(f"retreat с целью base должен вести домой, а в файле:\n{текст}")

if беды:
    print("ПЛОХО:")
    for б in беды:
        print("  -", б)
    raise SystemExit(1)
print("ХОРОШО: четыре приказа волне переводятся, разбираются и ложатся в файл приказа; "
      "в симуляторе перевод не включается")
