# -*- coding: utf-8 -*-
"""Вердикт о BALANCE: имя направления и ОТКАЗ ИГРЫ.

Повод, 23.09, разбор дебюта base27 (простой съедает там 44,5 процента труда).
На 90-й секунде модель послала шестнадцать человек на еду. Игра отказала —
`GATHER res0: no deposit of this kind within 40` (поля не засеяны), — а мост
сказал в итоге прошлого решения: «BALANCE  16: отправлено, проверить нечем».
Следующие четыре такта на еде стоял ноль при двенадцати свободных.

Две беды в одной строке, и обе чинятся здесь:

  1. ИМЯ НАПРАВЛЕНИЯ ПУСТОЕ. Роль бралась из СЫРОГО поля ответа модели, а не
     из разбора, который сводит синонимы и числа. Без имени вердикт не попадал
     ни в одну проверку — ни «нет мельницы», ни счёт людей.
  2. ОТКАЗ ИГРЫ НЕ НАЗЫВАЛСЯ. Мост говорил «отправлено» там, где игра сказала
     «нет», — правило 1 проекта наизнанку.
"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import llm_policy as L

ошибок = 0


def проверить(условие, что):
    global ошибок
    if not условие:
        ошибок += 1
        print("  СБОЙ:", что)
    else:
        print("  ок:", что)


ОТКАЗ = "| GATHER res0: no deposit of this kind within 40. Food is seeded"

print("1. отказ игры назван, а не проглочен")
строки = L.итог_прошлого({"on_food": 0, "mills": 1},
                         {"on_food": 0, "mills": 1, "last_fail": ОТКАЗ},
                         [("BALANCE", "food", 16)])
текст = " ".join(строки)
проверить("НЕ СРАБОТАЛО, игра отказала" in текст, f"сказано прямо: {текст[-90:]}")
проверить("GATHER" in текст, "приведены слова игры, а не наша догадка")

print("2. когда люди пошли, отказа не выдумываем")
строки = L.итог_прошлого({"on_food": 0, "mills": 1},
                         {"on_food": 9, "mills": 1, "last_fail": ОТКАЗ},
                         [("BALANCE", "food", 16)])
текст = " ".join(строки)
проверить("0->9" in текст and "отказала" not in текст,
          f"счёт людей важнее старого отказа: {текст[-70:]}")

print("3. без мельницы — прежний вердикт, он точнее")
строки = L.итог_прошлого({"on_food": 0, "mills": 0},
                         {"on_food": 0, "mills": 0, "last_fail": ОТКАЗ},
                         [("BALANCE", "food", 16)])
проверить("НЕТ МЕЛЬНИЦЫ" in " ".join(строки), "мельница названа первой причиной")

print("4. имя направления берётся из РАЗБОРА, а не из сырого поля")
исходник = open(os.path.join(os.path.dirname(os.path.abspath(__file__)),
                             "llm_policy.py"), encoding="utf-8").read()
проверить('нормализовать(i)[1] or str(i.get("role", ""))' in исходник,
          "роль в прошлом заказе — из нормализовать()")
c, role, total = L.нормализовать({"cmd": "BALANCE", "res": "food", "total": 16})
проверить(role == "food", f"синоним res читается как роль: {role!r}")

print("5. молчаливого «проверить нечем» без имени больше нет")
строки = L.итог_прошлого({"on_food": 0, "mills": 1},
                         {"on_food": 0, "mills": 1}, [("BALANCE", "food", 16)])
проверить("BALANCE food 16" in " ".join(строки),
          "направление названо: " + " ".join(строки)[-60:])

print()
print("ошибок:", ошибок)
sys.exit(1 if ошибок else 0)
