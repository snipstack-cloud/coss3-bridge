# -*- coding: utf-8 -*-
"""Охота: возврат волны в клетку и порог перевеса (мак, 27.09).

Повод — разбор плеча hunt_peasants: ключ отдал ОДИН приказ за партию (смен цели
0/0/0), потому что переставлял цель только по опустевшей клетке, а модель в тех же
партиях отдала 28-34 своих ATTACK и увела волну. Плюс на единственном приказе копия
3 повела 16 бойцов в клетку, где его бойцов рядом было девять.
"""
import io
import os

import llm_policy as L

ошибок = []
_ = lambda т: ошибок.append(т)

def клетки(*тройки):
    """сетка prow с крестьянами и бойцами в заданных клетках"""
    st = {"grid_n": 16, "my_cx": 1.0, "my_cy": 1.0}
    prow = [["." for _ in range(16)] for _ in range(16)]
    frow = [["." for _ in range(16)] for _ in range(16)]
    for x, y, кр, бой in тройки:
        # ЕГО бойцы живут в frow, наши в arow: «бойцов_рядом» считается по frow
        # (`coss3_map.крестьяне_врага`). Спутать сетки значит всегда получать
        # клетку без охраны — ровно тот ложный ноль, от которого стережёт их же
        # проверка про имя ключа.
        prow[y][x] = "9" if кр >= 9 else str(кр)
        if бой:
            frow[y][x] = "9" if бой >= 9 else str(бой)
    for y in range(16):
        st[f"prow{y}"] = "".join(prow[y])
        st[f"frow{y}"] = "".join(frow[y])
    return st

# 1. порог: все клетки под охраной — охоты нет
st = клетки((12, 13, 9, 9))
if L.клетка_охоты(st, (2, 2), наших=8) is not None:
    _("при охране 9 против наших 8 клетку брать нельзя (порог 0,75)")
# 2. тот же такт, но бойцов у нас втрое больше — клетка годится
if L.клетка_охоты(st, (2, 2), наших=40) is None:
    _("при наших 40 против охраны 9 клетка обязана годиться")
# 3. без параметра поведение прежнее — их девятнадцать проверок на этом стоят
if L.клетка_охоты(st, (2, 2)) is None:
    _("без параметра наших порог не должен срабатывать")
# 4. порог именно 0,75 и назван числом, а не спрятан в коде
if abs(L.ОХОТА_ПОРОГ_ПЕРЕВЕСА - 0.75) > 1e-9:
    _("порог перевеса должен быть 0,75 — число из замера по 81 записи")

# --- условие возврата читается в источнике: вмешательство внутри такта -------
ист = io.open(os.path.join(os.path.dirname(os.path.abspath(__file__)),
                           "llm_policy.py"), encoding="utf-8").read()
for кусок, зачем in (
        ("_не_там", "признак «волна ушла из клетки охоты»"),
        ("not _есть_в_цели or _не_там", "приказ повторяется и когда волна ушла"),
        ('наших=_вдали', "порог перевеса считается от числа бойцов вдали"),
        ('ОХОТА["возвратов"]', "возвраты считаются отдельно от опустевших клеток"),
        ("под охраной", "отказ по порогу говорится вслух")):
    if кусок not in ист:
        _(f"в источнике нет «{кусок}» — {зачем}")

print("selftest_hunt_return: " + ("ОК, 9 проверок" if not ошибок
                                  else "ОШИБКИ\n  " + "\n  ".join(ошибок)))
raise SystemExit(1 if ошибок else 0)
