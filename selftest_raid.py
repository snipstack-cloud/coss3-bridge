# -*- coding: utf-8 -*-
"""Самопроверка блока «ВРАГ У ТВОЕЙ БАЗЫ» и вердикта о волне.

Живая партия 17.09 23:05: враг дважды приходил к нашей базе, мост молчал; после
ATTACK 50 волна встала в 21-37 от базы живой, а мост говорил «считай их
погибшими». Здесь оба места проверяются на снимках, снятых с той партии.
"""
import sys
import llm_policy as L
import coss3_map as M

беды = []


def проверка(имя, условие, пояснение=""):
    if условие:
        print("  ОК   " + имя)
    else:
        беды.append(имя)
        print("  ПЛОХО " + имя + (" — " + пояснение if пояснение else ""))


def сетка(**клетки):
    """frow0..15 с цифрами в названных клетках: сетка(**{'10,12': 9})."""
    строки = [["."] * 16 for _ in range(16)]
    for k, v in клетки.items():
        x, y = (int(t) for t in k.split(","))
        строки[y][x] = str(v)
    return {f"frow{y}": "".join(строки[y]) for y in range(16)}


БАЗА = dict(gametime=734, grid_n=16, map_w=256, map_h=256, my_cx=12, my_cy=13,
            map_open=1, peasants=31, mil_inf=10, mil_shooters=33, my_freewar=33,
            my_army_cx=12, my_army_cy=12, my_army_n=33)

# 1. Сетка: враг в двух клетках от ратуши — как в файле состояния после партии.
st = dict(БАЗА, **сетка(**{"10,12": 9, "10,13": 9, "3,3": 4}))
у = M.у_базы(st)
проверка("считает только у базы", у["бойцов"] == 18, str(у))
проверка("срезанную девятку называет", у["не_меньше"] is True)
проверка("сторона — запад", у["сторона"] == "W", у["сторона"])
проверка("далёкий враг не в счёт", all(x != 3 for _, x, _y in у["клетки"]))
проверка("без сетки — пусто", M.у_базы(dict(peasants=5)) == {})
проверка("пустая сетка — ноль", M.у_базы(dict(БАЗА, **сетка()))["бойцов"] == 0)

# 2. Блок в запросе: набег виден, команда на отпор дана, убыль названа.
было = dict(БАЗА, gametime=714, peasants=45, mil_inf=36, mil_shooters=27)
L.ЧЕСТНО = False
т = "\n".join(L.набег(st, было))
проверка("заголовок есть", "ВРАГ У ТВОЕЙ БАЗЫ" in т)
проверка("число и сторона", "не меньше 18 бойцов врага" in т and ", W," in т, т)
проверка("убыль крестьян названа", "45 -> 31" in т, т)
проверка("убыль бойцов названа", "63 -> 43" in т, т)
проверка("кулак стоит врозь — сказано", "кулаком их никто не собирал" in т)
проверка("дана команда в клетку врага",
         '{"cmd":"ATTACK","count":33,"target":"cell","cx":10,"cy":12}' in т, т)
проверка("в поход не посылать", "не посылай" in т)

# 3. Тишина, когда врага нет и крестьяне целы.
проверка("без врага и убыли молчит",
         L.набег(dict(БАЗА, **сетка()), dict(БАЗА, gametime=714)) == [])
# Убыль в одного — голод, не набег.
проверка("минус один крестьянин — молчит",
         L.набег(dict(БАЗА, **сетка()), dict(БАЗА, gametime=714, peasants=32)) == [])
# Убыль в двоих без сетки (карта закрыта) — говорит, но команды не даёт.
т2 = "\n".join(L.набег(dict(БАЗА, **сетка()), dict(БАЗА, gametime=714, peasants=40)))
проверка("убыль без сетки названа", "убивают у тебя дома" in т2, т2)
проверка("а команды без цели нет", "ATTACK" not in т2)

# 4. Честность: карта закрыта — сетку не читаем, убыль своих видим.
L.ЧЕСТНО = True
т3 = "\n".join(L.набег(dict(st, map_open=0), было))
проверка("при закрытой карте чужих не считает", "бойцов врага" not in т3, т3)
проверка("но своих потерянных называет", "45 -> 31" in т3)
L.ЧЕСТНО = False

# 5. Вердикт о волне: «никого дальше 60» при живой армии — не «погибли».
def вердикт(st, было=None):
    return L.situation(st, {}, [], "", было=было)

L.ОТПРАВКА.clear()
ж = dict(БАЗА, gametime=856, wave_sent=50, mil_away=0, mil_far=21, mil_hurt=0,
         mil_inf=12, mil_shooters=51, my_freewar=12, **сетка())
проверка("без памяти отправки — прежний текст", "ВОЛНА НЕ ВЕРНУЛАСЬ" in вердикт(ж))
L.ОТПРАВКА.update(gt=832, послано=50, армия=57)
т4 = вердикт(ж)
проверка("армия не убыла — живы", "ЖИВЫ и стоят у дома" in т4)
проверка("а «погибли» не сказано", "ВОЛНА НЕ ВЕРНУЛАСЬ" not in т4)
L.ОТПРАВКА.update(gt=672, послано=25, армия=62)
# 11:54 той же партии: армия 63 при 33 раненых — волна ещё жива и дерётся у дома.
п = dict(ж, gametime=714, wave_sent=25, mil_inf=36, mil_shooters=27, mil_hurt=33)
проверка("ранены, но армия цела — ещё живы", "ЖИВЫ и стоят у дома" in вердикт(п))
# 12:14: армия 43 при 62 в миг отправки — вот теперь погибли.
п = dict(ж, gametime=734, wave_sent=25, mil_inf=10, mil_shooters=33)
проверка("армия убыла на волну — погибли", "ВОЛНА НЕ ВЕРНУЛАСЬ" in вердикт(п))
L.ОТПРАВКА.clear()
проверка("между партиями память пуста", L.ОТПРАВКА == {})

print()
print(f"ПРОВАЛОВ: {len(беды)}")
sys.exit(1 if беды else 0)
