# -*- coding: utf-8 -*-
"""Самопроверка: предел на сбросы срока сбора (`--gather-resets`).

Зачем ключ. Срок 120 с считается заново от КАЖДОГО подкрепления
(`llm_policy.py`, ветка «К СБОРУ ПРИМКНУЛИ»), а подкрепление идёт почти каждый
такт. Поэтому зависший поход нельзя ни завершить, ни отменить: счёт по свежим
трассам 24.09 (`разборы/ИСТЁК.md`) — на 12 походов истечение ОДНО, а
`local_llama/4` шёл 870 игровых секунд при 31 сбросе.

Ключ НЕ приближает удар (этим занят `--gather-share`) — он возвращает ВЫХОД:
после предела срок не продлевается, поход истекает, войско освобождается.
"""
import sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import llm_policy as L

ошибок = 0


def проверить(что, условие):
    global ошибок
    print(("  ОК   " if условие else "  СБОЙ ") + что)
    ошибок += not условие


class МостЗаглушка:
    """Игра всегда принимает приказ: нас интересует только учёт срока."""
    def attack(self, *a, **k):
        return True


def марш(предел, сбросов=0, t0=100):
    L.ПРЕДЕЛ_СБРОСОВ = предел
    L.МАРШ.clear()
    L.МАРШ.update(фаза="сбор", t0=t0, послано=10, цель="cell", via=[5, 5],
                  клетка=[9, 9], expires=120, сбросов=сбросов, отчёт=[])
    return L.МАРШ


def примкнуть(предел, сбросов, t0=100, gt=300, фаза="сбор"):
    """Настоящий вызов моста: `примкнуть_к_маршу` с подставной игрой."""
    L.ПРЕДЕЛ_СБРОСОВ = предел
    L.МАРШ.clear()
    L.МАРШ.update(фаза=фаза, t0=t0, послано=10, цель="cell", via=[5, 5],
                  клетка=[9, 9], expires=120, сбросов=сбросов, отчёт=[])
    ответ = L.примкнуть_к_маршу({}, МостЗаглушка(), gt, 5)
    return L.МАРШ, ответ


print("предел ВЫКЛЮЧЕН (0) — ведём себя как раньше:")
м, о = примкнуть(0, сбросов=9)
проверить("срок продлён до текущего такта", м["t0"] == 300)
проверить("счётчик сбросов вырос", м["сбросов"] == 10)
проверить("в отчёте прежняя строка", "считается заново" in о)

print("\nпредел НЕ достигнут (2 из 3) — срок ещё продлевается:")
м, о = примкнуть(3, сбросов=2)
проверить("срок продлён", м["t0"] == 300)
проверить("счётчик дошёл до предела", м["сбросов"] == 3)

print("\nпредел ДОСТИГНУТ (3 из 3) — срок больше не продлевается:")
м, о = примкнуть(3, сбросов=3)
проверить("срок НЕ тронут", м["t0"] == 100)
проверить("счётчик не вырос", м["сбросов"] == 3)
проверить("модели сказано почему", "НЕ продлён" in о and "истечёт" in о)
проверить("подкрепление всё равно примкнуло", м["послано"] == 15)

print("\nфаза «стоим» — срок не трогается и предел ни при чём:")
м, о = примкнуть(3, сбросов=3, фаза="стоим")
проверить("срок НЕ тронут", м["t0"] == 100)
проверить("счётчик НЕ тронут", м["сбросов"] == 3)
проверить("строка про порог, а не про срок", "порог" in о)

print("\nпривязка к настоящему коду:")
исходник = open(os.path.join(os.path.dirname(os.path.abspath(__file__)),
                             "llm_policy.py"), encoding="utf-8").read()
проверить("ветка сброса читает ПРЕДЕЛ_СБРОСОВ",
          'if ПРЕДЕЛ_СБРОСОВ and МАРШ["сбросов"] >= ПРЕДЕЛ_СБРОСОВ' in исходник)
проверить("сброс увеличивает счётчик", 'МАРШ["сбросов"] += 1' in исходник)
проверить("новый марш ставит сбросов=0", "сбросов=0," in исходник)
проверить("ключ --gather-resets объявлен", '"--gather-resets"' in исходник)
проверить("ключ применяется к настройке",
          'globals()["ПРЕДЕЛ_СБРОСОВ"] = int(a.gather_resets)' in исходник)
проверить("в фазе «стоим» срок не трогается (ветка выше цела)",
          'if МАРШ["фаза"] == "стоим":' in исходник)

L.ПРЕДЕЛ_СБРОСОВ = 0
print(f"\n{'ВСЁ ОК' if not ошибок else str(ошибок) + ' СБОЕВ'}")
sys.exit(1 if ошибок else 0)
