проверка("4. «держать»/«к_своим» без полных приказов замаскированы", им(я, "держать", "к_своим") == {"держать": 0, "к_своим": 0})
# 5. частота: через 5 с без изменений решения нет; контакт — решение раньше срока
р5 = я.решить(dict(БАЗА, gametime=305, ocells=волна, ecells=его_далеко))
