"""§111: маска исполнимости, CONTINUE и частота решений в `tactic_core.Ядро`; метка учителя (`sim/учитель.метка`)."""
import os
import sys

import tactic_core as TC
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "sim"))
import учитель as У

беды = []


def проверка(имя, условие, пояснение=""):
    print(("  ОК   " if условие else "  ПЛОХО ") + имя + ("" if условие else " — " + str(пояснение)[:300]))
    if not условие:
        беды.append(имя)


def ядро():
    return TC.Ядро([0.0] * TC.N_ВЕСОВ3)


БАЗА = {"my_cx": 3, "my_cy": 3, "en_base": [12, 12], "upg_done": "", "my_freewar": 0}
дом = [{"x": 3, "y": 3, "n": 20, "пик": 20, "стрелков": 0}]
волна = [{"x": 8, "y": 8, "n": 30, "пик": 30, "стрелков": 0}]
его_далеко = [{"x": 12, "y": 12, "n": 40, "пик": 20, "стрелков": 20, "идут": 0, "tx": -1, "ty": -1}]
его_рядом = [{"x": 9, "y": 8, "n": 20, "пик": 10, "стрелков": 10, "идут": 0, "tx": -1, "ty": -1}]
его_к_базе = [{"x": 6, "y": 4, "n": 25, "пик": 15, "стрелков": 10, "идут": 25, "tx": 3, "ty": 3}]


def им(я, *имена):
    return {и: я.маска_[я.решения.index(и)] for и in имена}


# 1. маска: без волны в поле и без свободных — только CONTINUE и накопить
я = ядро(); я.решить(dict(БАЗА, gametime=300, ocells=дом, ecells=его_далеко))
проверка("1. дома 20 без свободных, волны нет: исполнимы лишь CONTINUE и накопить",
         [n for n, v in zip(я.решения, я.маска_) if v] == ["ничего", "накопить"], им(я, *я.решения))
# 2. свободные есть, волны нет — удары можно, приказы волне нельзя
я = ядро(); я.решить(dict(БАЗА, gametime=300, ocells=дом, ecells=его_далеко, my_freewar=20))
м = им(я, "удар_армия", "удар_база", "на_ближайшую", "домой", "к_своим", "подмога", "встретить")
проверка("2. свободные без волны: удары да, домой/к своим/подмога/встретить нет",
         м["удар_армия"] == 1 and м["удар_база"] == 1 and м["на_ближайшую"] == 1 and м["домой"] == 0 and м["к_своим"] == 0
         and м["подмога"] == 0 and м["встретить"] == 0, м)
# 3. волна в поле (единственная куча) — тип «волна_в_поле», домой можно
я = ядро(); я.решить(dict(БАЗА, gametime=300, ocells=волна, ecells=его_далеко))
проверка("3. единственная куча в поле — это волна, не дом: тип волна_в_поле, домой исполнимо",
         я.тип == "волна_в_поле" and им(я, "домой")["домой"] == 1, (я.тип, им(я, "домой")))
# 4. внутренние приказы без COSS3_NET_ORDERS=полные — пустые и маскируются
проверка("4. «держать»/«к_своим» без полных приказов замаскированы", им(я, "держать", "к_своим") == {"держать": 0, "к_своим": 0})
# 5. частота: через 5 с без изменений решения нет; контакт — решение раньше срока
р5 = я.решить(dict(БАЗА, gametime=305, ocells=волна, ecells=его_далеко))
р10 = я.решить(dict(БАЗА, gametime=310, ocells=волна, ecells=его_рядом))
проверка("5. наблюдение 5 с без изменений — None; контакт у волны — решение раньше 15 с", р5 is None and р10 is not None and я.тип == "контакт")
# 6. набег: встретить исполнимо при угрозе базе, тип «набег»
я = ядро(); я.решить(dict(БАЗА, gametime=300, ocells=дом, ecells=его_к_базе, my_freewar=20))
проверка("6. его группа идёт к ратуше: тип набег, «встретить» исполнимо", я.тип == "набег" and им(я, "встретить")["встретить"] == 1, (я.тип, им(я, "встретить")))
# 7. распределение: K = число исполнимых, H/lnK ≤ 1, p1 ≥ 1/K
p, K, H, Hn, p1, разрыв = я.распределение(я.оценки(я.признаки(dict(БАЗА, gametime=300, ocells=дом, ecells=его_к_базе, my_freewar=20), 300)), я.маска_)
проверка("7. распределение по маске: K исполнимых, H/lnK ≤ 1, p лучшего ≥ 1/K, вне маски p = 0",
         K == sum(я.маска_) and Hn is not None and Hn <= 1.0 + 1e-9 and p1 >= 1 / K - 1e-9 and all(p[k] == 0 for k in range(len(p)) if not я.маска_[k]), (K, Hn, p1))
# 8. сэмпл по маске: PPO-траектория несёт маску и не выбирает замаскированное
import random
я = ядро(); я.сэмпл = random.Random(1)
for t in range(300, 900, 15):
    я.решить(dict(БАЗА, gametime=t, ocells=дом, ecells=его_далеко))
проверка("8. сэмпл: траектория (x, a, logp, маска), выбор только из исполнимых",
         all(len(z) == 4 and z[3][z[1]] == 1 for z in я.траектория) and len(я.траектория) >= 10, len(я.траектория))
# 9. метка учителя
я = ядро(); st = dict(БАЗА, gametime=300, ocells=волна, ecells=его_рядом, my_freewar=10); я.решить(st)
проверка("9а. RETREAT без цели → домой", У.метка([{"cmd": "RETREAT", "count": 200}], я, st) == "домой")
проверка("9б. ATTACK в клетку его ближней кучи → на_ближайшую",
         У.метка([{"cmd": "ATTACK", "count": 10, "target": "cell", "cx": 9, "cy": 8, "group": 1}], я, st) == "на_ближайшую")
проверка("9в. STAGE → накопить; только MOVE/экономика → ничего",
         У.метка([{"cmd": "STAGE", "cx": 8, "cy": 8}], я, st) == "накопить" and У.метка([{"cmd": "TRAIN", "role": "infantry17"}], я, st) == "ничего")
проверка("9г. ATTACK target base → удар_база; peasants_free → удар_крестьяне; wave → подмога",
         У.метка([{"cmd": "ATTACK", "count": "all", "target": "base"}], я, st) == "удар_база"
         and У.метка([{"cmd": "ATTACK", "count": "all", "target": "peasants_free"}], я, st) == "удар_крестьяне"
         and У.метка([{"cmd": "ATTACK", "count": "all", "target": "wave"}], я, st) == "подмога")
я2 = ядро(); st2 = dict(БАЗА, gametime=300, ocells=дом, ecells=его_далеко, my_freewar=10); я2.решить(st2)
проверка("9д. метка вне маски сводится к исполнимой: «домой» без волны → ничего",
         У.метка([{"cmd": "RETREAT", "count": 200}], я2, st2) == "ничего")
# 10. сводка диагностики — по типам и смен в минуту
св = я.сводка_диагностики()
проверка("10. сводка диагностики: типы и смен_в_минуту", "смен_в_минуту" in св and any(k in св for k in TC.ТИПЫ_СОСТОЯНИЙ), св)

# 11. тень учителя: усыновление чужих групп в реестр волн (§111а)
import json as _json
хоз = _json.load(open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "sim", "поиск", "шт_s2_оборона.json"), encoding="utf-8"))["итог"]
тень = У.ТеньУчителя(хоз)
