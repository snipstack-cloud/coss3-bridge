"""Селфтест (218), живая Польша против Польши 4.11: пика бота 1+1 против 3+3 у игрока (удар 6 против 17, размен 7:1),
копилка держала 2916 золота, академию не заложили. Проверяет:
  (1) файл польша_пика_сразу_академия_первой.json: пика атака/защита 6 со сроком 0, копить_кроме_пики 1, академия_первой 1;
  (2) план прокачек Стратегии из файла: 12 ступеней пики со сроком < 1 с;
  (3) код: копилка пропускает bar.pikeman* при ключе; ветка академии стоит ПЕРЕД «ba17 раньше шахт».
"""
import json, sys
sys.path.insert(0, "sim")
import поиск_стратегии as ПС

ок, пало = 0, []
def проверить(что, имя):
    global ок
    ок += 1 if что else 0
    if not что: пало.append(имя)

п = json.load(open("sim/поиск/польша_пика_сразу_академия_первой.json", encoding="utf-8"))["итог"]
проверить(п["пик_ат"] == 6 and п["срок пик_ат"] == 0 and п["пик_защ"] == 6 and п["срок пик_защ"] == 0
          and п["копить_кроме_пики"] == 1 and п["академия_первой"] == 1 and п["академия_после"] == 1
          and п["огонь_рядом"] == 0 and п["ратуша_у_леса"] == 0, "(1) ключи файла")
с = ПС.Стратегия(п)
пики = [(u, t) for u, t in с.срок.items() if "pikeman" in u]
проверить(len(пики) == 12 and all(t < 1 for _, t in пики), f"(2) 12 ступеней пики сразу ({len(пики)})")
код = open("strategy_live.py", encoding="utf-8").read()
проверить('if int(float(п.get("копить_кроме_пики", 0) or 0)):' in код
          and 'not str(c.get("role") or "").startswith("bar.pikeman")' in код, "(3а) копилка пропускает пику")
проверить(код.index("академия первой после казармы") < код.index('отдано["BUILD ba17 раньше шахт"]'), "(3б) академия первой в очереди")
проверить("_ак_по_карману = all(" in код and "and _ак_по_карману and not _ак_голод):" in код, "(4) академия первой — только по карману (218а) и не при голоде (228)")
проверить(п.get("прокачка") == "ценность" and п.get("ступени_при_казармах") == 0 and п.get("ценность_цена") == 0
          and п.get("ценность_мин") == 0, "(5) ступени пики — оценщик без тормозов (218б)")
print(f"selftest_польша_пика: {ок} из {ок + len(пало)}")
for и in пало: print("  ПАЛО:", и)
raise SystemExit(1 if пало else 0)
