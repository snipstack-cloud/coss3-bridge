# -*- coding: utf-8 -*-
"""Самопроверка: походы врага ПО ОТРЯДАМ (`--enemy-march 1`, сетка `drow`).

Зачем. До 24.09 модель знала о движении врага одну среднюю клетку целей всех
идущих (`p1_mv_cx/cy`): два отряда врозь давали точку между ними, а
«к твоей базе» считалось только для целей ближе 60 ед. от ратуши. Блок
(ветка idea/enemy-march, живой игрой НЕ проверен) пишет сетку целей `drow`
теми же знаками, что frow; python режет её на отряды, называет сторону,
расстояние до нас, ближайший его источник и время подхода.
"""
import sys, os
sys.argv = [sys.argv[0]]
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import llm_policy as L
import coss3_map as M

ошибок = 0


def проверить(что, условие, пояснение=""):
    global ошибок
    print(("  ОК   " if условие else "  СБОЙ ") + что + (f" — {пояснение}" if пояснение else ""))
    ошибок += not условие


def сетка(имя, **клетки):
    строки = [["."] * 16 for _ in range(16)]
    for k, v in клетки.items():
        x, y = (int(t) for t in k.split(","))
        строки[y][x] = v if isinstance(v, str) else M.знак(v)
    return {f"{имя}{y}": "".join(строки[y]) for y in range(16)}


БАЗА = dict(gametime=600, grid_n=16, map_w=256, map_h=256, my_cx=12, my_cy=12,
            map_open=1, my_freewar=40, p1_enemy="true", p1_army=60,
            p1_mv_n=45, p1_mv_base=0, p1_mv_cx=7, p1_mv_cy=7,
            wave_n=30, wave_cx=6, wave_cy=3, wave_sent=30)
# два отряда: 25 идут к нашей ратуше (12,12), 20 — к нашей волне (6,3); стоят они в (3,3) и (2,2)
st = dict(БАЗА,
          **сетка("drow", **{"12,12": 25, "7,3": 20}),
          **сетка("frow", **{"3,3": 30, "2,2": 30}))

print("отряды по сетке целей:")
п = M.походы_врага(st)
проверить("найдено два отряда, а не одна средняя клетка", len(п) == 2, str(п))
проверить("первым — тот, что ближе к нам", п[0]["x"] == 12 and п[0]["y"] == 12 and п[0]["n"] == 25, str(п[0]))
проверить("он назван «к ТВОЕЙ РАТУШЕ»", п[0]["куда"] == "к ТВОЕЙ РАТУШЕ")
проверить("второй — к волне", п[1]["куда"] == "к ТВОЕЙ ВОЛНЕ", str(п[1]))
проверить("источник — ближайшая клетка его силы (до (7,3) от (3,3) четыре, от (2,2) пять)", п[0]["откуда"] == (3, 3) and п[1]["откуда"] == (3, 3), str(п))
проверить("время подхода: 9 кл. × 16 ед. / 2 = 72 с", п[0]["сек"] == 72, str(п[0]["сек"]))
проверить("без drow — пусто", M.походы_врага(dict(БАЗА, **сетка("frow", **{"3,3": 30}))) == [])
проверить("средняя клетка врёт: (7,7) — там никого нет", not any(o["x"] == 7 and o["y"] == 7 for o in п))

print("\nстроки в запросе:")
L.ЧЕСТНО = False
L.ПОХОДЫ_ВРАГА = False
текст = "\n".join(L.открытая_информация(st, {}))
проверить("без ключа — только прежняя средняя клетка", "в движении: 45" in текст and "отряд 25" not in текст)
L.ПОХОДЫ_ВРАГА = True
текст = "\n".join(L.открытая_информация(st, {}))
проверить("с ключом — оба отряда", "отряд 25 идёт в клетку (12,12)" in текст and "отряд 20 идёт в клетку (7,3)" in текст, текст)
проверить("сказано, куда именно", "это к ТВОЕЙ РАТУШЕ" in текст and "это к ТВОЕЙ ВОЛНЕ" in текст)
проверить("откуда и за сколько", "стоит в (3,3), ему 9 кл. — дойдёт за ~72 с" in текст, текст)
проверить("догадка названа догадкой", "это ближайший" in текст)
st_там = dict(БАЗА, **сетка("drow", **{"9,13": 30}), **сетка("frow", **{"9,13": 30}))
текст_там = "\n".join(L.открытая_информация(st_там, {}))
проверить("отряд, чья цель — его же клетка: «уже стоят», а не «дойдёт за 0 с»",
          "УЖЕ стоят в этой клетке" in текст_там and "дойдёт за ~0 с" not in текст_там, текст_там)
L.ПОХОДЫ_ВРАГА = False

print("\nпривязка к коду:")
py = open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "llm_policy.py"), encoding="utf-8").read()
inc = open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "block_hstate.inc"), encoding="latin-1").read()
проверить("блок пишет drow", "'drow'+IntToStr(hmj)" in inc)
проверить("массив целей объявлен на уровне блока рядом с hmforce",
          inc.find("var hmdest : array") > 0 and inc.find("var hmdest : array") < inc.find("for hmi := 0 to cHmGrid-1 do"))
проверить("массив обнуляется вместе с hmforce", "hmdest[hmi][hmj] := 0;" in inc)
проверить("цель копится только у идущих (внутри hsytx > -999999)",
          inc.find("hmdest[hmdx][hmdy] := hmdest[hmdx][hmdy] + 1") > inc.find("if (hsytx > -999999) then"))
проверить("в блоке нет кириллицы", all(ord(c) < 128 for c in inc))
проверить("drow пишется в трассу", '"brow", "drow"' in py)
проверить("отряды пишутся в трассу", '_снимок["en_march"]' in py)
проверить("ключ --enemy-march заведён и доезжает", '"--enemy-march"' in py and 'globals()["ПОХОДЫ_ВРАГА"] = True' in py)

print()
print("СБОЕВ: %d" % ошибок)
sys.exit(1 if ошибок else 0)
