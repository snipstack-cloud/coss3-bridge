беды = []


def проверка(имя, условие, пояснение=""):
    print(("  ОК   " if условие else "  ПЛОХО ") + имя + ("" if условие else " — " + str(пояснение)[:300]))
    if not условие:
        беды.append(имя)


НАШИ = ("infantry17=pikeman,hp90,atk9,wkind1,pause0,rmax188,dpike3,dsword2,dbullet4"
        " musk17=musketeer,hp65,atk10,wkind3,pause375,rmax1500,dpike0,dsword0,dbullet0")
ЕГО = ("infantry17=hp90,atk10,wkind1,pause0,rmax188,dpike5,dsword4,dbullet4"
       " musk17=hp65,atk12,wkind3,pause375,rmax1500,dpike0,dsword0,dbullet0")
свои, чужие = __import__("combat_math").разобрать(НАШИ), __import__("combat_math").разобрать(ЕГО)


def живая(**ключи):
    ж = SL.ЖиваяСтратегия.__new__(SL.ЖиваяСтратегия)
    ж.п = dict(json.load(open(os.path.join("sim", "поиск", "шт_s2_оборона.json"), encoding="utf-8"))["итог"], ручеёк=1, **ключи)
    ж.сеть, ж.имя, ж.n, ж.номера, ж.сводим = None, "тест", 1, 0, {}
    ж.пропущено, ж.отдано = collections.Counter(), collections.Counter()
    ж.реестр = SL.РеестрВолн()
    return ж


def st_(**кв):
    st = {"gametime": 600, "my_cx": 3, "my_cy": 3, "en_base": [12, 12], "fighters": НАШИ, "p1_fighters": ЕГО, "p1_squads_form": 0,
          "mil_inf": 60, "mil_shooters": 0, "mil_cav": 0, "mil_away": 0, "p1_inf": 40, "p1_shoot": 0, "p1_cav": 0,
          "ecells": [], "ocells": [{"x": 3, "y": 3, "n": 60, "пик": 60, "стрелков": 0, "конных": 0}], "groups": []}
    st.update(кв); return st


