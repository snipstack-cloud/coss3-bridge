#!/usr/bin/env python3
"""ПРИКАЗ ГРУППЕ БЕЗ ЧИСЛА (11.10, §150): Д4 4:09 — «волна W2 (13) ДОМОЙ» ушла в мост числом 1 (`move {'n': 1}`), блок
пересобрал группу 1 из одного бойца (состояние: `groups` 1,13 → 1,1), двенадцать шли дальше без волны и легли 12 на 4 у его
десяти в (5,6). В Д2 9:11 и 9:21 — то же (`n: 1`). Причина — `to_commands`: при номере группы и `count` 0 ставилось
`движение = 1`, и `br.attack(1, …, group=N)` для блока значит «пересобрать группу из одного».

Проверяется разбор: (а) RETREAT group 1 без числа — флаг «число ноль», группа 1; (б) MOVE count all group 92 — группа
92, число 9999 (создать из всех свободных); (в) MOVE group 92 без числа — флаг, группа 92 (раньше номер у MOVE не
читался вовсе); (г) ATTACK group 92 без числа — удар по группе, флаг; (д) ATTACK count 13 group 1 — как было, без флага;
(е) мост: `_приказ(0, …, group=1)` даёт count 0 и group 1, а без группы ноль — отказ.

    python3 selftest_приказ_группе.py
"""
import os, sys
К = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, К)
import llm_policy as L
import coss3_bridge as CB

ошибок = 0
def проверить(усл, что):
    global ошибок
    print(("ОК   " if усл else "ОШИБКА ") + что); ошибок += not усл

def разобрать(к):
    r = L.to_commands({"commands": [к]}, st={})
    return dict(attack=r[1], движение=r[5], цель=r[6], гр_дв=L.ГРУППА_ДВИЖЕНИЯ, гр_ат=L.ГРУППА_АТАКИ,
                счёт0=L.СЧЁТ_ПО_ГРУППЕ, удар0=L.УДАР_ПО_ГРУППЕ, брак=r[3])

о = разобрать({"cmd": "RETREAT", "count": 0, "target": "cell", "cx": 2, "cy": 2, "group": 1, "face": [1, 3]})
проверить(о["счёт0"] and о["гр_дв"] == 1 and о["цель"] == "retreat_cell" and not о["брак"], f"(а) RETREAT группе 1 без числа: {о}")
о = разобрать({"cmd": "MOVE", "count": "all", "target": "cell", "cx": 2, "cy": 2, "group": 92})
проверить(not о["счёт0"] and о["гр_дв"] == 92 and о["движение"] == L.ВСЕ_СВОБОДНЫЕ, f"(б) MOVE all группа 92 — создать из всех: {о}")
о = разобрать({"cmd": "MOVE", "group": 92, "target": "cell", "cx": 2, "cy": 2})
проверить(о["счёт0"] and о["гр_дв"] == 92 and not о["брак"], f"(в) MOVE группе 92 без числа: {о}")
о = разобрать({"cmd": "ATTACK", "group": 92, "target": "cell", "cx": 3, "cy": 3})
проверить(о["удар0"] and о["гр_ат"] == 92 and о["attack"] >= 1 and not о["брак"], f"(г) ATTACK группе 92 без числа: {о}")
о = разобрать({"cmd": "ATTACK", "count": 13, "target": "cell", "cx": 9, "cy": 9, "group": 1})
проверить(not о["удар0"] and о["гр_ат"] == 1 and о["attack"] == 13, f"(д) ATTACK 13 группа 1 — как было: {о}")
о = разобрать({"cmd": "MOVE", "count": 0, "target": "cell", "cx": 2, "cy": 2})
проверить(о["движение"] == 0 and о["брак"], f"(е) MOVE без числа и без группы — брак, как было: {о}")
b = CB.Bridge.__new__(CB.Bridge)
п = CB.Bridge._приказ(b, 0, "cell", mode="retreat", cx=2, cy=2, group=1, face=(1, 3))
проверить(п is not None and п.get("count") == 0 and п.get("group") == 1, f"(ж) мост: count 0 + group 1 — приказ запомненной группе: {п}")
проверить(CB.Bridge._приказ(b, 0, "cell", mode="retreat", cx=2, cy=2) is None, "(ж) мост: ноль без группы — отказ")
print(f"ошибок: {ошибок}")
sys.exit(1 if ошибок else 0)
