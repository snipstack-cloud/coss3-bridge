#!/usr/bin/env python3
"""ЦИКЛ САМОДОРАБОТКИ: модель сама пишет правило, сама пишет меру, цикл судит.

    python llm_policy.py --human --dir ИГРА --self-loop 1 --self-iters 6

Зачем. Вопрос игрока 20.09: какие части модель берёт на себя лучше, а что
лучше высчитывает питон. У моста уже есть шесть ключей, которыми питон отобрал
у модели решение (`--auto-seed`, `--auto-builders`, `--auto-train`,
`--auto-food`, `--base-hit`, `--face-threat`), и НИ ОДИН не измерен серией.
Цикл делает то же самое, но сам: пишет правило, объявляет меру, играет и
сравнивает с базой.

Одна итерация:

    1. БАЗА. Если трасс базы ещё нет — сыграть их. Это единственное плечо,
       которое цикл не трогает, и всё остальное меряется против него.
    2. ЗАМЫСЕЛ. Модель получает журнал прошлых итераций, НАСТОЯЩИЕ имена полей
       из снимка состояния и список помощников — и пишет правило и меры.
    3. ПРОВЕРКИ ДО ПАРТИЙ (`selfrules.py`): песочница правила по записанным
       состояниям и достижимость каждой меры по трассам базы. Не прошло —
       партий не тратим, а отказ ложится в журнал и в следующий запрос.
    4. ПАРТИИ. Отдельный процесс `llm_policy.py` с `--self-rules`.
    5. СУД по НЕПЕРЕСЕЧЕНИЮ РАЗМАХОВ: эффект засчитывается, только если
       размахи плеч не перекрываются. Пересеклись — вердикт «это разброс», и
       он объявлен правильным ответом. Критерий выбран не из красоты: первая
       сборка сравнивала средние с разбросом базы и на самопроверке выдала
       находку там, где её нет (см. `сравнить`).

ПЛАЦЕБО. Каждая N-я итерация (`--self-placebo`) играется БЕЗ правил, но в
журнале и в запросе к модели значится как обычная правка. Всё, что цикл там
«найдёт», — его собственная частота ложных находок. Это единственное число в
отчёте, которое говорит, чего стоят остальные.

ГРАНИЦЫ, которые цикл не переходит:
  * `.inc` не трогается ничем: его проверка только живой игрой на Windows;
  * `master` не трогается: всё живёт в ветке `idea/self-loop` и приходит
    игроку диффом;
  * мера пишется ДО партий и сверяется хешем — задним числом не переписать.
"""
