# --- журнал ------------------------------------------------------------------
def дописать(путь: str, запись: dict) -> None:
    with open(путь, "a", encoding="utf-8") as f:
        f.write(json.dumps(запись, ensure_ascii=False) + "\n")


def прочесть_журнал(путь: str) -> list:
    if not os.path.exists(путь):
        return []
    вышло = []
    with open(путь, encoding="utf-8") as f:
        for строка in f:
            строка = строка.strip()
            if строка:
                try:
                    вышло.append(json.loads(строка))
                except json.JSONDecodeError:
                    pass
    return вышло


def хеш(текст: str) -> str:
    return hashlib.sha256(текст.encode("utf-8")).hexdigest()[:12]


# --- трассы -------------------------------------------------------------------
def прочесть_трассу(путь: str) -> list:
    """Трасса партии — тот же jsonl, что пишет --botlog."""
    if not os.path.exists(путь):
        return []
    такты = []
    with open(путь, encoding="utf-8") as f:
        for строка in f:
            строка = строка.strip()
            if not строка:
                continue
            try:
                д = json.loads(строка)
            except json.JSONDecodeError:
                continue
            if isinstance(д, dict):
                такты.append(д)
    return такты


def партии_из(каталог: str) -> list:
    """Все партии плеча: по файлу трассы на партию.

    Мост пишет все партии эпизода в ОДИН botlog, поэтому режем по такту, где
    игровое время пошло назад, — это и есть новая партия.
    """
    if not os.path.isdir(каталог):
        # Молчаливый пустой список здесь означал бы «партий нет», и цикл судил
        # бы по пустоте — та же форма ложного нуля, от которой защищён весь
        # остальной файл. Пусть будет видно, что каталога НЕТ.
        print(f"    каталога нет: {каталог}")
        return []
    файлы = sorted(os.path.join(каталог, f) for f in os.listdir(каталог)
                   if f.endswith(".jsonl"))
    if not файлы:
        print(f"    в {каталог} нет ни одной трассы .jsonl")
        return []
    партии = []
    for путь in файлы:
        такты = прочесть_трассу(путь)
        текущая: list = []
        прошлое = -1.0
        for т in такты:
            gt = float(т.get("gt") or (т.get("state") or {}).get("gametime") or 0)
            if текущая and gt < прошлое:
                партии.append({"трасса": текущая, "итог": итог_партии(текущая)})
                текущая = []
            прошлое = gt
            текущая.append(т)
        if текущая:
            партии.append({"трасса": текущая, "итог": итог_партии(текущая)})
    return партии


def итог_партии(трасса: list) -> dict:
    """Чем кончилась партия. Считается ЗДЕСЬ, а не берётся из отчёта моста:
    цикл должен уметь судить и оборванную партию."""
    если_нет = {"тактов": len(трасса)}
    if not трасса:
        return если_нет
    последний = трасса[-1]
    st = последний.get("state") or {}
    цель = any(т.get("веха_убийства") for т in трасса)
    # ИМЕНА ПОЛЕЙ СВЕРЕНЫ С НАСТОЯЩЕЙ ТРАССОЙ base21 (209 тактов, 21.09), а не
    # взяты по смыслу. Первая же попытка написать их по памяти дала `my_army` и
    # `my_peasants`, которых в снимке нет вовсе, — и все четыре партии показали
    # армию НОЛЬ. Это шестой ложный ноль проекта за двое суток и первый, который
    # цикл поймал на себе самом.
    return {
        "тактов": len(трасса),
        "gt": float(последний.get("gt") or st.get("gametime") or 0),
        "цель": 1 if цель else 0,
        "армия": selfrules.чис(st, "mil_inf") + selfrules.чис(st, "mil_shooters"),
        "крестьян": selfrules.чис(st, "peasants"),
        "еда": selfrules.чис(st, "food"),
    }


def состояния_из(партии: list) -> list:
    """Снимки состояния из трасс — по ним гоняется песочница правила."""
    вышло = []
    for п in партии:
        for т in п.get("трасса", []):
            st = т.get("state")
            if isinstance(st, dict) and st:
                вышло.append(st)
    return вышло


# --- запуск партий ------------------------------------------------------------
def аргументы_партии(партий: int, botlog: str, лог: str, правила: str) -> list:
    """Собрать командную строку партии из ТОЙ ЖЕ, которой запущен цикл.

    Так плечо наследует всё, что дал контейнер (модель, такт, горизонт, мир,
    подсказки, запреты), и отличается от базы ровно ключом --self-rules. Иначе
    вторая разница между плечами убила бы замер — ровно как это случилось с
    серией stage_num 20.09.
    """
    свои = {"--self-loop", "--self-io", "--self-iters", "--self-games",
            "--self-placebo", "--self-rules", "--episodes", "--botlog", "--log"}
    чужие, i = [], 0
    сырьё = sys.argv[1:]
    while i < len(сырьё):
        x = сырьё[i]
        имя = x.split("=", 1)[0]
        if имя in свои:
            i += 2 if "=" not in x and i + 1 < len(сырьё) and not сырьё[i + 1].startswith("--") else 1
            continue
        чужие.append(x)
        i += 1
    аргс = [sys.executable, "-u", "llm_policy.py"] + чужие + [
        "--episodes", str(партий), "--botlog", botlog, "--log", лог]
    if правила:
        аргс += ["--self-rules", правила]
    return аргс


def сыграть(партий: int, каталог: str, правила: str, тайм_аут: float) -> dict:
    """Одно плечо: партии отдельным процессом, трасса в свой каталог."""
    os.makedirs(каталог, exist_ok=True)
    botlog = os.path.join(каталог, "bot.jsonl")
    лог = os.path.join(каталог, "policy.log")
    аргс = аргументы_партии(партий, botlog, лог, правила)
    начало = time.time()
    print("    " + " ".join(аргс[2:]))
    try:
        r = subprocess.run(аргс, timeout=тайм_аут,
                           cwd=os.path.dirname(os.path.abspath(__file__)))
        код = r.returncode
    except subprocess.TimeoutExpired:
        код = -1
    return {"код": код, "секунд": round(time.time() - начало, 1),
            "каталог": каталог, "оборвано": код == -1}


# --- запрос к модели ----------------------------------------------------------
def поля_снимка(состояния: list, сколько: int = 220) -> list:
    """НАСТОЯЩИЕ имена полей состояния — самое важное в запросе.

    Без них модель сочиняет поле, которого в снимке нет, правило молча ничего
    не делает, и получается ложный ноль. За 20.09 таких было пять, и три из
    них — ровно про «поле в трассу не пишется».
    """
    поля = {}
    for st in состояния:
        for k, v in st.items():
            if k not in поля and v not in (None, ""):
                поля[k] = str(v)[:24]
    имена = sorted(поля)[:сколько]
    return [f"{k} = {поля[k]}" for k in имена]


def запрос(журнал: list, поля: list, база: dict, итерация: int) -> str:
    прошлое = []
    for з in журнал[-8:]:
        if з.get("вид") != "итерация":
            continue
        прошлое.append(
            f"- итерация {з.get('итерация')}: правило «{з.get('правило', '?')}» — "
            f"{з.get('вердикт', '?')}. {з.get('почему', '')}"[:400])
    н = "\n"
    return f"""Итерация {итерация}.

## Что ты пишешь

Одно ПРАВИЛО на питоне и одну-три МЕРЫ к нему.

Правило — функция такта. Её зовут после всех правок моста, она видит команды,
которые УЙДУТ В ИГРУ, и может их поменять:

    def правило(st, cmds, ctx):
        # st   — снимок состояния, значения СТРОКАМИ (бери через чис(st, 'имя'))
        # cmds — список Command, что модель решила в этот такт
        # ctx  — {{'gt': игровые секунды, 'attack': идёт ли волна}}
        # вернуть (новый список команд, [строки, которые мост скажет вслух])
        return cmds, []

Правило ОБЯЗАНО объяснять словами каждую свою правку: молчаливое вмешательство
в трассу не попадает, и потом его не отличить от бездействия.

Мера — функция по готовой партии, возвращает ЧИСЛО:

    def мера(трасса, итог):
        # трасса — список тактов; в такте есть 'state' (снимок), 'cmds'
        #          (команды модели), 'forced' (чем вмешался мост), 'gt'
        # итог   — {{'тактов','gt','цель','армия','крестьян','еда'}}
        return 0.0

## Что можно звать внутри

build(роль, сколько) train(роль, сколько) balance(ресурс, людей)
builders(потолок) seed() upgrade(имя) formation()
чис(st, 'поле') есть(st, 'поле') INFINITE RESOURCE BUILDABLE
len int float min max abs sorted sum any all range round str dict list set
tuple enumerate zip bool isinstance

Ничего больше: ни импортов, ни файлов, ни времени.

## НАСТОЯЩИЕ поля снимка (имя = пример значения)

{н.join(поля)}

## База, против которой будут мерить

партий {база.get('партий')}, тактов {база.get('тактов')},
цель взята в {база.get('целей')} из {база.get('партий')}

## Что уже пробовали

{н.join(прошлое) or 'ничего, это первая итерация'}

## Чего от тебя ждут

Забрать у модели решение, которое питон считает лучше. Признак такого решения:
оно узкое, однозначное и проверяется числом из снимка. Признак плохого — «пусть
правило играет всю партию»: это не проверить и не сравнить.

Мера должна РАЗЛИЧАТЬ: если по партиям базы она даёт одно и то же число, её
отвергнут, не сыграв ни партии. Мера про поле, которого нет в списке выше,
тоже будет отвергнута.

## Ответ

{{"правило": {{"имя": "короткое_имя", "зачем": "что именно чинит и почему это питон, а не модель", "код": "def правило(st, cmds, ctx):\\n    ..."}},
 "меры": [{{"имя": "...", "зачем": "...", "больше_лучше": true, "код": "def мера(трасса, итог):\\n    ..."}}],
 "чего_жду": "какое число и куда сдвинется, если правило право",
 "признак_вреда": "по какому числу будет видно, что правило вредит"}}"""


def спросить(client, модель: str, текст: str, таймаут: float = 180.0) -> dict:
    r = client.chat.completions.create(
        model=модель,
        messages=[{"role": "system", "content": СИСТЕМА},
                  {"role": "user", "content": текст}],
        temperature=0.6,
        max_tokens=4000,
        timeout=таймаут,
    )
    сырое = (r.choices[0].message.content or "").strip()
    if "```" in сырое:
        куски = сырое.split("```")
        for к in куски:
            к = к.strip()
            if к.startswith("json"):
                к = к[4:].strip()
            if к.startswith("{"):
                сырое = к
                break
    return json.loads(сырое)


# --- суд ----------------------------------------------------------------------
def посчитать(меры: list, партии: list) -> dict:
    """Каждая мера по каждой партии плеча."""
    вышло = {}
    for м in меры:
        значения = []
        for п in партии:
            try:
                значения.append(float(м.функция(п.get("трасса", []),
                                                dict(п.get("итог", {})))))
            except Exception:
                значения.append(float("nan"))
        вышло[м.имя] = значения
    return вышло


def сравнить(имя: str, база: list, плечо: list, больше_лучше: bool) -> dict:
    """Суд по НЕПЕРЕСЕЧЕНИЮ РАЗМАХОВ, а не по разнице средних.

    Первая сборка цикла сравнивала разницу средних с разбросом ВНУТРИ БАЗЫ — и
    самопроверка тут же поймала её на том самом случае, ради которого всё
    затевалось. Пара base22/switch4, 20.09: база 132 и 115 (размах 17), плечо
    225 и 97 (размах 128). Разница средних 37,5 больше 17 — по тому правилу
    вышла бы «находка», хотя плечо разбросано вчетверо сильнее самой разницы, и
    правильный ответ, который тогда дал и критик, — «это разброс».

    Поэтому критерий такой: разница засчитывается, только если размахи плеч НЕ
    ПЕРЕСЕКАЮТСЯ. При двух-четырёх партиях на плечо это единственное, что
    вообще можно утверждать честно, и оно не даёт выдать разброс за эффект.
    Цена известна заранее: настоящий, но некрупный эффект на двух партиях так
    не увидеть — для этого нужны 10–15 партий на плечо.
    """
    ч = [x for x in база if x == x]
    п = [x for x in плечо if x == x]
    if not ч or not п:
        return {"мера": имя, "вердикт": "не посчиталось",
                "база": база, "плечо": плечо}
    сб, сп = sum(ч) / len(ч), sum(п) / len(п)
    разброс_б = max(ч) - min(ч) if len(ч) > 1 else 0.0
    разброс_п = max(п) - min(п) if len(п) > 1 else 0.0
    разница = сп - сб
    выше = min(п) > max(ч)
    ниже = max(п) < min(ч)
    хватает = выше or ниже
    лучше = (выше if больше_лучше else ниже)
    return {
        "мера": имя, "база": ч, "плечо": п,
        "среднее_базы": round(сб, 3), "среднее_плеча": round(сп, 3),
        "разница": round(разница, 3),
        "разброс_базы": round(разброс_б, 3), "разброс_плеча": round(разброс_п, 3),
        "размах_базы": [round(min(ч), 3), round(max(ч), 3)],
        "размах_плеча": [round(min(п), 3), round(max(п), 3)],
        "вердикт": ("это разброс" if not хватает else
                    ("лучше базы" if лучше else "хуже базы")),
        "хватает_ли": bool(хватает),
        "почему": ("размахи плеч пересекаются — при таком числе партий "
                   "отличить эффект от разброса нельзя" if not хватает else
                   "размахи плеч не пересекаются"),
    }


# --- одна итерация ------------------------------------------------------------
def итерация(client, a, io: str, n: int, базапартии: list, журнал: list,
             плацебо: bool) -> dict:
    состояния = состояния_из(базапартии)
    сводка_базы = {
        "партий": len(базапартии), "тактов": len(состояния),
        "целей": sum(int(п["итог"].get("цель", 0)) for п in базапартии),
    }
    print(f"\n=== итерация {n}{' (ПЛАЦЕБО)' if плацебо else ''} ===")
    текст = запрос(журнал, поля_снимка(состояния), сводка_базы, n)
    try:
        ответ = спросить(client, a.model, текст, float(a.timeout or 180))
    except Exception as e:
        print(f"    модель не ответила: {type(e).__name__}: {e}")
        return {"вид": "итерация", "итерация": n, "вердикт": "модель не ответила",
                "почему": f"{type(e).__name__}: {e}", "плацебо": плацебо}

    п_сырое = ответ.get("правило") or {}
    имя = str(п_сырое.get("имя", f"правило{n}"))
    запись = {"вид": "итерация", "итерация": n, "плацебо": плацебо,
              "правило": имя, "зачем": str(п_сырое.get("зачем", ""))[:600],
              "чего_жду": str(ответ.get("чего_жду", ""))[:400],
              "признак_вреда": str(ответ.get("признак_вреда", ""))[:400],
              "код_хеш": хеш(str(п_сырое.get("код", ""))),
              "время": time.strftime("%Y-%m-%d %H:%M:%S")}
    print(f"    правило «{имя}»: {запись['зачем'][:150]}")

    # --- проверка 2: песочница правила
    п = selfrules.Правило(имя=имя, зачем=запись["зачем"],
                          код=str(п_сырое.get("код", "")))
    try:
        п.функция = selfrules.скомпилировать(п.код, "правило")
    except Exception as e:
        запись.update(вердикт="правило не компилируется",
                      почему=f"{type(e).__name__}: {e}")
        print(f"    ОТКАЗ: {запись['почему']}")
        return запись
    проба = selfrules.проверить_правило(п, состояния)
    запись["песочница"] = проба
    print(f"    песочница: {проба['срабатываний']} срабатываний на "
          f"{проба['тактов']} тактах, сбоев {проба['сбоев']} — {проба['почему']}")
    if not проба["годно"]:
        запись.update(вердикт="правило отвергнуто до партий",
                      почему=f"песочница: {проба['почему']}"
                             + (f"; {проба['примеры'][0]}" if проба["примеры"] else ""))
        return запись

    # --- проверка 1: достижимость мер
    меры = []
    for m in (ответ.get("меры") or [])[:3]:
        м = selfrules.Мера(имя=str(m.get("имя", "мера")),
                           зачем=str(m.get("зачем", "")),
                           код=str(m.get("код", "")),
                           больше_лучше=bool(m.get("больше_лучше", True)))
        try:
            м.функция = selfrules.скомпилировать(м.код, "мера")
        except Exception as e:
            м.функция = None
            м.зачем += f" [НЕ КОМПИЛИРУЕТСЯ: {e}]"
        меры.append(м)
    достижимость = {м.имя: selfrules.достижима(м, базапартии) for м in меры}
    запись["достижимость"] = достижимость
    for имя_м, d in достижимость.items():
        print(f"    мера «{имя_м}»: {d['вердикт']}"
              + (f", по базе {d.get('значения')}" if d.get("значения") else ""))
    годные = [м for м in меры if достижимость.get(м.имя, {}).get("годна")]
    if not годные:
        запись.update(вердикт="мер нет",
                      почему="ни одна мера не различает партии базы — "
                             "любой её ноль после правки означал бы только, "
                             "что считать нечем")
        return запись

    # --- партии
    каталог = os.path.join(io, f"iter{n:03d}")
    файл_правил = os.path.join(каталог, ПРАВИЛА_ФАЙЛ)
    os.makedirs(каталог, exist_ok=True)
    with open(файл_правил, "w", encoding="utf-8") as f:
        json.dump({"правила": [{"имя": п.имя, "зачем": п.зачем, "код": п.код}]},
                  f, ensure_ascii=False, indent=1)
    with open(os.path.join(каталог, МЕРЫ_ФАЙЛ), "w", encoding="utf-8") as f:
        json.dump({"меры": [{"имя": м.имя, "зачем": м.зачем, "код": м.код,
                             "больше_лучше": м.больше_лучше} for м in годные]},
                  f, ensure_ascii=False, indent=1)
    партий = int(getattr(a, "self_games", 2) or 2)
    срок = float(партий) * float(a.horizon or 1200) * 3 + 900
    итог = сыграть(партий, каталог, "" if плацебо else файл_правил, срок)
    запись["партии"] = итог
    новые = партии_из(каталог)
    if not новые:
        запись.update(вердикт="партий нет",
                      почему=f"процесс вернул {итог['код']}, трасса пуста")
        print(f"    ОТКАЗ: {запись['почему']}")
        return запись

    # --- суд
    счёт_базы = посчитать(годные, базапартии)
    счёт_плеча = посчитать(годные, новые)
    сравнения = [сравнить(м.имя, счёт_базы[м.имя], счёт_плеча[м.имя],
                          м.больше_лучше) for м in годные]
    запись["сравнения"] = сравнения
    запись["итог_плеча"] = [п["итог"] for п in новые]
    for с in сравнения:
        print(f"    {с['мера']}: база {с.get('размах_базы')} -> плечо "
              f"{с.get('размах_плеча')} — {с['вердикт']}")
    нашлось = [с for с in сравнения if с.get("хватает_ли")]
    запись["вердикт"] = ("ничего не изменилось" if not нашлось else
                         "; ".join(f"{с['мера']} {с['вердикт']}" for с in нашлось))
    запись["почему"] = ("разница между плечами не больше разброса внутри базы"
                        if not нашлось else "")
    if плацебо and нашлось:
        запись["ложная_находка"] = True
        print("    ВНИМАНИЕ: это ПЛАЦЕБО, правило не применялось — "
              "всё найденное здесь есть ложная находка")
    return запись


# --- отчёт --------------------------------------------------------------------
def отчёт(журнал: list, путь: str) -> None:
    итерации = [з for з in журнал if з.get("вид") == "итерация"]
    плацебо = [з for з in итерации if з.get("плацебо")]
    ложные = [з for з in плацебо if з.get("ложная_находка")]
    строки = [
        "# Цикл самодоработки — что получилось",
        "",
        f"Итераций: {len(итерации)}. Из них плацебо: {len(плацебо)}.",
        "",
        "## ЧЕГО СТОЯТ ЭТИ ЧИСЛА",
        "",
    ]
    if not плацебо:
        строки.append("Плацебо не игралось ни разу — частота ложных находок "
                      "цикла НЕИЗВЕСТНА, и находки ниже нечем взвесить.")
    else:
        строки.append(
            f"В {len(плацебо)} итерациях правило НЕ применялось, а цикл об этом "
            f"не знал. «Находок» там {len(ложные)}. Это его собственная частота "
            f"ложных находок, и все выводы ниже надо читать через неё.")
    строки += ["", "## Итерации", "",
               "| # | правило | песочница | вердикт |", "|---|---|---|---|"]
    for з in итерации:
        п = з.get("песочница") or {}
        строки.append(
            f"| {з.get('итерация')}{' П' if з.get('плацебо') else ''} "
            f"| {з.get('правило', '?')} "
            f"| {п.get('срабатываний', '—')}/{п.get('тактов', '—')} "
            f"| {str(з.get('вердикт', '?'))[:80]} |")
    отвергнутые = [з for з in итерации if "отвергнут" in str(з.get("вердикт", ""))
                   or "не компилируется" in str(з.get("вердикт", ""))
                   or з.get("вердикт") == "мер нет"]
    строки += ["", "## Отвергнуто ДО партий", ""]
    if not отвергнутые:
        строки.append("ничего — все замыслы дошли до партий")
    for з in отвергнутые:
        строки.append(f"* итерация {з.get('итерация')}, «{з.get('правило')}»: "
                      f"{з.get('почему', '')}")
    строки += ["", "## Что найдено", ""]
    находки = [з for з in итерации if not з.get("плацебо")
               and з.get("сравнения") and any(с.get("хватает_ли")
                                              for с in з["сравнения"])]
    if not находки:
        строки.append("ничего, что превысило бы разброс внутри базы")
    for з in находки:
        строки.append(f"### итерация {з.get('итерация')}: {з.get('правило')}")
        строки.append("")
        строки.append(з.get("зачем", ""))
        строки.append("")
        for с in з["сравнения"]:
            строки.append(
                f"* {с['мера']}: база {с.get('размах_базы')} (среднее "
                f"{с.get('среднее_базы')}) -> плечо {с.get('размах_плеча')} "
                f"(среднее {с.get('среднее_плеча')}) — {с['вердикт']}")
        строки.append("")
    with open(путь, "w", encoding="utf-8") as f:
        f.write("\n".join(строки) + "\n")


# --- вход ---------------------------------------------------------------------
def run_from_policy(a, client) -> int:
    io = (getattr(a, "self_io", "") or
          (os.path.dirname(os.path.abspath(a.botlog)) if getattr(a, "botlog", "")
           else os.getcwd()))
    io = os.path.join(io, "selfloop")
    os.makedirs(io, exist_ok=True)
    журнал_путь = os.path.join(io, ЖУРНАЛ)
    отчёт_путь = os.path.join(io, ОТЧЁТ)
    партий = int(getattr(a, "self_games", 2) or 2)
    всего = int(getattr(a, "self_iters", 0) or 0)
    каждая = int(getattr(a, "self_placebo", 4) or 0)

    print(f"цикл самодоработки: каталог {io}, партий на плечо {партий}, "
          f"итераций {всего or 'пока не погасят'}, "
          f"плацебо каждая {каждая or '—'}-я")
    print("ЧЕГО ЦИКЛ НЕ ТРОГАЕТ: .inc (проверяется только живой игрой на "
          "Windows) и master (всё идёт в ветку и приходит диффом)")

    # --- база
    базакаталог = os.path.join(io, "база")
    базапартии = партии_из(базакаталог)
    if not базапартии:
        print(f"\n=== база: {партий} партий без единого правила ===")
        срок = float(партий) * float(a.horizon or 1200) * 3 + 900
        сыграть(партий, базакаталог, "", срок)
        базапартии = партии_из(базакаталог)
    if not базапартии:
        print("базы нет — партии не сыграны, мерить не с чем. Останавливаюсь.")
        return 1
    print(f"база: {len(базапартии)} партий, "
          f"{len(состояния_из(базапартии))} тактов состояния")
    дописать(журнал_путь, {"вид": "база", "партий": len(базапартии),
                           "итоги": [п["итог"] for п in базапартии],
                           "время": time.strftime("%Y-%m-%d %H:%M:%S")})

    n = len([з for з in прочесть_журнал(журнал_путь)
             if з.get("вид") == "итерация"])
    сделано = 0
    while всего == 0 or сделано < всего:
        n += 1
        сделано += 1
        плацебо = bool(каждая) and (n % каждая == 0)
        журнал = прочесть_журнал(журнал_путь)
        try:
            запись = итерация(client, a, io, n, базапартии, журнал, плацебо)
        except KeyboardInterrupt:
            print("\nостановлено рукой")
            break
        except Exception as e:
            запись = {"вид": "итерация", "итерация": n, "плацебо": плацебо,
                      "вердикт": "цикл упал",
                      "почему": f"{type(e).__name__}: {e}"}
            print(f"    цикл упал: {type(e).__name__}: {e}")
        дописать(журнал_путь, запись)
        отчёт(прочесть_журнал(журнал_путь), отчёт_путь)
        print(f"    отчёт: {отчёт_путь}")
    отчёт(прочесть_журнал(журнал_путь), отчёт_путь)
    return 0
