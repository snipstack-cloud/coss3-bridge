# -*- coding: utf-8 -*-
"""Самопроверка: подкрепление волны — готовым приказом, а не советом в конце.

Живая партия 20.09. Волна ушла на 12:02 (73 бойца), и дальше дома копилось
79 -> 95 -> 103 свободных, которые простояли три с половиной минуты. Модель
дословно повторяла первый совет строки «ДОТЕКАНИЕ»: «волна 73 уже в поле,
коплю дома второй кулак».

Игрок увидел то же на экране: «большое количество армии осталось на базе и не
была подведена к противнику».

`ATTACK target=wave` в строке БЫЛ — но последним из трёх вариантов и без числа.
По правилу матрицы связок это то же, что молчание: команда без посчитанного
числа и готового приказа не берётся (MOVE в 75 процентах тактов — ноль
приказов; UPGRADE в 2 процентах — 56 приказов, потому что рядом цена).

Стережётся:
* готовый приказ на подкрепление стоит ПЕРВЫМ и с числом свободных;
* оговорка про растягивание не потеряна — отдельный поход по-прежнему назван
  худшим выбором, с причиной;
* совет «копить дома» больше не идёт первым.
"""
import llm_policy as L

беды = []


def проверка(имя, условие, пояснение=""):
    if условие:
        print("  ОК    " + имя)
    else:
        беды.append(имя)
        print("  ПЛОХО " + имя + (" — " + пояснение if пояснение else ""))


def состояние(послано=73, дома=103, ушли=28):
    n = 16
    ст = {"gametime": 873, "grid_n": n, "map_open": 1, "my_cx": 3, "my_cy": 12,
          "peasants": 60, "mil_inf": дома + ушли, "mil_shooters": 0, "mil_cav": 0,
          "my_freewar": дома, "mil_away": ушли, "wave_sent": послано,
          "ba17": 2, "smiths": 1, "mills": 1, "centers": 1,
          "food": 9000, "gold": 5000, "iron": 3000, "wood": 3000, "stone": 3000,
          "p1_enemy": 1, "p1_army": 109, "mil_far": 200, "mil_near": 10}
    for y in range(n):
        ст[f"frow{y}"] = "." * n
        ст[f"arow{y}"] = "." * n
    return ст


ст = состояние()
т = L.situation(ст, ст, [], "", None)
строка = next((s for s in т.splitlines() if "ДОТЕКАНИЕ:" in s and "в поле" in s), "")

проверка("строка дотекания есть", bool(строка), "не нашлась")
проверка("готовый приказ на подкрепление с числом",
         '"cmd":"ATTACK","count":103,"target":"wave"' in строка, строка[:200])
проверка("приказ идёт РАНЬШЕ оговорки про отдельный поход",
         строка.find("target") < строка.find("Отдельный ATTACK"), строка[:200])
проверка("сказано, что мост ведёт их к дерущимся",
         "к тем, кто уже дерётся" in строка)
проверка("оговорка про растягивание не потеряна",
         "дойдут по одному" in строка and "защитников" in строка)
проверка("копить третий кулак названо худшим",
         "худшее из трёх" in строка, строка[-120:])
проверка("совет копить больше не идёт первым",
         "Либо копи новый кулак дома" not in строка)

# когда в поле никого — строки быть не должно
ст2 = состояние(послано=0, ушли=0)
т2 = L.situation(ст2, ст2, [], "", None)
проверка("без волны в поле строки дотекания нет",
         not any("ДОТЕКАНИЕ:" in s and "в поле" in s for s in т2.splitlines()),
         "подкреплять некого")

print()
if беды:
    print(f"БЕД: {len(беды)} — {', '.join(беды)}")
    raise SystemExit(1)
print("всё чисто")
