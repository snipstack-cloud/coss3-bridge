#!/usr/bin/env python3
"""BALANCE по шахте ВЫВОДИТ лишних, а не только досылает (20.10, задание мака по Д9).

Находка мака по трассе Д9: ветка шахт в блоке только досылала, и на
`BALANCE gold 5` при пятнадцати внутри отвечала «15 already work that mine» —
44 раза за партию. Значит правила «снять с золота» (153 и 166б) живьём не
сработали ни разу: снятие было строкой в why и ничем больше.

Блок правлен на Windows и проверяется ЖИВОЙ игрой (в game.log
`MINE res3 let out K, inside was M`). Здесь проверяется МОК: он обязан врать в
ту же сторону, что игра, иначе петля «сняли с золота — отдали камню»
проверяется вслепую, как это и вышло за четыре партии.
"""
import os
import sys
import tempfile

sys.argv = [sys.argv[0]]
import mock_human as m  # noqa: E402

провалов = 0


def проверить(имя, условие):
    global провалов
    print(("  ОК   " if условие else "  ПРОВАЛ ") + имя)
    if not условие:
        провалов += 1


def мир(d, шахт, на):
    w = m.Мир(d, plind=0)
    w.peasants = 30
    for k in w.res:
        w.res[k] = 99999
    w.здания["minegold"] = шахт
    w.здания["mineiron"] = 1
    w.здания["mill"] = 1
    w.на.update(на)
    return w


def balance(d, w, res, n):
    with open(os.path.join(d, "coss3_cmd_P0.dat"), "w", encoding="utf-8") as f:
        f.write("count=1\n0_cmd=BALANCE\n0_a1=%d\n0_a2=%d\n" % (res, n))
    w.команды()


with tempfile.TemporaryDirectory() as d:
    # (а) просьба меньше, чем сидит внутри: лишние выходят
    w = мир(d, 3, {"gold": 15, "iron": 3, "stone": 2})
    свободно_до = w.свободно()
    balance(d, w, 3, 5)
    проверить("(а) на золоте 15, просят 5: стало 5", w.на["gold"] == 5)
    проверить("(а) вышедшие десять стали свободны",
              w.свободно() == свободно_до + 10)
    проверить("(а) железо и камень не тронуты",
              w.на["iron"] == 3 and w.на["stone"] == 2)

    # (б) ровно столько, сколько просят: ничего не двигается
    w = мир(d, 3, {"gold": 5})
    balance(d, w, 3, 5)
    проверить("(б) на золоте 5, просят 5: осталось 5", w.на["gold"] == 5)

    # (в) просьба больше: досылка работает как раньше
    w = мир(d, 2, {"gold": 5})
    balance(d, w, 3, 7)
    проверить("(в) на золоте 5, просят 7, мест 10: стало 7", w.на["gold"] == 7)

    # (г) вывод идёт по своей шахте: просьба по железу не трогает золото
    w = мир(d, 3, {"gold": 12, "iron": 5})
    balance(d, w, 4, 3)
    проверить("(г) просят железо 3: железо 3, золото 12",
              w.на["iron"] == 3 and w.на["gold"] == 12)

    # (д) ноль в ветку шахт не входит вовсе: страж `hca2 > 0` в блоке. Мок молчит
    # так же — «опустошить шахту» сейчас не выражается приказом, и это сказано маку.
    w = мир(d, 3, {"gold": 9})
    balance(d, w, 3, 0)
    проверить("(д) просят золото 0: блок молчит, и мок молчит — осталось 9",
              w.на["gold"] == 9)

print("\nПРОВАЛОВ: %d" % провалов)
raise SystemExit(1 if провалов else 0)
