# -*- coding: utf-8 -*-
"""Маленькая карта по правилам хакатона — и архив, который от этого не ломается.

Повод, 27.09. Правила хакатона требуют МАЛЕНЬКУЮ карту (`mapsize` 3, 256 единиц;
0 -> 320, 1 -> 480, 2 -> 640 — `donewgame.inc`). Размер не задавал НИКТО: блок
`NEW` выставлял ресурсы, перемирие, шар, пушки, захват, рынок и век, а карту брал
из `profile.dat`, где стояло `mapsize = 0`. То есть 213 прогонов архива сыграны на
320, а не на 256.

Цена ошибки не только в условиях. Клетка сетки — это `width/16`: 20 единиц на 320
и 16 на 256. Значит каждый порог «в клетках» означал не ту дистанцию, что записана:
«пять клеток это 80 единиц» — на самом деле 100, а тыл стрелков в шести клетках —
120 единиц против предельного выстрела мушкетёра 15.

Стережётся:
* `mapsize` доезжает командой `NEW` и эхом возвращается в квитанции;
* состояние отдаёт `map_w`/`map_h`, и python считает клетку ПО ФАКТУ;
* у записей без этого поля берётся 20 (карта контейнеров), а не 16 — иначе старая
  молчаливая константа снова соврёт;
* рынок и век больше не вложены в `capture`: раньше без захвата они молча не
  уезжали;
* контейнер по умолчанию ставит маленькую карту, и её можно вернуть на старую
  одним ключом окружения — так архив размечается, а не ломается.
"""
import io
import os

import coss3_map as M

беды = []


def проверка(имя, условие, пояснение=""):
    if условие:
        print("  ОК    " + имя)
    else:
        беды.append(имя)
        print("  ПЛОХО " + имя + (" — " + str(пояснение)[:300] if пояснение else ""))


ЗДЕСЬ = os.path.dirname(os.path.abspath(__file__))
БЛОК_ПЕТЛИ = io.open(os.path.join(ЗДЕСЬ, "block_gameloop.inc"), encoding="utf-8").read()
БЛОК_СОСТ = io.open(os.path.join(ЗДЕСЬ, "block_hstate.inc"), encoding="utf-8").read()
МОСТ = io.open(os.path.join(ЗДЕСЬ, "coss3_bridge.py"), encoding="utf-8").read()
ПОЛИТИКА = io.open(os.path.join(ЗДЕСЬ, "llm_policy.py"), encoding="utf-8").read()
ВХОД = io.open(os.path.join(ЗДЕСЬ, "docker", "entrypoint.sh"), encoding="utf-8").read()
ОТКРЫТИЕ = io.open(os.path.join(ЗДЕСЬ, "opening.py"), encoding="utf-8").read()

# 1. Блок петли: читает, применяет и отдаёт эхом.
проверка("NEW читает mapsize",
         "brctlmapsz := ParserGetIntValueByKeyByHandle(hctl, 'mapsize');" in БЛОК_ПЕТЛИ)
проверка("NEW применяет его к настройкам карты",
         "gMap.settings.gen.mapsize := brctlmapsz;" in БЛОК_ПЕТЛИ)
проверка("квитанция отдаёт применённый размер эхом",
         "ParserSetIntValueByKeyByHandle(back, 'mapsize', gMap.settings.gen.mapsize);"
         in БЛОК_ПЕТЛИ)
# Объявление раньше использования — форма, которая однажды положила тик.
проверка("объявление brctlmapsz раньше чтения",
         БЛОК_ПЕТЛИ.index("var brctlmapsz") < БЛОК_ПЕТЛИ.index("hctl, 'mapsize'"))
проверка("в блоке петли нет кириллицы",
         not any(ord(c) > 127 for c in БЛОК_ПЕТЛИ))

# 2. Состояние отдаёт размер карты.
проверка("состояние пишет map_w",
         "ParserSetIntValueByKeyByHandle(hsp, 'map_w', GetMapWidth);" in БЛОК_СОСТ)
проверка("состояние пишет map_h",
         "ParserSetIntValueByKeyByHandle(hsp, 'map_h', GetMapHeight);" in БЛОК_СОСТ)
# И ГЛАВНОЕ — ВНЕ ГЕЙТА РАТУШИ. Первая живая проверка 27.09 три минуты не видела
# поля просто потому, что ратуша ещё не встала: я поставил его рядом с сетками, а
# их секция закрыта `if (hscen > 0)`. Размер карты к ратуше отношения не имеет.
# Делим по КОДУ, а не по любому вхождению строки: мой же пояснительный
# комментарий выше содержит «if (hscen > 0)» в кавычках, и первая версия этой
# проверки поймала собственный комментарий вместо гейта.
_до_гейта = БЛОК_СОСТ.split("if (hscen > 0) then")[0]
проверка("map_w написан ДО гейта ратуши, а не внутри него",
         "'map_w'" in _до_гейта, "поле снова внутри секции сеток")
проверка("размер карты идёт в снимок",
         '"map_w", "map_h",' in ПОЛИТИКА)

# 3. Клетка считается по факту.
проверка("карта 256 даёт клетку 16", M.клетка_единиц({"map_w": 256}) == 16)
проверка("карта 320 даёт клетку 20", M.клетка_единиц({"map_w": 320}) == 20)
проверка("карта 640 даёт клетку 40", M.клетка_единиц({"map_w": 640}) == 40)
проверка("без поля берём 20 — карту контейнеров, а не старую константу 16",
         M.клетка_единиц({}) == 20)
проверка("мусор в поле не ломает счёт", M.клетка_единиц({"map_w": "нет"}) == 20)

# 4. Мост: ключ есть, и рынок с веком больше не вложены в capture.
проверка("control знает mapsize", "mapsize: int = -1" in МОСТ)
проверка("mapsize уезжает в файл команды",
         'поля["mapsize"] = int(mapsize)' in МОСТ)
_после = МОСТ.split('поля["capture"] = int(capture)')[1][:400]
проверка("рынок и век вынесены из-под capture",
         '\n        if int(market) >= 0:' in _после
         and '\n        if int(century18) >= 0:' in _после, _после[:200])

# 5. Контейнер: маленькая карта по умолчанию, но с обратной дорогой.
проверка("entrypoint ставит маленькую карту по умолчанию",
         ': "${COSS3_MATCH_MAPSIZE:=3}"' in ВХОД)
проверка("и передаёт её команде NEW",
         "--mapsize ${COSS3_MATCH_MAPSIZE}" in ВХОД)
проверка("вернуть старую карту можно одним ключом окружения",
         "COSS3_MATCH_MAPSIZE=0" in ВХОД)
проверка("опыты с дебютом тоже шлют размер",
         'mapsize=n("COSS3_MATCH_MAPSIZE")' in ОТКРЫТИЕ)

print()
if беды:
    print(f"БЕД: {len(беды)} — {', '.join(беды)}")
    raise SystemExit(1)
print("всё чисто")
