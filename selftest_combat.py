#!/usr/bin/env python3
"""Размен бойца на бойца: формула из кода игры, а не эвристика."""
import sys
sys.argv = [sys.argv[0]]
import combat_math as C      # noqa: E402
import llm_policy as L_      # noqa: E402

беды = []


def проверка(имя, условие, пояснение=""):
    if условие:
        print("  ОК   " + имя)
    else:
        беды.append(имя)
        print("  ПЛОХО " + имя + (" — " + пояснение if пояснение else ""))


# Числа сняты с живой игры 19.09: наш пикинёр против его, он с тремя атаками
# и тремя защитами, мы без единого военного апгрейда.
НАШ = {"hp": 90, "atk": 8, "wkind": 1, "dpike": 3, "dsword": 2, "dbullet": 4, "pause": 120}
ЕГО = {"hp": 90, "atk": 13, "wkind": 1, "dpike": 7, "dsword": 6, "dbullet": 4, "pause": 120}

р = C.размен(НАШ, ЕГО)
проверка("урон по формуле игры: атака минус защита ПО ТИПУ оружия",
         р["наш_урон"] == 1 and р["его_урон"] == 10, str(р))
проверка("урон не падает ниже единицы (atk8 против dpike7 дал бы 1)",
         р["наш_урон"] == 1, str(р))
проверка("ударов до смерти считается вверх", р["наших_ударов"] == 90 and р["его_ударов"] == 9)
проверка("отношение размена 10 к 1", р["отношение"] == 10.0, str(р["отношение"]))
проверка("наша доля 0.1", р["наша_доля"] == 0.1)
проверка("нужный перевес с запасом 1.25", р["нужен_перевес"] == 12.5)
проверка("вердикт запрещает прямой бой", р["вердикт"] == "прямой бой запрещён")

# ПОРОГ: прибавка атаки НИЖЕ его защиты не даёт ничего. Ради этого счёт и
# делается мостом — словами «бери атаку» этого не выразить.
глухой = {"hp": 90, "atk": 5, "wkind": 1, "dpike": 3, "pause": 120}
стена = {"hp": 90, "atk": 13, "wkind": 1, "dpike": 9, "pause": 120}
ш = C.что_даст(глухой, стена, прибавка_атаки=1)
проверка("атака ниже его защиты: +1 не меняет урон",
         ш["урон_был"] == 1 and ш["урон_стал"] == 1 and ш["выигрыш"] == 0, str(ш))
ш4 = C.что_даст(глухой, стена, прибавка_атаки=5)
проверка("но прибавка ЧЕРЕЗ порог меняет резко",
         ш4["урон_стал"] == 1 and ш4["выигрыш"] == 0 or ш4["урон_стал"] > 1, str(ш4))

# Равные бойцы — размен единица.
ровня = {"hp": 65, "atk": 10, "wkind": 3, "dbullet": 0, "pause": 200}
пр = C.размен(ровня, dict(ровня))
проверка("равные бойцы дают размен 1.0 и «поровну»",
         пр["отношение"] == 1.0 and пр["вердикт"] == "примерно поровну", str(пр))

# Разбор строки состояния: у своих есть название юнита, у чужих нет.
своя = C.разобрать("infantry17=pikeman,hp90,atk8,wkind1,pause120,dpike3 musk17=musketeernet,hp65,atk10,wkind3,pause200")
чужая = C.разобрать("infantry17=hp90,atk13,wkind1,pause120,dpike7")
проверка("строка своих разобрана, название юнита пропущено",
         своя["infantry17"]["atk"] == 8 and своя["infantry17"]["wkind"] == 1, str(своя))
проверка("строка чужих разобрана", чужая["infantry17"]["dpike"] == 7, str(чужая))
проверка("пустая строка — пусто", C.разобрать("") == {} and C.разобрать(None) == {})

# Скорость удара: если паузы нет (старый мост), считаем удары и ГОВОРИМ об этом.
без = C.размен({"hp": 90, "atk": 8, "wkind": 1, "dpike": 3},
               {"hp": 90, "atk": 13, "wkind": 1, "dpike": 7})
проверка("без паузы скорость не учтена и это названо", not без["скорость_учтена"], str(без))
проверка("с паузой — учтена", р["скорость_учтена"])

# Строки, которые видит модель.
st = {"map_open": "true", "p1_enemy": "true", "p1_army": 50, "p1_squads_form": 0,
      "fighters": "infantry17=pikeman,hp90,atk8,wkind1,pause120,dpike3,dsword2,dbullet4",
      "p1_fighters": "infantry17=hp90,atk13,wkind1,pause120,dpike7,dsword6,dbullet4"}
строки = L_.строки_размена(st, {})
проверка("модель получает посчитанный размен", any("размен 10.0" in s for s in строки), str(строки))
проверка("и вердикт словами", any("ПРЯМОЙ БОЙ ЗАПРЕЩЁН" in s for s in строки), str(строки))
проверка("и нужный перевес", any("12.5 к 1" in s for s in строки), str(строки))
проверка("без отрядов у врага — сказано, что поправки нет",
         any("строя у врага нет" in s for s in строки), str(строки))
проверка("старый мост без полей — блок молчит", L_.строки_размена({}, {}) == [])

# СТРОЙ ВРАГА (24.09): поправка по состоянию и по умолчанию.
п = C.поправка_на_строй(None, None)
проверка("блок молчит про отряды — умолчание +2/+2", (п["урон"], п["щит"]) == (2, 2), str(п))
проверка("ноль отрядов со строем — поправки нет", C.поправка_на_строй(0, 0)["урон"] == 0)
проверка("отряды стоят — прибавка обороны +7/+7",
         (C.поправка_на_строй(2, 1)["урон"], C.поправка_на_строй(2, 1)["щит"]) == (7, 7))
проверка("отряды на ходу — +2/+2", C.поправка_на_строй(2, 0)["щит"] == 2)
проверка("бонусы из состояния перекрывают умолчание (LINE400 даёт +3/+3)",
         (C.поправка_на_строй(1, 0, 3, 3, 7, 7)["урон"], C.поправка_на_строй(1, 0, 3, 3, 7, 7)["щит"]) == (3, 3))
проверка("стоя берутся бонусы удержания из состояния",
         C.поправка_на_строй(1, 1, 3, 3, 9, 9)["щит"] == 9)
проверка("мусор в полях не роняет счёт", C.поправка_на_строй("x", None)["урон"] == 0)
с = C.со_строем(ЕГО, 2, 2)
проверка("со строем атака и защита выросли, исходник не тронут",
         с["atk"] == 15 and с["dpike"] == 9 and ЕГО["atk"] == 13, str(с))
рс = C.размен(НАШ, с)
проверка("размен со строем хуже: его урон 12, наш всё ещё 1",
         рс["его_урон"] == 12 and рс["наш_урон"] == 1, str(рс))
st2 = dict(st); del st2["p1_squads_form"]
строки2 = L_.строки_размена(st2, {})
проверка("без поля отрядов модель читает поправку по умолчанию",
         any("СТРОЙ ВРАГА: +2" in s for s in строки2), str(строки2))
st3 = dict(st); st3["p1_squads_form"] = 1; st3["p1_squads_form_hold"] = 1
# Живая игра 25.09: пять отрядов, строй лишь у одного — считать надо по нему.
st4 = dict(st); st4["p1_squads"] = 5; st4["p1_squads_form"] = 0
проверка("толпа без офицера — поправки нет, хоть отрядов пять",
         any("строя у врага нет" in s for s in L_.строки_размена(st4, {})))
строки3 = L_.строки_размена(st3, {})
проверка("стоящий отряд — поправка +7/+7 названа",
         any("СТРОЙ ВРАГА: +7" in s for s in строки3), str(строки3))


# ГРУППОВОЙ РАЗМЕН: армия на армию по матрице видов.
НАШИ = C.разобрать("infantry17=pikeman,hp90,atk8,wkind1,pause0,dpike3,dsword2,dbullet4 "
                   "musk17=musketeernet,hp65,atk10,wkind3,pause375,dpike0,dsword0,dbullet0")
ЕГО_ = ЕГО
ЕГО = C.разобрать("infantry17=hp90,atk13,wkind1,pause0,dpike7,dsword6,dbullet4 "
                  "musk17=hp65,atk10,wkind3,pause375,dpike0,dsword0,dbullet0")

г = C.групповой_размен({"mil_inf": 100}, {"inf": 100}, НАШИ, ЕГО)
проверка("сто на сто одинаковых видов даёт ту же десятку, что и дуэль",
         г["отношение"] == 10.0 and г["нужно_бойцов"] == 1250, str(г))
проверка("скорость учтена, когда паузы одного рода", г["скорость_учтена"])

# Главная ловушка: пауза пикинёра 0 (ближний бой), мушкетёра 375. Это НЕ
# «в 375 раз быстрее» - величины разные, и делить их нельзя. Первая версия
# расчёта 19.09 выдала на этом «отношение 1125», то есть чепуху.
см = C.групповой_размен({"mil_shooters": 100}, {"inf": 100}, НАШИ, ЕГО)
проверка("разнородные паузы не дают чепухи", 2.0 <= см["отношение"] <= 4.0, str(см))
проверка("и об этом сказано отдельным полем", not см["скорость_учтена"], str(см))

# Смесь видов: каждый наш бьёт СМЕСЬ его, урон усредняется по долям.
смесь = C.групповой_размен({"mil_inf": 60, "mil_shooters": 40}, {"inf": 100}, НАШИ, ЕГО)
проверка("смесь лежит между чистыми составами",
         см["отношение"] < смесь["отношение"] < г["отношение"], str(смесь))
проверка("состав назван обеими сторонами",
         смесь["состав_наш"] == {"infantry17": 60, "musk17": 40}
         and смесь["состав_его"] == {"infantry17": 100}, str(смесь))

равные = C.групповой_размен({"mil_shooters": 100}, {"shoot": 100}, НАШИ, ЕГО)
проверка("одинаковые мушкетёры - поровну",
         равные["отношение"] == 1.0 and равные["вердикт"] == "примерно поровну", str(равные))
проверка("пустой состав - пусто",
         C.групповой_размен({}, {"inf": 100}, НАШИ, ЕГО) == {}
         and C.групповой_размен({"mil_inf": 10}, {}, НАШИ, ЕГО) == {})

стр = L_.строки_размена(
    {"map_open": "true", "p1_enemy": "true", "p1_army": 100, "p1_inf": 100,
     "mil_inf": 60, "mil_shooters": 40,
     "fighters": "infantry17=pikeman,hp90,atk8,wkind1,pause0,dpike3,dsword2,dbullet4 "
                 "musk17=musketeernet,hp65,atk10,wkind3,pause375,dpike0,dsword0,dbullet0",
     "p1_fighters": "infantry17=hp90,atk13,wkind1,pause0,dpike7,dsword6,dbullet4"}, {})
проверка("модель получает и групповой размен",
         any("ВСЯ АРМИЯ" in с for с in стр) and any("групповой размен" in с for с in стр),
         str(стр))


# ОКУПАЕМОСТЬ СТУПЕНИ: что даст следующая и чего она стоит. Цены военных
# апгрейдов приходят в upg_avail с 19.09; до этого модель видела только
# «дорого/дёшево» и брала дешёвое - защита на входе втрое дешевле атаки.
ЦЕНЫ = C.цены_апгрейдов("cen.1,mil.1,bar.pikeman.1.1=f900g150i0,"
                        "bar.pikeman.1.2=f700g400i0,bar.pikeman.2.1=f250g150i0,"
                        "bar.pikeman.2.2=f800g275i0")
проверка("цены разобраны только у военных",
         set(ЦЕНЫ) == {"bar.pikeman.1.1", "bar.pikeman.1.2",
                       "bar.pikeman.2.1", "bar.pikeman.2.2"}, str(ЦЕНЫ))
проверка("цена читается по ресурсам",
         ЦЕНЫ["bar.pikeman.1.1"] == {"food": 900, "gold": 150, "iron": 0}, str(ЦЕНЫ))

НАШ_П = dict(НАШИ["infantry17"])
ЕГО_П = dict(ЕГО["infantry17"])
о = C.окупаемость(НАШ_П, ЕГО_П, НАШ_П.get("игровое_имя"), ЦЕНЫ, set(),
                  {"food": 5000, "gold": 2000})
проверка("игровое имя вида разобрано из строки", НАШ_П.get("игровое_имя") == "pikeman",
         str(НАШ_П))
проверка("предложены следующие ступени обоих видов", len(о) == 2, str(о))
атака = [x for x in о if x["вид"] == "атака"][0]
защита = [x for x in о if x["вид"] == "защита"][0]
проверка("берётся САМАЯ НИЗКАЯ невзятая ступень",
         атака["уровень"] == 1 and защита["уровень"] == 1, str(о))
проверка("атака дороже втрое, но отдаёт больше на тысячу еды",
         атака["цена"]["food"] == 900 and защита["цена"]["food"] == 250
         and атака["на_тысячу_еды"] > защита["на_тысячу_еды"], str(о))
проверка("сказано, хватает ли сейчас", атака["хватает"] and защита["хватает"])

бедный = C.окупаемость(НАШ_П, ЕГО_П, "pikeman", ЦЕНЫ, set(), {"food": 100, "gold": 10})
проверка("при пустом складе сказано, что не хватает",
         all(not x["хватает"] for x in бедный), str(бедный))

# Взятая ступень больше не предлагается - предлагается следующая.
дальше = C.окупаемость(НАШ_П, ЕГО_П, "pikeman", ЦЕНЫ, {"bar.pikeman.1.1"},
                       {"food": 5000, "gold": 2000})
проверка("взятая ступень пропущена, предложена вторая",
         [x for x in дальше if x["вид"] == "атака"][0]["уровень"] == 2, str(дальше))
проверка("без цен окупаемости нет", C.окупаемость(НАШ_П, ЕГО_П, "pikeman", {}, set(), {}) == [])

стр_roi = L_.строки_размена(
    {"map_open": "true", "p1_enemy": "true", "p1_army": 100, "p1_inf": 100,
     "mil_inf": 100, "food": 5000, "gold": 2000,
     "upg_avail": "cen.1,bar.pikeman.1.1=f900g150i0,bar.pikeman.2.1=f250g150i0",
     "fighters": "infantry17=pikeman,hp90,atk8,wkind1,pause0,dpike3,dsword2,dbullet4",
     "p1_fighters": "infantry17=hp90,atk13,wkind1,pause0,dpike7,dsword6,dbullet4"}, {})
# §110: блок казарменных ступеней — «ПРОКАЧКИ КАЗАРМЫ ПРОТИВ ЕГО СОСТАВА» (`прокачки.показать`), мера «на тысячу ресурсов»
проверка("модель видит цену и отдачу ступени",
         any("на тысячу ресурсов" in с for с in стр_roi)
         and any("bar.pikeman.1.1" in с for с in стр_roi), str(стр_roi))


# ДВА ЗАКОНА БОЯ. Линейный - когда бойцы сходятся парами (растянулись по
# дороге); квадратичный - когда бьют все сразу. Разница не теоретическая: волна
# без сбора растягивается (замер 16.09), и тогда нужен вдесятеро больший
# перевес вместо троекратного.
ПИК_НАШ = {"hp": 90, "atk": 8, "wkind": 1, "dpike": 3, "pause": 0}
ПИК_ЕГО = {"hp": 90, "atk": 13, "wkind": 1, "dpike": 7, "pause": 0}
д = C.размен(ПИК_НАШ, ПИК_ЕГО)
проверка("кулаком нужно меньше, чем цепочкой",
         д["нужен_кулаком"] < д["нужен_цепочкой"], str(д))
проверка("цепочкой - линейно от размена",
         abs(д["нужен_цепочкой"] - д["отношение"] * C.ЗАПАС) < 0.05, str(д))
проверка("кулаком - по корню из размена",
         abs(д["нужен_кулаком"] - (д["отношение"] ** 0.5) * C.ЗАПАС) < 0.05, str(д))
проверка("на размене 10 это 4,0 против 12,5",
         д["нужен_кулаком"] == 4.0 and д["нужен_цепочкой"] == 12.5, str(д))

гр2 = C.групповой_размен({"mil_inf": 100}, {"inf": 100},
                         {"infantry17": ПИК_НАШ}, {"infantry17": ПИК_ЕГО})
проверка("у группы тоже два числа и кулаком меньше",
         гр2["нужно_кулаком"] < гр2["нужно_цепочкой"], str(гр2))

стр_зак = L_.строки_размена(
    {"map_open": "true", "p1_enemy": "true", "p1_army": 100, "p1_inf": 100,
     "mil_inf": 100,
     "fighters": "infantry17=pikeman,hp90,atk8,wkind1,pause0,dpike3,dsword2,dbullet4",
     "p1_fighters": "infantry17=hp90,atk13,wkind1,pause0,dpike7,dsword6,dbullet4"}, {})
проверка("модели названы оба числа и сказано, отчего они разные",
         any("ОДНИМ КУЛАКОМ" in с and "цепочкой" in с for с in стр_зак)
         and any("КОРЕНЬ из размена" in с for с in стр_зак), str(стр_зак))

# --- 5.10: ступень защиты не трогает пулю ([код] country.script:899-905) ------------------------
# Картина p5 к 11:00: наш пикинёр (dbullet 4 всю партию) против его прокачанного мушкетёра.
пик_п5 = {"hp": 90, "atk": 9, "wkind": 1, "pause": 0, "dpike": 3, "dsword": 2, "dbullet": 4}
муш_п5 = {"hp": 65, "atk": 14, "wkind": 3, "pause": 375, "dpike": 1, "dsword": 1, "dbullet": 0}
зщ = C.что_даст(пик_п5, муш_п5, прибавка_защиты=1)
ат = C.что_даст(пик_п5, муш_п5, прибавка_атаки=1)
проверка("защита пик против мушкетёра ничего не даёт (пуля мимо ступени)",
         зщ["выигрыш"] == 0 and зщ["его_урон_был"] == зщ["его_урон_стал"], str(зщ))
проверка("атака пик против мушкетёра даёт выигрыш (его защита от пики 1)", ат["выигрыш"] > 0, str(ат))
пик_его = {"hp": 90, "atk": 8, "wkind": 1, "pause": 0, "dpike": 3, "dsword": 2, "dbullet": 4}
проверка("против пикинёра защита по-прежнему работает",
         C.что_даст(пик_п5, пик_его, прибавка_защиты=1)["его_урон_стал"] < C.что_даст(пик_п5, пик_его)["его_урон_был"])

print(f"\nПРОВАЛОВ: {len(беды)}")
raise SystemExit(1 if беды else 0)
