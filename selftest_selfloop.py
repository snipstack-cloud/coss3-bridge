#!/usr/bin/env python3
"""Самопроверка цикла самодоработки — БЕЗ игры, БЕЗ модели, без денег.

    python selftest_selfloop.py <каталог с трассами base21>

Проверяется не «работает ли код», а то, ЛОВИТ ЛИ ЦИКЛ ЛОЖНЫЙ НОЛЬ. Каждый
случай ниже — это реальная ошибка проекта, повторённая нарочно:

  * мера про поле, которого в снимке нет (20.09, `upg_avail`);
  * мера, дающая одно и то же число на всех партиях базы (20.09, `STAGE`
    искали в `cmds`, куда он не пишется, — ноль во всех партиях);
  * правило, которое не срабатывает ни разу;
  * правило, которое падает;
  * разница между плечами МЕНЬШЕ разброса внутри базы (20.09, base22/switch4:
    пик армии 225 и 97 против 132 и 115 — и это был не эффект).

Проверка идёт по НАСТОЯЩИМ трассам, а не по выдуманным: выдуманная трасса не
поймала бы ни одного из этих случаев — они все про то, что в настоящих данных
лежит не то, что ожидалось.
"""
from __future__ import annotations

import os
import sys

import selfloop as L
import selfrules as S

ПРОВАЛЫ = []


def проверить(что: str, условие: bool, подробно: str = "") -> None:
    print(("  ок   " if условие else "  ПЛОХО") + f" {что}"
          + (f" — {подробно}" if подробно else ""))
    if not условие:
        ПРОВАЛЫ.append(что)


def мера_из(код: str, имя: str = "м", больше_лучше: bool = True) -> S.Мера:
    м = S.Мера(имя=имя, зачем="проба", код=код, больше_лучше=больше_лучше)
    try:
        м.функция = S.скомпилировать(код, "мера")
    except Exception:
        м.функция = None
    return м


def правило_из(код: str, имя: str = "п") -> S.Правило:
    п = S.Правило(имя=имя, зачем="проба", код=код)
    try:
        п.функция = S.скомпилировать(код, "правило")
    except Exception as e:
        п.выключено = True
        п.последний_сбой = str(e)
    return п


def main() -> int:
    каталог = sys.argv[1] if len(sys.argv) > 1 else ""
    if not каталог or not os.path.isdir(каталог):
        print(__doc__)
        print("нужен каталог с трассами: python selftest_selfloop.py <каталог>")
        return 2

    партии = L.партии_из(каталог)
    состояния = L.состояния_из(партии)
    print(f"\nтрассы: {len(партии)} партий, {len(состояния)} тактов состояния")
    проверить("трассы прочитаны", len(партии) >= 2 and len(состояния) > 50,
              f"{len(партии)} партий, {len(состояния)} тактов")

    # Итоги должны быть РАЗНЫМИ и НЕНУЛЕВЫМИ. Ноль во всех партиях означал бы,
    # что имя поля не то, — так и случилось при первой сборке цикла.
    армии = [п["итог"]["армия"] for п in партии]
    print(f"армия к концу по партиям: {армии}")
    проверить("армия не ноль во всех партиях", any(x > 0 for x in армии),
              "иначе имя поля в итог_партии не то")
    проверить("армия различается между партиями", len(set(армии)) > 1)

    print("\n--- меры ---")
    годная = мера_из("def мера(трасса, итог):\n    return итог['армия']\n", "армия")
    d = S.достижима(годная, партии)
    проверить("нормальная мера признана годной", d["годна"], str(d.get("значения")))

    нет_поля = мера_из(
        "def мера(трасса, итог):\n"
        "    return sum(чис(т.get('state') or {}, 'upg_avail') for т in трасса)\n",
        "нет_поля")
    d = S.достижима(нет_поля, партии)
    проверить("мера про несуществующее поле ОТВЕРГНУТА",
              not d["годна"] and d["вердикт"] == "не различает",
              f"{d['вердикт']}, значения {d.get('значения')}")

    константа = мера_из("def мера(трасса, итог):\n    return 7\n", "константа")
    d = S.достижима(константа, партии)
    проверить("постоянная мера ОТВЕРГНУТА",
              not d["годна"] and d["вердикт"] == "не различает", d["вердикт"])

    падучая = мера_из("def мера(трасса, итог):\n    return 1 / 0\n", "падучая")
    d = S.достижима(падучая, партии)
    проверить("падающая мера ОТВЕРГНУТА",
              not d["годна"] and d["вердикт"] == "падает", d["вердикт"])

    # Настоящая ловушка 20.09: STAGE ищут в cmds, куда он не пишется вовсе.
    stage_в_cmds = мера_из(
        "def мера(трасса, итог):\n"
        "    return sum(1 for т in трасса\n"
        "               for c in (т.get('cmds') or [])\n"
        "               if c.get('cmd') == 'STAGE')\n", "stage_в_cmds")
    d = S.достижима(stage_в_cmds, партии)
    проверить("ЛОВУШКА 20.09 (STAGE в cmds) ОТВЕРГНУТА до партий",
              not d["годна"],
              f"{d['вердикт']}, значения {d.get('значения')}")

    print("\n--- правила ---")
    срабатывает = правило_из(
        "def правило(st, cmds, ctx):\n"
        "    if чис(st, 'food') < 500:\n"
        "        return cmds + [balance('food', 5)], ['мало еды']\n"
        "    return cmds, []\n", "срабатывает")
    r = S.проверить_правило(срабатывает, состояния)
    проверить("рабочее правило признано годным", r["годно"],
              f"{r['срабатываний']} из {r['тактов']}")

    молчун = правило_из(
        "def правило(st, cmds, ctx):\n"
        "    if чис(st, 'food') < -1:\n"
        "        return cmds + [seed()], ['никогда']\n"
        "    return cmds, []\n", "молчун")
    r = S.проверить_правило(молчун, состояния)
    проверить("правило, не срабатывающее НИ РАЗУ, отвергнуто",
              not r["годно"] and r["почему"] == "не срабатывает ни разу",
              r["почему"])

    падучее = правило_из(
        "def правило(st, cmds, ctx):\n"
        "    return st['такого_ключа_нет'], []\n", "падучее")
    r = S.проверить_правило(падучее, состояния)
    проверить("падающее правило отвергнуто",
              not r["годно"] and r["сбоев"] > 0, r["почему"])

    # Правило не имеет права вернуть что попало: мост не должен упасть в такте.
    дурное = правило_из(
        "def правило(st, cmds, ctx):\n"
        "    return 'не список', ['ага']\n", "дурное")
    cmds, слова = S.применить([дурное], состояния[0], [], {})
    проверить("мусор от правила не уходит в игру",
              cmds == [] and слова == [] and дурное.сбоев == 1,
              f"сбоев {дурное.сбоев}")

    # Пять сбоев — и правило само выключается, но факт остаётся в отчёте.
    for _ in range(5):
        S.применить([дурное], состояния[0], [], {})
    проверить("правило выключается после пяти сбоев", дурное.выключено,
              f"сбоев {дурное.сбоев}")
    отч = S.отчёт_правил([дурное])
    проверить("выключенное правило видно в отчёте",
              отч and отч[0]["выключено"] and отч[0]["сбоев"] >= 5)

    print("\n--- суд ---")
    # Разница меньше разброса внутри базы — это разброс, и никак иначе.
    с = L.сравнить("проба", [132.0, 115.0], [225.0, 97.0], True)
    проверить("разница внутри разброса названа разбросом",
              с["вердикт"] == "это разброс",
              f"разница {с['разница']}, разброс базы {с['разброс_базы']}")
    с = L.сравнить("проба", [100.0, 101.0], [400.0, 402.0], True)
    проверить("настоящий сдвиг назван сдвигом",
              с["вердикт"] == "лучше базы" and с["хватает_ли"], с["вердикт"])
    с = L.сравнить("проба", [100.0, 101.0], [10.0, 11.0], True)
    проверить("падение названо ухудшением", с["вердикт"] == "хуже базы")
    с = L.сравнить("потери", [100.0, 101.0], [10.0, 11.0], False)
    проверить("мера «меньше — лучше» считается наоборот",
              с["вердикт"] == "лучше базы", с["вердикт"])

    print("\n--- поля для запроса ---")
    поля = L.поля_снимка(состояния)
    имена = {с.split(" = ")[0] for с in поля}
    проверить("в запрос уходят НАСТОЯЩИЕ имена полей",
              {"food", "peasants", "mil_inf"} <= имена,
              f"{len(поля)} полей")
    проверить("выдуманного поля в списке нет", "my_army" not in имена)

    print()
    if ПРОВАЛЫ:
        print(f"ПРОВАЛОВ: {len(ПРОВАЛЫ)}")
        for x in ПРОВАЛЫ:
            print(f"  * {x}")
        return 1
    print("всё сошлось")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
