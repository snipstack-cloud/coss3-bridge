#!/usr/bin/env python3
"""§170н (25.10, вопрос игрока «как оборонятся, если противник выберет Польшу»): его войска в наших пиках, стрелки против брони 0,
его конюшня. Живого кейса с Польшей нет — берутся такты Д15 (`партия_д15_25_10_5-30_7-30`) с подставленными статами польских
бойцов в `p1_fighters` (из `unit.script`: пика 90 hp/8/брони 0, мушкетёр 70/9/пауза 100, крылатый гусар 225/14/броня 1/2/5).

(а) веса: net против net — 1,0 по всем; против Польши пика ≈ 0,62, стрелок ≈ 1,16, крылатый гусар против драгуна ≈ 1,43; строка `§170н качество врага`
    есть только против Польши; (б) стрелки: при доле стрелков 0,15 (34 пики, 6 стрелков) с ключом против Польши — TRAIN musk17,
    без ключа или против net — нет; (в) конюшня: p1_stable 1 — `стрелки_позади` 1, шахта золота в 59 от ратуши не закладывается
    (`§170н его конюшня`), ключ 0 — BUILD minegold есть; p1_stable 0 — ключи вернулись к исходным.

    python3 selftest_польша.py
"""
import copy, json, os, sys, tempfile
К = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, К); sys.path.insert(0, os.path.join(К, "sim"))
os.environ.pop("COSS3_WAVE_CONTRACT", None)
import strategy_live as SL
import анализ_врага as АВ

д15 = [json.loads(l) for l in open(os.path.join(К, "sim/кейсы/партия_д15_25_10_5-30_7-30.jsonl"), encoding="utf-8")]
ПОЛЬША = ("infantry17=hp90,atk8,wkind1,pause0,rmax207,dmgs0,dmgp0,dinit8,dpike0,dsword0,dbullet0 "
          "musk17=hp70,atk9,wkind3,pause312,rmax1312,dmgs0,dmgp0,dinit9,dpike0,dsword0,dbullet0 "
          "dragoon17=hp225,atk14,wkind1,pause0,rmax188,dmgs0,dmgp0,dinit14,dpike1,dsword2,dbullet5")
ошибок = 0
def проверить(усл, что):
    global ошибок
    print(("ОК   " if усл else "ОШИБКА ") + что); ошибок += not усл
def стратегия(доп):
    д = json.load(open(os.path.join(К, "sim/поиск/шт_s2_оборона_ручеёк_эко_так15_нужда.json"), encoding="utf-8"))
    д["итог"].update({"бюджет_с_академией": 0, "качество_врага": 0, "стрелки_против_брони": 0, "конюшня_его": 0})
    д["итог"].update(доп)
    with tempfile.NamedTemporaryFile("w", suffix=".json", delete=False, encoding="utf-8") as f:
        json.dump(д, f, ensure_ascii=False)
    return SL.ЖиваяСтратегия(f.name)
def при(t): return next(s for s in д15 if float(s["gametime"]) >= t)
def ответ(С, s):
    АВ._ТЕКУЩИЙ.update({"а": None, "t": None, "ответ": None}); return С.ответ(copy.deepcopy(s))
def команды(о, cmd, что=""): return [c for c in о["commands"] if c["cmd"] == cmd and что in str(c.get("role") or "")]
def метки(о, что): return [x for x in о["why"].split(", ") if что in x][:3]
def польский(s, **patch):
    s = copy.deepcopy(s); s["p1_fighters"] = ПОЛЬША; s.update(patch); return s

# (а) веса
s = при(360)
в_net = SL._веса_качества(s); в_pol = SL._веса_качества(польский(s))
проверить(в_net and all(abs(в_net[k] - 1.0) < 0.01 for k in ("пик", "стрелков", "конных")), f"(а) net против net: {в_net}")
проверить(в_pol and 0.6 < в_pol["пик"] < 0.66 and 1.3 < в_pol["конных"] < 1.6 and 1.0 < в_pol["стрелков"] < 1.3,
          f"(а′) против Польши: пика {в_pol['пик']:.2f}, стрелок {в_pol['стрелков']:.2f}, конный {в_pol['конных']:.2f}, наша пуля по его пике {в_pol['наша_пуля_по_его_пике']:.0f}, его по нашей {в_pol['его_пуля_по_нашей_пике']:.0f}")
о = ответ(стратегия({"качество_врага": 1}), польский(s))
проверить("§170н качество врага: его 42 голов = 26 наших" in о["why"], f"(а″) {метки(о, '§170н')}")
о = ответ(стратегия({"качество_врага": 1}), s)
проверить("§170н" not in о["why"], f"(а‴) net против net — строки §170н нет")
# (б) стрелки против брони 0
s6 = dict(при(360), mil_inf=34, mil_shooters=6)
о1 = ответ(стратегия({"стрелки_против_брони": 1}), польский(s6))
о0 = ответ(стратегия({}), польский(s6))
оn = ответ(стратегия({"стрелки_против_брони": 1}), s6)
проверить(команды(о1, "TRAIN", "musk") and "§170н стрелки против брони 0" in о1["why"], f"(б) против Польши: {команды(о1, 'TRAIN')}; {метки(о1, '§170н стрелки')}")
проверить(not команды(о0, "TRAIN", "musk"), f"(б′) ключ 0: {команды(о0, 'TRAIN')}")
проверить(not команды(оn, "TRAIN", "musk") and "§170н стрелки" not in оn["why"], f"(б″) против net (броня 4): {команды(оn, 'TRAIN')}")
# (в) его конюшня
s4 = при(344)
С = стратегия({"конюшня_его": 1})
о1 = ответ(С, dict(s4, p1_stable=1))
проверить("§170н его конюшня" in о1["why"] and not any(c.get("role") == "minegold" for c in команды(о1, "BUILD")) and С.п.get("стрелки_позади") == 1,
          f"(в) конюшня стоит, золото в {s4['ore_gold_dist']}: BUILD {[c.get('role') for c in команды(о1, 'BUILD')]}, стрелки_позади {С.п.get('стрелки_позади')}, отряд_с {С.п.get('отряд_с')}; {метки(о1, '§170н его')}")
о0 = ответ(стратегия({}), dict(s4, p1_stable=1))
проверить(any(c.get("role") == "minegold" for c in команды(о0, "BUILD")), f"(в′) ключ 0: BUILD {[c.get('role') for c in команды(о0, 'BUILD')]}")
о2 = ответ(С, dict(s4, p1_stable=0))
проверить("§170н его конюшня" not in о2["why"] and С.п.get("стрелки_позади") == С._п_исход.get("стрелки_позади"), f"(в″) конюшни нет — ключи вернулись: стрелки_позади {С.п.get('стрелки_позади')}")
print(f"\nошибок: {ошибок}")
