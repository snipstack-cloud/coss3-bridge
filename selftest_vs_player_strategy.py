# -*- coding: utf-8 -*-
"""ВОРОТА МОДЕЛИ ПРИ КЛЮЧЕ СТРАТЕГИИ (3.10): партия §50 не должна требовать счёт.

Зачем. 2.10 проверка 3 не запускалась не из-за моста и не из-за игры: контроль
`против_игрока.py` требовал готовую модель с остатком счёта, а при ключе
`--strategy` модель не зовут ни разу (`llm_policy.py:9122`). Здесь проверяется
ровно это: ключ со стороны настройки находится, и контроль идёт без модели.

    python selftest_vs_player_strategy.py
"""
import importlib
import os
import sys

ЗДЕСЬ = os.path.dirname(os.path.abspath(__file__))
if ЗДЕСЬ not in sys.path:
    sys.path.insert(0, ЗДЕСЬ)

вп = importlib.import_module("против_игрока")

беды = []

# 1. Ключ из строки `ключи` файла настройки — оба написания.
случаи = [
    ("--memo --strategy sim/поиск/мушк_s1.json --world world.md",
     "sim/поиск/мушк_s1.json"),
    ("--strategy=sim/поиск/s1.json --memo", "sim/поиск/s1.json"),
    ("--memo --world world.md", ""),
    ("", ""),
    # Ключ последним и БЕЗ значения — брать нечего, и падать тоже нельзя.
    ("--memo --strategy", ""),
]
for строка, ждём in случаи:
    вышло = вп._ключ_стратегии(строка)
    if вышло != ждём:
        беды.append(f"_ключ_стратегии({строка!r}) = {вышло!r}, ждали {ждём!r}")

# 2. Файл, который просит мак для проверки 3, существует — иначе разговор о
#    воротах беспредметен.
if not os.path.exists(os.path.join(ЗДЕСЬ, "sim", "поиск", "мушк_s1.json")):
    беды.append("нет sim/поиск/мушк_s1.json — проверке 3 играть нечем")

# 3. Ворота модели: при стратегии проверка счёта НЕ зовётся. Ловим подменой
#    `модель_жива` на часового — он кричит, если его тронули.
тронули = []
вп.модель_жива = lambda адрес, модель: тронули.append((адрес, модель)) or "мёртво"


def _контроль(стратегия: str) -> list[str]:
    """Прогон main() до конца контроля, без игры и без NEW."""
    вп.контроль = lambda игра, партия, против_ии=False: []
    вп.пульс = lambda игра: "живо"
    арг = ["против_игрока.py", "--только-проверка"]
    if стратегия:
        арг += ["--стратегия", стратегия]
    сохр, sys.argv = sys.argv, арг
    try:
        код = вп.main()
    finally:
        sys.argv = сохр
    return код


код = _контроль("sim/поиск/мушк_s1.json")
if тронули:
    беды.append(f"при стратегии модель всё равно проверялась: {тронули}")
if код != 0:
    беды.append(f"при стратегии контроль не прошёл (код {код}) — а мешать нечему")

код = _контроль("")
if not тронули:
    беды.append("БЕЗ стратегии модель не проверялась — ворота сняты совсем, "
                "а кончившийся счёт в логе выглядит как «модель замолчала» (17.09)")
if код == 0:
    беды.append("без стратегии контроль прошёл при мёртвой модели")

if беды:
    print("ПЛОХО:")
    for б in беды:
        print("  -", б)
    raise SystemExit(1)
print("ХОРОШО: ключ стратегии находится в настройке, ворота модели при нём "
      "сняты, а без него держат")
