#!/usr/bin/env python3
"""Открытая информация (18.09): ресурсы, апгрейды, очереди, движение и
крестьяне противника по клеткам доезжают до запроса, трассы и разбора сеток.

Правило «как человек» снято новыми правилами хакатона; матч против другого
бота по сети. Поля пишет block_hstate.inc с ветки idea/open-info (НЕ проверено
живой игрой); здесь проверяется python.
"""
import sys
sys.argv = [sys.argv[0]]
import llm_policy as L      # noqa: E402
import coss3_map as M       # noqa: E402

беды = []


def проверка(имя, условие, пояснение=""):
    if условие:
        print("  ОК   " + имя)
    else:
        беды.append(имя)
        print("  ПЛОХО " + имя + (" — " + пояснение if пояснение else ""))


def сетка(имя, **клетки):
    строки = [["."] * 16 for _ in range(16)]
    for k, v in клетки.items():
        x, y = (int(t) for t in k.split(","))
        строки[y][x] = M.знак(v)
    return {f"{имя}{y}": "".join(строки[y]) for y in range(16)}


БАЗА = dict(gametime=500, grid_n=16, map_w=256, map_h=256, my_cx=12, my_cy=13,
            map_open=1, peasants=30, mil_inf=20, mil_shooters=10, my_freewar=30,
            p1_enemy="true", p1_peasants=40, p1_army=60, p1_bldgs=12,
            p1_food=1200, p1_wood=900, p1_stone=400, p1_gold=2600, p1_iron=700, p1_coal=300,
            p1_upg_done="milfood140,peaeng", p1_train="pikeman:inf",
            p1_mv_n=25, p1_mv_base=22, p1_mv_cx=11, p1_mv_cy=12)
st = dict(БАЗА, **сетка("frow", **{"3,3": 40, "10,12": 20}), **сетка("prow", **{"3,3": 30, "6,1": 6, "4,3": 4}))

кл = M.крестьяне_врага(st)
проверка("клетки крестьян найдены", len(кл) == 3, str(кл))
проверка("первой идёт клетка без охраны", кл[0]["x"] == 6 and кл[0]["y"] == 1 and кл[0]["бойцов_рядом"] == 0, str(кл[0]))
проверка("соседняя с армией клетка знает охрану", any(c["x"] == 4 and c["бойцов_рядом"] >= 36 for c in кл), str(кл))
проверка("без prow — пусто", M.крестьяне_врага(dict(БАЗА)) == [])

L.ЧЕСТНО = False
стр = L.открытая_информация(st, {})
текст = "\n".join(стр)
проверка("ресурсы противника в запросе", "золото 2600" in текст and "уголь 300" in текст, текст)
проверка("вторая казарма по карману у врага названа", "вторую казарму" in текст)
проверка("апгрейды врага", "milfood140" in текст)
проверка("что куёт", "pikeman:inf" in текст)
проверка("движение и направление", "в движении: 25" in текст and "от твоей ратуши" in текст, текст)
проверка("идут на тебя", "ИДУТ НА ТЕБЯ: 22" in текст)
проверка("клетка без охраны с готовой командой", '"cx":6,"cy":1' in текст, текст)

перехват = dict(st, p1_mv_base=0, p1_mv_cx=12, p1_mv_cy=6, wave_cx=12, wave_cy=7, wave_n=90)
текст3 = "\n".join(L.открытая_информация(перехват, {}))
проверка("наперерез волне названо", "НАПЕРЕРЕЗ" in текст3 and "против 25" in текст3, текст3)
проверка("без волны — не наперерез", "НАПЕРЕРЕЗ" not in "\n".join(L.открытая_информация(dict(перехват, wave_n=0), {})))
проверка("далеко от волны — не наперерез", "НАПЕРЕРЕЗ" not in "\n".join(L.открытая_информация(dict(перехват, wave_cx=3), {})))

тихо = dict(st, p1_mv_n=0, p1_mv_base=0, p1_train="", p1_upg_done="")
текст2 = "\n".join(L.открытая_информация(тихо, {}))
проверка("ноль движения сказан словами", "стоят" in текст2)
проверка("пустая очередь названа", "стоят пустые" in текст2)
проверка("нет апгрейдов — сказано", "ни одного" in текст2)

старое = dict(БАЗА)
for k in list(старое):
    if k.startswith("p1_") and k not in ("p1_enemy", "p1_peasants", "p1_army", "p1_bldgs"):
        del старое[k]
проверка("старый мост без полей — блок молчит", L.открытая_информация(старое, {}) == [])

# Сетка крестьян рисуется рядом с войсками
карта = M.render(st, {})
проверка("сетка крестьян врага в карте", "Enemy peasants" in карта)


# Его бойцы В ЧИСЛАХ (19.09). Имена апгрейдов говорят, ЧТО он взял, но не что
# это дало; свои числа модель видит в карточке бойца, и сравнить своего пикинёра
# с его она не могла. objbase движок держит ПО ИГРОКУ, так что его атака и
# защита читаются той же строкой, что наши, — только индекс другой.
счисл = dict(st, p1_fighters=("infantry17=hp90,atk11,dpike4,dsword3,dbullet2 "
                              "musk17=hp80,atk10,dpike2,dsword2,dbullet3 "))
строки = L.открытая_информация(счисл, {})
бой = [с for с in строки if "в числах" in с]
проверка("его бойцы в числах названы", len(бой) == 1, str(строки))
проверка("атака и защита видны обе", бой and "atk11" in бой[0] and "dpike4" in бой[0],
         str(бой))
# Совет «сравни со своими» убран 19.09: размен теперь считает мост (блок
# «РАЗМЕН ОДИН НА ОДИН»), и вычитать атаку из защиты модели незачем.
проверка("размен посчитан рядом, а не отдан модели в уме",
         any("РАЗМЕН ОДИН НА ОДИН" in с for с in строки)
         or not счисл.get("fighters"), str(строки))
# 'none-found' значит «ролей не нашлось», а не «бойцы с нулевой атакой».
проверка("none-found молчит",
         not [с for с in L.открытая_информация(dict(st, p1_fighters="none-found"), {})
              if "в числах" in с])
проверка("старый мост без поля молчит",
         not [с for с in L.открытая_информация(st, {}) if "в числах" in с])

print(f"\nПРОВАЛОВ: {len(беды)}")
raise SystemExit(1 if беды else 0)
