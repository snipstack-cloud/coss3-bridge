# -*- coding: utf-8 -*-
"""ОЦЕНЩИК СТУПЕНЕЙ КАЗАРМЫ — один для промпта, `--auto-upgrade` и стратегии симулятора (6.10, §110).

Зачем. Промпт и автопокупка считали ступень «род против того же рода» (наш пикинёр против его пикинёра),
стратегия — по расписанию. В p5 к 11:03 у игрока 52 стрелка из 84, а защита пик считалась против 32 его пик.
Здесь одна реализация; промпт (`показать`) и автопокупка (`выбрать`) берут ОДНУ оценку одного снимка и
различаются только тем, кто решает.

Порядок (по разбору игрока 6.10):
  1. МАТРИЦА: каждая следующая ступень × каждый его род — урон за удар, ударов до убийства, его урон по нам,
     сколько его ударов переживает наш боец, до/после. Числа — `combat_math` (формула урона игры), прибавки
     ступеней — `combat_math.ПРИБАВКИ_СТУПЕНЕЙ` [код] (защита — пика, сабля, стрела; НЕ пуля).
  2. ТРИ СОСТАВА: вся его армия (фон), его бойцы у нашей группировки (≤ `РАДИУС_БОЯ` клеток), подходящие к ней
     (`угрозы.py`: идут, куда, через сколько). Бой = рядом + подходящие.
  3. ВЕС ПО УРОНУ, а не по головам: для защиты вес его рода = его бойцов × урон за удар по нашему роду × ТЕМП —
     закон боя симулятора (§6, `sim/combat.py`, ворота 27.09): ближний бьёт весь контакт, стрелок в клетке
     контакта стреляет лишь `ДОЛЯ_ТАКТОВ_ОГНЯ` тактов плюс залпы форы до контакта (`combat_math.залпы_форы`).
     Для атаки — доля его бойцов этого рода (кого наш род бьёт).
  4. ВРЕМЯ: исследование `combat_math.ИССЛЕДОВАНИЕ_С` (15,6 с [код]). Если бой уже идёт или его группа подойдёт
     раньше — ступень выгоды ЭТОГО боя не получает, только фон. Стоят рядом без контакта — успеет, если контакт
     не раньше чем через 16 с, и это сказано.
  5. ЦЕНА: в БОЙЦАХ НАЙМА — сколько пикинёров купила бы та же еда или то же железо (`combat_math.ЦЕНА_ПИКИНЁРА`,
     по более узкому); парные прогоны развилки p5 11:03 (§110): ступень мушкетёра за 2000 еды (80 пикинёров) при
     оценке 1,4 стоила 50 бойцов армии к 15:00, защита пик за 250 еды (10) при оценке 8 — около нуля или плюс.
     Цена в бойцах ПОКАЗЫВАЕТСЯ, но покупку по умолчанию НЕ режет (`ДОЛЯ_ЦЕНЫ` 0): оценка — снимок ближайшего
     боя, а ступень живёт до конца партии и на всех будущих нанятых. Проверено отложенными противниками §110
     (`sim/проверка_пары`): ворота 0,5 / 0,25 / 0,1 × цены давали p3 размен 0,54 / 0,62 / 0,85 при 0,97 у
     расписания, без ворот — 1,60 (армия к 15:00 146 против 90), p3о 0,90 против 0,61, p2 15/30 против 11/30.
     Порядок покупки — оценка на тысячу ресурсов; ограничение — еда и золото ПОСЛЕ покупки не ниже порогов;
     найм ступень не останавливает (игрок 6.10). `доля_цены` остаётся рычагом (`ценность_цена` в файле стратегии).
  6. НЕИЗВЕСТНОСТЬ отдельно: если его состав не виден (нет `ecells` и `p1_inf/p1_shoot`), веса родов равные и
     `видно = False` — показывается словами, не выдаётся за ноль. Правила хакатона с 18.09 открывают всю партию.

Единица оценки — «бойцов-эквивалент»: сумма по нашим бойцам рода выигрыша размена (Δ отношения размена,
взвешенного его составом). Оценка 1,0 ≈ один наш боец, ставший вдвое ценнее.
"""
import combat_math as CM

ИССЛЕДОВАНИЕ_С = CM.ИССЛЕДОВАНИЕ_С
РАДИУС_БОЯ = 3               # клеток от нашей группировки: «рядом»
ФОН = 0.5                    # вес фона (вся армия) рядом с ближайшим боем
БОЙ_СВЕЖ_С = 20              # событие гибели не старше — бой идёт (живой мост, поле `kills`)
ДЛИНА_БОЯ_С = 60.0           # типичная длина контакта для веса темпа стрелка (§6: вспышки, зазоры)
РОДА = ("infantry17", "musk17", "dragoon17")
ИМЕНА = {"infantry17": "пикинёр", "musk17": "мушкетёр", "dragoon17": "драгун"}
РОД_ИМ = {"infantry17": "пикинёра", "musk17": "мушкетёра", "dragoon17": "драгуна"}

