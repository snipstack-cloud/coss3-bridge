ряд = [s for s in состояния if 255 <= s["gametime"] <= 316]        # анализу нужно ~30 с стояния, чтобы назвать лагерь
_321 = copy.deepcopy(ряд[-1]); _321["gametime"] = 321; ряд.append(_321)   # такт после 5:16: заслон идёт тактом позже сирот
print(f"в: {[s['gametime'] for s in ряд]} с — в 316: наши {[(c['x'], c['y'], c['n']) for c in при(316)['ocells']]}, его {[(c['x'], c['y'], c['n']) for c in при(316)['ecells']]}, свободных {при(316)['my_freewar']}")
for имя, доп, ждём_лагерь in (("с ключами", {}, False), ("без ключей", БЕЗ, True)):
    С = стратегия(доп); волна(С, 1, 1, (2, 2))
    АВ._ТЕКУЩИЙ.update({"а": None, "t": None, "ответ": None})
    все, потактно, причины_в = [], [], []
    for s in ряд:
        о = С.ответ(copy.deepcopy(s))
        все += боевые(о); потактно.append(боевые(о)); причины_в.append(о["why"])
    б = боевые(о)
    лагерь = [c for c in все if c[0] == "ATTACK" and c[1] in ("all", 9999) and (c[3], c[4]) == (5, 6)]
    проверить(bool(лагерь) == ждём_лагерь, f"(в) {имя}: удар по лагерю всеми в (5,6) {'есть' if лагерь else 'нет'}: {лагерь or б}")
    if not ждём_лагерь:
        засл = [c for c in все if c[0] == "MOVE" and c[2] == 93]
        т_з = next((i for i, т in enumerate(потактно) if any(c[0] == "MOVE" and c[2] == 93 for c in т)), None)
        дома_з = sum(c["n"] for c in ряд[т_з]["ocells"] if max(abs(c["x"] - 2), abs(c["y"] - 2)) <= 1) if т_з is not None else -1
        проверить(len(засл) == 1 and (засл[0][3], засл[0][4]) == (3, 3) and засл[0][5] == [5, 6] and 5 <= засл[0][1] == min(дома_з, ряд[т_з]["my_freewar"]),
                  f"(в) заслон группой 93 в (3,3) лицом к 5,6 числом свободных ДОМА ({дома_з}), один раз за ряд: {засл}")
        проверить(т_з is not None and "ЗАСЛОН:" in причины_в[т_з] and any("НЕ ГОНИМСЯ" in w for w in причины_в[т_з:]),
                  f"(в) «ЗАСЛОН:» в такте заслона, «НЕ ГОНИМСЯ» (лагерь назван через 30 с стояния) дальше по ряду: {[x for x in причины_в[т_з or 0].split('; ') if 'ЗАСЛОН' in x][:1]}")
        проверить("заслон" in о["why"] and "стоит" in о["why"] and "ЗАСЛОН:" not in о["why"], f"(в) в последнем такте заслон стоит, приказ не повторён: {[x for x in о['why'].split('; ') if 'заслон' in x][:1]}")
        сир = [(i, c) for i, т in enumerate(потактно) for c in т if c[0] == "RETREAT" and not c[2] and (c[1] or 0) >= 11 and (c[3], c[4]) == (2, 2)]
        проверить(bool(сир) and т_з is not None and сир[0][0] < т_з, f"(в) сироты 11-12 домой РАНЬШЕ заслона (такт {сир[0][0] if сир else None} < {т_з}): {сир[:1]}")
        вместе = [т for т in потактно if any(c[0] == "MOVE" and c[2] == 93 for c in т) and any(c[0] == "RETREAT" and not c[2] for c in т)]
        проверить(not вместе, f"(в) заслон и сироты не в одном такте (файл приказа один): {вместе}")
        С_в = С

