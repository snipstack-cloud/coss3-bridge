#!/usr/bin/env python3
"""ТРИ КЛЮЧА ПЕРВОГО БОЯ Д4 (12.10, §152): состояния четвёртой живой партии Д (`sim/кейсы/партия_д4_11_10_2_00-12_30.jsonl`).
Вживую: 3:49 волна W2 (13) ушла из дома навстречу его 10, идущим к ратуше (местный перевес 1,9), встала в (5,5) и легла по
частям — 12 за 4; 4:36 наши 12 стояли в (5,5) без волны (W2 пересобрана из одного, §150) и бот ничего не делал; 5:16 удар
по лагерю всеми 33 на его 10 в (5,6) в 4 кл. от ратуши — погоня, его 4 пришли к крестьянам. Двойник и экзамен
(sim/решения/д4_первый_бой.md): Б — стоять у ратуши, Б — сирот домой, Г — встать между ним и ратушей.

Ключи `не_навстречу` 2,0, `без_волны_домой` 3, `не_гнаться` 4 (клетки), `не_гнаться_при` 4,0:
(а) 3:44, его 10 идут (через ~97 с), W2 (13) ГОТОВА дома: с ключом удара нет, причина «навстречу не идём»; без ключа —
    ATTACK группой 1 в его клетку, как было;
(б) 4:36, наши 12 в (5,5) без волны: RETREAT числом ≥ 12 в клетку ратуши лицом к его 5,6; без ключа — ничего;
(в) 5:00–5:16, его 10 стоят в (5,6), наших 33 дома: удара по лагерю нет («НЕ ГОНИМСЯ»), сироты 11 домой, заслон —
    MOVE группой 93 в (4,4) лицом к 5,6; без ключей — ATTACK all в (5,6), как было;
(г) то же без сирот, W2 (23) ГОТОВА дома: контракт не бьёт («НЕ_ГОНИМСЯ»); без ключей — ORDER_ATTACK МЕСТНЫЙ_ПЕРЕВЕС;
(д) его кучи ушли дальше 4 клеток, заслон 93 стоит: RETREAT группе 93 в клетку ратуши;
(е) Д3 (в поле никого, его дальше 4 клеток от ратуши): команды с ключами и без них одинаковы.

    python3 selftest_д4_три_ключа.py
"""
import copy, json, os, sys, tempfile
К = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, К); sys.path.insert(0, os.path.join(К, "sim"))
os.environ.pop("COSS3_WAVE_CONTRACT", None)     # живьём контракт — сама ЖиваяСтратегия; с «1» базовая строит ВТОРУЮ внутри, и ключи срабатывают дважды
import strategy_live as SL
import анализ_врага as АВ

состояния = [json.loads(l) for l in open(os.path.join(К, "sim/кейсы/партия_д4_11_10_2_00-12_30.jsonl"), encoding="utf-8")]
ошибок = 0
def проверить(усл, что):
    global ошибок
    print(("ОК   " if усл else "ОШИБКА ") + что); ошибок += not усл

БЕЗ = {"не_навстречу": 0, "без_волны_домой": 0, "не_гнаться": 0}
def стратегия(доп):
    д = json.load(open(os.path.join(К, "sim/поиск/шт_s2_оборона_ручеёк_эко_так15_нужда.json"), encoding="utf-8"))
    д["итог"].update(доп)
    with tempfile.NamedTemporaryFile("w", suffix=".json", delete=False, encoding="utf-8") as f:
        json.dump(д, f, ensure_ascii=False)
    return SL.ЖиваяСтратегия(f.name)

def волна(С, группа, размер, клетка, состояние="ГОТОВА"):
    в = SL.Волна("W2", группа, 100.0, клетка); в.состояние, в.подтверждена, в.размер = состояние, True, размер
    С.реестр.волны.append(в); С.реестр.счёт = 2
    return в

def ответ(С, st):
    АВ._ТЕКУЩИЙ.update({"а": None, "t": None, "ответ": None})
    return С.ответ(copy.deepcopy(st))

def при(t):
    return next(s for s in состояния if s["gametime"] >= t)

def боевые(о):
    return [(c["cmd"], c.get("count"), c.get("group"), c.get("cx"), c.get("cy"), c.get("face")) for c in о["commands"]
            if c["cmd"] in ("ATTACK", "MOVE", "RETREAT", "ENGAGE")]

# (а) 3:44 — его 10 идут к базе, W2 (13) готова дома
st_а = при(224)
print(f"а: {st_а['gametime']} с — его клетки {[(c['x'], c['y'], c['n']) for c in st_а['ecells']]}, наши {[(c['x'], c['y'], c['n']) for c in st_а['ocells']]}")
for имя, доп, ждём_удар in (("с ключом", {}, False), ("без ключа", БЕЗ, True)):
    С = стратегия(доп); волна(С, 1, 13, (2, 2))
    о = ответ(С, st_а)
    удары = [c for c in боевые(о) if c[0] == "ATTACK" and c[2] == 1]
    проверить(bool(удары) == ждём_удар, f"(а) {имя}: удар W2 группой 1 {'есть' if удары else 'нет'} {удары}")
    if not ждём_удар:
        проверить("навстречу не идём" in о["why"], f"(а) причина названа: {[x for x in о['why'].split(' | ') if 'ПОДХОД' in x][:1]}")

# (б) 4:36 — 12 в (5,5) без волны
st_б = при(276)
print(f"б: {st_б['gametime']} с — наши {[(c['x'], c['y'], c['n']) for c in st_б['ocells']]}, его {[(c['x'], c['y'], c['n']) for c in st_б['ecells']]}")
for имя, доп, ждём in (("с ключом", {}, True), ("без ключа", БЕЗ, False)):
    С = стратегия(доп); волна(С, 1, 1, (2, 2))
    о = ответ(С, st_б)
    отх = [c for c in боевые(о) if c[0] == "RETREAT" and not c[2] and (c[1] or 0) >= 12 and (c[3], c[4]) == (2, 2)]
    проверить(bool(отх) == ждём, f"(б) {имя}: сироты домой {'есть' if отх else 'нет'} {отх or боевые(о)}")
    if ждём:
        проверить(bool(отх) and отх[0][5] == [5, 6], f"(б) лицом к его 5,6: {отх and отх[0][5]}")
        проверить("СИРОТЫ" in о["why"], "(б) причина «СИРОТЫ» в why")

# (в) 5:00–5:16 — его 10 стоят в (5,6), наших 33 дома; анализу нужна история — кормим подряд
ряд = [s for s in состояния if 255 <= s["gametime"] <= 316]        # анализу нужно ~30 с стояния, чтобы назвать лагерь
print(f"в: {[s['gametime'] for s in ряд]} с — в 316: наши {[(c['x'], c['y'], c['n']) for c in при(316)['ocells']]}, его {[(c['x'], c['y'], c['n']) for c in при(316)['ecells']]}, свободных {при(316)['my_freewar']}")
for имя, доп, ждём_лагерь in (("с ключами", {}, False), ("без ключей", БЕЗ, True)):
    С = стратегия(доп); волна(С, 1, 1, (2, 2))
    АВ._ТЕКУЩИЙ.update({"а": None, "t": None, "ответ": None})
    все = []
    for s in ряд:
        о = С.ответ(copy.deepcopy(s))
        все += боевые(о)
    б = боевые(о)
    лагерь = [c for c in б if c[0] == "ATTACK" and c[1] in ("all", 9999) and (c[3], c[4]) == (5, 6)]
    проверить(bool(лагерь) == ждём_лагерь, f"(в) {имя}: удар по лагерю всеми в (5,6) {'есть' if лагерь else 'нет'}: {б}")
    if not ждём_лагерь:
        засл = [c for c in б if c[0] == "MOVE" and c[2] == 93]
        проверить(засл and (засл[0][3], засл[0][4]) == (4, 4) and засл[0][5] == [5, 6] and засл[0][1] == 33, f"(в) заслон группой 93 в (4,4) лицом к 5,6 числом 33: {засл}")
        проверить("НЕ ГОНИМСЯ" in о["why"] and "ЗАСЛОН" in о["why"], f"(в) причины: {[x for x in о['why'].split('; ') if 'ГОНИМ' in x or 'ЗАСЛОН' in x]}")
        сир = [c for c in все if c[0] == "RETREAT" and not c[2] and (c[1] or 0) >= 11 and (c[3], c[4]) == (2, 2)]
        проверить(bool(сир), f"(в) сироты 11-12 из (5,5)/(5,6) домой хоть в одном такте ряда: {сир[:2]}")

# (г) контракт из дома: W2 (23) ГОТОВА в (1,2), сирот нет
st_г = copy.deepcopy(при(316))
st_г["ocells"] = [c for c in st_г["ocells"] if max(abs(c["x"] - 2), abs(c["y"] - 2)) <= 1]
st_г["groups"] = [{"id": 1, "n": 23, "пик": 20, "стрелков": 3, "конных": 0, "cx": 1, "cy": 2, "режим": 2, "tx": -1, "ty": -1}]
st_г["mil_away"] = 0; st_г["wave_n"] = 0   # в поле никого и волны блока нет — иначе RETREAT стрелков позади (§87) занимает такт, и волну не спрашивают
for имя, доп, ждём_удар in (("с ключами", {}, False), ("без ключей", БЕЗ, True)):
    С = стратегия(доп); волна(С, 1, 23, (1, 2))
    о = ответ(С, st_г)
    удары = [c for c in боевые(о) if c[0] == "ATTACK" and c[2] == 1]
    проверить(bool(удары) == ждём_удар, f"(г) {имя}: удар W2 (23) из дома на его 10 в (5,6) {'есть' if удары else 'нет'} {удары}")
    if not ждём_удар:
        проверить("НЕ_ГОНИМСЯ" in о["why"], f"(г) причина: {[x for x in о['why'].split(' | ') if 'ГОНИМ' in x][:1]}")

# (д) его ушли — заслон 93 домой
st_д = copy.deepcopy(st_г)
st_д["ecells"] = [c for c in st_д["ecells"] if max(abs(c["x"] - 2), abs(c["y"] - 2)) > 4]
st_д["groups"] = [{"id": 93, "n": 30, "пик": 27, "стрелков": 3, "конных": 0, "cx": 4, "cy": 4, "режим": 2, "tx": -1, "ty": -1}]
st_д["ocells"] = st_д["ocells"] + [{"x": 4, "y": 4, "n": 30, "пик": 27, "стрелков": 3, "конных": 0}]
С = стратегия({}); С._заслон_поля = {"кл": (4, 4), "t": 300.0, "его": (5, 6)}
о = ответ(С, st_д)
дом93 = [c for c in боевые(о) if c[0] == "RETREAT" and c[2] == 93 and (c[3], c[4]) == (2, 2)]
проверить(bool(дом93), f"(д) его дальше 4 клеток — заслон 93 домой: {дом93 or боевые(о)}")
сир = [c for c in боевые(о) if c[0] == "RETREAT" and not c[2]]
проверить(not сир, f"(д) заслон не считается сиротами: {сир}")

# (е) Д3 7:26 — его далеко: команды одинаковы
д3 = [json.loads(l) for l in open(os.path.join(К, "sim/кейсы/партия_д3_10_10_2_00-8_30.jsonl"), encoding="utf-8")]
st_е = next(s for s in д3 if s["gametime"] >= 200 and not int(s.get("mil_away") or 0)
            and all(max(abs(c["x"] - 2), abs(c["y"] - 13)) > 4 for c in s.get("ecells") or []))
ком = lambda о: sorted(json.dumps(c, ensure_ascii=False, sort_keys=True) for c in о["commands"])
о1, о0 = ответ(стратегия({}), st_е), ответ(стратегия(БЕЗ), st_е)
проверить(ком(о1) == ком(о0), f"(е) Д3 {st_е['gametime']} с: команды с ключами и без них одинаковы ({len(о1['commands'])})")
print(f"ошибок: {ошибок}")
sys.exit(1 if ошибок else 0)
