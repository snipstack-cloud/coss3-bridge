# -*- coding: utf-8 -*-
"""«К ВОЛНЕ» БЕЗ МАРША ЗАВОДИТ МАРШ (24.09, ключ --wave-march).

Счёт по девяти партиям 23-24.09, 1484 такта с атакой: 81 процент приказов
модели - ATTACK target=wave, и в 971 случае из 1206 марша в этот миг НЕ БЫЛО.
Мост находил своих в поле, брал их клетку и слал подкрепление туда простым
движением - без сбора, порога, срока и удара. Так войско текло к месту боя
струйкой, той самой цепочкой, из-за которой волны гибнут по одному, а
механика сбора включалась 0-1 раз за партию: планку нечем было мерить,
gather_resets - тем более.

Марш заводится ТОЛЬКО от клетки сбора в контракте (via). С ключом «к волне»
без марша получает via = клетка волны, а целью удара - ближайшую к ней клетку
крестьян врага (ради них партия и играется); если крестьян на карте не видно,
бьём по клетке волны.

Что проверяется - по коду, потому что живой такт здесь не собрать:
  1. ключ есть, по умолчанию ВЫКЛЮЧЕН - это идея, а не починка;
  2. срабатывает только при ЧЕТЫРЁХ условиях разом: цель была wave, марша
     нет, контракт без via, ключ включён - иначе прежнее поведение;
  3. клетка сбора = клетка волны, цель удара = ближайшие крестьяне врага;
  4. без крестьян на карте цель удара - клетка волны;
  5. вмешательство названо вслух с обеими клетками и способом отключить;
  6. признак «цель была wave» снимается ДО подмены её на cell.
"""
import io, os, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

ошибок = 0


def проверить(условие, что):
    global ошибок
    if not условие:
        ошибок += 1
        print("  СБОЙ:", что)
    else:
        print("  ок:", что)


И = io.open(os.path.join(os.path.dirname(os.path.abspath(__file__)),
                         "llm_policy.py"), encoding="utf-8").read()
блок = И[И.index("# «К ВОЛНЕ» БЕЗ МАРША -> МАРШ НА КЛЕТКУ ВОЛНЫ"):][:2600]

print("1. ключ выключен по умолчанию")
проверить(re.search(r'--wave-march",\s*type=int,\s*default=0', И) is not None,
          "default=0: поведение базы не задето")

print("2. четыре условия разом")
for у in ('цель_атаки == "cell"', "_было_wave", 'not контракт.get("via")',
          'getattr(a, "wave_march", 0)', "not МАРШ"):
    проверить(у in блок, f"условие: {у}")

print("3-4. клетка сбора и цель удара")
проверить('контракт["via"] = tuple(клетка)' in блок, "сбор в клетке волны")
проверить("coss3_map.крестьяне_врага(st)" in блок, "цель ищется среди клеток крестьян врага")
проверить("min(_кр, key=" in блок and "abs(к[\"x\"] - клетка[0])" in блок,
          "берётся БЛИЖАЙШАЯ к волне клетка крестьян")
проверить("if _кр:" in блок, "без крестьян на карте цель остаётся клеткой волны")

print("5. вмешательство названо вслух")
проверить("заведён МАРШЕМ" in блок and "--wave-march 0" in блок,
          "сказано, что сделано и чем отключается")
проверить("сбор в клетке волны" in блок and "удар по" in блок, "названы обе клетки")

print("6. признак снимается до подмены wave -> cell")
i_признак = И.index('_было_wave = bool(attack and цель_атаки == "wave")')
i_подмена = И.index('ATTACK {attack} -> wave: к волне в клетку')
проверить(i_признак < i_подмена, "«цель была wave» запоминается раньше, чем она становится cell")

# блок марша стоит НИЖЕ правки, иначе via не успеет попасть в контракт
i_правка = И.index("# «К ВОЛНЕ» БЕЗ МАРША -> МАРШ НА КЛЕТКУ ВОЛНЫ")
i_марш = И.index('if attack and not вето_волны and контракт.get("via"):')
проверить(i_правка < i_марш, "блок марша читает via уже после правки")

print()
print("ошибок:", ошибок)
sys.exit(1 if ошибок else 0)
