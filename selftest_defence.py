"""Сторож рук (6.10, `ЖиваяСтратегия._оборона`): картина p6 в 6:17 — его 25 идут к ратуше, дома 9, волна 30 в
поле. С ключом `оборона`: удар 21 на его базу не уезжает, волна идёт домой лицом к нему. Без ключа — как было."""
import sys
import strategy_live as SL

ж = SL.ЖиваяСтратегия.__new__(SL.ЖиваяСтратегия)
ж.п = {"штурм_при": 0.92, "оборона": 1}
ж.реестр = SL.РеестрВолн()
в = SL.Волна("W1", 1, 0.0, (6, 9), "cell")
в.подтверждена, в.состояние, в.размер = True, "В_БОЮ", 30
ж.реестр.волны.append(в)
st = {"map_w": 256, "obuild": [{"тип": "center", "x": 40, "z": 54}],
      "ecells": [{"x": 3, "y": 6, "n": 25, "стрелков": 5, "идут": 25, "tx": 2, "ty": 4}],
      "ocells": [{"x": 2, "y": 3, "n": 9}, {"x": 6, "y": 9, "n": 30}]}
ош = 0
из, зап = ж._оборона([{"cmd": "ATTACK", "count": 21, "target": "base"}], st)
if any(c.get("target") == "base" for c in из):
    print("ПРОВАЛ: удар из дома при набеге уехал:", из); ош += 1
if not any(c.get("cmd") == "RETREAT" and c.get("group") == 1 and c.get("face") for c in из) or в.состояние != "ДОМОЙ":
    print("ПРОВАЛ: волна не позвана домой лицом к нему:", из, в.состояние); ош += 1
ж.п["оборона"] = 0
из2, зап2 = ж._оборона([{"cmd": "ATTACK", "count": 21, "target": "base"}], st)
if not из2 or зап2:
    print("ПРОВАЛ: без ключа правило не должно действовать"); ош += 1
print(f"ошибок: {ош}")
sys.exit(1 if ош else 0)
