# -*- coding: utf-8 -*-
"""Самопроверка окупаемости апгрейда: выигрыш умножается на ЧИСЛО БОЙЦОВ.

Формула игрока (калькулятор производственных функций): T_payback = C/(m*dq),
где m — сколько бойцов получат апгрейд. В мосту множителя m не было вовсе, и
счёт врал в пользу редких видов.

Живая партия 19.09: 176 пикинёров против 31 мушкетёра. Четвёртая ступень пики
читалась «0,02 на тысячу еды», то есть мусором, хотя её получают 176 бойцов
разом; с множителем это 2,84. Мушкетёрская защита за 170 еды была лучшей
покупкой и так (0,71), с множителем 21,88.
"""
import combat_math as C

беды = []


def проверка(имя, условие, пояснение=""):
    if условие:
        print("  ОК    " + имя)
    else:
        беды.append(имя)
        print("  ПЛОХО " + имя + (" — " + пояснение if пояснение else ""))


НАШ = C.разобрать("infantry17=pikeman,hp90,atk13,wkind1,pause0,"
                  "dpike9,dsword8,dbullet4")["infantry17"]
ЕГО = C.разобрать("infantry17=hp90,atk13,wkind1,pause0,"
                  "dpike9,dsword8,dbullet4")["infantry17"]
ЦЕНЫ = C.цены_апгрейдов("bar.pikeman.2.4=f9305g707i0")
ЗАПАС = {"food": 20000, "gold": 9000}

один = C.окупаемость(НАШ, ЕГО, "pikeman", ЦЕНЫ, set(), ЗАПАС)
много = C.окупаемость(НАШ, ЕГО, "pikeman", ЦЕНЫ, set(), ЗАПАС, 176)

print("Самопроверка окупаемости:")
проверка("ступень посчитана", bool(один) and bool(много))
if один and много:
    проверка("число бойцов доходит до результата",
             один[0]["скольких"] == 0 and много[0]["скольких"] == 176)
    проверка("общий выигрыш = на одного умножить на число",
             много[0]["выигрыш_армии"] == round(много[0]["выигрыш"] * 176, 2))
    проверка("выигрыш на тысячу еды растёт со 176 бойцами",
             много[0]["на_тысячу_еды"] > один[0]["на_тысячу_еды"] * 100,
             f"было {один[0]['на_тысячу_еды']}, стало {много[0]['на_тысячу_еды']}")
    ноль = C.окупаемость(НАШ, ЕГО, "pikeman", ЦЕНЫ, set(), ЗАПАС, 0)
    проверка("при неизвестном числе счёт как раньше, на одного",
             ноль[0]["на_тысячу_еды"] == один[0]["на_тысячу_еды"])
    проверка("редкий вид больше не выигрывает одной лишь дешевизной",
             много[0]["на_тысячу_еды"] > 1.0,
             "четвёртая ступень пики на 176 бойцов не должна читаться мусором")

print()
if беды:
    print(f"БЕД: {len(беды)} — {', '.join(беды)}")
    raise SystemExit(1)
print("всё чисто")
