#!/usr/bin/env python3
"""ВЫХОД В Д5 — УДАР ПО ЛАГЕРЮ ПО ПРОГНОЗУ, §152 ТОЛЬКО ПРО ОСТАТОК (14.10, §160). Состояния пятой живой партии Д
(`sim/кейсы/партия_д5_13_10_2_00-15_15.jsonl`, составы бойцов для прогноза — `sim/кейсы/партия_д5_бойцы.json`).
Вживую бот не вышел ни разу: он стоял лагерем у ратуши всю партию, а удар по лагерю требовал свободных ≥ 1,5 × лагеря
(`лагерь_перевес`); в 14:39 его 77 в (5,11), наших 105 — «не бьём: 105 < 1.5×77». Двойник в 14:39: удар 7 : 36, 16 : 35,
14 : 58 у трёх агентов; прогноз `лагерь_R` даёт R = 2,07. Но и с низким порогом удар запирало §152 «НЕ ГОНИМСЯ» (в ≤ 4 кл.
без перевеса 4×) — правило про остаток в 10 (Д4), а не про лагерь в 77.

Ключи в файле партии: `лагерь_R` 1,3 (прогноз вместо числа) и `не_гнаться_до` 20 (§152 держит только кучи ≤ 20).
§162 (16.10, Д6 10:45): путь к лагерю считается честно (2 кл. = ~33 с, не 14) и ключ `лагерь_с_подходом` 1 — в его силу входят
идущие к лагерю, которые успеют к бою. От этого удар 14:39 ПРОПАДАЕТ: из его 39 успевают 30 (через ~28 с), 105 против его 89 у лагеря — R 1,12 < 1,3.
Удар 14:39 остаётся только как правило турнира (`выход_к`, ПЛАН) — решение игрока.
(а) 13:20 → 15:15 с ключами партии: ударов нет, 14:39 «не бьём: прогноз мал … R=1.12 … наших 105 против его 89 … (с подходом 30)»; (а2) с
`лагерь_с_подходом` 0: ударов тоже нет — R 2,07 годится, но «его подход через ~28 с раньше нас (~33 с)»; (б) без `лагерь_R`
(перевес 1,5): «не бьём: наших 105 < 1.5×77»; (в) `не_гнаться_до` 0 и `лагерь_с_подходом` 0: «НЕ ГОНИМСЯ за его 77»;
(г) 5:40 → 8:20: ударов нет; 7:37 остаток 10 — с ключами партии «прогноз мал R=0.26», с `лагерь_с_подходом` 0 — «НЕ ГОНИМСЯ
за его 10»; 8:04 лагерь 26 — R 1,01 < 1,3 («прогноз мал»).

    python3 selftest_д5_выход.py
"""
import copy, json, os, sys, tempfile
К = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, К); sys.path.insert(0, os.path.join(К, "sim"))
os.environ.pop("COSS3_WAVE_CONTRACT", None)
import strategy_live as SL
import анализ_врага as АВ

кейс = [json.loads(l) for l in open(os.path.join(К, "sim/кейсы/партия_д5_13_10_2_00-15_15.jsonl"), encoding="utf-8")]
_ст = [i for i in range(1, len(кейс)) if кейс[i]["gametime"] < кейс[i - 1]["gametime"]]
кейс = кейс[_ст[-1]:] if _ст else кейс
бойцы = {int(k): v for k, v in json.load(open(os.path.join(К, "sim/кейсы/партия_д5_бойцы.json"), encoding="utf-8")).items()}
ошибок = 0
def проверить(усл, что):
    global ошибок
    print(("ОК   " if усл else "ОШИБКА ") + что); ошибок += not усл

def стратегия(доп, убрать=()):
    д = json.load(open(os.path.join(К, "sim/поиск/шт_s2_оборона_ручеёк_эко_так15_нужда.json"), encoding="utf-8"))
    assert д["итог"].get("лагерь_R") == 1.3 and д["итог"].get("не_гнаться_до") == 20, "в файле партии ждём лагерь_R 1.3 и не_гнаться_до 20"
    for k in убрать: д["итог"].pop(k, None)
    д["итог"].update(доп)
    with tempfile.NamedTemporaryFile("w", suffix=".json", delete=False, encoding="utf-8") as f:
        json.dump(д, f, ensure_ascii=False)
    return SL.ЖиваяСтратегия(f.name)

def м(t): return f"{int(t)//60}:{int(t)%60:02d}"

def прогон(С, a, b):
    """Такты a..b подряд (анализ лагеря копит историю); возвращает [(время, удар, строки why про лагерь)]."""
    АВ._ТЕКУЩИЙ.update({"а": None, "t": None, "ответ": None})
    итог = []
    for s in кейс:
        t = s["gametime"]
        if t < a or t > b: continue
        st = copy.deepcopy(s)
        bс = бойцы[min(бойцы, key=lambda k: abs(k - t))]
        for k in ("fighters", "en_fighters", "upg_done", "en_upg_done"):
            st.setdefault(k, bс[k])
        о = С.ответ(st)
        удар = [(c["cmd"], c.get("count"), c.get("cx"), c.get("cy")) for c in о["commands"] if c["cmd"] in ("ATTACK", "ENGAGE")]
        why = [x for x in о["why"].split("; ") if "ЛАГЕР" in x or "НЕ ГОНИМСЯ" in x]
        итог.append((t, удар, why))
    return итог

# (а) ключи партии: ударов нет, 14:39 — прогноз с подходом 39
ит = прогон(стратегия({}), 800, 916)
удары = [(м(t), у[0]) for t, у, _ in ит if у]
_1439 = next((w for t, _, w in ит if 877 <= t <= 881), [])
проверить(not удары, f"(а) 13:20–15:15 с ключами партии: ударов нет: {удары}")
проверить(any(x.startswith("ЛАГЕРЬ его 77") and "прогноз мал" in x and "R=1.12" in x and "наших 105 против его 89" in x and "(с подходом 30)" in x for x in _1439), f"(а) why 14:39: {[x[:260] for x in _1439]}")
# (а2) без подхода: R 2,07 годится, но честный путь 33 с дольше его подхода 28 с
ит = прогон(стратегия({"лагерь_с_подходом": 0}), 800, 916)
удары = [(м(t), у[0]) for t, у, _ in ит if у]
_1439 = next((w for t, _, w in ит if 877 <= t <= 881), [])
проверить(not удары and any("его подход через ~28 с раньше нас (~33 с)" in x for x in _1439), f"(а2) лагерь_с_подходом 0: ударов {len(удары)}, why {[x[:120] for x in _1439]}")

# (б) без прогноза — перевес 1,5: ударов нет
ит = прогон(стратегия({}, убрать=("лагерь_R",)), 800, 916)
удары = [(м(t), у[0]) for t, у, _ in ит if у]
_1439 = next((w for t, _, w in ит if 877 <= t <= 881), [])
проверить(not удары and any("не бьём: наших 105 < 1.5×77" in x for x in _1439), f"(б) перевес 1,5: ударов {len(удары)}, why {[x[:80] for x in _1439]}")

# (в) §152 без предела: ударов нет, «НЕ ГОНИМСЯ за его 77»
ит = прогон(стратегия({"не_гнаться_до": 0, "лагерь_с_подходом": 0}), 800, 916)
удары = [(м(t), у[0]) for t, у, _ in ит if у]
_1439 = next((w for t, _, w in ит if 877 <= t <= 881), [])
проверить(not удары and any(x.startswith("НЕ ГОНИМСЯ за его 77") for x in _1439), f"(в) не_гнаться_до 0: ударов {len(удары)}, why {[x[:80] for x in _1439]}")

# (г) раннее окно 5:40–8:20: ударов нет ни с ключами партии, ни с пределом 0
for имя, доп in (("ключи партии", {}), ("лагерь_с_подходом 0", {"лагерь_с_подходом": 0})):
    ит = прогон(стратегия(доп), 340, 500)
    удары = [(м(t), у[0]) for t, у, _ in ит if у]
    _737 = next((w for t, _, w in ит if 455 <= t <= 459), [])
    _804 = next((w for t, _, w in ит if 482 <= t <= 486), [])
    проверить(not удары, f"(г) {имя}, 5:40–8:20: ударов по лагерю нет: {удары}")
    if доп:
        проверить(any(x.startswith("НЕ ГОНИМСЯ за его 10") for x in _737), f"(г) {имя}, 7:37 остаток 10 — «НЕ ГОНИМСЯ»: {[x[:70] for x in _737]}")
    else:
        проверить(any(x.startswith("ЛАГЕРЬ его 10") and "прогноз мал" in x and "R=0.26" in x for x in _737), f"(г) {имя}, 7:37 остаток 10 с подходом — прогноз R=0.26: {[x[:90] for x in _737]}")
    проверить(any("не бьём" in x and "R=1.01" in x for x in _804), f"(г) {имя}, 8:04 лагерь 26 — прогноз R=1.01 < 1,3: {[x[:90] for x in _804]}")
print(f"ошибок: {ошибок}")
sys.exit(1 if ошибок else 0)
