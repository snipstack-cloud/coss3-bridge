#!/usr/bin/env python3
"""Документ по одному прогону: что проверяли, чем кончилось, что видно в трассе.

    python3 run_report.py /io                  > отчёт
    python3 run_report.py /io --out /io/отчёт.md

Зачем отдельно от log_review. Тот показывает ТАКТЫ — построчно, что думала
модель. Этого мало, чтобы через неделю понять, что за прогон перед тобой: какая
версия моста играла, на каких условиях, чем кончилось и отличался ли он от базы.
Здесь шапка и итог, а подробности — там.

Читает то, что контейнер кладёт рядом с трассой, и молчит про то, чего нет:
отсутствие файла — это тоже сведение, и врать про него нельзя.
"""
from __future__ import annotations
import argparse
import json
import os
import sys

for _s in (sys.stdout, sys.stderr):
    try: _s.reconfigure(encoding="utf-8", errors="replace")
    except Exception: pass

# Исходы, как их пишет llm_policy в поле finish. «цель» с 14.09 отмечается в
# трассе наравне с победой: до этого она возвращалась простым return, отметки не
# было, и отчёт показывал взятую цель как «не кончилась».
ИСХОД = {"win": "ПОБЕДА", "lose": "ПОРАЖЕНИЕ", "цель": "ЦЕЛЬ",
         "горизонт": "горизонт", "отрезок": "отрезок", "обрыв": "обрыв"}


def прочесть(путь: str) -> str:
    try:
        with open(путь, encoding="utf-8", errors="replace") as f:
            return f.read().strip()
    except OSError:
        return ""


def разбор_dat(путь: str) -> dict[str, str]:
    """Файлы игры: `ключ = значение`, по строке."""
    из: dict[str, str] = {}
    for строка in прочесть(путь).splitlines():
        если = строка.split("=", 1)
        if len(если) == 2:
            из[если[0].strip()] = если[1].strip()
    return из


def трасса(путь: str) -> list[dict]:
    из = []
    try:
        with open(путь, encoding="utf-8") as f:
            for строка in f:
                строка = строка.strip()
                if строка:
                    try:
                        из.append(json.loads(строка))
                    except ValueError:
                        pass
    except OSError:
        pass
    return из


def партии(записи: list[dict]) -> list[list[dict]]:
    """Режем по откату игрового времени — так же, как log_review."""
    из, тек = [], []
    for р in записи:
        if тек and р.get("gt", 0) < тек[-1].get("gt", 0):
            из.append(тек)
            тек = []
        тек.append(р)
    if тек:
        из.append(тек)
    return из


def чис(v) -> int:
    """Число из снимка. В старых трассах поля приходили строками, и «0» + «0»
    давало «00» вместо нуля — тихая ошибка ровно того рода, за которой этот
    отчёт и заведён."""
    try:
        return int(str(v).strip())
    except (TypeError, ValueError):
        return 0


def мм(gt) -> str:
    gt = int(gt or 0)
    return f"{gt // 60}:{gt % 60:02d}"


def вражьи_крестьяне(р: dict):
    с = р.get("state") or {}
    свои = [чис(v) for k, v in с.items()
            if k.endswith("_peasants") and not k.startswith("my") and v is not None]
    return max(свои) if свои else None


def отчёт(io: str) -> str:
    строки: list[str] = []
    д = строки.append
    такты = трасса(os.path.join(io, "coss3_bot.jsonl"))
    опыт = {}
    try:
        опыт = json.loads(прочесть(os.path.join(io, "опыт.json")) or "{}")
    except ValueError:
        pass

    # --- шапка: что это был за прогон ---------------------------------------
    название = опыт.get("опыт") or "одиночный прогон"
    д(f"# Прогон: {название}")
    д("")
    if опыт.get("что"):
        д(f"**Идея:** {опыт['что']}")
        д("")
    шапка = []
    if опыт.get("флаги"):
        # Флаги приходят и списком (их пишет exp.py), и строкой (их пишет
        # pick_experiment.py). " ".join() по строке склеивает её ПОБУКВЕННО, и
        # в отчёте стояло «- - b u i l d e r s - f i r s t   9 9».
        _ф = опыт["флаги"]
        _ф = " ".join(_ф) if isinstance(_ф, (list, tuple)) else str(_ф)
        шапка.append(("чем отличается от базы", _ф.strip() or "ничем"))
    if опыт.get("база"):
        шапка.append(("сравнивать с", опыт["база"]))
    if опыт.get("копия") is not None:
        шапка.append(("копия", str(опыт["копия"])))
    if опыт.get("начало"):
        шапка.append(("начат", опыт["начало"]))
    sha = прочесть(os.path.join(io, "bridge.sha"))
    шапка.append(("версия моста", sha or "НЕ ЗАПИСАНА — прогон не воспроизвести"))

    матч = разбор_dat(os.path.join(io, "match.dat"))
    if матч:
        РЕС = {"0": "1000", "1": "4000", "2": "5000"}
        СЛОЖНОСТЬ = {"0": "Normal", "1": "Hard", "2": "Very Hard", "3": "Impossible"}
        условия = []
        if "res" in матч:
            условия.append(f"ресурсов {РЕС.get(матч['res'], '?')} (res={матч['res']})")
        if "peace" in матч:
            условия.append("без времени мира" if матч["peace"] == "0"
                           else f"мир {матч['peace']} мин")
        if "ai1" in матч:
            условия.append(f"противник {СЛОЖНОСТЬ.get(матч['ai1'], '?')} (ai={матч['ai1']})")
        if "nat0" in матч:
            условия.append(f"наша нация cid={матч['nat0']}")
        шапка.append(("условия партии", ", ".join(условия)))
    else:
        шапка.append(("условия партии", "НЕ ЗАПИСАНЫ — сравнивать с другими копиями нельзя"))

    for имя, знач in шапка:
        д(f"* **{имя}:** {знач}")
    д("")

    if not такты:
        д("## Трассы нет")
        д("")
        д("`coss3_bot.jsonl` пуст или отсутствует. Значит модель не сделала ни "
          "одного хода. Смотреть в таком порядке:")
        д("")
        д("1. `policy.log` — что сказала сама политика: ошибка ключей, "
          "отсутствие ключа модели, негодный слот;")
        д("2. `install.log` — встали ли блоки (должно быть ЧЕТЫРЕ и ДВА файла);")
        д("3. `game.log` — поднялась ли игра под Wine;")
        д("4. `coss3_llm.log` — отвечал ли провайдер.")
        return "\n".join(строки)

    # --- итог ---------------------------------------------------------------
    сп = партии(такты)
    д(f"## Итог: партий {len(сп)}")
    д("")
    д("| партия | тактов | до | исход | крестьян | армия | крестьян у врага |")
    д("|---|---|---|---|---|---|---|")
    for n, п in enumerate(сп, 1):
        концы = [р for р in п if р.get("finish")]
        ходы = [р for р in п if not р.get("finish")]
        исход = ИСХОД.get(str(концы[-1]["finish"]), str(концы[-1]["finish"])) \
            if концы else "не кончилась"
        посл = п[-1].get("state") or {}
        враг0 = next((в for в in (вражьи_крестьяне(р) for р in п) if в is not None), None)
        враг1 = next((в for в in (вражьи_крестьяне(р) for р in reversed(п))
                      if в is not None), None)
        враг = "—" if враг0 is None else (f"{враг0} → {враг1}")
        армия = чис(посл.get("mil_inf")) + чис(посл.get("mil_shooters"))
        д(f"| {n} | {len(ходы)} | {мм(п[-1].get('gt'))} | {исход} | "
          f"{посл.get('peasants', '—')} | {армия} | {враг} |")
    д("")

    # С КАКОЙ СЕКУНДЫ бот вообще начал играть. Это первое, что решает, сравним
    # ли прогон с другими: 12.09 политику запускали отдельной командой после
    # боя, и бот не существовал полторы минуты — а по трассе это выглядело как
    # «полторы минуты ничего не строил», то есть артефакт запуска читался как
    # поведение модели.
    первый_ход = next((int(р.get("gt", 0)) for п in сп for р in п
                       if not р.get("finish")), 0)
    if первый_ход > 15:
        д(f"> **ПОДКЛЮЧИЛИСЬ ПОЗДНО: первый ход на {мм(первый_ход)}.** Всё это "
          f"время бот не играл, а игра шла. С прогонами, начатыми с нуля, этот "
          f"НЕ СРАВНИМ — разница будет не про идею, а про то, сколько партия "
          f"прожила без бота.")
    else:
        д(f"*Первый ход на {мм(первый_ход)} — бот играл партию с начала.*")
    д("")

    # Цель хакатона названа отдельно: по таблице её легко проглядеть.
    #
    # Считать надо от БЕГУЩЕГО МАКСИМУМА, а не от начала партии. Враг растёт с 18
    # до 90-150, поэтому сравнение «последнее против первого» давало «не взята»
    # ВСЕГДА — 14.09 так пропала цель, взятая на 12:07. Ровно та же ошибка была
    # в llm_policy и была там исправлена 13.09; здесь осталась жить.
    def цель_в_партии(п) -> bool:
        if any(str(р.get("finish", "")) == "цель" for р in п):
            return True                     # отметка моста, самый надёжный признак
        пик = None
        for р in п:
            в = вражьи_крестьяне(р)
            if в is None:
                continue
            if пик is not None and в < пик:
                return True
            пик = в if пик is None else max(пик, в)
        return False

    взята = any(цель_в_партии(п) for п in сп)
    # Третий путь, для старых прогонов: сама игра проверяет цель КАЖДУЮ секунду,
    # а трасса пишется раз в двадцать. 14.09 цель взяли на 12:07, последний такт
    # был на 12:05 — падения 70 -> 69 в трассе нет вовсе, и восстановить его по
    # ней невозможно. В логе прогона оно есть.
    if not взята:
        лог = прочесть(os.path.join(io, "policy.log"))
        взята = "ЦЕЛЬ ДОСТИГНУТА" in лог
    д(f"**Цель (убить крестьянина врага): {'ВЗЯТА' if взята else 'не взята'}.**")
    д("")

    # --- что мешало ---------------------------------------------------------
    брак = [(р.get("gt", 0), б) for р in такты for б in (р.get("rejected") or [])]
    вето = [(р.get("gt", 0), str(р.get("veto") or "")) for р in такты if р.get("veto")]
    молча = sum(1 for р in такты
                if not р.get("finish") and not str(р.get("why", "")).strip())
    д("## Что не доехало до игры")
    д("")
    д(f"* команд отвергнуто: **{len(брак)}**")
    д(f"* волн отвергнуто порогом: **{len(вето)}**")
    д(f"* тактов без объяснения: **{молча}**")
    д("")
    for gt, б in брак[:10]:
        д(f"* {мм(gt)} — {б}")
    if len(брак) > 10:
        д(f"* …и ещё {len(брак) - 10}")
    if брак or вето:
        д("")
    for gt, в in вето[:5]:
        д(f"* {мм(gt)} ВЕТО ВОЛНЫ — {в[:160]}")
    if вето:
        д("")

    # --- своими словами модели ----------------------------------------------
    for ключ, заголовок, зачем in (
            ("idea", "Гипотезы модели", "их НЕ возвращают в запрос — они для проверки нами"),
            ("lesson", "Уроки модели", "записаны ею самой по ходу партии")):
        текст = [(р.get("gt", 0), str(р.get(ключ) or "").strip()) for р in такты]
        текст = [(g, т) for g, т in текст if т]
        д(f"## {заголовок}")
        д("")
        д(f"*{зачем}*")
        д("")
        if текст:
            for g, т in текст:
                д(f"* {мм(g)} — {т}")
        else:
            д("* ни одной")
        д("")

    д("## Где подробности")
    д("")
    д("* `coss3_bot.jsonl` — трасса по тактам, она самодостаточна;")
    д("* `report.txt` — та же трасса, разобранная `log_review.py`;")
    д("* `coss3_llm.log` — что отвечал провайдер;")
    д("* `game.log`, `install.log` — игра и установка моста.")
    return "\n".join(строки)


def main() -> int:
    p = argparse.ArgumentParser(description="документ по одному прогону")
    p.add_argument("io", help="каталог прогона (в контейнере /io)")
    p.add_argument("--out", default="", help="куда записать; без него — на экран")
    a = p.parse_args()
    т = отчёт(a.io)
    if a.out:
        with open(a.out, "w", encoding="utf-8") as f:
            f.write(т + "\n")
        print(f"отчёт: {a.out}")
    else:
        print(т)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
