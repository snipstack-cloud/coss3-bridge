import collections, json, os, sys
К = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, К); sys.path.insert(0, os.path.join(К, "sim"))
import strategy_live as SL
import поиск_стратегии as ПС
ок, пало = 0, []
def проверить(что, имя):
    global ок
    ок += 1 if что else 0
    print(("ОК   " if что else "ОШИБКА ") + имя)
    if not что: пало.append(имя)
ФАЙЛ = os.path.join(К, "sim", "поиск", "польша_судья_по_врагу.json")
_п = json.load(open(ФАЙЛ, encoding="utf-8"))["итог"]
_st = {"gametime": 150, "ba17": 1, "academies": 0, "my_officers": 0, "my_drummers": 0, "mil_inf": 4, "mil_shooters": 0, "squads": 0, "squad_units": 0,
       "train_now": "", "враг_слот": 0, "p0_army": 4, "food": 800, "gold": 900, "wood": 400, "stone": 300, "upg_done": "mil.1", "peasants": 24,
       "mines_gold": 0, "on_gold": 0, "mines_iron": 0, "mills": 1, "food_ready": 1, "centers": 1, "houses": 1, "my_farm": 100, "my_farmused": 30,
       "on_food": 6, "on_wood": 8, "on_stone": 6, "on_mine": 0, "on_build": 2, "idle_pea": 0, "iron": 900, "my_stores": 1, "wip": ""}
def такт(доп, st_доп=None, стр=None):
    п = {**_п, **доп}; st = dict(_st, **(st_доп or {}))
    с = стр or ПС.Стратегия(п)
    if стр is None: с(dict(st))
    отд = collections.Counter()
    из = SL.привести([], dict(st), п, с, collections.Counter(), отд)
    return из, с, отд
def стройки(из): return [c.get("role") for c in из if c.get("cmd") == "BUILD"]
def баланс(из): return {c.get("role"): c.get("total") for c in из if c.get("cmd") == "BALANCE"}
проверить(int(_п.get("рубеж_еды", 0)) == 1200, "(0) живой польский файл: рубеж_еды 1200")
# пункт 2/5: до рубежа — ни шахты, ни академии
из1, с1, о1 = такт({})
print("  до рубежа (еда 800):", стройки(из1), [k for k in о1 if "(256)" in k][:2])
проверить("minegold" not in стройки(из1) and "academi" not in стройки(из1), "(1) еда 800 < 1200 — шахты и академии нет (только крестьяне и пика)")
проверить(any("ждёт — только крестьяне и пика" in k for k in о1), "(1б) вслух: что ждёт")
# пункт 4: поле созрело — все на еду
б1 = баланс(из1)
проверить(б1.get("food") == 22 and б1.get("wood") == 0 and б1.get("stone") == 0, f"(2) поле созрело, рубеж не взят — все на еду: {б1} (земля 22 = 24 − 2 строителей)")
из1б, _, _ = такт({"рубеж_бригада": 4})
проверить(баланс(из1б).get("food") == 18 and баланс(из1б).get("wood") == 2 and баланс(из1б).get("stone") == 2, f"(2б) рубеж_бригада 4 — 2 на дерево, 2 на камень: {баланс(из1б)}")
из1в, _, _ = такт({}, {"food_ready": 0})
проверить(баланс(из1в).get("food") != 22, f"(2в) поле не созрело — прежние правила ({баланс(из1в)})")
# пункт 5: рубеж взят — первая золотая первой
из2, с2, о2 = такт({}, {"food": 1300})
print("  рубеж взят (еда 1300):", стройки(из2), [k for k in о2 if "(256)" in k][:2])
проверить("minegold" in стройки(из2), "(3) еда 1300 ≥ 1200 — первая золотая первой закладкой")
из3, _, _ = такт({}, {"food": 900, "gametime": 200}, с2)
проверить("minegold" in стройки(из3), "(3б) рубеж пройден навсегда: еда снова 900 — золотая всё равно идёт")
из3в, _, _ = такт({}, {"food": 900, "gametime": 200, "mines_gold": 1, "on_gold": 5}, с2)
проверить(not any("первая золотая" in k for k in такт({}, {"food": 900, "gametime": 200, "mines_gold": 1, "on_gold": 5}, с2)[2]), "(3в) золотая есть — правило больше не вмешивается (дальше по плану)")
# страховка по сроку
из4, с4, о4 = такт({}, {"food": 700, "gametime": 430})
проверить(getattr(с4, "_рубеж_пройден_gt", None) is not None and not any("все на еду" in k for k in о4) and not any("ждёт — только" in k for k in о4),
          "(4) к 7:00 рубеж не взят — фаза снята по сроку (вслух при первом проходе), прежние правила")
# ключ 0 — как было
из5, _, о5 = такт({"рубеж_еды": 0})
проверить(not any("(256)" in k for k in о5), "(5) рубеж_еды 0 — правило молчит")
print(f"selftest_рубеж_еды: {ок} из {ок + len(пало)}")
