def _клетка(st: dict, x: float, z: float) -> tuple:
    """Мировые координаты → клетка сетки 16x16, той же, что в `ocells` и `ecells`."""
    ш = float(st.get("map_w") or 256) / 16.0
    в = float(st.get("map_h") or 256) / 16.0
    return (max(0, min(15, int(float(x) // ш))), max(0, min(15, int(float(z) // в))))


def _список(st: dict, ключ: str, разбор):
    """Поле клеток или зданий СПИСКОМ, как бы оно ни пришло.

    Куплено живой игрой 3.10 (`smoke_net/1`): в ЧАСТОМ СНИМКЕ эти поля уже списки
    словарей, а в ЖИВОМ СОСТОЯНИИ — строки вида «x,y,...;...». Я написал обход по
    `st.get("obuild")` напрямую — и в партии на каждом внутреннем приказе получал
    `AttributeError: 'str' object has no attribute 'get'`: строка обходится по
    символам. Такт при этом не пропадал (ловится «стратегия упала, запасная»), то
    есть ошибка была ТИХОЙ. Разбор — тот же, которым пользуется весь проект
    (`coss3_map`), а не свой.
    """
    v = st.get(ключ)
    if isinstance(v, list):
        return [c for c in v if isinstance(c, dict)]
    try:
        import coss3_map
        return разбор(st)
    except Exception:
        return []


def _группы(st: dict) -> list:
    """Наши группы с номерами из состояния — тем же разбором, что и весь проект."""
    import coss3_map
    v = st.get("groups")
    if isinstance(v, list):
        return [г for г in v if isinstance(г, dict)]
    try:
        return coss3_map.наши_группы(st)
    except Exception:
        return []


def _дом(st: dict) -> tuple:
    """Клетка нашей ратуши. Берётся из `obuild` — там наши здания с координатами."""
    import coss3_map
    for b in _список(st, "obuild", coss3_map.наши_здания):
        if str(b.get("тип") or "") == "center":
            return _клетка(st, b.get("x") or 0, b.get("z") or 0)
    return (8, 8)


def _в_мостовые(c: dict, cmd: str, st: dict):
    """Внутренний приказ симулятора → мостовой, или None, если мост так не умеет.

    ЧТО УМЕЕТ ИГРА, проверено по блоку (`block_hcmd.inc`, ветка файла приказа). Отбор
    бойцов и назначение блок читает ПОРОЗНЬ: `retreat` и `engage` берут всех дальше 60
    от ратуши, чем бы они ни были заняты (волну в поле, раненых — всех), а цель `cell`
    ведёт их в центр названной клетки. Отсюда:

    * `_К_СВОИМ` -> RETREAT в клетку ближайшей своей кучи (ходом БЕЗ боя). Если ближайшая
      своя — дом, это обычный RETREAT домой, как и в симуляторе;
    * `_СТОЙ`    -> RETREAT в клетку, где волна СТОИТ СЕЙЧАС. Это ПРИБЛИЖЕНИЕ: бойцы
      дойдут до центра своей клетки и встанут, а не замрут на месте. Точного «стоять»
      у моста нет — для него нужен блок (`_squad_holdmode` либо обнуление приказа);
    * `_ВПЕРЁД` -> ENGAGE на ту же цель: отменяет отход и разворачивает в бой;
    * `_ОТРЯД`  -> RETREAT долей бойцов в клетку `aim` (отделение части волны).

    ЧЕМ ЭТО ОТЛИЧАЕТСЯ ОТ СИМУЛЯТОРА, и это надо знать до разбора: симулятор водит
    ГРУППАМИ и выбирает, какая именно идёт (`_К_СВОИМ` берёт самую дальнюю от дома,
    `_ОТРЯД` — самую большую). Мост групп не различает: он берёт ПЕРВЫХ `count` бойцов
    дальше 60 от ратуши в порядке движка. Поэтому при одной куче в поле поведение
    совпадает, а при двух и больше приказ может достаться не той.
    """
    import coss3_map
    кучи = [k for k in _список(st, "ocells", coss3_map.наши_клетки)
            if int(k.get("n") or 0) > 0]
    дом = _дом(st)
    поле = [k for k in кучи if (int(k.get("x") or 0), int(k.get("y") or 0)) != дом]
    # «В ПОЛЕ» СЧИТАЕМ ТАК ЖЕ, КАК БЛОК, а не по клеткам. Блок берёт бойцов дальше 60
    # от ратуши (`block_hcmd.inc`), и ровно столько их в поле `mil_away`; клетка же
    # шириной 16, поэтому соседняя с домашней клетка — это ещё не поле. На живых
    # снимках прогона так и выходило: куча из двух бойцов в соседней клетке при
    # `mil_away = 0`. Без этой проверки приказ уехал бы и получил отказ «дальше 60
    # никого нет» — отказ честный, но приказ бессмысленный, а §51 требует гасить
    # такие до отправки.
    вдали = int(float(st.get("mil_away") or 0))
    if вдали <= 0:
        return None
    if cmd == "_ВПЕРЁД":
        цель = str(c.get("target") or "army")
        из = {"cmd": "ENGAGE", "count": 200, "target": цель}
        aim = c.get("aim")
        if цель == "cell" and isinstance(aim, (list, tuple)) and len(aim) >= 2:
            из.update(cx=int(aim[0]), cy=int(aim[1]))
        elif цель == "cell":
            return None
        return из
    if cmd == "_НА_КЛЕТКУ":
        # Все, кто в поле, — на клетку, В БОЙ (решение сети «на_меньшую»: идти на меньшую
        # его кучу). Та же дорога, что у `_ВПЕРЁД`, только цель названа клеткой.
        aim = c.get("aim")
        if not поле or not isinstance(aim, (list, tuple)) or len(aim) < 2:
            return None
        return {"cmd": "ENGAGE", "count": 200, "target": "cell",
                "cx": int(aim[0]), "cy": int(aim[1])}
    if cmd == "_К_СВОИМ":
        # ЕСЛИ У НАС ЕСТЬ НОМЕРНЫЕ ГРУППЫ — идём к своим АДРЕСНО и сливаемся
        # (цель `group`, 4.10). Это точнее клетки: группа-получатель может
        # сдвинуться, и тогда клетка приведёт в опустевшее место — именно это
        # случилось в живой партии 4.10 с первым приказом слияния. Повторять
        # приказ, пока клетки не совпадут, умеет `ЖиваяСтратегия.ответ`.
        группы = [г for г in _группы(st) if int(г.get("n") or 0) > 0]
        if len(группы) >= 2:
            гол = max(группы, key=lambda г: (int(г["cx"]) - дом[0]) ** 2
                      + (int(г["cy"]) - дом[1]) ** 2)
            прочие = [г for г in группы if г is not гол]
            цель = min(прочие, key=lambda г: (int(г["cx"]) - int(гол["cx"])) ** 2
                       + (int(г["cy"]) - int(гол["cy"])) ** 2)
            if (int(гол["cx"]), int(гол["cy"])) != (int(цель["cx"]), int(цель["cy"])):
                return {"cmd": "RETREAT", "count": 0, "target": "group",
                        "group": int(гол["id"]), "gid": int(цель["id"])}
            return None            # уже в одной клетке: слиёт блок состояния
        if not поле:
            return None            # волны в поле нет — приказ бессмысленный, §51
        голова = max(поле, key=lambda k: (int(k["x"]) - дом[0]) ** 2 + (int(k["y"]) - дом[1]) ** 2)
        свои = [k for k in кучи if k is not голова]
        if not свои:
            return None
        к = min(свои, key=lambda k: (int(k["x"]) - int(голова["x"])) ** 2
                + (int(k["y"]) - int(голова["y"])) ** 2)
        цx, цy = int(к["x"]), int(к["y"])
        счёт = max(1, min(вдали, int(голова.get("n") or 1)))
        if (цx, цy) == дом:
            return {"cmd": "RETREAT", "count": счёт}      # ближайшая своя — дом
        return {"cmd": "RETREAT", "count": счёт, "target": "cell", "cx": цx, "cy": цy}
    if cmd == "_СТОЙ":
        if not поле:
            return None
        большая = max(поле, key=lambda k: int(k.get("n") or 0))
        return {"cmd": "RETREAT", "count": max(1, min(вдали, int(большая.get("n") or 1))),
                "target": "cell", "cx": int(большая["x"]), "cy": int(большая["y"])}
    if cmd == "_ОТРЯД":
        aim = c.get("aim")
        if not поле or not isinstance(aim, (list, tuple)) or len(aim) < 2:
            return None
        большая = max(поле, key=lambda k: int(k.get("n") or 0))
        доля = min(max(float(c.get("share") or 0.25), 0.05), 0.95)
        счёт = max(1, min(вдали, int(round(int(большая.get("n") or 1) * доля))))
        return {"cmd": "RETREAT", "count": счёт, "target": "cell",
                "cx": int(aim[0]), "cy": int(aim[1])}
    return None


class ЖиваяСтратегия:
    def __init__(self, путь: str, сеть: str = ""):
        with open(путь, encoding="utf-8") as f:
            w = json.load(f)
        self.п = w.get("итог", w)
        # СЕТЬ ТАКТИКА ВОЮЕТ (3.10, §61): волны и тактика стратегии выключаются ровно как в
        # обучении (`sim/тактик.Тактик`), решение о бое раз в 15 с даёт сеть.
        self.сеть = None
        if сеть:
            import tactic_core
            with open(сеть, encoding="utf-8") as f:
                self.сеть = tactic_core.Ядро(json.load(f)["theta"])
            self.имя_сети = os.path.basename(сеть)
            self.п = {k: v for k, v in self.п.items() if k not in ("отход", "подмога", "слабая", "возврат")}
            self.п.update(T1=1e9, T2=1e9, P1=0.0)
            self.решения = collections.Counter()
        self.имя = os.path.basename(путь)
        # Мы — живой мост: приказы волне в поле переводятся в мостовые (`_в_мостовые`).
        globals()["ЖИВОЙ_МОСТ"] = True
        import поиск_стратегии as ПС
        ПС.ПРАВИЛА_ЖИВЫЕ = True          # вживую правила моста действуют всегда
        import debut as _D               # §58: мостовой дебют — тем же порядком, что у стратегии
        _D.ПОРЯДОК_ИГРОКА = bool(self.п.get("дебют_игрока", 0))
        self.стр = ПС.Стратегия(self.п)
        self.n = max(1, int(self.п.get("n", 20)))
        self.пропущено = collections.Counter()
        self.отдано = collections.Counter()
        # КОГО С КЕМ СВОДИМ (4.10). Приказ `target: group` наводится на место
        # получателя В МОМЕНТ ПРИКАЗА и в погоню не ведёт — живая партия 4.10
        # показала это первым же слиянием: получатель шёл, и пославший пришёл в
        # опустевшую клетку. Поэтому приказ ПОВТОРЯЕТСЯ каждый такт, пока клетки
        # не совпадут. Такт — пять игровых секунд, а не каждая секунда: приказ
        # идущей группе каждую секунду это перестроение, от которого волны уже
        # вставали («a unit already marching is left alone... it stalls»,
        # block_hcmd.inc).
        self.сводим = {}

    def ответ(self, st: dict) -> dict:
        """Ответ в форме модели: {"commands": [...], "why": "..."}.

        Правила хозяйства и порядок команд (`привести`) применяет сама `Стратегия` — и в
        симуляторе, и здесь (3.10, §57): поиск оптимизирует ровно то, что исполняется вживую."""
        if not self.стр.я.дебют.готов(st):
            # дебют ведёт мост (`debut.py` той же длины); команды дебюта стратегии — в числовой
            # форме Command и мосту модельным путём непонятны
            return {"commands": [], "why": f"стратегия {self.имя}: ждёт конца дебюта"}
        из = self.стр(st)
        why = f"стратегия {self.имя}: {len(из)} команд"
        из = [_мостовая_цель(c) for c in из]
        if self.сеть is not None:
            # признаки — тем же переводом живого снимка, что у тени (§44); приказ сети — первым
            import shadow_tactic, tactic_core
            с = shadow_tactic.из_моста(st)
            р = self.сеть.решить(с)
            if р is not None:
                имя = tactic_core.РЕШЕНИЯ[р[0]]
                self.решения[имя] += 1
                # ПРИКАЗЫ ВОЛНЕ ОТ СЕТИ ПЕРЕВОДЯТСЯ, А НЕ ОТБРАСЫВАЮТСЯ (3.10). Здесь
                # стояло `if not cmd.startswith("_")`, и это съедало ровно те решения, из-за
                # которых приказы и делались: в прогоне `smoke_net/1` сеть трижды сказала
                # «держать» при волне В ПОЛЕ (540, 572, 680 с), а в игру не ушло ничего —
                # внутренние команды отсекались ДО перевода. Переводим живым состоянием
                # `st`, а не `с`: `_в_мостовые` читает `obuild`, `ocells` и `mil_away`, а
                # `с` — уже пересчитанная в форму симулятора сводка.
                бой = []
                for c in self.сеть.команды(р[0], с, живой=True):
                    cmd = str(c.get("cmd", ""))
                    if cmd.startswith("_"):
                        пер = _в_мостовые(c, cmd, st)
                        if пер is None:
                            self.пропущено[f"сеть: {cmd}"] += 1
                            continue
                        self.пропущено[f"сеть: {cmd} -> {пер['cmd']}"] += 1
                        бой.append(_мостовая_цель(пер))
                        continue
                    бой.append(_мостовая_цель(c))
                if бой:
                    # Приказ сети вытесняет собственные ATTACK/RETREAT стратегии, и ENGAGE
                    # тоже: файл приказа один, двум командам одного рода в такте не уехать.
                    из = бой + [c for c in из
                                if c["cmd"] not in ("ATTACK", "RETREAT", "ENGAGE")]
                    из = из[:ПОТОЛОК_КОМАНД]
                why += f"; сеть {self.имя_сети}: {имя}"
                if self.пропущено:
                    why += " (" + ", ".join(f"{k} ×{v}" for k, v in
                                            self.пропущено.most_common(3)) + ")"
        # ПОВТОР ПРИКАЗА СЛИЯНИЯ. Сам приказ мог прийти этим тактом (тогда он уже
        # в `из`) или тактами раньше; пока клетки разные, его надо повторять, иначе
        # получатель уйдёт, а пославший встанет в пустой клетке.
        # getattr, а не прямое поле: объект иногда собирают через __new__ (так делают
        # проверки), и отсутствие памяти не имеет права ронять такт.
        if not hasattr(self, "сводим"):
            self.сводим = {}
        for c in из:
            if c.get("target") == "group" and c.get("group") and c.get("gid"):
                self.сводим[int(c["group"])] = int(c["gid"])
        if self.сводим:
            места = {int(г["id"]): (int(г["cx"]), int(г["cy"]))
                     for г in _группы(st) if int(г.get("n") or 0) > 0}
            for a in list(self.сводим):
                b = self.сводим[a]
                if a not in места or b not in места or места[a] == места[b]:
                    # слились, дошли или группы больше нет — повторять нечего
                    self.сводим.pop(a, None)
                    continue
                уже = any(c.get("group") == a and c.get("target") == "group" for c in из)
                занят = any(c["cmd"] in ("ATTACK", "RETREAT", "ENGAGE") for c in из)
                if уже or занят:
                    # файл приказа один на такт: повторим следующим, а не затрём бой
                    why += f"; слияние {a}->{b} отложено (приказ такта занят)"
                    break
                из.append({"cmd": "RETREAT", "count": 0, "target": "group",
                           "group": a, "gid": b})
                why += f"; повтор слияния {a}->{b}"
                break
        if self.стр.пропущено:
            why += "; живая игра не умеет: " + ", ".join(f"{k} ×{v}" for k, v in self.стр.пропущено.most_common(4))
        return {"commands": из, "why": why}


def _мостовая_цель(c: dict) -> dict:
    """`peasants_free` есть только в симуляторе (крестьяне без его армии); у моста — `peasants`,
    которая тоже ищет клетку с крестьянами и отбрасывает охраняемые (`клетка_охоты`)."""
    if c.get("cmd") == "ATTACK" and c.get("target") == "peasants_free":
        c = dict(c, target="peasants")
    # клетка: симулятор пишет `aim: [x, y]`, мост ждёт `cx`, `cy` (`to_commands`)
    if c.get("cmd") == "ATTACK" and c.get("target") == "cell" and isinstance(c.get("aim"), (list, tuple)):
        c = dict(c, cx=int(c["aim"][0]), cy=int(c["aim"][1]))
        c.pop("aim", None)
    return c


def _его_база(st: dict):
    v = st.get("en_base")
    if isinstance(v, str):
        v = [x for x in v.replace(";", ",").split(",") if x.strip()]
    try:
        return (int(float(v[0])), int(float(v[1])))
    except (TypeError, ValueError, IndexError):
        return None


def _наша_база(st: dict) -> tuple:
    if st.get("my_cx") is not None and st.get("my_cy") is not None:
        return (int(float(st["my_cx"])), int(float(st["my_cy"])))
    return _дом(st)


def клетка_сбора(st: dict, от_его: int = 4):
    """§74: на прямой от нашей ратуши к его — в `от_его` клетках (Чебышёв) от его ратуши."""
    е, н = _его_база(st), _наша_база(st)
    if е is None:
        return None
    dx, dy = н[0] - е[0], н[1] - е[1]
    d = max(abs(dx), abs(dy))
    if d <= от_его:
        return н
    return (е[0] + round(dx * от_его / d), е[1] + round(dy * от_его / d))


def _сбор(из: list, st: dict, п: dict, стр, пропущено, отдано) -> list:
    """СБОР ВОЛН (4.10, §74; задание Windows в ПЛАН.md). Волну стратегии (ATTACK) мост не
    отдаёт сразу: сперва стоячий STAGE в клетку сбора (4 клетки от его ратуши), и когда там
    `сбор_доля` наших бойцов И (наших не меньше его армии ИЛИ ждём `сбор_ждать` с) — STAGE off и
    ENGAGE на цель волны. Проверка 3: волна входила в его базу кусками 24 → 15+15 → 25 → 29 → 35.
    Общее для симулятора и моста (§57). Выключено, пока у стратегии нет рычага `сбор` ≥ 0,5."""
    if float(п.get("сбор", 0) or 0) < 0.5:
        return из
    t = float(st.get("gametime") or 0)
    с = getattr(стр, "_сбор_сост", None)
    волны = [c for c in из if c.get("cmd") == "ATTACK"]
    из = [c for c in из if c.get("cmd") != "ATTACK"]
    if any(c.get("cmd") == "RETREAT" for c in из):
        return из              # отход стратегии главнее; сбор не сбрасывается — вернувшиеся свободны,
                               # и STAGE снова ведёт их в клетку сбора (перегруппировка)
    if с is None and волны:
        кл = клетка_сбора(st, int(п.get("сбор_клеток", 4)))
        if кл is None:
            return из + волны[:1]
        цель = волны[0].get("target") or "army"
        с = {"клетка": кл, "цель": "army" if цель == "wave" else цель, "aim": волны[0].get("aim"), "t0": None}
        стр._сбор_сост = с
        отдано["STAGE (сбор)"] += 1
        return [{"cmd": "STAGE", "cx": int(кл[0]), "cy": int(кл[1]), "keep": 0}] + из
    if с is None:
        return из
    if волны:
        пропущено["ATTACK -> копим в сборе"] += len(волны)
    кл = с["клетка"]
    собрано = sum(float(c.get("n") or 0) for c in _список(st, "ocells", __import__("coss3_map").наши_клетки)
                  if abs(int(c.get("x", -9)) - кл[0]) <= 1 and abs(int(c.get("y", -9)) - кл[1]) <= 1)
    всего = sum(float(st.get(k) or 0) for k in ("mil_inf", "mil_shooters", "mil_cav"))
    if собрано >= 1 and с["t0"] is None:
        с["t0"] = t
    вс = st.get("враг_слот")
    его = float(st.get(f"p{int(вс)}_army" if вс is not None else "p1_army") or 0)
    ждём = t - с["t0"] if с["t0"] is not None else 0.0
    if всего > 0 and собрано >= float(п.get("сбор_доля", 0.8)) * всего and \
            (собрано >= его or ждём >= float(п.get("сбор_ждать", 120))):
        стр._сбор_сост = None
        # count обязателен: без него мост бракует ENGAGE («нужно число бойцов > 0», selftest_сбор)
        удар = {"cmd": "ENGAGE", "count": 200, "target": с["цель"]}
        if с["цель"] == "cell" and с.get("aim"):
            удар.update(cx=int(с["aim"][0]), cy=int(с["aim"][1]))
        отдано["ENGAGE (сбор)"] += 1
        return [{"cmd": "STAGE", "off": 1}, удар] + из
    return из


def _сзади(из: list, st: dict, п: dict, стр, пропущено, отдано) -> list:
    """СТРЕЛКИ ПОЗАДИ ВОЛНЫ (4.10, §87) — прикрытие §82 на НЫНЕШНЕМ блоке, без правок: пока волна в поле,
    через такт стрелки получают RETREAT who=musk17 в клетку на шаг от волны к нашей базе. RETREAT берёт
    бойцов дальше 60 от ратуши (идущих тоже), `who` — род, цель-клетка — ход без боя; там они стоят без
    приказа и, по замеру §82, бьют из соседней клетки. Одна команда волне за такт — поэтому в такты без
    своего ATTACK/RETREAT/ENGAGE. Проверка 4: стрелки шли с волной под приказом — 2 убитых на 12 своих."""
    if float(п.get("мушк_сзади", 0) or 0) < 0.5:
        return из
    стр._сзади_такт = not getattr(стр, "_сзади_такт", False)
    if not стр._сзади_такт or any(c.get("cmd") in ("ATTACK", "RETREAT", "ENGAGE", "MOVE", "STAGE") for c in из):
        return из
    if float(st.get("mil_shooters") or 0) < 3 or float(st.get("wave_n") or 0) < 5 or st.get("wave_cx") is None:
        return из
    wx, wy = int(float(st["wave_cx"])), int(float(st["wave_cy"]))
    нx, нy = _наша_база(st)
    кл = (wx + (нx > wx) - (нx < wx), wy + (нy > wy) - (нy < wy))
    отдано["RETREAT стрелков позади (§87)"] += 1
    # `target: cell` обязателен: без него разбор моста ставит цель base и клетку (-1,-1) — проверено to_commands
    return [{"cmd": "RETREAT", "count": 200, "who": "musk17", "target": "cell", "cx": int(кл[0]), "cy": int(кл[1])}] + из


def привести(сырые: list, st: dict, п: dict, стр, пропущено, отдано) -> list:
    """Команды стратегии → то, что уходит в игру за такт (3.10, §57; общее для симулятора и моста).

    Внутренние команды симулятора (`_ЗАПАС`, `_ВПЕРЁД`, …) отбрасываются — мост их не умеет, и
    симулятор не должен на них рассчитывать; одна волна за такт; доли еды/дерева/камня от людей
    на земле; золото и железо явно; одна закладка за такт; порядок и потолок."""
    из, атака = [], False
    for c in сырые:
        cmd = str(c.get("cmd") or "")
        if cmd.startswith("_"):
            # ЧЕТЫРЕ ПРИКАЗА ВОЛНЕ В ПОЛЕ (3.10, задание игрока) переводятся в мостовые,
            # а не отбрасываются — но ТОЛЬКО на живом мосте: симулятор исполняет их сам и
            # точнее (`sim.py`, `_К_СВОИМ` сводит две группы навстречу), а здесь они
            # становятся тем, что игра действительно умеет. Что именно умеет и чем это
            # отличается от симулятора — в `_в_мостовые`, и то же говорится вслух в `why`.
            переведено = _в_мостовые(c, cmd, st) if ЖИВОЙ_МОСТ else None
            if переведено is None:
                пропущено[cmd] += 1
                continue
            пропущено[f"{cmd} -> {переведено['cmd']}"] += 1
            отдано[переведено["cmd"]] += 1
            из.append(переведено)
            continue
        c = dict(c)
        if cmd == "UPGRADE" and "upg" in c:
            c["role"] = c.pop("upg")
        if cmd == "RETREAT":
            c.setdefault("count", 200)
        if cmd == "ATTACK":
            if атака:                      # одна волна за такт — первая по порядку стратегии
                пропущено["ATTACK второй за такт"] += 1
                continue
            атака = True
        отдано[cmd] += 1
        из.append(c)
    из = _сбор(из, st, п, стр, пропущено, отдано)
    из = _сзади(из, st, п, стр, пропущено, отдано)
    # ЕДА И ЗОЛОТО ЯВНО (3.10, контейнер Windows `smoke_strategy/1`: стратегия ни разу не дала
    # BALANCE food — еда 993 -> 0 к 2:33, крестьян 18 -> 3). Ярус 1 шлёт на еду только
    # ПРОСТАИВАЮЩИХ (4 и больше) — в симуляторе их много, вживую почти нет, а мостовой дебют
    # короткий (n бойцов) и кончается раньше созревания поля. Здесь доля еды из стратегии
    # (`еда_до` до 7:00, `еда_после` после) и 5 на шахту золота выставляются каждый такт.
    gt = float(st.get("gametime") or 0)
    крест = float(st.get("peasants") or 0)
    доля = float(п.get("еда_до", 2 / 3)) if gt < 420 else float(п.get("еда_после", 1 / 3))
    # ДОЛИ ОТ ЛЮДЕЙ НА ЗЕМЛЕ (3.10, третий прогон: на еде 9 из 35 при цели 17 — 20 человек в
    # шахтах, на земле 15, а еда+дерево+камень просили 29, и мост резал все три
    # пропорционально, `llm_policy.распределить_balance`). Земля — как у моста: крестьяне
    # минус шахтёры минус строители. Еда первой (доля деревни, но не больше земли), дерево и
    # камень — из остатка; сумма не превышает землю, и мосту резать нечего.
    земля = max(0, int(крест - float(st.get("on_mine") or 0) - float(st.get("on_build") or 0)))
    # 3.10 (§64, контейнер smoke_net): «еда первой» отдавала еде всю землю — с 4:00 до 7:00 на
    # дереве и камне 0-3 человека, камня 20, вторая шахта золота к 9:00, вторая казарма к 11:30,
    # а еды к 10:00 лежало 5 тысяч без дела. Теперь сперва МИНИМУМ дерева и камня стратегии
    # (ярус 1 так и задуман: «держать на дереве не меньше стольких»), еде — остальное.
    # `COSS3_WOOD_FIRST=0` — как было.
    # …но только когда еды запасено (`ЗАПАС_ЕДЫ_ДЕРЕВУ`, 1000): без порога «дерево первым» в
    # начале снимало с еды всех, и деревня гибла (симулятор: армия к 10:00 — 4)
    # рычаг стратегии `дерево_при_еде` (§65) — порог запаса еды; от 5900 — никогда (как «еда
    # первой»); без рычага — выключатель окружения, как раньше
    порог = п.get("дерево_при_еде")
    if порог is not None:
        дерево_первым = float(порог) < 5900 and float(st.get("food") or 0) >= float(порог)
    else:
        дерево_первым = ДЕРЕВО_ПЕРВЫМ and float(st.get("food") or 0) >= ЗАПАС_ЕДЫ_ДЕРЕВУ
    мин_дер = мин_кам = 0
    if дерево_первым:
        мин_дер = min(int(п.get("дерево", 0)), земля)
        мин_кам = min(int(п.get("камень", 0)), земля - мин_дер)
        цель_еды = max(0, min(int(крест * доля), земля - мин_дер - мин_кам))
    else:
        цель_еды = min(int(крест * доля), земля)
    if float(st.get("mills") or 0) >= 1 and float(st.get("on_food") or 0) < цель_еды - 1:
        из = [c for c in из if not (c["cmd"] == "BALANCE" and c.get("role") == "food")]
        из.append({"cmd": "BALANCE", "role": "food", "total": цель_еды, "_важно": True})
        отдано["BALANCE food (переходник)"] += 1
    остаток = земля - (цель_еды if float(st.get("mills") or 0) >= 1 else 0)
    for роль in ("wood", "stone"):
        for c in из:
            if c["cmd"] == "BALANCE" and c.get("role") == роль:
                c["total"] = max(0, min(int(c.get("total") or 0), остаток))
        остаток -= min(int(п.get({"wood": "дерево", "stone": "камень"}[роль], 0)), max(остаток, 0))
    из = [c for c in из if not (c["cmd"] == "BALANCE" and c.get("role") in ("wood", "stone") and c["total"] <= 0)]
    if дерево_первым:
        for роль, ключ, мин in (("wood", "on_wood", мин_дер), ("stone", "on_stone", мин_кам)):
            if мин > 0 and float(st.get(ключ) or 0) < мин and not any(c["cmd"] == "BALANCE" and c.get("role") == роль for c in из):
                из.append({"cmd": "BALANCE", "role": роль, "total": мин, "_важно": True})
    # СТРОЙКА ЯВНО (3.10, контейнер `smoke_strategy` второй прогон: армия встала на 17 — железо
    # кончилось к 4:57, шахты железа не было ни одной; вторая казарма и шахты золота 2-3 тоже
    # не встали). Ярус 1 ставит закладку, только пока ничего не строится, а стратегия каждый
    # такт просит академию — вживую что-то строится всегда; и потолок 7 срезал стройки в
    # хвосте списка. Здесь — ОДНА закладка за такт, самая нужная по порядку: шахта железа →
    # шахта золота → казармы → дом → академия. BUILD декларативный (total — сколько должно
    # стоять), повтор безопасен.
    из = [c for c in из if c["cmd"] not in ("BUILD", "BUILDERS")]
    def ч(k):
        return float(st.get(k) or 0)
    есть_дер_кам = ч("wood") >= 100 and ч("stone") >= 100
    закладка = None
    if ч("ba17") >= 1 and ч("mines_iron") < 1 and есть_дер_кам:
        закладка = ("mineiron", 1)
    elif (ч("mines_gold") < int(п.get("шахт_золота", 2)) and ч("on_gold") >= 5 * ч("mines_gold") - 1
          and есть_дер_кам):
        закладка = ("minegold", int(ч("mines_gold")) + 1)
    elif ч("ba17") >= 1 and ч("ba17") < int(п.get("казарм", 1)):
        закладка = ("ba17", int(ч("ba17")) + 1)
    elif ч("my_farm") - ч("my_farmused") <= 5 and есть_дер_кам:
        закладка = ("house", int(ч("houses")) + 1)
    elif стр.академия and ч("ba17") >= 1 and ч("academies") < 1 and gt >= getattr(стр, "академия_с", 0):
        закладка = ("academi", 1)
    if закладка:
        из += [{"cmd": "BUILDERS", "total": 5}, {"cmd": "BUILD", "role": закладка[0], "total": закладка[1]}]
        отдано[f"BUILD {закладка[0]} (переходник)"] += 1
    if ч("mines_iron") >= 1 and ч("on_iron") < 5:
        из = [c for c in из if not (c["cmd"] == "BALANCE" and c.get("role") == "iron")]
        из.append({"cmd": "BALANCE", "role": "iron", "total": 5, "_важно": True})
    шахт = float(st.get("mines_gold") or 0)
    if шахт >= 1 and float(st.get("on_gold") or 0) < 5 * шахт:
        из = [c for c in из if not (c["cmd"] == "BALANCE" and c.get("role") == "gold")]
        из.append({"cmd": "BALANCE", "role": "gold", "total": int(5 * шахт), "_важно": True})
    # ПОТОЛОК КОМАНД ЗА ТАКТ — 12 (решение игрока 3.10). Порядок всё равно нужен:
    # волна и прокачки — вперёд, затем стройка (BUILDERS сразу перед своим BUILD),
    # найм, люди; повтор BALANCE по ресурсу — последний.
    #
    # Семь стояло как «мост читает не больше семи», и это ОКАЗАЛОСЬ НЕВЕРНО: предела в
    # семь нет ни в python (`coss3_bridge.send` пишет `count` и столько пар, сколько
    # дали), ни в блоке (`block_hcmd.inc:84,91` — `for hcn := 0 to hccount-1`). Семь
    # живёт только в тексте промпта для МОДЕЛИ (`llm_policy.py:346`), а стратегия
    # моделью не идёт. Чего семь стоило, измерено контейнером 3.10: после того как
    # встала академия (749 с), стратегия просит по семь `aca.*` за такт, вес UPGRADE
    # равен 1, и в окно не проходило НИЧЕГО — ни еды, ни найма, ни стройки в 89 тактах
    # подряд (срезано 1032 команды), а между 7:00 и 12:30 еда доходила в 8 тактах из 64.
    пары, прочее = [], []
    for i, c in enumerate(из):
        if c["cmd"] == "BUILD":
            пред = из[i - 1] if i and из[i - 1]["cmd"] == "BUILDERS" else None
            пары.append([пред, c] if пред else [c])
        elif c["cmd"] != "BUILDERS":
            прочее.append(c)
    вес = {"ATTACK": 0, "RETREAT": 0, "STAGE": 0, "ENGAGE": 0, "UPGRADE": 1, "FORMATION": 1, "SEED": 3, "TRAIN": 4, "BALANCE": 5}
    балансы = {}
    for c in прочее:
        if c["cmd"] == "BALANCE":
            балансы[c.get("role")] = c
    прочее = [c for c in прочее if c["cmd"] != "BALANCE"] + list(балансы.values())
    прочее.sort(key=lambda c: вес.get(c["cmd"], 6))
    важные = [c for c in прочее if c.get("_важно")]
    прочее = [c for c in прочее if not c.get("_важно")]
    for c in важные:
        c.pop("_важно", None)
    # еда и золото — сразу после волны и прокачек, раньше строек: их не срезает потолок
    из = [c for c in прочее if вес.get(c["cmd"], 6) <= 1] + важные + [x for пара in пары for x in пара] + \
        [c for c in прочее if вес.get(c["cmd"], 6) > 1]
    if len(из) > ПОТОЛОК_КОМАНД:
        пропущено[f"сверх {ПОТОЛОК_КОМАНД} команд"] += len(из) - ПОТОЛОК_КОМАНД
        из = из[:ПОТОЛОК_КОМАНД]
    return из
