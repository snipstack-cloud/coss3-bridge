def _клетки_крестьян(st: dict, его_кл: list) -> list:
    """Его крестьяне по клеткам: живое поле `en_pea_cells` [{x, y, крестьян, бойцов_рядом}], иначе сетка `prow0..15`
    (симулятор), охрана — его бойцы в 1 клетке по `ecells`. Общее для правила ручейка (§113)."""
    v = st.get("en_pea_cells")
    if isinstance(v, list) and v:
        return [q for q in v if isinstance(q, dict)]
    import coss3_map
    из = []
    for y in range(16):
        ряд = st.get(f"prow{y}")
        if not isinstance(ряд, str):
            continue
        for x, ch in enumerate(ряд):
            n = coss3_map.счёт(ch) if ch != "+" else 62
            if n >= 1:
                охр = sum(int(c.get("n") or 0) for c in его_кл if max(abs(int(c["x"]) - x), abs(int(c["y"]) - y)) <= 1)
                из.append(dict(x=x, y=y, крестьян=n, бойцов_рядом=охр))
    return из


def _наша_база(st: dict) -> tuple:
    if st.get("my_cx") is not None and st.get("my_cy") is not None:
        return (int(float(st["my_cx"])), int(float(st["my_cy"])))
    return _дом(st)


def клетка_сбора(st: dict, от_его: int = 4):
    """§74: на прямой от нашей ратуши к его — в `от_его` клетках (Чебышёв) от его ратуши."""
    е, н = _его_база(st), _наша_база(st)
    if е is None:
        return None
    dx, dy = н[0] - е[0], н[1] - е[1]
    d = max(abs(dx), abs(dy))
    if d <= от_его:
        return н
    return (е[0] + round(dx * от_его / d), е[1] + round(dy * от_его / d))


def _сбор(из: list, st: dict, п: dict, стр, пропущено, отдано) -> list:
    """СБОР ВОЛН (4.10, §74; задание Windows в ПЛАН.md). Волну стратегии (ATTACK) мост не
    отдаёт сразу: сперва стоячий STAGE в клетку сбора (4 клетки от его ратуши), и когда там
    `сбор_доля` наших бойцов И (наших не меньше его армии ИЛИ ждём `сбор_ждать` с) — STAGE off и
    ENGAGE на цель волны. Проверка 3: волна входила в его базу кусками 24 → 15+15 → 25 → 29 → 35.
    Общее для симулятора и моста (§57). Выключено, пока у стратегии нет рычага `сбор` ≥ 0,5."""
    if float(п.get("сбор", 0) or 0) < 0.5:
        return из
    t = float(st.get("gametime") or 0)
    с = getattr(стр, "_сбор_сост", None)
    волны = [c for c in из if c.get("cmd") == "ATTACK"]
    из = [c for c in из if c.get("cmd") != "ATTACK"]
    if any(c.get("cmd") == "RETREAT" for c in из):
        return из              # отход стратегии главнее; сбор не сбрасывается — вернувшиеся свободны,
                               # и STAGE снова ведёт их в клетку сбора (перегруппировка)
    if с is None and волны:
        кл = клетка_сбора(st, int(п.get("сбор_клеток", 4)))
        if кл is None:
            return из + волны[:1]
        цель = волны[0].get("target") or "army"
        с = {"клетка": кл, "цель": "army" if цель == "wave" else цель, "aim": волны[0].get("aim"), "t0": None}
        стр._сбор_сост = с
        отдано["STAGE (сбор)"] += 1
        return [{"cmd": "STAGE", "cx": int(кл[0]), "cy": int(кл[1]), "keep": 0}] + из
    if с is None:
        return из
    if волны:
        пропущено["ATTACK -> копим в сборе"] += len(волны)
    кл = с["клетка"]
    собрано = sum(float(c.get("n") or 0) for c in _список(st, "ocells", __import__("coss3_map").наши_клетки)
                  if abs(int(c.get("x", -9)) - кл[0]) <= 1 and abs(int(c.get("y", -9)) - кл[1]) <= 1)
    всего = sum(float(st.get(k) or 0) for k in ("mil_inf", "mil_shooters", "mil_cav"))
    if собрано >= 1 and с["t0"] is None:
        с["t0"] = t
    вс = st.get("враг_слот")
    его = float(st.get(f"p{int(вс)}_army" if вс is not None else "p1_army") or 0)
    ждём = t - с["t0"] if с["t0"] is not None else 0.0
    if всего > 0 and собрано >= float(п.get("сбор_доля", 0.8)) * всего and \
            (собрано >= его or ждём >= float(п.get("сбор_ждать", 120))):
        стр._сбор_сост = None
        # count обязателен: без него мост бракует ENGAGE («нужно число бойцов > 0», selftest_сбор)
        удар = {"cmd": "ENGAGE", "count": 200, "target": с["цель"]}
        if с["цель"] == "cell" and с.get("aim"):
            удар.update(cx=int(с["aim"][0]), cy=int(с["aim"][1]))
        отдано["ENGAGE (сбор)"] += 1
        return [{"cmd": "STAGE", "off": 1}, удар] + из
    return из


def _сзади(из: list, st: dict, п: dict, стр, пропущено, отдано) -> list:
    """СТРЕЛКИ ПОЗАДИ ВОЛНЫ (4.10, §87) — прикрытие §82 на НЫНЕШНЕМ блоке, без правок: пока волна в поле,
    через такт стрелки получают RETREAT who=musk17 в клетку на шаг от волны к нашей базе. RETREAT берёт
    бойцов дальше одной клетки от ратуши (идущих тоже), `who` — род, цель-клетка — ход без боя; там они стоят без
    приказа и, по замеру §82, бьют из соседней клетки. Одна команда волне за такт — поэтому в такты без
    своего ATTACK/RETREAT/ENGAGE. Проверка 4: стрелки шли с волной под приказом — 2 убитых на 12 своих."""
    if float(п.get("мушк_сзади", 0) or 0) < 0.5:
        return из
    стр._сзади_такт = not getattr(стр, "_сзади_такт", False)
    if not стр._сзади_такт or any(c.get("cmd") in ("ATTACK", "RETREAT", "ENGAGE", "MOVE", "STAGE") for c in из):
        return из
    if float(st.get("mil_shooters") or 0) < 3 or float(st.get("wave_n") or 0) < 5 or st.get("wave_cx") is None:
        return из
    wx, wy = int(float(st["wave_cx"])), int(float(st["wave_cy"]))
    нx, нy = _наша_база(st)
    кл = (wx + (нx > wx) - (нx < wx), wy + (нy > wy) - (нy < wy))
    отдано["RETREAT стрелков позади (§87)"] += 1
    # `target: cell` обязателен: без него разбор моста ставит цель base и клетку (-1,-1) — проверено to_commands
    return [{"cmd": "RETREAT", "count": 200, "who": "musk17", "target": "cell", "cx": int(кл[0]), "cy": int(кл[1])}] + из


def _шаг_к(откуда: tuple, куда: tuple, шагов: int = 1) -> tuple:
    x, y = откуда
    for _ in range(шагов):
        x += (куда[0] > x) - (куда[0] < x)
        y += (куда[1] > y) - (куда[1] < y)
    return (int(x), int(y))


def _прикрытие(из: list, st: dict, п: dict, стр, пропущено, отдано) -> list:
    """ПРИКРЫТИЕ (4.10, §93; манёвр §82 второй сессии — «пики бьют, стрелки позади», +9…+14 из 100 в
    эпизодах). Волна стратегии уходит ДВУМЯ группами: пики — её ATTACK (`who=infantry17`), стрелки —
    отдельный ATTACK в клетку на два шага от нашей ратуши к нему (два ATTACK за такт мост возит).
    Дальше в такты без своего ATTACK группе стрелков — RETREAT по номеру в клетку на шаг позади
    пикинёров (ход без боя; бьют из соседней клетки, §82). Через такт подмога «к волне» уступает
    место этому приказу: пару ATTACK + RETREAT группе мост в один файл пока не кладёт."""
    if float(п.get("прикрытие", 0) or 0) < 0.5:
        return из
    дом = _наша_база(st)
    его = _его_база(st) or дом
    if float(st.get("mil_shooters") or 0) >= 3:
        новые = []
        for c in из:
            if (c.get("cmd") == "ATTACK" and c.get("target") not in ("wave", "home") and not c.get("who")
                    and not c.get("group") and str(c.get("count")) not in ("0", "0.0")):
                кл = _шаг_к(дом, его, 2)
                новые.append(dict(c, who="infantry17"))
                новые.append({"cmd": "ATTACK", "count": "all", "who": "musk17", "target": "cell",
                              "cx": кл[0], "cy": кл[1]})
                отдано["ATTACK стрелков прикрытием (§93)"] += 1
                continue
            новые.append(c)
        из = новые
    # подтянуть стрелков за пикинёрами
    группы = [г for г in _группы(st) if int(г.get("n") or 0) > 0 and (int(г["cx"]), int(г["cy"])) != дом]
    пики = [г for г in группы if int(г.get("пик") or 0) >= int(г.get("стрелков") or 0) and int(г["n"]) >= 5]
    стрелки = [г for г in группы if int(г.get("стрелков") or 0) > int(г.get("пик") or 0) and int(г["n"]) >= 3]
    if not (пики and стрелки):
        return из
    P = max(пики, key=lambda г: int(г["n"]))
    M = max(стрелки, key=lambda г: int(г["n"]))
    цель = _шаг_к((int(P["cx"]), int(P["cy"])), дом, 1)
    if (int(M["cx"]), int(M["cy"])) == цель:
        return из
    стр._прикр_такт = not getattr(стр, "_прикр_такт", False)
    атаки = [c for c in из if c.get("cmd") in ("ATTACK", "RETREAT", "ENGAGE")]
    if атаки and not (стр._прикр_такт and all(c.get("cmd") == "ATTACK" and c.get("target") == "wave" for c in атаки)):
        return из
    if атаки:
        пропущено["подмога уступила такт прикрытию"] += 1
        из = [c for c in из if c not in атаки]
    отдано["RETREAT стрелков за пиками (§93)"] += 1
    return [{"cmd": "RETREAT", "count": 0, "group": int(M["id"]), "target": "cell",
             "cx": цель[0], "cy": цель[1]}] + из


def _цена_здания(st: dict, роль: str) -> dict:
    """{ресурс: цена} следующей постройки `роль` из `build_cost` состояния (вживую; в двойнике поля нет — {})."""
    for кусок in str(st.get("build_cost") or "").split():
        имя, _, хвост = кусок.partition("=")
        if имя != роль:
            continue
        цена = {}
        for поле in хвост.split(","):
            буквы = поле.rstrip("0123456789")
            цифры = поле[len(буквы):]
            if буквы and цифры.isdigit() and int(цифры) > 0:
                цена[буквы] = int(цифры)
        return цена
    return {}


def привести(сырые: list, st: dict, п: dict, стр, пропущено, отдано) -> list:
    """Команды стратегии → то, что уходит в игру за такт (3.10, §57; общее для симулятора и моста).

    Внутренние команды симулятора (`_ЗАПАС`, `_ВПЕРЁД`, …) отбрасываются — мост их не умеет, и
    симулятор не должен на них рассчитывать; одна волна за такт; доли еды/дерева/камня от людей
    на земле; золото и железо явно; одна закладка за такт; порядок и потолок."""
    из, атака = [], 0
    for c in сырые:
        cmd = str(c.get("cmd") or "")
        if cmd.startswith("_"):
            # ЧЕТЫРЕ ПРИКАЗА ВОЛНЕ В ПОЛЕ (3.10, задание игрока) переводятся в мостовые,
            # а не отбрасываются — но ТОЛЬКО на живом мосте: симулятор исполняет их сам и
            # точнее (`sim.py`, `_К_СВОИМ` сводит две группы навстречу), а здесь они
            # становятся тем, что игра действительно умеет. Что именно умеет и чем это
            # отличается от симулятора — в `_в_мостовые`, и то же говорится вслух в `why`.
            переведено = _лицом_к_врагу(
                _в_мостовые(c, cmd, st), st) if ЖИВОЙ_МОСТ else None
            if переведено is None:
                пропущено[cmd] += 1
                continue
            пропущено[f"{cmd} -> {переведено['cmd']}"] += 1
            отдано[переведено["cmd"]] += 1
            из.append(переведено)
            continue
        c = dict(c)
        if cmd == "UPGRADE" and "upg" in c:
            c["role"] = c.pop("upg")
        if cmd == "RETREAT":
            c.setdefault("count", 200)
        if cmd == "ATTACK":
            # ВТОРОЙ УДАР БОЛЬШЕ НЕ РЕЖЕТСЯ (4.10). Прежде за такт уезжал один:
            # файл приказа нёс одну команду. Партия проверки 5 показала цену —
            # стратегия просила два удара В КАЖДОМ ТАКТЕ (по базе и подмогу к
            # волне), и один из них пропадал каждый такт. С §78 файл возит список,
            # и `to_commands` отправляет оба одним файлом; третий и дальше по-
            # прежнему не возим, и мост говорит об этом вслух.
            атака += 1
            if атака > 2:
                пропущено["ATTACK третий за такт"] += 1
                continue
        отдано[cmd] += 1
        из.append(c)
    из = _сбор(из, st, п, стр, пропущено, отдано)
    из = _сзади(из, st, п, стр, пропущено, отдано)
    из = _прикрытие(из, st, п, стр, пропущено, отдано)
    # ЕДА И ЗОЛОТО ЯВНО (3.10, контейнер Windows `smoke_strategy/1`: стратегия ни разу не дала
    # BALANCE food — еда 993 -> 0 к 2:33, крестьян 18 -> 3). Ярус 1 шлёт на еду только
    # ПРОСТАИВАЮЩИХ (4 и больше) — в симуляторе их много, вживую почти нет, а мостовой дебют
    # короткий (n бойцов) и кончается раньше созревания поля. Здесь доля еды из стратегии
    # (`еда_до` до 7:00, `еда_после` после) и 5 на шахту золота выставляются каждый такт.
    gt = float(st.get("gametime") or 0)
    крест = float(st.get("peasants") or 0)
    доля = float(п.get("еда_до", 2 / 3)) if gt < 420 else float(п.get("еда_после", 1 / 3))
    # ДОЛИ ОТ ЛЮДЕЙ НА ЗЕМЛЕ (3.10, третий прогон: на еде 9 из 35 при цели 17 — 20 человек в
    # шахтах, на земле 15, а еда+дерево+камень просили 29, и мост резал все три
    # пропорционально, `llm_policy.распределить_balance`). Земля — как у моста: крестьяне
    # минус шахтёры минус строители. Еда первой (доля деревни, но не больше земли), дерево и
    # камень — из остатка; сумма не превышает землю, и мосту резать нечего.
    земля = max(0, int(крест - float(st.get("on_mine") or 0) - float(st.get("on_build") or 0)))
    # 3.10 (§64, контейнер smoke_net): «еда первой» отдавала еде всю землю — с 4:00 до 7:00 на
    # дереве и камне 0-3 человека, камня 20, вторая шахта золота к 9:00, вторая казарма к 11:30,
    # а еды к 10:00 лежало 5 тысяч без дела. Теперь сперва МИНИМУМ дерева и камня стратегии
    # (ярус 1 так и задуман: «держать на дереве не меньше стольких»), еде — остальное.
    # `COSS3_WOOD_FIRST=0` — как было.
    # …но только когда еды запасено (`ЗАПАС_ЕДЫ_ДЕРЕВУ`, 1000): без порога «дерево первым» в
    # начале снимало с еды всех, и деревня гибла (симулятор: армия к 10:00 — 4)
    # рычаг стратегии `дерево_при_еде` (§65) — порог запаса еды; от 5900 — никогда (как «еда
    # первой»); без рычага — выключатель окружения, как раньше
    порог = п.get("дерево_при_еде")
    if порог is not None:
        дерево_первым = float(порог) < 5900 and float(st.get("food") or 0) >= float(порог)
    else:
        дерево_первым = ДЕРЕВО_ПЕРВЫМ and float(st.get("food") or 0) >= ЗАПАС_ЕДЫ_ДЕРЕВУ
    мин_дер = мин_кам = 0
    # ДЕРЕВО ПО НУЖДЕ (8.10, партии В и Г): вторая казарма — 500 дерева, 500 камня, 2500 золота; золото на неё
    # набиралось к 7:20-7:30, а дерево при трёх рубщиках (`дерево` 3) — к 7:58 (В) и 9:53 (Г), при еде 6-11 тысяч
    # без дела. Игрок: «дерево с начала рубят 5-7». В Г упирался и камень: 500 набралось к 10:08, закладка 10:23.
    # Ключи `дерево_нужда`/`камень_нужда` N: пока ресурса меньше `дерево_до`/`камень_до` (по умолчанию 600), на нём
    # не меньше N; 0 или нет ключа — как было. Двойник это правило не судит: у него казарма ждёт золота (§129).
    def _по_нужде(ключ, ресурс):
        n = int(п.get(ключ, 0))
        if int(п.get(ключ + "_нужда", 0) or 0) > n and float(st.get(ресурс) or 0) < float(п.get(ключ + "_до", 600) or 600):
            n = int(п[ключ + "_нужда"])
        return n
    дер_n, кам_n = _по_нужде("дерево", "wood"), _по_нужде("камень", "stone")
    нужда_активна = дер_n > int(п.get("дерево", 0)) or кам_n > int(п.get("камень", 0))
    # НУЖДА НЕ МИГАЕТ (10.10, §133, смоук партии Д против невозможного): `дерево_первым` ждёт еды
    # ≥ `дерево_при_еде` (2788), а еда в 5:00-8:00 ходила 2416-3201 вокруг порога — и рубщики с ним:
    # 7 → 0 → 7 → 0 (`on_wood` ноль на 6:02 и 6:32 при дереве 246 и 146). Пока нужда действует,
    # её порог еды свой — `нужда_при_еде` (1200: прокорм 80 голов — 8 в секунду, 8 пахарей дают 32);
    # 0 — как было (мигает с общим порогом).
    нужда_при_еде = float(п.get("нужда_при_еде", 1200) or 0)
    if нужда_активна and not дерево_первым and нужда_при_еде > 0 and float(st.get("food") or 0) >= нужда_при_еде:
        дерево_первым = True
    if дерево_первым:
        мин_дер = min(дер_n, земля)
        мин_кам = min(кам_n, земля - мин_дер)
        цель_еды = max(0, min(int(крест * доля), земля - мин_дер - мин_кам))
    else:
        цель_еды = min(int(крест * доля), земля)
    if дерево_первым and (дер_n > int(п.get("дерево", 0)) or кам_n > int(п.get("камень", 0))):
        # по нужде еда уступает: команда яруса 1 на еду не урезана землёй, и мост резал бы все три
        # пропорционально (`llm_policy.распределить_balance`) — прибавка дереву размылась бы обратно к ~4
        for c in из:
            if c["cmd"] == "BALANCE" and c.get("role") == "food":
                c["total"] = min(int(c.get("total") or 0), цель_еды)
    if float(st.get("mills") or 0) >= 1 and float(st.get("on_food") or 0) < цель_еды - 1:
        из = [c for c in из if not (c["cmd"] == "BALANCE" and c.get("role") == "food")]
        из.append({"cmd": "BALANCE", "role": "food", "total": цель_еды, "_важно": True})
        отдано["BALANCE food (переходник)"] += 1
    остаток = земля - (цель_еды if float(st.get("mills") or 0) >= 1 else 0)
    for роль in ("wood", "stone"):
        for c in из:
            if c["cmd"] == "BALANCE" and c.get("role") == роль:
                c["total"] = max(0, min(int(c.get("total") or 0), остаток))
        остаток -= min(дер_n if роль == "wood" else кам_n, max(остаток, 0))
    из = [c for c in из if not (c["cmd"] == "BALANCE" and c.get("role") in ("wood", "stone") and c["total"] <= 0)]
    if дерево_первым:
        for роль, ключ, мин in (("wood", "on_wood", мин_дер), ("stone", "on_stone", мин_кам)):
            if мин > 0 and float(st.get(ключ) or 0) < мин and not any(c["cmd"] == "BALANCE" and c.get("role") == роль for c in из):
                из.append({"cmd": "BALANCE", "role": роль, "total": мин, "_важно": True})
            elif мин > int(п.get({"wood": "дерево", "stone": "камень"}[роль], 0)):
                # по нужде: команда яруса 1 несёт прежнее `дерево`/`камень` — поднять до минимума
                for c in из:
                    if c["cmd"] == "BALANCE" and c.get("role") == роль and int(c.get("total") or 0) < мин:
                        c["total"], c["_важно"] = мин, True
    # СТРОЙКА ЯВНО (3.10, контейнер `smoke_strategy` второй прогон: армия встала на 17 — железо
    # кончилось к 4:57, шахты железа не было ни одной; вторая казарма и шахты золота 2-3 тоже
    # не встали). Ярус 1 ставит закладку, только пока ничего не строится, а стратегия каждый
    # такт просит академию — вживую что-то строится всегда; и потолок 7 срезал стройки в
    # хвосте списка. Здесь — ОДНА закладка за такт, самая нужная по порядку: шахта железа →
    # шахта золота → казармы → дом → академия. BUILD декларативный (total — сколько должно
    # стоять), повтор безопасен.
    из = [c for c in из if c["cmd"] not in ("BUILD", "BUILDERS")]
    def ч(k):
        return float(st.get(k) or 0)
    есть_дер_кам = ч("wood") >= 100 and ч("stone") >= 100
    закладка = None
    # КАЗАРМА РАНЬШЕ ШАХТ (10.10, §133, смоук партии Д): шахты золота 2-3 стоят здесь выше казармы и
    # берут по 100 дерева и 100 камня, как только набралось, — за 5:01-8:08 рубщики принесли 308 дерева,
    # 200 ушли в две шахты, казарма (500/500/2500) не встала вовсе. Ключ `казарма_раньше_шахт` 1: пока
    # ждёт казарма, (а) если на неё хватает — она первой; (б) шахты 2-3 закладываются только сверх
    # резерва дерева и камня под казарму. Первые шахты (железа и золота) не трогаем. Цена — из
    # `build_cost` состояния (вживую), иначе 500/500/2500 (двойник). 0 или нет ключа — как было.
    казарма_ждёт = ч("ba17") >= 1 and ч("ba17") < int(п.get("казарм", 1))
    раньше = bool(int(п.get("казарма_раньше_шахт", 0) or 0)) and казарма_ждёт
    цена_каз = _цена_здания(st, "ba17") or {"wood": 500, "stone": 500, "gold": 2500}
    цена_шахты = _цена_здания(st, "minegold") or {"wood": 100, "stone": 100}
    хватает_каз = all(ч(r) >= v for r, v in цена_каз.items())
    # РЕЗЕРВ ТОЛЬКО КОГДА ЗОЛОТО БЛИЗКО (10.10, §134, второй смоук Д): резерв 500/500 задержал шахту 2 с 4:49 до 5:53
    # (ждал камня 600), а казарму держало ЗОЛОТО — 1561 из 2500 к 7:15 при одной шахте (7,6/с на пятерых). Шахта
    # стоит 100/100 и при нужде 7/6 окупается деревом и камнем за 20 с, золото же без неё копится минутами. Резерв
    # нужен лишь когда золота не хватает меньше `резерв_при_золоте` (600 — около минуты одной шахты): тогда дерево и
    # камень могут стать последним, чего ждёт казарма. 0 — резерв всегда, как в §133.
    резерв_при_золоте = float(п.get("резерв_при_золоте", 600) or 0)
    золота_нет = max(0.0, float(цена_каз.get("gold", 2500)) - ч("gold"))
    резерв_нужен = раньше and ч("mines_gold") >= 1 and (резерв_при_золоте <= 0 or золота_нет <= резерв_при_золоте)
    резерв_ок = (not резерв_нужен
                 or (ч("wood") >= цена_шахты.get("wood", 100) + цена_каз.get("wood", 500)
                     and ч("stone") >= цена_шахты.get("stone", 100) + цена_каз.get("stone", 500)))
    if раньше and хватает_каз:
        закладка = ("ba17", int(ч("ba17")) + 1)
        отдано["BUILD ba17 раньше шахт"] += 1
    elif ч("ba17") >= 1 and ч("mines_iron") < 1 and есть_дер_кам:
        закладка = ("mineiron", 1)
    elif (ч("mines_gold") < int(п.get("шахт_золота", 2)) and ч("on_gold") >= 5 * ч("mines_gold") - 1
          and есть_дер_кам and резерв_ок):
        закладка = ("minegold", int(ч("mines_gold")) + 1)
    elif казарма_ждёт:
        закладка = ("ba17", int(ч("ba17")) + 1)
        if раньше and not резерв_ок:
            отдано["шахта ждёт резерва под казарму"] += 1
    elif ч("my_farm") - ч("my_farmused") <= 5 and есть_дер_кам:
        закладка = ("house", int(ч("houses")) + 1)
    elif стр.академия and ч("ba17") >= 1 and ч("academies") < 1 and gt >= getattr(стр, "академия_с", 0):
        закладка = ("academi", 1)
    # ЕДА ПЕРВОЙ, ПОКА НАЙМ СТОИТ (10.10, §145, третья партия Д живьём): движок не выпускает никого при еде ниже 500,
    # а лестница этого не знала. В Д3 поле созрело в 2:10 при еде 376, и с 2:20 еда получала ОСТАТОК земли: шахта
    # золота 2 заложена в 3:25 (пятеро строителей с еды), 3 — в 4:55, бригада §135а держала по трое на дереве и
    # камне; на еде 5 → 1 → 0, еда 400-480 до 5:00, крестьян 24 и ни одного найма после 5:00 (в Д2 при той же еде
    # 16-20 пахарей пробивали порог доставками — 29 к 5:00), mil.1 (750 еды) не куплена, еда 0 к 8:36, армия 14
    # против его 84 — партия решилась к 5:00. Правило: пока еды меньше `еда_найма` (600; 0 — выкл) и поле созрело,
    # закладываются только мельница и ПЕРВЫЕ шахты железа и золота (остальные ждут еды — найм всё равно стоит), а
    # бригада §135а держится только под первую шахту золота; земля без них достаётся еде сама (`цель_еды` — min
    # доли и земли). Начатая стройка не бросается: закладка декларативна, и без неё блок достраивает (Д3 4:00 —
    # шахта 2 строилась при закладке ba17 и встала в 4:15). Двойник правило не судит: без дохода дерева и камня его
    # шахты 2-3 и так встают после 8:00 (§142). Судья — партия Д живьём.
    еда_найма = float(п.get("еда_найма", 600) or 0)
    голод = (еда_найма > 0 and ч("mills") >= 1 and ч("food") < еда_найма
             and float(st.get("food_ready") or 0) > 0)
    if голод and закладка:
        первые = {"mill": True, "mineiron": ч("mines_iron") < 1, "minegold": ч("mines_gold") < 1}
        if not первые.get(закладка[0], False):
            отдано[f"закладка {закладка[0]} ждёт еды {еда_найма:.0f}: еда {ч('food'):.0f}, найм стоит"] += 1
            закладка = None
    if закладка:
        из += [{"cmd": "BUILDERS", "total": 5}, {"cmd": "BUILD", "role": закладка[0], "total": закладка[1]}]
        отдано[f"BUILD {закладка[0]} (переходник)"] += 1
    # ЗАКЛАДКА ЖДЁТ РЕСУРСА, НА КОТОРОМ НИКОГО — ТРОЕ ТУДА (10.10, §135, партия Д живьём): после созревания
    # поля (2:09) ярус 1 снял всех с камня (камень 40), первая шахта золота ждала 100 камня до 5:00 — в В и Г
    # она встала в 2:50-3:00, потому что камень успел дойти до 160 до того же снятия. Нужда §129 (7/6) была
    # заперта порогом еды 1200 до 4:30. Правило: пока хотят шахту (железа или золота) или ждёт закладка
    # лестницы, и дерева/камня меньше цены, а на этом ресурсе НОЛЬ человек — туда `людей_под_закладку`
    # (3), еда уступает столько же (иначе BALANCE food вторым проходом блока отберёт их обратно). 0 — выкл.
    людей = int(п.get("людей_под_закладку", 3) or 0)
    # §142 (10.10): В ДВОЙНИКЕ ПРАВИЛО МОЛЧИТ. Двойник дерево и камень только тратит (рубщиков у него нет), и бригада
    # «держится, пока ресурса меньше цены» держалась вечно: BALANCE wood 3 / stone 3 каждый такт, еда −6, с 2:35 на еде
    # ноль, еда 0 к 5:00, армия 9 за всю партию (хронология_сим после §135а). Признак живой партии — `build_cost`
    # в состоянии (цены зданий отдаёт только мост); селфтесты идут по живым кейсам, в них он есть.
    if людей > 0 and not дерево_первым and st.get("build_cost"):   # при нужде §129 бригаду 7/6 держит она сама
        хотят = []
        if закладка:
            хотят.append(закладка[0])
        if ч("ba17") >= 1 and ч("mines_iron") < 1 and "mineiron" not in хотят:
            хотят.append("mineiron")
        if (ч("mines_gold") < int(п.get("шахт_золота", 2)) and ч("on_gold") >= 5 * ч("mines_gold") - 1
                and резерв_ок and "minegold" not in хотят):
            хотят.append("minegold")
        # §149 (11.10, Д4 2:17 и Д3 2:20 живьём): первая шахта золота уже заложена и ОПЛАЧЕНА (`wip minegold`), камень 60,
        # а бригада держала троих на камне «под шахту» до её готовности (2:17-2:53) — на еде 5-7 из 20, найм стоял.
        # Бригада не под то, что уже строится.
        в_стройке = {_ч_.split("/")[0].strip() for _ч_ in str(st.get("wip") or "").split(",") if _ч_.strip()}
        if в_стройке:
            было, хотят = хотят, [р for р in хотят if р not in в_стройке]
            for р in было:
                if р not in хотят:
                    отдано[f"бригада под {р}: уже строится"] += 1
        if голод:   # §145: при еде ниже `еда_найма` бригада — только под первую шахту золота, остальное еде
            было, хотят = хотят, [р for р in хотят if р == "minegold" and ч("mines_gold") < 1]
            for р in было:
                if р not in хотят:
                    отдано[f"бригада под {р} ждёт еды {еда_найма:.0f}"] += 1
        умолч = {"ba17": {"wood": 500, "stone": 500, "gold": 2500}, "academi": {"wood": 1050, "stone": 1230}}
        # §135а (10.10, вторая партия Д): условие «на ресурсе ноль» МИГАЛО через такт — такт А: трое на камень, еда −3;
        # такт Б: на камне трое, правило молчит, еда просит прежнее, второй проход BALANCE food блока забирает троих
        # обратно; 2:20-6:00 дерево 402 и камень 60 стояли на месте, на еде 7-10 вместо 13-15, еда ниже 500, найм стоял.
        # Теперь бригада ДЕРЖИТСЯ, пока ресурса меньше цены, и еда уступает её каждый такт; снимается, когда ресурс
        # набран или стратегия сама просит на него не меньше.
        держим = set()
        for роль in хотят:
            цена = _цена_здания(st, роль) or умолч.get(роль) or {"wood": 100, "stone": 100}
            for рес in ("wood", "stone"):
                if рес in держим or ч(рес) >= цена.get(рес, 0):
                    continue
                своё = max([int(c.get("total") or 0) for c in из if c["cmd"] == "BALANCE" and c.get("role") == рес] or [0])
                if своё >= людей:
                    continue
                держим.add(рес)
                if ч("on_" + рес) < людей:       # команда — только когда людей там меньше; еда уступает всегда
                    из = [c for c in из if not (c["cmd"] == "BALANCE" and c.get("role") == рес)]
                    из.append({"cmd": "BALANCE", "role": рес, "total": людей, "_важно": True})
                for c in из:
                    if c["cmd"] == "BALANCE" and c.get("role") == "food":
                        c["total"] = max(0, int(c.get("total") or 0) - людей)
                отдано[f"BALANCE {рес} {людей}: закладка {роль} ждёт {рес}"] += 1
    if ч("mines_iron") >= 1 and ч("on_iron") < 5:
        из = [c for c in из if not (c["cmd"] == "BALANCE" and c.get("role") == "iron")]
        из.append({"cmd": "BALANCE", "role": "iron", "total": 5, "_важно": True})
    шахт = float(st.get("mines_gold") or 0)
    if шахт >= 1 and float(st.get("on_gold") or 0) < 5 * шахт:
        из = [c for c in из if not (c["cmd"] == "BALANCE" and c.get("role") == "gold")]
        из.append({"cmd": "BALANCE", "role": "gold", "total": int(5 * шахт), "_важно": True})
    # ПОТОЛОК КОМАНД ЗА ТАКТ — 12 (решение игрока 3.10). Порядок всё равно нужен:
    # волна и прокачки — вперёд, затем стройка (BUILDERS сразу перед своим BUILD),
    # найм, люди; повтор BALANCE по ресурсу — последний.
    #
    # Семь стояло как «мост читает не больше семи», и это ОКАЗАЛОСЬ НЕВЕРНО: предела в
    # семь нет ни в python (`coss3_bridge.send` пишет `count` и столько пар, сколько
    # дали), ни в блоке (`block_hcmd.inc:84,91` — `for hcn := 0 to hccount-1`). Семь
    # живёт только в тексте промпта для МОДЕЛИ (`llm_policy.py:346`), а стратегия
    # моделью не идёт. Чего семь стоило, измерено контейнером 3.10: после того как
    # встала академия (749 с), стратегия просит по семь `aca.*` за такт, вес UPGRADE
    # равен 1, и в окно не проходило НИЧЕГО — ни еды, ни найма, ни стройки в 89 тактах
    # подряд (срезано 1032 команды), а между 7:00 и 12:30 еда доходила в 8 тактах из 64.
    пары, прочее = [], []
    for i, c in enumerate(из):
        if c["cmd"] == "BUILD":
            пред = из[i - 1] if i and из[i - 1]["cmd"] == "BUILDERS" else None
            пары.append([пред, c] if пред else [c])
        elif c["cmd"] != "BUILDERS":
            прочее.append(c)
    вес = {"ATTACK": 0, "RETREAT": 0, "STAGE": 0, "ENGAGE": 0, "UPGRADE": 1, "FORMATION": 1, "SEED": 3, "TRAIN": 4, "BALANCE": 5}
    балансы = {}
    for c in прочее:
        if c["cmd"] == "BALANCE":
            балансы[c.get("role")] = c
    прочее = [c for c in прочее if c["cmd"] != "BALANCE"] + list(балансы.values())
    прочее.sort(key=lambda c: вес.get(c["cmd"], 6))
    важные = [c for c in прочее if c.get("_важно")]
    прочее = [c for c in прочее if not c.get("_важно")]
    for c in важные:
        c.pop("_важно", None)
    # еда и золото — сразу после волны и прокачек, раньше строек: их не срезает потолок
    из = [c for c in прочее if вес.get(c["cmd"], 6) <= 1] + важные + [x for пара in пары for x in пара] + \
        [c for c in прочее if вес.get(c["cmd"], 6) > 1]
    if len(из) > ПОТОЛОК_КОМАНД:
        пропущено[f"сверх {ПОТОЛОК_КОМАНД} команд"] += len(из) - ПОТОЛОК_КОМАНД
        из = из[:ПОТОЛОК_КОМАНД]
    return из
