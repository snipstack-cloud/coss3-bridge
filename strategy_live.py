ТАКТОВ_БЕЗ_РОСТА = 3

# СКОЛЬКО ТАКТОВ ЖДАТЬ, ПОКА ВОЛНА РОДИТСЯ В ИГРЕ. Приказ уходит файлом, блок
# читает его следующим тиком, бойцы собираются и идут — группа появляется не
# мгновенно. Шесть тактов это тридцать игровых секунд: столько волна имеет право
# не существовать, прежде чем считать приказ неисполненным.
ТАКТОВ_НА_РОЖДЕНИЕ = 6


class Волна:
    """Одна волна: личность (id), номер группы в игре и состояние.

    `номер` — это номер группы, которым волне приказывают. Он берётся ОДИН раз,
    при рождении, и держится до конца жизни волны: именно пересоздание номера
    каждый такт выжгло 16 из 16 в партии 4.10.
    """

    __slots__ = ("id", "номер", "рождена", "сбор", "цель", "состояние", "размер",
                 "ударов", "причина", "не_растёт", "подтверждена", "тактов",
                 "цель_клетка")

    def __init__(self, id: str, номер: int, рождена: float, сбор: tuple, цель: str = ""):
        self.id = id
        self.номер = int(номер)
        self.рождена = float(рождена)
        self.сбор = tuple(сбор) if сбор else (0, 0)
        self.цель = цель or ""
        self.состояние = "СБОР"
        self.размер = 0
        self.ударов = 0
        self.причина = ""
        # Сколько тактов подряд волна НЕ РАСТЁТ. Это и есть признак «собрано»,
        # когда подмога законна и потому не отвергается: в партии 4.10 волна
        # стояла на 59 бойцах с 11:02 до 14:58, а приказы подмоги уезжали честно
        # и каждый такт — ждать было уже нечего, но сказать это было нечем.
        self.не_растёт = 0
        # ПОДТВЕРЖДЕНА — значит группа с этим номером ПОЯВИЛАСЬ В ИГРЕ. Пока
        # приказ не исполнен, группы нет, и считать волну погибшей нельзя:
        # живая партия 5.10 с первым контрактом делала ровно это и заводила
        # новую волну каждый такт — W41, W42, ... W53 к 8:26, при том что из
        # дома не ушёл ни один боец (`mil_away` = 0 всю партию).
        self.подтверждена = False
        self.тактов = 0
        # КУДА ПОСЛАНА. Нужна, чтобы отличить «идёт» от «пришла и стоит»: живая
        # партия 5.10 показала, что без этого волна остаётся в В_БОЮ навсегда —
        # W1 ушла в 1:29, дошла до клетки (7,6), и с 1:29 до 8:07 стояла там и
        # росла, пока его кучи стояли в (3,2), (2,3) и (4,4).
        self.цель_клетка = None

    def __repr__(self):
        return (f"Волна({self.id}, группа {self.номер}, {self.состояние}, "
                f"{self.размер} бойцов, клетка {self.сбор})")


class РеестрВолн:
    """Реестр волн: кто живой, кто собрался, кто в бою. Меры считает сам.

    Мера, которой не было и из-за которой простой 4.10 пришлось вскрывать
    руками: `простой_готовой` — сколько ТАКТОВ боеспособная волна стояла без
    приказа. Число приказов её не заменяет: 94 повтора и 94 такта простоя — это
    одно и то же событие, но лечится только второе.
    """

    def __init__(self):
        self.волны: list = []
        self.счёт = 0
        self.мера = collections.Counter()
        self.простой_готовой = 0      # ВСЕГО тактов простоя готовой волны за эпизод
        self.подряд = 0               # сколько тактов подряд простой идёт сейчас
        self.первый_удар = None       # игровое время первого ATTACK по врагу
        self.записи: list = []        # строки такта для `why`

    # --- жизнь волн ---------------------------------------------------------
    def живые(self) -> list:
        return [в for в in self.волны if в.состояние != "КОНЧЕНА"]

    def активная(self):
        """Волна, которой сейчас принадлежит миссия. Одна на весь реестр."""
        ж = self.живые()
        return ж[0] if ж else None

    def обновить(self, st: dict) -> None:
        """Сверить реестр с игрой: кто ещё есть, где стоит, кого уже нет."""
        места = {int(г.get("id") or 0): г for г in _группы(st)
                 if int(г.get("n") or 0) > 0}
        for в in self.живые():
            в.тактов += 1
            г = места.get(в.номер)
            if г is None:
                if в.подтверждена:
                    # Группа БЫЛА и исчезла: бойцы погибли или влились в чужую.
                    в.состояние = "КОНЧЕНА"
                    self.мера["волн кончилось"] += 1
                    self.записи.append(f"WAVE_DONE {в.id} группа {в.номер}")
                elif в.тактов > ТАКТОВ_НА_РОЖДЕНИЕ:
                    # Приказ так и не исполнился: волна не родилась. Закрываем,
                    # но ВСЛУХ и один раз, а не заводим новую каждый такт.
                    в.состояние = "КОНЧЕНА"
                    self.мера["волна не родилась"] += 1
                    self.записи.append(
                        f"WAVE_DONE {в.id} группа {в.номер} (не родилась за "
                        f"{в.тактов} тактов)")
                continue
            в.подтверждена = True
            было = int(в.размер or 0)
            в.размер = int(г.get("n") or 0)
            в.сбор = (int(г.get("cx") or 0), int(г.get("cy") or 0))
            в.не_растёт = 0 if в.размер > было else в.не_растёт + 1

    def родить(self, st: dict, цель: str):
        """Новая волна — ТОЛЬКО если живой нет. Иначе бойцы входят в живую."""
        if self.активная() is not None:
            return None
        номер = _свободный_номер(st)
        if not номер:
            self.мера["номера кончились"] += 1
            return None
        self.счёт += 1
        в = Волна(f"W{self.счёт}", номер, float(st.get("gametime") or 0),
                  _дом(st), цель)
        self.волны.append(в)
        self.мера["волн заведено"] += 1
        self.записи.append(f"WAVE_CREATED {в.id} группа {номер} "
                           f"t={_мин(в.рождена)} цель={цель or '-'}")
        return в


def _мин(с) -> str:
    """Игровые секунды как время партии: разбор 4.10 читался по минутам."""
    try:
        с = int(float(с or 0))
    except (TypeError, ValueError):
        return "?"
    return f"{с // 60}:{с % 60:02d}"


def домашних_бойцов(st: dict) -> int:
    """Сколько бойцов ДОМА, то есть кого ещё можно послать подмогой.

    Без этого числа приказ «к волне» неотличим от приказа «стоять»: в партии
    4.10 вся армия уже стояла в клетке волны, и 94 приказа подмоги не двинули
    никого. `mil_away` даёт ушедших, остальное — дом.
    """
    ч = lambda к: float(st.get(к) or 0)
    всего = ч("mil_inf") + ч("mil_shooters") + ч("mil_cav")
    return max(0, int(всего - ч("mil_away")))


def нормализовать_подмогу(c: dict, волна, st: dict):
    """Приказ подмоги -> (приказ или None, причина отказа или '').

    ЗАПРЕЩЕНО ДВА СЛУЧАЯ, и оба наблюдались вживую 4.10:
      * подмога В КЛЕТКУ САМОЙ ВОЛНЫ — «иди туда, где ты уже стоишь»;
      * подмога, посылать которую некем: дома бойцов нет.
    """
    цель = str(c.get("target") or "")
    if c.get("cmd") not in ("ATTACK", "ENGAGE") or цель != "wave":
        return c, ""
    if волна is None:
        return None, "НЕТ_ЦЕЛИ"
    # ВОЛНЫ В ПОЛЕ НЕТ — ПРИСОЕДИНЯТЬСЯ НЕ К КОМУ. Так и было все 94 раза 4.10:
    # группа стояла в клетке (5,2), и это была клетка нашей же ратуши, поэтому
    # мост честно отвечал «в поле нет своих дальше двух клеток от базы, идти не
    # к кому». Отсюда два признака, и оба из состояния: ушедших нет (`mil_away`)
    # либо группа стоит дома.
    if int(float(st.get("mil_away") or 0)) <= 0:
        return None, "СОБРАНО"
    if tuple(волна.сбор) == tuple(_дом(st)):
        return None, "СОБРАНО"
    if домашних_бойцов(st) <= 0:
        # Все уже в волне — собирать больше некого, значит волна СОБРАНА.
        return None, "СОБРАНО"
    клетка = (int(c.get("cx") or -1), int(c.get("cy") or -1))
    if клетка == tuple(волна.сбор):
        return None, "СОБРАНО"
    # ГЛАВНОЕ, И КУПЛЕНО ЖИВОЙ ПАРТИЕЙ 5.10. Цель `wave` МОСТ РАЗРЕШАЕТ САМ — в
    # клетку, где волна стоит СЕЙЧАС. В логе это видно дословно, каждые пять
    # секунд подряд: «ATTACK 9999 -> wave: к волне в клетку (8,1)» -> «урезан до
    # 34: столько сейчас свободно» -> «34 бойца ушли на cell, группа 1». Это те
    # же самые бойцы: мост считает их свободными, посылает в клетку, которую они
    # занимают, и марш начинается заново КАЖДЫЙ ТАКТ. Отряд стоит и топчется —
    # ровно это игрок и увидел глазами.
    #
    # Поэтому приказ не отвергается, а ПЕРЕНАЦЕЛИВАЕТСЯ: подмога идёт не туда,
    # где волна стоит, а туда, КУДА ОНА ИДЁТ. Тогда новобранцы догоняют её на
    # цели, а идущих никто не разворачивает. Если волна никуда не идёт, подмога
    # бессмысленна — отказ с причиной, и дальше решает переход «собрано -> бить».
    if волна.цель_клетка and tuple(волна.цель_клетка) != tuple(волна.сбор):
        return (dict(c, target="cell", cx=int(волна.цель_клетка[0]),
                     cy=int(волна.цель_клетка[1])), "")
    return None, "СОБРАНО"


class ЖиваяСтратегия:
    def __init__(self, путь: str, сеть: str = ""):
        with open(путь, encoding="utf-8") as f:
            w = json.load(f)
        self.п = w.get("итог", w)
        # СЕТЬ ТАКТИКА ВОЮЕТ (3.10, §61): волны и тактика стратегии выключаются ровно как в
        # обучении (`sim/тактик.Тактик`), решение о бое раз в 15 с даёт сеть.
        self.сеть = None
        if сеть:
            import tactic_core
            with open(сеть, encoding="utf-8") as f:
                self.сеть = tactic_core.Ядро(json.load(f)["theta"])
            self.имя_сети = os.path.basename(сеть)
            self.п = {k: v for k, v in self.п.items() if k not in ("отход", "подмога", "слабая", "возврат")}
            self.п.update(T1=1e9, T2=1e9, P1=0.0)
            self.решения = collections.Counter()
        self.имя = os.path.basename(путь)
        # Мы — живой мост: приказы волне в поле переводятся в мостовые (`_в_мостовые`).
        globals()["ЖИВОЙ_МОСТ"] = True
        import поиск_стратегии as ПС
        ПС.ПРАВИЛА_ЖИВЫЕ = True          # вживую правила моста действуют всегда
        import debut as _D               # §58: мостовой дебют — тем же порядком, что у стратегии
        _D.ПОРЯДОК_ИГРОКА = bool(self.п.get("дебют_игрока", 0))
        self.стр = ПС.Стратегия(self.п)
        self.n = max(1, int(self.п.get("n", 20)))
        self.пропущено = collections.Counter()
        self.отдано = collections.Counter()
        # КОГО С КЕМ СВОДИМ (4.10). Приказ `target: group` наводится на место
        # получателя В МОМЕНТ ПРИКАЗА и в погоню не ведёт — живая партия 4.10
        # показала это первым же слиянием: получатель шёл, и пославший пришёл в
        # опустевшую клетку. Поэтому приказ ПОВТОРЯЕТСЯ каждый такт, пока клетки
        # не совпадут. Такт — пять игровых секунд, а не каждая секунда: приказ
        # идущей группе каждую секунду это перестроение, от которого волны уже
        # вставали («a unit already marching is left alone... it stalls»,
        # block_hcmd.inc).
        self.сводим = {}
        # НОМЕРА ВОЛНАМ (4.10, решение игрока). Пока волны были безымянны, адресные
        # приказы умела только рука: приказы «к своим», «держать», «вперёд» брали
        # ВСЕХ дальше одной клетки от ратуши и задевали подмогу, которая ещё идёт. Теперь
        # каждая уходящая волна получает номер, и дальше ей приказывают по нему.
        # Номер берётся СВОБОДНЫЙ по состоянию, а не по счётчику: иначе новая волна
        # заняла бы номер живой группы и перебила бы ей состав.
        self.номера = 0
        # КОНТРАКТ ВОЛНЫ (5.10). Реестр держит личность волны между тактами —
        # то, чего не было и из-за чего номер выдавался заново каждые пять
        # секунд. Он же считает простой готовой волны, меру, которой в разборе
        # 4.10 не хватило: 94 повтора приказа и 94 такта простоя — одно событие.
        self.реестр = РеестрВолн()

    def _удар_готовой(self, волна, st: dict):
        """Чем ударить собранной волне -> (приказ или None, причина).

        МЕСТНЫЙ ПЕРЕВЕС, А НЕ ОБЩИЙ. Разбор 4.10 показал, что общий счёт на
        вопрос «можно ли бить ближайшую кучу» не отвечает: у нас было 135 пехоты
        против его 114 (перевес 1,18 по партии), а рядом с волной стояли его
        кучи по 28 и 30 — против них перевес вчетверо больше, и бить их можно
        было с 7-й минуты. Поэтому сначала считается куча РЯДОМ.

        Порог не выдуман: это `штурм_при` самой стратегии (у шт_s2 — 0,92),
        то же число, которым она решает штурм в симуляторе.
        """
        порог = float(self.п.get("штурм_при", 0.92) or 0.92)
        # ПОРОГ БЛИЖНЕЙ КУЧИ ОТДЕЛЬНО (мак 5.10, §97): развилка §94 на p5 — удар по ближней куче при
        # местном перевесе 1,69 стоил 86-92 наших за 59-74 его; ключ `рядом_при` в файле стратегии
        # даёт ей свой порог. Нет ключа — как было, `штурм_при`.
        порог_рядом = float(self.п.get("рядом_при", порог) or порог)
        # ЧЬИМИ СИЛАМИ БЬЁМ. Если группа в игре уже есть — её бойцами (`count` 0
        # значит «приказ существующей группе»). Если волна ещё не родилась,
        # бойцы пойдут ИЗ ДОМА, и тогда сила — домашние, а `count` обязан быть
        # числом: иначе приказ адресуется группе, которой нет, и из дома не
        # уходит никто. Живая партия 5.10 показала это на себе — `attack: 0`
        # каждый такт при 64 бойцах дома и `mil_away` = 0 всю партию.
        дома = домашних_бойцов(st)
        if волна.подтверждена and int(волна.размер or 0) > 0:
            свои, счёт = int(волна.размер), 0
        else:
            свои, счёт = дома, дома
        if свои <= 0:
            return None, "МАЛО_СИЛ свои=0"
        import coss3_map as _КМ
        кучи = _список(st, "ecells", _КМ.его_клетки)
        кучи = [к for к in кучи if int(к.get("n") or 0) > 0]
        if кучи:
            вx, вy = волна.сбор
            # БЛИЖАЙШАЯ, А ПРИ РАВНОЙ БЛИЗОСТИ — САМАЯ БОЛЬШАЯ. Без доводки по
            # размеру выбор выходил глупым: в снимке 7:01 ближайшей оказалась
            # клетка с ОДНИМ бойцом, а его двенадцать стояли в соседней, на одну
            # клетку дальше. Клетки рядом для боя это одно место: движок бьётся
            # и через границу клетки.
            дист = lambda к: max(abs(int(к["x"]) - вx), abs(int(к["y"]) - вy))
            ближе = min(дист(к) for к in кучи)
            бл = max((к for к in кучи if дист(к) <= ближе + 1),
                     key=lambda к: int(к.get("n") or 0))
            рядом = int(бл.get("n") or 0)
            # ЕГО ПОДКРЕПЛЕНИЕ У ЦЕЛИ (мак 5.10, §97 развилка): в 11:03 p5 перевес 1,97 считался против кучи
            # 36, а его 23 стояли в двух клетках и подошли за полминуты. Ключ `рядом_окно` k в файле
            # стратегии: «рядом» — все его бойцы в k клетках от выбранной кучи. Нет ключа — 0, как было.
            _окно = int(self.п.get("рядом_окно", 0) or 0)
            if _окно > 0:
                рядом = sum(int(к.get("n") or 0) for к in кучи
                            if max(abs(int(к["x"]) - int(бл["x"])), abs(int(к["y"]) - int(бл["y"]))) <= _окно)
            if (int(бл["x"]), int(бл["y"])) == tuple(волна.сбор):
                # Он в НАШЕЙ клетке: бой уже идёт, и приказ «иди сюда» был бы тем
                # самым «иди туда, где стоишь», из-за которого вся эта правка и
                # делалась. Причина названа, приказа нет.
                return None, (f"БОЙ_ИДЁТ свои={свои} рядом={рядом} "
                              f"клетка={волна.сбор[0]},{волна.сбор[1]}")
            if свои >= порог_рядом * рядом:
                # `face` на ту же кучу НАЗВАН ЯВНО, хотя блок сам ставит строй
                # лицом к точке цели и вышло бы то же: приказ, который читают
                # глазами в логе и в трассе, не должен полагаться на умолчание
                # блока. Если умолчание однажды изменится, удар останется лицом
                # к врагу.
                return ({"cmd": "ATTACK", "count": счёт, "target": "cell",
                         "cx": int(бл["x"]), "cy": int(бл["y"]),
                         "face": [int(бл["x"]), int(бл["y"])],
                         "group": волна.номер},
                        f"МЕСТНЫЙ_ПЕРЕВЕС свои={свои} рядом={рядом} "
                        f"ratio={свои / max(1, рядом):.2f} порог={порог_рядом:.2f}")
            # Ближнюю кучу не берём — мимо неё не ходим. Причина НАЗВАНА, и это
            # не то же, что «цели нет»: разбор должен различать «не дошли» и
            # «не решились».
            return None, (f"МАЛО_СИЛ свои={свои} рядом={рядом} "
                          f"ratio={свои / max(1, рядом):.2f} порог={порог_рядом:.2f}")
        # Куч рядом нет — значит цель это его база, если она на карте известна.
        try:
            б = _КМ.база_врага(st)
        except Exception:
            б = {}
        if not б:
            return None, "НЕТ_ЦЕЛИ"
        его = float(st.get("p1_army") or 0)
        if его > 0 and свои < порог * его:
            return None, (f"МАЛО_СИЛ свои={свои} его={его:.0f} "
                          f"порог={порог:.2f}")
        return ({"cmd": "ATTACK", "count": счёт, "target": "cell",
                 "cx": int(б["cx"]), "cy": int(б["cy"]),
                 "face": [int(б["cx"]), int(б["cy"])], "group": волна.номер},
                f"БАЗА свои={свои} его={его:.0f} порог={порог:.2f}")

    def итог_волн(self) -> dict:
        """Меры волн за эпизод. `простой_готовой` важнее числа приказов: она
        прямо меряет, сколько тактов боеспособная волна стояла без решения."""
        р = self.реестр
        return {"волн": р.счёт,
                "простой_готовой_тактов": р.простой_готовой,
                "простой_подряд": р.подряд,
                "первый_удар": р.первый_удар,
                "мера": dict(р.мера)}

    def ответ(self, st: dict) -> dict:
        """Ответ в форме модели: {"commands": [...], "why": "..."}.

        Правила хозяйства и порядок команд (`привести`) применяет сама `Стратегия` — и в
        симуляторе, и здесь (3.10, §57): поиск оптимизирует ровно то, что исполняется вживую."""
        if not self.стр.я.дебют.готов(st):
            # дебют ведёт мост (`debut.py` той же длины); команды дебюта стратегии — в числовой
            # форме Command и мосту модельным путём непонятны
            return {"commands": [], "why": f"стратегия {self.имя}: ждёт конца дебюта"}
        из = self.стр(st)
        why = f"стратегия {self.имя}: {len(из)} команд"
        из = [_мостовая_цель(c) for c in из]
        if self.сеть is not None:
            # признаки — тем же переводом живого снимка, что у тени (§44); приказ сети — первым
            import shadow_tactic, tactic_core
            с = shadow_tactic.из_моста(st)
            р = self.сеть.решить(с)
            if р is not None:
                имя = tactic_core.РЕШЕНИЯ[р[0]]
                self.решения[имя] += 1
                # ПРИКАЗЫ ВОЛНЕ ОТ СЕТИ ПЕРЕВОДЯТСЯ, А НЕ ОТБРАСЫВАЮТСЯ (3.10). Здесь
                # стояло `if not cmd.startswith("_")`, и это съедало ровно те решения, из-за
                # которых приказы и делались: в прогоне `smoke_net/1` сеть трижды сказала
                # «держать» при волне В ПОЛЕ (540, 572, 680 с), а в игру не ушло ничего —
                # внутренние команды отсекались ДО перевода. Переводим живым состоянием
                # `st`, а не `с`: `_в_мостовые` читает `obuild`, `ocells` и `mil_away`, а
                # `с` — уже пересчитанная в форму симулятора сводка.
                бой = []
                for c in self.сеть.команды(р[0], с, живой=True):
                    cmd = str(c.get("cmd", ""))
                    if cmd.startswith("_"):
                        пер = _лицом_к_врагу(_в_мостовые(c, cmd, st), st)
                        if пер is None:
                            self.пропущено[f"сеть: {cmd}"] += 1
                            continue
                        self.пропущено[f"сеть: {cmd} -> {пер['cmd']}"] += 1
                        бой.append(_мостовая_цель(пер))
                        continue
                    бой.append(_мостовая_цель(c))
                if бой:
                    # Приказ сети вытесняет собственные ATTACK/RETREAT стратегии, и ENGAGE
                    # тоже: файл приказа один, двум командам одного рода в такте не уехать.
                    из = бой + [c for c in из
                                if c["cmd"] not in ("ATTACK", "RETREAT", "ENGAGE")]
                    из = из[:ПОТОЛОК_КОМАНД]
                why += f"; сеть {self.имя_сети}: {имя}"
                if self.пропущено:
                    why += " (" + ", ".join(f"{k} ×{v}" for k, v in
                                            self.пропущено.most_common(3)) + ")"
        # РЕЕСТР ВОЛН СВЕРЯЕТСЯ С ИГРОЙ ДО ВСЕГО ОСТАЛЬНОГО: кто ещё жив, где
        # стоит, кого уже нет. Иначе приказ уйдёт волне, которой в игре нет.
        # getattr, а не прямое поле: объект иногда собирают через __new__ (так
        # делают проверки `selftest_groups`, `selftest_wave_orders`), и
        # отсутствие реестра не имеет права ронять такт — ровно та же оговорка,
        # что уже стоит у памяти слияний ниже.
        if not hasattr(self, "реестр"):
            self.реестр = РеестрВолн()
        self.реестр.записи.clear()
        self.реестр.обновить(st)
        # НОМЕР УХОДЯЩЕЙ ВОЛНЕ. Только ATTACK с числом бойцов: это и есть «волна
        # ушла», и ровно она становится группой. Приказы уже существующим группам
        # (count 0) номера не трогают.
        for c in из:
            if c["cmd"] == "ATTACK" and not c.get("group"):
                # `count` бывает СЛОВОМ «all» — так стратегия и сеть просят всех
                # свободных («подмога»). Живая партия проверки 5 показала цену
                # недосмотра: номер получила ОДНА волна из 81, потому что
                # int(float("all")) падал и число считалось нулём. Остальные
                # восемьдесят ушли безымянными, и адресовать их было нечем.
                _сч = c.get("count", 0)
                if isinstance(_сч, str) and _сч.strip().lower() in ("all", "все"):
                    _сколько = 1          # «все свободные» — это заведомо больше нуля
                else:
                    try:
                        _сколько = int(float(_сч or 0))
                    except (TypeError, ValueError):
                        _сколько = 0
                if _сколько > 0:
                    # ПРИСОЕДИНЕНИЕ, А НЕ РОЖДЕНИЕ. Пока волна жива, уходящие
                    # бойцы входят в неё под её же номером: именно выдача нового
                    # номера каждый такт выжгла 16 из 16 в партии 4.10.
                    _в = self.реестр.активная()
                    if _в is not None:
                        c["group"] = _в.номер
                        self.отдано["вошли в волну"] += 1
                        self.реестр.мера["вошли в волну"] += 1
                        continue
                    _в = self.реестр.родить(st, str(c.get("target") or ""))
                    _ном = _в.номер if _в is not None else 0
                    if _ном:
                        c["group"] = _ном
                        self.номера += 1
                        # В `why` про рождение группы НЕ ПИШЕМ, и это куплено прогоном
                        # `smoke_hard4` 4.10: там стратегия просила подмогу к волне
                        # каждый такт, мост 17 раз отказывал честно («в поле нет своих
                        # дальше двух клеток от базы, идти не к кому»), а моё `why` все
                        # 17 раз сообщало «волна становится группой 1» — группы не было
                        # ни одной. Номер здесь только НАЗНАЧАЕТСЯ приказу; родилась
                        # группа или нет, знает отправка, и она об этом говорит сама
                        # («волна N: ... , группа M»). Намерение видно в трассе: поле
                        # `group` лежит в самой команде.
                        self.отдано["номер волне"] += 1
                    else:
                        why += "; номера групп кончились (16), волна без номера"
        # --- ВАЛИДАТОР ПРИКАЗОВ: ПОДМОГА В СВОЮ ЖЕ КЛЕТКУ ЗАПРЕЩЕНА ----------
        #
        # 4.10 таких приказов было 94 из 95. Отбросить их недостаточно: тогда
        # вместо бессмысленного приказа получится молчание, из которого потом
        # нельзя понять, почему бот снова простоял. Поэтому отказ ведёт к ЯВНОМУ
        # переходу состояния ниже, и у него всегда есть названная причина.
        волна = self.реестр.активная()
        _оставить, _отказы = [], collections.Counter()
        for c in из:
            _пр, _прич = нормализовать_подмогу(c, волна, st)
            if _пр is not None:
                _оставить.append(_пр)
            else:
                _отказы[_прич] += 1
                self.реестр.мера[f"подмога отвергнута: {_прич}"] += 1
        из = _оставить

        # КУДА ВОЛНА ПОСЛАНА — ЗАПОМИНАЕМ С ЛЮБОГО ПРИКАЗА, не только своего.
        # Удар на T1 отдаёт сама стратегия, и без этого волна не знала бы своей
        # цели: тогда подмога к ней снова пошла бы в клетку, где она стоит, а
        # это и есть топтание на месте из партии 5.10.
        if волна is not None:
            for c in из:
                if (c.get("cmd") in ("ATTACK", "ENGAGE")
                        and c.get("target") == "cell"
                        and c.get("cx") is not None and c.get("cy") is not None):
                    волна.цель_клетка = (int(c["cx"]), int(c["cy"]))
                    break

        # --- ЯВНЫЙ ПЕРЕХОД «СОБРАНО -> АТАКОВАТЬ ИЛИ НАЗВАТЬ ПРИЧИНУ» --------
        if волна is not None:
            # ПРИШЛА И СТОИТ — ЗНАЧИТ ПОРА ПЕРЕСПРОСИТЬ СЕБЯ. Это CONTINUE/REGROUP
            # из автомата: без него волна остаётся в В_БОЮ до конца партии.
            # Живая партия 5.10: W1 ушла в 1:29, дошла до клетки (7,6) и стояла
            # там с 1:29 до 8:07, растя с 21 до 27, пока его кучи стояли в
            # (3,2), (2,3) и (4,4) — то есть «стоящая армия» вернулась, просто
            # после удара. Признак «дошла» — своя клетка совпала с клеткой
            # приказа; признак «стоит» — тот же, что у сбора: не растёт.
            if (волна.состояние == "В_БОЮ" and волна.цель_клетка
                    and tuple(волна.сбор) == tuple(волна.цель_клетка)
                    and волна.не_растёт >= ТАКТОВ_БЕЗ_РОСТА):
                волна.состояние = "ГОТОВА"
                волна.цель_клетка = None
                self.реестр.мера["волна дошла и переспрашивает"] += 1
                self.реестр.записи.append(
                    f"WAVE_ARRIVED {волна.id} cell={волна.сбор[0]},{волна.сбор[1]} "
                    f"size={волна.размер} t={_мин(st.get('gametime'))}")
            # ДВА ПРИЗНАКА «СОБРАНО», и второй куплен разбором 4.10 на живых
            # снимках. Первый: подмогу отвергли — посылать больше некого.
            # Второй: подмога законна и уезжает каждый такт, а волна НЕ РАСТЁТ.
            # Ровно так и было с 11:02 до 14:58: 59 бойцов, приказы подмоги
            # уходят честно, рост нулевой, удара нет. Без второго признака волна
            # остаётся в СБОРЕ вечно, и вся эта правка не сработала бы.
            _почему = ""
            if _отказы.get("СОБРАНО"):
                _почему = "подмогу отвергли"
            elif волна.не_растёт >= ТАКТОВ_БЕЗ_РОСТА:
                _почему = f"не растёт {волна.не_растёт} тактов"
            if _почему and волна.состояние == "СБОР":
                волна.состояние = "ГОТОВА"
                self.реестр.мера[f"собрано: {_почему.split()[0]}"] += 1
                self.реестр.записи.append(
                    f"WAVE_READY {волна.id} size={волна.размер} "
                    f"t={_мин(st.get('gametime'))} ({_почему})")
            занят = any(c["cmd"] in ("ATTACK", "RETREAT", "ENGAGE") for c in из)
            if волна.состояние == "ГОТОВА" and not занят:
                приказ, причина = self._удар_готовой(волна, st)
                if приказ is not None:
                    из.append(приказ)
                    волна.состояние = "В_БОЮ"
                    волна.ударов += 1
                    волна.причина = ""
                    волна.цель_клетка = (int(приказ.get("cx", -1)),
                                         int(приказ.get("cy", -1)))
                    if self.реестр.первый_удар is None:
                        self.реестр.первый_удар = float(st.get("gametime") or 0)
                    self.реестр.мера["удар готовой волны"] += 1
                    self.реестр.подряд = 0
                    self.реестр.записи.append(
                        f"ORDER_ATTACK {волна.id} target={приказ.get('target')} "
                        f"reason={причина}")
                else:
                    # НЕТ ПРИКАЗА — НО ЕСТЬ ПРИЧИНА. Ровно эта запись и была
                    # нужна в разборе 4.10 вместо 94 одинаковых приказов.
                    волна.причина = причина
                    self.реестр.простой_готовой += 1
                    self.реестр.подряд += 1
                    self.реестр.мера[f"простой готовой: {причина}"] += 1
                    self.реестр.записи.append(
                        f"NO_ACTION {волна.id} reason={причина} "
                        f"тактов подряд {self.реестр.подряд}")

        # ПОВТОР ПРИКАЗА СЛИЯНИЯ. Сам приказ мог прийти этим тактом (тогда он уже
        # в `из`) или тактами раньше; пока клетки разные, его надо повторять, иначе
        # получатель уйдёт, а пославший встанет в пустой клетке.
        # getattr, а не прямое поле: объект иногда собирают через __new__ (так делают
        # проверки), и отсутствие памяти не имеет права ронять такт.
        if not hasattr(self, "сводим"):
            self.сводим = {}
        for c in из:
            if c.get("target") == "group" and c.get("group") and c.get("gid"):
                self.сводим[int(c["group"])] = int(c["gid"])
        if self.сводим:
            места = {int(г["id"]): (int(г["cx"]), int(г["cy"]))
                     for г in _группы(st) if int(г.get("n") or 0) > 0}
            for a in list(self.сводим):
                b = self.сводим[a]
                if a not in места or b not in места or места[a] == места[b]:
                    # слились, дошли или группы больше нет — повторять нечего
                    self.сводим.pop(a, None)
                    continue
                уже = any(c.get("group") == a and c.get("target") == "group" for c in из)
                занят = any(c["cmd"] in ("ATTACK", "RETREAT", "ENGAGE") for c in из)
                if уже or занят:
                    # файл приказа один на такт: повторим следующим, а не затрём бой
                    why += f"; слияние {a}->{b} отложено (приказ такта занят)"
                    break
                из.append({"cmd": "RETREAT", "count": 0, "target": "group",
                           "group": a, "gid": b})
                why += f"; повтор слияния {a}->{b}"
                break
        if self.стр.пропущено:
            why += "; живая игра не умеет: " + ", ".join(f"{k} ×{v}" for k, v in self.стр.пропущено.most_common(4))
        # СТРОКА ТАКТА ПРО ВОЛНУ. Одна запись вместо 94 одинаковых приказов:
        # разбор 4.10 пришлось вести руками по номерам приказов именно потому,
        # что состояние волны нигде не писалось.
        _в = self.реестр.активная()
        if _в is not None:
            why += (f" | wave={_в.id} status={_в.состояние} size={_в.размер}"
                    f" cell={_в.сбор[0]},{_в.сбор[1]}")
            if _в.причина:
                why += f" reason={_в.причина}"
        if _отказы:
            why += " | подмога отвергнута: " + ", ".join(
                f"{k} ×{v}" for k, v in _отказы.most_common(3))
        if self.реестр.записи:
            why += " | " + "; ".join(self.реестр.записи)
        return {"commands": из, "why": why}


def _мостовая_цель(c: dict) -> dict:
    """`peasants_free` есть только в симуляторе (крестьяне без его армии); у моста — `peasants`,
    которая тоже ищет клетку с крестьянами и отбрасывает охраняемые (`клетка_охоты`)."""
    if c.get("cmd") == "ATTACK" and c.get("target") == "peasants_free":
        c = dict(c, target="peasants")
    # клетка: симулятор пишет `aim: [x, y]`, мост ждёт `cx`, `cy` (`to_commands`)
    if c.get("cmd") == "ATTACK" and c.get("target") == "cell" and isinstance(c.get("aim"), (list, tuple)):
        c = dict(c, cx=int(c["aim"][0]), cy=int(c["aim"][1]))
        c.pop("aim", None)
    return c


def _его_база(st: dict):
    v = st.get("en_base")
    if isinstance(v, str):
        v = [x for x in v.replace(";", ",").split(",") if x.strip()]
    try:
        return (int(float(v[0])), int(float(v[1])))
    except (TypeError, ValueError, IndexError):
        return None


def _наша_база(st: dict) -> tuple:
    if st.get("my_cx") is not None and st.get("my_cy") is not None:
        return (int(float(st["my_cx"])), int(float(st["my_cy"])))
    return _дом(st)


def клетка_сбора(st: dict, от_его: int = 4):
    """§74: на прямой от нашей ратуши к его — в `от_его` клетках (Чебышёв) от его ратуши."""
    е, н = _его_база(st), _наша_база(st)
    if е is None:
        return None
    dx, dy = н[0] - е[0], н[1] - е[1]
    d = max(abs(dx), abs(dy))
    if d <= от_его:
        return н
    return (е[0] + round(dx * от_его / d), е[1] + round(dy * от_его / d))


def _сбор(из: list, st: dict, п: dict, стр, пропущено, отдано) -> list:
    """СБОР ВОЛН (4.10, §74; задание Windows в ПЛАН.md). Волну стратегии (ATTACK) мост не
    отдаёт сразу: сперва стоячий STAGE в клетку сбора (4 клетки от его ратуши), и когда там
    `сбор_доля` наших бойцов И (наших не меньше его армии ИЛИ ждём `сбор_ждать` с) — STAGE off и
    ENGAGE на цель волны. Проверка 3: волна входила в его базу кусками 24 → 15+15 → 25 → 29 → 35.
    Общее для симулятора и моста (§57). Выключено, пока у стратегии нет рычага `сбор` ≥ 0,5."""
    if float(п.get("сбор", 0) or 0) < 0.5:
        return из
    t = float(st.get("gametime") or 0)
    с = getattr(стр, "_сбор_сост", None)
    волны = [c for c in из if c.get("cmd") == "ATTACK"]
    из = [c for c in из if c.get("cmd") != "ATTACK"]
    if any(c.get("cmd") == "RETREAT" for c in из):
        return из              # отход стратегии главнее; сбор не сбрасывается — вернувшиеся свободны,
                               # и STAGE снова ведёт их в клетку сбора (перегруппировка)
    if с is None and волны:
        кл = клетка_сбора(st, int(п.get("сбор_клеток", 4)))
        if кл is None:
            return из + волны[:1]
        цель = волны[0].get("target") or "army"
        с = {"клетка": кл, "цель": "army" if цель == "wave" else цель, "aim": волны[0].get("aim"), "t0": None}
        стр._сбор_сост = с
        отдано["STAGE (сбор)"] += 1
        return [{"cmd": "STAGE", "cx": int(кл[0]), "cy": int(кл[1]), "keep": 0}] + из
    if с is None:
        return из
    if волны:
        пропущено["ATTACK -> копим в сборе"] += len(волны)
    кл = с["клетка"]
    собрано = sum(float(c.get("n") or 0) for c in _список(st, "ocells", __import__("coss3_map").наши_клетки)
                  if abs(int(c.get("x", -9)) - кл[0]) <= 1 and abs(int(c.get("y", -9)) - кл[1]) <= 1)
    всего = sum(float(st.get(k) or 0) for k in ("mil_inf", "mil_shooters", "mil_cav"))
    if собрано >= 1 and с["t0"] is None:
        с["t0"] = t
    вс = st.get("враг_слот")
    его = float(st.get(f"p{int(вс)}_army" if вс is not None else "p1_army") or 0)
    ждём = t - с["t0"] if с["t0"] is not None else 0.0
    if всего > 0 and собрано >= float(п.get("сбор_доля", 0.8)) * всего and \
            (собрано >= его or ждём >= float(п.get("сбор_ждать", 120))):
        стр._сбор_сост = None
        # count обязателен: без него мост бракует ENGAGE («нужно число бойцов > 0», selftest_сбор)
        удар = {"cmd": "ENGAGE", "count": 200, "target": с["цель"]}
        if с["цель"] == "cell" and с.get("aim"):
            удар.update(cx=int(с["aim"][0]), cy=int(с["aim"][1]))
        отдано["ENGAGE (сбор)"] += 1
        return [{"cmd": "STAGE", "off": 1}, удар] + из
    return из


def _сзади(из: list, st: dict, п: dict, стр, пропущено, отдано) -> list:
    """СТРЕЛКИ ПОЗАДИ ВОЛНЫ (4.10, §87) — прикрытие §82 на НЫНЕШНЕМ блоке, без правок: пока волна в поле,
    через такт стрелки получают RETREAT who=musk17 в клетку на шаг от волны к нашей базе. RETREAT берёт
    бойцов дальше одной клетки от ратуши (идущих тоже), `who` — род, цель-клетка — ход без боя; там они стоят без
    приказа и, по замеру §82, бьют из соседней клетки. Одна команда волне за такт — поэтому в такты без
    своего ATTACK/RETREAT/ENGAGE. Проверка 4: стрелки шли с волной под приказом — 2 убитых на 12 своих."""
    if float(п.get("мушк_сзади", 0) or 0) < 0.5:
        return из
    стр._сзади_такт = not getattr(стр, "_сзади_такт", False)
    if not стр._сзади_такт or any(c.get("cmd") in ("ATTACK", "RETREAT", "ENGAGE", "MOVE", "STAGE") for c in из):
        return из
    if float(st.get("mil_shooters") or 0) < 3 or float(st.get("wave_n") or 0) < 5 or st.get("wave_cx") is None:
        return из
    wx, wy = int(float(st["wave_cx"])), int(float(st["wave_cy"]))
    нx, нy = _наша_база(st)
    кл = (wx + (нx > wx) - (нx < wx), wy + (нy > wy) - (нy < wy))
    отдано["RETREAT стрелков позади (§87)"] += 1
    # `target: cell` обязателен: без него разбор моста ставит цель base и клетку (-1,-1) — проверено to_commands
    return [{"cmd": "RETREAT", "count": 200, "who": "musk17", "target": "cell", "cx": int(кл[0]), "cy": int(кл[1])}] + из


def _шаг_к(откуда: tuple, куда: tuple, шагов: int = 1) -> tuple:
    x, y = откуда
    for _ in range(шагов):
        x += (куда[0] > x) - (куда[0] < x)
        y += (куда[1] > y) - (куда[1] < y)
    return (int(x), int(y))


def _прикрытие(из: list, st: dict, п: dict, стр, пропущено, отдано) -> list:
    """ПРИКРЫТИЕ (4.10, §93; манёвр §82 второй сессии — «пики бьют, стрелки позади», +9…+14 из 100 в
    эпизодах). Волна стратегии уходит ДВУМЯ группами: пики — её ATTACK (`who=infantry17`), стрелки —
    отдельный ATTACK в клетку на два шага от нашей ратуши к нему (два ATTACK за такт мост возит).
    Дальше в такты без своего ATTACK группе стрелков — RETREAT по номеру в клетку на шаг позади
    пикинёров (ход без боя; бьют из соседней клетки, §82). Через такт подмога «к волне» уступает
    место этому приказу: пару ATTACK + RETREAT группе мост в один файл пока не кладёт."""
    if float(п.get("прикрытие", 0) or 0) < 0.5:
        return из
    дом = _наша_база(st)
    его = _его_база(st) or дом
    if float(st.get("mil_shooters") or 0) >= 3:
        новые = []
        for c in из:
            if (c.get("cmd") == "ATTACK" and c.get("target") not in ("wave", "home") and not c.get("who")
                    and not c.get("group") and str(c.get("count")) not in ("0", "0.0")):
                кл = _шаг_к(дом, его, 2)
                новые.append(dict(c, who="infantry17"))
                новые.append({"cmd": "ATTACK", "count": "all", "who": "musk17", "target": "cell",
                              "cx": кл[0], "cy": кл[1]})
                отдано["ATTACK стрелков прикрытием (§93)"] += 1
                continue
            новые.append(c)
        из = новые
    # подтянуть стрелков за пикинёрами
    группы = [г for г in _группы(st) if int(г.get("n") or 0) > 0 and (int(г["cx"]), int(г["cy"])) != дом]
    пики = [г for г in группы if int(г.get("пик") or 0) >= int(г.get("стрелков") or 0) and int(г["n"]) >= 5]
    стрелки = [г for г in группы if int(г.get("стрелков") or 0) > int(г.get("пик") or 0) and int(г["n"]) >= 3]
    if not (пики and стрелки):
        return из
    P = max(пики, key=lambda г: int(г["n"]))
    M = max(стрелки, key=lambda г: int(г["n"]))
    цель = _шаг_к((int(P["cx"]), int(P["cy"])), дом, 1)
    if (int(M["cx"]), int(M["cy"])) == цель:
        return из
    стр._прикр_такт = not getattr(стр, "_прикр_такт", False)
    атаки = [c for c in из if c.get("cmd") in ("ATTACK", "RETREAT", "ENGAGE")]
    if атаки and not (стр._прикр_такт and all(c.get("cmd") == "ATTACK" and c.get("target") == "wave" for c in атаки)):
        return из
    if атаки:
        пропущено["подмога уступила такт прикрытию"] += 1
        из = [c for c in из if c not in атаки]
    отдано["RETREAT стрелков за пиками (§93)"] += 1
    return [{"cmd": "RETREAT", "count": 0, "group": int(M["id"]), "target": "cell",
             "cx": цель[0], "cy": цель[1]}] + из


def привести(сырые: list, st: dict, п: dict, стр, пропущено, отдано) -> list:
    """Команды стратегии → то, что уходит в игру за такт (3.10, §57; общее для симулятора и моста).

    Внутренние команды симулятора (`_ЗАПАС`, `_ВПЕРЁД`, …) отбрасываются — мост их не умеет, и
    симулятор не должен на них рассчитывать; одна волна за такт; доли еды/дерева/камня от людей
    на земле; золото и железо явно; одна закладка за такт; порядок и потолок."""
    из, атака = [], 0
    for c in сырые:
        cmd = str(c.get("cmd") or "")
        if cmd.startswith("_"):
            # ЧЕТЫРЕ ПРИКАЗА ВОЛНЕ В ПОЛЕ (3.10, задание игрока) переводятся в мостовые,
            # а не отбрасываются — но ТОЛЬКО на живом мосте: симулятор исполняет их сам и
            # точнее (`sim.py`, `_К_СВОИМ` сводит две группы навстречу), а здесь они
            # становятся тем, что игра действительно умеет. Что именно умеет и чем это
            # отличается от симулятора — в `_в_мостовые`, и то же говорится вслух в `why`.
            переведено = _лицом_к_врагу(
                _в_мостовые(c, cmd, st), st) if ЖИВОЙ_МОСТ else None
            if переведено is None:
                пропущено[cmd] += 1
                continue
            пропущено[f"{cmd} -> {переведено['cmd']}"] += 1
            отдано[переведено["cmd"]] += 1
            из.append(переведено)
            continue
        c = dict(c)
        if cmd == "UPGRADE" and "upg" in c:
            c["role"] = c.pop("upg")
        if cmd == "RETREAT":
            c.setdefault("count", 200)
        if cmd == "ATTACK":
            # ВТОРОЙ УДАР БОЛЬШЕ НЕ РЕЖЕТСЯ (4.10). Прежде за такт уезжал один:
            # файл приказа нёс одну команду. Партия проверки 5 показала цену —
            # стратегия просила два удара В КАЖДОМ ТАКТЕ (по базе и подмогу к
            # волне), и один из них пропадал каждый такт. С §78 файл возит список,
            # и `to_commands` отправляет оба одним файлом; третий и дальше по-
            # прежнему не возим, и мост говорит об этом вслух.
            атака += 1
            if атака > 2:
                пропущено["ATTACK третий за такт"] += 1
                continue
        отдано[cmd] += 1
        из.append(c)
    из = _сбор(из, st, п, стр, пропущено, отдано)
    из = _сзади(из, st, п, стр, пропущено, отдано)
    из = _прикрытие(из, st, п, стр, пропущено, отдано)
    # ЕДА И ЗОЛОТО ЯВНО (3.10, контейнер Windows `smoke_strategy/1`: стратегия ни разу не дала
    # BALANCE food — еда 993 -> 0 к 2:33, крестьян 18 -> 3). Ярус 1 шлёт на еду только
    # ПРОСТАИВАЮЩИХ (4 и больше) — в симуляторе их много, вживую почти нет, а мостовой дебют
    # короткий (n бойцов) и кончается раньше созревания поля. Здесь доля еды из стратегии
    # (`еда_до` до 7:00, `еда_после` после) и 5 на шахту золота выставляются каждый такт.
    gt = float(st.get("gametime") or 0)
    крест = float(st.get("peasants") or 0)
    доля = float(п.get("еда_до", 2 / 3)) if gt < 420 else float(п.get("еда_после", 1 / 3))
    # ДОЛИ ОТ ЛЮДЕЙ НА ЗЕМЛЕ (3.10, третий прогон: на еде 9 из 35 при цели 17 — 20 человек в
    # шахтах, на земле 15, а еда+дерево+камень просили 29, и мост резал все три
    # пропорционально, `llm_policy.распределить_balance`). Земля — как у моста: крестьяне
    # минус шахтёры минус строители. Еда первой (доля деревни, но не больше земли), дерево и
    # камень — из остатка; сумма не превышает землю, и мосту резать нечего.
    земля = max(0, int(крест - float(st.get("on_mine") or 0) - float(st.get("on_build") or 0)))
    # 3.10 (§64, контейнер smoke_net): «еда первой» отдавала еде всю землю — с 4:00 до 7:00 на
    # дереве и камне 0-3 человека, камня 20, вторая шахта золота к 9:00, вторая казарма к 11:30,
    # а еды к 10:00 лежало 5 тысяч без дела. Теперь сперва МИНИМУМ дерева и камня стратегии
    # (ярус 1 так и задуман: «держать на дереве не меньше стольких»), еде — остальное.
    # `COSS3_WOOD_FIRST=0` — как было.
    # …но только когда еды запасено (`ЗАПАС_ЕДЫ_ДЕРЕВУ`, 1000): без порога «дерево первым» в
    # начале снимало с еды всех, и деревня гибла (симулятор: армия к 10:00 — 4)
    # рычаг стратегии `дерево_при_еде` (§65) — порог запаса еды; от 5900 — никогда (как «еда
    # первой»); без рычага — выключатель окружения, как раньше
    порог = п.get("дерево_при_еде")
    if порог is not None:
        дерево_первым = float(порог) < 5900 and float(st.get("food") or 0) >= float(порог)
    else:
        дерево_первым = ДЕРЕВО_ПЕРВЫМ and float(st.get("food") or 0) >= ЗАПАС_ЕДЫ_ДЕРЕВУ
    мин_дер = мин_кам = 0
    if дерево_первым:
        мин_дер = min(int(п.get("дерево", 0)), земля)
        мин_кам = min(int(п.get("камень", 0)), земля - мин_дер)
        цель_еды = max(0, min(int(крест * доля), земля - мин_дер - мин_кам))
    else:
        цель_еды = min(int(крест * доля), земля)
    if float(st.get("mills") or 0) >= 1 and float(st.get("on_food") or 0) < цель_еды - 1:
        из = [c for c in из if not (c["cmd"] == "BALANCE" and c.get("role") == "food")]
        из.append({"cmd": "BALANCE", "role": "food", "total": цель_еды, "_важно": True})
        отдано["BALANCE food (переходник)"] += 1
    остаток = земля - (цель_еды if float(st.get("mills") or 0) >= 1 else 0)
    for роль in ("wood", "stone"):
        for c in из:
            if c["cmd"] == "BALANCE" and c.get("role") == роль:
                c["total"] = max(0, min(int(c.get("total") or 0), остаток))
        остаток -= min(int(п.get({"wood": "дерево", "stone": "камень"}[роль], 0)), max(остаток, 0))
    из = [c for c in из if not (c["cmd"] == "BALANCE" and c.get("role") in ("wood", "stone") and c["total"] <= 0)]
    if дерево_первым:
        for роль, ключ, мин in (("wood", "on_wood", мин_дер), ("stone", "on_stone", мин_кам)):
            if мин > 0 and float(st.get(ключ) or 0) < мин and not any(c["cmd"] == "BALANCE" and c.get("role") == роль for c in из):
                из.append({"cmd": "BALANCE", "role": роль, "total": мин, "_важно": True})
    # СТРОЙКА ЯВНО (3.10, контейнер `smoke_strategy` второй прогон: армия встала на 17 — железо
    # кончилось к 4:57, шахты железа не было ни одной; вторая казарма и шахты золота 2-3 тоже
    # не встали). Ярус 1 ставит закладку, только пока ничего не строится, а стратегия каждый
    # такт просит академию — вживую что-то строится всегда; и потолок 7 срезал стройки в
    # хвосте списка. Здесь — ОДНА закладка за такт, самая нужная по порядку: шахта железа →
    # шахта золота → казармы → дом → академия. BUILD декларативный (total — сколько должно
    # стоять), повтор безопасен.
    из = [c for c in из if c["cmd"] not in ("BUILD", "BUILDERS")]
    def ч(k):
        return float(st.get(k) or 0)
    есть_дер_кам = ч("wood") >= 100 and ч("stone") >= 100
    закладка = None
    if ч("ba17") >= 1 and ч("mines_iron") < 1 and есть_дер_кам:
        закладка = ("mineiron", 1)
    elif (ч("mines_gold") < int(п.get("шахт_золота", 2)) and ч("on_gold") >= 5 * ч("mines_gold") - 1
          and есть_дер_кам):
        закладка = ("minegold", int(ч("mines_gold")) + 1)
    elif ч("ba17") >= 1 and ч("ba17") < int(п.get("казарм", 1)):
        закладка = ("ba17", int(ч("ba17")) + 1)
    elif ч("my_farm") - ч("my_farmused") <= 5 and есть_дер_кам:
        закладка = ("house", int(ч("houses")) + 1)
    elif стр.академия and ч("ba17") >= 1 and ч("academies") < 1 and gt >= getattr(стр, "академия_с", 0):
        закладка = ("academi", 1)
    if закладка:
        из += [{"cmd": "BUILDERS", "total": 5}, {"cmd": "BUILD", "role": закладка[0], "total": закладка[1]}]
        отдано[f"BUILD {закладка[0]} (переходник)"] += 1
    if ч("mines_iron") >= 1 and ч("on_iron") < 5:
        из = [c for c in из if not (c["cmd"] == "BALANCE" and c.get("role") == "iron")]
        из.append({"cmd": "BALANCE", "role": "iron", "total": 5, "_важно": True})
    шахт = float(st.get("mines_gold") or 0)
    if шахт >= 1 and float(st.get("on_gold") or 0) < 5 * шахт:
        из = [c for c in из if not (c["cmd"] == "BALANCE" and c.get("role") == "gold")]
        из.append({"cmd": "BALANCE", "role": "gold", "total": int(5 * шахт), "_важно": True})
    # ПОТОЛОК КОМАНД ЗА ТАКТ — 12 (решение игрока 3.10). Порядок всё равно нужен:
    # волна и прокачки — вперёд, затем стройка (BUILDERS сразу перед своим BUILD),
    # найм, люди; повтор BALANCE по ресурсу — последний.
    #
    # Семь стояло как «мост читает не больше семи», и это ОКАЗАЛОСЬ НЕВЕРНО: предела в
    # семь нет ни в python (`coss3_bridge.send` пишет `count` и столько пар, сколько
    # дали), ни в блоке (`block_hcmd.inc:84,91` — `for hcn := 0 to hccount-1`). Семь
    # живёт только в тексте промпта для МОДЕЛИ (`llm_policy.py:346`), а стратегия
    # моделью не идёт. Чего семь стоило, измерено контейнером 3.10: после того как
    # встала академия (749 с), стратегия просит по семь `aca.*` за такт, вес UPGRADE
    # равен 1, и в окно не проходило НИЧЕГО — ни еды, ни найма, ни стройки в 89 тактах
    # подряд (срезано 1032 команды), а между 7:00 и 12:30 еда доходила в 8 тактах из 64.
    пары, прочее = [], []
    for i, c in enumerate(из):
        if c["cmd"] == "BUILD":
            пред = из[i - 1] if i and из[i - 1]["cmd"] == "BUILDERS" else None
            пары.append([пред, c] if пред else [c])
        elif c["cmd"] != "BUILDERS":
            прочее.append(c)
    вес = {"ATTACK": 0, "RETREAT": 0, "STAGE": 0, "ENGAGE": 0, "UPGRADE": 1, "FORMATION": 1, "SEED": 3, "TRAIN": 4, "BALANCE": 5}
    балансы = {}
    for c in прочее:
        if c["cmd"] == "BALANCE":
            балансы[c.get("role")] = c
    прочее = [c for c in прочее if c["cmd"] != "BALANCE"] + list(балансы.values())
    прочее.sort(key=lambda c: вес.get(c["cmd"], 6))
    важные = [c for c in прочее if c.get("_важно")]
    прочее = [c for c in прочее if not c.get("_важно")]
    for c in важные:
        c.pop("_важно", None)
    # еда и золото — сразу после волны и прокачек, раньше строек: их не срезает потолок
    из = [c for c in прочее if вес.get(c["cmd"], 6) <= 1] + важные + [x for пара in пары for x in пара] + \
        [c for c in прочее if вес.get(c["cmd"], 6) > 1]
    if len(из) > ПОТОЛОК_КОМАНД:
        пропущено[f"сверх {ПОТОЛОК_КОМАНД} команд"] += len(из) - ПОТОЛОК_КОМАНД
        из = из[:ПОТОЛОК_КОМАНД]
    return из
