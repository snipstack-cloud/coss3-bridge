#!/usr/bin/env python3
"""§170м (25.10, Д14/Д15, слово игрока «все три части» + четвёртая по Д15): пол пахарей прокормом, добор до пола вместо
«все на еду», нужда спит до mil.1, порог золота по цене просимого. Кейсы — живые такты Д14 (`партия_д14_24_10_3-00_7-40`)
и Д15 (`партия_д15_25_10_5-30_7-30`). Ключи в файле партии на 25.10 — 0; тест ставит их сам и судит правило.

(а) Д14 3:40 (еда 565, нужда включена, 23 крестьянина, на еде 6): `пол_прокормом` 1 — пол ≥ 10, запись §170м; ключ 0 — еда 6.
(б) Д14 4:40 → 4:55 (еда 403 < гистерезиса 420): `добор_до_пола` 2 — нужда не гаснет (§167 в why), еда растёт на 2, не «все
    на еду»; ключ 0 — BALANCE food ≥ 17 (как было).
(в) Д14 3:34 (еда 614, mil.1 не куплена, 3:34 ≤ 5:00, бойцов 5): `нужда_после_mil1` 1 — нужда спит (порог 1550), §167 молчит;
    ключ 0 — §167 переброс.
(г) Д15 6:27 (золото 2501, казарма 2 ждёт по 2500): `золото_по_цене` 1 — §166б не снимает шахтёров (порог 2800); ключ 0 — снимает.
    Д15 6:56 (золото 278, на золоте 5 из 15, на дереве 14; ключи Д15, бюджет с академией 0): возврат шахтёров — приказ wood
    ниже 14, запись §170м; ключ 0 — wood не ниже.

    python3 selftest_д15_прокорм.py
"""
import copy, json, os, sys, tempfile
К = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, К); sys.path.insert(0, os.path.join(К, "sim"))
os.environ.pop("COSS3_WAVE_CONTRACT", None)
import strategy_live as SL
import анализ_врага as АВ

д14 = [json.loads(l) for l in open(os.path.join(К, "sim/кейсы/партия_д14_24_10_3-00_7-40.jsonl"), encoding="utf-8")]
д15 = [json.loads(l) for l in open(os.path.join(К, "sim/кейсы/партия_д15_25_10_5-30_7-30.jsonl"), encoding="utf-8")]
ошибок = 0
def проверить(усл, что):
    global ошибок
    print(("ОК   " if усл else "ОШИБКА ") + что); ошибок += not усл
def стратегия(доп):
    д = json.load(open(os.path.join(К, "sim/поиск/шт_s2_оборона_ручеёк_эко_так15_нужда.json"), encoding="utf-8"))
    д["итог"].update({"переброс_раз": 0, "бюджет_с_академией": 1, "пол_прокормом": 0, "добор_до_пола": 0, "нужда_после_mil1": 0, "золото_по_цене": 0})
    д["итог"].update(доп)
    with tempfile.NamedTemporaryFile("w", suffix=".json", delete=False, encoding="utf-8") as f:
        json.dump(д, f, ensure_ascii=False)
    return SL.ЖиваяСтратегия(f.name)
def при(кейс, t): return next(s for s in кейс if float(s["gametime"]) >= t)
def ответ(С, s):
    АВ._ТЕКУЩИЙ.update({"а": None, "t": None, "ответ": None}); return С.ответ(copy.deepcopy(s))
def баланс(о, роль):
    v = [c.get("total") for c in о["commands"] if c["cmd"] == "BALANCE" and c.get("role") == роль]
    return v[-1] if v else None
def метки(о, что): return [x for x in о["why"].split(", ") if что in x][:3]

def прогон(доп, кейс, t0, t1):
    """одна стратегия ведётся по тактам t0..t1 — нужда и гистерезис живут в её состоянии"""
    С = стратегия(доп); о = None; последний = None
    for s in кейс:
        if t0 <= float(s["gametime"]) <= t1:
            о = ответ(С, s); последний = s
    return о, последний
# (а) пол прокормом: нужда проснулась в 3:34 (еда 614), судим 3:40
о1, s = прогон({"пол_прокормом": 1}, д14, 200, 220)
о0, _ = прогон({}, д14, 200, 220)
проверить("§170м пол пахарей прокормом" in о1["why"] and (баланс(о1, "food") or 0) >= 10,
          f"(а) {s['gametime']} с еда {s['food']} крестьян {s['peasants']}: food {баланс(о1, 'food')}, wood {баланс(о1, 'wood')}; {метки(о1, '§170м')}")
проверить("§170м" not in о0["why"] and (баланс(о0, "food") or 0) <= 6 and "§167" in о0["why"], f"(а′) ключ 0: food {баланс(о0, 'food')}, wood {баланс(о0, 'wood')}")
# (б) добор до пола: тот же прогон до 4:55 (еда 403 < 420)
о1, s = прогон({"добор_до_пола": 2}, д14, 200, 296)
о0, _ = прогон({}, д14, 200, 296)
проверить("§170м добор до пола" in о1["why"] and "§167 переброс" in о1["why"] and 6 < (баланс(о1, "food") or 0) < 15,
          f"(б) {s['gametime']} с еда {s['food']}: food {баланс(о1, 'food')}, wood {баланс(о1, 'wood')}; {метки(о1, '§170м')}")
проверить((баланс(о0, "food") or 0) >= 17 and "§167" not in о0["why"], f"(б′) ключ 0 — все на еду: food {баланс(о0, 'food')}; {метки(о0, 'ждёт еды')}")
# (в) нужда спит до mil.1: 3:34
о1, s = прогон({"нужда_после_mil1": 1}, д14, 200, 214)
о0, _ = прогон({}, д14, 200, 214)
проверить("§170м нужда спит до mil.1" in о1["why"] and "§167 переброс" not in о1["why"] and (баланс(о1, "food") or 0) >= 10,
          f"(в) {s['gametime']} с еда {s['food']} mil.1 нет: food {баланс(о1, 'food')}, wood {баланс(о1, 'wood')}; {метки(о1, '§170м')}")
проверить("§167 переброс" in о0["why"], f"(в′) ключ 0: {метки(о0, '§167')}")
# (г) золото по цене: первый такт Д15 с золотом ≥ 2500 при одной казарме
tз = next(float(s["gametime"]) for s in д15 if float(s["gold"]) >= 2500 and float(s["ba17"]) == 1)
о1, s = прогон({"золото_по_цене": 1}, д15, 330, tз)
о0, _ = прогон({}, д15, 330, tз)
проверить("золото лежит" not in о1["why"] and баланс(о1, "gold") != 5,
          f"(г) {s['gametime']} с золото {s['gold']} казарма ждёт: gold {баланс(о1, 'gold')}; {метки(о1, 'золото')}")
проверить("золото лежит (≥ 2500)" in о0["why"] and баланс(о0, "gold") == 5, f"(г′) ключ 0: gold {баланс(о0, 'gold')}; {метки(о0, 'золото лежит')}")
# возврат шахтёров после покупки (6:56: золото 278, на золоте 5 из 15)
о1, s = прогон({"золото_по_цене": 1, "бюджет_с_академией": 0}, д15, 330, 416)   # ключи Д15: бюджет с академией 0, цель §167 — дерево
о0, _ = прогон({"бюджет_с_академией": 0}, д15, 330, 416)
проверить("§170м возврат шахтёров" in о1["why"] and баланс(о1, "gold") == 15 and (баланс(о1, "wood") or 99) < s["on_wood"],
          f"(г″) {s['gametime']} с золото {s['gold']} на золоте {s['on_gold']}, на дереве {s['on_wood']}: wood {баланс(о1, 'wood')}, gold {баланс(о1, 'gold')}; {метки(о1, '§170м')}")
проверить("§170м" not in о0["why"] and баланс(о0, "gold") == 15, f"(г‴) ключ 0: wood {баланс(о0, 'wood')}, gold {баланс(о0, 'gold')}; {метки(о0, '§167')}")
print(f"\nошибок: {ошибок}")
