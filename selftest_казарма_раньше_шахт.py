#!/usr/bin/env python3
"""КАЗАРМА РАНЬШЕ ШАХТ И НУЖДА БЕЗ МИГАНИЯ (10.10, §133): состояния смоука партии Д против невозможного 5:00-8:08
(`sim/кейсы/партия_смоук_д_5_00-8_08.jsonl`, из `coss3_bot.jsonl` 10.10). Вживую: шахты золота 2-3 съели 200 дерева из
308 принесённых, казарма не встала; `on_wood` ходил 7 → 0 → 7 → 0 вместе с едой вокруг порога 2788.

С ключами `казарма_раньше_шахт` 1 и `нужда_при_еде` 1200: (а) при дереве 190 / камне 120, ждущей казарме и золоте
БЛИЗКО к 2500 шахта НЕ закладывается, закладка — казарма; (б) при еде 2416-2700 (< 2788, ≥ 1200) на дерево просится
не меньше 7; (в) при дереве/камне ≥ 600 шахта снова разрешена; (г) при 500/500/2500 казарма идёт первой. Без ключей — как было.

§134 (второй смоук Д, `sim/кейсы/партия_смоук_д133_4_40-7_15.jsonl`): резерв задержал шахту 2 с 4:49 до 5:53, а казарму
держало золото (1561 из 2500 к 7:15). Ключ `резерв_при_золоте` 600: (д) в 4:49 (374/220, золота 964 — не хватает 1536)
шахта 2 закладывается; с ключом 0 — нет, как в §133; (е) там же при золоте 2000 (не хватает 500 ≤ 600) резерв держит,
закладка — казарма; (ж) в 5:53 (738/620) шахта при любом ключе.

    python3 selftest_казарма_раньше_шахт.py
"""
import copy, json, os, sys, tempfile
К = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, К); sys.path.insert(0, os.path.join(К, "sim"))
import strategy_live as SL
import анализ_врага as АВ

состояния = [json.loads(l) for l in open(os.path.join(К, "sim/кейсы/партия_смоук_д_5_00-8_08.jsonl"), encoding="utf-8")]
ошибок = 0
def проверить(усл, что):
    global ошибок
    print(("ОК   " if усл else "ОШИБКА ") + что)
    ошибок += not усл

def стратегия(доп):
    д = json.load(open(os.path.join(К, "sim/поиск/шт_s2_оборона_ручеёк_эко_так15_нужда.json"), encoding="utf-8"))
    д["итог"]["переброс"] = 0          # §167 (18.10) переносит всю бригаду на ресурс с большей недостачей; здесь судится деление §133
    # 26.10: §170п (`переброс_раз` 50 в файле партии) даёт одно перемещение за 50 с и гасит остальные приказы.
    # Здесь судятся правила ДО него — пришпиливаем к 0, как мак сделал для трёх своих.
    д["итог"]["переброс_раз"] = 0
    # 29.10: ключи стока/казармы/гистерезиса в живом файле — здесь судятся старые правила, пришпилены к 0
    for _к5 in ("сток_излишек", "золото_лежит_по_факту", "шахта_без_срока", "закладка_по_срокам", "выпущенные_в_бюджет", "переброс_по_долям", "недостача_по_казарме", "казарма_первой_в_оплате", "пули_при_стрелках", "цель_гистерезис", "прогноз_по_лагерю", "выход_не_при_осаде", "оборона_всем"):
        д["итог"][_к5] = 0
    д["итог"].update(доп)
    with tempfile.NamedTemporaryFile("w", suffix=".json", delete=False, encoding="utf-8") as f:
        json.dump(д, f, ensure_ascii=False)
    return SL.ЖиваяСтратегия(f.name)

def ответ(С, st):
    АВ._ТЕКУЩИЙ.update({"а": None, "t": None, "ответ": None})
    return С.ответ(copy.deepcopy(st))

def стройки(о):
    return [(c.get("role"), c.get("total")) for c in о["commands"] if c["cmd"] == "BUILD"]

def дерево(о):
    return max([int(c.get("total") or 0) for c in о["commands"] if c["cmd"] == "BALANCE" and c.get("role") == "wood"] or [0])

# состояние 5:46: шахт золота 1, дерево 190, камень 120, казарма 1 из 3, еда 3201 — вживую тут заложили шахту 2
st_а = next(s for s in состояния if s["gametime"] >= 346)
# состояние с едой ниже 2788 и выше 1200, шахт 2 (6:17: еда 2841 → 6:47 2623)
st_б = next(s for s in состояния if 1200 <= float(s["food"]) < 2788 and s["gametime"] > 360)
print(f"состояния: а {st_а['gametime']} с (дерево {st_а['wood']}, камень {st_а['stone']}, еда {st_а['food']}), "
      f"б {st_б['gametime']} с (еда {st_б['food']}, on_wood {st_б['on_wood']})")

новая, старая = стратегия({}), стратегия({"казарма_раньше_шахт": 0, "нужда_при_еде": 0})

# (а) золото близко (2100 из 2500): резерв держит, шахта при 190 дерева не закладывается
st_а_зол = dict(st_а); st_а_зол["gold"] = 2100
о = ответ(новая, st_а_зол)
проверить(not any(р == "minegold" for р, _ in стройки(о)), f"(а) с ключом и золотом 2100 шахта 2 при дереве {st_а['wood']} не закладывается: {стройки(о)}")
проверить(any(р == "ba17" for р, _ in стройки(о)), f"(а) закладка — казарма: {стройки(о)}")
о0 = ответ(старая, st_а)
проверить(any(р == "minegold" for р, _ in стройки(о0)), f"без ключа шахта 2 закладывается, как было: {стройки(о0)}")

о = ответ(новая, st_б)
проверить(дерево(о) >= 7, f"(б) при еде {st_б['food']} на дерево просится ≥ 7: {дерево(о)}")
о0 = ответ(старая, st_б)
проверить(дерево(о0) < 7, f"без ключа при еде {st_б['food']} дерево мигает (< 7), как было: {дерево(о0)}")

st_в = dict(st_а); st_в.update({"wood": 620, "stone": 610, "gold": 1500})
о = ответ(новая, st_в)
проверить(any(р == "minegold" for р, _ in стройки(о)), f"(в) при дереве 620 / камне 610 шахта 2 разрешена: {стройки(о)}")

st_г = dict(st_а); st_г.update({"wood": 520, "stone": 510, "gold": 2600})
о = ответ(новая, st_г)
проверить(стройки(о) and стройки(о)[0][0] == "ba17", f"(г) при 520/510/2600 казарма первой: {стройки(о)}")

# §134: второй смоук — резерв только когда золото близко
состояния133 = [json.loads(l) for l in open(os.path.join(К, "sim/кейсы/партия_смоук_д133_4_40-7_15.jsonl"), encoding="utf-8")]
st_д = next(s for s in состояния133 if s["gametime"] >= 289)          # 4:49: 374/220, золота 964, шахта 1, на золоте 5
st_ж = next(s for s in состояния133 if s["gametime"] >= 353)          # 5:53: 738/620 — вживую тут заложили шахту 2
print(f"состояния §134: д {st_д['gametime']} с (дерево {st_д['wood']}, камень {st_д['stone']}, золото {st_д['gold']}, "
      f"шахт {st_д['mines_gold']}, на золоте {st_д['on_gold']}), ж {st_ж['gametime']} с ({st_ж['wood']}/{st_ж['stone']})")
всегда = стратегия({"резерв_при_золоте": 0})
о = ответ(новая, st_д)
проверить(any(р == "minegold" for р, _ in стройки(о)), f"(д) 4:49, золота не хватает {2500 - st_д['gold']}: шахта 2 закладывается: {стройки(о)}")
о0 = ответ(всегда, st_д)
проверить(not any(р == "minegold" for р, _ in стройки(о0)), f"(д) с ключом 0 резерв держит, как в §133 (вживую шахта ждала до 5:53): {стройки(о0)}")
st_е = dict(st_д); st_е["gold"] = 2000
о = ответ(новая, st_е)
проверить(not any(р == "minegold" for р, _ in стройки(о)) and any(р == "ba17" for р, _ in стройки(о)),
          f"(е) 4:49 при золоте 2000 (не хватает 500 ≤ 600) резерв держит, закладка — казарма: {стройки(о)}")
for имя, С in (("600", новая), ("0", всегда)):
    о = ответ(С, st_ж)
    проверить(any(р == "minegold" for р, _ in стройки(о)), f"(ж) 5:53 при 738/620 шахта 2 при ключе {имя}: {стройки(о)}")

# цена из состояния
проверить(SL._цена_здания(st_а, "ba17") == {"wood": 500, "stone": 500, "gold": 2500}, f"цена казармы из build_cost: {SL._цена_здания(st_а, 'ba17')}")
проверить(SL._цена_здания({}, "ba17") == {}, "без build_cost — пусто (двойник берёт 500/500/2500)")
print(f"ошибок: {ошибок}")
sys.exit(1 if ошибок else 0)
