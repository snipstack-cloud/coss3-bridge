#!/usr/bin/env python3
"""КАЗАРМА РАНЬШЕ ШАХТ И НУЖДА БЕЗ МИГАНИЯ (10.10, §133): состояния смоука партии Д против невозможного 5:00-8:08
(`sim/кейсы/партия_смоук_д_5_00-8_08.jsonl`, из `coss3_bot.jsonl` 10.10). Вживую: шахты золота 2-3 съели 200 дерева из
308 принесённых, казарма не встала; `on_wood` ходил 7 → 0 → 7 → 0 вместе с едой вокруг порога 2788.

С ключами `казарма_раньше_шахт` 1 и `нужда_при_еде` 1200: (а) при дереве 190 / камне 120 и ждущей казарме шахта НЕ
закладывается, закладка — казарма; (б) при еде 2416-2700 (< 2788, ≥ 1200) на дерево просится не меньше 7;
(в) при дереве/камне ≥ 600 шахта снова разрешена; (г) при 500/500/2500 казарма идёт первой. Без ключей — как было.

    python3 selftest_казарма_раньше_шахт.py
"""
import copy, json, os, sys, tempfile
К = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, К); sys.path.insert(0, os.path.join(К, "sim"))
import strategy_live as SL
import анализ_врага as АВ

состояния = [json.loads(l) for l in open(os.path.join(К, "sim/кейсы/партия_смоук_д_5_00-8_08.jsonl"), encoding="utf-8")]
ошибок = 0
def проверить(усл, что):
    global ошибок
    print(("ОК   " if усл else "ОШИБКА ") + что)
    ошибок += not усл

def стратегия(доп):
    д = json.load(open(os.path.join(К, "sim/поиск/шт_s2_оборона_ручеёк_эко_так15_нужда.json"), encoding="utf-8"))
    д["итог"].update(доп)
    with tempfile.NamedTemporaryFile("w", suffix=".json", delete=False, encoding="utf-8") as f:
        json.dump(д, f, ensure_ascii=False)
    return SL.ЖиваяСтратегия(f.name)

def ответ(С, st):
    АВ._ТЕКУЩИЙ.update({"а": None, "t": None, "ответ": None})
    return С.ответ(copy.deepcopy(st))

def стройки(о):
    return [(c.get("role"), c.get("total")) for c in о["commands"] if c["cmd"] == "BUILD"]

def дерево(о):
    return max([int(c.get("total") or 0) for c in о["commands"] if c["cmd"] == "BALANCE" and c.get("role") == "wood"] or [0])

# состояние 5:46: шахт золота 1, дерево 190, камень 120, казарма 1 из 3, еда 3201 — вживую тут заложили шахту 2
st_а = next(s for s in состояния if s["gametime"] >= 346)
# состояние с едой ниже 2788 и выше 1200, шахт 2 (6:17: еда 2841 → 6:47 2623)
st_б = next(s for s in состояния if 1200 <= float(s["food"]) < 2788 and s["gametime"] > 360)
print(f"состояния: а {st_а['gametime']} с (дерево {st_а['wood']}, камень {st_а['stone']}, еда {st_а['food']}), "
      f"б {st_б['gametime']} с (еда {st_б['food']}, on_wood {st_б['on_wood']})")

новая, старая = стратегия({}), стратегия({"казарма_раньше_шахт": 0, "нужда_при_еде": 0})

о = ответ(новая, st_а)
проверить(not any(р == "minegold" for р, _ in стройки(о)), f"(а) с ключом шахта 2 при дереве {st_а['wood']} не закладывается: {стройки(о)}")
проверить(any(р == "ba17" for р, _ in стройки(о)), f"(а) закладка — казарма: {стройки(о)}")
о0 = ответ(старая, st_а)
проверить(any(р == "minegold" for р, _ in стройки(о0)), f"без ключа шахта 2 закладывается, как было: {стройки(о0)}")

о = ответ(новая, st_б)
проверить(дерево(о) >= 7, f"(б) при еде {st_б['food']} на дерево просится ≥ 7: {дерево(о)}")
о0 = ответ(старая, st_б)
проверить(дерево(о0) < 7, f"без ключа при еде {st_б['food']} дерево мигает (< 7), как было: {дерево(о0)}")

st_в = dict(st_а); st_в.update({"wood": 620, "stone": 610, "gold": 1500})
о = ответ(новая, st_в)
проверить(any(р == "minegold" for р, _ in стройки(о)), f"(в) при дереве 620 / камне 610 шахта 2 разрешена: {стройки(о)}")

st_г = dict(st_а); st_г.update({"wood": 520, "stone": 510, "gold": 2600})
о = ответ(новая, st_г)
проверить(стройки(о) and стройки(о)[0][0] == "ba17", f"(г) при 520/510/2600 казарма первой: {стройки(о)}")

# цена из состояния
проверить(SL._цена_здания(st_а, "ba17") == {"wood": 500, "stone": 500, "gold": 2500}, f"цена казармы из build_cost: {SL._цена_здания(st_а, 'ba17')}")
проверить(SL._цена_здания({}, "ba17") == {}, "без build_cost — пусто (двойник берёт 500/500/2500)")
print(f"ошибок: {ошибок}")
sys.exit(1 if ошибок else 0)
