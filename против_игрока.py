    if новое_gt is None:
        print(f"новая партия не поднялась: на слоте {партия['слот']} время не пошло "
              f"назад от {было_gt}. Старая партия ещё идёт или карта не "
              f"сгенерировалась — модель не запускаю, иначе она получит не ту партию")
