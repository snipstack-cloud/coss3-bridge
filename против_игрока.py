def _ц(к: configparser.SectionProxy, имя: str, умолчание: int = -1) -> int:
    v = (к.get(имя) or "").strip()
    try:
        return int(v)
    except ValueError:
        return умолчание


def прочитать(путь: str) -> tuple[dict, dict]:
    к = configparser.ConfigParser()
    # Ключи с кириллицей и БЕЗ приведения регистра: configparser по умолчанию
    # опускает имена в нижний регистр, а у нас они и так строчные — но пусть
    # будет явно, чтобы правка ini не ломала чтение.
    к.optionxform = str
    прочитано = к.read(путь, encoding="utf-8")
    if not прочитано:
        raise SystemExit(f"не нашёл настройку {путь}")
    if "партия" not in к or "бот" not in к:
        raise SystemExit(f"в {путь} нужны разделы [партия] и [бот]")
    п, б = к["партия"], к["бот"]
    партия = dict(
        слот=_ц(п, "слот_бота", 1),
        нация=(п.get("нация") or "").strip(),
        # НАЦИЯ ВТОРОГО СЛОТА ОТДЕЛЬНО (29.10, `nation2` мака). Пусто — как
        # было: одно значение `нация` уезжает ОБОИМ слотам. Против человека
        # слот 0 ваш, слот 1 бота, значит `нация` — ваша, а `нация_бота` — его;
        # против ИИ наоборот (бот на нуле, ИИ на первом). Нужно это для судьи
        # §170н «противник другой нации» — вопрос игрока «как обороняться,
        # если он выберет Польшу»: вы берёте Польшу, бот остаётся на
        # Нидерландах, и сравнимость его хозяйства со всеми прежними партиями
        # цела.
        нация_бота=(п.get("нация_бота") or "").strip(),
        mapsize=_ц(п, "размер_карты"),
        res=_ц(п, "ресурсы"),
        peace=_ц(п, "мир"),
        balloon=_ц(п, "шар"),
        cannons=_ц(п, "пушки"),
        capture=_ц(п, "захват"),
        market=_ц(п, "рынок"),
        century18=_ц(п, "век18"),
        speed=_ц(п, "скорость"),
    )
    бот = dict(
        модель=(б.get("модель") or "").strip(),
        каждые=_ц(б, "решение_раз_в", 15),
        горизонт=_ц(б, "горизонт", 900),
        подсказка=(б.get("подсказка") or "").strip(),
        запрет=(б.get("запрет") or "").strip(),
        армия_по_клеткам=_ц(б, "армия_по_клеткам", 0),
        числа18=_ц(б, "числа_18_века", 0),
        каталог=(б.get("каталог") or "").strip(),
        адрес=(б.get("адрес") or "").strip(),
        ключи=(б.get("ключи") or "").strip(),
    )
    return партия, бот


def _ключ_стратегии(ключи: str) -> str:
    """Путь из `--strategy файл.json` в строке лишних ключей, иначе пусто.

    Нужно потому, что ключ может лежать в `ключи` файла настройки — и тогда
    модель не зовётся так же, как со своим `--стратегия`. Читать это надо ДО
    контроля: иначе он требует счёт у модели, которой в партии не будет.
    """
    части = (ключи or "").split()
    for i, ч in enumerate(части):
        if ч == "--strategy" and i + 1 < len(части):
            return части[i + 1]
        if ч.startswith("--strategy="):
            return ч.split("=", 1)[1]
    return ""


