    # верно поймал новую партию по времени, пошедшему назад, запустил модель —
    # и тут игра замерла на догенерации карты. В первом прогоне тишина длилась
    # больше 30 с, во втором больше 60 с даже с поднятым `--stall 60`: состояние
    # стояло на 20-й игровой секунде, а возобновилось около 2:00, когда модель
    # была уже мертва. Поднимать терпение дальше нельзя — тогда настоящий обрыв
    # (свёрнутое окно, конец партии) заметится слишком поздно. Поэтому ждём здесь
    # и дешёво: пока игровое время не прибавит ШАГ_ЖИВОЙ секунд от первого
    # прочитанного. Это и значит «симуляция бежит», а не «файл однажды написан».
    ШАГ_ЖИВОЙ = 10
    try:
        _нач = int(float(st.get("gametime") or 0))
    except (TypeError, ValueError):
        _нач = 0
    _до = time.time() + 300
    _идёт = False
    while time.time() < _до:
        _s = br.read_state() or {}
        try:
            _g = int(float(_s.get("gametime") or -1))
        except (TypeError, ValueError):
            _g = -1
