import os
# Путь к мосту берём ОТ ЭТОГО ФАЙЛА, а не абсолютом: иначе копия стенда из
# git worktree молча импортирует llm_policy рабочей копии и померит не ту
# версию. 21.09 так и вышло при сравнении форматов.
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import llm_policy as L

# Стенд должен уметь спросить ОБЕ версии вопроса, иначе дуэль «без расхода
# против с расходом» гонялась бы правкой кода, а это разные запуски и разный
# набор задач. Ключ тот же, что у моста.
НУЖДА = "--need" in sys.argv
if НУЖДА:
    L.ПОКАЗ_РАСХОДА = 1
    sys.argv.remove("--need")

# Адрес ollama. Умолчание прежнее, но стенд теперь можно гнать С ДРУГОЙ
# МАШИНЫ: 22.09 модели живут на маке, а стенд запускается с Windows, где
# ollama нет вовсе. На маке нужен OLLAMA_HOST=0.0.0.0:11434, иначе он
# слушает только петлю и снаружи молчит.
АДРЕС = os.environ.get("OLLAMA_URL",
                       "http://localhost:11434") + "/api/generate"
КУДА = [к for к, _, _ in L.КУДА_РУКИ]


def спросить_локально(модель, промпт, таймаут=180):
    """Со СХЕМОЙ — так и надо звать локальную модель (вывод стенда найма 21.09):
    единственная их ошибка на узком вопросе это выдуманное имя, а схема с
    перечислением закрывает её целиком.

    `keep_alive` обязателен: без него ollama выгружает модель между вызовами, и
    замер меряет загрузку с диска, а не работу.
    """
    тело = {"model": модель, "prompt": L.система_рук() + "\n\n" + промпт,
            "stream": False, "keep_alive": "10m",
            # num_predict 200, а не 80: ответ списком длиннее ответа строкой,
            # и обрыв по длине выглядел бы как неразобранный JSON.
            "options": {"num_predict": 200, "num_ctx": 2048,
                        "temperature": 0},
            # СХЕМА ДОПУСКАЕТ ОБЕ ФОРМЫ, как системный текст и как мост
            # (`руки_в_команды`). 22.09: здесь стояло `"куда": string`, то
            # есть РОВНО ОДНО направление, — при том что система_рук с 21.09
            # говорит «МОЖНО НЕСКОЛЬКО» и показывает форму со списком.
            # Локальная модель делить людей не могла физически, и замер
            # «llama отдала одного в 20 случаях из 21» мерил СХЕМУ, а не
            # модель. Облако схемы не получает вовсе и делило.
            "format": {"type": "object",
                       "properties": {
                           "куда": {"anyOf": [
                               {"type": "string", "enum": КУДА + ["wait"]},
                               {"type": "array", "minItems": 1,
                                "items": {
                                    "type": "object",
                                    "properties": {
                                        "куда": {"type": "string",
                                                 "enum": КУДА},
                                        "сколько": {"type": "integer"}},
                                    "required": ["куда", "сколько"]}}]},
                           "сколько": {"type": "integer"},
                           "why": {"type": "string"}},
                       "required": ["куда"]}}
    тело = json.dumps(тело).encode()
    t = time.time()
    d = json.load(urllib.request.urlopen(urllib.request.Request(
        АДРЕС, тело, {"Content-Type": "application/json"}), timeout=таймаут))
    return d.get("response", ""), time.time() - t


def спросить_облако(клиент, модель, промпт):
    t = time.time()
    d = L.ask(клиент, модель, промпт, False, system=L.система_рук())
    return json.dumps(d, ensure_ascii=False), time.time() - t


def разобрать(текст):
    i, j = текст.find("{"), текст.rfind("}")
    if i < 0 or j <= i:
        return None
    try:
        return json.loads(текст[i:j + 1])
    except json.JSONDecodeError:
        return None


def годен(d, задача):
    """Примет ли мост этот ответ. Возвращает (годен, причина)."""
    if not isinstance(d, dict):
        return False, "не JSON"
    # ОБЕ ФОРМЫ: строкой и списком. У формы-списка «сколько» на верхнем
    # уровне нет вовсе, и прежняя проверка объявляла бы её негодной.
    пп = пары(d)
    for куда, сколько in пп:
        if куда not in КУДА + ["wait", "ждать", "none"]:
            return False, f"неизвестное «{куда}»"
        if not isinstance(сколько, int) or isinstance(сколько, bool):
            try:
                сколько = int(сколько)
            except (TypeError, ValueError):
                return False, "«сколько» не число"
        if сколько < 0:
            return False, "«сколько» отрицательное"
    перевод = L.руки_в_команды(d, задача["состояние"])
    if all(к in ("wait", "ждать", "none") for к, _ in пп):
        return True, "ждать"
    if not перевод.get("commands"):
        return False, "мост ответ не принял: " + перевод.get("why", "")[:40]
    return True, ""


def пары(d):
    """Обе формы ответа к одному виду: [(ресурс, прибавка), ...].

    Приведение то же, что в `руки_в_команды` моста: стенд не должен понимать
    ответ по-своему, иначе он померит собственный разбор. 22.09 учёт стенда
    знал только форму со строкой и падал на списке (`выбор[куда]`,
    unhashable list) — на облаке, которое как раз делило людей.
    """
    сп = (d or {}).get("куда")
    if isinstance(сп, list):
        out = []
        for э in сп:
            if isinstance(э, dict):
                out.append((str(э.get("куда") or э.get("ресурс") or "").strip().lower(),
                            э.get("сколько")))
        return out
    return [(str(сп or "").strip().lower(), (d or {}).get("сколько"))]


def отдано(d):
    """Сколько людей ответ раздаёт ВСЕГО, по всем направлениям."""
    n = 0
    for _, ск in пары(d):
        try:
            n += max(0, int(ск))
        except (TypeError, ValueError):
            pass
    return n


def в_пустоту(d, st):
    """Ушёл бы приказ в никуда? Мост сказал это числом: max_add=0."""
    беды = []
    for куда, _ in пары(d):
        if куда in ("", "wait", "ждать", "none"):
            continue
        if куда not in КУДА:
            беды.append(f"несуществующее направление {куда}")
            continue
        можно, почему = L.сколько_можно(st, куда, L._чис(st.get("idle_pea")))
        if можно <= 0:
            беды.append(f"на {куда}, где max_add=0 ({почему})")
    return "; ".join(беды)


def просевшее(задача):
    """Какое ОТКРЫТОЕ направление сильнее всего проседает (net самый низкий).

    Не «верный ответ»: верного у этого вопроса нет. Это наблюдение — меняет ли
    новая колонка выбор в сторону того, что убывает. Считается по самому
    запросу, чтобы стенд не пересобирал состояние своим кодом.
    """
    худшее, низ = "", None
    for строка in задача["запрос"].splitlines():
        поля = строка.split(",")
        if len(поля) < 5 or поля[0] not in КУДА:
            continue
        try:
            net = float(поля[4])
        except ValueError:
            continue
        if низ is None or net < низ:
            худшее, низ = поля[0], net
    return худшее


def прогон(имя, спросить, задачи):
    годных, времена, пустых, ответы = 0, [], [], []
    в_просевшее, было_просевшее = 0, 0
    # ДОЛЯ РОЗДАННЫХ и ДЕЛЕНИЕ — главные меры этого вопроса с 21.09: ответ
    # «один человек на дерево» при 18 свободных мост примет, а дела не сделает.
    делил, роздано = 0, []
    выбор = {}
    всех_отдал = 0        # отдал ли ВСЕХ, кого можно: признак «не читает, а берёт максимум»
    for з in задачи:
        try:
            текст, сек = спросить(з["запрос"])
        except Exception as e:
            print(f"    gt={з['gt']:>4}  СБОЙ: {str(e)[:60]}")
            ответы.append(None)
            continue
        d = разобрать(текст)
        ок, причина = годен(d or {}, з)
        пусто = в_пустоту(d or {}, з["состояние"]) if ок else ""
        времена.append(сек)
        годных += int(ок)
        if пусто:
            пустых.append(пусто)
        ответы.append(d)
        пп = пары(d)
        for куда, _ in пп:
            выбор[куда or "-"] = выбор.get(куда or "-", 0) + 1
        if len(пп) > 1:
            делил += 1
        пр = просевшее(з)
        if пр:
            было_просевшее += 1
            в_просевшее += int(any(к == пр for к, _ in пп))
        # ОТДАЛ ЛИ ВСЕХ — по СУММЕ всех направлений против числа свободных, а
        # не по одному полю: у формы-списка счёт по полю всегда занижен.
        всего = отдано(d)
        роздано.append(всего)
        своб = int(L._чис(з["состояние"].get("idle_pea")) or з["свободных"])
        if ок and своб and всего >= своб:
            всех_отдал += 1
        видно = "+".join(f"{к} {ск}" for к, ск in пп)
        print(f"    gt={з['gt']:>4} своб={з['свободных']:>3}  {сек:5.1f} с  "
              f"{'ГОДЕН' if ок else 'НЕТ  '}  {видно:<22s} роздано {всего:>2d}"
              + (f"   ← {пусто}" if пусто else "")
              + (f"   [{причина}]" if причина and причина != "ждать" else ""))
    print(f"  {имя}: годных {годных}/{len(задачи)}, "
          f"в пустоту {len(пустых)}, отдал максимум {всех_отдал}/{len(задачи)}, "
          f"делил {делил}/{len(задачи)}, "
          f"роздано медиана {stx.median(роздано):.0f} чел., "
          f"в просевшее {в_просевшее}/{было_просевшее}, "
          f"время медиана {stx.median(времена):.1f} с" if времена else f"  {имя}: нет ответов")
    print("    выбор: " + ", ".join(f"{к} {n}" for к, n in sorted(выбор.items(), key=lambda x: -x[1])))
    return {"модель": имя, "годных": годных, "всего": len(задачи),
            "в_пустоту": пустых, "всех_отдал": всех_отдал, "выбор": выбор,
            "делил": делил,
            "роздано_медиана": stx.median(роздано) if роздано else None,
            "в_просевшее": в_просевшее, "было_просевшее": было_просевшее,
            "время": stx.median(времена) if времена else None, "ответы": ответы}


