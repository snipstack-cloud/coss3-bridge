#!/usr/bin/env python3
"""КРЕСТЬЯНЕ ЖДУТ mil.1 (14.10, §147б, ключ `пауза_крестьян`): состояния четвёртой и пятой живых партий Д
(`sim/кейсы/партия_д4_11_10_2_00-12_30.jsonl`, `партия_д5_13_10_2_00-15_15.jsonl`). Вживую в Д4 стратегия просила mil.1
каждый такт с 3:59 (20 бойцов — пол еды моста), а еда ходила 377-650 до 6:27: бесконечный заказ крестьян (100 еды и 50
золота каждые 12 с) съедал приход; mil.1 куплена в 6:32. В Д5 — в 4:28 при золоте 259 (250 — цена). Блок §147б принимает
`TRAIN peasant 0` (снять бесконечный заказ), python его не звал. Экзамен (sim/решения/экзамен_147б.txt): А 8/8.

Ключ `пауза_крестьян` 1 (в файле партии): (а) Д4 3:59 (20 бойцов, еда 512, пахарей 8, mil.1 просят) — `TRAIN peasant 0`,
приказа `-1` нет, память паузы; (б) Д4 3:24 (15 бойцов, до 5:00, еда 532 < 800 + 750 — пол еды моста покупку не пропустит)
— ключ 1 паузы не ставит, ключ 2 ставит, ключ 1 при поле 0 ставит; (в) повтор `TRAIN peasant 0`, пока `peaeng` в
`train_now`, не чаще раза в 15 с; заказ снят — приказа нет, `TRAIN peasant -1` яруса 1 не пропускается; (г) mil.1 в
`upg_doing` — пауза кончена, `TRAIN peasant -1` сразу; (д) дольше 120 с — пауза кончена, заказ возвращён, новая не раньше
чем через 120 с; (е) ключ 0 — ни паузы, ни `TRAIN peasant 0`; (ж) Д5 9:09, mil.1 куплена — паузы нет.

    python3 selftest_д4_mil1.py
"""
import copy, json, os, sys, tempfile
К = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, К); sys.path.insert(0, os.path.join(К, "sim"))
os.environ.pop("COSS3_WAVE_CONTRACT", None)     # с «1» базовая стратегия строит ВТОРУЮ ЖиваяСтратегия внутри — ключи дважды
import strategy_live as SL
import анализ_врага as АВ

д4 = [json.loads(l) for l in open(os.path.join(К, "sim/кейсы/партия_д4_11_10_2_00-12_30.jsonl"), encoding="utf-8")]
д5 = [json.loads(l) for l in open(os.path.join(К, "sim/кейсы/партия_д5_13_10_2_00-15_15.jsonl"), encoding="utf-8")]
ошибок = 0
def проверить(усл, что):
    global ошибок
    print(("ОК   " if усл else "ОШИБКА ") + что); ошибок += not усл

def стратегия(доп):
    д = json.load(open(os.path.join(К, "sim/поиск/шт_s2_оборона_ручеёк_эко_так15_нужда.json"), encoding="utf-8"))
    assert д["итог"].get("пауза_крестьян") == 1, "в файле партии ждём пауза_крестьян 1"
    д["итог"].update(доп)
    with tempfile.NamedTemporaryFile("w", suffix=".json", delete=False, encoding="utf-8") as f:
        json.dump(д, f, ensure_ascii=False)
    return SL.ЖиваяСтратегия(f.name)

def ответ(С, st):
    АВ._ТЕКУЩИЙ.update({"а": None, "t": None, "ответ": None})
    return С.ответ(copy.deepcopy(st))

def при(ряд, t):
    return next(s for s in ряд if s["gametime"] >= t)

def крестьяне(о):
    return [c.get("total") for c in о["commands"] if c["cmd"] == "TRAIN" and c.get("role") == "peasant"]

def пауза(С):
    return getattr(С.стр, "_крестьяне_пауза", None)

st_204, st_239, st_244, st_254, st_392 = при(д4, 204), при(д4, 239), при(д4, 244), при(д4, 254), при(д4, 392)
for имя, s in (("3:24", st_204), ("3:59", st_239), ("6:32", st_392)):
    print(f"Д4 {имя}: еда {s['food']}, золото {s['gold']}, пахарей {s['on_food']}, бойцов {s['mil_inf'] + s['mil_shooters']}, "
          f"очередь {s['train_now']}, идёт {s.get('upg_doing')!r}, взято {s['upg_done']}")
assert SL.ПОЛ_ЕДЫ == 800, SL.ПОЛ_ЕДЫ

# (а) 3:59 — пауза: TRAIN peasant 0, без -1
С = стратегия({})
о = ответ(С, st_239)
проверить(крестьяне(о) == [0], f"(а) 3:59 ключ 1: TRAIN peasant 0 и ничего больше крестьянам: {крестьяне(о)}")
проверить(пауза(С) is not None, f"(а) память паузы: {пауза(С)}")
проверить(any(k.startswith("§147б пауза крестьян под mil.1: еда 512") for k in С.стр.отдано), f"(а) отдано: {[k for k in С.стр.отдано if '147' in k]}")
проверить(any(c["cmd"] == "UPGRADE" and c.get("role") == "mil.1" for c in о["commands"]), "(а) mil.1 по-прежнему просится")

# (б) 3:24 — 15 бойцов до 5:00, еда 532: пол еды моста (800) покупку не пропустит
for имя, доп, пол, ждём in (("ключ 1", {}, 800, False), ("ключ 2", {"пауза_крестьян": 2}, 800, True), ("ключ 1, пол 0", {}, 0, True)):
    SL.ПОЛ_ЕДЫ = пол
    С2 = стратегия(доп); о = ответ(С2, st_204)
    проверить((крестьяне(о) == [0]) == ждём and (пауза(С2) is not None) == ждём,
              f"(б) 3:24 {имя}: пауза {'есть' if ждём else 'нет'}: {крестьяне(о)}, {пауза(С2)}")
SL.ПОЛ_ЕДЫ = 800

# (в) повтор не чаще раза в 15 с, пока peaeng в очереди; снят — приказа нет, -1 яруса 1 не проходит
о = ответ(С, st_244)
проверить(крестьяне(о) == [], f"(в) 4:04 (5 с после приказа), peaeng ещё в очереди: повтора нет: {крестьяне(о)}")
о = ответ(С, st_254)
проверить(крестьяне(о) == [0], f"(в) 4:15 (15 с), peaeng ещё в очереди: повтор TRAIN peasant 0: {крестьяне(о)}")
st_снят = copy.deepcopy(st_254); st_снят["gametime"] = 260; st_снят["train_now"] = "pikeman:inf"
о = ответ(С, st_снят)
проверить(крестьяне(о) == [] and С.стр.пропущено.get("TRAIN peasant -1 (§147б: ждём mil.1)", 0) >= 1,
          f"(в) заказ снят, еда {st_снят['food']} ≥ 500: ярус 1 просит -1, не пропущен: {крестьяне(о)}, {dict(С.стр.пропущено)}")
проверить(пауза(С) is not None, "(в) пауза жива")

# (г) mil.1 в upg_doing — пауза кончена, заказ сразу
st_г = copy.deepcopy(st_392); st_г["train_now"] = "pikeman:inf"
о = ответ(С, st_г)
проверить(крестьяне(о) == [-1] and пауза(С) is None and С.стр.отдано.get("§147б крестьяне снова (mil.1 куплена)", 0) == 1,
          f"(г) 6:32 mil.1 исследуется: TRAIN peasant -1, паузы нет: {крестьяне(о)}, {[k for k in С.стр.отдано if '147' in k]}")

# (д) дольше 120 с — заказ возвращён, новая пауза не раньше чем через 120 с
С = стратегия({}); ответ(С, st_239)
st_д = copy.deepcopy(st_239); st_д["gametime"] = 239 + 125; st_д["train_now"] = "pikeman:inf"
о = ответ(С, st_д)
проверить(крестьяне(о) == [-1] and пауза(С) is None and С.стр.отдано.get("§147б крестьяне снова (дольше 120 с)", 0) == 1,
          f"(д) 125 с паузы, mil.1 не куплена: заказ возвращён: {крестьяне(о)}, {[k for k in С.стр.отдано if 'снова' in k]}")
st_д2 = copy.deepcopy(st_239); st_д2["gametime"] = 239 + 130
о = ответ(С, st_д2)
проверить(крестьяне(о) == [] and пауза(С) is None, f"(д) через 5 с после снятия — новой паузы нет: {крестьяне(о)}")
st_д3 = copy.deepcopy(st_239); st_д3["gametime"] = 239 + 125 + 121
о = ответ(С, st_д3)
проверить(крестьяне(о) == [0] and пауза(С) is not None, f"(д) через 121 с — пауза снова: {крестьяне(о)}")

# (е) ключ 0 — ничего
С0 = стратегия({"пауза_крестьян": 0}); о = ответ(С0, st_239)
проверить(крестьяне(о) == [] and пауза(С0) is None and not any("147" in k for k in С0.стр.отдано), f"(е) ключ 0: {крестьяне(о)}")

# (ж) Д5 9:09 — mil.1 куплена
st_ж = при(д5, 549); С = стратегия({}); о = ответ(С, st_ж)
проверить("mil.1" in st_ж["upg_done"] and крестьяне(о) == [] and пауза(С) is None, f"(ж) Д5 {st_ж['gametime']} с, mil.1 взята: паузы нет: {крестьяне(о)}")
print(f"ошибок: {ошибок}")
sys.exit(1 if ошибок else 0)
