#!/usr/bin/env python3
"""БЮДЖЕТ С АКАДЕМИЕЙ (24.10, §170з, по Д13 на блоке №2 — винда: «бюджет камня надо считать с ценой академии»): такты Д12
(`sim/кейсы/партия_д12_22_10_2-40_12-46.jsonl`). План §166 академию считал, но в людей это не превращалось: ворота еды 1200
держали нужду выключенной с 1:25 до 4:27 (на камне трое), а переброс §167 мерил недостачу до ближайшей закладки и уводил
бригаду с камня на дерево при закладке шахты/казармы. Ключ `бюджет_с_академией` 1 (файл партии); 0 — как было.

(а) 3:15 (еда 611, камень 20, дерево 402, земля 15, академии нет): с ключом нужда действует от еды найма 600 — stone ≥ 6
(бригада после пола пахарей и бюджета без снятия), запись `§170з бюджет с академией`; (б) то же с ключом 0 — как было:
stone ≤ 4, записи §170з нет; (в) 4:00 (еда 213 < 420 — найм стоит): нужда и с ключом выключена, stone ≤ 4 — голодная
защита остаётся; (г) 4:27 (еда 1353, камень 100, дерево 86, закладка казармы 500/500): переброс на КАМЕНЬ (до академии
1130 против дерева 964), запись `до закладки и академии`; без ключа — на дерево («недостача 414 до закладки»); (д) 3:15 с
построенной академией — ключ молчит: stone ≤ 4.

    python3 selftest_д13_бюджет_академии.py
"""
import copy, json, os, sys, tempfile
К = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, К); sys.path.insert(0, os.path.join(К, "sim"))
os.environ.pop("COSS3_WAVE_CONTRACT", None)
import strategy_live as SL
import анализ_врага as АВ

кейс = [json.loads(l) for l in open(os.path.join(К, "sim/кейсы/партия_д12_22_10_2-40_12-46.jsonl"), encoding="utf-8")]
ошибок = 0
def проверить(усл, что):
    global ошибок
    print(("ОК   " if усл else "ОШИБКА ") + что); ошибок += not усл
def стратегия(доп):
    д = json.load(open(os.path.join(К, "sim/поиск/шт_s2_оборона_ручеёк_эко_так15_нужда.json"), encoding="utf-8"))
    # 24.10: ключ откачен в 0 по живой Д14 (mil.1 ушла на 7:04, казармы 2 нет) — тест судит ПРАВИЛО и ставит ключ сам.
    assert д["итог"].get("переброс") == 1 and д["итог"].get("нужда_макс") == 10
    д["итог"]["бюджет_с_академией"] = 1
    д["итог"].update(доп)
    with tempfile.NamedTemporaryFile("w", suffix=".json", delete=False, encoding="utf-8") as f:
        json.dump(д, f, ensure_ascii=False)
    return SL.ЖиваяСтратегия(f.name)
def при(t): return next(s for s in кейс if float(s["gametime"]) >= t)
def ответ(С, s):
    АВ._ТЕКУЩИЙ.update({"а": None, "t": None, "ответ": None}); return С.ответ(copy.deepcopy(s))
def баланс(о, роль):
    v = [c.get("total") for c in о["commands"] if c["cmd"] == "BALANCE" and c.get("role") == роль]
    return v[-1] if v else None
def два(доп, t, patch=None):
    С = стратегия(доп); ответ(С, при(t - 6))          # закладка прошлого такта в памяти (такты Д12 через 5–6 с)
    s = copy.deepcopy(при(t)); s.update(patch or {})
    return ответ(С, s), s
def метки(о, что): return [x for x in о["why"].split(", ") if что in x][:2]

о, s = два({}, 195)
проверить((баланс(о, "stone") or 0) >= 6 and "§170з бюджет с академией" in о["why"] and (баланс(о, "food") or 0) >= 6,
          f"(а) 3:15 еда {s['food']} камень {s['stone']}: stone {баланс(о, 'stone')}, wood {баланс(о, 'wood')}, food {баланс(о, 'food')}; {метки(о, '§170з')}")
о0, s = два({"бюджет_с_академией": 0}, 195)
проверить((баланс(о0, "stone") or 0) <= 4 and "§170з" not in о0["why"],
          f"(б) ключ 0 — как было: stone {баланс(о0, 'stone')}, wood {баланс(о0, 'wood')}")
о, s = два({}, 240)
проверить((баланс(о, "stone") or 0) <= 4 and "§170з" not in о["why"],
          f"(в) 4:00 еда {s['food']} (найм стоит): stone {баланс(о, 'stone')}, нужда выключена; {метки(о, '§16')}")
о, s = два({}, 267)
проверить("на stone" in о["why"] and "до закладки и академии" in о["why"] and (баланс(о, "stone") or 0) >= 6 and (баланс(о, "wood") or 0) <= 3,
          f"(г) 4:27 камень {s['stone']} дерево {s['wood']}: stone {баланс(о, 'stone')}, wood {баланс(о, 'wood')}; {метки(о, '§167')}")
о0, s = два({"бюджет_с_академией": 0}, 267)
проверить("на wood" in о0["why"] and "до закладки," in о0["why"] + ",",
          f"(г′) без ключа — на дерево: stone {баланс(о0, 'stone')}, wood {баланс(о0, 'wood')}; {метки(о0, '§167')}")
о, s = два({}, 195, {"academies": 1})
проверить((баланс(о, "stone") or 0) <= 4 and "§170з" not in о["why"],
          f"(д) академия построена — ключ молчит: stone {баланс(о, 'stone')}")
print(f"\nошибок: {ошибок}")
