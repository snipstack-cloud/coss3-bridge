#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Свод фактов по ВСЕМ трассам: как часто что случается, и где встают стройки.

    python3 факты_свод.py [<каталог результатов>] [--вывод свод.md]

Стадия A ночного разбора. Языковая модель берёт восемь минут на партию, то есть
451 партия это шестьдесят часов; счёт фактов питоном проходит их все за минуты
и даёт ТОЧНЫЕ числа. Модель потом смотрит туда, куда укажет этот свод.

Считается на 100 тактов, а не в штуках: партии разной длины, и «22 отказа»
у длинной и у короткой значат разное.

И ОБЯЗАТЕЛЬНО ПО ДАТАМ. Первый прогон 23.09 дал «BUILDERS без BUILD — 32,9 на
100 тактов» по всему корпусу, и это число врёт: по датам видно 71,2 у 13.09 и
1,6 у 22.09. Мост менялся все двенадцать дней, поэтому общий итог показывает
ИСТОРИЮ, а не состояние. Смотреть надо на последний столбец и на то, какие
виды за эти дни НЕ упали, — вот они и есть живые беды.
"""
import json, os, re, sys, collections
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import факты as Ф

РЕЗ = os.path.expanduser(sys.argv[1]) if len(sys.argv) > 1 and not sys.argv[1].startswith("--") \
    else os.path.expanduser("~/coss3-res")
ВЫВОД = None
if "--вывод" in sys.argv:
    ВЫВОД = sys.argv[sys.argv.index("--вывод") + 1]


def тип(ф):
    """Факт -> вид. Числа и имена зданий выкидываем, иначе видов будут сотни."""
    if ф.startswith("повтор BUILD"):
        return "повтор BUILD по строящемуся"
    if ф.startswith("пустой BUILD"):
        return "пустой BUILD (столько уже есть)"
    if ф.startswith("BUILDERS"):
        return "BUILDERS без BUILD (пустой ход)"
    if ф.startswith("BALANCE просит"):
        return "BALANCE просит больше людей, чем есть"
    if ф.startswith("мост отбросил"):
        м = re.search(r"мост отбросил: (\w+)", ф)
        хвост = "UPGRADE уже взят" if "УЖЕ ВЗЯТ" in ф else (м.group(1) if м else "?")
        return f"отказ моста: {хвост}"
    if ф.startswith("вето"):
        return "вето моста"
    if ф.startswith("еда"):
        return "еда ниже порога"
    if ф.startswith("простой"):
        return "простой крестьян"
    if ф.startswith("волна"):
        return "волна: фаза/застой"
    if ф.startswith("за такт"):
        return "бой: потери за такт"
    if ф.startswith("атака"):
        return "атака начал./конч."
    return "прочее"


def застой(строки):
    """Самая долгая стройка БЕЗ ДВИЖЕНИЯ: (роль, %, с, по, тактов)."""
    ряды, лучший, пред = {}, None, {}
    for d in строки:
        st = d.get("state") or {}
        if not st:
            continue
        gt = Ф._ч(d.get("gt"))
        текущ = Ф._строится(st)
        for роль, проц in текущ.items():
            if пред.get(роль) == проц:
                ряды[роль] = (ряды[роль][0], gt, ряды[роль][2] + 1)
            else:
                ряды[роль] = (gt, gt, 1)
            if not лучший or ряды[роль][1] - ряды[роль][0] > лучший[3] - лучший[2]:
                лучший = (роль, проц, ряды[роль][0], ряды[роль][1], ряды[роль][2])
        for роль in list(ряды):
            if роль not in текущ:
                ряды.pop(роль, None)
        пред = текущ
    return лучший


виды = collections.Counter()
виды_партий = collections.Counter()
по_идее = collections.defaultdict(collections.Counter)
такты_идеи = collections.Counter()
по_датам = collections.defaultdict(collections.Counter)
такты_даты = collections.Counter()
застои = []
трасс = тактов = 0

for корень, _, файлы in os.walk(РЕЗ):
    if "coss3_bot.jsonl" not in файлы:
        continue
    путь = os.path.join(корень, "coss3_bot.jsonl")
    части = путь.split(os.sep)
    if len(части) < 4 or not re.match(r"20\d\d-\d\d-\d\d", части[-4]):
        continue
    идея, дата = части[-3], части[-4]
    строки = [json.loads(s) for s in open(путь, encoding="utf-8") if s.strip()]
    ф_по_тактам = Ф.факты(строки)
    n = len(ф_по_тактам)
    if not n:
        continue
    трасс += 1
    тактов += n
    такты_идеи[(дата, идея)] += n
    такты_даты[дата] += n
    здесь = set()
    for gt, фф in ф_по_тактам:
        for ф in фф:
            в = тип(ф)
            виды[в] += 1
            по_идее[(дата, идея)][в] += 1
            по_датам[дата][в] += 1
            здесь.add(в)
    for в in здесь:
        виды_партий[в] += 1
    з = застой(строки)
    if з and з[3] - з[2] >= 120:
        застои.append((з[3] - з[2], з[4], з[0], з[1], os.path.relpath(путь, РЕЗ)))

строки_вывода = []
д = строки_вывода.append
д(f"# Свод фактов по всем трассам\n")
д(f"Трасс {трасс}, тактов с состоянием {тактов}. Считано `факты.py` без всякой модели.\n")
д("## Какой факт как часто\n")
д("| вид факта | случаев | на 100 тактов | в скольких трассах из %d |" % трасс)
д("|---|---|---|---|")
for в, n in виды.most_common():
    д(f"| {в} | {n} | {100 * n / тактов:.1f} | {виды_партий[в]} |")

д("\n## ПО ДАТАМ — главное, потому что мост менялся каждый день\n")
д("Общий итог выше показывает историю, а не состояние. Живая беда — та, что по")
д("датам НЕ падает.\n")
даты = sorted(такты_даты)
виды6 = [в for в, _ in виды.most_common(8)]
д("| вид факта (на 100 тактов) | " + " | ".join(d[-5:] for d in даты) + " |")
д("|---" * (len(даты) + 1) + "|")
for в in виды6:
    ячейки = " | ".join(f"{100 * по_датам[d][в] / такты_даты[d]:.1f}" for d in даты)
    д(f"| {в} | {ячейки} |")

д("\n## ЗАСТРЯВШИЕ СТРОЙКИ — стройка без движения дольше 120 игровых секунд\n")
д("| секунд | тактов | здание | % | трасса |")
д("|---|---|---|---|---|")
for сек, n, роль, проц, ф in sorted(застои, reverse=True)[:20]:
    д(f"| **{сек}** | {n} | `{роль}` | {проц}% | {ф} |")
д(f"\nВсего трасс с застоем дольше 120 с: **{len(застои)} из {трасс}**.")

д("\n## По идеям, СВЕЖИЕ ВПЕРЁД (на 100 тактов)\n")
д("Только здесь идеи сравнимы между собой: в таблице по датам они смешаны.\n")
заметные = [в for в, _ in виды.most_common(6)]
д("| дата | идея | тактов | " + " | ".join(заметные) + " |")
д("|---" * (len(заметные) + 3) + "|")
for (дата, идея), n in sorted(такты_идеи.items(), reverse=True)[:22]:
    ячейки = " | ".join(f"{100 * по_идее[(дата, идея)][в] / n:.1f}" for в in заметные)
    д(f"| {дата[-5:]} | {идея} | {n} | {ячейки} |")

текст = "\n".join(строки_вывода)
print(текст)
if ВЫВОД:
    open(ВЫВОД, "w", encoding="utf-8").write(текст + "\n")
    print(f"\n-> {ВЫВОД}", file=sys.stderr)
