# -*- coding: utf-8 -*-
"""Самопроверка: сторож досылки в волну (`--topup-min`).

Зачем ключ. По четырём свежим сериям 23.09 (16 партий, `разборы/ВОЙНА.md`)
66–87 % всех посланных бойцов уходили досылкой `ATTACK target=wave` пачками
медианно по 30 раз в такт под фразой «вливаю в волну, чтобы не гибли
поодиночке». После первого удара выход падал с 21,4 до 1,7 крестьянина на сто
посланных, армия по снимкам стояла в 6–9 клетках, в клетке боя мы в
меньшинстве в 67–73 % контактов.

Сторож не пускает досылку меньше N и говорит почему; копилки и автоотправки
нет намеренно — модель просит досылку сама почти каждый такт и переспросит,
когда дома наберётся порог. Примыкание к сбору сторожа не касается.
"""
import sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import llm_policy as L

ошибок = 0


def проверить(что, условие):
    global ошибок
    print(("  ОК   " if условие else "  СБОЙ ") + что)
    ошибок += not условие


def сторож(порог, attack, свободных):
    L.МИН_ДОСЫЛКА = порог
    return L.сторож_досылки(attack, свободных)


print("сторож ВЫКЛЮЧЕН (0) — всё как раньше:")
п, о = сторож(0, 29, 29)
проверить("пачка 29 проходит", о is None and п == 29)
п, о = сторож(0, 3, 40)
проверить("пачка 3 проходит", о is None and п == 3)

print("\nпорог 50:")
п, о = сторож(50, 29, 29)
проверить("29 при 29 свободных — НЕ уходит", о is not None and п == 29)
проверить("модели названы пачка, порог и число свободных",
          "29" in о and "50" in о and "Свободных дома 29" in о)
проверить("сказано, что та же команда пройдёт, когда наберётся", "пройдёт" in о)
проверить("предложен кулак через сбор", '"via"' in о)
п, о = сторож(50, 53, 53)
проверить("53 при 53 — уходит", о is None and п == 53)
п, о = сторож(50, 50, 50)
проверить("ровно 50 — уходит (порог включительно)", о is None and п == 50)
п, о = сторож(50, 9999, 60)
проверить("«all» (9999) при 60 свободных — пачка 60, уходит", о is None and п == 60)
п, о = сторож(50, 9999, 30)
проверить("«all» при 30 свободных — пачка 30, НЕ уходит", о is not None and п == 30)
п, о = сторож(50, 20, 60)
проверить("20 при 60 свободных — дробит кулак, НЕ уходит", о is not None and п == 20)
п, о = сторож(50, 40, 0)
проверить("свободных ноль — не дело сторожа (скажет ветка «собирать некого»)",
          о is None and п == 0)
п, о = сторож(50, 40, None)
проверить("свободных нет в состоянии — то же, что ноль", о is None and п == 0)

print("\nпривязка к настоящему коду:")
исходник = open(os.path.join(os.path.dirname(os.path.abspath(__file__)),
                             "llm_policy.py"), encoding="utf-8").read()
проверить("ветка target=wave зовёт сторожа",
          '_пачка, _отказ = сторож_досылки(attack, st.get("my_freewar", 0))' in исходник)
i_ст = исходник.find('_пачка, _отказ = сторож_досылки(')
i_кл = исходник.find('_кв = _клетка_волны(st) if attack else None')
проверить("сторож стоит ДО подстановки клетки волны", 0 < i_ст < i_кл)
i_пр = исходник.find('if (attack and not вето_волны and МАРШ.get("фаза") in ("сбор", "стоим")')
проверить("примыкание к сбору отрабатывает РАНЬШЕ сторожа", 0 < i_пр < i_ст)
проверить("отказ уходит модели через «Мост вмешался»",
          'вмешательство = (вмешательство + "; " if вмешательство else "") + _отказ' in исходник)
проверить("отвергнутая досылка убрана из «Итога прошлого решения»",
          исходник.count('прошлый_заказ = [т for т in прошлый_заказ if т[0] != "ATTACK"]') >= 2)
проверить("после отказа attack обнулён — волна не уйдёт другой веткой",
          'удержано_досылок.append(' in исходник and
          исходник.find('attack = 0', i_ст) < i_кл)
проверить("удержанные пишутся в трассу", '"удержано": len(удержано_досылок)' in исходник)
проверить("ключ --topup-min заведён", '"--topup-min"' in исходник)
проверить("ключ доезжает до МИН_ДОСЫЛКА", 'globals()["МИН_ДОСЫЛКА"] = int(a.topup_min)' in исходник)

print()
print("СБОЕВ: %d" % ошибок)
sys.exit(1 if ошибок else 0)
