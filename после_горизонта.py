#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Писать состояние ОБОИХ человеческих слотов после горизонта политики.

    python после_горизонта.py                        # пути по умолчанию, раз в секунду
    python после_горизонта.py --каждые 2 --секунд 600
    python после_горизонта.py --выход C:\\coss3-io-igrok\\после_горизонта_P1.jsonl

Зачем. Горизонт политики 900 с: после 15:00 `llm_policy` встаёт, и трасса со
снимком обрываются. А блок состояния в игре пишет `coss3_eco_P<n>.dat` КАЖДУЮ
игровую секунду, политика ему не нужна. 21.10 на этом чуть не потерялся главный
факт партии Д10: по трассе выходила бескровная ничья, а игрок ударил после
15 минут и снял 216 наших бойцов и 32 крестьянина за ~90 с. Числа достались
только потому, что игра осталась открытой и файл не перезаписали; будь закрыта —
пропало бы совсем.

Что даёт этот цикл: не одно число на конец, а КОЛЬЦО ГИБЕЛИ по тактам — кто
терял и когда, где стояла армия, что менялось в ступенях. Тогда бой «куча против
строя» меряется прямо, а не домысливается.

Три правила, которые тут важнее удобства:

1. **Писать оба слота.** Наш слот говорит о наших потерях, слот игрока — о его
   собственных числах (`fighters`, `squads_form`, прокачки) в тот же момент.
2. **Не писать одно и то же.** Такт добавляется, только если `gametime`
   изменился: игра на паузе (окно не в фокусе) переписывает файл тем же числом.
3. **Молчать нельзя.** Нет файла, не читается, не меняется время — сказать и
   назвать причину, а не копить пустые строки.

Файл кладётся рядом с трассой и уезжает в `coss3-results` тем же
`push_results.py`.
"""
from __future__ import annotations
import sys as _sys
for _s in (_sys.stdout, _sys.stderr):
    try: _s.reconfigure(encoding="utf-8", errors="replace")
    except Exception: pass

import argparse
import json
import os
import re
import time

ИГРА = r"C:\Program Files (x86)\Steam\steamapps\common\Cossacks 3"
ВЫХОД = r"C:\coss3-io-igrok\после_горизонта.jsonl"


def прочитать(путь: str) -> dict:
    """Разобрать `coss3_eco_P<n>.dat` в словарь. Формат — `ключ = значение`.

    ПОСТРОЧНО, как это делает мост (`llm_policy`, `split("=", 1)`), и это не
    придирка к стилю. Первая редакция читала файл одним куском выражением
    `^\\s*(\\w+)\\s*=\\s*(.*?)\\s*$` — и ПУСТОЕ значение съедало следующую строку:
    `\\s*` после знака равенства проходит перенос, и у `wip = ` значением
    становилось «mil_inf = 227», а сам `mil_inf` из словаря исчезал. Поймано на
    своём же выводе: «наших ?+18» при 227 в файле. Так же пропадал `mil_hurt`
    после пустого `mil_side`. Ложный ноль ровно того вида, о котором
    предупреждает скилл разбора: поля нет не в игре, а в моём чтении.
    """
    try:
        d = open(путь, encoding="latin-1").read()
    except OSError as e:
        return {"_ошибка": f"{type(e).__name__}: {e}"}
    пары = {}
    for строка in d.splitlines():
        if "=" not in строка:
            continue
        k, v = строка.split("=", 1)
        k, v = k.strip(), v.strip()
        if not re.fullmatch(r"[A-Za-z0-9_]+", k):
            continue
        try:
            пары[k] = int(v)
        except ValueError:
            try:
                пары[k] = float(v)
            except ValueError:
                пары[k] = v
    return пары


def главное(s: dict, свой: int) -> str:
    """Одна строка в консоль: то, ради чего цикл запущен."""
    ч = lambda k: s.get(k, "?")
    gt = float(s.get("gametime") or 0)
    чужой = 1 - свой
    return (f"{int(gt) // 60}:{int(gt) % 60:02d}  наших {ч('mil_inf')}+{ч('mil_shooters')} "
            f"(ранено {ч('mil_hurt')}), потеряно бойцов {ч('my_mil_lost')} крестьян {ч('my_pea_lost')}; "
            f"его армия {ч(f'p{чужой}_army')}, его потери {ч(f'p{чужой}_mil_lost')}, "
            f"строй {ч(f'p{чужой}_squads_form')}")


def main() -> int:
    ap = argparse.ArgumentParser(description="состояние обоих слотов после горизонта политики")
    ap.add_argument("--dir", default=ИГРА, help="каталог игры")
    ap.add_argument("--выход", default=ВЫХОД, dest="выход", help="куда дописывать строки")
    ap.add_argument("--слот", type=int, default=1, dest="слот", help="слот бота (его состояние главное)")
    ap.add_argument("--каждые", type=float, default=1.0, dest="каждые", help="пауза между чтениями, с")
    ap.add_argument("--секунд", type=float, default=900.0, dest="секунд", help="сколько всего писать, с")
    ap.add_argument("--тихо", action="store_true", dest="тихо", help="не печатать строку каждого такта")
    a = ap.parse_args()

    пути = {n: os.path.join(a.dir, f"coss3_eco_P{n}.dat") for n in (0, 1)}
    нет = [p for p in пути.values() if not os.path.exists(p)]
    if нет:
        print("нет файлов состояния: " + ", ".join(нет))
        print("это значит, что партия не идёт или блок состояния не установлен — писать нечего")
        return 2

    начало, прошлое, тактов, пусто = time.time(), None, 0, 0
    print(f"пишу в {a.выход}, слот бота {a.слот}, раз в {a.каждые:g} с, {a.секунд:g} с всего")
    with open(a.выход, "a", encoding="utf-8") as f:
        while time.time() - начало < a.секунд:
            свои = {n: прочитать(p) for n, p in пути.items()}
            gt = свои[a.слот].get("gametime")
            if gt is None or gt == прошлое:
                # Игра на паузе (окно не в фокусе) или файл не обновился: пустых строк не копим.
                пусто += 1
                if пусто % 30 == 0:
                    print(f"  время не идёт ({gt}) — игра на паузе или партия кончилась, {пусто} чтений подряд")
                time.sleep(a.каждые)
                continue
            прошлое, пусто = gt, 0
            f.write(json.dumps({"gametime": gt, "real": round(time.time() - начало, 1),
                                "P0": свои[0], "P1": свои[1]}, ensure_ascii=False) + "\n")
            f.flush()
            тактов += 1
            if not a.тихо:
                print("  " + главное(свои[a.слот], a.слот))
            time.sleep(a.каждые)
    print(f"записано тактов: {тактов} → {a.выход}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
