"""Сторож §100: удар готовой волны по ближней куче — перевес по огню и с подкреплением (ключи
`вес_стрелка`, `рядом_окно`), и без ключей — по головам, как было. Картина — 11:03 проверки p5."""
import sys
import strategy_live as SL

def волна_и_стратегия(ключи):
    ж = SL.ЖиваяСтратегия.__new__(SL.ЖиваяСтратегия)
    ж.п = dict({"штурм_при": 0.92}, **ключи)
    в = SL.Волна("W1", 1, 0.0, (10, 10), "cell")
    в.подтверждена, в.размер = True, 71
    return ж, в

st = {"groups": [{"id": 1, "n": 71, "пик": 65, "стрелков": 6, "конных": 0, "cx": 10, "cy": 10}],
      "ecells": [{"x": 9, "y": 8, "n": 36, "пик": 15, "стрелков": 21}, {"x": 7, "y": 7, "n": 23, "пик": 13, "стрелков": 10}],
      "mil_inf": 65, "mil_shooters": 6, "mil_away": 71, "p1_army": 84}
ош = 0
ж, в = волна_и_стратегия({})
пр, прич = ж._удар_готовой(в, st)
if пр is None or "МЕСТНЫЙ_ПЕРЕВЕС" not in прич:
    print("ПРОВАЛ: без ключей удар по головам должен уйти (как живьём 5.10):", прич); ош += 1
ж, в = волна_и_стратегия({"вес_стрелка": 3, "рядом_окно": 2, "рядом_при": 0.92})
пр, прич = ж._удар_готовой(в, st)
if пр is not None or "сила=" not in прич:
    print("ПРОВАЛ: с огнём и окном 11:03 — ждать, причина с силой:", пр, прич); ош += 1
st2 = dict(st, ecells=[{"x": 9, "y": 8, "n": 12, "пик": 10, "стрелков": 2}])
пр, прич = ж._удар_готовой(в, st2)
if пр is None:
    print("ПРОВАЛ: одна куча 12 почти без стрелков — бить:", прич); ош += 1
print(f"ошибок: {ош}")
sys.exit(1 if ош else 0)
