def отчёт(модель, з, партии, итог, файл):
    w = []
    w.append(f"# Управление армией: человек против бота\n")
    w.append(f"Собрано {date.today().isoformat()} агентом `агент_армия.py`, модель `{модель or 'нет (--сухой)'}`. "
             f"Партий {len(партии)}: {', '.join(п['имя'] for п in партии)}.\n")
    w.append("Числа в таблицах посчитаны питоном по трассам. Строки модели — НАБЛЮДЕНИЯ: каждая прошла проверку "
             "ссылок (эпизоды, такты, принципы существуют), но не проверку смысла.\n")
    if итог:
        w.append("## Итог: что отличает человека\n")
        for о in итог["принято"]:
            w.append(f"* **{о['аспект']}** ({о['партий']} из {len(партии)} партий{', ' + о['принцип'] if о.get('принцип') else ''}): "
                     f"{о['вывод']}\n  * боту: {о['что_делать_боту']}\n  * опора: {', '.join(о['опора']) or '—'}")
        for о in итог["отброшено"]:
            w.append(f"* ~~{о.get('аспект')}: {о.get('вывод')}~~ — _{о['почему']}_")
        w.append("")
    if з:
        w.append("## Конспект из сети\n")
        for п in з["конспект"]:
            w.append(f"* **{п['id']}** [{п['тема']}] {п['принцип']} — признак: {п['признак_в_партии']} "
                     f"({'; '.join(п['источники'])})")
        w.append(f"\nИсточников {len(з['источники'])}, принципов с найденной цитатой {len(з['принципы'])}, "
                 f"отброшено {len(з['отброшено'])}.\n")
    for п in партии:
        w.append(f"## {п['метка']} {п['имя']}\n")
        w.append(f"Трасса `{os.path.relpath(п['путь'], os.path.expanduser('~'))}`, партий в файле {п['партий_в_файле']} "
                 f"(взята последняя), тактов {п['тактов']}, {п['от']}–{п['до']}. Наша ратуша {п['наш_дом']}, его "
                 f"{п['его_дом']}. Событий гибели {п['событий_гибели']} из kills_n {п['kills_n']}, наш номер в кольце {п['наш_pl']}.\n")
        w.append(таблица_сторон(п) + "\n")
        w.append("**Бои**\n\n" + бои_строками(п) + "\n")
        w.append("**Эпизоды (правило питона)**\n")
        for э in п["эпизоды"]:
            w.append(f"* `{э['id']}` {э['вид']} {э['с']}–{э['по']}: {э['текст']}")
        if not п["эпизоды"]:
            w.append("_нет_")
        if п.get("сравнение"):
            w.append("\n**Сравнение (модель)**\n")
            for с in п["сравнение"]["принято"]:
                w.append(f"* **{с['аспект']}** — человек: {с['человек']}; бот: {с['бот']} "
                         f"[{', '.join(с['эпизоды']) or '—'}; такты {с['такты']}; {с['принцип'] or '—'}] "
                         f"проверить: {с['как_проверить']}")
            for с in п["сравнение"]["отброшено"]:
                w.append(f"* ~~{с.get('аспект')}: {с.get('человек')} / {с.get('бот')}~~ — _{с['почему']}_")
        w.append("")
    open(файл, "w", encoding="utf-8").write("\n".join(w))


