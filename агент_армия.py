    ш = float(s0.get("map_w") or 256)
    наш_дом = _центр(s0.get("obuild"), ш) or (int(s0.get("my_cx") or 8), int(s0.get("my_cy") or 8))
    его_дом = None
    for t in T:
        его_дом = _центр(t["state"].get("ebuild"), ш)
