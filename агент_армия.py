    def первый(сторона, усл):
        for t, сн in zip(T, снимки):
            if усл(сн[сторона]):
                return мм(t["gt"])
        return "нет"

    стороны = {}
    for ст in ("бот", "человек"):
        армии = [сн[ст]["n"] for сн in снимки if сн[ст]["n"] >= 20]
