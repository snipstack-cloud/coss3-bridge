            эп = "\n".join(f"{э['id']} [{э['вид']}] {э['с']}–{э['по']}, такты {э['такты']}: {э['текст']}"
                           for э in п["эпизоды"]) or "(нет)"
            о = спросить(модель, ВОПРОС_ПАРТИЯ.format(конспект=конспект_строками(з), таблица=таблица_сторон(п),
                                                      бои=бои_строками(п), эпизоды=эп), СХЕМА_ПАРТИЯ) or {}
            пр, отб = проверить_строки(о.get("сравнение"), п, ид)
