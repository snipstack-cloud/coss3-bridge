def искать(запрос, сколько):
    url = "https://lite.duckduckgo.com/lite/?q=" + urllib.parse.quote(запрос)
    try:
        сырое = urllib.request.urlopen(urllib.request.Request(url, headers=UA), timeout=20).read().decode("utf-8", "replace")
    except Exception as e:
        print(f"  поиск «{запрос}» не удался: {e}")
        return []
    if "uddg=" not in сырое and ("anomaly" in сырое.lower() or "captcha" in сырое.lower()):
        raise Капча(запрос)
    ссылки = []
    for u in re.findall(r'uddg=([^&"\']+)', сырое):
        u = urllib.parse.unquote(u)
        if u.startswith("http") and not any(п in u for п in ПРОПУСК) and u not in ссылки:
            ссылки.append(u)
    return ссылки[:сколько]


class _Текст(HTMLParser):
    ПРОЧЬ = {"script", "style", "noscript", "svg", "nav", "footer", "header", "form"}

    def __init__(self):
        super().__init__()
        self.куски, self.глубина = [], 0

    def handle_starttag(self, tag, attrs):
        if tag in self.ПРОЧЬ:
            self.глубина += 1
        elif tag in ("p", "br", "li", "h1", "h2", "h3", "h4", "tr", "div"):
            self.куски.append("\n")

    def handle_endtag(self, tag):
        if tag in self.ПРОЧЬ and self.глубина:
            self.глубина -= 1

    def handle_data(self, data):
        if not self.глубина:
            self.куски.append(data)


def страница(url):
    """Текст страницы из кэша или из сети. Кэш — по sha1 адреса, рядом адрес."""
    os.makedirs(КЭШ, exist_ok=True)
    ключ = hashlib.sha1(url.encode()).hexdigest()[:16]
    путь = os.path.join(КЭШ, ключ + ".txt")
    if os.path.exists(путь):
        return open(путь, encoding="utf-8").read().split("\n", 1)[1]
    try:
        адрес = urllib.parse.quote(url, safe=":/?&=%#+,;()'")     # кириллица в пути: urllib шлёт только ascii
        r = urllib.request.urlopen(urllib.request.Request(адрес, headers=UA), timeout=25)
        if "html" not in (r.headers.get("Content-Type") or "html"):
            return ""
        сырое = r.read(3_000_000).decode(r.headers.get_content_charset() or "utf-8", "replace")
    except Exception as e:
        print(f"  {url[:70]}: не скачалась ({e})")
        return ""
    п = _Текст()
    try:
        п.feed(сырое)
    except Exception:
        pass
    текст = html.unescape("".join(п.куски))
    текст = "\n".join(s for s in (re.sub(r"[ \t\xa0]+", " ", x).strip() for x in текст.split("\n")) if len(s) > 2)
    with open(путь, "w", encoding="utf-8") as f:
        f.write(url + "\n" + текст)
    return текст


def _норм(s):
    return re.sub(r"\s+", " ", re.sub(r"[^\w\s]", " ", str(s).lower())).strip()


def цитата_есть(цитата, текст):
    """Цитата ищется в странице: подряд 40 знаков, либо 85 % её слов (модель правит пунктуацию)."""
    ц, т = _норм(цитата), _норм(текст)
    if len(ц) < 25:
        return False
    if ц[:40] in т:
        return True
    слова = [w for w in ц.split() if len(w) > 3]
    есть = set(т.split())
    return len(слова) >= 6 and sum(w in есть for w in слова) / len(слова) >= 0.85


