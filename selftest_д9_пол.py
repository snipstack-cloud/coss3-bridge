#!/usr/bin/env python3
"""ПОЛ ПАХАРЕЙ Д9 — БЮДЖЕТ БЕЗ СНЯТИЯ (20.10 ночь, §169в): такты девятой живой партии Д
(`sim/кейсы/партия_д9_20_10_0_12-15_15.jsonl`, мост c8effaa с §168а). Винда: «пол 6 пробит — на еде 2–5 в 5:15–7:00». Кейс
воспроизводит живые приказы такт в такт. Блок наземного BALANCE только добирает (приказ ниже текущего пуст) и вторым проходом
берёт у кого попало; живьём (1) ярус слал `wood 3` при ужатом `мин_дер` 1 — сумма 19 при земле 17, камень и еда тянули одного
человека каждый такт; (2) после переброса на дерево трое на камне с приказом 0 остались, дерево 9 и еда 6 при земле 15 тянули
друг у друга 30 с. Правка: цель переброса получает остаток видимой земли за вычетом еды и людей не-цели (их снять нельзя), все
три приказа несут ровно цели, еда добирается строго и идёт последней в файле; такт смены цели — бригада целиком.

(а) одной стратегией 4:39–6:40: в каждом такте, кроме окна переброса (2 такта: 4:44, 4:50, 5:55, 6:00), сумма наземных приказов ≤ видимой земле
(еда + дерево + камень + праздные); (б) 5:35: `wood` не выше 1 (живьём 3) и есть `food 6`; (в) 6:15: `wood` ≤ 15 − 6 − 3 = 6
(живьём 9) и `food 6`; (г) 5:55 (смена на wood): `wood 10` целиком, `food 6`, еда — последний наземный приказ; (д) ключ
`пол_без_снятия` 0 в 6:10 — `wood 9` без приказа еды, как живьём; (е) при поле еда всегда после дерева и камня в списке команд.
    python3 selftest_д9_пол.py
"""
import copy, json, os, sys, tempfile
К = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, К); sys.path.insert(0, os.path.join(К, "sim"))
os.environ.pop("COSS3_WAVE_CONTRACT", None)
import strategy_live as SL
import анализ_врага as АВ

кейс = [json.loads(l) for l in open(os.path.join(К, "sim/кейсы/партия_д9_20_10_0_12-15_15.jsonl"), encoding="utf-8")]
ошибок = 0
def проверить(усл, что):
    global ошибок
    print(("ОК   " if усл else "ОШИБКА ") + что); ошибок += not усл
def стратегия(доп):
    д = json.load(open(os.path.join(К, "sim/поиск/шт_s2_оборона_ручеёк_эко_так15_нужда.json"), encoding="utf-8"))
    assert д["итог"].get("нужда_макс") == 10 and д["итог"].get("переброс") == 1
    д["итог"].update(доп)
    with tempfile.NamedTemporaryFile("w", suffix=".json", delete=False, encoding="utf-8") as f:
        json.dump(д, f, ensure_ascii=False)
    return SL.ЖиваяСтратегия(f.name)
def ответ(С, s):
    АВ._ТЕКУЩИЙ.update({"а": None, "t": None, "ответ": None}); return С.ответ(copy.deepcopy(s))
def наземные(о):
    return [(c["role"], int(c.get("total") or 0)) for c in о["commands"] if c["cmd"] == "BALANCE" and c.get("role") in ("food", "wood", "stone")]
def видно(s):
    return int(sum(float(s.get(k) or 0) for k in ("on_food", "on_wood", "on_stone", "idle_pea")))
def прогон(доп, t0=279, t1=400):
    С = стратегия(доп); из = {}
    for s in кейс:
        gt = int(float(s["gametime"]))
        if gt < t0: continue
        if gt > t1: break
        из[gt] = (s, ответ(С, s))
    return из

п = прогон({})
смены = {gt for gt, (s, о) in п.items() if any("такт переброса" in k for k in о.get("why", "").split(", "))}
проверить(смены == {284, 290, 355, 360}, f"(а) окно переброса 2 такта: 4:44, 4:50, 5:55, 6:00: {sorted(смены)}")
плохие = [(gt, наземные(о), видно(s)) for gt, (s, о) in п.items() if gt not in смены and sum(t for _, t in наземные(о)) > видно(s)]
проверить(not плохие, f"(а) вне смены сумма наземных ≤ видимой земле: нарушений {len(плохие)} {плохие[:3]}")
s535, о535 = п[335]; н = dict(наземные(о535))
проверить(н.get("wood", 0) <= 1 and н.get("food") == 6, f"(б) 5:35: wood ≤ 1 и food 6: {наземные(о535)}")
s615, о615 = п[375]; н = dict(наземные(о615))
проверить(н.get("wood", 0) <= 6 and н.get("food") == 6, f"(в) 6:15: wood ≤ 6 и food 6: {наземные(о615)}")
s555, о555 = п[355]; н = naz = наземные(о555)
проверить(dict(naz).get("wood") == 10 and dict(naz).get("food") == 6 and naz[-1][0] == "food", f"(г) 5:55 смена: wood 10, food 6, еда последней: {naz}")
плохой_порядок = [(gt, наземные(о)) for gt, (s, о) in п.items() if "food" in dict(наземные(о)) and наземные(о)[-1][0] != "food"]
проверить(not плохой_порядок, f"(е) при поле еда всегда последней: {плохой_порядок[:3]}")
п0 = прогон({"пол_без_снятия": 0}, 279, 370)
н0 = dict(наземные(п0[370][1]))
проверить(н0.get("wood") == 9 and "food" not in н0, f"(д) ключ 0: 6:10 wood 9 и без еды, как живьём: {наземные(п0[370][1])}")
print("ИТОГ:", "чисто" if not ошибок else f"ошибок {ошибок}")
sys.exit(1 if ошибок else 0)
