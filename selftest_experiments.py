# -*- coding: utf-8 -*-
"""Реестр идей читается ЦЕЛИКОМ — так же, как его читает контейнер.

Повод, 22.09. В описании идеи `buy_wip` стояло «готово N%». configparser у
контейнера читает значения с интерполяцией, для него одиночный «%» — синтаксис,
и `pick_experiment.py` упал с InterpolationSyntaxError. Контейнер честно
остановился («идея не взята», прогон без флагов под именем идеи не начат), но
две копии успели поднять игру и скачать мост.

Моя проверка перед этим молчала, потому что читала ОДИН ключ (`база`):
интерполяция срабатывает лишь при чтении того значения, где стоит «%».
Отсюда правило теста: читать КАЖДОЕ значение КАЖДОЙ секции.

Заодно проверяется то, на чём контейнер останавливается сам: у каждой идеи
должны быть непустые `что` и `флаги` — прогон «без флагов» под именем идеи
выглядел бы законным и попал бы в сравнение.
"""
import configparser, io, os, sys

ФАЙЛ = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                    "docker", "experiments.ini")
ошибок = 0

# КАК У КОНТЕЙНЕРА: docker/exp.py с 25.09 читает БЕЗ интерполяции, потому что
# одиночный «%» в описании идеи ронял чтение файла целиком, а значения здесь —
# русская проза с числами, и подстановка не нужна никогда. Читать иначе, чем
# контейнер, значит проверять не то.
c = configparser.ConfigParser(interpolation=None)
c.read(ФАЙЛ, encoding="utf-8")
_как_в_exp = io.open(os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                 "docker", "exp.py"), encoding="utf-8").read()
if "configparser.ConfigParser(interpolation=None)" not in _как_в_exp:
    print("  СБОЙ: docker/exp.py читает файл ИНАЧЕ, чем эта проверка")
    ошибок += 1
print(f"секций: {len(c.sections())}")

for сек in c.sections():
    for ключ in c[сек]:
        try:
            значение = c[сек][ключ]
        except Exception as e:
            ошибок += 1
            print(f"  СБОЙ [{сек}] {ключ}: {type(e).__name__}: {str(e)[:90]}")
            continue
        if ключ == "что" and not значение.strip():
            ошибок += 1
            print(f"  СБОЙ [{сек}]: «что» пусто — мера не названа")

# ПУСТЫЕ ФЛАГИ — ПРЕДУПРЕЖДЕНИЕ, А НЕ СБОЙ. Часть старых секций (baseline,
# base_open, builders_topup) флагов не имеет: это точки отсчёта, игранные
# умолчаниями, и переписывать их задним числом значит врать про то, как они
# снимались. Контейнер про такую идею скажет сам при запуске.
предупреждений = 0
for сек in c.sections():
    if not c[сек].get("флаги", "").strip():
        предупреждений += 1
        print(f"  предупреждение [{сек}]: флагов нет — годится только как "
              f"точка отсчёта на умолчаниях")
print("предупреждений:", предупреждений)

print("ошибок:", ошибок)
sys.exit(1 if ошибок else 0)
