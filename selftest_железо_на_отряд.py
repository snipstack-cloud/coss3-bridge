#!/usr/bin/env python3
"""ЖЕЛЕЗО НА ОФИЦЕРА (4.11, пара bot2_wsave): ключ `железо_на_отряд`.

Офицер стоит 30 железа; при `шахта_железа` 2 и польской пике (0 железа) шахта не строилась, железо кончалось к 15–19 мин,
и после гибели офицера отряд больше не собирался. С ключом и `отрядов` ≥ 1 `_железо_нужно` отвечает «да»; без ключа или
без отрядов — как было.
    python3 selftest_железо_на_отряд.py"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import strategy_live as SL  # noqa: E402

ошибок = 0


def проверить(усл, что):
    global ошибок
    print(("ОК   " if усл else "ОШИБКА ") + что)
    ошибок += not усл


# настоящая строка из трассы bot2_wsave_pol/3 (Польша): пика iron0
st = {"fighters": "infantry17=pikemanpol,hp90,atk8,wkind1,pause0,rmax206,dmgs0,dmgp0,dinit8,dpike0,dsword0,dbullet0,food25,gold1,iron0,coal0 "
                  "musk17=musketeerpol,hp70,atk9,wkind3,pause312,rmax1312,dmgs0,dmgp0,dinit9,dpike0,dsword0,dbullet0,food40,gold3,iron3,coal0"}
б = SL._разбор_бойцов(st["fighters"])
проверить((б.get("infantry17") or {}).get("iron") == 0, f"(0) разбор бойцов видит пику без железа: {б.get('infantry17')}")
проверить(SL._железо_нужно({"шахта_железа": 2, "отрядов": 1}, st) is False, "(1) ключ 2, пика без железа, без нового ключа — шахта не нужна (как было)")
проверить(SL._железо_нужно({"шахта_железа": 2, "отрядов": 1, "железо_на_отряд": 200}, dict(st, iron=150)) is True, "(2) с `железо_на_отряд` 200, отрядами и железом 150 — нужна")
проверить(SL._железо_нужно({"шахта_железа": 2, "отрядов": 1, "железо_на_отряд": 200}, dict(st, iron=350)) is False, "(2б) железа 350 ≥ порога — ещё не нужна")
проверить(SL._железо_нужно({"шахта_железа": 2, "отрядов": 0, "железо_на_отряд": 200}, dict(st, iron=0)) is False, "(3) без отрядов ключ ничего не меняет")
проверить(SL._железо_нужно({"шахта_железа": 0, "отрядов": 1, "железо_на_отряд": 200}, dict(st, iron=0)) is False, "(4) `шахта_железа` 0 главнее — не строить")
print(f"ошибок: {ошибок}")
raise SystemExit(1 if ошибок else 0)
