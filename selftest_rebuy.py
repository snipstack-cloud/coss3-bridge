# -*- coding: utf-8 -*-
"""Самопроверка четвёртого повода: «денег хватило на то, в чём отказали».

Наблюдение игрока 21.09 на живой игре: «ресурсы есть, а вторую казарму не
ставит». Разбор трассы: на 533 с модель заказала казарму при золоте 2184 и
цене 2500. Игра отказала, и мост честно сказал это полем `last_fail` —
«BUILD netbar: NOT ENOUGH RESOURCES. It costs ... gold=2500». К 565 с золота
стало 2698, но заказ никто не повторил: к недоделанному не возвращаются, а сам
он не повторяется.

Роль узнаётся СВЕРКОЙ ЦЕНЫ, а не разбором sid: игра называет sid с приставкой
нации («netbar»), соответствия приставок у нас нет, а цена названа тут же и
указывает на постройку однозначно.

Стережётся: событие поднимается ровно в тот такт, когда хватило, и не раньше;
память отказа держится, пока не хватит; ответ даёт BUILD ВМЕСТЕ с BUILDERS —
закладка без строителей это котлован, который никто не роет.
"""
import llm_policy as L

беды = []


def проверка(имя, условие, пояснение=""):
    if условие:
        print("  ОК    " + имя)
    else:
        беды.append(имя)
        print("  ПЛОХО " + имя + (" — " + str(пояснение)[:300] if пояснение else ""))


ЦЕНЫ = ("center=food0,wood2100,stone2100,gold0,iron0,coal0 "
        "ba17=food0,wood500,stone500,gold2500,iron0,coal0 "
        "minegold=food0,wood100,stone100,gold0,iron0,coal0")
ОТКАЗ = ("| BUILD netbar: NOT ENOUGH RESOURCES. It costs food=0 wood=500 "
         "stone=500 gold=2500 iron=0 coal=0")


def ст(**правки):
    s = {"gametime": 500, "build_cost": ЦЕНЫ, "idle_pea": 7,
         "wood": 2600, "stone": 2700, "gold": 2184, "food": 2000,
         "iron": 500, "coal": 500, "ba17": 1, "wip": ""}
    s.update(правки)
    return s


# --- СРАБАТЫВАНИЕ
п = {}
проверка("при выключенном ключе молчит",
         L.отказ_по_деньгам(ст(last_fail=ОТКАЗ), п, 0) is None,
         "без --rebuy мост обязан вести себя как база")

п = {}
проверка("отказ запомнен, но денег ещё нет — молчим",
         L.отказ_по_деньгам(ст(last_fail=ОТКАЗ), п, 1) is None)
проверка("цена из отказа разобрана",
         п.get("цена") == {"wood": 500, "stone": 500, "gold": 2500}, п)
проверка("роль узнана СВЕРКОЙ ЦЕНЫ", п.get("роль") == "ba17",
         "sid в отказе — netbar, с приставкой нации")
проверка("денег хватило — СОБЫТИЕ",
         L.отказ_по_деньгам(ст(gold=2698), п, 1) == "ba17")
проверка("после срабатывания память очищена", not п.get("цена"),
         "иначе событие повторялось бы каждый такт")
проверка("без отказа в памяти молчит",
         L.отказ_по_деньгам(ст(gold=999999), п, 1) is None)

# СВЕРЯЕМСЯ С ЖИВЫМ СОСТОЯНИЕМ, а не с тем, что было в миг отказа: пока копили,
# могли и потратить.
п = {}
L.отказ_по_деньгам(ст(last_fail=ОТКАЗ), п, 1)
проверка("хватило по золоту, но потратили дерево — молчим",
         L.отказ_по_деньгам(ст(gold=2698, wood=100), п, 1) is None,
         "сверять надо ВСЕ ресурсы и по живому состоянию")

# --- ЗАПРОС
п = {}
L.отказ_по_деньгам(ст(last_fail=ОТКАЗ), п, 1)
L.отказ_по_деньгам(ст(gold=2698), п, 1)
з = L.запрос_докупки(ст(gold=2698), ст(gold=2698), "ba17")
проверка("запрос КОРОТКИЙ", len(з) < 700, f"{len(з)} символов")
проверка("сказано, что уже отказывали", "ОТКАЗАЛА" in з)
проверка("сказано, что заказ НЕ повторяется сам", "НЕ ПОВТОРЯЕТСЯ САМ" in з,
         "ради этого повод и заведён")
проверка("показано надо/есть по каждому ресурсу",
         "gold,2500,2698" in з.replace(" ", ""), з)
проверка("названо число свободных", "свободных крестьян 7" in з)
проверка("сказано про чужой недострой",
         "НЕ снимают с другого недостроя" in з)

# --- ОТВЕТ
о = L.докупка_в_команды({"что": "ba17", "строителей": 12, "why": "х"}, ст(gold=2698))
проверка("ответ даёт BUILD И BUILDERS",
         [c["cmd"] for c in о["commands"]] == ["BUILD", "BUILDERS"],
         "закладка без строителей — котлован, который никто не роет")
проверка("BUILD задаёт ИТОГ, а не прибавку",
         о["commands"][0]["total"] == 2, "казарма была одна, просим вторую")
проверка("строители переданы как названо", о["commands"][1]["total"] == 12)

о2 = L.докупка_в_команды({"что": "ba17", "why": "без строителей"}, ст(gold=2698))
проверка("строителей не назвали — мост ставит сам",
         о2["commands"][1]["total"] > 0)
проверка("и говорит об этом ВСЛУХ", "мост поставил" in о2["why"],
         "молчаливая подстановка неотличима от решения модели")

проверка("wait понимается",
         L.докупка_в_команды({"что": "wait", "why": "ж"}, ст())["commands"] == [])
проверка("незнакомая постройка не глотается",
         "не знает" in L.докупка_в_команды({"что": "дворец", "why": "?"},
                                           ст())["why"])

# --- РЕЕСТР
проверка("повод в реестре", "докупка" in L.ПОВОДЫ)
проверка("у повода все пять частей",
         set(L.ПОВОДЫ["докупка"]) >= {"system", "запрос", "метка", "словами", "ответ"})
проверка("метка годна для счёта по серии",
         L.ПОВОДЫ["докупка"]["метка"]("ba17") == "докупка#ba17")
исх = open("llm_policy.py", encoding="utf-8").read()
проверка("память отказа ведётся ВСЕГДА",
         "_докупка = отказ_по_деньгам(st, отказ_денег, докупка_вкл)" in исх
         and "if not СОБЫТИЕ and _докупка:" in исх,
         "иначе отказ при занятом событии потеряется")
проверка("повод стоит ПЕРВЫМ среди событий",
         исх.index("_докупка = отказ_по_деньгам") < исх.index("_вернулась = еда_вернулась"),
         "упущенная постройка дороже найма и перестановки людей")

print()
if беды:
    print(f"БЕД: {len(беды)} — {', '.join(беды)}")
    raise SystemExit(1)
print("всё чисто")
