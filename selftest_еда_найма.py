#!/usr/bin/env python3
"""ЕДА ПЕРВОЙ, ПОКА НАЙМ СТОИТ (10.10, §145): состояния третьей живой партии Д 2:00-8:30
(`sim/кейсы/партия_д3_10_10_2_00-8_30.jsonl`, из `coss3_bot.jsonl` 10.10 20:30). Вживую: еда ниже 500 с 1:45 до конца,
шахта золота 2 заложена в 3:25 и 3 — в 4:55 (строители и шахтёры с еды), бригада §135а по трое на дереве и камне
с 2:20 до 7:30; на еде 5 → 1 → 0, крестьян 24 и ни одного найма после 5:00, mil.1 не куплена, еда 0 к 8:36, армия 14.

Ключ `еда_найма` 600: пока еды меньше и поле созрело — (а) 3:25: шахта 2 НЕ закладывается, бригады дерева/камня нет,
на еду просится не меньше 10 (вся земля); с ключом 0 — `BUILD minegold 2`, как было; (б) 4:55: шахта 3 не закладывается;
(в) 7:26: вторая казарма (золота 4279 ≥ 2500) не закладывается — найм стоит, казарма бесполезна; с ключом 0 — `BUILD ba17 2`;
(г) 2:20: первая шахта золота ждёт камня (60 < 100) — бригада на камень 3 остаётся, бригады на дерево под казарму нет;
(д) 4:00: шахта 2 строится (`building_now` 1), вживую закладка была уже `ba17 2`, и шахта встала в 4:15 — закладок нет,
стройка идёт без них;
(е) Д2 6:00 (еда 1212 ≥ 600) — команды с ключом и без него одинаковы.

    python3 selftest_еда_найма.py
"""
import copy, json, os, sys, tempfile
К = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, К); sys.path.insert(0, os.path.join(К, "sim"))
import strategy_live as SL
import анализ_врага as АВ

состояния = [json.loads(l) for l in open(os.path.join(К, "sim/кейсы/партия_д3_10_10_2_00-8_30.jsonl"), encoding="utf-8")]
ошибок = 0
def проверить(усл, что):
    global ошибок
    print(("ОК   " if усл else "ОШИБКА ") + что); ошибок += not усл

def стратегия(доп):
    д = json.load(open(os.path.join(К, "sim/поиск/шт_s2_оборона_ручеёк_эко_так15_нужда.json"), encoding="utf-8"))
    д["итог"].update(доп)
    with tempfile.NamedTemporaryFile("w", suffix=".json", delete=False, encoding="utf-8") as f:
        json.dump(д, f, ensure_ascii=False)
    return SL.ЖиваяСтратегия(f.name)

def ответ(С, st):
    АВ._ТЕКУЩИЙ.update({"а": None, "t": None, "ответ": None})
    return С.ответ(copy.deepcopy(st))

def стройки(о):
    return [(c.get("role"), c.get("total")) for c in о["commands"] if c["cmd"] == "BUILD"]

def баланс(о, роль):
    return max([int(c.get("total") or 0) for c in о["commands"] if c["cmd"] == "BALANCE" and c.get("role") == роль] or [0])

def при(t):
    return next(s for s in состояния if s["gametime"] >= t)

st_а, st_б, st_в, st_г, st_д = при(205), при(295), при(446), при(140), при(240)
for имя, s in (("а", st_а), ("б", st_б), ("в", st_в), ("г", st_г), ("д", st_д)):
    print(f"{имя}: {s['gametime']} с — еда {s['food']}, крестьян {s['peasants']}, на еде {s['on_food']}, шахт золота {s['mines_gold']}, "
          f"дерево {s['wood']}, камень {s['stone']}, золото {s['gold']}, строится {s['building_now']} {s['wip']!r}, вживую {s['_cmds_live']}")

новая, старая = стратегия({}), стратегия({"еда_найма": 0})

о = ответ(новая, st_а); о0 = ответ(старая, st_а)
проверить(not any(р == "minegold" for р, _ in стройки(о)), f"(а) 3:25 с ключом шахта 2 не закладывается: {стройки(о)}")
проверить(баланс(о, "wood") < 3 and баланс(о, "stone") < 3, f"(а) бригад на дерево/камень нет: дерево {баланс(о, 'wood')}, камень {баланс(о, 'stone')}")
проверить(баланс(о, "food") >= 10, f"(а) на еду просится ≥ 10 (земли 10): {баланс(о, 'food')}")
проверить(("minegold", 2) in стройки(о0), f"(а) с ключом 0 — BUILD minegold 2, как было: {стройки(о0)}")

о = ответ(новая, st_б); о0 = ответ(старая, st_б)
проверить(not any(р == "minegold" for р, _ in стройки(о)), f"(б) 4:55 с ключом шахта 3 не закладывается: {стройки(о)}")
проверить(("minegold", 3) in стройки(о0), f"(б) с ключом 0 — BUILD minegold 3, как было: {стройки(о0)}")

о = ответ(новая, st_в); о0 = ответ(старая, st_в)
проверить(not any(р == "ba17" for р, _ in стройки(о)), f"(в) 7:26 при еде {st_в['food']} казарма 2 не закладывается: {стройки(о)}")
проверить(("ba17", 2) in стройки(о0), f"(в) с ключом 0 — BUILD ba17 2, как было: {стройки(о0)}")

о = ответ(новая, st_г)
проверить(баланс(о, "stone") >= 3, f"(г) 2:20 первая шахта золота ждёт камня — бригада на камень 3: {баланс(о, 'stone')}")
проверить(баланс(о, "wood") < 3, f"(г) бригады на дерево под казарму нет: {баланс(о, 'wood')}")

о = ответ(новая, st_д)
проверить(стройки(о) == [], f"(д) 4:00 шахта 2 строится (вживую закладка ba17 2, шахта встала в 4:15) — закладок нет: {стройки(о)}")

д2 = [json.loads(l) for l in open(os.path.join(К, "sim/кейсы/партия_д_10_10_2_00-9_30.jsonl"), encoding="utf-8")]
st_е = next(s for s in д2 if float(s["food"]) >= 1200 and s["gametime"] >= 350)
о = ответ(новая, st_е); о0 = ответ(старая, st_е)
ком = lambda о: sorted(json.dumps(c, ensure_ascii=False, sort_keys=True) for c in о["commands"])
проверить(ком(о) == ком(о0), f"(е) Д {st_е['gametime']} с при еде {st_е['food']}: команды с ключом и без него одинаковы ({len(о['commands'])})")
print(f"ошибок: {ошибок}")
sys.exit(1 if ошибок else 0)
