# -*- coding: utf-8 -*-
"""Самопроверка: шахта в таблице «что купить», одной мерой со зданиями.

Наблюдение игрока 21.09 на живой игре: 37 крестьян, одна золотая шахта, все
пять мест заняты — а казарма стоит золота. Мост при этом говорил «работает 5
из 5 мест» и «свободная залежь в 38 на NE» СЫРЫМИ числами, рядом с таблицей,
где всё посчитано бойцами. Сравнить их было нечем.

Шахта бойцов не куёт — она СНИМАЕТ ОГРАНИЧЕНИЕ, без которого казармы не
купить. Поэтому считается через узкое место: места на замеренную отдачу дают
приход, приход сокращает ожидание казармы, сокращённое ожидание — это бойцы.

Стережётся: совет появляется ТОЛЬКО когда узко (шахта полна И ресурса не
хватает); молчит, когда мест хватает или денег и так довольно; не выдумывает
отдачу там, где она не замерена; каждое звено цепочки видно в строке, а натяжки
названы.
"""
import llm_policy as L

беды = []


def проверка(имя, условие, пояснение=""):
    if условие:
        print("  ОК    " + имя)
    else:
        беды.append(имя)
        print("  ПЛОХО " + имя + (" — " + str(пояснение)[:300] if пояснение else ""))


def состояние(**правки):
    ст = {
        "gametime": 600, "peasants": 48,
        "food": 2500, "wood": 3000, "stone": 3000, "gold": 400,
        "iron": 2000, "coal": 1000,
        "mines_gold": 1, "cap_gold": 5, "on_gold": 5,
        "mines_iron": 1, "cap_iron": 5, "on_iron": 5,
        "centers": 1, "smiths": 1, "ba17": 1, "stables": 0, "mills": 1,
        "academi": 1,
        # Цены построек приходят полем build_cost — строка настоящей игры
        # 21.09, чтобы проверка не разошлась с живыми числами.
        "build_cost": ("center=food0,wood2100,stone2100,gold0,iron0,coal0 "
                       "mill=food0,wood60,stone300,gold0,iron0,coal0 "
                       "smith=food0,wood400,stone120,gold0,iron2560,coal0 "
                       "ba17=food0,wood500,stone500,gold2500,iron0,coal0 "
                       "minegold=food0,wood100,stone100,gold0,iron0,coal0 "
                       "mineiron=food0,wood100,stone100,gold0,iron0,coal0 "
                       "stable=food0,wood800,stone400,gold1200,iron0,coal0 "
                       "academi=food0,wood1050,stone1230,gold0,iron0,coal0"),
    }
    ст.update(правки)
    return ст


def строка_шахты(ст):
    L.РЕСУРСЫ_ИСТОРИЯ.clear()
    for s in L.что_купить(ст):
        if "шахта" in s:
            return s
    return ""


# --- КОГДА СОВЕТ ДОЛЖЕН БЫТЬ
с = строка_шахты(состояние())
проверка("шахта полна и золота мало — совет есть", bool(с), "строки нет вовсе")
проверка("названо, что шахта ПОЛНА", "ПОЛНА" in с and "5 из 5" in с, с[:160])
проверка("названо, сколько НЕ ХВАТАЕТ", "не хватает" in с, с[:160])
проверка("назван приход новых мест", "в секунду по замеру" in с, с[:200])
проверка("сказано, насколько РАНЬШЕ придёт казарма", "раньше" in с, с[:200])
проверка("число названо ОЦЕНКОЙ, а не замером", "ОЦЕНКА" in с,
         "цепочка длинная, выдавать её за замер нельзя")
проверка("натяжки названы вслух", "НАТЯЖКИ" in с,
         "время стройки шахты не учтено, приход взят как у нынешней")

# --- КОГДА СОВЕТА БЫТЬ НЕ ДОЛЖНО
проверка("мест хватает — молчим",
         not строка_шахты(состояние(on_gold=2)),
         "надо посылать людей, а не тратиться на стройку")
проверка("золота и так довольно — молчим",
         not строка_шахты(состояние(gold=999999)),
         "казарма по карману, шахта не к спеху")
проверка("поле мест пусто — это НЕ полнота",
         not строка_шахты(состояние(cap_gold=None)),
         "неизвестное не выдаём за ноль")

# --- ОТДАЧА ТОЛЬКО ЗАМЕРЕННАЯ
проверка("отдача золота взята из замера",
         abs(L.ОТДАЧА_НА_ЧЕЛОВЕКА["gold"] - 98.0 / 60.0) < 0.01
         or L.ОТДАЧА_НА_ЧЕЛОВЕКА["gold"] > 0,
         "число должно приходить из ДОБЫЧА_НА_ЧЕЛОВЕКА, а не из воздуха")

# --- МЕРА ТА ЖЕ, ЧТО У ЗДАНИЙ
L.РЕСУРСЫ_ИСТОРИЯ.clear()
все = L.что_купить(состояние())
проверка("шахта стоит в ОДНОЙ таблице с казармой",
         any("казарма" in s for s in все) and any("шахта" in s for s in все),
         "ради этого всё и делалось: сравнить их числом, а не на глаз")
проверка("у шахты мера в бойцах, как у зданий",
         "бойца" in с or "бойцов" in с, с[:120])

print()
if беды:
    print(f"БЕД: {len(беды)} — {', '.join(беды)}")
    raise SystemExit(1)
print("всё чисто")
