def _смесь(виды):
    всего = sum(n for n, _ in виды)
    return [(n / всего, х) for n, х in виды] if всего else []


def урон_эфф(атакующий, цель) -> float:
    """Урон за удар по формуле кода, но не меньше ДОЛЯ_АТАКИ_МИНИМУМ от атаки."""
    return max(float(CM.урон(атакующий, цель)), ДОЛЯ_АТАКИ_МИНИМУМ * float(атакующий.get("atk", 0)))


def урон_на_голову(бьющие, цели) -> float:
    """Средний урон одного бойца стороны за удар по смеси целей."""
    с = _смесь(цели)
    всего = sum(n for n, _ in бьющие)
    if not всего or not с:
        return 0.0
    return sum(n * sum(доля * урон_эфф(х, ц) for доля, ц in с) for n, х in бьющие) / всего


def hp_на_голову(виды) -> float:
    всего = sum(n for n, _ in виды)
    return sum(n * int(х.get("hp") or 1) for n, х in виды) / всего if всего else 1.0


