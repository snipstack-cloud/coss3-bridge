БЛИЖНИЙ_РАДИУС = 200      # пикселей: у кого radiusmin больше — в клетке не бьёт

# ГЕОМЕТРИЯ, ИСПРАВЛЕННАЯ 27.09 (ошибка была моя и стоила серии `rear_shooters`).
