# и дыру §13л НЕ закрыл: с потолком 20 полный словарь всё равно выигрывал 18 из 48
# (было 22), а реплей home_defense2/1 промахнулся в другую сторону (наши 223
# против 99 в записи), его потери по 64 записям упали до 3715/4597. Оставлен, чтобы
# проверить заново на записях с точными `cells`.
ФРОНТ_У_ЕГО_БАЗЫ = None


# [код+игрок, 27.09] СТРЕЛОК В КЛЕТКЕ КОНТАКТА НЕ СТРЕЛЯЕТ. У мушкетёра и
# драгуна `radiusmin` = 300 пикселей = 5,6 клетки (`параметры.json`, из
# `SetObjBaseWeapon`), у лучника 7,5, а у пикинёра 0,66. Движок, найдя цель
# ближе минимума, не стреляет, а ОТХОДИТ на нужную дистанцию
# (`lib/unit.script:7898`). Клетка же 16 единиц, то есть внутри клетки контакта
# расстояния меньше одной клетки ВСЕГДА — значит стрелки там не бьют вовсе,
# только гибнут. Игрок сказал это словами раньше, чем нашёлся код: «если к
# мушкетёрам подойдут в упор, стрелять они не будут, а будут отходить».
# Проверка по 451 живому бою: размен по доле наших стрелков 0,40 / 0,69 / 0,58 /
# 0,33 (ноль / до 20 % / 20-40 % / 40 %+), а закон без этой поправки предсказывал
# монотонный рост 0,35 / 0,42 / 0,50 / 0,54 — то есть ровно наоборот на краю.
БЛИЖНИЙ_РАДИУС = 200      # пикселей: у кого radiusmin больше — в клетке не бьёт


def ближние(стороны):
    """Кто реально бьёт в клетке контакта: у стрелков `radiusmin` больше клетки."""
    из = []
    for n, х in стороны:
        rmin = х.get("radiusmin_px")
        if rmin is None:
            rmin = 0 if (х.get("rmax") or 0) <= 500 else 300
        if float(rmin) <= БЛИЖНИЙ_РАДИУС:
            из.append((n, х))
    return из


def ставки(A, B, лок_наш, лок_его, насыщено, k=K_УДАРОВ_В_СЕК, кап_наш=None):
    """Потери обеих сторон в бойцах за секунду контакта. A, B — [(n, характеристики)]."""
    n_наш = sum(n for n, _ in A)
    n_его = sum(n for n, _ in B)
    # Ворота боя 25.09: если при насыщении клетки считать бьющими всю армию, потери
    # завышаются втрое (смещение +1,61 log2). Число в клетке — даже как нижняя
    # граница «36 и больше» — ближе к правде: у боя есть фронт. Поэтому бьют
    # min(сторон) плюс половина излишка: f=0,5 даёт |log2| 0,82 и 59 % в пределах
    # двух раз против 0,90 и 54 % при чистом min и 0,84 при «каждый бьёт».
    # бьют только ближние; гибнут все, кто в клетке
    A_б, B_б = ближние(A), ближние(B)
    доля_a = sum(n for n, _ in A_б) / n_наш if n_наш else 0.0
    доля_b = sum(n for n, _ in B_б) / n_его if n_его else 0.0
    l1 = (min(лок_наш, n_наш) if лок_наш else n_наш) * доля_a
    l2 = (min(лок_его, n_его) if лок_его else n_его) * доля_b
    m = min(l1, l2)
    бьют_наш = m + ДОЛЯ_ИЗЛИШКА * (l1 - m)
    бьют_его = m + ДОЛЯ_ИЗЛИШКА * (l2 - m)
    if кап_наш is not None:
        бьют_наш = min(бьют_наш, кап_наш)
    наши = k * бьют_его * урон_на_голову(B_б or B, A) / hp_на_голову(A)
    его = k * бьют_наш * урон_на_голову(A_б or A, B) / hp_на_голову(B)
    return {"наши": наши, "его": его, "бьют_наш": бьют_наш, "бьют_его": бьют_его}


def залпы(стрелки, цели, ближние_цели):
    """Потери цели от ЗАЛПОВ ДО КОНТАКТА за один эпизод.

    [код+игрок 27.09] Стрелок в клетке не бьёт (`ближние`), но пока противник
    ПОКРЫВАЕТ РАЗРЫВ ДАЛЬНОСТЕЙ, он стреляет безнаказанно: у мушкетёра
    `rmax` 16,9 клетки против 1,9 у пикинёра, и `combat_math.залпы_форы` даёт
    по этому разрыву число выстрелов (честно вниз, без выстрела в упор).
    Ровно тактика игрока: «10 пикинёров задержат подход, пока 20 мушкетёров
    расстреливают». Залп считается ОДИН РАЗ за эпизод: подходят к нам однажды,
    а не каждую секунду.
    """
    если_нет = 0.0
    if not стрелки or not цели:
        return если_нет
    образец = (ближние_цели or цели)[0][1]
    из = 0.0
    for n, х in стрелки:
        выстрелов = CM.залпы_форы(х, образец)
        if выстрелов <= 0:
            continue
        из += n * выстрелов * урон_эфф(х, образец) / max(hp_на_голову(цели), 1.0)
    return из


def потери_за_бой(A, B, длина_с, лок_наш, лок_его, насыщено, k=K_УДАРОВ_В_СЕК,
                  шум: random.Random | None = None, кап_наш=None, залпом=False) -> dict:
    """Ожидаемые (или разыгранные) потери за эпизод, не больше численности стороны."""
    с = ставки(A, B, лок_наш, лок_его, насыщено, k, кап_наш)
    наши = с["наши"] * длина_с
    его = с["его"] * длина_с
    if залпом:
        # стрелки той и другой стороны бьют по подходящему противнику
        дальние_a = [(n, х) for n, х in A if (n, х) not in ближние(A)]
        дальние_b = [(n, х) for n, х in B if (n, х) not in ближние(B)]
        его += залпы(дальние_a, B, ближние(B))
        наши += залпы(дальние_b, A, ближние(A))
    if шум is not None:
        наши *= 2 ** шум.gauss(0, СИГМА_LOG2)
        его *= 2 ** шум.gauss(0, СИГМА_LOG2)
    return {"наши": min(наши, sum(n for n, _ in A)), "его": min(его, sum(n for n, _ in B))}


def бой_за_такт(A, B, dt, лок_наш, лок_его, насыщено, rng: random.Random, k=K_УДАРОВ_В_СЕК,
                у_его_базы=False, залпом=False) -> dict:
    """Потери за такт симулятора с шумом; дробные потери накапливать снаружи.

    `залпом` — первый такт контакта: только в нём считаются выстрелы, сделанные
    ПОКА противник подходил. Дальше стороны уже вплотную, и стрелки молчат.
    """
    return потери_за_бой(A, B, dt, лок_наш, лок_его, насыщено, k, rng,
                         ФРОНТ_У_ЕГО_БАЗЫ if (у_его_базы and ФРОНТ_У_ЕГО_БАЗЫ) else None, залпом)
