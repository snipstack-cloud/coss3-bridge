# -*- coding: utf-8 -*-
"""Ядро боя симулятора — §6 спецификации, закон потерь, проверенный воротами боя.

Потери стороны за секунду контакта:

    потери_наши/с = k · бьющих_его · урон_его_за_удар(с поправкой на строй) / hp_наш
    потери_его/с  = k · бьющих_наш · урон_наш_за_удар / hp_его

где урон за удар — формула игры (`combat_math.урон`: атака минус защита по типу
оружия, не меньше 1) по смеси видов противника, hp — среднее здоровье на голову.
«Бьющих» — фронт: min(сторон в клетках боя) плюс половина излишка большей
стороны; число в клетке берётся как есть и при насыщении («+» = 36 и больше),
потому что «бьёт вся армия» завышает потери втрое (ворота 25.09). k — ударов в
секунду на бойца, единственная подгоняемая константа: 0,315 по 329 боям.

Отношение потерь при этом задаётся качеством (урон и здоровье с поправкой на
строй), а не численным перевесом — так показал замер 24.09 (`validate_combat.py`).
Шум — множитель 2^N(0, σ) на потери каждой стороны, σ = 1,33 log2 по сторонам
после подгонки: исход одного боя не предсказывается, тенденция серии — да.
"""
import math
import os
import random
import sys

sys.path.insert(0, os.path.expanduser("~/coss3-bridge"))
import combat_math as CM  # noqa: E402

K_УДАРОВ_В_СЕК = 0.315    # [замер] ворота боя 25.09: подгонка под нулевое смещение по 329 боям
СИГМА_LOG2 = 1.33         # [замер] разброс log2(пред/факт) по сторонам после подгонки
НАСЫЩЕНИЕ = 36
ДОЛЯ_ИЗЛИШКА = 0.5        # бьёт min(сторон) плюс половина излишка большей стороны (§6, фронт)


def _смесь(виды):
    всего = sum(n for n, _ in виды)
    return [(n / всего, х) for n, х in виды] if всего else []


def урон_на_голову(бьющие, цели) -> float:
    """Средний урон одного бойца стороны за удар по смеси целей."""
    с = _смесь(цели)
    всего = sum(n for n, _ in бьющие)
    if not всего or not с:
        return 0.0
    return sum(n * CM._урон_по_смеси(х, с) for n, х in бьющие) / всего


def hp_на_голову(виды) -> float:
    всего = sum(n for n, _ in виды)
    return sum(n * int(х.get("hp") or 1) for n, х in виды) / всего if всего else 1.0


def ставки(A, B, лок_наш, лок_его, насыщено, k=K_УДАРОВ_В_СЕК):
    """Потери обеих сторон в бойцах за секунду контакта. A, B — [(n, характеристики)]."""
    n_наш = sum(n for n, _ in A)
    n_его = sum(n for n, _ in B)
    # Ворота боя 25.09: если при насыщении клетки считать бьющими всю армию, потери
    # завышаются втрое (смещение +1,61 log2). Число в клетке — даже как нижняя
    # граница «36 и больше» — ближе к правде: у боя есть фронт. Поэтому бьют
    # min(сторон) плюс половина излишка: f=0,5 даёт |log2| 0,82 и 59 % в пределах
    # двух раз против 0,90 и 54 % при чистом min и 0,84 при «каждый бьёт».
    l1 = min(лок_наш, n_наш) if лок_наш else n_наш
    l2 = min(лок_его, n_его) if лок_его else n_его
    m = min(l1, l2)
    бьют_наш = m + ДОЛЯ_ИЗЛИШКА * (l1 - m)
    бьют_его = m + ДОЛЯ_ИЗЛИШКА * (l2 - m)
    наши = k * бьют_его * урон_на_голову(B, A) / hp_на_голову(A)
    его = k * бьют_наш * урон_на_голову(A, B) / hp_на_голову(B)
    return {"наши": наши, "его": его, "бьют_наш": бьют_наш, "бьют_его": бьют_его}


def потери_за_бой(A, B, длина_с, лок_наш, лок_его, насыщено, k=K_УДАРОВ_В_СЕК,
                  шум: random.Random | None = None) -> dict:
    """Ожидаемые (или разыгранные) потери за эпизод, не больше численности стороны."""
    с = ставки(A, B, лок_наш, лок_его, насыщено, k)
    наши = с["наши"] * длина_с
    его = с["его"] * длина_с
    if шум is not None:
        наши *= 2 ** шум.gauss(0, СИГМА_LOG2)
        его *= 2 ** шум.gauss(0, СИГМА_LOG2)
    return {"наши": min(наши, sum(n for n, _ in A)), "его": min(его, sum(n for n, _ in B))}


def бой_за_такт(A, B, dt, лок_наш, лок_его, насыщено, rng: random.Random, k=K_УДАРОВ_В_СЕК) -> dict:
    """Потери за такт симулятора с шумом; дробные потери накапливать снаружи."""
    return потери_за_бой(A, B, dt, лок_наш, лок_его, насыщено, k, rng)
