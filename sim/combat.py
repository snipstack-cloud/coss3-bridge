# за удар выходит 1-2 (155 эпизодов из 370: размен факт 0,30, предсказано 0,17).
# Формула за удар верна, но темп потерь ей не линеен — с эффективным уроном не
# меньше четверти атаки размен по полосам сходится: 0,30/0,31, 0,47/0,53,
