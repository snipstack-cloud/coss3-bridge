K_УДАРОВ_В_СЕК = 0.237    # [замер] ворота боя 27.09: подгонка при «стрелки в клетке не бьют» + залпы до контакта: подгонка при пороге урона и «бьют все» (0,359 при доле излишка 0,5)
# [замер] 26.09, 370 эпизодов: линейный «атака минус защита, не меньше 1» (код игры,
