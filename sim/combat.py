"""Ядро боя симулятора — §6 спецификации, закон потерь, проверенный воротами боя.

Потери стороны за секунду контакта:

    потери_наши/с = k · бьющих_его · урон_его_за_удар(с поправкой на строй) / hp_наш
    потери_его/с  = k · бьющих_наш · урон_наш_за_удар / hp_его

где урон за удар — формула игры (`combat_math.урон`: атака минус защита по типу
оружия, не меньше 1) по смеси видов противника, hp — среднее здоровье на голову.
«Бьющих» — фронт: min(сторон в клетках боя) плюс половина излишка большей
стороны; число в клетке берётся как есть и при насыщении («+» = 36 и больше),
потому что «бьёт вся армия» завышает потери втрое (ворота 25.09). k — ударов в
секунду на бойца, единственная подгоняемая константа: 0,315 по 329 боям.

Отношение потерь при этом задаётся качеством (урон и здоровье с поправкой на
строй), а не численным перевесом — так показал замер 24.09 (`validate_combat.py`).
Шум — множитель 2^N(0, σ) на потери каждой стороны, σ = 1,33 log2 по сторонам
после подгонки: исход одного боя не предсказывается, тенденция серии — да.
"""
import math
import os
import random
import sys

sys.path.insert(0, os.path.expanduser("~/coss3-bridge"))
import combat_math as CM  # noqa: E402

K_УДАРОВ_В_СЕК = 0.237    # [замер] ворота боя 27.09: подгонка при «стрелки в клетке не бьют» + залпы до контакта: подгонка при пороге урона и «бьют все» (0,359 при доле излишка 0,5)
# [замер] 26.09, 370 эпизодов: линейный «атака минус защита, не меньше 1» (код игры,
# miscext2.script:434) в СУММЕ по эпизодам занижает его потери там, где наш урон
# за удар выходит 1-2 (155 эпизодов из 370: размен факт 0,30, предсказано 0,17).
# Формула за удар верна, но темп потерь ей не линеен — с эффективным уроном не
# меньше четверти атаки размен по полосам сходится: 0,30/0,31, 0,47/0,53,
# 0,70/0,69 (пред/факт). Порог — только здесь, в ядре симулятора; калькулятор
# моста (`combat_math.урон`) остаётся формулой кода.
ДОЛЯ_АТАКИ_МИНИМУМ = 0.25
СИГМА_LOG2 = 1.33         # [замер] разброс log2(пред/факт) по сторонам после подгонки
НАСЫЩЕНИЕ = 36
# [замер] 26.09 вечер, home_defense2: при настоящих числах (194 наших дома против
# 36 его, копия 2) размен факт 2,77, «бьют все» даёт 2,69, половина излишка — 1,60;
# по 387 эпизодам при перевесе наших больше двух раз пред/факт 0,69/0,66 против
# 0,54/0,66 с половиной. Общая точность та же (|log2| 0,87), поэтому доля 1,0.
ДОЛЯ_ИЗЛИШКА = 1.0


def _смесь(виды):
    всего = sum(n for n, _ in виды)
    return [(n / всего, х) for n, х in виды] if всего else []


def урон_эфф(атакующий, цель) -> float:
    """Урон за удар по формуле кода, но не меньше ДОЛЯ_АТАКИ_МИНИМУМ от атаки."""
    return max(float(CM.урон(атакующий, цель)), ДОЛЯ_АТАКИ_МИНИМУМ * float(атакующий.get("atk", 0)))


def урон_на_голову(бьющие, цели) -> float:
    """Средний урон одного бойца стороны за удар по смеси целей."""
    с = _смесь(цели)
    всего = sum(n for n, _ in бьющие)
    if not всего or not с:
        return 0.0
    return sum(n * sum(доля * урон_эфф(х, ц) for доля, ц in с) for n, х in бьющие) / всего


def hp_на_голову(виды) -> float:
    всего = sum(n for n, _ in виды)
    return sum(n * int(х.get("hp") or 1) for n, х in виды) / всего if всего else 1.0


