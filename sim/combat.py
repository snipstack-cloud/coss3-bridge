# Прежняя запись «radiusmin 5,6 клетки» путала единицы с клетками.
ОГОНЬ_ОТ = 7.5            # единиц: ближе стрелок отходит и молчит [код]
ОГОНЬ_ДО = 15.0           # единиц: дальше не достаёт [код]
# ЗАМЕР по 1 073 такту боя с полем «между» (27.09): в полосе огня 7,5-15 стрелки
# учетверяют размен (0,67 при доле стрелков 15 %+ против 0,14 при малой), а
