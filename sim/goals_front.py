"""Лестница и награда стратегии «УКРЕПЛЁННЫЙ ФРОНТ» (28.09, замысел игрока).

Замысел: две казармы дают массовость пехоты, отряды с приоритетом защиты держат
ключевые клетки и не дают продавить линию. Ниже он переведён в измеримое, и КАЖДАЯ
замена названа — иначе лестница награждала бы за то, чего в симуляторе нет.

ЧТО ЗАМЕНЕНО И ПОЧЕМУ:

1. «Армия разделена на отряды по 8-20 юнитов, отряды на удержании» — ОТРЯДОВ В
   ИГРОВОМ СМЫСЛЕ У НАС НЕТ. Строй собирается вокруг офицера и барабанщика, а их
   делает только академия, и она вне правил партии (world.md, `--ban academi` в
   старых сериях; сегодня измерено, что она и не окупается). Поэтому «отряд» здесь
   это наша группа моста, а «удержание» — такты, когда наша группа стоит в клетке
   подхода и в ней есть его бойцы.
2. «Процент отбитых атак» — НЕ НАША МЕРА. Враг в симуляторе это ЗАПИСЬ: он нападает
   тогда, когда нападал в записи, а не в ответ на нас. Поэтому «отбитых атак» в
   чистом виде было бы подарком записи (ровно как прежняя ступень 5 общей лестницы,
   где ярус 1 брал её, не убив никого). Вместо этого мерится РАЗМЕН В ОБОРОНЕ: его
   потери на нашу в клетках не дальше пяти от НАШЕЙ базы.
3. «Выживаемость юнита» — В СИМУЛЯТОРЕ НЕ СЧИТАЕТСЯ: отдельных бойцов нет, есть
   числа по видам. Вместо неё в ступени 3 остаётся проверяемая часть: взяты ли
   апгрейды защиты не позже атаки (по уровням линеек `bar.*.2.*` против `bar.*.1.*`).
4. «Ключевые клетки, узкие проходы» — понятия узких проходов у нас нет: карта это
   16×16 чисел. Ключевыми считаются клетки ПОДХОДА: не дальше пяти от нашей базы и
   не ближе трёх к его — то есть та полоса, через которую идёт его волна.
5. Скользящее окно 3-5 минут заменено счётом за партию: снимки раз в 5 с, и окно из
   них шумит сильнее, чем разница между политиками (та же причина, что у мушкетёров).

ЧИСЛА ПОРОГОВ: 15 пехоты — из замера, что ключ еды даёт 18-25 бойцов к 300 с;
размен 1:1,2 (0,83) — из живого замера полосы перевеса у базы; две казармы — из
слов игрока про осаду (две казармы, две конюшни, два центра).
"""
import math
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

ч = lambda d, k: float((d or {}).get(k) or 0)

СТУПЕНИ = (
    ("1 две казармы", "2 казармы и 15+ пехоты"),
    ("2 поток пехоты", "ДВЕ казармы, найм 8+ в минуту, доля пехоты 60 %+"),
    ("3 защита раньше", "2+ уровня защиты и их не меньше, чем атаки"),
    ("4 удержание", "20 %+ тактов наши стоят в клетке подхода с его бойцами"),
    ("5 размен в обороне", "у нашей базы его потери на нашу не хуже 1:1,2"),
    ("6 контратака", "после удержания убито 10+ его крестьян"),
)
ВЕСА = (1.0, 1.0, 1.5, 1.5, 2.0, 1.0)
ПОРОГ_РАЗМЕНА = 1 / 1.2
ВЕС_РАЗМЕНА = 1.5
ПОТОЛОК_РАЗМЕНА = 2.0
ВЕС_УДЕРЖАНИЯ = 1.0
ПОТОЛОК_УДЕРЖАНИЯ = 0.6
ПЛАТА_ЗА_ПЕХОТУ = 0.004


def _уровни(взято):
    """(уровней атаки, уровней защиты) по именам `bar.<вид>.<линейка>.<ступень>`"""
    ат = защ = 0
    for у in взято:
        части = str(у).split(".")
        if len(части) == 4 and части[0] == "bar":
            if части[2] == "1":
                ат += 1
            elif части[2] == "2":
                защ += 1
    return ат, защ


def числа(сим, история):
    посл = история[-1] if история else {}
    пехота = ч(посл, "mil_inf") + ч(посл, "mil_shooters")
    армия = пехота + ч(посл, "mil_cav")
    взято = {x.strip() for x in str(посл.get("upg_done") or "").split(",") if x.strip()}
    ат, защ = _уровни(взято)
    # НАЙМ ПЕХОТЫ: прирост плюс потери — так же, как мост считает найм врага
    нанято = 0.0
    for a, b in zip(история, история[1:]):
        нанято += max(0.0, (ч(b, "mil_inf") + ч(b, "mil_shooters"))
                      - (ч(a, "mil_inf") + ч(a, "mil_shooters")))
    нанято += max(0.0, ч(посл, "my_mil_lost"))
    минут = max(ч(посл, "gametime") / 60.0, 1.0)
    # УДЕРЖАНИЕ и ОБОРОНА — по журналу боя: (t, cx, cy, режим, наших, его, наши, его)
    eb = getattr(сим.з, "en_base", None) or (15, 15)
    mb = (getattr(сим.з, "my_cx", 0.0), getattr(сим.з, "my_cy", 0.0))
    держали = 0
    наши_дома = его_дома = 0.0
    for запись in getattr(сим, "журнал_боя", []):
        t, cx, cy, режим, n, его_в, a, b = запись[:8]
        d_дом = math.hypot(cx - mb[0], cy - mb[1])
        d_его = math.hypot(cx - eb[0], cy - eb[1])
        if d_дом <= 5 and d_его > 3:
            держали += 1
            наши_дома += a
            его_дома += b
    тактов = max(len(история), 1)
    return dict(казарм=ч(посл, "ba17"), пехота=пехота, армия=армия,
                доля=(пехота / армия) if армия > 0 else 0.0,
                атаки=ат, защиты=защ, темп_найма=нанято / минут,
                держали=держали, доля_удержания=держали / тактов,
                размен_обороны=(его_дома / наши_дома) if наши_дома > 0 else 0.0,
                потери_пехоты=ч(посл, "my_mil_lost"),
                убито_крестьян=getattr(сим, "убито_крестьян", 0.0))


def ступени(сим, история):
    д = числа(сим, история)
    п = {}
    взято = set()

    п[1] = min(1.0, д["пехота"] / 15.0) * (0.5 + 0.5 * min(1.0, д["казарм"] / 2.0))
    if д["казарм"] >= 2 and д["пехота"] >= 15:
        взято.add(1)

    # ПОТОК ЧЕРЕЗ ДВЕ КАЗАРМЫ, а не просто поток: ярус 1 с одной казармой даёт
    # 10 пехоты в минуту при доле 100 % и брал эту ступень даром (замер 28.09).
    п[2] = min(1.0, д["темп_найма"] / 8.0) * min(1.0, д["казарм"] / 2.0)
    if д["казарм"] >= 2 and д["темп_найма"] >= 8.0 and д["доля"] >= 0.6:
        взято.add(2)

    # «ЗАЩИТА НЕ ПОЗЖЕ АТАКИ» выполняется и когда атаки не взято вовсе — требовать
    # обе линейки было бы строже замысла (поймано на пробе 28.09: 2 уровня защиты
    # при нуле атаки ступень не брали).
    п[3] = min(1.0, д["защиты"] / 2.0) if д["защиты"] >= д["атаки"] else 0.0
    if д["защиты"] >= 2 and д["защиты"] >= д["атаки"]:
        взято.add(3)

    п[4] = min(1.0, д["доля_удержания"] / 0.20)
    if д["доля_удержания"] >= 0.20:
        взято.add(4)

    п[5] = min(1.0, д["размен_обороны"] / ПОРОГ_РАЗМЕНА) if ПОРОГ_РАЗМЕНА else 0.0
    if д["размен_обороны"] >= ПОРОГ_РАЗМЕНА and д["держали"] >= 3:
        взято.add(5)

    п[6] = min(1.0, д["убито_крестьян"] / 10.0) if 4 in взято else 0.0
    if 4 in взято and д["убито_крестьян"] >= 10:
        взято.add(6)
    return взято, п, д


def награда(сим, история) -> float:
    взято, п, д = ступени(сим, история)
    r = sum(ВЕСА[i - 1] * (1.0 if i in взято else п.get(i, 0.0))
            for i in range(1, len(СТУПЕНИ) + 1))
    r += ВЕС_РАЗМЕНА * min(д["размен_обороны"], ПОТОЛОК_РАЗМЕНА)
    r += ВЕС_УДЕРЖАНИЯ * min(д["доля_удержания"], ПОТОЛОК_УДЕРЖАНИЯ)
    # Плата только при удержании: иначе политика учится не иметь пехоты вовсе
    if д["доля_удержания"] >= 0.05:
        r -= ПЛАТА_ЗА_ПЕХОТУ * д["потери_пехоты"]
    return r
