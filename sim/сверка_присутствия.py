#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""СВЕРКА: чему научилась сеть §30 сверх голого «присутствия» (1.10).

Повод: обученные на агентном враге сети (§30, `sim/ночь01/`) с 7:00 включают режим
«присутствие» (каждые 15 с вся свободная армия к нему, досылкой в волну) и больше не
делают почти ничего — ни прокачки, ни удара «вся армия по армии». А досылка частями во
всех прежних проверках проигрывала (§23: −4,3 против +0,7 у кулака). Если голое
присутствие скриптом даёт на агентном враге столько же, сколько сеть, — сеть нашла не
стратегию, а дыру симулятора.

Кандидаты на одних партиях и зёрнах (25 отложенных × 3), против каждого стиля врага:
сети s1-s3, расписание поиска §29в против этого стиля, присутствие скриптом (то же
хозяйство, мушкетёры, режим с 7:00), ярус 1 без войны. Мера — `поиск_стратегии.мера`
и её части; плюс где он теряет бойцов (у своей базы / в поле / у нас) — по журналу боя.

    python3 sim/сверка_присутствия.py [нет|родной,горячий,осторожный]   # «нет» — прежний симулятор, без агента
"""
import json
import math
import os
import statistics as St
import sys
from multiprocessing import Pool

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
К = os.path.dirname(os.path.abspath(__file__))
ЭКО = dict(дерево=2, камень=1, шахт_золота=2, казарм=2, еда_после=0.55)


class Присутствие:
    """То, что делают сети, — без сети: мушкетёры с 5:00, присутствие с 7:00."""
    def __init__(self, цель="peasants_free", с=420.0):
        import tier1 as T1
        self.я, self.цель, self.с = T1.Ярус1(**ЭКО), цель, с

    def __call__(self, st):
        из = self.я(st)
        t = float(st.get("gametime") or 0)
        if t >= 300 and float(st.get("ba17") or 0) > 0 and "musketeer" not in str(st.get("train_now") or ""):
            из.append({"cmd": "TRAIN", "role": "musk17", "total": -1})
        if t >= self.с and float(st.get("my_freewar") or 0) > 0:
            вне = float(st.get("mil_away") or 0)
            из.append({"cmd": "ATTACK", "count": "all", "target": "wave" if вне > 0 else self.цель})
        return из


def _партия(з):
    вид, арг, стиль, d, seed = з
    import numpy as np
    import sim as SIM
    import policy_strat as PS
    import поиск_стратегии as ПС
    import tier1 as T1
    SIM.АГЕНТНЫЙ_ВРАГ = стиль != "нет"
    if SIM.АГЕНТНЫЙ_ВРАГ:
        SIM.СТИЛЬ_ВРАГА, SIM.ВРАГ_СЛЕДУЕТ, SIM.ОБОРОНА_ДОМА = стиль, 6.0, 3
    if вид == "сеть":
        PS.ЭКО_ЯРУСА.clear(); PS.ЭКО_ЯРУСА.update(ЭКО)
        PS.включить_удар_по_армии()
        п = PS.Стратег(np.load(арг), 0.0, np.random.default_rng(seed))
    elif вид == "поиск":
        п = ПС.Стратегия(арг)
    elif вид == "присутствие":
        п = Присутствие(арг)
    else:
        п = T1.Ярус1()
    сим, и = SIM.партия(d, п, seed=seed)
    м = ПС.мера(сим, и)
    з_ = сим.з
    мой, его = (з_.my_cx, з_.my_cy), з_.en_base
    места = {"у него": 0.0, "в поле": 0.0, "у нас": 0.0}
    for t, cx, cy, _, _, _, пн, пе, _ in сим.журнал_боя:
        if t > 900:
            continue
        if math.hypot(cx - его[0], cy - его[1]) <= 3:
            места["у него"] += пе
        elif math.hypot(cx - мой[0], cy - мой[1]) <= 5:
            места["у нас"] += пе
        else:
            места["в поле"] += пе
    м.update({"его_" + k: v for k, v in места.items()}, победа=сим.исход == "победа")
    return м


def main():
    if len(sys.argv) > 1:
        sys.argv_стили = tuple(sys.argv[1].split(","))
    sys.argv = [sys.argv[0], "--корпус", os.path.join(К, "корпус_27_09.txt")]
    import train as TR
    _, тест = TR.разбить(TR.партии([]))
    задания_партий = [(d, 100000 + 100 * j + i) for j in range(3) for i, d in enumerate(тест)]
    with Pool(12) as пул:
        стили = sys.argv_стили if hasattr(sys, "argv_стили") else ("родной", "горячий", "осторожный")
        for стиль in стили:
            поиск = json.load(open(os.path.join(К, "поиск", f"агент_{стиль}.json" if стиль != "нет" else "s1.json"),
                                   encoding="utf-8"))["итог"]
            кандидаты = [("сеть s1", "сеть", os.path.join(К, "ночь01", "армия_s1.npy")),
                         ("сеть s2", "сеть", os.path.join(К, "ночь01", "армия_s2.npy")),
                         ("сеть s3", "сеть", os.path.join(К, "ночь01", "армия_s3.npy")),
                         ("поиск (расписание)", "поиск", поиск),
                         ("присутствие → крестьяне", "присутствие", "peasants_free"),
                         ("присутствие → армия", "присутствие", "army"),
                         ("ярус 1 без войны", "ярус1", None)]
            print(f"\n=== противник: {стиль} (25 партий × 3)", flush=True)
            print(f"  {'кандидат':24} {'награда':>8} {'уничт':>6} {'побед':>5} {'его 15:00':>9} {'размен':>6} {'наши пот':>8} | его потери: у него / в поле / у нас")
            for имя, вид, арг in кандидаты:
                р = пул.map(_партия, [(вид, арг, стиль, d, s) for d, s in задания_партий])
                уб, пот = sum(x["убито"] for x in р), sum(x["потери"] for x in р)
                print(f"  {имя:24} {St.mean(x['награда'] for x in р):+8.2f} {sum(x['уничтожена'] for x in р):6d} {sum(x['победа'] for x in р):5d}"
                      f" {St.median(x['его15'] for x in р):9.0f} {уб / max(пот, 1):6.2f} {St.median(x['потери'] for x in р):8.0f} |"
                      f" {sum(x['его_у него'] for x in р) / len(р):5.0f} / {sum(x['его_в поле'] for x in р) / len(р):5.0f} / {sum(x['его_у нас'] for x in р) / len(р):5.0f}", flush=True)


if __name__ == "__main__":
    main()
