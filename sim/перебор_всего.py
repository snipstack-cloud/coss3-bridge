# -*- coding: utf-8 -*-
"""ПОЛНЫЙ ПЕРЕКРЁСТ параметров: все значения на все, под НОВУЮ цель партии.

Просьба игрока 27.09: «запустим симуляцию исходов при параметрах, в которые
подставим значение, и перемножим все на все». Здесь это и делается, но с двумя
оговорками, без которых перебор считал бы не то.

**ЦЕЛЬ ПАРТИИ СМЕНИЛАСЬ** (§13э, игрок 27.09): победа — убить ВСЮ армию
противника, а при неясном исходе за 15 минут считают очки экономики (§13ю).
Поэтому главная мера здесь — его армия к концу (чем меньше, тем лучше), вторая —
наши потери (каждый наш погибший даёт ему двойные очки), третья — оценка очков.
Убитые крестьяне остаются справкой, а не целью.

**ДЫРА У ЕГО БАЗЫ** (§13з, 13к): удар по базе в симуляторе щедрее жизни, и любой
перебор выберет его первым. Поэтому цель удара «база» в сетку НЕ ВХОДИТ, а
варианты помечаются местом боя, чтобы победителя можно было отличить от
эксплойта.

    python3 sim/перебор_всего.py <корни> [--партий 6] [--процессов 10] [--быстро]
"""
import itertools
import os
import statistics as S
import sys
from multiprocessing import Pool

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import combat            # noqa: E402
import debut as D        # noqa: E402
import sim as SIM        # noqa: E402
import train as TR       # noqa: E402
from tier1 import в_словарь  # noqa: E402

ЗАЩИТА = [f"bar.pikeman.2.{i}" for i in range(1, 7)]
АТАКА = [f"bar.pikeman.1.{i}" for i in range(1, 7)]
ОЧКИ = {"centers": 1000, "ba17": 500, "academies": 500, "houses": 100,
        "peasants": 20, "mil_inf": 10, "mil_shooters": 20, "mil_cav": 50}


def стройки(казарм, шахт_золота, дома, угля=0):
    из = [("smith", "smiths", 1, {"wood": 100, "stone": 30}),
          ("minegold", "mines_gold", 1, {"wood": 100, "stone": 100}),
          ("ba17", "ba17", 1, {"wood": 100, "stone": 100, "gold": 500}),
          ("mineiron", "mines_iron", 1, {"wood": 100, "stone": 100})]
    из += [("minegold", "mines_gold", i + 2, {"wood": 100, "stone": 100}) for i in range(шахт_золота - 1)]
    из += [("ba17", "ba17", i + 2, {"wood": 100, "stone": 100, "gold": 500 * 5 ** (i + 1)}) for i in range(казарм - 1)]
    из += [("minecoal", "mines_coal", i + 1, {"wood": 100, "stone": 100}) for i in range(угля)]
    из += [("store", "my_stores", 1, {"wood": 50, "stone": 20})]
    if дома:
        из += [("house", "houses", i + 1, {"wood": 100, "stone": 100}) for i in range(14)]
    return из


def сыграть(каталог, seed, п, до=1200.0):
    з = SIM.Запись(каталог)
    сим = SIM.Симулятор(з, seed)
    деб = D.Дебют(20)
    список = стройки(п["казарм"], п["шахт"], п["дома"], п["угля"])
    ряд = {"защита": ЗАЩИТА, "атака": АТАКА, "нет": []}[п["апгрейды"]]
    отведены = None
    места = {"у него": 0, "иное": 0}
    while сим.t < до and not сим.исход:
        s = сим.состояние()
        из = []
        if not деб.готов(s):
            из += [в_словарь(c) for c in деб.такт(s, int(сим.t))[0]]
        else:
            if float(s.get("centers") or 0) > 0:
                из.append({"cmd": "TRAIN", "role": "peasant", "total": -1})
            for роль, поле, скл, цена in список:
                if float(s.get(поле) or 0) >= скл:
                    continue
                нет = [р for р, надо in цена.items() if float(s.get(р) or 0) < надо]
                if нет:
                    из += [{"cmd": "BALANCE", "role": р, "total": 10} for р in нет]
                elif float(s.get("building_now") or 0) == 0:
                    из.append({"cmd": "BUILD", "role": роль, "total": скл})
                break
            кр = float(s.get("peasants") or 0)
            в_шахтах = 0.0
            for рес, поле in (("gold", "mines_gold"), ("iron", "mines_iron")):
                ш = float(s.get(поле) or 0)
                if ш > 0:
                    в_шахтах += 5 * ш
                    из.append({"cmd": "BALANCE", "role": рес, "total": int(5 * ш)})
            назем = max(кр - в_шахтах, 0.0)
            еда = int(round(назем * п["еда"]))
            дер = int(round((назем - еда) * 2 / 3))
            кам = int(назем) - еда - дер
            for рес, n in (("food", еда), ("wood", дер), ("stone", кам)):
                if n > 0:
                    из.append({"cmd": "BALANCE", "role": рес, "total": n})
            if float(s.get("ba17") or 0) > 0:
                пик = float(s.get("mil_inf") or 0)
                стр = float(s.get("mil_shooters") or 0)
                есть = стр / max(пик + стр, 1e-9)
                из.append({"cmd": "TRAIN", "role": "musk17" if (п["стрелки"] > 0 and есть < п["стрелки"]) else "infantry17", "total": -1})
            for u in ряд:
                if u not in сим.апгрейды:
                    из.append({"cmd": "UPGRADE", "upg": u})
                    break
            # РЕЖИМ «ДОМА» (27.09): волн не посылаем вовсе. Домашняя группа стоит у
            # ратуши и бьёт то, что пришло к ней само — в симуляторе это работает,
            # потому что бой считается по клеткам и группа 0 в них участвует.
            # ЗАЧЕМ: у своей базы записи дают размен 2,7 (194 против 36) против 0,24
            # у его базы, а все наборы перекрёста до сих пор атаковали.
            if п["режим"] == "дома":
                pass
            elif float(s.get("my_freewar") or 0) > 0 and сим.t >= п["удар_с"]:
                цель = "wave" if float(s.get("mil_away") or 0) > 0 else п["цель"]
                из.append({"cmd": "ATTACK", "count": "all", "target": цель})
        сим.команды(из)
        сим.такт()
        for г in сим.группы[1:]:
            if г.get("в_контакте"):
                d = max(abs(г["x"] - з.en_base[0]), abs(г["y"] - з.en_base[1]))
                места["у него" if d <= 3 else "иное"] += 1
    s = сим.состояние()
    очки = sum(в * float(s.get(k) or 0) for k, в in ОЧКИ.items()) + 2 * 10 * сим.убито_бойцов + 2 * 20 * сим.убито_крестьян
    вс = max(sum(места.values()), 1)
    return dict(его_армия=float(s.get("p1_army_eff") or s.get("p1_army") or 0), потери=сим.my_mil_lost,
                его_потери=сим.убито_бойцов, убито=сим.убито_крестьян, очки=очки,
                у_базы=места["у него"] / вс, армия=float(s.get("mil_inf") or 0) + float(s.get("mil_shooters") or 0),
                выстрелов=getattr(сим, "выстрелов", 0.0), без_пороха=getattr(сим, "без_пороха", 0))


def один(задача):
    п, партии = задача
    из = [сыграть(d, i, п) for i, d in enumerate(партии)]
    р = sum(x["его_потери"] for x in из) / max(sum(x["потери"] for x in из), 1)
    return п, dict(его_армия=S.median(x["его_армия"] for x in из), потери=S.median(x["потери"] for x in из),
                   его_потери=S.median(x["его_потери"] for x in из), убито=S.median(x["убито"] for x in из),
                   очки=S.median(x["очки"] for x in из), размен=р,
                   у_базы=S.median(x["у_базы"] for x in из), армия=S.median(x["армия"] for x in из),
                   выстрелов=S.median(x["выстрелов"] for x in из),
                   без_пороха=S.median(x["без_пороха"] for x in из))


def main():
    корни = [a for a in sys.argv[1:] if not a.startswith("--")]
    n = int(sys.argv[sys.argv.index("--партий") + 1]) if "--партий" in sys.argv else 6
    проц = int(sys.argv[sys.argv.index("--процессов") + 1]) if "--процессов" in sys.argv else 10
    быстро = "--быстро" in sys.argv
    # КАРТА: записи сыграны на 320 (клетка 20 ед), турнир идёт на 256 (клетка 16).
    # Клетки сетки остаются те же, меняется их РАЗМЕР в единицах: марш в клетках
    # становится быстрее. Это приближение, и оно названо: расстановка врага берётся с
    # карты записей, а время пути пересчитывается под турнирную.
    if "--карта" in sys.argv:
        ш = float(sys.argv[sys.argv.index("--карта") + 1])
        SIM.ЕДИНИЦ_В_КЛЕТКЕ = ш / SIM.СЕТКА
        SIM.СКОРОСТЬ = 1.15 / SIM.ЕДИНИЦ_В_КЛЕТКЕ
        print(f"карта {ш:.0f} единиц: клетка {SIM.ЕДИНИЦ_В_КЛЕТКЕ:.1f} ед, "
              f"марш {SIM.СКОРОСТЬ * 60:.2f} клеток в минуту")
    все = TR.партии(корни)
    _, тест = TR.разбить(все)
    партии = тест[:n]
    сетка = {
        "еда": [0.35, 0.5, 0.65, 0.8],
        "стрелки": [0.0, 0.3, 0.5],
        "казарм": [1, 2],
        "шахт": [1, 2],
        "апгрейды": ["защита", "атака", "нет"],
        "угля": [0, 1, 2],
        "удар_с": [300, 450, 600, 750],
        "цель": ["peasants", "army"],
        "дома": [False, True],
    }
    if быстро:
        сетка = {k: v[:2] for k, v in сетка.items()}
    имена = list(сетка)
    наборы = []
    for зн in itertools.product(*(сетка[k] for k in имена)):
        п = dict(zip(имена, зн))
        наборы.append(dict(п, режим="атака"))
        # оборона: удар_с и цель ей не нужны, поэтому берём по одному значению
        if п["удар_с"] == сетка["удар_с"][0] and п["цель"] == сетка["цель"][0]:
            наборы.append(dict(п, режим="дома", удар_с=0, цель="—"))
    print(f"партий на вариант {len(партии)}, вариантов {len(наборы)}, процессов {проц};"
          f" всего партий {len(наборы) * len(партии)}", flush=True)
    из = []
    with Pool(проц) as pool:
        for i, (п, м) in enumerate(pool.imap_unordered(один, [(п, партии) for п in наборы], chunksize=4), 1):
            из.append((п, м))
            if i % 50 == 0:
                print(f"  посчитано {i}/{len(наборы)}", flush=True)
    # ПОРЯДОК ПО НОВОЙ ЦЕЛИ: сперва его армия к концу, потом наши потери, потом очки
    из.sort(key=lambda x: (x[1]["его_армия"], x[1]["потери"], -x[1]["очки"]))
    print("\nЛУЧШИЕ ПО НОВОЙ ЦЕЛИ (его армия к концу, потом наши потери):")
    print("%-66s %9s %7s %7s %7s %7s %6s" % ("набор", "его армия", "потери", "его", "размен", "очки", "у базы"))
    for п, м in из[:15]:
        имя = ("%s еда %.0f%% стр %.0f%% каз %d зол %d апг %s угля %d удар %d цель %s дома %s"
               % (п["режим"].upper(), п["еда"] * 100, п["стрелки"] * 100, п["казарм"], п["шахт"],
                  п["апгрейды"], п["угля"], п["удар_с"], п["цель"], "да" if п["дома"] else "нет"))
        print("%-66s %9.0f %7.0f %7.0f %7.2f %7.0f %5.0f%%" % (
            имя, м["его_армия"], м["потери"], м["его_потери"], м["размен"], м["очки"], 100 * м["у_базы"]))
    print("\nЛУЧШИЕ ПО ОЧКАМ (ничья по правилам турнира):")
    для_очков = sorted(из, key=lambda x: -x[1]["очки"])[:8]
    for п, м in для_очков:
        print("  очки %6.0f, его армия %4.0f, потери %4.0f, выстрелов %5.0f: %s еда %.0f%% стр %.0f%% каз %d апг %s угля %d удар %d цель %s дома %s"
              % (м["очки"], м["его_армия"], м["потери"], м["выстрелов"], п["режим"], п["еда"] * 100, п["стрелки"] * 100,
                 п["казарм"], п["апгрейды"], п["угля"], п["удар_с"], п["цель"], "да" if п["дома"] else "нет"))


if __name__ == "__main__":
    main()
