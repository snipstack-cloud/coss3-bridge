def награда_лестница(сим, история) -> float:
    """Курс: число взятых ступеней + половина прогресса к ближайшей невзятой − 0,002 за
    потерянного бойца. Ступени и прогресс — `goals.курс`, одни и те же для записи и
    симулятора; текущая цель — первая невзятая (`ПЛАН.md`, «Лестница целей»)."""
    if МУШКЕТЁРЫ:
        import goals_musk as GM
        return GM.награда(сим, история)
    if ФРОНТ:
        import goals_front as GF
        return GF.награда(сим, история)
    if ЭТАП:
        import goals_этапы as GЭ
        return GЭ.награда(сим, история, ЭТАП)
    if ОЧКИ:
        import goals_score as GS
        return GS.награда(сим, история, GS.ГОРИЗОНТ_ТУРНИРА)
    взято, п = G.курс(история, сим.з.en_base)
    # ПРЕДОХРАНИТЕЛЬ (27.09, §13л): ступени выше ПОТОЛОК_СТУПЕНИ в награду не идут,
    # пока открыта дыра у его базы — полный словарь выучил «всей армией на его
    # базу» и брал ступени 8-9 там, где живая запись такого удара проиграла 66 за 7.
    # Снять, когда §13л закрыт записями с точными клетками.
    взято = {i for i in взято if i <= ПОТОЛОК_СТУПЕНИ}
    ближайшая = next((i for i in range(1, ПОТОЛОК_СТУПЕНИ + 1) if i not in взято), None)
    r = float(len(взято))
    if ближайшая is not None:
        r += 0.5 * п.get(ближайшая, 0.0)
    # ПОПРАВКА ОТ WINDOWS 25.09 (разборы/ПОЧЕМУ_НЕ_БЬЁМ.md): низкие потери сами по
    # себе не успех — стратег с платой за потери учился не сближаться. Потери
    # считаются только в связке с тем, дошли ли до крестьян: доля тактов после
    # 300 с, когда наши стоят в клетках с его крестьянами. По 52 записям убийства
    # происходят при mil_far 201–232 (медиана 214), поэтому мера — не порог
    # расстояния (280 достижимо не на всякой карте), а само присутствие у крестьян.
    доля = G.доля_у_крестьян(история)
    r += 1.5 * min(доля, 0.4)
    if доля >= 0.05:
        r -= 0.002 * сим.my_mil_lost
    # ТЕМП УБИЙСТВ (27.09, §15д): цель — не «убить сколько-то», а держать темп ВЫШЕ его
    # найма. Он прибавляет крестьян 5,8 в минуту [замер], значит ниже шести его число не
    # падает и ступень 10 недостижима по построению. Плотный сигнал: доля пути к шести
    # убийствам в минуту. Прежняя награда за счёт убитых этого различить не могла —
    # 70 убитых за партию это 4,7 в минуту, и его крестьян к концу оставалось 110.
    минут = max(сим.t / 60.0, 1.0)
    темп = сим.убито_крестьян / минут
    # ВЕС 3,0, А НЕ 0,5 (перезапуск 27.09 после 28 поколений). При весе 0,5 темп давал
    # 0,04 награды против 4,0 за ступени 1-4, и четыре зерна из четырёх выучили осторожную
    # игру: потери 24-29 против 172 у записи, размен 0,5-0,6, но убито 8-11 и темп 0,4 в
    # минуту при нужных шести. Ступени 1-4 берутся хозяйством и доставкой, драться для них
    # не надо, поэтому сеть на них и остановилась. Теперь полный темп стоит трёх ступеней.
    r += ВЕС_ТЕМПА * min(темп / НУЖНЫЙ_ТЕМП, 1.0)
    # РАЗМЕН: доля пути к 0,5 по НАШИМ убийствам его бойцов. Считается только при
    # потерях — иначе политика, которая не воюет вовсе, получала бы полный вес.
    if сим.my_mil_lost > 0:
        размен = сим.убито_бойцов / сим.my_mil_lost
        r += ВЕС_РАЗМЕНА * min(размен / НУЖНЫЙ_РАЗМЕН, 1.0)
    return r


def награда(сим) -> float:
    """Третий прогон (25.09) научил сеть НЕ ВОЕВАТЬ: плата 0,002 за живого бойца
    сделала армию в 201 дома выгоднее любого удара (0,747 против 0,675 у команд
    записи при нуле убитых). Поэтому за живых не платим вовсе; платим за убитых,
    за победу и за стояние у его базы после 7:00 — то, из чего состоит цель.
    Экономические слагаемые оставлены крошечными, только чтобы дебют не рухнул."""
    r = 0.03 * сим.убито_крестьян + 0.005 * сим.убито_бойцов - 0.003 * сим.my_mil_lost
    r += 0.1 * min(1.0, getattr(сим, "тактов_у_его_базы", 0) / 60.0)
    r += 0.01 * min(сим.эк.здания.get("ba17", 0), 3) + 0.01 * min(сим.эк.здания.get("mines_gold", 0), 3)
    if сим.исход == "победа":
        r += 1.0
    elif сим.исход == "поражение":
        r -= 0.5
    return r


