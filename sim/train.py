def разбить(все, seed=7):
    rng = random.Random(seed)
    перем = list(все)
    rng.shuffle(перем)
    n_test = max(1, int(len(перем) * ДОЛЯ_ТЕСТА))
    return перем[n_test:], перем[:n_test]


