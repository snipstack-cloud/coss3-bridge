def награда_боя(сим, история) -> float:
    """Только БОЕВЫЕ слагаемые: присутствие, темп убийств, размен, плата за потери.

    Этап 1 замысла игрока (28.09): «сперва научить воевать». Без этого награда по
    очкам научила НЕ воевать — убито 0, потери 0, награда +3,05 против −2,90 у
    живой модели, которая дралась. Числа и оговорки те же, что в лестнице:
    плата за потери берётся ТОЛЬКО при присутствии (иначе сеть учится не
    сближаться, замер 25.09), темп нужен 6 убийств в минуту (его найм крестьян
    5,8), размен целится в 0,5 (у записи по корпусу 0,42).
    """
    r = 0.0
    доля = G.доля_у_крестьян(история)
    r += 1.5 * min(доля, 0.4)
    if доля >= 0.05:
        r -= 0.002 * сим.my_mil_lost
    минут = max(сим.t / 60.0, 1.0)
    r += ВЕС_ТЕМПА * min((сим.убито_крестьян / минут) / НУЖНЫЙ_ТЕМП, 1.0)
    if сим.my_mil_lost > 0:
        r += ВЕС_РАЗМЕНА * min((сим.убито_бойцов / сим.my_mil_lost) / НУЖНЫЙ_РАЗМЕН, 1.0)
    return r


