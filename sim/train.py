def проверить(theta, отл, k=6):
    """Средние веса на ОТЛОЖЕННЫХ партиях, без разведки (температура 0).

    Зачем: строка «лучшая/средняя» в логе считается по k случайным ОБУЧАЮЩИМ
    партиям, и она шумит сильнее, чем движется политика — у одного зерна 4,79 на
    81-м поколении и 3,13 на 105-м. Прогон 27.09 это подтвердил дорого: веса
    120-го поколения на отложенных партиях ХУЖЕ весов 81-го (4,60-4,97 против
    5,26-5,87, убито 33 против 52), а сохранялись только последние — лучшие
    пропали. Теперь мерим по фиксированным партиям и храним лучшие.
    """
    из = []
    for i, d in enumerate(отл[:k]):
        r, _, _ = сыграть(theta, d, i, температура=0.0)
        из.append(r)
    return float(np.mean(из)) if из else -1e9


def обучить(обуч, gens, pop, k, выход, seed=1, старт=None, отл=None):
    """`старт` — веса предыдущего урока: следующий урок продолжает с достигнутого
    (учебная программа, 27.09). Без него эволюция каждый раз начинает с нуля, и
    связка из нескольких команд (академия -> офицер -> барабанщик -> строй) за
    60 поколений не складывается."""
    rng = np.random.default_rng(seed)
    # Масштаб весов важен: при N(0, 0,1) логиты около нуля, выбор почти равномерный,
    # и при общих семенах все 64 кандидата ходили одинаково — лучшая награда равнялась
    # средней до третьего знака 100 поколений подряд. Веса N(0, 0,5) дают логиты
    # порядка единицы, и шум σ 0,3 меняет решения.
    theta = (np.load(старт).astype(np.float32) if старт else rng.normal(0, 0.5, n_весов()).astype(np.float32))
    sigma = 0.3 if not старт else 0.2
    лучший = (-1e9, theta.copy())   # (оценка на ОТЛОЖЕННЫХ, веса)
    t0 = time.time()
    for g in range(gens):
        выбор = [обуч[rng.integers(len(обуч))] for _ in range(k)]
        семена = [int(rng.integers(1 << 30)) for _ in range(k)]
        шумы = rng.normal(0, 1, (pop, n_весов())).astype(np.float32)
        очки = np.zeros(pop)
        побед = 0
        for j in range(pop):
            кандидат = theta + sigma * шумы[j]
            s = 0.0
            for d, seed in zip(выбор, семена):
                r, сим, _ = сыграть(кандидат, d, seed + j, температура=0.5)   # разведка при обучении; семя своё у кандидата
                s += r
                побед += сим.исход == "победа"
            очки[j] = s / k
        порядок = np.argsort(-очки)
        элита = порядок[:max(4, pop // 4)]
        theta = theta + sigma * шумы[элита].mean(axis=0)
        sigma = max(0.1, sigma * 0.99)
        # ПРЕЖДЕ здесь `лучший` обновлялся по очкам ОБУЧАЮЩИХ партий и никуда не
        # шёл — мёртвый код. Теперь имя занято лучшей точкой по ОТЛОЖЕННЫМ, и две
        # шкалы в одной переменной смешивать нельзя: обучающие очки выше (5-7
        # против 4-5) и заблокировали бы всякую запись.
        # ПОСЛЕДНИЕ веса пишем всегда — по ним видно, чем кончилось; ЛУЧШИЕ по
        # отложенным партиям пишем в `выход`, потому что именно их потом несут в
        # игру. Без этого обучение теряет свою же лучшую точку (27.09).
        np.save(выход.replace(".npy", "") + "_последний.npy", theta)
        отл_оценка = None
        if отл and ((g + 1) % ПРОВЕРКА_КАЖДЫЕ == 0 or g == gens - 1 or g == 0):
            отл_оценка = проверить(theta, отл)
            if отл_оценка > лучший[0]:
                лучший = (отл_оценка, theta.copy())
                np.save(выход, theta)
        elif not отл:
            np.save(выход, theta)
        print(f"поколение {g + 1:3d}/{gens}: лучшая {очки[порядок[0]]:+.3f}, средняя {очки.mean():+.3f}, "
              f"побед {побед}/{pop * k}, σ {sigma:.3f}, {time.time() - t0:.0f} с"
              + (f", ОТЛОЖЕННЫЕ {отл_оценка:+.3f}"
                 + (" — лучшее, сохранено" if отл_оценка == лучший[0] else
                    f" (лучшее {лучший[0]:+.3f})") if отл_оценка is not None else ""),
              flush=True)
    if отл:
        print(f"итог: в {выход} лежат ЛУЧШИЕ веса по отложенным партиям "
              f"({лучший[0]:+.3f}), последние — в {выход.replace('.npy','')}_последний.npy",
              flush=True)
        return лучший[1]
    return theta


