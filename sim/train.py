def базы(каталоги):
    пустая = []
    запись = []
    for i, d in enumerate(каталоги):
        сим, ист = SIM.партия(d, lambda st: [], seed=i)
        пустая.append((оценка_партии(сим, ист), сим.исход, сим.убито_крестьян, сим.my_mil_lost, сим.убито_бойцов, sum(сим.эк.армия.values())))
        # команды записи в замкнутом цикле — с историей для лестницы
        з = SIM.Запись(d)
        такты = iter(з.такты)
        ближ = next(такты, None)
        сим2 = SIM.Симулятор(з, i)
        ист2 = []
        while сим2.t < SIM.ч(з.снапы[-1]["gametime"]) and not сим2.исход:
            while ближ is not None and ближ[0] <= сим2.t:
                сим2.команды(R.команды_такта(ближ[2]))
                ближ = next(такты, None)
            сим2.такт()
            ист2.append(сим2.состояние())
        запись.append((оценка_партии(сим2, ист2), сим2.исход, сим2.убито_крестьян, сим2.my_mil_lost, сим2.убито_бойцов, sum(сим2.эк.армия.values())))
    return пустая, запись


