ЗАЩИТА = [f"bar.pikeman.2.{i}" for i in range(1, 7)]
АТАКА = [f"bar.pikeman.1.{i}" for i in range(1, 7)]
МЕСТ_В_ШАХТЕ = 5  # [код] _player_OrderUnitsToGoInside, проверено sim.команда


def стройки(зол, жел, уг, каз, порог=0.0):
    """Порядок закладок. Кузница первой: без неё нет казармы [код country.script].

    КАЗАРМА СРАЗУ ПОСЛЕ ПЕРВОЙ ЗОЛОТОЙ ШАХТЫ, остальные шахты после неё. Первая
    редакция этого замера ставила все шахты вперёд, и шесть шахт отодвигали
    казарму с 240-й секунды на 425-ю: армия падала с 48 до 12. Это и есть
    механизм живой серии `mines2` («больше шахт — хуже»): наказывались не шахты,
    а отложенная казарма.

    Цена казармы растёт впятеро за каждую следующую [код, costpercent 500]:
    500, 2 500, 12 500 золота. Отсюда смысл второй и третьей золотой шахты —
    без них это золото не набрать.
    """
    из = [("smith", "smiths", 1, {"wood": 100, "stone": 30}, 0),
          ("minegold", "mines_gold", 1, {"wood": 100, "stone": 100}, 0),
          ("ba17", "ba17", 1, {"wood": 100, "stone": 100, "gold": 500}, 0),
          ("mineiron", "mines_iron", 1, {"wood": 100, "stone": 100}, 0)]
    # ПОРОГ ЕДЫ У ПОЗДНИХ ШАХТ: каждый шахтёр снят с поля, и вторая золотая
    # шахта, заложенная рано, держит еду у порога 500 всю партию — найм
    # крестьян стопорится (57 человек против 84), и экономика не раскручивается.
    # Поэтому шахты сверх первой ждут, пока еды не станет вдвое больше порога.
    из += [("minegold", "mines_gold", i + 2, {"wood": 100, "stone": 100}, порог) for i in range(зол - 1)]
    из += [("ba17", "ba17", i + 2, {"wood": 100, "stone": 100, "gold": 500 * 5 ** (i + 1)}, 0)
           for i in range(каз - 1)]
    из += [("mineiron", "mines_iron", i + 2, {"wood": 100, "stone": 100}, порог) for i in range(жел - 1)]
    из += [("store", "my_stores", 1, {"wood": 50, "stone": 20}, 0)]
    из += [("minecoal", "mines_coal", i + 1, {"wood": 100, "stone": 100}, порог) for i in range(уг)]
    return из


def сыграть(каталог, seed, план, ряд=ЗАЩИТА, до=1200.0):
    """Партия одним планом. СОСТАВ АРМИИ — параметр (добавлен 27.09 после того, как
    живая серия food_share2 опровергла вывод про еду: в прежнем переборе армия была
    чисто пиковой, и переброска людей с золота и железа на еду ничего не стоила).

    Цены [код]: пикинёр 25 еды + 3 золота + 20 ЖЕЛЕЗА, мушкетёр 50 ЕДЫ + 8 золота
    + 4 железа, драгун 100 еды + 70 золота. То есть стрелок дорог едой и золотом,
    а пикинёр железом — и апгрейды защиты пикинёра (тоже еда) отнимают еду именно
    у стрелков. Это и есть механизм, которым проиграла food_share2.
    """
    зол, жел, уг, каз, доля_еды, порог, дома, доля_стрелков, апг = план
    з = SIM.Запись(каталог)
    сим = SIM.Симулятор(з, seed)
    деб = D.Дебют(20)
    список = стройки(зол, жел, уг, каз, порог)
    пора_шахт = None
    while сим.t < до and not сим.исход:
        s = сим.состояние()
        из = []
        if not деб.готов(s):
            cmds, _ = деб.такт(s, int(сим.t))
            из += [в_словарь(c) for c in cmds]
        else:
            if float(s.get("centers") or 0) > 0:
                из.append({"cmd": "TRAIN", "role": "peasant", "total": -1})
            # следующая незаложенная стройка: ждём её материалы, потом кладём
            for роль, поле, сколько, цена, порог_еды in список:
                if float(s.get(поле) or 0) >= сколько:
                    continue
                if порог_еды and float(s.get("food") or 0) < порог_еды:
                    break
                нет = [р for р, надо in цена.items() if float(s.get(р) or 0) < надо]
                if нет:
                    из += [{"cmd": "BALANCE", "role": р, "total": 10} for р in нет]
                elif float(s.get("building_now") or 0) == 0:
                    из.append({"cmd": "BUILD", "role": роль, "total": сколько})
                break
            # ЛЮДИ. Шахтёры — по числу ГОТОВЫХ шахт: пять на шахту, больше не
            # войдёт. Остальные делятся между едой, деревом и камнем.
            кр = float(s.get("peasants") or 0)
            в_шахтах = 0.0
            for рес, поле in (("gold", "mines_gold"), ("iron", "mines_iron"), ("coal", "mines_coal")):
                шахт = float(s.get(поле) or 0)
                if шахт > 0:
                    n = МЕСТ_В_ШАХТЕ * шахт
                    в_шахтах += n
                    из.append({"cmd": "BALANCE", "role": рес, "total": int(n)})
            наземных = max(кр - в_шахтах, 0.0)
            if пора_шахт is None and в_шахтах >= МЕСТ_В_ШАХТЕ * (зол + жел + уг):
                пора_шахт = сим.t
            еда = int(round(наземных * доля_еды))
            дерево = int(round((наземных - еда) * 2 / 3))
            камень = int(наземных) - еда - дерево
            for рес, n in (("food", еда), ("wood", дерево), ("stone", камень)):
                if n > 0:
                    из.append({"cmd": "BALANCE", "role": рес, "total": n})
            # ДОМА: предел населения [код] = 100 за ратушу + 150 за казарму +
            # 25 за дом, и производство в здании стоит, пока предел занят. Дом
            # стоит 100 дерева + 100 камня и строится 31 с.
            вместимость, занято = сим.эк.предел_населения()
            if дома and вместимость - занято < 30 and float(s.get("building_now") or 0) == 0:
                цена = {"wood": 100, "stone": 100}
                нет = [р for р, надо in цена.items() if float(s.get(р) or 0) < надо]
                if нет:
                    из += [{"cmd": "BALANCE", "role": р, "total": 10} for р in нет]
                else:
                    из.append({"cmd": "BUILD", "role": "house",
                               "total": int(float(s.get("houses") or 0)) + 1})
            # СОСТАВ: заказываем тот вид, которого не хватает до целевой доли.
            # Оба заказа разом делят темп казармы, поэтому отдаём по одному.
            if float(s.get("ba17") or 0) > 0:
                пик = float(s.get("mil_inf") or 0)
                стр = float(s.get("mil_shooters") or 0)
                есть = стр / max(пик + стр, 1e-9)
                вид = "musk17" if (доля_стрелков > 0 and есть < доля_стрелков) else "infantry17"
                из.append({"cmd": "TRAIN", "role": вид, "total": -1})
            if апг:
                for u in ряд:
                    if u not in сим.апгрейды:
                        из.append({"cmd": "UPGRADE", "upg": u})
                        break
            if float(s.get("my_freewar") or 0) > 0 and сим.t >= 520:
                из.append({"cmd": "ATTACK", "count": "all",
                           "target": "wave" if float(s.get("mil_away") or 0) > 0 else "peasants"})
        сим.команды(из)
        сим.такт()
    s = сим.состояние()
    return dict(убито=сим.убито_крестьян, потери=сим.my_mil_lost, его=сим.убито_бойцов,
                армия=float(s.get("mil_inf") or 0), еда=сим.эк.res["food"],
                золото=сим.эк.res["gold"], шахты_с=пора_шахт if пора_шахт else 0.0,
                казарм=float(s.get("ba17") or 0), домов=float(s.get("houses") or 0),
                стрелков=float(s.get("mil_shooters") or 0),
                доля_стр=float(s.get("mil_shooters") or 0) / max(float(s.get("mil_inf") or 0) + float(s.get("mil_shooters") or 0), 1e-9),
                предел=сим.эк.предел_населения()[0], население=сим.эк.предел_населения()[1],
                ступеней=len([u for u in сим.апгрейды if u.startswith(ряд[0][:-2])]))


def main():
    корни = [a for a in sys.argv[1:] if not a.startswith("--")]
    n_партий = int(sys.argv[sys.argv.index("--партий") + 1]) if "--партий" in sys.argv else 12
    ряд = АТАКА if "--ряд" in sys.argv and sys.argv[sys.argv.index("--ряд") + 1] == "атака" else ЗАЩИТА
    все = TR.партии(корни)
    _, тест = TR.разбить(все)
    партии = тест[:n_партий]
    сетка = []
    # ВТОРОЙ ЗАХОД (27.09): первый показал, что при пороге 1500 на поздние шахты
    # их число не влияет (убито 30,1 / 30,2 / 30,0 при одной, двух, трёх), а
    # рычагов два — доля еды (65 % против 50 %: убито 30,1 против 12,5) и вторая
    # казарма (армия 214 против 127). Уточняем оба и пробуем угольную шахту:
    # 11 апгрейдов академии стоят угля, aca.15 даёт стрелкам +25 % урона.
    # ЧЕТВЁРТЫЙ ЗАХОД (27.09, после живой серии): состав армии и апгрейды —
    # ПАРАМЕТРЫ. Живая игра сказала, что доля еды сама по себе ничего не решает:
    # 76 % на еде дали 0 убитых при 117 у базы, потому что стрелков стало ноль.
    for доля_еды in (0.35, 0.5, 0.65, 0.8):
        for доля_стрелков in (0.0, 0.3, 0.5):
            for апг in (True, False):
                сетка.append((1, 1, 0, 2, доля_еды, 1500.0, False, доля_стрелков, апг))
    print(f"партий {len(партии)}, вариантов {len(сетка)}; ряд {'АТАКА' if ряд is АТАКА else 'ЗАЩИТА'}")
    print("%-24s %5s %6s %6s %6s %6s %6s %6s" % (
        "еда/стрелки/апгр", "стрелк", "долястр", "армия", "убито", "потери", "размен", "ступ"))
    строки = []
    for план in сетка:
        из = [сыграть(d, i, план, ряд) for i, d in enumerate(партии)]
        р = sum(x["его"] for x in из) / max(sum(x["потери"] for x in из), 1)
        уб = S.median(x["убито"] for x in из)
        строки.append((уб, план, из, р))
        print("%-24s %5.0f %6.0f %6.0f %6.1f %6.0f %6.2f %6.0f" % (
            "%.0f%%/%.0f%%/%s" % (план[4] * 100, план[7] * 100, "да" if план[8] else "нет"),
            S.median(x["стрелков"] for x in из), 100 * S.median(x["доля_стр"] for x in из),
            S.median(x["армия"] for x in из), уб, S.median(x["потери"] for x in из),
            р, S.median(x["ступеней"] for x in из)), flush=True)
    строки.sort(key=lambda x: -x[0])
    print("\nЛУЧШИЕ ПО УБИТЫМ:")
    for уб, план, из, р in строки[:3]:
        print("  убито %.1f, размен %.2f: еда %.0f%%, стрелков %.0f%%, апгрейды %s"
              % (уб, р, план[4] * 100, план[7] * 100, "да" if план[8] else "нет"))


if __name__ == "__main__":
    main()
