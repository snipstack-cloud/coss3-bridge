"""Перебор ШАХТ и РАСПРЕДЕЛЕНИЯ КРЕСТЬЯН: сколько шахт каждого вида и сколько людей куда.

Две прежние редакции этого замера мерили не то:

* 27.09, первая: `BALANCE food N` меняет только еду, остальные ресурсы получают
  тех, кого сняли, — «20 человек на еде» означало «никого на золоте»;
* 27.09, вторая: доли задавались по всем шести ресурсам, и доли золота с железом
  НЕ ВЛИЯЛИ НИ НА ЧТО. Причина найдена в `sim.команда`: `n = min(n, 5 * шахт)` —
  в шахту заходит пять человек [код], и при одной шахте доля 15 % и 35 % дают
  одних и тех же пятерых. Рычаг не доля, а ЧИСЛО ШАХТ.

Поэтому здесь перебираются: число золотых, железных и угольных шахт, и доля
еды среди наземных крестьян (остальные на дерево и камень в отношении 2:1 —
дерева нужно больше, шахта стоит 100 дерева и 100 камня, а дом и склад дерева).

Числа механик: шахта 100 дерева + 100 камня, `costpercent` 0 — вторая шахта НЕ
дороже первой [код]; строится 94 с; балансовый темп 1,65 золота, 1,68 железа,
1,67 угля на крестьянина в секунду [замер]. То есть шахта = 8,3 ресурса в
секунду за 200 материала, и цена не растёт.

Живая серия `mines2` (15.09) сказала «больше шахт — хуже» (цель 1 из 6 против
4 из 6), но она строила шахты ВМЕСТО армии. Здесь план один и тот же, меняется
только число шахт, — и это проверяет то же утверждение честно.

    python3 sim/сетка_людей.py <корни> [--партий 12] [--ряд защита|атака]
"""
