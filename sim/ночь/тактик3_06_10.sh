#!/bin/bash
# 6.10 (§108): сеть тактика v3 — глаза (угроза базе) и решения обороны; PPO против p3о / p2 / случайного / налётчика,
# в награде — наши крестьяне. Запускается ПОСЛЕ поиска §107 (ждёт его «конец»).
# МЕРЫ ДО ПРОГОНА (отложенные): «налёт (p3,p5,p6)» — наших крестьян НИЖЕ, чем без сети (13 в пробе);
# случайный — уничтожена не ниже 45 из 100 (тень п1 44, без сети 61 с хозяйством шт_s2_угроза);
# ворота «без глаз»: слепая хуже зрячей хотя бы на одном наборе на 1,0 награды; решения «домой»/«встретить» > 0 %.
set -u
cd ~/coss3-bridge || exit 1
OUT=sim/ночь/тактик3_06_10
mkdir -p "$OUT"
until grep -q "^конец" sim/ночь/налёт_06_10/журнал.txt 2>/dev/null; do sleep 60; done
echo "старт $(date '+%F %T') на $(git rev-parse --short HEAD)" > "$OUT/журнал.txt"
for s in 1 2 3; do
  caffeinate -i python3 sim/ppo_тактик.py --v3 --iters 300 --eps 48 --seed "$s" --out "sim/тактик/ppo3_$s.npy" > "$OUT/ppo3_$s.txt" 2>&1 &
done
wait
echo "конец $(date '+%F %T')" >> "$OUT/журнал.txt"
