#!/bin/bash
# 6.10 (§107): поиск против смеси с налётчиком, по худшему противнику, с ценой наших крестьян.
# МЕРЫ ДО ПРОГОНА (проверка: случайный / p3 / p3о / p2 / p5 / p6 / налёт на отложенных записях игрока p3,p5,p6):
#  * наших крестьян на «налёт» и p6 — НИЖЕ, чем у шт_s2_угроза (30 и 36), не хуже рук обороны вручную (10 и 17);
#  * случайный — уничтожена не ниже 50 из 100 (шт_s2_угроза 58): оборона не должна убить наступление;
#  * оборона выбрана (=1) хотя бы в двух зёрнах из трёх.
set -u
cd ~/coss3-bridge || exit 1
OUT=sim/ночь/налёт_06_10
mkdir -p "$OUT"
echo "старт $(date '+%F %T') на $(git rev-parse --short HEAD)" > "$OUT/журнал.txt"
export COSS3_WAVE_CONTRACT=1 COSS3_PEA_W=2 COSS3_WORST=1
for s in 1 2 3; do
  COSS3_MIX=случайный,налётчик_о,p2 caffeinate -i python3 sim/поиск_стратегии.py --смесь --хозяйство --тактика --все-прокачки --состав --штурм --оборона --огонь \
    --gens 80 --pop 48 --k 18 --seed "$s" --out "sim/поиск/нл_s$s.json" > "$OUT/поиск_s$s.txt" 2>&1 &
done
wait
echo "поиск кончен $(date '+%F %T')" >> "$OUT/журнал.txt"
COSS3_RAID_SET=1 COSS3_P5=1 COSS3_P6=1 caffeinate -i python3 sim/проверка_пары.py sim/поиск/шт_s2_угроза.json sim/ночь/оборона_06_10/об.json \
  sim/поиск/нл_s1.json sim/поиск/нл_s2.json sim/поиск/нл_s3.json --json "$OUT/итог.json" > "$OUT/итог.txt" 2>&1
echo "конец $(date '+%F %T')" >> "$OUT/журнал.txt"
