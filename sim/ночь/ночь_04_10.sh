#!/bin/bash
# Ночь 4.10 (§70-§72): поиск стратегии и сеть тактика на исправленном симуляторе.
# Запуск: nohup caffeinate -i bash sim/ночь/ночь_04_10.sh > /dev/null 2>&1 &
# Итог: sim/ночь/04_10/ИТОГ.txt. Имена переменных латиницей (кириллица в bash падает у игрока).
set -u
cd ~/coss3-bridge || exit 1
OUT=sim/ночь/04_10
mkdir -p "$OUT"
LOG="$OUT/журнал.txt"
echo "старт $(date '+%F %T')" > "$LOG"

# 1. Поиск стратегии: три зерна параллельно, против случайных противников (с заслоном, строем,
#    порогом вступления и прокачкой мушкетёров), те же 48 рычагов, что у сл2_s1
for s in 1 2 3; do
  COSS3_MIX=случайный python3 sim/поиск_стратегии.py --смесь --хозяйство --тактика --все-прокачки \
    --gens 80 --pop 48 --k 18 --seed "$s" --out "sim/поиск/н4_s$s.json" > "$OUT/поиск_s$s.txt" 2>&1 &
done
wait
echo "поиск кончен $(date '+%F %T')" >> "$LOG"

# 2. Проверка стратегий без сети: отложенный набор 100, p3 30, p2 30
python3 sim/проверка_пары.py sim/поиск/сл2_s1.json sim/поиск/н4_s1.json sim/поиск/н4_s2.json sim/поиск/н4_s3.json \
  --json "$OUT/стратегии.json" > "$OUT/стратегии.txt" 2>&1
BEST=$(python3 - "$OUT/стратегии.json" <<'EOF'
import json, sys
d = json.load(open(sys.argv[1], encoding="utf-8"))
лучшая = max(d, key=lambda k: (d[k]["случайный"]["уничтожена"], d[k]["p3"]["размен"]))
print("sim/поиск/" + лучшая)
EOF
)
echo "лучшая стратегия: $BEST" >> "$LOG"

# 3. Сеть тактика поверх лучшей: три зерна параллельно (её собственная проверка в конце — с p3)
for s in 1 2 3; do
  python3 sim/тактик.py --враг случайный --хоз "$BEST" --gens 80 --pop 48 --k 18 --seed "$s" \
    --out "sim/тактик/н4_$s.npy" > "$OUT/тактик_s$s.txt" 2>&1 &
done
wait
echo "сети кончены $(date '+%F %T')" >> "$LOG"

# 4. Пары на тех же трёх наборах: новые сети и нынешняя пара Windows для сравнения
{
  echo "=== стратегии без сети ==="; cat "$OUT/стратегии.txt"
  echo; echo "=== лучшая: $BEST ==="
  echo; echo "=== пары ==="
  python3 sim/проверка_пары.py sim/поиск/сл2_s1.json --сеть nets/tactic_shadow.json 2>&1 | grep -v "^ПРОТИВНИК\|^ХОЗЯЙ\|^корпус"
  for s in 1 2 3; do
    python3 sim/проверка_пары.py "$BEST" --сеть "sim/тактик/н4_${s}_среднее.npy" 2>&1 | grep -v "^ПРОТИВНИК\|^ХОЗЯЙ\|^корпус"
  done
} > "$OUT/ИТОГ.txt"
echo "конец $(date '+%F %T')" >> "$LOG"
