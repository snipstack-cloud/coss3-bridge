# -*- coding: utf-8 -*-
"""Уроки: учим политику КАЖДОЙ команде отдельно, с плотной наградой (27.09).

Почему так. Награда-лестница (`goals.py`) ставит одну большую цель на всю
партию, и на честном симуляторе (§13м-13о) она почти не даёт сигнала: сеть
залипает на одном действии, а связки из нескольких команд («накопить дерево ->
построить академию -> нанять офицера и барабанщика -> включить строй») не
складываются, потому что платят только за исход.

Урок — это ОДНА проверяемая цель с наградой за ПРИБЛИЖЕНИЕ к ней. Ученик,
прошедший урок, умеет отдать связку команд, ведущую к цели; чему он научился,
видно сразу по доле партий, где цель взята, и по времени её взятия.

Каждый урок: `награда(сим, история) -> float` (0..2, плотная) и
`сделано(сим, история) -> bool`. Награда всегда содержит «хвост» за
незавершённое приближение, иначе сеть не отличит «почти получилось» от
«не начинал».

    python3 sim/train.py <корни> --урок академия --gens 60
    python3 sim/уроки.py <корни>            # что умеет ярус 1 и запись
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import sim as SIM  # noqa: E402


def _ч(v):
    return SIM.ч(v)


def _когда(история, поле, порог):
    """Время, когда поле впервые достигло порога, иначе None."""
    for s in история:
        if _ч(s.get(поле)) >= порог:
            return float(s.get("gametime") or 0)
    return None


def _максимум(история, поле):
    return max((_ч(s.get(поле)) for s in история), default=0.0)


def _скорость(t, срок):
    """1,0 если взято сразу, 0,0 если к сроку; за срок не наказываем ниже нуля."""
    return max(0.0, min(1.0, 1.0 - (t or срок) / срок))


class Урок:
    def __init__(self, имя, описание, награда, сделано, срок=1200.0):
        self.имя, self.описание, self._награда, self._сделано, self.срок = имя, описание, награда, сделано, срок

    def награда(self, сим, история):
        return float(self._награда(сим, история))

    def сделано(self, сим, история):
        return bool(self._сделано(сим, история))


def _ресурс_к_цели(сим, история, рес, цель):
    """Доля пути к запасу ресурса: максимум за партию, обрезанный целью."""
    м = _максимум(история, рес)
    return min(1.0, м / цель)


def _здание(имя_поля, цель=1):
    def сделано(сим, история):
        return _ч(сим.состояние().get(имя_поля)) >= цель or _максимум(история, имя_поля) >= цель
    return сделано


УРОКИ = {}


def _урок(имя, описание, награда, сделано, срок=1200.0):
    УРОКИ[имя] = Урок(имя, описание, награда, сделано, срок)


# --- 1. простые постройки: проверка, что ученик вообще учится ---------------
_урок("мельница", "мельница до 120 с",
      lambda с, и: (1.0 + _скорость(_когда(и, "mills", 1), 120.0)) if _когда(и, "mills", 1) else
                   0.5 * min(1.0, _максимум(и, "wood") / 30.0),
      _здание("mills"), срок=120.0)

_урок("казарма", "казарма до 300 с (нужна кузница)",
      lambda с, и: (1.0 + _скорость(_когда(и, "ba17", 1), 300.0)) if _когда(и, "ba17", 1) else
                   0.3 * _ч(_максимум(и, "smiths") > 0) + 0.3 * min(1.0, _максимум(и, "gold") / 500.0),
      _здание("ba17"), срок=300.0)

# --- 2. ресурс, которого не хватает: дерево ---------------------------------
_урок("дерево", "накопить 1200 дерева (цена академии) — [замер] 27.09: дерево падает ниже 1050 в 48 партиях из 69, а золота в конце 14 тысяч",
      lambda с, и: 2.0 * _ресурс_к_цели(с, и, "wood", 1200.0),
      lambda с, и: _максимум(и, "wood") >= 1200.0)

# --- 3. то, чего не было ни в одной живой партии -----------------------------
_урок("академия", "построить академию (1050 дерева + 1230 камня, 625 с стройки): заказана 124 раза, достроена НИ РАЗУ",
      lambda с, и: 2.0 if _здание("academi")(с, и) else
                   0.7 * min(1.0, _максимум(и, "wood") / 1050.0) + 0.7 * min(1.0, _максимум(и, "stone") / 1230.0)
                   + 0.3 * _ч(any(x["роль"] == "academi" for x in с.стройки)),
      _здание("academi"))

_урок("строй", "включить строй: академия -> офицер и барабанщик -> FORMATION (+2/+2 на ходу, +7/+7 стоя)",
      lambda с, и: (2.0 if с.строй else
                    0.4 * min(1.0, _максимум(и, "wood") / 1050.0) + 0.4 * min(1.0, _максимум(и, "stone") / 1230.0)
                    + 0.6 * _ч(_здание("academi")(с, и)) + 0.3 * min(1.0, с.офицеры) + 0.3 * min(1.0, с.барабанщики)),
      lambda с, и: bool(с.строй))

_урок("конюшня", "построить конюшню (2500 дерева) и нанять драгуна (320 hp против 90 у пикинёра)",
      lambda с, и: (2.0 if _ч(с.состояние().get("mil_cav")) >= 1 else
                    1.2 * _ч(_здание("stables")(с, и)) + 0.8 * min(1.0, _максимум(и, "wood") / 2500.0)),
      lambda с, и: _ч(с.состояние().get("mil_cav")) >= 1)

_урок("казарма3", "три казармы (каждая следующая дороже: costpercent)",
      lambda с, и: min(2.0, 0.6 * _ч(с.эк.здания.get("ba17", 0))),
      lambda с, и: _ч(с.эк.здания.get("ba17", 0)) >= 3)

# --- 4. война: те же связки, но про армию ------------------------------------
_урок("армия40", "40 бойцов к 500 с",
      lambda с, и: (1.0 + _скорость(_когда(и, "mil_inf", 40), 500.0)) if _когда(и, "mil_inf", 40) else
                   min(1.0, _максимум(и, "mil_inf") / 40.0),
      lambda с, и: _максимум(и, "mil_inf") >= 40, срок=500.0)

# ЛОЖНЫЙ НОЛЬ, пойманный сразу (27.09): первая редакция урока считала поле
# `у_крестьян`, которого в истории СИМУЛЯТОРА нет вовсе (оно есть только в
# снимках моста) — обучение честно давало 0,000 и не двигалось. Считаем по
# счётчику самого симулятора.
_урок("доставка", "простоять у его крестьян 10 тактов (50 с): наши в клетке с его крестьянами",
      lambda с, и: 2.0 * min(1.0, с.тактов_у_крестьян / 10.0),
      lambda с, и: с.тактов_у_крестьян >= 10)

_урок("убить10", "убить 10 его крестьян",
      lambda с, и: 2.0 * min(1.0, с.убито_крестьян / 10.0),
      lambda с, и: с.убито_крестьян >= 10)

_урок("размен", "убить его бойцов не меньше половины своих потерь",
      lambda с, и: 2.0 * min(1.0, с.убито_бойцов / max(0.5 * с.my_mil_lost, 1.0)) if с.my_mil_lost >= 10 else 0.0,
      lambda с, и: с.my_mil_lost >= 10 and с.убито_бойцов >= 0.5 * с.my_mil_lost)


def main():
    import statistics as S
    import tier1 as T1
    import train as TR
    корни = [a for a in sys.argv[1:] if not a.startswith("--")]
    все = TR.партии(корни)
    _, тест = TR.разбить(все)
    print(f"отложенных партий {len(тест)}; что берут ярус 1 и команды записи\n")
    print("%-10s %-72s %8s %8s" % ("урок", "цель", "ярус 1", "запись"))
    for имя, у in УРОКИ.items():
        я = з = 0
        for i, d in enumerate(тест):
            с, и = SIM.партия(d, T1.Ярус1(), seed=i)
            я += у.сделано(с, и)
            с2, и2 = TR._запись_партия(d, i) if hasattr(TR, "_запись_партия") else (None, None)
            if с2 is not None:
                з += у.сделано(с2, и2)
        print("%-10s %-72s %7.0f%% %7s" % (имя, у.описание[:72], 100 * я / len(тест),
                                           f"{100 * з / len(тест):.0f}%" if с2 is not None else "—"))


if __name__ == "__main__":
    main()
