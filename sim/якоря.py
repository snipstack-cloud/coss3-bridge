#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""ЯКОРЯ ИГРОКА (§114, сценой одной командой): развилки записей игрока «удар сразу», медиана 8 зёрен, наши/его до конца
записи против живого исхода. Прежде считались разовыми прогонами `развилка.py` (таблицы §114–§114д); здесь — чтобы
правку ядра (§119: скорость реакций агента) сравнивать «до/после» на одном коде.

    python3 sim/якоря.py [--зёрен 8]
"""
import os
import statistics as St
import sys
from multiprocessing import Pool

К = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, К)
sys.path.insert(0, os.path.dirname(К))

СЦЕНЫ = (("p5 13:47", "~/coss3-res-игрок-отл/igrok_04_10_p5/1", 827.0, "p3", (20, 61)),
         ("p3 8:17", "~/coss3-res-игрок-отл/igrok_03_10_p3/1", 497.0, "p3", (53, 7)),
         ("p6 7:37", "~/coss3-res-игрок-отл/igrok_06_10_p6/1", 457.0, "p3", (75, 46)),
         ("p2 6:50", "~/coss3-res-игрок-отл/igrok_02_10_p2/1", 410.0, "p2", (59, 14)))


ГОРИЗОНТ_С = 240.0     # §114: живые 53/7, 75/46, 59/14 — ровно 4 минуты от развилки; p5 — до конца записи (60 с)


def _з(з):
    import развилка as R
    import sim as SIM
    имя, каталог, t, вид, seed = з
    сим, куча = R.построить(os.path.expanduser(каталог), t, вид, seed)
    клетка = (int(round(куча["x"])), int(round(куча["y"]))) if куча else (int(round(сим.з.my_cx)), int(round(сим.з.my_cy)))
    п = R.Ветка("удар сразу", куча["id"] if куча else None, клетка)
    конец = min(float(сим.з.снапы[-1]["gametime"]), t + ГОРИЗОНТ_С)
    п0, у0 = сим.my_mil_lost, сим.убито_бойцов
    while сим.t < конец and not сим.исход:
        сим.команды(п(сим, сим.состояние()) or [])
        сим.такт()
    SIM.ФОРМА_ВРАГА = None
    return имя, dict(наши=сим.my_mil_lost - п0, его=сим.убито_бойцов - у0)


def прогнать(зёрен=8):
    зад = [(имя, к, t, вид, 100 + s) for имя, к, t, вид, _ in СЦЕНЫ for s in range(зёрен)]
    with Pool(12) as пул:
        р = пул.map(_з, зад)
    из = {}
    for имя, к, t, вид, живьём in СЦЕНЫ:
        рр = [x for и, x in р if и == имя]
        н, е = St.median(x["наши"] for x in рр), St.median(x["его"] for x in рр)
        из[имя] = (н, е, sum(x["его"] for x in рр) / max(sum(x["наши"] for x in рр), 1), живьём)
    return из


if __name__ == "__main__":
    зёрен = int(sys.argv[sys.argv.index("--зёрен") + 1]) if "--зёрен" in sys.argv else 8
    for имя, (н, е, r, ж) in прогнать(зёрен).items():
        print(f"  {имя:9} живьём {ж[0]:3d}/{ж[1]:3d} ({ж[1] / ж[0]:.2f})   двойник {н:5.0f}/{е:5.0f} ({r:.2f})")
