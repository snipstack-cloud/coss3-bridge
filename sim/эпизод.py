"""БОЕВОЙ ЭПИЗОД (4.10, §78): законченное столкновение без хозяйства — семейство «сбор и повторный удар».

Зачем (игрок 4.10, план п. 4). Награда полной партии манёвр не различает: в §55 три сети с
разным составом решений получили одну награду, а слепые сошлись к одному числу — её делает
экономика и «слать всё». Здесь армии и позиции заданы, хозяйство заморожено (найм обеих сторон
0), и мера — только исход столкновения. Если ручной план сбора не бьёт прямой удар на наборе
таких эпизодов, манёвр в этом ядре не окупается и учить его нечему.

Сцена (`сцена(rng, записи)`, [допущение] диапазоны): передовая группа A (10-30 пикинёров) стоит в
поле в `d_ab` (3-6) клетках от дома по прямой к его базе и идёт на его кучу H (20-70, доля
мушкетёров 0-1) ещё в `d_ah` (2-4) клетках; основные силы B (20-60) дома. Его повадки — розыгрыш
`случайный_враг` (погоня, вступает, отход, сила, дистанция, вступать_при), найм 0; он ХОЧЕТ стоять
на H (`sim.ФОРМА_ВРАГА`) и реагирует только по стилю. Характеристики бойцов и его крестьяне — из
записи-основы на 10:00 (`t0` 600 с); характеристики бойцов У ОБЕИХ СТОРОН — его из записи на t0, заморожены (манёвр, не прокачка). Длина эпизода `T` 420 с; конец раньше —
когда одна сторона ниже 10 % начального.

Политики (все — только командами, которые есть в симуляторе и мосте):
  ничего   — A бьёт одна, B стоит (нижняя граница);
  лоб      — B сразу на его армию, A продолжает (постоянная досылка: A приходит раньше B);
  сбор     — A к своим (домой), B ждёт; когда A дома или через 120 с — все на его армию;
  встреча  — A стоит, B к волне; когда B в клетке от A — все, кто в поле, на H (сбор перед контактом);
  правила  — правила войны §40 (отход 0,75, подмога от 20) поверх немой экономики;
  сеть     — тень тактика `nets/tactic_shadow.json` (решение раз в 15 с), и она же «без глаз».
Мера на эпизод: его потери, наши потери, размен, его куча уничтожена (< 10 %), наших выжило.

    python3 sim/эпизод.py [--n 100] [--seed 7] [--T 420] [--json файл]
"""
import json
import math
import os
import statistics as St
import sys
from multiprocessing import Pool

К = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, К)
sys.path.insert(0, os.path.dirname(К))

T0 = 600.0
ДИАПАЗОНЫ = (("n_a", 10, 30, True), ("n_b", 20, 60, True), ("n_h", 20, 70, True), ("d_ab", 3, 6, True), ("d_ah", 2, 4, True))


def сцена(rng, записи):
    import случайный_враг as СВ
    с = {имя: int(rng.integers(lo, hi + 1)) for имя, lo, hi, _ in ДИАПАЗОНЫ}
    с["враг"] = dict(СВ.разыграть(rng), найм=0.0)
    с["враг"]["вступать_при"] = round(float(rng.uniform(0.0, 1.0)), 3)
    с["запись"] = записи[int(rng.integers(len(записи)))]
    return с


def _клетка(база, цель, d, N=16):
    dx, dy = цель[0] - база[0], цель[1] - база[1]
    L = math.hypot(dx, dy) or 1.0
    return (min(N - 1, max(0, int(round(база[0] + dx / L * d)))), min(N - 1, max(0, int(round(база[1] + dy / L * d)))))


def построить(с, seed):
    """Симулятор на 10:00 записи-основы с заданными армиями; хозяйство и найм заморожены."""
    import sim as SIM
    import тактик as ТК
    ТК._настроить(dict(с["враг"]))            # агент, стиль, состав «доля», найм 0, обычный профиль боя
    st = SIM.СТИЛЬ_ВРАГА
    st["вступать_при"] = с["враг"].get("вступать_при", 0.0)
    зап = SIM.Запись(с["запись"])
    сим = SIM.Симулятор(зап, seed)
    сим.t = сим.t0 = T0
    # прокачки ОБЕИХ сторон — записи на t0: его идут из `p1_fighters` снимка сами, наши — из `upg_done`
    # такта (иначе его пикинёр с 2-3 ступенями против нашего голого: все политики проигрывали)
    _st0 = зап.такт_до(T0)[1]
    сим.апгрейды |= {u for u in str(_st0.get("upg_done") or "").split(",") if u}
    # РАВНОЕ КАЧЕСТВО БОЙЦОВ (§78): у родного ИИ на 10:00 пикинёр atk 13 / dpike 7 против нашего 8 / 5
    # по `upg_done` — наш удар уходит в минимум 1 (atk − def), его 8: при 56 против 31 размен 0,23.
    # Чтобы эпизод мерил манёвр, а не прокачку, обе стороны получают ЕГО характеристики на t0 и
    # дальше они заморожены (его прокачки позже t0 не идут); прокачка его мушкетёров (§70) снята.
    _его_х0 = {k: dict(v) for k, v in сим.его_х(_st0).items()}
    сим.его_х = lambda st: _его_х0
    сим.наши_х = lambda: {k: dict(v) for k, v in _его_х0.items()}
    SIM.ПРОКАЧКА_ВРАГА = None
    дом = (float(зап.my_cx), float(зап.my_cy))
    A = _клетка(дом, зап.en_base, с["d_ab"])
    H = _клетка(дом, зап.en_base, с["d_ab"] + с["d_ah"])
    # наши: дом — B пикинёров; A — группа в поле, идёт на H
    сим.группы[0]["состав"] = {"infantry17": float(с["n_b"]), "musk17": 0.0, "dragoon17": 0.0}
    сим.эк.армия = {"mil_inf": float(с["n_b"] + с["n_a"]), "mil_shooters": 0.0, "mil_cav": 0.0}
    сим.эк.запас_найма = 1e12                 # найм стоит
    сим.группы.append({"состав": {"infantry17": float(с["n_a"]), "musk17": 0.0, "dragoon17": 0.0},
                       "x": float(A[0]), "y": float(A[1]), "цель": (float(H[0]), float(H[1])), "режим": "марш", "карман": 0.0,
                       "конечная": (float(H[0]), float(H[1])), "без_армии": False, "старт": (float(A[0]), float(A[1])),
                       "t_приказа": сим.t, "хвост": 0.0})
    # его: вся армия на H, хочет там и стоять
    N = len(сим.враг.h)
    сим.враг.h = [[0.0] * N for _ in range(N)]
    сим.враг.h[H[1]][H[0]] = float(с["n_h"])
    сим.враг.нанято = 0.0
    форма = [[0] * N for _ in range(N)]
    форма[H[1]][H[0]] = с["n_h"]
    SIM.ФОРМА_ВРАГА = форма
    return сим, A, H


# ---------------------------------------------------------------- политики
class Скрипт:
    def __init__(self, имя, H):
        self.имя, self.H, self.этап = имя, H, 0

    def __call__(self, сим, st):
        поле = [г for г in сим.группы[1:] if sum(г["состав"].values()) > 0.5]
        t = сим.t - сим.t0
        н = self.имя
        if н == "ничего":
            return []
        if н == "лоб":
            if self.этап == 0:
                self.этап = 1
                return [{"cmd": "ATTACK", "count": "all", "target": "army"}]
            return []
        if н == "сбор":
            if self.этап == 0:
                self.этап = 1
                return [{"cmd": "_К_СВОИМ"}]
            if self.этап == 1 and (not поле or t >= 120):
                self.этап = 2
                return [{"cmd": "ATTACK", "count": "all", "target": "army"}]
            return []
        if н == "встреча":
            if self.этап == 0:
                self.этап = 1
                return [{"cmd": "_СТОЙ"}, {"cmd": "ATTACK", "count": "all", "target": "wave"}]
            if self.этап == 1:
                стоящие = [г for г in поле if г.get("стоит")]
                идущие = [г for г in поле if not г.get("стоит")]
                рядом = стоящие and идущие and min(math.hypot(a["x"] - b["x"], a["y"] - b["y"]) for a in стоящие for b in идущие) <= 1.0
                if рядом or len(поле) == 1 or t >= 150:
                    self.этап = 2
                    return [{"cmd": "_НА_КЛЕТКУ", "aim": [self.H[0], self.H[1]]}]
            return []
        return []


class Правила:
    """Правила войны §40 поверх немой экономики: отход 0,75, подмога от 20, волны на его армию."""

    def __init__(self):
        import поиск_стратегии as ПС
        хоз = json.load(open(os.path.join(К, "поиск", "сл2_s1.json"), encoding="utf-8"))["итог"]
        self.с = ПС.Стратегия(dict(хоз, отход=0.75, подмога=20, слабая=0, T1=0.0, P1=0.0, T2=0.0, шаг=60.0, порог=5.0, Ц2=1))

    def __call__(self, сим, st):
        return [c for c in self.с(st) if c.get("cmd") in ("ATTACK", "RETREAT", "_ВПЕРЁД", "_К_СВОИМ", "ENGAGE", "MOVE", "_СТОЙ", "_НА_КЛЕТКУ")]


class Сеть:
    def __init__(self, theta, среднее=None):
        from tactic_core import Ядро
        self.я = Ядро(theta)
        self.я.след = 0.0
        self.среднее = среднее
        self.лог = []
        if среднее is not None:
            я = self.я
            исх = я.признаки

            def слепые(st, t):
                исх(st, t)
                return list(среднее)
            я.признаки = слепые

    def __call__(self, сим, st):
        р = self.я.решить(st)
        if р is None:
            return []
        self.лог.append(р[1])
        return self.я.команды(р[0], st)


def _веса():
    п = os.path.join(os.path.dirname(К), "nets", "tactic_shadow.json")
    return json.load(open(п, encoding="utf-8"))["theta"] if os.path.exists(п) else None


def прогнать(с, политика, seed, T):
    import sim as SIM
    сим, A, H = построить(с, seed)
    n_h0 = с["n_h"]
    n_наши0 = с["n_a"] + с["n_b"]
    конец = "T"
    while сим.t - сим.t0 < T:
        st = сим.состояние()
        сим.команды(политика(сим, st) or [])
        сим.такт()
        его = сим.враг.всего()
        наши = sum(sum(г["состав"].values()) for г in сим.группы)
        if его < 0.1 * n_h0:
            конец = "его нет"
            break
        if наши < 0.1 * n_наши0:
            конец = "наших нет"
            break
    SIM.ФОРМА_ВРАГА = None
    return dict(его=round(сим.убито_бойцов, 1), наши=round(сим.my_mil_lost, 1), выжило=round(sum(sum(г["состав"].values()) for г in сим.группы), 1),
                его_осталось=round(сим.враг.всего(), 1), конец=конец, t=round(сим.t - сим.t0),
                уничтожена=конец == "его нет", потерь_нет=конец == "наших нет")


def _задача(з):
    с, имя, seed, T, theta, среднее = з
    H = None
    if имя in ("ничего", "лоб", "сбор", "встреча"):
        import sim as SIM
        зап = SIM.Запись(с["запись"])
        H = _клетка((float(зап.my_cx), float(зап.my_cy)), зап.en_base, с["d_ab"] + с["d_ah"])
        п = Скрипт(имя, H)
    elif имя == "правила":
        п = Правила()
    elif имя in ("сеть", "сеть без глаз"):
        п = Сеть(theta, среднее)
    р = прогнать(с, п, seed, T)
    if имя == "сеть":
        import numpy as np
        from tactic_core import N_ПРИЗНАКОВ
        р["среднее"] = [float(v) for v in (np.mean(п.лог, axis=0) if п.лог else np.zeros(N_ПРИЗНАКОВ))]
    return р


def свод(р):
    его, наши = sum(x["его"] for x in р), sum(x["наши"] for x in р)
    return (f"его потери {его:6.0f} | наши {наши:6.0f} | размен {его / max(наши, 1):4.2f} | уничтожена {sum(x['уничтожена'] for x in р):3d}/{len(р)}"
            f" | наших нет {sum(x['потерь_нет'] for x in р):3d} | выжило медиана {St.median(x['выжило'] for x in р):4.0f} | длина медиана {St.median(x['t'] for x in р):4.0f} с")


def main():
    def опц(имя, умолч, тип=int):
        return тип(sys.argv[sys.argv.index(имя) + 1]) if имя in sys.argv else умолч
    n, seed, T = опц("--n", 100), опц("--seed", 7), опц("--T", 420, float)
    import numpy as np
    import батарея as Б
    _, тест, _, _ = Б.наборы()
    rng = np.random.default_rng(seed)
    сцены = [сцена(rng, тест) for _ in range(n)]
    theta = _веса()
    политики = ["ничего", "лоб", "сбор", "встреча", "правила"] + (["сеть"] if theta else [])
    итог = {}
    print(f"ЭПИЗОДЫ «сбор и повторный удар»: {n} сцен, зерно {seed}, T {T:.0f} с, t0 {T0:.0f}; A {ДИАПАЗОНЫ[0][1]}-{ДИАПАЗОНЫ[0][2]}, B {ДИАПАЗОНЫ[1][1]}-{ДИАПАЗОНЫ[1][2]}, H {ДИАПАЗОНЫ[2][1]}-{ДИАПАЗОНЫ[2][2]}", flush=True)
    with Pool(12) as пул:
        for имя in политики:
            р = пул.map(_задача, [(с, имя, 100 + i, T, theta, None) for i, с in enumerate(сцены)])
            итог[имя] = р
            print(f"  {имя:14} {свод(р)}", flush=True)
            if имя == "сеть":
                сл = пул.map(_задача, [(с, "сеть без глаз", 100 + i, T, theta, x["среднее"]) for i, (с, x) in enumerate(zip(сцены, р))])
                итог["сеть без глаз"] = сл
                print(f"  {'сеть без глаз':14} {свод(сл)}", flush=True)
        # срезы: по перевесу H над A+B и по погоне
        print("\nСРЕЗЫ (уничтожена / размен):")
        for подпись, усл in (("H ≤ 0,8·(A+B)", lambda с: с["n_h"] <= 0.8 * (с["n_a"] + с["n_b"])), ("H > 0,8·(A+B)", lambda с: с["n_h"] > 0.8 * (с["n_a"] + с["n_b"])),
                             ("погоня 0", lambda с: с["враг"]["погоня"] == 0), ("погоня ≥ 3", lambda с: с["враг"]["погоня"] >= 3),
                             ("вступать_при ≥ 0,5", lambda с: с["враг"]["вступать_при"] >= 0.5)):
            идx = [i for i, с in enumerate(сцены) if усл(с)]
            if not идx:
                continue
            print(f"  {подпись:20} n {len(идx):3d}: " + "; ".join(
                f"{имя} {sum(итог[имя][i]['уничтожена'] for i in идx)}/{sum(итог[имя][i]['его'] for i in идx) / max(sum(итог[имя][i]['наши'] for i in идx), 1):.2f}"
                for имя in итог), flush=True)
    if "--json" in sys.argv:
        json.dump({"сцены": сцены, "итог": {k: [{q: v for q, v in x.items() if q != "среднее"} for x in р] for k, р in итог.items()}},
                  open(sys.argv[sys.argv.index("--json") + 1], "w", encoding="utf-8"), ensure_ascii=False, indent=1)


if __name__ == "__main__":
    main()
