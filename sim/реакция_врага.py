#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""РЕАКЦИЯ ПРОТИВНИКА ПО ОТРЯДАМ — для стилей агентного врага (29.09, §29).

Читает новые поля снимка (мост с 29.09): `ecells` — его армия по клеткам с составом и
приказами (`n, пик, стрелков, конных, идут, tx, ty`), `ocells` — наша по клеткам с
составом, `p1_human` — противник человек. Прежде была одна средняя цель на всю его
армию (`p1_mv_*`), и отряд, бросившийся на наших стрелков, не отличался от стоящей армии.

Три меры, каждая — параметр стиля в `sim/враг.py`:
1. НА СТРЕЛКОВ (`на_стрелков`): его клетки в 2–4 клетках от наших; доля тех, что идут
   (`идут` > 0) с целью не дальше 1 клетки от нашей группы — отдельно, когда в ней есть
   стрелки, и когда одни пикинёры. Разница — приманка работает или нет.
2. ОТХОД (`отход`): его клетки, где нас больше чем вдвое (по `ocells` в той же клетке);
   доля идущих с целью ДАЛЬШЕ от нас, чем стоят сейчас.
3. ВСТУПАЕТ (`вступает`): с какого расстояния его идущие бойцы целятся в клетку нашей
   группы — распределение расстояний от его клетки до нашей для таких приказов.

    python3 sim/реакция_врага.py ~/coss3-res/<дата>/igrok_29_09 [ещё каталоги...]
"""
import json
import math
import os
import sys
from collections import defaultdict


def _снимки(путь):
    for s in open(путь, encoding="utf-8"):
        s = s.strip()
        if s.startswith("{"):
            try:
                x = json.loads(s)
            except ValueError:
                continue
            if "gametime" in x:
                yield x


def _клетки(поле, имена):
    """В снимке — список словарей (мост пишет разобранное); на всякий случай и строка."""
    if not поле or поле == "none":
        return []
    if isinstance(поле, list):
        из = []
        for c in поле:
            if isinstance(c, dict):
                из.append(c)
            elif isinstance(c, (list, tuple)) and len(c) >= 2 + len(имена):
                из.append(dict(x=c[0], y=c[1], **{k: v for k, v in zip(имена, c[2:])}))
        return из
    из = []
    for кусок in str(поле).split(";"):
        ч = кусок.split(",")
        if len(ч) == 2 + len(имена):
            try:
                ч = [int(v) for v in ч]
            except ValueError:
                continue
            из.append(dict(x=ч[0], y=ч[1], **{k: v for k, v in zip(имена, ч[2:])}))
    return из


ЕГО = ("n", "пик", "стрелков", "конных", "идут", "tx", "ty")
НАШ = ("n", "пик", "стрелков", "конных")


def разобрать(путь, итог):
    for s in _снимки(путь):
        его = _клетки(s.get("ecells"), ЕГО)
        наши = [c for c in _клетки(s.get("ocells"), НАШ) if c.get("n", 0) > 0]
        if not его or not наши:
            continue
        итог["снимков"] += 1
        итог["человек"] += bool(s.get("p1_human"))
        for e in его:
            n, идут = e.get("n", 0), e.get("идут", 0)
            if n <= 0:
                continue
            ближ = min(наши, key=lambda o: math.hypot(o["x"] - e["x"], o["y"] - e["y"]))
            d = math.hypot(ближ["x"] - e["x"], ближ["y"] - e["y"])
            цель = (e.get("tx", -1), e.get("ty", -1)) if идут > 0 and e.get("tx", -1) >= 0 else None
            # 1. на стрелков
            if 2 <= d <= 4:
                вид = "со стрелками" if ближ.get("стрелков", 0) > 0 else "одни пики"
                итог[f"рядом {вид}: бойцов"] += n
                if цель and math.hypot(цель[0] - ближ["x"], цель[1] - ближ["y"]) <= 1:
                    итог[f"рядом {вид}: идут на нас"] += идут
            # 2. отход в меньшинстве
            if d < 0.5 and ближ["n"] >= 2 * n:
                итог["в меньшинстве: бойцов"] += n
                if цель and math.hypot(цель[0] - ближ["x"], цель[1] - ближ["y"]) > d + 1:
                    итог["в меньшинстве: уходят"] += идут
            # 3. с какого расстояния идут в нашу клетку
            if цель:
                for o in наши:
                    if math.hypot(цель[0] - o["x"], цель[1] - o["y"]) <= 0.5:
                        итог[f"идут в нашу клетку с {min(int(round(d)), 6)}"] += идут
                        break


def main():
    корни = [os.path.expanduser(a) for a in sys.argv[1:]]
    if not корни:
        raise SystemExit(__doc__)
    итог = defaultdict(float)
    n = 0
    for корень in корни:
        for d, _, ф in sorted(os.walk(корень)):
            if "coss3_snap.jsonl" in ф:
                разобрать(os.path.join(d, "coss3_snap.jsonl"), итог)
                n += 1
    print(f"записей {n}, снимков с его и нашей армией {int(итог['снимков'])}, из них противник-человек {int(итог['человек'])}")
    if not итог["снимков"]:
        print("НЕТ ДАННЫХ: в снимках нет `ecells`/`ocells` — мост старше 29.09 или армий не было")
        return
    for вид in ("со стрелками", "одни пики"):
        б, и = итог[f"рядом {вид}: бойцов"], итог[f"рядом {вид}: идут на нас"]
        print(f"1. его бойцы в 2–4 клетках от нашей группы ({вид}): {б:.0f}, идут на неё {и:.0f} — {100 * и / б if б else float('nan'):.0f} %")
    б, и = итог["в меньшинстве: бойцов"], итог["в меньшинстве: уходят"]
    print(f"2. его бойцы в нашей клетке при нашем двойном перевесе: {б:.0f}, уходят от нас {и:.0f} — {100 * и / б if б else float('nan'):.0f} %")
    print("3. идут в клетку нашей группы — с расстояния (клеток):",
          ", ".join(f"{r}: {итог[f'идут в нашу клетку с {r}']:.0f}" for r in range(7)))


if __name__ == "__main__":
    main()
