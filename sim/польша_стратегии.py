#!/usr/bin/env python3
"""ПОЛЬША-ПРОТИВНИК: две стратегии и что они значат для нас (1.11, вопрос игрока).

Стратегия 2 «две казармы, пики, прокачки, академия потом» — ЗАМЕР: живая партия 30.10, игрок Польшей (`nat0 = 6`), сторона p1.
Стратегия 1 «одна казарма, сразу академия, офицер + барабанщик, отряд, прокачки» — РАСЧЁТ на темпах той же записи: темп одной
казармы берётся из её отрезка с одной казармой, академия — по нашим записям (заложена → готова), отряд — по `formations.cfg`.

Числа юнитов — `нации.юниты_из_скрипта()` (с поправками `case nation of`); бонус отряда +2/+2 на ходу, +7/+7 стоя (world.md [код],
`miscext2.script:351-353, 428-431`); урон = атака − защита по виду оружия, не меньше 1 (`combat_math.урон`).

    python3 sim/польша_стратегии.py [каталог записи 30.10]
"""
import json
import os
import sys

К = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, К)
import нации as Н  # noqa: E402

ЗАПИСЬ = os.path.expanduser("~/coss3-res/2026-10-30/igrok_30_10_партияПольша_§170н/1")
ВЕХИ = (240, 300, 360, 420, 480, 600, 720, 840)
АКАДЕМИЯ_С = 58          # [замер] заложена → готова, 8 записей 30–31.10 при 18–20 строителях: 55–60 с
ОТРЯДЫ = (36, 72, 120)   # размеры строя `formations.cfg` (15 — тоже отряд, но бонус тот же, а людей мало)


def партия_p1(каталог):
    """Самый длинный отрезок записи с армией p1 (в файле несколько партий подряд: gametime сбрасывается)."""
    отрезки, cur, prev = [], [], -1
    for ln in open(os.path.join(каталог, "coss3_bot.jsonl"), encoding="utf-8"):
        try:
            j = json.loads(ln)
        except ValueError:
            continue
        st = j.get("state") or j
        t = st.get("gametime")
        if t is None:
            continue
        if t < prev - 30:
            отрезки.append(cur)
            cur = []
        cur.append(st)
        prev = t
    отрезки.append(cur)
    return max(отрезки, key=lambda s: max((x.get("p1_army") or 0) for x in s))


def на(s, t, поле):
    for st in s:
        if st["gametime"] >= t:
            return st.get(поле)
    return s[-1].get(поле)


def первый(s, усл):
    for st in s:
        if усл(st):
            return st["gametime"]
    return None


def мин(t):
    return "—" if t is None else f"{int(t) // 60}:{int(t) % 60:02d}"


def main():
    s = партия_p1(sys.argv[1] if len(sys.argv) > 1 else ЗАПИСЬ)
    # --- стратегия 2, замер
    ба2 = первый(s, lambda st: (st.get("p1_ba17") or 0) >= 2)
    пики_с = первый(s, lambda st: "pikemanpol:inf" in str(st.get("p1_train") or ""))
    a0 = на(s, пики_с + 20, "p1_army")
    темп1 = (на(s, ба2, "p1_army") - a0) / ((ба2 - пики_с - 20) / 60.0)
    темп2 = (на(s, ба2 + 140, "p1_army") - на(s, ба2 + 35, "p1_army")) / (105 / 60.0)
    print("СТРАТЕГИЯ 2 (замер 30.10, человек Польшей): казарма 2 в", мин(ба2), "| найм с", мин(пики_с))
    print(f"  темп: одна казарма {темп1:.1f} пик/мин, две {темп2:.1f} пик/мин (по коду 20 на казарму: 96 кадров = 3 с)")
    print("  железо всю партию:", sorted({st.get('p1_iron') for st in s if st['gametime'] > 120}), "| шахт железа:",
          max((st.get('p1_miron') or 0) for st in s), "| золото к концу:", s[-1].get("p1_gold"))
    print("  прокачки:", s[-1].get("p1_upg_done"))
    print("  армия:", "  ".join(f"{мин(t)} {на(s, t, 'p1_army')}" for t in ВЕХИ))
    # --- стратегия 1, расчёт: те же первые минуты, дерево на академию вместо шахт золота
    дерево_950 = первый(s, lambda st: (st.get("p1_wood") or 0) >= 950 and (st.get("p1_stone") or 0) >= 800)
    print("\nСТРАТЕГИЯ 1 (расчёт): академия 950 дерева + 800 камня; в записи эти деньги лежали к", мин(дерево_950),
          "(игрок тратил дерево на три шахты золота, без них — раньше)")
    for оплата in (150, дерево_950):
        готова = оплата + АКАДЕМИЯ_С
        оф = готова + 15                       # офицер 10 с + барабанщик 5 с в той же казарме [код]
        def пики(t):
            return max(0, a0 + темп1 * (t - пики_с - 20) / 60.0 - (темп1 * 15 / 60.0 if t > оф else 0))
        строй = []
        for n in ОТРЯДЫ:
            t = пики_с + 20 + (n - a0) / темп1 * 60.0
            строй.append(f"{n} — {мин(max(t, оф))}")
        print(f"  академия оплачена {мин(оплата)}, готова {мин(готова)}, офицер и барабанщик {мин(оф)}; отряд: " + ", ".join(строй))
        print("  пик:", "  ".join(f"{мин(t)} {round(пики(t))}" for t in ВЕХИ))
    # --- дуэль
    ю = Н.юниты_из_скрипта()
    наш, его = ю["pikeman"], ю["pikemanpol"]
    наш_м = ю["musketeernet"]
    print("\nДУЭЛЬ пика на пику (90 hp обе): сколько ударов нужно, кто выгоднее")
    # (имя, прокачка атаки, прокачка защиты, бонус строя) — прокачка защиты пулю не держит (`country.script` ctypeProtection*:
    # только pike/sword/arrow), бонус строя `fAddShield` держит
    for имя, атк, защ, строй in (("его пика без строя", 0, 0, 0), ("+ его атака-1 и защита-1 (к 8:00 в записи)", 1, 1, 0),
                                 ("его ОТРЯД на ходу (+2/+2)", 0, 0, 2), ("отряд на ходу + атака-1/защита-1", 1, 1, 2),
                                 ("его ОТРЯД СТОЯ (+7/+7)", 0, 0, 7)):
        он = max(1, его["atk"] + атк + строй - наш["dpike"])
        мы = max(1, наш["atk"] - (его["dpike"] + защ + строй))
        пуля = max(1, наш_м["atk"] - (его["dbullet"] + строй))
        уд_он, уд_мы = -(-наш["hp"] // он), -(-его["hp"] // мы)
        print(f"  {имя:44s} он нам {он}, мы ему {мы}: нам {уд_мы} ударов, ему {уд_он} — {'мы' if уд_мы < уд_он else 'он'} "
              f"сильнее в {max(уд_мы, уд_он) / min(уд_мы, уд_он):.2f} раза; наш мушкетёр ему {пуля} за выстрел")
    print("  (защита от прокачек пики у Польши, как у нас, к пуле не прибавляется — мушкетёр бьёт полной пулей; бонус строя — прибавляется)")
    print("\nЗЕРКАЛО: НАШ отряд против его пик без строя (его атака-1/защита-1 учтены)")
    for имя, строй in (("наш отряд на ходу (+2/+2)", 2), ("наш отряд СТОЯ (+7/+7)", 7)):
        он = max(1, его["atk"] + 1 - (наш["dpike"] + строй))
        мы = max(1, наш["atk"] + строй - (его["dpike"] + 1))
        уд_он, уд_мы = -(-наш["hp"] // он), -(-его["hp"] // мы)
        print(f"  {имя:44s} он нам {он}, мы ему {мы}: нам {уд_мы} ударов, ему {уд_он} — мы сильнее в {уд_он / уд_мы:.2f} раза")


if __name__ == "__main__":
    main()
