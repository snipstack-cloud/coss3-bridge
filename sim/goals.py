def ч(v):
    try:
        return float(v or 0)
    except (TypeError, ValueError):
        return 0.0


def _сетка(st, имя):
    if isinstance(st.get(имя), list):
        return SIM.сетка(st[имя])
    ряды = [st.get(f"{имя}{y}") for y in range(16)]
    return SIM.сетка([r for r in ряды if r is not None])


def ступени(снимки, такты, en_base, my_lost0=0.0, p1_lost0=0.0, p1_pea0=0.0):
    """Взятые ступени по последовательности снимков (5 с) и тактов (с сетками).

    `снимки`: словари с gametime, mil_inf, mil_far, my_mil_lost, p1_mil_lost,
    p1_pea_lost, p1_inf/shoot/cav, у_крестьян (список клеток [x,y,крестьян,наших]);
    `такты`: (gt, st) с сетками arow/prow. Для истории симулятора оба — одно и то же.
    """
    взято = set()
    пик_кр = 0.0
    for x in снимки:
        пик_кр = max(пик_кр, ч(x.get("p1_peasants")))
        if пик_кр >= 60 and 0 < ч(x.get("p1_peasants")) < 30 and ч(x["gametime"]) >= 420:
            взято.add(10)
    if any(ч(x.get("mil_inf")) >= 20 and ч(x["gametime"]) <= 300 for x in снимки):
        взято.add(1)
    if any(ч(x.get("mil_far")) >= 180 and ч(x["gametime"]) <= 480 for x in снимки):
        взято.add(2)
    # удар: убыль его крестьян в шагах, где наши стоят в их клетках (голод не считать)
    убито = 0.0
    for a, b in zip(снимки, снимки[1:]):
        if a.get("у_крестьян"):
            убито += max(0.0, ч(b.get("p1_pea_lost")) - ч(a.get("p1_pea_lost")))
    if убито >= 10:
        взято.add(3)
    посл = снимки[-1]
    потери = ч(посл.get("my_mil_lost")) - my_lost0
    # РАЗМЕН СЧИТАЕТСЯ ПО НАШИМ УБИЙСТВАМ, а не по его счётчику: `p1_mil_lost` в
    # записи растёт сам (ярус 1 «набирает» 48 его потерь, не убив никого).
    его = ч(посл.get("мы_убили_бойцов"))
    if его <= 0:
        его = ч(посл.get("p1_mil_lost")) - p1_lost0   # старые записи без поля
    if потери > 0 and его >= 0.5 * потери:
        взято.add(4)
    # ПОТОК: убито его бойцов после 7:00 не меньше 30 И его армия к концу не
    # больше, чем была на 7:00 — то есть мы бьём не медленнее, чем он нанимает.
    # Число 30 — от замера 27.09: сети дают 25 убитых бойцов в медиане, ярус 1
    # ноль, значит порог чуть выше достигнутого и политике принадлежит целиком.
    _на420 = next((x for x in снимки if ч(x["gametime"]) >= 420), None)
    if _на420 is not None:
        # ПОТОК — по НАШИМ убийствам после 7:00. Второе условие («его армия не
        # выросла») снято: враг в симуляторе это запись, и его найм по ней же —
        # армия растёт с 12 до 180 в КАЖДОЙ партии, условие недостижимо по
        # построению. Порог 25 взят по замеру 27.09: сети дают 25 убитых бойцов
        # за партию в медиане, ярус 1 — ноль.
        _наши_после = ч(посл.get("мы_убили_бойцов")) - ч(_на420.get("мы_убили_бойцов"))
        if _наши_после >= 25:
            взято.add(5)
    подряд = 0
    for gt, st in такты:
        if gt < 420:
            continue
        # такт без сетки крестьян — не «ноль крестьян», а нет данных: пропускаем
        сырой = st.get("prow") if isinstance(st.get("prow"), list) else [st.get(f"prow{y}") for y in range(16)]
        if not сырой or all(not r for r in сырой):
            continue
        P = _сетка(st, "prow")
        A = _сетка(st, "arow")
        кр = SIM.сумма(P)
        у = sum(v for y, r in enumerate(A) for x, v in enumerate(r) if math.hypot(x - en_base[0], y - en_base[1]) <= 2)
        армия = ч(st.get("p1_inf")) + ч(st.get("p1_shoot")) + ч(st.get("p1_cav"))
        if у > 50:
            взято.add(6)
        if кр < 20:
            взято.add(7)
        # ступень 10: общий счётчик его крестьян (не сетка снаружи). ВАЖНО: сначала
        # он должен ВЫРАСТИ до 60, иначе ступень брал бы любой ранний такт, когда у
        # него ещё 18 крестьян — так первая редакция дала 67 % вместо 2 %.
        усл = (армия < 10) + (кр < 10) + (у > 50)
        if усл >= 2:
            взято.add(8)
        подряд = подряд + 1 if усл == 3 else 0
        if подряд >= 2:
            взято.add(9)
    return взято


def прогресс(снимки, такты, en_base, my_lost0=0.0, p1_lost0=0.0) -> dict:
    """Доля пути к каждой ступени, 0..1 — для курса обучения: награда за
    приближение к ближайшей невзятой ступени, а не только за факт."""
    def кл(x):
        return max(0.0, min(1.0, x))
    п = {}
    п[1] = кл(max([ч(x.get("mil_inf")) for x in снимки if ч(x["gametime"]) <= 300] or [0]) / 20.0)
    п[2] = кл(max([ч(x.get("mil_far")) for x in снимки if ч(x["gametime"]) <= 480] or [0]) / 180.0)
    убито = 0.0
    for a, b in zip(снимки, снимки[1:]):
        if a.get("у_крестьян"):
            убито += max(0.0, ч(b.get("p1_pea_lost")) - ч(a.get("p1_pea_lost")))
    п[3] = кл(убито / 10.0)
    посл = снимки[-1]
    потери = ч(посл.get("my_mil_lost")) - my_lost0
    его = ч(посл.get("p1_mil_lost")) - p1_lost0
    п[4] = кл(его / (0.5 * потери)) if потери > 0 else 0.0
    армии = [ч(x.get("p1_inf")) + ч(x.get("p1_shoot")) + ч(x.get("p1_cav")) for x in снимки if ч(x["gametime"]) >= 420]
    п[5] = кл((30.0 - min(армии)) / 20.0) if армии else 0.0
    кр_счёт = [ч(x.get("p1_peasants")) for x in снимки
               if ч(x["gametime"]) >= 420 and ч(x.get("p1_peasants")) > 0]
    пик = max([ч(x.get("p1_peasants")) for x in снимки] or [0.0])
    if кр_счёт and пик >= 60:
        # от его пика до 30: доля пройденного пути
        п[10] = кл((пик - min(кр_счёт)) / max(пик - 30.0, 1.0))
    else:
        п[10] = 0.0
    у_макс = 0.0
    кр_мин = None
    усл_макс = 0
    подряд = подряд_макс = 0
    for gt, st in такты:
        if gt < 420:
            continue
        сырой = st.get("prow") if isinstance(st.get("prow"), list) else [st.get(f"prow{y}") for y in range(16)]
        if not сырой or all(not r for r in сырой):
            continue
        P = _сетка(st, "prow")
        A = _сетка(st, "arow")
        кр = SIM.сумма(P)
        у = sum(v for y, r in enumerate(A) for x, v in enumerate(r) if math.hypot(x - en_base[0], y - en_base[1]) <= 2)
        армия = ч(st.get("p1_inf")) + ч(st.get("p1_shoot")) + ч(st.get("p1_cav"))
        у_макс = max(у_макс, у)
        кр_мин = кр if кр_мин is None else min(кр_мин, кр)
        # ступень 10: общий счётчик его крестьян (не сетка снаружи). ВАЖНО: сначала
        # он должен ВЫРАСТИ до 60, иначе ступень брал бы любой ранний такт, когда у
        # него ещё 18 крестьян — так первая редакция дала 67 % вместо 2 %.
        усл = (армия < 10) + (кр < 10) + (у > 50)
        усл_макс = max(усл_макс, усл)
        подряд = подряд + 1 if усл == 3 else 0
        подряд_макс = max(подряд_макс, подряд)
    п[6] = кл(у_макс / 50.0)
    п[7] = кл((40.0 - кр_мин) / 20.0) if кр_мин is not None else 0.0
    п[8] = кл(усл_макс / 2.0)
    п[9] = кл(подряд_макс / 6.0)
    return п


def по_записи(каталог):
    з = SIM.Запись(каталог)
    if len(з.снапы) < 20:
        return None
    return ступени(з.снапы, [(gt, st) for gt, st, _ in з.такты], з.en_base,
                   ч(з.снапы[0].get("my_mil_lost")), ч(з.снапы[0].get("p1_mil_lost")), ч(з.снапы[0].get("p1_pea_lost")))


def по_истории(история, en_base):
    """Для симулятора: история состояний раз в 5 с (у_крестьян нет — считаем по сеткам)."""
    сн = []
    for s in история:
        x = dict(s)
        P = _сетка(s, "prow")
        A = _сетка(s, "arow")
        x["у_крестьян"] = [(xx, yy, P[yy][xx], A[yy][xx]) for yy in range(min(len(P), len(A)))
                           for xx in range(min(len(P[yy]), len(A[yy]))) if P[yy][xx] and A[yy][xx]]
        сн.append(x)
    return ступени(сн, [(ч(s["gametime"]), s) for s in история], en_base)


def доля_у_крестьян(история) -> float:
    """Доля тактов после 300 с, когда хоть один наш боец стоит в клетке с его
    крестьянами, — «дошли ли до крестьян» (по сеткам arow/prow истории)."""
    n = у = 0
    for s in история:
        if ч(s.get("gametime")) < 300:
            continue
        n += 1
        P = _сетка(s, "prow")
        A = _сетка(s, "arow")
        if any(P[yy][xx] and A[yy][xx] for yy in range(min(len(P), len(A))) for xx in range(min(len(P[yy]), len(A[yy])))):
            у += 1
    return у / n if n else 0.0


def курс(история, en_base) -> tuple[set, dict]:
    """Для награды обучения: взятые ступени и прогресс по всем — по истории симулятора."""
    сн = []
    for s in история:
        x = dict(s)
        P = _сетка(s, "prow")
        A = _сетка(s, "arow")
        x["у_крестьян"] = [(xx, yy, P[yy][xx], A[yy][xx]) for yy in range(min(len(P), len(A)))
                           for xx in range(min(len(P[yy]), len(A[yy]))) if P[yy][xx] and A[yy][xx]]
        сн.append(x)
    такты = [(ч(s["gametime"]), s) for s in история]
    return ступени(сн, такты, en_base), прогресс(сн, такты, en_base)


def лестница(наборы: dict):
    """Печать: доля партий с каждой ступенью для каждого набора (имя -> список множеств)."""
    имена = list(наборы)
    print("%-16s %-44s" % ("ступень", "что") + "".join("%12s" % и[:12] for и in имена))
    for i, (имя, что) in enumerate(СТУПЕНИ, 1):
        print("%-16s %-44s" % (имя, что) + "".join("%11.0f%%" % (100 * sum(1 for s in наборы[и] if i in s) / max(len(наборы[и]), 1)) for и in имена))


