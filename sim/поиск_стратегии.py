def _ступень_по_ценности_impl(self, st, взято, t):
    """§110: ступень казармы — лучшая по оценщику `прокачки.py` (тот же, что промпт и `--auto-upgrade` моста):
    матрица против каждого его рода, вес по урону, три состава, время исследования, цена. Ключи файла стратегии:
    `прокачка: "ценность"` (включить; без него — расписание, baseline), `прокачка_с` (с какой секунды, 300),
    `ценность_мин` (порог оценки в бойцах-эквивалентах, 1,0), `ценность_еда` (еда после покупки, 800),
    `ценность_цена` (покупать при оценке ≥ доля × цены в бойцах найма, 0,5)."""
    п = self.п
    if t < float(п.get("прокачка_с", 300) or 0):
        return None
    if not st.get("upg_avail"):
        return None
    import прокачки
    оц = прокачки.оценить(st, еда_после=float(п.get("ценность_еда", 800) or 0))
    # §123: до `ступень_до_с` — не выше `ступень_до` в линейке (игрок качается так, что армия растёт: дорогие верхние
    # ступени, 1.5 за 16 030 еды = 640 пикинёров, останавливали найм в двойнике после 8:00)
    if п.get("ступень_до") and t < float(п.get("ступень_до_с", 600) or 0):
        _n = int(п["ступень_до"])
        оц = dict(оц, кандидаты=[к for к in оц["кандидаты"] if not str(к["имя"]).startswith("bar.") or int(str(к["имя"]).rsplit(".", 1)[1]) <= _n])
    # §123: линейки только своего основного рода (не меньше `ступень_род_доля` армии): ступень мушкетёра при 6 мушкетёрах
    # из 60 — деньги мимо силы
    if п.get("ступень_род_доля"):
        _пик, _стр = float(st.get("mil_inf") or 0), float(st.get("mil_shooters") or 0)
        _вс = max(1.0, _пик + _стр)
        _доля = float(п["ступень_род_доля"])
        _можно = {"pikeman": _пик / _вс >= _доля, "musketeernet": _стр / _вс >= _доля}
        оц = dict(оц, кандидаты=[к for к in оц["кандидаты"] if not str(к["имя"]).startswith("bar.")
                                 or _можно.get(str(к["имя"]).split(".")[1], True)])
    # §128: при еде ≥ `цена_снята_при` порог цены снимается — лежащая сверх двух казарм еда идёт в дорогие ступени своего рода
    # (третья казарма стоит 2500 дерева, 2500 камня и 12 500 золота — найм упирается в две, у игрока тоже две)
    _доля = float(п.get("ценность_цена", прокачки.ДОЛЯ_ЦЕНЫ) or 0)
    if п.get("цена_снята_при") and float(st.get("food") or 0) >= float(п["цена_снята_при"]):
        _доля = 0.0
    к = прокачки.выбрать(оц, float(п.get("ценность_мин", 1.0) or 0), _доля)
    if к is None or к["имя"] in взято:
        return None
    return к["имя"]


