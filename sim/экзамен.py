def _ступени(коды, линейка):
    коды = [c for c in коды if c]
    return (sum(1 for c in коды if c.startswith(f"bar.{линейка}.1.")), sum(1 for c in коды if c.startswith(f"bar.{линейка}.2.")))


def _состав(d):
    п, м, к = round(d.get("infantry17", 0) or d.get("пик", 0)), round(d.get("musk17", 0) or d.get("стрелков", 0)), round(d.get("dragoon17", 0) or d.get("конных", 0))
    ч = [f"{п} пикинёров" if п else "", f"{м} мушкетёров" if м else "", f"{к} конных" if к else ""]
    return ", ".join(x for x in ч if x) or "никого"


def _мин(t):
    return f"{int(t) // 60}:{int(t) % 60:02d}"


