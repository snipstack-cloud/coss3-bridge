def спросить_fable(текст, таймаут=300):
    """Ответ чистой Fable: пустая папка, без настроек, памяти и инструментов."""
    global _ПУСТАЯ
    if _ПУСТАЯ is None:
        _ПУСТАЯ = tempfile.mkdtemp(prefix="coss3_экзамен_")
    t0 = time.time()
    # `encoding` ОБЯЗАТЕЛЕН: без него `text=True` берёт кодировку системы, и на
    # Windows (cp1251/cp866) ответ про клетки и пикинёров падает на кириллице.
    # Сторож `selftest_encoding.py` ловит это во всём репозитории — он и поймал.
    р = subprocess.run(["claude", "-p", "--model", FABLE, "--setting-sources", "", "--tools", ""], input=текст,
                       capture_output=True, text=True, encoding="utf-8", errors="replace",
                       cwd=_ПУСТАЯ, timeout=таймаут)
    return (р.stdout or р.stderr).strip(), time.time() - t0


def спросить_ollama(текст, модель, таймаут=600):
    t0 = time.time()
    тело = json.dumps(dict(model=модель, prompt=текст, stream=False, options=dict(temperature=0.7))).encode()
    з = urllib.request.Request(OLLAMA + "/api/generate", data=тело, headers={"Content-Type": "application/json"})
    with urllib.request.urlopen(з, timeout=таймаут) as r:
        о = json.loads(r.read())
    ответ = re.sub(r"<think>.*?</think>", "", о.get("response") or "", flags=re.S).strip()
    return ответ, time.time() - t0


def спросить(модель, текст):
    модель = модель.removesuffix("+п")         # «+п» — тот же вопрос с прогнозом боя в тексте вариантов
    return спросить_fable(текст) if модель == "fable" else спросить_ollama(текст, модель)


def разобрать(ответ, буквы=БУКВЫ):
    """(буква или None, почему) — первая строка с буквой варианта; «**А** — …» тоже."""
    for стр in ответ.splitlines():
        с = стр.strip().lstrip("*(# ").strip()
        if not с:
            continue
        м = re.match(r"^([" + буквы + r"])(?![а-яё])", с)
        if м:
            почему = с[1:].strip(" *)—-.:")
            if not почему:
                ост = [x.strip() for x in ответ.splitlines() if x.strip()]
                почему = ост[ост.index(стр.strip()) + 1] if стр.strip() in ост and ост.index(стр.strip()) + 1 < len(ост) else ""
            return м.group(1), почему
        break
    return None, ответ[:200]


def опрос(задания, потоков=4):
    """[(ключ, модель, текст)] → {ключ: [(модель, буква, почему, сек, сырой)]}. Fable параллельно, ollama по одному."""
    из = defaultdict(list)

    def одно(з):
        ключ, модель, текст = з
        try:
            ответ, сек = спросить(модель, текст)
        except Exception as e:
            ответ, сек = f"ОШИБКА {type(e).__name__}: {e}", 0.0
        б, почему = разобрать(ответ)
        return ключ, (модель, б, почему, round(сек, 1), ответ)

    fable = [з for з in задания if з[1].removesuffix("+п") == "fable"]
    прочие = [з for з in задания if з[1].removesuffix("+п") != "fable"]
    with ThreadPoolExecutor(потоков) as пул:
        будущие = [пул.submit(одно, з) for з in fable]
        for з in прочие:                   # локальная модель одна на машину — по очереди, пока Fable думает в облаке
            к, р = одно(з)
            из[к].append(р)
            print(f"  {к} {р[0]}: {р[1]} ({р[3]} с)", flush=True)
        for б in будущие:
            к, р = б.result()
            из[к].append(р)
            print(f"  {к} {р[0]}: {р[1]} ({р[3]} с)", flush=True)
    return из


