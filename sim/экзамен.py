def прогнозы(st, сим, я, своб, дом, сырые=False):
    """{решение: строка} — прогноз боя `прогноз.py` (тот же, что у моста в правиле «ручеёк») для вариантов с боем."""
    import combat_math as CM
    import прогноз as ПР
    import прокачки as ПК
    свои, чужие = CM.разобрать(st.get("fighters") or ""), ПК._чужие_со_строем(st)
    if not свои or not чужие:
        return {}
    его_кл = [c for c in (st.get("ecells") or []) if c.get("n", 0) >= 1]
    д0 = сим.группы[0]["состав"]
    n0 = sum(д0.values())
    дом_своб = {р: (д0.get(р, 0) * своб / n0 if n0 else 0.0) for р in ПР.РОДА}
    поле = [г for г in сим.группы[1:] if sum(г["состав"].values()) >= 1]
    def сумма(*сс):
        return {р: sum(float(с.get(р, 0) or 0) for с in сс) for р in ПР.РОДА}
    def строка(п):
        if п.get("R") is None:
            return "боя не предвидится"
        return (f"R={п['R']:.2f}, наши потери ~{sum(п['наши_потери'].values()):.0f} из {п['наших_всего']:.0f}, "
                f"его ~{sum(п['его_потери'].values()):.0f} из {п['его_всего']:.0f}" + (", его группа уничтожена" if п.get("уничтожена") else ""))
    eb = st.get("en_base") or [13, 13]

    def по_приходу(ц, его, у_базы):
        """§116б: обе стороны вступают по времени прихода. Наши: каждая полевая группа и свободные из дома — через путь
        до клетки цели (соседняя клетка — сразу). Его: кучи в ≤ 1 клетке — сразу, в 2–`ПОДХОД_ЕГО` клетках — через путь
        (при `ПОДХОД_ЕГО` 1 — прежний прогноз: только куча у цели, ручеёк наших учитывается)."""
        наши = [(ПР.сек_пути(max(0, max(abs(round(г["x"]) - ц[0]), abs(round(г["y"]) - ц[1])) - 1)), г["состав"]) for г in поле]
        if sum(дом_своб.values()) >= 1:
            наши.append((ПР.сек_пути(max(0, max(abs(дом[0] - ц[0]), abs(дом[1] - ц[1])) - 1)), дом_своб))
        наши = [(т, с) for т, с in наши if sum(с.values()) >= 1]
        if not наши:
            return None
        его_ф = []
        for c in его_кл:
            д = max(abs(c["x"] - ц[0]), abs(c["y"] - ц[1]))
            if д <= ПОДХОД_ЕГО:
                его_ф.append((ПР.сек_пути(max(0, д - 1)), ПР.состав_из_клеток([c])))
        if not его_ф:
            return None
        п = ПР.бой_по_приходу(наши, его_ф, свои, чужие, у_его_базы=у_базы)
        п0 = min(т for т, _ in наши)
        позже = [(т, с) for т, с in наши if т > п0 + ПР.СЕК_НА_КЛЕТКУ]
        if позже:
            п.update(случай="подмога", прибытие_с=round(max(т for т, _ in позже) - п0),
                     передних=sum(sum(с.values()) for т, с in наши if т <= п0 + ПР.СЕК_НА_КЛЕТКУ))
        п["его_подходят"] = sum(sum(с.values()) for т, с in его_ф if т > 0)
        return п

    def строка_п(п):
        if сырые:
            return п
        с = строка(п)
        if п and п.get("случай") == "подмога":
            с += f"; передние {п['передних']:.0f} бьются одни {п['прибытие_с']} с до подхода остальных"
        if п and п.get("его_подходят"):
            с += f"; учтён подход его {п['его_подходят']:.0f} из соседних клеток"
        return с
    из = {}
    if я.ближ_клетка:
        ц = tuple(я.ближ_клетка)
        его = ПР.состав_из_клеток(его_кл, ц, 1)
        у_базы = max(abs(ц[0] - eb[0]), abs(ц[1] - eb[1])) <= 2
        if sum(его.values()) >= 1:
            п = по_приходу(ц, его, у_базы)
            if п:
                из["на_ближайшую"] = из["пики_вперёд"] = строка_п(п)
            if я.встреча:
                п = по_приходу(tuple(я.встреча), его, False)
                if п:
                    из["встретить"] = строка_п(п)
    if его_кл and своб >= 1:
        к = max(его_кл, key=lambda c: c["n"])
        его = ПР.состав_из_клеток(его_кл, (к["x"], к["y"]), 1)
        из["удар_армия"] = строка(ПР.новая_волна(дом_своб, его, свои, чужие, max(abs(к["x"] - eb[0]), abs(к["y"] - eb[1])) <= 2))
    if поле and своб >= 1:
        г = max(поле, key=lambda г: sum(г["состав"].values()))
        гк = (round(г["x"]), round(г["y"]))
        его = ПР.состав_из_клеток(его_кл, гк, 1)
        if sum(его.values()) >= 1:
            из["подмога"] = строка(ПР.подмога(дом_своб, г["состав"], его, свои, чужие,
                                             ПР.сек_пути(max(abs(гк[0] - дом[0]), abs(гк[1] - дом[1])))))
    return из


def не_пусто(кейс, решение, seed=300, тактов=3):
    """§116в: исполняется ли решение ПО ДЕЛУ — сдвинул ли его приказ хоть одну группу (цель, режим, новая группа,
    накопление) за первые такты, сравнительно с «ничего». Маска §111 считает волной кучу дальше 1,5 клетки от
    ратуши, а исполнитель (ENGAGE/RETREAT, как мост §74) двигает только бойцов дальше 60 единиц (`ПОЛЕ_КЛЕТОК`):
    группа в 1,5–3,75 клетки — ни волна, ни свободные, приказ пуст (p5 10:28: 63 бойца стоят под огнём 200 с)."""
    import развилка as R
    import кейсы as КС
    import numpy as np

    def след(р):
        сим, _ = R.построить(кейс["запись"], float(кейс["t"]), кейс["агент"], seed)
        к, _ = КС._контроллер(f"скрипт:{р}", КС._хоз(), seed, сим.t, np.zeros(1))
        for _ in range(тактов):
            сим.команды(к(сим.состояние()) or [])
            сим.такт()
        гр = {(г.get("id") if г.get("id") is not None else -1): (str(г.get("цель")), г.get("режим"), sum(г["состав"].values()))
              for г in сим.группы if sum(г["состав"].values()) >= 1}
        return гр, str(getattr(сим, "накопление", None)), sum(sum(г["состав"].values()) for г in сим.группы)
    try:
        (г1, н1, всего), (г0, н0, _) = след(решение), след("ничего")
        if н1 != н0:
            return True
        сдвинуто = sum(v[2] for i, v in г1.items() if i not in г0 or (v[0], v[1]) != (г0[i][0], г0[i][1]))
        return сдвинуто >= max(5.0, 0.25 * всего)
    except Exception:
        return True


