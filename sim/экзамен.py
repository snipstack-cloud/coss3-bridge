def выбрать_кейсы(n, типы, источник, seed):
    кк = json.load(open(os.path.join(К, "кейсы", "кейсы.json"), encoding="utf-8"))
    if типы:
        кк = [k for k in кк if k["тип"] in типы]
    if источник != "все":
        кк = [k for k in кк if k["источник"] == источник]
    rng = random.Random(seed)
    по = defaultdict(list)
    for k in кк:
        по[k["тип"]].append(k)
    на = max(1, n // max(1, len(по)))
    из = [k for t in sorted(по) for k in rng.sample(по[t], min(на, len(по[t])))]
    return из[:n] if len(из) > n else из


