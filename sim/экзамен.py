def отчёт(строки, модели):
    def ср(v):
        v = [x for x in v if x is not None]
        return (St.mean(v), len(v)) if v else (None, 0)

    def ф(x):
        return "—" if x is None else f"{x:+.1f}"
    print("\nПО ТИПАМ (мера типа на зёрнах оценки; «≥ клона+3» — доля кейсов, где выбор модели выше клона больше шума):")
    колонки = ["клон", "учитель", "домой", "потолок"] + модели
    print(f"  {'тип':13} {'кейсов':>6} " + " ".join(f"{c[:14]:>14}" for c in колонки) + "   " + " ".join(f"{м[:10]:>10} совп/≥клона+3" for м in модели))
    типы = sorted({с["тип"] for с in строки}) + ["ВСЕ"]
    for тип in типы:
        сс = [с for с in строки if тип == "ВСЕ" or с["тип"] == тип]
        знач = [ср([с["клон"] for с in сс])[0], ср([с["учитель"] for с in сс])[0], ср([с["мера"].get("домой") for с in сс])[0],
                ср([с["потолок"] for с in сс])[0]]
        доли = []
        for мод in модели:
            v, совп, выше, всего = [], 0, 0, 0
            for с in сс:
                for о in с["ответы"].get(мод, []):
                    if о["решение"] is None:
                        continue
                    x = с["мера"].get(о["решение"])
                    v.append(x)
                    всего += 1
                    совп += о["решение"] == с["лучший"]
                    выше += x is not None and с["клон"] is not None and x > с["клон"] + 3
            знач.append(ср(v)[0])
            доли.append(f"{совп}/{выше} из {всего}")
        print(f"  {тип:13} {len(сс):6d} " + " ".join(f"{ф(x):>14}" for x in знач) + "   " + " ".join(f"{д:>24}" for д in доли))
    for мод in модели:
        ч = defaultdict(int)
        for с in строки:
            for о in с["ответы"].get(мод, []):
                ч[о["решение"]] += 1
        print(f"  {мод} выбирает: " + ", ".join(f"{р} {n}" for р, n in sorted(ч.items(), key=lambda kv: -kv[1])))


