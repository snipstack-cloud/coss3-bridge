def экзамен_вопроса(путь, модели, раз):
    текст = open(путь, encoding="utf-8").read()
    имя = os.path.basename(путь).replace("_вопрос.txt", "")
    отв = опрос([(имя, м, текст) for м in модели for _ in range(раз)])[имя]
    print(f"\n| кто | ответы | почему (первый) |\n|---|---|---|")
    for м in модели:
        оо = [о for о in отв if о[0] == м]
        print(f"| {м} | {', '.join(о[1] or '?' for о in оо)} | {оо[0][2] if оо else ''} |")
    os.makedirs(ПАПКА, exist_ok=True)
    json.dump([dict(модель=о[0], буква=о[1], почему=о[2], сек=о[3], сырой=о[4]) for о in отв],
              open(os.path.join(ПАПКА, f"{имя}.json"), "w", encoding="utf-8"), ensure_ascii=False, indent=1)


