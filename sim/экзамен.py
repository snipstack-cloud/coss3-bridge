def сверка_прогноза(путь):
    """§116б: знак прогноза удара «на ближайшую» (R > 1) против двойника (мера удара > мера «домой» на всех зёрнах оценки)
    на кейсах готового экзамена — без вызовов моделей; подход его куч 1 (прежний) и 3 клетки."""
