#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""СЛУЧАЙНЫЙ ПРОТИВНИК (2.10, §55): каждая партия обучения — новый розыгрыш врага.

Зачем. Сеть тактика (§41-44) и поиск стратегии (§49) учились против двух-трёх ФИКСИРОВАННЫХ
противников: агент «родной», агент «одни мушкетёры», две-три записи живого игрока. Итог —
сеть выучила почти открытую петлю («каждые 15 с всех на армию», §41), а поиск подстроился под
конкретные записи. Урок SMACv2: противника надо разыгрывать заново в каждой партии обучения —
тогда политика вынуждена читать обстановку, а не запоминать расписание. На турнире будет
чужой бот, которого мы не видели (память игрока 28.09).

Розыгрыш — словарь параметров ОДНОЙ партии (`разыграть`), все диапазоны — [допущение],
подобраны так, чтобы накрыть всё, что видели в записях и в стилях `враг.СТИЛИ`:
  доля_мушкетёров 0-1   состав его армии: p мушкетёров, остальные пикинёры (`sim.СОСТАВ_ВРАГА`
                        = ("доля", p)); родной ИИ — 0, игрок 2.10 — 1, «половина» — 0,5
  погоня 0-9, во_сколько 1,0-4,0   погоня агента (§43, §62): радиус и во сколько раз больше нашей
                        группы идёт за ней; 0 — не гонится (родной по записям)
  дистанция 0-0,8       доля его стрелков, уходящих из нашей клетки в соседнюю (§53; 0,4 подобрано
                        по проверке 2)
  вступает 0-2          радиус, с которого его бойцы идут в клетку нашей группы (§29)
  отход 0-0,6           при своём перевесе ниже этого отходит к базе (§29, «осторожный» 0,5)
  сила 0,3-1            доля соседних бойцов, втягиваемых за такт (§31)
  найм 0,6-1,6          множитель его восполнения из записи (`sim.НАЙМ_ВРАГА_МНОЖ`): размер армии
  запись                партия-основа (его форма `frow`, найм, крестьяне): из корпуса или игрока
Профиль боя — всегда обычный с залпами: профиль «игрок» (залпы сняты) против стрелков неверен
(§52). На_стрелков — 0 всегда (родной по записям 28.09 на стрелков не бросается).

Применение — `применить(п)` в процессе пула, до `sim.партия`, через те же глобалы, что
`тактик._настроить`. Отложенный набор — 100 розыгрышей зерна 7 на ОТЛОЖЕННЫХ записях корпуса
(`train.разбить`) и записях игрока: `python3 sim/случайный_враг.py --тест` → `случайный_тест.json`.
"""
import json
import os
import sys

К = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, К)
ТЕСТ = os.path.join(К, "случайный_тест3.json")   # §62: новые диапазоны погони; прежний — случайный_тест.json
# имя, нижняя, верхняя, целое
ДИАПАЗОНЫ = (("доля_мушкетёров", 0.0, 1.0, False), ("погоня", 0, 9, True), ("во_сколько", 1.0, 4.0, False),   # §62: шире — замер игрока 6-9 кл., 3-6×
             ("дистанция", 0.0, 0.8, False), ("вступает", 0, 2, True), ("отход", 0.0, 0.6, False),
             ("сила", 0.3, 1.0, False), ("найм", 0.6, 1.6, False),
             # §67: расстановка по параметрам (с вероятностью `расст` — иначе форма записи). Игрок 2.10:
             # главная куча 60-84 %, в 3,5-7 клетках от своей базы, вторая рядом
             ("расст", 0.0, 1.0, False), ("выдвижение", 0, 8, True), ("выход", 120, 600, False),
             ("доля_главная", 0.5, 1.0, False), ("вторая", 0, 2, True), ("порог_отхода", 1.2, 5.0, False),
             ("атака_с", 360, 1300, False), ("доля_атаки", 0.3, 1.0, False))
ДОЛЯ_РАССТАНОВКИ = 0.7   # в такой доле розыгрышей расстановка по параметрам, в остальных — запись


def разыграть(rng, записи=None):
    """Параметры одного противника; `rng` — numpy Generator (зерно задания). `записи` — из чего
    выбрать партию-основу; без них ключа «запись» нет (её даёт задание)."""
    п = {}
    for имя, lo, hi, цел in ДИАПАЗОНЫ:
        п[имя] = int(rng.integers(lo, hi + 1)) if цел else round(float(rng.uniform(lo, hi)), 4)
    if записи:
        п["запись"] = записи[int(rng.integers(len(записи)))]
    return п


def применить(п):
    """Поставить глобалы симулятора и профиль боя под розыгрыш `п` (в процессе пула, до партии)."""
    import sim as SIM
    import combat
    стиль = dict(вступает=int(п["вступает"]), на_стрелков=0, отход=float(п["отход"]), сила=float(п["сила"]),
                 погоня=int(п["погоня"]), во_сколько=float(п["во_сколько"]), дистанция=float(п["дистанция"]))
    if float(п.get("расст", 1.0)) < ДОЛЯ_РАССТАНОВКИ and "выдвижение" in п:
        # порог отхода от 4,5 — «не отходит никогда»; атака после 15:00 — «не атакует»
        стиль["расстановка"] = dict(выдвижение=int(п["выдвижение"]), выход=float(п["выход"]),
                                    доля_главная=float(п["доля_главная"]), вторая=int(п["вторая"]),
                                    порог_отхода=float(п["порог_отхода"]) if п["порог_отхода"] < 4.5 else 99.0,
                                    атака_с=float(п["атака_с"]), доля_атаки=float(п["доля_атаки"]))
    SIM.АГЕНТНЫЙ_ВРАГ, SIM.СТИЛЬ_ВРАГА, SIM.ВРАГ_СЛЕДУЕТ, SIM.ОБОРОНА_ДОМА = True, стиль, 6.0, 3
    SIM.СОСТАВ_ВРАГА = ("доля", float(п["доля_мушкетёров"]))
    SIM.НАЙМ_ВРАГА_МНОЖ = float(п["найм"])
    # профиль боя — обычный, с залпами (как `тактик._настроить` для всех, кроме «игрок»)
    combat.МЕНЬШИНСТВО_СТЕПЕНЬ, combat.МЕНЬШИНСТВО_ВЕЗДЕ, combat.МЕНЬШИНСТВО_СТОРОНЫ = 0.25, False, "обе"
    if hasattr(combat, "_залпы_исх"):
        combat.залпы = combat._залпы_исх


def описать(п):
    return (f"мушк {п['доля_мушкетёров']:.2f} погоня {п['погоня']}×{п['во_сколько']:.1f} дист {п['дистанция']:.2f} "
            f"вступ {п['вступает']} отход {п['отход']:.2f} сила {п['сила']:.2f} найм {п['найм']:.2f}")


def тест():
    """Отложенный набор: 100 розыгрышей (зерно 7) или уже сохранённый файл."""
    if os.path.exists(ТЕСТ):
        return json.load(open(ТЕСТ, encoding="utf-8"))["розыгрыши"]
    return None


def _сделать_тест(n=100, зерно=7):
    import glob
    import numpy as np
    sys.argv = [sys.argv[0], "--корпус", os.path.join(К, "корпус_27_09.txt")]
    import train as TR
    _, отложенные = TR.разбить(TR.партии([]))
    игрок = sorted(os.path.dirname(x) for x in glob.glob(os.path.expanduser("~/coss3-res-игрок/*/*/coss3_snap.jsonl")))
    записи = отложенные + игрок
    rng = np.random.default_rng(зерно)
    р = [разыграть(rng, записи) for _ in range(n)]
    json.dump({"зерно": зерно, "записей": len(записи), "отложенных_корпуса": len(отложенные), "игрока": len(игрок),
               "диапазоны": [list(x) for x in ДИАПАЗОНЫ], "розыгрыши": р},
              open(ТЕСТ, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    print(f"{n} розыгрышей зерна {зерно} на {len(записи)} записях ({len(отложенные)} отложенных корпуса + {len(игрок)} игрока) → {ТЕСТ}")
    for п in р[:5]:
        print("  ", описать(п), os.path.relpath(п["запись"], os.path.expanduser("~")))


if __name__ == "__main__":
    if "--тест" in sys.argv:
        _сделать_тест()
    else:
        import numpy as np
        print(описать(разыграть(np.random.default_rng(int(sys.argv[1]) if len(sys.argv) > 1 else 0))))
