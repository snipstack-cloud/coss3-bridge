sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import goals_score as GS   # noqa: E402

ч = lambda d, k: float((d or {}).get(k) or 0)
кл = lambda x: max(0.0, min(1.0, x))
СТУПЕНИ = (
    ("1 машина", "казарма и 15+ пехоты, её доля 50 %+"),
    ("2 две казармы", "2 казармы и найм пехоты 8+ в минуту"),
    ("3 отряды", "2+ отряда и удержание не меньше трети тактов"),
    ("4 технологии", "апгрейды взяты, защита не ниже 0,8 от атаки"),
    ("5 оборона", "его бойцы входят в нашу клетку, размен там 0,8+"),
    ("6 контратака", "после удержания убито 10+ его крестьян"),
)
ВЕСА = (1.0, 1.5, 1.5, 2.0, 1.5, 1.0)          # максимум 8,5 — как в замысле
ЦЕЛЬ_АПГРЕЙДОВ = 6                              # три казарменных плюс три aca.12-14


def числа(сим, история):
    посл = история[-1] if история else {}
    пехота = ч(посл, "mil_inf") + ч(посл, "mil_shooters")
    армия = пехота + ч(посл, "mil_cav")
    нанято = 0.0
    for a, b in zip(история, история[1:]):
        нанято += max(0.0, (ч(b, "mil_inf") + ч(b, "mil_shooters"))
                      - (ч(a, "mil_inf") + ч(a, "mil_shooters")))
    нанято += max(0.0, ч(посл, "my_mil_lost"))
    минут = max(ч(посл, "gametime") / 60.0, 1.0)
    взято = {x.strip() for x in str(посл.get("upg_done") or "").split(",") if x.strip()}
    ат = sum(1 for у in взято if у.startswith("bar.") and у.split(".")[2:3] == ["1"])
    защ = sum(1 for у in взято if у.startswith("bar.") and у.split(".")[2:3] == ["2"])
    ака = len(взято & {"aca.12", "aca.13", "aca.14"})
    # ОБОРОНА: бои в клетках не дальше пяти от НАШЕЙ базы
    eb = getattr(сим.з, "en_base", None) or (15, 15)
    mb = (getattr(сим.з, "my_cx", 0.0), getattr(сим.з, "my_cy", 0.0))
    наши_дома = его_дома = 0.0
    боёв_дома = 0
    for з in getattr(сим, "журнал_боя", []):
        t, cx, cy, режим, n, его_в, a, b = з[:8]
        if math.hypot(cx - mb[0], cy - mb[1]) <= 5 and math.hypot(cx - eb[0], cy - eb[1]) > 3:
            боёв_дома += 1
            наши_дома += a or 0.0
            его_дома += b or 0.0
    тактов = max(len(история), 1)
    return dict(
        казарм=ч(посл, "ba17"), пехота=пехота, армия=армия,
        доля=(пехота / армия) if армия > 0 else 0.0,
        темп=нанято / минут, отрядов=getattr(сим, "отряды_собрано", 0),
        удержание=getattr(сим, "тактов_удержания", 0) / тактов,
        апгрейдов=ат + защ + ака, атаки=ат, защиты=защ,
        боёв_дома=боёв_дома,
        размен_дома=(его_дома / наши_дома) if наши_дома > 0 else 0.0,
        убито_крестьян=getattr(сим, "убито_крестьян", 0.0),
        потери=ч(посл, "my_mil_lost"))


def ступени(сим, история):
    д = числа(сим, история)
    п = {}
    # 1. ВОЕННАЯ МАШИНА
    п[1] = кл((д["пехота"] - 5) / (15 - 5)) * (1.0 if д["казарм"] >= 1 else 0.0)
    if д["доля"] < 0.5:
        п[1] *= д["доля"] / 0.5
    # 2. ДВЕ КАЗАРМЫ И ПОТОК
    п[2] = (кл((д["казарм"] - 1) / 1.0) + кл((д["темп"] - 4) / (8 - 4))) / 2.0
    # 3. ОТРЯДЫ И УДЕРЖАНИЕ
    п[3] = (кл((д["отрядов"] - 1) / (3 - 1)) + кл((д["удержание"] - 0.10) / (0.33 - 0.10))) / 2.0
    # 4. ТЕХНОЛОГИИ
    доля_защ = (д["защиты"] / д["атаки"]) if д["атаки"] > 0 else (1.0 if д["защиты"] else 0.0)
    п[4] = (кл(д["апгрейдов"] / ЦЕЛЬ_АПГРЕЙДОВ) + кл(доля_защ / 0.8)) / 2.0
    # 5. ОБОРОНА
    п[5] = (кл(д["боёв_дома"] / 10.0) + кл((д["размен_дома"] - 0.5) / (1.2 - 0.5))) / 2.0
    # 6. КОНТРАТАКА
    п[6] = кл(д["убито_крестьян"] / 10.0) if д["удержание"] > 0 else 0.0
    взято = {i for i, v in п.items() if v >= 0.999}
    return взято, п, д


def r_steps(сим, история) -> float:
    _, п, _ = ступени(сим, история)
    return sum(ВЕСА[i - 1] * п.get(i, 0.0) for i in range(1, 7))


def награда(сим, история, этап=2) -> float:
    """Этап 1 — только воевать; 2 — плюс лестница; 3 — плюс очки как главное."""
    import train as TR
    бой = TR.награда_боя(сим, история)          # присутствие, темп, размен, плата
    # ШТРАФ ЗА ПЛОХУЮ ПОЛОСУ — во ВСЕХ этапах, а не только в награде по очкам
    # (28.09, по трём проверкам обученных сетей). Замер: 54-59 % наших потерь
    # понесено в клетках с перевесом ниже 0,75, где размен 0,13-0,19 по живым
    # записям. Сеть научилась приходить и бить, но не выбирать, КОГДА бить.
    if GS.ПОЛОСА:
        бой -= GS.ЦЕНА_ПЛОХОЙ_ПОЛОСЫ * GS.потери_в_плохой_полосе(сим)
    if этап == 1:
        return бой
    if этап == 2:
        return бой + r_steps(сим, история)
    # ЭТАП 3: очки главные — НО ТОЛЬКО ЕСЛИ БЫЛО СРАЖЕНИЕ. Это не ухищрение, а
    # буква правила хакатона: «если к 15-й минуте непонятно, кто победил, НО
    # АКТИВНЫЕ ДЕЙСТВИЯ БЫЛИ (сражение), победителя определяем по очкам». Без
    # этого условия проверка 28.09 дала ровно мою утреннюю ошибку: политика, не
    # воюющая вовсе, получала +6,04 против −3,62 у набега, то есть этап 3 снова
    # учил стоять дома.
    # УТОЧНЕНО 28.09 (правило судей): без атаки или активной защиты поражение
    # получают ОБА, и засчитывается только ВЫХОД АРМИИ К НЕМУ. Прежняя мерка —
    # любой наш боец в клетке с его крестьянами в 5 % тактов — пропускала и
    # разведчика, и стычку у наших шахт. Теперь вес очков растёт с пиком наших
    # бойцов у его базы и полный с порога похода (goals.ПОХОД_БОЙЦОВ).
    import goals as G
    пик = G.поход_к_нему(история, сим.з.en_base)
    очки = GS.награда(сим, история, GS.ГОРИЗОНТ_ТУРНИРА)
    вес_очков = 2.0 * min(1.0, пик / G.ПОХОД_БОЙЦОВ)
    return вес_очков * очки + 0.5 * r_steps(сим, история) + бой
