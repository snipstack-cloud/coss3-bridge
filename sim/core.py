def загрузить():
    п = json.load(open(os.path.join(ЗДЕСЬ, "параметры.json"), encoding="utf-8"))
    т = п["темпы_из_трасс"]
    return п, т


def разыграть_темпы(т, rng):
    """Вектор темпов добычи одной случайной записанной партии (без еды).

    Ворота 25.09: между партиями темпы дерева и камня различаются в разы — это
    расположение леса и залежей, параметр карты. Разыгрывается вектор целиком,
    чтобы сохранить связь между ресурсами одной карты.
    """
    векторы = т.get("розыгрыш_темпов_по_партиям") or []
    if not векторы:
        return {}
    return dict(векторы[rng.randrange(len(векторы))])


def значения(п, sid):
    for k, v in п["объекты"].items():
        if k == sid or sid in v["sids"]:
            return v["значения"]
    raise KeyError(sid)


class Экономика:
    def __init__(self, п, т, начальное: dict, вариант_еды: str = "чистая", задержка_доставки: float = 0.0,
                 темпы_партии: dict | None = None):
        """`вариант_еды`: «чистая» — темп еды уже за вычетом едоков (так он мерен),
        «валовая» — вычитать 0,10 на голову всегда (СПЕЦИФИКАЦИЯ §10.1)."""
        self.п, self.т = п, т
        self.вариант_еды = вариант_еды
        self.res = {r: float(начальное.get(r) or 0) for r in РЕСУРСЫ}
        self.peasants = float(начальное.get("peasants") or 0)
        self.армия = {"mil_inf": float(начальное.get("mil_inf") or 0),
                      "mil_shooters": float(начальное.get("mil_shooters") or 0),
                      "mil_cav": float(начальное.get("mil_cav") or 0)}
        self.здания = {поле: int(начальное.get(поле) or 0) for _, (_, поле) in ЗДАНИЯ.items()}
        self.дробь_найма = {k: 0.0 for k in НАЙМ}
        # Доставка: крестьянин носит добычу партиями, и в трассе ресурс растёт
        # СКАЧКАМИ через 30-40 с после назначения (base28/1: камень 20 при 8-12
        # на камне с 93 по 129 с, потом +240 разом). Ядро может держать добычу в
        # пути `задержка_доставки` секунд, прежде чем зачесть.
        self.задержка = задержка_доставки
        self.в_пути = []      # (когда зачесть, ресурс, сколько)
        self.журнал = []      # что и когда списано — для разбора расхождений
        # Балансовые темпы (ворота 25.09), если посчитаны; иначе пошаговые.
        бал = т.get("добыча_балансовая_на_крестьянина_в_сек") or {}
        self.темп = {r: (бал.get(r) or т["добыча_на_крестьянина_в_сек"][r])["медиана"] for r in РЕСУРСЫ}
        for k, v in (темпы_партии or {}).items():
            if k in self.темп:
                self.темп[k] = v
        if бал and вариант_еды == "чистая":
            # балансовый темп еды валовый — с ним расход вычитается всегда
            self.вариант_еды = "валовая"
        self.расход_еды = т.get("еда_расход_на_голову_в_сек_баланс") or т["еда_расход_на_голову_в_сек"]["медиана"]

    # --- покупки -------------------------------------------------------------
    def цена_здания(self, роль):
        sid, поле = ЗДАНИЯ[роль]
        з = значения(self.п, sid)
        cp = (з.get("costpercent") or 100) / 100.0
        n = self.здания[поле]
        return {r: round(float(_база_здания(sid, з).get(r, 0)) * (cp ** n)) for r in РЕСУРСЫ}

    def цена_здания_с_ожиданием(self, роль, ожидает: int):
        """Цена следующего здания роли, когда `ожидает` уже заложены, но не достроены."""
        sid, поле = ЗДАНИЯ[роль]
        з = значения(self.п, sid)
        cp = (з.get("costpercent") or 100) / 100.0
        n = self.здания[поле] + ожидает
        return {r: round(float(_база_здания(sid, з).get(r, 0)) * (cp ** n)) for r in РЕСУРСЫ}

    def списать(self, цена: dict, за_что: str, t: float):
        for r, v in цена.items():
            if v:
                self.res[r] -= v
        self.журнал.append((t, за_что, {r: v for r, v in цена.items() if v}))

    def заложить(self, роль, t):
        self.списать(self.цена_здания(роль), f"BUILD {роль}", t)
        self.здания[ЗДАНИЯ[роль][1]] += 1

    def цена_юнита(self, имя):
        н = _нация_юнит(имя)
        if н is not None:
            return {r: float(н["цена"].get(r, 0)) for r in РЕСУРСЫ}
        з = значения(self.п, НАЙМ[имя][0])
        return dict(з["price"])

    # --- такт --------------------------------------------------------------------
    def множитель_еды(self, апгрейды) -> float:
        return self.множитель("food", апгрейды)

    def множитель(self, r, апгрейды) -> float:
        таб = ЭФФЕКТ_РЕСУРСА.get(r) or {}
        return 1.0 + sum(таб.get(u, 0) for u in (апгрейды or ())) / 100.0

    def шаг(self, dt: float, t: float, работники: dict, заказы: dict, потери: dict, апгрейды=None):
        """`работники`: on_food..on_coal (+ food_ready); `заказы`: {имя: True} — что стоит в
        очереди; `потери`: {'mil_inf': k, 'peasants': k}; `апгрейды` — взятые имена."""
        # 1. добыча
        # §127: ГОТОВНОСТЬ ПОЛЯ — множителем ДО задержки. Прежде добыча еды уходила «в пути» на `задержка` с, а за
        # несозревшее поле та же добыча вычиталась СРАЗУ: еда утекала (12 на еде — 23 в секунду), упиралась в ноль,
        # найм стоял под порогом 500, а через 20 с отложенная добыча приходила разом (партия А: 870 → 291 еды к 2:00,
        # армия 5 к 3:00 при 12 живьём, и лишние 2000 еды к 4:00)
        готовность = работники.get("food_ready")
        доля_поля = 1.0 if готовность is None else max(0.0, min(1.0, float(готовность or 0)))
        for r in РЕСУРСЫ:
            k = self.множитель(r, апгрейды)
            добыто = self.темп[r] * k * float(работники.get("on_" + r) or 0) * dt * (доля_поля if r == "food" else 1.0)
            if self.задержка > 0:
                self.в_пути.append((t + self.задержка, r, добыто))
            else:
                self.res[r] += добыто
        if self.в_пути:
            остаток = []
            for когда, r, сколько in self.в_пути:
                if когда <= t + dt:
                    self.res[r] += сколько
                else:
                    остаток.append((когда, r, сколько))
            self.в_пути = остаток
        # поле: пока нет ни одного готового участка (первое поле зреет ~87 с после
        # мельницы, [замер] по 52 партиям), крестьяне на еде ничего не приносят
        # `food_ready` — ДОЛЯ полного сбора (0..1), а не признак: поле выходит на
        # полный выход не сразу (§16б, замер по 12 записям карты 256).
        # (вычитание за несозревшее поле снято §127: готовность — множитель добычи выше)
        # 2. еда
        едоки = self.peasants + sum(self.армия.values())
        if self.вариант_еды == "валовая":
            self.res["food"] -= self.расход_еды * едоки * dt
        elif not работники.get("on_food"):
            # темп мерен чистым только там, где еду добывали; без добытчиков едят как есть
            self.res["food"] -= self.расход_еды * едоки * dt
        # еда не уходит в минус: в игре при нуле производство просто стоит (порог 500),
        # а отрицательного запаса не бывает [27.09: сеть уводила всех с еды и копила
        # −4464, после чего найм стоял «по порогу», но ресурсы считались как есть]
        if self.res["food"] < 0:
            self.res["food"] = 0.0
        # 3. найм
        for имя, (sid, поле, ключ_темпа, здание) in НАЙМ.items():
            if not заказы.get(имя):
                self.дробь_найма[имя] = 0.0
                continue
            n_зд = self.здания.get(здание, 0)
            # ЗАПАС ЕДЫ под прокачку (29.09, §28): бойцы нанимаются только сверх него —
            # копить на ступень, не останавливая найм. Крестьян запас не касается.
            запас = getattr(self, "запас_найма", 0.0) if имя != "peaeng" else 0.0
            # §127 ДИСКРЕТНОСТЬ ДОСТАВКИ: живьём еда приходит порциями (крестьянин донёс груз) и на миг переходит порог, и
            # найм стартует — партия А 2:47–3:18: шесть пикинёров при 413–491 еды. Ровный поток двойника держал еду чуть
            # ниже 500 и не нанимал. Порог сравнивается с едой плюс доля уже добытой в пути (`ДОСТАВКА_В_ПОРОГ`).
            в_пути = sum(сколько for _, r, сколько in self.в_пути if r == "food") * ДОСТАВКА_В_ПОРОГ
            if n_зд <= 0 or self.res["food"] + в_пути < ПОРОГ_ЕДЫ + запас:
                continue
            # предел населения: производство стоит, пока не освободится место
            вместимость, занято = self.предел_населения()
            if занято >= вместимость:
                self.дробь_найма[имя] = min(self.дробь_найма[имя], 1.0)
                continue
            # здание делает по одному: несколько активных очередей на одном здании
            # делят его темп (26.09; иначе пикинёры и мушкетёры разом удваивали выпуск)
            очередей = sum(1 for и2, (_, _, _, зд2) in НАЙМ.items() if зд2 == здание and заказы.get(и2))
            темп = (self.т.get(ключ_темпа + "_баланс") or self.т[ключ_темпа])["медиана"] / 60.0 * n_зд * dt / max(1, очередей) \
                * множитель_найма(имя)
            self.дробь_найма[имя] += темп
            вышло = int(self.дробь_найма[имя])
            if вышло:
                цена = self.цена_юнита(имя)
                # без ресурсов на цену производство стоит (движок не выпускает в долг)
                хватает = int(min((self.res[r] // v) for r, v in цена.items() if v) if any(цена.values()) else вышло)
                вышло = max(0, min(вышло, хватает, int(вместимость - занято)))
                if not вышло:
                    self.дробь_найма[имя] = min(self.дробь_найма[имя], 1.0)
                    continue
                self.дробь_найма[имя] -= вышло
                for _ in range(вышло):
                    self.списать(цена, f"TRAIN {имя}", t)
                if поле == "peasants":
                    self.peasants += вышло
                else:
                    self.армия[поле] += вышло
        # 4. потери
        self.армия["mil_inf"] -= float(потери.get("mil_inf") or 0)
        self.peasants -= float(потери.get("peasants") or 0)

    def предел_населения(self):
        """Вместимость (`gPlayer.farm`) и занятое (`counter.farmused`)."""
        вместимость = sum(k * self.здания.get(поле, 0) for поле, k in ВМЕСТИМОСТЬ.items())
        занято = self.peasants + sum(self.армия.values())
        return вместимость, занято

    def снимок(self):
        из = {r: round(v) for r, v in self.res.items()}
        из["peasants"] = round(self.peasants)
        из.update({k: round(v) for k, v in self.армия.items()})
        из.update(self.здания)
        return из
