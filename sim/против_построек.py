#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""ФАЙЛЫ СТРАТЕГИИ ПРОТИВ ПОСТРОЕК ИГРОКА (2.11, слово игрока «проверить на симуляторе тактики против разных построек,
которые у меня были»).

Противник — запись живой партии игрока против бота (его постройка, хозяйство, армия по записи) с агентом повадок:
«д» (отряды, вход в нашу кучу при 0,9), «налётчик_о» (налёт туда, где нашей армии нет), «осада_о» (стрелки у нашей
ратуши). Двойник под нации (151): нация бота — по записи. Включены `COSS3_WAVE_CONTRACT=1` (правила волн, штурма,
отхода живого моста) и `COSS3_SIM_BUILD_COST=1` (живые цены построек). НЕ СУДИТСЯ: наш отряд как группа (двойник
держит долю «в строю»), реакция игрока на нашу тактику сверх агента повадок.

    python3 sim/против_построек.py файл.json [файл.json ...] [--зёрен 3] [--json итог.json]
"""
import glob
import json
import os
import statistics as St
import sys
from multiprocessing import Pool

os.environ.setdefault("COSS3_WAVE_CONTRACT", "1")
os.environ.setdefault("COSS3_SIM_BUILD_COST", "1")
К = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, К)
sys.path.insert(0, os.path.dirname(К))
import тактик as ТК  # noqa: E402

АГЕНТЫ = ("д", "налётчик_о", "осада_о")
НАЦИЯ_ФАЙЛОВ = "pol"


def записи():
    """Живые партии против игрока с частым снимком: Д18 и позже (28.10–1.11)."""
    из = []
    for п in sorted(glob.glob(os.path.expanduser("~/coss3-results/2026-1[01]-*/igrok_*/1/coss3_snap.jsonl"))):
        имя = п.split("/")[-3]
        # Д19–Д27 и польские 30.10–1.11; Д18 падает в двойнике (IndexError в снимке), «Д2» 10.10 — не эта эпоха
        # Польшей бот играл только с 31.10 (30.10 и Д19–Д27 — бот Нидерландами: польский файл на нидерландской пике
        # упирается в железо, армия к 15:00 — 0). Нация бота — `sim.нация_записи`; берём записи, где она совпадает
        # с нацией файла (`--нация`, по умолчанию pol)
        import sim as _SIM
        if имя.startswith("igrok_") and _SIM.нация_записи(os.path.dirname(п)) == НАЦИЯ_ФАЙЛОВ:
            из.append(os.path.dirname(п))
    return из


def _задача(a):
    файл, хоз, агент, d, seed = a
    try:
        м = ТК._партия(("без", хоз, хоз, агент, d, seed))
    except Exception as e:
        return dict(файл=файл, агент=агент, запись=d, ошибка=f"{type(e).__name__}: {e}")
    return dict(файл=файл, агент=агент, запись=d, убито=м["убито"], потери=м["потери"], уничтожена=bool(м["уничтожена"]),
                наша15=м["наша15"], его15=м["его15"], крест=м.get("наши_крест", 0))


def main():
    арг = sys.argv[1:]
    зёрен = int(арг[арг.index("--зёрен") + 1]) if "--зёрен" in арг else 3
    global НАЦИЯ_ФАЙЛОВ
    if "--нация" in арг:
        НАЦИЯ_ФАЙЛОВ = арг[арг.index("--нация") + 1]
    вых = арг[арг.index("--json") + 1] if "--json" in арг else None
    файлы = [a for i, a in enumerate(арг) if a.endswith(".json") and (i == 0 or арг[i - 1] != "--json")]
    зп = записи()
    print(f"записей {len(зп)}, файлов {len(файлы)}, агентов {len(АГЕНТЫ)}, зёрен {зёрен} → партий {len(зп) * len(файлы) * len(АГЕНТЫ) * зёрен}")
    задания = []
    for ф in файлы:
        хоз = json.load(open(ф, encoding="utf-8"))["итог"]
        for агент in АГЕНТЫ:
            for d in зп:
                for s in range(зёрен):
                    задания.append((os.path.basename(ф), хоз, агент, d, 200000 + s))
    # КАЖДАЯ ПАРТИЯ — В СВЕЖЕМ ПРОЦЕССЕ: глобалы двойника, агента врага и анализа переживали партию внутри рабочего
    # процесса (2.11: в пакете «наша армия к 15:00 — 0» и одинаковые числа у разных файлов; та же партия отдельно — 134)
    with Pool(maxtasksperchild=1) as пул:
        р = пул.map(_задача, задания, chunksize=1)
    ошибки = [x for x in р if "ошибка" in x]
    if ошибки:
        print(f"ОШИБОК {len(ошибки)}: {ошибки[0]['ошибка']} ({ошибки[0]['запись'].split('/')[-2]})")
    р = [x for x in р if "ошибка" not in x]

    def свод(x):
        if not x:
            return dict(n=0, размен=float("nan"), уничтожена=0, наша15=0, его15=0, крест=0)
        уб, пот = sum(y["убито"] for y in x), sum(y["потери"] for y in x)
        return dict(n=len(x), размен=round(уб / max(пот, 1), 2), уничтожена=sum(y["уничтожена"] for y in x),
                    наша15=St.median(y["наша15"] for y in x), его15=St.median(y["его15"] for y in x),
                    крест=St.median(y["крест"] for y in x))
    print("\nПО АГЕНТАМ")
    for агент in АГЕНТЫ:
        for ф in файлы:
            с = свод([y for y in р if y["агент"] == агент and y["файл"] == os.path.basename(ф)])
            print(f"  {агент:11} {os.path.basename(ф):40} размен {с['размен']:5.2f} | уничтожена {с['уничтожена']:3d}/{с['n']:<3d} "
                  f"| наша 15:00 {с['наша15']:4.0f} | его 15:00 {с['его15']:4.0f} | наших крестьян {с['крест']:3.0f}")
    print("\nПО ЗАПИСЯМ (все агенты): размен")
    for d in зп:
        стр = "  ".join(f"{свод([y for y in р if y['запись'] == d and y['файл'] == os.path.basename(ф)])['размен']:5.2f}" for ф in файлы)
        print(f"  {d.split('/')[-2][:44]:44} {стр}")
    if вых:
        json.dump(р, open(вых, "w", encoding="utf-8"), ensure_ascii=False, indent=0)


if __name__ == "__main__":
    main()
