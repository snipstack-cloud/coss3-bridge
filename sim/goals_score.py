# -*- coding: utf-8 -*-
"""Награда ПО ОЧКАМ ДВИЖКА к 15-й минуте — правило хакатона (28.09).

Решение игрока: «граница матча 15 минут», а победителя при неясном исходе
определяют по очкам экономики. Значит и учить надо ровно этому: разнице очков на
900-й игровой секунде, а партию в обучении останавливать ТАМ ЖЕ — иначе сеть
оптимизирует двадцатиминутную игру, которой в турнире не будет.

Правило счёта (world.md, `unit.script:3841, 3948`, `miscext2.script:445`): за
созданного очки растут, за потерянного падают, за убитого чужого дают ДВОЙНЫЕ его
очки; ЗАПАСЫ РЕСУРСОВ НЕ СЧИТАЮТСЯ. Отсюда:

    наш  = живое(наше) + 2 * (убито его бойцов * цена + убито его крестьян * 20)
    его  = живое(его)  + 2 * (наших бойцов погибло * цена + наших крестьян * 20)

ПОЧЕМУ ЭТО И ЕСТЬ «ВЫИГРАТЬ АРМИЕЙ»: убитый его боец даёт нам вдвое и снимает с
него единожды — тройной сдвиг счёта; а наш потерянный даёт ему вдвое, поэтому
награда сама запрещает самоубийственные волны, за которые платил «темп убийств».

Очки: ратуша 1000, казарма 500, академия 500, дом 100, крестьянин 20, пикинёр 10,
мушкетёр 20, драгун 50. Цены мельницы, кузницы, склада и шахт НЕ ИЗМЕРЕНЫ и в
счёт не идут ни нам, ни ему.
"""
ГОРИЗОНТ_ТУРНИРА = 900.0

ОЧКИ_НАШИХ_ЗДАНИЙ = {"centers": 1000, "ba17": 500, "ba18": 500,
                     "academies": 500, "houses": 100}
ОЧКИ_НАШИХ_БОЙЦОВ = {"mil_inf": 10, "mil_shooters": 20, "mil_cav": 50}
ОЧКИ_ЕГО_ЗДАНИЙ = {"p1_center": 1000, "p1_ba17": 500, "p1_ba18": 500,
                   "p1_academi": 500, "p1_house": 100}
ОЧКИ_ЕГО_БОЙЦОВ = {"p1_inf": 10, "p1_shoot": 20, "p1_cav": 50}
ОЧКИ_КРЕСТЬЯНИНА = 20
ДЕЛИТЕЛЬ = 1000.0        # чтобы награда была порядка единиц, как у лестницы

ч = lambda d, k: float((d or {}).get(k) or 0)


def счёт(сим, история, до=ГОРИЗОНТ_ТУРНИРА):
    """(наш, его, подробности) на секунде `до` — по состоянию симулятора."""
    с = история[0] if история else {}
    for x in история:
        if ч(x, "gametime") <= до:
            с = x
    наш_живое = (sum(ч(с, k) * v for k, v in ОЧКИ_НАШИХ_ЗДАНИЙ.items())
                 + sum(ч(с, k) * v for k, v in ОЧКИ_НАШИХ_БОЙЦОВ.items())
                 + ч(с, "peasants") * ОЧКИ_КРЕСТЬЯНИНА)
    его_живое = (sum(ч(с, k) * v for k, v in ОЧКИ_ЕГО_ЗДАНИЙ.items())
                 + sum(ч(с, k) * v for k, v in ОЧКИ_ЕГО_БОЙЦОВ.items())
                 + ч(с, "p1_peasants") * ОЧКИ_КРЕСТЬЯНИНА)
    его_всего = sum(ч(с, k) for k in ОЧКИ_ЕГО_БОЙЦОВ)
    цена_его = (sum(ч(с, k) * v for k, v in ОЧКИ_ЕГО_БОЙЦОВ.items()) / его_всего
                if его_всего > 0 else 10.0)
    наш_всего = sum(ч(с, k) for k in ОЧКИ_НАШИХ_БОЙЦОВ)
    цена_наш = (sum(ч(с, k) * v for k, v in ОЧКИ_НАШИХ_БОЙЦОВ.items()) / наш_всего
                if наш_всего > 0 else 10.0)
    # УБИТОЕ И ПОТЕРЯННОЕ — по счётчикам СИМУЛЯТОРА, а не по записи: считаем свою
    # игру, а не чужую (та же поправка, что в лестнице 28.09).
    его_бц = getattr(сим, "убито_бойцов", 0.0)
    его_кр = getattr(сим, "убито_крестьян", 0.0)
    наши_бц = getattr(сим, "my_mil_lost", 0.0)
    наши_кр = getattr(сим, "my_pea_lost", 0.0)
    наш = наш_живое + 2 * (его_бц * цена_его + его_кр * ОЧКИ_КРЕСТЬЯНИНА)
    его = его_живое + 2 * (наши_бц * цена_наш + наши_кр * ОЧКИ_КРЕСТЬЯНИНА)
    return наш, его, dict(наш_живое=наш_живое, его_живое=его_живое,
                          его_бц=его_бц, его_кр=его_кр,
                          наши_бц=наши_бц, наши_кр=наши_кр,
                          цена_его=цена_его, цена_наш=цена_наш)


# ВТОРАЯ ИДЕЯ (28.09): бить только в выгодной полосе. Живой замер по 81 записи:
# при перевесе в клетке меньше 0,75 своих на одного его размен 0,13-0,19, а в
# полосе 1,5-3 — 0,85-1,27. Поэтому потери, понесённые в безнадёжной полосе,
# наказываются отдельно: очки за них уже вычтены, но сеть должна УЧИТЬСЯ их не
# нести, а не узнавать об этом из суммы. Верхнюю границу не награждаем: полоса
# «больше 3» стоит на четырёх чистых окнах, этого мало.
ПОЛОСА_ПЛОХАЯ = 0.75
ЦЕНА_ПЛОХОЙ_ПОЛОСЫ = 0.004     # за бойца, как плата за потери в лестнице
ПОЛОСА = False                  # включается ключом --полоса


def потери_в_плохой_полосе(сим) -> float:
    """Наши потери в тактах, где перевес в клетке был ниже 0,75."""
    из = 0.0
    for запись in getattr(сим, "журнал_боя", []):
        _, _, _, _, наших, его_в, наши_потери, _ = запись[:8]
        if (его_в or 0) <= 0:
            continue
        if (наших or 0) / max(его_в, 1e-9) < ПОЛОСА_ПЛОХАЯ:
            из += наши_потери or 0.0
    return из


def награда(сим, история, до=ГОРИЗОНТ_ТУРНИРА) -> float:
    """Разница очков к 15-й минуте, делённая на тысячу.

    Победа по §7 (перебили поток, крестьян меньше 30, осада) прибавляет ещё
    единицу: в турнире это снимает вопрос о ничьей совсем.
    """
    наш, его, _ = счёт(сим, история, до)
    r = (наш - его) / ДЕЛИТЕЛЬ
    if getattr(сим, "исход", "") == "победа":
        r += 1.0
    if ПОЛОСА:
        r -= ЦЕНА_ПЛОХОЙ_ПОЛОСЫ * потери_в_плохой_полосе(сим)
    return r
