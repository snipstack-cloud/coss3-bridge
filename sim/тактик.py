class Тактик(Ядро):
    """Хозяйство и прокачка — `поиск_стратегии.Стратегия` с войной выключенной; война — сеть `Ядро`."""

    def __init__(self, theta, хоз, температура=0.0, rng=None):
        import поиск_стратегии as ПС
        super().__init__(theta)
        # война стратегии выключена: ни сроков волн, ни её тактики (§60) — воюет сеть
        хоз = {k: v for k, v in хоз.items() if k not in ("отход", "подмога", "слабая", "возврат")}
        self.хоз = ПС.Стратегия(dict(хоз, T1=1e9, T2=1e9, P1=0.0))
        self.лог_x = []       # признаки каждого шага — для ворот «без глаз» (§55)

    def __call__(self, st):
        из = self.хоз(st)
        р = self.решить(st)
        if р is not None:
            self.лог_x.append(р[1])
            # §60: как мост — «к своим» отходом домой, внутренние приказы симулятора не исполняются.
            # §63: мост научен приказам волне в поле (e50bd84: к своим, вперёд, отряд, на меньшую;
            # держать — приближением), и при `COSS3_NET_ORDERS=полные` сеть учится и им —
            # симулятор исполняет их своим кодом
            if ПРИКАЗЫ_ПОЛНЫЕ:
                из += self.команды(р[0], st, живой=False)
            else:
                из += [c for c in self.команды(р[0], st, живой=ЖИВОЙ) if not (ЖИВОЙ and str(c.get("cmd", "")).startswith("_"))]
        return из


class Слепой(Тактик):
    """ВОРОТА «БЕЗ ГЛАЗ» (§55): та же сеть, но вектор признаков заменён постоянным — средним
    по партии зрячей сети на той же записи и зерне. Память и сводка считаются как у зрячей,
    чтобы «к своим» и «на меньшую» работали одинаково; меняется только вход сети. Если
    награда слепой не хуже зрячей — сеть не читает обстановку, а играет расписание."""

    def __init__(self, theta, хоз, среднее):
        super().__init__(theta, хоз)
        self.среднее = [float(v) for v in среднее]

    def признаки(self, st, t):
        super().признаки(st, t)
        return list(self.среднее)


