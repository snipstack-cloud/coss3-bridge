def _настроить(враг):
    import sim as SIM, combat
    import враг as ВР
    SIM.НАЙМ_ВРАГА_МНОЖ = 1.0        # §55: после случайного противника — обычный найм
    SIM.ПРОКАЧКА_ВРАГА = None        # §70: и прокачка его мушкетёров — как в записи
    SIM.ЗАСЛОН = SIM.ЗАСЛОН_ИСХ       # §71: и заслон — по умолчанию
    SIM.ОТРЯДЫ_ВРАГА = None           # §79: и отряды — из записи
    if isinstance(враг, dict):
        # СЛУЧАЙНЫЙ ПРОТИВНИК (§55): розыгрыш `случайный_враг.разыграть` — все глобалы и профиль боя
        import случайный_враг as СВ
        СВ.применить(враг)
        return
    # §43: против игрока и мушкетёров — с погоней (кусок по размеру нашей группы гонится за ней);
    # «родной» без погони, как его записи
    if враг in ("налётчик", "налётчик_о"):
        # §107: повадки игрока (p3 / p3о) + налёт туда, где нашей армии нет — проверка 6, набег в 7:00
        _настроить("p3о" if враг == "налётчик_о" else "p3")
        SIM.СТИЛЬ_ВРАГА = dict(SIM.СТИЛЬ_ВРАГА, налёт=dict(с=240, доля=0.35, мин=10, порог=0.8))
        return
    if враг == "p3о":
        # §79: «p3 с отрядами» — те же повадки, его армия в отрядах и держит удержание у базы
        _настроить("p3")
        SIM.ОТРЯДЫ_ВРАГА = (1.0, 1)
        return
    if враг == "p3":
        # §72: игрок 3.10 (пополам пики и мушкетёры) не гонится и вступает только с перевесом —
        # сверка агента на командах записи: погоня 0 и `вступать_при` 1,0 дают его потери
        # 1,4/2,4/3,5/7,0 к 8/9/10/15:00 при живых 2/2/5/18 (с погоней 4 — 17,7/23,1/29,9/44,7)
        стиль = dict(ВР.СТИЛИ["родной"], погоня=0, вступать_при=1.0)
        SIM.АГЕНТНЫЙ_ВРАГ, SIM.СТИЛЬ_ВРАГА, SIM.ВРАГ_СЛЕДУЕТ, SIM.ОБОРОНА_ДОМА = True, стиль, 6.0, 3
        SIM.СОСТАВ_ВРАГА = None
        combat.МЕНЬШИНСТВО_СТЕПЕНЬ, combat.МЕНЬШИНСТВО_ВЕЗДЕ, combat.МЕНЬШИНСТВО_СТОРОНЫ = 0.25, False, "обе"
        if hasattr(combat, "_залпы_исх"):
            combat.залпы = combat._залпы_исх
        return
    стиль = dict(ВР.СТИЛИ["родной"], погоня=ПОГОНЯ, во_сколько=3.0)   # §62: замер по ecells игрока if враг in ("игрок", "мушкетёры", "половина", "p2") and ПОГОНЯ else "родной"
    SIM.АГЕНТНЫЙ_ВРАГ, SIM.СТИЛЬ_ВРАГА, SIM.ВРАГ_СЛЕДУЕТ, SIM.ОБОРОНА_ДОМА = True, стиль, 6.0, 3
    SIM.СОСТАВ_ВРАГА = {"мушкетёры": "мушкетёры", "половина": "половина"}.get(враг)
    # «p2» (§53): запись игрока-мушкетёра 2.10 — обычный профиль боя (он сошёлся с живой
    # партией: §52), не профиль «игрок» с выключенными залпами
    if враг == "игрок":
        combat.МЕНЬШИНСТВО_СТЕПЕНЬ, combat.МЕНЬШИНСТВО_ВЕЗДЕ, combat.МЕНЬШИНСТВО_СТОРОНЫ = 1.0, True, "наши"  # как поиск §32
        combat.залпы = lambda *a, **k: 0.0
    else:
        combat.МЕНЬШИНСТВО_СТЕПЕНЬ, combat.МЕНЬШИНСТВО_ВЕЗДЕ, combat.МЕНЬШИНСТВО_СТОРОНЫ = 0.25, False, "обе"
        if hasattr(combat, "_залпы_исх"):
            combat.залпы = combat._залпы_исх


def _партия(з):
    вид, арг, хоз, враг, d, seed = з
    import combat, sim as SIM, поиск_стратегии as ПС
    if not hasattr(combat, "_залпы_исх"):
        combat._залпы_исх = combat.залпы
    if враг == "случайный":
        # §55: каждое задание — новый розыгрыш, зерно задания; запись-основа — из задания
        import случайный_враг as СВ
        враг = dict(СВ.разыграть(np.random.default_rng(seed)), запись=d)
    _настроить(враг)
    if вид in ("сеть", "слепая"):
        п = Тактик(арг, хоз, 0.0, np.random.default_rng(seed))
    else:
        SIM.СБОР_ВОЛН = 1.5 if вид == "правила" else 0.0
        п = ПС.Стратегия(арг)
    сим, и = SIM.партия(d, п, seed=seed)
    if вид == "слепая":
        # ворота «без глаз» (§55): среднее признаков зрячей на этой же партии, потом партия вслепую
        среднее = np.mean(п.лог_x, axis=0) if п.лог_x else np.zeros(N_ПРИЗНАКОВ)
        п = Слепой(арг, хоз, среднее)
        сим, и = SIM.партия(d, п, seed=seed)
    SIM.СБОР_ВОЛН = 0.0
    м = ПС.мера(сим, и)
    м["враг"] = враг if isinstance(враг, str) else "случайный"
    if вид in ("сеть", "слепая"):
        м["решения"] = [п.история.count(i) for i in range(len(п.решения))]
    return м


