class Тактик(Ядро):
    """Хозяйство и прокачка — `поиск_стратегии.Стратегия` с войной выключенной; война — сеть `Ядро`."""

    def __init__(self, theta, хоз, температура=0.0, rng=None):
        import поиск_стратегии as ПС
        super().__init__(theta)
        self.хоз = ПС.Стратегия(dict(хоз, T1=1e9, T2=1e9, P1=0.0))

    def __call__(self, st):
        из = self.хоз(st)
        р = self.решить(st)
        if р is not None:
            из += self.команды(р[0], st)
        return из


ПОГОНЯ = int(os.environ.get("COSS3_POGONYA", "4"))   # радиус погони, 0 — выкл (§43)


# ПРОТИВНИКИ — смесь: родной (агент), одни мушкетёры, запись игрока (профиль §32)
def _настроить(враг):
    import sim as SIM, combat
    import враг as ВР
    # §43: против игрока и мушкетёров — с погоней (кусок по размеру нашей группы гонится за ней);
    # «родной» без погони, как его записи
    стиль = dict(ВР.СТИЛИ["родной"], погоня=ПОГОНЯ, во_сколько=1.5) if враг in ("игрок", "мушкетёры", "половина", "p2") and ПОГОНЯ else "родной"
    SIM.АГЕНТНЫЙ_ВРАГ, SIM.СТИЛЬ_ВРАГА, SIM.ВРАГ_СЛЕДУЕТ, SIM.ОБОРОНА_ДОМА = True, стиль, 6.0, 3
    SIM.СОСТАВ_ВРАГА = {"мушкетёры": "мушкетёры", "половина": "половина"}.get(враг)
    # «p2» (§53): запись игрока-мушкетёра 2.10 — обычный профиль боя (он сошёлся с живой
    # партией: §52), не профиль «игрок» с выключенными залпами
    if враг == "игрок":
        combat.МЕНЬШИНСТВО_СТЕПЕНЬ, combat.МЕНЬШИНСТВО_ВЕЗДЕ, combat.МЕНЬШИНСТВО_СТОРОНЫ = 1.0, True, "наши"  # как поиск §32
        combat.залпы = lambda *a, **k: 0.0
    else:
        combat.МЕНЬШИНСТВО_СТЕПЕНЬ, combat.МЕНЬШИНСТВО_ВЕЗДЕ, combat.МЕНЬШИНСТВО_СТОРОНЫ = 0.25, False, "обе"
        if hasattr(combat, "_залпы_исх"):
            combat.залпы = combat._залпы_исх


def _партия(з):
    вид, арг, хоз, враг, d, seed = з
    import combat, sim as SIM, поиск_стратегии as ПС
    if not hasattr(combat, "_залпы_исх"):
        combat._залпы_исх = combat.залпы
    _настроить(враг)
    if вид == "сеть":
        п = Тактик(арг, хоз, 0.0, np.random.default_rng(seed))
    else:
        SIM.СБОР_ВОЛН = 1.5 if вид == "правила" else 0.0
        п = ПС.Стратегия(арг)
    сим, и = SIM.партия(d, п, seed=seed)
    SIM.СБОР_ВОЛН = 0.0
    м = ПС.мера(сим, и)
    м["враг"] = враг
    if вид == "сеть":
        м["решения"] = [п.история.count(i) for i in range(len(РЕШЕНИЯ))]
    return м


def наборы():
    import glob
    sys.argv_сохр = list(sys.argv)
    sys.argv = [sys.argv[0], "--корпус", os.path.join(К, "корпус_27_09.txt")]
    import train as TR
    обуч, тест = TR.разбить(TR.партии([]))
    sys.argv = sys.argv_сохр
    игрок = sorted(os.path.dirname(x) for x in glob.glob(os.path.expanduser("~/coss3-res-игрок/*/*/coss3_snap.jsonl")))
    return обуч, тест, игрок


def задания_для(вид, арг, хоз, партии_обуч, игрок, rng, k, g):
    з = []
    for j in range(k):
        враг = ("родной", "мушкетёры", "игрок")[j % 3]
        d = игрок[rng.integers(len(игрок))] if враг == "игрок" else партии_обуч[rng.integers(len(партии_обуч))]
        з.append((вид, арг, хоз, враг, d, 1000 * g + j))
    return з


def проверка(пул, вид, арг, хоз, тест, игрок):
    итог = {}
    # игрок по партиям отдельно (§42): партия 1 решается обороной (он пришёл сам — «никогда не
    # выходить» уничтожает его в 25/30), тактику решает партия 2; обе в обучении, другие зёрна
    for имя, враг, партии in (("родной", "родной", тест * 3), ("мушкетёры", "мушкетёры", тест * 3),
                              ("игрок-1", "игрок", игрок[:1] * 30), ("игрок-2", "игрок", игрок[1:] * 30)):
        р = пул.map(_партия, [(вид, арг, хоз, враг, d, 100000 + i) for i, d in enumerate(партии)])
        уб, пот = sum(x["убито"] for x in р), sum(x["потери"] for x in р)
        if вид == "сеть":
            сч = np.sum([x["решения"] for x in р], axis=0)
            print(f"  решения против «{имя}»: " + ", ".join(f"{РЕШЕНИЯ[i]} {100 * сч[i] / сч.sum():.0f}%" for i in range(len(сч)) if сч[i]), flush=True)
        итог[имя] = (St.mean(x["награда"] for x in р), sum(x["уничтожена"] for x in р), len(р),
                      St.median(x["его15"] for x in р), уб / max(пот, 1), St.median(x["наша15"] for x in р))
    return итог


def печать(имя, итог):
    for враг, (r, у, n, е, рз, н) in итог.items():
        print(f"  {имя:22} {враг:13} награда {r:+5.2f} | уничтожена {у:2d}/{n} | его 15:00 {е:4.0f} | размен {рз:4.2f} | наша {н:4.0f}", flush=True)


def main():
    def опц(имя, умолч, тип=int):
        return тип(sys.argv[sys.argv.index(имя) + 1]) if имя in sys.argv else умолч
    gens, pop, k, seed = опц("--gens", 60), опц("--pop", 48), опц("--k", 9), опц("--seed", 1)
    выход = опц("--out", os.path.join(К, "тактик", f"s{seed}.npy"), str)
    хоз = json.load(open(os.path.join(К, "поиск", "игрок_хоз_агент.json")))["итог"]
    правила = dict(хоз, отход=0.75, подмога=20, слабая=0)
    обуч, тест, игрок = наборы()
    if "--export" in sys.argv:
        # веса для тени в живом мосте (§44): JSON без numpy
        i = sys.argv.index("--export")
        откуда, куда = sys.argv[i + 1], sys.argv[i + 2]
        th = np.load(откуда)
        os.makedirs(os.path.dirname(куда) or ".", exist_ok=True)
        json.dump({"theta": [round(float(v), 6) for v in th], "откуда": os.path.basename(откуда),
                   "погоня": ПОГОНЯ}, open(куда, "w"), ensure_ascii=False)
        print("веса →", куда, len(th))
        return
    with Pool(12) as пул:
        if "--eval" in sys.argv:
            th = np.load(sys.argv[sys.argv.index("--eval") + 1])
            печать("сеть", проверка(пул, "сеть", th, хоз, тест, игрок))
            печать("правила (§40)", проверка(пул, "правила", правила, хоз, тест, игрок))
            печать("без тактики", проверка(пул, "без", хоз, хоз, тест, игрок))
            return
        os.makedirs(os.path.dirname(выход), exist_ok=True)
        rng = np.random.default_rng(seed)
        mu, sigma = np.zeros(N_ВЕСОВ), np.full(N_ВЕСОВ, 0.5)
        лучший, лучшая = mu.copy(), -1e9
        for g in range(gens):
            X = rng.normal(mu, sigma, size=(pop, N_ВЕСОВ))
            набор = задания_для(None, None, хоз, обуч, игрок, rng, k, g)
            задания = [("сеть", x, хоз, з[3], з[4], з[5]) for x in X for з in набор]
            р = пул.map(_партия, задания)
            R = np.array([St.mean(q["награда"] for q in р[i * k:(i + 1) * k]) for i in range(pop)])
            иx = np.argsort(-R)[:8]
            mu, sigma = X[иx].mean(axis=0), np.maximum(X[иx].std(axis=0), 0.02)
            if R[иx[0]] > лучшая:
                лучшая, лучший = float(R[иx[0]]), X[иx[0]].copy()
                np.save(выход, лучший)
            np.save(выход.replace(".npy", "_среднее.npy"), mu)
            print(f"поколение {g + 1:3d}/{gens}: лучшая {R[иx[0]]:+5.2f} средняя {R.mean():+5.2f} σ {sigma.mean():.3f}", flush=True)
        print("\nПРОВЕРКА на отложенных (родной, мушкетёры — 25×3; игрок — 2×15):")
        печать("сеть (среднее)", проверка(пул, "сеть", mu, хоз, тест, игрок))
        печать("правила (§40)", проверка(пул, "правила", правила, хоз, тест, игрок))
        печать("без тактики", проверка(пул, "без", хоз, хоз, тест, игрок))


if __name__ == "__main__":
    main()
