def проверка(пул, вид, арг, хоз, тест, игрок):
    итог = {}
    # игрок по партиям отдельно (§42): партия 1 решается обороной (он пришёл сам — «никогда не
    # выходить» уничтожает его в 25/30), тактику решает партия 2; обе в обучении, другие зёрна
    import случайный_враг as СВ
    случ = СВ.тест() or []
    наборы_пр = [("родной", "родной", тест * 3), ("мушкетёры", "мушкетёры", тест * 3), ("половина", "половина", тест * 3),
                 ("игрок-1", "игрок", игрок[:1] * 30), ("игрок-2", "игрок", игрок[1:] * 30), ("p2", "p2", _p2() * 30), ("p3", "p3", _p3() * 30), ("p3о", "p3о", _p3() * 30),
                 # §55: отложенный набор случайных противников — 100 розыгрышей зерна 7, у каждого своя запись
                 ("случайный", None, случ)]
    for имя, враг, партии in наборы_пр:
        if not партии:
            continue
        if враг is None:
            задания = [(вид, арг, хоз, п, п["запись"], 100000 + i) for i, п in enumerate(партии)]
        else:
            задания = [(вид, арг, хоз, враг, d, 100000 + i) for i, d in enumerate(партии)]
        р = пул.map(_партия, задания)
        уб, пот = sum(x["убито"] for x in р), sum(x["потери"] for x in р)
        if вид in ("сеть", "слепая"):
            сч = np.sum([x["решения"] for x in р], axis=0)
            from tactic_core import РЕШЕНИЯ2
            print(f"  решения против «{имя}»: " + ", ".join(f"{РЕШЕНИЯ2[i]} {100 * сч[i] / сч.sum():.0f}%" for i in range(len(сч)) if сч[i]), flush=True)
        итог[имя] = (St.mean(x["награда"] for x in р), sum(x["уничтожена"] for x in р), len(р),
                      St.median(x["его15"] for x in р), уб / max(пот, 1), St.median(x["наша15"] for x in р))
    return итог


def печать(имя, итог):
    for враг, (r, у, n, е, рз, н) in итог.items():
        print(f"  {имя:22} {враг:13} награда {r:+5.2f} | уничтожена {у:2d}/{n} | его 15:00 {е:4.0f} | размен {рз:4.2f} | наша {н:4.0f}", flush=True)


def ворота_без_глаз(пул, th, хоз, тест, игрок, зрячая=None):
    """§55: та же сеть с постоянным вектором признаков; печатает разницу наград по видам."""
    зрячая = зрячая or проверка(пул, "сеть", th, хоз, тест, игрок)
    слепая = проверка(пул, "слепая", th, хоз, тест, игрок)
    печать("без глаз", слепая)
    for враг in зрячая:
        a, b = зрячая[враг], слепая[враг]
        print(f"  ворота «без глаз»     {враг:13} награда {a[0]:+5.2f} → {b[0]:+5.2f} (Δ {a[0] - b[0]:+5.2f}) | уничтожена {a[1]}/{a[2]} → {b[1]}/{b[2]}", flush=True)
    return зрячая, слепая


