# -*- coding: utf-8 -*-
"""Его крестьяне бьют, но целями не становятся (замер живой игрой 27.09).

Событие гибели из block_kills.inc назвало убийцу каждой смерти: 22 наших потери за
партию, ПЯТЬ от его крестьян вблизи. До этой правки симулятор считал стояние среди
его крестьян бесплатным.
"""
import sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import combat as C

ошибок = []
пикинёр = {"hp": 90, "atk": 8, "wkind": 1, "dpike": 3, "dsword": 2, "dbullet": 4}
A = [(20.0, пикинёр)]          # наши двадцать
B = [(10.0, пикинёр)]          # его десять

C.ДОЛЯ_КРЕСТЬЯНИНА = 0.20
# 1. крестьяне добавляют урон по нам
без = C.ставки(A, B, 20, 10, False)
с_кр = C.ставки(A, B, 20, 10, False, крестьян=30.0, крестьянин_х=пикинёр)
if not (с_кр["наши"] > без["наши"] * 1.05):
    ошибок.append("тридцать его крестьян обязаны прибавить нам потерь")
# 2. и НЕ добавляют ему потерь: целями они не становятся
if abs(с_кр["его"] - без["его"]) > 1e-9:
    ошибок.append("крестьяне не должны увеличивать ЕГО потери — они не цели")
# 3. без стат крестьянина урон не считается наугад
пусто = C.ставки(A, B, 20, 10, False, крестьян=30.0, крестьянин_х=None)
if abs(пусто["наши"] - без["наши"]) > 1e-9:
    ошибок.append("без чисел крестьянина прибавки быть не должно")
# 4. клетка БЕЗ его бойцов: крестьяне всё равно бьют, и это главное
одни = C.ставки(A, [], 20, 0, False, крестьян=30.0, крестьянин_х=пикинёр)
if not (одни["наши"] > 0):
    ошибок.append("в клетке без бойцов крестьяне обязаны бить — иначе стояние бесплатно")
if одни["его"] != 0:
    ошибок.append("в клетке без его бойцов его потерь быть не может")
# 5. доля крестьянина выключена — всё как было
C.ДОЛЯ_КРЕСТЬЯНИНА = 0.0
выкл = C.ставки(A, B, 20, 10, False, крестьян=30.0, крестьянин_х=пикинёр)
if abs(выкл["наши"] - без["наши"]) > 1e-9:
    ошибок.append("при нулевой доле крестьяне не должны влиять")
# 6. число подобрано и названо
C.ДОЛЯ_КРЕСТЬЯНИНА = 0.20
if abs(C.ДОЛЯ_КРЕСТЬЯНИНА - 0.20) > 1e-9:
    ошибок.append("доля крестьянина должна быть 0,20 — подогнана под живые 23 %")

print("selftest_крестьяне_бьют: " + ("ОК, 7 проверок" if not ошибок
                                     else "ОШИБКИ\n  " + "\n  ".join(ошибок)))
raise SystemExit(1 if ошибок else 0)
