#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""ДВЕ ПРОВЕРКИ ДО ОБУЧЕНИЯ (29.09, §23): окупается ли кулак под наградой CEM.

То, что симулятор после §22 лучше воспроизводит размен по перевесу, ещё не значит,
что НАГРАДА обучения делает выгодным «копить и ударить раз». Прежде чем тратить ночь
на шесть прогонов CEM — два скриптованных ответа, на новом ядре и на прежнем:

1. ПАРА: «кулак» (копить до P, один удар всей армией в T по его свободным крестьянам,
   дальше не ходить — общее у выигрывающих сетей §19) против «частями» (с 5:00 каждый
   свободный боец к нему, с досылкой в волну — как проигрывавшая сеть §19).
2. СКЛОН: кулак по сетке P × T. Если награда растёт к большому удару и у пика видна
   гора — CEM есть по чему подниматься; если поле плоское или пик — шум, обучение
   ничего не найдёт.

Экономика у всех планов одна — ярус 1. Меры — ровно то, что видит обучение:
награда этапа 3 (`goals_этапы.награда`, этап 3), побед по правилу (поход к нему и
впереди по очкам на 900-й секунде), медиана разницы очков, наши потери, его убитые.

    python3 sim/проверка_кулака.py [--ядро новое|старое|оба] [--поражение] [--быстро]
"""
import os
import statistics as S
import sys
from multiprocessing import Pool

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import combat          # noqa: E402
import goals as G      # noqa: E402
import goals_score as GS   # noqa: E402
import goals_этапы as GЭ   # noqa: E402
import sim as SIM      # noqa: E402
import tier1 as T1     # noqa: E402

КОРПУС = os.path.join(os.path.dirname(os.path.abspath(__file__)), "корпус_27_09.txt")


class Кулак:
    """Копим до `порог` свободных, в `с` или позже бьём РОВНО `порог` бойцами ОДИН раз.

    Ровно, а не всей армией: к 5-9 минуте армия уже больше любого порога, и «все»
    склеивало размер удара со временем (первый прогон 29.09: столбцы по P совпадали)."""
    def __init__(self, порог, с, цель="peasants_free"):
        self.порог, self.с, self.цель = порог, с, цель
        self.я = T1.Ярус1()
        self.ударил = False

    def __call__(self, st):
        из = self.я(st)
        t = float(st.get("gametime") or 0)
        if not self.ударил and t >= self.с and float(st.get("my_freewar") or 0) >= self.порог:
            из.append({"cmd": "ATTACK", "count": self.порог, "target": self.цель})
            self.ударил = True
        return из


class Частями:
    """С `с` каждый свободный боец к нему; уже вышедшие — досылкой в волну."""
    def __init__(self, с=300.0, цель="peasants_free"):
        self.с, self.цель = с, цель
        self.я = T1.Ярус1()

    def __call__(self, st):
        из = self.я(st)
        t = float(st.get("gametime") or 0)
        if t >= self.с and float(st.get("my_freewar") or 0) >= 1:
            вне = float(st.get("mil_away") or 0)
            из.append({"cmd": "ATTACK", "count": "all", "target": "wave" if вне > 0 else self.цель})
        return из


def _ядро(имя):
    # «+п» — награда с поражением без похода (§23); передаётся с заданием, потому что
    # пул на macOS поднимает процессы заново и глобальные главного процесса не видит
    GЭ.БЕЗ_ПОХОДА_ПОРАЖЕНИЕ = имя.endswith("+п")
    имя = имя.removesuffix("+п")
    if имя == "старое":
        SIM.МЕСТНЫЙ_ВРАГ = False
        combat.МЕНЬШИНСТВО_СТЕПЕНЬ = None


def _партия(задание):
    ядро, план, d, seed = задание
    _ядро(ядро)
    вид, *пар = план
    п = Кулак(*пар) if вид == "кулак" else Частями(*пар) if вид == "частями" else T1.Ярус1()
    с, и = SIM.партия(d, п, seed=seed)
    наш, его, _ = GS.счёт(с, и)
    поход = G.поход_к_нему(и, с.з.en_base)
    return dict(награда=GЭ.награда(с, и, 3), разница=наш - его,
                победа=поход >= G.ПОХОД_БОЙЦОВ and наш > его, поход=поход >= G.ПОХОД_БОЙЦОВ,
                потери=с.my_mil_lost, убито=с.убито_бойцов, крестьян=с.убито_крестьян)


def свод(р):
    return (f"награда {S.mean(x['награда'] for x in р):+6.2f}  побед {sum(x['победа'] for x in р):3d}/{len(р)}"
            f"  поход {sum(x['поход'] for x in р):3d}  очки медиана {S.median(x['разница'] for x in р):+6.0f}"
            f"  потери {S.median(x['потери'] for x in р):5.0f}  убито {S.median(x['убито'] for x in р):4.0f}"
            f"  крестьян {S.median(x['крестьян'] for x in р):4.0f}")


def main():
    ядра = {"новое": ["новое"], "старое": ["старое"], "оба": ["новое", "старое"]}[
        sys.argv[sys.argv.index("--ядро") + 1] if "--ядро" in sys.argv else "оба"]
    if "--поражение" in sys.argv:
        ядра = [я + "+п" for я in ядра]
    партии = [x.strip() for x in open(КОРПУС, encoding="utf-8") if x.strip()]
    партии = [d for d in партии if os.path.exists(os.path.join(d, "coss3_snap.jsonl"))]
    if "--быстро" in sys.argv:
        партии = партии[::3]
    планы = [("ярус1",), ("частями", 300.0), ("кулак", 35, 360.0)]
    сетка = [("кулак", P, T) for P in (10, 20, 35, 50, 80) for T in (300.0, 420.0, 540.0, 660.0)]
    print(f"партий {len(партии)}, зерно = номер партии", flush=True)
    with Pool(12) as пул:
        for ядро in ядра:
            print(f"\n=== ЯДРО {ядро} ===", flush=True)
            print("1. ПАРА", flush=True)
            for план in планы:
                р = пул.map(_партия, [(ядро, план, d, i) for i, d in enumerate(партии)])
                print(f"  {' '.join(map(str, план)):22} {свод(р)}", flush=True)
            print("2. СКЛОН: кулак, порог P × время T — средняя награда (побед)", flush=True)
            таб = {}
            for план in сетка:
                р = пул.map(_партия, [(ядро, план, d, i) for i, d in enumerate(партии)])
                таб[план[1:]] = (S.mean(x["награда"] for x in р), sum(x["победа"] for x in р),
                                 S.median(x["разница"] for x in р))
            print("  P \\ T  " + "".join(f"{int(T):>18}" for T in (300, 420, 540, 660)))
            for P in (10, 20, 35, 50, 80):
                print(f"  {P:5d}  " + "".join(f"  {таб[(P, T)][0]:+6.2f} ({таб[(P, T)][1]:2d}) {таб[(P, T)][2]:+5.0f}"
                                              for T in (300.0, 420.0, 540.0, 660.0)), flush=True)


if __name__ == "__main__":
    main()
