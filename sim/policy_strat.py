def _следующий(линейка, st):
    взято = {x.strip() for x in str(st.get("upg_done") or "").split(",") if x.strip()}
    return next((u for u in линейка if u not in взято), None)


def декодировать(индекс, st):
    д = РЕШЕНИЯ[индекс]
    if д["cmd"] is None or д["cmd"] == "PRESENCE":
        return []
    # МУШКЕТЁРСКАЯ ЛИНИЯ: академия и её апгрейды — прямо, без словаря полного
    # набора действий (в нём этих имён нет, и делегирование упало бы).
    if д["cmd"] == "BUILD" and str(д.get("total")) == "+1":
        # «+1» значит ЕЩЁ ОДНО здание, а симулятор читает total как СКОЛЬКО ВСЕГО:
        # при total=1 и одной казарме он просто ничего не делал (поймано 28.09).
        поле = {"ba17": "ba17", "ba18": "ba18", "mill": "mills", "smith": "smiths",
                "center": "centers", "house": "houses", "store": "stores"}.get(д["role"], д["role"])
        есть = float(st.get(поле) or 0)
        return [{"cmd": "BUILD", "role": д["role"], "total": int(есть) + 1}]
    if д["cmd"] == "BUILD" and д["role"] == "academi":
        # total — СКОЛЬКО ВСЕГО зданий этого вида хотим (так читает симулятор)
        return [{"cmd": "BUILD", "role": "academi", "total": 1}]
    if д["cmd"] == "УДАР_ПРИ_ПЕРЕВЕСЕ":
        # цель — клетка с его крестьянами, где его бойцов рядом меньше всего;
        # бьём, только если свободных хватает на `порог` к его защитникам.
        свободных = float(st.get("my_freewar") or 0)
        порог = float(д.get("порог") or 1.5)
        клетки = coss3_map.крестьяне_врага(st, топ=8) or []
        if not клетки or свободных < 5:
            return []
        лучшая = min(клетки, key=lambda к: (к.get("бойцов_рядом") or 0, -(к.get("крестьян") or 0)))
        его = float(лучшая.get("бойцов_рядом") or 0)
        if свободных < порог * max(его, 1.0):
            return []          # ЖДЁМ: перевеса нет, и это решение — не бить
        return [{"cmd": "ATTACK", "count": "all", "target": "cell",
                 "cx": int(лучшая["x"]), "cy": int(лучшая["y"])}]
    if д["cmd"] == "ATTACK" and д.get("target") == "держать":
        # клетка подхода: треть пути от нашей базы к его
        mx, my = float(st.get("my_cx") or 0), float(st.get("my_cy") or 0)
        # его база в состоянии лежит СПИСКОМ `en_base` (не en_cx/en_cy — это
        # поймано тестом, а не игрой)
        еб = st.get("en_base")
        if isinstance(еб, (list, tuple)) and len(еб) == 2:
            ex, ey = float(еб[0]), float(еб[1])
        else:
            ex, ey = 8.0, 8.0
        cx = int(round(mx + (ex - mx) / 3.0))
        cy = int(round(my + (ey - my) / 3.0))
        return [{"cmd": "ATTACK", "count": 30, "target": "cell", "cx": cx, "cy": cy}]
    if д["cmd"] == "BALANCE" and д["role"] == "дерево_камень":
        крест = float(st.get("peasants") or 0)
        # ПОЛОВИНА НА ДЕРЕВО, треть на камень — по замеру 28.09: при таких долях
        # академия (1050 дерева, 1230 камня) окупается к 300-й секунде, а при 30 %
        # и 20 % дерево не накапливалось вовсе, потому что его съедали дома.
        на_дерево = max(2, int(round(крест * 0.4)))
        на_камень = max(2, int(round(крест * 0.4)))
        return [{"cmd": "BALANCE", "role": "wood", "total": на_дерево},
                {"cmd": "BALANCE", "role": "stone", "total": на_камень}]
    if д["cmd"] == "UPGRADE" and д["role"] in ("пуля_урон", "пуля_пауза"):
        линейка = АКА_УРОН if д["role"] == "пуля_урон" else АКА_ПАУЗА
        имя = _следующий(линейка, st)
        return [{"cmd": "UPGRADE", "role": имя, "upg": имя}] if имя else []
    if д["cmd"] == "UPGRADE":
        return P.декодировать(next(i for i, x in enumerate(P.ДЕЙСТВИЯ) if x.get("cmd") == "UPGRADE" and x.get("role") == д["role"]), st)
    if д["cmd"] == "BUILD":
        return P.декодировать(next(i for i, x in enumerate(P.ДЕЙСТВИЯ) if x.get("cmd") == "BUILD" and x.get("role") == д["role"]), st)
    return [dict(д)]


class Стратег:
    """Ярус 1 каждые 15 с + решение сети каждые 60 с (с 300-й секунды)."""

    def __init__(self, theta, температура=0.0, rng=None, с_секунды=300.0):
        self.W1, self.b1, self.W2, self.b2 = развернуть(theta)
        self.температура = температура
        self.rng = rng or np.random.default_rng(0)
        self.ярус1 = T1.Ярус1()
        self.следующее = с_секунды
        self.история = []
        self.присутствие = False
        self.цель_присутствия = "peasants"
        # ДЕРЕВО И КАМЕНЬ — РЕЖИМ, а не разовая команда (28.09). Ярус 1 каждые 5 с
        # переставляет людей по-своему, и минутная BALANCE от стратега затиралась
        # одиннадцать тактов из двенадцати: в пробе дерева к концу было 18 при
        # 7370 камня, хотя решение выбиралось 14 раз из 16. Режим держится 180 с от
        # последнего выбора и обновляется, если сеть выбрала его снова.
        self.лес_до = -1.0

    def выбрать(self, st):
        x = P.признаки(st)
        h = np.tanh(x @ self.W1 + self.b1)
        л = h @ self.W2 + self.b2
        if self.температура > 0:
            p = np.exp((л - л.max()) / self.температура)
            p /= p.sum()
            i = int(self.rng.choice(len(p), p=p))
        else:
            i = int(np.argmax(л))
        self.история.append(i)
        return i

    def __call__(self, st):
        из = self.ярус1(st)
        t = float(st.get("gametime") or 0)
        if t >= self.следующее:
            self.следующее = t + ШАГ_РЕШЕНИЯ
            i = self.выбрать(st)
            if РЕШЕНИЯ[i]["cmd"] == "BALANCE" and РЕШЕНИЯ[i].get("role") == "дерево_камень":
                self.лес_до = t + 180.0
            if РЕШЕНИЯ[i]["cmd"] == "PRESENCE":
                self.присутствие = РЕШЕНИЯ[i]["on"]
                self.цель_присутствия = РЕШЕНИЯ[i].get("target", "peasants")
            из += декодировать(i, st)
        # РЕЖИМ ЛЕСА: команды идут КАЖДЫЙ такт, иначе ярус 1 их затрёт
        if t <= self.лес_до:
            крест = float(st.get("peasants") or 0)
            # 40/40, а не 50/30: академии нужны ОБА ресурса (1050 дерева и 1230
            # камня), а при 50/30 камень оставался на 787 — ярус 1 забирает людей
            # обратно, и меньшая доля не держится (замер 28.09).
            из += [{"cmd": "BALANCE", "role": "wood", "total": max(2, int(round(крест * 0.4)))},
                   {"cmd": "BALANCE", "role": "stone", "total": max(2, int(round(крест * 0.4)))}]
        if self.присутствие and float(st.get("my_freewar") or 0) > 0:
            цель = "wave" if float(st.get("mil_away") or 0) > 0 else self.цель_присутствия
            из.append({"cmd": "ATTACK", "count": "all", "target": цель})
        return из
