"""ХРОНОЛОГИЯ БОТ ПРОТИВ ИГРОКА: где бот теряет время (8.10, §122).

Игрок 8.10: «игрок выигрывает временем каждого действия — как быстро поставится казарма, включится найм, прокачка,
соберётся группа; замедление золотой шахты плохо, чуть позднее казарма ещё хуже, забыл найм из второй казармы — провал;
каждый шаг должен давать преимущество относительно противника». В снимке партии против человека есть обе стороны
(наши поля и `p1_*` — противник, открытая информация), и шаги можно положить рядом.

По каждой записи игрока: время первой/второй/третьей казармы, второй и третьей золотой шахты, первой военной ступени;
по минутам 4/6/8/10/12 — армия, крестьяне, военных ступеней, лежащие ресурсы (еда+золото: деньги, не ставшие армией).

    python3 sim/хронология.py              # все записи игрока
"""
import glob
import json
import os


def _ч(v):
    try:
        return float(v or 0)
    except (TypeError, ValueError):
        return 0.0


def _ступени(s):
    return len([u for u in str(s or "").split(",") if u.startswith("bar.")])


def _снимки(каталог):
    из = []
    for стр in open(os.path.join(каталог, "coss3_snap.jsonl"), encoding="utf-8"):
        try:
            из.append(json.loads(стр))
        except ValueError:
            pass
    # только последняя партия файла (запись дописывается)
    t = [_ч(s.get("gametime")) for s in из]
    сбросы = [i for i in range(1, len(t)) if t[i] + 30 < t[i - 1]]
    return из[сбросы[-1]:] if сбросы else из


СТОРОНЫ = {"бот": dict(казармы="ba17", золото="mines_gold", ступени="upg_done", пик="mil_inf", стр="mil_shooters",
                       кр="peasants", еда="food", зол="gold"),
           "игрок": dict(казармы="p1_ba17", золото="p1_mgold", ступени="p1_upg_done", пик="p1_inf", стр="p1_shoot",
                         кр="p1_peasants", еда="p1_food", зол="p1_gold")}
МИНУТЫ = (4, 6, 8, 10, 12)


def хронология(каталог):
    S = _снимки(каталог)
    из = {}
    for сторона, п in СТОРОНЫ.items():
        шаги = {}
        for s in S:
            t = _ч(s.get("gametime"))
            for n in (1, 2, 3):
                if f"казарма {n}" not in шаги and _ч(s.get(п["казармы"])) >= n:
                    шаги[f"казарма {n}"] = t
            for n in (2, 3):
                if f"золото {n}" not in шаги and _ч(s.get(п["золото"])) >= n:
                    шаги[f"золото {n}"] = t
            for n in (1, 3, 6):
                if f"ступеней {n}" not in шаги and _ступени(s.get(п["ступени"])) >= n:
                    шаги[f"ступеней {n}"] = t
        поминутно = {}
        for м in МИНУТЫ:
            s = next((x for x in S if _ч(x.get("gametime")) >= м * 60), None)
            if s is None:
                continue
            поминутно[м] = dict(армия=round(_ч(s.get(п["пик"])) + _ч(s.get(п["стр"]))), кр=round(_ч(s.get(п["кр"]))),
                                ступ=_ступени(s.get(п["ступени"])), лежит=round(_ч(s.get(п["еда"])) + _ч(s.get(п["зол"]))))
        из[сторона] = dict(шаги=шаги, поминутно=поминутно)
    return из


def _мм(t):
    return "—" if t is None else f"{int(t) // 60}:{int(t) % 60:02d}"


if __name__ == "__main__":
    записи = sorted(glob.glob(os.path.expanduser("~/coss3-res-игрок-отл/*/*/coss3_snap.jsonl")))
    итог = {}
    for путь in записи:
        к = os.path.dirname(путь)
        имя = os.path.basename(os.path.dirname(к))
        х = хронология(к)
        if not any(х["игрок"]["поминутно"].get(м, {}).get("армия") for м in МИНУТЫ):
            continue                  # нет полей противника — не партия с открытой информацией
        print(f"\n== {имя}")
        ключи = ["казарма 1", "казарма 2", "казарма 3", "золото 2", "золото 3", "ступеней 1", "ступеней 3", "ступеней 6"]
        print("   шаг         " + "".join(f"{k:>11}" for k in ключи))
        for сторона in ("бот", "игрок"):
            print(f"   {сторона:11} " + "".join(f"{_мм(х[сторона]['шаги'].get(k)):>11}" for k in ключи))
        print("   минута      " + "".join(f"{f'{м}:00 армия/кр/ступ/лежит':>26}" for м in МИНУТЫ))
        for сторона in ("бот", "игрок"):
            пм = х[сторона]["поминутно"]
            print(f"   {сторона:11} " + "".join(f"{(str(пм[м]['армия']) + '/' + str(пм[м]['кр']) + '/' + str(пм[м]['ступ']) + '/' + str(пм[м]['лежит'])) if м in пм else '—':>26}" for м in МИНУТЫ))
        итог[имя] = х
