# -*- coding: utf-8 -*-
"""Ворота боя: закон потерь ядра против записанных боёв (§6 спецификации).

Факт — эпизоды боя из частых снимков (те же, что в `validate_combat.py`): отрезок,
где растут счётчики потерь, с составами обеих сторон, числами в клетках боя,
длиной и местом. Ядро (`sim/combat.py`) должно предсказать ПОТЕРИ КАЖДОЙ СТОРОНЫ
в штуках за эпизод — не отношение, как в сверке 24.09, а абсолют: симулятору
нужны именно они.

Закон в ядре: потери стороны за секунду = k × (сколько чужих бьёт) × (урон
одного чужого за удар с поправкой на строй / здоровье нашего). «Сколько бьёт» —
число в клетках боя, если клетка не насыщена («+» = 36 и больше), иначе вся
армия стороны. k — единственная подгоняемая константа, ударов в секунду на
бойца, и подгоняется здесь (`--fit`), а потом проверяется на тех же эпизодах:
знак, ранг, медиана |log2 ошибки| и доля попаданий в пределах двух раз.

    python3 sim/gate_combat.py <корень с прогонами> [ещё...] [--fit]
"""
import glob
import math
import os
import statistics as S
import sys

sys.path.insert(0, os.path.expanduser("~/coss3-bridge"))
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import combat_math as CM        # noqa: E402
import validate_combat as V     # noqa: E402
import combat as K              # noqa: E402


def эпизоды_с_составами(каталог):
    """Как `validate_combat.разбор_партии`, но с характеристиками сторон и бонусом строя."""
    снап = os.path.join(каталог, "coss3_snap.jsonl")
    бот = os.path.join(каталог, "coss3_bot.jsonl")
    if not (os.path.exists(снап) and os.path.exists(бот)):
        return []
    снимки = sorted(V.читать(снап), key=lambda x: V.ч(x.get("gametime")))
    снимки = [x for x in снимки if "my_mil_lost" in x and "p1_mil_lost" in x]
    тк = V.такты(бот)
    if len(снимки) < 3 or not тк:
        return []
    из = []
    for i0, i1 in V.эпизоды(снимки):
        a, b = снимки[i0], снимки[i1]
        наши_п = V.ч(b["my_mil_lost"]) - V.ч(a["my_mil_lost"])
        его_п = V.ч(b["p1_mil_lost"]) - V.ч(a["p1_mil_lost"])
        if наши_п + его_п < V.МИН_ПОТЕРЬ:
            continue
        st = V.ближайший_такт(тк, V.ч(a["gametime"]))
        наши_х = CM.разобрать(st.get("fighters"))
        его_х = CM.разобрать(st.get("p1_fighters"))
        строй = CM.поправка_на_строй(st.get("p1_squads_form"), st.get("p1_squads_form_hold"),
                                     st.get("p1_squad_dmg"), st.get("p1_squad_def"),
                                     st.get("p1_squad_hdmg"), st.get("p1_squad_hdef"))
        его_х = {и: CM.со_строем(х, строй["урон"], строй["щит"]) for и, х in его_х.items()}
        A = V.сторона(a, V.СОСТАВ_НАШ, наши_х)
        B = V.сторона(a, V.СОСТАВ_ЕГО, его_х)
        if not A or not B:
            continue
        лок_наш = лок_его = 0
        насыщено = False
        for x in снимки[i0:i1 + 1]:
            # с 26.09 в снимке есть точные числа клеток контакта (`cells`, без
            # потолка) — они главнее знаков сетки, и насыщения при них нет
            точные = x.get("cells")
            if isinstance(точные, list) and точные:
                кл = [[к["x"], к["y"], к["наших"], к["его"]] for к in точные if isinstance(к, dict) and к.get("его", 0) > 0]
                потолок = 10 ** 9
            else:
                кл = x.get("бой") or []
                потолок = 62 if "cells" in x else 36
            s1 = sum(к[2] for к in кл)
            s2 = sum(к[3] for к in кл)
            if s1 + s2 > лок_наш + лок_его:
                лок_наш, лок_его = s1, s2
            if any(к[2] >= потолок or к[3] >= потолок for к in кл):
                насыщено = True
        cx, cy = V.ч(st.get("my_cx")), V.ч(st.get("my_cy"))
        дист = None
        for x in снимки[i0:i1 + 1]:
            for к in (x.get("бой") or []):
                d = math.hypot(к[0] - cx, к[1] - cy)
                дист = d if дист is None else min(дист, d)
        место = "нет клеток" if дист is None else ("дома" if дист <= 3 else ("в поле" if дист <= 8 else "у него"))
        из.append({"каталог": каталог, "gt": int(V.ч(a["gametime"])),
                   "длина": max(5.0, V.ч(b["gametime"]) - V.ч(a["gametime"])),
                   "наши_п": наши_п, "его_п": его_п, "A": A, "B": B,
                   "n_наш": sum(n for n, _ in A), "n_его": sum(n for n, _ in B),
                   "лок_наш": лок_наш, "лок_его": лок_его, "насыщено": насыщено, "место": место})
    return из


def оценить(строки, k):
    """Метрики предсказания потерь обеих сторон при коэффициенте k."""
    ошибки = []
    знак_верен = знак_всего = 0
    for э in строки:
        п = K.потери_за_бой(э["A"], э["B"], э["длина"], э["лок_наш"], э["лок_его"],
                            э["насыщено"], k=k, шум=None)
        for факт, пред in ((э["наши_п"], п["наши"]), (э["его_п"], п["его"])):
            ошибки.append(math.log2((пред + 0.5) / (факт + 0.5)))
        if abs(math.log2((э["его_п"] + 0.5) / (э["наши_п"] + 0.5))) >= 0.3:
            знак_всего += 1
            знак_верен += (п["его"] > п["наши"]) == (э["его_п"] > э["наши_п"])
    return {"n": len(ошибки), "смещение": S.median(ошибки), "abs": S.median(abs(e) for e in ошибки),
            "в_2_раза": sum(1 for e in ошибки if abs(e) <= 1) / len(ошибки),
            "знак": знак_верен / знак_всего if знак_всего else None, "знак_n": знак_всего}


def подобрать_k(строки):
    """k, при котором медиана log2(пред/факт) по обеим сторонам равна нулю."""
    lo, hi = 1e-4, 1.0
    for _ in range(40):
        mid = math.sqrt(lo * hi)
        if оценить(строки, mid)["смещение"] > 0:
            hi = mid
        else:
            lo = mid
    return math.sqrt(lo * hi)


def печать(имя, о):
    print("%-26s n %4d  смещение %+5.2f  |log2| %4.2f  в 2 раза %3.0f%%  знак %s" % (
        имя, о["n"], о["смещение"], о["abs"], 100 * о["в_2_раза"],
        f"{100 * о['знак']:.0f}% ({о['знак_n']})" if о["знак"] is not None else "—"))


def main():
    корни = [a for a in sys.argv[1:] if not a.startswith("--")]
    if not корни:
        raise SystemExit(__doc__)
    строки = []
    for корень in корни:
        for снап in sorted(glob.glob(os.path.join(корень, "**", "coss3_snap.jsonl"), recursive=True)):
            строки.extend(эпизоды_с_составами(os.path.dirname(снап)))
    print(f"эпизодов боя: {len(строки)}; потерь наших {sum(э['наши_п'] for э in строки):.0f}, "
          f"его {sum(э['его_п'] for э in строки):.0f}; длина медиана {S.median(э['длина'] for э in строки):.0f} с")
    k = K.K_УДАРОВ_В_СЕК
    if "--fit" in sys.argv:
        чистые = [э for э in строки if not э["насыщено"] and э["лок_наш"] and э["лок_его"]]
        k = подобрать_k(чистые)
        print(f"подобрано k = {k:.4f} ударов/с на бойца по {len(чистые)} эпизодам без насыщения "
              f"(в ядре {K.K_УДАРОВ_В_СЕК:.4f})")
    печать("ВСЕ ЭПИЗОДЫ", оценить(строки, k))
    for место in ("дома", "в поле", "у него"):
        ч_ = [э for э in строки if э["место"] == место]
        if len(ч_) >= 8:
            печать(f"  место: {место}", оценить(ч_, k))
    печать("  без насыщения клетки", оценить([э for э in строки if not э["насыщено"]], k))
    печать("  с насыщением («+»)", оценить([э for э in строки if э["насыщено"]], k))
    крупные = [э for э in строки if э["наши_п"] + э["его_п"] >= 20]
    печать("  крупные (потерь >= 20)", оценить(крупные, k))
    # отдельно по сторонам
    for сторона, поле in (("наши потери", "наши"), ("его потери", "его")):
        ош = []
        for э in строки:
            п = K.потери_за_бой(э["A"], э["B"], э["длина"], э["лок_наш"], э["лок_его"], э["насыщено"], k=k, шум=None)
            ош.append(math.log2((п[поле] + 0.5) / (э[f"{поле}_п"] + 0.5)))
        print("%-26s смещение %+5.2f  |log2| %4.2f  в 2 раза %3.0f%%" % (
            "  " + сторона, S.median(ош), S.median(abs(e) for e in ош), 100 * sum(1 for e in ош if abs(e) <= 1) / len(ош)))


if __name__ == "__main__":
    main()
