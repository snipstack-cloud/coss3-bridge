def сетка(строки, потолок=None):
    """Список строк сетки -> [[int]]; знаки как в блоке: 1-9, a-z = 10-35, A-Z = 36-61,
    '+' = потолок и больше (36 в старых записях, 62 с 26.09)."""
    потолок = ПОТОЛОК_ПЛЮС if потолок is None else потолок
    из = []
    for s in строки or []:
        ряд = []
        for c in str(s):
            if c == "+":
                ряд.append(потолок)
            else:
                ряд.append(coss3_map.счёт(c))
        из.append(ряд)
    return из


def сумма(сет):
    return sum(sum(r) for r in сет)


def центр(сет):
    """Взвешенный центр сетки или None."""
    s = wx = wy = 0
    for y, r in enumerate(сет):
        for x, v in enumerate(r):
            s += v
            wx += v * x
            wy += v * y
    return (wx / s, wy / s) if s else None


def argmax_клетка(сет):
    лучшая, m = None, 0
    for y, r in enumerate(сет):
        for x, v in enumerate(r):
            if v > m:
                m, лучшая = v, (x, y)
    return лучшая


