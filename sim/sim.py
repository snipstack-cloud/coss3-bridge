class Запись:
    """Записанная партия: враг, карта, цены апгрейдов, начальное состояние."""

    def __init__(self, каталог):
        self.каталог = каталог
        self.снапы = []
        # потолок знака «+» в сетках этой записи: 62, если мост уже писал точные
        # клетки (`cells` в снимке появилось вместе с A-Z 26.09), иначе 36
        self.потолок = 62 if any("cells" in x for x in self.снапы) else 36
        for s in open(os.path.join(каталог, "coss3_snap.jsonl"), encoding="utf-8"):
            s = s.strip()
            if s:
                try:
                    x = json.loads(s)
                except json.JSONDecodeError:
                    continue
                if "gametime" in x:
                    self.снапы.append(x)
        self.снапы.sort(key=lambda x: ч(x["gametime"]))
        self.такты = []
        for s in open(os.path.join(каталог, "coss3_bot.jsonl"), encoding="utf-8"):
            s = s.strip()
            if not s:
                continue
            try:
                r = json.loads(s)
            except json.JSONDecodeError:
                continue
            st = r.get("state")
            if isinstance(st, dict) and "gametime" in st:
                self.такты.append((ч(st["gametime"]), st, r))
        self.такты.sort(key=lambda x: x[0])
        гр = [i for i in range(1, len(self.такты)) if self.такты[i][0] < self.такты[i - 1][0] - 60]
        if гр:
            self.такты = self.такты[гр[-1]:]
        self.цены_апгрейдов = {}
        for _, st, _ in self.такты:
            for поле in ("upg_shown", "upg_aca"):
                for кусок in str(st.get(поле) or "").split(","):
                    if "=" in кусок:
                        имя, цена = кусок.split("=", 1)
                        import re
                        self.цены_апгрейдов.setdefault(имя.strip(), {БУКВЫ[m[0]]: int(m[1]) for m in re.findall(r"([fwsgic])(\d+)", цена)})
        # наша ратуша: в первых тактах ратуши ещё нет и my_cx/my_cy = 0,0 — брать первый
        # такт с ратушей (иначе дом уезжает в угол, а базой врага становятся наши же здания)
        self.my_cx, self.my_cy = 0.0, 0.0
        for gt, st, _ in self.такты:
            if ч(st.get("centers")) > 0 and (ч(st.get("my_cx")) or ч(st.get("my_cy"))):
                self.my_cx, self.my_cy = ч(st.get("my_cx")), ч(st.get("my_cy"))
                break
        # база врага: центр ЕГО зданий в brow (легенда coss3_map: H наш центр, b наше
        # здание, a союзник, e враг) — только «e», по одному на клетку; до 26.09 brow
        # читалась как сетка чисел, и наши «b» весили 11, а «H» ноль. Если brow нет —
        # центр его крестьян на 150–420 с
        self.en_base = None
        for gt, st, _ in self.такты:
            b = st.get("brow")
            if isinstance(b, list):
                c = центр([[1 if ch == "e" else 0 for ch in str(row)] for row in b])
                if c and math.hypot(c[0] - self.my_cx, c[1] - self.my_cy) > 3:
                    self.en_base = c
                    break
        if self.en_base is None:
            for gt, st, _ in self.такты:
                if 150 <= gt <= 420 and isinstance(st.get("prow"), list):
                    c = центр(сетка(st["prow"]))
                    if c:
                        self.en_base = c
                        break
        if self.en_base is None:
            self.en_base = (15 - self.my_cx, 15 - self.my_cy)

    def снимок_до(self, t):
        лучший = self.снапы[0]
        for x in self.снапы:
            if ч(x["gametime"]) <= t:
                лучший = x
            else:
                break
        return лучший

    def такт_до(self, t):
        лучший = self.такты[0]
        for x in self.такты:
            if x[0] <= t:
                лучший = x
            else:
                break
        return лучший

    def начальное(self):
        s = dict(self.снапы[0])
        st = self.такты[0][1]
        for k in ("stables", "academi", "houses", "food_ready"):
            s.setdefault(k, st.get(k))
        return s


