            # ОТВЕРГНУТО (§16в): по замеру участков становится 27 уже через минуту после
            # мельницы, пик 32 на 2-3-й минуте, дальше спад до 18 к 16-й. При 5,3 в
            # секунду на участок это 95-170 в секунду — больше, чем способны собрать
            # люди (40 человек дают 60), то есть предел по участкам не связывает НИКОГДА
            # после первой минуты. Моя первая редакция считала участки по командам SEED и
            # получала один: еда падала до 1438 против 4974, пехота до 98 против 104.
            зрело = t - self.мельница_t - ЗРЕЕТ_ПОЛЕ
            работники["food_ready"] = (0 if зрело < 0 else
                                       min(1.0, зрело / РАЗГОН_ПОЛЯ) if РАЗГОН_ПОЛЯ > 0 else 1)
            # число участков — по замеру, для состояния и для мер разбора
            мин = max(0.0, (t - self.мельница_t - ЗРЕЕТ_ПОЛЕ) / 60.0)
            # кривая по замеру: 27 участков через минуту, 32 на 2-3-й, дальше спад
            # примерно на один в минуту, к 16-й остаётся 18-19
