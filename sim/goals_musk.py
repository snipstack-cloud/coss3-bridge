"""Лестница и награда стратегии «МУШКЕТЁРЫ» (28.09, по указанию игрока).

Замысел прислан игроком: поощрять путь «ничего → +60 % урона → +скорость
перезарядки → размен 1:1». Здесь он переведён в измеримое, и каждое место, где
мера пришлось изменить, названо — иначе лестница награждала бы за недостижимое.

ЧТО ПРИШЛОСЬ ПОПРАВИТЬ ПРОТИВ ПРИСЛАННОГО ЗАМЫСЛА, с причинами:

* ЛИНЕЙКА ПАУЗЫ (aca.31, aca.33) НЕДОСТИЖИМА в 15-минутной партии: она стоит
  15200 угля и 6000 камня при наших 1000 угля к 900-й секунде. Поэтому «1:1
  против пики», ради которого замысел и строился, в турнирном сроке не берётся:
  достижимо +35 % урона (aca.12-14), и порог падает с 2,4 мушкетёра на пикинёра
  только до ~2,0. Ступень 4 переписана на достижимый потолок урона;
* «исследованы aca.12-15» требует АКАДЕМИИ, а она стоит 1050 дерева и 1230 камня.
  Камня к шестой минуте 1771, а дерева НИКОГДА больше 230 — оно тратится на дома
  и стройки (замер 28.09). Поэтому в ступень 2 входит и само наличие академии, а
  стратегу добавлено решение «люди на дерево и камень»: без него ступени 2 и 4
  недостижимы по построению, и сеть училась бы обходить их;
* «мушкетёры регулярно выигрывают лобовые столкновения» и «≥ 60 % урона по
  юнитам» раскладки по видам требуют, а симулятор её НЕ ИМЕЕТ. Считаем
  приблизительно: его потери делятся по доле мушкетёров в нашем уроне, наши — по
  доле мушкетёров в клетке (`sim.убито_пик_мушкетёрами`,
  `sim.потери_мушкетёров_от_пик`). Для награды годится, для вывода о механике нет;
* «противник вынужден контрить мушкетёров» не измеримо вовсе: враг — ЗАПИСЬ, его
  поведение от нас не зависит. Эта часть шестой ступени снята, и вместо неё —
  доля мушкетёров в наших убийствах его бойцов;
* скользящее окно 3-5 минут заменено счётом за партию: снимки идут раз в 5 с, и
  окно из них шумит сильнее, чем разница между политиками.

ЧИСЛА ПОРОГОВ взяты из живых замеров, а не назначены: 20 бойцов к 300 с (ступень 1
общей лестницы держится ключом `--food-floor`), 1:1 против пики — из счёта с
попаданием в голову (`world.md`, 28.09), 2 казармы — из слов игрока про осаду.
"""
import io
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

ч = lambda d, k: float((d or {}).get(k) or 0)

СТУПЕНИ = (
    ("1 линия", "казарма и 8+ мушкетёров, их доля в армии 30 %+"),
    ("2 урон", "академия стоит и взят хотя бы один из aca.12-15"),
    ("3 масса", "20+ мушкетёров и их доля 50 %+"),
    # СТУПЕНЬ 4 ПЕРЕПИСАНА 28.09, ДО ПЕРВОГО ПРОГОНА. В присланном замысле это была
    # «скорость перезарядки, aca.31 и aca.33 -> размен 1:1». Цены по записям:
    # aca.31 — 5500 золота, 4200 железа и 6000 камня; aca.33 — 5500 золота,
    # 5000 дерева и 15200 УГЛЯ. К 900-й секунде при копящем хозяйстве у нас золота
    # 15158, железа 6588, а угля 1000 — линейка паузы недостижима в турнирной
    # партии по построению, и награждать за неё значило бы учить недостижимому.
    # Достижимый потолок урона: aca.12 (5000 железа), aca.13 (4000 золота) и
    # aca.14 (7000 золота) — вместе +35 %; aca.15 требует 11000 угля и тоже вне игры.
    ("4 потолок урона", "взяты все три доступных: aca.12, aca.13, aca.14 (+35 %)"),
    ("5 размен", "мушкетёры против пик: убито/потеряно не хуже 1:1,2"),
    ("6 ядро", "мушкетёрами сделано 60 %+ наших убийств его бойцов"),
)

# веса ступеней из присланного замысла: урон 1,5, скорость 2,0 — ключевые скачки
ВЕСА = (1.0, 1.5, 1.0, 2.0, 1.5, 1.0)
ПОРОГ_РАЗМЕНА = 1 / 1.2        # 0,83: «не хуже 1:1,2»
ДОЛЯ_ЯДРА = 0.6
ВЕС_РАЗМЕНА = 1.5              # R_exchange, потолок 2,0 по замыслу
ПОТОЛОК_РАЗМЕНА = 2.0
ВЕС_ДАВЛЕНИЯ = 1.0             # R_pressure, потолок 0,6
ПОТОЛОК_ДАВЛЕНИЯ = 0.6
ПЛАТА_ЗА_МУШКЕТЁРА = 0.004     # R_loss_musk, между 0,002 и 0,005 по замыслу


def доли_и_числа(сим, история):
    """Всё, из чего складываются ступени, одним словарём — чтобы печатать и мерить."""
    посл = история[-1] if история else {}
    муск = ч(посл, "mil_shooters")
    армия = муск + ч(посл, "mil_inf") + ч(посл, "mil_cav")
    # ПИК МУШКЕТЁРОВ, а не число в конце: к концу их могли перебить, и ступень
    # «масса» тогда не берётся у политики, которая их набрала и потратила.
    пик_муск = max([ч(s, "mil_shooters") for s in история] or [0.0])
    доля_сейчас = (муск / армия) if армия > 0 else 0.0
    доля_пик = max([(ч(s, "mil_shooters") /
                     max(ч(s, "mil_shooters") + ч(s, "mil_inf") + ч(s, "mil_cav"), 1e-9))
                    for s in история] or [0.0])
    взято = {x.strip() for x in str(посл.get("upg_done") or "").split(",") if x.strip()}
    убил = getattr(сим, "убито_пик_мушкетёрами", 0.0)
    потерял = getattr(сим, "потери_мушкетёров_от_пик", 0.0)
    размен = убил / потерял if потерял > 0 else (убил if убил > 0 else 0.0)
    всего_убито = getattr(сим, "убито_бойцов", 0.0)
    доля_ядра = (убил / всего_убито) if всего_убито > 0 else 0.0
    тактов = max(len(история), 1)
    давление = getattr(сим, "тактов_давления_мушк", 0) / тактов
    return dict(муск=муск, армия=армия, пик_муск=пик_муск, доля=доля_сейчас,
                доля_пик=доля_пик, взято=взято, казарм=ч(посл, "ba17"),
                академия=ч(посл, "academies") or ч(посл, "academi"),
                убил=убил, потерял=потерял, размен=размен, доля_ядра=доля_ядра,
                давление=давление, потери_муск=потерял)


def ступени(сим, история):
    """(взятые номера, прогресс к каждой 0..1) — по тем же числам, что печать."""
    д = доли_и_числа(сим, история)
    прогресс = {}
    взято = set()

    прогресс[1] = min(1.0, д["пик_муск"] / 8.0) * (1.0 if д["казарм"] > 0 else 0.0)
    if д["казарм"] > 0 and д["пик_муск"] >= 8 and д["доля_пик"] >= 0.30:
        взято.add(1)

    есть_урон = bool(д["взято"] & {"aca.12", "aca.13", "aca.14", "aca.15"})
    прогресс[2] = (1.0 if есть_урон else (0.5 if д["академия"] > 0 else 0.0))
    if д["академия"] > 0 and есть_урон:
        взято.add(2)

    прогресс[3] = min(1.0, д["пик_муск"] / 20.0)
    if д["пик_муск"] >= 20 and д["доля_пик"] >= 0.50:
        взято.add(3)

    # ПОТОЛОК УРОНА вместо линейки паузы: см. причину в СТУПЕНЯХ.
    доступные = {"aca.12", "aca.13", "aca.14"}
    взято_урона = len(д["взято"] & доступные)
    прогресс[4] = взято_урона / 3.0
    if взято_урона == 3:
        взято.add(4)

    прогресс[5] = min(1.0, д["размен"] / ПОРОГ_РАЗМЕНА) if ПОРОГ_РАЗМЕНА else 0.0
    if д["размен"] >= ПОРОГ_РАЗМЕНА and д["убил"] >= 3:
        взято.add(5)

    прогресс[6] = min(1.0, д["доля_ядра"] / ДОЛЯ_ЯДРА)
    if д["доля_ядра"] >= ДОЛЯ_ЯДРА and д["убил"] >= 5:
        взято.add(6)
    return взято, прогресс, д


def награда(сим, история) -> float:
    """R = ступени + размен + давление − плата за мушкетёров, по замыслу игрока."""
    взято, прогресс, д = ступени(сим, история)
    r = sum(ВЕСА[i - 1] * (1.0 if i in взято else прогресс.get(i, 0.0))
            for i in range(1, len(СТУПЕНИ) + 1))
    r += ВЕС_РАЗМЕНА * min(д["размен"], ПОТОЛОК_РАЗМЕНА)
    r += ВЕС_ДАВЛЕНИЯ * min(д["давление"], ПОТОЛОК_ДАВЛЕНИЯ)
    # ПЛАТА ТОЛЬКО ПРИ ДАВЛЕНИИ, как в общей лестнице: иначе сеть учится не
    # использовать мушкетёров вовсе, чтобы их не терять (было 25.09).
    if д["давление"] >= 0.05:
        r -= ПЛАТА_ЗА_МУШКЕТЁРА * д["потери_муск"]
    return r
