#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""ОТХОД ИЗ КЛЕТКИ КОНТАКТА — живые записи (29.09). Кто уходит живым, а кто гибнет.

Вопрос §18: закон «бьют все» завышает удар меньшинства, и вероятная причина —
из проигранной клетки уходят, а уходящий не бьёт. Прежде чем ставить в симулятор
механику отхода, её надо ИЗМЕРИТЬ: сколько бойцов каждой стороны за окно 5 с
покидают клетку живыми, в зависимости от перевеса.

Правила счёта (те же, что в `бой_по_событиям.py`):
* окно — пара соседних снимков, берётся, только если пришли ВСЕ события гибели;
* клетка контакта — из точного `cells` предыдущего снимка, обе стороны > 0;
* число в клетке в следующем снимке — из `cells`, если клетка там есть, иначе из
  сетки (`arow` наши, `frow` его; «.» — ноль). `cells` пишет только клетки, где
  стоят НАШИ вместе с его бойцами или крестьянами, так что её отсутствие значит
  «одной из сторон там нет» — сетка это и называет;
* убыль = было − погибло в клетке − стало. Положительная — ушли живыми (за вычетом
  пришедших, поэтому это НИЖНЯЯ граница ухода); отрицательная — пришли;
* то же для окна 3×3 вокруг клетки: уход дальше соседней клетки — это уже отход,
  а не колыхание боя через границу.

    python3 sim/отход_по_клеткам.py [--h=6] ~/coss3-res/2026-09-28 [~/coss3-res/2026-09-27 ...]
"""
import json, math, os, sys
from collections import defaultdict

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from бой_по_событиям import БОЙЦЫ, ПОЛОСЫ, полоса, центр, место  # noqa: E402
from sim import сетка  # noqa: E402

ПОТОЛОК = 62  # знак «+» при сетке A–Z (26.09 и позже; все записи с событиями новее)


def _грид(з, ключ):
    if з.get(ключ + "0") is not None and not з.get(ключ):
        строки = [з.get(f"{ключ}{i}", "") for i in range(64) if з.get(f"{ключ}{i}") is not None]
    else:
        строки = з.get(ключ)
    return сетка(строки, ПОТОЛОК) if строки else None


def _клетки(з):
    return {(c["x"], c["y"]): c for c in (з.get("cells") or []) if isinstance(c, dict)}


def _число(кл, грид, ключ, x, y):
    c = кл.get((x, y))
    if c is not None:
        return c.get(ключ) or 0
    if грид and 0 <= y < len(грид) and 0 <= x < len(грид[y]):
        return грид[y][x]
    return None


def _окно(кл, грид, ключ, x, y, r=1):
    s = 0
    for yy in range(y - r, y + r + 1):
        for xx in range(x - r, x + r + 1):
            v = _число(кл, грид, ключ, xx, yy)
            if v is None:
                continue
            s += v
    return s


ГОРИЗОНТ = 1  # снимков вперёд (1 = 5 с)


def запись(путь, итог, счёт):
    снимки = [з for з in (json.loads(s) for s in open(путь, encoding="utf-8") if s.strip().startswith("{"))
              if "kills_n" in з]
    события = {}
    for з in снимки:
        for с in (з.get("гибель") or []):
            if len(с) == 11:
                события[с[0]] = с
    for i in range(len(снимки) - ГОРИЗОНТ):
        a, b = снимки[i], снимки[i + ГОРИЗОНТ]
        n0, n1 = int(a["kills_n"]), int(b["kills_n"])
        if n1 < n0 or float(b.get("gametime", 0)) - float(a.get("gametime", 0)) > 8 * ГОРИЗОНТ:
            continue
        нужно = range(n0 + 1, n1 + 1)
        if any(q not in события for q in нужно):
            счёт["окон неполных"] += 1
            continue
        кa, кb = _клетки(a), _клетки(b)
        fb, ab = _грид(b, "frow"), _грид(b, "arow")
        if fb is None or ab is None:
            счёт["без сетки"] += 1
            continue
        fa, aa = _грид(a, "frow"), _грид(a, "arow")
        мой, его = центр(a.get("brow"), "bH"), центр(a.get("brow"), "e")
        гибель = defaultdict(lambda: [0, 0])  # (x, y) -> [наших, его]
        for q in нужно:
            с = события[q]
            if с[3] in БОЙЦЫ:
                гибель[(с[4], с[5])][0 if с[2] == 0 else 1] += 1
        for (x, y), c in кa.items():
            н, е = c.get("наших") or 0, c.get("его") or 0
            if н <= 0 or е <= 0:
                continue
            счёт["клеток"] += 1
            п = полоса(н / е)
            м = место(x, y, мой, его)
            гн, ге = гибель[(x, y)]
            н1 = _число(кb, ab, "наших", x, y)
            е1 = _число(кb, fb, "его", x, y)
            # окно 3×3: было, погибло, стало
            н9a, е9a = _окно(кa, aa, "наших", x, y), _окно(кa, fa, "его", x, y)
            н9b, е9b = _окно(кb, ab, "наших", x, y), _окно(кb, fb, "его", x, y)
            гн9 = sum(гибель[(xx, yy)][0] for xx in range(x - 1, x + 2) for yy in range(y - 1, y + 2))
            ге9 = sum(гибель[(xx, yy)][1] for xx in range(x - 1, x + 2) for yy in range(y - 1, y + 2))
            for ключ in ((м, п), ("всё", п)):
                r = итог[ключ]
                r["n"] += 1
                r["наших"] += н; r["его"] += е
                r["гиб_наш"] += гн; r["гиб_его"] += ге
                r["ушло_наш"] += н - гн - н1
                r["ушло_его"] += е - ге - е1
                r["наших9"] += н9a; r["его9"] += е9a
                r["ушло9_наш"] += н9a - гн9 - н9b
                r["ушло9_его"] += е9a - ге9 - е9b
                # клетка опустела: сторона ушла целиком (не погибла вся)
                if н1 == 0 and гн < н:
                    r["наши_ушли_целиком"] += 1
                if е1 == 0 and ге < е:
                    r["его_ушли_целиком"] += 1


def main():
    global ГОРИЗОНТ
    арг = sys.argv[1:]
    if арг and арг[0].startswith("--h="):
        ГОРИЗОНТ = int(арг.pop(0)[4:])
    пути = [os.path.expanduser(p) for p in (арг or ["~/coss3-res/2026-09-28"])]
    итог = defaultdict(lambda: defaultdict(float))
    счёт = defaultdict(int)
    n = 0
    for корень in пути:
        for d, _, ф in sorted(os.walk(корень)):
            if "coss3_snap.jsonl" in ф:
                запись(os.path.join(d, "coss3_snap.jsonl"), итог, счёт)
                n += 1
    print(f"записей {n}; " + ", ".join(f"{k} {v}" for k, v in счёт.items()))
    print("доли — на одного бойца в клетке за окно 5 с; «ушло» = было − погибло − стало (нижняя граница)")
    print(f"{'место':7} {'полоса':9} {'окон':>5} | {'наших':>6} {'гиб%':>5} {'ушло%':>6} {'3×3%':>6} {'целиком':>7} |"
          f" {'его':>6} {'гиб%':>5} {'ушло%':>6} {'3×3%':>6} {'целиком':>7}")
    for м in ("у него", "в поле", "у нас", "всё"):
        for _, _, п in ПОЛОСЫ:
            r = итог.get((м, п))
            if not r or not r["n"]:
                continue
            def д(a, b):
                return 100.0 * a / b if b else float("nan")
            print(f"{м:7} {п:9} {int(r['n']):5d} | {int(r['наших']):6d} {д(r['гиб_наш'], r['наших']):5.1f}"
                  f" {д(r['ушло_наш'], r['наших']):6.1f} {д(r['ушло9_наш'], r['наших9']):6.1f}"
                  f" {д(r['наши_ушли_целиком'], r['n']):6.1f}% |"
                  f" {int(r['его']):6d} {д(r['гиб_его'], r['его']):5.1f} {д(r['ушло_его'], r['его']):6.1f}"
                  f" {д(r['ушло9_его'], r['его9']):6.1f} {д(r['его_ушли_целиком'], r['n']):6.1f}%")


if __name__ == "__main__":
    main()
