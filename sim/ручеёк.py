#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""ЗАПРЕТ РУЧЕЙКА ПРОТИВ p3о — опыт на одинаковых начальных состояниях (8.10, §113, задание игрока).

Сравниваются на одних и тех же развилках (кейсы игрока против агента «p3о» — он стоит отрядами у базы, как игрок):
  текущая досылка          стратегия `шт_s2_оборона` как есть (подмога по 4-8 бойцов каждый такт);
  сбор волны размера N     ключи `подмога` = `порог` = N — подмога и новая волна только от N свободных;
  сбор до порога размена   ключ `ручеёк: 1` с `размен_при` ∈ {0,8; 1,0; 1,3} — прогноз боя (`прогноз.py`) перед каждым приказом.
Варианты сцены: его отряды у базы × {0,7; 1,0; 1,4} и сдвиг ±1 клетка (`развилка`-варианты), наши дома × {0,7; 1,0; 1,3}
(скорость поступления подмоги). Порог подбирается на ЧЁТНЫХ сценах, проверяется на НЕЧЁТНЫХ. Эпизод — до конца записи.

Метрики (на эпизод, медианы/суммы по набору): итог по стоимости (его потери − наши, по цене найма пикинёра), наши
крестьяне; погибло в малых группах (наши потери в боях, где наших в клетке < 15 — ручеёк); размер нашей группы при
первом контакте; время первого результативного удара; тактов накопления без выхода; точность прогноза размена
(прогноз потерь за 60 с против факта в те же 60 с, медиана |log2|). Последние две — чтобы «запрет ручейка» не стал
«запретом боя».

    python3 sim/ручеёк.py [--зёрен 2] [--json sim/ночь/…/ручеёк.json]
"""
import json
import math
import os
import statistics as St
import sys
from collections import defaultdict
from multiprocessing import Pool

К = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, К)
sys.path.insert(0, os.path.dirname(К))

ПОЛИТИКИ = {
    "досылка": {},
    "сбор 50": {"подмога": 50, "порог": 50},
    "ручеёк 1,0": {"ручеёк": 1, "размен_при": 1.0},
    # §113б: прогноз с его подкреплением — все его бойцы в 3 клетках от цели (окно 1 одобрял бои, которые симулятор проигрывал:
    # соседние его кучи вступают), и остаток группы ≥ 0,5
    "ручеёк 1,0 окно 3": {"ручеёк": 1, "размен_при": 1.0, "рядом_окно": 3},
    "ручеёк 1,3 окно 3": {"ручеёк": 1, "размен_при": 1.3, "рядом_окно": 3},
    "ручеёк 1,0 окно 3 ост 0,5": {"ручеёк": 1, "размен_при": 1.0, "рядом_окно": 3, "остаток_при": 0.5},
}
ТИПЫ = ("сбор", "контакт", "подкрепление", "окно_удара", "отход")
ЦЕНА_БОЙЦА = 48.0


def _хоз():
    return json.load(open(os.path.join(К, "поиск", "шт_s2_оборона.json"), encoding="utf-8"))["итог"]


def сцены():
    кейсы = json.load(open(os.path.join(К, "кейсы", "кейсы.json"), encoding="utf-8"))
    базовые = [k for k in кейсы if k["источник"] == "игрок" and k["агент"] == "p3о" and k["тип"] in ТИПЫ]
    из = []
    for i, k in enumerate(базовые):
        for kе in (0.7, 1.0, 1.4):
            for kн in (0.7, 1.0, 1.3):
                из.append(dict(k, k=kе, дома=kн, dx=0, dy=0, сцена=i, половина="подбор" if i % 2 == 0 else "проверка"))
    return из


def эпизод(сц, политика, seed):
    import развилка as R
    import учитель as У
    import sim as SIM
    import combat
    if not hasattr(combat, "_залпы_исх"):
        combat._залпы_исх = combat.залпы
    сим, _ = R.построить(сц["запись"], float(сц["t"]), сц["агент"], seed)
    N = len(сим.враг.h)
    for имя in ("h", "s"):
        g = getattr(сим.враг, имя, None)
        if g is not None:
            for y in range(N):
                for x in range(N):
                    g[y][x] *= сц["k"]
    for род in сим.группы[0]["состав"]:
        сим.группы[0]["состав"][род] *= сц["дома"]
    сим.эк.армия = {"mil_inf": sum(г["состав"]["infantry17"] for г in сим.группы), "mil_shooters": sum(г["состав"]["musk17"] for г in сим.группы),
                    "mil_cav": sum(г["состав"]["dragoon17"] for г in сим.группы)}
    т = У.ТеньУчителя(dict(_хоз(), **ПОЛИТИКИ[политика]))
    t0 = сим.t
    п0, у0, кр0 = сим.my_mil_lost, сим.убито_бойцов, сим.my_pea_lost
    конец = float(сим.з.снапы[-1]["gametime"])
    ряд = []            # (t, наши потери, его убито) по тактам — для факта против прогноза
    первый_удар = None
    while сим.t < min(конец, t0 + 600.0) and not сим.исход:
        os.environ["COSS3_WAVE_CONTRACT"] = "1"
        st = сим.состояние()
        сим.команды(т(st) or [])
        сим.такт()
        ряд.append((сим.t, сим.my_mil_lost, сим.убито_бойцов))
        if первый_удар is None and сим.убито_бойцов - у0 >= 1:
            первый_удар = сим.t - t0
    SIM.ФОРМА_ВРАГА = None
    # ручеёк-потери: наши потери в боях, где наших в клетке < 15 (журнал боя: (t, cx, cy, режим, n_всего, его, наши, его_потери, …))
    малые = sum(float(з[6]) for з in сим.журнал_боя if з[0] >= t0 and float(з[4]) < 15)
    первый_контакт = next((float(з[4]) for з in сим.журнал_боя if з[0] >= t0), None)
    мера = т.ж.реестр.мера
    # точность прогноза: предсказанные потери за 60 с против факта
    ошибки = []
    for п in getattr(т.ж, "прогнозы", []):
        a = next((r for r in ряд if r[0] >= п["t"]), None)
        b = next((r for r in ряд if r[0] >= п["t"] + 60), None)
        if a and b:
            факт_н, факт_е = b[1] - a[1], b[2] - a[2]
            if п["наши_потери"] > 0 and факт_н > 0:
                ошибки.append(abs(math.log2(п["наши_потери"] / факт_н)))
            if п["его_потери"] > 0 and факт_е > 0:
                ошибки.append(abs(math.log2(п["его_потери"] / факт_е)))
    return dict(политика=политика, сцена=сц["сцена"], тип=сц["тип"], половина=сц["половина"],
                наши=сим.my_mil_lost - п0, его=сим.убито_бойцов - у0, крест=сим.my_pea_lost - кр0,
                итог=(сим.убито_бойцов - у0 - (сим.my_mil_lost - п0)) * ЦЕНА_БОЙЦА - 2 * ЦЕНА_БОЙЦА * (сим.my_pea_lost - кр0),
                малые=малые, первый_контакт=первый_контакт, первый_удар=первый_удар,
                сбор_тактов=мера.get("ручеёк: тактов сбора", 0), отказов=мера.get("ручеёк: отказов", 0), охота=мера.get("ручеёк: перенацелено на охоту", 0),
                точность=St.median(ошибки) if ошибки else None, прогнозов=len(ошибки),
                армия=sum(sum(г["состав"].values()) for г in сим.группы), его_армия=сим.враг.всего())


def _задача(з):
    сц, политика, seed = з
    try:
        return эпизод(сц, политика, seed)
    except Exception as e:
        return dict(политика=политика, сцена=сц["сцена"], тип=сц["тип"], половина=сц["половина"], ошибка=f"{type(e).__name__}: {e}")


def main():
    def опц(имя, умолч, тип=int):
        return тип(sys.argv[sys.argv.index(имя) + 1]) if имя in sys.argv else умолч
    зёрен = опц("--зёрен", 2)
    сц = сцены()
    зад = [(с, п, 500 + z) for с in сц for п in ПОЛИТИКИ for z in range(зёрен)]
    print(f"РУЧЕЁК против p3о: {len({с['сцена'] for с in сц})} развилок × 9 вариантов = {len(сц)} сцен × {len(ПОЛИТИКИ)} политик × {зёрен} зёрен = {len(зад)} партий", flush=True)
    with Pool(12) as пул:
        р = [x for x in пул.imap_unordered(_задача, зад, chunksize=4)]
    ош = [x for x in р if "ошибка" in x]
    р = [x for x in р if "ошибка" not in x]
    if ош:
        print(f"  ошибок: {len(ош)}; первая: {ош[0]['ошибка']}")

    def строка(xs):
        if not xs:
            return "—"
        т = [x["точность"] for x in xs if x["точность"] is not None]
        фк = [x["первый_контакт"] for x in xs if x["первый_контакт"] is not None]
        фу = [x["первый_удар"] for x in xs if x["первый_удар"] is not None]
        return (f"итог {St.mean(x['итог'] for x in xs):7.0f} | наши {St.mean(x['наши'] for x in xs):5.1f} его {St.mean(x['его'] for x in xs):5.1f} "
                f"крест {St.mean(x['крест'] for x in xs):4.1f} | в малых группах {St.mean(x['малые'] for x in xs):5.1f} | "
                f"группа при 1-м контакте {St.median(фк) if фк else float('nan'):4.0f} | 1-й удар {St.median(фу) if фу else float('nan'):4.0f} с ({len(фу)}/{len(xs)}) | "
                f"сбор тактов {St.mean(x['сбор_тактов'] for x in xs):4.1f} отказов {St.mean(x['отказов'] for x in xs):4.1f} охота {sum(x['охота'] for x in xs)} | "
                f"прогноз |log2| {St.median(т) if т else float('nan'):.2f} ({sum(x['прогнозов'] for x in xs)})")
    for половина in ("подбор", "проверка"):
        print(f"\n{половина.upper()} ({len({x['сцена'] for x in р if x['половина'] == половина})} развилок):")
        for п in ПОЛИТИКИ:
            print(f"  {п:26} " + строка([x for x in р if x["половина"] == половина and x["политика"] == п]), flush=True)
    print("\nПО ТИПАМ (проверка): итог по стоимости")
    for тип in ТИПЫ:
        куски = []
        for п in ПОЛИТИКИ:
            xs = [x for x in р if x["половина"] == "проверка" and x["политика"] == п and x["тип"] == тип]
            if xs:
                куски.append(f"{п} {St.mean(x['итог'] for x in xs):6.0f}")
        if куски:
            print(f"  {тип:13} " + " | ".join(куски))
    if "--json" in sys.argv:
        json.dump(р, open(опц("--json", "", str), "w", encoding="utf-8"), ensure_ascii=False, indent=0)


if __name__ == "__main__":
    main()
