#!/usr/bin/env python3
"""ЧТО ВЫГОДНЕЕ ПОСЛЕ ДВУХ КАЗАРМ: ТРЕТЬЯ КАЗАРМА, КОНЮШНЯ ИЛИ XVIII ВЕК (1.11, вопрос игрока) — Нидерланды и Польша.

Двойник (`sim/sim.py`) ни конюшни, ни века не знает: в нём пики, стрелки и хозяйство. Поэтому здесь расчёт из кода игры,
а не прогон. Он отвечает на один вопрос: сколько боевой силы прибывает за минуту и за тысячу ресурсов, и когда.

Числа:
  * бойцы — `нации.юниты_из_скрипта()` (unit.script + `case nation of`); XVIII век — живые `en_fighters` записи 1.11
    (pikeman18 85/9, musk18 100/16, dragun18 225/19), dragoon18net — unit.script;
  * кто кому доступен — `country.script:2660-2790` (`_country_AddMember`): Нидерланды — рейтар и драгун из конюшни, в веке
    кирасир, гусар, dragoon18net, pikeman18 и musketeer18 из `ba2`; Польша — крылатый гусар, рейтар pol, драгун pol, в веке
    кирасир, гусар, dragoon18, pikeman18, musketeer18;
  * цены зданий — живой `build_cost` записей 1.11 (третья казарма 2500 дерева / 2500 камня / 12 500 золота, конюшня
    2500 / 100 / 600) и `sim/параметры.json` (церковь tem, депо art, `ba2`); `cen.1` — живой ценник: net 33 000 еды /
    4800 зол / 1800 жел / 1800 угля, pol 30 000 / 4800 / 2200 / 2200; нужны академия, церковь и депо (`country.script:3438`);
  * срок стройки — единицы buildtime; академия (2000) строится ~58 с при 18–20 строителях [замер, 8 записей 30–31.10],
    отсюда 2000 ед. ≈ 58 с при 20 строителях, обратно пропорционально числу строителей.
Сила бойца — «пик-эквивалент» против ЕГО пики (без строя и прокачек): ударов, чтобы убить его пику, против ударов, чтобы
его пика убила нашего (урон = атака − защита по виду оружия, не меньше 1, `miscext2.script:434`), относительно нашей пики.
ДОПУЩЕНИЕ, как в `польша_конница.py`: темп удара в ближнем бою одинаков у всех. Стрелков (драгун) так не сравнить —
для них дан урон пули по его пике за минуту.

    python3 sim/век_казарма_конюшня.py
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import нации as Н  # noqa: E402

СТРОИТЕЛЕЙ = 20
ЕД_НА_С = 58.0 * 20 / 2000          # секунд × строителей на единицу buildtime (академия 2000 ед. ≈ 58 с при 20)

# живые числа XVIII века (en_fighters записи igrok_31_10_Польша_6680: те же у обеих наций)
ВЕК = {"pikeman18": dict(hp=85, atk=9, wkind=1, dpike=0, dsword=0, dbullet=0, цена=dict(food=30, gold=2, iron=0), найм_с=1.25),
       "musketeer18": dict(hp=100, atk=16, wkind=3, pause=469, dpike=0, dbullet=0, цена=dict(food=50, gold=40, iron=40), найм_с=4.5),
       "dragoon18": dict(hp=225, atk=19, wkind=3, pause=531, dpike=0, dbullet=0, цена=dict(food=70, gold=60, iron=7), найм_с=24.0)}

ЗДАНИЯ = {"казарма 3": (dict(wood=2500, stone=2500, gold=12500), 300),
          "конюшня": (dict(wood=2500, stone=100, gold=600), 2000),
          "церковь": (dict(wood=1000, stone=1200, iron=500), 500),
          "депо": (dict(wood=100, stone=1000, coal=1400), 787),
          "казарма века ba2": (dict(wood=1700, stone=2950, gold=4000), 18000)}
ВЕК_ЦЕНА = {"net": dict(food=33000, gold=4800, iron=1800, coal=1800), "pol": dict(food=30000, gold=4800, iron=2200, coal=2200)}


def урон(атакующий, цель):
    вид = {1: "dpike", 2: "dsword", 3: "dbullet"}.get(атакующий.get("wkind"), "dpike")
    return max(1, атакующий["atk"] - int(цель.get(вид) or 0))


def ударов(hp, у):
    return -(-hp // у)


def сила(наш, его_пика, наша_пика):
    """Пик-эквивалент: (его ударов до смерти нашего) / (наших ударов до смерти его) относительно нашей пики."""
    def отношение(u):
        return ударов(u["hp"], урон(его_пика, u)) / ударов(его_пика["hp"], урон(u, его_пика))
    return отношение(наш) / отношение(наша_пика)


def стройка_с(ед):
    return ед * ЕД_НА_С / СТРОИТЕЛЕЙ


def цена_т(ц):
    return " / ".join(f"{v} {к}" for к, v in (("еды", ц.get("food", 0)), ("дер", ц.get("wood", 0)), ("кам", ц.get("stone", 0)),
                                              ("зол", ц.get("gold", 0)), ("жел", ц.get("iron", 0)), ("угл", ц.get("coal", 0))) if v)


def main():
    ю = Н.юниты_из_скрипта()
    ю["dragoon18net"] = dict(ю["dragoon18net"], hp=320, atk=17, pause=500)
    for k, v in ВЕК.items():
        ю.setdefault(k, {}).update(v)
    нации = {"net": dict(имя="НИДЕРЛАНДЫ", пика="pikeman", конюшня=["reiter", "dragoon"], век_конюшня=["cuirassier", "hussar", "dragoon18net"]),
             "pol": dict(имя="ПОЛЬША", пика="pikemanpol", конюшня=["wingedhussar", "reiterpol", "dragoonpol"],
                         век_конюшня=["cuirassier", "hussar", "dragoon18"])}
    for код, н in нации.items():
        наша = ю[н["пика"]]
        print(f"\n================ {н['имя']} (наша пика {н['пика']}: {наша['hp']} hp, атака {наша['atk']}, броня от пики {наша['dpike']}, "
              f"найм {наша['найм_с']} с, {цена_т(наша['цена'])}) ================")
        for его_имя in ("pikeman", "pikemanpol"):
            его = ю[его_имя]
            print(f"\n  против ЕГО пики {его_имя} (броня от пики {его['dpike']}):")
            print(f"  {'боец':14s} {'откуда':22s} {'сила':>5s} {'найм с':>6s} {'в мин':>6s} {'силы/мин':>8s} {'силы на 1000 рес.':>17s}  цена бойца")
            ряды = [(н["пика"], "казарма 3")]
            ряды += [(u, "конюшня") for u in н["конюшня"]]
            ряды += [(u, "век: конюшня") for u in н["век_конюшня"]] + [("pikeman18", "век: ba2"), ("musketeer18", "век: ba2")]
            for u, где in ряды:
                d = ю.get(u)
                if not d or not d.get("atk"):
                    continue
                в_мин = 60.0 / d["найм_с"]
                рес = sum(int(d["цена"].get(r) or 0) for r in ("food", "gold", "iron", "wood", "stone", "coal"))
                if d.get("wkind") == 3:      # стрелок: урон пули по его пике за минуту
                    пуля = урон(d, его)
                    в_мин_выстр = 60.0 / (max(1, d.get("pause") or 375) * 0.03125)
                    print(f"  {u:14s} {где:22s} {'—':>5s} {d['найм_с']:6.2f} {в_мин:6.1f} {'стрелок':>8s} {'':>17s}  {цена_т(d['цена'])}; "
                          f"{d['hp']} hp, пуля {пуля} по его пике, {в_мин_выстр:.1f} выстр/мин")
                    continue
                с = сила(d, его, наша)
                print(f"  {u:14s} {где:22s} {с:5.2f} {d['найм_с']:6.2f} {в_мин:6.1f} {с * в_мин:8.1f} {с * 1000 / рес:17.1f}  {цена_т(d['цена'])}")
        print("\n  ЦЕНА ВХОДА и срок до первого бойца (строителей", СТРОИТЕЛЕЙ, "):")
        for зд in ("казарма 3", "конюшня"):
            ц, ед = ЗДАНИЯ[зд]
            print(f"    {зд:18s} {цена_т(ц):38s} стройка ~{стройка_с(ед):.0f} с")
        век = dict(ВЕК_ЦЕНА[код])
        for зд in ("церковь", "депо"):
            for r, v in ЗДАНИЯ[зд][0].items():
                век[r] = век.get(r, 0) + v
        print(f"    век (cen.1 + церковь + депо) {цена_т(век)}; стройка церкви и депо ~{стройка_с(500) + стройка_с(787):.0f} с, "
              f"исследование ~9 с; плюс ba2 {цена_т(ЗДАНИЯ['казарма века ba2'][0])}, стройка ~{стройка_с(18000) / 60:.1f} мин")


if __name__ == "__main__":
    main()
