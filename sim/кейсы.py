def _кучи(кл):
    """[(n, cx, cy, [клетки])] связными компонентами (8 соседей), по убыванию n."""
    ост = {(c["x"], c["y"]): c for c in кл if c.get("n", 0) >= 1}
    из = []
    while ост:
        p0 = next(iter(ост)); стек, куча = [p0], []
        del ост[p0]
        while стек:
            p = стек.pop(); куча.append(p)
            for dx in (-1, 0, 1):
                for dy in (-1, 0, 1):
                    q = (p[0] + dx, p[1] + dy)
                    if q in ост:
                        del ост[q]; стек.append(q)
        кл_к = [c for c in кл if (c["x"], c["y"]) in куча]
        n = sum(c["n"] for c in кл_к)
        из.append((n, sum(c["x"] * c["n"] for c in кл_к) / n, sum(c["y"] * c["n"] for c in кл_к) / n, кл_к))
    return sorted(из, key=lambda k: -k[0])


def сканер(каталог):
    """Кейсы одной записи: [{t, тип, ...описание}]."""
    import sim as SIM
    import развилка as R
    зап = SIM.Запись(каталог)
    дом = (int(зап.my_cx), int(зап.my_cy))
    конец = float(зап.снапы[-1]["gametime"])
    времена = sorted({float(s["gametime"]) for s in зап.снапы} if (зап.снапы and зап.снапы[len(зап.снапы) // 2].get("ocells") is not None)
                     else {float(t) for t, _, _ in зап.такты})
    кейсы, последний = [], {}
    приходы = []        # t, когда его ≥ 8 оказались в ≤ 2 клетках от ратуши
    for t in времена:
        if t < 240 or t > конец - ОКНО_ПО_УМОЛЧАНИЮ:
            continue
        наши, его = R.клетки_записи(зап, t)
        нк = _кучи(наши); ек = [k for k in _кучи(его) if k[0] >= 8]
        дома = sum(k[0] for k in нк if math.hypot(k[1] - дом[0], k[2] - дом[1]) <= 1.5)
        поле = [k for k in нк if math.hypot(k[1] - дом[0], k[2] - дом[1]) > 1.5 and k[0] >= 10]
        W = max(поле, key=lambda k: k[0]) if поле else None
        найдено = {}
        if any(_чеб((round(k[1]), round(k[2])), дом) <= 2 for k in ек):
            приходы.append(t)
        if W:
            wc = (round(W[1]), round(W[2]))
            близ = [k for k in ек if _чеб((round(k[1]), round(k[2])), wc) <= 2]
            if близ:
                E = max(близ, key=lambda k: k[0])
                найдено["контакт"] = dict(W=W[0], E=E[0], d=_чеб((round(E[1]), round(E[2])), wc))
                ec = (round(E[1]), round(E[2]))
                другие = [k for k in ек if k is not E and _чеб((round(k[1]), round(k[2])), ec) <= 4]
                if другие:
                    найдено["подкрепление"] = dict(W=W[0], E=E[0], E2=max(k[0] for k in другие))
                if _чеб(ec, wc) <= 1 and E[0] >= 1.5 * W[0]:
                    найдено["отход"] = dict(W=W[0], E=E[0])
            в3 = [k for k in ек if _чеб((round(k[1]), round(k[2])), wc) <= 3]
            if в3:
                E = min(в3, key=lambda k: _чеб((round(k[1]), round(k[2])), wc))
                ec = (round(E[1]), round(E[2]))
                if E[0] <= 0.8 * W[0] and not any(k is not E and _чеб((round(k[1]), round(k[2])), ec) <= 3 for k in ек):
                    найдено["окно_удара"] = dict(W=W[0], E=E[0])
            elif дома >= 15:
                найдено["сбор"] = dict(W=W[0], дома=дома)
            try:
                _, st, _ = зап.такт_до(t)
                кр = [c for c in (st.get("en_pea_cells") or []) if isinstance(c, dict) and int(c.get("крестьян") or 0) >= 3]
            except Exception:
                кр = []
            охота = [c for c in кр if _чеб((int(c["x"]), int(c["y"])), wc) <= 3 and float(c.get("бойцов_рядом") or 0) <= 0.5 * W[0]]
            if охота:
                c = max(охота, key=lambda c: int(c["крестьян"]))
                найдено["охота"] = dict(W=W[0], крестьян=int(c["крестьян"]), охрана=float(c.get("бойцов_рядом") or 0), клетка=[int(c["x"]), int(c["y"])])
        for тип, оп in найдено.items():
            if t - последний.get(тип, -1e9) >= 90:
                кейсы.append(dict(t=t, тип=тип, **оп))
                последний[тип] = t
    # набеги — по приходам: развилка за 90 с до первого прихода серии (за 60, если 90 с назад он уже стоял у базы)
    серия_t = None
    for i, t in enumerate(приходы):
        if серия_t is not None and t - приходы[i - 1] <= 90:
            continue
        серия_t = t
        _, его_р = R.клетки_записи(зап, max(240.0, t - 90))
        стоял = any(k[0] >= 8 and _чеб((round(k[1]), round(k[2])), дом) <= 3 for k in _кучи(его_р))
        t0 = max(240.0, t - (60 if стоял else 90))
        if t0 <= конец - ОКНО["набег"]:
            кейсы.append(dict(t=t0, тип="набег", приход=t, стоял=стоял))
    return кейсы


def собрать(выход=os.path.join(ПАПКА, "кейсы.json")):
    все = []
    for к, агент, ист in записи():
        try:
            кк = сканер(к)
        except Exception as e:
            print(f"  {os.path.basename(os.path.dirname(к))}: сканер упал: {type(e).__name__}: {e}", flush=True)
            continue
        for x in кк:
            все.append(dict(x, запись=к, агент=агент, источник=ист, имя=os.path.basename(os.path.dirname(к)) + "/" + os.path.basename(к)))
    os.makedirs(ПАПКА, exist_ok=True)
    json.dump(все, open(выход, "w", encoding="utf-8"), ensure_ascii=False, indent=0)
    сч = Counter((x["тип"], x["источник"]) for x in все)
    print(f"КЕЙСОВ: {len(все)} из {len(записи())} записей")
    for тип in ("набег", "контакт", "подкрепление", "окно_удара", "отход", "сбор", "охота"):
        print(f"  {тип:13} игрок {сч[(тип, 'игрок')]:3d}  корпус {сч[(тип, 'корпус')]:4d}")
    return все


