def _чеб(a, b):
    return max(abs(a[0] - b[0]), abs(a[1] - b[1]))


def записи():
    """[(каталог, агент, источник)] — записи игрока (отложенные и обучающие) и корпус."""
    import тактик as ТК
    из = []
    for к in sorted(glob.glob(os.path.expanduser("~/coss3-res-игрок-отл/*/*/coss3_snap.jsonl")) +
                    glob.glob(os.path.expanduser("~/coss3-res-игрок/*/*/coss3_snap.jsonl"))):
        к = os.path.dirname(к)
        имя = os.path.basename(os.path.dirname(к))
