class Скрипт(TC.Ядро):
    """Одно решение словаря в момент развилки (если маска разрешает), дальше CONTINUE. Хозяйство — как у `Тактик`."""

    def __init__(self, решение, хоз, t0):
        import поиск_стратегии as ПС
        super().__init__([0.0] * TC.N_ВЕСОВ3)
        хоз2 = {k: v for k, v in хоз.items() if k not in ("отход", "подмога", "слабая", "возврат")}
        self.хоз = ПС.Стратегия(dict(хоз2, T1=1e9, T2=1e9, P1=0.0))
        self.решение, self.исполнено, self.исполнимо = решение, False, None
        self.след = t0
        os.environ["COSS3_WAVE_CONTRACT"] = "0"     # хозяйство скрипта — без контракта (в одном процессе до него мог идти учитель)

    def __call__(self, st):
        из = self.хоз(st)
        р = self.решить(st)
        if р is not None and not self.исполнено:
            i = self.решения.index(self.решение)
            self.исполнимо = bool(self.маска_[i])
            self.исполнено = True
            if self.исполнимо:
                self.текущее = i
                из += [c for c in self.команды(i, st, живой=True) if not str(c.get("cmd", "")).startswith("_")]
        return из


def _контроллер(вид, хоз, seed, t0, theta):
    import учитель as У
    import тактик as ТК
    if вид.startswith("учитель"):
        if ":" in вид:          # «учитель:отход=1.0;штурм_при=1.2» — тот же учитель с другими порогами стратегии (§112)
            хоз = dict(хоз, **{k: float(v) for k, v in (x.split("=") for x in вид.split(":", 1)[1].split(";") if x)})
        return У.ТеньУчителя(хоз), None
    os.environ["COSS3_WAVE_CONTRACT"] = "0"
    if вид == "случайный":
        п = У.Случайная(хоз, seed); п.след = t0; return п, п
    if вид == "клон":
        п = ТК.Тактик(theta, хоз); п.след = t0; return п, п
    assert вид.startswith("скрипт:")
    п = Скрипт(вид.split(":", 1)[1], хоз, t0)
    return п, п


def эпизод(кейс, вид, theta, seed):
    import развилка as R
    import sim as SIM
    import combat
    if not hasattr(combat, "_залпы_исх"):
        combat._залпы_исх = combat.залпы
    сим, _ = R.построить(кейс["запись"], float(кейс["t"]), кейс["агент"], seed)
    t0 = сим.t
    окно = ОКНО_ВСЕМ or ОКНО.get(кейс["тип"], ОКНО_ПО_УМОЛЧАНИЮ)
    к, ядро = _контроллер(вид, _хоз(), seed, t0, theta)
    п0, у0, кр0, екр0 = сим.my_mil_lost, сим.убито_бойцов, сим.my_pea_lost, сим.убито_крестьян
    while сим.t < t0 + окно and not сим.исход:
        st = сим.состояние()
        if вид.startswith("учитель"):
            os.environ["COSS3_WAVE_CONTRACT"] = "1"
        сим.команды(к(st) or [])
        сим.такт()
    SIM.ФОРМА_ВРАГА = None
    из = dict(вид=вид, наши=сим.my_mil_lost - п0, его=сим.убито_бойцов - у0, крест=сим.my_pea_lost - кр0, его_крест=сим.убито_крестьян - екр0,
              армия=sum(sum(г["состав"].values()) for г in сим.группы))
    из["счёт"] = из["его"] - из["наши"] - 2.0 * из["крест"] + 3.0 * из["его_крест"]     # цель турнира — его крестьянин — весит
    if isinstance(к, Скрипт):
        из["исполнимо"] = к.исполнимо
    return из


def _задача(з):
    кейс, вид, theta, seed = з
    try:
        return кейс, эпизод(кейс, вид, theta, seed)
    except Exception as e:
        return кейс, dict(вид=вид, ошибка=f"{type(e).__name__}: {e}")


# МЕРА ТИПА — то, за что кейс и выбран: набег — наши крестьяне (меньше лучше → со знаком минус), охота — его крестьяне убиты,
# остальные — его потери минус наши. Общий счёт хвалит «домой» за отложенный бой; мера типа — нет.
def мера_типа(тип, x):
    if тип == "набег":
        return -2.0 * x["крест"]
    if тип == "охота":
        return 3.0 * x["его_крест"] - x["наши"]
    return x["его"] - x["наши"]


СКРИПТЫ = ("ничего", "домой", "встретить", "на_ближайшую", "подмога", "удар_армия", "удар_крестьяне", "удар_база", "накопить", "пики_вперёд")


def решаемость(кейсы, сеть, зёрен=1, кейсов=None, выход=os.path.join(ПАПКА, "решаемость.json"), seed=7):
    th = np.array(json.load(open(сеть, encoding="utf-8"))["theta"]) if сеть.endswith(".json") else np.load(сеть)
    rng = random.Random(seed)
    if кейсов and len(кейсы) > кейсов:
        # поровну по типам, насколько есть
        по_типу = defaultdict(list)
        for k in кейсы:
            по_типу[k["тип"]].append(k)
        кв = max(1, кейсов // len(по_типу))
        кейсы = [k for t, kk in по_типу.items() for k in rng.sample(kk, min(кв, len(kk)))]
    виды = ["учитель", "клон", "случайный"] + [f"скрипт:{s}" for s in СКРИПТЫ]
    зад = [(dict(k, _i=i, _z=z), в, th, 300 + z) for i, k in enumerate(кейсы) for в in виды for z in range(зёрен)]
    print(f"РЕШАЕМОСТЬ: {len(кейсы)} кейсов × {len(виды)} контроллеров × {зёрен} зёрен = {len(зад)} эпизодов", flush=True)
    итог = defaultdict(lambda: defaultdict(list))
    with Pool(12) as пул:
        for к, р in пул.imap_unordered(_задача, зад, chunksize=4):
            р["_z"] = к["_z"]
            итог[к["_i"]][р["вид"]].append(р)
    for i in итог:
        for в in итог[i]:
            итог[i][в].sort(key=lambda x: x["_z"])
    строки = []
    for i, k in enumerate(кейсы):
        рр = итог[i]
        # ЧЕСТНЫЙ ПОТОЛОК: при зёрнах ≥ 2 лучший скрипт выбирается по ПЕРВОМУ зерну, а его счёт (и счёт учителя/клона/случайного)
        # берётся по ОСТАЛЬНЫМ — иначе максимум из десяти скриптов на одном зерне завышен отбором (победитель шума)
        def ср(вид, поле="счёт", зёрна="оценка"):
            xs = [x for x in рр.get(вид, []) if "ошибка" not in x]
            if зёрен >= 2:
                xs = xs[:1] if зёрна == "выбор" else xs[1:]
            v = [x[поле] for x in xs]
            return St.mean(v) if v else None
        испол = {в for в in рр if в.startswith("скрипт:") and all(x.get("исполнимо") for x in рр[в] if "ошибка" not in x)}
        выбор = {в.split(":", 1)[1]: ср(в, зёрна="выбор") for в in испол if ср(в, зёрна="выбор") is not None}
        скр = {в.split(":", 1)[1]: ср(в) for в in испол if ср(в) is not None}
        лучший = (None, None)
        if выбор:
            имя_л = max(выбор.items(), key=lambda kv: kv[1])[0]
            лучший = (имя_л, скр.get(имя_л))
        тип = k["тип"]
        def мт(вид, зёрна="оценка"):
            xs = [x for x in рр.get(вид, []) if "ошибка" not in x]
            if зёрен >= 2:
                xs = xs[:1] if зёрна == "выбор" else xs[1:]
            return St.mean(мера_типа(тип, x) for x in xs) if xs else None
        выбор_т = {в.split(":", 1)[1]: мт(в, "выбор") for в in испол if мт(в, "выбор") is not None}
        лучший_т = (None, None)
        if выбор_т:
            имя_т = max(выбор_т.items(), key=lambda kv: kv[1])[0]
            лучший_т = (имя_т, мт(f"скрипт:{имя_т}"))
        строки.append(dict(кейс={kk: vv for kk, vv in k.items() if kk not in ("_i", "_z")}, учитель=ср("учитель"), клон=ср("клон"), случайный=ср("случайный"),
                           скрипты=скр, лучший=лучший[0], лучший_счёт=лучший[1],
                           крест=dict(учитель=ср("учитель", "крест"), клон=ср("клон", "крест"), лучший=ср(f"скрипт:{лучший[0]}", "крест") if лучший[0] else None),
                           его_крест=dict(клон=ср("клон", "его_крест"), лучший=ср(f"скрипт:{лучший[0]}", "его_крест") if лучший[0] else None),
                           мера=dict(учитель=мт("учитель"), клон=мт("клон"), случайный=мт("случайный"), лучший=лучший_т[0], лучший_счёт=лучший_т[1]),
                           ошибки=sum(1 for в in рр for x in рр[в] if "ошибка" in x)))
    os.makedirs(ПАПКА, exist_ok=True)
    json.dump(строки, open(выход, "w", encoding="utf-8"), ensure_ascii=False, indent=0)
    отчёт(строки)
    return строки


def отчёт(строки):
    print("\nПО ТИПАМ (средний счёт = его − наши − 2·наши крестьяне + 3·его крестьяне; «есть чему учиться» — лучший скрипт выше клона больше, чем на 3):")
    print(f"  {'тип':13} {'кейсов':>6} {'учитель':>8} {'клон':>7} {'случ.':>7} {'лучший скрипт':>13} {'учиться есть':>12} {'клон≥потолка':>12}  побеждают")
    for тип in ("набег", "контакт", "подкрепление", "окно_удара", "отход", "сбор", "охота"):
        с = [x for x in строки if x["кейс"]["тип"] == тип and x["клон"] is not None and x["лучший_счёт"] is not None]
        if not с:
            continue
        учиться = sum(1 for x in с if x["лучший_счёт"] > x["клон"] + ШУМ)
        равно = sum(1 for x in с if x["клон"] >= x["лучший_счёт"] - ШУМ)
        поб = Counter(x["лучший"] for x in с if x["лучший_счёт"] > x["клон"] + ШУМ).most_common(3)
        уч = [x["учитель"] for x in с if x["учитель"] is not None]
        print(f"  {тип:13} {len(с):6d} {St.mean(уч) if уч else float('nan'):8.1f} {St.mean(x['клон'] for x in с):7.1f} {St.mean(x['случайный'] for x in с if x['случайный'] is not None):7.1f} "
              f"{St.mean(x['лучший_счёт'] for x in с):13.1f} {учиться:5d} ({100 * учиться / len(с):3.0f}%) {равно:5d} ({100 * равно / len(с):3.0f}%)  "
              + ", ".join(f"{a} {b}" for a, b in поб))
    print("\nПО МЕРЕ ТИПА (набег: −2·наши крестьяне; охота: 3·его крестьяне − наши; бой: его − наши):")
    print(f"  {'тип':13} {'кейсов':>6} {'учитель':>8} {'клон':>7} {'случ.':>7} {'лучший скрипт':>13} {'учиться есть':>12}  побеждают")
    for тип in ("набег", "контакт", "подкрепление", "окно_удара", "отход", "сбор", "охота"):
        с = [x for x in строки if x["кейс"]["тип"] == тип and x.get("мера") and x["мера"]["клон"] is not None and x["мера"]["лучший_счёт"] is not None]
        if not с:
            continue
        учиться = sum(1 for x in с if x["мера"]["лучший_счёт"] > x["мера"]["клон"] + ШУМ)
        поб = Counter(x["мера"]["лучший"] for x in с if x["мера"]["лучший_счёт"] > x["мера"]["клон"] + ШУМ).most_common(3)
        уч = [x["мера"]["учитель"] for x in с if x["мера"]["учитель"] is not None]
        print(f"  {тип:13} {len(с):6d} {St.mean(уч) if уч else float('nan'):8.1f} {St.mean(x['мера']['клон'] for x in с):7.1f} "
              f"{St.mean(x['мера']['случайный'] for x in с if x['мера']['случайный'] is not None):7.1f} {St.mean(x['мера']['лучший_счёт'] for x in с):13.1f} "
              f"{учиться:5d} ({100 * учиться / len(с):3.0f}%)  " + ", ".join(f"{a} {b}" for a, b in поб))
    ош = sum(x["ошибки"] for x in строки)
    if ош:
        print(f"  ошибок эпизодов: {ош}")
    # набег и охота — свои меры
    наб = [x for x in строки if x["кейс"]["тип"] == "набег" and x["крест"]["клон"] is not None and x["крест"]["лучший"] is not None]
    if наб:
        print(f"\n  НАБЕГ, наших крестьян (среднее): учитель {St.mean(x['крест']['учитель'] for x in наб if x['крест']['учитель'] is not None):.1f}, "
              f"клон {St.mean(x['крест']['клон'] for x in наб):.1f}, лучший скрипт {St.mean(x['крест']['лучший'] for x in наб):.1f}; "
              f"кейсов, где лучший скрипт спасает ≥ 3 крестьян против клона: {sum(1 for x in наб if x['крест']['клон'] - x['крест']['лучший'] >= 3)}/{len(наб)}")
    ох = [x for x in строки if x["кейс"]["тип"] == "охота" and x["его_крест"]["клон"] is not None and x["его_крест"]["лучший"] is not None]
    if ох:
        print(f"  ОХОТА, его крестьян убито (среднее): клон {St.mean(x['его_крест']['клон'] for x in ох):.1f}, лучший скрипт "
              f"{St.mean(x['его_крест']['лучший'] for x in ох):.1f}; кейсов с убийством у лучшего: {sum(1 for x in ох if x['его_крест']['лучший'] >= 1)}/{len(ох)}, у клона: {sum(1 for x in ох if x['его_крест']['клон'] >= 1)}/{len(ох)}")


def учитель_с_ключами(кейсы, варианты, зёрен=2, типы=("контакт", "подкрепление", "окно_удара", "отход", "сбор", "охота", "набег"),
                     основа=os.path.join(ПАПКА, "решаемость.json"), seed=7):
    """Учитель (тень под контрактом) с разными порогами стратегии на тех же кейсах: средняя мера типа против базового
    учителя, клона и честного потолка из `основа`. Варианты — строки «отход=1.0;штурм_при=1.2»."""
    осн = {json.dumps(x["кейс"], sort_keys=True, ensure_ascii=False): x for x in json.load(open(основа, encoding="utf-8"))}
    кейсы = [k for k in кейсы if k["тип"] in типы and json.dumps(k, sort_keys=True, ensure_ascii=False) in осн]
    виды = ["учитель"] + [f"учитель:{в}" for в in варианты]
    зад = [(dict(k, _i=i, _z=z), в, None, 300 + 10 + z) for i, k in enumerate(кейсы) for в in виды for z in range(зёрен)]
    print(f"УЧИТЕЛЬ С КЛЮЧАМИ: {len(кейсы)} кейсов × {len(виды)} вариантов × {зёрен} зёрен", flush=True)
    итог = defaultdict(lambda: defaultdict(list))
    with Pool(12) as пул:
        for к, р in пул.imap_unordered(_задача, зад, chunksize=4):
            if "ошибка" not in р:
                итог[к["_i"]][р["вид"]].append(р)
    print(f"  {'тип':13} {'кейсов':>6} {'клон':>7} {'потолок':>8} {'учитель':>8} " + " ".join(f"{в[:22]:>22}" for в in варианты))
    for тип in типы:
        idx = [i for i, k in enumerate(кейсы) if k["тип"] == тип]
        if not idx:
            continue
        ряд = []
        for в in виды:
            v = [St.mean(мера_типа(тип, x) for x in итог[i][в]) for i in idx if итог[i].get(в)]
            ряд.append(St.mean(v) if v else float("nan"))
        о = [осн[json.dumps(кейсы[i], sort_keys=True, ensure_ascii=False)] for i in idx]
        клон = St.mean(x["мера"]["клон"] for x in о if x["мера"]["клон"] is not None)
        пот = St.mean(x["мера"]["лучший_счёт"] for x in о if x["мера"]["лучший_счёт"] is not None)
        print(f"  {тип:13} {len(idx):6d} {клон:7.1f} {пот:8.1f} {ряд[0]:8.1f} " + " ".join(f"{r:22.1f}" for r in ряд[1:]), flush=True)


