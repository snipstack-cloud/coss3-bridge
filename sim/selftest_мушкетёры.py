# -*- coding: utf-8 -*-
"""Лестница «мушкетёры»: ступени считаются по тому, что политика сделала (28.09)."""
import os
import sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import goals_musk as GM

ошибок = []


class Сим:
    def __init__(self, убил=0.0, потерял=0.0, всего=0.0, давление=0):
        self.убито_пик_мушкетёрами = убил
        self.потери_мушкетёров_от_пик = потерял
        self.убито_бойцов = всего
        self.тактов_давления_мушк = давление


def ист(муск=0, пика=0, upg="", казарм=1, академий=0, тактов=10):
    return [{"gametime": 300 + i * 5, "mil_shooters": муск, "mil_inf": пика,
             "mil_cav": 0, "upg_done": upg, "ba17": казарм, "academies": академий}
            for i in range(тактов)]


# 1. пусто — ни одной ступени и награда ноль
в, п, д = GM.ступени(Сим(), ист())
if в or abs(GM.награда(Сим(), ист())) > 1e-9:
    ошибок.append("на пустой партии ступеней и награды быть не должно")

# 2. ступень 1: казарма и 8 мушкетёров при доле 30 %+
в, п, д = GM.ступени(Сим(), ист(муск=8, пика=10))
if 1 not in в:
    ошибок.append("8 мушкетёров при доле 44 % — ступень 1")
в, п, д = GM.ступени(Сим(), ист(муск=8, пика=100))
if 1 in в:
    ошибок.append("доля 7 % — ступень 1 брать нельзя")
в, п, д = GM.ступени(Сим(), ист(муск=8, пика=0, казарм=0))
if 1 in в:
    ошибок.append("без казармы ступень 1 брать нельзя")

# 3. ступень 2 требует И академии, И апгрейда
в, п, д = GM.ступени(Сим(), ист(муск=8, академий=1))
if 2 in в:
    ошибок.append("одна академия без апгрейда — не ступень 2")
if abs(п[2] - 0.5) > 1e-9:
    ошибок.append("академия без апгрейда это половина пути ко второй ступени")
в, п, д = GM.ступени(Сим(), ист(муск=8, академий=1, upg="aca.12"))
if 2 not in в:
    ошибок.append("академия и aca.12 — ступень 2")

# 4. ступень 4 — ВСЕ ТРИ доступных, линейка паузы тут не участвует
в, п, д = GM.ступени(Сим(), ист(муск=8, академий=1, upg="aca.12,aca.13"))
if 4 in в or abs(п[4] - 2 / 3) > 1e-9:
    ошибок.append("две из трёх ступеней урона — это две трети, а не взятая ступень")
в, п, д = GM.ступени(Сим(), ист(муск=8, академий=1, upg="aca.12,aca.13,aca.14"))
if 4 not in в:
    ошибок.append("три апгрейда урона — ступень 4")
в, п, д = GM.ступени(Сим(), ист(муск=8, академий=1, upg="aca.31,aca.33"))
if 4 in в:
    ошибок.append("линейка паузы недостижима и ступень 4 ею не берётся")

# 5. ступень 5 — размен не хуже 1:1,2 и хотя бы три убитых
в, п, д = GM.ступени(Сим(убил=10, потерял=10), ист(муск=8))
if 5 not in в:
    ошибок.append("размен 1,0 — ступень 5")
в, п, д = GM.ступени(Сим(убил=2, потерял=1), ист(муск=8))
if 5 in в:
    ошибок.append("двух убитых мало: порог 3")
в, п, д = GM.ступени(Сим(убил=5, потерял=10), ист(муск=8))
if 5 in в:
    ошибок.append("размен 0,5 — ступень 5 брать нельзя")

# 6. ступень 6 — доля мушкетёров в наших убийствах
в, п, д = GM.ступени(Сим(убил=7, потерял=1, всего=10), ист(муск=8))
if 6 not in в:
    ошибок.append("70 % убийств мушкетёрами — ступень 6")
в, п, д = GM.ступени(Сим(убил=4, потерял=1, всего=10), ист(муск=8))
if 6 in в:
    ошибок.append("40 % — ступень 6 брать нельзя")

# 7. плата за мушкетёров: при ОДИНАКОВОМ давлении больше потерь — меньше награда
мало = GM.награда(Сим(убил=5, потерял=5, всего=10, давление=10), ист(муск=8))
много = GM.награда(Сим(убил=5, потерял=50, всего=10, давление=10), ист(муск=8))
if not (много < мало):
    ошибок.append("при равном давлении больше потерянных мушкетёров — меньше награда")
# и БЕЗ давления плата не берётся вовсе (иначе сеть учится их не использовать)
без_давл_мало = GM.награда(Сим(убил=0, потерял=5, всего=0), ист(муск=8))
без_давл_много = GM.награда(Сим(убил=0, потерял=50, всего=0), ист(муск=8))
if abs(без_давл_мало - без_давл_много) > 1e-9:
    ошибок.append("без давления плата за потери браться не должна")

print("selftest_мушкетёры: " + ("ОК, 15 проверок" if not ошибок
                                else "ОШИБКИ\n  " + "\n  ".join(ошибок)))
raise SystemExit(1 if ошибок else 0)
