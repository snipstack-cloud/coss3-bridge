# -*- coding: utf-8 -*-
"""АГЕНТНЫЙ ВРАГ (29.09, §29): его армия — настоящие бойцы по клеткам, а не запись.

Зачем (игрок 29.09). В прежнем симуляторе его армия — сетка ЗАПИСИ: число в клетке каждый
такт подтягивалось к записи, наша волна бежала за его самой большой клеткой, и бой ни
разу не доводился до конца. Поэтому не было ПРОГРЕССИИ («чем меньше их, тем быстрее
гибнут») и не могло быть РЕАКЦИИ на наши действия (приманка стрелками, срыв строя).

Устройство — сетка `h[y][x]` его бойцов (дробные числа):
* НАЙМ — ровно тот, что в записи (прирост его армии плюс его потери между снимками);
  новые появляются в клетке его базы. Найм от его потерь не зависит (§27, r = −0,02);
* КУДА ОН ХОЧЕТ — форма его сетки в записи (`frow`), отмасштабированная на его ТЕКУЩУЮ
  армию: запись говорит, где родной ИИ держит армию и куда ведёт волны;
* ДВИЖЕНИЕ — избыток клетки над желаемым уходит на один шаг к ближайшей клетке с
  недостатком со скоростью марша; выбитую клетку добирают только те, кто дошёл пешком;
* ПОГИБШИЕ вычитаются из своей клетки и не возвращаются;
* СТИЛЬ — поведение отряда поверх записи, параметрами:
    `вступает` — радиус (клеток), с которого его бойцы идут в клетку нашей группы;
    `на_стрелков` — радиус, с которого он бросается на наших стрелков (приманка);
    `отход` — при своём перевесе в клетке ниже этого (его/наших) отходит к базе.
  Родной ИИ по записям 28.09 на стрелков не бросается (после их выстрелов его цель у
  места боя в 46 % против 69 % до), поэтому по умолчанию `на_стрелков` = 0.
"""
import math

СТИЛИ = {
    "родной": dict(вступает=1, на_стрелков=0, отход=0.0),
    "горячий": dict(вступает=2, на_стрелков=3, отход=0.0),     # клюёт на приманку
    "осторожный": dict(вступает=1, на_стрелков=0, отход=0.5),  # отходит, проигрывая
}


class Враг:
    def __init__(self, база, сетка0, армия0, скорость_клеток_в_сек, стиль="родной", размер=16):
        self.N = размер
        self.база = (min(self.N - 1, max(0, int(round(база[0])))), min(self.N - 1, max(0, int(round(база[1])))))
        self.v = скорость_клеток_в_сек
        self.стиль = dict(СТИЛИ[стиль]) if isinstance(стиль, str) else dict(стиль)
        self.h = [[0.0] * self.N for _ in range(self.N)]
        s = sum(sum(r) for r in сетка0) if сетка0 else 0
        if s > 0 and армия0 > 0:
            for y in range(min(self.N, len(сетка0))):
                for x in range(min(self.N, len(сетка0[y]))):
                    self.h[y][x] = армия0 * сетка0[y][x] / s
        elif армия0 > 0:
            self.h[self.база[1]][self.база[0]] = армия0
        self.нанято = 0.0
        self.отошло = 0.0

    def всего(self):
        return sum(sum(r) for r in self.h)

    def нанять(self, n):
        if n > 0:
            self.h[self.база[1]][self.база[0]] += n
            self.нанято += n

    def потери(self, x, y, n):
        if 0 <= y < self.N and 0 <= x < self.N:
            self.h[y][x] = max(0.0, self.h[y][x] - n)

    def шаг(self, dt, форма, наши):
        """форма — сетка записи (куда он хочет); наши — {(x, y): (бойцов, стрелков)}."""
        N, h = self.N, self.h
        T = self.всего()
        if T <= 0:
            return
        # желаемое: форма записи на его текущую армию
        s = sum(sum(r) for r in форма) if форма else 0
        g = [[0.0] * N for _ in range(N)]
        if s > 0:
            for y in range(min(N, len(форма))):
                for x in range(min(N, len(форма[y]))):
                    g[y][x] = T * форма[y][x] / s
        else:
            g[self.база[1]][self.база[0]] = T
        # РЕАКЦИИ СТИЛЯ. Сначала кто вступает в бой: его бойцы в радиусе `вступает` от
        # нашей группы хотят в её клетку (так в жизни 85 % смертей — в общей клетке, §21);
        # на стрелков — с радиуса `на_стрелков`. Взятые под бой из желаемого снимаются.
        притяжение = {}
        for (x, y), (n, стр) in наши.items():
            r = self.стиль["вступает"]
            if стр > 0 and self.стиль["на_стрелков"] > r:
                r = self.стиль["на_стрелков"]
            if r <= 0 or n <= 0:
                continue
            рядом = 0.0
            for yy in range(max(0, y - r), min(N, y + r + 1)):
                for xx in range(max(0, x - r), min(N, x + r + 1)):
                    рядом += h[yy][xx]
            if рядом > 0:
                притяжение[(x, y)] = рядом
        for (x, y), m in притяжение.items():
            r = max(self.стиль["вступает"], self.стиль["на_стрелков"] if наши[(x, y)][1] > 0 else 0)
            снято = 0.0
            for yy in range(max(0, y - r), min(N, y + r + 1)):
                for xx in range(max(0, x - r), min(N, x + r + 1)):
                    k = min(g[yy][xx], h[yy][xx])
                    g[yy][xx] -= k
                    снято += k
            g[y][x] += снято
        # отход: где его меньше `отход` от наших, он хочет домой
        if self.стиль["отход"] > 0:
            for (x, y), (n, _) in наши.items():
                if n > 0 and 0 < h[y][x] < self.стиль["отход"] * n:
                    g[self.база[1]][self.база[0]] += g[y][x]
                    g[y][x] = 0.0
                    self.отошло += h[y][x]
        # ДВИЖЕНИЕ: избыток клетки идёт на шаг к ближайшей клетке с недостатком
        дефицит = [(x, y) for y in range(N) for x in range(N) if g[y][x] - h[y][x] > 0.01]
        if not дефицит:
            return
        доля = min(1.0, self.v * dt)          # доля клетки, проходимая за такт
        приход = [[0.0] * N for _ in range(N)]
        for y in range(N):
            for x in range(N):
                избыток = h[y][x] - g[y][x]
                if избыток <= 0.01:
                    continue
                цx, цy = min(дефицит, key=lambda p: max(abs(p[0] - x), abs(p[1] - y)) + 0.001 * math.hypot(p[0] - x, p[1] - y))
                dx = (цx > x) - (цx < x)
                dy = (цy > y) - (цy < y)
                k = избыток * доля
                h[y][x] -= k
                приход[y + dy][x + dx] += k
        for y in range(N):
            for x in range(N):
                h[y][x] += приход[y][x]
