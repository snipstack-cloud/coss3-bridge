# -*- coding: utf-8 -*-
"""АГЕНТНЫЙ ВРАГ (29.09, §29): его армия — настоящие бойцы по клеткам, а не запись.

Зачем (игрок 29.09). В прежнем симуляторе его армия — сетка ЗАПИСИ: число в клетке каждый
такт подтягивалось к записи, наша волна бежала за его самой большой клеткой, и бой ни
разу не доводился до конца. Поэтому не было ПРОГРЕССИИ («чем меньше их, тем быстрее
гибнут») и не могло быть РЕАКЦИИ на наши действия (приманка стрелками, срыв строя).

Устройство — сетка `h[y][x]` его бойцов (дробные числа):
* НАЙМ — ровно тот, что в записи (прирост его армии плюс его потери между снимками);
  новые появляются в клетке его базы. Найм от его потерь не зависит (§27, r = −0,02);
* КУДА ОН ХОЧЕТ — форма его сетки в записи (`frow`), отмасштабированная на его ТЕКУЩУЮ
  армию: запись говорит, где родной ИИ держит армию и куда ведёт волны;
* ДВИЖЕНИЕ — избыток клетки над желаемым уходит на один шаг к ближайшей клетке с
  недостатком со скоростью марша; выбитую клетку добирают только те, кто дошёл пешком;
* ПОГИБШИЕ вычитаются из своей клетки и не возвращаются;
* СТИЛЬ — поведение отряда поверх записи, параметрами:
    `вступает` — радиус (клеток), с которого его бойцы идут в клетку нашей группы;
    `на_стрелков` — радиус, с которого он бросается на наших стрелков (приманка);
    `отход` — при своём перевесе в клетке ниже этого (его/наших) отходит к базе.
  Родной ИИ по записям 28.09 на стрелков не бросается (после их выстрелов его цель у
  места боя в 46 % против 69 % до), поэтому по умолчанию `на_стрелков` = 0.
"""
import math
import os as _os

# §95: доля стрелков, уходящих за такт из клетки боя, когда их прикрывают пики (подбор по воротам состава)
УХОД_ЗА_ПИКАМИ = float(_os.environ.get("COSS3_TYPES_LEAVE", "0.3"))   # [замер] §96: сетка уход × вступать_при × заслон на p3/p5/p2

СТИЛИ = {
    "родной": dict(вступает=1, на_стрелков=0, отход=0.0),
    "горячий": dict(вступает=2, на_стрелков=3, отход=0.0),     # клюёт на приманку
    "осторожный": dict(вступает=1, на_стрелков=0, отход=0.5),  # отходит, проигрывая
    "по_записи": dict(вступает=0, на_стрелков=0, отход=0.0),   # не втягивается: бой там, куда привела запись
}


class Враг:
    def __init__(self, база, сетка0, армия0, скорость_клеток_в_сек, стиль="родной", размер=16):
        self.N = размер
        self.база = (min(self.N - 1, max(0, int(round(база[0])))), min(self.N - 1, max(0, int(round(база[1])))))
        self.v = скорость_клеток_в_сек
        self.стиль = dict(СТИЛИ[стиль]) if isinstance(стиль, str) else dict(стиль)
        self.h = [[0.0] * self.N for _ in range(self.N)]
        s = sum(sum(r) for r in сетка0) if сетка0 else 0
        if s > 0 and армия0 > 0:
            for y in range(min(self.N, len(сетка0))):
                for x in range(min(self.N, len(сетка0[y]))):
                    self.h[y][x] = армия0 * сетка0[y][x] / s
        elif армия0 > 0:
            self.h[self.база[1]][self.база[0]] = армия0
        self.нанято = 0.0
        self.отошло = 0.0
        # СЕТКА ТИПОВ (4.10, §95): `s[y][x]` — его стрелки в клетке, пики = h − s. None — без типов
        # (состав общий на армию, как до §95). Включает `включить_типы`; дальше найм, потери и
        # движение ведут обе сетки, а реакции различают: в нашу клетку входят пики, стрелки из неё
        # уходят в соседнюю и бьют оттуда (§52-53) — не долей, а поштучно.
        self.s = None

    def включить_типы(self, доля=None, сетка_стр=None):
        """Стрелки по клеткам: из сетки записи `сетка_стр` (ecells) или долей `доля` от каждой клетки."""
        N = self.N
        self.s = [[0.0] * N for _ in range(N)]
        if сетка_стр:
            for y in range(min(N, len(сетка_стр))):
                for x in range(min(N, len(сетка_стр[y]))):
                    self.s[y][x] = min(self.h[y][x], float(сетка_стр[y][x]))
        elif доля:
            for y in range(N):
                for x in range(N):
                    self.s[y][x] = self.h[y][x] * float(доля)

    def всего(self):
        return sum(sum(r) for r in self.h)

    def всего_стр(self):
        return sum(sum(r) for r in self.s) if self.s is not None else 0.0

    def стрелков(self, x, y):
        return self.s[y][x] if self.s is not None and 0 <= y < self.N and 0 <= x < self.N else 0.0

    def нанять(self, n, доля_стр=0.0):
        if n > 0:
            self.h[self.база[1]][self.база[0]] += n
            if self.s is not None:
                self.s[self.база[1]][self.база[0]] += n * max(0.0, min(1.0, float(доля_стр)))
            self.нанято += n

    def потери(self, x, y, n):
        if 0 <= y < self.N and 0 <= x < self.N:
            было = self.h[y][x]
            self.h[y][x] = max(0.0, было - n)
            if self.s is not None and было > 0:
                self.s[y][x] = max(0.0, min(self.h[y][x], self.s[y][x] * self.h[y][x] / было))

    def шаг(self, dt, форма, наши, дом=None, оборона=0, доля_стр=0.0, t=None):
        """форма — сетка записи (куда он хочет); наши — {(x, y): (бойцов, стрелков)};
        дом — клетка нашей домашней армии, `оборона` — радиус, с которого она сама бьёт
        подошедших (в игре бойцы атакуют врага в поле зрения; без этого его волна у края
        нашей базы проходила мимо, и бои у нас были 230 наших потерь против 514 в жизни)."""
        N, h = self.N, self.h
        T = self.всего()
        if T <= 0:
            return
        # желаемое: форма записи на его текущую армию
        s = sum(sum(r) for r in форма) if форма else 0
        g = [[0.0] * N for _ in range(N)]
        if s > 0:
            for y in range(min(N, len(форма))):
                for x in range(min(N, len(форма[y]))):
                    g[y][x] = T * форма[y][x] / s
        else:
            g[self.база[1]][self.база[0]] = T
        # РАССТАНОВКА ПО ПАРАМЕТРАМ (3.10, §67, предложение игрока: «симуляции рандомных параметров
        # человека»). Форма записи — где стоял противник ПРОТИВ ТОГО бота, что был в записи (у игрока
        # 2.10 — против 18-34 бойцов): против сильного бота агент стоял бы так же. Здесь агент сам
        # решает, где держать армию: главная куча (`доля_главная`) выдвигается от своей базы к нашей
        # на `выдвижение` клеток к `выход` секундам; вторая — рядом, у его базы (крестьяне) или на
        # фланге; при наших в `порог_отхода` раз больше его — главная к своей базе; с `атака_с`
        # доля `доля_атаки` идёт на нашу базу. Реакции ниже (втягивание, погоня, разбег) — поверх.
        р = self.стиль.get("расстановка")
        if р and дом is not None:
            g = [[0.0] * N for _ in range(N)]
            bx, by = self.база
            hx, hy = дом
            dx, dy = hx - bx, hy - by
            dd = max(math.hypot(dx, dy), 1e-6)
            ux, uy = dx / dd, dy / dd
            tt = float(t or 0.0)
            выд = float(р.get("выдвижение", 4)) * min(1.0, tt / max(float(р.get("выход", 360)), 1.0))
            наших = sum(n for n, _ in наши.values())
            if наших >= float(р.get("порог_отхода", 99)) * T:
                выд = 0.0                                 # наша армия сильнее — к своей базе
            def клетка(x, y):
                return (min(N - 1, max(0, int(round(x)))), min(N - 1, max(0, int(round(y)))))
            гл = клетка(bx + ux * выд, by + uy * выд)
            атака = T * float(р.get("доля_атаки", 0.5)) if tt >= float(р.get("атака_с", 1e9)) else 0.0
            главная = (T - атака) * float(р.get("доля_главная", 0.8))
            вторая = T - атака - главная
            вид = int(р.get("вторая", 0))
            if вид == 1:
                вт = (bx, by)                             # у своей базы, при крестьянах
            elif вид == 2:
                вт = клетка(bx + ux * выд * 0.6 - uy * 3, by + uy * выд * 0.6 + ux * 3)   # фланг
            else:
                вт = клетка(гл[0] - ux * 1.5, гл[1] - uy * 1.5)                         # рядом, сзади
            def положить(c, n):
                # куча плотная, но не в одной клетке: половина в центре, остальное в 8 соседних
                g[c[1]][c[0]] += n * 0.5
                сос = [(c[0] + a, c[1] + b) for a in (-1, 0, 1) for b in (-1, 0, 1)
                       if (a or b) and 0 <= c[0] + a < N and 0 <= c[1] + b < N]
                for x, y in сос:
                    g[y][x] += n * 0.5 / len(сос)
            положить(гл, главная)
            положить(вт, вторая)
            if атака > 0:
                положить(клетка(hx, hy), атака)
        # НАЛЁТ (6.10, §107): ход игрока проверки 6 — часть армии идёт туда, где нашей армии НЕТ. Каждый такт
        # заново: если у нашей ратуши (±1 клетка) наших бойцов не больше `порог` × налётной доли — доля
        # `доля` его армии (не меньше `мин`) уходит в клетку нашей ратуши; вернулась наша армия — налёт сам
        # сходит на нет (форма записи забирает их назад). Наших крестьян там режет закон §106.
        нл = self.стиль.get("налёт")
        if нл and дом is not None and float(t or 0.0) >= float(нл.get("с", 240)):
            налёт = max(float(нл.get("мин", 10)), T * float(нл.get("доля", 0.35)))
            налёт = min(налёт, T)
            hx, hy = дом
            у_дома = sum(n for (x, y), (n, _) in наши.items() if max(abs(x - hx), abs(y - hy)) <= 1)
            if у_дома <= float(нл.get("порог", 0.8)) * налёт:
                всего_g = sum(sum(r) for r in g)
                if всего_g > 0:
                    k = max(0.0, 1.0 - налёт / всего_g)
                    g = [[v * k for v in r] for r in g]
                g[min(N - 1, max(0, int(hy)))][min(N - 1, max(0, int(hx)))] += налёт
                self.налётов = getattr(self, "налётов", 0) + 1
        # РЕАКЦИИ СТИЛЯ. Сначала кто вступает в бой: его бойцы в радиусе `вступает` от
        # нашей группы хотят в её клетку (так в жизни 85 % смертей — в общей клетке, §21);
        # на стрелков — с радиуса `на_стрелков`. Взятые под бой из желаемого снимаются.
        # СТРЕЛКИ ДЕРЖАТ ДИСТАНЦИЮ (2.10, §53, проверка 2: 102 из 139 убиты стрелком из СОСЕДНЕЙ
        # клетки). Доля `доля_стр` его армии — стрелки (армия без типов, состав общий): в нашу
        # клетку втягиваются только остальные, а стрелки из нашей клетки отходят в соседнюю
        # свободную, ближе к своей базе, и бьют оттуда огнём (`sim.ОГОНЬ_СОСЕДЕЙ`).
        # доля уходящих за такт: подбор по проверке 2 (агент по её записи, 10 зёрен) — 0,35 даёт
        # 128/95/0,74/78 %, 0,5 — 137/84/0,64/82 % при живых 139/91/0,65/73 %; 1,0 — 168/27/0,16
        # 3.10 (§62): с погоней по замеру переподобрано — огонь 0,4, дистанция 0,1 (118/79/0,66/71 %)
        дист = доля_стр * float(self.стиль.get("дистанция", 0.1))
        уйти = {}
        if дист > 0 or (self.s is not None and float(self.стиль.get("дистанция", 0.1)) > 0):
            for (x, y), (n, _) in наши.items():
                if n < 1 or h[y][x] <= 0.02:
                    continue
                куда = [(max(abs(xx - self.база[0]), abs(yy - self.база[1])), xx, yy)
                        for yy in range(max(0, y - 1), min(N, y + 2)) for xx in range(max(0, x - 1), min(N, x + 2))
                        if (xx, yy) != (x, y) and (xx, yy) not in наши]
                if куда:
                    # РАЗБЕГАНИЕ (3.10, §66, слова игрока и замер p2): движок разводит стрелков ПО
                    # ОДНОМУ в разные стороны прочь от пики, а не группой. 172 случая «наши в его
                    # клетке со стрелками»: через 5 с его бойцы в медианно 3 соседних клетках (в 87 %
                    # — в 2+), не в главной куче 37 %. Главная доля `разбег_главная` (0,63) — в клетку
                    # ближе к его базе, остальное поровну в прочие свободные соседние.
                    if self.s is None:
                        k = дист * h[y][x]
                    else:
                        # §95: стрелки за пиками уходят из клетки боя СРАЗУ (живьём p3: пики держат (12,3),
                        # стрелки в (11,3)); без пик в клетке — долей `дистанция`, их догоняют (p2)
                        _hh, _ss = h[y][x], self.s[y][x]
                        _за_пиками = _hh > 0 and (_hh - _ss) / _hh >= float(self.стиль.get("стрелки_за_пиками", 0.25))
                        k = (float(self.стиль.get("уход_за_пиками", УХОД_ЗА_ПИКАМИ)) if _за_пиками else float(self.стиль.get("дистанция", 0.1))) * _ss
                    if k <= 0:
                        continue
                    g[y][x] = max(0.0, g[y][x] - k)
                    куда.sort()
                    главная = float(self.стиль.get("разбег_главная", 0.63)) if len(куда) > 1 else 1.0
                    g[куда[0][2]][куда[0][1]] += k * главная
                    for _, xx, yy in куда[1:]:
                        g[yy][xx] += k * (1.0 - главная) / (len(куда) - 1)
                    уйти[(x, y)] = k
        притяжение = {}
        радиус = {}
        for (x, y), (n, стр) in наши.items():
            r = self.стиль["вступает"]
            if стр > 0 and self.стиль["на_стрелков"] > r:
                r = self.стиль["на_стрелков"]
            if дом is not None and (x, y) == дом and оборона > r:
                r = оборона
            радиус[(x, y)] = r
            if r <= 0 or n <= 0:
                continue
            рядом = 0.0
            for yy in range(max(0, y - r), min(N, y + r + 1)):
                for xx in range(max(0, x - r), min(N, x + r + 1)):
                    рядом += h[yy][xx]
            if рядом > 0:
                притяжение[(x, y)] = рядом
        for (x, y), m in притяжение.items():
            r = радиус[(x, y)]
            # ВСТУПАЕТ ТОЛЬКО С ПЕРЕВЕСОМ (3.10, §72). Живой игрок p3 до 10:00: в 90 % клеток контакта
            # его больше (28,6 против наших 10,1), наших больше — в 10 % и то 4,5 против 1,3; агент
            # без этого правила подавал соседей малыми порциями, и наших больше было в 74 %. Соседи
            # входят в нашу клетку, только если с уже стоящими их наберётся `вступать_при` × наших;
            # 0 — как прежде (всегда).
            _q = float(self.стиль.get("вступать_при", 0.0))
            if _q > 0:
                _n_наших = наши[(x, y)][0]
                _можно = h[y][x] + sum(min(g[yy][xx], h[yy][xx]) * self.стиль.get("сила", 1.0) * (1.0 - дист)
                                       for yy in range(max(0, y - r), min(N, y + r + 1))
                                       for xx in range(max(0, x - r), min(N, x + r + 1)) if (xx, yy) != (x, y))
                if _можно < _q * _n_наших:
                    continue
            снято = 0.0
            for yy in range(max(0, y - r), min(N, y + r + 1)):
                for xx in range(max(0, x - r), min(N, x + r + 1)):
                    # СИЛА ВТЯГИВАНИЯ (§31): доля соседних бойцов, идущих за такт в бой в нашей
                    # клетке. 1 — все (первая редакция); при постоянной досылке это давало
                    # вчетверо больше боя, чем в жизни (§30).
                    if (xx, yy) == (x, y):
                        continue      # свои в нашей клетке уже там; стрелки из неё уходят (выше)
                    k = min(g[yy][xx], h[yy][xx]) * self.стиль.get("сила", 1.0) * (1.0 - дист)
                    g[yy][xx] -= k
                    снято += k
            g[y][x] += снято
        # ПОГОНЯ (2.10, §43, игрок по карте 8:58: у него 63 и 21 — 21 оторвались и гнались).
        # На нашу группу в поле с радиуса `погоня` клеток идёт не вся его армия, а сколько
        # нужно, чтобы её было `во_сколько` раз больше нашей; ближние клетки первыми.
        # Так приманка отрывает от его кучи кусок по своему размеру — манёвр «растащить».
        # 3.10 (§62) ЗАМЕР вместо допущения: по `ecells` (идут/tx/ty, раз в 5 с) трёх партий игрока
        # на нашу кучу идёт 70-90 % его армии, в 2-3 раза больше кучи (на мелкую группу до 10 —
        # в 5-6 раз), с 6-9 клеток в начале и 1-3 при сближении. Сдерживается он одним: когда наша
        # куча не меньше его армии, идёт лишь часть (25 наших против 45 — пошло 18, 0,6×).
        # Правило: наша куча меньше всей его армии — идут все в радиусе, сколько нужно до
        # `во_сколько`; иначе — `при_перевесе` (0,6) от нашей кучи.
        R = int(self.стиль.get("погоня", 0))
        if R > 0:
            q = float(self.стиль.get("во_сколько", 3.0))
            всего_его = self.всего()
            for (x, y), (n, _) in наши.items():
                if n < 1 or (дом is not None and (x, y) == дом):
                    continue
                нужно = (q * n if n < всего_его else float(self.стиль.get("при_перевесе", 0.6)) * n) - g[y][x]
                if нужно <= 0:
                    continue
                клетки = sorted((max(abs(xx - x), abs(yy - y)), xx, yy)
                                for yy in range(max(0, y - R), min(N, y + R + 1))
                                for xx in range(max(0, x - R), min(N, x + R + 1))
                                if (xx, yy) != (x, y) and h[yy][xx] > 0.02)
                for _, xx, yy in клетки:
                    # §62: в погоне его пикинёры идут В нашу клетку, а стрелки — в соседнюю с ней со
                    # своей стороны: живой мушкетёр подходит на выстрел, а не в рукопашную (иначе
                    # замкнутый цикл p2 давал наших 69-102 при живых 139 — их рубили пики)
                    k = min(g[yy][xx], h[yy][xx], нужно)
                    if k <= 0:
                        continue
                    сосед = (x + (xx > x) - (xx < x), y + (yy > y) - (yy < y))
                    if сосед in наши:
                        сосед = (x, y)
                    g[yy][xx] -= k
                    g[y][x] += k * (1.0 - доля_стр)
                    g[сосед[1]][сосед[0]] += k * доля_стр
                    нужно -= k
                    self.в_погоне = getattr(self, "в_погоне", 0.0) + k
                    if нужно <= 0:
                        break
        # отход: где его меньше `отход` от наших, он хочет домой
        if self.стиль["отход"] > 0:
            for (x, y), (n, _) in наши.items():
                if n > 0 and 0 < h[y][x] < self.стиль["отход"] * n:
                    g[self.база[1]][self.база[0]] += g[y][x]
                    g[y][x] = 0.0
                    self.отошло += h[y][x]
        # ДВИЖЕНИЕ — честное распределение (§29, вторая редакция). Пары «избыток →
        # недостаток» по возрастанию расстояния, и каждая пара получает не больше, чем
        # нужно недостатку. Первая редакция слала ВЕСЬ избыток клетки к ОДНОЙ ближайшей
        # клетке с недостатком; мелкие недостатки у его базы (найм, округление) глотали
        # весь поток, и его волны к нашей базе не формировались: бои у нас 105 и 31
        # наших потерь против 514 в жизни.
        избытки = {(x, y): h[y][x] - g[y][x] for y in range(N) for x in range(N) if h[y][x] - g[y][x] > 0.02}
        недостатки = {(x, y): g[y][x] - h[y][x] for y in range(N) for x in range(N) if g[y][x] - h[y][x] > 0.02}
        if not избытки or not недостатки:
            return
        пары = sorted(((max(abs(a[0] - b[0]), abs(a[1] - b[1])), a, b) for a in избытки for b in недостатки),
                      key=lambda p: p[0])
        доля = min(1.0, self.v * dt)          # доля клетки, проходимая за такт
        приход = [[0.0] * N for _ in range(N)]
        # КЛЕТКИ, ГДЕ СТОЯТ НАШИ (1.10, §36, игрок по карте: «мои прошли сквозь 21 —
        # такое невозможно, моя армия сначала убила бы всех»): (1) его бойцы в такой клетке
        # заняты боем и из неё не уходят; (2) идущие останавливаются в ПЕРВОЙ клетке пути,
        # где стоят наши, — не перепрыгивают её (при ВРАГ_СЛЕДУЕТ 6 шаг был 2 клетки за такт).
        занято = {к for к, (n, _) in наши.items() if n >= 1}
        приход_стр = [[0.0] * N for _ in range(N)] if self.s is not None else None
        for d, a, b in пары:
            k = min(избытки[a], недостатки[b])
            if k <= 0:
                continue
            if a in занято:
                # из клетки с нашими уходят только стрелки (§53), не больше их доли
                k = min(k, уйти.get(a, 0.0))
                if k <= 0:
                    continue
                уйти[a] -= k
            if self.s is not None and b in занято and a not in занято:
                # §95: СТРЕЛКИ ЗА ПИКАМИ — в нашу клетку из клетки, где его пик не меньше `стрелки_за_пиками`
                # (0,25, как ЗАСЛОН_ДОЛЯ_ПИК §71), идут только пики: стрелки стоят за ними и бьют огнём соседей.
                # Без пик (p2) стрелки входят и попадают под наши пики, как живьём (§71: наши догнали 89).
                _h, _s = h[a[1]][a[0]], self.s[a[1]][a[0]]
                if _h > 0 and (_h - _s) / _h >= float(self.стиль.get("стрелки_за_пиками", 0.25)):
                    k = min(k, max(0.0, _h - _s))
                    if k <= 0:
                        continue
            избытки[a] -= k
            недостатки[b] -= k
            # за такт проходит `v·dt` клеток: меньше одной — доля пути до соседней клетки;
            # больше — сразу на столько клеток к цели, но не дальше неё
            путь = self.v * dt
            if путь < 1 or d <= 1:
                шаг, клеток = k * (доля if d >= 1 else 1.0), min(1, d)
            else:
                шаг, клеток = k, min(d, int(round(путь)))
            ex = (b[0] > a[0]) - (b[0] < a[0])
            ey = (b[1] > a[1]) - (b[1] < a[1])
            nx, ny = a
            for _ in range(клеток):
                if nx != b[0]:
                    nx += ex
                if ny != b[1]:
                    ny += ey
                if (nx, ny) in занято:
                    break
            if self.s is not None:
                # типы: из нашей клетки уходят стрелки (§53), иначе — по составу клетки. Правило «в нашу
                # клетку входят только пики» ПРОВЕРЕНО И СНЯТО: на p2 его потери 29 вместо 86 при живых
                # 91 — живые мушкетёры в рукопашную попадают, наши пики их догоняют (§71)
                _h, _s = h[a[1]][a[0]], self.s[a[1]][a[0]]
                if a in занято:
                    ш_стр = min(шаг, _s)
                elif b in занято and _h > 0 and (_h - _s) / _h >= float(self.стиль.get("стрелки_за_пиками", 0.25)):
                    ш_стр = 0.0
                else:
                    ш_стр = шаг * _s / _h if _h > 0 else 0.0
                self.s[a[1]][a[0]] = max(0.0, self.s[a[1]][a[0]] - ш_стр)
                приход_стр[ny][nx] += ш_стр
            h[a[1]][a[0]] -= шаг
            приход[ny][nx] += шаг
        for y in range(N):
            for x in range(N):
                h[y][x] += приход[y][x]
                if self.s is not None:
                    self.s[y][x] = min(h[y][x], self.s[y][x] + приход_стр[y][x])
