#!/usr/bin/env python3
"""ПОЛЬСКАЯ КОННИЦА против наших пик и мушкетёров (1.11, вопрос игрока после поиска в интернете).

Польша в XVII веке нанимает в конюшне двух конных (`country.script:2971, 2976`, оба после кузницы):
крылатого гусара `wingedhussar` и польского рейтара `reiterpol`. `hussar` — только XVIII век, а он в наших партиях запрещён.
Числа — `нации.юниты_из_скрипта()`, урон — `_misc_DoDamage` (`miscext2.script:276-440`):
  * урон = атака + бонус отряда − защита по виду оружия, не меньше 1;
  * пуля по ЛЁГКОЙ коннице (`usage_fasthorse`: гусары, `unit.script:1329`) на ходу — ещё −5, и тогда без выстрела в голову (:335-337, :420);
  * выстрел в голову: 5 % пуль, +U(0..500) урона, в среднем +250 (:420, :437; случайное число у каждой пули своё, `weapon.script:1048`);
  * бонус отряда +2/+2 на ходу, +7/+7 стоя, к пуле тоже (:427, условие «кроме пули» закомментировано).
ДОПУЩЕНИЕ: темп удара в рукопашной одинаков у всех, поэтому сила считается в ударах, а не в секундах.
Мушкетёр стреляет раз в 375 кадров, то есть раз в 11,7 с.

    python3 sim/польша_конница.py
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import нации as Н  # noqa: E402

ГОЛОВА = 0.05 * 250      # средняя прибавка выстрела в голову на пулю


def уд(hp, урон):
    return -(-hp // max(1, урон))


def main():
    ю = Н.юниты_из_скрипта()
    пика, муш = ю["pikeman"], ю["musketeernet"]
    for сид in ("wingedhussar", "reiterpol"):
        к = ю[сид]
        вид = {1: "dpike", 2: "dsword"}[к["wkind"]]
        лёгкая = сид == "wingedhussar"
        ц = к["цена"]
        print(f"\n{сид}: hp {к['hp']}, атака {к['atk']} ({вид[1:]}), защита пика/меч/пуля {к['dpike']}/{к['dsword']}/{к['dbullet']}, "
              f"цена {ц['food']} еды / {ц['gold']} зол / {ц['iron']} жел, найм {к['найм_с']} с")
        print("  НАША ПИКА в рукопашной:")
        for имя, строй in (("пика без строя", 0), ("отряд на ходу (+2/+2)", 2), ("отряд СТОЯ (+7/+7)", 7)):
            он = max(1, к["atk"] - (пика[вид] + строй))
            мы = max(1, пика["atk"] + строй - к["dpike"])
            уо, ум = уд(пика["hp"], он), уд(к["hp"], мы)
            print(f"    {имя:24s} он нам {он:2d} ({уо} ударов), мы ему {мы:2d} ({ум} ударов): одного стоит {ум / уо:.1f} наших пик")
        print("  НАШ МУШКЕТЁР, выстрелов на одного (в среднем, с выстрелом в голову):")
        for имя, строй in (("одиночный", 0), ("отряд стоя (+7)", 7)):
            стоит = муш["atk"] + строй - к["dbullet"] + ГОЛОВА
            ход = max(1, муш["atk"] + строй - к["dbullet"] - 5) if лёгкая else стоит
            print(f"    {имя:24s} по стоящему/в бою {к['hp'] / стоит:5.1f}, по скачущему {к['hp'] / ход:5.1f}")


if __name__ == "__main__":
    main()
