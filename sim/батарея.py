def _запустить(скрипт, арг):
    r = subprocess.run([sys.executable, os.path.join(К, скрипт)] + арг, capture_output=True, text=True, encoding="utf-8", errors="replace", cwd=os.path.dirname(К))
    return r.stdout + ("\n[stderr] " + r.stderr[-600:] if r.returncode else "")


def ворота(тест):
    из = {}
    # экономика: блок «валовая» — последний в выводе
    текст = _запустить("gate.py", тест)
    блок = текст.split("ВОРОТА, еда «валовая»")[-1]
    эк = {}
    for m in re.finditer(r"^\s+(\w+)\s+(\d+)%\s+(ок|НЕТ)\s+(\d+) / (\d+)", блок, re.M):
        эк[m.group(1)] = dict(ошибка600=int(m.group(2)), вердикт=m.group(3), конец_сим=int(m.group(4)), конец_факт=int(m.group(5)))
    из["экономика"] = эк or {"ошибка": текст[-400:]}
    # закон боя по архиву
    текст = _запустить("gate_combat.py", [os.path.expanduser("~/coss3-res")])
    бой = {}
    for m in re.finditer(r"^\s*(ВСЕ ЭПИЗОДЫ|место: дома|место: в поле|место: у него|крупные \(потерь >= 20\))\s+n\s+(\d+)\s+смещение\s+([-+\d.]+)\s+\|log2\|\s+([\d.]+)\s+в 2 раза\s+(\d+)%", текст, re.M):
        бой[m.group(1)] = dict(n=int(m.group(2)), смещение=float(m.group(3)), log2=float(m.group(4)), в_2_раза=int(m.group(5)))
    for m in re.finditer(r"^\s*(наши потери|его потери)\s+смещение\s+([-+\d.]+)\s+\|log2\|\s+([\d.]+)\s+в 2 раза\s+(\d+)%", текст, re.M):
        бой[m.group(1)] = dict(смещение=float(m.group(2)), log2=float(m.group(3)), в_2_раза=int(m.group(4)))
    из["закон_боя"] = бой or {"ошибка": текст[-400:]}
    # размен по местам, 27-28.09, одно зерно
    текст = _запустить("ворота_мест.py", [os.path.expanduser("~/coss3-res/2026-09-28"), os.path.expanduser("~/coss3-res/2026-09-27"), "--seeds=1"])
    места = {}
    for m in re.finditer(r"^(у него|в поле|у нас|всё)\s+\|\s+(\d+)\s+(\d+)\s+\|\s+(\d+)\s+(\d+)\s+\|\s+([\d.]+)\s+([\d.]+)", текст, re.M):
        места[m.group(1)] = dict(наши_жизнь=int(m.group(2)), наши_сим=int(m.group(3)), его_жизнь=int(m.group(4)), его_сим=int(m.group(5)),
                                размен_жизнь=float(m.group(6)), размен_сим=float(m.group(7)))
    из["по_местам"] = места or {"ошибка": текст[-400:]}
    return из


