class Манёвр:
    """Политика-расписание: хозяйство `сл2_s1` без своих волн + все приказы волне по часам,
    чтобы разделение, слияние, отход и его отмена случились в каждой партии."""

    def __init__(self, хоз, en_base, середина):
        import поиск_стратегии as ПС
        self.хоз = ПС.Стратегия(dict(хоз, T1=1e9, T2=1e9, P1=0.0))
        eb, m = en_base, середина
        self.план = [
            (300, {"cmd": "ATTACK", "count": "all", "target": "army"}),
            (360, {"cmd": "RETREAT"}), (365, {"cmd": "_ВПЕРЁД", "target": "army"}),
            (420, {"cmd": "_ОТРЯД", "share": 0.3, "aim": [eb[0], eb[1]]}),
            (450, {"cmd": "_К_СВОИМ"}), (480, {"cmd": "_СТОЙ"}),
            (510, {"cmd": "ATTACK", "count": "all", "target": "wave"}),
            (540, {"cmd": "STAGE", "cx": m[0], "cy": m[1]}), (600, {"cmd": "ENGAGE", "target": "army"}),
            (630, {"cmd": "STAGE", "off": 1}), (660, {"cmd": "MOVE", "count": "all", "target": "home"}),
            (720, {"cmd": "ATTACK", "count": "all", "target": "base"}), (780, {"cmd": "RETREAT"}),
            (785, {"cmd": "_ВПЕРЁД", "target": "army"}), (840, {"cmd": "_НА_КЛЕТКУ", "aim": [m[0], m[1]]}),
        ]
        self.i = 0
        self.отдано = []

    def __call__(self, st):
        из = self.хоз(st)
        t = float(st.get("gametime") or 0)
        while self.i < len(self.план) and self.план[self.i][0] <= t:
            из.append(dict(self.план[self.i][1]))
            self.отдано.append((t, self.план[self.i][1]["cmd"]))
            self.i += 1
        return из


def _инварианты_партии(з):
    """Одна партия с проверками на каждом такте. Возвращает счётчики нарушений и диагностику."""
    d, seed, агент = з
    import sim as SIM
    import враг as ВР
    _режим_записи()
    if агент:
        import тактик as ТК
        ТК._настроить("мушкетёры" if seed % 2 else "родной")
    # учёт снятого с его клеток: сколько запрошено и сколько снято на самом деле
    учёт = {"запрошено": 0.0, "снято": 0.0}
    _исх = ВР.Враг.потери

    def потери_с_учётом(self, x, y, n):
        было = self.h[y][x] if 0 <= y < self.N and 0 <= x < self.N else 0.0
        _исх(self, x, y, n)
        стало = self.h[y][x] if 0 <= y < self.N and 0 <= x < self.N else 0.0
        учёт["запрошено"] += max(0.0, n)
        учёт["снято"] += было - стало
    ВР.Враг.потери = потери_с_учётом
    try:
        зап = SIM.Запись(d)
        сим = SIM.Симулятор(зап, seed)
        п = Манёвр(_хоз(), зап.en_base, (int((зап.my_cx + зап.en_base[0]) / 2), int((зап.my_cy + зап.en_base[1]) / 2)))
        армия0 = сим.враг.всего() if сим.враг is not None else None
        нар = {k: 0 for k in ("nan", "отриц_группа", "группы≠экономика", "его_отриц", "его_баланс", "после_RETREAT_не_домой",
                              "после_ВПЕРЁД_домой", "ОТРЯД_слился_за_такт")}
        макс_разрыв = 0.0
        след = сим.t
        прошлый_приказ = None
        n_групп_до_отряда = None
        while not сим.исход:
            if сим.t >= след:
                было_отдано = len(п.отдано)
                n_групп = len([г for г in сим.группы[1:] if sum(г["состав"].values()) > 0.5 and г["режим"] != "домой"])
                сим.команды(п(сим.состояние()) or [])
                след += SIM.ШАГ_РЕШЕНИЯ
                if len(п.отдано) > было_отдано:
                    прошлый_приказ = п.отдано[-1][1]
                    n_групп_до_отряда = n_групп
                else:
                    прошлый_приказ = None
            сим.такт()
            s = сим.состояние()
            нар["nan"] += sum(1 for v in s.values() if isinstance(v, float) and (math.isnan(v) or math.isinf(v)))
            гр = 0.0
            for г in сим.группы:
                for v in г["состав"].values():
                    if v < -1e-6:
                        нар["отриц_группа"] += 1
                    гр += v
            разрыв = abs(гр - sum(сим.эк.армия.values()))
            макс_разрыв = max(макс_разрыв, разрыв)
            if разрыв > 0.01:
                нар["группы≠экономика"] += 1
            if сим.враг is not None:
                h = сим.враг.h
                if any(v < -1e-9 for row in h for v in row):
                    нар["его_отриц"] += 1
                if abs(сим.враг.всего() - (армия0 + сим.враг.нанято - учёт["снято"])) > 0.01:
                    нар["его_баланс"] += 1
            # приказы волне: проверка сразу после такта, в котором отдан приказ
            поле = [г for г in сим.группы[1:] if sum(г["состав"].values()) > 0.5]
            if прошлый_приказ == "RETREAT" and any(г["режим"] != "домой" for г in поле):
                нар["после_RETREAT_не_домой"] += 1
            if прошлый_приказ == "_ВПЕРЁД" and any(г["режим"] == "домой" for г in поле):
                нар["после_ВПЕРЁД_домой"] += 1
            if прошлый_приказ == "_ОТРЯД" and n_групп_до_отряда and \
                    len([г for г in поле if г["режим"] != "домой"]) <= n_групп_до_отряда:
                нар["ОТРЯД_слился_за_такт"] += 1   # диагностика: отряд и голова в одной клетке сливаются обратно в конце такта
            прошлый_приказ = None
        итог = dict(нарушения=нар, макс_разрыв=round(макс_разрыв, 4), тактов=len(п.отдано), исход=сим.исход,
                    потери=round(сим.my_mil_lost, 2), убито=round(сим.убито_бойцов, 2), приказов=len(п.отдано),
                    отказов=len(сим.квитанции),
                    отказов_манёвра=sum(1 for q in сим.квитанции if q[1].split(":")[0].split(" ")[0] in {c["cmd"] for _, c in п.план}))
        if сим.враг is not None:
            итог["перебито_сверх_клетки"] = round(учёт["запрошено"] - учёт["снято"], 2)
            итог["его_убито"] = round(учёт["снято"], 2)
        return итог
    finally:
        ВР.Враг.потери = _исх


