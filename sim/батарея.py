def замкнутый_цикл(пул, тест):
    р = [x for x in пул.map(_цикл, [(d, 0) for d in тест]) if x]
    из = {"партий": len(р), "исходы": {k: sum(1 for x in р if x["исход"] == k) for k in sorted(set(x["исход"] for x in р))}}
    for k in ("наши", "его", "крестьяне", "наши_крестьяне"):
        сим, факт = sum(x[k][0] for x in р), sum(x[k][1] for x in р)
        л2 = [abs(math.log2((x[k][0] + 1) / (x[k][1] + 1))) for x in р]
        из[k] = dict(сим=round(сим), факт=round(факт), смещение_log2=round(math.log2((сим + 1) / (факт + 1)), 3), медиана_log2=round(St.median(л2), 3))
    # первая волна за 180 единиц от ратуши: когда вышла в симуляторе и в записи (медианы по партиям, где была у обоих)
    волны = [x["волна"] for x in р if x["волна"][0] and x["волна"][1]]
    из["первая_волна_с"] = dict(сим=round(St.median(v[0] for v in волны)), факт=round(St.median(v[1] for v in волны)), партий=len(волны)) if волны else {}
    из["первая_волна_позже_факта_с"] = round(St.median(v[0] - v[1] for v in волны)) if волны else None
    худшие = sorted(р, key=lambda x: -abs(math.log2((x["наши"][0] + 1) / (x["наши"][1] + 1))))[:3]
    из["худшие_по_нашим_потерям"] = [dict(запись=os.path.relpath(x["d"], os.path.expanduser("~")), сим=round(x["наши"][0]), факт=round(x["наши"][1])) for x in худшие]
    return из


