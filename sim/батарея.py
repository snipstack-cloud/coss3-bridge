def сплющить(d, пред=""):
    из = {}
    for k, v in d.items():
        имя = f"{пред}.{k}" if пред else str(k)
        if isinstance(v, dict):
            из.update(сплющить(v, имя))
        elif isinstance(v, (int, float)) and not isinstance(v, bool):
            из[имя] = v
        elif isinstance(v, (list, tuple)) and len(v) == 2 and all(isinstance(q, (int, float)) for q in v):
            из[имя + ".сим"], из[имя + ".факт"] = v
    return из


def сравнить(новый, старый):
    a, b = сплющить(новый), сплющить(старый)
    сдвиги = []
    for k in sorted(a):
        if k.startswith("шапка") or k not in b:
            continue
        x, y = a[k], b[k]
        if x == y:
            continue
        rel = abs(x - y) / max(abs(y), 1e-9)
        if rel > 0.05 or abs(x - y) > 0.05:
            сдвиги.append((k, y, x))
    return сдвиги


