def инварианты(пул, тест):
    из = {}
    # детерминизм: 5 записей × 2 повтора в РАЗНЫХ процессах
    зад = [(d, 1, None) for d in тест[:5]]
    a = пул.map(_партия_числа, зад)
    b = пул.map(_партия_числа, зад)
    из["детерминизм_расхождений"] = sum(1 for x, y in zip(a, b) if x != y)
    # инварианты с манёврами: 8 записей, противник запись и агент
    р = пул.map(_инварианты_партии, [(d, i, False) for i, d in enumerate(тест[:8])] + [(d, i, True) for i, d in enumerate(тест[:8])])
    нар = {}
    for x in р:
        for k, v in x["нарушения"].items():
            нар[k] = нар.get(k, 0) + v
    из["нарушения"] = нар
    из["макс_разрыв_группы_экономика"] = max(x["макс_разрыв"] for x in р)
    аг = [x for x in р if "перебито_сверх_клетки" in x]
    из["перебито_сверх_клетки_сумма"] = round(sum(x["перебито_сверх_клетки"] for x in аг), 2)
    из["его_убито_агентом_сумма"] = round(sum(x["его_убито"] for x in аг), 2)
    из["отказов_на_партию"] = round(St.mean(x["отказов"] for x in р), 1)          # почти все — очередь UPGRADE/BUILD хозяйства
    из["отказов_манёвра_на_партию"] = round(St.mean(x["отказов_манёвра"] for x in р), 1)
    из["приказов_манёвра_на_партию"] = round(St.mean(x["приказов"] for x in р), 1)
    # шаг решения: 5 с против 15 с при зерне 1; шум зерна — 5 с при зёрнах 1 и 2
    s5 = пул.map(_партия_числа, [(d, 1, 5.0) for d in тест])
    s15 = пул.map(_партия_числа, [(d, 1, 15.0) for d in тест])
    s5b = пул.map(_партия_числа, [(d, 2, 5.0) for d in тест])

    def л2(x, y, k):
        return abs(math.log2((x[k] + 1) / (y[k] + 1)))
    for k in ("потери", "убито"):
        из[f"шаг_5_против_15_|log2|_{k}"] = round(St.median(л2(x, y, k) for x, y in zip(s5, s15)), 3)
        из[f"шум_зерна_|log2|_{k}"] = round(St.median(л2(x, y, k) for x, y in zip(s5, s5b)), 3)
    из["шаг_5_против_15_исход_разошёлся"] = sum(1 for x, y in zip(s5, s15) if x["исход"] != y["исход"])
    из["шум_зерна_исход_разошёлся"] = sum(1 for x, y in zip(s5, s5b) if x["исход"] != y["исход"])
    return из


