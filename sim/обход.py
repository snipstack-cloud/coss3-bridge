"""Путь к цели В ОБХОД его армии (просьба игрока 27.09).

«Нужно освоить подход военных юнитов к крестьянам, так как в лоб можно напороться
на армию противника и слить всю армию или часть.»

Дийкстра по сетке 16×16: шаг в соседнюю клетку стоит 1, а клетка, в окне которой
стоят его бойцы, стоит дороже — тем дороже, чем их больше. Путь возвращается
списком клеток; движению нужна только СЛЕДУЮЩАЯ, поэтому отдаём и её.

Числа, из которых взят штраф: у его базы наши потери 2,19 за такт против 1,81 в
поле при вдвое меньшем числе врагов (§15), то есть заход в занятую клетку стоит
примерно такта боя. Штраф 6 за бойца в клетке подобран так, чтобы обход в две-три
клетки был выгоднее прохода сквозь клетку с десятком его бойцов.
"""
import heapq

ШТРАФ_ЗА_БОЙЦА = 6.0
ОКНО = 1          # его бойцы в этой клетке и соседних делают клетку опасной


def стоимости(его_сетка, окно=ОКНО):
    """Опасность каждой клетки: сколько его бойцов в её окне."""
    n = len(его_сетка)
    из = [[0.0] * n for _ in range(n)]
    for y in range(n):
        for x in range(n):
            s = 0.0
            for yy in range(max(0, y - окно), min(n, y + окно + 1)):
                for xx in range(max(0, x - окно), min(len(его_сетка[yy]), x + окно + 1)):
                    s += float(его_сетка[yy][xx] or 0)
            из[y][x] = s
    return из


def путь(старт, цель, его_сетка, штраф=ШТРАФ_ЗА_БОЙЦА):
    """Список клеток от старта до цели, огибающий его бойцов. Пустой — если некуда."""
    if not его_сетка:
        return [цель]
    n = len(его_сетка)
    оп = стоимости(его_сетка)
    s = (int(round(старт[0])), int(round(старт[1])))
    ц = (int(round(цель[0])), int(round(цель[1])))
    if not (0 <= s[0] < n and 0 <= s[1] < n and 0 <= ц[0] < n and 0 <= ц[1] < n):
        return [цель]
    дист = {s: 0.0}
    откуда = {}
    куча = [(0.0, s)]
    while куча:
        d, у = heapq.heappop(куча)
        if у == ц:
            break
        if d > дист.get(у, float("inf")):
            continue
        x, y = у
        for dx in (-1, 0, 1):
            for dy in (-1, 0, 1):
                if dx == 0 and dy == 0:
                    continue
                nx, ny = x + dx, y + dy
                if not (0 <= nx < n and 0 <= ny < n):
                    continue
                шаг = (1.4 if dx and dy else 1.0) + штраф * оп[ny][nx]
                нов = d + шаг
                if нов < дист.get((nx, ny), float("inf")):
                    дист[(nx, ny)] = нов
                    откуда[(nx, ny)] = у
                    heapq.heappush(куча, (нов, (nx, ny)))
    if ц not in дист:
        return [цель]
    п = [ц]
    while п[-1] != s:
        п.append(откуда[п[-1]])
    п.reverse()
    return [(float(x), float(y)) for x, y in п[1:]] or [цель]


def следующая(старт, цель, его_сетка, штраф=ШТРАФ_ЗА_БОЙЦА):
    """Куда шагнуть СЕЙЧАС, чтобы идти к цели в обход. Цель — если обходить нечего."""
    п = путь(старт, цель, его_сетка, штраф)
    return п[0] if п else цель


def опасность_прямой(старт, цель, его_сетка):
    """Сколько его бойцов стоит на прямой от старта к цели — для сравнения с обходом."""
    if not его_сетка:
        return 0.0
    оп = стоимости(его_сетка)
    n = len(его_сетка)
    шагов = int(max(abs(цель[0] - старт[0]), abs(цель[1] - старт[1]))) or 1
    сумма = 0.0
    for i in range(1, шагов + 1):
        x = int(round(старт[0] + (цель[0] - старт[0]) * i / шагов))
        y = int(round(старт[1] + (цель[1] - старт[1]) * i / шагов))
        if 0 <= x < n and 0 <= y < n:
            сумма += оп[y][x]
    return сумма
