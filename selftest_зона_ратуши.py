"""ЗОНА РАТУШИ И РЕЙД НА ПОДХОДЕ (2.11, разбор разделения армии): ключи `ратуша_радиус` и `ратуша_подход`.

10 живых партий: 327 из 333 наших крестьян убиты в клетке ратуши (162) или соседней (165). Человек делит армию —
большая группа стоит лагерем в 3–6 клетках, малая режет крестьян у ратуши; правило `ратуша_своими` смотрело одну клетку.
Кейсы — настоящие такты трасс:
  * №10 1.11 (`раздел_ратуша_своими_0930-1120`): его 51 в соседней с ратушей (12,3) клетке (12,2), 13 крестьян за
    минуту при 165 праздных; правило молчало до 11:00 (его 81 вошли в саму клетку ратуши), первый крестьянин — 10:56;
  * №7 31.10 (`раздел_6680_1000-1200`): рейд 28–30 шёл (9,14) → (11,14) → (12,14) к ратуше (13,14), бот в 11:03 ударил
    по лагерю 88, рейд вошёл в клетку ратуши, 49 крестьян за полминуты.
    python3 selftest_зона_ратуши.py"""
import copy
import json
import os
import sys
import tempfile

К = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, К)
import strategy_live as SL  # noqa: E402
import анализ_врага as АВ  # noqa: E402

ошибок = 0


def проверить(усл, что):
    global ошибок
    print(("ОК   " if усл else "ОШИБКА ") + что)
    ошибок += not усл


def живое(t):
    """Трасса хранит клетки и здания списками, живое состояние — строками «x,y,…;…»."""
    st = {}
    for k, v in t["state"].items():
        st[k] = ";".join(",".join(str(x) for x in r) for r in v) \
            if isinstance(v, list) and v and all(isinstance(r, list) for r in v) else v
    st["gametime"] = t["gt"]
    return st


def кейс(имя):
    return [живое(json.loads(s)) for s in open(os.path.join(К, f"sim/кейсы/{имя}.jsonl"), encoding="utf-8")]


def стратегия(доп):
    АВ._ТЕКУЩИЙ.update({"а": None, "t": None, "ответ": None})
    д = json.load(open(os.path.join(К, "sim/поиск/шт_s2_оборона_без_атаки_12мин_стойка_отряд_рефлекс.json"), encoding="utf-8"))
    д["итог"].update(доп)
    with tempfile.NamedTemporaryFile("w", suffix=".json", delete=False, encoding="utf-8") as f:
        json.dump(д, f, ensure_ascii=False)
    return SL.ЖиваяСтратегия(f.name)


def первый_удар(состояния, доп):
    С = стратегия(доп)
    for st in состояния:
        из, why = С._ратуша_своими([{"cmd": "BALANCE", "role": "food"}], copy.deepcopy(st))
        a = [c for c in из if c["cmd"] == "ATTACK"]
        if a:
            return st["gametime"], a[0], why, С
    return None, None, "", С


# --- №10 1.11: рейд в СОСЕДНЕЙ клетке
К10 = кейс("раздел_ратуша_своими_0930-1120")
t0, _, w0, _ = первый_удар(К10, {"ратуша_своими": 10})
t1, a1, w1, С1 = первый_удар(К10, {"ратуша_своими": 10, "ратуша_радиус": 1})
проверить(t0 is None or t0 >= 650, f"(а) №10 без радиуса правило молчит, пока он в соседней клетке: первый удар {t0}")
проверить(t1 is not None and t1 < 656, f"(б) №10 с радиусом 1 удар по соседней клетке РАНЬШЕ первого убитого крестьянина (10:56): {t1} — {w1[:110]}")
проверить(a1 is not None and (a1["cx"], a1["cy"]) != (12, 3) and max(abs(a1["cx"] - 12), abs(a1["cy"] - 3)) == 1,
          f"(в) цель — соседняя с ратушей клетка, не сама ратуша: {a1 and (a1['cx'], a1['cy'])}")
проверить(С1.реестр.мера["оборона: зона ратуши"] >= 1, "(г) мера «оборона: зона ратуши» посчитана")

# --- №7 31.10: рейд НА ПОДХОДЕ
К7 = кейс("раздел_6680_1000-1200")
t2, a2, w2, _ = первый_удар(К7, {"ратуша_своими": 10, "ратуша_радиус": 1})
t3, a3, w3, _ = первый_удар(К7, {"ратуша_своими": 10, "ратуша_радиус": 1, "ратуша_подход": 1})
проверить(t3 is not None and (t2 is None or t3 < t2),
          f"(д) №7 с подходом удар раньше, чем без него: {t3} против {t2} — {w3[:110]}")
проверить(t3 is not None and t3 <= 663, f"(е) №7 удар по рейду не позже удара бота по лагерю 88 (11:03): {t3}")

# --- без ключей — как было
t4, _, _, _ = первый_удар(К10, {})
проверить(t4 is None, "(ж) без `ратуша_своими` правило молчит, как было")

# --- через полный ответ(): приказ не снимается правилами после
С = стратегия({"ратуша_своими": 10, "ратуша_радиус": 1})
дошёл = None
for st in К10:
    о = С.ответ(copy.deepcopy(st))
    if any(c.get("cmd") == "ATTACK" and c.get("_оборона") and not c.get("who")
           and max(abs(int(c.get("cx", -9)) - 12), abs(int(c.get("cy", -9)) - 3)) == 1 for c in о["commands"]):
        дошёл = st["gametime"]
        break
проверить(дошёл is not None and дошёл < 656, f"(з) через ответ(): удар по соседней с ратушей клетке на {дошёл}")

print(f"ошибок: {ошибок}")
raise SystemExit(1 if ошибок else 0)
