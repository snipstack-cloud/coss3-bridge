# -*- coding: utf-8 -*-
"""Собирает НАСТОЯЩИЕ запросы события «куда людей» из отыгранных партий.

Задачи берутся не из головы: по трассам `base24` ищется тот самый переход,
на котором событие и срабатывает, — `on_build` упал в ноль, а свободных
крестьян стало больше порога. Запрос строится тем же кодом, каким его строит
мост (`запрос_рук`), и на состоянии ПОСЛЕ перехода, то есть ровно на том, что
модель увидит вживую.

Чистый приход считается по ПРЕДЫДУЩЕМУ такту той же партии — иначе в задаче
стояло бы «прихода нет», а такого в живой партии не бывает нигде, кроме
первых секунд.

    python3 bench_hands_cases.py [<каталог с трассами>] > задачи_руки.json
"""
import json, glob, sys
sys.path.insert(0, '/Users/gs/coss3-bridge')
import llm_policy as L

КАТАЛОГ = sys.argv[1] if len(sys.argv) > 1 else '/Users/gs/coss3-res/2026-09-21/base24'
ПОРОГ = 3

партии = []
for ф in sorted(glob.glob(f'{КАТАЛОГ}/*/coss3_bot.jsonl')):
    текущая = []
    for строка in open(ф, encoding='utf-8'):
        строка = строка.strip()
        if not строка:
            continue
        x = json.loads(строка)
        if 'finish' in x:
            if текущая:
                партии.append((ф, текущая))
                текущая = []
            continue
        st = x.get('state')
        if isinstance(st, dict) and 'gametime' in st:
            текущая.append(st)
    if текущая:
        партии.append((ф, текущая))

задачи, видели = [], set()
for ф, такты in партии:
    for i in range(1, len(такты)):
        до, после = такты[i - 1], такты[i]
        if not (L._чис(до.get('on_build')) > 0 and L._чис(после.get('on_build')) == 0):
            continue
        свободных = int(L._чис(после.get('idle_pea')))
        if свободных < ПОРОГ:
            continue
        # Разнообразие важнее числа задач: одинаковые обстановки меряют одно и
        # то же. Ключ — что в дефиците и что уже построено.
        ключ = (L._чис(после.get('food')) < L.ПОРОГ_ЕДЫ,
                int(L._чис(после.get('mills'))) > 0,
                int(L._чис(после.get('mines_gold'))) > 0,
                int(L._чис(после.get('mines_iron'))) > 0,
                min(3, свободных // 4), int(L._чис(после.get('gametime')) // 300))
        if ключ in видели:
            continue
        видели.add(ключ)
        L.РЕСУРСЫ_ИСТОРИЯ.clear()
        L.чистый_приход(до)
        задачи.append({
            'откуда': ф.split('/')[-2], 'gt': int(L._чис(после.get('gametime'))),
            'свободных': свободных,
            'состояние': после,
            'запрос': L.запрос_рук(после, после, свободных, такт=20),
        })

print(json.dumps(задачи, ensure_ascii=False, indent=1))
print(f'задач: {len(задачи)}', file=sys.stderr)
