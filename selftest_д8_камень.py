#!/usr/bin/env python3
"""КАМЕНЬ Д8 — МИГАНИЕ БРИГАДЫ (20.10, §168а): такты восьмой живой партии Д (`sim/кейсы/партия_д8_20_10_0_13-10_14.jsonl`, мост
47c8825 с §166/§167). Вживую: переброс и снятые с золота ставили на камень/дерево 20–28 при земле 16–29, на еде 1–4; еда 1347 → 795
за 40 с, нужда гасла (гистерезис 840), BALANCE food 30, еда до 1200 — и снова; период 40–60 с, цель переброса ходила stone → wood →
stone (недостачи до казармы 160 и 186), камень 40 → 340 → 240 при 107 тактах нужды. Три правки: пол пахарей `еда_пахарей_мин` (6 при
`нужда_макс` > 0), липкая цель переброса (держится, пока по ней недостача), снятые с золота — не сверх `нужда_доля` земли с учётом
снятых, остаток еде.

(а) 4:56 нужда включилась: stone ≥ 7 и запись `§168а пол пахарей 6`; 5:01 (земля 13, живьём на еде 1): BALANCE food ≥ 6; (б) 6:17 → 6:22: живьём цель
перескочила на wood (недостача 186 против 160) — теперь держится stone; (в) 6:17 → 6:43 одной стратегией (золото 2527, земля 16, живьём stone 20 и еде ничего): food ≥ 6, stone + wood + food ≤ земля + снятые 10 + 2; (г) 4:56–6:43 одной стратегией: цель меняется не больше одного
раза; (д) `нужда_макс` 0 — записи §168а нет.

    python3 selftest_д8_камень.py
"""
import copy, json, os, sys, tempfile
К = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, К); sys.path.insert(0, os.path.join(К, "sim"))
os.environ.pop("COSS3_WAVE_CONTRACT", None)
import strategy_live as SL
import анализ_врага as АВ

кейс = [json.loads(l) for l in open(os.path.join(К, "sim/кейсы/партия_д8_20_10_0_13-10_14.jsonl"), encoding="utf-8")]
ошибок = 0
def проверить(усл, что):
    global ошибок
    print(("ОК   " if усл else "ОШИБКА ") + что); ошибок += not усл
def стратегия(доп):
    д = json.load(open(os.path.join(К, "sim/поиск/шт_s2_оборона_ручеёк_эко_так15_нужда.json"), encoding="utf-8"))
    assert д["итог"].get("нужда_макс") == 10 and д["итог"].get("переброс") == 1
    # 26.10: §170п (`переброс_раз` 50 в файле партии) даёт одно перемещение за 50 с и гасит остальные приказы.
    # Здесь судятся правила ДО него — пришпиливаем к 0, как мак сделал для трёх своих.
    д["итог"]["переброс_раз"] = 0
    # 27.10: §170м (пол прокормом, добор до пола, нужда после mil.1, золото по цене) включён в файле Д17 —
    # здесь судятся правила ДО него, пришпиливаем к 0 тем же порядком.
    for _к in ("пол_прокормом", "добор_до_пола", "нужда_после_mil1", "золото_по_цене", "пачка_крестьян"):
        д["итог"][_к] = 0
    # 29.10 (ключи стока и шахты в живом файле по слову игрока): здесь судятся правила ДО них — пришпилены к 0 тем же порядком, что §170м
    for _к5 in ("сток_излишек", "золото_лежит_по_факту", "шахта_без_срока", "закладка_по_срокам", "выпущенные_в_бюджет", "переброс_по_долям"):
        д["итог"][_к5] = 0
    д["итог"].update(доп)
    with tempfile.NamedTemporaryFile("w", suffix=".json", delete=False, encoding="utf-8") as f:
        json.dump(д, f, ensure_ascii=False)
    return SL.ЖиваяСтратегия(f.name)
def при(t): return next(s for s in кейс if float(s["gametime"]) >= t)
def ответ(С, s):
    АВ._ТЕКУЩИЙ.update({"а": None, "t": None, "ответ": None}); return С.ответ(copy.deepcopy(s))
def баланс(о, роль):
    v = [c.get("total") for c in о["commands"] if c["cmd"] == "BALANCE" and c.get("role") == роль]
    return v[-1] if v else None
def земля(s): return int(float(s["peasants"]) - float(s.get("on_mine") or 0) - float(s.get("on_build") or 0))

# (а) 5:01
С = стратегия({}); s = при(296); о = ответ(С, s)
проверить((баланс(о, "stone") or 0) >= 7 and "§168а пол пахарей 6" in о["why"], f"(а) 4:56 нужда включилась: stone {баланс(о, 'stone')}; {[x for x in о['why'].split(', ') if '§168а' in x][:1]}")
s = при(301); о = ответ(С, s)
проверить((баланс(о, "food") or 0) >= 6 and ((баланс(о, "stone") or 0) >= 7 or int(s["on_stone"]) >= 7),
          f"(а) 5:01 земля {земля(s)}, живьём на еде {s['on_food']}: food {баланс(о, 'food')}, на камне {s['on_stone']}")
# (б) 6:17 → 6:22 липкая цель
С = стратегия({}); ответ(С, при(377)); о = ответ(С, при(382))
проверить(getattr(С.стр, "_переброс_цель", None) == "stone" and "на wood" not in о["why"],
          f"(б) 6:22: цель {getattr(С.стр, '_переброс_цель', None)} (живьём перескочила на wood); {[x for x in о['why'].split(', ') if '§167' in x][:1]}")
# (в) 6:43 золото при нужде — еда не пуста
С = стратегия({})
for _s in кейс:                                     # нужда включилась в 6:17 (еда 1338) и держится гистерезисом
    if 377 <= float(_s["gametime"]) < 403: ответ(С, _s)
s = при(403); о = ответ(С, s)
сумма = sum(баланс(о, r) or 0 for r in ("food", "wood", "stone"))
проверить((баланс(о, "food") or 0) >= 6 and сумма <= земля(s) + 10 + 2 and баланс(о, "gold") == 5,
          f"(в) 6:43 земля {земля(s)}: food {баланс(о, 'food')}, stone {баланс(о, 'stone')}, wood {баланс(о, 'wood')}, gold {баланс(о, 'gold')} — сумма {сумма} ≤ {земля(s) + 12}")
# (г) 4:56–6:43 — цель не прыгает
С = стратегия({}); цели = []
for s in кейс:
    t = float(s["gametime"])
    if 296 <= t <= 403:
        ответ(С, s); ц = getattr(С.стр, "_переброс_цель", None)
        if ц and (not цели or цели[-1] != ц): цели.append(ц)
проверить(len(цели) <= 1, f"(г) 4:56–6:43 цели переброса по порядку: {цели} (живьём stone → wood → stone)")
# (д) ключ
С0 = стратегия({"нужда_макс": 0}); ответ(С0, при(296)); о0 = ответ(С0, при(301))
проверить("§168а" not in о0["why"], "(д) нужда_макс 0 — пола пахарей нет")
print(f"\nошибок: {ошибок}")
sys.exit(1 if ошибок else 0)
