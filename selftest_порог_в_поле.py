# -*- coding: utf-8 -*-
"""Самопроверка: падение «в поле» само по себе не повод отзывать волну (3.11).

`mil_away` — порог по клетке, `mil_away_u` — порог по `1.5*hqw/hqn` единицам
(`block_hstate.inc:502`). Один шаг кучки через границу рушит оба вдвое-впятеро
при ЦЕЛОЙ армии: 23 таких падения на 12 трассах пары Нидерландов, и счётчик
гибели движка сдвинулся в них на 0..2 при 9..91 «пропавших из поля» — ни одно
не объяснялось гибелью даже наполовину. До правки мост на этом сам отзывал
волну домой (отход по `retreat_below` читал живых по `mil_away`).

Проверяется ровно три вещи:
  * гибель НЕ объясняет пропажу — отход не отдан, волна остаётся в ударе;
  * гибель объясняет — отход отдан, как прежде;
  * счётчика гибели в снимке нет (старый мост) — поведение прежнее.
"""
import llm_policy as L

беды = []


def проверка(имя, условие, пояснение=""):
    if условие:
        print("  ОК   " + имя)
    else:
        беды.append(имя)
        print("  ПЛОХО " + имя + (" — " + пояснение if пояснение else ""))


class Мост:
    def __init__(self):
        self.приказы = []
        self.занят = False

    def attack(self, count, target="base", mode="", cx=-1, cy=-1):
        if self.занят:
            return False
        self.приказы.append((count, target, mode, cx, cy))
        return True


def сетка(имя, **клетки):
    строки = [["."] * 16 for _ in range(16)]
    for k, v in клетки.items():
        x, y = (int(t) for t in k.split(","))
        строки[y][x] = str(v)
    return {f"{имя}{y}": "".join(строки[y]) for y in range(16)}


БАЗА = dict(gametime=400, grid_n=16, my_cx=13, my_cy=14, mil_inf=30,
            mil_shooters=20, my_freewar=45, map_open=1)


def довести_до_удара(база):
    """Общее начало: марш с retreat_below=0.5, двадцать дошли, удар начат."""
    L.МАРШ.clear()
    мост, волны = Мост(), []
    L.начать_марш(1000, 40, "cell", (13, 4),
                  {"via": (13, 8), "retreat": 0.5}, dict(база))
    L.шаг_марша(dict(база, gametime=1020, wave_n=40), мост, 1020, волны)
    L.шаг_марша(dict(база, gametime=1040, **сетка("arow", **{"13,8": "k"})),
                мост, 1040, волны)
    return мост, волны


# 1. ШАГ ЧЕРЕЗ ГРАНИЦУ: в поле 9 из 20, а погибших нет. Волну не отзываем.
мост, волны = довести_до_удара(dict(БАЗА, my_mil_lost=7))
проверка("удар начат", L.МАРШ["фаза"] == "удар", L.МАРШ.get("фаза"))
проверка("гибель в миг удара запомнена",
         L.МАРШ.get("потерь_при_ударе") == 7, str(L.МАРШ.get("потерь_при_ударе")))
L.шаг_марша(dict(БАЗА, gametime=1120, mil_away=9, my_mil_lost=7),
            мост, 1120, волны)
проверка("падение без гибели — отход НЕ отдан",
         L.МАРШ["фаза"] == "удар", L.МАРШ["фаза"])
проверка("приказ домой не ушёл",
         all(п[1] != "home" for п in мост.приказы), str(мост.приказы))
проверка("артефакт назван вслух",
         any("ОТХОД НЕ ОТДАН" in с and "порог" in с for с in L.МАРШ["отчёт"]),
         str(L.МАРШ["отчёт"][-1:]))
проверка("жалоба сказана один раз, а не каждый такт",
         sum(1 for с in L.МАРШ["отчёт"] if "ОТХОД НЕ ОТДАН" in с) == 1)
L.шаг_марша(dict(БАЗА, gametime=1140, mil_away=8, my_mil_lost=7),
            мост, 1140, волны)
проверка("и на следующем такте не отзывает",
         L.МАРШ["фаза"] == "удар" and L.МАРШ.get("отход_отклонён") == 2,
         str(L.МАРШ.get("отход_отклонён")))

# 2. НАСТОЯЩЕЕ ТАЯНИЕ: пропало 11, погибло 8 — отход отдан, как прежде.
мост, волны = довести_до_удара(dict(БАЗА, my_mil_lost=7))
L.шаг_марша(dict(БАЗА, gametime=1120, mil_away=9, my_mil_lost=15),
            мост, 1120, волны)
проверка("гибель объясняет пропажу — отход отдан",
         L.МАРШ["фаза"] == "отход", L.МАРШ["фаза"])
проверка("приказ retreat ушёл домой",
         мост.приказы[-1] == (40, "home", "retreat", -1, -1), str(мост.приказы))

# 3. СТАРЫЙ МОСТ: поля гибели в снимке нет — ведём себя как до правки.
мост, волны = довести_до_удара(БАЗА)
проверка("без поля гибель не запомнена",
         L.МАРШ.get("потерь_при_ударе") is None,
         str(L.МАРШ.get("потерь_при_ударе")))
L.шаг_марша(dict(БАЗА, gametime=1120, mil_away=9), мост, 1120, волны)
проверка("без счётчика поведение прежнее — отход отдан",
         L.МАРШ["фаза"] == "отход", L.МАРШ["фаза"])

# 4. СЛОВА МОДЕЛИ: ложное «пропали» названо артефактом, настоящее — нет.
ПОЛЕ = dict(БАЗА, gametime=1200, mil_away=60, mil_near=5, mil_far=30,
            my_mil_lost=7, wave_sent=60)
т = "\n".join(L.situation(dict(ПОЛЕ, gametime=1220, mil_away=20, my_mil_lost=7),
                          {}, [], "", было=dict(ПОЛЕ)).splitlines())
проверка("модели сказано, что это не потери",
         "НЕ ПРОПАЛИ" in т and "порогом по клетке" in т,
         [с for с in т.splitlines() if "ПРОПАЛИ" in с])
т2 = "\n".join(L.situation(dict(ПОЛЕ, gametime=1220, mil_away=20, my_mil_lost=40),
                           {}, [], "", было=dict(ПОЛЕ)).splitlines())
проверка("при настоящей гибели артефакт НЕ объявляется",
         "НЕ ПРОПАЛИ" not in т2,
         [с for с in т2.splitlines() if "ПРОПАЛИ" in с])

print()
if беды:
    print("ПРОВАЛОВ: %d" % len(беды))
    raise SystemExit(1)
print("порог «в поле»: все проверки пройдены")
