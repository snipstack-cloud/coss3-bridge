"""Самопроверка второго повода событийного канала: «стройка кончилась».

Замысел игрока 21.09: событийный вызов понравился на найме — развить его в
реестр поводов и завести второй. Повод выбран по [замеру] 9 партий `base24`
(455 тактов):

* свободные крестьяне есть в 44-49 тактах из 49-53 — 12,8 процента всего
  труда крестьян уходит в никуда;
* переход `on_build` в ноль случается 5-6 раз за партию во всех девяти
  партиях и освобождает медианно 5 человек при 33 крестьянах — это событие;
* порог по одному лишь простою сработал бы 24 раза за партию, то есть был бы
  вторым тактом, а не событием, и потому отвергнут;
* узкий вопрос стоит 1,9 с и 35 токенов против 6,8 с и 242 у обычного такта,
  а обычный такт идёт медианно раз в 21 с, в десятой части случаев — раз в
  46 с и дольше. Столько эти люди и стоят.

Стережётся:
* событие ловит ПЕРЕХОД, а не простой, и молчит при выключенном ключе;
* запрос короткий и говорит правду о невозможном (нет мельницы, нет шахты,
  места на земле заняты) — иначе совет уйдёт в пустоту;
* ответ короткой схемы переводится в BALANCE с ИТОГОВЫМ числом, потому что
  модель отвечает прибавкой, а команда задаёт итог;
* просьба больше, чем свободных, урезается и названа вслух;
* реестр поводов разбирает оба вида, и найм от этого не изменился.
"""
