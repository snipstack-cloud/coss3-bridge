# -*- coding: utf-8 -*-
"""Самопроверка режима `--critic-trace`: разбор ГОТОВОЙ трассы.

Критик вызывается один раз в конце партии, и всё, что оборвалось раньше,
остаётся без разбора навсегда. 20.09 пара `base22`/`switch4` была остановлена
после первых партий, и две трассы из четырёх ушли в архив без единого слова
критика — включая ЕДИНСТВЕННУЮ партию, где сработала проверяемая связка.

Стережётся:
* трасса делится на партии по падению времени и по записи `finish`;
* исход партии берётся из `finish`, а у оборванной честно назван неизвестным;
* строки тактов собираются ТЕМ ЖЕ `строка_такта`, что и в живой петле —
  двух разных текстов быть не должно, иначе разборы двух путей несравнимы;
* уроки модели переносятся из поля `lesson`;
* дневник восстанавливается: вехи построек и волны;
* сетки `frow`/`arow` разворачиваются из списка в `frow0..frowN` — без этого
  всё, что считается по клеткам, молчит по построению (ложный ноль, дважды);
* без `--critic` режим отказывается работать и говорит почему.
"""
import io
import json
import os
import tempfile
import types

import llm_policy as L

беды = []


def проверка(имя, условие, пояснение=""):
    if условие:
        print("  ОК    " + имя)
    else:
        беды.append(имя)
        print("  ПЛОХО " + имя + (" — " + пояснение if пояснение else ""))


def такт(gt, пехота=10, казарм=1, урок="", атака=0, цель="", финиш=None):
    n = 16
    ст = {"gametime": gt, "grid_n": n, "map_w": 256, "map_open": 1,
          "my_cx": 3, "my_cy": 12, "my_freewar": пехота, "peasants": 40,
          "mil_inf": пехота, "mil_shooters": 0, "mil_cav": 0,
          "ba17": казарм, "mills": 1, "centers": 1, "food": 3000, "gold": 2000,
          "wood": 900, "stone": 800, "iron": 1500, "coal": 900,
          "p1_enemy": 1, "p1_army": 50, "p1_peasants": 30,
          "frow": ["." * n for _ in range(n)],
          "arow": ["." * n for _ in range(n)]}
    д = {"gt": gt, "state": ст, "cmds": [{"cmd": "TRAIN", "a1": 1, "a2": -1, "upg": ""}]}
    if урок:
        д["lesson"] = урок
    if атака:
        д["attack"] = атака
        д["target"] = цель
    if финиш:
        д["finish"] = финиш
    return д


путь = os.path.join(tempfile.mkdtemp(), "трасса.jsonl")
строки = [такт(100), такт(200, урок="золото держит план"),
          такт(300, казарм=2, атака=20, цель="cell"),
          такт(400, финиш="горизонт"),
          такт(100), такт(200)]          # вторая партия, оборванная
with io.open(путь, "w", encoding="utf-8") as ф:
    for д in строки:
        ф.write(json.dumps(д, ensure_ascii=False) + "\n")

партии = L._партии_из_трассы(путь)
проверка("трасса поделена на две партии", len(партии) == 2, f"вышло {len(партии)}")
проверка("первая партия закрыта по finish", len(партии[0]) == 4, f"{len(партии[0])} тактов")
проверка("вторая партия — остаток", len(партии[1]) == 2, f"{len(партии[1])} тактов")

# разбор без обращения к модели: подменяем самого критика
собрано = []


def поддельный_разбор(a, client, номер, итог, дневник):
    собрано.append({"номер": номер, "итог": итог,
                    "тактов": list(L.ТРАССА_ПАРТИИ), "уроки": list(L.УРОКИ_ПАРТИИ),
                    "вехи": list(дневник.вехи), "волны": list(дневник.волны)})
    return "разбор"


прежний = L.разбор_партии
L.разбор_партии = поддельный_разбор
a = types.SimpleNamespace(critic=os.path.join(tempfile.mkdtemp(), "разбор.md"),
                          critic_trace=путь, model="нет", think=False)
код = L.разбор_трассы(a, None)
L.разбор_партии = прежний

проверка("режим отработал без ошибки", код == 0, f"код {код}")
проверка("разобраны обе партии", len(собрано) == 2, f"{len(собрано)}")
if len(собрано) == 2:
    п1, п2 = собрано
    проверка("исход первой взят из finish", п1["итог"] == "горизонт", п1["итог"])
    проверка("у оборванной исход назван неизвестным",
             "оборвана" in п2["итог"], п2["итог"])
    проверка("строки тактов собраны", len(п1["тактов"]) == 4, str(len(п1["тактов"])))
    проверка("урок модели перенесён",
             any("золото держит план" in у for у in п1["уроки"]), str(п1["уроки"]))
    проверка("веха постройки восстановлена",
             any("казарм" in в for в in п1["вехи"]), str(п1["вехи"]))
    проверка("волна восстановлена", len(п1["волны"]) == 1, str(п1["волны"]))
    проверка("в строке такта есть ресурсы и люди",
             "еда=3000" in п1["тактов"][0] and "пехота=10" in п1["тактов"][0],
             п1["тактов"][0][:120])
    # ТОТ ЖЕ текст, что дала бы живая петля
    ст = dict(строки[0]["state"])
    for имя in ("frow", "arow"):
        for i, ряд in enumerate(ст.get(имя) or []):
            ст[f"{имя}{i}"] = ряд
    живая = L.строка_такта(ст, ст, [L._Кмд(c) for c in строки[0]["cmds"]], 0, "")
    проверка("строка разбора совпадает со строкой живой петли ДОСЛОВНО",
             живая == п1["тактов"][0], "разошлись — критик увидит не то, что видел бы вживую")

# без --critic писать некуда
a2 = types.SimpleNamespace(critic="", critic_trace=путь, model="нет", think=False)
проверка("без --critic режим отказывается", L.разбор_трассы(a2, None) == 2)

# трасса, которой нет
a3 = types.SimpleNamespace(critic="/нет/такого", critic_trace="/нет/трассы.jsonl",
                           model="нет", think=False)
проверка("пропавшая трасса не роняет разбор", L.разбор_трассы(a3, None) == 2)

# ЗАМЕРЫ в системной строке критика: без них он систематически звал атаковать
# (83 гипотезы из 349 за проект против 6 «держать дома»), не зная, что поход
# втрое убыточнее обороны.
свод = L.замеры_для_критика()
проверка("критику дают размен дома против поля", "0,67" in свод and "0,19" in свод)
проверка("критику дают, что мы никуда не успеваем", "100 с" in свод and "4,5 раза" in свод)
проверка("критику дают темпы армий", "12,3" in свод and "13,1" in свод)
проверка("критику сказано, что цель берётся редко", "из пяти-десяти" in свод)
проверка("свод разнородный, а не про один бой",
         all(сл in свод for сл in ("ЗОЛОТО", "Голод", "ДРАГУН")),
         "иначе блок задаст единственный приоритет")
проверка("противоречие данным разрешено называть", "противоречие ценнее" in свод)

# РАЗБОР СЕРИИ: критик видит оба плеча сразу. Заведён потому, что по одной
# партии он расходится сам с собой — 20.09 на трёх партиях одного прогона вышли
# три взаимоисключающих совета, а разброс внутри плеча был больше эффекта.
такты = L._партии_из_трассы(путь)[0]
свод = L.сводка_партии(такты, "плечо А, партия 1")
проверка("в сводке есть исход", any("исход:" in с for с in свод), str(свод[:2]))
проверка("в сводке есть пик армии и просадка",
         any("армия к пику" in с and "просадка" in с for с in свод))
проверка("в сводке есть вехи построек", any("построено:" in с for с in свод))
проверка("в сводке есть волны", any("волн " in с for с in свод))
проверка("сводка короткая — не потактовая трасса", len(свод) < 25, f"{len(свод)} строк")

# числа врага не должны обнуляться усечённой записью finish
хвост = [с for с in свод if "к концу:" in с]
проверка("числа врага берутся последние НЕПУСТЫЕ",
         хвост and "армия 50" in хвост[0], хвост[0] if хвост else "нет строки")

серия = []
def поддельная_серия(client, model, запрос, think, retry=1, max_tokens=0):
    серия.append(запрос)
    return {"различие": "нет", "это_эффект_или_разброс": "разброс",
            "механизм": "не видно", "что_мерить_дальше": "больше партий"}

прежний_ask = L.ask
L.ask = поддельная_серия
a4 = types.SimpleNamespace(critic=os.path.join(tempfile.mkdtemp(), "с.md"),
                           critic_trace="", critic_series=[f"А={путь}", f"Б={путь}"],
                           critic_diff="ключ --switch-kind 1", model="нет", think=False)
код4 = L.разбор_серии(a4, None)
L.ask = прежний_ask
проверка("разбор серии отработал", код4 == 0, f"код {код4}")
проверка("в запрос попали оба плеча",
         серия and "## Плечо А" in серия[0] and "## Плечо Б" in серия[0])
проверка("критику сказано, чем плечи отличаются",
         серия and "--switch-kind 1" in серия[0])
проверка("в системной строке серии есть предупреждение о разбросе",
         "это разброс" in L.SYSTEM_CRITIC_SERIES)
проверка("ответ «разброс» назван правильным ответом",
         "правильный ответ" in L.SYSTEM_CRITIC_SERIES)

a5 = types.SimpleNamespace(critic="x", critic_trace="", critic_series=[f"А={путь}"],
                           critic_diff="", model="нет", think=False)
проверка("одно плечо — не серия", L.разбор_серии(a5, None) == 2)
a6 = types.SimpleNamespace(critic="x", critic_trace="", critic_series=["безравно"],
                           critic_diff="", model="нет", think=False)
проверка("кривой аргумент назван вслух", L.разбор_серии(a6, None) == 2)

print()
if беды:
    print(f"БЕД: {len(беды)} — {', '.join(беды)}")
    raise SystemExit(1)
print("всё чисто")
