#!/usr/bin/env python3
"""ЗАСЛОН НЕ ВПЛОТНУЮ И НЕ В БОЮ (13.10, §154): состояния пятой живой партии Д (`sim/кейсы/партия_д5_13_10_2_00-15_15.jsonl`).
Вживую: 5:51 его 24 встали в (6,10), 3 клетки от ратуши (3,13), — заслон §152 поставил всех 36 в (5,11), ВПЛОТНУЮ к нему;
6:06 он сдвинулся в (5,10) — повтор в (4,11), наши разделились 15/21; 6:32 он ударил в (5,11) 24 на 36 — к 6:52 21 : 24;
6:52 кулак §143 (свободных «+16» — это заслон дошёл и стал свободным) MOVE всех 37 из рукопашной в ратушу, 7:02 заслон
повторён в (4,12) (его куча сдвинулась в клетку боя) — на отходе 13 : 4. Двойник (sim/решения/д5_первый_бой.md): заслон
на 2 клетки худшая ветка у всех трёх агентов; живьём второй бой 9:09 у ратуши — 18 : 25 в нашу пользу.

Ключ `заслон_от_ратуши` 1 (в файле партии): (а) 5:51 — один MOVE группой 93 в (4,12) лицом к 6,10 числом 36; с ключом 2 —
тоже (4,12): зазор 2 клетки до его кучи старше ключа, (5,11) ключ 2 даёт при куче в 4 клетках; с ключом 0 — приказа нет, «заслон выключен»; (б) 5:51 → 6:06 — его куча в (5,10): клетка заслона та же
(4,12), повтора нет, «заслон 36 в 4,12 стоит»; (в) → 6:52 и 7:02 — его куча в клетке боя (5,11), 2 клетки от ратуши: MOVE
93 нет ни в одном такте (вплотную не ставим), память жива; (г) рукопашная: наша клетка = его клетка с ≥ 3 в 3 клетках
от ратуши (глаза угрозы базе не видят) — заслон не ставится, «рукопашная — заслон не переставляем»; (д) минута после кулака §143 — то же,
«кулак только что»; (е) 9:09 его 25 вошли в клетку ратуши — приказов заслона нет, команды с ключом 1 и 2 одинаковы.

    python3 selftest_д5_заслон.py
"""
import copy, json, os, sys, tempfile
К = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, К); sys.path.insert(0, os.path.join(К, "sim"))
os.environ.pop("COSS3_WAVE_CONTRACT", None)     # с «1» базовая стратегия строит ВТОРУЮ ЖиваяСтратегия внутри — ключи дважды
import strategy_live as SL
import анализ_врага as АВ

состояния = [json.loads(l) for l in open(os.path.join(К, "sim/кейсы/партия_д5_13_10_2_00-15_15.jsonl"), encoding="utf-8")]
ошибок = 0
def проверить(усл, что):
    global ошибок
    print(("ОК   " if усл else "ОШИБКА ") + что); ошибок += not усл

def стратегия(доп):
    д = json.load(open(os.path.join(К, "sim/поиск/шт_s2_оборона_ручеёк_эко_так15_нужда.json"), encoding="utf-8"))
    assert д["итог"].get("заслон_от_ратуши") == 1, "в файле партии ждём заслон_от_ратуши 1"
    д["итог"].update(доп)
    with tempfile.NamedTemporaryFile("w", suffix=".json", delete=False, encoding="utf-8") as f:
        json.dump(д, f, ensure_ascii=False)
    return SL.ЖиваяСтратегия(f.name)

def ответ(С, st):
    АВ._ТЕКУЩИЙ.update({"а": None, "t": None, "ответ": None})
    return С.ответ(copy.deepcopy(st))

def при(t):
    return next(s for s in состояния if s["gametime"] >= t)

def боевые(о):
    return [(c["cmd"], c.get("count"), c.get("group"), c.get("cx"), c.get("cy"), c.get("face")) for c in о["commands"]
            if c["cmd"] in ("ATTACK", "MOVE", "RETREAT", "ENGAGE")]

def заслоны(о):
    return [c for c in боевые(о) if c[0] == "MOVE" and c[2] == 93]

st_351, st_366, st_412, st_422 = при(351), при(366), при(412), при(422)
for имя, s in (("351", st_351), ("366", st_366), ("412", st_412), ("422", st_422)):
    print(f"{имя}: наши {[(c['x'], c['y'], c['n']) for c in s['ocells']]}, его {[(c['x'], c['y'], c['n']) for c in s['ecells'] if c['n'] >= 3]}, "
          f"свободных {s['my_freewar']}, вживую: {[x for x in (s.get('_why_live') or '').split(' | ') if 'ЗАСЛОН' in x or 'КУЛАК' in x][:1]}")

# (а) 5:51 — его 24 стоят в (6,10), наших 36 дома. Ключ 2 при куче в 3 клетках тоже даёт (4,12): зазор 2 клетки до
# неё старше ключа; 2 клетки от ратуши ключ 2 даёт при куче в 4 клетках (его 24 в (7,9) — (5,11), как было вживую)
for имя, доп, ждём in (("ключ 1", {}, (4, 12)), ("ключ 2 при куче в 3 кл.", {"заслон_от_ратуши": 2}, (4, 12)), ("ключ 0", {"заслон_от_ратуши": 0}, None)):
    С = стратегия(доп)
    о = ответ(С, st_351)
    з = заслоны(о)
    if ждём is None:
        проверить(not з and "заслон выключен" in о["why"], f"(а) {имя}: приказа заслону нет, «заслон выключен»: {з or [x for x in о['why'].split('; ') if 'заслон' in x][:1]}")
    else:
        проверить(len(з) == 1 and (з[0][3], з[0][4]) == ждём and з[0][5] == [6, 10] and з[0][1] == 36,
                  f"(а) {имя}: MOVE группой 93 в {ждём} лицом к 6,10 числом 36: {з}")
        проверить("ЗАСЛОН:" in о["why"] and f"в {ждём[0]},{ждём[1]} лицом" in о["why"], f"(а) {имя}: why: {[x for x in о['why'].split('; ') if 'ЗАСЛОН' in x][:1]}")
st_а4 = copy.deepcopy(st_351)
st_а4["ecells"] = [c for c in st_а4["ecells"] if (c["x"], c["y"]) not in ((6, 10), (5, 10))] + [{"x": 7, "y": 9, "n": 24, "пик": 24, "стрелков": 0, "конных": 0, "идут": 0, "tx": -1, "ty": -1, "n18": 0}]
for имя, доп, ждём in (("ключ 1", {}, (4, 12)), ("ключ 2 (как было)", {"заслон_от_ратуши": 2}, (5, 11))):
    з = заслоны(ответ(стратегия(доп), st_а4))
    проверить(len(з) == 1 and (з[0][3], з[0][4]) == ждём and з[0][5] == [7, 9], f"(а) его 24 в (7,9), 4 кл.: {имя} — заслон в {ждём}: {з}")

# (б) 5:51 → 6:06 — его куча сдвинулась в (5,10): та же клетка заслона, повтора нет
С = стратегия({})
ответ(С, st_351)
о = ответ(С, st_366)
проверить(not заслоны(о) and "заслон 36 в 4,12 стоит" in о["why"],
          f"(б) 6:06 его в (5,10): повтора нет, «заслон 36 в 4,12 стоит»: {заслоны(о) or [x for x in о['why'].split('; ') if 'заслон' in x][:1]}")
проверить(С._заслон_поля is not None and tuple(С._заслон_поля["кл"]) == (4, 12), f"(б) память заслона (4,12): {С._заслон_поля}")

# (в) → 6:52, 7:02 — его куча в клетке боя (5,11), 2 клетки от ратуши: вплотную не ставим
for имя, s in (("6:52", st_412), ("7:02", st_422)):
    о = ответ(С, s)
    проверить(not заслоны(о), f"(в) {имя} его в (5,11), 2 кл.: приказа заслону нет: {боевые(о)}")
    if имя == "7:02":       # в 6:52 ОБОРОНА (его 24 «к базе через 0 с») держит дом, ветка заслона молчит — как вживую
        проверить("стоит против его" in о["why"] and "ЗАСЛОН:" not in о["why"], f"(в) {имя} why: {[x for x in о['why'].split('; ') if 'заслон' in x.lower()][:1]}")
проверить(С._заслон_поля is not None, "(в) память заслона жива (его у ратуши ещё есть)")

# (г) рукопашная в 3 клетках от ратуши (глаза угрозы базе не видят): наши 20 в его клетке (6,10) с 17, дома 36
st_г = copy.deepcopy(st_351)
st_г["ocells"] = st_г["ocells"] + [{"x": 6, "y": 10, "n": 20, "пик": 20, "стрелков": 0, "конных": 0}]
С = стратегия({})
о = ответ(С, st_г)
проверить(not заслоны(о) and "рукопашная — заслон не переставляем" in о["why"],
          f"(г) рукопашная в (6,10): заслон не ставится: {заслоны(о) or [x for x in о['why'].split('; ') if 'заслон' in x][:1]}")

# (д) минута после кулака §143
С = стратегия({}); С._кулак_t = 320.0
о = ответ(С, st_351)
проверить(not заслоны(о) and "кулак только что — заслон не переставляем" in о["why"],
          f"(д) 5:51 через 31 с после кулака: заслон не ставится: {заслоны(о) or [x for x in о['why'].split('; ') if 'заслон' in x][:1]}")
С._кулак_t = 280.0
о = ответ(С, st_351)
проверить(bool(заслоны(о)), f"(д) через 71 с после кулака — ставится: {заслоны(о)}")

# (е) 9:09 — его 25 в клетке ратуши: приказов заслона нет, ключ 1 и 2 — команды одинаковы
st_е = при(549)
ком = lambda о: sorted(json.dumps(c, ensure_ascii=False, sort_keys=True) for c in о["commands"])
о1, о2 = ответ(стратегия({}), st_е), ответ(стратегия({"заслон_от_ратуши": 2}), st_е)
проверить(not заслоны(о1) and ком(о1) == ком(о2), f"(е) {st_е['gametime']} с его {[(c['x'], c['y'], c['n']) for c in st_е['ecells'] if c['n'] >= 10]}: заслона нет, команды одинаковы ({len(о1['commands'])})")
print(f"ошибок: {ошибок}")
sys.exit(1 if ошибок else 0)
