# -*- coding: utf-8 -*-
"""Самопроверка сторожа недописанного состояния (`ОПОРНЫЕ_КЛЮЧИ`).

Откуда взялось. Игра собирает состояние в памяти и сохраняет одним вызовом
(`block_hstate.inc:1534`), а мост читает файл по времени изменения. Между
началом записи и её концом файл существует наполовину, и разбор такого файла
даёт не ошибку, а ПРАВДОПОДОБНЫЙ обрывок.

[Замер] 22.09 по трассам 20-21.09: обрывок доехал до модели как полноценная
обстановка 1 раз на 1684 такта — `free_hands2/2`, gt=967, пятнадцать случайных
ключей. Были ресурсы и время, не было ни крестьян, ни зданий, ни армии врага,
ни `can_now`. По трассе такой такт не отличить от настоящего, а решение на нём
принималось вслепую.

Стережётся:
* обрывок не отдаётся наружу, и мост говорит об этом вслух (правило 1 проекта:
  молчаливый отброс неотличим от бездействия);
* ВРЕМЯ ИЗМЕНЕНИЯ файла при этом не двигается — иначе дописанный файл сочли бы
  уже виденным и пропустили бы целый такт;
* целое состояние проходит как прежде;
* `victory` пустой строкой (так оно и приходит почти всегда) обрывком НЕ
  считается: проверяется наличие ключа, а не истинность значения.
"""
import os
import tempfile

from coss3_bridge import Bridge, ОПОРНЫЕ_КЛЮЧИ

беды = []


def проверка(имя, условие, пояснение=""):
    if условие:
        print("  ОК    " + имя)
    else:
        беды.append(имя)
        print("  ПЛОХО " + имя + (" — " + str(пояснение)[:300] if пояснение else ""))


def записать(путь, значения):
    """Файл состояния в том же виде, в каком его пишет игра."""
    тело = "".join(f"   {k} = {v}\n" for k, v in значения.items())
    with open(путь, "w", encoding="latin-1") as f:
        f.write("br_eco\n{\n" + тело + "}\n")
    # mtime вперёд: иначе второй записи в ту же секунду мост не заметит
    ст = os.stat(путь)
    os.utime(путь, (ст.st_atime, ст.st_mtime + 1))


ЦЕЛОЕ = {"gametime": 120, "food": 900, "wood": 300, "peasants": 18,
         "centers": 1, "mil_inf": 4, "victory": ""}
# Ровно та беда, что случилась в free_hands2/2: голова файла есть, хвоста нет.
ОБРЫВОК = {"gametime": 140, "food": 950, "wood": 320}

каталог = tempfile.mkdtemp()
br = Bridge(каталог, plind=0)

записать(br.state_path, ЦЕЛОЕ)
st = br.read_state()
проверка("целое состояние проходит", st is not None and st.get("peasants") == 18, st)
время_после_целого = br._last_mtime

записать(br.state_path, ОБРЫВОК)
st = br.read_state()
проверка("обрывок наружу не отдаётся", st is None, st)
проверка("время изменения не сдвинуто: дописанный файл прочтём снова",
         br._last_mtime == время_после_целого, br._last_mtime)
проверка("обрывок посчитан", br.обрывков == 1, br.обрывков)

# Игра дописала файл — тот же такт должен прочитаться целиком
записать(br.state_path, dict(ЦЕЛОЕ, gametime=140))
st = br.read_state()
проверка("дописанный файл прочитан, такт не потерян",
         st is not None and st.get("gametime") == 140, st)

# victory пустой строкой — это НОРМА, а не обрывок
записать(br.state_path, dict(ЦЕЛОЕ, gametime=160, victory=""))
st = br.read_state()
проверка("пустой victory обрывком не считается",
         st is not None and st.get("gametime") == 160, st)

# каждого опорного ключа хватает, чтобы поймать обрыв
for ключ in ОПОРНЫЕ_КЛЮЧИ:
    br2 = Bridge(tempfile.mkdtemp(), plind=0)
    урезанное = {k: v for k, v in ЦЕЛОЕ.items() if k != ключ}
    записать(br2.state_path, урезанное)
    проверка(f"без «{ключ}» состояние не проходит", br2.read_state() is None)

print()
if беды:
    print(f"БЕД: {len(беды)} — {', '.join(беды)}")
    raise SystemExit(1)
print("всё чисто")
