#!/usr/bin/env python3
"""Пункт 4 списка правок блока (30.10 ночь): цена у КАЖДОГО апгрейда в `upg_avail`, не только у военных (3 точки) и
академии — `bla.1=f0g500i0w300` читается тем же разборщиком, что `bar.pikeman.1.4=f6700g1950i0`; имена без цены
по-прежнему допустимы (старый блок); обрезка для модели режет имя до «=».
    python3 selftest_цены_всех.py"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import combat_math as CM
import llm_policy as LP
ошибок = 0
def проверить(усл, что):
    global ошибок
    print(("ОК   " if усл else "ОШИБКА ") + что); ошибок += not усл
строка = "l,cen.1=f0g0i0,mil.1=f500g200i0,bla.1=f0g500i0w300,bar.pikeman.1.1=f1000g300i50,aca.13=f0g4000i200s1000,sto.1=f0g300i0w400"
ц = CM.цены_апгрейдов(строка)
проверить(ц.get("bla.1") == {"food": 0, "gold": 500, "iron": 0, "wood": 300}, f"(а) bla.1 с ценой: {ц.get('bla.1')}")
проверить(ц.get("mil.1") == {"food": 500, "gold": 200, "iron": 0} and ц.get("sto.1", {}).get("wood") == 400, f"(б) mil.1 и sto.1 с ценой: {ц.get('mil.1')} {ц.get('sto.1')}")
проверить(ц.get("bar.pikeman.1.1") == {"food": 1000, "gold": 300, "iron": 50} and ц.get("aca.13", {}).get("stone") == 1000, "(в) военный и академический как прежде")
проверить("l" not in ц and ц.get("cen.1") == {"food": 0, "gold": 0, "iron": 0}, f"(г) имя без цены — не в словаре; бесплатный апгрейд — нули (блок пишет f,g,i всегда, w/s/c при > 0): {ц.get('cen.1')}")
# обрезка для модели: имена с ценой проходят отбор по зданиям так же, как без неё
st = {"ba17": 1, "mills": 1, "my_stores": 0, "academies": 0, "blacksmiths": 1, "hssmith": 1, "upg_done": ""}
видно, срез, чем = LP.отобрать_апгрейды(строка.split(","), st)
имена = [у.split("=", 1)[0] for у in видно]
видно0, _, _ = LP.отобрать_апгрейды([у.split("=", 1)[0] for у in строка.split(",")], st)
проверить(имена == видно0, f"(д) отбор по зданиям не зависит от цены: {имена} == {видно0}")
print(f"ошибок: {ошибок}"); raise SystemExit(1 if ошибок else 0)
