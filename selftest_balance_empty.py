# -*- coding: utf-8 -*-
"""ПУСТАЯ КОМАНДА BALANCE: просили не больше, чем уже стоит.

Найдено 24.09 счётом по трём сериям (base27, base28, debut4). Из 760 команд
`BALANCE`, отданных В ТАКТАХ СО СВОБОДНЫМИ крестьянами:

    люди прибавились            46 %
    просили НЕ БОЛЬШЕ текущего  38 %   <- каждая третья команда пустая
    людей стало меньше           4 %
    игра отказала (залежи нет)   1 %
    просили больше, не двинулись 10 %

`BALANCE` задаёт ИТОГ, а не прибавку: просьба о числе ниже текущего не двигает
никого — занятые сами не уходят, а свободным команда не адресована. Мост об
этом молчал, и модель повторяла такую команду тактами: «на дерево 6» при
восьми работающих. Это не отказ игры и не нехватка мест, а непонимание слова
«итог» — и сказать о нём надо прямо, с числом, которое сработает.

Что проверяется:
  1. пустая команда названа пустой, с текущим числом и с тем, что просить;
  2. когда просят больше и люди пошли — прежний вердикт, без нотаций;
  3. когда просят больше, а никто не пошёл — прежнее объяснение про свободных;
  4. равенство (просят ровно столько, сколько стоит) — тоже пустая команда;
  5. вердикт про отсутствие мельницы остаётся первым: он глубже по причине.
"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import llm_policy as L

ошибок = 0


def проверить(условие, что):
    global ошибок
    if not условие:
        ошибок += 1
        print("  СБОЙ:", что)
    else:
        print("  ок:", что)


def вердикт(было, стало, заказ, мельниц=1):
    б = dict(было); с = dict(стало)
    б.setdefault("mills", мельниц); с.setdefault("mills", мельниц)
    return " ".join(L.итог_прошлого(б, с, заказ))


print("1. пустая команда названа пустой")
т = вердикт({"on_wood": 8}, {"on_wood": 8}, [("BALANCE", "wood", 6)])
проверить("НИЧЕГО НЕ СДЕЛАНО" in т, "сказано прямо")
проверить("уже 8" in т and "просишь 6" in т, "названы оба числа")
проверить("9 и выше" in т, "подсказано число, которое сработает")
проверить("ИТОГОВОЕ" in т, "объяснено слово «итог»")

print("2-3. когда просят больше — вердикты прежние")
т = вердикт({"on_wood": 8}, {"on_wood": 11}, [("BALANCE", "wood", 11)])
проверить("8->11" in т and "НИЧЕГО НЕ СДЕЛАНО" not in т, "рост засчитан без нотаций")
т = вердикт({"on_wood": 8}, {"on_wood": 8}, [("BALANCE", "wood", 12)])
проверить("не изменилось" in т and "НИЧЕГО НЕ СДЕЛАНО" not in т,
          "просили больше, никто не пошёл — прежнее объяснение про свободных")

print("4. равенство — тоже пусто")
т = вердикт({"on_stone": 5}, {"on_stone": 5}, [("BALANCE", "stone", 5)])
проверить("НИЧЕГО НЕ СДЕЛАНО" in т, "просить ровно столько же бессмысленно")

print("5. мельница остаётся первой причиной")
т = вердикт({"on_food": 3}, {"on_food": 3}, [("BALANCE", "food", 2)], мельниц=0)
проверить("НЕТ МЕЛЬНИЦЫ" in т, "без мельницы говорим про мельницу, а не про итог")

print()
print("ошибок:", ошибок)
sys.exit(1 if ошибок else 0)
