# -*- coding: utf-8 -*-
"""Самопроверка блока «Хватит ли на бойцов» (плановая выполнимость).

Снимки промпта его не ловят: фикстуры зовут situation() без ПРОШЛОГО состояния,
а без него прихода не посчитать. Поэтому проверяем функцию напрямую.

Главное, что здесь стережётся, — порог еды 500. Тратить можно только запас ВЫШЕ
порога: уйдя под него, наём встаёт целиком, сколько бы железа и золота ни лежало
(doprogressorders.inc гасит весь блок производства). Если это забыть, мост
пообещает модели двадцать пикинёров там, где не будет ни одного.
"""
import sys
import llm_policy as L

БОЕЦ = "infantry17=pikeman,hp90,atk8,dpike3,dsword2,dbullet4,food25,gold3,iron20,coal0"
беды = []


def проверка(имя, условие, пояснение=""):
    if условие:
        print("  ОК   " + имя)
    else:
        беды.append(имя + (" — " + пояснение if пояснение else ""))
        print("  ПЛОХО" + " " + имя + (" — " + пояснение if пояснение else ""))


def текст(st, было):
    return "\n".join(L.выполнимость(st, было))


# 1. Обычный случай: запас растёт, числа не убывают с горизонтом.
st = dict(gametime=300, food=1000, gold=120, iron=260, coal=0, ba17=1, fighters=БОЕЦ)
было = dict(gametime=280, food=920, gold=110, iron=200, coal=0)
т = текст(st, было)
числа = [int(ч) for ч in __import__("re").findall(r"через \d+ с — (\d+)", т)]
проверка("горизонты не убывают", числа == sorted(числа), str(числа))
проверка("узкое место названо", "узкое место" in т)

# 2. Порог еды: 510 еды при цене 25 — это НОЛЬ бойцов, а не двадцать.
st2 = dict(st, food=510, gold=9999, iron=9999)
было2 = dict(было, food=505, gold=9999, iron=9999)
т2 = текст(st2, было2)
проверка("порог еды вычтен из запаса", "сейчас оплачено: 0 шт" in т2,
         "510 еды это 10 сверх порога, на пикинёра за 25 не хватает")

# 3. Еда под порогом и растёт — мост говорит, через сколько оживёт наём.
st3 = dict(st, food=446)
было3 = dict(было, food=400)
т3 = текст(st3, было3)
проверка("под порогом сказано вслух", "НИЖЕ 500" in т3)
проверка("названо время возврата", "порог вернётся через" in т3)

# 4. Еда под порогом и НЕ растёт — обещать возврат нельзя.
st4 = dict(st, food=446)
было4 = dict(было, food=460)
т4 = текст(st4, было4)
проверка("падающая еда не обещает возврата", "НЕ РАСТЁТ" in т4)
проверка("и не врёт про время", "порог вернётся через" not in т4)

# 5. Молчать, когда покупать негде или нечем: без казармы и без цены.
проверка("без казармы блока нет", L.выполнимость(dict(st, ba17=0), было) == [])
проверка("без цены блока нет", L.выполнимость(dict(st, fighters=""), было) == [])
проверка("без прошлого состояния блока нет", L.выполнимость(st, None) == [])
проверка("такт нулевой длины не делится", L.выполнимость(st, dict(было, gametime=300)) == [])

print()
print("ПРОВАЛОВ:", len(беды))
sys.exit(1 if беды else 0)
