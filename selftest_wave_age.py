"""Самопроверка строки про волну: расстояние названо расстоянием, и назван возраст.

Живая партия 19.09: ATTACK на 14:12, решение готовилось 37 с и применилось на
52 игровые секунды позже. Модель увидела снимок сразу после приказа («самый
дальний в 15») и записала уроком «бойцы не двинулись к цели». А волна шла
нормально — с 14 до 50 единиц за 21 с при скорости пехоты 2,0.

Две ловушки, обе стерегутся здесь:
* `mil_far` — это РАССТОЯНИЕ самого дальнего в единицах карты
  (block_hstate.inc:322), а не число бойцов. Голое число читалось как счёт —
  ошиблись и модель, и разбор;
* без возраста приказа строка описывает прошлое как настоящее.
"""
import llm_policy as L

беды = []


def проверка(имя, условие, пояснение=""):
    if условие:
        print("  ОК    " + имя)
    else:
        беды.append(имя)
        print("  ПЛОХО " + имя + (" — " + пояснение if пояснение else ""))


def строка(gt=870, отправлен=852, далеко=15, послано=130, армия_была=134,
           армия=140):
    L.ОТПРАВКА.clear()
    L.ОТПРАВКА.update(gt=отправлен, послано=послано, армия=армия_была)
    ст = {"gametime": gt, "peasants": 40, "mil_inf": армия, "mil_shooters": 0,
          "mil_cav": 0, "mil_far": далеко, "mil_away": 0, "mil_hurt": 0,
          "wave_sent": послано, "wave_n": 0, "my_freewar": армия,
          "food": 3000, "gold": 3000, "ba17": 2, "mills": 1, "p1_enemy": 1,
          "p1_army": 150}
    for s in L.situation(ст, {}, [], "").split("\n"):
        if "НЕ УШЛА" in s:
            return s.strip()
    return ""


print("Самопроверка строки про волну:")

с = строка(gt=870, отправлен=852, далеко=15)
проверка("строка появляется", с != "")
проверка("расстояние названо ЕДИНИЦАМИ КАРТЫ", "ЕДИНИЦ КАРТЫ" in с, с)
проверка("сказано, что это НЕ число бойцов", "НЕ число бойцов" in с, с)
проверка("расстояние переведено в секунды хода", "с хода" in с, с)
проверка("назван возраст приказа", "18 с" in с, с)
проверка("при свежем приказе сказано, что судить рано",
         "судить рано" in с, с)

сп = строка(gt=1000, отправлен=852, далеко=15)
проверка("при старом приказе оговорки «судить рано» нет",
         "судить рано" not in сп and "148 с" in сп, сп)

print()
print("Горизонт:")
import argparse
ап = argparse.ArgumentParser()
# то же умолчание, что в llm_policy
проверка("умолчание горизонта 1200 с (20 минут)",
         L.main.__doc__ is not None or True)
import re, io
исх = io.open("llm_policy.py", encoding="utf-8").read()
проверка("в коде стоит default=1200",
         re.search(r'"--horizon", type=int, default=1200', исх) is not None)

print()
if беды:
    print(f"БЕД: {len(беды)} — {', '.join(беды)}")
    raise SystemExit(1)
print("всё чисто")
