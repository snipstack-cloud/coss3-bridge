#!/usr/bin/env python3
"""КАЧЕЛИ, ВТОРОЙ КРУГ (2.11): ключи `отход_действие` и `отряд_отвечает`.

Волна swing_* показала: `отход_по_всем` убрал отмены (12/10 → 0/0), но размен упал вдвое (1,18/1,42 → 0,50/0,62) —
«продолжить» ничего не делало: дом не посылался, а отряд в поле стоял в удержании, и малая группа рядом срезала его
(swing_net/1 20:36–21:37, отряд 184 → 131, 74 наших против 15). Экзамен вслепую: Fable Б×3 на оба вопроса.
  * `отход_действие`: выгодное продолжение — приказ всем (`all`) в клетку цели;
  * `отряд_отвечает`: отряд в поле в удержании бьёт строем его группу рядом, если она меньше половины отряда.
Кейсы — настоящие такты (`sim/кейсы/качели_drop_*`, `отряд_в_поле_swing_net_1215-1300`), через полный ответ().
    python3 selftest_качели2.py"""
import copy
import json
import os
import sys
import tempfile

К = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, К)
import strategy_live as SL  # noqa: E402
import анализ_врага as АВ  # noqa: E402

ошибок = 0


def проверить(усл, что):
    global ошибок
    print(("ОК   " if усл else "ОШИБКА ") + что)
    ошибок += not усл


def живое(t):
    st = {k: (";".join(",".join(str(x) for x in r) for r in v)
              if isinstance(v, list) and v and all(isinstance(r, list) for r in v) else v)
          for k, v in t["state"].items()}
    st["gametime"] = t["gt"]
    return st


def прогон(кейс, доп):
    АВ._ТЕКУЩИЙ.update({"а": None, "t": None, "ответ": None})
    д = json.load(open(os.path.join(К, "sim/поиск/ветка_казарма3_без_капли.json"), encoding="utf-8"))
    д["итог"].update(доп)
    with tempfile.NamedTemporaryFile("w", suffix=".json", delete=False, encoding="utf-8") as f:
        json.dump(д, f, ensure_ascii=False)
    С = SL.ЖиваяСтратегия(f.name)
    из = []
    for s in open(os.path.join(К, f"sim/кейсы/{кейс}.jsonl"), encoding="utf-8"):
        st = живое(json.loads(s))
        о = С.ответ(copy.deepcopy(st))
        из.append((st["gametime"], о))
    return из, С


# --- продолжение = действие
for кейс, цель in (("качели_drop_net_1170-1350", (13, 7)), ("качели_drop_pol_1200-1350", (12, 5))):
    о1, _ = прогон(кейс, {"отход_по_всем": 1})
    без = [g for g, о in о1 if "ПРОДОЛЖЕН ДЕЛОМ" in о["why"]]
    проверить(not без, f"(а) {кейс}: без `отход_действие` продолжение без приказа (как в волне): {без}")
    о2, С2 = прогон(кейс, {"отход_по_всем": 1, "отход_действие": 1})
    дело = [(g, [c for c in о["commands"] if c.get("cmd") == "ATTACK" and c.get("all") == 1 and c.get("count") == "all"
                 and (c.get("cx"), c.get("cy")) == цель]) for g, о in о2 if "ПРОДОЛЖЕН ДЕЛОМ" in о["why"]]
    проверить(дело and all(a for _, a in дело), f"(б) {кейс}: с ключом — ATTACK all в клетку цели {цель}: {[g for g, _ in дело]}")
    проверить(С2.реестр.мера["качели: продолжение всеми"] >= 1, "(в) мера «продолжение всеми» посчитана")

# --- отряд в поле
о0, _ = прогон("отряд_в_поле_swing_net_1215-1300", {})
проверить(not any("ОТРЯД ОТВЕЧАЕТ" in о["why"] for _, о in о0), "(г) без ключа отряд стоит, как в волне")
о3, С3 = прогон("отряд_в_поле_swing_net_1215-1300", {"отряд_отвечает": 1})
ответы = [(g, [c for c in о["commands"] if c.get("_отряд")]) for g, о in о3 if "ОТРЯД ОТВЕЧАЕТ" in о["why"]]
проверить(ответы and ответы[0][0] <= 1250, f"(д) с ключом отряд бьёт в первые такты (до 20:50): {[g for g, _ in ответы]}")
проверить(ответы and all(a and a[0].get("all") == 1 and (a[0]["cx"], a[0]["cy"]) in ((8, 8), (9, 8), (9, 7)) for _, a in ответы),
          f"(е) приказ — отряду (all) в клетку его группы рядом: {ответы[:1]}")
проверить(all(b - a >= 10 for (a, _), (b, _) in zip(ответы, ответы[1:])), "(ж) повтор не чаще 10 с")
проверить(С3.реестр.мера["отряд в поле: ответил"] >= 1, "(з) мера «отряд в поле: ответил» посчитана")

print(f"ошибок: {ошибок}")
raise SystemExit(1 if ошибок else 0)
