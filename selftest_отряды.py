#!/usr/bin/env python3
"""Пункт 3 списка правок блока (30.10 ночь): ВСЕ отряды в состоянии — поле `squads_list` блока
«uid,men,formation,cx,cy,hold,hunt,holdmode;…» ('none' — пусто) читается в список словарей и в строку запроса.
    python3 selftest_отряды.py"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import llm_policy as LP
ошибок = 0
def проверить(усл, что):
    global ошибок
    print(("ОК   " if усл else "ОШИБКА ") + что); ошибок += not усл
st = {"squads_list": "7,36,-,4,4,0,1,0;8,15,LINE15,3,3,1,0,1;9,9,-,6,5,0,0,0", "squads_list_n": 3}
о = LP.отряды_из_состояния(st)
проверить(len(о) == 3 and о[0]["uid"] == 7 and о[0]["n"] == 36 and о[0]["form"] == "" and о[0]["hunt"] == 1
          and о[1]["form"] == "LINE15" and о[1]["hold"] == 1 and о[1]["holdmode"] == 1 and (о[2]["cx"], о[2]["cy"]) == (6, 5),
          f"(а) три отряда разобраны: {о}")
проверить(LP.отряды_из_состояния({"squads_list": "none"}) == [] and LP.отряды_из_состояния({}) == [] and LP.отряды_из_состояния({"squads_list": ""}) == [],
          "(б) 'none', нет поля, пусто — пустой список")
проверить(LP.отряды_из_состояния({"squads_list": "7,36;8,15,LINE15,3,3,1,0,1;x,y,z,1,2,3,4,5"}) == [
    {"uid": 8, "n": 15, "form": "LINE15", "cx": 3, "cy": 3, "hold": 1, "hunt": 0, "holdmode": 1}],
          "(в) короткая и битая записи пропускаются, целая остаётся")
с = LP._отряды_строкой(st)
проверить(с.startswith("отряды 3:") and "#7 без строя 36 чел. в (4,4) охотится" in с and "#8 LINE15 15 чел. в (3,3) держит строй" in с
          and "#9 без строя 9 чел. в (6,5) идёт" in с, f"(г) строка запроса: {с}")
проверить(LP._отряды_строкой({"squads_list": "none"}) == "" and LP._отряды_строкой({}) == "", "(д) без отрядов строка пустая (старый блок — молчим)")
# (е) пункт 7: его отряды тем же разборщиком по ключу p1_squads_list, строка «его отряды N: …»
st2 = {"p1_squads_list": "3,120,LINE120,8,8,1,0,1;4,36,-,9,9,0,1,0", "p1_squads_list_n": 2}
о2 = LP.отряды_из_состояния(st2, "p1_squads_list"); с2 = LP._отряды_строкой(st2, "p1_squads_list", "его отряды")
проверить(len(о2) == 2 and о2[0]["form"] == "LINE120" and о2[0]["hold"] == 1 and с2.startswith("его отряды 2:") and "#4 без строя 36 чел. в (9,9) охотится" in с2,
          f"(е) его отряды: {с2}")
проверить(LP.отряды_из_состояния({"p1_squads_list": "none"}, "p1_squads_list") == [] and LP._отряды_строкой({}, "p1_squads_list", "его отряды") == "", "(ж) 'none'/нет поля — пусто")
print(f"ошибок: {ошибок}"); raise SystemExit(1 if ошибок else 0)
