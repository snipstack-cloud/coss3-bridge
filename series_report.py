#!/usr/bin/env python3
"""Сравнение серии с базой по трассам: партия за партией и итог.

Зачем отдельно от run_report.py и results_ui.py. Те отвечают на вопрос «что было
в прогоне», а здесь один вопрос: ВЗЯТА ли мера, названная до серии. 14.09 идея
fighters дала «цель 5 из 9 против 3 из 9» — число красивое, а смотреть надо было
на состав: в четырёх из пяти взятых целей стрелков было ноль. Такую таблицу
руками каждый раз не собрать, а без неё легко засчитать шум.

    python3 series_report.py <каталог идеи> [<каталог базы>]
    python3 series_report.py ~/coss3-results/2026-09-14/shooters \\
                             ~/coss3-results/2026-09-14/fighters

Каталог — тот, что уезжает в coss3-results: внутри по подкаталогу на копию, в
каждом coss3_bot.jsonl. Исход партии берётся из записи `finish`, а не считается
заново: мост уже решил, взята цель или нет, и второй счёт разошёлся бы с ним.
"""
import json
import os
import sys

# a1 в команде TRAIN — движковая роль. Числа из dmscript.global:362-366.
РОЛИ = {1: "peasant", 23: "infantry17", 25: "musk17"}


def эпизоды(путь: str) -> list[dict]:
    """Партии из одной трассы. Граница — игровое время пошло назад."""
    итог, тек, пред = [], None, -1
    for строка in open(путь, encoding="utf-8", errors="replace"):
        строка = строка.strip()
        if not строка:
            continue
        try:
            d = json.loads(строка)
        except ValueError:
            continue
        if d.get("finish"):                      # запись о конце партии
            if тек:
                тек["исход"] = d["finish"]
                тек["конец"] = d.get("gt", тек["gt"])
            continue
        gt = d.get("gt", 0)
        if тек is None or gt < пред:
            тек = {"musk": 0, "inf": 0, "стрелки": 0, "пехота": 0, "волны": 0,
                   "gt": 0, "исход": "—", "конец": 0, "враг": 0}
            итог.append(тек)
        пред = gt
        тек["gt"] = max(тек["gt"], gt)
        for c in d.get("cmds") or []:
            if c.get("cmd") != "TRAIN":
                continue
            роль = РОЛИ.get(c.get("a1"))
            if роль == "musk17":
                тек["musk"] += 1
            elif роль == "infantry17":
                тек["inf"] += 1
        if d.get("attack"):
            тек["волны"] += 1
        s = d.get("state") or {}
        ц = lambda k: int(s.get(k) or 0)
        тек["стрелки"] = max(тек["стрелки"], ц("mil_shooters"))
        тек["пехота"] = max(тек["пехота"], ц("mil_inf"))
        for к in s:
            if к.endswith("_peasants") and к != "peasants":
                тек["враг"] = max(тек["враг"], ц(к))
    # Партия короче минуты — это обрыв подключения, а не игра.
    return [э for э in итог if э["gt"] > 60]


def разбор(каталог: str) -> list[tuple[str, int, dict]]:
    ряд = []
    for копия in sorted(os.listdir(каталог)):
        путь = os.path.join(каталог, копия, "coss3_bot.jsonl")
        if os.path.exists(путь):
            for i, э in enumerate(эпизоды(путь), 1):
                ряд.append((копия, i, э))
    return ряд


def показать(имя: str, ряд: list) -> dict:
    print(f"\n===== {имя}: партий {len(ряд)} =====")
    ит = {"musk": 0, "inf": 0, "цели": 0, "стрелки": 0,
          "цель_со_стрелками": 0, "волны": 0}
    for копия, i, э in ряд:
        мм, сс = divmod(э["конец"] or э["gt"], 60)
        цель = э["исход"] == "цель"
        print(f"  {копия}.{i}: {э['исход']:9} {мм:2}:{сс:02d}  "
              f"musk17 {э['musk']:3}  стрелков {э['стрелки']:3}  "
              f"infantry17 {э['inf']:3}  пехоты {э['пехота']:3}  "
              f"волн {э['волны']:2}  крестьян врага до {э['враг']:3}")
        ит["musk"] += э["musk"]
        ит["inf"] += э["inf"]
        ит["волны"] += э["волны"]
        ит["цели"] += цель
        ит["стрелки"] = max(ит["стрелки"], э["стрелки"])
        ит["цель_со_стрелками"] += цель and э["стрелки"] > 0
    print(f"  ИТОГО: цель {ит['цели']} из {len(ряд)}; TRAIN musk17 {ит['musk']}, "
          f"infantry17 {ит['inf']}; стрелков максимум {ит['стрелки']}; "
          f"волн {ит['волны']}")
    if ит["цели"]:
        # Главная строка отчёта: если цели берут партии БЕЗ стрелков, разница с
        # базой не про стрелков, сколько бы красиво ни выглядело «5 из 9».
        print(f"  из взятых целей со стрелками: {ит['цель_со_стрелками']} "
              f"из {ит['цели']}")
    return ит


def main() -> int:
    if len(sys.argv) < 2:
        print(__doc__)
        return 1
    идея = разбор(sys.argv[1])
    ит_и = показать(os.path.basename(sys.argv[1].rstrip("/")), идея)
    if len(sys.argv) > 2:
        база = разбор(sys.argv[2])
        ит_б = показать(os.path.basename(sys.argv[2].rstrip("/")), база)
        print("\n===== разница =====")
        for ключ, подпись in (("цели", "цель взята"), ("musk", "TRAIN musk17"),
                              ("inf", "TRAIN infantry17"), ("волны", "волн")):
            print(f"  {подпись:18} {ит_и[ключ]:4} против {ит_б[ключ]:4}")
        if len(идея) < 9 or len(база) < 9:
            print("\n  ОСТОРОЖНО: меньше девяти партий в плече. Разброс базы в "
                  "этом проекте вдвое-втрое по всему, кроме ратуши и времени "
                  "первой волны, — это наблюдение, а не измерение.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
