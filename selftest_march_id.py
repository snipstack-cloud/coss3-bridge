# -*- coding: utf-8 -*-
"""Поход имеет устойчивую личность, не зависящую от сбросов срока.

Повод, 24.09. Разбирая wave_resets против wave_march, я посчитал походы тремя
способами и получил три разных ответа на одних и тех же данных:

    по t0 (как считал assess_report)   база 154 похода,  8% дошли | идея 65, 22%
    по непрерывной череде тактов       база  10,        70%       | идея 14, 71%
    по падению «сбросов» в ноль        база  21,        57%       | идея 37, 86%

Первый способ негоден ДОКАЗУЕМО: сброс срока двигает t0. В базе один поход шёл
t0 = 540, 545, 574, 588, 609, 625 при сбросов = 0..5 — это шесть «походов»
вместо одного. А сбросы режет ровно тот ключ, который и проверялся
(--gather-resets), то есть счёт по t0 возмущается проверяемым ключом и
завышает знаменатель тем сильнее, чем слабее ключ.

Лечение: мост пишет НОМЕР похода, который растёт только при настоящем новом
марше. Тогда «походов за партию», «доля дошедших» и «доля зависших» считаются
однозначно и раз навсегда.

Что проверяется:
  1. счётчик заведён и обнуляется на каждую партию;
  2. начать_марш даёт НОВЫЙ номер и пишет настоящее начало t_старта;
  3. сброс срока двигает t0 и сбросов, но НЕ трогает поход и t_старта;
  4. поле доезжает до трассы (оно идёт туда вместе со всем МАРШ);
  5. assess_report сводит по «поход», а на старых трассах ГОВОРИТ ВСЛУХ, что
     считает смещённым способом.
"""
import io, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import llm_policy as L

ошибок = 0


def проверить(условие, что):
    global ошибок
    if not условие:
        ошибок += 1
        print("  СБОЙ:", что)
    else:
        print("  ок:", что)


ЗДЕСЬ = os.path.dirname(os.path.abspath(__file__))
И = io.open(os.path.join(ЗДЕСЬ, "llm_policy.py"), encoding="utf-8").read()
А = io.open(os.path.join(ЗДЕСЬ, "assess_report.py"), encoding="utf-8").read()

print("1. счётчик заведён и обнуляется на партию")
проверить("НОМЕР_ПОХОДА: list[int] = [0]" in И, "НОМЕР_ПОХОДА заведён")
проверить("НОМЕР_ПОХОДА[0] = 0" in И, "обнуляется на партию")

print("2. начать_марш даёт новый номер и настоящее начало")
контракт = {"via": (5, 13), "expires": 120}
состояние = {"mil_inf": 40, "mil_shooters": 0, "mil_hurt": 0}
L.НОМЕР_ПОХОДА[0] = 0
L.начать_марш(300, 12, "cell", (2, 14), контракт, состояние)
первый = dict(L.МАРШ)
L.начать_марш(500, 20, "cell", (2, 14), контракт, состояние)
второй = dict(L.МАРШ)
проверить(первый.get("поход") == 1 and второй.get("поход") == 2,
          "номер растёт с каждым новым маршем: %s, %s"
          % (первый.get("поход"), второй.get("поход")))
проверить(первый.get("t_старта") == 300 and второй.get("t_старта") == 500,
          "t_старта — настоящее начало похода")
проверить(первый.get("t0") == первый.get("t_старта"),
          "в миг старта t0 и t_старта совпадают")

print("3. сброс срока не трогает личность похода")
# Сброс в мосту делает ровно это: двигает t0 и увеличивает сбросов.
до = dict(L.МАРШ)
L.МАРШ["t0"] = 560
L.МАРШ["сбросов"] += 1
проверить(L.МАРШ["поход"] == до["поход"],
          "номер похода после сброса прежний")
проверить(L.МАРШ["t_старта"] == до["t_старта"],
          "t_старта после сброса прежнее, хотя t0 уехало 500 -> 560")
проверить('МАРШ["t0"] = int(gt)' in И and "НОМЕР_ПОХОДА" not in
          И.split('МАРШ["t0"] = int(gt)')[1].split("\n")[0],
          "в самой ветке сброса номер не трогается")

print("4. поле доезжает до трассы")
проверить('"march": ({k: v for k, v in МАРШ.items() if k != "отчёт"}' in И,
          "в трассу идёт весь МАРШ, значит и «поход» с «t_старта»")

print("5. инструмент сводит по «поход» и говорит про старые трассы")
проверить('_ид = m.get("поход")' in А, "assess_report берёт «поход» первым")
проверить("старых.add(f)" in А, "трассы без поля помечаются")
проверить("ЗАВЫШЕНО" in А and "--gather-resets" in А,
          "на старых трассах смещение называется вслух")

print()
print("ошибок:", ошибок)
sys.exit(1 if ошибок else 0)
