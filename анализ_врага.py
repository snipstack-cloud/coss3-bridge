# ОДИН АНАЛИЗ НА ПАРТИЮ для моста: строка такта стратегии, снимок трассы и запрос модели зовут его в одном такте —
# такт считается один раз (тот же t — тот же ответ); время назад больше чем на 30 с — новая партия.
_ТЕКУЩИЙ = {"а": None, "t": None, "ответ": None}


def текущий(st: dict) -> dict:
    t = float(st.get("gametime") or 0)
    т = _ТЕКУЩИЙ
    if т["а"] is None or (т["t"] is not None and t < т["t"] - 30):
        т["а"], т["t"], т["ответ"] = АнализВрага(), None, None
    if т["t"] == t and т["ответ"] is not None:
        return т["ответ"]
    т["ответ"], т["t"] = т["а"].обновить(st), t
    return т["ответ"]


def в_снимок(о: dict):
    """Короткая форма находок для трассы: [[вид, n, стрелков, x, y, сек], ...] или None."""
    if not о or not о["находки"]:
        return None
    из = []
    for н in о["находки"][:4]:
        место = н.get("центр") or н.get("куда") or (None, None)
        из.append([н["вид"], н.get("n"), н.get("стрелков"), место[0], место[1], н.get("сек", н.get("поток_сек"))])
    return из
