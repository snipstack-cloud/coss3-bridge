"""АНАЛИЗ ПРОТИВНИКА: что он ГОТОВИТ, а не только кто уже идёт (7.10, §118).

Зачем (игрок 7.10, разбор партии А): «нужно видеть заранее, куда идёт противник; если уже пришли и встали — считай,
что проиграли; основная проблема — нет анализа действий противника». В партии А его ход был виден за 2,5 минуты:
с 5:00 передовой лагерь в трёх клетках от нашей ратуши, поток подкреплений к нему, в 6:47 десять стрелков отделились
от пик и пошли к ратуше, в 7:32 встали у неё и до 9:00 убили 28 крестьян. Глаза (`угрозы.py`) видели только «его N к
базе через T» в каждом такте отдельно; стратегия на всё отвечала «сидеть дома».

Здесь — память на `ПАМЯТЬ_С` секунд снимков и распознавание по ней. РЕШЕНИЙ НЕТ, только картина (как у глаз):
  * ЛАГЕРЬ — его куча (связные клетки, ≥ `ЛАГЕРЬ_МИН` бойцов) стоит в `ЛАГЕРЬ_ОТ`–`ЛАГЕРЬ_ДО` клетках от нашей ратуши,
    дальше `ЕГО_БАЗА_ВНЕ` от своей базы, не меньше `ЛАГЕРЬ_С` секунд: рост за минуту, поток (его бойцы, идущие в
    клетку лагеря или соседнюю), состав;
  * СТРЕЛКИ БЕЗ ПИК — его группа, где стрелков ≥ `ДОЛЯ_СТРЕЛКОВ`, идёт к нашей базе/хозяйству, и его пики туда не идут:
    цель, время прихода; по словам игрока такие стрелки бьют крестьян и держатся вне досягаемости пик;
  * ОТРЫВ — его группа идёт к нам, а остальные его силы дальше `ОТРЫВ_КЛЕТОК` от неё (её можно бить отдельно);
  * ЦЕЛЬ — у клетки, куда он идёт: ратуша/мельница/шахта — крестьяне, наша куча — армия, иначе поле.
Мера качества — опережение: за сколько секунд до первых потерь у нашей базы поднят признак (`python3 анализ_врага.py`
по записям игрока).
"""
import math

import угрозы as УГ

ПАМЯТЬ_С = 150.0
ЛАГЕРЬ_МИН = 8
ЛАГЕРЬ_ОТ, ЛАГЕРЬ_ДО = 2, 5
ЕГО_БАЗА_ВНЕ = 3
ЛАГЕРЬ_С = 30.0
ДОЛЯ_СТРЕЛКОВ = 0.7
СТРЕЛКИ_МИН = 4
ОТРЫВ_КЛЕТОК = 3
К_НАМ = 3                 # клеток от ратуши/хозяйства до цели группы: «идёт к нам»


def _чеб(a, b):
    return max(abs(int(a[0]) - int(b[0])), abs(int(a[1]) - int(b[1])))


def _его_база(st):
    eb = st.get("en_base")
    if isinstance(eb, str):
        try:
            eb = [float(v) for v in eb.replace(";", ",").split(",")][:2]
        except ValueError:
            eb = None
    return (int(round(float(eb[0]))), int(round(float(eb[1])))) if eb else None


def _кучи(клетки):
    """Связные (Чебышёв 1) кучи его клеток: [[(x, y), ...], ...]."""
    ост = {(int(c["x"]), int(c["y"])): c for c in клетки if int(c.get("n") or 0) > 0}
    из = []
    while ост:
        k0 = next(iter(ост))
        стек, куча = [k0], []
        del ост[k0]
        while стек:
            k = стек.pop()
            куча.append(k)
            for dx in (-1, 0, 1):
                for dy in (-1, 0, 1):
                    q = (k[0] + dx, k[1] + dy)
                    if q in ост:
                        del ост[q]
                        стек.append(q)
        из.append(куча)
    return из


class АнализВрага:
    def __init__(self):
        self.история = []          # [(t, [клетки его])]
        self.лагеря = {}           # центр (округлённый) -> {с, n_история}
        self.первые = {}           # признак -> время первого появления

    def обновить(self, st: dict) -> dict:
        t = float(st.get("gametime") or 0)
        его = [c for c in УГ._его(st) if int(c.get("n") or 0) > 0]
        наши = УГ._наши(st)
        д = УГ.дом(st)
        eb = _его_база(st)
        self.история = [(tt, кк) for tt, кк in self.история if t - tt <= ПАМЯТЬ_С] + [(t, его)]
        ш = УГ._клетка_ед(st)
        сек_кл = ш / УГ.МАРШ_ЕД_В_С
        хоз = [(int(float(b["x"]) // ш), int(float(b["z"]) // ш)) for b in УГ._здания(st)
               if str(b.get("тип")) in УГ.ХОЗЯЙСТВЕННЫЕ + ("center",)]
        по = {(int(c["x"]), int(c["y"])): c for c in его}
        дома = sum(int(c.get("n") or 0) for c in наши if д and _чеб((c["x"], c["y"]), д) <= 1)
        в_поле = [c for c in наши if д and _чеб((c["x"], c["y"]), д) > 1]
        находки = []

        def цель_что(куда):
            if д is not None and _чеб(куда, д) <= 1:
                return "крестьяне у ратуши"
            if any(_чеб(куда, h) <= 1 for h in хоз):
                return "крестьяне у хозяйства"
            if any(_чеб(куда, (k["x"], k["y"])) <= 1 for k in наши):
                return "наша армия"
            return "поле"

        # --- ЛАГЕРЬ ---
        лагеря_сейчас = {}
        if д is not None:
            for куча in _кучи(его):
                n = sum(int(по[k].get("n") or 0) for k in куча)
                if n < ЛАГЕРЬ_МИН:
                    continue
                идут = sum(int(по[k].get("идут") or 0) for k in куча
                           if по[k].get("tx") is not None and _чеб((по[k]["tx"], по[k]["ty"]), k) > 1)
                cx = sum(k[0] * int(по[k].get("n") or 0) for k in куча) / n
                cy = sum(k[1] * int(по[k].get("n") or 0) for k in куча) / n
                ц = (int(round(cx)), int(round(cy)))
                от_нас = _чеб(ц, д)
                if not (ЛАГЕРЬ_ОТ <= от_нас <= ЛАГЕРЬ_ДО) or (eb is not None and _чеб(ц, eb) <= ЕГО_БАЗА_ВНЕ):
                    continue
                if идут > 0.5 * n:
                    continue                            # куча на марше — не лагерь
                пик = sum(int(по[k].get("пик") or 0) for k in куча)
                стр = sum(int(по[k].get("стрелков") or 0) for k in куча)
                лагеря_сейчас[ц] = dict(центр=ц, n=n, пик=пик, стрелков=стр, от_нас=от_нас)
        новые = {}
        for ц, л in лагеря_сейчас.items():
            прежний = next((к for к in self.лагеря if _чеб(к, ц) <= 1), None)
            зап = self.лагеря.get(прежний) if прежний is not None else None
            if зап is None:
                зап = {"с": t, "n": []}
            зап["n"] = [(tt, nn) for tt, nn in зап["n"] if t - tt <= 90] + [(t, л["n"])]
            новые[ц] = зап
            стоит = t - зап["с"]
            if стоит >= ЛАГЕРЬ_С:
                n60 = next((nn for tt, nn in зап["n"] if t - tt <= 60), л["n"])
                поток = sum(int(c.get("идут") or 0) for c in его
                            if c.get("tx") is not None and _чеб((c["tx"], c["ty"]), ц) <= 1 and _чеб((c["x"], c["y"]), ц) >= 2)
                поток_сек = min([round(_чеб((c["x"], c["y"]), ц) * сек_кл) for c in его
                                 if c.get("tx") is not None and _чеб((c["tx"], c["ty"]), ц) <= 1 and _чеб((c["x"], c["y"]), ц) >= 2] or [None]) \
                    if поток else None
                находки.append(dict(вид="лагерь", t=t, стоит=round(стоит), **л, рост_60=л["n"] - n60, поток=поток,
                                    поток_сек=поток_сек, наших_дома=дома,
                                    строка=f"ЛАГЕРЬ его {л['n']} (пик {л['пик']}, стрелков {л['стрелков']}) в {л['центр']}, "
                                           f"{л['от_нас']} кл. от ратуши, стоит {round(стоит)} с, за минуту {л['n'] - n60:+d}"
                                           + (f", к нему идут {поток}" + (f" (ближние через ~{поток_сек} с)" if поток_сек is not None else "") if поток else "")
                                           + f"; наших дома {дома}"))
        self.лагеря = новые

        # --- СТРЕЛКИ БЕЗ ПИК и ОТРЫВ ---
        if д is not None:
            цели_пик = [((int(c["tx"]), int(c["ty"])), int(c.get("пик") or 0)) for c in его
                        if int(c.get("идут") or 0) > 0 and c.get("tx") is not None]
            for c in его:
                n = int(c.get("n") or 0)
                идут = int(c.get("идут") or 0)
                if идут <= 0 or c.get("tx") is None:
                    continue
                откуда, куда = (int(c["x"]), int(c["y"])), (int(c["tx"]), int(c["ty"]))
                к_нам = _чеб(куда, д) <= К_НАМ or any(_чеб(куда, h) <= 1 for h in хоз)
                if not к_нам or _чеб(откуда, куда) < 1:
                    continue
                стр = int(c.get("стрелков") or 0)
                сек = round(_чеб(откуда, куда) * сек_кл)
                что = цель_что(куда)
                if n >= СТРЕЛКИ_МИН and стр >= ДОЛЯ_СТРЕЛКОВ * n:
                    пики_туда = sum(p for к, p in цели_пик if _чеб(к, куда) <= 1)
                    if пики_туда < 0.3 * стр:
                        находки.append(dict(вид="стрелки без пик", t=t, n=n, стрелков=стр, откуда=откуда, куда=куда, сек=сек, цель=что,
                                            строка=f"СТРЕЛКИ БЕЗ ПИК: {стр} из {откуда} идут к {куда} ({что}), через ~{сек} с, "
                                                   f"пики за ними не идут; наших дома {дома}"))
                # отрыв: остальные его силы далеко от этой группы
                прочие = sum(int(q.get("n") or 0) for q in его if _чеб((q["x"], q["y"]), откуда) <= ОТРЫВ_КЛЕТОК) - n
                if n >= СТРЕЛКИ_МИН and прочие < 0.5 * n and что != "поле":     # поток к своему лагерю — не отрыв
                    находки.append(dict(вид="отрыв", t=t, n=n, откуда=откуда, куда=куда, сек=сек, цель=что,
                                        строка=f"ОТРЫВ: его {n} (стрелков {стр}) из {откуда} к {куда} ({что}) без поддержки в "
                                               f"{ОТРЫВ_КЛЕТОК} кл., через ~{сек} с"))
        for н in находки:
            self.первые.setdefault(н["вид"], t)
        return {"t": t, "находки": находки, "первые": dict(self.первые),
                "строка": "; ".join(н["строка"] for н in находки[:3]) or "намерений у нашей базы не видно"}


def прогон(каталог, с=0.0, по=1e9, печать=True):
    """По записи: признаки по времени и первые потери у нашей базы (крестьяне — по `my_pea_lost`)."""
    import json
    import os
    а = АнализВрага()
    путь = os.path.join(os.path.expanduser(каталог), "coss3_snap.jsonl")
    кр0, первая_потеря, прежняя = None, None, None
    for строка in open(путь, encoding="utf-8"):
        s = json.loads(строка)
        t = float(s.get("gametime") or 0)
        if not (с <= t <= по):
            continue
        кр = float(s.get("my_pea_lost") or 0)
        if кр0 is None:
            кр0 = кр
        if первая_потеря is None and кр - кр0 >= 3:
            первая_потеря = t
        о = а.обновить(s)
        if печать and о["находки"]:
            ключ = tuple(sorted({н["вид"] for н in о["находки"]}))
            if ключ != прежняя or int(t) % 30 < 5:
                print(f"{int(t) // 60:2d}:{int(t) % 60:02d}  {о['строка']}")
            прежняя = ключ
    return а.первые, первая_потеря


