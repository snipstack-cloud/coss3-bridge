#!/usr/bin/env python3
"""Снимки ЗАПРОСА на неподвижных состояниях + проверки смысла.

Зачем. 16.09 мост дважды соврал модели, и оба раза правка была «очевидной»:
  * `atk8` добавили в строку найма — и `не_по_карману()` посчитал это ЦЕНОЙ,
    мост сообщал «НЕ ХВАТАЕТ РЕСУРСОВ: 8 atk». Я смотрел одного читателя строки
    из нескольких;
  * счётчик мини-карты дописали ПОСЛЕ однострочного `if` — он выполнялся для
    каждого объекта, и сетка «вражеские солдаты» считала крестьян и здания.
Оба ловятся за секунду, если смотреть на ГОТОВЫЙ ЗАПРОС, а не на diff.

Как устроено. В fixtures/ лежат настоящие состояния из живых партий. Тест
рендерит запрос и сверяет со снимком fixtures/<имя>.prompt.txt. Снимок меняется
только осознанно: `python3 selftest_prompt.py --update`, и разницу видно в
`git diff` — там же её и читают на ревью.

Снимок ловит ЛЮБОЕ изменение, в том числе безобидное. Поэтому ниже есть второй
слой — проверки смысла: они не зависят от формулировок и держатся за правила,
купленные ошибками.
"""
import sys, os, re, json, difflib

# Флаг читаем ДО того, как стереть argv: llm_policy разбирает argv при импорте,
# и стёртый argv унёс бы с собой --update. Поймано этим же тестом.
ОБНОВИТЬ = "--update" in sys.argv[1:]
sys.argv = [sys.argv[0]]                  # llm_policy читает argv при импорте
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import llm_policy as L                                        # noqa: E402

КАТАЛОГ = os.path.join(os.path.dirname(os.path.abspath(__file__)), "fixtures")


def состояние(путь: str) -> dict:
    st = {}
    for строка in open(путь, encoding="latin-1"):
        if "=" in строка:
            ключ, _, знач = строка.partition("=")
            st[ключ.strip()] = знач.strip()
    return st


def параметры(имя: str) -> dict:
    """Контекст фикстуры: были ли в ЭТОЙ партии свои волны.

    Он нужен, потому что `wave_sent` в состоянии — это поле ИГРЫ, и оно
    переживает конец партии. Чья волна в нём записана, решает не состояние, а
    петля такта.
    """
    путь = os.path.join(КАТАЛОГ, f"{имя}.params.json")
    if os.path.exists(путь):
        return json.load(open(путь, encoding="utf-8"))
    return {}


def запрос(st: dict, волны: list | None = None) -> str:
    """Тот же путь, каким состояние идёт к модели в живом такте.

    Сначала снимается волна прошлой партии — это делает петля, а не рендер, и
    тест обязан повторять петлю, иначе проверяет не то, что играет.

    Всё, что зависит от файлов и времени, выключено нарочно: подсказки, мир и
    история пусты. Иначе снимок менялся бы от правки hints_human.txt.
    """
    L.ЧЕСТНО = True
    волны = list(волны or [])
    st = dict(st)
    L.снять_чужую_волну(st, волны, ["молча"])   # список непустой: не печатаем
    return L.situation(st, {}, [], "", волны=волны, мир="")


def проверки_смысла(имя: str, st: dict, текст: str) -> list[str]:
    беды = []

    # 1. Боевые свойства - НЕ ЦЕНА. 16.09 мост писал «НЕ ХВАТАЕТ: 8 atk».
    for строка in текст.splitlines():
        низ = строка.lower()
        если_про_нехватку = ("не хватает" in низ or "не по карману" in низ
                             or "нехватка" in низ)
        if если_про_нехватку and re.search(r"\b(atk|dpike|dsword|dbullet)\b", низ):
            беды.append(f"{имя}: боевое свойство названо ценой -> {строка.strip()[:90]}")

    # 2. Сетка сил обещает СОЛДАТ. 16.09 она считала крестьян и здания.
    клетки = sum(int(c) for y in range(16)
                 for c in str(st.get(f"frow{y}", "")) if c.isdigit())
    армия = 0
    for k, v in st.items():
        if re.match(r"^p\d_army$", k):
            try:
                армия += int(float(v))
            except (TypeError, ValueError):
                pass
    if клетки and клетки > армия:
        беды.append(f"{имя}: в сетке сил {клетки} бойцов, а армия врага {армия} — "
                    f"сетка считает не солдат")
    if армия == 0 and клетки:
        беды.append(f"{имя}: армия врага 0, а сетка показывает {клетки}")

    # 3. Волна ПРОШЛОЙ партии не выдаётся за свою, пока своей не было.
    своя_волна = bool(параметры(имя).get("волны"))
    if not своя_волна and "в последней волне было послано" in текст:
        беды.append(f"{имя}: своей волны в этой партии не было, а запрос "
                    f"говорит о посланной — волна ПРОШЛОЙ партии не снята")

    # 4. Закрытая карта прячет числа врага.
    закрыто = dict(st, map_open="False")
    т2 = запрос(закрыто, параметры(имя).get("волны"))
    if "крестьян у противника" in т2 or "армия противника" in т2:
        беды.append(f"{имя}: карта закрыта, а числа врага в запросе")

    # 5. Взятый апгрейд не предлагается снова.
    взяты = L.взятые_апгрейды(st)
    показаны = ""
    for строка in текст.splitlines():
        if "апгрейды, доступные тебе сейчас" in строка:
            показаны = строка
    for у in взяты:
        if re.search(rf"[ ,]{re.escape(у)}[ ,]", показаны):
            беды.append(f"{имя}: апгрейд {у} уже взят, но предложен снова")

    # 6. То же самое ПРЯМЫМ вызовом, а не по тексту: 16.09 «не по карману»
    # считал ценой любое поле вида имя+число, кроме hp, и мост сообщал
    # «atk 0 при цене 8». Проверено на коммите 796fff5^: старый код это
    # выдаёт, нынешний молчит.
    проба = dict(st, fighters=("infantry17=pikeman,hp90,atk8,dpike3,dsword2,"
                               "dbullet4,food25,gold3,iron20,coal0"),
                 food="0", gold="0", iron="0", coal="0", wood="0", stone="0",
                 ba17="1")
    for строка in L.не_по_карману("infantry17", проба):
        if re.search(r"\b(atk|dpike|dsword|dbullet)\b", str(строка).lower()):
            беды.append(f"{имя}: боевое свойство названо ценой -> {строка}")

    # 7. ДОТЕКАНИЕ: волна в поле, дома свободные — модель обязана знать, что
    #    новый ATTACK уйдёт отдельной струйкой. Механику назвал игрок 16.09,
    #    подтверждена кодом игры (_ai_ProgressDefenders).
    ушли = L._чис(st.get("mil_away"))
    послано = L._чис(st.get("wave_sent"))
    дома = L._чис(st.get("my_freewar"))
    if послано and ушли and дома and параметры(имя).get("волны"):
        if "ДОТЕКАНИЕ" not in текст:
            беды.append(f"{имя}: {послано} в поле и {дома} дома, а про дотекание "
                        f"модель не предупреждена")

    # 8. Пустых «: ничего» и голых None в запрос не отдаём.
    for строка in текст.splitlines():
        if "None" in строка:
            беды.append(f"{имя}: None в запросе -> {строка.strip()[:80]}")
    return беды


def main() -> int:
    файлы = sorted(f for f in os.listdir(КАТАЛОГ) if f.endswith(".dat"))
    if not файлы:
        print(f"нет фикстур в {КАТАЛОГ}")
        return 1
    провалов, беды_всего = 0, []
    for ф in файлы:
        имя = ф[:-4]
        st = состояние(os.path.join(КАТАЛОГ, ф))
        текст = запрос(st, параметры(имя).get("волны"))
        снимок = os.path.join(КАТАЛОГ, f"{имя}.prompt.txt")
        if ОБНОВИТЬ or not os.path.exists(снимок):
            with open(снимок, "w", encoding="utf-8") as f:
                f.write(текст)
            print(f"  снимок записан: {имя}.prompt.txt ({len(текст)} символов)")
        else:
            было = open(снимок, encoding="utf-8").read()
            if было != текст:
                провалов += 1
                разница = list(difflib.unified_diff(
                    было.splitlines(), текст.splitlines(),
                    "снимок", "сейчас", lineterm="", n=1))
                print(f"  ПРОВАЛ  {имя}: запрос изменился, строк разницы "
                      f"{len([d for d in разница if d[:1] in '+-'])}")
                for строка in разница[:14]:
                    print(f"      {строка}")
                print("      если изменение задумано: python3 selftest_prompt.py --update")
            else:
                print(f"  ОК      {имя}: запрос совпал со снимком "
                      f"({len(текст)} символов)")
        беды_всего += проверки_смысла(имя, st, текст)
    for б in беды_всего:
        print(f"  ПРОВАЛ  {б}")
    провалов += len(беды_всего)
    print(f"\nПРОВАЛОВ: {провалов}")
    return 1 if провалов else 0


if __name__ == "__main__":
    raise SystemExit(main())
