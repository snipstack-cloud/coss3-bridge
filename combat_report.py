# -*- coding: utf-8 -*-
"""Combat Readiness — боевая готовность по трассам отыгранных партий.

Пара к `egr_report.py`. Тот считает экономику, этот — удар. Появился 17.09,
когда выяснилось, что экономику чинить дальше бесполезно: правка BALANCE подняла
доставку волны с 40 до 83 процентов, а доля целей СРЕДИ ДОШЕДШИХ волн осталась
прежней — 38 против 39. Значит цель теряется в самом ударе.

    python3 combat_report.py <каталог идеи> [<каталог идеи> ...]

Два решения, без которых счёт врёт:
  * всё меряется В МОМЕНТ ПОДХОДА волны к базе врага, а не в конце партии.
    Партия, оборванная целью, короче горизонта: армия врага в ней не успевает
    вырасти, и «перевес» задним числом даёт AUC 0,99 на пустом месте.
  * «дошла» — это mil_far >= 180. Расстояние до базы врага около 210.
"""
import glob, json, os, statistics as st, sys

ДОШЛА = 180


def эпизоды(путь):
    эп, тек = [], []
    for строка in open(путь, encoding="utf-8"):
        r = json.loads(строка)
        тек.append(r)
        if "finish" in r:
            эп.append(тек)
            тек = []
    return эп


def ч(s, k):
    try:
        return float(s.get(k, 0) or 0)
    except (TypeError, ValueError):
        return 0.0


def партия(e):
    т = [r for r in e if r.get("state")]
    if len(т) < 10:
        return None                      # призрак: партии не было
    S = [r["state"] for r in т]
    исход = next((r["finish"] for r in e if "finish" in r), "?")
    свои = [ч(s, "mil_inf") + ч(s, "mil_shooters") for s in S]
    убаз = [i for i, s in enumerate(S) if ч(s, "mil_far") >= ДОШЛА]
    д = dict(цель=(исход == "цель"), дошла=bool(убаз),
             дальность=max((ч(s, "mil_far") for s in S), default=0.0))
    if not убаз:
        return д
    i0, i1 = убаз[0], убаз[-1]
    волна0 = ч(S[i0], "mil_away")
    враг = max(1.0, ч(S[i0], "p1_army"))
    д.update(
        кулак=волна0,                                  # сколько пришло
        доля_армии=волна0 / max(1.0, свои[i0]),        # какую часть привели
        перевес=волна0 / враг,                         # против кого встали
        тактов_у_базы=len(убаз),
        потери=max(0.0, волна0 - ч(S[i1], "mil_away")),
        таяние=1.0 - ч(S[i1], "mil_away") / max(1.0, волна0),
        прицел=прицел_на_подходе(т, i0),               # куда повёл волну, когда она дошла
        апгрейдов=len([x for x in str(S[i0].get("upg_done") or "").split(",") if x.startswith("mil")]))
    д["CR"] = round(100 * (0.35 * min(1.0, д["перевес"]) + 0.25 * д["доля_армии"]
                           + 0.25 * д["прицел"] + 0.15 * min(1.0, д["апгрейдов"] / 2)), 1)
    return д


def прицел_на_подходе(т, с_такта):
    """1, если ПЕРВЫЙ приказ после подхода вёл волну на крестьян, иначе 0.

    Считать долю по всем тактам после подхода нельзя: партия с целью обрывается
    через такт-другой, и доля у неё берётся из двух приказов, а у проигранной из
    двадцати. Это та же ловушка короткой партии, что и с армией врага.
    """
    for i in range(с_такта, len(т)):
        ц = т[i].get("target")
        if ц:
            return 1.0 if ц == "peasants" else 0.0
    return 0.0


def auc(гр, поле):
    a = [x[поле] for x in гр if x["цель"] and поле in x]
    b = [x[поле] for x in гр if not x["цель"] and поле in x]
    if not a or not b:
        return None
    return sum((1 if x > y else 0.5 if x == y else 0) for x in a for y in b) / (len(a) * len(b))


def main(каталоги):
    гр = []
    for кат in каталоги:
        for путь in sorted(glob.glob(os.path.join(кат, "*", "coss3_bot.jsonl"))):
            for e in эпизоды(путь):
                д = партия(e)
                if д:
                    гр.append(д)
    if not гр:
        sys.exit("трасс не нашлось")
    дошли = [x for x in гр if x["дошла"]]
    цели = sum(1 for x in гр if x["цель"])
    print("партий %d | цель %d (%.0f%%) | волна дошла %d (%.0f%%)"
          % (len(гр), цели, 100.0*цели/len(гр), len(дошли), 100.0*len(дошли)/len(гр)))
    print("ЦЕЛЬ, ЕСЛИ ДОШЛА: %d из %d (%.0f%%) — это и есть конверсия удара"
          % (sum(1 for x in дошли if x["цель"]), len(дошли),
             100.0*sum(1 for x in дошли if x["цель"])/max(len(дошли), 1)))
    if not дошли:
        return
    print()
    print("В МОМЕНТ ПОДХОДА К БАЗЕ ВРАГА (медианы по дошедшим):")
    print("%-16s%10s%10s%8s" % ("мера", "цель", "нет", "AUC"))
    for поле in ("CR", "кулак", "доля_армии", "перевес", "прицел", "апгрейдов"):
        a = [x[поле] for x in дошли if x["цель"] and поле in x]
        b = [x[поле] for x in дошли if not x["цель"] and поле in x]
        if not a or not b:
            continue
        print("%-16s%10.2f%10.2f%8.2f" % (поле, st.median(a), st.median(b), auc(дошли, поле)))
    print()
    print("ОПИСАТЕЛЬНО, СРАВНИВАТЬ НЕЛЬЗЯ — эти меры обрываются вместе с партией:")
    for поле in ("таяние", "тактов_у_базы", "потери"):
        a = [x[поле] for x in дошли if x["цель"] and поле in x]
        b = [x[поле] for x in дошли if not x["цель"] and поле in x]
        if a and b:
            print("  %-14s цель %6.2f | нет %6.2f (у взятой цели партия кончается сразу)"
                  % (поле, st.median(a), st.median(b)))
    print()
    print("Читать так: AUC 0,5 — мера ничего не знает об исходе. «Прицел» — доля")
    print("приказов ATTACK по крестьянам после подхода; остальные уводят волну")
    print("к ЗДАНИЮ, потому что в блоке любая цель кроме peasants ищет постройку.")


if __name__ == "__main__":
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    main(sys.argv[1:])
