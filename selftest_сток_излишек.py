#!/usr/bin/env python3
"""§170ф (29.10): припаркованные стоком блока сверх его целей — свободные люди для §170п. Ключ `сток_излишек` 0 = как было."""
from collections import Counter
import strategy_live as SL

class _Стр:  # носитель состояния правила
    pass

def _st(**kw):
    st = {"gametime": 125, "food": 1000, "idle_pea": 0, "on_food": 0, "on_wood": 18, "on_stone": 3,
          "on_gold": 0, "on_iron": 0, "on_coal": 0, "tgt_food": -1, "tgt_wood": 16, "tgt_stone": 3, "sink_pea": 2}
    st.update(kw); return st

ошибок = 0
def проверка(имя, ок, подробно=""):
    global ошибок
    print(("ОК  " if ок else "ПЛОХО") + "  " + имя + (f" — {подробно}" if подробно else ""))
    if not ок: ошибок += 1

из = [{"cmd": "BALANCE", "role": "stone", "total": 5}]
# (а) без ключа — как было: праздных 0, прибавка 2 < порога 3 → не шлём
отд = Counter(); стр = _Стр()
вышло = SL._переброс([dict(c) for c in из], _st(), {"переброс_раз": 50}, стр, отд)
проверка("(а) без ключа камень 3→5 не уходит (праздных 0)", вышло == [] and any("не шлём" in k for k in отд), str(dict(отд))[:200])
# (б) с ключом — 2 припаркованных на дереве (18 при цели 16) свободны: прибавка 2 уходит без срока и зоны
отд = Counter(); стр = _Стр()
вышло = SL._переброс([dict(c) for c in из], _st(), {"переброс_раз": 50, "сток_излишек": 1}, стр, отд)
проверка("(б) с ключом камень 3→5 уходит за счёт излишка стока", len(вышло) == 1 and вышло[0]["total"] == 5, str(dict(отд))[:200])
# (в) с ключом, но излишка нет (дерево ровно по цели) — как без ключа
отд = Counter(); стр = _Стр()
вышло = SL._переброс([dict(c) for c in из], _st(tgt_wood=18, sink_pea=0), {"переброс_раз": 50, "сток_излишек": 1}, стр, отд)
проверка("(в) с ключом без излишка — не уходит", вышло == [], str(dict(отд))[:200])
# (г) с ключом запрос больше излишка: 3→9 при излишке 2 — заполнение не глубже свободных, «доноров нет» называет излишек
отд = Counter(); стр = _Стр()
вышло = SL._переброс([{"cmd": "BALANCE", "role": "stone", "total": 9}], _st(), {"переброс_раз": 50, "сток_излишек": 1}, стр, отд)
проверка("(г) 3→9 при излишке 2 — не уходит, причина называет излишек", вышло == [] and any("излишек стока 2" in k for k in отд), str(dict(отд))[:200])
# (д) без поля tgt_* в состоянии (старый блок) ключ молчит
отд = Counter(); стр = _Стр()
st = _st(); [st.pop(k) for k in ("tgt_food", "tgt_wood", "tgt_stone", "sink_pea")]
вышло = SL._переброс([dict(c) for c in из], st, {"переброс_раз": 50, "сток_излишек": 1}, стр, отд)
проверка("(д) старый блок без tgt_* — ключ молчит, как было", вышло == [])
print(f"ИТОГ: ошибок {ошибок}")
raise SystemExit(1 if ошибок else 0)
