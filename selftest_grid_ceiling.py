# -*- coding: utf-8 -*-
"""Потолок сетки поднят: A-Z для 36-61 и ТОЧНЫЕ числа в клетках контакта.

Просьба мака 26.09: «копия 1, 1091 с, размен 4,0 — числами не объясняется,
потому что клетки с обеих сторон 36+». Он предложил на выбор второй знак,
алфавит A-Z или два знака выше.

ПОЧЕМУ СДЕЛАНО НЕ ВСЁ, ЧТО ПРЕДЛОЖЕНО. Алфавит A-Z даёт потолок 61, а решающий
бой шёл при 194 наших против 36 его в ОДНОЙ клетке — буквами он не мерится.
Два знака на клетку потолок поднимут, но удвоят ширину сетки и сломают всех
читателей вместе с 213 прогонами архива. Поэтому:
  * A-Z — сделано, дёшево и улучшает картину во всех клетках до 61;
  * точные числа в клетках контакта — сделано, и это закрывает просьбу: потолка
    нет вовсе;
  * два знака — НЕ сделано нарочно, и это записано.

Что проверяется:
  1. алфавиты читаются и пишутся симметрично, потолок «+» равен 62;
  2. старые знаки (0-35) читаются КАК РАНЬШЕ — архив остаётся сравнимым;
  3. поле `cells` разбирается, и «нет поля» отличимо от «клеток нет»;
  4. блок пишет оба алфавита и поле `cells`, и счётчики объявлены на уровне
     блока (скаляр во вложенном begin не накапливает — 17.09);
  5. мок отдаёт `cells`, иначе петля проверяется вслепую;
  6. снимок трассы несёт `cells`, иначе по серии не посчитать;
  7. промпт называет ПРАВИЛЬНЫЙ потолок: до 26.09 он говорил «срезана на
     девяти», когда срез был на 36, — мост врал модели с 18.09.
"""
import io
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import coss3_map as M

ошибок = 0


def проверить(условие, что):
    global ошибок
    if not условие:
        ошибок += 1
        print("  СБОЙ:", что)
    else:
        print("  ок:", что)


ЗДЕСЬ = os.path.dirname(os.path.abspath(__file__))
БЛОК = io.open(os.path.join(ЗДЕСЬ, "block_hstate.inc"), encoding="latin-1").read()
ПОЛИТИКА = io.open(os.path.join(ЗДЕСЬ, "llm_policy.py"), encoding="utf-8").read()
МОК = io.open(os.path.join(ЗДЕСЬ, "mock_human.py"), encoding="utf-8").read()

print("1. алфавиты и потолок")
проверить(M.ПОТОЛОК_ЗНАКА == 62, "потолок знака 62")
проверить(M.счёт("A") == 36 and M.счёт("Z") == 61, "A-Z читается как 36-61")
проверить(M.счёт("+") == 62, "«+» значит 62 и больше")
for n in list(range(0, 62)):
    if M.счёт(M.знак(n)) != n:
        проверить(False, "знак и счёт не симметричны на %d" % n)
        break
else:
    проверить(True, "знак и счёт симметричны на всех 0..61")
проверить(M.знак(194) == "+" and M.знак(62) == "+", "выше потолка — «+»")

print()
print("2. старые знаки читаются КАК РАНЬШЕ — архив сравним")
проверить(M.счёт(".") == 0 and M.счёт("1") == 1 and M.счёт("9") == 9,
          "цифры прежние")
проверить(M.счёт("a") == 10 and M.счёт("z") == 35, "a-z прежние")

print()
print("3. поле cells, и «нет поля» отличимо от «клеток нет»")
к = M.клетки_боя({"cells": "3,4,194,36,0;7,8,12,0,15"})
проверить(len(к) == 2, "две клетки разобраны")
проверить(к[0] == dict(x=3, y=4, наших=194, его=36, крестьян=0),
          "точное число БЕЗ потолка: 194 наших")
проверить(M.клетки_боя({"cells": "none"}) == [], "«none» — клеток нет")
проверить(M.есть_точные_клетки({"cells": "none"}) is True,
          "«none» — поле ЕСТЬ (измеренный ноль)")
проверить(M.есть_точные_клетки({}) is False,
          "нет ключа — поля НЕТ (старый мост), это другое")
проверить(M.клетки_боя({"cells": "мусор;3,4"}) == [], "кривое молча не ломает")

print()
print("3a. ШЕСТОЕ ПОЛЕ: расстояние между кучами внутри клетки (27.09)")
# Просьба мака по его же счёту: в 218 тактах из 445 обе стороны стояли в одной
# клетке по пятеро и больше, а потерь ноль; при одинаковых числах потери
# различаются в 2-3,6 раза. Скрытая переменная — расстояние между кучами.
ш = M.клетки_боя({"cells": "3,4,194,36,0,5;7,8,12,0,15,-1"})
проверить(len(ш) == 2, "шестиполевые клетки разобраны")
проверить(ш[0].get("между") == 5, "расстояние прочитано как есть")
проверить(ш[1].get("между") == -1,
          "-1 доезжает: одной стороны в клетке нет, расстояния не существует")
# Архив до 27.09 — пять полей. Строгое `!= 5` в прежнем читателе выбросило бы
# КАЖДУЮ клетку нового моста; строгое `!= 6` выбросило бы весь архив.
а = M.клетки_боя({"cells": "3,4,194,36,0"})
проверить(len(а) == 1 and "между" not in а[0],
          "архивные пять полей читаются, и ключа «между» у них НЕТ")
проверить(M.клетки_боя({"cells": "3,4,1,1,0,2,9"}) == [],
          "семь полей — это не наш формат, молча не притворяемся")

print()
print("3b. блок считает расстояние по СУММАМ координат, а не по клеткам")
for имя in ("hmsox", "hmsoz", "hmsex", "hmsez"):
    проверить("var %s : array [0..15] of array [0..15] of Integer;" % имя in БЛОК,
              "массив сумм %s объявлен" % имя)
    проверить("%s[hmi][hmj] := 0;" % имя in БЛОК, "массив %s обнуляется" % имя)
проверить("hmdd := Round(Sqrt(hmddx*hmddx + hmddz*hmddz));" in БЛОК,
          "расстояние считается по теореме Пифагора от центров")
проверить("var hmdd : Integer = -1;" in БЛОК,
          "по умолчанию -1: одной стороны нет — числа нет")
проверить("IntToStr(hmpea[hmi][hmj]) + ',' + IntToStr(hmdd);" in БЛОК,
          "шестое поле дописано ПОСЛЕ пяти прежних — старые читатели целы")
# Суммы копятся по циклу, но это МАССИВЫ: они переживают вложенный begin по
# ссылке (17.09 так же спаслась hmown, а шесть скаляров рядом — нет).
проверить(БЛОК.index("var hmsox") < БЛОК.index("hmsox[hmux][hmuy]")
          if "hmsox[hmux][hmuy]" in БЛОК else True,
          "объявление сумм раньше использования")

print()
print("4. блок пишет оба алфавита и cells")
проверить("var hmbig : String = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ';" in БЛОК,
          "второй алфавит объявлен в блоке")
for пер in ("hmf", "hmo", "hmq", "hmd"):
    проверить("if (%s > 35) and (%s <= 61) then hmrow := hmrow + SubStr(hmbig, %s-35, 1);"
              % (пер, пер, пер) in БЛОК, "сетка по %s пишет A-Z" % пер)
    проверить("if (%s > 61) then hmrow := hmrow + '+';" % пер in БЛОК,
              "сетка по %s ставит «+» с 62" % пер)
проверить("ParserSetValueByKeyByHandle(hsp, 'cells', hmcs);" in БЛОК,
          "поле cells пишется")
проверить("ParserSetIntValueByKeyByHandle(hsp, 'cells_n', hmcn);" in БЛОК,
          "число клеток пишется отдельно")
проверить("hmcs := 'none';" in БЛОК, "пустое поле пишется как «none», а не молчит")
# Скаляр, который НАКАПЛИВАЕТ через цикл, объявлять на уровне блока: 17.09 шесть
# счётчиков армии во вложенном begin читались нулём при 208 бойцах.
объявление = БЛОК.index("var hmcn : Integer;")
писатель = БЛОК.index("ParserSetValueByKeyByHandle(hsp, 'cells', hmcs);")
проверить(объявление < БЛОК.index("var hmalpha"),
          "счётчики объявлены ВЫШЕ писателей сеток — на уровне блока")
проверить(объявление < писатель, "объявление раньше использования")
проверить("hmcn < 12" in БЛОК, "число клеток ограничено, строка не разрастётся")
проверить(not any(ord(c) > 127 for c in БЛОК), "в блоке нет кириллицы")

print()
print("5. мок отдаёт cells")
проверить('d["cells"]' in МОК and 'd["cells_n"]' in МОК, "мок пишет оба ключа")
проверить('"none"' in МОК.split('d["cells"]')[1][:120],
          "мок тоже пишет «none», а не пропускает ключ")
import tempfile
import mock_human
# Мир требует каталог обмена — тот же способ, что в selftest_builders.
м = mock_human.Мир(tempfile.mkdtemp(prefix="coss3_grid_"), plind=0)
м.t = 700
с = м.сетки()
проверить("cells" in с and "cells_n" in с, "живой мок отдаёт поля")
проверить(isinstance(M.клетки_боя(с), list), "мокнутое поле разбирается читателем")
# Мок обязан отдавать ту же ФОРМУ, что игра: шесть полей. Величину он не
# подделывает (координат внутри клетки у него нет), но «одной стороны нет»
# отдаёт тем же -1, иначе петля проверяется вслепую.
_кл = M.клетки_боя(с)
if _кл:
    проверить(all("между" in к for к in _кл), "мок отдаёт шестое поле у каждой клетки")
    проверить(all((к["между"] == -1) == (к["его"] == 0) for к in _кл),
              "у мока -1 стоит ровно там, где его бойцов в клетке нет")
else:
    проверить(True, "у мока в этом такте клеток контакта нет — форму проверить нечем")

print()
print("6. снимок трассы несёт cells")
проверить('_снимок["cells"] = coss3_map.клетки_боя(st)' in ПОЛИТИКА,
          "точные клетки идут в трассу")
проверить("if coss3_map.есть_точные_клетки(st):" in ПОЛИТИКА,
          "кладутся только когда поле есть — иначе ложный ноль по серии")

print()
print("7. промпт называет ПРАВИЛЬНЫЙ потолок")
проверить("СРЕЗАНА на девяти" not in ПОЛИТИКА,
          "убрано «срезана на девяти» — мост врал этим с 18.09")
проверить("СРЕЗАНА на {coss3_map.ПОТОЛОК_ЗНАКА}" in ПОЛИТИКА,
          "потолок берётся из coss3_map, чтобы текст не отстал от блока")

print()
print("ошибок:", ошибок)
sys.exit(1 if ошибок else 0)
