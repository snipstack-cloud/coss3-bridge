# -*- coding: utf-8 -*-
"""Самопроверка связки 8: армия стоит не на том направлении.

Наблюдение игрока 20.09: «армия должна ставиться по направлению противника,
иначе в бой врывается меньшим составом и проигрывает». Бойцы стоят там, где
вышли из казарм, и когда враг приходит, дерётся ближайшая часть.

[замер] 35 тактов боя у своей базы: рядом с местом боя медиана 52 процента
армии, в 48 процентах тактов меньше половины, есть такты с НУЛЁМ из 70, 74, 76.
[замер] 553 такта девяти партий: связка срабатывает в 110.

Стережётся:
* без ключа молчим;
* когда армия УЖЕ на направлении угрозы (ближе двух клеток), молчим;
* мелкий отряд не повод дёргать армию — есть порог значимости;
* клетка встречи ставится У СВОИХ зданий, а не в клетке врага;
* названы и плата, и способ отменить сбор.
"""
import llm_policy as L
import coss3_map

беды = []


def проверка(имя, условие, пояснение=""):
    if условие:
        print("  ОК    " + имя)
    else:
        беды.append(имя)
        print("  ПЛОХО " + имя + (" — " + пояснение if пояснение else ""))


def состояние(враг_в=(3, 8), сколько=20, армия_в=(3, 12), свободных=40):
    """Наша ратуша в (3,12). Враг ставится в названную клетку."""
    n = 16
    ст = {"gametime": 700, "grid_n": n, "map_w": 256, "map_open": 1,
          "my_cx": 3, "my_cy": 12, "my_freewar": свободных,
          "my_army_cx": армия_в[0], "my_army_cy": армия_в[1],
          "peasants": 50, "mil_inf": свободных, "mil_shooters": 0, "mil_cav": 0,
          "ba17": 2, "mills": 1, "food": 9000, "gold": 3000,
          "p1_enemy": 1, "p1_army": max(сколько, 60)}
    for y in range(n):
        ряд = ["."] * n
        if y == враг_в[1]:
            ряд[враг_в[0]] = coss3_map.знак(сколько)
        ст[f"frow{y}"] = "".join(ряд)
        ст[f"arow{y}"] = "." * n
    return ст


def текст(ключ=1, **kw):
    L.ВСТРЕТИТЬ_УГРОЗУ = ключ
    ст = состояние(**kw)
    return "\n".join(L.встретить_угрозу(ст, ст))


проверка("без ключа молчим", текст(ключ=0) == "")

с = текст()
проверка("связка говорит, когда армия в стороне", с != "", "ожидали строку")
проверка("названо, где армия и откуда угроза",
         "(3,12)" in с and "(3,8)" in с, с[:170])
проверка("назван готовый STAGE", '"cmd":"STAGE"' in с, с[:250])
проверка("клетка встречи — У СВОИХ зданий, а не в клетке врага",
         '"cy":11' in с and '"cy":8' not in с.split("STAGE")[1][:40],
         "иначе сбор уводит армию прямо на врага")
проверка("названа причина числом про кулак и цепочку",
         "КОРНЮ из размена" in с and "52 процента" in с)
проверка("названа ПЛАТА", "плата:" in с and "ОДНОМ направлении" in с)
проверка("сказано, как отменить", '"off":1' in с)

# армия уже на направлении — молчим
проверка("армия рядом с угрозой — молчим",
         текст(армия_в=(3, 9)) == "", "иначе связка дёргает уже собранных")

# мелкий отряд — не повод
проверка("против мелкого отряда молчим",
         текст(сколько=6, свободных=40) == "", "порог значимости")
проверка("против крупного отряда говорим даже при малой армии",
         текст(сколько=30, свободных=12) != "")

# нет карты — нет чужих чисел
L.ЧЕСТНО = True
ст = состояние()
ст["map_open"] = 0
L.ВСТРЕТИТЬ_УГРОЗУ = 1
проверка("при закрытой карте молчим", L.встретить_угрозу(ст, ст) == [],
         "числа врага без карты брать нельзя")

проверка("при крошечной армии молчим", текст(свободных=4) == "")

print()
if беды:
    print(f"БЕД: {len(беды)} — {', '.join(беды)}")
    raise SystemExit(1)
print("всё чисто")
