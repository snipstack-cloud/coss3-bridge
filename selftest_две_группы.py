#!/usr/bin/env python3
"""ОБОРОНА ДВУМЯ ГРУППАМИ / КУЛАК У РАТУШИ (10.10, §143): состояния партии Д2 10:20-12:05
(`sim/кейсы/партия_д2_10_10_10_20-12_05.jsonl`). Вживую наши 48-55 стояли в (1,13)/(1,14) без приказа, его 67-78 пик
вошли к ним (33 наших за 6 его), его 38 прошли в клетку ратуши-мельницы (2,14) и убили 41 крестьянина за 15 с.

(а) 10:33, его 80 идут к базе, свободных 46, ключ `две_группы_заслон` 0,67: MOVE заслона 30 (группа 91) в клетку на шаг
    от ратуши навстречу и MOVE остальных (группа 92) в клетку ратуши; (б) то же с долей 0: один MOVE всех в клетку ратуши;
(в) 12:15: его 12 стрелков в (2,10) — четыре клетки от ратуши, отряд не бьёт; (г) синтетика: его 12 стрелков без пик в (2,12),
    отряд 92 из 18 у ратуши — ATTACK отряда в (2,12) по прогнозу; (д) клетка опустела — отряд MOVE назад к ратуше;
(е) без ключа — команд групп 91/92 нет.

    python3 selftest_две_группы.py
"""
import copy, json, os, sys, tempfile
К = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, К); sys.path.insert(0, os.path.join(К, "sim"))
import strategy_live as SL
import анализ_врага as АВ

состояния = [json.loads(l) for l in open(os.path.join(К, "sim/кейсы/партия_д2_10_10_10_20-12_05.jsonl"), encoding="utf-8")]
ошибок = 0
def проверить(усл, что):
    global ошибок
    print(("ОК   " if усл else "ОШИБКА ") + что)
    ошибок += not усл

def стратегия(доп):
    д = json.load(open(os.path.join(К, "sim/поиск/шт_s2_оборона_ручеёк_эко_так15_нужда.json"), encoding="utf-8"))
    д["итог"].update(доп)
    with tempfile.NamedTemporaryFile("w", suffix=".json", delete=False, encoding="utf-8") as f:
        json.dump(д, f, ensure_ascii=False)
    return SL.ЖиваяСтратегия(f.name)

def ответ(С, st):
    АВ._ТЕКУЩИЙ.update({"а": None, "t": None, "ответ": None})
    return С.ответ(copy.deepcopy(st))

def группы(о):
    return [(c["cmd"], c.get("count"), c.get("group"), c.get("cx"), c.get("cy")) for c in о["commands"] if c.get("group") in (91, 92)]

st_а = next(s for s in состояния if s["gametime"] >= 633)
st_в = next(s for s in состояния if s["gametime"] >= 735) if any(s["gametime"] >= 735 for s in состояния) else состояния[-1]
print(f"состояния: а {st_а['gametime']} с (свободных {st_а.get('my_freewar')}, его к базе), в {st_в['gametime']} с")

С = стратегия({"оборона_две_группы": 1, "две_группы_заслон": 0.67})
о = ответ(С, st_а)
г = группы(о)
проверить(any(c[0] == "MOVE" and c[2] == 91 and c[1] == 30 for c in г), f"(а) заслон 30 (группа 91) MOVE: {г}")
проверить(any(c[0] == "MOVE" and c[2] == 92 and c[1] == "all" and (c[3], c[4]) == (2, 14) for c in г), f"(а) отряд (группа 92) MOVE в клетку ратуши (2,14): {г}")
з = next((c for c in г if c[2] == 91), None)
проверить(з is not None and (з[3], з[4]) == (2, 13), f"(а) заслон в клетке на шаг навстречу (2,13): {з}")
проверить("ДВЕ ГРУППЫ" in str(о.get("why") or ""), f"(а) запись в why: {str(о.get('why'))[:160]}")

С0 = стратегия({"оборона_две_группы": 1, "две_группы_заслон": 0})
о = ответ(С0, st_а)
г = группы(о)
проверить(len(г) == 1 and г[0][0] == "MOVE" and г[0][2] == 92 and г[0][1] == "all" and (г[0][3], г[0][4]) == (2, 14),
          f"(б) доля 0: один MOVE всех в клетку ратуши: {г}")
проверить("КУЛАК У РАТУШИ" in str(о.get("why") or ""), f"(б) запись: {str(о.get('why'))[:120]}")

# (в) 12:15: его стрелки за 4 клетки — отряд стоит; группы 92 в состоянии нет (вживую её не ставили) — правило молчит
о = ответ(С, st_в)
проверить(not any(c[0] == "ATTACK" for c in группы(о)), f"(в) {st_в['gametime']} с: отряд не бьёт стрелков за 4 клетки: {группы(о)}")

# (г) синтетика: отряд 92 (18: 12 пик + 6 стрелков) у ратуши, его 12 стрелков без пик в (2,12), его пики далеко
st_г = copy.deepcopy(st_а)
st_г["gametime"] = st_а["gametime"] + 30
st_г["groups"] = [{"id": 92, "n": 18, "пик": 12, "стрелков": 6, "конных": 0, "cx": 2, "cy": 14, "режим": 2, "tx": -1, "ty": -1},
                  {"id": 91, "n": 30, "пик": 30, "стрелков": 0, "конных": 0, "cx": 2, "cy": 13, "режим": 2, "tx": -1, "ty": -1}]
st_г["ecells"] = [{"x": 2, "y": 12, "n": 12, "пик": 0, "стрелков": 12, "конных": 0, "идут": 0, "tx": -1, "ty": -1, "n18": 0},
                  {"x": 2, "y": 9, "n": 70, "пик": 70, "стрелков": 0, "конных": 0, "идут": 70, "tx": 1, "ty": 11, "n18": 0}]
о = ответ(С, st_г)
г = группы(о)
проверить(any(c[0] == "ATTACK" and c[2] == 92 and (c[3], c[4]) == (2, 12) for c in г), f"(г) отряд бьёт его 12 стрелков в (2,12): {г} | {[x for x in str(о.get('why')).split(' | ') if 'ДВЕ ГРУППЫ' in x or 'две группы' in x]}")
# (д) клетка опустела — отряд назад
st_д = copy.deepcopy(st_г); st_д["gametime"] += 20
st_д["ecells"] = [c for c in st_д["ecells"] if (c["x"], c["y"]) != (2, 12)]
о = ответ(С, st_д)
г = группы(о)
проверить(any(c[0] == "MOVE" and c[2] == 92 and (c[3], c[4]) == (2, 14) for c in г), f"(д) стрелков нет — отряд назад в клетку ратуши: {г}")

Сбез = стратегия({"оборона_две_группы": 0})
о = ответ(Сбез, st_а)
проверить(not группы(о), f"(е) без ключа команд групп 91/92 нет: {группы(о)}")
print(f"ошибок: {ошибок}")
sys.exit(1 if ошибок else 0)
