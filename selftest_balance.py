# -*- coding: utf-8 -*-
"""Самопроверка распределения BALANCE одной пачки (18.09).

Живая партия: пачка «еда 11, дерево 4, камень 4» при двенадцати на земле пять
минут гоняла крестьян по кругу — второй проход блока снимает людей с другого
ресурса. Теперь пачка урезается пропорционально до людей на земле и об этом
говорится модели; шахтные BALANCE не трогаются.
"""
import sys
import llm_policy as L
from coss3_bridge import balance, build

беды = []


def проверка(имя, условие, пояснение=""):
    if условие:
        print("  ОК   " + имя)
    else:
        беды.append(имя)
        print("  ПЛОХО " + имя + (" — " + пояснение if пояснение else ""))


def распр(cmds, **st):
    сост = dict(peasants=22, on_mine=10, on_build=0)
    сост.update(st)
    return L.распределить_balance(cmds, сост)


def карта(cmds):
    return {c.a1: c.a2 for c in cmds if c.cmd == "BALANCE"}


# 1. Пачка из живой партии: 11+4+4 = 19 при 12 на земле.
cmds, текст = распр([balance("food", 11), balance("wood", 4), balance("stone", 4)])
проверка("сумма урезана до земли", sum(карта(cmds).values()) == 12, str(карта(cmds)))
проверка("пропорция сохранена: еда больше всех, остаток ей", карта(cmds)[0] == 7 and карта(cmds)[1] + карта(cmds)[2] == 5, str(карта(cmds)))
проверка("сказано, сколько просили и сколько есть", "просит 19" in текст and "на земле 12" in текст, текст)
проверка("названо, до чего урезано", "урезано до" in текст)

# 2. Влезает — не трогаем и молчим.
cmds, текст = распр([balance("food", 6), balance("wood", 3), balance("stone", 3)])
проверка("в пределах земли — без изменений", карта(cmds) == {0: 6, 1: 3, 2: 3} and текст == "")

# 3. Шахтные BALANCE и прочие команды проходят как есть.
cmds, текст = распр([balance("gold", 10), balance("food", 20), build("smith", 1)])
проверка("золото не считается землёй", карта(cmds)[3] == 10, str(карта(cmds)))
проверка("еда урезана до всей земли", карта(cmds)[0] == 12)
проверка("BUILD на месте и порядок сохранён", [c.cmd for c in cmds] == ["BALANCE", "BALANCE", "BUILD"])

# 4. На земле никого — BALANCE снят целиком, причина названа.
cmds, текст = L.распределить_balance([balance("food", 8), build("mill", 1)],
                                     dict(peasants=10, on_mine=5, on_build=5))
проверка("на земле никого — BALANCE снят", карта(cmds) == {} and [c.cmd for c in cmds] == ["BUILD"])
проверка("сказано, что переставлять некого", "переставлять некого" in текст, текст)

# 5. Остаток округления уходит самому большому запросу, сумма сходится ровно.
cmds, текст = распр([balance("food", 7), balance("wood", 7), balance("stone", 7)], peasants=15, on_mine=5)
проверка("сумма ровно земля", sum(карта(cmds).values()) == 10, str(карта(cmds)))

# 6. Без BALANCE — ничего не делает.
cmds, текст = распр([build("mill", 1)])
проверка("без BALANCE молчит", текст == "" and [c.cmd for c in cmds] == ["BUILD"])

# 7. Запрос больше не обещает «сумма ничего не значит».
проверка("запрос не обещает, что сумма не важна", "сумма ничего не значит" not in (L.SYSTEM + L.SYSTEM_HUMAN))
проверка("запрос говорит, что пачка делит одних людей", "ДЕЛЯТ ОДНИХ И ТЕХ ЖЕ" in (L.SYSTEM + L.SYSTEM_HUMAN))

print()
print(f"ПРОВАЛОВ: {len(беды)}")
sys.exit(1 if беды else 0)
