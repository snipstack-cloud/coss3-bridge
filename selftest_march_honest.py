# -*- coding: utf-8 -*-
"""Марш-контракт пишет честные числа рядом с лживыми.

Повод, 25.09 (Windows, счёт по 109 тактам с контрактом в base27/base28/tier1,
разборы/МАРШ_КОНТРАКТ.md). Два поля контракта лгут, и оба читались как «сколько
людей в колонне»:

    послано   в base27/3 растёт 39 -> 2916 при живой армии 100: каждое
              примыкание к сбору его увеличивает (примкнуть_к_маршу), то есть
              это НАКОПИТЕЛЬНЫЙ счётчик, а не размер колонны;
    в_пути    это wave_n, ВСЕ свои вдали от базы, а не колонна: больше
              «послано» в 23 тактах из 27 у tier1 (40 против 99 у base28/4).

Переименовать их нельзя: «послано» читает sim/gate_move.py, «в_пути» и «надо» —
факты.py. Поэтому рядом пишутся три честных поля.

ЧЕГО ЭТА ПРАВКА НЕ ДЕЛАЕТ: она не меняет ПОВЕДЕНИЕ. Порог сбора по-прежнему
считается от накопленного «послано» (надо = 2/3 * послано, откуда 1944 при
армии 100 — и порог взят 1 раз из 55 тактов). Лечится это ключом
`--gather-share`, который уже есть и считает базу как min(послано, армия);
оставлять поведение как было — нарочно, правки поведения в master молча не
кладут.

Что проверяется:
  1. три честных поля пишутся в контракт;
  2. «в_колонне» не больше живой армии и не больше «послано»;
  3. «лишних_вдали» — это в_пути минус колонна, и оно не отрицательное;
  4. «послано» и «в_пути» НЕ переименованы — инструменты мака не сломаны;
  5. порог и второй выход по-прежнему считаются от «послано» (поведение цело),
     и про второй выход сказано вслух, что --gather-share его НЕ чинит.
"""
import io, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

ошибок = 0


def проверить(условие, что):
    global ошибок
    if not условие:
        ошибок += 1
        print("  СБОЙ:", что)
    else:
        print("  ок:", что)


ЗДЕСЬ = os.path.dirname(os.path.abspath(__file__))
И = io.open(os.path.join(ЗДЕСЬ, "llm_policy.py"), encoding="utf-8").read()

print("1. три честных поля пишутся в контракт")
for поле in ("живая_армия=_жив", "в_колонне=_в_колонне", "лишних_вдали=max(0,"):
    проверить(поле in И, "пишется " + поле.split("=")[0])

print()
print("2. в_колонне не больше ни армии, ни послано")
проверить('_в_колонне = min(МАРШ["послано"], _жив) if _жив else МАРШ["послано"]' in И,
          "в_колонне = min(послано, живая армия)")
# арифметика на числах, без игры
for послано, жив in ((2916, 100), (40, 149), (21, 21), (63, 64), (8, 0)):
    вк = min(послано, жив) if жив else послано
    проверить(вк <= послано and (not жив or вк <= жив),
              "послано %-5d армия %-4d -> в колонне %d" % (послано, жив, вк))

print()
print("3. лишних_вдали не отрицательное")
for впути, вк in ((99, 40), (21, 21), (0, 63), (85, 64)):
    проверить(max(0, впути - вк) >= 0,
              "в пути %-3d колонна %-3d -> лишних %d" % (впути, вк, max(0, впути - вк)))

print()
print("4. лживые поля НЕ переименованы — инструменты мака целы")
проверить('в_пути=в_пути' in И, "«в_пути» на месте")
проверить('МАРШ["послано"]' in И, "«послано» на месте")
для_мака = io.open(os.path.join(ЗДЕСЬ, "sim", "gate_move.py"), encoding="utf-8").read()
проверить('m.get("послано")' in для_мака, "sim/gate_move.py по-прежнему находит «послано»")
факты = io.open(os.path.join(ЗДЕСЬ, "факты.py"), encoding="utf-8").read()
проверить('m.get("в_пути")' in факты, "факты.py по-прежнему находит «в_пути»")

print()
print("5. ПОВЕДЕНИЕ не тронуто, и про второй выход сказано вслух")
проверить('надо = max(1, int(ДОЛЯ_СБОРА * МАРШ["послано"]))' in И,
          "порог по умолчанию по-прежнему от накопленного «послано»")
проверить('иссяк = в_пути <= 2 and дошло > 0 and дошло * 2 >= МАРШ["послано"]' in И,
          "второй выход по-прежнему от «послано»")
проверить("чинит первый выход, но НЕ этот" in И,
          "сказано вслух, что --gather-share второй выход не чинит")

print()
print("6. честные числа ДОЕЗЖАЮТ до разбора, иначе поля немые")
проверить('{k: v for k, v in МАРШ.items() if k != "отчёт"}' in И,
          "контракт целиком идёт в трассу — новые поля туда попадают сами")
проверить('m.get("в_колонне")' in факты and 'm.get("лишних_вдали")' in факты,
          "факты.py читает оба честных поля")
проверить("НЕ из этой колонны" in факты,
          "лишние бойцы вдали называются словами")
проверить("на старых трассах их нет" in факты,
          "на старых трассах строка остаётся прежней, и это сказано")

print()
print("ошибок:", ошибок)
sys.exit(1 if ошибок else 0)
