# -*- coding: utf-8 -*-
"""Потери по клеткам: СЧЁТЧИК говорит сколько, клетки говорят где (27.09).

Раскладка потерь жила в python и умела только «точно при ОДНОЙ клетке контакта» —
а это затишье: 105 «точных» тактов трёх партий и ни одного погибшего в них, 302
пустых такта из 514 по архиву. Мера была механической и мерила дефект, не идею.

Почему разность клеток врала. Она приписывала смерть КАЖДОМУ убавлению в клетке, а
маршевая колонна из шестидесяти пересекает границы непрерывно: при стороне клетки
16 единиц это порядка десяти ложных «смертей» в секунду, тысячи за партию против
двух сотен настоящих.

Почему теперь не врёт. Блок спрашивает СНАЧАЛА картовый счётчик (`my_mil_lost` =
`gPlayer.stat.killed`): сколько погибло — он знает точно. Если счётчик не двинулся,
никакие убавления не рассматриваются вовсе, и марш в счёт не попадает. Если
двинулся — этот бюджет раскладывается по клеткам, где убыло, причём клеткам с его
бойцами в первую очередь. Сумма ограничена счётчиком и уехать не может.

ТУПИК, КОТОРЫЙ СТОИЛ ЖИВОЙ ПАРТИИ, и он записан тут нарочно. Первый замысел
спрашивал, жив ли запомненный ХЭНДЛ (`GetGameObjectStateMachineHandle <> 0`), и не
приписал НИ ОДНОЙ смерти: счётчик шёл 1-2-6, а раскладка оставалась `none`. Труп
уходит из списка объектов игрока раньше, чем умирает его машина состояний: на
следующей секунде бойца уже не обходят (значит не перезаписывают), а хэндл ещё
отвечает «жив» — и через такт память о нём стирала очистка.

МЕРА. Прежняя — «сумма против счётчика в пределах десяти процентов» — с этим
устройством верна ПО ПОСТРОЕНИЮ и потому не проверяет ничего. Мерится:
* `сходится` — сумма плюс неопознанные равны счётчику точно (сторож кода);
* `доля_без_клетки` — какая часть смертей не легла ни в одну клетку. Это и есть
  качество поля.

Здесь стережётся всё, на чём правка может провалиться молча:
* ИМЕНА полей — как их пишет блок. За 27.09 пять раз ошибка была в имени, а не в
  замысле, и молчаливый ложный ноль стоил серии;
* ПОРЯДОК: раскладка идёт ПОСЛЕ обхода объектов (до него сетка `hmown` не собрана),
  а память прошлой секунды перезаписывается ПОСЛЕ того, как по ней посчитали;
* ЧТЕНИЕ ТОЛЬКО ПО КЛЮЧУ: ни `ParserGetCountByHandle`, ни `ParserGetKeyName`, ни
  `StrToInt` от имени ключа — именно эта часть в мосту ничем не проверена, и
  первый замысел мог провалиться ещё и из-за неё;
* бюджет не может уйти в минус, а остаток называется вслух полем `lost_cells_odd`:
  молчаливый отброс неотличим от бездействия.
"""
import io
import os

import coss3_map as M
import llm_policy as L

беды = []


def проверка(имя, условие, пояснение=""):
    if условие:
        print("  ОК    " + имя)
    else:
        беды.append(имя)
        print("  ПЛОХО " + имя + (" — " + str(пояснение)[:300] if пояснение else ""))


ЗДЕСЬ = os.path.dirname(os.path.abspath(__file__))
БЛОК = io.open(os.path.join(ЗДЕСЬ, "block_hstate.inc"), encoding="utf-8").read()
МОК = io.open(os.path.join(ЗДЕСЬ, "mock_human.py"), encoding="utf-8").read()
ПОЛИТИКА = io.open(os.path.join(ЗДЕСЬ, "llm_policy.py"), encoding="utf-8").read()
ИНСТРУМЕНТ = io.open(os.path.join(ЗДЕСЬ, "мера_потерь.py"), encoding="utf-8").read()

# --- 1. ИМЕНА полей: ровно то, что пишет блок ------------------------------
for поле, вызов in (
        ("lost_cells", "ParserSetValueByKeyByHandle(hsp, 'lost_cells', hslcs);"),
        ("lost_cells_n", "ParserSetIntValueByKeyByHandle(hsp, 'lost_cells_n', hslcn);"),
        ("lost_cells_sum", "ParserSetIntValueByKeyByHandle(hsp, 'lost_cells_sum', hslsum);"),
        ("lost_cells_odd", "ParserSetIntValueByKeyByHandle(hsp, 'lost_cells_odd', hslodd);"),
        ("lost_cells_more", "ParserSetIntValueByKeyByHandle(hsp, 'lost_cells_more', hslmore);")):
    проверка(f"блок пишет {поле}", вызов in БЛОК, вызов)

проверка("в блоке нет кириллицы", not any(ord(c) > 127 for c in БЛОК))

# --- 2. БЮДЖЕТ берётся со счётчика, а не с клеток --------------------------
проверка("бюджет секунды — разность картового счётчика",
         "var hsldie : Integer = hslm - ParserGetIntValueByKeyByHandle(hslpv, 'lost')"
         in БЛОК,
         "hslm — то же число, что уходит в my_mil_lost")
проверка("бюджет не уходит в минус",
         "if (hsldie < 0) then" in БЛОК and "hsldie := 0;" in БЛОК)
проверка("клетки смотрят ТОЛЬКО когда счётчик двинулся",
         "if (hsldie > 0) then" in БЛОК,
         "иначе марш колонны дал бы тысячи ложных смертей")
проверка("клетка берёт не больше остатка бюджета",
         "if (hsltake > hsldie) then" in БЛОК and "hsltake := hsldie;" in БЛОК)
проверка("остаток назван вслух, а не отброшен",
         "hslodd := hslodd + hsldie;" in БЛОК
         and "ParserSetIntValueByKeyByHandle(hslac, 'odd', hslodd);" in БЛОК)
# Порядок двух проходов — не украшение: без него порядок обхода сетки решал бы,
# какой клетке достанутся чужие смерти.
# ТРИ прохода после первой живой проверки: контакт с убылью, контакт без убыли,
# убыль без контакта. Убавление первичным признаком быть не может — из десяти
# смертей оно положило одну, и ту в тыл (2,2), откуда люди просто ушли.
проверка("контакт первым, убыль вторым — три прохода",
         "for hslpass := 0 to 2 do" in БЛОК
         and "if (hslpass = 0) and (hmforce[hmi][hmj] > 0) and (hsldrop > 0) then" in БЛОК
         and "if (hslpass = 1) and (hmforce[hmi][hmj] > 0) and (hsldrop <= 0) then" in БЛОК
         and "if (hslpass = 2) and (hmforce[hmi][hmj] = 0) and (hsldrop > 0) then" in БЛОК)
проверка("контактная клетка без убыли берёт не больше стоящих в ней",
         "hslcap := hmown[hmi][hmj];" in БЛОК)

# --- 3. ПОРЯДОК внутри такта ----------------------------------------------
_обход = БЛОК.index("hmown[hmoxx][hmoyy] := hmown[hmoxx][hmoyy] + 1;")
_бюджет = БЛОК.index("var hsldie : Integer")
_память = БЛОК.index("ParserClearByHandle(hslpv);", _бюджет)
_счёт_в_память = БЛОК.index("ParserSetIntValueByKeyByHandle(hslpv, 'lost', hslm);")
_выдача = БЛОК.index("'lost_cells'")
проверка("бюджет снимается ПОСЛЕ обхода объектов", _обход < _бюджет,
         "до обхода сетка hmown ещё не собрана")
проверка("память прошлой секунды перезаписывается ПОСЛЕ раскладки",
         _бюджет < _память, "иначе считать было бы нечем")
проверка("счётчик кладётся в память ПОСЛЕ очистки", _память < _счёт_в_память,
         "иначе очистка стёрла бы его же")
проверка("выдача поля — последней", _счёт_в_память < _выдача)
проверка("в память пишутся только занятые клетки",
         "if (hmown[hmi][hmj] > 0) then" in БЛОК)

# --- 4. ТОЛЬКО ПО КЛЮЧУ: непроверенных вызовов в новом коде нет ------------
_новое = БЛОК[БЛОК.index("var hslpv : Integer"):]
for опасное in ("ParserGetCountByHandle", "ParserSelectByHandleByIndex",
                "ParserGetKeyName", "StrToInt"):
    проверка(f"в новом коде нет {опасное}", опасное not in _новое,
             "перебор парсера в этом мосту ничем не проверен")
проверка("склады заводятся так же, как часы блока",
         "ParserSelectByKey('br_lprev')" in БЛОК and "ParserCreate('br_lprev')" in БЛОК
         and "ParserSelectByKey('br_lost')" in БЛОК and "ParserCreate('br_lost')" in БЛОК)
проверка("новая партия чистит оба склада",
         "if (hsnow < hslast) then" in БЛОК
         and "ParserClearByHandle(hslac);" in БЛОК)
# Объявления: скаляры, накапливающие в цикле, живут на уровне блока. Гейт сеток —
# ПОСЛЕДНИЙ из двух с таким отступом (первый закрывает экономику), и искать его надо
# кодом: в пояснениях блока эта строка тоже встречается.
_ГЕЙТ = БЛОК.rindex("      [*] = ;         if (hscen > 0) then")
проверка("строка-накопитель объявлена выше гейта сеток",
         БЛОК.index("var hslcs : String;") < _ГЕЙТ,
         "скаляр во вложенном begin читается нулём при 208 бойцах")

# --- 5. Разбор поля в python ----------------------------------------------
клетки = M.потери_клеток({"lost_cells": "3,4,7;10,2,1"})
проверка("разбор: две клетки с числами",
         [(к["x"], к["y"], к["погибло"]) for к in клетки] == [(3, 4, 7), (10, 2, 1)],
         клетки)
проверка("none — это пусто", M.потери_клеток({"lost_cells": "none"}) == [])
проверка("нет поля — тоже пусто", M.потери_клеток({}) == [])
проверка("«нет поля» отличимо от «нет потерь»",
         M.есть_потери_клеток({"lost_cells": "none"}) is True
         and M.есть_потери_клеток({}) is False)
проверка("мусорная часть не роняет разбор",
         M.потери_клеток({"lost_cells": "3,4;5,6,2;x,y,z"}) ==
         [{"x": 5, "y": 6, "погибло": 2}])

# --- 6. МЕРА: сходимость отдельно, качество отдельно ----------------------
хорошо = M.мера_потерь_по_клеткам(
    {"lost_cells": "3,4,7;10,2,3", "lost_cells_sum": 100, "lost_cells_odd": 5,
     "my_mil_lost": 105})
проверка("сходится и качество хорошее",
         хорошо and хорошо["сходится"] is True and хорошо["качество"] is True, хорошо)
плохо = M.мера_потерь_по_клеткам(
    {"lost_cells": "3,4,7", "lost_cells_sum": 60, "lost_cells_odd": 40,
     "my_mil_lost": 100})
проверка("сходится, но качество плохое",
         плохо and плохо["сходится"] is True and плохо["качество"] is False
         and abs(плохо["доля_без_клетки"] - 0.4) < 1e-9, плохо)
кривое = M.мера_потерь_по_клеткам(
    {"lost_cells": "3,4,7", "lost_cells_sum": 50, "lost_cells_odd": 10,
     "my_mil_lost": 100})
проверка("расхождение суммы со счётчиком — это ОШИБКА КОДА, и она видна",
         кривое and кривое["сходится"] is False, кривое)
проверка("нет поля — мера молчит, а не осуждает",
         M.мера_потерь_по_клеткам({"my_mil_lost": 100}) is None)
ноль = M.мера_потерь_по_клеткам(
    {"lost_cells": "none", "lost_cells_sum": 0, "lost_cells_odd": 0, "my_mil_lost": 0})
проверка("никто не погиб — мера не спорит",
         ноль and ноль["сходится"] is True and ноль["качество"] is True, ноль)

# --- 7. Инструмент: приговор различает сходимость и качество --------------
import importlib.util as _iu

