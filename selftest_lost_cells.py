# -*- coding: utf-8 -*-
"""Потери по клеткам, приписанные БЛОКОМ по хэндлу (поле `lost_cells`, 27.09).

Зачем правка в `.inc`, если раскладка уже есть в python. Та считает УБЫЛЬ —
разность чисел в клетке между двумя снимками, — и потому не отличает погибшего от
ушедшего. Снимок берётся раз в пять секунд, а за пять секунд боец меняет клетку
легко; хуже того, маршевая колонна из шестидесяти пересекает границы клеток
непрерывно: при стороне клетки 16 единиц это порядка десяти ложных «смертей» в
секунду, тысячи за партию против двух сотен настоящих. Поэтому признак `точно`
поднимался лишь при ОДНОЙ клетке контакта — а это затишье: в разборе боя 105
«точных» тактов и ни одного погибшего в них, в архиве 302 пустых такта из 514.

Довод за блок — РАЗРЕШЕНИЕ, а не удобство: блок видит клетки каждую игровую
секунду, и за секунду боец из клетки почти не уходит. Больше того, разность там не
нужна вовсе: клетка приписана ХЭНДЛУ. Кто стоял в клетке секунду назад и у кого
больше нет машины состояний — тот погиб, и движение в счёт не входит.

МЕРА, НАЗВАННАЯ ДО ПРАВКИ: сумма смертей по клеткам сходится с картовым счётчиком
`my_mil_lost` в пределах десяти процентов за партию. Сравнение честное по
построению — блок отбирает бойца в сетку по списку ролей `hmof`, а счётчик
складывает `gPlayer.stat.killed` ровно по тем же ролям.

Здесь стережётся всё, на чём эта правка может провалиться молча:
* ИМЕНА полей — как их пишет блок. За 27.09 пять раз ошибка была в имени, а не в
  замысле, и молчаливый ложный ноль стоил серии;
* ПОРЯДОК внутри такта: проход смерти по прошлому содержимому идёт ДО очистки, а
  очистка — ДО записи живых. Иначе память затирается прежде, чем прочитана;
* тихая проверка живости хэндла: `_unit_GetTObj` на мёртвом хэндле пишет в
  `ErrorLog`, и это двести строк в секунду;
* накопление в блоке, а не «за такт»: python читает каждое пятое состояние, и
  поле «за секунду» терялось бы в четырёх непрочитанных;
* сумма БЕЗ потолка, строка с потолком: урезанная сумма сделала бы меру
  бессмысленной, а урезание строки названо вслух полем `lost_cells_more`.
"""
import io
import os

import coss3_map as M
import llm_policy as L

беды = []


def проверка(имя, условие, пояснение=""):
    if условие:
        print("  ОК    " + имя)
    else:
        беды.append(имя)
        print("  ПЛОХО " + имя + (" — " + str(пояснение)[:300] if пояснение else ""))


ЗДЕСЬ = os.path.dirname(os.path.abspath(__file__))
БЛОК = io.open(os.path.join(ЗДЕСЬ, "block_hstate.inc"), encoding="utf-8").read()
МОК = io.open(os.path.join(ЗДЕСЬ, "mock_human.py"), encoding="utf-8").read()
ПОЛИТИКА = io.open(os.path.join(ЗДЕСЬ, "llm_policy.py"), encoding="utf-8").read()

# --- 1. ИМЕНА полей: ровно то, что пишет блок ------------------------------
for поле, вызов in (("lost_cells", "ParserSetValueByKeyByHandle(hsp, 'lost_cells', hslcs);"),
                    ("lost_cells_n", "ParserSetIntValueByKeyByHandle(hsp, 'lost_cells_n', hslcn);"),
                    ("lost_cells_sum", "ParserSetIntValueByKeyByHandle(hsp, 'lost_cells_sum', hslsum);"),
                    ("lost_cells_more", "ParserSetIntValueByKeyByHandle(hsp, 'lost_cells_more', hslmore);")):
    проверка(f"блок пишет {поле}", вызов in БЛОК, вызов)

проверка("в блоке нет кириллицы", not any(ord(c) > 127 for c in БЛОК))

# --- 2. СКЛАД: два парсера, живущие между тактами ---------------------------
проверка("склад прошлой секунды заводится как br_hstate",
         "var hslsn : Integer = ParserSelectByKey('br_lseen');" in БЛОК
         and "hslsn := ParserCreate('br_lseen');" in БЛОК)
проверка("накопитель за партию заводится так же",
         "var hslst : Integer = ParserSelectByKey('br_lost');" in БЛОК
         and "hslst := ParserCreate('br_lost');" in БЛОК)
# Вторая партия в том же процессе: часы упали назад — склад обязан сброситься,
# иначе потери первой партии доедут во вторую и мера соврёт на обеих.
проверка("новая партия чистит оба склада",
         "if (hsnow < hslast) then" in БЛОК
         and "ParserClearByHandle(hslsn);" in БЛОК
         and "ParserClearByHandle(hslst);" in БЛОК)

# --- 3. ПОРЯДОК внутри такта: в нём весь замысел ----------------------------
_проход = БЛОК.index("var hslalive : Boolean = False;")
_очистка = БЛОК.rindex("ParserClearByHandle(hslsn);")
_запись = БЛОК.index("ParserSetIntValueByKeyByHandle(hslsn, IntToStr(hmog),")
_выдача = БЛОК.index("'lost_cells'")
проверка("проход смерти ДО очистки склада", _проход < _очистка)
проверка("очистка склада ДО записи живых", _очистка < _запись)
проверка("запись живых ДО выдачи поля наружу", _запись < _выдача)
# Объявление раньше использования — форма, которая уже кладала тик.
проверка("hslsn объявлен раньше, чем в него пишут",
         БЛОК.index("var hslsn : Integer") < _запись)
# Гейт ищем КОДОМ, а не любым вхождением строки: в блоке она сначала встречается
# в ПОЯСНЕНИИ (`block_hstate.inc:34`), и первая версия этой проверки поймала
# комментарий вместо гейта — та же ловушка, что описана в selftest_mapsize.
# Гейтов с этим отступом ДВА — экономика (`:368`) и сетки (`:1370`), — и нужен
# ПОСЛЕДНИЙ: раскладка живёт в секции сеток. Первая версия проверки брала первый и
# объявляла беду на верном коде.
_ГЕЙТ = "      [*] = ;         if (hscen > 0) then"
_ГЕЙТ_СЕТОК = БЛОК.rindex(_ГЕЙТ)
проверка("гейт секции сеток стоит ПЕРЕД складом — раскладка внутри секции",
         _ГЕЙТ_СЕТОК < БЛОК.index("var hslsn : Integer"))
проверка("строка-накопитель объявлена на уровне блока, а не во вложенном begin",
         БЛОК.index("var hslcs : String;") < _ГЕЙТ_СЕТОК,
         "скаляр, накапливающий в цикле, во вложенном begin читается нулём")

# --- 4. ТИХАЯ проверка живости ---------------------------------------------
проверка("живость хэндла проверяется идиомой игры",
         "if (GetGameObjectStateMachineHandle(hslh) <> 0) then" in БЛОК)
# Область — ИМЕННО проход смерти: дальше по файлу `_unit_GetTObj` живёт законно,
# там хэндлы взяты обходом живых объектов и мёртвых среди них нет.
_проход_смерти = БЛОК[БЛОК.index("var hsli : Integer"):
                      БЛОК.rindex("ParserClearByHandle(hslsn);")]
проверка("в проходе смерти нет ВЫЗОВА _unit_GetTObj (он пишет в ErrorLog)",
         "_unit_GetTObj(" not in _проход_смерти,
         "ищем вызов со скобкой: само имя стоит в предупреждающем комментарии")
проверка("и предупреждение о нём в проходе записано",
         "_unit_GetTObj must NOT be used here" in _проход_смерти)
проверка("проход смерти вообще найден", len(_проход_смерти) > 200)
проверка("нулевой хэндл в движок не уходит",
         "if (hslh <> 0) then" in БЛОК)

# --- 5. Клетка хранится со сдвигом: ноль не должен читаться как «нет» -------
проверка("клетка пишется как код+1",
         "hmoxx*cHmGrid + hmoyy + 1);" in БЛОК)
проверка("и читается со сдвигом назад",
         "var hslck : String = IntToStr(hslv-1);" in БЛОК)
проверка("пустое значение отброшено", "if (hslv > 0) then" in БЛОК)

# --- 6. Разбор поля в python ----------------------------------------------
клетки = M.потери_клеток({"lost_cells": "3,4,7;10,2,1"})
проверка("разбор: две клетки с числами",
         [(к["x"], к["y"], к["погибло"]) for к in клетки] == [(3, 4, 7), (10, 2, 1)],
         клетки)
проверка("none — это пусто", M.потери_клеток({"lost_cells": "none"}) == [])
проверка("нет поля — тоже пусто", M.потери_клеток({}) == [])
# И РАЗЛИЧАТЬ ЭТО ОБЯЗАТЕЛЬНО: «потерь не было» и «моста с полем нет» — разные
# вещи, и путать их значит хоронить правку из-за старой записи.
проверка("«нет поля» отличимо от «нет потерь»",
         M.есть_потери_клеток({"lost_cells": "none"}) is True
         and M.есть_потери_клеток({}) is False)
проверка("мусорная часть не роняет разбор",
         M.потери_клеток({"lost_cells": "3,4;5,6,2;x,y,z"}) ==
         [{"x": 5, "y": 6, "погибло": 2}])

# --- 7. МЕРА: сумма против картового счётчика ------------------------------
сошлось = M.мера_потерь_по_клеткам(
    {"lost_cells": "3,4,7;10,2,3", "lost_cells_sum": 100, "my_mil_lost": 95})
проверка("расхождение в 5 процентов — сошлось",
         сошлось and сошлось["сошлось"] is True, сошлось)
не_сошлось = M.мера_потерь_по_клеткам(
    {"lost_cells": "3,4,7", "lost_cells_sum": 130, "my_mil_lost": 100})
проверка("расхождение в 30 процентов — не сошлось",
         не_сошлось and не_сошлось["сошлось"] is False, не_сошлось)
проверка("знак расхождения виден: завышение отличимо от занижения",
         не_сошлось["расхождение"] == 30 and не_сошлось["доля"] == 0.3)
# Нет поля — НЕ приговор: старые записи не должны читаться как провал меры.
проверка("нет поля — мера молчит, а не осуждает",
         M.мера_потерь_по_клеткам({"my_mil_lost": 100}) is None)
ноль = M.мера_потерь_по_клеткам(
    {"lost_cells": "none", "lost_cells_sum": 0, "my_mil_lost": 0})
проверка("никто не погиб — мера сошлась", ноль and ноль["сошлось"] is True, ноль)
пусто_при_счётчике = M.мера_потерь_по_клеткам(
    {"lost_cells": "none", "lost_cells_sum": 0, "my_mil_lost": 40})
проверка("счётчик есть, раскладки нет — это провал, а не тишина",
         пусто_при_счётчике and пусто_при_счётчике["сошлось"] is False)

# --- 8. Обвязка: снимок ---------------------------------------------------
for поле in ("lost_cells_sum", "lost_cells_n", "lost_cells_more"):
    проверка(f"{поле} в белом списке снимка", поле in L.ПОЛЯ_СНИМКА)
проверка("раскладка идёт в снимок РАЗОБРАННОЙ, а не строкой",
         'строка["потери_клетки"] = [[к["x"], к["y"], к["погибло"]] for к in _потери]'
         in ПОЛИТИКА,
         "через _число строка проехала бы нулём")
проверка("строку в белый список не положили",
         "lost_cells\"," not in str(L.ПОЛЯ_СНИМКА) and "lost_cells" not in L.ПОЛЯ_СНИМКА)

# --- 9. Обвязка: мок врёт в ту же сторону ---------------------------------
проверка("мок отдаёт lost_cells", 'd["lost_cells"] = ' in МОК)
проверка("мок отдаёт сумму и потолок",
         'd["lost_cells_sum"] = sum(self.потери_клетки.values())' in МОК
         and 'd["lost_cells_more"] = max(0, len(_потери) - 24)' in МОК)
проверка("у мока счётчик равен сумме по клеткам",
         '"my_mil_lost": self.мил_потери,' in МОК,
         "иначе мера проверялась бы на несогласованных числах")

# --- 10. Петля на моке целиком: поле доезжает и мера на нём сходится ------
import mock_human as МОКМОД

мок = МОКМОД.Мир(ЗДЕСЬ, plind=1)
мок.волна = 20
for _ in range(40):
    мок.тик(5.0)
ст = мок.сетки()
ст["my_mil_lost"] = мок.мил_потери
клетки = M.потери_клеток(ст)
проверка("на моке раскладка непуста после похода", bool(клетки), ст.get("lost_cells"))
мера = M.мера_потерь_по_клеткам(ст)
проверка("на моке сумма сходится со счётчиком", мера and мера["сошлось"] is True, мера)
проверка("сумма по клеткам равна сумме поля",
         sum(к["погибло"] for к in клетки) == мера["сумма"], (клетки, мера))

print()
if беды:
    print(f"ПЛОХО: {len(беды)} — " + "; ".join(беды))
    raise SystemExit(1)
print("все проверки прошли")
