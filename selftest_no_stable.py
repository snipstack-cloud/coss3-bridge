# -*- coding: utf-8 -*-
"""Ключ --no-stable: в 15-минутной партии ни конюшни, ни драгун (игрок, 28.09).

Исключение — ОБА условия сразу: у него конницы 5+ и больше нашей вдвое, И у нас
золота 1500+. Числа: казарма 500, военный апгрейд 150-300.
"""
import llm_policy as L

ошибок = []
такт = lambda **кв: dict({"gold": 800, "p1_cav": 0, "mil_cav": 0,
                          "centers": 1, "smiths": 1, "ba17": 1}, **кв)

L.БЕЗ_КОНЮШНИ = False
if L.конюшню_нельзя(такт()) is not None:
    ошибок.append("выключенный ключ вмешался")

L.БЕЗ_КОНЮШНИ = True
# 1. обычный случай — нельзя, и сказано почему
нет = L.конюшню_нельзя(такт())
if нет is None:
    ошибок.append("без исключений конюшня должна быть запрещена")
else:
    for ч in ("--no-stable", "500", "1500"):
        if ч not in нет:
            ошибок.append(f"в отказе нет «{ч}»")
# 2. только перевес конницы, золота мало — всё равно нельзя (нужны ОБА)
if L.конюшню_нельзя(такт(p1_cav=12, gold=800)) is None:
    ошибок.append("одного перевеса конницы не хватает — нужны оба условия")
# 3. только золото, конницы у него нет — нельзя
if L.конюшню_нельзя(такт(gold=3000)) is None:
    ошибок.append("одного золота не хватает — нужны оба условия")
# 4. ОБА условия — можно
if L.конюшню_нельзя(такт(p1_cav=12, mil_cav=2, gold=1600)) is not None:
    ошибок.append("при обоих исключениях конюшня разрешена")
# 5. его конницы 5, но наша 3 — не «вдвое больше», нельзя
if L.конюшню_нельзя(такт(p1_cav=5, mil_cav=3, gold=2000)) is None:
    ошибок.append("перевес считается как «больше нашей вдвое»")
# 6. драгун зовётся своим словом в отказе
нет = L.конюшню_нельзя(такт(), "dragoon")
if нет is None or "ДРАГУН" not in нет:
    ошибок.append("отказ по драгуну обязан называть драгуна")
# 7. и конюшня своим
нет = L.конюшню_нельзя(такт(), "stable")
if нет is None or "КОНЮШНЯ" not in нет:
    ошибок.append("отказ по конюшне обязан называть конюшню")
L.БЕЗ_КОНЮШНИ = False

print("selftest_no_stable: " + ("ОК, 7 проверок" if not ошибок
                                else "ОШИБКИ\n  " + "\n  ".join(ошибок)))
raise SystemExit(1 if ошибок else 0)
