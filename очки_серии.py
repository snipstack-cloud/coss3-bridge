# -*- coding: utf-8 -*-
"""Очки движка по живой серии — то, чем решается ничья на 15-й минуте (28.09).

Правило (world.md, `unit.script:3841, 3948`, `miscext2.script:445`): за каждого
созданного очки растут, за потерянного падают, за убитого чужого дают ДВОЙНЫЕ его
очки; ЗАПАСЫ РЕСУРСОВ НЕ СЧИТАЮТСЯ. Отсюда текущий счёт равен сумме ЖИВОГО плюс
двойная цена убитого у противника.

Очки: ратуша 1000, казарма 500, академия 500, дом 100, крестьянин 20, пикинёр 10,
мушкетёр 20, драгун 50. ЧЕГО НЕ ЗНАЕМ: цены мельницы, кузницы, склада и шахт —
они не измерены, и в счёт не идут ни нам, ни ему (у обоих их примерно столько же,
так что перекос мал, но он есть, и это сказано вслух).
"""
import json, os, sys

ОЧКИ_ЗДАНИЙ = {"centers": 1000, "ba17": 500, "ba18": 500, "academies": 500, "houses": 100}
ОЧКИ_БОЙЦОВ = {"mil_inf": 10, "mil_shooters": 20, "mil_cav": 50}
ОЧКИ_ЕГО_ЗДАНИЙ = {"p1_center": 1000, "p1_ba17": 500, "p1_ba18": 500,
                   "p1_academi": 500, "p1_house": 100}
ОЧКИ_ЕГО_БОЙЦОВ = {"p1_inf": 10, "p1_shoot": 20, "p1_cav": 50}
ОЧКИ_КРЕСТЬЯНИНА = 20


def снимки(к):
    из = []
    with open(os.path.join(к, "coss3_snap.jsonl"), encoding="utf-8", errors="replace") as f:
        for x in f:
            x = x.strip()
            if not x:
                continue
            try:
                s = json.loads(x)
            except Exception:
                continue
            s = s.get("state", s)
            if "gametime" in s:
                из.append(s)
    return из


def ч(s, k):
    return float((s or {}).get(k) or 0)


def счёт(к, до=900.0):
    """(наш счёт, его счёт, подробности) на игровой секунде `до`."""
    L = снимки(к)
    if not L:
        return None
    с = L[0]
    for x in L:
        if x["gametime"] <= до:
            с = x
    наш_живое = sum(ч(с, k) * v for k, v in ОЧКИ_ЗДАНИЙ.items())
    наш_живое += sum(ч(с, k) * v for k, v in ОЧКИ_БОЙЦОВ.items())
    наш_живое += ч(с, "peasants") * ОЧКИ_КРЕСТЬЯНИНА
    его_живое = sum(ч(с, k) * v for k, v in ОЧКИ_ЕГО_ЗДАНИЙ.items())
    его_живое += sum(ч(с, k) * v for k, v in ОЧКИ_ЕГО_БОЙЦОВ.items())
    его_живое += ч(с, "p1_peasants") * ОЧКИ_КРЕСТЬЯНИНА
    # УБИТОЕ: разность накопительных счётчиков от начала партии
    его_бойцов_убито = ч(с, "p1_mil_lost") - ч(L[0], "p1_mil_lost")
    его_крестьян_убито = ч(с, "p1_pea_lost") - ч(L[0], "p1_pea_lost")
    наших_бойцов_убито = ч(с, "my_mil_lost") - ч(L[0], "my_mil_lost")
    наших_крестьян_убито = ч(с, "my_pea_lost") - ч(L[0], "my_pea_lost")
    # цена его убитого бойца — по его нынешнему составу, иначе взяли бы пикинёра
    его_всего = sum(ч(с, k) for k in ОЧКИ_ЕГО_БОЙЦОВ)
    цена_его = (sum(ч(с, k) * v for k, v in ОЧКИ_ЕГО_БОЙЦОВ.items()) / его_всего
                if его_всего > 0 else 10.0)
    наш_всего = sum(ч(с, k) for k in ОЧКИ_БОЙЦОВ)
    цена_наш = (sum(ч(с, k) * v for k, v in ОЧКИ_БОЙЦОВ.items()) / наш_всего
                if наш_всего > 0 else 10.0)
    наш = наш_живое + 2 * (его_бойцов_убито * цена_его
                           + его_крестьян_убито * ОЧКИ_КРЕСТЬЯНИНА)
    его = его_живое + 2 * (наших_бойцов_убито * цена_наш
                           + наших_крестьян_убито * ОЧКИ_КРЕСТЬЯНИНА)
    return наш, его, dict(наш_живое=наш_живое, его_живое=его_живое,
                          его_убито_бц=его_бойцов_убито, его_убито_кр=его_крестьян_убито,
                          наших_убито_бц=наших_бойцов_убито,
                          наших_убито_кр=наших_крестьян_убито,
                          цена_его=цена_его, цена_наш=цена_наш, до=до)


if __name__ == "__main__":
    до = 900.0
    корни = [a for a in sys.argv[1:] if not a.startswith("--")]
    for a in sys.argv[1:]:
        if a.startswith("--до"):
            до = float(a.split("=")[1])
    print("ОЧКИ НА %d-й СЕКУНДЕ (ничья решается ими)" % до)
    print("%-22s %9s %9s %9s %26s" % ("серия/копия", "наш", "его", "разница", "чем он взял (2× наши потери)"))
    for корень in корни:
        имя = os.path.basename(корень.rstrip("/"))
        for c in sorted(os.listdir(корень)):
            d = os.path.join(корень, c)
            if not os.path.isdir(d) or not os.path.exists(os.path.join(d, "coss3_snap.jsonl")):
                continue
            из = счёт(d, до)
            if из is None:
                continue
            наш, его, п = из
            print("%-22s %9.0f %9.0f %+9.0f %26.0f"
                  % (имя + "/" + c, наш, его, наш - его,
                     2 * (п["наших_убито_бц"] * п["цена_наш"] + п["наших_убито_кр"] * ОЧКИ_КРЕСТЬЯНИНА)))
