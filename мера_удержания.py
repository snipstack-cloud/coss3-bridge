#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""МЕРА «УДЕРЖАНИЕ СТРОЯ ДОЕХАЛО» на живой игре (5.10, §102).

Меры названы маком ДО правки, здесь они только исполняются:

  1. группа 15-20 бойцов + `FACE` с удержанием на его сторону; стратегия рядом
     каждый такт отдаёт приказы ПО СВОБОДНЫМ — группа должна стоять в своей
     клетке шесть тактов подряд, и в логе не должно быть ни одного взятия её
     бойцов. Наоборот, должны появиться строки «skipped N holding soldiers»;
  2. `my_freewar` падает на число держащих — иначе `ATTACK count=all` разобрал бы
     тот самый строй, которому велели держать;
  3. `ATTACK` ПО НОМЕРУ ГРУППЫ снимает удержание: в логе `hold released by`,
     режим группы меняется, группа уходит;
  4. СТРЕЛЯЮТ ЛИ ДЕРЖАЩИЕ СТРЕЛКИ — главный вопрос мака. Мерится событиями
     гибели: убийца наш, класс `S`, оружие `U` (пуля), клетка убийцы — клетка
     держащей группы. По коду движка (`unit.script:8416-8425`) держащий сам
     ищет жертву в радиусе атаки и бьёт, так что ждём «да»;
  5. пики в удержании: те же события с классом убийцы `I` в её клетке.

Запускается рядом с идущей партией. Лог игры лежит в каталоге сохранений
(`Documents/cossacks/log/cos_*.log`), и `LogFileEnabled = false` его НЕ отключает.
"""
from __future__ import annotations
import argparse
import glob
import os
import sys
import time

for _s in (sys.stdout, sys.stderr):
    try:
        _s.reconfigure(encoding="utf-8", errors="replace")
    except Exception:
        pass

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from coss3_bridge import Bridge
import coss3_map as M

ИГРА = r"C:\Program Files (x86)\Steam\steamapps\common\Cossacks 3"
ЛОГИ = os.path.expanduser(r"~\OneDrive\Documents\cossacks\log")
ПРОТУХ = 60.0


def сказать(текст, журнал):
    строка = time.strftime("%H:%M:%S ") + текст
    print(строка, flush=True)
    журнал.write(строка + "\n")
    журнал.flush()


def лог_игры():
    ф = sorted(glob.glob(os.path.join(ЛОГИ, "cos_*.log")), key=os.path.getmtime)
    return ф[-1] if ф else None


def строки_моста(путь, с_байта=0):
    if not путь or not os.path.exists(путь):
        return [], с_байта
    with open(путь, "rb") as ф:
        ф.seek(с_байта)
        кусок = ф.read()
        конец = ф.tell()
    из = [с.strip() for с in кусок.decode("latin-1", "replace").splitlines()
          if "bridge-human:" in с]
    return из, конец


def состояние(br, журнал, прошлое=None):
    """Свежайшее состояние; None — партия встала. Два разных «пусто»: read_state
    молчит, когда файл не изменился, и это не беда."""
    возраст = br.возраст_состояния()
    if возраст is None or возраст > ПРОТУХ:
        сказать(f"состояние ПРОТУХЛО (возраст {возраст}) — партия стоит или "
                f"окно не в фокусе", журнал)
        return None
    новое = br.read_state()
    return новое if новое else (прошлое if прошлое else {})


def группы(st):
    return {int(г.get("id") or 0): г for г in M.наши_группы(st)}


def отдать(br, приказ, журнал, попыток=40):
    for _ in range(попыток):
        if br.attack_many([приказ]):
            сказать(f"ОТДАН {приказ}", журнал)
            до = time.time() + 25
            while time.time() < до and os.path.exists(br.atk_path):
                time.sleep(0.4)
            взят = not os.path.exists(br.atk_path)
            сказать("  файл забран игрой" if взят else "  файл НЕ забран", журнал)
            return взят
        time.sleep(1.5)
    сказать(f"НЕ ОТДАН (файл занят стратегией): {приказ}", журнал)
    return False


def main() -> int:
    ap = argparse.ArgumentParser(description="мера удержания строя (§102)")
    ap.add_argument("--dir", default=ИГРА)
    ap.add_argument("--plind", type=int, default=0)
    ap.add_argument("--отчёт", default="мера_удержания.log")
    ap.add_argument("--в-поле", type=int, default=12,
                    help="сколько бойцов в поле ждать перед FACE")
    ap.add_argument("--тактов", type=int, default=8,
                    help="сколько тактов смотреть, стоит ли группа")
    a = ap.parse_args()

    br = Bridge(a.dir, plind=a.plind)
    путь = лог_игры()
    with open(a.отчёт, "w", encoding="utf-8", newline="") as ж:
        сказать("МЕРА §102: удержание строя, живая игра", ж)
        сказать(f"лог игры: {путь}", ж)
        _, край = строки_моста(путь)

        st = состояние(br, ж) or {}
        if not st:
            return 1
        дом = M.дом_клетка(st)
        б = M.база_врага(st) or {}
        if дом is None or not б:
            сказать(f"нет ратуши ({дом}) или базы врага ({б})", ж)
            return 1
        сказать(f"ратуша {дом}, его база ({б['cx']},{б['cy']})", ж)

        # Ждём бойцов В ПОЛЕ: FACE берёт их, а свободных стратегия не копит.
        до = time.time() + 600
        последнее = st
        while time.time() < до:
            st = состояние(br, ж, последнее)
            if st is None:
                return 1
            if st:
                последнее = st
                if int(float(st.get("mil_away") or 0)) >= a.в_поле:
                    break
            time.sleep(3)
        st = последнее
        сказать(f"в поле {st.get('mil_away')}, свободных {st.get('my_freewar')}, "
                f"gt={st.get('gametime')}", ж)
        своб_до = int(float(st.get("my_freewar") or 0))

        # 1. FACE с удержанием на его базу.
        if not отдать(br, {"count": 200, "target": "home", "mode": "face",
                           "group": 7, "face": [int(б["cx"]), int(б["cy"])],
                           "hold": 1}, ж):
            return 1
        time.sleep(5)
        нов, край = строки_моста(путь, край)
        for с in нов:
            сказать("  ЛОГ " + с, ж)
        st = состояние(br, ж, последнее) or последнее
        г = группы(st).get(7) or {}
        держат = int(г.get("n") or 0)
        клетка = (г.get("cx"), г.get("cy"))
        сказать(f"ГРУППА 7: n={держат} в {клетка} режим {г.get('режим')} "
                f"(4 = держит); свободных было {своб_до}, стало "
                f"{st.get('my_freewar')}", ж)

        # 2. Стоит ли она, пока стратегия отдаёт свои приказы.
        места, свои_убийства = [], []
        видел = set()
        for такт in range(a.тактов):
            time.sleep(7)
            st = состояние(br, ж, последнее)
            if st is None:
                break
            if st:
                последнее = st
            г = группы(st).get(7) or {}
            места.append((г.get("cx"), г.get("cy"), г.get("n"), г.get("режим")))
            сказать(f"  такт {такт+1}: группа 7 n={г.get('n')} в "
                    f"({г.get('cx')},{г.get('cy')}) режим {г.get('режим')}, "
                    f"свободных {st.get('my_freewar')}, в поле {st.get('mil_away')}", ж)
            # События гибели: кто убил, чем и из какой клетки.
            for е in M.события_гибели(st):
                _к = int(е.get("seq") or -1)
                if _к in видел:
                    continue
                видел.add(_к)
                if int(е.get("убийца_pl", -1)) == a.plind:
                    свои_убийства.append(е)
            нов, край = строки_моста(путь, край)
            for с in нов:
                if "FACE" in с or "holding" in с or "hold" in с or "GROUP" in с:
                    сказать("  ЛОГ " + с, ж)

        # 3. Что вышло.
        # «СТОЯЛА» — НЕ «ярлык клетки не менялся». Среднее тринадцати бойцов
        # ложится на границу клеток, и ярлык мигает между соседними, хотя строй
        # не идёт никуда: в первом прогоне вышло (8,8) четыре такта и (8,9)
        # четыре, и прежний критерий назвал это уходом. Считаем по Чебышёву от
        # ПЕРВОЙ клетки: ушла — значит дальше одной клетки. Плюс состав: у
        # держащей группы он не должен убывать от чужих приказов.
        _клетки = [(м[0], м[1]) for м in места if м[0] is not None]
        _ушла = any(max(abs(к[0] - _клетки[0][0]), abs(к[1] - _клетки[0][1])) > 1
                    for к in _клетки) if _клетки else False
        _состав = [м[2] for м in места if м[2] is not None]
        _разобрали = bool(_состав) and min(_состав) < держат
        стояла = (not _ушла) and (not _разобрали)
        сказать("", ж)
        сказать(f"СТОЯЛА НА МЕСТЕ: {'ДА' if стояла else 'НЕТ'} — клетки по тактам "
                f"{_клетки}, ушла дальше клетки: {_ушла}, состав убывал: "
                f"{_разобрали} (держали {держат}, минимум {min(_состав) if _состав else '-'})", ж)
        в_клетке = [е for е in свои_убийства
                    if (е.get("kx"), е.get("ky")) == (клетка[0], клетка[1])]
        стрелки = [е for е in в_клетке if е.get("убийца") == "S"]
        пики = [е for е in в_клетке if е.get("убийца") == "I"]
        сказать(f"НАШИХ УБИЙСТВ всего {len(свои_убийства)}, из клетки держащей "
                f"группы {len(в_клетке)}: стрелками {len(стрелки)}, пиками "
                f"{len(пики)}", ж)
        if стрелки:
            сказать(f"  ДЕРЖАЩИЕ СТРЕЛКИ СТРЕЛЯЮТ: {стрелки[:4]}", ж)
        if пики:
            сказать(f"  ДЕРЖАЩИЕ ПИКИ БЬЮТСЯ: {пики[:4]}", ж)

        # 4. Снятие удержания приказом по номеру.
        if not отдать(br, {"count": 0, "target": "cell", "mode": "",
                           "cx": int(б["cx"]), "cy": int(б["cy"]), "group": 7}, ж):
            return 1
        time.sleep(6)
        нов, край = строки_моста(путь, край)
        for с in нов:
            сказать("  ЛОГ " + с, ж)
        for _ in range(4):
            time.sleep(7)
            st = состояние(br, ж, последнее) or последнее
            г = группы(st).get(7) or {}
            сказать(f"  после приказа: n={г.get('n')} в ({г.get('cx')},"
                    f"{г.get('cy')}) режим {г.get('режим')} — держала {клетка}", ж)
        сказать("", ж)
        сказать(f"ИТОГ: держали {держат}, стояла на месте "
                f"{'ДА' if стояла else 'НЕТ'}, убийств из её клетки "
                f"{len(в_клетке)} (стрелками {len(стрелки)})", ж)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
