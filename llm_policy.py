def compare(client, models: list[str], think: bool, probes: int, every: int) -> int:
    """Гоняем один и тот же запрос по моделям и печатаем таблицу. Решает не
    средняя скорость, а худший вызов: он и определяет, слепнет ли цикл."""
    budget = every / 1.38
    rows = []
    for model in models:
        waits, toks, bad, why = [], [], 0, ""
        for _ in range(probes):
            t = time.time()
            try:
                ask(client, model, "Время 0:30. Ресурсов нет, крестьян 20. "
                                   "Что строить первым? Ответь JSON.", think, retry=0)
                waits.append(time.time() - t)
                toks.append(LAST_TOKENS)
            except Exception as e:
                bad += 1
                waits.append(time.time() - t)
                why = why or str(e).replace("\n", " ")[:100]
                if waits[-1] < 3:           # мгновенный отказ повторять незачем
                    bad = probes
                    break
        worst = max(waits) if waits else 0.0
        avg_tok = sum(toks) // len(toks) if toks else 0
        rows.append((model, worst, avg_tok, bad))
        print(f"  {model:44s} худшая {worst:6.1f} с  {avg_tok:5d} ток  "
              f"сбоев {bad}/{probes}")
        if why:
            print(f"      причина: {why}")
    print(f"\nбюджет такта при 1,38× и --every {every}: {budget:.0f} с")
    годные = [r for r in rows if r[3] == 0 and r[1] < budget]
    if not годные:
        print("в такт не встала ни одна — модели место вне партии (роль L2)")
        return 1
    годные.sort(key=lambda r: r[1])
    print("годятся в такт, от быстрой к медленной:")
    for m, w, t, _ in годные:
        print(f"  {m}  ({w:.1f} с, {t} токенов)")
    print(f"\nставьте её так: python llm_policy.py --model {годные[0][0]}")
    return 0


