def поля_из_текста(текст: str) -> dict:
    """Четыре поля критика из текста, даже если JSON битый.

    Модель отвечает коротко и по схеме, но иногда ставит лишнее вокруг скобок
    или кавычку внутри строки — и json.loads отказывается. Сам ответ при этом
    полезен, а второй вызов стоит денег и времени.
    """
    из = {}
    for ключ in ("причина", "узкое_место", "гипотеза", "как_проверить"):
        м = re.search(rf'"{ключ}"\s*:\s*"(.*?)"\s*[,}}\n]', текст, re.S)
        if not м:
            м = re.search(rf'"{ключ}"\s*:\s*"([^"]*)', текст, re.S)
        if м:
            з = " ".join(м.group(1).split())
            if з:
                из[ключ] = з
    return из


def разбор_партии(a, client, номер: int, итог: str, дневник) -> str:
    """Критик: один вызов после партии. Возвращает записанное или пусто.

    Зачем отдельной ролью, а не полем в такте: в бою модель занята ходом, и
    выводы у неё получаются про последний такт. Здесь она видит партию целиком
    и не платит за это задержкой — партия уже кончилась.
    """
    if not a.critic:
        return ""
    строки = дневник.строки() if дневник else []
    if not строки and not ТРАССА_ПАРТИИ:
        print("        разбор не делаю: ни дневника, ни трассы (нужен --memo)")
        return ""
    # 15.09: критику давали ТОЛЬКО дневник, и он пять раз из девяти написал «не
    # видно из данных», а в остальных случаях достроил недостающее сам —
    # предлагал строить лесопилку и каменоломню, которых в игре нет. Теперь он
    # получает то же, что видим мы: такты с ресурсами и людьми, и уроки, которые
    # модель писала по ходу партии.
    части = [f"# Партия {номер}, исход: {итог}"]
    if строки:
        части += ["", "## Дневник партии", *строки]
    if ТРАССА_ПАРТИИ:
        части += ["", "## Такты партии (ресурсы, люди, здания, команды)",
                  *ТРАССА_ПАРТИИ]
    if УРОКИ_ПАРТИИ:
        части += ["", "## Что модель заметила по ходу партии", *УРОКИ_ПАРТИИ]
    запрос = "\n".join(части)
    ответ = {}
    try:
        прежний = SYSTEM
        globals()["SYSTEM"] = SYSTEM_CRITIC
        try:
            ответ = ask(client, a.model, запрос, a.think, retry=1,
                        max_tokens=3000)
        finally:
            globals()["SYSTEM"] = прежний
    except Exception as e:
        # JSON не собрался — но разбор это не такт, терять его жалко. Ответ
        # критика короткий (замер 14.09: 417 символов), и поля из него
        # вытаскиваются построчно даже когда скобки битые: лишний текст вокруг,
        # кавычка внутри строки, оборванный хвост.
        сырое = str(e)
        ответ = поля_из_текста(сырое)
        if ответ:
            print("        JSON критика битый — разобрал по полям")
        else:
            print(f"        разбор не удался: {сырое[:400]}")
            return ""
    if not ответ:
        print("        разбор пуст: модель не вернула разбираемого JSON")
        return ""
    куски = [f"## Партия {номер}: {итог}"]
    for ключ, подпись in (("причина", "Причина"), ("узкое_место", "Узкое место"),
                          ("гипотеза", "Гипотеза"), ("как_проверить", "Как проверить")):
        з = str(ответ.get(ключ, "") or "").strip()
        if з:
            куски.append(f"* **{подпись}:** {з}")
    if len(куски) == 1:
        print("        разбор пуст: модель не заполнила поля")
        return ""
    текст = "\n".join(куски)
    print("\n".join("        " + с for с in текст.splitlines()))
    try:
        with open(a.critic, "a", encoding="utf-8") as f:
            f.write(текст + "\n\n")
    except OSError as e:
        print(f"        разбор не записан ({e})")
    return текст


def показать_счёт(explicit: str = "") -> int:
    """Остаток на счету OpenRouter. Своя ручка, не через OpenAI-клиент.

    Без этого 402 виден только как строка ошибки внутри сбоя вызова, а в бою
    это выглядит как «модель молчит»: 11.09.2026 половина замера ушла в 402,
    и по счётчику сбоёв было не отличить деньги от лимита провайдера.
    """
    import urllib.request
    key, src = load_key(explicit)
    if not key:
        print("нет ключа")
        return 1
    if "openrouter" not in BASE_URL:
        print(f"счёт умеет показывать только OpenRouter, а адрес {BASE_URL}")
        return 1
    req = urllib.request.Request(BASE_URL.rsplit("/v1", 1)[0] + "/v1/credits",
                                 headers={"Authorization": f"Bearer {key}"})
    try:
        d = json.load(urllib.request.urlopen(req, timeout=20))["data"]
    except Exception as e:
        print(f"счёт не отдался: {str(e)[:120]}")
        return 1
    куплено = float(d.get("total_credits", 0))
    потрачено = float(d.get("total_usage", 0))
    print(f"ключ из {src}\nкуплено ${куплено:.2f}, потрачено ${потрачено:.2f}, "
          f"ОСТАТОК ${куплено - потрачено:.2f}")
    if куплено - потрачено < 1:
        print("  меньше доллара — дорогая модель начнёт отвечать 402 уже сейчас:\n"
              "  запрос отвергается, если возможная цена ответа больше остатка")
    return 0


def предпросмотр_подсказок(a) -> int:
    """Что из подсказок реально уйдёт в модель — по звеньям цепочки.

    Между файлом и моделью стоит фильтр: строки с # отбрасываются, а строка с
    меткой звена исчезает, когда звено пройдено. Поэтому «файл изменился» и
    «модель это увидела» — не одно и то же, и вот это их и разводит.
    """
    сырое = load_hints(a.hints)
    print(f"файл {a.hints}: {len(сырое)} символов, {len(сырое.splitlines())} строк\n")
    d = os.path.expandvars(a.dir)
    plind = a.plind if a.plind is not None else find_ai_plind(d, human=a.human)
    живое = None
    if plind is not None:
        живое = Bridge(d, plind).read_state()
    if живое:
        показ = [("сейчас в партии", живое)]
    else:
        print("живой партии нет — показываю для типовых состояний\n")
        показ = [
            ("голый старт", {"peasants": 5, "smiths": 0, "ba17": 0}),
            ("кузница есть", {"peasants": 20, "smiths": 1, "ba17": 0}),
            ("казарма есть", {"peasants": 20, "smiths": 1, "ba17": 1}),
            ("армия и волна", {"peasants": 20, "smiths": 1, "ba17": 1,
                               "mil_inf": 5, "my_armies": 1}),
        ]
    for имя, st in показ:
        текст = отобрать_подсказки(сырое, st)
        цепь = " ".join(("+" if ok else "-") + n for n, ok, _ in stages(st))
        print(f"=== {имя}: {цепь}")
        print(f"    {len(текст)} симв., ~{len(текст) // 3} токенов")
        for стр in текст.splitlines():
            print(f"    | {стр}")
        print()
    отброшено = [l.strip() for l in сырое.splitlines() if l.strip().startswith("#")]
    if отброшено:
        print(f"строк с # отброшено: {len(отброшено)} — в модель они не идут")
    плохие = неизвестные_метки(сырое)
    if плохие:
        print(f"\nВНИМАНИЕ: метки не из списка звеньев: {', '.join(sorted(set(плохие)))}")
        print(f"  звенья только эти: {', '.join(ЗВЕНЬЯ)}")
        print("  строка с чужой меткой видна ВСЕГДА и не исчезнет по ходу партии")
    # Подсказка, помеченная звеном, которое пройдено уже на старте, не дойдёт
    # до модели НИ РАЗУ. Это записано в шапке hints_human.txt с 12.09, и на
    # этом успели споткнуться дважды — поэтому предпросмотр обязан сказать сам,
    # а не полагаться на то, что кто-то помнит.
    НИКОГДА = {"экономика": "звено проходится при peasants>=15, "
                            "а партия начинается с 18"}
    беда = []
    for строка in load_hints(a.hints).splitlines():
        м = re.match(r"\s*\[([^\]]+)\]", строка)
        if м and м.group(1).strip().lower() in НИКОГДА:
            беда.append((м.group(1).strip().lower(), строка.strip()[:70]))
    if беда:
        print()
        print("!" * 60)
        print("ЭТИ СТРОКИ НЕ ДОЙДУТ ДО МОДЕЛИ НИ РАЗУ:")
        for метка, текст in беда:
            print(f"  [{метка}] {текст}")
            print(f"      {НИКОГДА[метка]}")
        print("Снимите метку, если строка нужна всегда.")
        print("!" * 60)
    return 0


def поднять_окно(log: str) -> None:
    """Запускает overlay.ps1 отдельным процессом. Он читает наш лог, так что
    переживает и смену эпизода, и перезапуск скрипта."""
    здесь = os.path.dirname(os.path.abspath(__file__))
    скрипт = os.path.join(здесь, "overlay.ps1")
    if os.name != "nt":
        print(f"окно поверх игры — только Windows; здесь запустите вручную:\n"
              f"        powershell -ExecutionPolicy Bypass -File {скрипт}")
        return
    if not os.path.exists(скрипт):
        print(f"не нашёл {скрипт} — окно не поднял")
        return
    if not log:
        print("окно нечего показывать: --log пустой")
        return
    try:
        subprocess.Popen(
            ["powershell", "-ExecutionPolicy", "Bypass", "-File", скрипт,
             "-Log", os.path.abspath(log), "-ClickThrough"],
            creationflags=getattr(subprocess, "CREATE_NEW_CONSOLE", 0))
        print("окно поверх игры поднято (клики сквозь него уходят в игру)")
    except Exception as e:
        print(f"окно не поднялось ({e}) — запустите overlay.ps1 руками")


