def неизвестные_метки(текст: str) -> list[str]:
    """Метки, которых нет среди звеньев. Такая строка видна ВСЕГДА, а автор
    рассчитывал, что она исчезнет — молчать об этом нельзя."""
    плохие = []
    for строка in текст.splitlines():
        s = строка.strip()
        if not s or s.startswith("#"):
            continue
        m = re.match(r"^\[([^\]]+)\]", s)
        if m and m.group(1).strip().lower() not in ЗВЕНЬЯ:
            плохие.append(m.group(1).strip())
    return плохие


def отобрать_подсказки(текст: str, st: dict) -> str:
    """Оставляем только то, что относится к ещё не пройденным звеньям.

    Подсказки уходят в КАЖДЫЙ вызов, так что файл нельзя растить бесконечно:
    это и деньги, и задержка, и потеря внимания модели к середине списка.
    Строка может начинаться с метки звена — [кузница], [казарма], [армия],
    [волна], [экономика]. Такая строка исчезает из промпта, как только звено
    пройдено: советы про постройку кузницы бессмысленны, когда она стоит.
    Строки без метки видны всегда. Строки с # — пояснения для человека, в
    промпт не попадают: документация не должна стоить денег в каждом вызове.
    """
    закрыто = {имя.lower() for имя, ok, _ in stages(st) if ok}
    # Что именно отброшено — наружу, а не молча. 12.09 подсказка с меткой
    # [экономика] не дошла до модели НИ РАЗУ: звено считается пройденным при
    # peasants>=15, а партия начинается с 18. Человек об этом не знал.
    отброшенные_метки.clear()
    оставили = []
    # Подсказка может не влезть в строку. Метка стоит только в первой, и раньше
    # продолжение жило своей жизнью: первую строку отбрасывало по звену, а
    # «хвост» оставался в промпте обрывком. Продолжение — строка с отступом.
    прошлая_отброшена = False
    for строка in текст.splitlines():
        s = строка.strip()
        if not s or s.startswith("#"):
            continue                        # # — пояснение для человека, не для модели
        продолжение = строка[:1].isspace()
        if продолжение and прошлая_отброшена:
            continue                        # хвост уходит вслед за своей головой
        m = re.match(r"^\[([^\]]+)\]\s*(.*)$", s)
        if not m:
            if not продолжение:
                прошлая_отброшена = False
            оставили.append(s)
            continue
        метка, тело = m.group(1).strip().lower(), m.group(2).strip()
        прошлая_отброшена = метка in закрыто
        if прошлая_отброшена:
            отброшенные_метки.add(метка)
            continue                        # звено пройдено — подсказка не нужна
        оставили.append(тело or s)
    return "\n".join(оставили)


