def load_world(path: str) -> str:
    """Файл мира -> готовый раздел промпта. Нет файла — пустая строка.

    Читается ДВА файла и склеивается: мастер рядом со скриптом (он приезжает из
    git и держит знания) и рабочий в /io (в нём копятся вопросы этой серии).
    Иначе получается то, что вышло 13.09 дважды подряд: рабочий файл от прошлого
    прогона уже лежал в томе, посев не делался — и знания из git не доезжали
    вовсе, а в логе стояло безобидное «0 строк знания».

    Читается перед каждым решением, как и подсказки: отвечать на вопрос модели
    удобно, не останавливая партию. Только локальные файлы, без ссылок.
    """
    if not path:
        return ""
    текст = _прочесть(path)
    мастер = _мастер_мира()
    if os.path.abspath(мастер) != os.path.abspath(path):
        текст = _прочесть(мастер) + "\n" + текст
    return мир_для_промпта(текст)


def подготовить_мир(path: str) -> None:
    """Посев файла мира из мастера рядом со скриптом.

    В контейнере клон моста одноразовый: что модель туда запишет, сгинет вместе
    с контейнером. Поэтому играть надо на файле в /io — он уезжает в результаты
    вместе с трассой. Но начальное знание лежит в git, рядом со скриптом, и
    копировать его руками в entrypoint нельзя: скрипты контейнера запечены в
    образ и из git не обновляются. Значит сеем отсюда.
    """
