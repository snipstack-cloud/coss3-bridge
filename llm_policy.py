TRANSIENT = ("500", "502", "503", "504", "timed out", "timeout",
            "connection", "overloaded", "too many requests", "429")


def think_worker(box: dict, client, model: str, prompt: str, think: bool,
                 tries: int = 3, spare: str = "") -> None:
    """Зовёт модель в фоне. Цикл тем временем живёт своей жизнью.

    500-е и таймаумы у бесплатного тира — обычное дело. Раз вызов не держит
    цикл, повтор бесплатен: пробуем несколько раз с паузой, и такт пропадает
    только если провайдер лежит целиком.
    """
    box["log"] = []
    очередь = [model] + ([spare] if spare else [])
    попытка = 0
    for кто in очередь:
        for n in range(tries):
            попытка += 1
            t = time.time()
            try:
                box["data"] = ask(client, кто, prompt, think)
                box["ready"] = time.time()   # когда ОТВЕТ готов, а не когда его забрали
                # Кто обслужил и сколько написал: у OpenRouter один и тот же id
                # уходит к разным провайдерам, и медленный вызов — обычно не
                # «модель думала», а «попали не к тому». Глобальные LAST_* к
                # моменту печати успевает затереть следующий вызов, поэтому
                # снимаем их здесь.
                box["provider"], box["tokens"] = LAST_PROVIDER, LAST_TOKENS
                box["tries"] = попытка
                box["model"] = кто
                return
            except Exception as e:
                msg = str(e).lower()
                box["err"] = e
                box["tries"] = попытка
                врем = any(w in msg for w in TRANSIENT)
                лимит = "429" in msg or "rate-limit" in msg
                box["log"].append(
                    f"{попытка}) {кто.split('/')[-1]}, {time.time() - t:.0f} с, "
                    f"{'лимит' if лимит else 'временная' if врем else 'НЕ временная'}: "
                    f"{str(e)[:160]}")
                if not врем:
                    return                  # не наша беда, ни повтор, ни замена не спасут
                if n + 1 >= tries:
                    break                   # эта модель не отвечает — пробуем запасную
                # Лимит провайдера полутора секундами не пересидеть: он общий
                # на всех и держится десятками секунд. Вызов в фоне, ждать дёшево.
                time.sleep((6.0 if лимит else 1.5) * (n + 1))


class Tee:
    """Пишем и в консоль, и в файл — overlay.ps1 показывает хвост этого файла.

    Строка уходит в файл сразу (buffering=1): окно поверх игры должно видеть
    решение в тот же миг, что и консоль, иначе смысла в нём нет.
    """

    def __init__(self, поток, path: str):
        self.поток = поток
        # Прежний лог не затираем, а отодвигаем в сторону. 11.09.2026 один
        # `--check` во время боя стёр лог партии целиком: файл открывался на
        # "w", а лог — единственная запись того, что делала модель.
        try:
            if os.path.getsize(path) > 0:
                метка = time.strftime("%m-%d_%H%M", time.localtime(os.path.getmtime(path)))
                корень, хвост = os.path.splitext(path)
                os.replace(path, f"{корень}.{метка}{хвост}")
        except OSError:
            pass                            # нет файла или не переименовать — не беда
        self.файл = open(path, "w", encoding="utf-8", buffering=1)

    def write(self, s: str) -> int:
        self.поток.write(s)
        try:
            self.файл.write(s)
        except Exception:
            pass                            # лог не должен ронять партию
        return len(s)

    def flush(self) -> None:
        self.поток.flush()
        try:
            self.файл.flush()
        except Exception:
            pass

    def isatty(self) -> bool:
        return False


def раскодировать(сырое: bytes) -> str:
    """Байты подсказок -> текст, какой бы редактор их ни сохранил.

    Файл правят и на маке, и на Windows: PowerShell при `>` пишет UTF-16LE,
    старые редакторы — CP1251, «Блокнот» умеет добавить BOM. Несовпадение
    кодировки не должно ронять партию, поэтому перебираем по очереди, а в
    самом конце декодируем с заменой — пусть лучше кракозябры, чем падение.
    """
    for bom, кодировка in ((b"\xef\xbb\xbf", "utf-8-sig"),
                           (b"\xff\xfe", "utf-16"),
                           (b"\xfe\xff", "utf-16")):
        if сырое.startswith(bom):
            try:
                return сырое.decode(кодировка).strip()
            except UnicodeDecodeError:
                break
    for кодировка in ("utf-8", "cp1251"):
        try:
            return сырое.decode(кодировка).strip()
        except UnicodeDecodeError:
            continue
    return сырое.decode("utf-8", "replace").strip()


_ПОДСКАЗКИ = {"текст": "", "когда": 0.0, "откуда": ""}


# Строки, дописанные ключом --hint-add. Живут глобально, потому что подсказки
# перечитываются из файла на каждом такте, а дописка должна переживать это.
ДОПИСКИ: list[str] = []


def _подсказки_из_файла(path: str, max_age: float = 10.0) -> str:
    """Подсказки из файла или по ссылке.

    Ссылка нужна, чтобы править их с другой машины: игра идёт на Windows, а
    редактировать удобнее с макбука. Сеть тут на горячем пути — промпт
    собирается в главном цикле, — поэтому таймаут короткий, ответ кешируется
    на max_age секунд, а при любой беде берётся последний удачный текст.
    Партия важнее свежести подсказок.
    """
    if path.startswith(("http://", "https://")):
        now = time.time()
        if _ПОДСКАЗКИ["откуда"] == path and now - _ПОДСКАЗКИ["когда"] < max_age:
            return _ПОДСКАЗКИ["текст"]
        try:
            import urllib.request
            with urllib.request.urlopen(path, timeout=3) as r:
                текст = раскодировать(r.read())
            _ПОДСКАЗКИ.update(текст=текст, когда=now, откуда=path)
            return текст
        except Exception:
            _ПОДСКАЗКИ["когда"] = now      # не долбить сеть каждый такт
            return _ПОДСКАЗКИ["текст"]
    try:
        сырое = open(path, "rb").read()
    except OSError:
        return ""
    return раскодировать(сырое)



def load_hints(path: str, max_age: float = 10.0) -> str:
    """Подсказки из файла плюс дописки ключа --hint-add.

    Дописка — это способ проверить идею КАК ЗНАНИЕ: модель узнаёт о
    возможности и решает сама, вместо того чтобы мост подменял её команду.
    13.09 игрок указал, что подмена нечестна — модель отдала BUILDERS 3,
    увидела мир, где ратуша встала втрое быстрее, и рассуждала дальше о том,
    чего не делала.
    """
    текст = _подсказки_из_файла(path, max_age)
    if ДОПИСКИ:
        текст = текст.rstrip("\n") + "\n" + "\n".join(ДОПИСКИ) + "\n"
    return текст

