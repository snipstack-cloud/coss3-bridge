# --- Канал вопросов: модель спрашивает, человек отвечает --------------------
#
# До 13.09 модель могла только записать догадку в lesson или idea и никогда не
# получала ответа. Итог — 151 строка lessons.txt, где верное и выдуманное лежат
# вперемешку, а про камень одна и та же мысль переоткрыта двадцать раз. Причина
# не в модели: описание мира неполно (на человеческом слоте в нём нет ни карты,
# ни залежей), а сказать об этом ей нечем.
#
# Здесь петля замыкается. Один вопрос за партию уходит в файл мира, человек
# отвечает между партиями, ответ возвращается в промпт ВСЕМ последующим
# партиям. В отличие от уроков, это безопасно возвращать: пишет человек, а не
# проигравшая модель, и у каждой строки стоит метка источника.
#
# Формат файла (world.md):
#
#     - [код] шахту игра ставит только на залежь, радиус расширения 85
#     - [игрок] на карте 4 залежи золота, 4 угля, 4 железа
#     ## Вопросы
#     - вопрос (эпизод 3, 6:20): сколько залежей золота рядом с базой?
#       ответ: четыре на всю карту, ближайшая к тебе одна
#
# Метка источника обязательна и не для красоты: 13.09 знание игрока про залежи
# оказалось верным, но бесполезным, пока не выяснилось радиусом из кода, что
# мост не умеет строить дальше 26. «Со слов игрока» и «проверено по коду» — не
# одно и то же, и модель должна видеть разницу.

МЕТКИ_ИСТОЧНИКА = ("код", "игрок", "замер")


def разобрать_мир(текст: str) -> tuple[list[str], list[tuple[str, str]]]:
    """Файл мира -> (строки знания, [(вопрос, ответ)]). Ответ пустой = открытый."""
    знание: list[str] = []
    вопросы: list[tuple[str, str]] = []
    в_вопросах = False
    # Строка с отступом — ПРОДОЛЖЕНИЕ предыдущей. Ровно на этом 13.09 уже
    # обожглись с подсказками: двухстрочная подсказка теряла вторую строку, и
    # до модели доезжал обрывок без начала. Здесь то же правило, явно.
    for сырая in текст.splitlines():
        строка = сырая.strip()
        отступ = сырая[:1].isspace()
        if not строка:
            continue
        if строка.lower().startswith("## вопрос"):
            в_вопросах = True
            continue
        if строка.startswith("#"):
            в_вопросах = False              # другой заголовок закрывает раздел
            continue
        if в_вопросах:
            if строка.lower().startswith("ответ:") and вопросы:
                в, о = вопросы[-1]
                вопросы[-1] = (в, (о + " " + строка.split(":", 1)[1].strip()).strip())
            elif строка.startswith("- "):
                тело = строка[2:]
                # «вопрос (эпизод 3, 6:20): текст» — служебную шапку срезаем,
                # модели важен сам вопрос, а не когда он был задан. Резать по
                # первому двоеточию нельзя: оно внутри времени, и от вопроса
                # оставался огрызок «20): сколько...».
                тело = re.sub(r"^вопрос\s*\([^)]*\)\s*:\s*", "", тело,
                              flags=re.IGNORECASE).strip()
                if тело:
                    вопросы.append((тело, ""))
            elif отступ and вопросы:
                в, о = вопросы[-1]
                вопросы[-1] = ((в + " " + строка).strip(), о) if not о \
                    else (в, (о + " " + строка).strip())
        elif строка.startswith("- "):
            знание.append(строка[2:].strip())
        elif отступ and знание:
            знание[-1] = (знание[-1] + " " + строка).strip()
    return знание, вопросы


def мир_для_промпта(текст: str) -> str:
    """Раздел о мире целиком — в отличие от подсказок, он не отбирается по звеньям.

    Знание о мире не устаревает с прохождением цепочки: залежи остаются
    залежами и на первой минуте, и на десятой.
    """
    знание, вопросы = разобрать_мир(текст)
    # Один и тот же вопрос может лежать и в мастере (с ответом), и в рабочем
    # файле (без). Оставляем по одному, с ответом если он есть хоть где-то.
    сведённые: list[tuple[str, str]] = []
    for в, о in вопросы:
        для_него = next((i for i, (в2, _) in enumerate(сведённые)
                         if _тот_же_вопрос(в, в2)), None)
        if для_него is None:
            сведённые.append((в, о))
        elif о and not сведённые[для_него][1]:
            сведённые[для_него] = (сведённые[для_него][0], о)
    вопросы = сведённые
    # Знание тоже может задвоиться, если кто-то скопировал строку в оба файла.
    знание = list(dict.fromkeys(знание))
    строки: list[str] = [f"  {з}" for з in знание]
    строки += [f"  Ответ на твой вопрос «{в}»: {о}" for в, о in вопросы if о]
    открытые = [в for в, о in вопросы if not о]
    куски = []
    if строки:
        куски += ["## ЧТО МЫ ЗНАЕМ О МИРЕ",
                  "  [код] — проверено по коду игры, [игрок] — со слов игрока, "
                  "[замер] — измерено в партии.", *строки]
    if открытые:
        куски += ["## ТВОИ ВОПРОСЫ БЕЗ ОТВЕТА (спрашивать снова не надо)"]
        куски += [f"  {в}" for в in открытые]
    return "\n".join(куски)


def _суть_вопроса(т: str) -> set:
    """Значимые слова вопроса. Сравнение дословное не годится: «сколько залежей
    у моей ратуши» и «сколько залежей у ратуши» — один вопрос, а строки разные.
    """
    слова = re.sub(r"[\W\d_]+", " ", т.lower()).split()
    return {с for с in слова if len(с) > 3}


def _тот_же_вопрос(a: str, b: str) -> bool:
    """Два вопроса об одном? По доле общих слов, порог 0,6 — подобран так,
    чтобы перефразировку считать повтором, а соседнюю тему — нет."""
    A, B = _суть_вопроса(a), _суть_вопроса(b)
    if not A or not B:
        return False
    return len(A & B) / len(A | B) >= 0.6


def записать_вопрос(path: str, вопрос: str, номер: int, gt: int) -> str:
    """Вопрос модели — в файл мира, в раздел «## Вопросы». Возвращает записанное.

    Пустая строка назад значит «не записали», и звать это надо так, чтобы
    причина отброса печаталась: молчаливый отброс неотличим от бездействия.
    """
    вопрос = " ".join(str(вопрос or "").split())[:300]
    if len(вопрос) < 12:
        return ""
    mm, ss = divmod(int(gt), 60)
    строка = f"- вопрос (эпизод {номер}, {mm}:{ss:02d}): {вопрос}"
    try:
        прежнее = open(path, encoding="utf-8").read() if os.path.exists(path) else ""
    except OSError:
        прежнее = ""
    мастер = _мастер_мира()
    if os.path.abspath(мастер) != os.path.abspath(path):
        прежнее = _прочесть(мастер) + "\n" + прежнее
    _, прежние = разобрать_мир(прежнее)
    if any(_тот_же_вопрос(вопрос, в) for в, _ in прежние):
        return ""                           # уже спрашивала — и с ответом, и без
    try:
        with open(path, "a", encoding="utf-8") as f:
            if "## Вопросы" not in прежнее:
                if прежнее and not прежнее.endswith("\n"):
                    f.write("\n")
                f.write("\n## Вопросы\n")
            f.write(строка + "\n")
    except OSError:
        return ""
    return вопрос


def записать_урок(data: dict, path: str, номер: int, gt: int,
                  не_ранее: int = 60) -> str:
    """Наблюдение модели — в отдельный файл, НЕ в промпт.

    Возвращать это обратно в подсказки нельзя: модель, проигравшая партию,
    впишет туда неверный вывод, следующая прочтёт его как истину, и мы получим
    машину закрепления ошибок. По TRAINING_PLAN такие гипотезы проверяются
    отдельно на фиксированных сидах и принимаются только если бьют чемпиона.
    Здесь мы их лишь собираем — материал для той проверки.
    """
    урок = str(data.get("lesson", "") or "").strip()
    if not урок or len(урок) < 12 or урок.lower() in ("none", "null", "-"):
        return ""
    if gt < не_ранее:
        # На первых секундах результатов ещё нет, и в lesson попадают планы
        # («строю центр, потом мельницу»), а не выводы. Планы нам не нужны:
        # файл читается как материал для проверки гипотез.
        return ""
    mm, ss = divmod(gt, 60)
    строка = f"эпизод {номер}, {mm}:{ss:02d} — {урок[:200]}"
    # Сравниваем БЕЗ ЧИСЕЛ: «камень узкое место, 60% на камень» и то же самое
    # с 70% — один и тот же урок. В файле на 11.09.2026 таких повторов о камне
    # набралось больше двадцати, и журнал рос, не прибавляя знания.
    def суть(т: str) -> str:
        return re.sub(r"\d+", "#", т.lower())[:90]

    try:
        прежние = open(path, encoding="utf-8").read() if os.path.exists(path) else ""
        if урок[:200] in прежние:
            return ""                       # то же самое, второй раз не пишем
        к = суть(урок)
        if any(суть(стр.split("—", 1)[-1].strip()) == к
               for стр in прежние.splitlines() if стр.strip()):
            return ""                       # та же мысль, другие числа
        with open(path, "a", encoding="utf-8") as f:
            f.write(строка + "\n")
    except OSError:
        return ""
    return урок[:200]


def рассказ(data: dict) -> list[str]:
    """Три строки объяснения от модели — их видно в окне поверх игры.

    Ключи латиницей нарочно: русские имена полей модели путают чаще, а текст
    внутри всё равно требуется по-русски.
    """
    строки = []
    for ключ, подпись in (("ok", "идёт"), ("stuck", "не идёт"), ("cause", "почему")):
        v = str(data.get(ключ, "") or "").strip()
        if v and v.lower() not in ("none", "null", "-"):
            строки.append(f"        {подпись}: {v[:110]}")
    return строки


# Как модель может назвать поля команды. Разные модели зовут их по-разному, а
# 11.09.2026 выяснилось, чем это кончается: haiku-4.5 писала
# {"cmd":"BALANCE","resource":"stone","value":60} — совершенно верное решение,
# парой 60/40 — а to_commands требовала "role", не находила и выбрасывала
# команду МОЛЧА. В игру не уходило ничего, в логе не появлялось ничего, и по
# логу это выглядело так, будто модель про камень даже не подумала. Синонимы
# дешевле ещё одного абзаца в промпте и работают на любой модели.
СИНОНИМ_РОЛИ = ("role", "resource", "res", "unit", "building", "target",
                "name", "what", "upgrade")
СИНОНИМ_ЧИСЛА = ("total", "count", "value", "amount", "qty", "num", "n",
                 "percent", "share")


def нормализовать(item: dict) -> tuple[str, str, int]:
    """Одна команда модели -> (КОМАНДА, роль, число), как бы она её ни назвала."""
    c = str(item.get("cmd", item.get("command", ""))).upper().strip()
    роль = ""
    for k in СИНОНИМ_РОЛИ:
        v = item.get(k)
        if isinstance(v, str) and v.strip():
            роль = v.strip()
            break
    число = 0
    for k in СИНОНИМ_ЧИСЛА:
        if k in item:
            try:
                число = int(float(item[k]))
                break
            except (TypeError, ValueError):
                continue
    return c, роль, число


def to_commands(data: dict, доступные: set[str] | None = None
                ) -> tuple[list, int, str, list[str], str, int, str]:
    """JSON модели -> команды моста. Что не разобралось — возвращаем строками.

    Раньше непонятное отбрасывалось молча, и потерянная команда была неотличима
    от ненаписанной: ни в игре, ни в логе, ни в следующем запросе. Теперь брак
    называется вслух — и в консоли, и в промпте следующего такта.
    """
    cmds, attack, брак = [], 0, []
    цель_атаки = "base"
    движение, цель_движения = 0, "home"
    for item in (data.get("commands") or [])[:6]:
        if not isinstance(item, dict):
            брак.append(f"{item!r}: команда должна быть объектом JSON")
            continue
        c, role, total = нормализовать(item)
        поля = ", ".join(sorted(k for k in item if k != "cmd"))
        try:
            if role and role in ЗАПРЕТ:
                брак.append(f"{c} {role}: запрещено настройками этой партии")
                continue
            if c == "BUILD":
                if role not in BUILDABLE:
                    брак.append(f"BUILD {role or '?'}: такую постройку мост не умеет"
                                f" (поля: {поля}). Роли: {', '.join(sorted(BUILDABLE))}")
                elif total <= 0:
                    брак.append(f"BUILD {role}: нужно ИТОГО зданий числом > 0"
                                f" в поле total (поля: {поля})")
                else:
                    cmds.append(build(role, total))
            elif c == "TRAIN":
                if role not in ROLE:
                    брак.append(f"TRAIN {role or '?'}: неизвестный юнит"
                                f" (поля: {поля})")
                elif total == 0:
                    брак.append(f"TRAIN {role}: число 0 — это ничего не значит;"
                                f" отрицательное = бесконечный заказ (поля: {поля})")
                else:
                    # Отрицательное = бесконечное производство, см. train().
                    cmds.append(train(role, max(total, INFINITE)))
            elif c == "UPGRADE":
                # Сверяем с тем, что игра назвала доступным ЭТОЙ нации, а не со
                # статическим списком: тот достался от компьютерного слота, где
                # апгрейды заказывались по движковым константам. На человеческом
                # слоте имена другие (eurmil.1), и ни одно имя из старого списка
                # не могло совпасть никогда — 13.09 это стоило 21 такта.
                if доступные and role not in доступные:
                    брак.append(
                        f"UPGRADE {role or '?'}: у твоей нации такого нет. "
                        f"Доступно: {', '.join(sorted(доступные))}")
                elif not role:
                    брак.append(f"UPGRADE: нужно имя в поле role (поля: {поля})")
                else:
                    cmds.append(upgrade(role))
            elif c == "MOVE":
                # То же движение, что у ATTACK, но без режима атаки: бойцы идут
                # и не ищут врага по дороге. Человек двигает войска кликом и не
                # обязан вести их в бой; у бота такой возможности не было вовсе.
                if total > 0:
                    движение = max(движение, total)
                    цель = str(item.get("target", item.get("where", ""))).strip().lower()
                    if цель in ("home", "peasants", "base", "army"):
                        цель_движения = цель
                    elif цель:
                        брак.append(f"MOVE target={цель}: не знаю такой цели; "
                                    f"можно home, peasants, base, army")
                else:
                    брак.append(f"MOVE: нужно число бойцов > 0 в поле count"
                                f" (поля: {поля})")
            elif c == "ATTACK":
                if total > 0:
                    attack = max(attack, total)
                    цель = str(item.get("target", item.get("where", ""))).strip().lower()
                    if цель in ("peasants", "base", "army"):
                        цель_атаки = цель
                    elif цель:
                        брак.append(f"ATTACK target={цель}: не знаю такой цели; "
                                    f"можно peasants, base, army")
                else:
                    брак.append(f"ATTACK: нужно число бойцов > 0 в поле count"
                                f" (поля: {поля})")
            elif c == "SEED":
                # Поля сеют вокруг мельницы, числа не нужно. Еда не залежь: без
                # посева BALANCE food некуда слать людей, и запас только падает.
                cmds.append(seed())
            elif c == "BUILDERS":
                if total > 0:
                    cmds.append(builders(total))
                else:
                    брак.append(f"BUILDERS {total}: нужно число > 0 — сколько "
                                f"крестьян максимум на одну стройку")
            elif c == "BALANCE":
                if role not in RESOURCE:
                    брак.append(f"BALANCE {role or '?'}: ресурс не опознан"
                                f" (поля: {поля}). Только: "
                                f"{', '.join(RESOURCE)}")
                else:
                    cmds.append(balance(role, total))
            else:
                брак.append(f"{c or '?'}: нет такой команды (поля: {поля})")
        except ValueError as e:
            брак.append(f"{c} {role}: {e}")
    # Атака важнее движения: если модель отдала обе, идём в бой, а про
    # проглоченный MOVE говорим вслух - молчаливый отброс неотличим от отказа.
    if attack and движение:
        брак.append("MOVE и ATTACK в одном ответе: выполнен ATTACK, "
                    "движение пропущено — файл приказа один")
        движение = 0
    return (cmds, attack, str(data.get("why", ""))[:200], брак, цель_атаки,
            движение, цель_движения)


MAX_TOKENS = 1200         # с запасом: обрезанный ответ теряет весь такт
LAST_TOKENS = 0           # токенов в последнем ответе: отличить болтливость от очереди
LAST_PROVIDER = ""        # кто обслужил: у OpenRouter это решает всё
# Провайдеры, которые не обслуживают наш регион. Отказ у них постоянный, так что
# запоминаем на сессию и просим OpenRouter больше туда не бросать.
BANNED: set[str] = set()
ЗАПРЕТ: set[str] = set()   # роли, запрещённые настройками партии (--ban)
ONLY: list[str] = []      # если задан — маршрут только через этих, без запасных
AUTOBAN = True            # выключается --no-provider-ban, чтобы проверить руками
REPLAY: list[dict] = []   # заранее записанные ответы вместо вызова модели
_REPLAY_I = 0
_REPLAY_LOCK = threading.Lock()


def загрузить_реплей(путь: str) -> int:
    """Ответы модели из файла: по JSON на строку, либо несколько подряд.

    Зачем: ключ живёт на игровой машине, а петлю надо проверять на маке. С
    реплеем `llm_policy.py` против `mock_game.py` прогоняется целиком и без
    сети — видно, доезжают ли до модели новые блоки запроса, живут ли счётчики
    между тактами, отбрасывается ли урок. Ответы из настоящего лога достаёт
    `log_review.py --replay-out`, и тогда это прогон по исторической партии:
    мост обязан ругаться там, где в тот раз промолчал.
    """
    текст = open(путь, encoding="utf-8").read()
    ответы = []
    for строка in текст.splitlines():
        строка = строка.strip()
        if not строка or строка.startswith("#"):
            continue
        try:
            ответы.append(json.loads(строка))
        except ValueError:
            ответы.extend(json_objects(строка))
    if not ответы:                          # не построчный файл — разберём целиком
        ответы = json_objects(текст)
    REPLAY.extend(ответы)
    return len(ответы)


def следующий_ответ() -> dict:
    global _REPLAY_I
    with _REPLAY_LOCK:
        if _REPLAY_I >= len(REPLAY):
            raise RuntimeError(f"ответы для --replay кончились ({len(REPLAY)} шт.)")
        _REPLAY_I += 1
        return REPLAY[_REPLAY_I - 1]


def json_objects(text: str) -> list[dict]:
    """Разобранные ответы модели, по порядку.

    Пробуем от КАЖДОЙ «{», а не считаем баланс скобок с начала: модель бросает
    недописанный объект и начинает заново, и одна незакрытая скобка в начале
    иначе проглатывает весь остальной текст.
    """
    dec = json.JSONDecoder()
    out = []
    for i, ch in enumerate(text):
        if ch != "{":
            continue
        try:
            obj, _ = dec.raw_decode(text, i)
        except ValueError:
            continue                       # огрызок — идём к следующей скобке
        if isinstance(obj, dict) and ("commands" in obj or "why" in obj):
            out.append(obj)                # внутренние {"cmd":...} сюда не попадут
    return out


def ask(client, model: str, prompt: str, think: bool = False,
        retry: int = 1, max_tokens: int = 0) -> dict:
    if REPLAY:                              # --replay: модель не зовём вовсе
        return следующий_ответ()
    kw = dict(
        model=model,
        messages=[{"role": "system", "content": SYSTEM},
                  {"role": "user", "content": prompt}],
        temperature=0.4,
        max_tokens=max_tokens or MAX_TOKENS,
    )
    extra: dict = {}
    if ONLY:
        extra["provider"] = {"order": list(ONLY), "allow_fallbacks": False}
    elif BANNED:
        extra["provider"] = {"ignore": sorted(BANNED)}
    # nemotron-3.5 по умолчанию рассуждает вслух и съедает лимит, не дойдя до
    # JSON. В такт это не влезает, поэтому рассуждения гасим. Модель, которая
    # такого ключа не знает, ответит 400 — тогда повторяем без него.
    if not think:
        extra["chat_template_kwargs"] = {"enable_thinking": False}
        # То же самое на языке OpenRouter. Ключ выше понимают NIM и vLLM, а
        # OpenRouter — нет, и рассуждающая модель через него съедает лимит,
        # не дойдя до JSON. Замер 11.09.2026 на deepseek-v4.1-flash, один и
        # тот же запрос: без этого поля 75 с и ответ обрезан на 1200 токенах,
        # с ним — 1,8 с и 84 токена. Провайдер, который поля не знает, ответит
        # 400, и весь extra_body снимается ниже.
        extra["reasoning"] = {"enabled": False}
    if extra:
        kw["extra_body"] = extra
    try:
        r = client.chat.completions.create(**kw)
    except Exception as e:
        msg = str(e)
        # Регион не поддерживается — отказ навсегда. Запоминаем провайдера и
        # сразу пробуем ещё раз, попросив OpenRouter его обойти.
        if AUTOBAN and not ONLY and "unsupported_country_region_territory" in msg:
            имя = re.search(r"'provider_name':\s*'([^']+)'", msg)
            if имя and имя.group(1) not in BANNED:
                BANNED.add(имя.group(1))
                print(f"        {имя.group(1)} не обслуживает наш регион — "
                      f"исключаю его из маршрутизации")
                return ask(client, model, prompt, think, retry)
        if "404" in msg or "not found" in msg.lower():
            # Пресет — не модель, и совет про каталог NVIDIA тут вреден: он
            # уводит от настоящей причины. 12.09 на этом потеряли круг: мост
            # подменил ответ сервера догадкой. Показываем, что сказал сервер.
            if model.startswith("@preset/"):
                raise RuntimeError(
                    f"пресет {model} не найден. Что проверить, по порядку:\n"
                    f"        1) пресет создан и СОХРАНЁН на openrouter.ai/settings/presets;\n"
                    f"        2) Slug совпадает буква в букву: "
                    f"{model.split('/', 1)[1]!r} (он не равен названию);\n"
                    f"        3) ключ из nim_key.txt принадлежит ТОМУ ЖЕ аккаунту, "
                    f"где лежит пресет;\n"
                    f"        4) в пресете выбрана хотя бы одна модель.\n"
                    f"        Ответ сервера: {msg[:300]}") from e
            raise RuntimeError(
                f"модель {model} не отвечает — её убрали из каталога?\n"
                f"        сверьтесь с openrouter.ai/models и задайте другую: "
                f"--model <id> или COSS3_MODEL\n"
                f"        Ответ сервера: {msg[:300]}") from e
        # Откат делаем ТОЛЬКО на отказ разобрать запрос. На таймауте и обрыве
        # повторять нельзя: вторая попытка удвоит и без того съеденный такт.
        отказ = any(w in msg.lower() for w in
                    ("400", "422", "extra", "not permitted", "unexpected",
                     "unrecognized", "invalid"))
        if "extra_body" not in kw or not отказ:
            raise
        kw.pop("extra_body")                # ключ рассуждений понимают не все
        r = client.chat.completions.create(**kw)
    global LAST_TOKENS, LAST_PROVIDER
    LAST_TOKENS = getattr(getattr(r, "usage", None), "completion_tokens", 0) or 0
    LAST_PROVIDER = str(getattr(r, "provider", "") or "")
    ch = r.choices[0]
    text = ch.message.content or ""
    objs = json_objects(text)
    if objs:
        rich = [o for o in objs if o.get("commands")]
        return (rich or objs)[-1]          # последний непустой: он и есть ответ
    fin = getattr(ch, "finish_reason", "") or "?"
    if retry > 0:                          # мусор бывает разовым — переспросим
        return ask(client, model, prompt, think, retry - 1)
    if fin == "length":
        raise ValueError(
            f"ответ обрезан на {MAX_TOKENS} токенах, до JSON модель не дошла. "
            f"Хвост: ...{text[-160:]}")
    # Показываем ответ ЦЕЛИКОМ (до 2000 символов). 14.09 здесь стояло 300, и
    # четыре подряд неудачи критика выглядели как «ответ обрезан провайдером»,
    # хотя обрезал их сам этот print. Чинить по обрезанной улике нельзя.
    raise ValueError(f"нет разбираемого JSON (finish_reason={fin}), "
                     f"длина {len(text)}: {text[:2000]}")


def одна_партия(a, client, br: Bridge, plind: int,
                номер_эпизода: int = 1) -> str:
    """Ведёт одну партию до конца. Возвращает исход:
    «цель» — крестьянин убит, «горизонт» — время вышло,
    «обрыв» — состояние перестало обновляться.
    """
    # ВАЖНО: сначала проглотить то, что лежит в файле, и только потом ждать
    # новую запись. После NEW в файле ещё состояние ПРОШЛОЙ партии — с её
    # игровым временем. Первый запрос уходил на нём, next_call назначался в
    # будущее прошлой партии, и цикл молчал полторы минуты.
    br.read_state()
    # После NEW игра ГЕНЕРИРУЕТ карту, и первого состояния приходится ждать
    # дольше обычного такта. 13.09 на живой игре переход между эпизодами занял
    # больше 31 с, а здесь стояли жёсткие 30 — и исправная загрузка была
    # объявлена обрывом, с диагностикой про «игра свёрнута или на паузе».
    # Ждём столько же, сколько ждёт сам запуск партии, и говорим, чего ждём:
    # молчащее ожидание неотличимо от зависания.
    первое_ожидание = float(a.new_timeout) if (a.new or номер_эпизода > 1) else 30.0
    st = None
    _крайний = time.time() + первое_ожидание
    while st is None:
        _осталось = _крайний - time.time()
        if _осталось <= 0:
            break
        try:
            st = br.wait_state(timeout=min(15.0, max(1.0, _осталось)))
        except TimeoutError:
            if _крайний - time.time() > 0:
                print(f"жду первое состояние новой партии: прошло "
                      f"{int(первое_ожидание - (_крайний - time.time()))} с из "
                      f"{int(первое_ожидание)} (после NEW игра генерирует карту)",
                      flush=True)
    if st is None:
        # Партия могла кончиться ДО того, как мы к ней подключились: так бывает
        # в контейнере, где политика встаёт после игры. Спрашиваем игру, но
        # только про свежие файлы — замороженное состояние прошлой партии лежит
        # рядом и назвало бы её исход вместо нынешнего.
        исход = br.outcome(свежесть=30)
        if исход:
            return конец_партии(a, br, исход, br.raw.get("gametime", 0))
        if первое_ожидание > 30:
            print(f"новая партия не подала состояния за {int(первое_ожидание)} с "
                  f"после NEW. Если карта всё ещё грузится — поднимите "
                  f"--new-timeout")
        stalled(br.save_dir, plind, no_mode=a.no_mode)
        return "обрыв"
    # НА КАКОЙ СЕКУНДЕ мы подключились. Это первое, что решает, сравним ли
    # прогон с другими. 12.09 партию заводили руками: сначала игра и бой, потом
    # отдельной командой политика — и бот не существовал первые полторы минуты.
    # По трассе это выглядело как «бот полторы минуты ничего не строил», то есть
    # инструмент показывал артефакт запуска как поведение модели.
    старт_gt = int(st.get("gametime", 0) or 0)
    if старт_gt > ПОЗДНО:
        мм, сс = divmod(старт_gt, 60)
        print(f"\n{'!' * 60}\n"
              f"ПОДКЛЮЧИЛИСЬ К ИДУЩЕЙ ПАРТИИ: она уже на {мм}:{сс:02d}.\n"
              f"Всё это время бот не играл, а игра шла. С прогонами, начатыми\n"
              f"с нуля, этот НЕ СРАВНИМ: разница будет не про идею, а про то,\n"
              f"сколько партия прожила без бота.\n"
              f"Начинать партию и политику надо одной командой: `--new` здесь\n"
              f"или COSS3_EXPERIMENT в контейнере.\n"
              f"{'!' * 60}")
        if a.max_start and старт_gt > a.max_start:
            print(f"--max-start {a.max_start}: не играю на такой партии")
            return "поздно"
    первый = not globals().get("_ШАПКА")
    globals()["_ШАПКА"] = True
    print(f"слот P{plind}, модель {a.model}, решение раз в {a.every} игровых секунд")
    if первый:                               # это одно и то же каждый эпизод
        _h = load_hints(a.hints)
        _в_промпте = отобрать_подсказки(_h, st)
        print(f"подсказки из {a.hints}, читаются перед каждым решением")
        print(f"  файл {len(_h)} симв., в промпт идёт {len(_в_промпте)} "
              f"(~{len(_в_промпте) // 3} токенов): # и пройденные звенья отброшены")
        if отброшенные_метки:
            print(f"  ОТБРОШЕНЫ ПО ЗВЕНЬЯМ: {', '.join(sorted(отброшенные_метки))} — "
                  f"эти строки в промпт НЕ пойдут.\n"
                  f"  Осторожно с [экономика]: звено проходится при peasants>=15, "
                  f"а партия начинается с 18,\n"
                  f"  то есть такая подсказка не дойдёт до модели ни разу. "
                  f"Снимите метку, если она нужна всегда")
        _плохие = неизвестные_метки(_h)
        if _плохие:
            print(f"  ВНИМАНИЕ: метки не из звеньев — {', '.join(sorted(set(_плохие)))}."
                  f"\n  Такие строки видны всегда. Звенья: {', '.join(ЗВЕНЬЯ)}")
        if len(_в_промпте) > 2500:
            print("  великовато. Пометьте строки звеном — [кузница], [казарма],\n"
                  "  [армия], [волна], [экономика] — они исчезнут, когда звено пройдено.\n"
                  "  Устойчивые правила держите в SYSTEM или в policy.py")
    if первый and a.world:
        # Канал вопросов включён — сказать об этом вслух и показать, что уже
        # накоплено. Молчащий канал неотличим от выключенного, а цена ошибки
        # здесь высокая: модель потратит вопрос, а человек его не увидит.
        try:
            _сыр = open(a.world, encoding="utf-8").read()
        except OSError:
            _сыр = ""
            print(f"КАНАЛ ВОПРОСОВ: файла {a.world} ещё нет — будет создан "
                  f"первым же вопросом модели")
        _зн, _воп = разобрать_мир(_сыр)
        _отв = [1 for _, о in _воп if о]
        if _сыр:
            print(f"мир из {a.world}: {len(_зн)} строк знания, "
                  f"{len(_отв)} отвеченных вопросов, "
                  f"{len(_воп) - len(_отв)} открытых — всё идёт в промпт целиком")
        print(f"  модель может задать {a.questions} вопрос(а) за партию; "
              f"ответы писать строкой «  ответ: ...» под вопросом")
        if _зн and not any(m in " ".join(_зн) for m in ("[код]", "[игрок]", "[замер]")):
            print("  ВНИМАНИЕ: ни у одной строки нет метки источника "
                  "([код]/[игрок]/[замер]) — модель не отличит проверенное от слов")
    print()

    globals()["ЧЕСТНО"] = bool(a.fair)
    if a.fair:
        print("честная игра: числа противника в запрос не идут, ПОКА карта "
              "закрыта. Открыта (монгольфьер всем, --balloon 2) — идут: там их "
              "видит и человек")
    else:
        print("ВНИМАНИЕ: --unfair. Мост подсказывает модели то, чего человек не "
              "видит. Такой прогон с честными сравнивать нельзя")
    globals()["КАНАЛ_ВОПРОСОВ"] = bool(a.world)
    globals()["ВОПРОС_ЗАДАН"] = ""       # счёт на партию, не на прогон
    globals()["ОТРЕЗОК"] = max(0, int(a.stop_at))
    if ОТРЕЗОК:
        _м, _с = divmod(ОТРЕЗОК, 60)
        print(f"учебный отрезок: партия обрывается на {_м}:{_с:02d} и начинается "
              f"новая (цель прежняя, горизонт {a.horizon} не отменён)")
    globals()["WAVE_MIN"] = max(0, int(a.wave_min))
    globals()["ОКНО_ИСТОРИИ"] = max(0, int(a.history))
    if a.history != 5:
        print(f"окно истории: {a.history} прошлых ходов "
              f"(по умолчанию 5; 0 — не показывать; больше числа тактов = вся партия)")
    # Размер запроса — не мелочь: бюджет такта 20 секунд, и он тратится на
    # ожидание ответа. Замер 13.09: SYSTEM 16 159 символов (~5 400 токенов) и
    # уходит КАЖДЫЙ такт, обстановка при окне 5 — около 630 токенов, при полной
    # истории партии — около 2 570. То есть голова втрое тяжелее хвоста, и
    # спорить про размер истории, не зная этого, бессмысленно.
    # Разделы дописываем ДО замера. Раньше и человеческий раздел, и канал
    # вопросов приклеивались ниже, и строка называла размер, которого в запросе
    # не будет: 16 159 символов она показывала и с ними, и без них.
    if a.human and SYSTEM_HUMAN not in SYSTEM:
        globals()["SYSTEM"] = SYSTEM + SYSTEM_HUMAN
    if a.world and SYSTEM_QUESTION not in SYSTEM:
        globals()["SYSTEM"] = SYSTEM + SYSTEM_QUESTION
    print(f"SYSTEM: {len(SYSTEM)} симв. (~{len(SYSTEM)//3} токенов), "
          f"уходит в каждом запросе"
          + (" (+раздел человека)" if a.human else "")
          + (" (+канал вопросов)" if a.world else ""))
    globals()["ЧЕЛОВЕК"] = bool(a.human)
    if WAVE_MIN:
        print(f"минимальный размер волны: {WAVE_MIN}. Мост НЕ держит волну, когда "
              f"бойцов меньше;\n  отвергается заниженный запрос при полной армии "
              f"(--wave-min 0 — выключить)")
    else:
        print("порог волны выключен (--wave-min 0): уйдёт любое число бойцов")
    if a.human:
        # На человеческом слоте выключать нечего: ProgressAI там не запускается
        # вовсе (progress.inc зовёт его только для bai или человека с советником).
        print("человеческий слот: нативного ИИ нет по построению, MODE не шлём")
        print("проверь в игре: свой слот ЧЕЛОВЕК, советник ВЫКЛЮЧЕН")
    elif not a.no_mode and br.send([mode(True, own_war=not a.native_war)]):
        # Не ждём wait_consumed: игра забирает файл на своём тике и без нас, а
        # ожидание стоило целого тика до первого решения.
        print("нативный билд-ордер выключен, ведёт модель")
        print("нативная атака " + ("ОСТАВЛЕНА: волны шлёт движок"
                                   if a.native_war else
                                   "выключена: волны идут только по команде ATTACK"))

    history: list[str] = []
    вопросов_задано = 0                  # один за партию: человек — узкое место
    дневник = Дневник() if a.memo else None
    ТРАССА_ПАРТИИ.clear()
    УРОКИ_ПАРТИИ.clear()
    # Критик живёт в main, а дневник — здесь; отдаём его наружу, чтобы разбор
    # видел ту же партию, а не собирал её заново из трассы.
    globals()["ПОСЛЕДНИЙ_ДНЕВНИК"] = дневник
    прошлый_мир = load_world(a.world)    # чтобы заметить ответ, данный на ходу
    next_call = 0
    base_enemy = None
    pending = None                       # (поток, коробка) с решением в работе
    ведёт_раш = a.fallback               # эталон раша, только если попросили
    волна_была = False                   # уходил ли хоть кто-то в атаку
    волны: list = []                     # (игровая секунда, сколько бойцов)
    сбоев_подряд = 0
    next_fb = 0
    next_alive = 0
    next_attack = 0                      # не гнать волны чаще, чем они доходят
    сказано_про_403 = False
    было_st: dict | None = None          # состояние на миг прошлого решения
    прошлый_заказ: list = []             # что тогда заказали, для проверки
    расхождение: list[str] = []          # названо в тексте, но не отдано командой
    брак: list[str] = []                 # что мост не разобрал в прошлом ответе
    вето_волны = ""                      # волну отверг сам мост, а не игра
    вмешательство = ""                   # мост подменил команду — сказать модели
    повторы: dict = {}                   # сколько тактов подряд заказ не проходит
    прошлые_подсказки = ""               # чтобы заметить правку на ходу
    if ведёт_раш:
        print("до первого ответа модели строит эталон раша — игра не простаивает")
    t0, gt0 = time.time(), int(st.get("gametime", 0)) if st else 0
    паузы: list[float] = []              # реальные секунды между записями состояния
    прошлое_чтение = time.time()

    def темп_игры() -> None:
        """Как часто игра писала состояние. Цикл забирает готовый ответ только
        после свежей записи, поэтому её темп — нижняя граница запаздывания."""
        if len(паузы) > 2:
            п = sorted(паузы)
            print(f"игра писала состояние: медиана {п[len(п)//2]:.1f} с, "
                  f"худшая пауза {п[-1]:.1f} с, записей {len(п)}")

    # Первый вызов уходит сразу, на уже прочитанном состоянии: ожидание свежего
    # стоило ещё одного тика ИИ, то есть 2-5 секунд до первого решения.
    if st:
        gt_н = int(st.get("gametime", 0))
        next_call = gt_н + a.every
        прошлые_подсказки = load_hints(a.hints)
        коробка: dict = {"gt": gt_н, "t": time.time()}
        поток = threading.Thread(
            target=think_worker,
            args=(коробка, client, a.model,
                  situation(st, br.read_map() or {}, [], прошлые_подсказки,
                            None, [], a.allow_restart, мир=load_world(a.world)),
                  a.think, a.tries, a.spare),
            daemon=True)
        поток.start()
        pending = (поток, коробка)
        print(f"первый запрос ушёл на {gt_н} игровой секунде")
    slow_after = a.every / 1.38          # 1,38× — замер из HANDOFF, уточним по факту
    while True:
        try:
            st = br.wait_state(timeout=30)
        except TimeoutError:
            # Состояние встало. Это НЕ повод гадать: у игры надо спросить.
            # Пульс интерфейса переживает паузу конца партии, а последняя
            # строка состояния успевает назвать исход в большинстве случаев.
            исход = br.outcome()
            if исход:
                return конец_партии(a, br, исход, br.raw.get("gametime", 0))
            # d здесь не существует: каталог знает только мост. Из-за этого
            # диагностика конца партии падала NameError поверх TimeoutError.
            stalled(br.save_dir, plind, no_mode=a.no_mode)
            return "обрыв"
        _т = time.time()
        паузы.append(_т - прошлое_чтение)
        прошлое_чтение = _т
        gt = int(st.get("gametime", 0))
        # Исход приходит той же строкой состояния, что и всё остальное. Ждать
        # тридцатисекундного обрыва, чтобы узнать о поражении, незачем.
        if st.get("victory") in ("win", "lose"):
            return конец_партии(a, br, str(st["victory"]), gt)
        mp = br.read_map()
        if int(st.get("my_agressors", 0) or 0) > 0:
            волна_была = True
        for p in range(8):
            # Человеческий блок кладёт крестьян врага прямо в состояние: файла
            # карты он не пишет, вся картина собирается одним проходом.
            _ист = mp if f"p{p}_peasants" in mp else st
            if st.get(f"p{p}_enemy") and f"p{p}_peasants" in _ист:
                en = int(_ист[f"p{p}_peasants"])
                # Сравниваем с ПРОШЛЫМ значением, а не с начальным.
                #
                # 13.09: прежняя проверка держала base_enemy = первое
                # увиденное число (18) и требовала упасть НИЖЕ него. Враг при
                # этом растёт до 55, и чтобы мост заметил ОДНОГО убитого,
                # пришлось бы убить тридцать семь. Разбор семи прогонов: в пяти
                # из них крестьяне врага падали после наших волн — 54->51,
                # 58->55, 54->47->44, 56->52, 56->53 — и каждый раз мост
                # отрапортовал «цель не взята».
                #
                # То есть бот брал цель, а инструмент этого не видел. Хуже
                # молчания: он говорил обратное.
                if base_enemy is None:
                    base_enemy = en
                elif en < base_enemy:
                    mm, ss = divmod(gt, 60)
                    if not волна_была:
                        # 11.09.2026: партия без единого бойца и без единой
                        # ATTACK отрапортовала «цель достигнута». Крестьяне у
                        # врага убывают и сами по себе, так что падение счётчика
                        # без нашей волны — не результат, а совпадение.
                        print(f"\n{mm}:{ss:02d}  у врага стало меньше крестьян "
                              f"({base_enemy} -> {en}), НО МЫ НИКОГО НЕ ПОСЫЛАЛИ "
                              f"— это не наша заслуга, партия продолжается")
                        base_enemy = en
                        continue
                    print()
                    темп_игры()
                    print(f"ЦЕЛЬ ДОСТИГНУТА на {mm}:{ss:02d}: крестьян у врага "
                          f"{base_enemy} -> {en}, убито {base_enemy - en}")
                    отметить_конец(a, st, gt, "цель")
                    return "цель"
                else:
                    # Враг вырос — запоминаем новое число. Без этого сравнение
                    # навсегда остаётся привязанным к старту.
                    base_enemy = en
        el = time.time() - t0
        if el > 60 and gt > gt0:
            slow_after = a.every * el / (gt - gt0)

        # Модель думает в фоне. Пока она думает, цикл продолжает читать
        # состояние и следить за целью — иначе задержка тира ослепляет нас
        # на минуты, а она гуляет от 3 до 240 с и не лечится выбором модели.
        if pending is None and gt >= next_call:
            next_call = gt + a.every
            box: dict = {"gt": gt, "t": time.time()}
            подсказки = load_hints(a.hints)
            if подсказки != прошлые_подсказки:
                if прошлые_подсказки:
                    print(f"        подсказки изменились ({len(подсказки)} симв.) — "
                          f"учтены с этого решения")
                прошлые_подсказки = подсказки
            мир_текст = load_world(a.world)
            if a.world and мир_текст != прошлый_мир:
                if прошлый_мир:
                    print(f"        мир изменился ({len(мир_текст)} симв.) — "
                          f"учтён с этого решения")
                прошлый_мир = мир_текст
            prompt = situation(st, mp, history, подсказки,
                               было_st, прошлый_заказ, a.allow_restart,
                               расхождение, повторы, брак, волны, вето_волны,
                               вмешательство, мир=мир_текст,
                               дневник=дневник.строки() if дневник else None)
            # Кладём запрос в коробку: ответ приходит асинхронно, и к моменту
            # записи трассы контекст такта уже сменился. Без этого в трассе
            # осталось бы решение без обстановки, из которой оно выросло.
            box["prompt"] = prompt
            if a.dump_prompt:
                try:
                    # дописываем, а не перезаписываем: при --replay нужен весь
                    # ряд запросов, чтобы видеть, как блоки меняются по тактам.
                    # Файл обнуляется один раз при запуске, в main().
                    with open(a.dump_prompt, "a", encoding="utf-8") as f:
                        f.write(f"\n\n# решение на {gt} игровой секунде\n\n")
                        f.write("### SYSTEM\n" + SYSTEM + "\n\n### ЗАПРОС\n" + prompt)
                except OSError:
                    pass                    # диагностика не должна ронять партию
            th = threading.Thread(target=think_worker,
                                  args=(box, client, a.model, prompt, a.think,
                                        a.tries, a.spare),
                                  daemon=True)
            th.start()
            pending = (th, box)

        # Пока модель молчит, игра не должна стоять: держим цели эталона раша.
        # Команды декларативные, так что перехват модели ничего не ломает.
        if ведёт_раш and gt >= next_fb:
            next_fb = gt + 10
            фб = rush_plan(st, a.wave, minimal=True)
            if фб and br.send(фб):
                br.wait_consumed(timeout=15)
            # Раш молчалив, и без этой строки лог выглядит мёртвым, хотя
            # партия идёт. Раз в минуту показываем, что мы живы.
            if gt >= next_alive:
                next_alive = gt + 60
                mm, ss = divmod(gt, 60)
                цепь = " ".join(("+" if ok else "-") + n for n, ok, _ in stages(st))
                кто = "раш" if фб else "раш (целей нет)"
                print(f"{mm}:{ss:02d}  [{кто}] {цепь}")

        if pending is None or pending[0].is_alive():
            continue                        # решение ещё готовится — не ждём
        _, box = pending
        pending = None
        wait = time.time() - box["t"]
        if "err" in box:
            if REPLAY and _REPLAY_I >= len(REPLAY):
                # Реплей кончился — эпизод окончен. По горизонту это не поймать:
                # у мока игровое время своё и с нуля не начинается.
                print()
                темп_игры()
                print(f"ответы для --replay кончились ({len(REPLAY)}) — эпизод окончен")
                return "реплей"
            сбоев_подряд += 1
            print(f"модель не ответила за {wait:.0f} с:")
            for стр in box.get("log", []):
                print(f"        {стр}")
            текст = str(box["err"])
            if "402" in текст or "insufficient" in текст.lower():
                print("        ДЕНЬГИ КОНЧИЛИСЬ на счету провайдера (402). Ни один\n"
                      "        вызов не пройдёт, партия доиграется вслепую.\n"
                      "        Пополнить: openrouter.ai/credits, проверить остаток:\n"
                      "        python llm_policy.py --credits")
            if ("403" in текст or "401" in текст) and not сказано_про_403:
                сказано_про_403 = True
                if "rate-limited" in текст or "429" in текст:
                    print("        провайдер держит лимит на эту модель. Свой ключ\n"
                          "        провайдера даёт собственные лимиты:\n"
                          "        openrouter.ai/settings/integrations")
                elif "unsupported_country" in текст:
                    print("        провайдер не обслуживает регион — исключён,\n"
                          "        следующие запросы пойдут мимо него")
                else:
                    print("        403/401 — проверьте баланс openrouter.ai/credits\n"
                          "        и настройки openrouter.ai/settings/privacy")
            if сбоев_подряд >= 2 and not ведёт_раш and a.fallback:
                ведёт_раш = True
                print("        два сбоя подряд — за пульт эталон раша, партия идёт")
            if сбоев_подряд == 5:
                print("        пять сбоёв подряд: модель фактически недоступна,\n"
                      "        дальше играет раш. Прервать — Ctrl+C")
            continue
        сбоев_подряд = 0
        подхват = ведёт_раш
        ведёт_раш = False
        # Имена апгрейдов берём из состояния: список зависит от нации и
        # приходит в поле upg_avail как «eurmil.1=food+140,...».
        _дост = {x.split("=", 1)[0].strip()
                 for x in str(st.get("upg_avail", "") or "").split(",")
                 if x.strip()}
        (cmds, attack, why, брак, цель_атаки,
         движение, цель_движения) = to_commands(box["data"], _дост)
        # Заниженная волна. Считаем ЗДЕСЬ, а не у отправки ниже: трасса такта
        # пишется раньше отправки, и вето, посчитанное позже, в неё не попало бы
        # — а именно по трассе потом разбирают партию.
        #
        # Порога накопления НЕТ нарочно: мост не держит волну, когда бойцов мало
        # (вето в этом проекте уже съедало волны — 11.09 так пропали все 15
        # команд ATTACK). Отвергаем ровно один случай: свободных хватает на
        # полную волну, а просят горстку. 12.09 это и убило партию — 14 волн по
        # 4-5 бойцов при 23-28 в строю гибли поодиночке.
        вето_волны = ""
        вмешательство = ""
        if attack and a.wave_min:
            _св = int(st.get("my_freewar", 0) or 0)
            _аг = int(st.get("my_agressors", 0) or 0)
            if attack < a.wave_min and _св + _аг >= a.wave_min:
                вето_волны = (
                    f"ATTACK {attack} на {цель_атаки}: НЕ ОТПРАВЛЕН МОСТОМ. "
                    f"Просишь {attack} бойцов, а послать можно {_св + _аг} "
                    f"(свободных {_св}, пул {_аг}). Меньше {a.wave_min} за раз "
                    f"не отправится: {attack} бойцов у вражеской базы — это одна "
                    f"проигранная стычка, а не волна. Собери всех и проси не "
                    f"меньше {a.wave_min}")
        # Пока ратуши нет — потолок строителей ставит МОСТ, а не модель.
        # Проверяется идея игрока от 13.09: партия начинается БЕЗ ратуши
        # (centers=0, замерено по трассе), а бот ставил её тремя строителями из
        # восемнадцати, хотя в котлован влезает двенадцать (wip='center/12').
        # Всё это время остальные рубили дерево, которое некуда сдавать.
        #
        # Почему потолок, а не приказ строить: BUILDERS действует на КАЖДУЮ
        # НОВУЮ стройку, поднимать его после закладки бесполезно. Значит поднять
        # надо ДО того, как модель закажет ратушу, — то есть с первого такта.
