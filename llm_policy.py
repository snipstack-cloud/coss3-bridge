KEY_FILES = ("nim_key.txt", os.path.expanduser("~/.coss3_nim_key"))


def load_key(explicit: str = "") -> tuple[str, str]:
    """Ключ и откуда он взялся. Файл рядом со скриптом — чтобы не звать setx."""
    if explicit:
        return explicit.strip(), "--key"
    for имя in ("OPENROUTER_API_KEY", "NVIDIA_API_KEY"):
        env = os.environ.get(имя, "").strip()
        if env:
            return env, имя
    here = os.path.dirname(os.path.abspath(__file__))
    for name in KEY_FILES:
        path = name if os.path.isabs(name) else os.path.join(here, name)
        try:
            with open(path, encoding="utf-8") as f:
                key = f.read().strip()
        except OSError:
            continue
        if key:
            return key, path
    return "", ""


def похожие(model: str, ids: list[str]) -> tuple[list[str], list[str]]:
    """Делим кандидатов на «та же модель» и «просто похоже называется».

    Сильное совпадение — один корень является продолжением другого ПО ГРАНИЦЕ
    дефиса: nemotron-3.5-lightning против nemotron-3.5-lightning-30b-a3b.
    Без проверки границы mistral-nemo сходит за mistral-nemotron, а это разные
    модели, и уехать на них молча — худшее, что может случиться.
    """
    корень = model.split("/")[-1].lower()
    куски = {c for c in корень.replace(".", "-").split("-") if len(c) > 3}
    сильные, слабые = [], []
    for x in ids:
        сво = x.split("/")[-1].lower()
        длин, крат = (сво, корень) if len(сво) > len(корень) else (корень, сво)
        if длин == крат or (длин.startswith(крат) and длин[len(крат)] == "-"):
            сильные.append(x)
            continue
        свои = {c for c in сво.replace(".", "-").split("-") if len(c) > 3}
        if len(куски & свои) >= 2:
            слабые.append(x)
    return sorted(сильные), sorted(слабые)


