def _мс(gt) -> str:
    м, с = divmod(max(0, int(gt or 0)), 60)
    return f"{м}:{с:02d}"


class Дневник:
    """Память о партии: вехи, неудачи, исходы волн. Живёт одну партию."""

    ВОЛНА_ИТОГ = 60          # через сколько игровых секунд подводить итог волны

    def __init__(self) -> None:
        self.вехи: list[str] = []
        self.неудачи: dict[str, list] = {}     # суть -> [время, текст, сколько раз]
        self.волны: list[dict] = []
        self._прежние: dict[str, int] = {}
        self._прошлый_сбой = ""      # last_fail держится в состоянии тактами
        self.карта_открыта = False   # map_open: на открытой карте врага видно

    @staticmethod
    def _ч(v) -> int:
        try:
            return int(float(str(v).strip()))
        except (TypeError, ValueError):
            return 0

    def такт(self, st: dict, брак: list[str] | None = None) -> None:
        gt = self._ч(st.get("gametime"))
        self.карта_открыта = str(st.get("map_open", "")).lower() in (
            "1", "true", "да", "yes")
        for ключ, имя in ЗДАНИЯ_ВЕХИ:
            if ключ not in st:
                continue
            было = self._прежние.get(ключ)
            стало = self._ч(st.get(ключ))
            if было is not None and стало > было:
                self.вехи.append(f"{_мс(gt)} {имя}"
                                 + (f" ×{стало}" if стало > 1 else ""))
            self._прежние[ключ] = стало
        # Неудачи: та же беда с другими числами — это одна беда, а не две.
        сбой = " ".join(str(st.get("last_fail") or "").split())[:120]
        новые = list(брак or [])
        if сбой and сбой != self._прошлый_сбой:
            новые.append(сбой)          # тот же текст подряд — та же попытка
        self._прошлый_сбой = сбой
        for текст in новые:
            текст = " ".join(текст.split())[:120]
            if not текст:
                continue
            суть = re.sub(r"\d+", "#", текст.lower())
            if суть in self.неудачи:
                self.неудачи[суть][2] += 1
            else:
                self.неудачи[суть] = [gt, текст, 1]
        # Итоги волн: что стало с ушедшими и с крестьянами врага.
        for в in self.волны:
            if в.get("итог") is None and gt - в["gt"] >= self.ВОЛНА_ИТОГ:
                в["итог"] = (self._наших(st), self._врага(st))

    @classmethod
    def _наших(cls, st: dict) -> int:
        return sum(cls._ч(st.get(k)) for k in ("mil_inf", "mil_shooters", "mil_cav"))

    @classmethod
    def _врага(cls, st: dict) -> int:
        for k, v in st.items():
            if k.endswith("_peasants"):
                return cls._ч(v)
        return 0

    def волна(self, gt: int, сколько: int, цель: str, st: dict) -> None:
        self.волны.append({"gt": gt, "сколько": сколько, "цель": цель,
                           "было": (self._наших(st), self._врага(st)),
                           "итог": None})

    def строки(self) -> list[str]:
        if not (self.вехи or self.неудачи or self.волны):
            return []
        out = ["", "## Что уже случилось в этой партии"]
        if self.вехи:
            out.append("  построено: " + "   ".join(self.вехи[-12:]))
        for время, текст, раз in sorted(self.неудачи.values())[-5:]:
            out.append(f"  {_мс(время)} НЕ ВЫШЛО: {текст}"
                       + (f" (и ещё {раз - 1} раз)" if раз > 1 else ""))
        for в in self.волны[-5:]:
            строка = f"  {_мс(в['gt'])} волна {в['сколько']} на {в['цель']}"
            if в["итог"]:
                (нб, вб), (нс, вс) = в["было"], в["итог"]
                строка += f": наших бойцов {нб} -> {нс}"
                # Что стало с крестьянами врага — честно только при контакте:
                # если наши дошли и дрались, человек это на экране видит. Если
                # волна ушла и никого не потеряла, знать про чужих крестьян
                # неоткуда, и подсказывать нельзя (правило игрока 13.09).
                if (not ЧЕСТНО) or self.карта_открыта or нс < нб:
                    строка += f", крестьян врага {вб} -> {вс}"
                    if вб == вс:
                        строка += " — НИ ОДНОГО НЕ УБИЛИ"
                elif ЧЕСТНО:
                    строка += " (до врага не дошли — что там, не видно)"
            else:
                строка += ": итог ещё не подведён"
            out.append(строка)
        return out


def situation(st: dict, mp: dict, history: list[str], hints: str,
              было: dict | None = None, заказ: list | None = None,
              restart_ok: bool = False, расхождение: list[str] | None = None,
              повторы: dict | None = None, брак: list[str] | None = None,
              волны: list | None = None, вето: str = "", вмеш: str = "",
              мир: str = "", дневник: list[str] | None = None) -> str:
    gt = int(st.get("gametime", 0))
    mm, ss = divmod(gt, 60)
    done = " ".join(("+" if ok else "-") + name for name, ok, _ in stages(st))
    lines = [
        f"# Время {mm}:{ss:02d}",
        f"Цепочка до цели: {done}",
        "",
        "## Ресурсы",
        f"  еда={st.get('food')} дерево={st.get('wood')} камень={st.get('stone')} "
        f"золото={st.get('gold')} железо={st.get('iron')} уголь={st.get('coal')}",
        *_ресурсы_изменение(было, st),
        "## Моё",
        f"  крестьян={st.get('peasants')} (еда {st.get('on_food')}, дерево {st.get('on_wood')}, "
        f"камень {st.get('on_stone')}"
        + (f", шахты {st.get('on_mine')}" if "on_mine" in st else "")
        + (f", стройка {st.get('on_build')}" if "on_build" in st else "")
        + f", свободных "
        + (str(st.get("idle_pea")) if "idle_pea" in st else str(_свободных(st))) + ")",
        f"  центров={st.get('centers')} кузниц={st.get('smiths')} казарм17={st.get('ba17')} "
        f"мельниц={st.get('mills')} складов={st.get('my_stores')} домов={st.get('houses')}",
        _шахты_строкой(st),
        f"  армия: пехота={st.get('mil_inf')} стрелки={st.get('mil_shooters')} "
        f"конница={st.get('mil_cav')}; свободных бойцов={st.get('my_freewar')}, "
        + (f"ударный пул={st.get('my_agressors')} (стоят у базы, это НЕ поход)"
           if "my_agressors" in st else "все они готовы к походу"),
        f"  можно послать сейчас: "
        f"{int(st.get('my_freewar', 0) or 0) + int(st.get('my_agressors', 0) or 0)}"
        f" бойцов" + (" (свободные + ударный пул)" if "my_agressors" in st else "")
        + (f". Волной считается {WAVE_MIN} и больше: когда послать можно "
           f"{WAVE_MIN}+, а просишь меньше, мост приказ ОТВЕРГНЕТ. Пока бойцов "
           f"меньше {WAVE_MIN} — уйдёт сколько есть, если сам решишь идти"
           if WAVE_MIN else ""),
        (f"  стройка занята {st.get('build_slots_used')}/{st.get('build_slots_total')} слотов"
         if "build_slots_used" in st else
         f"  недостроено зданий: {st.get('building_now', 0)}"),
    ]
    # Что именно в закладке и каков потолок строителей. Без этой строки модель
    # видела только «недостроено N» и не знала, ЧТО строится, — 12.09 она из-за
    # этого повторяла BUILD на уже заложенное здание такт за тактом.
    _стройка = разобрать_wip(st)
    if _стройка:
        def _окотловане(имя, тройка):
            предел, строят, готово = тройка
            куски = [f"строителей влезает {предел}" if предел else "предел не посчитан"]
            if строят is not None:
                куски.append(f"строят сейчас {строят}")
            if готово is not None:
                куски.append(f"готово {готово}%")
            return f"{имя} (" + ", ".join(куски) + ")"
        # Приписку про процент даём, только если он ЕСТЬ: на старом мосту
        # поля нет, и совет сравнивать несуществующее число был бы ложью.
        _есть_процент = any(т[2] is not None for т in _стройка.values())
        lines.append("  СЕЙЧАС СТРОИТСЯ: " + ", ".join(
            _окотловане(имя, т) for имя, т in _стройка.items())
            + ". Повторный BUILD на это здание ничего не даст — заказ уже принят"
            + (". Готовность растёт тем быстрее, чем больше строителей: сравни"
               " её между тактами и увидишь, что даёт лишний человек"
               if _есть_процент else ""))
    # Какие апгрейды уже сделаны. Без этого модель заказывает один и тот же
    # раз за разом: подтверждения-то нет.
    сделано = [и for и in ("food140", "reaper", "feelds", "century", "horse",
                           "fort", "wood", "stone200", "builders")
               if str(st.get("upg_" + и, "")).lower() in ("1", "true", "да")]
    if "upg_food140" in st:                 # поля есть только на новом мосте
        lines.append("  апгрейды сделаны: " + (", ".join(сделано) or "ни одного"))
    # Что нация УМЕЕТ. Раньше список апгрейдов жил в SYSTEM общим для всех
    # наций, и это была ложь: наборы различаются. 13.09 модель заказала reaper
    # при мельнице и получила «нет такого апгрейда у нашей нации» — такт ушёл
    # на несуществующее. Теперь список приходит из игры.
    _дост = str(st.get("upg_avail", "") or "").strip()
    if _дост:
        _спис = [у for у in _дост.split(",") if у.strip()]
        # РЕЖЕМ ЗДЕСЬ, а не в игре. У нации две с лишним сотни апгрейдов, и
        # целиком этот список — около пяти килобайт в КАЖДОМ запросе при
        # бюджете такта в двадцать секунд.
        #
        # Обрезка живёт в python нарочно. 13.09 я трижды пробовал сделать её
        # в блоке .inc, и каждый раз весь тик Progress переставал
        # компилироваться: там нет способа проверить правку, кроме как поставить
        # в игру и ждать две минуты. Здесь она проверяется за секунду и не может
        # уронить игру.
        _видно, _срез = _спис, 0
        if len(_спис) > СПИСОК_АПГРЕЙДОВ:
            _видно, _срез = _спис[:СПИСОК_АПГРЕЙДОВ], len(_спис) - СПИСОК_АПГРЕЙДОВ
        lines.append(f"  апгрейды твоей нации ({len(_спис)}): "
                     + ", ".join(_видно))
        if _срез:
            lines.append(f"  ...и ещё {_срез} — в запрос не влезли. Если нужного "
                         f"нет в списке, скажи об этом в 'stuck'")
        lines.append("  Имя копируй отсюда БУКВА В БУКВУ. Другого игра не примет: "
                     "имена вроде 'food140' или 'reaper' не существуют.")
    # Что стало с ПОСЛАННОЙ волной. До 13.09 трасса знала, сколько бойцов ушло,
    # и ничего о том, дошли ли они: семь прогонов слали по 20-30 и не убили ни
    # одного крестьянина врага, а отличить «погибли по дороге» от «стоят на
    # месте» было нечем.
    _п = st.get("wave_sent")
    if _п is not None and int(float(_п or 0)):
        lines.append(f"  в последней волне было послано: {int(float(_п))}")
    # УБЫЛЬ АРМИИ — единственный честный признак того, что наших убивают.
    #
    # Считается здесь, а не в блоке .inc: общий счёт армии человек видит в
    # интерфейсе, и он убывает при потерях — так подсказал игрок. В игре для
    # этого ничего добавлять не надо, а правка python проверяется за секунду и
    # не может уронить тик Progress (правило 8).
    #
    # Именно этого не хватало, чтобы понять, что стало с волной: поле из
    # именованной группы на тот же вопрос отвечало ложью — группа не теряет
    # своих мёртвых.
    if было:
        _б = _чис(было.get("mil_inf")) + _чис(было.get("mil_shooters"))
        _с = _чис(st.get("mil_inf")) + _чис(st.get("mil_shooters"))
        if _б and _с < _б:
            lines.append(f"  АРМИЯ УБЫЛА: было {_б}, стало {_с} — наших убивают "
                         f"прямо сейчас. Если волна ушла, тает она")
    if not int(float(st.get("centers", 0) or 0)):
        lines.append("  ратуши НЕТ: без неё не построить ничего, кроме мельницы,"
                     " и не нанять крестьян")
    _з = _запас_мест(st)
    if _з is not None:                      # на старом мосте поля нет — молчим
        lines.append(f"  жилых мест занято {st.get('my_farmused')} из "
                     f"{st.get('my_farm')}"
                     + (" — запас кончается, найм встанет" if _з < 20 else ""))
    # Волны считаем САМИ, а не по счётчику игры: 11.09.2026 выяснилось, что
    # my_agressors — это пул назначенных в агрессоры, он растёт от формирования
    # отрядов и мобилизации и не пустеет. Модель читала его как «волна идёт» и
    # за весь эпизод не отдала ни одной ATTACK: ждала результата похода,
    # которого не было.
    # Что здания ДЕЛАЮТ прямо сейчас: заказ принят, но юнит ещё в работе —
    # это не то же самое, что «заказ не прошёл». Поля появились 11.09.2026,
    # на старом мосте их нет.
    if "inprod_pea" in st:
        lines.append(f"  в производстве: крестьян {st.get('inprod_pea')}, "
                     f"пехоты {st.get('inprod_inf')}")
    if st.get("last_fail"):
        # Почему прошлая команда не прошла — словами игры, а не догадкой модели.
        # Без этой строки она сочиняет причину: за один прогон на моке успела
        # «выяснить», что в цену зданий входит еда.
        lines.append(f"  ПОСЛЕДНИЙ ОТКАЗ: {st.get('last_fail')}")
    if "on_build" in st:
        lines.append(f"  на стройках занято {st.get('on_build')} крестьян"
                     + (" (сколько послать, решаешь ты командой BUILDERS)"
                        if "idle_pea" in st else
                        " (их забрала игра, доля BALANCE их не касается)"))
    if "cost_ok" in st and str(st.get("cost_ok")).lower() in ("1", "true", "да"):
        lines.append(f"  цена крестьянина (из движка): еда {st.get('pea_food')}, "
                     f"дерево {st.get('pea_wood')}, золото {st.get('pea_gold')}")
    if "can_pea" in st:
        # Ответ самого движка: хватает ли РЕСУРСОВ на одного. Цены юнитов лежат
        # в бинарнике, и без этой строки причина отказа была неугадываема.
        _д = lambda k: str(st.get(k, "")).lower() in ("1", "true", "да")
        lines.append(f"  движок говорит: на крестьянина ресурсов "
                     f"{'ХВАТАЕТ' if _д('can_pea') else 'НЕ ХВАТАЕТ'}, "
                     f"на пехотинца {'хватает' if _д('can_inf') else 'НЕ ХВАТАЕТ'}"
                     + (", и объявлен ГОЛОД" if _д("famine") else ""))
    if волны is not None:
        if волны:
            _мм, _сс = divmod(волны[-1][0], 60)
            lines.append(f"  волны: отправлено {len(волны)}, последняя на "
                         f"{_мм}:{_сс:02d} из {волны[-1][1]} бойцов "
                         f"на {волны[-1][2]}")
        else:
            lines.append("  волны: НИ ОДНОЙ. Никто никуда не идёт, пока ты не "
                         "отдашь ATTACK")
    # ЧТО СТАЛО С УШЕДШЕЙ ВОЛНОЙ. 18 партий, 1139 бойцов отправлено, ноль убитых
    # крестьян врага — и по трассе нельзя было отличить «погибли по дороге» от
    # «дошли и не справились». wave_sent говорит, сколько УШЛО; что дальше —
    # молчание, и модель гадала («возможно, волна ещё идёт»).
    # Даём только СВОИХ и только то, что человек и так видит: свою армию на
    # карте и штатное оповещение «ваши войска атакованы». Раненый — значит его
    # бьют прямо сейчас.
    _ушли = _чис(st.get("mil_away")) if "mil_away" in st else None
    if _ушли is not None:
        _ранены, _дальше = _чис(st.get("mil_hurt")), _чис(st.get("mil_far"))
        _всего = _чис(st.get("mil_inf")) + _чис(st.get("mil_shooters"))
        _что = [f"{_всего} бойцов всего"]
        if _ушли:
            # Где именно они стоят и идут ли кучей. Человек видит это на карте
            # одним взглядом; по одному «самый дальний» отличить растянутую
            # цепочку от плотной группы нельзя, а 15.09 модель пять раз подряд
            # писала «бойцы подходят по одному» и проверить это было нечем.
            _близко, _сторона = _чис(st.get("mil_near")), str(st.get("mil_side") or "")
            _куда = f" на {_сторона}" if _сторона else ""
            if _близко and _дальше - _близко > 20:
                _что.append(f"{_ушли} УШЛИ{_куда} и РАСТЯНУЛИСЬ: от {_близко} до "
                            f"{_дальше} от базы — это не кулак, а цепочка")
            else:
                _что.append(f"{_ушли} УШЛИ{_куда} кучей (от {_близко} до {_дальше})")
        else:
            _что.append("от базы никто не ушёл — все дома")
        if _ранены:
            _что.append(f"{_ранены} РАНЕНЫ: их бьют прямо сейчас")
        lines.append("  твои войска: " + ", ".join(_что))
        # «Ушли» и «волна» — РАЗНЫЕ вещи, и путать их дорого. mil_away считает
        # всех, кто дальше 60, чем бы они там ни занимались; wave_sent — только
        # тех, кого ты послал командой ATTACK. Боец может оказаться в поле сам:
        # движок гонит его за врагом, попавшим в радиус поиска.
        _послано = _чис(st.get("wave_sent"))
        if _ушли and not _послано:
            lines.append("  но в атаку ты не посылал НИКОГО: эти ушли не по твоей "
                         "команде — скорее всего погнались за врагом сами. "
                         "Волна — только то, что отдано через ATTACK")
        if _ушли == 0 and _послано > 0:
            lines.append(f"  ВОЛНА НЕ ВЕРНУЛАСЬ: ты посылал {_послано}, а у базы "
                         "сейчас нет никого дальше 60 — считай их погибшими, а не "
                         "идущими")
    # Кого вообще можно нанять в бой. Новичок открывает казарму и читает, что
    # там лежит; у бота этого не было никогда. 14.09, 12 партий: армия целиком
    # из пикинёров (infantry17 заказан 144 раза, musk17 — ноль), и каждая волна
    # гибла у базы врага, не убив ни одного крестьянина.
    _бойцы = str(st.get("fighters", "") or "").split()
    if _бойцы == ["none-found"]:
        # Молчать тут нельзя: пустая строка неотличима от «блок не встал».
        lines.append("  кого можно нанять в бой: МОСТ НЕ НАШЁЛ НИ ОДНОЙ боевой "
                     "роли у этой нации. Это похоже на поломку моста, а не на "
                     "правило игры — заказывай по прежнему опыту")
    elif _бойцы:
        _разбор = []
        for _б in _бойцы:
            _роль, _, _хвост = _б.partition("=")
            _части = [ч for ч in _хвост.split(",") if ч]
            _имя = _части[0] if _части else _роль
            # Нулевую цену не показываем: в казарме у ресурса, которого юнит не
            # стоит, просто пусто. Отбрасывать по endswith('0') нельзя — так
            # уходит и food10, и hp120; смотрим на ЧИСЛО.
            _свойства = []
            for _ч in _части[1:]:
                _м = re.fullmatch(r"([a-z]+)(-?\d+)", _ч)
                if _м and int(_м.group(2)) == 0:
                    continue
                _свойства.append(_ч)
            _разбор.append(f"{_роль} ({_имя}: {', '.join(_свойства)})")
        lines.append("  кого можно нанять в бой: " + "; ".join(_разбор))
    # БЕЗ РАТУШИ ДОБЫЧИ НЕТ. Замер на живой игре 14.09: десять рубщиков при
    # отсутствии ратуши дали дерево 1000 -> 1000 и разошлись за двадцать секунд;
    # та же команда после ратуши дала 300 -> 580. Крестьянам некуда нести, и они
    # бросают работу. Модель каждую партию первые полторы минуты раскидывает
    # людей по ресурсам впустую.
    if _чис(st.get("centers")) <= 0:
        lines.append("  РАТУШИ НЕТ — добычи не будет: крестьяне уйдут к лесу, "
                     "порубят и разойдутся, ресурс не прибавится. Пока ратуша "
                     "не достроена, BALANCE на дерево и камень бесполезен")
    # Лес и камень НА ЗЕМЛЕ, а не в запасе. Модель сама записала урок: «15
    # человек на камне дали камень +0 — он, видимо, уже исчерпан в пределах 40».
    # Была права и проверить не могла: состояние говорило только про запас.
    # Числа — вместимость в рабочих местах, а не «сколько тонн»: в клетке леса
    # помещается 2 рубщика, в клетке камня 3.
    _мест = []
    for _к, _имя in (("wood", "дерево"), ("stone", "камень")):
        if f"{_к}_slots_near" not in st:
            continue
        _вс, _св = _чис(st.get(f"{_к}_slots_near")), _чис(st.get(f"{_к}_slots_free"))
        if _вс <= 0:
            _мест.append(f"{_имя} — РЯДОМ КОНЧИЛОСЬ, посылать некуда")
        elif _св <= 0:
            _мест.append(f"{_имя} — все {_вс} мест заняты, лишние встанут без дела")
        else:
            _мест.append(f"{_имя} — свободно {_св} мест из {_вс}")
    if _мест:
        lines.append("  на земле рядом (в пределах 40): " + "; ".join(_мест))
    # Сколько людей BALANCE может переставить ПРЯМО СЕЙЧАС. Число свободных
    # крестьян игрок видит в интерфейсе, так что форы нет; а вот связать его со
    # своей командой модель не догадывалась. 13.09 в base_open3 копия 1 четыре
    # такта подряд слала BALANCE food 12 при нуле свободных, еда падала, и
    # крестьяне умерли от голода при полном наборе рабочих на стройке.
    _своб = _чис(st.get("idle_pea")) if "idle_pea" in st else _свободных(st)
    _строит = _чис(st.get("on_build"))
    if _своб <= 0:
        lines.append(f"  BALANCE сейчас НЕ ПОДЕЙСТВУЕТ: свободных крестьян нет "
                     f"(на стройке {_строит}). Команда берёт только свободных — "
                     f"снимай со строек через BUILDERS или жди, пока достроят")
    else:
        lines.append(f"  BALANCE может переставить сейчас не больше {_своб} "
                     f"человек — столько свободных"
                     + (f"; ещё {_строит} заняты стройкой" if _строит else ""))
    # Что по карману ПРЯМО СЕЙЧАС — ответ движка (_unit_CanApplyCostByID), а не
    # догадка. Раньше модель выясняла это ценой такта: закажи, получи тишину,
    # гадай, какой ресурс виноват. Человек видит это как погашенную кнопку.
    _мочь = str(st.get("can_now", "") or "").split()
    _немочь = str(st.get("cant_now", "") or "").split()
