def find_ai_plind(d: str, fresh: float = 30, human: bool = False) -> int | None:
    """Чей слот вести. На компьютерном ищем bai, на человеческом — human:
    правила хакатона требуют играть за человека, а там флага bai нет вовсе."""
    best, best_mtime = None, -1.0
    try:
        names = os.listdir(d)
    except OSError:                          # каталога нет — разбираться будет diagnose
        return None
    for name in names:
        m = re.fullmatch(r"coss3_eco_P(\d+)\.dat", name)
        if not m:
            continue
        n = int(m.group(1))
        mtime = os.path.getmtime(os.path.join(d, name))
        if fresh and time.time() - mtime > fresh:
            continue
        try:
            st = Bridge(d, n).read_state() or {}
        except Exception:
            continue
        свой = st.get("human") if human else st.get("bai")
        if свой and mtime > best_mtime:
            best, best_mtime = n, mtime
    return best


