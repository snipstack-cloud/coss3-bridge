# -*- coding: utf-8 -*-
"""Самопроверка событийного вопроса «кого нанимать».

Предложение игрока 20.09: мост может звать модель САМ, не дожидаясь своего
такта. Первый случай — достроенная казарма: такт идёт раз в 15-20 игровых
секунд, и здание, готовое сразу после решения, простаивает до следующего.
[замер] 20.09: очередь пустовала в 45 тактах из 209, и найм был по карману в 29
из них. Пустая казарма не делает никого.

Вопрос задаётся узко и со всеми числами, чтобы ответ пришёл за секунды:
кандидаты с ценой и разменом против ТОГО, кем враг воюет на самом деле, чем
платим, что уже есть, что в очереди ИМЕННО этого здания.

Стережётся:
* запрос короткий — иначе смысл события теряется;
* названы кандидаты именно этого здания (казарма и конюшня куют разное);
* размен считается против его ГЛАВНОГО вида, а не против первого попавшегося;
* очередь показывается своя, а не «здание пусто» всегда;
* ответ короткой схемы переводится в обычную команду TRAIN.
"""
import llm_policy as L

беды = []


def проверка(имя, условие, пояснение=""):
    if условие:
        print("  ОК    " + имя)
    else:
        беды.append(имя)
        print("  ПЛОХО " + имя + (" — " + пояснение if пояснение else ""))


def состояние(очередь="1:pikeman:inf,2:none", стрелков=0, его_пик=54):
    return {
        "gametime": 722, "peasants": 65, "mil_inf": 76, "mil_shooters": стрелков,
        "mil_cav": 0, "my_freewar": 73, "ba17": 2, "stables": 1, "mills": 1,
        "smiths": 1, "centers": 1, "food": 15792, "gold": 1538, "iron": 3683,
        "coal": 1000, "wood": 2000, "stone": 2000, "ba_queues": очередь,
        "p1_enemy": 1, "p1_army": его_пик, "p1_inf": его_пик, "p1_shoot": 0,
        "fighters": ("infantry17=pikeman,hp90,atk13,wkind1,pause0,rmax188,"
                     "dpike3,dsword2,dbullet4,food25,gold3,iron20 "
                     "musk17=musketeernet,hp65,atk10,wkind3,pause375,rmax1500,"
                     "dpike1,dsword1,dbullet0,food50,gold8,iron4 "
                     "dragoon17=dragoon,hp220,atk15,wkind3,pause562,rmax1500,"
                     "dpike0,dsword0,dbullet0,food90,gold7,iron5"),
        "p1_fighters": ("infantry17=hp90,atk13,wkind1,pause0,rmax188,dpike7,"
                        "dsword6,dbullet4"),
    }


ст = состояние()
казарма = L.запрос_найма(ст, ст, "ba17", 2)

проверка("запрос КОРОТКИЙ", len(казарма) < 1500, f"{len(казарма)} символов")
проверка("названо, что достроено", "казарма №2" in казарма, казарма[:60])
проверка("кандидаты казармы названы",
         "infantry17" in казарма and "musk17" in казарма)
проверка("конница в казарме не предлагается", "dragoon17" not in казарма,
         "её куёт конюшня")
проверка("у каждого кандидата есть цена", казарма.count("цена") >= 2)
проверка("размен считается против его ГЛАВНОГО вида",
         "против его infantry17" in казарма)
проверка("сказано, сколько такого бойца уже есть", "76 уже есть" in казарма)
проверка("назван порог еды", "меньше 500" in казарма)

# очередь ЭТОГО здания
проверка("пустая очередь названа пустой",
         "СЕЙЧАС ПУСТО" in L.запрос_найма(ст, ст, "ba17", 2),
         "у казармы №2 стоит none")
занята = состояние(очередь="1:pikeman:inf,2:pikeman:inf")
проверка("занятая очередь не выдаётся за пустую",
         "СЕЙЧАС ПУСТО" not in L.запрос_найма(занята, занята, "ba17", 2))
проверка("сказано, что новый заказ заменит очередь",
         "заменит очередь" in L.запрос_найма(занята, занята, "ba17", 2))

конюшня = L.запрос_найма(ст, ст, "stable", 1)
проверка("для конюшни предлагается конница", "dragoon17" in конюшня)
# Ищем именно СТРОКИ-КАНДИДАТЫ, а не любое упоминание: «против его
# infantry17» — это описание врага, и оно там законно. На этом проверка
# сперва дала ложную тревогу.
кандидаты_конюшни = [с for с in конюшня.splitlines()
                     if с.startswith("  ") and ":" in с and "уже есть" in с]
проверка("в конюшне кандидат только конница",
         all("dragoon17" in с for с in кандидаты_конюшни) and кандидаты_конюшни,
         str(кандидаты_конюшни)[:120])
проверка("очередь конюшни ищется по ключу s1",
         "СЕЙЧАС ПУСТО" in конюшня, "в поле нет записи s1 — значит пусто")

# РАЗМЕН в смешанной паре: пауза есть у одного, нет у другого
import combat_math as C
м = C.разобрать(ст["fighters"])["musk17"]
в = C.разобрать(ст["p1_fighters"])["infantry17"]
р = C.размен(м, в)
проверка("размен смешанной пары считается по ударам",
         р["отношение"] < 10, f"вышло {р['отношение']}, было 1125 до починки")
проверка("флаг честно говорит, что скорость не учтена",
         not р["скорость_учтена"])

# короткий ответ переводится в TRAIN
ответ = {"role": "musk17", "total": -1, "why": "пика упёрлась в пол"}
переведён = {"commands": [{"cmd": "TRAIN", "role": ответ["role"],
                           "total": ответ.get("total", -1)}], "why": "по событию"}
cmds, *_ = L.to_commands(переведён, set(), set())
проверка("короткий ответ даёт команду TRAIN",
         any(getattr(c, "cmd", "") == "TRAIN" for c in cmds),
         str([getattr(c, "cmd", "?") for c in cmds]))

# БОЕПРИПАС. Игрок 21.09: «модель не знает, что для стреляющей армии нужен
# уголь». Проверено по коду: musketeernet тратит 3 угля и 1 железо ЗА ВЫСТРЕЛ,
# драгун 3 и 2, пикинёр — ничего (lib/unit.script:800-801, 809). Живая партия
# 20.09: уголь стоял на 1000, пока стрелков было мало, и рухнул до 226 при сотне
# стрелков и НУЛЕ угольных шахт. Прежний замер «уголь не кончается» был сделан
# на 18 партиях с пиковой армией, где стрелять было некому.
без_угля = состояние()
без_угля.update({"coal": 529, "mil_shooters": 93, "mines_coal": 0})
т = L.запрос_найма(без_угля, без_угля, "ba17", 2)
строка_м = next(с for с in т.splitlines() if с.strip().startswith("musk17"))
строка_п = next(с for с in т.splitlines() if с.strip().startswith("infantry17"))

проверка("у стрелка назван расход за выстрел",
         "3 угля" in строка_м and "1 железа" in строка_м, строка_м[:150])
проверка("посчитан расход на ЗАЛП", "за ЗАЛП" in строка_м)
проверка("сказано, на сколько залпов хватит", "хватит на" in строка_м)
проверка("отсутствие угольной шахты названо",
         "УГОЛЬНОЙ ШАХТЫ НЕТ" in строка_м, строка_м[-90:])
проверка("у пикинёра сказано, что боеприпас не тратит",
         "Боеприпас не тратит" in строка_п, строка_п[-90:])

с_шахтой = состояние()
с_шахтой.update({"coal": 5000, "mil_shooters": 20, "mines_coal": 1})
строка2 = next(с for с in L.запрос_найма(с_шахтой, с_шахтой, "ba17", 2).splitlines()
               if с.strip().startswith("musk17"))
проверка("при своей шахте про её отсутствие не пишем",
         "УГОЛЬНОЙ ШАХТЫ НЕТ" not in строка2)

проверка("таблица расхода знает всех троих",
         set(L.ВЫСТРЕЛ_СТОИТ) >= {"musk17", "dragoon17", "infantry17"})
проверка("у пикинёра расход пустой", not L.ВЫСТРЕЛ_СТОИТ["infantry17"])

print()
if беды:
    print(f"БЕД: {len(беды)} — {', '.join(беды)}")
    raise SystemExit(1)
print("всё чисто")
