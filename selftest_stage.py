# -*- coding: utf-8 -*-
"""Самопроверка STAGE — стоячего накопления армии.

Предложение игрока 19.09: видно, что армия врага идёт к базе и прошла
полпути — надо собрать своих заранее и держать кулак ближе к нему.

Почему нужна НОВАЯ команда, а не MOVE: MOVE разовый, он уводит свободных
СЕЙЧАС, а выкованные следом остаются дома. По замеру 15.09 модель не отдала
MOVE ни разу за серию. STAGE держится до отмены, и досылку делает мост.

Стережётся:
* приказ запоминается и переживает такты;
* мост досылает свежих сверх keep и говорит об этом вслух;
* свой ATTACK/MOVE модели в тот же такт ОТМЕНЯЕТ досылку — иначе одних и тех
  же бойцов дёргают дважды за такт;
* off:1 выключает;
* между партиями состояние чистится.
"""
import llm_policy as L

беды = []


def проверка(имя, условие, пояснение=""):
    if условие:
        print("  ОК    " + имя)
    else:
        беды.append(имя)
        print("  ПЛОХО " + имя + (" — " + пояснение if пояснение else ""))


L.НАКОПЛЕНИЕ.clear()
рез = L.to_commands({"commands": [{"cmd": "STAGE", "cx": 9, "cy": 7, "keep": 20}]})
проверка("STAGE запомнен", L.НАКОПЛЕНИЕ.get("cx") == 9 and L.НАКОПЛЕНИЕ.get("cy") == 7,
         str(L.НАКОПЛЕНИЕ))
проверка("keep запомнен", L.НАКОПЛЕНИЕ.get("keep") == 20, str(L.НАКОПЛЕНИЕ))

# клетки нет — приказ отвергается вслух, а не молча
L.НАКОПЛЕНИЕ.clear()
рез = L.to_commands({"commands": [{"cmd": "STAGE"}]})
брак = рез[3]
проверка("без клетки STAGE отвергнут ВСЛУХ",
         not L.НАКОПЛЕНИЕ and any("STAGE" in b for b in брак), str(брак))

# off выключает
L.НАКОПЛЕНИЕ.update(cx=9, cy=7, keep=0, who="")
рез = L.to_commands({"commands": [{"cmd": "STAGE", "off": 1}]})
проверка("off:1 выключает накопление", not L.НАКОПЛЕНИЕ, str(L.НАКОПЛЕНИЕ))

# строка состояния появляется, пока приказ стоит
L.НАКОПЛЕНИЕ.update(cx=9, cy=7, keep=20, who="")
ст = {"gametime": 300, "peasants": 30, "my_freewar": 50, "mil_inf": 50,
      "mil_shooters": 0, "mil_cav": 0, "food": 3000, "gold": 3000,
      "ba17": 1, "mills": 1, "p1_enemy": 1, "p1_army": 100}
т = L.situation(ст, {}, [], "")
проверка("модель видит, что накопление включено", "НАКОПЛЕНИЕ ВКЛЮЧЕНО" in т,
         "стоячий приказ невидим, если о нём не напоминать")
проверка("названа клетка и keep", "(9,7)" in т and "20" in т, "")

L.НАКОПЛЕНИЕ.clear()
т2 = L.situation(ст, {}, [], "")
проверка("без приказа строки нет", "НАКОПЛЕНИЕ ВКЛЮЧЕНО" not in т2)

проверка("STAGE есть в списке команд для модели",
         "STAGE" in L.ПОЛИТИКА["команды"], str(L.ПОЛИТИКА["команды"]))

print()
if беды:
    print(f"БЕД: {len(беды)} — {', '.join(беды)}")
    raise SystemExit(1)
print("всё чисто")
