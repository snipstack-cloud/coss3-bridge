# -*- coding: utf-8 -*-
"""Самопроверка STAGE — стоячего накопления армии.

Предложение игрока 19.09: видно, что армия врага идёт к базе и прошла
полпути — надо собрать своих заранее и держать кулак ближе к нему.

Почему нужна НОВАЯ команда, а не MOVE: MOVE разовый, он уводит свободных
СЕЙЧАС, а выкованные следом остаются дома. По замеру 15.09 модель не отдала
MOVE ни разу за серию. STAGE держится до отмены, и досылку делает мост.

Стережётся:
* приказ запоминается и переживает такты;
* мост досылает свежих сверх keep и говорит об этом вслух;
* свой ATTACK/MOVE модели в тот же такт ОТМЕНЯЕТ досылку — иначе одних и тех
  же бойцов дёргают дважды за такт;
* off:1 выключает;
* между партиями состояние чистится.
"""
import llm_policy as L

беды = []


def проверка(имя, условие, пояснение=""):
    if условие:
        print("  ОК    " + имя)
    else:
        беды.append(имя)
        print("  ПЛОХО " + имя + (" — " + пояснение if пояснение else ""))


L.НАКОПЛЕНИЕ.clear()
рез = L.to_commands({"commands": [{"cmd": "STAGE", "cx": 9, "cy": 7, "keep": 20}]})
проверка("STAGE запомнен", L.НАКОПЛЕНИЕ.get("cx") == 9 and L.НАКОПЛЕНИЕ.get("cy") == 7,
         str(L.НАКОПЛЕНИЕ))
проверка("keep запомнен", L.НАКОПЛЕНИЕ.get("keep") == 20, str(L.НАКОПЛЕНИЕ))

# клетки нет — приказ отвергается вслух, а не молча
L.НАКОПЛЕНИЕ.clear()
рез = L.to_commands({"commands": [{"cmd": "STAGE"}]})
брак = рез[3]
проверка("без клетки STAGE отвергнут ВСЛУХ",
         not L.НАКОПЛЕНИЕ and any("STAGE" in b for b in брак), str(брак))

# off выключает
L.НАКОПЛЕНИЕ.update(cx=9, cy=7, keep=0, who="")
рез = L.to_commands({"commands": [{"cmd": "STAGE", "off": 1}]})
проверка("off:1 выключает накопление", not L.НАКОПЛЕНИЕ, str(L.НАКОПЛЕНИЕ))

# строка состояния появляется, пока приказ стоит
L.НАКОПЛЕНИЕ.update(cx=9, cy=7, keep=20, who="")
ст = {"gametime": 300, "peasants": 30, "my_freewar": 50, "mil_inf": 50,
      "mil_shooters": 0, "mil_cav": 0, "food": 3000, "gold": 3000,
      "ba17": 1, "mills": 1, "p1_enemy": 1, "p1_army": 100}
т = L.situation(ст, {}, [], "")
проверка("модель видит, что накопление включено", "НАКОПЛЕНИЕ ВКЛЮЧЕНО" in т,
         "стоячий приказ невидим, если о нём не напоминать")
проверка("названа клетка и keep", "(9,7)" in т and "20" in т, "")

L.НАКОПЛЕНИЕ.clear()
т2 = L.situation(ст, {}, [], "")
проверка("без приказа строки нет", "НАКОПЛЕНИЕ ВКЛЮЧЕНО" not in т2)

проверка("STAGE есть в списке команд для модели",
         "STAGE" in L.ПОЛИТИКА["команды"], str(L.ПОЛИТИКА["команды"]))

# ПРЕДЛОЖЕНИЕ ЧИСЛОМ, А НЕ УПОМИНАНИЕМ КОМАНДЫ.
# Замер 20.09 (base21, 51 такт): MOVE упомянут в 75 процентах тактов и НЕ
# ОТДАН НИ РАЗУ; UPGRADE по имени — в 2 процентах, отдан 56 раз, потому что
# рядом стоит цена и выигрыш. STAGE не упоминался в запросе вовсе.
L.НАКОПЛЕНИЕ.clear()
оц = {"клетки": [{"x": 2, "y": 13, "крестьян": 5, "их_рядом": 10,
                  "их_подкрепление": 0, "их_успеют": 0, "их_eta": None,
                  "наш_кулак": 50, "наш_eta": 80, "встретит": 10,
                  "перевес": 5.0, "перевес_без_подкрепления": 5.0,
                  "вердикт": "можно"}],
      "прогноз": {"их_армия": 100, "их_через_60": 110, "наша_армия": 50,
                  "наша_через_60": 60, "голод": False},
      "режим": "УДАР",
      "кулак": {"n": 50, "cx": 12, "cy": 13, "что": "свободные"}}
т = chr(10).join(L.строки_оценки(оц))
проверка("предложение о сборе появляется", "ЕСЛИ КОПИТЬ ЗАРАНЕЕ" in т, т[-200:])
проверка("названа КОНКРЕТНАЯ клетка сбора", '"cx":7' in т, т[-300:])
проверка("названа экономия секунд", "с 80 с до ~40 с" in т, т[-300:])
проверка("названа ПЛАТА за выдвижение", "0,67 против 0,19" in т, t if False else т[-300:])

# при включённом накоплении предлагать нечего
L.НАКОПЛЕНИЕ.update(cx=7, cy=13, keep=10, who="")
т2 = chr(10).join(L.строки_оценки(оц))
проверка("при включённом STAGE предложения нет", "ЕСЛИ КОПИТЬ ЗАРАНЕЕ" not in т2)
L.НАКОПЛЕНИЕ.clear()

# близкая цель предложения не стоит
оц2 = dict(оц)
оц2["клетки"] = [dict(оц["клетки"][0], наш_eta=30)]
проверка("при близкой цели (меньше 60 с) не предлагаем",
         "ЕСЛИ КОПИТЬ ЗАРАНЕЕ" not in chr(10).join(L.строки_оценки(оц2)))

# --- приказ виден В ТРАССЕ, а не только по следу досылки (20.09) ----------
#
# Поле `stage` заведено после того, как «STAGE не отдан ни разу» дважды
# оказалось ошибкой измерения: STAGE не попадает в `cmds`, и по трассе его
# было не видно вовсе. Вывод ушёл в итог идеи base21 и в RESUME, и на нём
# построили следующую серию. Стережём обе стороны: отметка ставится и
# отметка НЕ ЗАЛИПАЕТ на следующий такт.
L.НАКОПЛЕНИЕ.clear(); L.STAGE_ЗА_ТАКТ.clear()

L.to_commands({"commands": [{"cmd": "STAGE", "cx": 7, "cy": 13, "keep": 20}]})
проверка("STAGE отмечен в такте включения",
         L.STAGE_ЗА_ТАКТ.get("что") == "включено", str(L.STAGE_ЗА_ТАКТ))
проверка("в отметке клетка и keep",
         (L.STAGE_ЗА_ТАКТ.get("cx"), L.STAGE_ЗА_ТАКТ.get("cy"),
          L.STAGE_ЗА_ТАКТ.get("keep")) == (7, 13, 20), str(L.STAGE_ЗА_ТАКТ))

L.to_commands({"commands": [{"cmd": "TRAIN", "unit": "peasant"}]})
проверка("отметка НЕ ЗАЛИПАЕТ на следующий такт", not L.STAGE_ЗА_ТАКТ,
         "иначе трасса скажет «включала» в каждом такте после первого")
проверка("сам приказ при этом стоит", bool(L.НАКОПЛЕНИЕ), str(L.НАКОПЛЕНИЕ))

L.to_commands({"commands": [{"cmd": "STAGE", "off": 1}]})
проверка("отмена отмечена в трассе",
         L.STAGE_ЗА_ТАКТ.get("что") == "отменено", str(L.STAGE_ЗА_ТАКТ))
проверка("после отмены приказа нет", not L.НАКОПЛЕНИЕ)
L.STAGE_ЗА_ТАКТ.clear()

print()

if беды:
    print(f"БЕД: {len(беды)} — {', '.join(беды)}")
    raise SystemExit(1)
print("всё чисто")
