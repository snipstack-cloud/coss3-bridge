# -*- coding: utf-8 -*-
"""Самопроверка третьего повода: «волна дошла до базы врага».

Замысел игрока 21.09: «повод настроил бы на манёвр армией — это сейчас узкое
место». Счёт по девяти партиям `base24` замысел подтвердил и уточнил:

* армия НЕ узкое место: перевес над врагом медианно 1,9 раза (1,3-4,7);
* волн за партию 25, а убивает хоть одного крестьянина лишь каждая девятая
  (25 из 218 волн с замеренным итогом через 90 с, `wave_report.py`);
* но у волн, которые реально ушли от базы, доля убийственных ВТРОЕ выше — 17
  процентов против 5. Дойти решает;
* состав при этом ни при чём: стрелков в `base24` не было ни в одной партии, а
  убийства есть (85 и 40 крестьян в двух партиях) — пехота крестьян догоняет;
* переходов «волна подошла» 12 на девять партий (медиана 2 за партию), волна
  стоит у врага медианно 4 такта (около 94 с), за это время крестьян у врага
  становится БОЛЬШЕ на 5, а дома в этот самый миг стоит медианно 40 свободных
  бойцов, максимум 123.

Отсюда и повод: спросить в миг подхода, пока такт (медиана 21 с, десятая часть
случаев 46 и дольше) до волны не добрался.

Стережётся:
* ловится ПЕРЕХОД через `ДОШЛА_ДО_БАЗЫ`, а не стояние: иначе вопрос повторялся
  бы каждое чтение состояния;
* при выключенном ключе не спрашивается ничего, и счётчик перехода всё равно
  ведётся — иначе первое же включение приняло бы старое стояние за подход;
* все пять ответов переводятся в НАСТОЯЩИЕ команды моста и доживают до
  `to_commands`;
* `reinforce` урезается по свежему числу свободных дома и говорит об этом;
* `retreat` при пустом поле не отдаётся: отзывать некого;
* неизвестное слово не глотается молча;
* честность вопроса: волну в поле нельзя перенаправить, и системный текст
  говорит это прямо.
"""
import llm_policy as L

беды = []


def проверка(имя, условие, пояснение=""):
    if условие:
        print("  ОК    " + имя)
    else:
        беды.append(имя)
        print("  ПЛОХО " + имя + (" — " + str(пояснение)[:400] if пояснение else ""))


def состояние(**правки):
    ст = {
        "gametime": 903, "mil_far": 210, "mil_away": 24, "my_freewar": 40,
        "mil_inf": 64, "mil_shooters": 0, "mil_cav": 0,
        "p1_army": 32, "p1_peasants": 51,
        "en_pea_cells": [{"x": 2, "y": 3, "крестьян": 10, "бойцов_рядом": 32}],
    }
    ст.update(правки)
    return ст


# --- КРЮЧОК ----------------------------------------------------------------
счёт = {}
проверка("первое чтение не будит: сравнивать не с чем",
         L.волна_дошла(состояние(mil_far=210), счёт, 5) is None)
счёт = {}
L.волна_дошла(состояние(mil_far=20, mil_away=0), счёт, 5)     # волна дома
проверка("переход через порог будит",
         L.волна_дошла(состояние(), счёт, 5) == 24)
проверка("стояние у врага НЕ будит второй раз",
         L.волна_дошла(состояние(), счёт, 5) is None)
счёт = {}
L.волна_дошла(состояние(mil_far=20, mil_away=0), счёт, 5)
проверка("волна меньше порога не будит",
         L.волна_дошла(состояние(mil_away=3), счёт, 5) is None)
счёт = {}
L.волна_дошла(состояние(mil_far=20, mil_away=0), счёт, 0)
проверка("при выключенном ключе молчим, но счётчик ведём",
         L.волна_дошла(состояние(), счёт, 0) is None and счёт.get("пришла") is True)
счёт = {}
L.волна_дошла(состояние(mil_far=20, mil_away=0), счёт, 5)
проверка("ушли далеко, но в поле никого — не подход",
         L.волна_дошла(состояние(mil_away=0), счёт, 5) is None)

# --- ВОПРОС ----------------------------------------------------------------
L.УДАР.clear()
L.УДАР.update(тактов=4, крестьян=46, армия=30, волна=30, время=809)
# Прирост крестьян врага считается по СВОЕЙ истории: событие приходит раньше
# такта, и счёт УДАРа в этот миг ещё пуст.
L.ВРАГ_ИСТОРИЯ[:] = [(803.0, 46.0), (843.0, 48.0)]
вопрос = L.ПОВОДЫ["дошли"]["запрос"](состояние(), {}, 24, 20)
проверка("в вопросе есть наши в поле и свободные дома",
         "in_field=24" in вопрос and "home_free=40" in вопрос, вопрос)
проверка("названы потери с подхода", "lost_since=6" in вопрос, вопрос)
проверка("названо прикрытие крестьян числом",
         "guard=32" in вопрос and "peasants_cell=10" in вопрос, вопрос)
проверка("назван РОСТ числа крестьян врага", "their_growth=+3" in вопрос, вопрос)
проверка("назван срок подхода подкрепления", "reinforce_eta_s=105" in вопрос, вопрос)
проверка("вопрос короткий: две строки", len(вопрос.splitlines()) == 2, вопрос)
пусто = L.ПОВОДЫ["дошли"]["запрос"](состояние(en_pea_cells=[], p1_army=None), {}, 24, 0)
проверка("неизвестное остаётся «?», а не нулём",
         "guard=?" in пусто and "enemy_army=?" in пусто, пусто)
L.ВРАГ_ИСТОРИЯ.clear()
без_истории = L.запрос_дошли(состояние(), {}, 24)
проверка("без истории прирост «?», а не ноль",
         "their_growth=?" in без_истории, без_истории)
L.ВРАГ_ИСТОРИЯ.clear()
проверка("системный текст честен про волну в поле",
         "НЕ подчиняется" in L.SYSTEM_ДОШЛИ and "retreat" in L.SYSTEM_ДОШЛИ)
проверка("метка и слова повода на месте",
         L.ПОВОДЫ["дошли"]["метка"](24) == "дошли#24"
         and "подошла к базе врага" in L.ПОВОДЫ["дошли"]["словами"](24))

# --- ОТВЕТЫ ----------------------------------------------------------------
ответ = L.ПОВОДЫ["дошли"]["ответ"]
п = ответ({"что": "reinforce", "сколько": 30, "why": "кулак"}, состояние())
проверка("reinforce -> ATTACK в волну",
         п["commands"] == [{"cmd": "ATTACK", "count": 30, "target": "wave"}], п)
п = ответ({"что": "reinforce", "сколько": 60}, состояние())
проверка("reinforce урезан по свободным и сказано вслух",
         п["commands"][0]["count"] == 40 and "просили 60" in п["why"], п)
п = ответ({"что": "reinforce", "сколько": 0}, состояние())
проверка("reinforce на ноль никого не шлёт", п["commands"] == [], п)
п = ответ({"что": "peasants"}, состояние())
проверка("peasants -> все свободные к крестьянам",
         п["commands"] == [{"cmd": "ATTACK", "count": "all", "target": "peasants"}], п)
п = ответ({"что": "army"}, состояние())
проверка("army -> все свободные на армию",
         п["commands"] == [{"cmd": "ATTACK", "count": "all", "target": "army"}], п)
п = ответ({"что": "retreat"}, состояние())
проверка("retreat -> RETREAT всех дальних",
         п["commands"] == [{"cmd": "RETREAT", "count": "all"}], п)
п = ответ({"что": "retreat"}, состояние(mil_away=0))
проверка("retreat при пустом поле не отдаётся",
         п["commands"] == [] and "отзывать некого" in п["why"], п)
п = ответ({"что": "wait", "why": "бой идёт"}, состояние())
проверка("wait ничего не трогает и говорит об этом",
         п["commands"] == [] and "ЖДУ" in п["why"], п)
п = ответ({"что": "чепуха"}, состояние())
проверка("неизвестный ответ назван вслух",
         п["commands"] == [] and "не знает ответа" in п["why"], п)
п = ответ({"что": "peasants"}, состояние(my_freewar=0))
проверка("посылать некого — сказано вслух",
         п["commands"] == [] and "свободных дома нет" in п["why"], п)

# --- КОМАНДЫ ДОЖИВАЮТ ДО ИГРЫ ----------------------------------------------
for что, ожидание in (("reinforce", ("attack", 30, "wave")),
                      ("peasants", ("attack", 9999, "peasants")),
                      ("army", ("attack", 9999, "army")),
                      ("retreat", ("move", 9999, "retreat"))):
    д = ответ({"что": что, "сколько": 30}, состояние())
    (cmds, attack, why, брак, цель_атаки, движение, цель_движения,
     клетка, контракт, кем_а, кем_д) = L.to_commands(д, None, set(), из_события=True)
    род, число, цель = ожидание
    вышло = ((attack, цель_атаки) if род == "attack" else (движение, цель_движения))
    проверка(f"{что} доживает до to_commands", вышло == (число, цель) and not брак,
             f"{вышло} брак={брак}")

print()
if беды:
    print(f"БЕД: {len(беды)} — {', '.join(беды)}")
    raise SystemExit(1)
print("всё чисто")
