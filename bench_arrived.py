# -*- coding: utf-8 -*-
"""Годится ли модель для событийного вызова «волна дошла».

Стенд-близнец `bench_hands.py`, тот же порядок и те же правила счёта. Вопрос
узкий: около 170 знаков против ~7000 токенов у обычного такта, ответ короткой
схемой {"что","сколько","why"}.

Верного ответа у этого вопроса нет — он зависит от замысла партии, — поэтому
меряется ГОДНОСТЬ: примет ли мост ответ и превратится ли он в настоящую команду
(`дошли_в_команды` + `to_commands`). Отдельно считается то, ради чего повод и
заводился:

  * СКОЛЬКО РАЗ ВЫБРАНО «wait». Стоящая у врага волна тает, а крестьян у него
    становится больше: если модель почти всегда ждёт, повод не нужен;
  * ОТВЕТ, КОГДА ГОНКА ПРОИГРЫВАЕТСЯ — крестьян у врага становится БОЛЬШЕ, а
    волна стоит. Это 34 задачи из 44, то есть обычное положение дел, и «wait»
    там значит «соглашаюсь проигрывать». Прикрытие, вопреки ожиданию, редко
    бывает большим: guard медианно 25 и превышает нашу волну лишь в 3 задачах
    из 44 — численно мы у его крестьян сильнее, а убить не выходит;
  * распределение ответов целиком, отдельно по настоящим ПОДХОДАМ.

    python3 bench_arrived.py <модель> [<модель> ...]   # локальные, через ollama
    python3 bench_arrived.py --облако <id>             # через OPENROUTER_BASE_URL
    python3 bench_arrived.py --задачи <файл.json> ...  # свой набор задач
"""
import json
import os
import statistics as stx
import sys
import time
import urllib.request

# Путь к мосту берём ОТ ЭТОГО ФАЙЛА, а не абсолютом: иначе копия стенда из git
# worktree молча импортирует llm_policy рабочей копии и померит не ту версию.
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import llm_policy as L

АДРЕС = "http://localhost:11434/api/generate"
ЧТО = list(L.ЧТО_ДОШЛИ)


def спросить_локально(модель, промпт, таймаут=180):
    """Со СХЕМОЙ: единственная ошибка локальных моделей на узком вопросе —
    выдуманное слово, и перечисление закрывает её целиком. `keep_alive`
    обязателен, иначе замер меряет загрузку весов с диска."""
    тело = {"model": модель, "prompt": L.SYSTEM_ДОШЛИ + "\n\n" + промпт,
            "stream": False, "keep_alive": "10m",
            "options": {"num_predict": 80, "num_ctx": 2048, "temperature": 0},
            "format": {"type": "object",
                       "properties": {"что": {"type": "string", "enum": ЧТО},
                                      "сколько": {"type": "integer"},
                                      "why": {"type": "string"}},
                       "required": ["что", "сколько"]}}
    t = time.time()
    d = json.load(urllib.request.urlopen(urllib.request.Request(
        АДРЕС, json.dumps(тело).encode(),
        {"Content-Type": "application/json"}), timeout=таймаут))
    return d.get("response", ""), time.time() - t


def спросить_облако(клиент, модель, промпт):
    t = time.time()
    d = L.ask(клиент, модель, промпт, False, system=L.SYSTEM_ДОШЛИ)
    return json.dumps(d, ensure_ascii=False), time.time() - t


def разобрать(текст):
    i, j = текст.find("{"), текст.rfind("}")
    if i < 0 or j <= i:
        return None
    try:
        return json.loads(текст[i:j + 1])
    except json.JSONDecodeError:
        return None


def годен(d, задача):
    """Примет ли мост этот ответ и дойдёт ли он до игры. (годен, причина)."""
    if not isinstance(d, dict):
        return False, "не JSON"
    что = str(d.get("что") or "").strip().lower()
    if что not in ЧТО:
        return False, f"неизвестное «{что}»"
    перевод = L.дошли_в_команды(d, задача["состояние"])
    if что == "wait":
        return True, "ждать"
    if not перевод.get("commands"):
        return False, "мост ответ не принял: " + перевод.get("why", "")[:40]
    итог = L.to_commands(перевод, None, set(), из_события=True)
    attack, брак, движение = итог[1], итог[3], итог[5]
    if брак:
        return False, f"брак при разборе: {брак}"
    if not attack and not движение:
        return False, "до игры не доехало ни атаки, ни движения"
    return True, ""


def проигрываем(задача):
    """Гонка проигрывается: крестьян у врага становится больше, а мы стоим."""
    строка = задача["запрос"]
    числа = {}
    for кусок in строка.replace("\n", " ").split():
        если = кусок.split("=")
        if len(если) == 2:
            числа[если[0]] = если[1]
    try:
        рост = float(числа.get("their_growth", "?"))
    except ValueError:
        return False
    return рост > 0


def прогон(имя, спросить, задачи):
    годных, времена, ответы = 0, [], []
    выбор, выбор_подход, при_проигрыше = {}, {}, {}
    for з in задачи:
        try:
            текст, сек = спросить(з["запрос"])
        except Exception as e:
            print(f"    gt={з['gt']:>4}  СБОЙ: {str(e)[:60]}")
            ответы.append(None)
            continue
        d = разобрать(текст) or {}
        ок, причина = годен(d, з)
        времена.append(сек)
        годных += int(ок)
        ответы.append(d)
        что = str(d.get("что", "-"))
        выбор[что] = выбор.get(что, 0) + 1
        if з["вид"] == "подход":
            выбор_подход[что] = выбор_подход.get(что, 0) + 1
        if проигрываем(з):
            при_проигрыше[что] = при_проигрыше.get(что, 0) + 1
        print(f"    gt={з['gt']:>4} {з['вид']:>6} поле={з['в_поле']:>3} дома={з['дома']:>3}  "
              f"{сек:5.1f} с  {'ГОДЕН' if ок else 'НЕТ  '}  {что:>9} {d.get('сколько', '')}"
              + (f"   [{причина}]" if причина and причина != "ждать" else ""))
    if not времена:
        print(f"  {имя}: нет ответов")
        return {"модель": имя, "время": None}
    def строкой(d):
        return ", ".join(f"{к} {n}" for к, n in sorted(d.items(), key=lambda x: -x[1]))
    print(f"  {имя}: годных {годных}/{len(задачи)}, медиана {stx.median(времена):.1f} с")
    print(f"    выбор: {строкой(выбор)}")
    print(f"    на настоящих подходах: {строкой(выбор_подход)}")
    print(f"    когда крестьян у врага прибавляется: {строкой(при_проигрыше)}")
    return {"модель": имя, "годных": годных, "всего": len(задачи), "выбор": выбор,
            "подход": выбор_подход, "проигрыш": при_проигрыше,
            "время": stx.median(времена), "ответы": ответы}


def main():
    арг = sys.argv[1:]
    файл = None
    if "--задачи" in арг:
        i = арг.index("--задачи")
        файл = арг[i + 1]
        del арг[i:i + 2]
    свой = os.path.dirname(os.path.abspath(__file__))
    задачи = (json.load(open(файл, encoding="utf-8")) if файл else
              json.loads(os.popen(
                  f"{sys.executable} {os.path.join(свой, 'bench_arrived_cases.py')}"
                  f" 2>/dev/null").read()))
    if not задачи:
        raise SystemExit("задач НЕТ — проверьте каталог трасс, молча мерить нечего")
    print(f"задач: {len(задачи)} (подходов "
          f"{sum(1 for з in задачи if з['вид'] == 'подход')}), длина запроса "
          f"{min(len(з['запрос']) for з in задачи)}-{max(len(з['запрос']) for з in задачи)} знаков")
    итоги = []
    if "--облако" in арг:
        i = арг.index("--облако")
        модель = арг[i + 1]
        from openai import OpenAI
        клиент = OpenAI(base_url=L.BASE_URL, api_key=os.environ["OPENROUTER_API_KEY"])
        print(f"\n  облако {модель}")
        итоги.append(прогон(модель, lambda p: спросить_облако(клиент, модель, p), задачи))
    else:
        for модель in арг:
            print(f"\n  {модель}")
            итоги.append(прогон(модель, lambda p, м=модель: спросить_локально(м, p), задачи))
    print()
    for и in итоги:
        if и["время"] is None:
            print(f"{и['модель']}: нет ответов")
            continue
        print(f"{и['модель']:>18}: годных {и['годных']}/{и['всего']}, "
              f"медиана {и['время']:.1f} с, ждать "
              f"{и['выбор'].get('wait', 0)}/{и['всего']}")


if __name__ == "__main__":
    main()
