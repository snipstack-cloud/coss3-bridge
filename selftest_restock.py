# -*- coding: utf-8 -*-
"""Самопроверка третьего повода: «еда вернулась — купи пачку числом».

Заведён 21.09 по вопросу игрока и находке того же дня. Механика движка:
конечный заказ списывает стоимость ВПЕРЁД за всю пачку (lib/unit.script:6045,
цикл _unit_ApplyCostByID по amount), а бесконечный платит ПОШТУЧНО при старте
каждого (doprogressorders.inc:210, под условием amount = produce_infinite).
Значит пачка переживает падение запаса, а бесконечный заказ встаёт.

[замер] 9 партий base24: модель отдала 191 бесконечный приказ и НИ ОДНОГО
конечного — механизмом не пользовалась ни разу. Переходов еды через 500 вверх
1-4 за партию (медиана 2), тактов с едой под порогом 5-14. Момент редкий и
потому событийный, а не второй такт.

Стережётся: срабатывание ТОЛЬКО на переходе; молчание при выключенном ключе;
что в запросе названо, сколько бойцов по карману и ЧТО кончится первым; что
ответ становится КОНЕЧНЫМ заказом, а отрицательное число отвергается вслух.
"""
import llm_policy as L

беды = []


def проверка(имя, условие, пояснение=""):
    if условие:
        print("  ОК    " + имя)
    else:
        беды.append(имя)
        print("  ПЛОХО " + имя + (" — " + пояснение if пояснение else ""))


СОСТОЯНИЕ = {
    "gametime": 700, "food": 900, "gold": 400, "iron": 300, "coal": 1000,
    "ba17": 1, "stables": 0, "mil_inf": 12, "mil_shooters": 0,
    "fighters": ("infantry17=pikeman,hp90,atk8,wkind1,pause0,rmax188,dpike3,"
                 "dsword2,dbullet4,food25,gold3,iron20,coal0 "
                 "musk17=musketeernet,hp65,atk10,wkind3,pause375,rmax1500,"
                 "dpike1,dsword1,dbullet0,food50,gold8,iron4"),
}

# --- СРАБАТЫВАНИЕ: только переход снизу вверх
счёт = {}
шаг = lambda еда, вкл=1: L.еда_вернулась({"gametime": 1, "food": еда}, счёт, вкл)
проверка("первый вызов молчит (нет прошлого)", шаг(300) is None,
         "иначе сытая партия подняла бы событие на первом же чтении")
проверка("под порогом молчит", шаг(400) is None)
проверка("ПЕРЕХОД вверх поднимает событие", шаг(600) == 600)
проверка("выше порога второй раз НЕ поднимает", шаг(900) is None,
         "иначе это порог по уровню, то есть второй такт")
проверка("падение вниз само по себе молчит", шаг(200) is None)
проверка("повторный переход снова поднимает", шаг(700) == 700)

счёт2 = {}
L.еда_вернулась({"gametime": 1, "food": 300}, счёт2, 0)
проверка("при выключенном ключе молчит",
         L.еда_вернулась({"gametime": 2, "food": 900}, счёт2, 0) is None,
         "без --restock мост обязан вести себя как база")

# --- ЗАПРОС
з = L.запрос_запаса(СОСТОЯНИЕ, СОСТОЯНИЕ, 900)
проверка("запрос КОРОТКИЙ", len(з) < 1200, f"{len(з)} символов")
проверка("названо, что еда вернулась", "ЕДА ВЕРНУЛАСЬ" in з)
проверка("назван порог", str(L.ПОРОГ_ЕДЫ) in з)
строки = [x.strip() for x in з.splitlines()]
пик = next((x for x in строки if x.startswith("infantry17,")), "")
мушк = next((x for x in строки if x.startswith("musk17,")), "")
проверка("пикинёр в таблице с ценой", пик.startswith("infantry17,25,3,20,"), пик)
проверка("сколько по карману посчитано", пик.split(",")[-2] == "15",
         f"900/25=36 еды, 400/3=133 золота, 300/20=15 железа -> 15; вышло {пик}")
проверка("названо, ЧТО кончится первым", пик.endswith(",iron"),
         "без этого «можно 15» ничего не объясняет")
проверка("у мушкетёра предел другой", мушк.endswith(",food"), мушк)

СТ_БЕЗ = dict(СОСТОЯНИЕ, ba17=0, stables=0)
проверка("без кующих зданий покупать негде",
         "покупать негде" in L.запрос_запаса(СТ_БЕЗ, СТ_БЕЗ, 900),
         "предлагать бойца без казармы значит звать в пустоту")
проверка("конница без конюшни не предлагается",
         "dragoon17" not in з, "её куёт конюшня, а её нет")

# --- ОТВЕТ
р = L.запас_в_команды({"кого": "infantry17", "сколько": 12, "why": "п"}, СОСТОЯНИЕ)
проверка("ответ даёт КОНЕЧНЫЙ заказ",
         len(р["commands"]) == 1 and р["commands"][0]["total"] == 12,
         "ради конечного заказа повод и заведён")
проверка("положительное число НЕ превращается в бесконечность",
         р["commands"][0]["total"] > 0)

о = L.запас_в_команды({"кого": "infantry17", "сколько": -1, "why": "б"}, СОСТОЯНИЕ)
проверка("отрицательное число отвергнуто", о["commands"] == [])
проверка("и отвергнуто ВСЛУХ", "не годится" in о["why"],
         "молчаливый отброс неотличим от бездействия")
проверка("незнакомый боец не глотается",
         "не знает" in L.запас_в_команды({"кого": "кирпич", "сколько": 5,
                                          "why": "?"}, СОСТОЯНИЕ)["why"])
проверка("wait понимается",
         L.запас_в_команды({"кого": "wait", "why": "ж"}, СОСТОЯНИЕ)["commands"] == [])

# --- РЕЕСТР И ЦИКЛ
проверка("повод в реестре", "запас" in L.ПОВОДЫ)
проверка("у повода все пять частей",
         set(L.ПОВОДЫ["запас"]) >= {"system", "запрос", "метка", "словами", "ответ"})
проверка("метка годна для счёта по серии",
         L.ПОВОДЫ["запас"]["метка"](900) == "запас#900")
исх = open("llm_policy.py", encoding="utf-8").read()
проверка("счётчик еды ведётся ВСЕГДА, не только при своём событии",
         "_вернулась = еда_вернулась(st, запас_еды, запас_вкл)" in исх
         and "if not СОБЫТИЕ and _вернулась:" in исх,
         "иначе первый переход после чужого события потеряется")
проверка("в системной строке сказано, ЗАЧЕМ числом",
         "ВПЕРЁД" in L.SYSTEM_ЗАПАС and "ПОШТУЧНО" in L.SYSTEM_ЗАПАС)
проверка("сказано про голод",
         "голод" in L.SYSTEM_ЗАПАС,
         "пачка не должна съесть весь запас: деревня ест каждую секунду")

print()
if беды:
    print(f"БЕД: {len(беды)} — {', '.join(беды)}")
    raise SystemExit(1)
print("всё чисто")
