# -*- coding: utf-8 -*-
"""Самопроверка блока «Что держит план».

Наблюдение игрока 19.09: модель копит еду, которая не тратится, и при этом не
может купить вторую казарму. Замер живой партии: на золоте РОВНО ПЯТЬ человек
девять минут подряд, еда 2 370 -> 44 705, казарма (2500 золота) заказана за три
секунды до горизонта.

Что здесь стережётся:
* при голоде блок молчит — там своя тревога, и «еды впрок» было бы ложью;
* узкое место названо по НЕДОСТАЮЩЕМУ ресурсу, а не по самому дешёвому;
* ноль добытчиков назван отдельно: «само не накопится»;
* числа «снять с еды N человек» в блоке НЕТ — она круговая и всегда давала
  «почти всех» (поймано при первой же проверке на живых состояниях).
"""
import llm_policy as L

беды = []


def проверка(имя, условие, пояснение=""):
    if условие:
        print("  ОК    " + имя)
    else:
        беды.append(имя)
        print("  ПЛОХО " + имя + (" — " + пояснение if пояснение else ""))


def текст(food=20000, gold=1000, on_food=40, on_gold=5, dt=20,
          food_было=None, gold_было=None):
    было = {"gametime": 300, "food": food if food_было is None else food_было,
            "gold": gold if gold_было is None else gold_было,
            "wood": 2000, "stone": 2000, "iron": 2000, "coal": 2000}
    st = {"gametime": 300 + dt, "food": food, "gold": gold,
          "wood": 2000, "stone": 2000, "iron": 2000, "coal": 2000,
          "on_food": on_food, "on_gold": on_gold, "peasants": 60,
          "ba17": 1, "mills": 1,
          # цена СЛЕДУЮЩЕЙ казармы — впятеро дороже первой (costpercent=500)
          "build_cost": "ba17=wood500,stone500,gold2500 minegold=wood200,gold300"}
    return "\n".join(L.узкое_место(st, было))


print("Самопроверка узкого места:")

т = текст(food=20000, gold=1000, on_food=40, on_gold=5,
          food_было=19000, gold_было=900)
проверка("излишек еды назван", "ЕДЫ 20000" in т, т)
проверка("узкое место — золото", "УЗКОЕ МЕСТО — ЗОЛОТО" in т, т)
проверка("названа НЕХВАТКА, а не запас", "не хватает 1500" in т, т)
проверка("сказано, сколько людей на узком ресурсе", "5 человек" in т, т)

т0 = текст(food=20000, gold=1000, on_food=40, on_gold=0,
           food_было=19000, gold_было=1000)
проверка("ноль добытчиков назван отдельно", "НЕТ НИ ОДНОГО человека" in т0, т0)

тг = текст(food=300, gold=1000, on_food=5, on_gold=5,
           food_было=500, gold_было=900)
проверка("при голоде про излишек еды молчим", "ЕДЫ 300" not in тг, тг)

тб = текст(food=20000, gold=9000, on_food=40, on_gold=5,
           food_было=19000, gold_было=8900)
проверка("когда всего хватает, узкого места нет",
         "УЗКОЕ МЕСТО" not in тб, тб)

проверка("круговое число «снять с еды» НЕ вернулось",
         "СНЯТЬ С ЕДЫ" not in т, т)

проверка("без прошлого такта блок молчит", L.узкое_место({"food": 1}, None) == [],
         "приход считать не из чего")

print()
if беды:
    print(f"БЕД: {len(беды)} — {', '.join(беды)}")
    raise SystemExit(1)
print("всё чисто")
