# -*- coding: utf-8 -*-
"""Общее для стендов: как звать ДУМАЮЩУЮ локальную модель.

Заведено 22.09, когда на стенд попала `qwen3:30b-a3b`. Её счёт на прежних
условиях был бы 0 из 24, и это счёт СТЕНДА, а не модели:

  * потолок ответа. `num_predict` 60-200 хватает нежующим 7-14B, а здесь
    рассуждение занимает 250-500 слов, и JSON не начинается вовсе;
  * ключ `think: false` рассуждение НЕ ВЫКЛЮЧАЕТ — оно просто переезжает в
    `response` и обрывается там же. Выключить его у этой модели нельзя,
    можно только отвести ему отдельное поле (`think: true`) и дать запас;
  * СО СХЕМОЙ (`format`) ollama кладёт ГОТОВЫЙ ОТВЕТ в поле `thinking`, а
    `response` оставляет ПУСТЫМ. Стенд, читающий только `response`, объявит
    0 из 11 модели, которая ответила верно за 0,7 с. Поймано 22.09 на найме.

Поэтому стенд спрашивает саму ollama, думающая ли модель, и правит запрос.
Для нежующих не меняется ничего — прежние числа остаются сравнимыми.
"""
import json, urllib.request, os

АДРЕС_БАЗА = os.environ.get("OLLAMA_URL", "http://localhost:11434")
ЗАПАС = 2500          # хватило самой длинной думе стенда удара (509 слов)
# Предел на словесное объяснение в схеме. Ставится ВСЕМ, не только думающим:
# разливается `why` у любой модели, а мосту оно не нужно длиннее строки.
ПРЕДЕЛ_ПОЧЕМУ = {"type": "string", "maxLength": 120}
_ПАМЯТЬ = {}


def думающая(модель, таймаут=30):
    """Есть ли у модели способность `thinking`. Спрашиваем ollama, не гадаем."""
    if модель in _ПАМЯТЬ:
        return _ПАМЯТЬ[модель]
    try:
        d = json.load(urllib.request.urlopen(urllib.request.Request(
            АДРЕС_БАЗА + "/api/show", json.dumps({"model": модель}).encode(),
            {"Content-Type": "application/json"}), timeout=таймаут))
        ответ = "thinking" in (d.get("capabilities") or [])
    except Exception:
        ответ = False      # не смогли спросить — ведём себя как раньше
    _ПАМЯТЬ[модель] = ответ
    return ответ


def поправить(тело, модель, запас=ЗАПАС):
    """Дописать в тело запроса то, без чего думающая модель не ответит.

    `think: true` ставится ТОЛЬКО без схемы. Со схемой рассуждения не будет
    в любом случае — грамматика ведёт модель в JSON с первого токена, — а
    ответ уедет в поле `thinking`; забирает его оттуда `вынуть`.
    """
    if not думающая(модель):
        return тело
    if "format" in тело:
        # Со схемой рассуждения не будет, и поднимать потолок НЕ НАДО: он
        # только даёт модели убежать. 22.09 на найме `why` разлилось на 2500
        # токенов и оборвало JSON на полуслове — 57 с вместо 1,7. Предел
        # длины на `why` ставит сам стенд (`ПРЕДЕЛ_ПОЧЕМУ`).
        return тело
    тело["think"] = True
    тело.setdefault("options", {})["num_predict"] = запас
    return тело


def вынуть(d):
    """Ответ модели, где бы ollama его ни положила.

    Пустой `response` при непустом `thinking` — это ответ под схемой, а не
    молчание модели. Путать их нельзя: первое говорит о раскладке полей,
    второе о самой модели.
    """
    о = d.get("response") or ""
    return о if о.strip() else (d.get("thinking") or "")


def дума(d):
    """Сколько слов ушло в рассуждение (0, если ответ лежит в `thinking`)."""
    return 0 if (d.get("response") or "").strip() == "" else len((d.get("thinking") or "").split())
