# -*- coding: utf-8 -*-
"""Сверка калькулятора боя с реальными потерями по трассам.

Эпизод боя = отрезок частых снимков (`coss3_snap.jsonl`, шаг ~5 игровых с), на
котором растут счётчики `my_mil_lost` / `p1_mil_lost`; разрывы до двух снимков
склеиваются. Факт эпизода — отношение потерь K = его_потери / наши_потери.

Предсказания (одно и то же K, четырьмя законами):
  КАЧЕСТВО   — только характеристики: K = (наш_dps_на_голову / его_hp) / (его_dps_на_голову / наш_hp).
               Закон «свалки»: бьётся столько, сколько влезает в фронт, числа не важны.
  ГЛОБАЛЬНО  — КАЧЕСТВО * (наших всего / его всего). Закон «все дерутся».
  ЛОКАЛЬНО   — КАЧЕСТВО * (наших в клетках боя / его в клетках боя), пик за эпизод.
  ER МОСТА   — 1 / размен из снимка (дуэль пикинёр на пикинёр), что мост даёт модели.

Характеристики берутся из ближайшего предшествующего такта `coss3_bot.jsonl`
(`fighters` / `p1_fighters`), потому что апгрейды меняют их по ходу партии.

    python3 validate_combat.py <корень с прогонами> [ещё корни...] [--his-bonus УРОН ЩИТ] [--dump]

ИТОГ 24.09.2026 по 52 партиям 22-24.09 (329 эпизодов, потерь наших 8306, его 3394):
  * без поправок калькулятор переоценивает нас ВТРОЕ: медиана log2(факт/предсказание)
    -1,44 по всем эпизодам, -1,64 у его базы, -1,43 в поле и +0,03 у нашей базы (17 эпизодов);
  * численный перевес на факт потерь не влияет: медиана K_факт 0,22 во всех корзинах
    перевеса от 0,7 до 2+, закон «все дерутся» (ГЛОБАЛЬНО) хуже закона «качество»;
  * недостающая механика — СТРОЙ ВРАГА: у отряда с офицером `damage := damage+bonus`
    (`lib/miscext2.script:428-431`) и щит `:351-353`; линейные построения дают +2/+2 в
    движении и +7/+7 в обороне (`game/var/formations.cfg`, LINE15..LINE196). Враг обучает
    офицеров и барабанщиков в 40 партиях из 52. С поправкой --his-bonus 2 2 смещение
    -1,44 -> -0,14, попаданий в пределах 2 раз 25% -> 40%, ЛОКАЛЬНО в поле смещение 0,00;
    +7/+7 перебарщивает (+1,58), то есть он дерётся в строю НА ХОДУ, а не стоя;
  * что остаётся: разброс. Медиана |ошибки| 1,26 log2 (2,4 раза), Спирмен 0,35-0,6.
    Локальные числа в клетках боя предсказывают лучше глобальных, но 176 эпизодов из
    329 упираются в насыщение клетки «+» (36 и больше).
"""
import glob
import json
import math
import os
import statistics as S
import sys

sys.path.insert(0, os.path.expanduser("~/coss3-bridge"))
import combat_math as CM  # noqa: E402

СОСТАВ_НАШ = {"infantry17": "mil_inf", "musk17": "mil_shooters", "dragoon17": "mil_cav"}
СОСТАВ_ЕГО = {"infantry17": "p1_inf", "musk17": "p1_shoot", "dragoon17": "p1_cav"}
МИН_ПОТЕРЬ = 4        # эпизоды мельче — шум одиночных смертей
РАЗРЫВ = 2            # снимков без потерь, которые ещё считаются тем же боем
СГЛАЖИВАНИЕ = 0.5     # чтобы log(0) не ломал счёт


def ч(v):
    try:
        return float(v or 0)
    except (TypeError, ValueError):
        return 0.0


def читать(путь):
    for строка in open(путь, encoding="utf-8"):
        строка = строка.strip()
        if строка:
            try:
                yield json.loads(строка)
            except json.JSONDecodeError:
                continue


def такты(путь):
    из = []
    for r in читать(путь):
        st = r.get("state")
        if isinstance(st, dict) and "gametime" in st and st.get("fighters") and st.get("p1_fighters"):
            из.append(st)
    из.sort(key=lambda s: ч(s["gametime"]))
    return из


def ближайший_такт(тк, gt):
    лучший = None
    for st in тк:
        if ч(st["gametime"]) <= gt:
            лучший = st
        else:
            break
    return лучший or (тк[0] if тк else None)


БОНУС_УРОН = 0     # поправка на строй врага: к его атаке
БОНУС_ЩИТ = 0      # и к его защите по всем типам оружия


def сторона(числа, карта, характеристики, бонус_урон=0, бонус_щит=0):
    """[(n, х)] по видам с ненулевым числом и известной атакой."""
    из = []
    for вид, поле in карта.items():
        n = int(ч(числа.get(поле)))
        х = характеристики.get(вид)
        if n > 0 and х and х.get("atk"):
            if бонус_урон or бонус_щит:
                х = dict(х)
                х["atk"] = int(х["atk"]) + бонус_урон
                for k in ("dpike", "dsword", "dbullet"):
                    х[k] = int(х.get(k) or 0) + бонус_щит
            из.append((n, х))
    return из


def смесь(виды):
    всего = sum(n for n, _ in виды)
    return [(n / всего, х) for n, х in виды] if всего else []


def dps_на_голову(виды, цели):
    """Средний урон в «удар» одного бойца стороны по смеси целей.

    Паузы у пехоты нулевые с обеих сторон, поэтому считаем по ударам, как и
    `combat_math.групповой_размен` при несопоставимых паузах. Стрелков в этих
    партиях почти нет, и на итог это не влияет; отмечено в выводе.
    """
    с = смесь(цели)
    всего = sum(n for n, _ in виды)
    if not всего or not с:
        return 0.0
    return sum(n * CM._урон_по_смеси(х, с) for n, х in виды) / всего


def hp_на_голову(виды):
    всего = sum(n for n, _ in виды)
    return sum(n * int(х.get("hp") or 1) for n, х in виды) / всего if всего else 0.0


def качество(A, B):
    """K по одним характеристикам: сколько его голов падает на одну нашу при равных числах."""
    наш = dps_на_голову(A, B)
    его = dps_на_голову(B, A)
    hpA, hpB = hp_на_голову(A), hp_на_голову(B)
    if not (наш and его and hpA and hpB):
        return None
    return (наш / hpB) / (его / hpA)


def эпизоды(снимки):
    """Индексы [i0, i1] отрезков с потерями; окно берётся от i0-1 до i1."""
    из = []
    тек = None
    last = -10
    for i in range(1, len(снимки)):
        a, b = снимки[i - 1], снимки[i]
        d = (ч(b.get("my_mil_lost")) - ч(a.get("my_mil_lost"))) + (ч(b.get("p1_mil_lost")) - ч(a.get("p1_mil_lost")))
        if d > 0:
            if тек is None or i - last > РАЗРЫВ:
                if тек:
                    из.append(тек)
                тек = [i - 1, i]
            else:
                тек[1] = i
            last = i
    if тек:
        из.append(тек)
    return из


def разбор_партии(каталог):
    снап = os.path.join(каталог, "coss3_snap.jsonl")
    бот = os.path.join(каталог, "coss3_bot.jsonl")
    if not (os.path.exists(снап) and os.path.exists(бот)):
        return []
    снимки = sorted(читать(снап), key=lambda x: ч(x.get("gametime")))
    снимки = [x for x in снимки if "my_mil_lost" in x and "p1_mil_lost" in x]
    тк = такты(бот)
    if len(снимки) < 3 or not тк:
        return []
    строки = []
    for i0, i1 in эпизоды(снимки):
        a, b = снимки[i0], снимки[i1]
        наши_п = ч(b["my_mil_lost"]) - ч(a["my_mil_lost"])
        его_п = ч(b["p1_mil_lost"]) - ч(a["p1_mil_lost"])
        if наши_п + его_п < МИН_ПОТЕРЬ:
            continue
        st = ближайший_такт(тк, ч(a["gametime"]))
        наши_х = CM.разобрать(st.get("fighters"))
        его_х = CM.разобрать(st.get("p1_fighters"))
        A = сторона(a, СОСТАВ_НАШ, наши_х)
        B = сторона(a, СОСТАВ_ЕГО, его_х, БОНУС_УРОН, БОНУС_ЩИТ)
        k_кач = качество(A, B)
        if not k_кач:
            continue
        n_наш = sum(n for n, _ in A)
        n_его = sum(n for n, _ in B)
        # локальные числа: пик суммы по клеткам боя за окно; «+» в клетке = 36 и это нижняя граница
        лок_наш = лок_его = 0
        насыщено = False
        for x in снимки[i0:i1 + 1]:
            кл = x.get("бой") or []
            s1 = sum(к[2] for к in кл)
            s2 = sum(к[3] for к in кл)
            if s1 + s2 > лок_наш + лок_его:
                лок_наш, лок_его = s1, s2
            if any(к[2] >= 36 or к[3] >= 36 for к in кл):
                насыщено = True
        # где дрались: расстояние клеток боя до нашей ратуши (в клетках)
        cx, cy = ч(st.get("my_cx")), ч(st.get("my_cy"))
        дист = None
        for x in снимки[i0:i1 + 1]:
            for к in (x.get("бой") or []):
                d = math.hypot(к[0] - cx, к[1] - cy)
                дист = d if дист is None else min(дист, d)
        место = "нет клеток" if дист is None else ("дома" if дист <= 3 else ("в поле" if дист <= 8 else "у него"))
        er = ч(a.get("размен")) or None
        строки.append({
            "партия": каталог, "gt": int(ч(a["gametime"])), "длина": int(ч(b["gametime"]) - ч(a["gametime"])),
            "наши_п": наши_п, "его_п": его_п,
            "n_наш": n_наш, "n_его": n_его, "лок_наш": лок_наш, "лок_его": лок_его, "насыщено": насыщено,
            "место": место,
            "K_факт": (его_п + СГЛАЖИВАНИЕ) / (наши_п + СГЛАЖИВАНИЕ),
            "K_качество": k_кач,
            "K_глобально": k_кач * n_наш / n_его if n_его else None,
            "K_локально": (k_кач * лок_наш / лок_его) if (лок_его and лок_наш and not насыщено) else None,
            "K_er": (1 / er) if er else None,
        })
    return строки


def ранги(xs):
    порядок = sorted(range(len(xs)), key=lambda i: xs[i])
    r = [0.0] * len(xs)
    i = 0
    while i < len(порядок):
        j = i
        while j + 1 < len(порядок) and xs[порядок[j + 1]] == xs[порядок[i]]:
            j += 1
        for k in range(i, j + 1):
            r[порядок[k]] = (i + j) / 2 + 1
        i = j + 1
    return r


def спирмен(x, y):
    if len(x) < 3:
        return None
    rx, ry = ранги(x), ранги(y)
    mx, my = S.mean(rx), S.mean(ry)
    num = sum((a - mx) * (b - my) for a, b in zip(rx, ry))
    den = math.sqrt(sum((a - mx) ** 2 for a in rx) * sum((b - my) ** 2 for b in ry))
    return num / den if den else None


def оценка(строки, ключ):
    пары = [(math.log2(s[ключ]), math.log2(s["K_факт"])) for s in строки if s.get(ключ)]
    if len(пары) < 5:
        return None
    p, f = zip(*пары)
    ошибки = [b - a for a, b in пары]
    # знак: кто потерял больше; ничьи (|log2 K| < 0.3, то есть в пределах 1,23 раза) не судим
    судимые = [(a, b) for a, b in пары if abs(b) >= 0.3]
    знак = (sum(1 for a, b in судимые if (a > 0) == (b > 0)) / len(судимые)) if судимые else None
    return {
        "n": len(пары), "спирмен": спирмен(list(p), list(f)),
        "знак": знак, "знак_n": len(судимые),
        "медиана_ошибки_log2": S.median(ошибки),
        "медиана_abs_log2": S.median(abs(e) for e in ошибки),
        "в_пределах_x2": sum(1 for e in ошибки if abs(e) <= 1) / len(ошибки),
    }


def печать_оценок(строки, заголовок):
    print(f"\n{заголовок}: эпизодов {len(строки)}")
    print("%-12s%5s%9s%14s%12s%12s%10s" % ("закон", "n", "спирмен", "знак верен", "смещение", "|ошибка|", "в 2 раза"))
    for ключ in ("K_качество", "K_глобально", "K_локально", "K_er"):
        о = оценка(строки, ключ)
        if not о:
            print("%-12s   мало данных" % ключ[2:])
            continue
        print("%-12s%5d%9.2f%9.0f%% (%3d)%+12.2f%12.2f%9.0f%%" % (
            ключ[2:], о["n"], о["спирмен"] or 0, 100 * (о["знак"] or 0), о["знак_n"],
            о["медиана_ошибки_log2"], о["медиана_abs_log2"], 100 * о["в_пределах_x2"]))


def main(корни):
    строки = []
    партий = 0
    for корень in корни:
        for снап in sorted(glob.glob(os.path.join(корень, "**", "coss3_snap.jsonl"), recursive=True)):
            s = разбор_партии(os.path.dirname(снап))
            партий += 1
            строки.extend(s)
    if not строки:
        print("эпизодов не нашлось")
        return
    print(f"партий {партий}, эпизодов боя с потерями >= {МИН_ПОТЕРЬ}: {len(строки)}")
    print(f"потерь всего: наших {sum(s['наши_п'] for s in строки):.0f}, его {sum(s['его_п'] for s in строки):.0f}")
    print(f"эпизодов с насыщенной клеткой («+»): {sum(1 for s in строки if s['насыщено'])}")
    print("K = его потери / наши потери; смещение = медиана log2(факт/предсказание): "
          "плюс — враг теряет больше, чем предсказано.")
    печать_оценок(строки, "ВСЕ ЭПИЗОДЫ")
    for место in ("дома", "в поле", "у него", "нет клеток"):
        ч_ = [s for s in строки if s["место"] == место]
        if len(ч_) >= 8:
            печать_оценок(ч_, f"МЕСТО: {место}")
    крупные = [s for s in строки if s["наши_п"] + s["его_п"] >= 20]
    if len(крупные) >= 8:
        печать_оценок(крупные, "КРУПНЫЕ БОИ (потерь >= 20)")
    # распределение факта по перевесу числом: подсказка, какой закон ближе
    print("\nФАКТ ПО КОРЗИНАМ ЧИСЛЕННОГО ПЕРЕВЕСА (наших всего / его всего), медиана K_факт и K_качество:")
    корзины = [(0, 0.7), (0.7, 1.0), (1.0, 1.4), (1.4, 2.0), (2.0, 99)]
    for lo, hi in корзины:
        ч_ = [s for s in строки if s["n_его"] and lo <= s["n_наш"] / s["n_его"] < hi]
        if ч_:
            print("  %4.1f..%-4.1f n=%3d  K_факт %.2f  K_качество %.2f  K_глобально %.2f" % (
                lo, hi, len(ч_), S.median(s["K_факт"] for s in ч_), S.median(s["K_качество"] for s in ч_),
                S.median(s["K_глобально"] for s in ч_)))
    if "--dump" in sys.argv:
        with open("эпизоды.jsonl", "w", encoding="utf-8") as f:
            for s in строки:
                f.write(json.dumps(s, ensure_ascii=False) + "\n")
        print("\nэпизоды записаны в эпизоды.jsonl")


if __name__ == "__main__":
    корни = [a for a in sys.argv[1:] if not a.startswith("--") and not a.isdigit()]
    if "--his-bonus" in sys.argv:
        i = sys.argv.index("--his-bonus")
        БОНУС_УРОН, БОНУС_ЩИТ = int(sys.argv[i + 1]), int(sys.argv[i + 2])
        print(f"ПОПРАВКА НА СТРОЙ ВРАГА: урон +{БОНУС_УРОН}, щит +{БОНУС_ЩИТ}")
    if not корни:
        raise SystemExit(__doc__)
    main(корни)
