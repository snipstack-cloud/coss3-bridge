# -*- coding: utf-8 -*-
"""Собирает НАСТОЯЩИЕ запросы события «волна дошла» из отыгранных партий.

Задачи берутся не из головы: по трассам `base24` ищется тот самый переход, на
котором повод и срабатывает, — `mil_far` перешагнул `ДОШЛА_ДО_БАЗЫ` при непустом
поле. Запрос строится тем же кодом, каким его строит мост (`запрос_дошли`), и на
состоянии ПОСЛЕ перехода, то есть ровно на том, что модель увидит вживую.

История крестьян врага наполняется предыдущими тактами ТОЙ ЖЕ партии — иначе
`their_growth` стоял бы «?» везде, а в живой игре он есть (мост наполняет её
каждое чтение состояния). Ту же ловушку 21.09 дважды поймали на стендах найма и
рук: инструмент уверенно мерил не то.

Переходов немного — 12 на девять партий, — поэтому добираем ПОЛОСОЙ: такты, где
волна уже стоит у врага, дают то же положение с другими числами потерь. Они
помечены полем `вид`, чтобы при разборе их можно было считать отдельно.

    python3 bench_arrived_cases.py [<каталог с трассами>] > задачи_дошли.json
"""
import glob
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import llm_policy as L

КАТАЛОГ = sys.argv[1] if len(sys.argv) > 1 else "/Users/gs/coss3-res/2026-09-21/base24"
ПОРОГ = 5

партии = []
for ф in sorted(glob.glob(f"{КАТАЛОГ}/*/coss3_bot.jsonl")):
    текущая = []
    for строка in open(ф, encoding="utf-8"):
        строка = строка.strip()
        if not строка:
            continue
        x = json.loads(строка)
        if "finish" in x:
            if текущая:
                партии.append((ф, текущая))
                текущая = []
            continue
        st = x.get("state")
        if isinstance(st, dict) and "gametime" in st:
            текущая.append(st)
    if текущая:
        партии.append((ф, текущая))

задачи, видели = [], set()
for ф, такты in партии:
    счёт: dict = {}
    for i, st in enumerate(такты):
        # Счётчик перехода ведём по КАЖДОМУ такту партии, как в живом цикле.
        пришли = L.волна_дошла(st, счёт, ПОРОГ)
        стоим = (L._чис(st.get("mil_far")) >= L.ДОШЛА_ДО_БАЗЫ
                 and L._чис(st.get("mil_away")) >= ПОРОГ)
        if not пришли and not стоим:
            continue
        вид = "подход" if пришли else "стоим"
        в_поле = int(L._чис(st.get("mil_away")))
        # Разнообразие важнее числа: одинаковые положения меряют одно и то же.
        ключ = (вид, min(3, в_поле // 15), int(L._чис(st.get("my_freewar")) // 30),
                int(L._чис(st.get("p1_peasants")) // 40), int(L._чис(st.get("gametime")) // 300))
        if ключ in видели:
            continue
        видели.add(ключ)
        L.ВРАГ_ИСТОРИЯ.clear()
        for пред in такты[max(0, i - 8):i]:
            L.прирост_крестьян(пред, L.ВРАГ_ИСТОРИЯ)
        L.УДАР.clear()
        задачи.append({
            "откуда": ф.split("/")[-2], "вид": вид,
            "gt": int(L._чис(st.get("gametime"))), "в_поле": в_поле,
            "дома": int(L._чис(st.get("my_freewar"))),
            "состояние": st,
            "запрос": L.запрос_дошли(st, {}, в_поле, такт=20),
        })

print(json.dumps(задачи, ensure_ascii=False, indent=1))
print(f"задач: {len(задачи)} "
      f"(подходов {sum(1 for з in задачи if з['вид'] == 'подход')})", file=sys.stderr)
