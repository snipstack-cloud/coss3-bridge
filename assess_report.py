# -*- coding: utf-8 -*-
"""Пороги оценки обстановки — по серии, а не руками.

Сводит КАЖДУЮ отправленную волну (как её видит outcome_report.py) со слагаемыми
оценки обстановки того же такта и говорит, что дал бы каждый порог: сколько волн
прошло бы, сколько из них дошло до врага, сколько убило крестьян и чего это
стоило. Появился 19.09: RESUME требовал двигать порог 1,3 «по серии, а не
руками», а инструмента для этого не было — счёт делался разовым скриптом.

    python3 assess_report.py <каталог идеи> [<каталог идеи> ...]
    python3 assess_report.py <каталог> --csv волны_оценка.csv

Что с чем сводится. Строка — такт с полем `attack` без вето (та же строка, что
у outcome_report). Оценка берётся из `state.assess` ЭТОГО такта, то есть ДО
приказа. Клетка берётся ЛУЧШАЯ (`клетки[0]`): координаты цели в трассе не
лежат, а мост сортирует клетки и именно первую предлагает модели. Как только
цель попадёт в трассу, сводить надо будет по ней — это единственное место, где
счёт огрубляет.

ВНИМАНИЕ (19.09, вечер): числа этого инструмента, посчитанные ДО починки
формулы, к величине `перевес` больше не относятся. Тогда `встретит` равнялся
ВСЕЙ армии врага (1229 случаев из 1229), и «порог 1,0 вместо 1,3» был выводом
про глобальный перевес. Теперь подкрепление считается по клеткам, и `перевес`
меряет местный — шкала другая, пороги надо мерить серией ЗАНОВО. Выводы, не
завязанные на `перевес`, остаются в силе: вето на волну в режиме ОПАСНОСТЬ
(28 волн, дошло 0, убила 0) и «армия врага <= 100» как лучшее одиночное
правило.

ЛОВУШКА, из-за которой считать «в лоб» нельзя: волна, посланная при враге у
своей базы, тащит на себе потери оборонительного боя. Таких волн половина, и
на них приходится 79 процентов всех потерь. Поэтому всё считается ДВАЖДЫ — по
всем волнам и по волнам без набега (`en_at_base` = 0).
"""
import csv, glob, json, os, sys

ДОШЛА = 180                                  # mil_far, при котором волна у базы врага
ДОМА = 60


def эпизоды(путь):
    """Как в outcome_report: `finish` ЗАКРЫВАЕТ эпизод, а не открывает."""
    эп, тек = [], []
    for строка in open(путь, encoding="utf-8"):
        строка = строка.strip()
        if not строка:
            continue
        r = json.loads(строка)
        тек.append(r)
        if "finish" in r:
            эп.append(тек)
            тек = []
    if тек:
        эп.append(тек)
    return эп


def ч(s, k):
    try:
        return float(s.get(k, 0) or 0)
    except (TypeError, ValueError):
        return 0.0


def после(т, i, секунд):
    t0 = ч(т[i]["state"], "gametime")
    for j in range(i + 1, len(т)):
        if ч(т[j]["state"], "gametime") >= t0 + секунд:
            return j
    return None


def есть(s, *поля):
    return all(s.get(p) is not None for p in поля)


def падения(т, i, j, поле):
    """Убыль по ПАДЕНИЯМ от такта к такту: армия врага растёт, и разность
    концов окна не видит ни одной потери (outcome_report, тот же счёт).

    Такт, где поля НЕТ, пропускается целиком. Без этой проверки пропажа поля
    читается как падение с N до нуля: первый прогон этого скрипта насчитал так
    15 волн с убылью крестьян врага вместо двух.
    """
    s = 0.0
    for k in range(i, min(j, len(т) - 1)):
        a, b = т[k]["state"], т[k + 1]["state"]
        if not (есть(a, поле) and есть(b, поле)):
            continue
        d = ч(a, поле) - ч(b, поле)
        if d > 0:
            s += d
    return s


def волны_с_оценкой(e, серия, копия, номер):
    т = [r for r in e if r.get("state")]
    if len(т) < 10:
        return []
    # Веха — отметка САМОГО МОСТА «волна дошла и убила крестьянина». Критерий
    # «убила» берётся по ней, как в outcome_report: иначе два инструмента
    # считают разное и числа в отчётах не сходятся.
    веха = next((r.get("веха_убийства") for r in т if r.get("веха_убийства")), None)
    отправки = [i for i, r in enumerate(т) if ч(r, "attack") > 0 and not r.get("veto")]
    из_них = []
    for n_, i in enumerate(отправки):
        s0 = т[i]["state"]
        a = s0.get("assess") or {}
        кл = (a.get("клетки") or [])
        л = кл[0] if кл else {}
        пр = a.get("прогноз") or {}
        j60 = после(т, i, 60) or len(т) - 1
        далеко = max((ч(т[k]["state"], "mil_far") for k in range(i, j60 + 1)), default=0)
        где = "у врага" if далеко >= ДОШЛА else ("дома" if далеко < ДОМА else "в пути")
        из_них.append({
            "серия": серия, "копия": копия, "партия": номер, "t": int(ч(s0, "gametime")),
            "ушло": int(ч(т[min(i + 1, len(т) - 1)]["state"], "wave_sent")),
            "режим": a.get("режим"), "вердикт": л.get("вердикт"),
            "перевес": л.get("перевес"), "перевес_без": л.get("перевес_без_подкрепления"),
            "кулак": л.get("наш_кулак"), "встретит": л.get("встретит"),
            "их_рядом": л.get("их_рядом"), "наш_eta": л.get("наш_eta"), "их_eta": л.get("их_eta"),
            "их_армия": пр.get("их_армия"), "наша_армия": пр.get("наша_армия"),
            "набег": 1 if ч(s0, "en_at_base") > 0 else 0,
            "где": где, "дошла": 1 if где == "у врага" else 0,
            # Окно вехи — до СЛЕДУЮЩЕЙ отправки, а не 60 с: так считает
            # outcome_report, и два инструмента должны давать одно число.
            "убила": 1 if (веха is not None and ч(s0, "gametime") < веха <=
                           (ч(т[отправки[n_ + 1]]["state"], "gametime")
                            if n_ + 1 < len(отправки) else 10 ** 6)) else 0,
            "своя_убыль_60": падения(т, i, j60, "mil_inf") + падения(т, i, j60, "mil_shooters"),
            "враг_убыль_60": падения(т, i, j60, "p1_army"),
            "крестьян_убыль_60": падения(т, i, j60, "p1_peasants"),
        })
    return из_них


def ряд(имя, g, всего):
    if not g:
        return f"{имя:32s}      —"
    д = sum(w["дошла"] for w in g)
    уб = sum(w["убила"] for w in g)
    св = sum(w["своя_убыль_60"] for w in g)
    return (f"{имя:32s} {len(g):5d} {len(g)/всего:6.0%} {д:6d} {д/len(g):6.0%} "
            f"{уб:6d} {св/len(g):9.1f}")


ШАПКА = f"{'правило':32s} {'волн':>5s} {'доля':>6s} {'дошло':>6s} {'из них':>6s} {'убили':>6s} {'потерь/волну':>9s}"


def отчёт(W):
    чис = [w for w in W if not w["набег"]]
    print(f"\nволн всего {len(W)}; при враге у своей базы {len(W)-len(чис)}, "
          f"без набега {len(чис)}")
    for имя, набор in (("ВСЕ ВОЛНЫ", W), ("ТОЛЬКО БЕЗ НАБЕГА", чис)):
        if not набор:
            continue
        n = len(набор)
        print(f"\n== {имя} ==\n{ШАПКА}")
        print(ряд("как есть", набор, n))
        for θ in (0.8, 1.0, 1.1, 1.3, 1.5):
            print(ряд(f"перевес >= {θ}", [w for w in набор if (w['перевес'] or 0) >= θ], n))
        for θ in (1.3, 3, 8, 20):
            print(ряд(f"перевес без подкр. >= {θ}",
                      [w for w in набор if (w['перевес_без'] or 0) >= θ], n))
        for θ in (60, 100, 120):
            print(ряд(f"армия врага <= {θ}",
                      [w for w in набор if (w['их_армия'] or 10**6) <= θ], n))
        print(ряд("не слать в режиме ОПАСНОСТЬ",
                  [w for w in набор if w["режим"] != "ОПАСНОСТЬ"], n))
        print(ряд("ОПАСНОСТЬ-вето + перевес >= 1.0",
                  [w for w in набор if w["режим"] != "ОПАСНОСТЬ" and (w['перевес'] or 0) >= 1.0], n))
    print("\n== режим в миг отправки ==")
    for m in ("ОПАСНОСТЬ", "КОПИТЬ", "УДАР", "ПЕРЕХВАТ", None):
        g = [w for w in W if w["режим"] == m]
        if g:
            print(ряд(f"режим {m}", g, len(W)))
    print("\n== вердикт лучшей клетки в миг отправки ==")
    for v in sorted({str(w["вердикт"]) for w in W}):
        print(ряд(f"вердикт «{v}»", [w for w in W if str(w["вердикт"]) == v], len(W)))


def достижимость(пути):
    """Проходят ли вердикты вообще — по ВСЕМ клеткам всех тактов, не только
    там, где ушла волна. 19.09 так выяснилось, что «можно, если его армия не
    двинется» недостижим: ветка требует `мы_первые`, а его армия стоит у его
    же базы, рядом с клетками его крестьян."""
    всего = первые = eta_нет = встретит_вся = 0
    по_вердикту = {}
    for п in пути:
        for f in sorted(glob.glob(os.path.join(п, "*", "coss3_bot.jsonl"))):
            for строка in open(f, encoding="utf-8"):
                строка = строка.strip()
                if not строка:
                    continue
                r = json.loads(строка)
                a = (r.get("state") or {}).get("assess") or {}
                армия = (a.get("прогноз") or {}).get("их_армия")
                for c in a.get("клетки") or []:
                    всего += 1
                    по_вердикту[c["вердикт"]] = по_вердикту.get(c["вердикт"], 0) + 1
                    ие, не_ = c["их_eta"], c["наш_eta"]
                    первые += 1 if (ие is None or (не_ is not None and не_ < ие)) else 0
                    eta_нет += 1 if ие is None else 0
                    встретит_вся += 1 if c["встретит"] == армия else 0
    if not всего:
        return
    print(f"\n== достижимость вердиктов: клеток {всего} во всех тактах ==")
    for k, v in sorted(по_вердикту.items(), key=lambda x: -x[1]):
        print(f"  «{k}»: {v} ({v/всего:.0%})")
    print(f"  мы приходим к клетке первыми: {первые} ({первые/всего:.0%}), "
          f"из них его eta неизвестен вовсе: {eta_нет}")
    print(f"  «встретит» = ВСЯ армия врага: {встретит_вся} ({встретит_вся/всего:.0%}) "
          f"— перевес считается к его армии целиком, а не к охране клетки")


def main(argv):
    пути, csv_out = [], None
    i = 0
    while i < len(argv):
        if argv[i] == "--csv":
            csv_out = argv[i + 1]; i += 2
        else:
            пути.append(argv[i]); i += 1
    W = []
    for п in пути:
        имя = os.path.basename(п.rstrip("/"))
        for f in sorted(glob.glob(os.path.join(п, "*", "coss3_bot.jsonl"))):
            копия = os.path.basename(os.path.dirname(f))
            for номер, e in enumerate(эпизоды(f), 1):
                W.extend(волны_с_оценкой(e, имя, копия, номер))
    if not W:
        print("волн не нашлось"); return 1
    с_оценкой = [w for w in W if w["перевес"] is not None]
    if not с_оценкой:
        print(f"волн {len(W)}, но оценки обстановки в трассе нет — "
              f"это мост без ветки open-info, считать нечего"); return 1
    if len(с_оценкой) < len(W):
        print(f"ВНИМАНИЕ: оценка есть только в {len(с_оценкой)} волнах из {len(W)}")
    отчёт(с_оценкой)
    достижимость(пути)
    if csv_out:
        with open(csv_out, "w", newline="", encoding="utf-8") as f:
            w = csv.DictWriter(f, fieldnames=list(с_оценкой[0].keys()))
            w.writeheader(); w.writerows(с_оценкой)
        print(f"\nтаблица: {csv_out} ({len(с_оценкой)} строк)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
