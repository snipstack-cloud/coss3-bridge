# -*- coding: utf-8 -*-
"""Размен бойца на бойца — по формуле САМОЙ ИГРЫ, а не по эвристике.

Урон за удар движок считает так (`lib/miscext2.script:380` и `:434`):

    damage := damage - TObjBase(pobjbase2).protection[weapkind];
    if (damage < 1) then damage := 1;

То есть из атаки вычитается защита цели ПО ТИПУ ОРУЖИЯ атакующего, и меньше
единицы урон не бывает. Тип оружия и пауза перезарядки берутся из того же слота,
где лежит атака (`lib/unit.script:520-539`: `objbase.weapon[i].damage`,
`objbase.weapon[i].pause`, `objprop.weapon[i].kind`).

Зачем считать это в мосту, а не словами в подсказке. 19.09 модель получила
числа обеих сторон и стала брать апгрейды атаки сама — но выбрала пятую ступень
за 16030 еды и осталась с армией на четверть меньше, чем без подсказки. Вычитать
атаку из защиты в уме на каждом такте она не обязана; мост считает это точно и
один раз, а решение остаётся за ней.

Пороги отношения размена названы до замеров и держатся тут, чтобы их можно было
двигать по серии, а не по памяти.
"""
from math import ceil

ТИПЫ = {1: "pike", 2: "sword", 3: "bullet"}
ЗАЩИТА_ПО_ТИПУ = {1: "dpike", 2: "dsword", 3: "dbullet"}
ЗАПАС = 1.25          # поправка на строй, рельеф и неизвестное
УРОН_МИНИМУМ = 1


def разобрать(строка: str) -> dict:
    """`infantry17=hp90,atk8,wkind1,pause120,dpike3,...` -> {имя: {поле: число}}.

    Имя юнита может нести и название (`infantry17=pikeman,hp90,...`) — оно
    пропускается: у своих бойцов строка длиннее, чем у чужих, а поля те же.
    """
    из_строки = {}
    for кусок in str(строка or "").split():
        if "=" not in кусок:
            continue
        имя, _, хвост = кусок.partition("=")
        поля = {}
        for часть in хвост.split(","):
            часть = часть.strip()
            m = _число(часть)
            if m:
                поля[m[0]] = m[1]
        if поля:
            из_строки[имя] = поля
    return из_строки


def _число(часть: str):
    """`atk8` -> ("atk", 8). Не число — None (это название юнита)."""
    i = len(часть)
    while i > 0 and (часть[i - 1].isdigit() or часть[i - 1] == "-"):
        i -= 1
    if i == len(часть) or i == 0:
        return None
    try:
        return часть[:i], int(часть[i:])
    except ValueError:
        return None


def урон(атакующий: dict, цель: dict) -> int:
    """Урон за удар: атака минус защита цели по типу оружия, но не меньше 1."""
    вид = атакующий.get("wkind")
    поле = ЗАЩИТА_ПО_ТИПУ.get(вид)
    # Тип не из трёх известных (ядро, картечь) — защиты такого рода в состоянии
    # нет, и выдумывать её нельзя: считаем по голой атаке и говорим об этом.
    защита = цель.get(поле, 0) if поле else 0
    return max(УРОН_МИНИМУМ, int(атакующий.get("atk", 0)) - int(защита))


def размен(наш: dict, его: dict) -> dict:
    """Отношение размена одного бойца на одного.

    ER = время, за которое МЫ убиваем его, делить на время, за которое ОН
    убивает нас. Больше единицы — он выгоднее в дуэли.
    """
    наш_урон = урон(наш, его)
    его_урон = урон(его, наш)
    наших_ударов = ceil(int(его.get("hp", 1)) / наш_урон)
    его_ударов = ceil(int(наш.get("hp", 1)) / его_урон)
    # Пауза приходит в СОТЫХ (блок с 19.09): `_misc_FramesToTime` даёт дробь, и
    # целое округление обнуляло паузу пикинёра на живой игре, оставляя
    # мушкетёру 4. Единицы здесь не важны — в отношении они сокращаются, —
    # важно лишь, чтобы обе стороны считались одинаково.
    # Со старого моста паузы нет вовсе: тогда считаем удары, а не время, и
    # говорим, что скорость не учтена.
    наша_пауза = наш.get("pause")
    его_пауза = его.get("pause")
    # Ноль — законное значение: ближний бой бьёт без перезарядки, и на живой
    # игре 19.09 у пикинёров обеих сторон пауза именно 0, а у мушкетёра 3.75.
    # Если она нулевая У ОБОИХ, скорость одинакова и сравнение ударов честное;
    # «не учтена» — только когда паузы нет вовсе (старый мост) или она есть
    # лишь у одной стороны.
    обе_нулевые = (наша_пауза == 0 and его_пауза == 0)
    скорость_учтена = обе_нулевые or bool(наша_пауза and его_пауза)
    наш_ttk = наших_ударов * (наша_пауза or 1)
    его_ttk = его_ударов * (его_пауза or 1)
    er = наш_ttk / его_ttk if его_ttk else float("inf")
    return {
        "наш_урон": наш_урон, "его_урон": его_урон,
        "наших_ударов": наших_ударов, "его_ударов": его_ударов,
        "наш_ttk": наш_ttk, "его_ttk": его_ttk,
        "скорость_учтена": скорость_учтена,
        "отношение": round(er, 2),
        "наша_доля": round(1 / er, 2) if er else 0.0,
        "нужен_перевес": round(er * ЗАПАС, 1),
        "вердикт": вердикт(er),
    }


def вердикт(er: float) -> str:
    if er < 0.85:
        return "мы сильнее"
    if er <= 1.15:
        return "примерно поровну"
    if er <= 1.50:
        return "прямой бой невыгоден"
    return "прямой бой запрещён"


def что_даст(наш: dict, его: dict, прибавка_атаки: int = 0,
             прибавка_защиты: int = 0) -> dict:
    """Каким станет размен, если взять ступень атаки или защиты.

    Нужно из-за порога `max(1, ...)`: прибавка атаки ниже защиты врага не даёт
    НИЧЕГО — урон как был единицей, так и останется. 19.09 на живой игре это и
    вышло: atk8 против dpike7 — урон 1, и пять ступеней атаки подряд довели его
    лишь до 7.
    """
    новый = dict(наш)
    новый["atk"] = int(наш.get("atk", 0)) + прибавка_атаки
    for поле in ("dpike", "dsword", "dbullet"):
        if поле in новый:
            новый[поле] = int(новый[поле]) + прибавка_защиты
    было, стало = размен(наш, его), размен(новый, его)
    return {"было": было["отношение"], "стало": стало["отношение"],
            "урон_был": было["наш_урон"], "урон_стал": стало["наш_урон"],
            "его_урон_был": было["его_урон"], "его_урон_стал": стало["его_урон"],
            "выигрыш": round(было["отношение"] - стало["отношение"], 2)}
