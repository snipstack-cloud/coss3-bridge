# -*- coding: utf-8 -*-
"""Ключ --food-floor: до 300-й секунды еда не ниже порога (27.09).

Числа взяты из живой серии early_push: население стояло на 22 все такты с едой
219-291 (копии 1 и 3), а победная копия имела 797 еды к 194 с и 25 бойцов к
300 с. Ключ держит именно это.
"""
import llm_policy as L

ошибок = []
такт = lambda **кв: dict({"gametime": 200, "food": 260, "peasants": 22,
                          "on_food": 6, "mil_inf": 4, "mil_shooters": 0,
                          "mil_cav": 0, "mills": 1, "food_ready": 10}, **кв)

# 1. ключ выключен — мост молчит
L.ЕДА_ПОРОГ = 0
if L.еда_порогом(такт()) is not None:
    ошибок.append("выключенный ключ вмешался")

L.ЕДА_ПОРОГ = 800
# 2. случай копий 1 и 3: еда 260 на 200-й секунде — вмешаться и сказать вслух
реш = L.еда_порогом(такт())
if реш is None:
    ошибок.append("еда 260 на 200-й секунде: ключ обязан вмешаться")
else:
    сколько, текст, роль = реш
    if роль != "food":
        ошибок.append(f"поле созрело (10 участков) — ставить на еду, а не на {роль}")
    if сколько != 15:                       # две трети от 22
        ошибок.append(f"две трети от 22 это 15, а ключ просит {сколько}")
    if "260" not in текст or "800" not in текст:
        ошибок.append("в тексте нет чисел этого такта")
    if "219-291" not in текст or "797" not in текст:
        ошибок.append("в тексте нет чисел, ради которых ключ сделан")
    if "--food-floor" not in текст:
        ошибок.append("текст не называет ключ, которым это отключается")

# 3. после срока ключ молчит, даже если еда низкая
if L.еда_порогом(такт(gametime=301)) is not None:
    ошибок.append("после 300 с ключ обязан молчать")

# 4. бойцов набрано — ключ молчит (цель достигнута)
if L.еда_порогом(такт(mil_inf=20)) is not None:
    ошибок.append("при 20 бойцах ключ обязан молчать")
if L.еда_порогом(такт(mil_inf=7, mil_shooters=7, mil_cav=6)) is not None:
    ошибок.append("20 бойцов складываются из трёх видов")

# 5. еда выше порога — ключ молчит
if L.еда_порогом(такт(food=800)) is not None:
    ошибок.append("при еде на пороге ключ обязан молчать")

# 6. модель уже отдала BALANCE food — мост не спорит
if L.еда_порогом(такт(), на_еде_уже=True) is not None:
    ошибок.append("своя команда модели важнее вмешательства моста")

# 7. людей на еде уже больше, чем попросил бы ключ — не трогать
if L.еда_порогом(такт(on_food=16)) is not None:
    ошибок.append("людей на еде уже больше — вмешательство лишнее")

# 8. крестьян почти нет — не отбирать последних
if L.еда_порогом(такт(peasants=2)) is not None:
    ошибок.append("при двух крестьянах ключ обязан молчать")

# 9. победная копия early_push: еда 1226 к 240 с — ключ уже не нужен
if L.еда_порогом(такт(gametime=240, food=1226, on_food=14)) is not None:
    ошибок.append("на числах победной копии ключ не должен вмешиваться")

# 10. порог настраивается: с 1000 та же победная копия уже под ключом
L.ЕДА_ПОРОГ = 1000
if L.еда_порогом(такт(gametime=194, food=797, on_food=6)) is None:
    ошибок.append("порог 1000 обязан ловить еду 797")
L.ЕДА_ПОРОГ = 800

# 11. §134: поле ещё не созрело (готовых участков 0) — те же люди на ДЕРЕВО, не в пустое ожидание еды
#     (второй смоук Д 10.10: 12 из 18 на еде в 1:03, участок поспел в 2:08 — 11 праздных 65 секунд)
реш = L.еда_порогом(такт(gametime=63, food=792, peasants=18, on_food=0, mil_inf=0, food_ready=0))
if реш is None:
    ошибок.append("поле не созрело, еда 792: ключ обязан вмешаться (деревом)")
else:
    сколько, текст, роль = реш
    if роль != "wood" or сколько != 12:
        ошибок.append(f"до созревания — BALANCE wood 12, а ключ дал {роль} {сколько}")
    if "не созрело" not in текст or "wood" not in текст:
        ошибок.append("текст не говорит, что поле не созрело и люди идут на дерево")
# 12. тот же такт, но участок поспел — на еду
реш = L.еда_порогом(такт(gametime=128, food=377, peasants=20, on_food=0, mil_inf=7, food_ready=36))
if реш is None or реш[2] != "food":
    ошибок.append(f"поле созрело — на еду, а ключ дал {реш}")
L.ЕДА_ПОРОГ = 0

print("selftest_food_floor: " + ("ОК, 12 проверок" if not ошибок
                                 else "ОШИБКИ\n  " + "\n  ".join(ошибок)))
raise SystemExit(1 if ошибок else 0)
