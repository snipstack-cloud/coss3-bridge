#!/usr/bin/env python3
"""Промпт и код должны говорить об одном и том же.

Расхождение этих двух — отдельный класс ошибок проекта, и он уже стоил серии:
промпт учил ставить BUILDERS 2-3 каждый такт, а код читал команду только вместе
с BUILD, и 75 тактов ушли вхолостую. Числа и списки живут в ПОЛИТИКА, но текст
промпта пишется руками, и разойтись они могут в любой день.

Здесь проверяется именно СОГЛАСИЕ: то, что обещано модели, мост исполняет, а
то, что мост режет, он называет вслух.
"""
import sys, os, re

sys.argv = [sys.argv[0]]
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import llm_policy as L                                        # noqa: E402

беды: list[str] = []


def проверка(условие: bool, что: str) -> None:
    print(f"  {'ОК  ' if условие else 'ПРОВАЛ'} {что}")
    if not условие:
        беды.append(что)


ТЕКСТ = L.SYSTEM + L.SYSTEM_HUMAN
П = L.ПОЛИТИКА

# 1. Предел команд назван модели тем же числом, каким режет мост.
#    Ищем ФРАЗУ, а не цифру: цифра найдётся в любом тексте на девятнадцать
#    тысяч знаков, и такая проверка молчит при настоящем расхождении —
#    поймано на этом же тесте 16.09.
предел = П["команд_за_такт"]
ЧИСЛИТЕЛЬНОЕ = {3: "трёх", 4: "четырёх", 5: "пяти", 6: "шести", 7: "семи",
                8: "восьми", 9: "девяти", 10: "десяти"}
словом = ЧИСЛИТЕЛЬНОЕ.get(предел, "")
фраза = re.search(rf"не больше ({словом}|{предел}) команд", ТЕКСТ.lower()) if словом \
    else re.search(rf"не больше {предел} команд", ТЕКСТ.lower())
проверка(bool(фраза),
         f"предел {предел} команд назван в промпте фразой «не больше ... команд»")

# 2. Отброшенное НЕ молчит. 16.09 седьмая команда исчезала без слова, и
#    выглядело это как «волна не ушла».
лишку = [{"cmd": "BUILD", "role": "mill", "total": 1}] * предел + [
    {"cmd": "ATTACK", "count": 20, "target": "peasants"}]
_, attack, _, брак, _, _, _, _ = L.to_commands({"commands": лишку})
проверка(any("не ушли" in b for b in брак) and attack == 0,
         "команда сверх предела названа вслух, а не отброшена молча")

# 3. Каждая команда из политики описана модели.
for имя in П["команды"]:
    проверка(имя in ТЕКСТ, f"команда {имя} описана в промпте")

# 4. Цели ATTACK и MOVE в промпте и в разборе — одни и те же.
for цель in П["цели_ATTACK"]:
    проверка(цель in ТЕКСТ, f"цель ATTACK {цель} названа в промпте")
_, _, _, брак2, _, _, _, _ = L.to_commands(
    {"commands": [{"cmd": "ATTACK", "count": 5, "target": "walls"}]})
проверка(any("walls" in b for b in брак2),
         "неизвестная цель ATTACK отвергнута и названа")

# 5. Запреты партии: что обещано модели, то мост и отвергает.
L.ЗАПРЕТ.add("academi")
try:
    st = {"gametime": 100, "food": 1, "wood": 1, "stone": 1, "gold": 1,
          "iron": 1, "coal": 1, "peasants": 5, "my_x": 0.0, "my_z": 0.0,
          "mil_inf": 0, "mil_shooters": 0, "mil_cav": 0, "my_freewar": 0}
    текст = L.situation(st, {}, [], "", волны=[])
    проверка("academi" in текст, "запрещённая роль названа модели")
    _, _, _, брак3, _, _, _, _ = L.to_commands(
        {"commands": [{"cmd": "BUILD", "role": "academi", "total": 1}]})
    проверка(any("запрещено" in b for b in брак3),
             "запрещённая роль отвергнута разбором")
finally:
    L.ЗАПРЕТ.discard("academi")

# 6. Порог волны: число из кода стоит в запросе, а не только в коде.
st2 = {"gametime": 300, "food": 900, "wood": 500, "stone": 300, "gold": 400,
       "iron": 0, "coal": 0, "peasants": 20, "my_x": 0.0, "my_z": 0.0,
       "mil_inf": 30, "mil_shooters": 0, "mil_cav": 0, "my_freewar": 30}
текст2 = L.situation(st2, {}, [], "", волны=[])
проверка(str(L.WAVE_MIN) in текст2,
         f"порог волны {L.WAVE_MIN} назван в запросе")

print(f"\nПРОВАЛОВ: {len(беды)}")
raise SystemExit(1 if беды else 0)
