# -*- coding: utf-8 -*-
"""Бой в числах ПО КЛЕТКЕ: где дерутся, каким перевесом и достают ли крестьян.

Почему это отдельный счёт. Мост считает перевес ПО АРМИЯМ ЦЕЛИКОМ («у тебя 89,
у него 32»), а дерутся не армии, а клетки. Пока сетки лежали в трассе строками,
проверить это было нечем, и вывод «перевес есть, можно бить» опирался на число,
которого в бою не существует.

Что он показал по `base24` (330 тактов с сетками, 22.09):

    контакт есть в 43 процентах тактов
    в клетке боя наших медианно 13 против его 19
    ЛОКАЛЬНЫЙ перевес ПО ГОЛОВАМ: медиана 1,00 (кв1 0,36, кв3 2,42)
      ниже порога 1,3 — 65 процентов контактов
    он же С КАЧЕСТВОМ: медиана 0,62, ниже порога — 70 процентов
      (ER пикинёров медиана 1,43: на десятой минуте его атака 18, наша 11,
       апгрейдов у него 9 против наших 4 — головы не равны)
    ГЛОБАЛЬНЫЙ перевес в те же миги: 1,27
    наша армия размазана медианно по 6 клеткам
    клеток с его крестьянами 1875, наши бойцы в них — 82 раза (4,4 процента)

То есть двукратный перевес по армии превращается в бою в ничью, а до крестьян
мы почти не доходим. Это и есть механика, стоящая за «убивает хоть одного
крестьянина лишь каждая девятая волна» (`wave_report.py`).

    python3 combat_cells.py <каталог идеи> [<каталог базы>]

Читает и трассы (`coss3_bot.jsonl`, сетки раз в такт), и частые снимки
(`coss3_snap.jsonl`, где бой уже сведён в числа ключом --snap-every).
"""
import glob
import json
import os
import statistics as S
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import coss3_map as M

ПОРОГ = 1.3          # тот самый порог, которым мост меряет перевес по армиям


def ч(v):
    try:
        return float(v)
    except (TypeError, ValueError):
        return 0.0


def записи(корень):
    """Такты трасс и строки снимков — по одной записи наружу.

    Снимок несёт готовые списки `бой`/`у_крестьян`, трасса — сетки строками.
    Разбирать надо оба: снимков в старых прогонах нет вовсе, а в новых они
    вчетверо подробнее.
    """
    for файл in sorted(glob.glob(f"{корень}/**/coss3_snap.jsonl", recursive=True)):
        for строка in open(файл, encoding="utf-8"):
            строка = строка.strip()
            if not строка:
                continue
            x = json.loads(строка)
            клетки = [{"x": к[0], "y": к[1], "наших": к[2], "его": к[3]}
                      for к in x.get("бой") or []]
            крест = [{"x": к[0], "y": к[1], "крестьян": к[2], "наших": к[3]}
                     for к in x.get("у_крестьян") or []]
            yield ("снимок", x, {"клетки": клетки, "у_крестьян": крест,
                                 "занято_клеток": x.get("занято_клеток") or 0,
                                 "наших": ч(x.get("mil_inf")) + ч(x.get("mil_shooters"))
                                 + ч(x.get("mil_cav")), "его": ч(x.get("p1_army"))})
    for файл in sorted(glob.glob(f"{корень}/**/coss3_bot.jsonl", recursive=True)):
        for строка in open(файл, encoding="utf-8"):
            строка = строка.strip()
            if not строка:
                continue
            x = json.loads(строка)
            st = x.get("state")
            if not isinstance(st, dict) or "gametime" not in st:
                continue
            if not (st.get("arow") and st.get("frow")):
                continue
            yield ("такт", st, M.бой_по_клеткам(st))


def разбор(корень):
    всего = с_контактом = контактов = 0
    наши_к, его_к, размены, занято = [], [], [], []
    с_качеством, кулаком, эры = [], [], []
    крест_клеток = крест_с_нами = 0
    наших_у_крестьян = []
    глобальные = []
    снимков = тактов = 0
    for вид, st, бой in записи(корень):
        всего += 1
        снимков += вид == "снимок"
        тактов += вид == "такт"
        if бой.get("занято_клеток"):
            занято.append(бой["занято_клеток"])
        вся_наша, вся_его = ч(бой.get("наших")), ч(бой.get("его"))
        if бой["клетки"]:
            с_контактом += 1
            if вся_его > 0:
                глобальные.append(вся_наша / вся_его)
        if бой.get("размен"):
            эры.append(бой["размен"])
        for к in бой["клетки"]:
            контактов += 1
            наши_к.append(к["наших"])
            его_к.append(к["его"])
            размены.append(к["наших"] / max(к["его"], 1))
            if к.get("перевес_с_качеством") is not None:
                с_качеством.append(к["перевес_с_качеством"])
                кулаком.append(к["перевес_кулаком"])
        for к in бой["у_крестьян"]:
            крест_с_нами += 1
            наших_у_крестьян.append(к["наших"])
    if not всего:
        print(f"{корень}: записей с сетками не нашлось")
        return None
    print(f"\n{корень}: записей {всего} (тактов {тактов}, снимков {снимков})")
    print(f"  контакт есть в {с_контактом} записях ({100 * с_контактом / всего:.0f}%), "
          f"клеток боя {контактов}")
    if контактов:
        ниже = sum(1 for р in размены if р < ПОРОГ)
        print(f"  в клетке боя: наших медиана {S.median(наши_к):.0f}, "
              f"его медиана {S.median(его_к):.0f}")
        print(f"  перевес ПО ГОЛОВАМ: медиана {S.median(размены):.2f} "
              f"(кв1 {sorted(размены)[len(размены)//4]:.2f}, "
              f"кв3 {sorted(размены)[3*len(размены)//4]:.2f}); "
              f"ниже порога {ПОРОГ} — {100 * ниже / контактов:.0f}%")
        if с_качеством:
            ниже_к = sum(1 for р in с_качеством if р < ПОРОГ)
            print(f"  он же С КАЧЕСТВОМ: медиана {S.median(с_качеством):.2f}, "
                  f"кулаком {S.median(кулаком):.2f}; "
                  f"ниже порога — {100 * ниже_к / len(с_качеством):.0f}%")
            print(f"  размен пикинёров (ER>1 — его боец выгоднее): медиана "
                  f"{S.median(эры):.2f}, максимум {max(эры):.2f}")
    if глобальные:
        print(f"  ГЛОБАЛЬНЫЙ перевес в те же миги: медиана {S.median(глобальные):.2f}")
    if занято:
        print(f"  армия размазана по клеткам: медиана {S.median(занято):.0f}, "
              f"максимум {max(занято)}")
    print(f"  наши бойцы стояли в клетке с его крестьянами: {крест_с_нами} раз"
          + (f", их там медиана {S.median(наших_у_крестьян):.0f}"
             if наших_у_крестьян else ""))
    return {"контактов": контактов,
            "перевес": S.median(размены) if размены else None,
            "с_качеством": S.median(с_качеством) if с_качеством else None,
            "ниже_порога": (100 * sum(1 for р in размены if р < ПОРОГ) / контактов
                            if контактов else None),
            "у_крестьян": крест_с_нами}


def main():
    if len(sys.argv) < 2:
        raise SystemExit(__doc__)
    идея = разбор(sys.argv[1])
    база = разбор(sys.argv[2]) if len(sys.argv) > 2 else None
    if идея and база and идея["перевес"] and база["перевес"]:
        print("\nРАЗНИЦА (идея против базы):")
        print(f"  локальный перевес по головам: {идея['перевес']:.2f} против "
              f"{база['перевес']:.2f}")
        if идея.get("с_качеством") and база.get("с_качеством"):
            print(f"  он же с качеством: {идея['с_качеством']:.2f} против "
                  f"{база['с_качеством']:.2f}")
        print(f"  доля боёв в меньшинстве: {идея['ниже_порога']:.0f}% против "
              f"{база['ниже_порога']:.0f}%")
        print(f"  выходов на клетку с его крестьянами: {идея['у_крестьян']} против "
              f"{база['у_крестьян']}")
        print("  Считается по клеткам, а их на партию сотни — число отличимо, "
              "в отличие от счёта по партиям.")


if __name__ == "__main__":
    main()
