#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""ГЛАЗА: куда и чем он идёт, что под угрозой и через сколько (6.10).

Зачем. Проверка 6: с 5:31 в состоянии моста лежало «его 25 из (6,9) идут в (1,5)» и «13 из (12,12) идут в
(1,6)» — к нашей ратуше в (2,3); в 6:57 его 25 стояли в (2,4), к 8:00 убито 24 крестьянина. Стратегия этого
не читала: она — расписание (T1, сроки, пороги), а контракт волны смотрит только на кучу у своей волны. Поле
`ecells` с `идут, tx, ty` мост отдаёт с 29.09.

Здесь — одна чистая функция `оценить(st)` на каждый такт, общая для моста, стратегии, промпта и симулятора
(в симуляторе `ecells` — список словарей, в живом мосте — строка; разбор один). Решений здесь НЕТ — только
картина: «его группа N бойцов (стрелков S) идёт к X, будет через T с; у X наших столько-то». Решает слой
реакции, чтобы глаза можно было проверять отдельно от рук.

Что под угрозой (цели — по клеткам нашей сетки 16×16):
  * БАЗА — клетка его цели или его кучи в `РАДИУС_БАЗЫ` клетках от нашей ратуши (Чебышёв);
  * ХОЗЯЙСТВО — в 1 клетке от нашей мельницы или шахты (там крестьяне; своих крестьян по клеткам мост не
    отдаёт, отдаёт здания);
  * ВОЛНА — в 1 клетке от нашей кучи в поле;
  * прочее — «в поле».
Время до цели — по Чебышёву между его клеткой и целью и маршевой скорости `[замер] 1,15 ед/с` (sim/sim.py,
`темпы.json`); на карте 256 клетка — 16 ед, ~14 с на клетку. Стоящие у базы (без приказа) — угроза с T = 0.
"""
import math

РАДИУС_БАЗЫ = 2          # клеток от ратуши: его цель здесь — это набег на базу
РАДИУС_ХОЗЯЙСТВА = 1     # клеток от мельницы/шахты
МАРШ_ЕД_В_С = 1.15       # [замер] sim/sim.py СКОРОСТЬ, темпы.json марш_ед_в_сек
ХОЗЯЙСТВЕННЫЕ = ("mill", "minegold", "mineiron", "minecoal", "mine", "field")


def _клетка_ед(st):
    return float(st.get("map_w") or 256) / 16.0


def _его(st):
    v = st.get("ecells")
    if isinstance(v, list):
        return [c for c in v if isinstance(c, dict)]
    try:
        import coss3_map
        return coss3_map.его_клетки(st)
    except Exception:
        return []


def _наши(st):
    v = st.get("ocells")
    if isinstance(v, list):
        return [c for c in v if isinstance(c, dict)]
    try:
        import coss3_map
        return coss3_map.наши_клетки(st)
    except Exception:
        return []


def _здания(st):
    v = st.get("obuild")
    if isinstance(v, list):
        return [b for b in v if isinstance(b, dict)]
    try:
        import coss3_map
        return coss3_map.наши_здания(st)
    except Exception:
        return []


def дом(st):
    """Клетка нашей ратуши: `my_cx/my_cy`, иначе ратуша из `obuild`. None — не знаем."""
    if st.get("my_cx") is not None and st.get("my_cy") is not None:
        return (int(float(st["my_cx"])), int(float(st["my_cy"])))
    ш = _клетка_ед(st)
    for b in _здания(st):
        if str(b.get("тип")) == "center":
            return (int(float(b["x"]) // ш), int(float(b["z"]) // ш))
    return None


def _чеб(a, b):
    return max(abs(int(a[0]) - int(b[0])), abs(int(a[1]) - int(b[1])))


def оценить(st: dict) -> dict:
    """Картина угроз такта.

    {"дом": (x, y) | None,
     "группы": [{откуда, n, стрелков, идут, куда, что, до, сек, наших_у_цели}],   # по убыванию опасности
     "база": {"его": N, "стрелков": S, "сек": T | None, "наших_дома": M, "наших_в_поле": K, "волна_дальше": D},
     "хозяйство": {...та же форма...},
     "строка": "одна строка для лога и промпта"}
    """
    д = дом(st)
    ш = _клетка_ед(st)
    сек_на_клетку = ш / МАРШ_ЕД_В_С
    его = _его(st)
    наши = _наши(st)
    хоз = []
    for b in _здания(st):
        if str(b.get("тип")) in ХОЗЯЙСТВЕННЫЕ:
            хоз.append((int(float(b["x"]) // ш), int(float(b["z"]) // ш)))
    дома_наших = sum(int(c.get("n") or 0) for c in наши if д and _чеб((c["x"], c["y"]), д) <= 1)
    в_поле = [c for c in наши if not д or _чеб((c["x"], c["y"]), д) > 1]
    группы = []
    for c in его:
        n = int(c.get("n") or 0)
        if n <= 0:
            continue
        откуда = (int(c["x"]), int(c["y"]))
        идут = int(c.get("идут") or 0)
        tx, ty = int(c.get("tx") if c.get("tx") is not None else -1), int(c.get("ty") if c.get("ty") is not None else -1)
        куда = (tx, ty) if идут > 0 and tx >= 0 and ty >= 0 else откуда
        # что под угрозой — по клетке цели (идущие) или по месту стоянки (стоящие)
        что = "поле"
        if д is not None and _чеб(куда, д) <= РАДИУС_БАЗЫ:
            что = "база"
        elif any(_чеб(куда, h) <= РАДИУС_ХОЗЯЙСТВА for h in хоз):
            что = "хозяйство"
        elif any(_чеб(куда, (k["x"], k["y"])) <= 1 for k in в_поле):
            что = "волна"
        до = _чеб(откуда, куда)
        у_цели = sum(int(k.get("n") or 0) for k in наши if _чеб((k["x"], k["y"]), куда) <= 1)
        группы.append(dict(откуда=откуда, n=n, стрелков=int(c.get("стрелков") or 0), идут=идут, куда=куда,
                           что=что, до=до, сек=round(до * сек_на_клетку), наших_у_цели=у_цели))

    def свод(цель):
        гр = [г for г in группы if г["что"] == цель]
        if not гр:
            return {"его": 0, "стрелков": 0, "сек": None, "наших_дома": дома_наших,
                    "наших_в_поле": sum(int(k.get("n") or 0) for k in в_поле), "волна_дальше": None}
        # волна дальше: сколько секунд нашей самой большой куче в поле до дома
        волна = max(в_поле, key=lambda k: int(k.get("n") or 0)) if в_поле else None
        return {"его": sum(г["n"] for г in гр), "стрелков": sum(г["стрелков"] for г in гр),
                "сек": min(г["сек"] for г in гр), "наших_дома": дома_наших,
                "наших_в_поле": sum(int(k.get("n") or 0) for k in в_поле),
                "волна_дальше": (round(_чеб((волна["x"], волна["y"]), д) * сек_на_клетку)
                                 if волна is not None and д is not None else None)}

    важность = {"база": 0, "хозяйство": 1, "волна": 2, "поле": 3}
    группы.sort(key=lambda г: (важность[г["что"]], г["сек"], -г["n"]))
    база, хозяйство = свод("база"), свод("хозяйство")
    куски = []
    for имя, с in (("БАЗА", база), ("ХОЗЯЙСТВО", хозяйство)):
        if с["его"]:
            куски.append(f"{имя}: его {с['его']} (стрелков {с['стрелков']}) через ~{с['сек']} с, "
                         f"наших дома {с['наших_дома']}, в поле {с['наших_в_поле']}"
                         + (f" (до дома ~{с['волна_дальше']} с)" if с["волна_дальше"] is not None else ""))
    if not куски:
        куски.append("угроз базе и хозяйству нет")
    return {"дом": д, "группы": группы, "база": база, "хозяйство": хозяйство, "строка": "; ".join(куски)}


if __name__ == "__main__":
    # Прогон по записи: когда глаза увидели угрозу базе. python3 угрозы.py <каталог записи> [с] [по]
    import json
    import os
    import sys
    к = os.path.expanduser(sys.argv[1])
    с, по = (float(sys.argv[2]) if len(sys.argv) > 2 else 0), (float(sys.argv[3]) if len(sys.argv) > 3 else 1e9)
    путь = os.path.join(к, "coss3_snap.jsonl")
    первая = None
    for строка in open(путь, encoding="utf-8"):
        s = json.loads(строка)
        t = float(s.get("gametime") or 0)
        if not (с <= t <= по):
            continue
        о = оценить(s)
        if о["база"]["его"] and первая is None:
            первая = t
        if о["база"]["его"] or о["хозяйство"]["его"]:
            print(f"{int(t) // 60:2d}:{int(t) % 60:02d}  {о['строка']}")
    print(f"первая угроза базе: {int(первая) // 60}:{int(первая) % 60:02d}" if первая is not None else "угрозы базе не было")
