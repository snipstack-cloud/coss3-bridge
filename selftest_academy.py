# -*- coding: utf-8 -*-
"""Самопроверка расшифровки апгрейдов академии.

Академия разрешена обеим сторонам с 20.09. Её имена — просто номера
(`aca.12`), в отличие от `bar.pikeman.2.3`, где видно и юнита, и вид, и
ступень. Без расшифровки модель видит список безымянных номеров.

Разобрано из кода игры (`country.script`, раздел «// academy»): 35 апгрейдов,
тип и значение — из `_country_AddUpgrade(... gc_upg_type_X, value ...)`, тип
оружия первым в iarr-хвосте, требования в sarr-хвосте.

Стережётся:
* расшифровываются ТОЛЬКО доступные сейчас апгрейды;
* недостижимое (порт, артиллерия, XVIII век) не предлагается вовсе;
* имена в списке идут вместе с ценой — сравнение по части до «=»;
* сказано главное следствие: пуля растёт, пика упёрлась в потолок.
"""
import llm_policy as L

беды = []


def проверка(имя, условие, пояснение=""):
    if условие:
        print("  ОК    " + имя)
    else:
        беды.append(имя)
        print("  ПЛОХО " + имя + (" — " + пояснение if пояснение else ""))


def текст(доступно):
    ст = {"gametime": 900, "grid_n": 16, "map_open": 1, "my_cx": 3, "my_cy": 12,
          "peasants": 60, "mil_inf": 50, "mil_shooters": 20, "my_freewar": 40,
          "ba17": 2, "smiths": 1, "academi": 1, "mills": 1, "centers": 1,
          "food": 9000, "gold": 8000, "iron": 3000, "wood": 4000, "stone": 3000,
          "p1_enemy": 1, "p1_army": 100,
          "upg_avail": ",".join(f"{у}=f0g500i0" for у in доступно),
          "upg_done": "", "upg_doing": ""}
    return L.situation(ст, ст, [], "", None)


с = текст(["aca.1", "aca.12", "aca.13", "aca.31", "bar.pikeman.2.1"])
проверка("расшифровка появляется", "В АКАДЕМИИ" in с)
проверка("имя с ценой всё равно распознано",
         "aca.12 — УРОН ПУЛИ" in с, "сравнение должно резать по «=»")
проверка("названо, на кого действует", "мушкетёр, драгун" in с)
проверка("перезарядка расшифрована", "ПЕРЕЗАРЯДКА ПУЛИ" in с)
проверка("экономический апгрейд тоже расшифрован", "aca.1 — еда" in с)
проверка("сказано следствие про пику", "ПИКА — НЕТ" in с and "потолок" in с)

# недостижимое не предлагаем
с2 = текст(["aca.35", "aca.36", "aca.28", "aca.17"])
проверка("апгрейды за XVIII веком не расшифровываются",
         "aca.35 —" not in с2 and "aca.36 —" not in с2)
проверка("портовые и артиллерийские не расшифровываются",
         "aca.28 —" not in с2 and "aca.17 —" not in с2)
проверка("при одних недоступных блок вовсе не выводится",
         "В АКАДЕМИИ" not in с2)

# без академии в списке — молчим
с3 = текст(["bar.pikeman.2.1", "bar.musketeernet.2.1"])
проверка("без академических апгрейдов блока нет", "В АКАДЕМИИ" not in с3)

# состав таблицы
проверка("недостижимое перечислено отдельно",
         {"aca.35", "aca.36", "aca.32"} <= L.АКАДЕМИЯ_НЕДОСТУПНО)
проверка("доступное и недостижимое не пересекаются",
         not (set(L.АКАДЕМИЯ) & L.АКАДЕМИЯ_НЕДОСТУПНО))
проверка("урон пули описан четырьмя ступенями",
         sum(1 for к, v in L.АКАДЕМИЯ.items() if "УРОН ПУЛИ" in v) == 4)
проверка("перезарядка пули описана двумя",
         sum(1 for к, v in L.АКАДЕМИЯ.items() if "ПЕРЕЗАРЯДКА ПУЛИ" in v) == 2)

# ТРАССА. Поля `upg_avail` в снимке не было вовсе, и 20.09 это дало ложный ноль:
# счёт сказал «академические апгрейды не попадали в список ни разу», тогда как в
# живом состоянии их было тридцать шесть, с ценами. Теперь в трассу идут
# академические имена и общее число остальных.
исходник = open("llm_policy.py", encoding="utf-8").read()
проверка("снимок трассы хранит академические апгрейды",
         '_снимок["upg_aca"]' in исходник,
         "иначе окупаемость академии не пересчитать по трассе")
проверка("снимок хранит и общее число доступных",
         '_снимок["upg_avail_n"]' in исходник)
проверка("поле academi тоже в снимке",
         '"mil_near", "mil_side", "academi"' in исходник,
         "без него не видно, была ли академия построена")

# СЧЁТ ОКУПАЕМОСТИ академического апгрейда
import combat_math as C
наш = {"atk": 10, "hp": 65, "wkind": 3, "pause": 375,
       "dpike": 1, "dsword": 1, "dbullet": 0}
его = {"atk": 10, "hp": 65, "wkind": 3, "pause": 375,
       "dpike": 1, "dsword": 1, "dbullet": 2}
цены = {"aca.12": {"iron": 5000}, "aca.31": {"gold": 5500, "iron": 4200, "stone": 6000},
        "aca.35": {"gold": 11500}}
итог = C.окупаемость_академии(наш, его, L.АКАДЕМИЯ_ЭФФЕКТ, цены, set(), {}, 40)
имена = {о["имя"] for о in итог}
проверка("урон пули посчитан", "aca.12" in имена, str(имена))
проверка("перезарядка пули посчитана", "aca.31" in имена, str(имена))
проверка("чужое оружие пропущено (пика для стрелка)", "aca.35" not in имена)
проверка("выигрыш выражен разменом",
         all(о["было"] > о["стало"] for о in итог),
         str([(о["имя"], о["было"], о["стало"]) for о in итог]))
проверка("цена сложена по ВСЕМ ресурсам, включая камень",
         next(о["плата"] for о in итог if о["имя"] == "aca.31") == 15700,
         "5500 золота + 4200 железа + 6000 камня")
проверка("взятый апгрейд второй раз не считается",
         not C.окупаемость_академии(наш, его, L.АКАДЕМИЯ_ЭФФЕКТ, цены,
                                    {"aca.12", "aca.31"}, {}, 40))
# у пикинёра паузы нет — ускорять нечего
пика = {"atk": 8, "hp": 90, "wkind": 1, "pause": 0,
        "dpike": 3, "dsword": 2, "dbullet": 4}
итог2 = C.окупаемость_академии(пика, его, L.АКАДЕМИЯ_ЭФФЕКТ, цены, set(), {}, 40)
проверка("пикинёру академия ничего не даёт", not итог2,
         "его апгрейды за восемнадцатым веком")

print()
if беды:
    print(f"БЕД: {len(беды)} — {', '.join(беды)}")
    raise SystemExit(1)
print("всё чисто")
