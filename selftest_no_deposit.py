# -*- coding: utf-8 -*-
"""ЗАЛЕЖИ НЕТ В РАДИУСЕ СБОРА — направление закрыто, и это сказано словами.

Найдено 23.09 разбором дебюта восьми партий (base27 и debut4), где простой
съедает 38-42 процента труда за первые 200 секунд. Считали так: во всех 58
тактах со свободными руками мост числил направления ОТКРЫТЫМИ, а `BALANCE`
не двигал никого — «некуда идти» объясняло РОВНО НОЛЬ процентов простоя.

Причина в разных мерках. Игра ищет залежь в 40 единицах: еду вокруг МЕЛЬНИЦЫ,
дерево и камень вокруг РАТУШИ (`block_hcmd.inc:536`). Мост считал места по
сетке ресурсов в десяти КЛЕТКАХ от ратуши — мерка много шире, и он звал
ставить людей туда, куда игра их не пошлёт. Модель слушалась, люди стояли.

Что проверяется:
  1. отказ `GATHER resN` закрывает ИМЕННО своё направление, с причиной;
  2. соседние направления остаются открытыми — закрываем по номеру, не гуртом;
  3. без отказа поведение прежнее;
  4. в такте отказ переводится словами и говорит, ЧТО ДЕЛАТЬ;
  5. закрытое направление в таблицу события «руки» не попадает — оно уходит
     в строку `closed`, откуда модель его не выбирает (замер 21.09: из
     таблицы выбирала в 4 случаях из 21, из `closed` — ни разу).
"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import llm_policy as L

ошибок = 0


def проверить(условие, что):
    global ошибок
    if not условие:
        ошибок += 1
        print("  СБОЙ:", что)
    else:
        print("  ок:", что)


ЕДА = "| GATHER res0: no deposit of this kind within 40. Food is searched around the MILL"
ДЕРЕВО = "| GATHER res1: no deposit of this kind within 40"
БАЗА = {"gametime": 90, "peasants": 18, "idle_pea": 12, "mills": 1,
        "my_farm": 100, "my_farmused": 18, "food_ready": 5,
        "wood_slots_free": 600, "stone_slots_free": 150}

print("1-2. закрывается своё направление, соседние целы")
st = dict(БАЗА, last_fail=ДЕРЕВО)
проверить(L.сколько_можно(st, "wood", 12) == (0, "no_deposit"), "дерево закрыто с причиной")
проверить(L.сколько_можно(st, "stone", 12)[0] > 0, "камень остался открыт")
st = dict(БАЗА, last_fail=ЕДА)
проверить(L.сколько_можно(st, "food", 12) == (0, "no_deposit"), "еда закрыта по своему номеру")
проверить(L.сколько_можно(st, "wood", 12)[0] > 0, "дерево при отказе по еде открыто")

print("3. без отказа — как было")
st = dict(БАЗА)
проверить(L.сколько_можно(st, "wood", 12)[0] == 12, "дерево открыто на всех свободных")

print("4. в такте отказ переведён и сказано, что делать")
текст = str(L.situation(dict(БАЗА, last_fail=ЕДА), {}, [], ""))
проверить("НА ЕДУ СЕЙЧАС НИКОГО НЕ ПОСЛАТЬ" in текст, "сказано прямо")
проверить("SEED" in текст and "строй ближе" in текст, "названы оба выхода")
проверить("Повторять ту же команду бесполезно" in текст,
          "сказано, что повтор не поможет — иначе модель повторяет")

print("5. закрытое не попадает в таблицу события «руки»")
таблица = L.ПОВОДЫ["руки"]["запрос"](dict(БАЗА, last_fail=ДЕРЕВО), {}, 12, 20)
проверить("wood=no_deposit" in таблица, "причина названа в строке closed")
проверить("\nwood," not in таблица, "строки дерева в таблице НЕТ")

print()
print("ошибок:", ошибок)
sys.exit(1 if ошибок else 0)
