#!/usr/bin/env python3
"""ШТУРМ ВСЕМ ДОМОМ (1.11, слово игрока «бот намного сильней и никуда не идёт»): ключ `штурм_всем`.

Живая партия 1.11 дала самый дорогой застой проекта. Волна W1 родилась размером 9 (столько было
свободных бойцов), и решение `_удар_готовой` судило ВСЕГДА по её размеру: `свои=9` при 160 дома,
ratio 0,04 против порога 0,92 — 77 тактов подряд «МАЛО_СИЛ». Волна не росла, потому что ATTACK по
`count` берёт только свободных, а 160 держала стойка (`my_held` 160, свободных 3). При этом найм
стоял на паузе, потому что «наших 160 ≥ 1,5 × его 78»: один бот считал себя сильным для паузы и
слабым для удара.

Блок умеет брать весь дом с 28.10 (ключ файла `all`), стратегия этим не пользовалась.
    python3 selftest_штурм_всем.py"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import strategy_live as SL  # noqa: E402

ошибок = 0


def проверить(усл, что):
    global ошибок
    print(("ОК   " if усл else "ОШИБКА ") + что)
    ошибок += not усл


ЖИВОЙ = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                     "sim/поиск/шт_s2_оборона_без_атаки_12мин_стойка_отряд_рефлекс_ратуша_пики_век_эко.json")


class _Волна:
    """Готовая волна из девяти — ровно то, что было в живой партии."""
    def __init__(self, размер=9, сбор=(4, 2), номер=1):
        self.подтверждена, self.размер, self.сбор, self.номер = True, размер, сбор, номер
        self.id = "W1"


# Дом: 165 бойцов, никто не ушёл; его куча 78 стоит в соседней клетке
СОСТОЯНИЕ = dict(
    gametime=600, mil_inf=147, mil_shooters=18, mil_cav=0, mil_away=0,
    my_held=160, my_freewar=3, p1_army=78,
    # форма ecells/ocells — девять полей: x,y,n,пик,стрелков,конных,идут,tx,ty
    ecells="5,2,78,78,0,0,0,-1,-1", ocells="4,2,165,147,18,0,0,-1,-1",
    my_cx=3, my_cy=3, p1_peasants=48, fighters="", p1_fighters="",
)


def решение(доп):
    стр = SL.ЖиваяСтратегия(ЖИВОЙ)
    стр.п = dict(стр.п, **доп)
    приказ, почему = стр._удар_готовой(_Волна(), dict(СОСТОЯНИЕ))
    return приказ, почему, стр


# (а) КАК БЫЛО: судим по волне в 9 человек — и не идём
п0, w0, с0 = решение({})
проверить("свои=9" in w0, f"(а) без ключа решение судит по волне из 9: «{w0[:70]}»")
проверить(п0 is None, "(б) без ключа удар не уходит — это и есть застой живой партии")

# (в) С КЛЮЧОМ: судим всем домом
п1, w1, с1 = решение({"штурм_всем": 1})
проверить("свои=165" in w1 or "свои=165" in str(п1),
          f"(в) с ключом судим ВСЕМ ДОМОМ (165, а не 9): «{w1[:80]}»")
проверить(с1.реестр.мера["штурм всем: волна усилена домом"] == 1
          and any("ШТУРМ ВСЕМ ДОМОМ" in з for з in с1.реестр.записи),
          "(г) усиление посчитано мерой и сказано вслух")
проверить(с0.реестр.мера["штурм всем: волна усилена домом"] == 0 and с0.реестр.записи == [],
          "(д) без ключа ни меры, ни строки")

# (е) приказ уходит и несёт признаки всего дома
проверить(п1 is not None and п1.get("cmd") == "ATTACK",
          f"(е) с ключом удар УХОДИТ: {п1.get('cmd') if п1 else None} — {w1[:60]}")
проверить(п1 is not None and п1.get("all") == 1 and п1.get("merge") == 1,
          "(ж) приказ несёт `all` (блок берёт и держащих строй, снимает удержание) и `merge`")
проверить(п1 is not None and int(п1.get("count") or 0) == 165,
          f"(з) count — весь дом, иначе из дома не уходит никто: {п1.get('count') if п1 else None}")
проверить(п0 is None or not п0.get("all"),
          "(и) без ключа признака `all` в приказе нет — прежние плечи не поедут")

# (к) дома НЕ больше волны — ключ ничего не меняет
п2, w2, с2 = решение({"штурм_всем": 1})
стр = SL.ЖиваяСтратегия(ЖИВОЙ)
стр.п = dict(стр.п, штурм_всем=1)
п3, w3 = стр._удар_готовой(_Волна(размер=400), dict(СОСТОЯНИЕ))
проверить(стр.реестр.мера["штурм всем: волна усилена домом"] == 0,
          "(к) волна больше дома — усиливать нечем, мера не растёт")

print(f"ошибок: {ошибок}")
raise SystemExit(1 if ошибок else 0)
