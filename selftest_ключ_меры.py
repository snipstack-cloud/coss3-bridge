#!/usr/bin/env python3
"""Имя счётчика стратегии без чисел состояния (2.11, Windows (124)): ключи вида «простой готовой: МАЛО_СИЛ свои=69 …»
превращали счётчик в журнал. `llm_policy._ключ_меры` режет имя на первом слове с «=», «×» или на числе.
    python3 selftest_ключ_меры.py"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import llm_policy as L  # noqa: E402

ошибок = 0
for вход, ждём in (
        ("простой готовой: МАЛО_СИЛ свои=69 рядом=118 ratio=0.47 порог=0.92 сила=83/177 стоящих=118×1.5", "простой готовой: МАЛО_СИЛ"),
        ("простой готовой: ОБОРОНА держим дом (213 дома)", "простой готовой: ОБОРОНА держим дом"),
        ("качели: продолжение всеми", "качели: продолжение всеми"),
        ("оборона: зона ратуши", "оборона: зона ратуши")):
    вышло = L._ключ_меры(вход)
    print(("ОК   " if вышло == ждём else "ОШИБКА ") + f"{вход[:50]!r} → {вышло!r}")
    ошибок += вышло != ждём
print(f"ошибок: {ошибок}")
raise SystemExit(1 if ошибок else 0)
