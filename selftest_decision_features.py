# -*- coding: utf-8 -*-
"""Проверки признаков решения об атаке (без игры и без сети)."""
import decision_features as D

ошибок = []


def равно(что, дано, ждём, допуск=0.05):
    if abs(float(дано) - float(ждём)) > допуск:
        ошибок.append(f"{что}: дано {дано}, ждём {ждём}")


# растяжение
р = D.растяжение([[0, 30, 0], [0, 0, 0]])
равно("кулак: клеток", р["клеток"], 1); равно("кулак: доля", р["доля_в_максимуме"], 1.0)
р = D.растяжение([[10, 10, 10], [0, 0, 0]])
равно("растянуто: клеток", р["клеток"], 3); равно("растянуто: доля", р["доля_в_максимуме"], 1 / 3)
р = D.растяжение(None)
равно("пустая сетка: всего", р["всего"], 0)

# подкрепление
равно("казарм 0", D.подкрепление_в_мин(0), 0.0)
равно("казарм 1", D.подкрепление_в_мин(1), 7.3)
равно("казарм 2", D.подкрепление_в_мин(2), 23.7)
равно("казарм 3 (продолжение)", D.подкрепление_в_мин(3), 23.7 + 16.4)
равно("казарм мусор", D.подкрепление_в_мин("нет"), 0.0)

# марш и добор
# УМОЛЧАНИЕ 20 единиц на клетку — карта архива 320 (27.09, поправка Windows);
# 16 это карта турнира 256, и она приходит полем map_w
равно("14 клеток на карте архива", D.марш_секунды(14), 14 * 20 / 1.1)
равно("14 клеток на карте турнира", D.марш_секунды(14, {"map_w": 256}), 14 * 16 / 1.1)
равно("добор за марш при 1 казарме", D.подкрепления_к_приходу(1, D.марш_секунды(14)), 7.3 * (14 * 20 / 1.1) / 60)
равно("клетка архива", D.единиц_в_клетке(), 20)
равно("клетка турнира", D.единиц_в_клетке({"map_w": 256}), 16)
равно("клетка 640", D.единиц_в_клетке({"map_w": 640}), 40)

# решение целиком: 40 наших против кулака 20 при одной казарме и 5 клетках пути
из = D.решение(40, [[0, 20, 0]], 1, 5)
равно("перевес сейчас", из["перевес_сейчас"], 2.0)
if not (из["перевес_к_приходу"] < из["перевес_сейчас"]):
    ошибок.append("перевес к приходу обязан быть НИЖЕ: он донабирает, пока мы идём")
# враг без казарм ничего не добавляет
из = D.решение(40, [[0, 20, 0]], 0, 5)
равно("без казарм добор нулевой", из["он_добавит"], 0.0)
равно("без казарм перевес не падает", из["перевес_к_приходу"], из["перевес_сейчас"])
# пустая клетка врага — перевес огромный, но не деление на ноль
из = D.решение(40, [[0, 0, 0]], 1, 5)
равно("пустая клетка", из["перевес_сейчас"], 99.0)

print(("ОШИБКИ:\n  " + "\n  ".join(ошибок)) if ошибок else "ВСЕ ПРОВЕРКИ ПРИЗНАКОВ РЕШЕНИЯ ПРОЙДЕНЫ")
raise SystemExit(1 if ошибок else 0)
