# -*- coding: utf-8 -*-
"""ЗАПАСНОЕ ОБЛАКО для события на локальной модели.

Повод, 23.09. До этого дня у локального события запасного не было вовсе
(`_зп = "" if локальный`), и отказ локального сервера означал молча пропавший
повод. Ollama на маке 22.09 ДВАЖДЫ переставала слушать порт, а 23.09 мак ещё и
переехал на другой адрес по DHCP.

Тонкость, ради которой всё переписано: прежняя очередь держала ИМЕНА моделей
при ОДНОМ клиенте, а запасное облако живёт на ДРУГОМ адресе. Поэтому очередь
стала очередью ПАР (клиент, модель).

Вторая тонкость: «connection refused» не попадает в TRANSIENT, и прежний код
на не временной беде возвращался сразу, не пробуя замену. Для запасного,
живущего в другом месте, это неверно: вся беда может быть именно в адресе.

Что проверяется:
  1. очередь строится парами, и запасная пара идёт последней;
  2. отказ локальной ВРЕМЕННОЙ бедой -> вопрос уходит запасной;
  3. отказ локальной НЕ временной бедой (сервер не слушает порт) -> вопрос всё
     равно уходит запасной, а не пропадает;
  4. когда локальная отвечает, запасную не трогают вовсе;
  5. в ящик записано, КТО ответил, — иначе при разборе не отличить.
"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import llm_policy as L

ошибок = 0


def проверить(условие, что):
    global ошибок
    if not условие:
        ошибок += 1
        print("  СБОЙ:", что)
    else:
        print("  ок:", что)


class Клиент:
    """Клиент, который либо отвечает, либо падает заданной бедой."""

    def __init__(self, имя, беда=None):
        self.имя, self.беда, self.звали = имя, беда, 0
        сам = self

        class chat:
            class completions:
                @staticmethod
                def create(**kw):
                    сам.звали += 1
                    if сам.беда:
                        raise RuntimeError(сам.беда)
                    class M: content = '{"role": "infantry17", "total": -1, "why": "%s"}' % сам.имя
                    class C: message = M(); finish_reason = "stop"
                    class R: choices = [C()]; usage = None; provider = сам.имя
                    return R()
        self.chat = chat


def позвать(локальная_беда):
    лок = Клиент("локальная", локальная_беда)
    обл = Клиент("облако")
    ящик = {}
    L.think_worker(ящик, лок, "llama3.1:8b", "спрос", False, tries=1,
                   spare="", system="роль", схема=None, усилие="",
                   запас=(обл, "cloud/model"))
    return ящик, лок, обл


print("1-2. локальная упала ВРЕМЕННОЙ бедой (500) — уходим в облако")
ящик, лок, обл = позвать("500 internal server error")
проверить(лок.звали >= 1 and обл.звали == 1, "спросили сперва локальную, потом облако")
проверить(ящик.get("data", {}).get("why") == "облако", "ответ пришёл из облака")
проверить(ящик.get("model") == "cloud/model", "в ящике записано, КТО ответил")

print("3. локальная НЕ отвечает вовсе (порт закрыт) — повод НЕ пропадает")
ящик, лок, обл = позвать("Connection refused: [Errno 111]")
проверить(обл.звали == 1, "облако спрошено, хотя беда не временная")
проверить(ящик.get("data", {}).get("why") == "облако", "ответ получен, событие не потеряно")

print("4. локальная отвечает — облако не трогаем")
ящик, лок, обл = позвать(None)
проверить(лок.звали == 1 and обл.звали == 0, "облако не спрошено ни разу")
проверить(ящик.get("model") == "llama3.1:8b", "ответила локальная, и это записано")

print("5. без запасного всё как раньше")
лок = Клиент("локальная", "Connection refused")
ящик = {}
L.think_worker(ящик, лок, "llama3.1:8b", "спрос", False, tries=1)
проверить("data" not in ящик and ящик.get("err") is not None,
          "запаса нет — беда остаётся бедой, поведение прежнее")

print()
print("ошибок:", ошибок)
sys.exit(1 if ошибок else 0)
