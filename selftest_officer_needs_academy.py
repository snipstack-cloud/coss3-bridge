# -*- coding: utf-8 -*-
"""Найм офицера и барабанщика БЕЗ академии должен отвергаться ВСЛУХ.

Правило игрока 27.09: «нельзя обходить правила, без академии барабанщика и
офицера не построить». Движок нам их даёт и без неё — блок зовёт
`_unit_ProduceUnit` мимо `_player_CheckAccessControlRequirements`
(`country.script:3051`, req0 = aca), и в серии `wood_academy` офицеры вышли на
537-й секунде без академии вовсе. Человек за тем же экраном так не может.

    python3 selftest_officer_needs_academy.py
"""
import sys

import llm_policy as L

ошибок = 0


def проверка(имя, состояние, команда, ждём_отказ):
    global ошибок
    данные = {"commands": [команда]}
    из_ = L.to_commands(данные, st=состояние)
    cmds, брак = из_[0], из_[3]
    ушло = bool(cmds)
    сказано = any("АКАДЕМИИ" in b.upper() for b in брак)
    плохо = (ушло and ждём_отказ) or (not ушло and not ждём_отказ) or (ждём_отказ and not сказано)
    ошибок += int(плохо)
    print(("  НЕ ТАК" if плохо else "  ОК   ") + f" {имя}: ушло={ушло}, сказано вслух={сказано}")


# КЛЮЧ СОСТОЯНИЯ — `academies`. Первая версия этого теста ставила в мок роль
# `academi`, ровно как и проверяемый код, и потому ПРОШЛА при сломанных воротах:
# в живой игре (wood_academy2) найм отвергался и при стоящей академии — 18 / 25 /
# 14 отказов на три копии, офицер не заказан ни разу. Мок, повторяющий ошибку
# кода, не проверяет ничего: имя ключа берём из СЧЁТЧИКА, как берёт его мост.
КЛЮЧ = L.СЧЁТЧИК["academi"]
st_без = {КЛЮЧ: 0, "ba17": 1, "food": 1000, "gametime": 600}
st_с = {КЛЮЧ: 1, "ba17": 1, "food": 1000, "gametime": 600}
st_роль = {"academi": 1, "ba17": 1, "food": 1000, "gametime": 600}
проверка("офицер без академии — отказ", st_без, {"cmd": "TRAIN", "role": "officer17", "total": 1}, True)
проверка("барабанщик без академии — отказ", st_без, {"cmd": "TRAIN", "role": "drummer17", "total": 1}, True)
проверка("офицер с академией — проходит", st_с, {"cmd": "TRAIN", "role": "officer17", "total": 1}, False)
проверка("пехота без академии — проходит", st_без, {"cmd": "TRAIN", "role": "infantry17", "total": -1}, False)
проверка("роль academi вместо ключа академией НЕ считается", st_роль,
         {"cmd": "TRAIN", "role": "officer17", "total": 1}, True)
# Ключ должен быть ТОТ, что пишет блок: состояние с одной лишь ролью `academi`
# академией не считается, иначе тест снова подтвердит ошибку кода.
проверка("роль вместо ключа академией НЕ считается", st_роль,
         {"cmd": "TRAIN", "role": "officer17", "total": 1}, True)
# И статическая страховка на весь этот класс ошибок: никто в мосте не должен
# читать РОЛЬ заказа как ключ состояния там, где имена расходятся.
import os as _os, re as _re
_ист = open(_os.path.join(_os.path.dirname(_os.path.abspath(__file__)), "llm_policy.py"),
            encoding="utf-8").read()
_путаница = sorted({р for р, к in L.СЧЁТЧИК.items()
                    if р != к and _re.search(r'st\.get\("' + _re.escape(р) + r'"\)', _ист)})
print(("  НЕ ТАК" if _путаница else "  ОК   ")
      + f" роль как ключ состояния нигде не читается: {_путаница or 'чисто'}")
ошибок += int(bool(_путаница))
print("\n" + ("всё чисто" if not ошибок else f"ОШИБОК: {ошибок}"))
sys.exit(1 if ошибок else 0)
