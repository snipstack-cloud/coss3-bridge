def читать(путь):
    из = []
    with io.open(путь, encoding="utf-8", errors="replace") as ф:
        for строка in ф:
            строка = строка.strip()
            if not строка:
                continue
            try:
                из.append(json.loads(строка))
            except ValueError:
                continue
    return из


def эпизоды(записи, время):
    """Разрез на партии по крупному откату игрового времени (см. докстринг)."""
    части, тек, пред = [], None, None
    for з in записи:
        g = время(з)
        if тек is None or (пред is not None and g < пред - ПОРОГ_ОТКАТА):
            тек = []
            части.append(тек)
        тек.append(з)
        пред = g
    return части


def ц(д, к):
    try:
        return float(д.get(к) or 0)
    except (TypeError, ValueError):
        return 0.0


def траты_окна(пред, след):
    """Еда, ПОТРАЧЕННАЯ между двумя снимками, по приросту того, что куплено.

    Считается по состоянию, а НЕ по командам трассы. Первая редакция брала
    запрошенные `TRAIN` и насчитала 921 мушкетёра при шести живых стрелках:
    мост запрашивает найм каждый такт, движок почти всегда отказывает (нет
    ресурса, казарма занята), а отказ еды не стоит. Прирост числа юнитов —
    это то, что действительно куплено и списано.

    ИЗЪЯН, названный вслух: гибель маскирует найм. Если за окно родился один
    пикинёр и погибли двое, прирост отрицательный, и покупка не видна. Значит
    в боевых окнах траты ЗАНИЖЕНЫ, и невязку там надо читать с этой поправкой.
    """
    всего, из_чего = 0.0, []
    for ключ, цена, имя in (("peasants", 100, "крестьянин"),
                            ("mil_inf", 25, "пикинёр"),
                            ("mil_shooters", 50, "мушкетёр"),
                            ("mil_cav", 100, "драгун")):
        прирост = int(ц(след, ключ) - ц(пред, ключ))
        if прирост > 0:
            всего += цена * прирост
            из_чего.append(имя + "x" + str(прирост))
    # ПРОКАЧКИ ЗДЕСЬ НЕ СЧИТАЮТСЯ, И ЭТО НЕ ЛЕНЬ. Ценник живёт в поле
    # `upg_avail` живого состояния, а в ЗАПИСЯХ его нет: ни в одном из 2601
    # снимка и ни в одной из 2179 строк трассы (проверено 7.10), хотя команд
    # UPGRADE там 949. Поэтому цену прокачки из записей берут иначе — провалом
    # еды перед её появлением, см. `лестница_цен`. Трата на прокачку остаётся в
    # невязке НАРОЧНО: пусть она будет видна как необъяснённое, а не размазана
    # по оценке, которой у нас нет.
    return всего, из_чего


def лестница_цен(партии):
    """Цены ступеней, снятые по провалу еды перед их появлением.

    Движок списывает ресурс В МОМЕНТ ЗАКАЗА, а в `upg_done` ступень попадает по
    завершении исследования — около 16 с позже. Отсюда способ достать цену из
    записей, где ценника нет вовсе: крупный провал еды, за которым через 8-30 с
    появляется ровно одна новая ступень, и есть её цена.

    ПРЕДЕЛ СПОСОБА, проверенный 8.10 настоящим ценником из `upg_avail` живого
    состояния: оценки занижены на 3-11 % (за те же секунды шёл приход), и это
    терпимо — но на ОДИНОЧНОМ наблюдении способ врёт в разы.
    `bar.musketeernet.2.1` он оценил в 15 675 еды при настоящих 170: провал от
    `bar.pikeman.1.5` был приписан мушкетёрской ступени, которая завершалась
    рядом, а проверка «две ступени сразу» такого не ловит. Поэтому: верить от
    пяти наблюдений и только как оценке СНИЗУ; где есть живой ценник — брать
    его, а не это. Настоящая лестница записана в `world.md`.

    Порог провала 1000: дороже всех юнитов крестьянин за 100 еды, и найм такого
    провала дать не может даже залпом.
    """
    ПРОВАЛ = 1000
    из = collections.defaultdict(list)
    for часть in партии:
        провалы = []
        for пред, след in zip(часть, часть[1:]):
            d_еда = ц(след, "food") - ц(пред, "food")
            if d_еда < -ПРОВАЛ:
                из_ = (int(ц(след, "gametime")), -d_еда,
                       -(ц(след, "gold") - ц(пред, "gold")))
                провалы.append(из_)
        было = set()
        for с in часть:
            стало = {x for x in str(с.get("upg_done") or "").split(",") if x}
            новые = стало - было
            if not новые:
                continue
            было = стало
            когда = int(ц(с, "gametime"))
            рядом = [p for p in провалы if 8 <= когда - p[0] <= 30]
            # Две ступени сразу или два провала рядом — не разделить, пропускаем:
            # приписать цену наугад хуже, чем не приписать.
            if len(новые) == 1 and len(рядом) == 1:
                из[next(iter(новые))].append((рядом[0][1], рядом[0][2]))
    return из


