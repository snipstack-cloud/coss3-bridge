# -*- coding: utf-8 -*-
"""Самопроверка блока «Удар идёт».

Блок считает от МОМЕНТА ПОДХОДА, поэтому у него есть память между тактами — и
именно память ломается незаметно: не почистишь между партиями, и следующая
партия начнётся с чужим счётчиком. Снимки промпта этого не ловят.
"""
import sys
import llm_policy as L

беды = []


def проверка(имя, условие, пояснение=""):
    if условие:
        print("  ОК   " + имя)
    else:
        беды.append(имя)
        print("  ПЛОХО " + имя + (" — " + пояснение if пояснение else ""))


def текст(s):
    return "\n".join(L.удар(s))


L.УДАР.clear()
далеко = dict(gametime=500, mil_far=205, mil_away=24, p1_peasants=51, p1_army=43)
близко = dict(далеко, mil_far=60)

# 1. Пока волна не дошла — молчать.
проверка("до подхода блока нет", текст(близко) == "")

# 2. Подошла — считает такты от подхода, а не от начала партии.
t1 = текст(далеко)
проверка("подход замечен", "волна у базы врага 1 такт" in t1)
проверка("время подхода названо", "8:20" in t1)

# 3. Считает изменение, а не мгновенный снимок.
t2 = текст(dict(далеко, gametime=560, mil_away=21, p1_peasants=58))
проверка("показано изменение", "51 -> 58" in t2 and "24 -> 21" in t2)

# 4. Третий такт без убитых крестьян — сказать вслух.
t3 = текст(dict(далеко, gametime=620, mil_away=16, p1_peasants=68))
проверка("проигранная гонка названа вслух", "ГОНКУ ТЫ ПРОИГРЫВАЕШЬ" in t3)
проверка("названа армия, которая прикрывает", "прикрывает" in t3)

# 5. Крестьяне убывают — не ругаться: удар идёт.
L.УДАР.clear()
текст(далеко); текст(далеко)
t5 = текст(dict(далеко, gametime=620, p1_peasants=44))
проверка("при убыли не ругается", "ГОНКУ ТЫ ПРОИГРЫВАЕШЬ" not in t5)
проверка("считает, за сколько дойдёт до нуля", "до нуля при таком темпе" in t5)

# 6. Волна ушла от базы — счётчик сбрасывается.
L.УДАР.clear()
текст(далеко)
текст(близко)
t6 = текст(далеко)
проверка("после отхода счёт с нуля", "1 такт" in t6)

# 7. Волны нет вовсе — молчать (mil_away = 0).
проверка("без бойцов в поле блока нет", текст(dict(далеко, mil_away=0)) == "")

# 8. Память чистится между партиями — иначе вторая партия унаследует счётчик.
L.УДАР.clear()
проверка("между партиями память пуста", L.УДАР == {})

print()
print("ПРОВАЛОВ:", len(беды))
sys.exit(1 if беды else 0)
