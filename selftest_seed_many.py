# -*- coding: utf-8 -*-
"""Самопроверка посева НЕСКОЛЬКИХ полей за один приказ.

Наблюдение игрока 21.09: когда участок у мельницы выкошен весь, поля засевают
несколько подряд, а не по одному. До этого `SEED` жёстко заказывал ОДНО поле
(`block_hcmd.inc`: `_unit_ProduceUnit(..., 1, ...)`), и пересев растягивался на
такты по двадцать игровых секунд — еда всё это время не росла, а ниже 500 еды
не нанимается никто.

Поле — это юнит, который производит мельница (`usage = gc_obj_usage_field`,
цена 5 золота, `unit.script:1692`), поэтому несколько полей это просто
несколько единиц в одном заказе.

Стережётся:
* команда несёт число и доходит до блока;
* без числа — по-прежнему одно поле, как было;
* выкошенное поле мост замечает и даёт ГОТОВЫЙ приказ с числом;
* названа плата: каждое поле стоит 5 золота;
* число не безгранично — золото узкое место в 61-98 процентах тактов.
"""
import coss3_bridge as B
import llm_policy as L

беды = []


def проверка(имя, условие, пояснение=""):
    if условие:
        print("  ОК    " + имя)
    else:
        беды.append(имя)
        print("  ПЛОХО " + имя + (" — " + пояснение if пояснение else ""))


# команда
проверка("seed() без числа даёт одно поле", B.seed().a1 == 1)
проверка("seed(5) несёт пятёрку", B.seed(5).a1 == 5)
проверка("ноль и отрицательное не проходят",
         B.seed(0).a1 == 1 and B.seed(-3).a1 == 1)

# разбор ответа модели
c1 = L.to_commands({"commands": [{"cmd": "SEED"}]}, set(), set())[0][0]
c5 = L.to_commands({"commands": [{"cmd": "SEED", "total": 5}]}, set(), set())[0][0]
проверка("ответ без числа — одно поле", c1.cmd == "SEED" and c1.a1 == 1)
проверка("ответ с числом доходит как есть", c5.cmd == "SEED" and c5.a1 == 5)


def состояние(готовых=0, на_еде=4):
    return {"gametime": 600, "mills": 1, "food_ready": готовых, "on_food": на_еде,
            "food": 900, "peasants": 40, "centers": 1, "ba17": 1, "my_freewar": 10,
            "mil_inf": 10, "p1_enemy": 1, "p1_army": 30, "grid_n": 16,
            "map_open": 1, "my_cx": 3, "my_cy": 12}


ст = состояние()
т = L.situation(ст, ст, [], "", None)
проверка("выкошенное поле замечено", "Поле ВЫКОШЕНО" in т)
проверка("дан готовый приказ с числом", '"cmd":"SEED","total":4' in т)
проверка("названа плата золотом", "стоит 5 золота" in т)
проверка("сказано, сколько тактов стоил бы пересев по одному",
         "занял бы 4 такта" in т, "и склонение должно быть верным")

# потолок: больше пяти не просим, золото узкое место
много = состояние(на_еде=30)
т2 = L.situation(много, много, [], "", None)
проверка("больше пяти за раз не предлагаем", '"total":5' in т2, т2[:80])

# поле созрело — совет другой
созрело = состояние(готовых=20, на_еде=0)
т3 = L.situation(созрело, созрело, [], "", None)
проверка("у созревшего поля совет про людей, а не про посев",
         "Поле СОЗРЕЛО" in т3 and "Поле ВЫКОШЕНО" not in т3)

# нет мельницы — молчим
без = состояние()
без["mills"] = 0
т4 = L.situation(без, без, [], "", None)
проверка("без мельницы про посев не говорим", "Поле ВЫКОШЕНО" not in т4)

# склонения
проверка("склонения считаются верно",
         (L._скл(1, "поле", "поля", "полей") == "поле"
          and L._скл(3, "поле", "поля", "полей") == "поля"
          and L._скл(5, "поле", "поля", "полей") == "полей"
          and L._скл(11, "такт", "такта", "тактов") == "тактов"))

print()
if беды:
    print(f"БЕД: {len(беды)} — {', '.join(беды)}")
    raise SystemExit(1)
print("всё чисто")
