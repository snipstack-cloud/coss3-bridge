#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Разбор ОДНОЙ трассы локальной моделью: что в партии выглядит странно.

    python3 разбор_трассы.py <путь к coss3_bot.jsonl> [--модель qwen3:30b-a3b]
    python3 разбор_трассы.py <...> --сухой     # только выжимка, без модели

Зачем локальная, а не облако: трасс 146, тактов в них 17901, и разбор задним
числом — ровно то место, где бесплатная модель, думающая по десять секунд,
лучше платной, отвечающей за полторы. Партию можно разобрать ночью, и это
ничего не стоит.

ЧЕГО ЭТОТ РАЗБОР НЕ ДЕЛАЕТ — не выносит выводов. Правило проекта, купленное
дважды за 22.09: `why` модели это ВЕРА модели, а не факт игры (в тот день её
рассуждение «не хватает 258» приняли за отказ игры, хотя заказ был принят).
Поэтому:

  * модель видит ВЫЖИМКУ, собранную python'ом из полей трассы, а не свои
    прежние слова: `why`, `lesson`, `idea` в выжимку НЕ идут вовсе;
  * каждое наблюдение обязано нести поле «как_проверить» — меру, которую
    можно посчитать по трассам. Нет меры — наблюдение отбрасывается здесь же,
    без обсуждения, и отброшенные печатаются отдельно;
  * такты, на которые модель ссылается, сверяются с трассой: выдуманный номер
    такта — признак того, что она сочиняет, и это видно сразу.

Разбор кладётся в `разборы/<дата>_<идея>_<копия>.md`, трасса помечается
разобранной в `разборы/реестр.tsv` (путь, sha256, тактов, модель, дата).
Реестр в ЭТОМ репозитории нарочно: `coss3-res` пишет ферма, и чужая рука в нём
поссорит прогоны.
"""
from __future__ import annotations
import hashlib, json, os, re, sys, time, urllib.request
from datetime import date

КОРЕНЬ = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, КОРЕНЬ)
import bench_local as BL
from coss3_bridge import ROLE, RESOURCE

# Обратные таблицы: в трассе команды лежат ЧИСЛАМИ (`BUILD 4/1` — это роль №4,
# всего 1). Первый разбор 22.09 это и погубило: модель прочитала числа как
# количество зданий, сложила 4+14 и выдала три ложные находки подряд. Числа
# без легенды нечитаемы, и виноват в этом инструмент, а не модель.
ИМЯ_РОЛИ = {v: k for k, v in ROLE.items()}
ИМЯ_РЕСУРСА = {v: k for k, v in RESOURCE.items()}

ПАПКА = os.path.join(КОРЕНЬ, "разборы")
РЕЕСТР = os.path.join(ПАПКА, "реестр.tsv")

ВОПРОС = """Ты разбираешь ОДНУ отыгранную партию Cossacks 3. Бот играл человеческим
слотом: каждый такт он видел состояние и отдавал команды.

Твоя задача — найти в выжимке СТРАННОСТИ: места, где поведение противоречит
само себе или числам. Например: команда повторяется, хотя предыдущая принята;
ресурс копится без расхода; люди стоят без дела; заказ отвергнут, а его
повторяют; армия растёт, но не идёт.

СТРОГИЕ ПРАВИЛА ОТВЕТА:
* каждое наблюдение — про КОНКРЕТНЫЕ такты, номера брать из колонки gt;
* каждое наблюдение обязано нести «как_проверить»: меру, которую можно
  ПОСЧИТАТЬ по трассам партий, числом. «Посмотреть внимательнее» — не мера;
* не предлагай правок и не объясняй, ПОЧЕМУ так вышло. Только что видно;
* если странностей нет — верни пустой список, это нормальный ответ;
* находок не больше ПЯТИ, самых заметных. Лучше три проверяемых, чем десять
  разговорных.

ЧТО НЕ ЯВЛЯЕТСЯ СТРАННОСТЬЮ, не трать на это находки:
* строка с непустым «событие» — отдельный вызов из фонового потока, она может
  стоять НЕ по возрастанию gt. Порядок строк тут ни о чём не говорит;
* `TRAIN ... /-1` — это бесконечный заказ, а не ошибка;
* пустые колонки «отвергнуто» и «бой» — обычное дело;
* BUILD в такте и «строится: ничего» в ТОМ ЖЕ такте — так и должно быть:
  закладка появляется следующим тактом. Странность — если её нет и дальше;
* BUILDERS N при N крестьянах без дела — это НЕ противоречие, а ответ: бот
  видит незанятых и отправляет их на стройку. То же с BALANCE;
* «BUILD ratusha всего 1» значит «хочу, чтобы ратуша была одна», а не «строю
  ещё одну». Это желаемый ИТОГ.

МЕРА в «как_проверить» должна считаться по МНОГИМ тактам или партиям
(«в скольких тактах из N ...», «сколько раз за партию ...»). Пересказ одного
такта мерой не является и будет отброшен.

Ответ — ТОЛЬКО JSON: {"находки": [{"что": "...", "такты": [123, 456],
"как_проверить": "..."}]}"""


def стройка(сколько, wip):
    """`1` + `minegold/5/3/98` -> `minegold 98%`. Пусто — «ничего».

    Прежняя склейка давала `1/minegold/5/3/98`, и модель 22.09 объявила такую
    колонку ПУСТОЙ, а заодно решила, что здание уже построено.
    """
    if not str(wip or "").strip():
        return "ничего"
    куски = []
    for ч in str(wip).split(","):
        поля = ч.split("/")
        куски.append(f"{поля[0]} {поля[-1]}%" if len(поля) >= 4 else ч)
    return ", ".join(куски)


def словами(c):
    """`{"cmd":"BUILD","a1":4,"a2":1}` -> `BUILD mill всего 1`.

    Без этого модель видит голые числа и сочиняет им смысл — проверено.
    """
    к, a1, a2 = c.get("cmd"), c.get("a1"), c.get("a2")
    if к in ("BUILD", "TRAIN"):
        роль = ИМЯ_РОЛИ.get(a1, f"роль№{a1}")
        сколько = "бесконечно" if a2 == -1 else f"всего {a2}"
        return f"{к} {роль} {сколько}"
    if к == "BALANCE":
        return f"BALANCE {ИМЯ_РЕСУРСА.get(a1, a1)} {a2} чел."
    if к == "BUILDERS":
        return f"BUILDERS {a1} чел."
    хвост = f" {a1}" + (f"/{a2}" if a2 not in (None, "") else "")
    return f"{к}{хвост}" + ((" " + c["upg"]) if c.get("upg") else "")


def выжимка(строки):
    """Сжать трассу до таблицы, которую можно показать модели.

    В выжимку идут ТОЛЬКО наблюдаемые величины: состояние, команды, отказы,
    события, потери. Слова модели (`why`, `lesson`, `idea`, `critic_hyp`) не
    идут — иначе разбор пойдёт по её же вере, а не по игре.
    """
    выжимка._прежние = (0, 0, 0, 0)
    строк = ["ПОРЯДОК ВНУТРИ СТРОКИ: сначала СОСТОЯНИЕ (каким бот его увидел),",
             "потом КОМАНДЫ, которые он на это состояние ответил. Команда — это",
             "ОТВЕТ на числа в той же строке, а не противоречие им. Итог команды",
             "виден в СЛЕДУЮЩИХ строках, а не в этой.",
             "",
             "gt | еда дер кам зол жел уг | крест(без дела) | пех кав | строится | команды | отвергнуто | событие | убито за такт"]
    for d in строки:
        st = d.get("state") or {}
        if not st:
            continue
        ч = lambda k: st.get(k, "")
        кмд = ";".join(словами(c) for c in (d.get("cmds") or []))
        отв = ";".join(str(r)[:40] for r in (d.get("rejected") or []))
        if d.get("veto"):
            отв += (" | вето: " + str(d["veto"])[:40])
        # РАЗНИЦА, а не накопленный итог. В трассе `потери` копятся за партию, и
        # «убито крест 6» стоит в пяти тактах подряд — это одни и те же шестеро.
        # Показывать их как есть значит звать модель сложить 6+6+6+6+6.
        п = d.get("потери") or {}
        сейчас = tuple(int(п.get(k, 0) or 0) for k in
                       ("en_pea", "en_mil", "my_pea", "my_mil"))
        было = выжимка._прежние
        выжимка._прежние = сейчас
        d_ = [a - b for a, b in zip(сейчас, было)]
        бой = (f"убито крест {d_[0]}, бойцов {d_[1]}; потеряно {d_[2]}/{d_[3]}"
               if any(d_) else "")
        соб = (f"{d.get('повод') or d.get('событие') or ''}").strip()
        строк.append(
            f"{d.get('gt')} | {ч('food')} {ч('wood')} {ч('stone')} {ч('gold')} {ч('iron')} {ч('coal')}"
            f" | {ч('peasants')}({ч('idle_pea')}) | {ч('mil_inf')} {ч('my_freewar')}"
            f" | {стройка(ч('building_now'), ч('wip'))}"
            f" | {кмд} | {отв} | {соб} | {бой}"
            + (f" | АТАКА на {d.get('target')}" if d.get("attack") else ""))
    return "\n".join(строк)


def спросить(модель, текст, таймаут=1800):
    тело = {"model": модель, "prompt": ВОПРОС + "\n\nВЫЖИМКА ПАРТИИ:\n" + текст,
            "stream": False, "keep_alive": "15m",
            # Окно ЯВНО: умолчание ollama 4096, а выжимка партии длиннее, и
            # обрезание было бы молчаливым — модель разобрала бы половину
            # партии, не сказав об этом.
            # 12000, потому что потолок делится между рассуждением и ответом:
            # на 4000 разбор партии оборвался посреди думы (1543 слова). Обрыв
            # стенд ловит и говорит вслух — молчаливого нуля тут быть не должно.
            "options": {"num_predict": 12000, "num_ctx": 32768, "temperature": 0}}
    BL.поправить(тело, модель, запас=12000)
    т = time.time()
    d = json.load(urllib.request.urlopen(urllib.request.Request(
        BL.АДРЕС_БАЗА + "/api/generate", json.dumps(тело).encode(),
        {"Content-Type": "application/json"}), timeout=таймаут))
    return BL.вынуть(d), time.time() - т, d


def разобрать_ответ(текст):
    i, j = текст.find("{"), текст.rfind("}")
    if i < 0 or j <= i:
        return None
    try:
        return json.loads(текст[i:j + 1])
    except json.JSONDecodeError:
        return None


def просеять(находки, такты):
    """Отделить проверяемое от разговоров. Возвращает (принятые, отброшенные)."""
    принятые, отброшенные = [], []
    for н in находки or []:
        если = []
        if not isinstance(н, dict):
            отброшенные.append((str(н)[:60], "не запись")); continue
        мера = str(н.get("как_проверить") or "").strip()
        if not мера:
            если.append("нет меры")
        # Мера, которая называет ровно тот же такт, что и находка, — это
        # пересказ наблюдения, а не проверка. Первый разбор 22.09 дал три
        # таких подряд, и все три оказались ложными.
        elif any(str(t) in мера for t in (н.get("такты") or [])):
            если.append("мера пересказывает тот же такт")
        чужие = [t for t in (н.get("такты") or []) if t not in такты]
        if чужие:
            если.append(f"таких тактов в партии нет: {чужие[:4]}")
        if not (н.get("такты") or []):
            если.append("не указаны такты")
        (отброшенные if если else принятые).append(
            (н, "; ".join(если)) if если else н)
    return принятые, отброшенные


def main():
    арг = [a for a in sys.argv[1:]]
    сухой = "--сухой" in арг
    if сухой:
        арг.remove("--сухой")
    модель = "qwen3:30b-a3b"
    if "--модель" in арг:
        i = арг.index("--модель"); модель = арг[i + 1]; del арг[i:i + 2]
    if not арг:
        raise SystemExit(__doc__)
    путь = os.path.abspath(арг[0])

    сырые = [json.loads(s) for s in open(путь, encoding="utf-8") if s.strip()]
    такты = {d.get("gt") for d in сырые if d.get("state")}
    текст = выжимка(сырые)
    print(f"трасса: {путь}\nтактов с состоянием: {len(такты)}, "
          f"выжимка {len(текст)} символов")
    if сухой:
        print("\n" + текст)
        return

    ответ, сек, сырой = спросить(модель, текст)
    дума = len((сырой.get("thinking") or "").split())
    print(f"модель {модель}: {сек:.0f} с, дума {дума} слов, "
          f"обрыв по длине: {'ДА' if сырой.get('done_reason') == 'length' else 'нет'}")
    d = разобрать_ответ(ответ)
    if d is None:
        print("ОТВЕТ НЕ РАЗОБРАН:\n" + ответ[:400]); sys.exit(1)
    принятые, отброшенные = просеять(d.get("находки"), такты)
    print(f"находок {len(d.get('находки') or [])}: принято {len(принятые)}, "
          f"отброшено {len(отброшенные)}")

    части = путь.split(os.sep)
    имя = f"{части[-3]}_{части[-2]}" if len(части) >= 3 else os.path.basename(путь)
    os.makedirs(ПАПКА, exist_ok=True)
    файл = os.path.join(ПАПКА, f"{имя}.md")
    sha = hashlib.sha256(open(путь, "rb").read()).hexdigest()[:12]
    with open(файл, "w", encoding="utf-8") as f:
        f.write(f"# Разбор трассы {имя}\n\n"
                f"Трасса: `{os.path.relpath(путь, os.path.expanduser('~'))}`, "
                f"sha256 `{sha}`, тактов {len(такты)}.\n"
                f"Разобрано {date.today().isoformat()} моделью `{модель}` "
                f"({сек:.0f} с, рассуждение {дума} слов).\n\n"
                "Наблюдения модели — это НАБЛЮДЕНИЯ, а не выводы: каждое несёт меру,\n"
                "которую надо посчитать, прежде чем считать находку находкой.\n\n"
                "## Принято\n\n")
        for н in принятые:
            f.write(f"* **{н.get('что')}**\n  * такты: {н.get('такты')}\n"
                    f"  * как проверить: {н.get('как_проверить')}\n")
        if not принятые:
            f.write("_ничего проверяемого_\n")
        f.write("\n## Отброшено стендом\n\n")
        for н, почему in отброшенные:
            что = н.get("что") if isinstance(н, dict) else н
            f.write(f"* {что} — _{почему}_\n")
        if not отброшенные:
            f.write("_ничего_\n")
    новый = not os.path.exists(РЕЕСТР)
    with open(РЕЕСТР, "a", encoding="utf-8") as f:
        if новый:
            f.write("трасса\tsha256\tтактов\tмодель\tдата\tфайл\tпринято\tотброшено\n")
        f.write(f"{os.path.relpath(путь, os.path.expanduser('~'))}\t{sha}\t{len(такты)}\t"
                f"{модель}\t{date.today().isoformat()}\t{os.path.basename(файл)}\t"
                f"{len(принятые)}\t{len(отброшенные)}\n")
    print(f"разбор: {файл}\nпомечено в реестре: {РЕЕСТР}")


if __name__ == "__main__":
    main()
