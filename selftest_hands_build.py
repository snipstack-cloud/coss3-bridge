# -*- coding: utf-8 -*-
"""СТРОЙКА как направление события «руки» (23.09, замысел игрока).

Событие умело послать свободные руки на шесть ресурсов, но не на НЕДОСТРОЙ —
хотя обычный такт это делает, и делает хорошо: живая партия 23.09, 52-я
секунда, один ход — `BUILD` мельницы и склада, `BUILDERS 8`, а остальные
десять разложены по еде, дереву и камню, со словами «ставлю мельницу, без неё
еда не добывается, параллельно начинаю цепочку к армии». Пока направления не
было, свободные руки при недострое могли только копать.

Что проверяется:
  1. `build` есть в перечислении схемы, рядом с ресурсами и `wait`;
  2. команда уходит BUILDERS (потолок строителей), а не BALANCE;
  3. число складывается с теми, кто уже строит, — как и у ресурсов;
  4. без недостроя направление ЗАКРЫТО с причиной `no_wip`, и в таблице его
     нет: закрытое в таблице модель выбирает (замер 21.09, 4 случая из 21);
  5. в таблице у `build` в колонке stock стоит ЧИСЛО НЕДОСТРОЕВ, а не ноль;
  6. свободные одни на всех: стройка и ресурс вместе не посылают больше, чем
     есть людей.
"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import llm_policy as L

ошибок = 0


def проверить(условие, что):
    global ошибок
    if not условие:
        ошибок += 1
        print("  СБОЙ:", что)
    else:
        print("  ок:", что)


ЕСТЬ = {"gametime": 300, "food": 900, "wood": 700, "stone": 400, "idle_pea": 12,
        "on_food": 8, "on_wood": 3, "on_build": 4, "mills": 1, "peasants": 30,
        "building_now": 2, "my_farm": 9, "my_farmused": 3}
НЕТ = dict(ЕСТЬ, building_now=0, wip="")

print("1. build в перечислении схемы")
enum = L.ПОВОДЫ["руки"]["схема"](ЕСТЬ, 12)["properties"]["куда"]["anyOf"][0]["enum"]
проверить("build" in enum, f"перечисление: {enum}")
проверить("wait" in enum, "wait на месте — ждать по-прежнему законный ответ")

print("2-3. команда BUILDERS и сложение с уже строящими")
о = L.руки_в_команды({"куда": [{"куда": "build", "сколько": 5}], "why": "достроить"}, ЕСТЬ)
к = о["commands"][0]
проверить(к["cmd"] == "BUILDERS", f"ушла команда {к['cmd']}, а не BALANCE")
проверить(к["total"] == 9, f"4 уже строят + 5 = {к['total']}")

print("4. без недостроя направление закрыто")
можно, отчего = L.сколько_можно(НЕТ, "build", 12)
проверить(можно == 0 and отчего == "no_wip", f"закрыто как {отчего!r}")
таблица = L.ПОВОДЫ["руки"]["запрос"](НЕТ, {}, 12, 20)
проверить("build=no_wip" in таблица, "причина названа в строке closed")
проверить("\nbuild," not in таблица, "закрытого направления в таблице НЕТ")
о = L.руки_в_команды({"куда": "build", "сколько": 5, "why": "достроить"}, НЕТ)
проверить(not о["commands"] and "no_wip" in о["why"],
          f"ответ отвергнут вслух: {о['why'][:60]}")

print("5. stock у стройки — число недостроев")
таблица = L.ПОВОДЫ["руки"]["запрос"](ЕСТЬ, {}, 12, 20)
строка = [s for s in таблица.splitlines() if s.startswith("build,")][0]
проверить(строка.split(",")[1] == "2", f"строка таблицы: {строка}")
проверить(строка.split(",")[2] == "4", "в колонке workers — те, кто уже строит")

print("6. свободные одни на всех")
о = L.руки_в_команды({"куда": [{"куда": "build", "сколько": 9},
                               {"куда": "food", "сколько": 9}], "why": "и то и то"}, ЕСТЬ)
сумма = ((о["commands"][0]["total"] - 4) if о["commands"] else 0) + \
        ((о["commands"][1]["total"] - 8) if len(о["commands"]) > 1 else 0)
проверить(сумма <= 12, f"роздано {сумма} при 12 свободных")

print()
print("ошибок:", ошибок)
sys.exit(1 if ошибок else 0)
