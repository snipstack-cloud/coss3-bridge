# -*- coding: utf-8 -*-
"""ПОЧЕМУ крестьяне стоят: простой, разложенный по причине.

`idle_report.py` отвечает, СКОЛЬКО труда уходит в никуда. Этот отвечает, почему
именно: было ли в тот миг куда поставить людей, какие линии стояли пустыми и не
провалилась ли уже еда под порог, при котором наём гаснет целиком.

Считается в КРЕСТЬЯНО-СЕКУНДАХ, а не в тактах: «свободных пять» при двадцати
крестьянах и при сотне — разные вещи, и по тактам этого не видно.

Доступность направления берётся ТЕМ ЖЕ кодом, каким мост считает `max_add`
(`llm_policy.сколько_можно`), а не переписывается здесь заново: иначе инструмент
мерил бы свои представления о правилах, а не правила моста.

    python3 idle_why.py <каталог идеи> [<каталог базы>]

Что он показал по `base24` 21.09 (464 такта, 9 партий) и почему после этого
появился ключ `--need`:

  тактов с простоем 422 из 464 (91 процент)
  крестьяно-секунд простоя 74 321 из 593 008 (12,5 процента)
  из простоя: БЫЛО КУДА поставить 100,0 процента, НЕКУДА 0,0
  на дереве ноль человек в 28,8 процента этого времени, на камне в 23,8
  еда ниже порога 500 в 13,2 процента

То есть места не кончались никогда: люди стояли при открытых направлениях, и
почти треть этого времени на дереве не работал НИКТО.
"""
import collections
import glob
import json
import os
import statistics as S
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import llm_policy as L


def ч(v):
    try:
        return float(v)
    except (TypeError, ValueError):
        return 0.0


def такты(файл):
    """Такты партии по трассе. Записи `finish` пропускаем: здесь границы партий
    не нужны, а счёт идёт по каждому такту отдельно."""
    из = []
    for строка in open(файл, encoding="utf-8"):
        строка = строка.strip()
        if not строка:
            continue
        x = json.loads(строка)
        if isinstance(x.get("state"), dict) and "gametime" in x["state"]:
            из.append(x)
    return из


def разбор(корень):
    пс_всего = пс_простоя = пс_открыто = 0.0
    тактов = с_простоем = открытых = с_балансом = 0
    свободных_в_такте = []
    пусто = collections.Counter()
    причины = collections.Counter()
    for файл in sorted(glob.glob(f"{корень}/**/coss3_bot.jsonl", recursive=True)):
        ряд = такты(файл)
        for i, т in enumerate(ряд):
            st = т["state"]
            # Шаг такта: до следующего, а у последнего — медиана партий base24.
            dt = 21.0
            if i + 1 < len(ряд):
                d = ч(ряд[i + 1]["state"]["gametime"]) - ч(st["gametime"])
                if 0 < d < 300:
                    dt = d
            тактов += 1
            пс_всего += ч(st.get("peasants")) * dt
            своб = ч(st.get("idle_pea"))
            if своб <= 0:
                continue
            с_простоем += 1
            пс_простоя += своб * dt
            свободных_в_такте.append(своб)
            открытые = []
            for ключ, _имя, _поле in L.КУДА_РУКИ:
                можно, почему = L.сколько_можно(st, ключ, int(своб))
                if можно > 0:
                    открытые.append(ключ)
                else:
                    причины[f"{ключ}={почему}"] += 1
                # ЛИНИЯ ПУСТА, А ПОСТАВИТЬ МОЖНО — то, ради чего всё считается.
                if можно > 0 and ч(st.get(L.РАБОТНИКИ_НА[ключ])) == 0:
                    пусто[ключ] += своб * dt
            if открытые:
                пс_открыто += своб * dt
                открытых += 1
                if any(str(c.get("cmd") or c).startswith("BALANCE")
                       for c in (т.get("cmds") or [])):
                    с_балансом += 1
            if ч(st.get("food")) < L.ПОРОГ_ЕДЫ:
                пусто["еда ниже порога"] += своб * dt
    if not тактов or not пс_простоя:
        print(f"{корень}: тактов с простоем не нашлось")
        return None
    print(f"\n{корень}")
    print(f"  тактов {тактов}, с простоем {с_простоем} ({100 * с_простоем / тактов:.0f}%)")
    print(f"  крестьяно-секунд всего {пс_всего:.0f}, простоя {пс_простоя:.0f} "
          f"({100 * пс_простоя / пс_всего:.1f}%)")
    print(f"  из простоя: БЫЛО КУДА поставить {100 * пс_открыто / пс_простоя:.1f}%, "
          f"НЕКУДА {100 * (пс_простоя - пс_открыто) / пс_простоя:.1f}%")
    print(f"  свободных в таком такте: медиана {S.median(свободных_в_такте):.0f}, "
          f"максимум {max(свободных_в_такте):.0f}")
    if открытых:
        print(f"  из тактов, где было куда, BALANCE отдан в {с_балансом} "
              f"({100 * с_балансом / открытых:.0f}%)")
    print("  на что пришёлся простой:")
    for к, v in пусто.most_common():
        имя = к if к.startswith("еда ниже") else f"{к}: НИКОГО, а поставить можно"
        print(f"   {100 * v / пс_простоя:5.1f}%  {имя}")
    if причины:
        print("  почему направление было закрыто (тактов): "
              + ", ".join(f"{к} {v}" for к, v in причины.most_common(6)))
    return {"доля": 100 * пс_простоя / пс_всего,
            "пусто": {к: 100 * v / пс_простоя for к, v in пусто.items()}}


def main():
    if len(sys.argv) < 2:
        raise SystemExit(__doc__)
    идея = разбор(sys.argv[1])
    база = разбор(sys.argv[2]) if len(sys.argv) > 2 else None
    if идея and база:
        print("\nРАЗНИЦА (идея минус база), в пунктах:")
        print(f"  простоя всего: {идея['доля'] - база['доля']:+.1f}")
        for к in sorted(set(идея["пусто"]) | set(база["пусто"])):
            и, б = идея["пусто"].get(к, 0.0), база["пусто"].get(к, 0.0)
            print(f"  {к}: {и:.1f} против {б:.1f} ({и - б:+.1f})")
        print("  Доли внутри простоя считаются ОТ СВОЕГО простоя: если упал он сам,"
              " доля может вырасти при меньшем абсолютном времени.")


if __name__ == "__main__":
    main()
