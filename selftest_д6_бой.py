#!/usr/bin/env python3
"""БОЙ Д6 (16.10, §162): состояния шестой живой партии Д (`sim/кейсы/партия_д6_16_10_0_14-12_26.jsonl` — частый снимок с составами
из бот-лога). Вживую (мост 68fea10, без §159–§161): 10:45 удар по лагерю — его 23 в (11,1), 2 кл. от ратуши (12,3), к ним 67
через ~42 с, «дойдём за ~14 с»; шли 35 с, его 23 отошли, наши 95 встали в (11,1) рядом с его 90. 11:25 волна W2 по местному
перевесу 0,93 ≥ 0,92 (сила 113/122) пошла в его клетку (10,1): 11:30–11:45 наших легло 84 при его ~0; бой 11:28–12:26 —
113 : 51, норм 0,50 (`sim/бои_по_кольцу.py Д6`). Экзамен (`sim/решения/экзамен_д6_бои.txt`): 10:45 Fable 3/3 — Б, не выходить
(«его 23 — приманка»); 11:25 Fable 3/3 — Г, стоять строем и стрелять, пиками не входить. Двойник (развилки 10:45, 11:15):
«к своим» лучшая ветка у всех трёх агентов, «удар сразу» в 11:15 хуже «ждать» у всех.

Ключи в файле партии: `лагерь_с_подходом` 1 (в силу лагеря входят идущие к нему, кто успеет к бою), `стоящий_вес` 1,5 (его
стоящие у цели весят ×1,5 в местном перевесе); путь к лагерю — от × 14 с + 5 (2 кл. = 33 с, было 14).
(а) 9:50 → 11:00 с ключами партии: ударов нет; 10:45 «ЛАГЕРЬ его 23 в (11, 1) не бьём: прогноз мал … R=1.26 … (с подходом 67)»;
(б) то же с `лагерь_с_подходом` 0: удар по лагерю с 10:24 (`ATTACK all` в (11,1)), «дойдём за ~33 с»; (в) 11:25, волна W2 (95)
в (11,1), его 90 в (10,1): с ключами партии приказа нет — «МАЛО_СИЛ … стоящих=87×1.5»; со `стоящий_вес` 0 — `ATTACK` в (10,1)
«МЕСТНЫЙ_ПЕРЕВЕС свои=95 рядом=90 ratio=0.93», как вживую; (г) 11:20 его 90 на марше к нам из (9,1)/(10,1) (цели за 2 кл.)
— стоящих нет, вес не считается, как без ключа.

    python3 selftest_д6_бой.py
"""
import copy, json, os, sys, tempfile
К = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, К); sys.path.insert(0, os.path.join(К, "sim"))
os.environ.pop("COSS3_WAVE_CONTRACT", None)
import strategy_live as SL
import анализ_врага as АВ

кейс = [json.loads(l) for l in open(os.path.join(К, "sim/кейсы/партия_д6_16_10_0_14-12_26.jsonl"), encoding="utf-8")]
ошибок = 0
def проверить(усл, что):
    global ошибок
    print(("ОК   " if усл else "ОШИБКА ") + что); ошибок += not усл

def стратегия(доп):
    д = json.load(open(os.path.join(К, "sim/поиск/шт_s2_оборона_ручеёк_эко_так15_нужда.json"), encoding="utf-8"))
    assert д["итог"].get("лагерь_с_подходом") == 1 and д["итог"].get("стоящий_вес") == 1.5, "в файле партии ждём лагерь_с_подходом 1 и стоящий_вес 1.5"
    д["итог"].update(доп)
    with tempfile.NamedTemporaryFile("w", suffix=".json", delete=False, encoding="utf-8") as f:
        json.dump(д, f, ensure_ascii=False)
    return SL.ЖиваяСтратегия(f.name)

def м(t): return f"{int(t)//60}:{int(t)%60:02d}"

def прогон(С, a, b):
    АВ._ТЕКУЩИЙ.update({"а": None, "t": None, "ответ": None})
    итог = []
    for s in кейс:
        t = s["gametime"]
        if t < a or t > b: continue
        АВ._ТЕКУЩИЙ.update({"t": None, "ответ": None})
        о = С.ответ(copy.deepcopy(s))
        удар = [(c["cmd"], c.get("count"), c.get("cx"), c.get("cy")) for c in о["commands"] if c["cmd"] in ("ATTACK", "ENGAGE")]
        why = [x for x in о["why"].split("; ") if "ЛАГЕР" in x]
        итог.append((t, удар, why))
    return итог

def при(t):
    return next(s for s in кейс if s["gametime"] >= t)

# (а) ключи партии: ударов по лагерю нет, 10:45 прогноз с подходом
ит = прогон(стратегия({}), 590, 660)
удары = [(м(t), у[0]) for t, у, _ in ит if у]
_1045 = next((w for t, _, w in ит if 643 <= t <= 647), [])
проверить(not удары, f"(а) 9:50–11:00 с ключами партии: ударов нет: {удары}")
проверить(any(x.startswith("ЛАГЕРЬ его 23 в (11, 1) не бьём: прогноз мал") and "R=1.26" in x and "(с подходом 67)" in x for x in _1045),
          f"(а) why 10:45: {[x[:170] for x in _1045]}")

# (б) без подхода — удар с 10:24, честный путь 33 с
ит = прогон(стратегия({"лагерь_с_подходом": 0}), 590, 660)
удары = [(м(t), у[0]) for t, у, _ in ит if у]
_1024 = next((w for t, _, w in ит if 622 <= t <= 626), [])
проверить(bool(удары) and удары[0][0] == "10:24" and all(у == ("ATTACK", "all", 11, 1) for _, у in удары),
          f"(б) лагерь_с_подходом 0: удар с 10:24 ATTACK all в (11,1): {удары[:3]}…{len(удары)}")
проверить(any(x.startswith("УДАР ПО ЛАГЕРЮ его 23") and "дойдём за ~33 с" in x for x in _1024), f"(б) why 10:24: {[x[:120] for x in _1024]}")

# (в) 11:25 — волна W2 (95) в (11,1), его 90 в (10,1) с целью (11,1): стоящие ×1,5 — приказа нет
def удар_готовой(доп, t):
    С = стратегия(доп); С._держим_дом = False
    в = SL.Волна("W2", 1, 480.0, (11, 1), "cell"); в.подтверждена = True; в.размер = 95; в.состояние = "ГОТОВА"
    return С._удар_готовой(в, copy.deepcopy(при(t)))
п, почему = удар_готовой({}, 685)
проверить(п is None and почему.startswith("МАЛО_СИЛ свои=95 рядом=90") and "стоящих=87×1.5" in почему, f"(в) 11:25 с ключами партии: {п}, {почему}")
п, почему = удар_готовой({"стоящий_вес": 0}, 685)
проверить(п is not None and п["cmd"] == "ATTACK" and (п["cx"], п["cy"]) == (10, 1) and "МЕСТНЫЙ_ПЕРЕВЕС свои=95 рядом=90 ratio=0.93" in почему,
          f"(в) 11:25 стоящий_вес 0 — как вживую: {п}, {почему}")

# (г) 11:20 — его 90 идут к (11,1) из (9,1) и (10,1): из (9,1) марш (2 кл.), из (10,1) шаг на нас — стоящих 44
п, почему = удар_готовой({}, 680)
проверить("стоящих=44×1.5" in почему and п is None, f"(г) 11:20: {п}, {почему}")
print(f"ошибок: {ошибок}")
sys.exit(1 if ошибок else 0)
