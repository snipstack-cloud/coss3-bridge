# -*- coding: utf-8 -*-
"""entrypoint.sh контейнера: флаги установки и форма продолжений строк.

Повод, 28.09, и он дорогой. Правка 27.09 вставила комментарии МЕЖДУ
`python3 install_bridge.py ... --reinstall \\` и строкой `--human-only ... \\`.
Это СИНТАКСИЧЕСКИ ЗАКОННО: оболочка заканчивает команду на комментарии, и
`bash -n` молчит. На деле установщик отработал без человеческих флагов и поставил
блоки КОМПЬЮТЕРНОГО слота, а строка с флагами выполнилась как команда
(«--human-only: command not found»). Серия `auto_upgrade` из трёх копий успела
подняться и сыграть не тем мостом, пока это не нашлось в логе.

Отсюда две проверки, которых не было:
* в команде установки присутствуют ВСЕ флаги человеческого слота — иначе
  контейнер ставит компьютерный мост, а лог при этом говорит «все блоки на
  месте», и он формально прав: про человеческие его не просили;
* НИ ОДНА строка файла, кончающаяся обратной косой, не продолжается
  комментарием. Это общая ловушка, а не только про эту команду.
"""
import io
import os
import re
import subprocess

беды = []


def проверка(имя, условие, пояснение=""):
    if условие:
        print("  ОК    " + имя)
    else:
        беды.append(имя)
        print("  ПЛОХО " + имя + (" — " + str(пояснение)[:300] if пояснение else ""))


ЗДЕСЬ = os.path.dirname(os.path.abspath(__file__))
ПУТЬ = os.path.join(ЗДЕСЬ, "docker", "entrypoint.sh")
строки = io.open(ПУТЬ, encoding="utf-8").read().split("\n")

# --- 1. Флаги человеческого слота в команде установки ----------------------
установка = [л for л in строки
             if "install_bridge.py" in л and "--reinstall" in л and not л.strip().startswith("#")]
проверка("команда установки моста найдена, и она одна", len(установка) == 1, установка)
if установка:
    к = установка[0]
    for флаг in ("--human-only", "--human-state", "--human-cmd", "--endgame", "--human-kills"):
        проверка(f"в команде установки есть {флаг}", флаг in к,
                 "без него контейнер поставит другой мост, а лог скажет «все блоки на месте»")
    проверка("команда не разорвана продолжением", not к.rstrip().endswith("\\"),
             "флаги на продолжении — та самая ловушка 27.09")

# --- 2. Комментарий не может продолжать строку с обратной косой ------------
кривые = []
for n, л in enumerate(строки[:-1]):
    if л.rstrip().endswith("\\") and строки[n + 1].strip().startswith("#"):
        кривые.append(n + 2)          # номер строки-комментария, как её видит человек
проверка("ни одно продолжение строки не прервано комментарием", not кривые,
         f"строки: {кривые} — оболочка закончит команду на комментарии, а bash -n промолчит")

# --- 3. И всё-таки разбор оболочкой: он ловит другое ----------------------
# Путь отдаём КОСЫМИ ВПЕРЁД и от каталога проекта: bash из Git Bash не понимает
# виндового пути с обратными косыми и отвечает «No such file or directory» —
# проверка тогда падает не по делу. Поймано ею же при первом запуске.
р = subprocess.run(["bash", "-n", "docker/entrypoint.sh"],
                   capture_output=True, text=True, cwd=ЗДЕСЬ)
проверка("bash -n принимает файл", р.returncode == 0, р.stderr[-200:])

# --- 4. Блоки, которые проверяются перед установкой ------------------------
проверки_блоков = [л for л in строки if "verify_blocks.py" in л and not л.strip().startswith("#")]
проверка("verify_blocks зовётся перед установкой", len(проверки_блоков) >= 1)
if проверки_блоков:
    к = " ".join(проверки_блоков)
    for блок in ("block_hstate.inc", "block_hcmd.inc", "block_kills.inc"):
        проверка(f"{блок} проверяется до установки", блок in к)

print()
if беды:
    print(f"ПЛОХО: {len(беды)} — " + "; ".join(беды))
    raise SystemExit(1)
print("все проверки прошли")
