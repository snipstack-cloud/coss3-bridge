#!/usr/bin/env python3
"""Оценка обстановки (19.09): клетки с перевесом к приходу, прогноз на минуту,
режим. Формула игрока, сведённая к измеримому; слагаемые видны и в трассе."""
import sys
sys.argv = [sys.argv[0]]
import llm_policy as L      # noqa: E402
import coss3_map as M       # noqa: E402

беды = []


def проверка(имя, условие, пояснение=""):
    if условие:
        print("  ОК   " + имя)
    else:
        беды.append(имя)
        print("  ПЛОХО " + имя + (" — " + пояснение if пояснение else ""))


def сетка(имя, **клетки):
    строки = [["."] * 16 for _ in range(16)]
    for k, v in клетки.items():
        x, y = (int(t) for t in k.split(","))
        строки[y][x] = M.знак(v)
    return {f"{имя}{y}": "".join(строки[y]) for y in range(16)}


БАЗА = dict(gametime=500, grid_n=16, map_w=320, map_h=320, my_cx=13, my_cy=14,
            food=1200, mil_inf=60, mil_shooters=0, mil_cav=0, my_freewar=60, ba17=2,
            ba_queues="1:pikeman:inf,2:pikeman:inf",
            p1_enemy="true", p1_peasants=40, p1_army=50, p1_ba17=2, p1_train="peaeng:1,pikeman:2",
            p1_mv_n=0, p1_mv_base=0)
# враг: 50 бойцов у своей ратуши (12,3); крестьяне под ними и шестеро в шахте (6,1)
st = dict(БАЗА, **сетка("frow", **{"12,3": 50}), **сетка("prow", **{"12,3": 30, "6,1": 6}),
          **сетка("arow", **{"13,13": 60}))
оц = L.оценка_обстановки(st, {})
проверка("оценка есть", bool(оц), str(оц))
к = {(c["x"], c["y"]): c for c in оц["клетки"]}
проверка("шахта без охраны первой, с оговоркой", оц["клетки"][0]["x"] == 6 and оц["клетки"][0]["вердикт"].startswith("можно, если"), str(оц["клетки"][0]))
проверка("оба перевеса названы", оц["клетки"][0]["перевес_без_подкрепления"] == 60.0 and оц["клетки"][0]["перевес"] == 1.2, str(оц["клетки"][0]))
шахта = к[(6, 1)]
проверка("подкрепление врага к шахте посчитано", шахта["их_подкрепление"] == 50 and шахта["их_eta"] is not None, str(шахта))
проверка("наш кулак — свободные, время подхода есть", шахта["наш_кулак"] == 60 and шахта["наш_eta"] > 0, str(шахта))
проверка("к приходу врагов встретит меньше, чем к ратуше", шахта["встретит"] < к[(12, 3)]["встретит"] or к[(12, 3)]["встретит"] == 50, str(к))
проверка("у ратуши врага перевес 60/50 — спорно", к[(12, 3)]["вердикт"] == "спорно", str(к[(12, 3)]))
п = оц["прогноз"]
проверка("прогноз: враг растёт на две казармы", п["их_через_60"] == 50 + int(2 * L.ПОДКРЕПЛЕНИЕ_КАЗАРМЫ * 60), str(п))
проверка("прогноз: мы растём на две казармы", п["наша_через_60"] == 60 + int(2 * L.ПОДКРЕПЛЕНИЕ_КАЗАРМЫ * 60), str(п))
проверка("режим при шахте без охраны — УДАР с оговоркой", оц["режим"] == "УДАР", оц["режим"])
н = L.оценка_обстановки(dict(st, my_freewar=0, **сетка("arow")), {})
проверка("без кулака — все клетки НЕТ и строка про пустой кулак", all(c["вердикт"] == "нет" for c in н["клетки"]) and any("кулака нет" in s for s in L.строки_оценки(н)))

# голод: прогноз без нашего прироста, режим ОПАСНОСТЬ
г = L.оценка_обстановки(dict(st, food=300), {})
проверка("голод — найм стоит", г["прогноз"]["наша_через_60"] == 60 and г["прогноз"]["голод"])
проверка("голод — режим ОПАСНОСТЬ", г["режим"] == "ОПАСНОСТЬ")

# идут к базе
б = L.оценка_обстановки(dict(st, p1_mv_n=40, p1_mv_base=40, p1_mv_cx=13, p1_mv_cy=14), {})
проверка("идут к базе — ОПАСНОСТЬ", б["режим"] == "ОПАСНОСТЬ")
проверка("идущие: срок подхода назван", б["прогноз"].get("идущих") == 40 and б["прогноз"].get("дойдут_через", 0) > 0, str(б["прогноз"]))

# перехват волны
в = L.оценка_обстановки(dict(st, wave_n=60, wave_cx=12, wave_cy=8, my_freewar=0,
                             p1_mv_n=40, p1_mv_base=0, p1_mv_cx=12, p1_mv_cy=7), {})
проверка("наперерез волне — ПЕРЕХВАТ", в["режим"] == "ПЕРЕХВАТ", в["режим"])
проверка("кулак — волна", в["кулак"]["что"] == "волна" and в["кулак"]["n"] == 60)

# явный перевес: враг мал
у = L.оценка_обстановки(dict(st, p1_army=10, **сетка("frow", **{"12,3": 10})), {})
проверка("перевес 6 к 1 — УДАР", у["режим"] == "УДАР" and у["клетки"][0]["вердикт"] == "можно", str(у["клетки"][0]))

# без prow — пусто и молчит
проверка("без сетки крестьян — пусто", L.оценка_обстановки(dict(БАЗА), {}) == {} and L.строки_оценки({}) == [])

стр = "\n".join(L.строки_оценки(оц))
проверка("строки: прогноз и режим", "прогноз на минуту" in стр and "режим:" in стр, стр)
проверка("строки: слагаемые клетки видны", "перевес" in стр and "порог 1.3" in стр, стр)
print("\n".join(L.строки_оценки(оц)))
print(f"\nПРОВАЛОВ: {len(беды)}")
raise SystemExit(1 if беды else 0)
