#!/usr/bin/env python3
"""Оценка обстановки (19.09): клетки с перевесом к приходу, прогноз на минуту,
режим. Формула игрока, сведённая к измеримому; слагаемые видны и в трассе."""
import sys
sys.argv = [sys.argv[0]]
import llm_policy as L      # noqa: E402
import coss3_map as M       # noqa: E402

беды = []


def проверка(имя, условие, пояснение=""):
    if условие:
        print("  ОК   " + имя)
    else:
        беды.append(имя)
        print("  ПЛОХО " + имя + (" — " + пояснение if пояснение else ""))


def сетка(имя, **клетки):
    строки = [["."] * 16 for _ in range(16)]
    for k, v in клетки.items():
        x, y = (int(t) for t in k.split(","))
        строки[y][x] = M.знак(v)
    return {f"{имя}{y}": "".join(строки[y]) for y in range(16)}


БАЗА = dict(gametime=500, grid_n=16, map_w=320, map_h=320, my_cx=13, my_cy=14,
            food=1200, mil_inf=60, mil_shooters=0, mil_cav=0, my_freewar=60, ba17=2,
            ba_queues="1:pikeman:inf,2:pikeman:inf",
            p1_enemy="true", p1_peasants=40, p1_army=50, p1_ba17=2, p1_train="peaeng:1,pikeman:2",
            p1_mv_n=0, p1_mv_base=0)
# враг: 50 бойцов у своей ратуши (12,3); крестьяне под ними и шестеро в шахте (6,1)
st = dict(БАЗА, **сетка("frow", **{"12,3": 50}), **сетка("prow", **{"12,3": 30, "6,1": 6}),
          **сетка("arow", **{"13,13": 60}))
оц = L.оценка_обстановки(st, {})
проверка("оценка есть", bool(оц), str(оц))
к = {(c["x"], c["y"]): c for c in оц["клетки"]}
к6 = [c for c in оц["клетки"] if c["x"] == 6][0]
проверка("шахта: оба перевеса названы", к6["перевес_без_подкрепления"] == 60.0 and к6["перевес"] == 1.2, str(к6))
проверка("шахта: его армия ближе — оговорки нет", not к6["вердикт"].startswith("можно, если"), str(к6))
шахта = к[(6, 1)]
проверка("подкрепление врага к шахте посчитано", шахта["их_подкрепление"] == 50 and шахта["их_eta"] is not None, str(шахта))
проверка("наш кулак — свободные, время подхода есть", шахта["наш_кулак"] == 60 and шахта["наш_eta"] > 0, str(шахта))
проверка("к приходу врагов встретит меньше, чем к ратуше", шахта["встретит"] < к[(12, 3)]["встретит"] or к[(12, 3)]["встретит"] == 50, str(к))
проверка("у ратуши врага перевес 60/50 — спорно", к[(12, 3)]["вердикт"] == "спорно", str(к[(12, 3)]))
п = оц["прогноз"]
проверка("прогноз: враг растёт на две казармы", п["их_через_60"] == 50 + int(2 * L.ПОДКРЕПЛЕНИЕ_КАЗАРМЫ * 60), str(п))
проверка("прогноз: мы растём на две казармы", п["наша_через_60"] == 60 + int(2 * L.ПОДКРЕПЛЕНИЕ_КАЗАРМЫ * 60), str(п))
проверка("шахта без охраны, его армия ближе нас — ШАНСа нет, вердикт по худшему случаю", оц["клетки"][0]["вердикт"] in ("спорно", "нет") or оц["клетки"][0]["x"] != 6, str(оц["клетки"][0]))
# мы ближе шахты, чем его армия: оговорка законна, режим ШАНС
бл = L.оценка_обстановки(dict(st, **сетка("arow", **{"9,3": 60})), {})
проверка("мы сильно первые — МОЖНО и УДАР", L.оценка_обстановки(dict(st, **сетка("arow", **{"7,3": 60})), {})["режим"] == "УДАР")
проверка("мы первые у шахты — можно, если; режим ШАНС", бл["клетки"][0]["x"] == 6 and бл["клетки"][0]["вердикт"].startswith("можно, если") and бл["режим"] == "ШАНС", str(бл["клетки"][0]) + бл["режим"])
# волна из 9 в поле при 60 дома: кулак — дома
мал = L.оценка_обстановки(dict(st, wave_n=9, wave_sent=9, wave_cx=12, wave_cy=8), {})
проверка("малая волна в поле не заслоняет кулак дома", мал["кулак"]["что"] == "свободные" and мал["кулак"]["n"] == 60, str(мал["кулак"]))
н = L.оценка_обстановки(dict(st, my_freewar=0, **сетка("arow")), {})
проверка("без кулака — все клетки НЕТ и строка про пустой кулак", all(c["вердикт"] == "нет" for c in н["клетки"]) and any("кулака нет" in s for s in L.строки_оценки(н)))

# голод: прогноз без нашего прироста, режим ОПАСНОСТЬ
г = L.оценка_обстановки(dict(st, food=300), {})
проверка("голод — найм стоит", г["прогноз"]["наша_через_60"] == 60 and г["прогноз"]["голод"])
проверка("голод — режим ОПАСНОСТЬ", г["режим"] == "ОПАСНОСТЬ")

# идут к базе
б = L.оценка_обстановки(dict(st, p1_mv_n=40, p1_mv_base=40, p1_mv_cx=13, p1_mv_cy=14), {})
проверка("идут к базе — ОПАСНОСТЬ", б["режим"] == "ОПАСНОСТЬ")
проверка("идущие: срок подхода назван", б["прогноз"].get("идущих") == 40 and б["прогноз"].get("дойдут_через", 0) > 0, str(б["прогноз"]))

# перехват волны
з = L.оценка_обстановки(dict(st, wave_n=2, wave_cx=12, wave_cy=8), {})
проверка("отбившиеся без отправки — не волна, кулак = свободные", з["кулак"]["что"] == "свободные" and з["кулак"]["n"] == 60, str(з["кулак"]))
в = L.оценка_обстановки(dict(st, wave_n=60, wave_sent=60, wave_cx=12, wave_cy=8, my_freewar=0,
                             p1_mv_n=40, p1_mv_base=0, p1_mv_cx=12, p1_mv_cy=7), {})
проверка("наперерез волне — ПЕРЕХВАТ", в["режим"] == "ПЕРЕХВАТ", в["режим"])
проверка("кулак — волна", в["кулак"]["что"] == "волна" and в["кулак"]["n"] == 60)

# явный перевес: враг мал
у = L.оценка_обстановки(dict(st, p1_army=10, **сетка("frow", **{"12,3": 10})), {})
проверка("перевес 6 к 1 — УДАР", у["режим"] == "УДАР" and у["клетки"][0]["вердикт"] == "можно", str(у["клетки"][0]))

# ПОДКРЕПЛЕНИЕ СЧИТАЕТСЯ ПО КЛЕТКАМ (19.09, починка формулы перевеса).
# Беда, найденная assess_report.py: `их_eta` мерился от ЦЕНТРА МАСС его армии,
# и условие «успеют» выходило истинным в 1229 случаях из 1229 — «перевес»
# читался как «наш кулак против всей его армии». Сценарий, который это ловит:
# армия разделена пополам, половина у цели, половина в дальнем углу. Центр масс
# лежит посередине — по нему успевают ВСЕ; по клеткам далёкая половина не
# успевает, и перевес становится местным.
далеко = dict(БАЗА, p1_army=80, my_freewar=60, my_cx=10, my_cy=2,
              **сетка("frow", **{"12,3": 40, "1,14": 40}),
              **сетка("prow", **{"12,3": 30}),
              **сетка("arow", **{"10,2": 60}))
д = L.оценка_обстановки(далеко, {})
клд = д["клетки"][0]
проверка("далёкая половина армии НЕ засчитана во «встретит»",
         клд["встретит"] == 40 and клд["их_рядом"] == 40, str(клд))
проверка("но она названа как подкрепление в стороне",
         клд["их_подкрепление"] == 40 and клд["их_успеют"] == 0, str(клд))
проверка("перевес стал местным: 60 против 40, а не против 80",
         клд["перевес"] == 1.5 and клд["вердикт"] == "можно", str(клд))
стр_д = chr(10).join(L.строки_оценки(д))
проверка("модели сказано и «в стороне», и «успеют»",
         "в стороне ещё 40" in стр_д and "успеют 0" in стр_д, стр_д)

# Обратный случай: та же половина стоит близко к цели — она успевает, и
# перевес обязан её учесть. Иначе починка просто перестала бы видеть подмогу.
близко = dict(далеко, **сетка("frow", **{"12,3": 40, "10,4": 40}))
б = L.оценка_обстановки(близко, {})
клб = б["клетки"][0]
проверка("близкая половина ЗАСЧИТАНА: успевает к нашему приходу",
         клб["их_успеют"] == 40 and клб["встретит"] == 80, str(клб))

# Знак '+' значит «36 и больше»: недостача до p1_army раскладывается по клеткам
# с '+', иначе у ратуши врага «рядом» выходит 36 вместо 50 и перевес врёт вверх.
плюс = dict(БАЗА, p1_army=50, **сетка("frow", **{"12,3": 50}),
            **сетка("prow", **{"12,3": 30}), **сетка("arow", **{"13,13": 60}))
пк = L.оценка_обстановки(плюс, {})["клетки"][0]
проверка("недостача знака '+' разложена: рядом 50, а не 36",
         пк["их_рядом"] == 50, str(пк))

# ВЕТКА «ШАНС» ДОЛЖНА БЫТЬ ДОСТИЖИМА. На старой формуле она была мёртвой: за
# 422 такта и 1229 клеток не выпала ни разу (assess_report.py, 19.09). Её окно
# узкое и осмысленное — мы приходим первыми, но подкрепление успевает в течение
# получаса боя. Проверяется обе границы окна, иначе ветка снова тихо умрёт.
def шанс(ax):
    st = dict(БАЗА, p1_army=50, my_cx=5, my_cy=1, my_freewar=60,
              **сетка("frow", **{f"{ax},1": 50}), **сетка("prow", **{"6,1": 6}),
              **сетка("arow", **{"5,1": 60}))
    оц_ = L.оценка_обстановки(st, {})
    return оц_["клетки"][0], оц_["режим"]

к8, р8 = шанс(8)          # их 20 с против наших 10 — успевают, но мы первые
проверка("ветка ШАНС жива: мы первые, подкрепление успевает",
         к8["вердикт"].startswith("можно, если") and р8 == "ШАНС", str(к8) + р8)
к11, р11 = шанс(11)       # их 50 с против наших 10+30 — не успевают вовсе
проверка("за окном подкрепление не успевает — чистое МОЖНО",
         к11["их_успеют"] == 0 and к11["вердикт"] == "можно" and р11 == "УДАР", str(к11) + р11)

# без prow — пусто и молчит
проверка("без сетки крестьян — пусто", L.оценка_обстановки(dict(БАЗА), {}) == {} and L.строки_оценки({}) == [])

стр = "\n".join(L.строки_оценки(оц))
проверка("строки: прогноз и режим", "прогноз на минуту" in стр and "режим:" in стр, стр)
проверка("строки: слагаемые клетки видны", "перевес" in стр and "порог 1.3" in стр, стр)
print("\n".join(L.строки_оценки(оц)))
print(f"\nПРОВАЛОВ: {len(беды)}")
raise SystemExit(1 if беды else 0)
